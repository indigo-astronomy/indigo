	def test_six_entrypoints_restore_after_term_during_connection_battery(self):
		for name in self.INTERFACES:
			for connected in ('ON', 'OFF'):
				with self.subTest(script=name, initial=connected):
					self.configure(name, connected)
					self.state['config'] = {'connection_delay': 0.25}
					process = subprocess.Popen(['bash', str(self.directory / (name + '_compliance.sh')), self.state['device'], 'fixture.invalid:0'], env=self.environment(), text=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
					try:
						deadline = time.monotonic() + 5
						changed = False
						while time.monotonic() < deadline and process.poll() is None:
							if self.current()['properties']['CONNECTION']['CONNECTED'] != connected:
								changed = True
								process.send_signal(signal.SIGTERM)
								break
							time.sleep(0.01)
						stdout, stderr = process.communicate(timeout=10)
						self.assertTrue(changed, stdout + stderr)
						self.assertEqual(143, process.returncode, stdout + stderr)
						self.assertEqual(connected, self.current()['properties']['CONNECTION']['CONNECTED'], stdout + stderr)
					finally:
						if process.poll() is None:
							process.kill()
							process.communicate()


