// deterministic pseudo random numbers, the tests never depend on the platform rand()
static uint32_t random_state = 20261113;

static double random_unit(void) {
	random_state = random_state * 1664525u + 1013904223u;
	return (random_state >> 8) / (double)(1u << 24);
}

static double seconds(struct timespec *from, struct timespec *to) {
	return (to->tv_sec - from->tv_sec) + (to->tv_nsec - from->tv_nsec) / 1e9;
}

static void test_performance(void) {
	indigo_scheduler_sky_build(&sky, T_NOVEMBER_NOON, LATITUDE, LONGITUDE, 140);
	for (int i = 0; i < MAX_TASKS; i++) {
		char name[16];
		snprintf(name, sizeof(name), "task %d", i);
		add_task(i, name, (scheduler_priority_class)(int)(random_unit() * 3), (int)(random_unit() * 100), 5 + (int)(random_unit() * 60));
		headers[i].has_target = true;
		headers[i].ra = random_unit() * 24;
		headers[i].dec = random_unit() * 150 - 60;
		headers[i].has_min_altitude = true;
		headers[i].min_altitude = 20 + random_unit() * 20;
		headers[i].has_moon = random_unit() < 0.5;
		headers[i].moon_separation = 30;
		headers[i].moon_width = 7;
		headers[i].repeat = 1 + (int)(random_unit() * 3);
		tasks[i].runs_left = headers[i].repeat;
	}
	struct timespec begin, finish;
	clock_gettime(CLOCK_MONOTONIC, &begin);
	for (int i = 0; i < MAX_TASKS; i++) {
		build_task(i);
	}
	int count = indigo_scheduler_plan(&sky, tasks, MAX_TASKS, T_NOVEMBER_NOON, indigo_scheduler_night_end(&sky, T_NOVEMBER_NOON), 1, 1, runs, 256);
	clock_gettime(CLOCK_MONOTONIC, &finish);
	double elapsed = seconds(&begin, &finish);
	printf("    %d runs of %d tasks planned in %.3f s\n", count, MAX_TASKS, elapsed);
	ASSERT_TRUE(count > 0);
	ASSERT_TRUE(elapsed < 1.0);
	// the runs follow each other and never overlap
	for (int i = 1; i < count; i++) {
		ASSERT_TRUE(runs[i].start >= runs[i - 1].end);
	}
}

// the worst case of the search for the next start: 128 tasks of 24 hours searched over the whole grid
static void test_next_start_search_cost(void) {
	indigo_scheduler_sky_build(&sky, T_NOVEMBER_NOON, LATITUDE, LONGITUDE, 140);
	for (int i = 0; i < MAX_TASKS; i++) {
		add_task(i, "long", SCHEDULER_PRIORITY_NORMAL, 50, 24 * 60);
		headers[i].has_target = true;
		headers[i].ra = random_unit() * 24;
		headers[i].dec = random_unit() * 150 - 60;
		headers[i].has_min_altitude = true;
		headers[i].min_altitude = 30;
		headers[i].twilight = SCHEDULER_TWILIGHT_NONE;
		build_task(i);
	}
	struct timespec begin, finish;
	clock_gettime(CLOCK_MONOTONIC, &begin);
	int found = 0;
	for (int round = 0; round < 10; round++) {
		for (int i = 0; i < MAX_TASKS; i++) {
			if (indigo_scheduler_points_next(&sky, &points[i], &headers[i], T_NOVEMBER_NOON, tasks[i].duration, 0, NULL) > 0) {
				found++;
			}
		}
	}
	clock_gettime(CLOCK_MONOTONIC, &finish);
	double elapsed = seconds(&begin, &finish);
	printf("    10 searches of %d tasks of 24 h in %.3f s, %d starts found\n", MAX_TASKS, elapsed, found);
	// only circumpolar targets above 30 degrees all day can run for 24 hours
	ASSERT_TRUE(found > 0 && found < 10 * MAX_TASKS);
	ASSERT_TRUE(elapsed < 1.0);
}

