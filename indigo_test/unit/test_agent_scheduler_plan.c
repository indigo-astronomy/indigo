#define T_NOVEMBER_NOON		1794484800	// 2026-11-12 12:00 UTC

#define LATITUDE			48.15
#define LONGITUDE			17.11

#define MAX_TASKS			128

static scheduler_sky_grid sky;
static scheduler_header headers[MAX_TASKS];
static scheduler_target_grid targets[MAX_TASKS];
static scheduler_task_points points[MAX_TASKS];
static scheduler_plan_task tasks[MAX_TASKS];
static scheduler_plan_run runs[512];

static void add_task(int i, const char *name, scheduler_priority_class priority_class, int level, int minutes) {
	scheduler_header *header = &headers[i];
	memset(header, 0, sizeof(*header));
	snprintf(header->name, sizeof(header->name), "%s", name);
	header->priority_class = priority_class;
	header->level = level;
	header->repeat = 1;
	header->enabled = true;
	header->twilight = SCHEDULER_TWILIGHT_ASTRONOMICAL;
	memset(&tasks[i], 0, sizeof(tasks[i]));
	tasks[i].header = header;
	tasks[i].target = &targets[i];
	tasks[i].points = &points[i];
	tasks[i].selectable = true;
	tasks[i].duration = minutes * 60;
	tasks[i].runs_left = 1;
}

// the tables are built after the header is complete
static void build_task(int i) {
	memset(&targets[i], 0, sizeof(targets[i]));
	if (headers[i].has_target) {
		indigo_scheduler_target_build(&sky, &headers[i], &targets[i]);
	}
	indigo_scheduler_points_build(&sky, &targets[i], &headers[i], &points[i]);
}

static int plan(int count, time_t now) {
	for (int i = 0; i < count; i++) {
		build_task(i);
	}
	return indigo_scheduler_plan(&sky, tasks, count, now, indigo_scheduler_night_end(&sky, now), 0, 0, runs, 512);
}

// the first time after now the astronomical twilight condition holds
static time_t dark_from(time_t now) {
	scheduler_header header;
	memset(&header, 0, sizeof(header));
	header.twilight = SCHEDULER_TWILIGHT_ASTRONOMICAL;
	header.repeat = 1;
	scheduler_target_grid none;
	memset(&none, 0, sizeof(none));
	scheduler_task_points dark;
	indigo_scheduler_points_build(&sky, &none, &header, &dark);
	return indigo_scheduler_points_next(&sky, &dark, &header, now, 60, 0, NULL);
}

