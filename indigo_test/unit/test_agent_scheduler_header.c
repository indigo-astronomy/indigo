#define BODY "var sequence = new Sequence(scheduler_task.name);\nsequence.start();\n"

static scheduler_header header;
static size_t body_offset;
static char error[256];

static bool parse(const char *text) {
	error[0] = 0;
	return indigo_scheduler_parse_header(text, &header, &body_offset, error, sizeof(error));
}

// asserts that text is rejected with a message containing expected
static void assert_rejected(const char *text, const char *expected) {
	bool result = parse(text);
	if (result || strstr(error, expected) == NULL) {
		fprintf(stderr, "text:\n%s\nerror: '%s', expected '%s'\n", text, error, expected);
	}
	ASSERT_FALSE(result);
	ASSERT_TRUE(strstr(error, expected) != NULL);
}

static void test_minimal_task_defaults(void) {
	const char *text = "// @task M31\n\n" BODY;
	ASSERT_TRUE(parse(text));
	ASSERT_STREQ("M31", header.name);
	ASSERT_EQ_INT(SCHEDULER_PRIORITY_NORMAL, header.priority_class);
	ASSERT_EQ_INT(50, header.level);
	ASSERT_FALSE(header.has_target);
	ASSERT_EQ_INT(SCHEDULER_TWILIGHT_NONE, header.twilight);
	ASSERT_EQ_INT(SCHEDULER_WINDOW_NONE, header.window_kind);
	ASSERT_FALSE(header.has_duration);
	ASSERT_EQ_INT(SCHEDULER_DEFAULT_DURATION, indigo_scheduler_header_duration(&header));
	ASSERT_EQ_INT(1, header.repeat);
	ASSERT_EQ_INT(0, header.retry);
	ASSERT_FALSE(header.preempted_fail);
	ASSERT_TRUE(header.enabled);
	// the blank line that ends the header is the first line of the body
	ASSERT_STREQ("\n" BODY, text + body_offset);
}

