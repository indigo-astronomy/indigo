const assert = require('node:assert/strict');
const { readFileSync } = require('node:fs');
const { join } = require('node:path');
const { test } = require('node:test');
const vm = require('node:vm');

const page = readFileSync(join(__dirname, '../../indigo_server/resource/mount.html'), 'utf8');
const script = page.match(/<script>([\s\S]*?)<\/script>/)[1];
const directions = [['West', 'MOUNT_MOTION_RA', 'WEST'], ['East', 'MOUNT_MOTION_RA', 'EAST'], ['North', 'MOUNT_MOTION_DEC', 'NORTH'], ['South', 'MOUNT_MOTION_DEC', 'SOUTH']];

function fixture() {
	const changes = [], windowEvents = {}, documentEvents = {}, captured = new Set(), classes = new Set(['idle-state']);
	const process = { state: 'Ok' };
	const context = vm.createContext({
		URL, console, guiSetup() { }, init() { },
		window: { location: { protocol: 'http:', host: 'localhost' }, addEventListener(name, callback) { windowEvents[name] = callback; } },
		document: { hidden: false, addEventListener(name, callback) { documentEvents[name] = callback; } },
		INDIGO: { devices: { 'Mount Agent': { AGENT_START_PROCESS: process } }, findProperty() { return null; } },
		changeProperty(device, name, values) { changes.push(JSON.parse(JSON.stringify({ device, name, values }))); }
	});
	vm.runInContext(script, context);
	const button = {
		classList: { replace(before, after) { if (classes.delete(before)) { classes.add(after); } } },
		setPointerCapture(id) { if (context.failCapture) { throw new Error('capture failed'); } captured.add(id); },
		releasePointerCapture(id) { captured.delete(id); if (context.failRelease) { throw new Error('capture already lost'); } context.stopManualMotion({ pointerId: id }); }
	};
	const event = { currentTarget: button, pointerId: 7, button: 0, isPrimary: true, preventDefault() { } };
	return { context, changes, windowEvents, documentEvents, captured, classes, process, button, event };
}

for (const [direction, property, item] of directions) {
	test(`${direction} captures press and stops on release outside button`, () => {
		const f = fixture();
		f.context[`move${direction}`](f.event);
		assert.deepEqual(f.changes, [{ device: 'Mount Agent', name: property, values: { [item]: true } }]);
		assert.equal(f.captured.has(7), true);
		assert.equal(f.classes.has('busy-state'), true);
		f.windowEvents.pointerup({ pointerId: 7 });
		assert.deepEqual(f.changes[1], { device: 'Mount Agent', name: property, values: { [item]: false } });
		assert.equal(f.captured.size, 0);
		assert.equal(f.classes.has('idle-state'), true);
		f.windowEvents.pointerup({ pointerId: 7 });
		f.context.stopManualMotion({ pointerId: 7 });
		assert.equal(f.changes.length, 2);
	});
	test(`${direction} button wires capture, release and cancellation events`, () => {
		const button = page.match(new RegExp('<button[^>]+@pointerdown\\.stop="window\\.move' + direction + '\\(\\$event\\)"[^>]*>'));
		assert.ok(button, 'direction must use pointerdown');
		for (const name of ['pointerup', 'pointercancel', 'lostpointercapture']) {
			assert.ok(button[0].includes(`@${name}.stop="window.stopManualMotion($event)"`));
		}
		assert.ok(button[0].includes('touch-action: none'));
	});
}

for (const loss of ['pointercancel', 'lostpointercapture', 'blur', 'hidden', 'pagehide']) {
	test(`${loss} stops motion once even after a BUSY state change`, () => {
		const f = fixture();
		f.context.moveWest(f.event);
		f.process.state = 'Busy';
		if (loss === 'hidden') {
			f.context.document.hidden = true;
			f.documentEvents.visibilitychange();
		} else if (loss === 'lostpointercapture') {
			f.context.stopManualMotion({ pointerId: 7 });
		} else {
			f.windowEvents[loss]({ pointerId: 7 });
		}
		f.context.stopManualMotion();
		assert.deepEqual(f.changes.map(change => change.values.WEST), [true, false]);
	});
}

test('unrelated pointer release and visible document do not stop held motion', () => {
	const f = fixture();
	f.context.moveNorth(f.event);
	f.windowEvents.pointerup({ pointerId: 8 });
	f.windowEvents.pointercancel({ pointerId: 8 });
	f.documentEvents.visibilitychange();
	assert.equal(f.changes.length, 1);
	f.windowEvents.pointerup({ pointerId: 7 });
	assert.equal(f.changes.length, 2);
});

for (const rejected of ['busy', 'right-button', 'secondary-pointer', 'failed-capture']) {
	test(`${rejected} press does not start motion`, () => {
		const f = fixture();
		if (rejected === 'busy') { f.process.state = 'Busy'; }
		if (rejected === 'right-button') { f.event.button = 2; }
		if (rejected === 'secondary-pointer') { f.event.isPrimary = false; }
		if (rejected === 'failed-capture') { f.context.failCapture = true; }
		f.context.moveEast(f.event);
		assert.equal(f.changes.length, 0);
		assert.equal(f.captured.size, 0);
		assert.equal(f.classes.has('idle-state'), true);
	});
}

test('duplicate or competing presses do not replace held motion', () => {
	const f = fixture();
	f.context.moveWest(f.event);
	f.context.moveWest(f.event);
	f.context.moveEast({ ...f.event, pointerId: 8 });
	assert.equal(f.changes.length, 1);
	f.windowEvents.pointerup({ pointerId: 7 });
	assert.deepEqual(f.changes.map(change => change.values.WEST), [true, false]);
});

test('already lost capture still sends stop and permits another press', () => {
	const f = fixture();
	f.context.moveSouth(f.event);
	f.context.failRelease = true;
	f.windowEvents.pointerup({ pointerId: 7 });
	assert.deepEqual(f.changes.map(change => change.values.SOUTH), [true, false]);
	f.context.moveSouth(f.event);
	assert.equal(f.changes.length, 3);
});

for (const hasAgentAbort of [false, true]) {
	test(`explicit Stop releases manual motion and retains ${hasAgentAbort ? 'agent' : 'mount'} abort`, () => {
		const f = fixture();
		f.context.INDIGO.findProperty = () => hasAgentAbort ? {} : null;
		f.context.moveEast(f.event);
		f.context.stop();
		assert.deepEqual(f.changes[1], { device: 'Mount Agent', name: 'MOUNT_MOTION_RA', values: { EAST: false } });
		assert.deepEqual(f.changes[2], { device: 'Mount Agent', name: hasAgentAbort ? 'AGENT_ABORT_PROCESS' : 'MOUNT_ABORT_MOTION', values: hasAgentAbort ? { ABORT: true } : { ABORT_MOTION: true } });
	});
}
