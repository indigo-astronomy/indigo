"""Check the Wi-Fi client password length guards of tools/rpi_ctrl.sh and tools/rpi_ctrl_v2.sh.

Each script is copied into a temporary directory with its configuration file
paths redirected there and run with a PATH that holds only logging stubs and a
short allowlist of harmless real tools (which, grep, head, tr). No network,
service, package or power command of the host is reachable: anything not
stubbed or allowlisted fails as "command not found". The stubs append their
argv to a log that the test inspects.
"""

import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[2]
BASH = "/bin/bash"
SSID = "fixture-net"

# Every external the scripts resolve with `which` or call by name, plus the
# commands an older Raspberry Pi network setup might use. All of them only log.
STUBBED = (
	"apt-cache", "apt-get", "date", "dhcpcd", "hostapd", "ifdown", "ifup", "ip",
	"iw", "nft", "nmcli", "poweroff", "raspi-config", "reboot", "service",
	"sleep", "sudo", "systemctl", "wifi_channel_selector.pl", "wpa_cli",
)
# File writers: logged, then the real tool runs on the redirected files.
LOGGED_REAL = ("cat", "cp", "sed")
# Read-only helpers the scripts need before any guard runs.
REAL = ("grep", "head", "tr", "which")

STUB = """#!/bin/sh
{ printf '%s' "${0##*/}"; for arg in "$@"; do printf '\\037%s' "$arg"; done; printf '\\n'; } >> "$RPI_CTRL_STUB_LOG"
"""

V1_FILES = {
	"CONF_HOSTAPD": ("hostapd.conf", "ssid=indigosky\nwpa_passphrase=indigosky\nchannel=6\n"),
	"CONF_WPA_SUPPLICANT": ("wpa_supplicant.conf", "network={\n\tssid=\"old-net\"\n\tpsk=\"old-password\"\n}\n"),
	# Without the access point lines rpi_ctrl.sh skips its GNU-only
	# `sed -i EXPR FILE` edits, so the accepted-password runs work with BSD sed.
	"CONF_DHCPCD": ("dhcpcd.conf", "hostname\nclientid\n"),
	"CONF_SYSCTL": ("sysctl.conf", "net.ipv4.ip_forward=1\n"),
	"PROC_FORWARD": ("ip_forward", "1\n"),
}
V2_FILES = {
	"CONF_SYSCTL": ("sysctl.conf", "net.ipv4.ip_forward=1\n"),
	"PROC_FORWARD": ("ip_forward", "1\n"),
}
SCRIPTS = {
	"rpi_ctrl.sh": V1_FILES,
	"rpi_ctrl_v2.sh": V2_FILES,
}


def real_tool(name):
	path = shutil.which(name, path="/usr/bin:/bin")
	if path is None:
		raise RuntimeError("required tool not found: " + name)
	return path


class Sandbox:
	def __init__(self, script):
		self.tmp = tempfile.TemporaryDirectory(prefix="rpi_ctrl_test_")
		self.root = Path(self.tmp.name)
		self.conf = self.root / "conf"
		stub_dir = self.root / "stub"
		real_dir = self.root / "real"
		for directory in (self.conf, stub_dir, real_dir):
			directory.mkdir()
		self.log = self.root / "calls.log"
		self.log.write_text("")
		for name in STUBBED:
			self._write_exe(stub_dir / name, STUB)
		for name in LOGGED_REAL:
			self._write_exe(stub_dir / name, STUB + 'exec "' + real_tool(name) + '" "$@"\n')
		for name in REAL:
			(real_dir / name).symlink_to(real_tool(name))
		text = (ROOT / "tools" / script).read_text()
		for variable, (file_name, content) in SCRIPTS[script].items():
			target = self.conf / file_name
			target.write_text(content)
			# rpi_ctrl.sh copies its configuration files to *.orig on every
			# run; existing copies keep that step from writing anything.
			if variable.startswith("CONF_"):
				(self.conf / (file_name + ".orig")).write_text(content)
			text, count = re.subn(r'^' + variable + r'="[^"]*"$', variable + '="' + str(target) + '"', text, flags=re.M)
			if count != 1:
				raise RuntimeError(script + ": cannot redirect " + variable)
		if re.search(r'^[A-Z_]+="/(etc|proc)/', text, flags=re.M):
			raise RuntimeError(script + ": unredirected system path")
		self.script = self.root / script
		self.script.write_text(text)
		self.env = {
			"PATH": str(stub_dir) + ":" + str(real_dir),
			"HOME": str(self.root),
			"LC_ALL": "C",
			"RPI_CTRL_STUB_LOG": str(self.log),
		}

	@staticmethod
	def _write_exe(path, content):
		path.write_text(content)
		path.chmod(0o755)

	def snapshot(self):
		return {path.name: path.read_text() for path in sorted(self.conf.iterdir())}

	def calls(self):
		return [line.split("\x1f") for line in self.log.read_text().splitlines()]

	def run(self, password):
		return subprocess.run(
			[BASH, str(self.script), "--set-wifi-client", SSID, password],
			env=self.env, cwd=str(self.root), capture_output=True, text=True, timeout=60,
		)

	def close(self):
		self.tmp.cleanup()


class RpiCtrlWifiClientPasswordTest(unittest.TestCase):
	def sandbox(self, script):
		sandbox = Sandbox(script)
		self.addCleanup(sandbox.close)
		return sandbox

	def assert_rejected(self, length, message):
		for script in SCRIPTS:
			with self.subTest(script=script, length=length):
				sandbox = self.sandbox(script)
				before = sandbox.snapshot()
				result = sandbox.run("p" * length)
				self.assertEqual(result.stdout, "ALERT: " + message + "\n", result.stderr)
				self.assertEqual(result.returncode, 1)
				self.assertNotIn("command not found", result.stderr)
				self.assertEqual(sandbox.calls(), [], "commands issued after an invalid password")
				self.assertEqual(sandbox.snapshot(), before, "configuration changed after an invalid password")

	def test_rejects_password_shorter_than_8(self):
		self.assert_rejected(7, "WIFI_CN_PW length < 8")

	def test_rejects_password_longer_than_63(self):
		self.assert_rejected(64, "WIFI_CN_PW length > 63")

	def test_accepts_passwords_of_length_8_and_63(self):
		for length in (8, 63):
			password = "p" * length
			with self.subTest(script="rpi_ctrl.sh", length=length):
				sandbox = self.sandbox("rpi_ctrl.sh")
				result = sandbox.run(password)
				# The script reboots after "OK" and does not exit itself, so
				# its exit status is that of its last option test.
				self.assertEqual(result.stdout, "OK\n", result.stderr)
				self.assertIn('psk="' + password + '"', sandbox.snapshot()["wpa_supplicant.conf"])
				calls = sandbox.calls()
				self.assertIn(["systemctl", "disable", "hostapd"], calls)
				self.assertIn(["reboot"], calls)
			with self.subTest(script="rpi_ctrl_v2.sh", length=length):
				sandbox = self.sandbox("rpi_ctrl_v2.sh")
				result = sandbox.run(password)
				self.assertEqual(result.stdout, "OK\n", result.stderr)
				self.assertEqual(result.returncode, 0)
				self.assertIn(["nmcli", "dev", "wifi", "connect", SSID, "password", password], sandbox.calls())


if __name__ == "__main__":
	unittest.main()
