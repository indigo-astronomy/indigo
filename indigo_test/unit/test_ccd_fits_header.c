// Code is generated by AI
// FITS header cards built by the CCD base driver from user text.

#include "../test_runner.h"
#include <stdlib.h>
#include <string.h>
#include <indigo/indigo_ccd_driver.h>

// returns the OBJECT card of the FITS header written for the object name, NULL if there is none; the buffer is freed by the caller
static unsigned char *header_for_object(indigo_device *device, const char *name, char **card) {
	// the FITS data is padded to a whole block
	unsigned char *data = calloc(1, 5 * FITS_HEADER_SIZE);
	indigo_set_text_item_value(CCD_LOCAL_MODE_OBJECT_ITEM, name);
	indigo_process_image(device, data, 2, 1, 16, true, false, NULL, false);
	*card = strstr((char *)data, "OBJECT  = ");
	return data;
}

// no NUL byte in the header before the END card, which is the proof that no later card was lost
static bool header_is_complete(const unsigned char *data) {
	for (int i = 0; i < FITS_HEADER_SIZE; i += 80) {
		if (!memcmp(data + i, "END     ", 8)) {
			return true;
		}
		if (memchr(data + i, 0, 80) != NULL) {
			return false;
		}
	}
	return false;
}

static void object_name_quotes_are_doubled_in_the_fits_header(void) {
	indigo_device storage = { .name = "Audit FITS header unit device" };
	indigo_device *device = &storage;
	ASSERT_TRUE(indigo_start() == INDIGO_OK);
	ASSERT_TRUE(indigo_ccd_attach(device, "audit-test", 1) == INDIGO_OK);
	indigo_set_switch(CCD_IMAGE_FORMAT_PROPERTY, CCD_IMAGE_FORMAT_FITS_ITEM, true);
	indigo_set_switch(CCD_PREVIEW_PROPERTY, CCD_PREVIEW_DISABLED_ITEM, true);
	char *card = NULL;
	unsigned char *data = header_for_object(device, "Barnard's Star", &card);
	ASSERT_TRUE(card != NULL && !strncmp(card, "OBJECT  = 'Barnard''s Star' / object name", 41));
	ASSERT_TRUE(header_is_complete(data));
	free(data);
	indigo_ccd_detach(device);
	ASSERT_TRUE(indigo_stop() == INDIGO_OK);
}

// the worst case: a name of quotes only, which is doubled and cut; the card is 80 characters, closed by a quote, with a space in the last column and no NUL in the header
static void long_quoted_object_name_keeps_the_card_and_the_header_intact(void) {
	indigo_device storage = { .name = "Audit FITS header unit device" };
	indigo_device *device = &storage;
	ASSERT_TRUE(indigo_start() == INDIGO_OK);
	ASSERT_TRUE(indigo_ccd_attach(device, "audit-test", 1) == INDIGO_OK);
	indigo_set_switch(CCD_IMAGE_FORMAT_PROPERTY, CCD_IMAGE_FORMAT_FITS_ITEM, true);
	indigo_set_switch(CCD_PREVIEW_PROPERTY, CCD_PREVIEW_DISABLED_ITEM, true);
	char *card = NULL;
	unsigned char *data = header_for_object(device, "'''''''''''''''''''''''''''''''''''''''''''''''''''''''''''''''", &card);
	ASSERT_TRUE(card != NULL);
	if (card) {
		// the doubled quotes are never split: an even number of them, then the closing quote
		int quotes = 0;
		while (card[11 + quotes] == '\'') {
			quotes++;
		}
		ASSERT_TRUE(quotes % 2 == 1 && quotes > 40);
		ASSERT_TRUE(!strncmp(card + 11 + quotes - 1, "' / object nam", 14));
		ASSERT_TRUE(card[79] == ' ');
	}
	ASSERT_TRUE(header_is_complete(data));
	free(data);
	indigo_ccd_detach(device);
	ASSERT_TRUE(indigo_stop() == INDIGO_OK);
}

int main(void) {
	if (!indigo_test_use_private_home()) {
		return 1;
	}
	const indigo_test_case tests[] = {
		{ "object_name_quotes_are_doubled_in_the_fits_header", object_name_quotes_are_doubled_in_the_fits_header },
		{ "long_quoted_object_name_keeps_the_card_and_the_header_intact", long_quoted_object_name_keeps_the_card_and_the_header_intact }
	};
	int result = indigo_run_tests("CCD FITS header", tests, 2);
	indigo_test_remove_private_home();
	return result;
}
