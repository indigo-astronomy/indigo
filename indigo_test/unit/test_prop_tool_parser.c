// Runs the function with stdout redirected to a temporary file and returns what it printed.
static bool capture_stdout(void (*function)(void), char *buffer, size_t size) {
	FILE *file = tmpfile();
	if (file == NULL) {
		return false;
	}
	fflush(stdout);
	int saved = dup(STDOUT_FILENO);
	dup2(fileno(file), STDOUT_FILENO);
	function();
	fflush(stdout);
	dup2(saved, STDOUT_FILENO);
	close(saved);
	rewind(file);
	size_t length = fread(buffer, 1, size - 1, file);
	buffer[length] = '\0';
	fclose(file);
	return true;
}

