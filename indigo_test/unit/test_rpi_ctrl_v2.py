def apt_cache_stub(missing_status):
	"""`apt-cache show indigo3=<version>` prints a record only for the known
	indigo3 version. apt 2.8 prints nothing and exits 0 for a missing version
	of a known package; it exits 100 for an unknown package."""
	return (
		'if [ "$1" = show ] && [ "$2" = "indigo3=' + INDIGO3_VERSION + '" ]; then\n'
		"\tprintf 'Package: indigo3\\nVersion: " + INDIGO3_VERSION + "\\n'\n"
		"\texit 0\n"
		"fi\n"
		"exit " + str(missing_status) + "\n"
	)


def real_tool(name):
	path = shutil.which(name, path="/usr/bin:/bin")
	if path is None:
		raise RuntimeError("required tool not found: " + name)
	return path


def grep_has_pcre():
	result = subprocess.run([real_tool("grep"), "-oPm1", "(?<=a:).*"], input="a:1\n", capture_output=True, text=True)
	return result.returncode == 0 and result.stdout == "1\n"


class Sandbox:
	def __init__(self, stubs=None):
		self.tmp = tempfile.TemporaryDirectory(prefix="rpi_ctrl_v2_test_")
		self.root = Path(self.tmp.name)
		self.stub_dir = self.root / "stub"
		real_dir = self.root / "real"
		conf = self.root / "conf"
		for directory in (self.stub_dir, real_dir, conf):
			directory.mkdir()
		self.log = self.root / "calls.log"
		self.log.write_text("")
		stubs = stubs or {}
		for name in STUBBED:
			path = self.stub_dir / name
			path.write_text(STUB + stubs.get(name, ""))
			path.chmod(0o755)
		for name in REAL:
			(real_dir / name).symlink_to(real_tool(name))
		text = SCRIPT.read_text()
		for variable, (file_name, content) in REDIRECTED.items():
			target = conf / file_name
			target.write_text(content)
			text, count = re.subn(r'^' + variable + r'="[^"]*"$', variable + '="' + str(target) + '"', text, flags=re.M)
			if count != 1:
				raise RuntimeError("cannot redirect " + variable)
		if re.search(r'/(etc|proc)/', text):
			raise RuntimeError("unredirected system path in the script copy")
		self.script = self.root / SCRIPT.name
		self.script.write_text(text)
		self.env = {
			"PATH": str(self.stub_dir) + ":" + str(real_dir),
			"HOME": str(self.root),
			"LC_ALL": "C",
			"RPI_CTRL_STUB_LOG": str(self.log),
		}

	def run(self, *args):
		return subprocess.run(
			[BASH, str(self.script)] + list(args),
			env=self.env, cwd=str(self.root), capture_output=True, text=True, timeout=60,
		)

	def calls(self, name=None):
		calls = [line.split("\x1f") for line in self.log.read_text().splitlines()]
		return [call for call in calls if name is None or call[0] == name]

	def close(self):
		self.tmp.cleanup()


class RpiCtrlV2Test(unittest.TestCase):
	def sandbox(self, stubs=None):
		sandbox = Sandbox(stubs)
		self.addCleanup(sandbox.close)
		return sandbox

	def assert_no_missing_command(self, result):
		self.assertNotIn("command not found", result.stderr)
		self.assertNotIn("No such file", result.stderr)

	# --get-wifi-channel

	def test_get_wifi_channel_without_indigo_profile_keeps_default(self):
		sandbox = self.sandbox({"nmcli": NMCLI_NO_PROFILE})
		result = sandbox.run("--get-wifi-channel")
		# Client mode: no channel to report, so the script exits quietly.
		self.assertEqual(result.stdout, "", result.stderr)
		self.assertEqual(result.returncode, 1)
		self.assert_no_missing_command(result)

	def require_pcre(self):
		if not grep_has_pcre():
			self.skipTest("grep without -P (PCRE) support; the script needs GNU grep")

	def test_get_wifi_channel_reports_active_ap_channel(self):
		self.require_pcre()
		sandbox = self.sandbox({"nmcli": NMCLI_ACTIVE_AP})
		result = sandbox.run("--get-wifi-channel")
		self.assertEqual(result.stdout, "11\n", result.stderr)
		self.assertEqual(result.returncode, 0)
		self.assert_no_missing_command(result)

	# --get-wifi-client and --get-wifi-server

	def test_get_wifi_settings_of_open_network(self):
		self.require_pcre()
		# indigo_server reads the first line: an SSID or SSID<TAB>password
		# sets the property OK, no output leaves it idle, "ALERT:" sets ALERT.
		cases = (
			(("--get-wifi-client",), "open-net\n", 0),
			(("--verbose", "--get-wifi-client"), "open-net\t\n", 0),
			# Client mode: no access point to report.
			(("--get-wifi-server",), "", 1),
			(("--verbose", "--get-wifi-server"), "open-net\t\n", 0),
		)
		for args, stdout, returncode in cases:
			with self.subTest(args=args):
				sandbox = self.sandbox({"nmcli": NMCLI_OPEN_CLIENT})
				result = sandbox.run(*args)
				self.assertEqual(result.stdout, stdout, result.stderr)
				self.assertEqual(result.returncode, returncode)
				self.assert_no_missing_command(result)

	def test_get_wifi_settings_of_secured_network_without_psk(self):
		self.require_pcre()
		for args in (("--get-wifi-client",), ("--get-wifi-server",)):
			with self.subTest(args=args):
				sandbox = self.sandbox({"nmcli": NMCLI_SECURED_CLIENT_NO_PSK})
				result = sandbox.run(*args)
				self.assertEqual(result.stdout, "ALERT: 'psk' not found\n", result.stderr)
				self.assertEqual(result.returncode, 1)
				self.assert_no_missing_command(result)

	# --install-version

	def assert_installs(self, sandbox, version, package):
		result = sandbox.run("--install-version", version)
		self.assertEqual(result.stdout, "OK\n", result.stderr)
		self.assert_no_missing_command(result)
		self.assertEqual(sandbox.calls("apt-get"), [["apt-get", "install", "-y", "--allow-downgrades", package + "=" + version]])
		self.assertEqual(sandbox.calls("reboot"), [["reboot"]])

	def test_install_indigo3_version(self):
		sandbox = self.sandbox({"apt-cache": apt_cache_stub(0)})
		self.assert_installs(sandbox, INDIGO3_VERSION, "indigo3")

	def test_install_indigo_version(self):
		for missing_status in (0, 100):
			with self.subTest(apt_cache_missing_status=missing_status):
				sandbox = self.sandbox({"apt-cache": apt_cache_stub(missing_status)})
				self.assert_installs(sandbox, INDIGO_VERSION, "indigo")

	# --set-wifi-client

	def test_set_wifi_client_empty_password_joins_open_network(self):
		sandbox = self.sandbox()
		result = sandbox.run("--set-wifi-client", SSID, "")
		self.assertEqual(result.stdout, "OK\n", result.stderr)
		self.assertEqual(result.returncode, 0)
		self.assert_no_missing_command(result)
		calls = sandbox.calls("nmcli")
		self.assertIn(["nmcli", "dev", "wifi", "connect", SSID], calls)
		self.assertFalse([call for call in calls if "password" in call], calls)

	def test_set_wifi_client_rejects_invalid_password_length(self):
		for length, message in ((1, "WIFI_CN_PW length < 8"), (7, "WIFI_CN_PW length < 8"), (64, "WIFI_CN_PW length > 63")):
			with self.subTest(length=length):
				sandbox = self.sandbox()
				result = sandbox.run("--set-wifi-client", SSID, "p" * length)
				self.assertEqual(result.stdout, "ALERT: " + message + "\n", result.stderr)
				self.assertEqual(result.returncode, 1)
				self.assert_no_missing_command(result)
				self.assertEqual(sandbox.calls(), [], "commands issued after an invalid password")

	def test_set_wifi_client_valid_password_joins_network(self):
		for length in (8, 63):
			with self.subTest(length=length):
				password = "p" * length
				sandbox = self.sandbox()
				result = sandbox.run("--set-wifi-client", SSID, password)
				self.assertEqual(result.stdout, "OK\n", result.stderr)
				self.assertEqual(result.returncode, 0)
				self.assert_no_missing_command(result)
				self.assertIn(["nmcli", "dev", "wifi", "connect", SSID, "password", password], sandbox.calls("nmcli"))

