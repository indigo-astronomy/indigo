# Faults apply only to this CLI translation unit. Real close always runs, so the
# failure cases also exercise normal ownership without leaking file descriptors.
FAULT_WRAPPER = r"""
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <errno.h>
static int fault(const char *name, unsigned count) {
	char point[32];
	snprintf(point, sizeof(point), "%s%u", name, count);
	return getenv("INDIGO_TEST_FAULT") && strcmp(getenv("INDIGO_TEST_FAULT"), point) == 0;
}
void *test_malloc(size_t bytes) {
	static unsigned count;
	return fault("malloc", ++count) ? NULL : malloc(bytes);
}
size_t test_fread(void *ptr, size_t size, size_t count, FILE *file) {
	static unsigned calls;
	return fault("fread", ++calls) ? 0 : fread(ptr, size, count, file);
}
size_t test_fwrite(const void *ptr, size_t size, size_t count, FILE *file) {
	static unsigned calls;
	return fault("fwrite", ++calls) ? 0 : fwrite(ptr, size, count, file);
}
int test_fclose(FILE *file) {
	static unsigned count;
	int result = fclose(file);
	if (fault("fclose", ++count)) {
		errno = EIO;
		return EOF;
	}
	return result;
}
"""


