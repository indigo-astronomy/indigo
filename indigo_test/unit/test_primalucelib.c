	ASSERT_EQ_INT(PRIMALUCELIB_MODEL_GIOTTO, primalucelib_model_from_name("GIOTTO"));
	ASSERT_EQ_INT(PRIMALUCELIB_MODEL_ALTO, primalucelib_model_from_name("ALTO"));
	ASSERT_EQ_INT(PRIMALUCELIB_MODEL_UNKNOWN, primalucelib_model_from_name("ARCO"));
	ASSERT_EQ_INT(PRIMALUCELIB_MODEL_UNKNOWN, primalucelib_model_from_name(NULL));
	ASSERT_TRUE(primalucelib_model_is_focuser(PRIMALUCELIB_MODEL_SESTOSENSO));
	ASSERT_TRUE(primalucelib_model_is_focuser(PRIMALUCELIB_MODEL_SESTOSENSO3));
