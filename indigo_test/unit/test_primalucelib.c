// Unit tests of the PrimaLuce Lab protocol library in indigo_drivers/shared/primalucelib, linked as
// the same static library the drivers link. Each case talks to the library over a fresh
// pseudo-terminal; a peer thread on the master side records every request and answers it from a
// script. The golden requests are the request templates of indigo_focuser_primaluce before the
// library was extracted, copied verbatim, so a byte that changes on the wire fails here.

