	CHECK(!strcmp(primalucelib_reply_stored_position_name(&test_link, 2), ""));
	CHECK(primalucelib_reply_stored_position_name(&test_link, 3) == NULL);
	CHECK(primalucelib_reply_rotator_angle(&test_link, PRIMALUCELIB_ANGLE_POSITION_DEG) == 12.5);
	CHECK(primalucelib_reply_rotator_angle(&test_link, PRIMALUCELIB_ANGLE_ABS_POS_DEG) == 30);
	CHECK(primalucelib_reply_rotator_angle(&test_link, PRIMALUCELIB_ANGLE_ABS_POS_REGISTER) == 0);
	primalucelib_reply_motor_config(&test_link, &config);
	CHECK(config.acceleration_speed == 1 && config.run_speed == 2 && config.deceleration_speed == 1);
	CHECK(config.acceleration_current == 7 && config.run_current == 7 && config.deceleration_current == 7 && config.hold_current == 1);
