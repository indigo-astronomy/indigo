"""Startup ownership regressions with in-memory output and mocked processes only."""

import importlib.util
import io
from pathlib import Path
import signal
import subprocess
import unittest
from unittest import mock

ROOT = Path(__file__).resolve().parents[2]
SPEC = importlib.util.spec_from_file_location("alpaca_omnisim_conformu", ROOT / "tools/alpaca_omnisim_conformu.py")
OMNISIM = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(OMNISIM)


class OmniSimStartupTests(unittest.TestCase):
	def setUp(self):
		self.process = mock.Mock(pid=12345)
		self.process.poll.return_value = None
		self.streams = []
		self.open = self.patch(OMNISIM, "open", side_effect=self.open_output, create=True)
		self.patch(OMNISIM.os, "makedirs")
		self.popen = self.patch(OMNISIM.subprocess, "Popen", side_effect=self.spawn)
		self.wait_for = self.patch(OMNISIM, "wait_for")
		self.get_json = self.patch(OMNISIM, "get_json", return_value=[1])
		self.killpg = self.patch(OMNISIM.os, "killpg")

	def patch(self, target, attribute, **kwargs):
		patcher = mock.patch.object(target, attribute, **kwargs)
		self.addCleanup(patcher.stop)
		return patcher.start()

	def open_output(self, *args, **kwargs):
		stream = io.StringIO()
		self.streams.append(stream)
		return stream

	def spawn(self, *args, **kwargs):
		self.assertIs(self.streams[-1], kwargs["stdout"])
		self.assertFalse(kwargs["stdout"].closed)
		return self.process

	def assert_output_closed(self):
		self.assertTrue(self.streams)
		self.assertTrue(all(stream.closed for stream in self.streams))

	def assert_stopped(self):
		self.killpg.assert_called_once_with(self.process.pid, signal.SIGTERM)
		self.process.wait.assert_called_once_with(10)

	def test_ready_process_is_returned_and_parent_output_is_closed(self):
		with mock.patch.dict(OMNISIM.os.environ, {"XDG_CONFIG_HOME": "/private/config", "XDG_DATA_HOME": "/private/data"}):
			process = OMNISIM.start_omnisim("fake-omnisim", 1234, "/fixture")
		self.assertIs(process, self.process)
		self.assert_output_closed()
		self.killpg.assert_not_called()
		self.process.wait.assert_not_called()
		args, kwargs = self.popen.call_args
		self.assertEqual(["fake-omnisim", "--urls=http://127.0.0.1:1234"], args[0])
		self.assertEqual("/fixture/omnisim_home", kwargs["cwd"])
		self.assertTrue(kwargs["start_new_session"])
		self.assertEqual(subprocess.STDOUT, kwargs["stderr"])
		self.assertNotIn("XDG_CONFIG_HOME", kwargs["env"])
		self.assertNotIn("XDG_DATA_HOME", kwargs["env"])
		self.assertEqual("/fixture/omnisim_home", kwargs["env"]["HOME"])
		predicate, timeout, what = self.wait_for.call_args.args
		self.assertEqual((60, "OmniSim"), (timeout, what))
		self.assertEqual([1], predicate())
		self.get_json.assert_called_once_with("http://127.0.0.1:1234/management/apiversions")

	def test_ready_response_does_not_return_an_already_exited_child(self):
		self.process.poll.return_value = 1
		with mock.patch.object(OMNISIM, "stop", wraps=OMNISIM.stop) as stop:
			with self.assertRaisesRegex(RuntimeError, "OmniSim exited before startup completed"):
				OMNISIM.start_omnisim("fake-omnisim", 1234, "/fixture")
			stop.assert_called_once_with(self.process)
		self.wait_for.assert_called_once()
		self.process.poll.assert_called()
		self.killpg.assert_not_called()
		self.process.wait.assert_not_called()
		self.assert_output_closed()

	def test_readiness_failure_stops_owned_session_and_preserves_exception(self):
		failure = RuntimeError("not ready")
		self.wait_for.side_effect = failure
		with self.assertRaises(RuntimeError) as raised:
			OMNISIM.start_omnisim("fake-omnisim", 1234, "/fixture")
		self.assertIs(failure, raised.exception)
		self.assert_stopped()
		self.assert_output_closed()

	def test_readiness_interrupt_stops_owned_session(self):
		interruption = KeyboardInterrupt()
		self.wait_for.side_effect = interruption
		with self.assertRaises(KeyboardInterrupt) as raised:
			OMNISIM.start_omnisim("fake-omnisim", 1234, "/fixture")
		self.assertIs(interruption, raised.exception)
		self.assert_stopped()
		self.assert_output_closed()

	def test_stop_failure_does_not_replace_readiness_failure(self):
		failure = RuntimeError("not ready")
		self.wait_for.side_effect = failure
		with mock.patch.object(OMNISIM, "stop", side_effect=OSError("cleanup failed")) as stop:
			with self.assertRaises(RuntimeError) as raised:
				OMNISIM.start_omnisim("fake-omnisim", 1234, "/fixture")
			stop.assert_called_once_with(self.process)
		self.assertIs(failure, raised.exception)
		self.assert_output_closed()

	def test_stop_interrupt_does_not_replace_readiness_failure(self):
		failure = RuntimeError("not ready")
		self.wait_for.side_effect = failure
		with mock.patch.object(OMNISIM, "stop", side_effect=KeyboardInterrupt()) as stop:
			with self.assertRaises(RuntimeError) as raised:
				OMNISIM.start_omnisim("fake-omnisim", 1234, "/fixture")
			stop.assert_called_once_with(self.process)
		self.assertIs(failure, raised.exception)
		self.assert_output_closed()

	def test_spawn_failure_closes_output_without_waiting(self):
		failure = OSError("spawn failed")
		self.popen.side_effect = failure
		with self.assertRaises(OSError) as raised:
			OMNISIM.start_omnisim("fake-omnisim", 1234, "/fixture")
		self.assertIs(failure, raised.exception)
		self.assert_output_closed()
		self.wait_for.assert_not_called()
		self.killpg.assert_not_called()

	def test_readiness_failure_retains_existing_force_stop_fallback(self):
		failure = RuntimeError("not ready")
		self.wait_for.side_effect = failure
		self.process.wait.side_effect = subprocess.TimeoutExpired("fake-omnisim", 10)
		with self.assertRaises(RuntimeError) as raised:
			OMNISIM.start_omnisim("fake-omnisim", 1234, "/fixture")
		self.assertIs(failure, raised.exception)
		self.killpg.assert_has_calls([mock.call(self.process.pid, signal.SIGTERM), mock.call(self.process.pid, signal.SIGKILL)])
		self.assertEqual(2, self.killpg.call_count)
		self.process.wait.assert_called_once_with(10)
		self.assert_output_closed()

	def test_readiness_failure_does_not_signal_an_already_exited_child(self):
		failure = RuntimeError("not ready")
		self.wait_for.side_effect = failure
		self.process.poll.return_value = 1
		with self.assertRaises(RuntimeError) as raised:
			OMNISIM.start_omnisim("fake-omnisim", 1234, "/fixture")
		self.assertIs(failure, raised.exception)
		self.killpg.assert_not_called()
		self.process.wait.assert_not_called()
		self.assert_output_closed()


