# Code is generated by AI

"""Bounded CLI token regressions of the standalone generator."""

import os
from pathlib import Path
import shlex
import subprocess
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[2]
VALID = 'driver probe { label = "Probe"; version = 1; aux { } }\n'


class GeneratorTokens(unittest.TestCase):
	@classmethod
	def setUpClass(cls):
		cls.temporary = tempfile.TemporaryDirectory(prefix="indigo-generator-tokens-")
		cls.directory = Path(cls.temporary.name)
		cls.binary = cls.directory / "indigo_generator"
		command = shlex.split(os.environ.get("CC", "cc")) + ["-std=gnu11", "-O1", "-Wno-format", str(ROOT / "indigo_tools/indigo_generator.c"), "-o", str(cls.binary)]
		subprocess.run(command, check=True, capture_output=True)

	@classmethod
	def tearDownClass(cls):
		cls.temporary.cleanup()

	def generate(self, source):
		path = self.directory / "probe.driver"
		path.write_text(source)
		return subprocess.run([str(self.binary), path.name], cwd=self.directory, capture_output=True, text=True, timeout=2)

	def test_valid_definition_still_generates(self):
		result = self.generate(VALID)
		self.assertEqual(0, result.returncode, result.stderr)
		for name in ["indigo_aux_probe.c", "indigo_aux_probe.h", "indigo_aux_probe_main.c"]:
			self.assertTrue((self.directory / name).is_file(), name)

	def test_unsupported_byte_rejected_with_position(self):
		for token in ["@", "?", "\x01", "é"]:
			with self.subTest(token=token):
				result = self.generate(VALID.replace("version = 1;", "version = 1; " + token))
				self.assertNotEqual(0, result.returncode, result.stderr)
				self.assertRegex(result.stderr, r"ERROR \(\d+:\d+\): Unsupported byte 0x[0-9A-F]{2}")

	def test_keyword_prefix_is_not_a_keyword(self):
		result = self.generate(VALID.replace("driver probe", "driverXYZ probe"))
		self.assertNotEqual(0, result.returncode, result.stderr)
		self.assertIn("Missing 'driver' keyword", result.stderr)

	def test_boolean_prefix_is_not_a_boolean(self):
		for token in ["trueXYZ", "falseXYZ"]:
			with self.subTest(token=token):
				result = self.generate(VALID.replace("version = 1;", "version = 1; multi_device_support = " + token + ";"))
				self.assertNotEqual(0, result.returncode, result.stderr)


if __name__ == "__main__":
	unittest.main(verbosity=2)
