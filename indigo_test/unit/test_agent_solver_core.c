// the code of a quad must not change under translation, rotation, scaling and mirroring of the image
static void test_quad_code_invariance(void) {
	int exact = 0;
	for (int n = 0; n < 300; n++) {
		indigo_solver_star a[4], b[4];
		float angle = frand() * 2 * M_PI, scale = 0.3 + 2 * frand(), tx = frand() * 1000, ty = frand() * 1000;
		bool mirror = frand() < 0.5;
		for (int i = 0; i < 4; i++) {
			memset(a + i, 0, sizeof(indigo_solver_star));
			a[i].x = frand() * 500;
			a[i].y = frand() * 500;
			float x = mirror ? -a[i].x : a[i].x;
			b[i] = a[i];
			b[i].x = tx + scale * (x * cos(angle) - a[i].y * sin(angle));
			b[i].y = ty + scale * (x * sin(angle) + a[i].y * cos(angle));
		}
		indigo_solver_quad qa, qb;
		indigo_solver_make_quad(&qa, a, a + 1, a + 2, a + 3);
		indigo_solver_make_quad(&qb, b, b + 1, b + 2, b + 3);
		int ax3, ay3, ax4, ay4, bx3, by3, bx4, by4;
		indigo_solver_quad_hash_components(qa.hash, &ax3, &ay3, &ax4, &ay4);
		indigo_solver_quad_hash_components(qb.hash, &bx3, &by3, &bx4, &by4);
		// rounding at a quantisation boundary or an ambiguous ordering may move the code by one quantum,
		// which the matching tolerance covers; the variants of the ambiguous codes must contain the other one
		bool close = abs(ax3 - bx3) <= 1 && abs(ay3 - by3) <= 1 && abs(ax4 - bx4) <= 1 && abs(ay4 - by4) <= 1;
		if (!close) {
			indigo_solver_quad variants[INDIGO_SOLVER_MAX_QUAD_VARIANTS];
			int count = indigo_solver_make_quad_variants(variants, INDIGO_SOLVER_MAX_QUAD_VARIANTS, a, a + 1, a + 2, a + 3);
			for (int i = 0; i < count && !close; i++) {
				int vx3, vy3, vx4, vy4;
				indigo_solver_quad_hash_components(variants[i].hash, &vx3, &vy3, &vx4, &vy4);
				close = abs(vx3 - bx3) <= 1 && abs(vy3 - by3) <= 1 && abs(vx4 - bx4) <= 1 && abs(vy4 - by4) <= 1;
			}
		}
		ASSERT_TRUE(close);
		ASSERT_TRUE(fabs(qb.baseline / qa.baseline - scale) < 1e-3 * scale);
		if (qa.hash == qb.hash) {
			exact++;
		}
	}
	ASSERT_TRUE(exact > 150);
}

static void test_quad_variants_canonical_first(void) {
	for (int n = 0; n < 200; n++) {
		indigo_solver_star s[4];
		for (int i = 0; i < 4; i++) {
			memset(s + i, 0, sizeof(indigo_solver_star));
			s[i].x = frand() * 500;
			s[i].y = frand() * 500;
		}
		indigo_solver_quad canonical, variants[INDIGO_SOLVER_MAX_QUAD_VARIANTS];
		indigo_solver_make_quad(&canonical, s, s + 1, s + 2, s + 3);
		int count = indigo_solver_make_quad_variants(variants, INDIGO_SOLVER_MAX_QUAD_VARIANTS, s, s + 1, s + 2, s + 3);
		ASSERT_TRUE(count >= 1 && count <= INDIGO_SOLVER_MAX_QUAD_VARIANTS);
		ASSERT_TRUE(variants[0].hash == canonical.hash);
		for (int i = 1; i < count; i++) {
			ASSERT_TRUE(variants[i].hash != variants[0].hash);
		}
		// the code lies in the lens between P1 = (0, 0) and P2 = (1, 0), mirrored to y3 >= 0
		ASSERT_TRUE(canonical.x3 >= -1e-5 && canonical.x3 <= 1 + 1e-5);
		ASSERT_TRUE(canonical.x4 >= -1e-5 && canonical.x4 <= 1 + 1e-5);
		ASSERT_TRUE(canonical.y3 >= -1e-5);
	}
}

static void test_index_file_roundtrip(void) {
	char path[] = "/tmp/indigo_test_solver_index_XXXXXX";
	int fd = mkstemp(path);
	ASSERT_TRUE(fd >= 0);
	close(fd);
	indigo_solve_index_header header = { .magic = INDIGO_SOLVER_INDEX_MAGIC, .version = INDIGO_SOLVER_INDEX_VERSION, .fov = 5, .star_count = 3, .quad_count = 2 };
	indigo_solver_index_star stars[3] = { { 0.1f, -0.2f }, { 1.5f, 0.7f }, { 6.2f, -1.4f } };
	indigo_solver_index_quad quads[2] = { { 0x0001000200030004ull, 123.5f, { 0, 1, 2, 0 } }, { 0x03E8000003E8FC18ull, 0.25f, { 2, 1, 0, 1 } } };
	FILE *file = fopen(path, "wb");
	ASSERT_TRUE(file != NULL);
	ASSERT_TRUE(indigo_solver_index_write_header(file, &header));
	ASSERT_TRUE(indigo_solver_index_write_stars(file, stars, 3));
	ASSERT_TRUE(indigo_solver_index_write_quads(file, quads, 2));
	fclose(file);
	file = fopen(path, "rb");
	ASSERT_TRUE(file != NULL);
	fseek(file, 0, SEEK_END);
	ASSERT_EQ_INT(INDIGO_SOLVER_INDEX_HEADER_SIZE + 3 * INDIGO_SOLVER_INDEX_STAR_SIZE + 2 * INDIGO_SOLVER_INDEX_QUAD_SIZE, (int)ftell(file));
	fseek(file, 0, SEEK_SET);
	indigo_solve_index_header read_header;
	indigo_solver_index_star read_stars[3];
	indigo_solver_index_quad read_quads[2];
	ASSERT_TRUE(indigo_solver_index_read_header(file, &read_header));
	ASSERT_TRUE(read_header.version == INDIGO_SOLVER_INDEX_VERSION && read_header.fov == 5 && read_header.star_count == 3 && read_header.quad_count == 2);
	ASSERT_TRUE(indigo_solver_index_read_stars(file, read_stars, 3));
	ASSERT_TRUE(indigo_solver_index_read_quads(file, read_quads, 2));
	ASSERT_TRUE(memcmp(stars, read_stars, sizeof(stars)) == 0);
	for (int i = 0; i < 2; i++) {
		ASSERT_TRUE(read_quads[i].hash == quads[i].hash && read_quads[i].baseline == quads[i].baseline && memcmp(read_quads[i].stars, quads[i].stars, sizeof(quads[i].stars)) == 0);
	}
	// a truncated file is reported
	ASSERT_FALSE(indigo_solver_index_read_quads(file, read_quads, 1));
	fclose(file);
	// a wrong magic or version is rejected
	file = fopen(path, "wb");
	ASSERT_TRUE(file != NULL);
	header.version = INDIGO_SOLVER_INDEX_VERSION + 1;
	ASSERT_TRUE(indigo_solver_index_write_header(file, &header));
	fclose(file);
	file = fopen(path, "rb");
	ASSERT_FALSE(indigo_solver_index_read_header(file, &read_header));
	fclose(file);
	file = fopen(path, "wb");
	ASSERT_TRUE(file != NULL);
	memcpy(header.magic, "FITS", 4);
	header.version = INDIGO_SOLVER_INDEX_VERSION;
	ASSERT_TRUE(indigo_solver_index_write_header(file, &header));
	fclose(file);
	file = fopen(path, "rb");
	ASSERT_FALSE(indigo_solver_index_read_header(file, &read_header));
	fclose(file);
	// a loaded index must reference existing stars only
	indigo_solver_star *loaded_stars;
	indigo_solver_quad *loaded_quads;
	int star_count, quad_count;
	file = fopen(path, "wb");
	ASSERT_TRUE(file != NULL);
	memcpy(header.magic, INDIGO_SOLVER_INDEX_MAGIC, 4);
	quads[1].stars[0] = 7;
	ASSERT_TRUE(indigo_solver_index_write_header(file, &header));
	ASSERT_TRUE(indigo_solver_index_write_stars(file, stars, 3));
	ASSERT_TRUE(indigo_solver_index_write_quads(file, quads, 2));
	fclose(file);
	ASSERT_FALSE(indigo_solver_load_index(path, &loaded_stars, &star_count, &loaded_quads, &quad_count));
	ASSERT_TRUE(loaded_stars == NULL && loaded_quads == NULL);
	quads[1].stars[0] = 2;
	file = fopen(path, "wb");
	ASSERT_TRUE(file != NULL);
	ASSERT_TRUE(indigo_solver_index_write_header(file, &header));
	ASSERT_TRUE(indigo_solver_index_write_stars(file, stars, 3));
	ASSERT_TRUE(indigo_solver_index_write_quads(file, quads, 2));
	fclose(file);
	ASSERT_TRUE(indigo_solver_load_index(path, &loaded_stars, &star_count, &loaded_quads, &quad_count));
	ASSERT_EQ_INT(3, star_count);
	ASSERT_EQ_INT(2, quad_count);
	// the unsorted input is sorted by hash on load
	ASSERT_TRUE(loaded_quads[0].hash <= loaded_quads[1].hash);
	ASSERT_TRUE(loaded_quads[0].stars[0] == loaded_stars + 0 && loaded_quads[0].stars[1] == loaded_stars + 1);
	indigo_solver_free_catalog(loaded_stars, loaded_quads);
	unlink(path);
}

static void test_index_selection(void) {
	char dir[] = "/tmp/indigo_test_solver_dir_XXXXXX";
	ASSERT_TRUE(mkdtemp(dir) != NULL);
	char path[PATH_MAX], selected[PATH_MAX];
	float fov;
	// no files: nothing to select
	ASSERT_FALSE(indigo_solver_select_index(dir, indigo_solver_index_fovs, INDIGO_SOLVER_INDEX_FOV_COUNT, 3 * DEG_TO_RAD, 2 * DEG_TO_RAD, selected, sizeof(selected), &fov));
	float present[] = { 2, 5, 20 };
	for (int i = 0; i < 3; i++) {
		indigo_solver_index_path(path, sizeof(path), dir, present[i]);
		FILE *file = fopen(path, "wb");
		ASSERT_TRUE(file != NULL);
		fclose(file);
	}
	// 3.75 x 2.8 degrees: 1.5 x geometric mean is 4.9, the largest present index below it is 2
	ASSERT_TRUE(indigo_solver_select_index(dir, present, 3, 3.75 * DEG_TO_RAD, 2.8 * DEG_TO_RAD, selected, sizeof(selected), &fov));
	ASSERT_TRUE(fov == 2);
	indigo_solver_index_path(path, sizeof(path), dir, 2);
	ASSERT_TRUE(strcmp(path, selected) == 0);
	// a 10 degree field selects 5, a 30 degree field 20, a tiny field falls back to the smallest present one
	ASSERT_TRUE(indigo_solver_select_index(dir, present, 3, 10 * DEG_TO_RAD, 8 * DEG_TO_RAD, selected, sizeof(selected), &fov) && fov == 5);
	ASSERT_TRUE(indigo_solver_select_index(dir, present, 3, 30 * DEG_TO_RAD, 20 * DEG_TO_RAD, selected, sizeof(selected), &fov) && fov == 20);
	ASSERT_TRUE(indigo_solver_select_index(dir, present, 3, 0.5 * DEG_TO_RAD, 0.3 * DEG_TO_RAD, selected, sizeof(selected), &fov) && fov == 2);
	// only the given FOVs are considered
	float only_20[] = { 20 };
	ASSERT_TRUE(indigo_solver_select_index(dir, only_20, 1, 3.75 * DEG_TO_RAD, 2.8 * DEG_TO_RAD, selected, sizeof(selected), &fov) && fov == 20);
	for (int i = 0; i < 3; i++) {
		indigo_solver_index_path(path, sizeof(path), dir, present[i]);
		unlink(path);
	}
	rmdir(dir);
}

