static void test_tangent_plane_roundtrip(void) {
	float ra0 = 97.9 * DEG_TO_RAD, dec0 = 5.1 * DEG_TO_RAD;
	for (int i = 0; i < 100; i++) {
		float ra = ra0 + (frand() - 0.5) * 6 * DEG_TO_RAD;
		float dec = dec0 + (frand() - 0.5) * 6 * DEG_TO_RAD;
		float xi, eta, ra_back, dec_back;
		ASSERT_TRUE(indigo_radec_to_tangent(ra0, dec0, ra, dec, &xi, &eta));
		indigo_tangent_to_radec(ra0, dec0, xi, eta, &ra_back, &dec_back);
		ASSERT_TRUE(fabs(ra_back - ra) < 1e-6);
		ASSERT_TRUE(fabs(dec_back - dec) < 1e-6);
	}
	// a point on the far hemisphere has no projection
	float xi, eta;
	ASSERT_FALSE(indigo_radec_to_tangent(ra0, dec0, ra0 + M_PI, -dec0, &xi, &eta));
	// RA wraps around 0/360
	ASSERT_TRUE(indigo_radec_to_tangent(0.5 * DEG_TO_RAD, 0, 359.5 * DEG_TO_RAD, 0, &xi, &eta));
	ASSERT_TRUE(fabs(xi + 1.0 * DEG_TO_RAD) < 1e-5);
}

