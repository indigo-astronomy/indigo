// The image scanner is exercised the same way as the DOM parser: from an exact heap copy of the text.
static bool scan_image_bytes(const char *text, size_t length, alpaca_json_image_format format, void **buffer, size_t *capacity, bool growable, alpaca_json_image *image) {
	char *copy = exact_copy(text, length);
	bool result = alpaca_json_parse_image(copy, length, format, buffer, capacity, growable, image, error, sizeof(error));
	free(copy);
	return result;
}

static bool scan_image(const char *text, int32_t **pixels, alpaca_json_image *image) {
	void *buffer = NULL;
	size_t capacity = 0;
	bool result = scan_image_bytes(text, strlen(text), ALPACA_JSON_IMAGE_INT32, &buffer, &capacity, true, image);
	*pixels = buffer;
	return result;
}

static bool image_rejects_bytes(const char *text, size_t length) {
	void *buffer = NULL;
	size_t capacity = 0;
	alpaca_json_image image = { 0 };
	bool result = scan_image_bytes(text, length, ALPACA_JSON_IMAGE_INT32, &buffer, &capacity, true, &image);
	free(buffer);
	if (result) {
		fprintf(stderr, "Image unexpectedly accepted: %.*s\n", (int)length, text);
		return false;
	}
	if (strstr(error, " at offset ") == NULL) {
		fprintf(stderr, "No error reported for image: %.*s\n", (int)length, text);
		return false;
	}
	return true;
}

static bool image_rejects(const char *text, const char *message) {
	if (!image_rejects_bytes(text, strlen(text))) {
		return false;
	}
	if (strstr(error, message) == NULL) {
		fprintf(stderr, "%s: expected error \"%s\", got \"%s\"\n", text, message, error);
		return false;
	}
	return true;
}

