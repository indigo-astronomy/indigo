#define ASSERT_EQ_INT64(expected, actual) ASSERT_TRUE((int64_t)(expected) == (int64_t)(actual))

static char error[256];

// Every text is parsed from a heap copy of exactly its length, without a terminating NUL, which is released
// before the result is used: the sanitizer build then reports any read past the end of the text and any
// reference from the DOM back into it.
static char *exact_copy(const char *text, size_t length) {
	char *copy = malloc(length > 0 ? length : 1);
	if (copy != NULL && length > 0) {
		memcpy(copy, text, length);
	}
	return copy;
}

static alpaca_json_value *parse_bytes(const char *text, size_t length) {
	char *copy = exact_copy(text, length);
	alpaca_json_value *root = alpaca_json_parse(copy, length, error, sizeof(error));
	free(copy);
	return root;
}

static alpaca_json_value *parse_text(const char *text) {
	return parse_bytes(text, strlen(text));
}

static bool rejects_bytes(const char *text, size_t length) {
	alpaca_json_value *root = parse_bytes(text, length);
	if (root != NULL) {
		fprintf(stderr, "Unexpectedly accepted: %.*s\n", (int)length, text);
		alpaca_json_free(root);
		return false;
	}
	if (strstr(error, " at offset ") == NULL) {
		fprintf(stderr, "No error reported for: %.*s\n", (int)length, text);
		return false;
	}
	return true;
}

static bool rejects(const char *text) {
	return rejects_bytes(text, strlen(text));
}

static bool rejects_all(const char *const *texts, int count) {
	bool result = true;
	for (int i = 0; i < count; i++) {
		if (!rejects(texts[i])) {
			result = false;
		}
	}
	return result;
}

static long error_offset(void) {
	const char *offset = strstr(error, " at offset ");
	return offset != NULL ? atol(offset + 11) : -1;
}

static bool parses_double(const char *text, double expected) {
	double value = 0;
	alpaca_json_value *root = parse_text(text);
	bool result = alpaca_json_get_type(root) == ALPACA_JSON_NUMBER && alpaca_json_get_double(root, &value) && value == expected;
	if (!result) {
		fprintf(stderr, "%s: expected %.17g, got %.17g (%s)\n", text, expected, value, error);
	}
	alpaca_json_free(root);
	return result;
}

static bool parses_int(const char *text, int64_t expected) {
	int64_t value = 0;
	alpaca_json_value *root = parse_text(text);
	bool result = alpaca_json_get_type(root) == ALPACA_JSON_NUMBER && alpaca_json_get_int(root, &value) && value == expected;
	if (!result) {
		fprintf(stderr, "%s: expected %lld, got %lld (%s)\n", text, (long long)expected, (long long)value, error);
	}
	alpaca_json_free(root);
	return result;
}

static bool is_number_but_not_int(const char *text) {
	int64_t value = 12345;
	alpaca_json_value *root = parse_text(text);
	bool result = alpaca_json_get_type(root) == ALPACA_JSON_NUMBER && alpaca_json_get_double(root, NULL) && !alpaca_json_get_int(root, &value) && value == 12345;
	if (!result) {
		fprintf(stderr, "%s: expected a number without an integer value (%s)\n", text, error);
	}
	alpaca_json_free(root);
	return result;
}

static bool parses_string(const char *text, const char *expected, size_t expected_length) {
	const char *value = NULL;
	alpaca_json_value *root = parse_text(text);
	bool result = alpaca_json_get_type(root) == ALPACA_JSON_STRING && alpaca_json_get_string(root, &value) && alpaca_json_get_string_length(root) == expected_length && memcmp(value, expected, expected_length + 1) == 0;
	if (!result) {
		fprintf(stderr, "%s: expected \"%s\", got \"%s\" (%s)\n", text, expected, value != NULL ? value : "(null)", error);
	}
	alpaca_json_free(root);
	return result;
}

static char *read_fixture(const char *path, size_t *length) {
	FILE *file = fopen(path, "rb");
	if (file == NULL) {
		perror(path);
		return NULL;
	}
	fseek(file, 0, SEEK_END);
	long size = ftell(file);
	fseek(file, 0, SEEK_SET);
	char *buffer = malloc(size > 0 ? (size_t)size : 1);
	*length = fread(buffer, 1, (size_t)size, file);
	fclose(file);
	return buffer;
}

static alpaca_json_value *parse_fixture(const char *path) {
	size_t length = 0;
	char *text = read_fixture(path, &length);
	if (text == NULL) {
		return NULL;
	}
	alpaca_json_value *root = alpaca_json_parse(text, length, error, sizeof(error));
	if (root == NULL) {
		fprintf(stderr, "%s: %s\n", path, error);
	}
	free(text);
	return root;
}

static bool member_int_equals(const alpaca_json_value *object, const char *name, int64_t expected) {
	int64_t value = 0;
	return alpaca_json_get_int(alpaca_json_get(object, name), &value) && value == expected;
}

static bool member_string_equals(const alpaca_json_value *object, const char *name, const char *expected) {
	const char *value = NULL;
	return alpaca_json_get_string(alpaca_json_get(object, name), &value) && strcmp(value, expected) == 0;
}

static double seconds(void) {
	struct timespec now = { 0 };
	clock_gettime(CLOCK_MONOTONIC, &now);
	return (double)now.tv_sec + (double)now.tv_nsec / 1e9;
}

static void parses_scalar_documents_of_every_type(void) {
	bool boolean = false;
	alpaca_json_value *root = parse_text("null");
	ASSERT_TRUE(root != NULL);
	ASSERT_EQ_INT(ALPACA_JSON_NULL, alpaca_json_get_type(root));
	ASSERT_TRUE(alpaca_json_is_null(root));
	alpaca_json_free(root);
	root = parse_text("true");
	ASSERT_EQ_INT(ALPACA_JSON_BOOL, alpaca_json_get_type(root));
	ASSERT_TRUE(alpaca_json_get_bool(root, &boolean) && boolean);
	ASSERT_FALSE(alpaca_json_is_null(root));
	alpaca_json_free(root);
	root = parse_text("false");
	ASSERT_EQ_INT(ALPACA_JSON_BOOL, alpaca_json_get_type(root));
	ASSERT_TRUE(alpaca_json_get_bool(root, &boolean) && !boolean);
	alpaca_json_free(root);
	ASSERT_TRUE(parses_int("42", 42));
	ASSERT_TRUE(parses_double("-2.5", -2.5));
	ASSERT_TRUE(parses_string("\"text\"", "text", 4));
	root = parse_text("[]");
	ASSERT_EQ_INT(ALPACA_JSON_ARRAY, alpaca_json_get_type(root));
	alpaca_json_free(root);
	root = parse_text("{}");
	ASSERT_EQ_INT(ALPACA_JSON_OBJECT, alpaca_json_get_type(root));
	alpaca_json_free(root);
}

static void parses_nested_containers(void) {
	alpaca_json_value *root = parse_text("{\"a\":[1,[2,3,{\"b\":null}],\"x\"],\"c\":{\"d\":{\"e\":[true,false]}},\"f\":-7}");
	ASSERT_TRUE(root != NULL);
	ASSERT_EQ_INT(3, alpaca_json_size(root));
	const alpaca_json_value *a = alpaca_json_get(root, "a");
	ASSERT_EQ_INT(ALPACA_JSON_ARRAY, alpaca_json_get_type(a));
	ASSERT_EQ_INT(3, alpaca_json_size(a));
	ASSERT_TRUE(member_int_equals(root, "f", -7));
	int64_t integer = 0;
	ASSERT_TRUE(alpaca_json_get_int(alpaca_json_array_get(a, 0), &integer) && integer == 1);
	const alpaca_json_value *inner = alpaca_json_array_get(a, 1);
	ASSERT_EQ_INT(3, alpaca_json_size(inner));
	ASSERT_TRUE(alpaca_json_get_int(alpaca_json_array_get(inner, 1), &integer) && integer == 3);
	ASSERT_TRUE(alpaca_json_is_null(alpaca_json_get(alpaca_json_array_get(inner, 2), "b")));
	const char *string = NULL;
	ASSERT_TRUE(alpaca_json_get_string(alpaca_json_array_get(a, 2), &string));
	ASSERT_STREQ("x", string);
	const alpaca_json_value *e = alpaca_json_get(alpaca_json_get(alpaca_json_get(root, "c"), "d"), "e");
	bool boolean = false;
	ASSERT_EQ_INT(2, alpaca_json_size(e));
	ASSERT_TRUE(alpaca_json_get_bool(alpaca_json_array_get(e, 0), &boolean) && boolean);
	ASSERT_TRUE(alpaca_json_get_bool(alpaca_json_array_get(e, 1), &boolean) && !boolean);
	alpaca_json_free(root);
}

static void parses_empty_containers(void) {
	alpaca_json_value *root = parse_text("{\"a\":[],\"b\":{},\"c\":[[],{},[{}]],\"d\":\"\"}");
	ASSERT_TRUE(root != NULL);
	ASSERT_EQ_INT(4, alpaca_json_size(root));
	ASSERT_EQ_INT(ALPACA_JSON_ARRAY, alpaca_json_get_type(alpaca_json_get(root, "a")));
	ASSERT_EQ_INT(0, alpaca_json_size(alpaca_json_get(root, "a")));
	ASSERT_TRUE(alpaca_json_first(alpaca_json_get(root, "a")) == NULL);
	ASSERT_EQ_INT(ALPACA_JSON_OBJECT, alpaca_json_get_type(alpaca_json_get(root, "b")));
	ASSERT_EQ_INT(0, alpaca_json_size(alpaca_json_get(root, "b")));
	const alpaca_json_value *c = alpaca_json_get(root, "c");
	ASSERT_EQ_INT(3, alpaca_json_size(c));
	ASSERT_EQ_INT(ALPACA_JSON_ARRAY, alpaca_json_get_type(alpaca_json_array_get(c, 0)));
	ASSERT_EQ_INT(ALPACA_JSON_OBJECT, alpaca_json_get_type(alpaca_json_array_get(c, 1)));
	ASSERT_EQ_INT(1, alpaca_json_size(alpaca_json_array_get(c, 2)));
	ASSERT_EQ_INT(ALPACA_JSON_OBJECT, alpaca_json_get_type(alpaca_json_array_get(alpaca_json_array_get(c, 2), 0)));
	ASSERT_TRUE(parses_string("\"\"", "", 0));
	alpaca_json_free(root);
}

