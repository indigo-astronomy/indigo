static void image_fails_cleanly_at_every_prefix(void) {
	const char *paths[] = { "fixtures/protocol/alpaca_imagearray_rank2.json", "fixtures/protocol/alpaca_imagearray_rank3.json", "fixtures/protocol/alpaca_error.json" };
	for (int i = 0; i < ARRAY_SIZE(paths); i++) {
		size_t length = 0;
		char *text = read_fixture(paths[i], &length);
		ASSERT_TRUE(text != NULL);
		while (length > 0 && (text[length - 1] == '\n' || text[length - 1] == '\r')) {
			length--;
		}
		for (size_t prefix = 0; prefix < length; prefix++) {
			if (!image_rejects_bytes(text, prefix)) {
				fprintf(stderr, "%s: prefix of %d bytes was accepted\n", paths[i], (int)prefix);
				ASSERT_TRUE(false);
			}
			ASSERT_TRUE(error_offset() >= 0 && (size_t)error_offset() <= prefix);
		}
		free(text);
	}
	const char *text = "{\"Type\":3,\"Extra\":{\"a\":[1,\"\\u00e9\"]},\"Value\":[[1.5e0,-2],[3,4.0]],\"ErrorMessage\":\"\\ud83d\\ude00\"}";
	for (size_t prefix = 0; prefix < strlen(text); prefix++) {
		ASSERT_TRUE(image_rejects_bytes(text, prefix));
	}
	int32_t *pixels = NULL;
	alpaca_json_image image = { 0 };
	ASSERT_TRUE(scan_image(text, &pixels, &image));
	ASSERT_EQ_INT(4, (int)image.count);
	ASSERT_STREQ("\xF0\x9F\x98\x80", image.error_message);
	free(pixels);
}

static void image_respects_caller_buffer(void) {
	const char *text = "{\"Value\":[[1,2,3],[4,5,6]]}";
	int32_t pixels[8] = { 0 };
	void *buffer = pixels;
	size_t capacity = 6;
	alpaca_json_image image = { 0 };
	pixels[6] = 777;
	ASSERT_TRUE(scan_image_bytes(text, strlen(text), ALPACA_JSON_IMAGE_INT32, &buffer, &capacity, false, &image));
	ASSERT_TRUE(buffer == pixels);
	ASSERT_EQ_INT(6, (int)capacity);
	ASSERT_EQ_INT(6, (int)image.count);
	ASSERT_EQ_INT(6, pixels[5]);
	ASSERT_EQ_INT(777, pixels[6]);
	capacity = 5;
	ASSERT_FALSE(scan_image_bytes(text, strlen(text), ALPACA_JSON_IMAGE_INT32, &buffer, &capacity, false, &image));
	ASSERT_TRUE(strstr(error, "Image buffer too small") != NULL);
	ASSERT_TRUE(buffer == pixels);
	ASSERT_EQ_INT(5, (int)capacity);
	ASSERT_EQ_INT(777, pixels[6]);
	buffer = NULL;
	capacity = 100;
	ASSERT_FALSE(scan_image_bytes(text, strlen(text), ALPACA_JSON_IMAGE_INT32, &buffer, &capacity, false, &image));
	ASSERT_TRUE(buffer == NULL);
	capacity = 2;
	buffer = malloc(capacity * sizeof(int32_t));
	ASSERT_TRUE(scan_image_bytes(text, strlen(text), ALPACA_JSON_IMAGE_INT32, &buffer, &capacity, true, &image));
	ASSERT_TRUE(capacity >= 6);
	ASSERT_EQ_INT(6, (int)image.count);
	ASSERT_EQ_INT(1, ((int32_t *)buffer)[0]);
	ASSERT_EQ_INT(6, ((int32_t *)buffer)[5]);
	const char *second = "{\"Value\":[[9,8]]}";
	size_t before = capacity;
	void *same = buffer;
	ASSERT_TRUE(scan_image_bytes(second, strlen(second), ALPACA_JSON_IMAGE_INT32, &buffer, &capacity, true, &image));
	ASSERT_TRUE(buffer == same && capacity == before);
	ASSERT_EQ_INT(2, (int)image.count);
	ASSERT_EQ_INT(9, ((int32_t *)buffer)[0]);
	ASSERT_EQ_INT(8, ((int32_t *)buffer)[1]);
	free(buffer);
}

// Not a benchmark: one generated 2000 x 1500 16-bit frame is scanned and verified, the printed time only
// shows the order of magnitude of the JSON fallback.
static void image_scans_large_generated_array(void) {
	const int width = 2000;
	const int height = 1500;
	size_t size = (size_t)width * (size_t)height * 6 + (size_t)width * 2 + 256;
	char *text = malloc(size);
	ASSERT_TRUE(text != NULL);
	size_t used = (size_t)snprintf(text, size, "{\"Type\":2,\"Rank\":2,\"Value\":[");
	for (int x = 0; x < width; x++) {
		text[used++] = '[';
		for (int y = 0; y < height; y++) {
			unsigned value = ((unsigned)x * 31U + (unsigned)y * 17U) & 0xFFFFU;
			char digits[8] = { 0 };
			int count = 0;
			do {
				digits[count++] = (char)('0' + value % 10);
				value /= 10;
			} while (value > 0);
			while (count > 0) {
				text[used++] = digits[--count];
			}
			text[used++] = y + 1 < height ? ',' : ']';
		}
		text[used++] = x + 1 < width ? ',' : ']';
	}
	used += (size_t)snprintf(text + used, size - used, ",\"ErrorNumber\":0,\"ErrorMessage\":\"\",\"ClientTransactionID\":1,\"ServerTransactionID\":2}");
	ASSERT_TRUE(used < size);
	void *buffer = NULL;
	size_t capacity = 0;
	alpaca_json_image image = { 0 };
	double start = seconds();
	bool result = alpaca_json_parse_image(text, used, ALPACA_JSON_IMAGE_INT32, &buffer, &capacity, true, &image, error, sizeof(error));
	double elapsed = seconds() - start;
	if (!result) {
		fprintf(stderr, "%s\n", error);
	}
	ASSERT_TRUE(result);
	printf("  INFO image_scans_large_generated_array: %d x %d, %.1f MB of JSON scanned in %.3f s (%.0f MB/s)\n", width, height, (double)used / 1e6, elapsed, (double)used / 1e6 / elapsed);
	ASSERT_TRUE(image.has_value);
	ASSERT_EQ_INT(2, image.rank);
	ASSERT_EQ_INT(width, image.dimensions[0]);
	ASSERT_EQ_INT(height, image.dimensions[1]);
	ASSERT_TRUE(image.count == (size_t)width * (size_t)height);
	ASSERT_TRUE(capacity >= image.count && capacity <= image.count * 2 + 65536);
	const int32_t *pixels = buffer;
	bool equal = true;
	for (int x = 0; x < width && equal; x++) {
		for (int y = 0; y < height && equal; y++) {
			equal = pixels[(size_t)x * (size_t)height + (size_t)y] == (int32_t)(((unsigned)x * 31U + (unsigned)y * 17U) & 0xFFFFU);
		}
	}
	ASSERT_TRUE(equal);
	ASSERT_TRUE(image.minimum == 0 && image.maximum == 65535);
	ASSERT_TRUE(image.has_client_transaction_id && image.client_transaction_id == 1);
	ASSERT_TRUE(image.has_server_transaction_id && image.server_transaction_id == 2);
	size_t fixed = image.count;
	ASSERT_TRUE(alpaca_json_parse_image(text, used, ALPACA_JSON_IMAGE_INT32, &buffer, &fixed, false, &image, error, sizeof(error)));
	ASSERT_FALSE(alpaca_json_parse_image(text, used - 1, ALPACA_JSON_IMAGE_INT32, &buffer, &capacity, true, &image, error, sizeof(error)));
	ASSERT_FALSE(alpaca_json_parse_image(text, used / 2, ALPACA_JSON_IMAGE_INT32, &buffer, &capacity, true, &image, error, sizeof(error)));
	ASSERT_TRUE(alpaca_json_parse(text, used, error, sizeof(error)) == NULL);
	ASSERT_STREQ("Text too long at offset 0", error);
	free(buffer);
	free(text);
}

