static void test_start_during_night_and_day(void) {
	synthetic(&nights);
	scheduler_night_state state;
	// START in the night: the night start is handled at once
	indigo_scheduler_night_reset(&state);
	ASSERT_EQ_INT(SCHEDULER_NIGHT_START, decide(&state, 1500, true));
	ASSERT_EQ_INT(SCHEDULER_NIGHT_NONE, decide(&state, 1600, true));
	ASSERT_EQ_INT(SCHEDULER_NIGHT_END, decide(&state, 2000, true));
	// STOP and START within one night: START resets the state, the night start runs again
	indigo_scheduler_night_reset(&state);
	ASSERT_EQ_INT(SCHEDULER_NIGHT_START, decide(&state, 3100, true));
	indigo_scheduler_night_reset(&state);
	ASSERT_EQ_INT(SCHEDULER_NIGHT_START, decide(&state, 3200, true));
	// START in the day: nothing until the night starts, and no end of the night before
	indigo_scheduler_night_reset(&state);
	ASSERT_EQ_INT(SCHEDULER_NIGHT_NONE, decide(&state, 2500, true));
	ASSERT_EQ_INT(SCHEDULER_NIGHT_NONE, decide(&state, 2999, true));
	ASSERT_EQ_INT(SCHEDULER_NIGHT_START, decide(&state, 3000, true));
}

static void test_boundaries_passing_during_a_task(void) {
	synthetic(&nights);
	scheduler_night_state state;
	indigo_scheduler_night_reset(&state);
	// a task runs from 900 to 1500: the night start is handled when it ends
	ASSERT_EQ_INT(SCHEDULER_NIGHT_NONE, decide(&state, 900, true));
	ASSERT_EQ_INT(SCHEDULER_NIGHT_START, decide(&state, 1500, true));
	// a task runs from 1500 to 2300: the night end is handled when it ends
	ASSERT_EQ_INT(SCHEDULER_NIGHT_END, decide(&state, 2300, true));
	ASSERT_EQ_INT(SCHEDULER_NIGHT_NONE, decide(&state, 2300, true));
	// a task runs from 3500 in the second night until 5500 in the third: both hooks, the end first
	ASSERT_EQ_INT(SCHEDULER_NIGHT_START, decide(&state, 3500, true));
	ASSERT_EQ_INT(SCHEDULER_NIGHT_END, decide(&state, 5500, true));
	ASSERT_EQ_INT(SCHEDULER_NIGHT_START, decide(&state, 5500, true));
	ASSERT_EQ_INT(SCHEDULER_NIGHT_NONE, decide(&state, 5500, true));
	// a task that covers a whole night: that night is neither started nor ended
	indigo_scheduler_night_reset(&state);
	ASSERT_EQ_INT(SCHEDULER_NIGHT_NONE, decide(&state, 900, true));
	ASSERT_EQ_INT(SCHEDULER_NIGHT_NONE, decide(&state, 2100, true));
}

