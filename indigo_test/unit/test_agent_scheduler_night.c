	ASSERT_EQ_INT(-SCHEDULER_NIGHT_OFFSET_LIMIT, nights.start_offset);
	ASSERT_EQ_INT(SCHEDULER_NIGHT_OFFSET_LIMIT, nights.end_offset);
	moved = *indigo_scheduler_night_at(&nights, T_NOVEMBER_NIGHT);
	ASSERT_EQ_INT((int)(plain.start - 240 * 60), (int)moved.start);
	ASSERT_EQ_INT((int)(plain.end + 240 * 60), (int)moved.end);
