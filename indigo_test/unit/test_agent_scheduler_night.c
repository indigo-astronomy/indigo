static void test_recomputed_and_moved_nights(void) {
	synthetic(&nights);
	scheduler_night_state state;
	indigo_scheduler_night_reset(&state);
	ASSERT_EQ_INT(SCHEDULER_NIGHT_START, decide(&state, 1200, true));
	// the hourly computation moves the ends by a few seconds: still the same night
	nights.nights[0].start = 1010;
	nights.nights[0].end = 1990;
	ASSERT_EQ_INT(SCHEDULER_NIGHT_NONE, decide(&state, 1300, true));
	ASSERT_EQ_INT(1990, (int)state.night.end);
	// a new site ends the night earlier
	nights.nights[0].end = 1400;
	ASSERT_EQ_INT(SCHEDULER_NIGHT_END, decide(&state, 1500, true));
	// a new site where it is another night: the old one ends, the new one starts
	synthetic(&nights);
	indigo_scheduler_night_reset(&state);
	ASSERT_EQ_INT(SCHEDULER_NIGHT_START, decide(&state, 1200, true));
	synthetic(&other);
	other.nights[0].start = 1600;
	other.nights[0].end = 2600;
	ASSERT_EQ_INT(SCHEDULER_NIGHT_NONE, indigo_scheduler_night_decide(&state, &other, 1700, true));
	nights = other;
	nights.nights[0].start = 1650;
	nights.nights[0].end = 2650;
	state.night.start = 1000;
	state.night.end = 1500;
	ASSERT_EQ_INT(SCHEDULER_NIGHT_END, decide(&state, 1700, true));
	ASSERT_EQ_INT(SCHEDULER_NIGHT_START, decide(&state, 1700, true));
}

static void test_endless_and_missing_nights(void) {
	scheduler_night_state state;
	indigo_scheduler_night_reset(&state);
	// the polar night starts once and does not end
	memset(&nights, 0, sizeof(nights));
	nights.valid = true;
	nights.count = 1;
	nights.nights[0].start = 0;
	nights.nights[0].end = 100000;
	char sequence[16] = "";
	for (time_t t = 100; t < 100000; t += 1000) {
		scheduler_night_action action = decide(&state, t, true);
		if (action != SCHEDULER_NIGHT_NONE) {
			strcat(sequence, action == SCHEDULER_NIGHT_START ? "S" : "E");
		}
		// the span moves with every computation
		nights.nights[0].start = t - 50000;
		nights.nights[0].end = t + 50000;
	}
	ASSERT_STREQ("S", sequence);
	// no night at all
	indigo_scheduler_night_reset(&state);
	memset(&nights, 0, sizeof(nights));
	nights.valid = true;
	for (time_t t = 0; t < 100000; t += 1000) {
		ASSERT_EQ_INT(SCHEDULER_NIGHT_NONE, decide(&state, t, true));
	}
}

static void test_real_nights_over_three_days(void) {
	// the night start and end once per night at a real site, with hourly recomputation
	scheduler_night_state state;
	indigo_scheduler_night_reset(&state);
	time_t from = T_NOVEMBER_NIGHT - 12 * 3600;
	char sequence[32] = "";
	for (time_t t = from; t < from + 3 * 86400; t += 300) {
		if ((t - from) % 3600 == 0) {
			build(t, LATITUDE, -12, -30, 0);
		}
		scheduler_night_action action;
		while ((action = decide(&state, t, true)) != SCHEDULER_NIGHT_NONE) {
			strcat(sequence, action == SCHEDULER_NIGHT_START ? "S" : action == SCHEDULER_NIGHT_END ? "E" : "K");
			ASSERT_TRUE(strlen(sequence) < 20);
			double altitude = indigo_scheduler_sun_altitude(action == SCHEDULER_NIGHT_START ? t + 30 * 60 : t, LATITUDE, LONGITUDE, ELEVATION);
			// decisions every five minutes: the Sun is at most about a degree past the limit
			ASSERT_NEAR(-12, altitude, 1.5);
		}
	}
	ASSERT_STREQ("SESESE", sequence);
}

