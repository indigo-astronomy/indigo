static void test_ends_lie_on_the_limit(void) {
	double limits[] = { -6, -12, -18 };
	for (int l = 0; l < 3; l++) {
		build(T_NOVEMBER_NIGHT, LATITUDE, limits[l], 0, 0);
		ASSERT_TRUE(nights.valid);
		ASSERT_EQ_INT(3, nights.count);
		for (int i = 0; i < nights.count; i++) {
			scheduler_night *night = nights.nights + i;
			ASSERT_TRUE(night->start_known && night->end_known);
			ASSERT_NEAR(limits[l], indigo_scheduler_sun_altitude(night->start, LATITUDE, LONGITUDE, ELEVATION), 0.1);
			ASSERT_NEAR(limits[l], indigo_scheduler_sun_altitude(night->end, LATITUDE, LONGITUDE, ELEVATION), 0.1);
			ASSERT_TRUE(indigo_scheduler_sun_altitude(night->start - 600, LATITUDE, LONGITUDE, ELEVATION) > limits[l]);
			ASSERT_TRUE(indigo_scheduler_sun_altitude(night->start + 600, LATITUDE, LONGITUDE, ELEVATION) < limits[l]);
			ASSERT_TRUE(indigo_scheduler_sun_altitude(night->end + 600, LATITUDE, LONGITUDE, ELEVATION) > limits[l]);
		}
	}
	// the night around 23:00 in November lasts about 12 hours at the nautical limit
	build(T_NOVEMBER_NIGHT, LATITUDE, -12, 0, 0);
	const scheduler_night *night = indigo_scheduler_night_at(&nights, T_NOVEMBER_NIGHT);
	ASSERT_TRUE(night != NULL);
	ASSERT_TRUE(night->end - night->start > 11 * 3600 && night->end - night->start < 13 * 3600);
}

