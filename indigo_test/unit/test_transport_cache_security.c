static void budgets_include_published_and_retired_buffers(void) {
	// Small compile-time limits keep this check bounded; production-limit builds skip allocations.
	ASSERT_TRUE(indigo_allocate_blob_upload((size_t)INDIGO_BLOB_UPLOAD_LIMIT + 1) == NULL);
	if (INDIGO_BLOB_UPLOAD_BUDGET > 65536) {
		return;
	}
	indigo_property *property = make_property(INDIGO_WO_PERM);
	indigo_blob_entry *entry = indigo_acquire_blob(property->items);
	void *buffers[32] = { 0 };
	size_t used = 0;
	int count = 0;
	while (used < INDIGO_BLOB_UPLOAD_BUDGET && count < 32) {
		size_t amount = INDIGO_BLOB_UPLOAD_BUDGET - used;
		if (amount > INDIGO_BLOB_UPLOAD_LIMIT) {
			amount = INDIGO_BLOB_UPLOAD_LIMIT;
		}
		buffers[count] = indigo_allocate_blob_upload(amount);
		ASSERT_TRUE(buffers[count] != NULL);
		used += amount;
		count++;
	}
	ASSERT_TRUE(indigo_allocate_blob_upload(1) == NULL);
	ASSERT_TRUE(indigo_publish_blob_upload(entry, buffers[0], INDIGO_BLOB_UPLOAD_LIMIT));
	indigo_release_property(property);
	ASSERT_TRUE(indigo_allocate_blob_upload(1) == NULL);
	indigo_release_blob(entry);
	void *available = indigo_allocate_blob_upload(INDIGO_BLOB_UPLOAD_LIMIT);
	ASSERT_TRUE(available != NULL);
	indigo_free_blob_upload(available, INDIGO_BLOB_UPLOAD_LIMIT);
	for (int i = 1; i < count; i++) {
		size_t amount = INDIGO_BLOB_UPLOAD_BUDGET - (size_t)i * INDIGO_BLOB_UPLOAD_LIMIT;
		if (amount > INDIGO_BLOB_UPLOAD_LIMIT) {
			amount = INDIGO_BLOB_UPLOAD_LIMIT;
		}
		indigo_free_blob_upload(buffers[i], amount);
	}
}

