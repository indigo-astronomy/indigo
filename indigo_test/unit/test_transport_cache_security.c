static indigo_item *race_item;
static atomic_bool race_stop;
static atomic_bool race_started;
static atomic_int race_errors;

static void *read_retiring_entry(void *unused) {
	while (!atomic_load(&race_stop)) {
		indigo_blob_entry *entry = indigo_acquire_blob(race_item);
		if (entry) {
			indigo_item copy;
			if (!indigo_snapshot_blob(entry, &copy)) {
				atomic_fetch_add(&race_errors, 1);
			} else {
				if (copy.blob.size != 4 || memcmp(copy.blob.value, "race", 4)) {
					atomic_fetch_add(&race_errors, 1);
				}
				free(copy.blob.value);
			}
			indigo_release_blob(entry);
			atomic_store(&race_started, true);
		}
	}
	return NULL;
}

static void concurrent_retirement_and_lookup(void) {
	for (int iteration = 0; iteration < 50; iteration++) {
		indigo_property *property = make_property(INDIGO_WO_PERM);
		race_item = property->items;
		indigo_blob_entry *entry = indigo_acquire_blob(race_item);
		void *buffer = indigo_allocate_blob_upload(4);
		ASSERT_TRUE(buffer != NULL);
		memcpy(buffer, "race", 4);
		ASSERT_TRUE(indigo_publish_blob_upload(entry, buffer, 4));
		indigo_release_blob(entry);
		atomic_store(&race_stop, false);
		atomic_store(&race_started, false);
		atomic_store(&race_errors, 0);
		pthread_t thread;
		ASSERT_EQ_INT(0, pthread_create(&thread, NULL, read_retiring_entry, NULL));
		for (int wait = 0; wait < 1000 && !atomic_load(&race_started); wait++) {
			usleep(1000);
		}
		bool started = atomic_load(&race_started);
		indigo_release_property(property);
		atomic_store(&race_stop, true);
		pthread_join(thread, NULL);
		ASSERT_TRUE(started);
		ASSERT_EQ_INT(0, atomic_load(&race_errors));
	}
}

