// Browser helper regression: sexagesimal conversion and the HOST_TIME timestamp of indigo_server/resource/indigo.js.
// The file starts a Vue application at load time, so only the tested functions are extracted and run in a VM.

const assert = require('node:assert/strict');
const { readFileSync } = require('node:fs');
const { join } = require('node:path');
const { test } = require('node:test');
const vm = require('node:vm');

const source = readFileSync(join(__dirname, '../../indigo_server/resource/indigo.js'), 'utf8');

function extract(name) {
	const match = source.match(new RegExp(`^function ${name}\\([\\s\\S]*?^}`, 'm'));
	assert.ok(match, `function ${name} not found`);
	return match[0];
}

function load(offset) {
	class FixedDate {
		getFullYear() { return 2026; }
		getMonth() { return 9; }
		getDate() { return 5; }
		getHours() { return 7; }
		getMinutes() { return 8; }
		getSeconds() { return 9; }
		getTimezoneOffset() { return offset; }
	}
	const context = vm.createContext({ Date: FixedDate });
	vm.runInContext([extract('dtos'), extract('stod'), extract('timestamp')].join('\n'), context);
	return context;
}

const js = load(0);

test('dtos keeps the sign of values between -1 and 0', () => {
	assert.equal(js.dtos(-0.5), '-0:30:00');
	assert.equal(js.dtos(-0.25), '-0:15:00');
	assert.equal(js.dtos(0.5), '0:30:00');
});

test('dtos formats zero and whole degrees', () => {
	assert.equal(js.dtos(0), '0:00:00');
	assert.equal(js.dtos(12), '12:00:00');
	assert.equal(js.dtos(-12), '-12:00:00');
	assert.equal(js.dtos(-12.5), '-12:30:00');
	assert.equal(js.dtos(23.75), '23:45:00');
});

test('stod keeps the sign of values between -1 and 0', () => {
	assert.equal(js.stod('-0:30:00'), -0.5);
	assert.equal(js.stod(' -0:15'), -0.25);
	assert.equal(js.stod('0:30:00'), 0.5);
});

test('stod parses zero and whole degrees', () => {
	assert.equal(js.stod('0:00:00'), 0);
	assert.equal(js.stod('12'), 12);
	assert.equal(js.stod('-12:30:00'), -12.5);
	assert.equal(js.stod('23:45:00'), 23.75);
});

test('dtos and stod round trip', () => {
	for (const value of [-89.5, -45.25, -1, -0.75, -0.5, -1 / 60, 0, 1 / 60, 0.5, 1, 45.25, 89.5]) {
		assert.equal(js.stod(js.dtos(value)), value, `value ${value}`);
	}
});

