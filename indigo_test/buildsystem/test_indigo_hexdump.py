# Code is generated by AI

"""indigo_hexdump writes the C array bytes of embedded files exactly as hexdump -v -e '1/1 "0x%02x, "' did."""
import gzip
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "indigo_tools/indigo_hexdump.c"
COMPILER = os.environ.get("CC") or shutil.which("cc") or shutil.which("clang") or shutil.which("gcc")


def expected(data):
	return "".join("0x%02x, " % byte for byte in data).encode("ascii")


@unittest.skipUnless(COMPILER, "a C compiler is required")
class IndigoHexdumpTests(unittest.TestCase):
	@classmethod
	def setUpClass(cls):
		cls.temp = tempfile.TemporaryDirectory(prefix="indigo-hexdump-")
		cls.base = Path(cls.temp.name)
		cls.tool = cls.base / "indigo_hexdump"
		subprocess.run([COMPILER, "-std=c99", "-Wall", "-Wextra", "-Werror", str(SOURCE), "-o", str(cls.tool)], check=True)

	@classmethod
	def tearDownClass(cls):
		cls.temp.cleanup()

	def inputs(self):
		yield "empty", b""
		yield "all byte values", bytes(range(256)) * 3
		yield "chunk boundary", bytes((index * 7) & 0xFF for index in range(4096 * 2 + 5))
		yield "CR LF and NUL", b"line\r\nline\n\x00\x1a\r"
		yield "boot.js", (ROOT / "indigo_drivers/agent_scripting/boot.js").read_bytes()
		yield "Sequencer.js", (ROOT / "indigo_drivers/agent_scripting/library/Sequencer.js").read_bytes()
		yield "gzipped resource", gzip.compress((ROOT / "indigo_server/resource/indigo.js").read_bytes(), mtime=0)

	def write(self, name, data):
		path = self.base / name.replace(" ", "_")
		path.write_bytes(data)
		return path

	def test_file_to_file(self):
		for name, data in self.inputs():
			with self.subTest(name):
				source = self.write(name, data)
				target = self.base / (source.name + ".dat")
				subprocess.run([str(self.tool), str(source), str(target)], check=True)
				self.assertEqual(target.read_bytes(), expected(data))

	def test_file_to_stdout_and_stdin_to_stdout(self):
		for name, data in self.inputs():
			with self.subTest(name):
				source = self.write(name, data)
				self.assertEqual(subprocess.run([str(self.tool), str(source)], check=True, capture_output=True).stdout, expected(data))
				self.assertEqual(subprocess.run([str(self.tool)], input=data, check=True, capture_output=True).stdout, expected(data))

	@unittest.skipUnless(shutil.which("hexdump"), "the system hexdump is not available")
	def test_identical_to_system_hexdump(self):
		for name, data in self.inputs():
			with self.subTest(name):
				source = self.write(name, data)
				reference = subprocess.run(["hexdump", "-v", "-e", '1/1 "0x%02x, "', str(source)], check=True, capture_output=True).stdout
				self.assertEqual(subprocess.run([str(self.tool), str(source)], check=True, capture_output=True).stdout, reference)

	def test_missing_input_fails_without_output(self):
		target = self.base / "missing.dat"
		run = subprocess.run([str(self.tool), str(self.base / "missing"), str(target)], capture_output=True)
		self.assertEqual(run.returncode, 1)
		self.assertIn(b"can't open", run.stderr)
		self.assertFalse(target.exists())

	def test_too_many_arguments_fail(self):
		run = subprocess.run([str(self.tool), "a", "b", "c"], capture_output=True)
		self.assertEqual(run.returncode, 2)
		self.assertIn(b"usage", run.stderr)


if __name__ == "__main__":
	unittest.main()
