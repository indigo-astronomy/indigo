"""Tests use the libindigo of the checkout they belong to, whatever LD_LIBRARY_PATH or DYLD_LIBRARY_PATH the caller exports.

A Factory worktree inherits the owner's environment, which may point at the primary checkout's build/lib. The tests
copy this checkout's libindigo into a foreign directory, put that directory in the library path and check which copy
a test binary loads, both started directly and from a recipe of indigo_test/Makefile.
"""
import os
from pathlib import Path
import shlex
import shutil
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[2]
TEST_DIR = ROOT / "indigo_test"
BUILD_LIB = ROOT / "build/lib"
SUFFIX = ".dylib" if sys.platform == "darwin" else ".so"
COMPILER = os.environ.get("CC") or shutil.which("cc") or shutil.which("gcc") or shutil.which("clang")
LIBRARY_VARIABLES = ("LD_LIBRARY_PATH", "DYLD_LIBRARY_PATH")

# Prints the path of every loaded libindigo; the function pointer keeps the library needed under --as-needed.
PROBE = r"""
#include <link.h>
#include <stdio.h>
#include <string.h>
#include <indigo/indigo_bus.h>

void *volatile keep = (void *)indigo_log;

static int report(struct dl_phdr_info *info, size_t size, void *data) {
	(void)size;
	(void)data;
	if (info->dlpi_name != NULL && strstr(info->dlpi_name, "libindigo.") != NULL) {
		printf("%s\n", info->dlpi_name);
	}
	return 0;
}

int main(void) {
	dl_iterate_phdr(report, NULL);
	return 0;
}
"""


def make_variable(name):
	return subprocess.run(["make", "-s", "print-variable", "VAR=" + name], cwd=TEST_DIR, env=clean_environment(), capture_output=True, text=True, check=True).stdout.strip()


def clean_environment(**variables):
	environment = {key: value for key, value in os.environ.items() if key not in LIBRARY_VARIABLES and key not in ("MAKEFLAGS", "MFLAGS", "MAKELEVEL")}
	environment.update(variables)
	return environment


@unittest.skipUnless((BUILD_LIB / ("libindigo" + SUFFIX)).exists(), "build/lib/libindigo%s is missing, run 'make all' first" % SUFFIX)
class CheckoutLibraryTests(unittest.TestCase):
	@classmethod
	def setUpClass(cls):
		cls.temp = tempfile.TemporaryDirectory(prefix="indigo-checkout-library-")
		cls.base = Path(cls.temp.name)
		cls.foreign = cls.base / "foreign"
		cls.foreign.mkdir()
		# a decoy with every name the loader may look for, as another checkout's build/lib would have
		for library in BUILD_LIB.glob("libindigo*"):
			if library.suffix != ".a":
				shutil.copy2(library, cls.foreign / library.name)

	@classmethod
	def tearDownClass(cls):
		cls.temp.cleanup()

	def build_probe(self, name, ldflags):
		source = self.base / "probe.c"
		source.write_text(PROBE)
		binary = self.base / name
		command = shlex.split(COMPILER) + shlex.split(make_variable("TEST_CFLAGS")) + ["-o", str(binary), str(source)] + ldflags
		subprocess.run(command, cwd=TEST_DIR, check=True)
		return binary

	def loaded(self, output):
		libraries = [Path(line).resolve() for line in output.splitlines() if line.strip()]
		self.assertEqual(len(libraries), 1, output)
		return libraries[0].parent

	def test_make_puts_this_build_first_in_the_library_path(self):
		foreign = str(self.foreign)
		probe = self.base / "variables.mk"
		probe.write_text("probe-library-path:\n\t@echo '$(LD_LIBRARY_PATH)'\n\t@echo '$(DYLD_LIBRARY_PATH)'\n")
		environment = clean_environment(LD_LIBRARY_PATH=foreign, DYLD_LIBRARY_PATH=foreign)
		result = subprocess.run(["make", "-s", "-f", "Makefile", "-f", str(probe), "probe-library-path"], cwd=TEST_DIR, env=environment, capture_output=True, text=True, check=True)
		for line in result.stdout.splitlines():
			entries = line.split(os.pathsep)
			self.assertEqual(Path(entries[0]).resolve(), BUILD_LIB.resolve(), line)
			self.assertIn(foreign, entries[1:], line)

	@unittest.skipUnless(sys.platform.startswith("linux") and COMPILER, "DT_RPATH and dl_iterate_phdr are Linux features; a C compiler is required")
	def test_test_binary_started_directly_loads_this_build(self):
		binary = self.build_probe("probe_rpath", shlex.split(make_variable("TEST_LDFLAGS")))
		result = subprocess.run([str(binary)], env=clean_environment(LD_LIBRARY_PATH=str(self.foreign)), capture_output=True, text=True, check=True)
		self.assertEqual(self.loaded(result.stdout), BUILD_LIB.resolve())

	@unittest.skipUnless(sys.platform.startswith("linux") and COMPILER, "DT_RUNPATH and dl_iterate_phdr are Linux features; a C compiler is required")
	def test_recipe_environment_overrides_a_foreign_path_also_for_runpath(self):
		# Control: with DT_RUNPATH, as indigo_server and the drivers are linked, the foreign directory wins when the
		# binary is started directly, which is the reported defect; started from a recipe, this build wins.
		ldflags = [flag for flag in shlex.split(make_variable("TEST_LDFLAGS")) if flag != "-Wl,--disable-new-dtags"] + ["-Wl,--enable-new-dtags"]
		binary = self.build_probe("probe_runpath", ldflags)
		direct = subprocess.run([str(binary)], env=clean_environment(LD_LIBRARY_PATH=str(self.foreign)), capture_output=True, text=True, check=True)
		self.assertEqual(self.loaded(direct.stdout), self.foreign.resolve())
		probe = self.base / "run.mk"
		probe.write_text("probe-run:\n\t@'%s'\n" % binary)
		recipe = subprocess.run(["make", "-s", "-f", "Makefile", "-f", str(probe), "probe-run"], cwd=TEST_DIR, env=clean_environment(LD_LIBRARY_PATH=str(self.foreign)), capture_output=True, text=True, check=True)
		self.assertEqual(self.loaded(recipe.stdout), BUILD_LIB.resolve())


if __name__ == "__main__":
	unittest.main()
