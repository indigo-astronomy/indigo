"""Build revision stamping in disposable checkouts, linked worktrees and exports."""
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[2]
HELPER = ROOT / "tools/make_indigo_build.sh"


@unittest.skipUnless(shutil.which("git"), "git is required")
class BuildRevisionTests(unittest.TestCase):
	def setUp(self):
		self.temp = tempfile.TemporaryDirectory(prefix="indigo-build-revision-")
		self.addCleanup(self.temp.cleanup)
		self.base = Path(self.temp.name)
		self.env = {key: value for key, value in os.environ.items() if not key.startswith("GIT_")}
		self.env.update(GIT_CONFIG_NOSYSTEM="1", GIT_CONFIG_GLOBAL=os.devnull)
		self.repo = self.base / "ordinary checkout"
		self.repo.mkdir()
		(self.repo / "indigo_libs").mkdir()
		(self.repo / "tracked").write_text("original\n")
		self.git(self.repo, "init", "-q")
		self.git(self.repo, "add", "tracked")
		self.git(self.repo, "-c", "user.name=Fixture", "-c", "user.email=fixture@example.invalid", "-c", "commit.gpgsign=false", "commit", "-qm", "fixture")
		self.commit = self.git(self.repo, "rev-parse", "--short", "HEAD").strip()

	def git(self, root, *args):
		return subprocess.check_output(["git", "-C", str(root), *args], env=self.env, stderr=subprocess.STDOUT, text=True)

	def stamp(self, root):
		run = subprocess.run(["sh", str(HELPER)], cwd=root / "indigo_libs", env=self.env, capture_output=True, text=True, check=True)
		self.assertEqual(run.stderr, "")
		self.assertIn('#include <indigo/indigo_config.h>', run.stdout)
		self.assertRegex(run.stdout, r'char \*indigo_build_time = "[^"\n]+";')
		match = re.search(r'char \*indigo_build_commit = "([^"\n]*)";', run.stdout)
		self.assertIsNotNone(match, run.stdout)
		return match.group(1)

	def test_ordinary_checkout_and_tracked_changes(self):
		self.assertEqual(self.stamp(self.repo), self.commit)
		(self.repo / "tracked").write_text("modified\n")
		self.assertEqual(self.stamp(self.repo), self.commit + "+")

	def test_linked_worktree_and_tracked_changes(self):
		worktree = self.base / "linked worktree"
		self.git(self.repo, "worktree", "add", "--detach", str(worktree), "HEAD")
		(worktree / "indigo_libs").mkdir()
		self.assertTrue((worktree / ".git").is_file())
		self.assertEqual(self.stamp(worktree), self.commit)
		(worktree / "tracked").write_text("modified\n")
		self.assertEqual(self.stamp(worktree), self.commit + "+")

	def test_export_without_git_metadata(self):
		export = self.base / "source export"
		(export / "indigo_libs").mkdir(parents=True)
		self.assertEqual(self.stamp(export), "production")

	def test_export_inside_unrelated_repository(self):
		export = self.repo / "nested export"
		(export / "indigo_libs").mkdir(parents=True)
		self.assertEqual(self.stamp(export), "production")

	def test_staged_only_and_untracked_changes_keep_existing_semantics(self):
		(self.repo / "tracked").write_text("staged\n")
		self.git(self.repo, "add", "tracked")
		(self.repo / "untracked").write_text("untracked\n")
		self.assertEqual(self.stamp(self.repo), self.commit)


if __name__ == "__main__":
	unittest.main()
