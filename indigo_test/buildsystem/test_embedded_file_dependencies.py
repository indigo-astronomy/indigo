# Code is generated by AI

"""A regenerated embedded file (.dat, .data) makes the object that includes it out of date.

The real makefiles run with make -q in a scratch tree of placeholder files with fixed timestamps, so nothing is compiled.
"""
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[2]
OLD, MIDDLE, NEW = 1_000_000_000, 1_000_001_000, 1_000_002_000


@unittest.skipUnless(shutil.which("make"), "make is required")
class EmbeddedFileDependencyTests(unittest.TestCase):
	def setUp(self):
		self.temp = tempfile.TemporaryDirectory(prefix="indigo-embedded-deps-")
		self.addCleanup(self.temp.cleanup)
		self.root = Path(self.temp.name)
		build = self.root / "build"
		(self.root / "Makefile.inc").write_text("BUILD_BIN = %s/bin\nBUILD_DRIVERS = %s/drivers\nBUILD_LIB = %s/lib\nOS_DETECTED = Linux\nCC = cc\nSOEXT = so\n" % (build, build, build))
		shutil.copy(ROOT / "Makefile.drv", self.root / "Makefile.drv")
		self.place("indigo_tools/indigo_hexdump.c", OLD)
		self.place("build/bin/indigo_hexdump", OLD)
		self.place("indigo_drivers/agent_scripting/library/Sequencer.js", OLD)

	def place(self, name, mtime):
		path = self.root / name
		path.parent.mkdir(parents=True, exist_ok=True)
		if not path.exists():
			path.write_text("")
		os.utime(path, (mtime, mtime))
		return path

	def up_to_date(self, directory, *targets, makefile=None):
		command = ["make", "-q"] + (["-f", makefile] if makefile else []) + list(targets)
		run = subprocess.run(command, cwd=self.root / directory, capture_output=True, text=True)
		self.assertIn(run.returncode, (0, 1), run.stderr)
		return run.returncode == 0

	def check_driver(self, driver, source, generated):
		directory = "indigo_drivers/" + driver
		(self.root / directory).mkdir(parents=True, exist_ok=True)
		shutil.copy(ROOT / directory / "Makefile.inc", self.root / directory / "Makefile.inc")
		self.place(directory + "/indigo_" + driver + ".c", OLD)
		self.place(directory + "/" + source, OLD)
		self.place(directory + "/" + generated, MIDDLE)
		self.place(directory + "/indigo_" + driver + ".o", MIDDLE)
		self.assertTrue(self.up_to_date(directory, generated, "indigo_" + driver + ".o", makefile="../../Makefile.drv"))
		self.place(directory + "/" + generated, NEW)
		self.assertFalse(self.up_to_date(directory, "indigo_" + driver + ".o", makefile="../../Makefile.drv"))
		self.place(directory + "/" + generated, MIDDLE)
		self.place(directory + "/" + source, NEW)
		self.assertFalse(self.up_to_date(directory, generated, makefile="../../Makefile.drv"))

	def test_scheduler_object_follows_sequencer_dat(self):
		self.check_driver("agent_scheduler", "../agent_scripting/library/Sequencer.js", "Sequencer.js.dat")

	def test_scripting_object_follows_boot_dat(self):
		self.check_driver("agent_scripting", "boot.js", "boot.js.dat")

	def test_server_object_follows_control_panel_data(self):
		(self.root / "indigo_server").mkdir()
		shutil.copy(ROOT / "indigo_server/Makefile", self.root / "indigo_server/Makefile")
		# --eval needs GNU make 3.82, macOS ships 3.81, so the extra rule comes from standard input
		listing = subprocess.run(["make", "-s", "-f", "Makefile", "-f", "-", "print-data"], input="print-data:\n\t@echo $(CTRLPANEL_DATA) $(CTRLPANEL_FILES)\n", cwd=self.root / "indigo_server", capture_output=True, text=True, check=True).stdout.split()
		self.assertIn("resource/indigo.js.data", listing)
		for data in listing:
			if data != "resource/Sequencer.js.data":
				self.place("indigo_server/" + data[:-len(".data")], OLD)
			self.place("indigo_server/" + data, MIDDLE)
		self.place("indigo_server/indigo_server.c", OLD)
		self.place("indigo_server/indigo_server.o", MIDDLE)
		self.assertTrue(self.up_to_date("indigo_server", "indigo_server.o", *listing))
		self.place("indigo_server/resource/indigo.js.data", NEW)
		self.assertFalse(self.up_to_date("indigo_server", "indigo_server.o"))


if __name__ == "__main__":
	unittest.main()
