# Code is generated by AI

"""The checked-in MCP help bundle matches its Markdown sources.

Visual Studio builds compile indigo_drivers/agent_mcp/indigo_agent_mcp_help.h as checked in and cannot regenerate it, so a
documentation change committed without running generate_help.py must fail here.
"""
from pathlib import Path
import subprocess
import sys
import unittest

ROOT = Path(__file__).resolve().parents[2]
GENERATOR = ROOT / "indigo_drivers/agent_mcp/generate_help.py"


class AgentMcpHelpTests(unittest.TestCase):
	def test_checked_in_bundle_is_current(self):
		run = subprocess.run([sys.executable, "-B", str(GENERATOR), "--check"], cwd=ROOT, capture_output=True, text=True)
		self.assertEqual(run.returncode, 0, run.stdout + run.stderr)
		self.assertIn("MCP help bundle is current", run.stdout)


if __name__ == "__main__":
	unittest.main()
