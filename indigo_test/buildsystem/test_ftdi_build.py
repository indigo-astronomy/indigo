"""FTDI build transactions use disposable files and synthetic macOS commands."""
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[2]
HELPER = ROOT / "tools/build_ftdi_macos.sh"
MAKE = subprocess.check_output(["xcrun", "--find", "make"], text=True).strip() if sys.platform == "darwin" else "make"
FAKE = r'''#!/usr/bin/env python3
import json, os, pathlib, sys
name = pathlib.Path(sys.argv[0]).name
args = sys.argv[1:]
with open(os.environ['EVENTS'], 'a') as log:
	log.write(json.dumps([name, args]) + '\n')
mode = os.environ.get('FAIL', '')
if name == 'hdiutil':
	if args[0] == 'attach':
		if mode == 'attach': sys.exit(1)
		mount = pathlib.Path(args[args.index('-mountpoint') + 1])
		(mount / 'release/build').mkdir(parents=True)
		for path in ['release/ftd2xx.h', 'release/WinTypes.h', 'release/build/libftd2xx.a']:
			if mode != 'headers' or not path.endswith('WinTypes.h'):
				(mount / path).write_text('VENDOR')
		if mode == 'partial-attach': sys.exit(1)
	elif mode in ('detach', 'all-detach') and ('-force' not in args or mode == 'all-detach'):
		sys.exit(1)
elif name == 'lipo':
	if '-archs' in args:
		print('x86_64 arm64')
	elif '-thin' in args:
		if mode == 'terminate':
			import signal
			os.kill(os.getppid(), signal.SIGTERM)
			sys.exit(1)
		arch = args[args.index('-thin') + 1]
		if mode == 'thin-' + arch: sys.exit(1)
		pathlib.Path(args[args.index('-output') + 1]).write_text(arch)
	elif '-create' in args:
		if mode == 'create': sys.exit(1)
		inputs = args[1:args.index('-output')]
		assert len(inputs) == 2
		assert all('STRIPPED INDEXED' in pathlib.Path(p).read_text() for p in inputs)
		pathlib.Path(args[args.index('-output') + 1]).write_text('COMPLETE')
	elif '-verify_arch' in args:
		assert len(args) == 3
		if mode == 'verify': sys.exit(1)
		assert pathlib.Path(args[0]).read_text() == 'COMPLETE'
elif name == 'ar':
	if mode == 'ar': sys.exit(1)
	with open(args[1], 'a') as stream: stream.write(' STRIPPED')
elif name == 'ranlib':
	if mode == 'ranlib': sys.exit(1)
	with open(args[0], 'a') as stream: stream.write(' INDEXED')
'''


class FtdiBuildTests(unittest.TestCase):
	def setUp(self):
		self.temp = tempfile.TemporaryDirectory(prefix="indigo-ftdi-test-")
		self.addCleanup(self.temp.cleanup)
		self.root = Path(self.temp.name)
		self.tools = self.root / "commands"
		self.tools.mkdir()
		for name in ("hdiutil", "lipo", "ar", "ranlib"):
			p = self.tools / name
			p.write_text(FAKE.replace("#!/usr/bin/env python3", "#!" + sys.executable))
			p.chmod(0o755)
		self.scratch = self.root / "temporary files"
		self.scratch.mkdir()
		self.output = self.root / "output files"
		self.output.mkdir()
		self.include = self.root / "include files"
		self.include.mkdir()
		self.image = self.root / "vendor image.dmg"
		self.image.write_text("SYNTHETIC")
		self.target = self.output / "libftd2xx.a"
		self.events = self.root / "events.jsonl"
		self.env = dict(os.environ, PATH=str(self.tools) + os.pathsep + os.environ['PATH'], TMPDIR=str(self.scratch), EVENTS=str(self.events))

	def run_helper(self, mode=""):
		return subprocess.run(["sh", str(HELPER), str(self.image), str(self.include), str(self.target), "core.o", "io.o"], cwd=self.root, env=dict(self.env, FAIL=mode), capture_output=True, text=True)

	def calls(self, name):
		return [args for command, args in (json.loads(line) for line in self.events.read_text().splitlines()) if command == name]

	def assert_clean(self):
		self.assertEqual(list(self.scratch.iterdir()), [])
		self.assertEqual([p for p in self.output.iterdir() if p.name != self.target.name], [])

	def test_success_publishes_complete_archive_and_all_headers(self):
		result = self.run_helper()
		self.assertEqual(result.returncode, 0, result.stderr)
		self.assertEqual(self.target.read_text(), "COMPLETE")
		self.assertEqual(self.target.stat().st_mode & 0o777, 0o644)
		self.assertTrue((self.include / "ftd2xx.h").is_file())
		self.assertTrue((self.include / "WinTypes.h").is_file())
		self.assertEqual(len(self.calls('ar')), 2)
		self.assertEqual(len(self.calls('ranlib')), 2)
		self.assertEqual(sum('-verify_arch' in args for args in self.calls('lipo')), 2)
		self.assert_clean()

	def test_busy_detach_forces_only_this_unique_mount(self):
		result = self.run_helper("detach")
		self.assertEqual(result.returncode, 0, result.stderr)
		calls = self.calls('hdiutil')
		mount = calls[0][-1]
		self.assertTrue(Path(mount).is_relative_to(self.scratch))
		self.assertEqual(calls[1:], [['detach', mount], ['detach', '-force', mount]])
		self.assertEqual(self.target.read_text(), "COMPLETE")
		self.assert_clean()

	def test_failed_detach_never_publishes_or_deletes_mount_workspace(self):
		result = self.run_helper("all-detach")
		self.assertNotEqual(result.returncode, 0)
		self.assertFalse(self.target.exists())
		self.assertEqual(list(self.output.iterdir()), [])
		self.assertEqual(len(list(self.scratch.iterdir())), 1)
		self.assertIn('retained', result.stderr)
		self.assertEqual(len(self.calls('hdiutil')), 3)

	def test_each_processing_failure_cleans_mount_and_staging(self):
		for mode in ('thin-x86_64', 'thin-arm64', 'ar', 'ranlib', 'create', 'verify', 'headers', 'terminate', 'partial-attach'):
			with self.subTest(mode=mode):
				self.events.unlink(missing_ok=True)
				result = self.run_helper(mode)
				self.assertNotEqual(result.returncode, 0)
				self.assertFalse(self.target.exists())
				self.assertEqual(self.calls('hdiutil')[-1][0], 'detach')
				self.assert_clean()

	def test_failure_preserves_existing_archive(self):
		self.target.write_text('PREVIOUS_COMPLETE')
		result = self.run_helper('thin-arm64')
		self.assertNotEqual(result.returncode, 0)
		self.assertEqual(self.target.read_text(), 'PREVIOUS_COMPLETE')
		self.assert_clean()

	def test_attach_failure_never_publishes(self):
		result = self.run_helper('attach')
		self.assertNotEqual(result.returncode, 0)
		self.assertFalse(self.target.exists())
		self.assert_clean()

	def test_makefile_target_uses_transaction_helper(self):
		self.assertIn('build_ftdi_macos.sh', (ROOT / 'indigo_libs/Makefile').read_text(), 'Refuse to execute the legacy recipe with its global mount path')
		output = self.root / 'make-output'
		include = self.root / 'make-include'
		include.mkdir()
		vendor = self.root / 'vendor'
		vendor.mkdir()
		(vendor / 'D2XX1.4.35.dmg').write_text('SYNTHETIC')
		target = output / 'libftd2xx.a'
		result = subprocess.run([MAKE, '-C', str(ROOT / 'indigo_libs'), str(target), 'OS_DETECTED=Darwin', 'BUILD_LIB=' + str(output), 'BUILD_INCLUDE=' + str(include), 'BIN_EXTERNALS=' + str(vendor)], env=dict(self.env, FAIL='detach'), capture_output=True, text=True)
		self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
		self.assertEqual(target.read_text(), 'COMPLETE')
		self.assertEqual(list(self.scratch.iterdir()), [])


if __name__ == '__main__':
	unittest.main()
