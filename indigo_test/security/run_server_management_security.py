"""Build source-current management regressions without executing management commands.

Only shell_escape, execute_command and the RPI INSTALL prefix of change_property
are extracted. Other change_property branches are excluded. The harness calls
that prefix with real public property types and stubbed property copy/publication
and popen/pclose; it does not claim bus authorization or deployed-helper coverage.
"""
import argparse
import os
from pathlib import Path
import shlex
import subprocess
import tempfile


def main():
	parser = argparse.ArgumentParser(description=__doc__)
	parser.add_argument("--sanitize", action="store_true")
	options = parser.parse_args()
	root = Path(__file__).resolve().parents[2]
	source = (root / "indigo_server/indigo_server.c").read_text()
	helpers = source[source.index("static char *shell_escape("):source.index("static char *execute_query(")]
	entry_start = source.index("static indigo_result change_property(indigo_device *device, indigo_client *client, indigo_property *property) {")
	entry_end = source.index("#endif /* RPI_MANAGEMENT */", entry_start) + len("#endif /* RPI_MANAGEMENT */")
	entry = source[entry_start:entry_end] + "\n\treturn INDIGO_OK;\n}\n"
	with tempfile.TemporaryDirectory(prefix="indigo-management-security-") as temporary:
		directory = Path(temporary)
		(directory / "server_management_source.inc").write_text(helpers + entry)
		command = shlex.split(os.environ.get("CC", "cc")) + ["-std=c11", "-D_GNU_SOURCE", "-D_DARWIN_C_SOURCE", "-DRPI_MANAGEMENT", "-O1", "-g", "-Wall", "-Wextra", "-Wno-unused-function", "-Wno-unused-parameter", "-I" + str(root / "indigo_libs"), "-I" + str(directory), str(root / "indigo_test/security/test_server_management_security.c"), "-pthread", "-o", str(directory / "test_server_management_security")]
		if options.sanitize:
			command += ["-fsanitize=address,undefined", "-fno-omit-frame-pointer"]
		subprocess.run(command, check=True, timeout=60)
		return subprocess.run([str(directory / "test_server_management_security")], timeout=30).returncode


if __name__ == "__main__":
	raise SystemExit(main())
