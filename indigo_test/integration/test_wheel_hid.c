// The Starlight Xpress wheel answers every two byte request with the current
// slot and the number of slots; a request with the high bit set starts a move.
long wheel_hid_write(indigo_uni_handle *opened_handle, const char *buffer, long length) {
	if (opened_handle == NULL) {
		return -1;
	}
	unsigned char command = (unsigned char)buffer[0];
	if (command & 0x80) {
		return model_set(command & 0x7f) ? length : -1;
	}
	return transfer() ? length : -1;
}

long wheel_hid_read(indigo_uni_handle *opened_handle, void *buffer, long length) {
	int count = 0, slot = 0;
	if (opened_handle == NULL) {
		return -1;
	}
	if (!model_query(&count, &slot)) {
		return -1;
	}
	((unsigned char *)buffer)[0] = (unsigned char)slot;
	((unsigned char *)buffer)[1] = (unsigned char)count;
	return 2;
}

