// Disconnecting while the wheel is turning stops the polling and closes the
// wheel without another transfer.
static void disconnect_during_motion(void) {
	SERIAL_CHECK_TRUE(driver_start());
	atomic_store(&move_polls, 20);
	SERIAL_CHECK_TRUE(select_slot(6, INDIGO_BUSY_STATE));
	disconnect_serial_device(&wheel);
	SERIAL_CHECK_TRUE(!context.connected);
	SERIAL_CHECK_EQ_INT(opened, closed);
	int calls = io_calls;
	indigo_usleep(1500000);
	SERIAL_CHECK_EQ_INT(calls, io_calls);
	SERIAL_CHECK_EQ_INT(0, io_after_close);
	atomic_store(&move_polls, 1);
	SERIAL_CHECK_TRUE(connect_wheel());
	SERIAL_CHECK_TRUE(select_slot(2, INDIGO_BUSY_STATE));
	SERIAL_CHECK_TRUE(slot_is(2));
cleanup:
	driver_stop();
}

