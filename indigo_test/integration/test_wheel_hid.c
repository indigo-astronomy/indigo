static indigo_uni_handle handle;

static void reset_fake(void) {
	atomic_store(&slot_count, 7);
	atomic_store(&current_slot, 1);
	atomic_store(&target_slot, 1);
	atomic_store(&move_polls, 2);
	atomic_store(&pending_polls, 0);
	atomic_store(&opened, 0);
	atomic_store(&closed, 0);
	atomic_store(&io_calls, 0);
	atomic_store(&io_after_close, 0);
	atomic_store(&references, 0);
	atomic_store(&attached, 0);
	atomic_store(&fail_open, 0);
	atomic_store(&fail_query, 0);
	atomic_store(&fail_set, 0);
	atomic_store(&fail_queue, 0);
	atomic_store(&fail_register, 0);
	atomic_store(&fail_attach, 0);
	atomic_store(&queries, 0);
	atomic_store(&sets, 0);
	atomic_store(&last_set, 0);
	hotplug = NULL;
}

// Every transfer is counted, and a transfer on a closed wheel is recorded
// separately so a test can prove the driver stopped talking to it.
static bool transfer(void) {
	atomic_fetch_add(&io_calls, 1);
	if (atomic_load(&opened) == atomic_load(&closed)) {
		atomic_fetch_add(&io_after_close, 1);
		return false;
	}
	return true;
}

static bool model_query(int *count, int *slot) {
	if (!transfer() || atomic_exchange(&fail_query, 0)) {
		return false;
	}
	atomic_fetch_add(&queries, 1);
	if (atomic_load(&pending_polls) > 0) {
		atomic_fetch_sub(&pending_polls, 1);
	} else {
		atomic_store(&current_slot, atomic_load(&target_slot));
	}
	*count = atomic_load(&slot_count);
	*slot = atomic_load(&current_slot);
	return true;
}

static bool model_set(int slot) {
	if (!transfer() || atomic_exchange(&fail_set, 0)) {
		return false;
	}
	atomic_fetch_add(&sets, 1);
	atomic_store(&last_set, slot);
	atomic_store(&target_slot, slot);
	atomic_store(&pending_polls, atomic_load(&move_polls));
	return true;
}

