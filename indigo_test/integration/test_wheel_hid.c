static bool state_seen(const char *property, indigo_property_state state, unsigned int revision) {
	if (wait_for_property_state_seen_after(property, state, revision)) {
		return true;
	}
	indigo_property *cached = find_cached_property(property);
	fprintf(stderr, "%s never published state %d (current %d)\n", property, state, cached == NULL ? -1 : cached->state);
	return false;
}

static bool select_slot(int slot, indigo_property_state state) {
	unsigned int revision = property_state_revision(WHEEL_SLOT_PROPERTY_NAME, state);
	return indigo_change_number_property_1(&simulator_test_client, wheel.device_name, WHEEL_SLOT_PROPERTY_NAME, WHEEL_SLOT_ITEM_NAME, slot) == INDIGO_OK && state_seen(WHEEL_SLOT_PROPERTY_NAME, state, revision);
}

// The driver publishes the busy state from its change macro before the handler
// has sent anything, so a command assertion has to wait for the wheel.
static bool slot_commanded(int slot) {
	for (int i = 0; i < 200; i++) {
		if (atomic_load(&last_set) == slot) {
			return true;
		}
		indigo_usleep(25000);
	}
	fprintf(stderr, "Slot %d was never commanded, last command was %d\n", slot, atomic_load(&last_set));
	return false;
}

static bool slot_is(int slot) {
	for (int i = 0; i < 400; i++) {
		indigo_property *property = find_cached_property(WHEEL_SLOT_PROPERTY_NAME);
		indigo_item *item = find_cached_item(WHEEL_SLOT_PROPERTY_NAME, WHEEL_SLOT_ITEM_NAME);
		if (property != NULL && item != NULL && property->state == INDIGO_OK_STATE && (int)item->number.value == slot) {
			return true;
		}
		indigo_usleep(25000);
	}
	indigo_property *property = find_cached_property(WHEEL_SLOT_PROPERTY_NAME);
	indigo_item *item = find_cached_item(WHEEL_SLOT_PROPERTY_NAME, WHEEL_SLOT_ITEM_NAME);
	fprintf(stderr, "Wheel did not settle at slot %d (value %g, state %d)\n", slot, item == NULL ? NAN : item->number.value, property == NULL ? -1 : property->state);
	return false;
}

// The wheel is attached by the arrival event the fake registration replays, so
// bringing the driver up is enough to make the device appear.
static bool driver_up(void) {
	reset_fake();
	if (!bring_up_serial_driver(&wheel)) {
		return false;
	}
	indigo_queue_drain(driver_queue);
	return true;
}

static bool connect_wheel(void) {
	return connect_serial_device(&wheel, NULL);
}

// A wheel that has to be probed before it answers can take longer to refuse a
// connection than the shared helper waits for.
static bool connection_refused(void) {
	for (int i = 0; i < 300; i++) {
		if (!context.connected && context.last_connection_state == INDIGO_ALERT_STATE) {
			return true;
		}
		indigo_usleep(100000);
	}
	fprintf(stderr, "Connection was not refused, connected %d state %d\n", context.connected, context.last_connection_state);
	return false;
}

static bool driver_start(void) {
	return driver_up() && connect_wheel();
}

static void driver_stop(void) {
	if (context.connected) {
		disconnect_serial_device(&wheel);
	}
	tear_down_serial_driver(&wheel);
	ASSERT_EQ_INT(0, attached);
	ASSERT_EQ_INT(0, references);
	ASSERT_EQ_INT(opened, closed);
	ASSERT_EQ_INT(0, io_after_close);
}

static void plug(void) {
	hotplug(NULL, (libusb_device *)(uintptr_t)1, LIBUSB_HOTPLUG_EVENT_DEVICE_ARRIVED, NULL);
	indigo_queue_drain(driver_queue);
}

static void unplug(void) {
	hotplug(NULL, (libusb_device *)(uintptr_t)1, LIBUSB_HOTPLUG_EVENT_DEVICE_LEFT, NULL);
	indigo_queue_drain(driver_queue);
}

