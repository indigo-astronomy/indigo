static void property_contract(void) {
	SERIAL_CHECK_TRUE(driver_up());
	reset_simulator_context(&wheel);
	enumerate_simulator_device();
	SERIAL_CHECK_TRUE(!has_defined_property(WHEEL_SLOT_PROPERTY_NAME));
	SERIAL_CHECK_TRUE(connect_wheel());
	assert_property_has_item(WHEEL_SLOT_PROPERTY_NAME, WHEEL_SLOT_ITEM_NAME);
	assert_defined_property(WHEEL_SLOT_NAME_PROPERTY_NAME);
	assert_defined_property(WHEEL_SLOT_OFFSET_PROPERTY_NAME);
	// The controller reports how many slots it has, and all three properties
	// have to follow it.
	indigo_item *slot = find_cached_item(WHEEL_SLOT_PROPERTY_NAME, WHEEL_SLOT_ITEM_NAME);
	SERIAL_CHECK_TRUE(slot != NULL && slot->number.min == 1 && slot->number.max == 7);
	SERIAL_CHECK_EQ_INT(7, find_cached_property(WHEEL_SLOT_NAME_PROPERTY_NAME)->count);
	SERIAL_CHECK_EQ_INT(7, find_cached_property(WHEEL_SLOT_OFFSET_PROPERTY_NAME)->count);
	SERIAL_CHECK_TRUE(slot_is(1));
	disconnect_serial_device(&wheel);
	for (int i = 0; i < 50 && find_cached_property(WHEEL_SLOT_PROPERTY_NAME) != NULL; i++) {
		indigo_usleep(100000);
	}
	SERIAL_CHECK_TRUE(find_cached_property(WHEEL_SLOT_PROPERTY_NAME) == NULL);
cleanup:
	driver_stop();
}

