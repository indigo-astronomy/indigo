// The wheel the fake transport models. A move takes move_polls readbacks to
// complete, so a test can observe BUSY before the wheel arrives.
static atomic_int slot_count = 7, current_slot = 1, target_slot = 1, move_polls, pending_polls;
static atomic_int opened, closed, io_calls, io_after_close, references, attached;
static atomic_int fail_open, fail_query, fail_set, fail_queue, fail_register, fail_attach;
static atomic_int queries, sets, last_set;
static libusb_hotplug_callback_fn hotplug;
