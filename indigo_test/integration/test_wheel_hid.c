// A move is reported as busy until the wheel says it arrived.
static void motion_progress(void) {
	SERIAL_CHECK_TRUE(driver_start());
	atomic_store(&move_polls, 4);
	int before = atomic_load(&queries);
	SERIAL_CHECK_TRUE(select_slot(6, INDIGO_BUSY_STATE));
	SERIAL_CHECK_TRUE(slot_commanded(6));
	// The wheel is polled until it reports the requested slot, and the property
	// stays busy for the whole turn.
	for (int i = 0; i < 200 && atomic_load(&queries) < before + 2; i++) {
		indigo_usleep(25000);
	}
	SERIAL_CHECK_TRUE(atomic_load(&queries) >= before + 2);
	SERIAL_CHECK_TRUE(find_cached_property(WHEEL_SLOT_PROPERTY_NAME)->state == INDIGO_BUSY_STATE);
	SERIAL_CHECK_TRUE(slot_is(6));
	SERIAL_CHECK_TRUE(atomic_load(&queries) >= before + 4);
cleanup:
	driver_stop();
}

