// The wheel is driven to the first, the last and an intermediate slot, and the
// driver has to command the slot number the client asked for.
static void positioning(void) {
	static const int slots[] = { 4, 7, 1, 3 };
	SERIAL_CHECK_TRUE(driver_start());
	SERIAL_CHECK_TRUE(slot_is(1));
	for (int i = 0; i < ARRAY_SIZE(slots); i++) {
		SERIAL_CHECK_TRUE(select_slot(slots[i], INDIGO_BUSY_STATE));
		SERIAL_CHECK_TRUE(slot_commanded(slots[i]));
		SERIAL_CHECK_TRUE(slot_is(slots[i]));
		SERIAL_CHECK_TRUE(wait_for_number_item_value(WHEEL_SLOT_PROPERTY_NAME, WHEEL_SLOT_ITEM_NAME, slots[i], 0));
	}
cleanup:
	driver_stop();
}

