static void init_rollback(void) {
	reset_fake();
	atomic_store(&fail_queue, 1);
	SERIAL_CHECK_TRUE(!bring_up_serial_driver(&wheel));
	SERIAL_CHECK_EQ_INT(0, attached);
	SERIAL_CHECK_TRUE(hotplug == NULL);
	atomic_store(&fail_register, 1);
	SERIAL_CHECK_TRUE(!bring_up_serial_driver(&wheel));
	SERIAL_CHECK_EQ_INT(0, attached);
	SERIAL_CHECK_EQ_INT(0, references);
	// A wheel whose attachment fails must not leave a reference or a device.
	atomic_store(&fail_attach, 1);
	SERIAL_CHECK_TRUE(bring_up_serial_driver(&wheel));
	indigo_queue_drain(driver_queue);
	SERIAL_CHECK_EQ_INT(0, attached);
	SERIAL_CHECK_EQ_INT(0, references);
	plug();
	SERIAL_CHECK_EQ_INT(1, attached);
	SERIAL_CHECK_TRUE(connect_wheel());
	SERIAL_CHECK_TRUE(slot_is(1));
cleanup:
	driver_stop();
}

