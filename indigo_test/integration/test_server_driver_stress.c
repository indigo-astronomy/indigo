// Code is generated by AI

// Driver load and unload stress against the real indigo_server.
//
// Loading and unloading a large set of drivers was reported to hang the server now and then. The server loads and
// unloads drivers synchronously inside its DRIVERS change handler, so this test launches build/bin/indigo_server on a
// free loopback port with a private HOME, connects to it as an ordinary INDIGO client and drives Server.DRIVERS:
//
// * each_driver_loads_and_unloads_alone   every driver is loaded and unloaded on its own, twice, so a defect is
//                                         attributed to the driver that triggers it. The server is restarted after
//                                         a failure and the remaining drivers are still tried;
// * all_drivers_load_then_unload          the whole set is switched on and then off again in one request each;
// * random_driver_sets_load_and_unload    random subsets, every request loads some drivers and unloads others.
//
// Every request is sent as soon as the previous one has been answered, as a client loading a profile does. After
// every request the server must answer DRIVERS within the timeout, still run, and answer a full enumeration: that
// calls into every attached device, so a driver that leaves a device attached after its library was unloaded crashes
// the server right there instead of at some later, unrelated request.
//
// A request without an answer is reported as a hang. The stacks of all server threads are then written next to the
// server log (sample on macOS, gdb on Linux) before the server is killed. Logs and stacks are kept in
// build/integration/server_driver_stress.
//
// The test launches indigo_server and opens loopback sockets, so it is not part of test-integration. Run it with
// make -C indigo_test test-server-driver-stress. Environment:
//
//   INDIGO_STRESS_DRIVERS     regular expression, only matching drivers are used (default: all the server lists)
//   INDIGO_STRESS_EXCLUDE     regular expression, matching drivers are left out
//   INDIGO_STRESS_TIMEOUT     seconds a request may take before it counts as a hang (default 60)
//   INDIGO_STRESS_CYCLES      load all / unload all cycles (default 5)
//   INDIGO_STRESS_ITERATIONS  random requests (default 30)
//   INDIGO_STRESS_SEED        seed of the random sets (default: time), printed so that a failing run can be repeated
//   INDIGO_STRESS_VERBOSE     print every request with its duration

