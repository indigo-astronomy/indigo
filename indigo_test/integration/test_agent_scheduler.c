static const char *case_filter = NULL;

static const char *case_name(int index) {
	return cases[index].name;
}

static bool case_selected(int index) {
	return case_filter == NULL || strstr(cases[index].name, case_filter) != NULL;
}

static unsigned case_timeout(int index) {
	return 150;
}

static int case_child(int index, const char *fixture) {
	char home[512];
	snprintf(home, sizeof(home), "%s/home", fixture);
	mkdir(home, 0700);
	if (!indigo_test_set_private_home(home)) {
		return 2;
	}
	int result = setup() ? indigo_run_tests("test_agent_scheduler", cases + index, 1) : 1;
	cleanup();
	fflush(NULL);
	return result || indigo_test_failures ? 1 : 0;
}

static int remove_entry(const char *path, const struct stat *info, int flag, struct FTW *ftw) {
	return remove(path);
}

int main(int argc, char **argv) {
	setvbuf(stdout, NULL, _IOLBF, 0);
	case_filter = argc > 1 ? argv[1] : getenv("SCHEDULER_TEST_FILTER");
	snprintf(fixture_dir, sizeof(fixture_dir), "/tmp/indigo-scheduler.XXXXXX");
	if (!mkdtemp(fixture_dir)) {
		perror("mkdtemp");
		return 1;
	}
	const parallel_case_runner runner = {
		"Scheduler Agent", fixture_dir, (int)ARRAY_SIZE(cases), 0, case_name, case_selected, case_timeout, case_child, NULL
	};
	int run = 0, passed = 0, failed = 0;
	run_parallel_cases(&runner, &run, &passed, &failed);
	if (!getenv("SCHEDULER_KEEP_FIXTURE")) {
		nftw(fixture_dir, remove_entry, 16, FTW_DEPTH | FTW_PHYS);
	}
	printf("Scheduler Agent: %d run, %d passed, %d failed\n", run, passed, failed);
	return failed || run == 0 ? 1 : 0;
}
