static void window_wait_and_expiry(void) {
	time_t now = time(NULL);
	char start[32], end[32], short_end[32];
	// the window opens at the next whole minute, at least 10 s ahead so the case sees it closed first
	time_t open = now - now % 60 + 60;
	if (open - now < 10) {
		open += 60;
	}
	utc(open, start);
	utc(open + 3600, end);
	utc(open, short_end);
	char text[512];
	snprintf(text, sizeof(text), "// @task Window\n// @window %s .. %s\n// @duration 1\n" BODY_WAIT(1), start, end);
	REQUIRE(upload(text));
	// a task whose window closes before its duration elapses never starts and expires
	snprintf(text, sizeof(text), "// @task TooShort\n// @window .. %s\n// @duration 5\n" BODY_WAIT(1), short_end);
	REQUIRE(upload(text));
	REQUIRE(control(AGENT_SCHEDULER_CONTROL_START_ITEM_NAME));
	ASSERT_TRUE(wait_task_state("Window", "WAITING", 5));
	ASSERT_TRUE(wait_reason("window", 5));
	indigo_property *current = snapshot(AGENT_SCHEDULER_CURRENT_PROPERTY_NAME);
	REQUIRE(current != NULL);
	char expected[64];
	indigo_timetoisogm(open, expected, sizeof(expected));
	ASSERT_STREQ(expected, indigo_get_text_item_value(indigo_get_item(current, AGENT_SCHEDULER_CURRENT_NEXT_START_ITEM_NAME)));
	ASSERT_STREQ("Window", indigo_get_text_item_value(indigo_get_item(current, AGENT_SCHEDULER_CURRENT_NEXT_ITEM_NAME)));
	indigo_release_property(current);
	ASSERT_EQ_INT(0, count_messages("Starting task 'Window'"));
	ASSERT_TRUE(wait_message("Starting task 'Window'", 1, (double)(open - time(NULL)) + 5));
	ASSERT_TRUE(time(NULL) >= open);
	ASSERT_TRUE(wait_task_state("Window", "DONE", 10));
	ASSERT_TRUE(wait_task_state("TooShort", "EXPIRED", 5));
	ASSERT_EQ_INT(0, count_messages("Starting task 'TooShort'"));
}

