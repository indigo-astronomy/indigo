// Each of the six ports occupies its own character in the status frame, so all of them are switched
// individually in both directions and confirmed from the device's own report.
static void every_usb_port_switches(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_external_serial_simulator(&simulator, AUX_UCH_SIMULATOR_EXECUTABLE));
	SERIAL_CHECK_TRUE(start_serial_driver(&uch_case, simulator.port));
	online = true;
	SERIAL_CHECK_TRUE(wait_for_first_poll());
	for (int i = 0; i < ARRAY_SIZE(usb_items); i++) {
		SERIAL_CHECK_TRUE(set_port(usb_items[i], false));
		SERIAL_CHECK_TRUE(wait_for_property_state(AUX_USB_PORT_PROPERTY_NAME, INDIGO_OK_STATE));
		SERIAL_CHECK_TRUE(wait_for_port(usb_items[i], false));
	}
	for (int i = 0; i < ARRAY_SIZE(usb_items); i++) {
		SERIAL_CHECK_TRUE(set_port(usb_items[i], true));
		SERIAL_CHECK_TRUE(wait_for_property_state(AUX_USB_PORT_PROPERTY_NAME, INDIGO_OK_STATE));
		SERIAL_CHECK_TRUE(wait_for_port(usb_items[i], true));
	}
cleanup:
	if (online) { stop_serial_driver(&uch_case); }
	stop_external_serial_simulator(&simulator);
}

