// AUX powerbox coverage for indigo_aux_uch against the standalone Pegasus USB Control Hub simulator
// over a real PTY. The hub switches six USB ports and reports supply voltage and uptime from a
// periodic "PA" status frame. Port state is owned by the device: the poll mirrors it back into
// AUX_USB_PORT, so a switch request has to be confirmed by the following status frame rather than
// by the driver echoing the request.

#include <indigo_drivers/aux_uch/indigo_aux_uch.h>

#include "serial_simulator_test_common.h"

#ifndef AUX_UCH_SIMULATOR_EXECUTABLE
#define AUX_UCH_SIMULATOR_EXECUTABLE "build/integration/aux_uch_simulator"
#endif

static const simulator_driver_case uch_case = {
	"PegasusAstro USB Control Hub",
	"indigo_aux_uch",
	"USB Control Hub",
	indigo_aux_uch,
	false,
	NULL, 0, NULL, 0, NULL, 0, NULL, 0
};

static const char *const usb_items[] = {
	AUX_USB_PORT_1_ITEM_NAME, AUX_USB_PORT_2_ITEM_NAME, AUX_USB_PORT_3_ITEM_NAME,
	AUX_USB_PORT_4_ITEM_NAME, AUX_USB_PORT_5_ITEM_NAME, AUX_USB_PORT_6_ITEM_NAME
};

static const char *info_text(const char *item_name) {
	indigo_item *item = find_cached_item(INFO_PROPERTY_NAME, item_name);
	return item == NULL ? "" : item->text.value;
}

static bool set_port(const char *item, bool value) {
	return indigo_change_switch_property_1(&simulator_test_client, uch_case.device_name, AUX_USB_PORT_PROPERTY_NAME, item, value) == INDIGO_OK;
}

// AUX_INFO is defined with zeroed items at attach, so its state says nothing about whether a status
// frame has arrived. The supply voltage is only ever written by a completed poll.
static bool wait_for_first_poll(void) {
	for (int i = 0; i < 500; i++) {
		if (cached_number_value(AUX_INFO_PROPERTY_NAME, AUX_INFO_VOLTAGE_ITEM_NAME) > 0) {
			return true;
		}
		indigo_usleep(10000);
	}
	return false;
}

// The poll mirrors the device's own port state back, so a request is only confirmed once the status
// frame agrees with it. The property must also have left BUSY: INDIGO_COPY_VALUES_PROCESS_CHANGE
// drops a change that arrives while the previous one is still running, so a test that issues the
// next request as soon as the item value looks right would silently lose it.
static bool wait_for_port(const char *item, bool value) {
	for (int i = 0; i < 500; i++) {
		indigo_property *property = find_cached_property(AUX_USB_PORT_PROPERTY_NAME);
		indigo_item *port = find_cached_item(AUX_USB_PORT_PROPERTY_NAME, item);
		if (property != NULL && property->state != INDIGO_BUSY_STATE && port != NULL && port->sw.value == value) {
			return true;
		}
		indigo_usleep(10000);
	}
	return false;
}

