// A datagram lost on the way back from the mount must cost one retry, not the session. The driver
// reads UDP replies through a handle whose receive timeout is reported as a read error, and that
// error latches, so a bare read would make every later transfer fail without touching the socket
// while the mount still reported itself connected.
static void synscan_mount_survives_lost_udp_replies(void) {
	external_serial_simulator simulator = { 0 };
	char url[INDIGO_VALUE_SIZE];
	int port = 11881;

	// Every seventh reply is dropped, a far worse loss rate than the roughly two percent measured
	// on the Wi-Fi link to the real mount, so a normal session loses several answers.
	SERIAL_CHECK_TRUE(start_lossy_udp_simulator(&simulator, port, 7));
	snprintf(url, sizeof(url), "synscan://127.0.0.1:%d", port);
	SERIAL_CHECK_TRUE(start_serial_driver(&synscan_mount, url));
	SERIAL_CHECK_TRUE(context.connected && context.last_connection_state == INDIGO_OK_STATE);

	// The mount has to keep answering afterwards. Each of these is a fresh transaction, so a
	// latched handle would fail all of them.
	for (int i = 0; i < 6; i++) {
		SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_change_switch_property_1(&simulator_test_client, synscan_mount.device_name, MOUNT_TRACKING_PROPERTY_NAME, i % 2 ? MOUNT_TRACKING_OFF_ITEM_NAME : MOUNT_TRACKING_ON_ITEM_NAME, true));
		SERIAL_CHECK_TRUE(wait_for_property_state(MOUNT_TRACKING_PROPERTY_NAME, INDIGO_OK_STATE));
	}
	SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_change_switch_property_1(&simulator_test_client, synscan_mount.device_name, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_OFF_ITEM_NAME, true));
	SERIAL_CHECK_TRUE(wait_for_property_state(MOUNT_TRACKING_PROPERTY_NAME, INDIGO_OK_STATE));

cleanup:
	if (context.connected) {
		stop_serial_driver(&synscan_mount);
	}
	stop_external_serial_simulator(&simulator);
}

// True when the host of a detected "synscan://<host>:<port>" URL is an address of this machine, where the simulator listens.
static bool synscan_port_is_local(const char *port) {
	char host[INDIGO_VALUE_SIZE];
	if (strncmp(port, "synscan://", 10)) {
		return false;
	}
	snprintf(host, sizeof(host), "%s", port + 10);
	host[strcspn(host, ":")] = 0;
	if (!strcmp(host, "127.0.0.1") || !strcmp(host, "localhost")) {
		return true;
	}
	struct ifaddrs *addresses = NULL;
	bool local = false;
	if (getifaddrs(&addresses) == 0) {
		for (struct ifaddrs *address = addresses; address != NULL && !local; address = address->ifa_next) {
			if (address->ifa_addr != NULL && address->ifa_addr->sa_family == AF_INET) {
				char text[INET_ADDRSTRLEN];
				if (inet_ntop(AF_INET, &((struct sockaddr_in *)address->ifa_addr)->sin_addr, text, sizeof(text)) != NULL && !strcmp(text, host)) {
					local = true;
				}
			}
		}
		freeifaddrs(addresses);
	}
	return local;
}

static void synscan_mount_connects_with_udp_autodetection(void) {
	external_serial_simulator simulator = { 0 };
	bool driver_started = false;

	SERIAL_CHECK_TRUE(start_udp_simulator_drop_first_replies(&simulator, 11880, 5));
	SERIAL_CHECK_TRUE(bring_up_serial_driver(&synscan_mount));
	driver_started = true;
	if (!connect_serial_device(&synscan_mount, "synscan://")) {
		// One active-discovery call can use five one-second receive timeouts; the driver
		// permits eight calls with pauses. The generic five-second connection wait
		// must not tear down the driver while those retries are still running.
		bool connected = false;
		for (int i = 0; i < 550; i++) {
			if (context.connected && !context.disconnected && context.last_connection_state == INDIGO_OK_STATE) {
				connected = true;
				break;
			}
			if (context.last_connection_state == INDIGO_ALERT_STATE) {
				break;
			}
			indigo_usleep(100000);
		}
		SERIAL_CHECK_TRUE(connected);
	}
	SERIAL_CHECK_TRUE(context.connected && context.last_connection_state == INDIGO_OK_STATE);
	// The broadcast reaches every SynScan WiFi mount on the network, and the simulator drops its first replies, so a
	// real mount powered on nearby answers first. Then this case cannot isolate the simulator and checks no further.
	indigo_item *port = find_cached_item(DEVICE_PORT_PROPERTY_NAME, DEVICE_PORT_ITEM_NAME);
	SERIAL_CHECK_TRUE(port != NULL);
	if (!synscan_port_is_local(port->text.value)) {
		printf("    a SynScan mount on the network answered the broadcast before the simulator, the simulator was not exercised\n");
		goto cleanup;
	}
	assert_serial_mount_class_property_completeness();

cleanup:
	if (driver_started && context.connected) {
		stop_serial_driver(&synscan_mount);
	} else if (driver_started) {
		tear_down_serial_driver(&synscan_mount);
	}
	stop_external_serial_simulator(&simulator);
}

