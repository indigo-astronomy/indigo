int main(void) {
	char folder[] = "/tmp/indigo_architecture_XXXXXX";
	char original[PATH_MAX];
	if (!getcwd(original, sizeof(original)) || !mkdtemp(folder)) {
		perror("architecture fixture");
		return 1;
	}
	if (chdir(folder) != 0) {
		rmdir(folder);
		return 1;
	}
	const indigo_test_case tests[] = {
		{ "SDK startup discovery without hot-plug", sdk_startup_discovery_without_hotplug },
		{ "C++ output selection, C linkage, extraction and unchanged C default", cpp_output_selection_and_extraction },
		{ "Generated transport scaffolding compiles as C11 and C++11", generated_code_compiles_as_c_and_cpp },
		{ "Old and C++ compatible USB registration preserve VID/PID on extraction", usb_registration_reverse_extraction },
		{ "Abort priority and unchanged synchronous, normal and guiding dispatch", abort_dispatch_uses_urgent_priority },
		{ "nine platform/CPU conditions and three reverse extractions", conditions_and_reverse_extraction },
		{ "unsupported fallback without SDK headers or linkage", unsupported_fallback },
		{ "unrestricted default", unrestricted_default },
		{ "name and name_value stay distinct in either order", name_and_name_value_are_distinct },
		{ "All supported DSL attributes and code blocks", all_supported_attributes },
		{ "USB duplicate, attachment and initialization rollback guards", libusb_lifecycle_guards },
		{ "All hotplug transports drain before detach", all_hotplug_shutdown_guards }
	};
	int result = indigo_run_tests("Generator architecture", tests, sizeof(tests) / sizeof(tests[0]));
	DIR *directory = opendir(".");
	if (directory) {
		struct dirent *entry;
		while ((entry = readdir(directory))) {
			if (strcmp(entry->d_name, ".") && strcmp(entry->d_name, "..") && unlink(entry->d_name) != 0) {
				result = 1;
			}
		}
		closedir(directory);
	} else {
		result = 1;
	}
	if (chdir(original) != 0 || rmdir(folder) != 0) {
		result = 1;
	}
	return result;
}
