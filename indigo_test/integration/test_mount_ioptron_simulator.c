static void check_manual_motion(int index) {
	const ioptron_dialect *d = dialects + index;
	io_fixture fixture = { 0 };
	external_serial_simulator *simulator = &fixture.simulator;
	SERIAL_CHECK_TRUE(io_open_mount(&fixture, d->protocol, NULL, TRACKING_ARGS));
	indigo_usleep(1200000);
	// North at maximum rate moves the declination axis until the axis is stopped.
	SERIAL_CHECK_TRUE(io_switch(&ioptron_mount, MOUNT_SLEW_RATE_PROPERTY_NAME, MOUNT_SLEW_RATE_MAX_ITEM_NAME, true, INDIGO_OK_STATE));
	double dec = DEC_VALUE();
	SERIAL_CHECK_TRUE(io_switch(&ioptron_mount, MOUNT_MOTION_DEC_PROPERTY_NAME, MOUNT_MOTION_NORTH_ITEM_NAME, true, INDIGO_BUSY_STATE));
	SERIAL_CHECK_TRUE(wait_event(simulator, d->rate_max, 0));
	SERIAL_CHECK_TRUE(wait_event(simulator, d->move_north, 0));
	SERIAL_CHECK_TRUE(wait_number_change(MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, MOUNT_EQUATORIAL_COORDINATES_DEC_ITEM_NAME, dec, 1.0));
	int stops = event_count(simulator, d->stop_dec);
	SERIAL_CHECK_TRUE(io_switch(&ioptron_mount, MOUNT_MOTION_DEC_PROPERTY_NAME, MOUNT_MOTION_NORTH_ITEM_NAME, false, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(wait_event(simulator, d->stop_dec, stops));
	indigo_usleep(2500000);
	SERIAL_CHECK_TRUE(number_stays(MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, MOUNT_EQUATORIAL_COORDINATES_DEC_ITEM_NAME, 0.01, 1500));
	// East then reversal to west on the RA axis.
	double ra = RA_VALUE();
	SERIAL_CHECK_TRUE(io_switch(&ioptron_mount, MOUNT_MOTION_RA_PROPERTY_NAME, MOUNT_MOTION_EAST_ITEM_NAME, true, INDIGO_BUSY_STATE));
	SERIAL_CHECK_TRUE(wait_event(simulator, d->move_east, 0));
	SERIAL_CHECK_TRUE(wait_number_change(MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, MOUNT_EQUATORIAL_COORDINATES_RA_ITEM_NAME, ra, 0.05));
	ra = RA_VALUE();
	SERIAL_CHECK_TRUE(io_switch(&ioptron_mount, MOUNT_MOTION_RA_PROPERTY_NAME, MOUNT_MOTION_WEST_ITEM_NAME, true, INDIGO_BUSY_STATE));
	SERIAL_CHECK_TRUE(wait_event(simulator, d->move_west, 0));
	SERIAL_CHECK_TRUE(wait_number_change(MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, MOUNT_EQUATORIAL_COORDINATES_RA_ITEM_NAME, ra + 0.2, -0.05));
	// Stopping one axis leaves the other axis moving.
	dec = DEC_VALUE();
	SERIAL_CHECK_TRUE(io_switch(&ioptron_mount, MOUNT_MOTION_DEC_PROPERTY_NAME, MOUNT_MOTION_SOUTH_ITEM_NAME, true, INDIGO_BUSY_STATE));
	SERIAL_CHECK_TRUE(wait_number_change(MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, MOUNT_EQUATORIAL_COORDINATES_DEC_ITEM_NAME, dec, -0.5));
	SERIAL_CHECK_TRUE(io_switch(&ioptron_mount, MOUNT_MOTION_DEC_PROPERTY_NAME, MOUNT_MOTION_SOUTH_ITEM_NAME, false, INDIGO_OK_STATE));
	SERIAL_CHECK_EQ_INT(INDIGO_BUSY_STATE, find_cached_property(MOUNT_MOTION_RA_PROPERTY_NAME)->state);
	indigo_usleep(2500000);
	ra = RA_VALUE();
	SERIAL_CHECK_TRUE(wait_number_change(MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, MOUNT_EQUATORIAL_COORDINATES_RA_ITEM_NAME, ra + 0.2, -0.05));
	stops = event_count(simulator, d->stop_ra);
	SERIAL_CHECK_TRUE(io_switch(&ioptron_mount, MOUNT_MOTION_RA_PROPERTY_NAME, MOUNT_MOTION_WEST_ITEM_NAME, false, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(wait_event(simulator, d->stop_ra, stops));
	indigo_usleep(2500000);
	SERIAL_CHECK_TRUE(number_stays(MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, MOUNT_EQUATORIAL_COORDINATES_RA_ITEM_NAME, 0.003, 1500));
	// Every slew-rate item maps to its documented speed command.
	static const char *items[] = { MOUNT_SLEW_RATE_GUIDE_ITEM_NAME, MOUNT_SLEW_RATE_CENTERING_ITEM_NAME, MOUNT_SLEW_RATE_FIND_ITEM_NAME };
	const char *commands[] = { d->rate_guide, d->rate_centering, d->rate_find };
	for (int i = 0; i < 3; i++) {
		SERIAL_CHECK_TRUE(io_switch(&ioptron_mount, MOUNT_SLEW_RATE_PROPERTY_NAME, items[i], true, INDIGO_OK_STATE));
		SERIAL_CHECK_TRUE(io_switch(&ioptron_mount, MOUNT_MOTION_DEC_PROPERTY_NAME, MOUNT_MOTION_NORTH_ITEM_NAME, true, INDIGO_BUSY_STATE));
		SERIAL_CHECK_TRUE(wait_event(simulator, commands[i], 0));
		SERIAL_CHECK_TRUE(io_switch(&ioptron_mount, MOUNT_MOTION_DEC_PROPERTY_NAME, MOUNT_MOTION_NORTH_ITEM_NAME, false, INDIGO_OK_STATE));
	}
	SERIAL_CHECK_EQ_INT(0, protocol_violations(simulator));
cleanup:
	io_close(&fixture);
}

