	SERIAL_CHECK_TRUE(!connect_serial_device(&ioptron_mount, NULL));
	SERIAL_CHECK_EQ_INT(INDIGO_ALERT_STATE, context.last_connection_state);
	// Both status reads fail during initialization: connection rolls back.
	SERIAL_CHECK_TRUE(io_replace_simulator(&fixture, "0300", NULL));
	SERIAL_CHECK_TRUE(inject(&fixture.simulator, "GLS", "DROP", 2));
	SERIAL_CHECK_TRUE(!connect_serial_device(&ioptron_mount, NULL));
	SERIAL_CHECK_EQ_INT(INDIGO_ALERT_STATE, context.last_connection_state);
	SERIAL_CHECK_TRUE(find_cached_property(MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME) == NULL);
	int polls = event_count(&fixture.simulator, "GEP");
	indigo_usleep(1500000);
	SERIAL_CHECK_EQ_INT(polls, event_count(&fixture.simulator, "GEP"));
	// A 9600 Bd probe without a product reply reopens and retries :MountInfo#.
	SERIAL_CHECK_TRUE(inject(&fixture.simulator, "MountInfo", "DROP", 1));
	int probes = event_count(&fixture.simulator, "MountInfo");
	fixture.mount = connect_serial_device(&ioptron_mount, NULL);
	SERIAL_CHECK_TRUE(fixture.mount);
	SERIAL_CHECK_TRUE(event_count(&fixture.simulator, "MountInfo") >= probes + 3);
	SERIAL_CHECK_TRUE(io_sync(6.5, -12.25, INDIGO_OK_STATE));
	SERIAL_CHECK_EQ_INT(0, protocol_violations(&fixture.simulator));
cleanup:
	io_close(&fixture);
