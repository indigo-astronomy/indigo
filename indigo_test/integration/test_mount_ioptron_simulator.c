static void check_tracking_rates(int index) {
	const ioptron_dialect *d = dialects + index;
	io_fixture fixture = { 0 };
	external_serial_simulator *simulator = &fixture.simulator;
	SERIAL_CHECK_TRUE(io_open_mount(&fixture, d->protocol, NULL, NULL));
	SERIAL_CHECK_EQ_INT(5, property_count(MOUNT_TRACK_RATE_PROPERTY_NAME));
	if (d->custom_rate) {
		SERIAL_CHECK_TRUE(io_number(&ioptron_mount, MOUNT_CUSTOM_TRACKING_RATE_PROPERTY_NAME, MOUNT_CUSTOM_TRACKING_RATE_ITEM_NAME, 1.5, INDIGO_OK_STATE));
	}
	static const char *items[] = { MOUNT_TRACK_RATE_LUNAR_ITEM_NAME, MOUNT_TRACK_RATE_KING_ITEM_NAME, MOUNT_TRACK_RATE_CUSTOM_ITEM_NAME, MOUNT_TRACK_RATE_SIDEREAL_ITEM_NAME, MOUNT_TRACK_RATE_SOLAR_ITEM_NAME };
	static const char *commands[] = { "RT1", "RT3", "RT4", "RT0", "RT2" };
	for (int i = 0; i < 5; i++) {
		int enables = event_count(simulator, "ST1");
		SERIAL_CHECK_TRUE(io_switch(&ioptron_mount, MOUNT_TRACK_RATE_PROPERTY_NAME, items[i], true, INDIGO_OK_STATE));
		SERIAL_CHECK_TRUE(wait_event(simulator, commands[i], 0));
		SERIAL_CHECK_TRUE(wait_event(simulator, "ST1", enables));
		if (i == 2 && d->custom_rate) {
			SERIAL_CHECK_TRUE(wait_event(simulator, "RR15000", 0));
		}
	}
	SERIAL_CHECK_TRUE(io_switch(&ioptron_mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_OFF_ITEM_NAME, true, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(wait_event(simulator, "ST0", 0));
	SERIAL_CHECK_TRUE(wait_light(MOUNT_STATE_TRACKING_ITEM_NAME, INDIGO_IDLE_STATE));
	if (index == I0300) {
		// A stopped mount drifts in RA at the sidereal rate; tracking holds position.
		SERIAL_CHECK_TRUE(io_switch(&ioptron_mount, MOUNT_TRACK_RATE_PROPERTY_NAME, MOUNT_TRACK_RATE_SIDEREAL_ITEM_NAME, true, INDIGO_OK_STATE));
		SERIAL_CHECK_TRUE(io_switch(&ioptron_mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_OFF_ITEM_NAME, true, INDIGO_OK_STATE));
		indigo_usleep(1200000);
		double ra = RA_VALUE();
		SERIAL_CHECK_TRUE(wait_number_change(MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, MOUNT_EQUATORIAL_COORDINATES_RA_ITEM_NAME, ra, 0.0008));
		SERIAL_CHECK_TRUE(io_switch(&ioptron_mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_ON_ITEM_NAME, true, INDIGO_OK_STATE));
		indigo_usleep(1200000);
		SERIAL_CHECK_TRUE(number_stays(MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, MOUNT_EQUATORIAL_COORDINATES_RA_ITEM_NAME, 0.0003, 3000));
		SERIAL_CHECK_TRUE(io_switch(&ioptron_mount, MOUNT_TRACK_RATE_PROPERTY_NAME, MOUNT_TRACK_RATE_SOLAR_ITEM_NAME, true, INDIGO_OK_STATE));
	}
	// The selected rate is read back from the mount after reconnecting.
	SERIAL_CHECK_TRUE(io_reconnect_mount(&fixture));
	SERIAL_CHECK_TRUE(switch_value(MOUNT_TRACK_RATE_PROPERTY_NAME, MOUNT_TRACK_RATE_SOLAR_ITEM_NAME));
	SERIAL_CHECK_EQ_INT(0, protocol_violations(simulator));
cleanup:
	io_close(&fixture);
}

