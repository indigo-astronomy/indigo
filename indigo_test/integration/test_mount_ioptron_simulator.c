// Starts the simulator and driver; selects force_item (NULL = autodetection)
// before connecting the mount device.
static bool io_open_mount(io_fixture *fixture, const char *protocol, const char *force_item, const char * const *extra) {
	if (!start_sim(&fixture->simulator, protocol, extra)) {
		return false;
	}
	if (!bring_up_serial_driver(&ioptron_mount)) {
		return false;
	}
	fixture->driver = true;
	enumerate_simulator_device();
	if (!set_mount_port(fixture->simulator.port)) {
		return false;
	}
	if (force_item != NULL && !io_switch(&ioptron_mount, PROTOCOL_PROPERTY, force_item, true, INDIGO_OK_STATE)) {
		return false;
	}
	fixture->mount = connect_serial_device(&ioptron_mount, NULL);
	return fixture->mount;
}

static bool io_open_guider(io_fixture *fixture, const char *protocol, const char * const *extra) {
	if (!start_sim(&fixture->simulator, protocol, extra)) {
		return false;
	}
	if (!bring_up_serial_driver(&ioptron_guider)) {
		return false;
	}
	fixture->driver = true;
	if (!set_mount_port(fixture->simulator.port)) {
		return false;
	}
	indigo_usleep(100000);
	fixture->guider = connect_serial_device(&ioptron_guider, NULL);
	return fixture->guider;
}

static bool io_reconnect_mount(io_fixture *fixture) {
	if (fixture->mount) {
		disconnect_serial_device(&ioptron_mount);
	}
	fixture->mount = connect_serial_device(&ioptron_mount, NULL);
	return fixture->mount;
}

// Replaces a stopped/lost simulator with a fresh one and points DEVICE_PORT at it.
static bool io_replace_simulator(io_fixture *fixture, const char *protocol, const char * const *extra) {
	stop_external_serial_simulator(&fixture->simulator);
	if (!start_sim(&fixture->simulator, protocol, extra)) {
		return false;
	}
	return indigo_change_text_property_1_raw(&simulator_test_client, ioptron_mount.device_name, DEVICE_PORT_PROPERTY_NAME, DEVICE_PORT_ITEM_NAME, fixture->simulator.port) == INDIGO_OK;
}

static void io_close(io_fixture *fixture) {
	if (fixture->driver) {
		if (fixture->guider) {
			disconnect_serial_device(&ioptron_guider);
		}
		if (fixture->mount) {
			disconnect_serial_device(&ioptron_mount);
		}
		tear_down_serial_driver(&ioptron_mount);
	}
	stop_external_serial_simulator(&fixture->simulator);
	memset(fixture, 0, sizeof(*fixture));
}

