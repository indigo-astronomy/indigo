	io_fixture fixture = { 0 };
	SERIAL_CHECK_TRUE(start_sim(&fixture.simulator, "0300", NULL));
	SERIAL_CHECK_TRUE(bring_up_serial_driver(&ioptron_mount));
	fixture.driver = true;
