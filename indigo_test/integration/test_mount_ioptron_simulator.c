static void ioptron_guider_directions_overlap_and_timing(void) {
	io_fixture fixture = { 0 };
	external_serial_simulator *simulator = &fixture.simulator;
	static const char *properties[] = { GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_RA_PROPERTY_NAME };
	static const char *items[] = { GUIDER_GUIDE_NORTH_ITEM_NAME, GUIDER_GUIDE_SOUTH_ITEM_NAME, GUIDER_GUIDE_EAST_ITEM_NAME, GUIDER_GUIDE_WEST_ITEM_NAME };
	static const char letters[] = { 'n', 's', 'e', 'w' };
	static const int durations[] = { 20, 100, 500 };
	double errors[48], percentages[48];
	int samples = 0;
	SERIAL_CHECK_TRUE(io_open_guider(&fixture, "0300", TRACKING_ARGS));
	for (int workload = 0; workload < 2; workload++) {
		for (int direction = 0; direction < 4; direction++) {
			if (workload) {
				int before = event_count(simulator, "MS1");
				const char *coordinate_items[] = { MOUNT_EQUATORIAL_COORDINATES_RA_ITEM_NAME, MOUNT_EQUATORIAL_COORDINATES_DEC_ITEM_NAME };
				double coordinates[] = { direction % 2 ? 2 : 22, direction % 2 ? 60 : -60 };
				SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_change_number_property(&simulator_test_client, ioptron_mount.device_name, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, 2, coordinate_items, coordinates));
				SERIAL_CHECK_TRUE(wait_event(simulator, "MS1", before));
			}
			for (int sample = -1; sample < 6; sample++) {
				int duration = sample < 0 ? 20 : durations[sample % 3];
				char command[32];
				snprintf(command, sizeof(command), "M%c%05d", letters[direction], duration);
				int before = event_count(simulator, command);
				int axis = direction < 2 ? 1 : 0;
				unsigned int revision = property_revision(properties[direction]);
				atomic_store(guide_completed + axis, 0);
				SERIAL_CHECK_TRUE(guide(properties[direction], items[direction], duration, INDIGO_BUSY_STATE));
				SERIAL_CHECK_TRUE(wait_event(simulator, command, before));
				SERIAL_CHECK_TRUE(wait_for_property_state_seen_after(properties[direction], INDIGO_OK_STATE, revision));
				double entered = 0;
				scan_events(simulator, command, false, &entered, NULL, 0);
				double completed = atomic_load(guide_completed + axis) / 1e9;
				double error = (completed - entered) * 1000 - duration;
				SERIAL_CHECK_TRUE(isfinite(error) && completed >= entered && completed - entered < 5);
				SERIAL_CHECK_TRUE(cached_number_value(properties[direction], items[direction]) == 0);
				if (sample >= 0) {
					percentages[samples] = error * 100 / duration;
					errors[samples++] = error;
				}
			}
		}
		if (!workload) {
			fixture.mount = connect_serial_device(&ioptron_mount, NULL);
			SERIAL_CHECK_TRUE(fixture.mount);
			SERIAL_CHECK_TRUE(io_switch(&ioptron_mount, MOUNT_ON_COORDINATES_SET_PROPERTY_NAME, MOUNT_ON_COORDINATES_SET_TRACK_ITEM_NAME, true, INDIGO_OK_STATE));
			reset_simulator_context(&ioptron_guider);
			enumerate_simulator_device();
		}
	}
	// A same-axis request while BUSY replaces the running pulse and reaches the mount; the other
	// axis stays independent. Before overlapping pulses were accepted this block asserted the
	// opposite, that Ms00100 was never sent, which recorded the request being discarded.
	SERIAL_CHECK_TRUE(guide(GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME, 500, INDIGO_BUSY_STATE));
	int before = event_count(simulator, "Ms00100");
	SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_change_number_property_1(&simulator_test_client, ioptron_guider.device_name, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_SOUTH_ITEM_NAME, 100));
	SERIAL_CHECK_TRUE(guide(GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_WEST_ITEM_NAME, 100, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(wait_for_property_state(GUIDER_GUIDE_DEC_PROPERTY_NAME, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(event_count(simulator, "Ms00100") > before);

	// The elapsed time has to follow the second request. Measuring the duration is the point of
	// these two cases: waiting only for the property to leave BUSY passes even when the second
	// request is discarded, which is how this behaviour went unverified before.
	double replacement_started = indigo_monotonic_time();
	SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_change_number_property_1(&simulator_test_client, ioptron_guider.device_name, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME, 2000));
	SERIAL_CHECK_TRUE(wait_for_property_state(GUIDER_GUIDE_DEC_PROPERTY_NAME, INDIGO_BUSY_STATE));
	indigo_usleep(500000);
	SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_change_number_property_1(&simulator_test_client, ioptron_guider.device_name, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME, 600));
	SERIAL_CHECK_TRUE(wait_for_property_not_busy(GUIDER_GUIDE_DEC_PROPERTY_NAME));
	SERIAL_CHECK_TRUE(wait_for_number_item_value(GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME, 0, 0.001));
	// Replacing finishes about 500 + 600 ms after the first request; keeping the superseded pulse
	// would run the full 2000 ms.
	double replaced = (indigo_monotonic_time() - replacement_started) * 1000.0;
	printf("    2000 ms north pulse replaced after 500 ms by a 600 ms north pulse finished in %.0f ms\n", replaced);
	SERIAL_CHECK_TRUE(replaced > 900 && replaced < 1700);

	replacement_started = indigo_monotonic_time();
	SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_change_number_property_1(&simulator_test_client, ioptron_guider.device_name, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME, 2000));
	SERIAL_CHECK_TRUE(wait_for_property_state(GUIDER_GUIDE_DEC_PROPERTY_NAME, INDIGO_BUSY_STATE));
	indigo_usleep(500000);
	SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_change_number_property_1(&simulator_test_client, ioptron_guider.device_name, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_SOUTH_ITEM_NAME, 300));
	SERIAL_CHECK_TRUE(wait_for_property_not_busy(GUIDER_GUIDE_DEC_PROPERTY_NAME));
	SERIAL_CHECK_TRUE(wait_for_number_item_value(GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME, 0, 0.001));
	SERIAL_CHECK_TRUE(wait_for_number_item_value(GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_SOUTH_ITEM_NAME, 0, 0.001));
	double reversed = (indigo_monotonic_time() - replacement_started) * 1000.0;
	printf("    2000 ms north pulse replaced after 500 ms by a 300 ms south pulse finished in %.0f ms\n", reversed);
	SERIAL_CHECK_TRUE(reversed > 600 && reversed < 1400);
	for (int i = 0; i < samples; i++) {
		for (int j = i + 1; j < samples; j++) {
			if (errors[j] < errors[i]) {
				double swap = errors[i];
				errors[i] = errors[j];
				errors[j] = swap;
			}
		}
	}
	double sum = 0, square = 0, absolute = 0, percent_sum = 0, percent_max = 0;
	for (int i = 0; i < samples; i++) {
		sum += errors[i];
		square += errors[i] * errors[i];
		absolute = fmax(absolute, fabs(errors[i]));
		percent_sum += percentages[i];
		percent_max = fmax(percent_max, fabs(percentages[i]));
	}
	if (samples == 48) {
		printf("  Guider software latency, simulator receipt to public OK callback; idle and mount GOTO/polling; 20/100/500 ms; n=%d min=%.3f mean=%.3f median=%.3f p95=%.3f p99=%.3f max=%.3f stddev=%.3f max_abs=%.3f ms\n", samples, errors[0], sum / samples, (errors[23] + errors[24]) / 2, errors[45], errors[47], errors[47], sqrt(fmax(0, square / samples - sum * sum / samples / samples)), absolute);
		printf("  Guider signed mean error=%.3f%% maximum absolute error=%.3f%%; no physical relay timing measured\n", percent_sum / samples, percent_max);
	}
cleanup:
	io_close(&fixture);
}

