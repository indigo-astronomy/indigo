	indigo_usleep(1000000);
	CHECK(exchange(handle, "!dome atpark#", "!dome atpark:1#", NULL, 0));
	CHECK(exchange(handle, "!dome athome#", "!dome athome:0#", NULL, 0));
	CHECK(exchange(handle, "!dome gohome#", "!dome gohome:0#", NULL, 0));
	indigo_usleep(2000000);
	CHECK(exchange(handle, "!dome athome#", "!dome athome:1#", NULL, 0));
	CHECK_EQ(1 << 8 | 1 << 11, exchange_value(handle, "!dome status#"));
	// savefs stops a turning rotator
