static bool network_url(char *url, size_t size) {
	const char *address = strstr(simulator.tcp_url, "://");
	if (address == NULL) {
		fprintf(stderr, "Simulator has no TCP URL\n");
		return false;
	}
	snprintf(url, size, "nexdome%s", address);
	return true;
}

static int unused_tcp_port(void) {
	struct sockaddr_in address = { 0 };
	socklen_t length = sizeof(address);
	int fd = socket(AF_INET, SOCK_STREAM, 0);
	address.sin_family = AF_INET;
	address.sin_addr.s_addr = htonl(INADDR_LOOPBACK);
	if (fd < 0 || bind(fd, (struct sockaddr *)&address, sizeof(address)) < 0 || getsockname(fd, (struct sockaddr *)&address, &length) < 0) {
		if (fd >= 0) {
			close(fd);
		}
		return -1;
	}
	close(fd);
	return ntohs(address.sin_port);
}

static int state_event_count(const char *text) {
	int count = load_events(), result = 0;
	for (int i = 0; i < count; i++) {
		if (!strcmp(events[i].kind, "STATE") && !strcmp(events[i].text, text)) {
			result++;
		}
	}
	return result;
}

