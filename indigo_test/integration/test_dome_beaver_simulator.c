static void trace_pending_line(const char *line) {
	int written = snprintf(trace_pending + trace_pending_length, sizeof(trace_pending) - trace_pending_length, "%s\n", line);
	if (written > 0 && trace_pending_length + written < sizeof(trace_pending)) {
		trace_pending_length += written;
	}
}

static void trace_property(observed_property *entry, const char *kind, indigo_property *property) {
	if (!atomic_load(&trace_active) || !traced_property(property->name)) {
		return;
	}
	char line[1024];
	size_t length = (size_t)snprintf(line, sizeof(line), "%s %s", kind, property->name);
	if (*kind != 'X') {
		length += (size_t)snprintf(line + length, sizeof(line) - length, " %s", state_name(property->state));
		if (*kind == 'D') {
			length += (size_t)snprintf(line + length, sizeof(line) - length, " %s count=%d", property->perm == INDIGO_RO_PERM ? "RO" : "RW", property->count);
		}
		bool masked = property->state == INDIGO_BUSY_STATE && !strcmp(property->name, DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME);
		for (int i = 0; i < property->count && length < sizeof(line); i++) {
			indigo_item *item = property->items + i;
			switch (property->type) {
				case INDIGO_NUMBER_VECTOR:
					if (masked) {
						length += (size_t)snprintf(line + length, sizeof(line) - length, " %s=*", item->name);
					} else {
						length += (size_t)snprintf(line + length, sizeof(line) - length, " %s=%g/%g", item->name, item->number.value, item->number.target);
					}
					break;
				case INDIGO_SWITCH_VECTOR:
					if (item->sw.value) {
						length += (size_t)snprintf(line + length, sizeof(line) - length, " %s", item->name);
					}
					break;
				case INDIGO_LIGHT_VECTOR:
					length += (size_t)snprintf(line + length, sizeof(line) - length, " %s=%s", item->name, state_name(item->light.value));
					break;
				case INDIGO_TEXT_VECTOR:
					if (!strcmp(property->name, DEVICE_PORT_PROPERTY_NAME)) {
						length += (size_t)snprintf(line + length, sizeof(line) - length, " %s=PORT", item->name);
					} else if (strcmp(property->name, INFO_PROPERTY_NAME) || !strcmp(item->name, INFO_DEVICE_MODEL_ITEM_NAME) || !strcmp(item->name, INFO_DEVICE_FW_REVISION_ITEM_NAME)) {
						length += (size_t)snprintf(line + length, sizeof(line) - length, " %s=%s", item->name, indigo_get_text_item_value(item));
					}
					break;
				default:
					break;
			}
		}
	}
	if (entry && *kind == 'U' && property->state == INDIGO_BUSY_STATE && !strcmp(entry->last_trace, line)) {
		return;
	}
	if (entry) {
		snprintf(entry->last_trace, sizeof(entry->last_trace), "%s", line);
	}
	trace_pending_line(line);
}

static void note_state(observed_property *entry, indigo_property *property) {
	entry->revision++;
	if (property->state == INDIGO_BUSY_STATE) {
		entry->busy++;
	} else if (property->state == INDIGO_ALERT_STATE) {
		entry->alert++;
	}
}

static indigo_result observe_define(indigo_client *client, indigo_device *device, indigo_property *property, const char *message) {
	pthread_mutex_lock(&observe_mutex);
	indigo_result result = simulator_client_define_property(client, device, property, message);
	if (is_current_device(property)) {
		observed_property *entry = observed_entry(property->name, true);
		if (entry) {
			entry->defines++;
			note_state(entry, property);
			*entry->last_trace = 0;
		}
		trace_property(entry, "D", property);
	}
	pthread_mutex_unlock(&observe_mutex);
	return result;
}

static indigo_result observe_update(indigo_client *client, indigo_device *device, indigo_property *property, const char *message) {
	pthread_mutex_lock(&observe_mutex);
	indigo_result result = simulator_client_update_property(client, device, property, message);
	if (is_current_device(property)) {
		observed_property *entry = observed_entry(property->name, true);
		if (entry) {
			note_state(entry, property);
		}
		if (!strcmp(property->name, DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME)) {
			double value = property->items[0].number.value;
			minimum_azimuth = value < minimum_azimuth ? value : minimum_azimuth;
			maximum_azimuth = value > maximum_azimuth ? value : maximum_azimuth;
		}
		trace_property(entry, "U", property);
		if (getenv("BEAVER_DEBUG")) {
			fprintf(stderr, "%.3f U %s %s\n", now(), property->name, state_name(property->state));
		}
	}
	pthread_mutex_unlock(&observe_mutex);
	return result;
}

static indigo_result observe_delete(indigo_client *client, indigo_device *device, indigo_property *property, const char *message) {
	pthread_mutex_lock(&observe_mutex);
	indigo_result result = simulator_client_delete_property(client, device, property, message);
	if (is_current_device(property) && !*property->name) {
		release_cached_properties();
	} else if (is_current_device(property)) {
		observed_property *entry = observed_entry(property->name, true);
		if (entry) {
			entry->deletes++;
			*entry->last_trace = 0;
		}
		trace_property(entry, "X", property);
	}
	pthread_mutex_unlock(&observe_mutex);
	return result;
}

static indigo_result observe_message(indigo_client *client, indigo_device *device, indigo_property *property, const char *message) {
	pthread_mutex_lock(&observe_mutex);
	if (device != NULL && context.driver_case != NULL && !strcmp(device->name, context.driver_case->device_name) && message != NULL) {
		const char *name = property ? property->name : "";
		if (message_count < MESSAGES_MAX) {
			snprintf(messages[message_count].property, sizeof(messages[message_count].property), "%s", name);
			snprintf(messages[message_count].text, sizeof(messages[message_count].text), "%s", message);
			message_count++;
		}
		if (atomic_load(&trace_active)) {
			char line[1024], text[INDIGO_VALUE_SIZE];
			snprintf(text, sizeof(text), "%s", message);
			char *port = strstr(text, " on /dev/");
			if (port) {
				strcpy(port, " on PORT");
			}
			snprintf(line, sizeof(line), "M %s \"%s\"", name, text);
			trace_pending_line(line);
		}
		if (getenv("BEAVER_DEBUG")) {
			fprintf(stderr, "%.3f M %s %s\n", now(), name, message);
		}
	}
	pthread_mutex_unlock(&observe_mutex);
	return INDIGO_OK;
}

