	CHECK(exchange(handle, "!dome gotoaz x#", "!dome gotoaz x:-1#", NULL, 0));
	CHECK(exchange(handle, "!dome status#", "!dome status:256#", NULL, 0));
	// elapsed-time rotation at 30 deg/s with optional timeout argument
	double started = now();
	CHECK(exchange(handle, "!dome gotoaz 130.000000 60#", "!dome gotoaz 130.000000 60:0#", NULL, 0));
	indigo_usleep(400000);
	double position = exchange_value(handle, "!dome getaz#");
	CHECK(position > 100 && position < 130);
	CHECK_EQ(257, exchange_value(handle, "!dome status#"));
	while (exchange_value(handle, "!dome getaz#") != 130 && now() - started < 5) {
		indigo_usleep(20000);
	}
	CHECK(now() - started >= 0.9);
	CHECK_EQ(256, exchange_value(handle, "!dome status#"));
	// shortest way across zero, abort variants
	CHECK(exchange(handle, "!dome gotoaz 330.000000#", "!dome gotoaz 330.000000:0#", NULL, 0));
	indigo_usleep(1200000);
	position = exchange_value(handle, "!dome getaz#");
	CHECK(position > 330 || position < 130);
	CHECK(exchange(handle, "!dome abort 0 0 1#", "!dome abort 0 0 1:0#", NULL, 0));
	CHECK_EQ(1, (int)exchange_value(handle, "!dome status#") & 1);
	CHECK(exchange(handle, "!dome abort 0 0 0#", "!dome abort 0 0 0:0#", NULL, 0));
	position = exchange_value(handle, "!dome getaz#");
	indigo_usleep(300000);
	CHECK_EQ(position, exchange_value(handle, "!dome getaz#"));
	CHECK_EQ(0, (int)exchange_value(handle, "!dome status#") & 1);
