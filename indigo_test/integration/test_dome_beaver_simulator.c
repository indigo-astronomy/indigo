// index following the last event of the n-th status poll, or -1 while it is incomplete
// A poll starts with "!dome status#" and ends with the failure code queries, optionally followed by failure messages.
static int poll_end_index(int count, int poll) {
	int start = rx_index(count, "!dome status#", poll);
	if (start < 0) {
		return -1;
	}
	int end = -1;
	bool pending = false;
	for (int i = start + 1; i < count; i++) {
		if (!strcmp(events[i].kind, "RX")) {
			if (!strcmp(events[i].text, "!dome status#")) {
				return end >= 0 ? end : i;
			}
			pending = is_failure_code_request(events[i].text) || is_failure_message_request(events[i].text);
		} else if (!strcmp(events[i].kind, "TX") && pending) {
			end = i + 1;
			pending = false;
		}
	}
	// a failure message request may still follow the last failure code reply
	if (end >= 0 && !pending && now() - events[end - 1].time > 0.15) {
		return end;
	}
	return -1;
}

static bool wait_polls(int polls, double timeout) {
	int target = rx_count("!dome status#") + polls;
	double end = now() + timeout;
	do {
		int count = load_events();
		if (poll_end_index(count, target) >= 0) {
			indigo_usleep(20000);
			return true;
		}
		indigo_usleep(20000);
	} while (now() < end);
	fprintf(stderr, "No %d status polls\n", polls);
	return false;
}

static bool rx_sequence(int mark, const char * const *expected, int expected_count, double timeout) {
	double end = now() + timeout;
	do {
		int count = load_events(), found = 0;
		bool matches = true;
		for (int i = mark; i < count && found < expected_count; i++) {
			if (strcmp(events[i].kind, "RX")) {
				continue;
			}
			if (strcmp(events[i].text, expected[found])) {
				fprintf(stderr, "RX #%d: expected %s, got %s\n", found, expected[found], events[i].text);
				matches = false;
				break;
			}
			found++;
		}
		if (!matches) {
			return false;
		}
		if (found == expected_count) {
			return true;
		}
		indigo_usleep(20000);
	} while (now() < end);
	fprintf(stderr, "RX sequence incomplete\n");
	return false;
}

