	// The weak interface assertion passes on the shared AUX bit alone, so pin the exact value: a
	// cover that does not advertise the lightbox bit is not offered as a flat panel by clients.
	indigo_item *interface = find_cached_item(INFO_PROPERTY_NAME, INFO_DEVICE_INTERFACE_ITEM_NAME);
	SERIAL_CHECK_TRUE(interface != NULL);
	SERIAL_CHECK_EQ_INT(INDIGO_INTERFACE_AUX_LIGHTBOX, (int)strtoul(interface->text.value, NULL, 10));
	assert_serial_aux_class_property_completeness();

