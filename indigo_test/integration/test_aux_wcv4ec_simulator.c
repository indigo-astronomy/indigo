static void reconnect_resumes_polling(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_wcv4ec(&simulator, NULL));
	SERIAL_CHECK_TRUE(start_serial_driver(&wcv4ec_aux, simulator.port));
	online = true;
	SERIAL_CHECK_TRUE(wait_for_first_poll());
	SERIAL_CHECK_TRUE(set_positions(150, 15));
	SERIAL_CHECK_TRUE(wait_for_confirmed_number(AUX_SET_OPEN_CLOSE_PROPERTY_NAME, AUX_COVER_OPEN_ITEM_NAME, 150, .01));
	disconnect_serial_device(&wcv4ec_aux);
	SERIAL_CHECK_TRUE(!context.connected);
	SERIAL_CHECK_TRUE(connect_serial_device(&wcv4ec_aux, simulator.port));
	// The box kept the taught angles, and the driver has to report those rather than its defaults.
	SERIAL_CHECK_TRUE(wait_for_confirmed_number(AUX_SET_OPEN_CLOSE_PROPERTY_NAME, AUX_COVER_OPEN_ITEM_NAME, 150, .01));
	SERIAL_CHECK_TRUE(wait_for_confirmed_number(AUX_SET_OPEN_CLOSE_PROPERTY_NAME, AUX_COVER_CLOSE_ITEM_NAME, 15, .01));
cleanup:
	if (online) { stop_serial_driver(&wcv4ec_aux); }
	stop_external_serial_simulator(&simulator);
}

static void repeated_disconnect_is_tolerated(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_wcv4ec(&simulator, NULL));
	SERIAL_CHECK_TRUE(start_serial_driver(&wcv4ec_aux, simulator.port));
	online = true;
	disconnect_serial_device(&wcv4ec_aux);
	SERIAL_CHECK_TRUE(!context.connected);
	disconnect_serial_device(&wcv4ec_aux);
	SERIAL_CHECK_TRUE(!context.connected);
	online = false;
	tear_down_serial_driver(&wcv4ec_aux);
cleanup:
	if (online) { stop_serial_driver(&wcv4ec_aux); }
	stop_external_serial_simulator(&simulator);
}

// The open only succeeds once a status frame identifies the box, so a port with nothing behind it
// has to be refused rather than reported as a connected cover.
static void vanished_port_is_refused(void) {
	external_serial_simulator simulator = { 0 };
	SERIAL_CHECK_TRUE(start_wcv4ec(&simulator, NULL));
	SERIAL_CHECK_TRUE(bring_up_serial_driver(&wcv4ec_aux));
	stop_external_serial_simulator(&simulator);
	SERIAL_CHECK_TRUE(!connect_serial_device(&wcv4ec_aux, simulator.port));
	SERIAL_CHECK_TRUE(!context.connected);
cleanup:
	tear_down_serial_driver(&wcv4ec_aux);
}

