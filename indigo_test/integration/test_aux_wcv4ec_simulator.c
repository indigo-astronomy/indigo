// AUX lightbox/cover coverage for indigo_aux_wcv4ec against the standalone WandererCover V4-EC
// simulator over a real PTY. The cover is a servo with configurable open and close angles: the box
// broadcasts an "A"-separated status frame once a second carrying both configured angles and the
// live position, and the driver decides a move is finished by comparing the live position against
// the configured one. Nothing is acknowledged, so every command is verified through the next frame.

#include <indigo_drivers/aux_wcv4ec/indigo_aux_wcv4ec.h>

#include "serial_simulator_test_common.h"

#ifndef AUX_WCV4EC_SIMULATOR_EXECUTABLE
#define AUX_WCV4EC_SIMULATOR_EXECUTABLE "build/integration/aux_wcv4ec_simulator"
#endif

#define AUX_DETECT_OPEN_CLOSE_PROPERTY_NAME "X_COVER_DETECT_OPEN_CLOSE"
#define AUX_SET_OPEN_CLOSE_PROPERTY_NAME    "X_COVER_SET_OPEN_CLOSE"
#define AUX_HEATER_PROPERTY_NAME            "X_HEATER"
#define AUX_HEATER_OFF_ITEM_NAME            "OFF"
#define AUX_HEATER_LOW_ITEM_NAME            "LOW"
#define AUX_HEATER_HIGH_ITEM_NAME           "HIGH"
#define AUX_HEATER_MAX_ITEM_NAME            "MAX"

// The simulator boots with the cover parked closed and these angles configured.
#define SIMULATED_OPEN_POSITION   270.0
#define SIMULATED_CLOSE_POSITION  20.0

static const simulator_driver_case wcv4ec_aux = {
	"WandererCover V4-EC Cover",
	"indigo_aux_wcv4ec",
	"WandererCover V4-EC",
	indigo_aux_wcv4ec,
	false,
	NULL, 0, NULL, 0, NULL, 0, NULL, 0
};

static bool start_wcv4ec(external_serial_simulator *simulator, const char * const *arguments) {
	if (arguments == NULL) {
		return start_external_serial_simulator(simulator, AUX_WCV4EC_SIMULATOR_EXECUTABLE);
	}
	return start_external_serial_simulator_with_args(simulator, AUX_WCV4EC_SIMULATOR_EXECUTABLE, arguments);
}

static double number_of(const char *property_name, const char *item_name) {
	return cached_number_value(property_name, item_name);
}

static const char *info_text(const char *item_name) {
	indigo_item *item = find_cached_item(INFO_PROPERTY_NAME, item_name);
	return item == NULL ? "" : item->text.value;
}

static bool set_switch(const char *property_name, const char *item_name, bool value) {
	return indigo_change_switch_property_1(&simulator_test_client, wcv4ec_aux.device_name, property_name, item_name, value) == INDIGO_OK;
}

static bool set_number(const char *property_name, const char *item_name, double value) {
	return indigo_change_number_property_1(&simulator_test_client, wcv4ec_aux.device_name, property_name, item_name, value) == INDIGO_OK;
}

// Both configured angles are sent to the device by a single handler, so most scenarios set them as
// one request rather than relying on whatever the untouched item's target happens to hold.
static bool set_positions(double open, double close) {
	static const char *items[] = { AUX_COVER_OPEN_ITEM_NAME, AUX_COVER_CLOSE_ITEM_NAME };
	const double values[] = { open, close };
	return indigo_change_number_property(&simulator_test_client, wcv4ec_aux.device_name, AUX_SET_OPEN_CLOSE_PROPERTY_NAME, 2, items, values) == INDIGO_OK;
}

// X_COVER_SET_OPEN_CLOSE is defined with compiled-in angles (110 / 22) that differ from the ones the
// simulator reports, so the arrival of the first status frame is observable as the open angle
// changing to the device's own value.
static bool wait_for_first_poll(void) {
	for (int i = 0; i < 500; i++) {
		if (fabs(number_of(AUX_SET_OPEN_CLOSE_PROPERTY_NAME, AUX_COVER_OPEN_ITEM_NAME) - SIMULATED_OPEN_POSITION) < .01) {
			return true;
		}
		indigo_usleep(10000);
	}
	return false;
}

// The poll rewrites both angles from the device once a second, and the change handler writes the
// requested value to the item straight away, so a value the box silently ignored is visible for up
// to a frame. Confirming an angle therefore means watching it survive more than one frame; a plain
// wait would pass on a request that never took effect.
static bool wait_for_confirmed_number(const char *property_name, const char *item_name, double value, double tolerance) {
	for (int i = 0; i < 1500; i++) {
		if (fabs(number_of(property_name, item_name) - value) <= tolerance) {
			indigo_usleep(2500000);
			return fabs(number_of(property_name, item_name) - value) <= tolerance;
		}
		indigo_usleep(10000);
	}
	return false;
}

static bool wait_for_number(const char *property_name, const char *item_name, double value, double tolerance) {
	for (int i = 0; i < 1500; i++) {
		indigo_property *property = find_cached_property(property_name);
		if (property != NULL && property->state != INDIGO_BUSY_STATE && fabs(number_of(property_name, item_name) - value) <= tolerance) {
			return true;
		}
		indigo_usleep(10000);
	}
	return false;
}

// A cover move ends when the driver sees the live position reach the configured angle, so the wait
// has to allow for the servo travelling at the simulated 15 degrees per second.
static bool wait_for_cover(const char *item_name) {
	for (int i = 0; i < 4000; i++) {
		indigo_property *property = find_cached_property(AUX_COVER_PROPERTY_NAME);
		indigo_item *item = find_cached_item(AUX_COVER_PROPERTY_NAME, item_name);
		if (property != NULL && property->state == INDIGO_OK_STATE && item != NULL && item->sw.value) {
			return true;
		}
		indigo_usleep(10000);
	}
	return false;
}

