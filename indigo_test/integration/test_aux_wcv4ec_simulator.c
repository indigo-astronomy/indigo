// The servo needs 45 degrees of separation; a request that would collapse the travel has to be
// refused with the reason, and the previously configured angles have to survive it.
static void too_small_a_travel_is_refused(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_wcv4ec(&simulator, NULL));
	SERIAL_CHECK_TRUE(start_serial_driver(&wcv4ec_aux, simulator.port));
	online = true;
	SERIAL_CHECK_TRUE(wait_for_first_poll());
	SERIAL_CHECK_TRUE(set_positions(120, 20));
	SERIAL_CHECK_TRUE(wait_for_confirmed_number(AUX_SET_OPEN_CLOSE_PROPERTY_NAME, AUX_COVER_OPEN_ITEM_NAME, 120, .01));
	unsigned int revision = property_revision(AUX_SET_OPEN_CLOSE_PROPERTY_NAME);
	SERIAL_CHECK_TRUE(set_positions(60, 20));
	SERIAL_CHECK_TRUE(wait_for_property_state_after(AUX_SET_OPEN_CLOSE_PROPERTY_NAME, INDIGO_ALERT_STATE, revision));
	// Exactly 45 degrees apart is still too little; the guard is strict.
	revision = property_revision(AUX_SET_OPEN_CLOSE_PROPERTY_NAME);
	SERIAL_CHECK_TRUE(set_positions(65, 20));
	SERIAL_CHECK_TRUE(wait_for_property_state_after(AUX_SET_OPEN_CLOSE_PROPERTY_NAME, INDIGO_ALERT_STATE, revision));
	// The device kept the angles it had, so the next poll restores them.
	SERIAL_CHECK_TRUE(wait_for_confirmed_number(AUX_SET_OPEN_CLOSE_PROPERTY_NAME, AUX_COVER_OPEN_ITEM_NAME, 120, .01));
	SERIAL_CHECK_TRUE(wait_for_confirmed_number(AUX_SET_OPEN_CLOSE_PROPERTY_NAME, AUX_COVER_CLOSE_ITEM_NAME, 20, .01));
	// And one more degree of separation is accepted.
	SERIAL_CHECK_TRUE(set_positions(66, 20));
	SERIAL_CHECK_TRUE(wait_for_confirmed_number(AUX_SET_OPEN_CLOSE_PROPERTY_NAME, AUX_COVER_OPEN_ITEM_NAME, 66, .01));
cleanup:
	if (online) { stop_serial_driver(&wcv4ec_aux); }
	stop_external_serial_simulator(&simulator);
}

