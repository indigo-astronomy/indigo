// Driver metadata, the published property inventory before and after connection, and the shape of
// both driver properties.
static void identity_inventory_and_property_contract(void) {
	indigo_driver_info info;
	memset(&info, 0, sizeof(info));
	assert_simulator_driver_info(&rts_shutter);
	reset_transport();
	SERIAL_CHECK_TRUE(bring_up_serial_driver(&rts_shutter));
	enumerate_simulator_device();
	assert_device_interface(INDIGO_INTERFACE_AUX_SHUTTER);
	assert_defined_properties(rts_base_properties, ARRAY_SIZE(rts_base_properties));
	assert_not_defined_properties(rts_hidden_properties, ARRAY_SIZE(rts_hidden_properties));
	assert_not_defined_properties(rts_connected_properties, ARRAY_SIZE(rts_connected_properties));
	assert_defined_property_count(ARRAY_SIZE(rts_base_properties));
	SERIAL_CHECK_TRUE(connect_serial_device(&rts_shutter, "fake-rts-port"));
	assert_serial_aux_class_property_completeness();
	assert_defined_properties(rts_connected_properties, ARRAY_SIZE(rts_connected_properties));
	assert_defined_property_count(ARRAY_SIZE(rts_base_properties) + ARRAY_SIZE(rts_connected_properties));
	indigo_property *exposure = find_cached_property(CCD_EXPOSURE_PROPERTY_NAME);
	indigo_property *abort = find_cached_property(CCD_ABORT_EXPOSURE_PROPERTY_NAME);
	indigo_item *exposure_item = find_cached_item(CCD_EXPOSURE_PROPERTY_NAME, CCD_EXPOSURE_ITEM_NAME);
	SERIAL_CHECK_TRUE(exposure != NULL && exposure->type == INDIGO_NUMBER_VECTOR && exposure->perm == INDIGO_RW_PERM && exposure->count == 1);
	SERIAL_CHECK_TRUE(abort != NULL && abort->type == INDIGO_SWITCH_VECTOR && abort->perm == INDIGO_RW_PERM && abort->rule == INDIGO_ANY_OF_MANY_RULE && abort->count == 1);
	SERIAL_CHECK_TRUE(exposure_item != NULL && exposure_item->number.min == 0 && exposure_item->number.max == 1000 && exposure_item->number.step == 1);
	// Connecting arms nothing and leaves the line alone.
	SERIAL_CHECK_TRUE(exposure_item->number.value == 0);
	SERIAL_CHECK_EQ_INT(0, transitions_seen());
	SERIAL_CHECK_TRUE(!atomic_load(&rts_line));
	SERIAL_CHECK_EQ_INT(INDIGO_OK, rts_shutter.entry(INDIGO_DRIVER_INFO, &info));
	SERIAL_CHECK_EQ_INT(INDIGO_DRIVER_API_3, INDIGO_DRIVER_API_GENERATION(info.version));
cleanup:
	tear_down();
}

// The line is held for exactly as long as was asked, whole seconds or not. The driver's callback is
// the only thing that closes the shutter, so this is the driver's core contract.
static void exposure_holds_the_shutter_for_the_requested_time(void) {
	static const double durations[] = { 0.3, 1, 2.5 };
	SERIAL_CHECK_TRUE(bring_up());
	for (int i = 0; i < ARRAY_SIZE(durations); i++) {
		double held = 0;
		SERIAL_CHECK_TRUE(timed_exposure(durations[i], &held));
		printf("  %gs requested, line held for %.3fs\n", durations[i], held);
		// Never shorter than requested, and late only by scheduling latency.
		SERIAL_CHECK_TRUE(held >= durations[i] - 0.01);
		SERIAL_CHECK_TRUE(held <= durations[i] + 0.4);
		SERIAL_CHECK_TRUE(!atomic_load(&rts_line));
		SERIAL_CHECK_TRUE(exposure_value() == 0);
	}
cleanup:
	tear_down();
}

// The published countdown is a whole-second view of the remaining time, never the raw remainder,
// and it never goes back up. Against the version that decremented the property by one per tick this
// case sees 1.5 and 0.5 for a 2.5 s exposure.
static void exposure_countdown_is_published_in_whole_seconds(void) {
	double samples[MAX_TRANSITIONS];
	int count = 0;
	SERIAL_CHECK_TRUE(bring_up());
	SERIAL_CHECK_TRUE(start_exposure(2.5));
	SERIAL_CHECK_TRUE(wait_for_property_state(CCD_EXPOSURE_PROPERTY_NAME, INDIGO_BUSY_STATE));
	for (int i = 0; i < 400; i++) {
		indigo_property *property = find_cached_property(CCD_EXPOSURE_PROPERTY_NAME);
		double value = exposure_value();
		if (count == 0 || samples[count - 1] != value) {
			if (count < ARRAY_SIZE(samples)) {
				samples[count++] = value;
			}
		}
		if (property != NULL && property->state != INDIGO_BUSY_STATE) {
			break;
		}
		indigo_usleep(10000);
	}
	printf("  countdown:");
	for (int i = 0; i < count; i++) {
		printf(" %g", samples[i]);
	}
	printf("\n");
	SERIAL_CHECK_TRUE(wait_for_property_state(CCD_EXPOSURE_PROPERTY_NAME, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(count >= 3);
	// The first sample is the request the framework echoed back with BUSY; every later one is the
	// driver's own countdown and has to be a whole number of seconds.
	for (int i = 1; i < count; i++) {
		SERIAL_CHECK_TRUE(samples[i] == floor(samples[i]));
		SERIAL_CHECK_TRUE(samples[i] < samples[i - 1]);
	}
	SERIAL_CHECK_TRUE(samples[count - 1] == 0);
cleanup:
	tear_down();
}

// Aborting closes the shutter immediately and reports the exposure as failed.
static void abort_closes_the_shutter(void) {
	SERIAL_CHECK_TRUE(bring_up());
	atomic_store(&transition_count, 0);
	SERIAL_CHECK_TRUE(start_exposure(30));
	SERIAL_CHECK_TRUE(wait_for_property_state(CCD_EXPOSURE_PROPERTY_NAME, INDIGO_BUSY_STATE));
	SERIAL_CHECK_TRUE(wait_for_line(true));
	SERIAL_CHECK_TRUE(abort_exposure());
	SERIAL_CHECK_TRUE(wait_for_property_state(CCD_EXPOSURE_PROPERTY_NAME, INDIGO_ALERT_STATE));
	SERIAL_CHECK_TRUE(wait_for_property_state(CCD_ABORT_EXPOSURE_PROPERTY_NAME, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(!atomic_load(&rts_line));
	double held = shutter_interval();
	printf("  aborted after %.3fs of a 30s exposure\n", held);
	SERIAL_CHECK_TRUE(held >= 0 && held < 5);
	assert_switch_item_value(CCD_ABORT_EXPOSURE_PROPERTY_NAME, CCD_ABORT_EXPOSURE_ITEM_NAME, false);
	// Nothing may reopen the shutter once the exposure was abandoned.
	indigo_usleep(1500000);
	SERIAL_CHECK_TRUE(!atomic_load(&rts_line));
	SERIAL_CHECK_EQ_INT(2, transitions_seen());
	// The device is still usable.
	double next = 0;
	SERIAL_CHECK_TRUE(timed_exposure(0.5, &next));
	SERIAL_CHECK_TRUE(next >= 0.49);
cleanup:
	tear_down();
}

// An abort that reaches the driver while the exposure request is still queued must still be
// honoured, and an abort request carrying a false value must not touch a running exposure.
static void queued_abort_and_false_abort(void) {
	SERIAL_CHECK_TRUE(bring_up());
	SERIAL_CHECK_TRUE(check_queued_abort(RTS_DEVICE_NAME, CCD_EXPOSURE_PROPERTY_NAME, CCD_EXPOSURE_ITEM_NAME, 30, false, CCD_ABORT_EXPOSURE_PROPERTY_NAME, CCD_ABORT_EXPOSURE_ITEM_NAME, false));
	SERIAL_CHECK_TRUE(check_queued_abort(RTS_DEVICE_NAME, CCD_EXPOSURE_PROPERTY_NAME, CCD_EXPOSURE_ITEM_NAME, 30, false, CCD_ABORT_EXPOSURE_PROPERTY_NAME, CCD_ABORT_EXPOSURE_ITEM_NAME, true));
	SERIAL_CHECK_TRUE(!atomic_load(&rts_line));
cleanup:
	tear_down();
}

// The RTS line is the whole protocol, so every failure to drive it has to surface on the property
// that asked for it, and the driver has to stay usable afterwards.
static void line_failures_are_reported(void) {
	SERIAL_CHECK_TRUE(bring_up());
	// Failing to raise the line fails the exposure outright.
	atomic_store(&rts_fail_on, 1);
	SERIAL_CHECK_TRUE(start_exposure(0.3));
	SERIAL_CHECK_TRUE(wait_for_property_state(CCD_EXPOSURE_PROPERTY_NAME, INDIGO_ALERT_STATE));
	SERIAL_CHECK_TRUE(!atomic_load(&rts_line));
	// Failing to lower it at the end reports the exposure as failed rather than successful.
	atomic_store(&transition_count, 0);
	SERIAL_CHECK_TRUE(start_exposure(0.3));
	SERIAL_CHECK_TRUE(wait_for_property_state(CCD_EXPOSURE_PROPERTY_NAME, INDIGO_BUSY_STATE));
	SERIAL_CHECK_TRUE(wait_for_line(true));
	atomic_store(&rts_fail_off, 1);
	SERIAL_CHECK_TRUE(wait_for_property_state(CCD_EXPOSURE_PROPERTY_NAME, INDIGO_ALERT_STATE));
	SERIAL_CHECK_TRUE(atomic_load(&rts_line));
	SERIAL_CHECK_TRUE(exposure_value() == 0);
	// Failing to lower it on abort reports the abort as failed.
	atomic_store(&rts_fail_off, 1);
	SERIAL_CHECK_TRUE(abort_exposure());
	SERIAL_CHECK_TRUE(wait_for_property_state(CCD_ABORT_EXPOSURE_PROPERTY_NAME, INDIGO_ALERT_STATE));
	SERIAL_CHECK_TRUE(abort_exposure());
	SERIAL_CHECK_TRUE(wait_for_property_state(CCD_ABORT_EXPOSURE_PROPERTY_NAME, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(!atomic_load(&rts_line));
	double held = 0;
	SERIAL_CHECK_TRUE(timed_exposure(0.4, &held));
	SERIAL_CHECK_TRUE(held >= 0.39);
cleanup:
	tear_down();
}

// Disconnecting in the middle of an exposure must release the line instead of leaving the camera
// shutter latched open.
static void disconnect_during_exposure_releases_the_line(void) {
	SERIAL_CHECK_TRUE(bring_up());
	SERIAL_CHECK_TRUE(start_exposure(30));
	SERIAL_CHECK_TRUE(wait_for_property_state(CCD_EXPOSURE_PROPERTY_NAME, INDIGO_BUSY_STATE));
	SERIAL_CHECK_TRUE(wait_for_line(true));
	disconnect_serial_device(&rts_shutter);
	SERIAL_CHECK_TRUE(!atomic_load(&rts_line));
	SERIAL_CHECK_TRUE(connected_properties_published(false));
	SERIAL_CHECK_EQ_INT(atomic_load(&rts_opens), atomic_load(&rts_closes));
	SERIAL_CHECK_TRUE(connect_serial_device(&rts_shutter, "fake-rts-port"));
	SERIAL_CHECK_TRUE(exposure_value() == 0);
	double held = 0;
	SERIAL_CHECK_TRUE(timed_exposure(0.4, &held));
	SERIAL_CHECK_TRUE(held >= 0.39);
cleanup:
	tear_down();
}

// A port that cannot be opened rolls back cleanly, a redundant disconnect is a no-op and the driver
// refuses to unload while a device is connected.
static void open_rollback_reconnect_and_refused_shutdown(void) {
	reset_transport();
	SERIAL_CHECK_TRUE(bring_up_serial_driver(&rts_shutter));
	enumerate_simulator_device();
	atomic_store(&rts_fail_open, 1);
	SERIAL_CHECK_TRUE(!connect_serial_device(&rts_shutter, "fake-rts-port"));
	SERIAL_CHECK_TRUE(wait_for_property_state(CONNECTION_PROPERTY_NAME, INDIGO_ALERT_STATE));
	SERIAL_CHECK_TRUE(!context.connected);
	SERIAL_CHECK_TRUE(connected_properties_published(false));
	SERIAL_CHECK_EQ_INT(0, atomic_load(&rts_opens));
	SERIAL_CHECK_TRUE(connect_serial_device(&rts_shutter, "fake-rts-port"));
	SERIAL_CHECK_EQ_INT(1, atomic_load(&rts_opens) - atomic_load(&rts_closes));
	SERIAL_CHECK_EQ_INT(INDIGO_BUSY, rts_shutter.entry(INDIGO_DRIVER_SHUTDOWN, NULL));
	SERIAL_CHECK_TRUE(context.connected);
	disconnect_serial_device(&rts_shutter);
	SERIAL_CHECK_TRUE(!context.connected);
	disconnect_serial_device(&rts_shutter);
	SERIAL_CHECK_TRUE(!context.connected);
	SERIAL_CHECK_TRUE(connect_serial_device(&rts_shutter, "fake-rts-port"));
	SERIAL_CHECK_TRUE(connected_properties_published(true));
cleanup:
	tear_down();
}

// A callback that runs late must not push the deadline out with it. This is what separates timing
// the exposure from counting the ticks that happen to fire during it.
static void a_stalled_queue_does_not_extend_the_exposure(void) {
	SERIAL_CHECK_TRUE(bring_up());
	atomic_store(&transition_count, 0);
	SERIAL_CHECK_TRUE(start_exposure(3));
	SERIAL_CHECK_TRUE(wait_for_property_state(CCD_EXPOSURE_PROPERTY_NAME, INDIGO_BUSY_STATE));
	SERIAL_CHECK_TRUE(wait_for_line(true));
	SERIAL_CHECK_TRUE(stall_device_queue(1.5));
	SERIAL_CHECK_TRUE(wait_for_property_state(CCD_EXPOSURE_PROPERTY_NAME, INDIGO_OK_STATE));
	double held = shutter_interval();
	printf("  3s exposure across a 1.5s stall, line held for %.3fs\n", held);
	SERIAL_CHECK_TRUE(held >= 2.99);
	SERIAL_CHECK_TRUE(held <= 3.4);
cleanup:
	tear_down();
}

