// Code is generated by AI

// AUX shutter coverage for indigo_aux_rts. The device is a bare RTS line on a serial port: there
// is no protocol, no reply and nothing to simulate over a PTY, and a pseudo terminal has no modem
// control lines to observe anyway. The driver is therefore linked against a fake
// indigo_uni_open_serial/indigo_uni_close/indigo_uni_set_rts boundary, which is the only place the
// RTS transitions and their timing can be seen.
//
// The exposure is timed by the driver's own callback, so the interval between the two RTS
// transitions is the exposure, and the published CCD_EXPOSURE countdown is only a view of it.

#include <stdatomic.h>

#include <indigo_drivers/aux_rts/indigo_aux_rts.h>
#include <indigo/indigo_uni_io.h>

#include "serial_simulator_test_common.h"
#include "abort_queue_test_common.h"

#ifndef RTS_DEVICE_NAME
#define RTS_DEVICE_NAME "RTS-on-COM shutter"
#endif

static const simulator_driver_case rts_shutter = {
	"RTS-on-COM shutter release",
	"indigo_aux_rts",
	RTS_DEVICE_NAME,
	indigo_aux_rts,
	false,
	NULL, 0, NULL, 0, NULL, 0, NULL, 0
};

static const char *rts_base_properties[] = {
	INFO_PROPERTY_NAME,
	CONFIG_PROPERTY_NAME,
	PROFILE_NAME_PROPERTY_NAME,
	PROFILE_PROPERTY_NAME,
	DEVICE_PORT_PROPERTY_NAME,
	DEVICE_PORTS_PROPERTY_NAME,
	ADDITIONAL_INSTANCES_PROPERTY_NAME,
	CONNECTION_PROPERTY_NAME
};

static const char *rts_hidden_properties[] = {
	SIMULATION_PROPERTY_NAME,
	DEVICE_BAUDRATE_PROPERTY_NAME,
	AUTHENTICATION_PROPERTY_NAME,
	AUX_LIGHT_SWITCH_PROPERTY_NAME,
	AUX_POWER_OUTLET_PROPERTY_NAME
};

static const char *rts_connected_properties[] = {
	CCD_ABORT_EXPOSURE_PROPERTY_NAME,
	CCD_EXPOSURE_PROPERTY_NAME
};

// -------------------------------------------------------------------------------- fake transport

#define MAX_TRANSITIONS 64

typedef struct {
	bool state;
	double at;
} rts_transition;

static indigo_uni_handle rts_handle;
static atomic_int rts_opens, rts_closes, rts_invalid;
static atomic_bool rts_line;
static atomic_int rts_fail_open, rts_fail_on, rts_fail_off;
static rts_transition transitions[MAX_TRANSITIONS];
static atomic_int transition_count;

static void reset_transport(void) {
	atomic_store(&rts_opens, 0);
	atomic_store(&rts_closes, 0);
	atomic_store(&rts_invalid, 0);
	atomic_store(&rts_line, false);
	atomic_store(&rts_fail_open, 0);
	atomic_store(&rts_fail_on, 0);
	atomic_store(&rts_fail_off, 0);
	atomic_store(&transition_count, 0);
}

indigo_uni_handle *rts_test_open(const char *port, int level) {
	if (atomic_exchange(&rts_fail_open, 0)) {
		return NULL;
	}
	atomic_fetch_add(&rts_opens, 1);
	return &rts_handle;
}

void rts_test_close(indigo_uni_handle **port) {
	if (*port != NULL) {
		if (*port != &rts_handle) {
			atomic_fetch_add(&rts_invalid, 1);
		}
		atomic_fetch_add(&rts_closes, 1);
		*port = NULL;
	}
}

int rts_test_set_rts(indigo_uni_handle *port, bool state) {
	// Driving the line of a handle that is not open would be a lifecycle defect of its own.
	if (port != &rts_handle || atomic_load(&rts_opens) == atomic_load(&rts_closes)) {
		atomic_fetch_add(&rts_invalid, 1);
		return -1;
	}
	if (state ? atomic_exchange(&rts_fail_on, 0) : atomic_exchange(&rts_fail_off, 0)) {
		return -1;
	}
	if (atomic_load(&rts_line) != state) {
		int index = atomic_fetch_add(&transition_count, 1);
		if (index < MAX_TRANSITIONS) {
			transitions[index].state = state;
			transitions[index].at = indigo_monotonic_time();
		}
		atomic_store(&rts_line, state);
	}
	return 0;
}

static int transitions_seen(void) {
	int count = atomic_load(&transition_count);
	return count > MAX_TRANSITIONS ? MAX_TRANSITIONS : count;
}

// The shutter is open between the rising and the falling edge of the line.
static double shutter_interval(void) {
	int count = transitions_seen();
	if (count < 2 || !transitions[count - 2].state || transitions[count - 1].state) {
		fprintf(stderr, "expected a rising edge followed by a falling one, saw %d transition(s)\n", count);
		return -1;
	}
	return transitions[count - 1].at - transitions[count - 2].at;
}

// -------------------------------------------------------------------------------- request helpers

// The framework publishes CCD_EXPOSURE as BUSY before it queues the handler, so the line is raised
// a moment after the state the client sees changes.
static bool wait_for_line(bool state) {
	for (int i = 0; i < 500; i++) {
		if (atomic_load(&rts_line) == state) {
			return true;
		}
		indigo_usleep(10000);
	}
	fprintf(stderr, "RTS line did not go %s\n", state ? "high" : "low");
	return false;
}

static double exposure_value(void) {
	return cached_number_value(CCD_EXPOSURE_PROPERTY_NAME, CCD_EXPOSURE_ITEM_NAME);
}

static bool start_exposure(double seconds) {
	return indigo_change_number_property_1(&simulator_test_client, RTS_DEVICE_NAME, CCD_EXPOSURE_PROPERTY_NAME, CCD_EXPOSURE_ITEM_NAME, seconds) == INDIGO_OK;
}

static bool abort_exposure(void) {
	return indigo_change_switch_property_1(&simulator_test_client, RTS_DEVICE_NAME, CCD_ABORT_EXPOSURE_PROPERTY_NAME, CCD_ABORT_EXPOSURE_ITEM_NAME, true) == INDIGO_OK;
}

// Run one exposure and report how long the line was actually held.
static bool timed_exposure(double seconds, double *held) {
	atomic_store(&transition_count, 0);
	if (!start_exposure(seconds)) {
		return false;
	}
	if (!wait_for_property_state(CCD_EXPOSURE_PROPERTY_NAME, INDIGO_BUSY_STATE)) {
		fprintf(stderr, "exposure of %gs did not become busy\n", seconds);
		return false;
	}
	if (!wait_for_property_state(CCD_EXPOSURE_PROPERTY_NAME, INDIGO_OK_STATE)) {
		fprintf(stderr, "exposure of %gs did not complete\n", seconds);
		return false;
	}
	*held = shutter_interval();
	return *held >= 0;
}

static bool connected_properties_published(bool expected) {
	for (int i = 0; i < ARRAY_SIZE(rts_connected_properties); i++) {
		if ((find_cached_property(rts_connected_properties[i]) != NULL) != expected) {
			fprintf(stderr, "%s is %spublished\n", rts_connected_properties[i], expected ? "not " : "");
			return false;
		}
	}
	return true;
}

// Occupy the device queue for a while, so the exposure callback cannot run on time. The helpers
// come from abort_queue_test_common.h, which queues a handler that spins until it is released.
static bool stall_device_queue(double seconds) {
	indigo_client observer = { .name = "Queue stall observer", .version = INDIGO_VERSION_CURRENT, .define_property = abort_test_capture };
	abort_test_name = RTS_DEVICE_NAME;
	abort_test_device = NULL;
	indigo_attach_client(&observer);
	indigo_enumerate_properties(&observer, &INDIGO_ALL_PROPERTIES);
	indigo_detach_client(&observer);
	if (abort_test_device == NULL) {
		fprintf(stderr, "the device under test was not found\n");
		return false;
	}
	atomic_store(&abort_test_entered, false);
	atomic_store(&abort_test_released, false);
	indigo_execute_handler(abort_test_device, abort_test_block);
	if (!abort_test_wait(&abort_test_entered)) {
		atomic_store(&abort_test_released, true);
		fprintf(stderr, "the queue did not stall\n");
		return false;
	}
	indigo_usleep((unsigned long)(seconds * 1000000));
	atomic_store(&abort_test_released, true);
	return true;
}

static bool bring_up(void) {
	reset_transport();
	return start_serial_driver(&rts_shutter, "fake-rts-port");
}

static void tear_down(void) {
	stop_serial_driver(&rts_shutter);
	ASSERT_EQ_INT(atomic_load(&rts_opens), atomic_load(&rts_closes));
	ASSERT_EQ_INT(0, atomic_load(&rts_invalid));
}

