static int event_count(external_serial_simulator *simulator, const char *command, double *last_time) {
	char path[PATH_MAX];
	snprintf(path, sizeof(path), "%s.events", simulator->ready_file);
	FILE *file = fopen(path, "r");
	if (file == NULL) {
		return 0;
	}
	char line[256];
	int count = 0;
	while (fgets(line, sizeof(line), file)) {
		char *tab = strchr(line, '\t');
		if (tab != NULL) {
			*tab++ = 0;
			tab[strcspn(tab, "\r\n")] = 0;
			if (!strcmp(tab, command)) {
				count++;
				if (last_time != NULL) {
					*last_time = atof(line);
				}
			}
		}
	}
	fclose(file);
	return count;
}

// The time of the first command whose name starts with the given prefix, which is how a test
// orders two commands whose arguments it does not want to spell out.
static bool first_event_time(external_serial_simulator *simulator, const char *prefix, double *when) {
	char path[PATH_MAX];
	snprintf(path, sizeof(path), "%s.events", simulator->ready_file);
	FILE *file = fopen(path, "r");
	if (file == NULL) {
		return false;
	}
	char line[256];
	bool found = false;
	while (!found && fgets(line, sizeof(line), file)) {
		char *tab = strchr(line, '\t');
		if (tab != NULL) {
			*tab++ = 0;
			if (!strncmp(tab, prefix, strlen(prefix))) {
				*when = atof(line);
				found = true;
			}
		}
	}
	fclose(file);
	return found;
}

// The count of a command once the log has stopped growing. A command the driver sends without
// waiting for a reply, which is every guide pulse, is written to the event log by the simulator
// after the driver has already moved on, so a count taken straight away can miss it and the
// next assertion then sees it as one command too many.
static int settled_event_count(external_serial_simulator *simulator, const char *command) {
	int count = event_count(simulator, command, NULL);
	for (int i = 0; i < 40; i++) {
		indigo_usleep(50000);
		int again = event_count(simulator, command, NULL);
		if (again == count) {
			return count;
		}
		count = again;
	}
	return count;
}

static bool wait_event(external_serial_simulator *simulator, const char *command, int before) {
	for (int i = 0; i < 500; i++) {
		if (event_count(simulator, command, NULL) > before) {
			return true;
		}
		indigo_usleep(10000);
	}
	fprintf(stderr, "Missing LX200 command %s\n", command);
	return false;
}

static bool inject_reply(external_serial_simulator *simulator, const char *command, const char *reply) {
	char path[PATH_MAX], temporary[PATH_MAX];
	snprintf(path, sizeof(path), "%s.control", simulator->ready_file);
	snprintf(temporary, sizeof(temporary), "%s.inject", simulator->ready_file);
	FILE *file = fopen(temporary, "w");
	if (file == NULL) {
		return false;
	}
	fprintf(file, "%s\t%s\n", command, reply);
	fclose(file);
	return rename(temporary, path) == 0;
}

