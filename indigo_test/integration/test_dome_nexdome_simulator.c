static bool wait_settled(const char *name, unsigned before, indigo_property_state expected, double timeout) {
	double end = now() + timeout;
	do {
		int state = state_of(name);
		if (revision_of(name) > before && state >= 0 && state != INDIGO_BUSY_STATE) {
			if (state == (int)expected) {
				return true;
			}
			fprintf(stderr, "%s settled in %s instead of %s\n", name, state_name(state), state_name(expected));
			return false;
		}
		indigo_usleep(20000);
	} while (now() < end);
	fprintf(stderr, "%s did not settle in %s\n", name, state_name(expected));
	return false;
}

static bool wait_fresh_state(const char *name, unsigned before, indigo_property_state expected, double timeout) {
	double end = now() + timeout;
	do {
		if (revision_of(name) > before && state_of(name) == (int)expected) {
			return true;
		}
		indigo_usleep(20000);
	} while (now() < end);
	fprintf(stderr, "No fresh %s state %s\n", name, state_name(expected));
	return false;
}

static bool wait_state(const char *name, indigo_property_state expected, double timeout) {
	double end = now() + timeout;
	do {
		if (state_of(name) == (int)expected) {
			return true;
		}
		indigo_usleep(20000);
	} while (now() < end);
	fprintf(stderr, "%s is %s instead of %s\n", name, state_name(state_of(name)), state_name(expected));
	return false;
}

static bool wait_present(const char *name, bool expected, double timeout) {
	double end = now() + timeout;
	do {
		if (present(name) == expected) {
			return true;
		}
		indigo_usleep(20000);
	} while (now() < end);
	fprintf(stderr, "%s presence is not %d\n", name, expected);
	return false;
}

static bool wait_value(const char *name, const char *item_name, double expected, double tolerance, double timeout) {
	double end = now() + timeout;
	do {
		if (fabs(value_of(name, item_name) - expected) <= tolerance) {
			return true;
		}
		indigo_usleep(20000);
	} while (now() < end);
	fprintf(stderr, "%s.%s is %g instead of %g\n", name, item_name, value_of(name, item_name), expected);
	return false;
}

