	// rain closes an open shutter
	before = revision_of(DOME_SHUTTER_PROPERTY_NAME);
	CHECK(control("rain", "1"));
	CHECK(wait_fresh_state(DOME_SHUTTER_PROPERTY_NAME, before, INDIGO_BUSY_STATE, 5));
