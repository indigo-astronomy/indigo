static bool driver_up(void) {
	reset_observations();
	return bring_up_serial_driver(&nexdome_dome);
}

static bool set_port(const char *port) {
	unsigned before = revision_of(DEVICE_PORT_PROPERTY_NAME);
	return indigo_change_text_property_1_raw(&simulator_test_client, context.driver_case->device_name, DEVICE_PORT_PROPERTY_NAME, DEVICE_PORT_ITEM_NAME, port) == INDIGO_OK && wait_settled(DEVICE_PORT_PROPERTY_NAME, before, strncmp(port, "/dev/indigo-", 12) ? INDIGO_OK_STATE : INDIGO_ALERT_STATE, 5);
}

static bool connect_to(const char *port, indigo_property_state expected, bool wait_first_poll) {
	if (!set_port(port)) {
		return false;
	}
	unsigned before = revision_of(CONNECTION_PROPERTY_NAME);
	if (request_switch(CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME) != INDIGO_OK || !wait_settled(CONNECTION_PROPERTY_NAME, before, expected, 20)) {
		return false;
	}
	if (expected != INDIGO_OK_STATE) {
		return !switch_of(CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME);
	}
	if (!switch_of(CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME)) {
		return false;
	}
	return !wait_first_poll || wait_polls(1, 6);
}

static bool disconnect(void) {
	unsigned before = revision_of(CONNECTION_PROPERTY_NAME);
	return request_switch(CONNECTION_PROPERTY_NAME, CONNECTION_DISCONNECTED_ITEM_NAME) == INDIGO_OK && wait_settled(CONNECTION_PROPERTY_NAME, before, INDIGO_OK_STATE, 15) && switch_of(CONNECTION_PROPERTY_NAME, CONNECTION_DISCONNECTED_ITEM_NAME);
}

static bool start_connected(void) {
	return driver_up() && connect_to(simulator.port, INDIGO_OK_STATE, true);
}

static void driver_down(void) {
	DEFECT_EXIT();
	if (switch_of(CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME)) {
		disconnect();
	}
	indigo_result result = indigo_dome_nexdome(INDIGO_DRIVER_SHUTDOWN, NULL);
	indigo_detach_client(&simulator_test_client);
	indigo_stop();
	pthread_mutex_lock(&observe_mutex);
	release_cached_properties();
	pthread_mutex_unlock(&observe_mutex);
	ASSERT_EQ_INT(INDIGO_OK, result);
}

static bool wait_message(const char *name, const char *text) {
	return message_seen(name, text);
}

static bool switch_to_device(const simulator_driver_case *device_case) {
	pthread_mutex_lock(&observe_mutex);
	reset_simulator_context(device_case);
	observed_count = 0;
	message_count = 0;
	pthread_mutex_unlock(&observe_mutex);
	enumerate_simulator_device();
	return wait_present(CONNECTION_PROPERTY_NAME, true, 5);
}

