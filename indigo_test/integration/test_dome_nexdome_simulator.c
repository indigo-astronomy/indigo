static void mask_digits(char *text) {
	char *output = text;
	for (char *input = text; *input; input++) {
		if (*input >= '0' && *input <= '9') {
			if (output == text || output[-1] != '#') {
				*output++ = '#';
			}
		} else if (*input == '.' && output > text && output[-1] == '#' && input[1] >= '0' && input[1] <= '9') {
			continue;
		} else {
			*output++ = *input;
		}
	}
	*output = 0;
}

static void trace_append(const char *line) {
	int written = snprintf(trace_text + trace_length, sizeof(trace_text) - trace_length, "%s\n", line);
	if (written > 0 && trace_length + written < sizeof(trace_text)) {
		trace_length += written;
	}
}

static int last_poll_end(int count) {
	int polls = 0;
	for (int i = 0; i < count; i++) {
		polls += !strcmp(events[i].kind, "RX") && !strcmp(events[i].text, "k");
	}
	for (; polls > 0; polls--) {
		int end = poll_end_index(count, polls);
		if (end >= 0) {
			return end;
		}
	}
	return -1;
}

static void trace_begin(bool polling) {
	if (polling) {
		wait_polls(1, 5);
		trace_mark = last_poll_end(load_events());
	} else {
		trace_mark = load_events();
	}
	pthread_mutex_lock(&observe_mutex);
	trace_pending_length = 0;
	*trace_pending = 0;
	for (int i = 0; i < observed_count; i++) {
		*observed[i].last_trace = 0;
	}
	pthread_mutex_unlock(&observe_mutex);
	atomic_store(&trace_active, true);
}

// A status poll is the query sequence k, m, q, u; consecutive identical polls collapse
static int poll_at(int count, int index, char *line, size_t size) {
	static const char * const sequence[] = { "k", "m", "q", "u" };
	if (strcmp(events[index].kind, "RX") || strcmp(events[index].text, "k")) {
		return -1;
	}
	int found = 0, end = -1;
	size_t length = (size_t)snprintf(line, size, "S POLL");
	for (int i = index; i < count && end < 0; i++) {
		if (!strcmp(events[i].kind, "RX")) {
			if (found == 4 || strcmp(events[i].text, sequence[found])) {
				return -1;
			}
			found++;
		} else if (!strcmp(events[i].kind, "TX") && found > 0) {
			char text[240];
			snprintf(text, sizeof(text), "%s", events[i].text);
			if (*text == 'Q') {
				mask_digits(text);
			}
			length += (size_t)snprintf(line + length, size - length, " [%s]", text);
			if (found == 4) {
				end = i + 1;
			}
		}
	}
	return length < size ? end : -1;
}

static bool trace_end(const char *step, bool polling, bool mask) {
	char line[2048], previous_poll[2048] = "";
	bool ok = polling ? wait_polls(1, 6) : (indigo_usleep(1500000), true);
	int count = load_events();
	if (polling) {
		int end = last_poll_end(count);
		count = end >= 0 ? end : count;
	}
	snprintf(line, sizeof(line), "## %s", step);
	trace_append(line);
	for (int i = trace_mark; i >= 0 && i < count; i++) {
		int end = poll_at(count, i, line, sizeof(line));
		if (end >= 0) {
			if (mask) {
				mask_digits(line);
			}
			if (strcmp(line, previous_poll)) {
				trace_append(line);
				snprintf(previous_poll, sizeof(previous_poll), "%s", line);
			}
			i = end - 1;
			continue;
		}
		if (strcmp(events[i].kind, "RX") && strcmp(events[i].kind, "TX") && strcmp(events[i].kind, "FAULT")) {
			continue;
		}
		if (mask && is_query(events[i].text)) {
			// incomplete polls around an asynchronous abort are timing dependent
			continue;
		}
		if (mask && !strcmp(events[i].kind, "TX") && i > 0 && !strcmp(events[i - 1].kind, "RX") && is_query(events[i - 1].text)) {
			continue;
		}
		*previous_poll = 0;
		snprintf(line, sizeof(line), "S %s %s", events[i].kind, events[i].text);
		if (mask && !strcmp(events[i].kind, "TX")) {
			mask_digits(line);
		}
		trace_append(line);
	}
	atomic_store(&trace_active, false);
	pthread_mutex_lock(&observe_mutex);
	if (mask) {
		// publications around an asynchronous abort are timing dependent: keep first occurrences only
		static char unique[sizeof(trace_pending) + 2];
		size_t unique_length = 1;
		mask_digits(trace_pending);
		unique[0] = '\n';
		unique[1] = 0;
		for (char *line_start = trace_pending, *line_end; (line_end = strchr(line_start, '\n')) != NULL; line_start = line_end + 1) {
			char needle[1100];
			snprintf(needle, sizeof(needle), "\n%.*s\n", (int)(line_end - line_start), line_start);
			if (strstr(unique, needle) == NULL) {
				unique_length += (size_t)snprintf(unique + unique_length, sizeof(unique) - unique_length, "%s", needle + 1);
			}
		}
		memcpy(trace_pending, unique + 1, unique_length);
		trace_pending_length = unique_length - 1;
	}
	if (trace_length + trace_pending_length < sizeof(trace_text)) {
		memcpy(trace_text + trace_length, trace_pending, trace_pending_length);
		trace_length += trace_pending_length;
		trace_text[trace_length] = 0;
	}
	trace_pending_length = 0;
	pthread_mutex_unlock(&observe_mutex);
	if (!ok) {
		fprintf(stderr, "Trace step %s did not end with a status poll\n", step);
	}
	return ok;
}

#define TRACE_STEP(step, begin_polling, end_polling, mask, action) do { \
	trace_begin(begin_polling); \
	CHECK(action); \
	CHECK(trace_end(step, end_polling, mask)); \
} while (0)

