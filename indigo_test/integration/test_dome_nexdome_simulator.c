	// the Arduino resets when the serial port opens: the first command waits 1 s
	CHECK(now() - requested >= 1.1);
	CHECK(wait_polls(1, 5));
	CHECK(rx_sequence(0, sequence, ARRAY_SIZE(sequence), 3));
	int count = load_events();
	CHECK(events[rx_index(count, "k", 1)].time - events[rx_index(count, "n", 1)].time >= 0.45);
	CHECK_STR("NexDome", text_of(INFO_PROPERTY_NAME, INFO_DEVICE_MODEL_ITEM_NAME));
	CHECK_STR("1.10", text_of(INFO_PROPERTY_NAME, INFO_DEVICE_FW_REVISION_ITEM_NAME));
	CHECK_EQ(6, count_of(INFO_PROPERTY_NAME));
	assert_device_interface(INDIGO_INTERFACE_DOME);
	CHECK(present(DOME_STEPS_PROPERTY_NAME) && present(DOME_DIRECTION_PROPERTY_NAME) && present(DOME_ABORT_MOTION_PROPERTY_NAME) && present(DOME_SHUTTER_PROPERTY_NAME) && present(DOME_PARK_PROPERTY_NAME));
	CHECK(present(DOME_DIMENSION_PROPERTY_NAME) && present(GEOGRAPHIC_COORDINATES_PROPERTY_NAME) && present(DOME_SLAVING_PARAMETERS_PROPERTY_NAME) && present(DOME_ON_COORDINATES_SET_PROPERTY_NAME));
