static void run_child(const nexdome_case *test) {
	setpgid(0, 0);
	setenv("HOME", home_path, 1);
	alarm(test->defect ? 120 : 240);
	if (!start_simulator_with(&simulator, test->args)) {
		_exit(2);
	}
	if (getenv("NEXDOME_DEBUG")) {
		indigo_set_log_level(INDIGO_LOG_DEBUG);
	}
	indigo_test_case runner = { test->name, test->run };
	int result = indigo_run_tests("NexDome", &runner, 1);
	stop_external_serial_simulator(&simulator);
	fflush(NULL);
	_exit(result);
}

int main(int argc, char **argv) {
	for (int i = 1; i < argc; i++) {
		if (!strcmp(argv[i], "--known-defects")) {
			known_defects_mode = true;
		} else if (!strcmp(argv[i], "--network")) {
			network_mode = true;
		} else if (i + 1 < argc && !strcmp(argv[i], "--capture-trace")) {
			capture_path = argv[++i];
		} else {
			fprintf(stderr, "Usage: %s [--known-defects] [--network] [--capture-trace PATH]\n", argv[0]);
			return 2;
		}
	}
	setvbuf(stdout, NULL, _IOLBF, 0);
	simulator_test_client.define_property = observe_define;
	simulator_test_client.update_property = observe_update;
	simulator_test_client.delete_property = observe_delete;
	simulator_test_client.send_message = observe_message;
	simulator_test_client.force_property_updates = true;
	snprintf(fixture_dir, sizeof(fixture_dir), "/tmp/indigo-nexdome.XXXXXX");
	if (!mkdtemp(fixture_dir)) {
		perror("mkdtemp");
		return 1;
	}
	snprintf(event_path, sizeof(event_path), "%s/events", fixture_dir);
	snprintf(fault_path, sizeof(fault_path), "%s/fault", fixture_dir);
	snprintf(control_path, sizeof(control_path), "%s/control", fixture_dir);
	snprintf(home_path, sizeof(home_path), "%s/home", fixture_dir);
	mkdir(home_path, 0700);
	setenv("INDIGO_NEXDOME_EVENTS", event_path, 1);
	setenv("INDIGO_NEXDOME_FAULT", fault_path, 1);
	setenv("INDIGO_NEXDOME_CONTROL", control_path, 1);
	const char *filter = getenv("NEXDOME_TEST_FILTER");
	int run = 0, passed = 0, failed = 0;
	for (int i = 0; i < (int)ARRAY_SIZE(cases); i++) {
		const nexdome_case *test = cases + i;
		if (test->defect != known_defects_mode || test->network != network_mode || (filter && !strstr(test->name, filter)) || (capture_path && test->run != reference_trace)) {
			continue;
		}
		unlink(event_path);
		unlink(fault_path);
		unlink(control_path);
		fflush(NULL);
		pid_t child = fork();
		if (child == 0) {
			run_child(test);
		}
		int status = 0;
		if (child > 0) {
			while (waitpid(child, &status, 0) < 0 && errno == EINTR) {
			}
			kill(-child, SIGTERM);
		}
		run++;
		bool ok = child > 0 && WIFEXITED(status) && WEXITSTATUS(status) == 0;
		if (known_defects_mode) {
			printf("%s %s (status %d)\n", ok ? "UNEXPECTED PASS" : "EXPECTED FAIL", test->name, status);
		} else if (!ok) {
			printf("FAIL %s (status %d)\n", test->name, status);
		}
		if (ok) {
			passed++;
		} else {
			failed++;
		}
	}
	if (!getenv("NEXDOME_KEEP_FIXTURE")) {
		nftw(fixture_dir, remove_entry, 16, FTW_DEPTH | FTW_PHYS);
	}
	if (known_defects_mode) {
		printf("NexDome defect reproducers: %d run, %d failed as expected, %d passed\n", run, failed, passed);
		return 0;
	}
	printf("NexDome: %d run, %d passed, %d failed\n", run, passed, failed);
	return failed ? 1 : 0;
}
