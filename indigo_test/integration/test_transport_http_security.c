static bool read_reply(int fd, char *buffer, size_t capacity) {
	size_t length = 0;
	buffer[0] = 0;
	while (length + 1 < capacity) {
		ssize_t count = read(fd, buffer + length, capacity - length - 1);
		if (count < 0) {
			return false;
		}
		if (count == 0) {
			buffer[length] = 0;
			return true;
		}
		length += count;
		buffer[length] = 0;
		char *body = strstr(buffer, "\r\n\r\n");
		char *content_length = strstr(buffer, "Content-Length: ");
		if (body && content_length && length - (size_t)(body + 4 - buffer) == strtoul(content_length + 16, NULL, 10)) {
			return true;
		}
	}
	buffer[length] = 0;
	return false;
}

