static int connect_loopback(int port) {
	int fd = socket(AF_INET, SOCK_STREAM, 0);
	if (fd < 0) {
		return -1;
	}
	struct sockaddr_in address = { 0 };
	address.sin_family = AF_INET;
	address.sin_port = htons(port);
	address.sin_addr.s_addr = htonl(INADDR_LOOPBACK);
	if (connect(fd, (struct sockaddr *)&address, sizeof(address)) < 0) {
		close(fd);
		return -1;
	}
	struct timeval timeout = { 5, 0 };
	setsockopt(fd, SOL_SOCKET, SO_RCVTIMEO, &timeout, sizeof(timeout));
	int value = 1;
	setsockopt(fd, IPPROTO_TCP, TCP_NODELAY, &value, sizeof(value));
	return fd;
}

static void stop_test_server(void) {
	if (server_started) {
		WAIT_UNTIL(atomic_load(&server_client_count) == 0, 10);
		int port = indigo_server_tcp_port;
		indigo_server_shutdown();
		if (!WAIT_UNTIL(atomic_load(&server_finished), 1)) {
			// the listener may stay in accept() after its socket is shut down, a connection wakes it
			int fd = connect_loopback(port);
			if (fd >= 0) {
				close(fd);
			}
		}
		if (WAIT_UNTIL(atomic_load(&server_finished), 5)) {
			pthread_join(server_thread, NULL);
		} else {
			fprintf(stderr, "    TCP server thread did not finish\n");
			indigo_test_failures++;
			pthread_detach(server_thread);
		}
		server_started = false;
	}
}

