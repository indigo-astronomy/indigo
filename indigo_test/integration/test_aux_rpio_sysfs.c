/** Characterization suite for the Raspberry Pi GPIO AUX driver.
 \file test_aux_rpio_sysfs.c
 The driver reaches the hardware only through the legacy sysfs GPIO and PWM
 interfaces, so the whole boundary is faked by replacing open/close/read/write
 and stat when the driver is compiled for this test. The fake models the kernel
 side: export creates a pin node, direction and value behave like their sysfs
 counterparts, and every interaction is appended to an ordered trace that can be
 compared before and after a refactoring step.
 */

