// AUX powerbox coverage for indigo_aux_wbprov3 against the standalone WandererBox Pro V3 simulator
// over a real PTY. Like the Plus V3 the box never acknowledges a command, it only broadcasts an
// "A"-separated status frame once a second, so every command is verified through the next frame.
// The Pro V3 is the wide variant: three switched outlet groups, five USB groups, three heaters and
// four temperature sensors, all of which are driven from a single handler per property. That makes
// crosstalk between channels the failure worth hunting, so most scenarios move one channel and
// assert that its neighbours stayed put.

