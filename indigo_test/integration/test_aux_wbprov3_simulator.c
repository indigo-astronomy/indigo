// Each heater has its own command range, and one change writes all three, so setting them to three
// different duty cycles at once is the scenario that catches a channel writing another's value.
static void heaters_hold_independent_duty_cycles(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_wbprov3(&simulator, NULL));
	SERIAL_CHECK_TRUE(start_serial_driver(&wbprov3_aux, simulator.port));
	online = true;
	SERIAL_CHECK_TRUE(wait_for_first_poll());
	// The percentage is quantised to an 8 bit PWM, so each duty cycle read back is the nearest
	// representable step. Asserting the nearest step rather than a one-step tolerance is what keeps
	// the conversion honest: truncating instead of rounding (DRV-205) lands a step low for every
	// request that does not fall exactly on a step. 60 and 100 land exactly on steps 153 and 255,
	// so 25 is the one carrying that part of the check: it falls between steps 63 and 64.
	static const char *items[] = { AUX_HEATER_OUTLET_1_ITEM_NAME, AUX_HEATER_OUTLET_2_ITEM_NAME, AUX_HEATER_OUTLET_3_ITEM_NAME };
	static const double values[] = { 25, 60, 100 };
	SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_change_number_property(&simulator_test_client, wbprov3_aux.device_name, AUX_HEATER_OUTLET_PROPERTY_NAME, 3, items, values));
	SERIAL_CHECK_TRUE(wait_for_property_state(AUX_HEATER_OUTLET_PROPERTY_NAME, INDIGO_OK_STATE));
	for (int i = 0; i < ARRAY_SIZE(items); i++) {
		double expected = round(values[i] * 255.0 / 100.0) / 255.0 * 100.0;
		SERIAL_CHECK_TRUE(wait_for_number(AUX_HEATER_OUTLET_PROPERTY_NAME, items[i], expected, .01));
		printf("Heater %d requested %.0f %%, device reports %.2f %% (nearest step %.2f %%)\n", i + 1, values[i], number_of(AUX_HEATER_OUTLET_PROPERTY_NAME, items[i]), expected);
	}
	// Moving one heater must leave the other two where they were.
	SERIAL_CHECK_TRUE(set_number(AUX_HEATER_OUTLET_PROPERTY_NAME, AUX_HEATER_OUTLET_2_ITEM_NAME, 0));
	SERIAL_CHECK_TRUE(wait_for_number(AUX_HEATER_OUTLET_PROPERTY_NAME, AUX_HEATER_OUTLET_2_ITEM_NAME, 0, .001));
	SERIAL_CHECK_TRUE(wait_for_number(AUX_HEATER_OUTLET_PROPERTY_NAME, AUX_HEATER_OUTLET_1_ITEM_NAME, round(25 * 255.0 / 100.0) / 255.0 * 100.0, .01));
	SERIAL_CHECK_TRUE(wait_for_number(AUX_HEATER_OUTLET_PROPERTY_NAME, AUX_HEATER_OUTLET_3_ITEM_NAME, 100, .001));
cleanup:
	if (online) { stop_serial_driver(&wbprov3_aux); }
	stop_external_serial_simulator(&simulator);
}

