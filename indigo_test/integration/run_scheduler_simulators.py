# Code is generated by AI

"""Run the Scheduler Agent in a private indigo_server with the CCD, mount and guider simulators.

The scheduler loads Sequencer.js itself and runs real capture, slew and guiding tasks through the
Imager, Mount and Guider agents. The client only uploads tasks over the JSON protocol and observes
properties, messages and the saved frames. No existing server or configuration is used.
"""

import argparse
import ctypes
import json
import os
from pathlib import Path
import shutil
import socket
import subprocess
import sys
import tempfile
import time

AGENT = "Scheduler Agent"
SUITE = "Scheduler simulators"


class Client:

	def __init__(self, connection, log):
		self.connection = connection
		self.connection.settimeout(0.25)
		self.buffer = ""
		self.decoder = json.JSONDecoder()
		self.properties = {}
		self.updates = {}
		self.messages = []
		self.log = log
		self.heartbeat = time.monotonic()
		import codecs
		self.utf8 = codecs.getincrementaldecoder("utf-8")()

	def send(self, operation, value):
		self.connection.sendall((json.dumps({operation: value}, ensure_ascii=False) + "\n").encode())

	def change_text(self, device, name, items):
		self.send("newTextVector", {"device": device, "name": name, "items": [{"name": k, "value": v} for k, v in items.items()]})

	def change_switch(self, device, name, items):
		self.send("newSwitchVector", {"device": device, "name": name, "items": [{"name": k, "value": v} for k, v in items.items()]})

	def change_number(self, device, name, items):
		self.send("newNumberVector", {"device": device, "name": name, "items": [{"name": k, "value": v} for k, v in items.items()]})

	def poll(self):
		# the server closes a JSON client that stays silent for a few seconds
		if time.monotonic() - self.heartbeat > 1:
			self.send("getProperties", {"version": 0x300, "device": AGENT, "name": "AGENT_SCHEDULER_STATE"})
			self.heartbeat = time.monotonic()
		try:
			data = self.connection.recv(1024 * 1024)
		except socket.timeout:
			return
		if not data:
			raise RuntimeError("INDIGO disconnected")
		self.buffer += self.utf8.decode(data)
		while self.buffer.strip():
			self.buffer = self.buffer.lstrip()
			try:
				packet, end = self.decoder.raw_decode(self.buffer)
			except json.JSONDecodeError:
				break
			self.buffer = self.buffer[end:]
			# a message without a property is a packet of its own
			if isinstance(packet.get("message"), str):
				self.messages.append((packet.get("device"), packet["message"]))
				self.log.write(json.dumps({"device": packet.get("device"), "message": packet["message"]}, ensure_ascii=False) + "\n")
				self.log.flush()
				continue
			for operation, value in packet.items():
				if not isinstance(value, dict):
					continue
				message = value.get("message")
				if message:
					self.messages.append((value.get("device"), message))
					self.log.write(json.dumps({"device": value.get("device"), "message": message}, ensure_ascii=False) + "\n")
					self.log.flush()
				if operation.startswith(("def", "set")) and "name" in value:
					key = (value["device"], value["name"])
					previous = self.properties.get(key, {}) if operation.startswith("set") else {}
					items = {i["name"]: i for i in previous.get("items", [])}
					for item in value.get("items", []):
						items[item["name"]] = dict(items.get(item["name"], {}), **item)
					merged = dict(previous, **value)
					merged["items"] = list(items.values())
					self.properties[key] = merged
					self.updates[key] = self.updates.get(key, 0) + 1
				elif operation.startswith("delete"):
					for key in [k for k in self.properties if k[0] == value.get("device") and (not value.get("name") or k[1] == value["name"])]:
						del self.properties[key]

	def wait(self, predicate, timeout, what):
		deadline = time.monotonic() + timeout
		while time.monotonic() < deadline:
			self.poll()
			if predicate():
				return
		raise TimeoutError("timed out waiting for " + what)

	def property(self, device, name):
		return self.properties.get((device, name))

	def state(self, device, name):
		p = self.property(device, name)
		return p.get("state") if p else None

	def value(self, device, name, item):
		p = self.property(device, name)
		if p:
			for i in p["items"]:
				if i["name"] == item:
					return i.get("value")
		return None

	def task_label(self, name):
		p = self.property(AGENT, "AGENT_SCHEDULER_TASK_STATE")
		if p:
			for i in p["items"]:
				label = i.get("label", "")
				if label.startswith(name + " "):
					return label
		return ""

	def message_count(self, text):
		return sum(text in m for d, m in self.messages if d == AGENT)

	def message_index(self, text):
		for i, (d, m) in enumerate(self.messages):
			if d == AGENT and text in m:
				return i
		return -1


class Run:

	def __init__(self, client, images, records):
		self.client = client
		self.images = images
		self.records = records
		self.results = []

	def record(self, line):
		if self.records:
			with open(self.records, "a") as output:
				output.write(line + "\n")

	def case(self, name, function):
		started = time.monotonic()
		try:
			function()
			status = "pass"
			detail = ""
		except (AssertionError, TimeoutError) as error:
			status = "fail"
			detail = str(error)
			# the state of the scheduler and the sequence at the failure, for the report
			snapshot = {}
			for key in ((AGENT, "AGENT_SCHEDULER_TASK_STATE"), (AGENT, "AGENT_SCHEDULER_CURRENT"), (AGENT, "AGENT_SCHEDULER_STATE"), ("Scripting Agent", "SEQUENCE_STATE"), ("Scripting Agent", "SEQUENCE_NAME"), ("Scripting Agent", "SCHEDULER_RESULT"), ("Guider Agent", "AGENT_START_PROCESS"), ("Imager Agent", "AGENT_START_PROCESS")):
				snapshot["/".join(key)] = self.client.property(*key)
			self.results_snapshot = snapshot
		self.results.append({"name": name, "status": status, "detail": detail, "seconds": round(time.monotonic() - started, 1), "snapshot": getattr(self, "results_snapshot", None) if status == "fail" else None})
		self.results_snapshot = None
		self.record(status + "\t" + SUITE + "\t" + name)
		print(("  PASS " if status == "pass" else "  FAIL ") + name + (" - " + detail if detail else ""), flush=True)

	def upload(self, text):
		key = (AGENT, "AGENT_SCHEDULER_ADD_TASK")
		before = self.client.updates.get(key, 0)
		self.client.change_text(AGENT, "AGENT_SCHEDULER_ADD_TASK", {"TASK": text})
		# the Busy acknowledgement and the result can arrive in one read
		self.client.wait(lambda: self.client.updates.get(key, 0) > before and self.client.state(*key) != "Busy", 10, "upload result")
		assert self.client.state(AGENT, "AGENT_SCHEDULER_ADD_TASK") == "Ok", "upload rejected: " + str(self.client.messages[-1:])
		# the scheduler stops by design when every task has finished, so a new task needs START
		if self.client.state(AGENT, "AGENT_SCHEDULER_STATE") != "Busy":
			self.control("START")

	def control(self, item):
		self.client.change_switch(AGENT, "AGENT_SCHEDULER_CONTROL", {item: True})

	def wait_task(self, name, state, timeout):
		self.client.wait(lambda: (" - " + state) in self.client.task_label(name), timeout, "task " + name + " in " + state + " (label '" + self.client.task_label(name) + "')")

	def frames(self, prefix):
		return [p for p in self.images.glob(prefix + "*") if p.is_file() and p.stat().st_size > 2880]


def devices_prologue():
	return (
		"var sequence = new Sequence(scheduler_task.name);\n"
		"sequence.select_imager_camera(\"CCD Imager Simulator\");\n"
		"sequence.select_mount(\"Mount Simulator\");\n"
		"sequence.select_guider_camera(\"CCD Guider Simulator\");\n"
		"sequence.select_guider(\"CCD Guider Simulator (guider)\");\n"
	)


def capture_body(images, prefix, count, exposure, guided):
	body = devices_prologue()
	body += "sequence.disable_meridian_flip();\n"
	body += "sequence.unpark();\n"
	body += "sequence.enable_tracking();\n"
	body += "sequence.slew(scheduler_task.ra, scheduler_task.dec);\n"
	body += "sequence.set_directory(" + json.dumps(str(images) + "/") + ");\n"
	body += "sequence.select_frame_type(\"Light\");\n"
	body += "sequence.select_image_format(\"FITS\");\n"
	if guided:
		body += "sequence.start_guiding(0.05);\n"
	body += "sequence.capture_batch(" + json.dumps(prefix + "_XXX") + ", " + str(count) + ", " + str(exposure) + ");\n"
	if guided:
		body += "sequence.stop_guiding();\n"
	body += "sequence.start();\n"
	return body


def sexagesimal(value, sign):
	negative = value < 0
	value = abs(value)
	degrees = int(value)
	minutes = int((value - degrees) * 60)
	seconds = (value - degrees - minutes / 60) * 3600
	return ("-" if negative else ("+" if sign else "")) + "%02d:%02d:%04.1f" % (degrees, minutes, seconds)


def main():
	parser = argparse.ArgumentParser(description=__doc__)
	parser.add_argument("--output", type=Path, help="New directory for retained logs, frames and JSON results")
	parser.add_argument("--keep", action="store_true", help="Keep the output directory")
	args = parser.parse_args()
	repo = Path(__file__).resolve().parents[2]
	output = args.output.resolve() if args.output else Path(tempfile.mkdtemp(prefix="indigo-scheduler-results-"))
	if args.output:
		output.mkdir(parents=True, exist_ok=False)
	home = output / "home"
	images = output / "images"
	home.mkdir()
	images.mkdir()
	library = next(p for p in (repo / "build/lib" / n for n in ("libindigo.so", "libindigo.dylib")) if p.is_file())
	native = ctypes.CDLL(str(library))
	native.indigo_lst.argtypes = [ctypes.POINTER(ctypes.c_long), ctypes.c_double]
	native.indigo_lst.restype = ctypes.c_double
	native.indigo_jnow_to_j2k.argtypes = [ctypes.POINTER(ctypes.c_double), ctypes.POINTER(ctypes.c_double)]
	native.indigo_jnow_to_j2k.restype = None
	with socket.socket() as reservation:
		reservation.bind(("127.0.0.1", 0))
		port = reservation.getsockname()[1]
	drivers = ["agent_scripting", "agent_scheduler", "agent_imager", "agent_mount", "agent_guider", "ccd_simulator", "mount_simulator"]
	command = [str(repo / "build/bin/indigo_server"), "--", "-p", str(port), "-b-", "-c-", "-w-"] + ([os.environ.get("INDIGO_TEST_DEBUG")] if os.environ.get("INDIGO_TEST_DEBUG") else [])
	env = dict(os.environ, HOME=str(home), INDIGO_CACHE_BASE=str(home / ".indigo"))
	process = None
	client = None
	run = None
	error = None
	records = os.environ.get("INDIGO_TEST_RESULTS")
	cases = ["library loaded by the scheduler", "guider calibration task", "slew, guiding and capture task", "urgent task preempts a guided capture", "target below the horizon waits", "shutdown hook parks the mount"]
	only = os.environ.get("SCHEDULER_SIMULATORS_ONLY")
	if records:
		with open(records, "a") as out:
			out.write("plan\t" + str(len(cases)) + "\t" + SUITE + "\n")
	try:
		with (output / "server.log").open("w") as server_log, (output / "messages.jsonl").open("w") as log:
			process = subprocess.Popen(command, cwd=repo, env=env, stdout=server_log, stderr=subprocess.STDOUT)
			deadline = time.monotonic() + 20
			while True:
				if process.poll() is not None:
					raise RuntimeError("private indigo_server exited, see server.log")
				try:
					connection = socket.create_connection(("127.0.0.1", port), timeout=0.5)
					break
				except OSError:
					if time.monotonic() >= deadline:
						raise TimeoutError("private indigo_server did not start")
					time.sleep(0.1)
			client = Client(connection, log)
			run = Run(client, images, records)
			client.send("getProperties", {"version": 0x300})
			client.wait(lambda: client.property("Server", "DRIVERS") is not None, 20, "server drivers")
			client.change_switch("Server", "DRIVERS", {"indigo_" + d: True for d in drivers})
			client.wait(lambda: client.property(AGENT, "AGENT_SCHEDULER_SETTINGS") is not None and client.property("Mount Agent", "GEOGRAPHIC_COORDINATES") is not None and client.property("Guider Agent", "AGENT_START_PROCESS") is not None, 30, "agents")
			client.change_number(AGENT, "AGENT_SCHEDULER_SETTINGS", {"IDLE_CHECK_INTERVAL": 1, "STOP_TIMEOUT": 60, "START_TIMEOUT": 10})
			# the site of the sky constraints comes from the Mount Agent
			client.change_switch("Mount Agent", "FILTER_MOUNT_LIST", {"Mount Simulator": True})
			# an unconfigured Mount Agent reports 0/0, which is a valid site; the test uses a real one
			client.change_number("Mount Agent", "GEOGRAPHIC_COORDINATES", {"LATITUDE": 48.15, "LONGITUDE": 17.11, "ELEVATION": 140})
			client.wait(lambda: client.value("Mount Agent", "GEOGRAPHIC_COORDINATES", "LATITUDE") == 48.15, 20, "site")
			latitude = client.value("Mount Agent", "GEOGRAPHIC_COORDINATES", "LATITUDE")
			longitude = client.value("Mount Agent", "GEOGRAPHIC_COORDINATES", "LONGITUDE")

			def zenith(offset_hours):
				now = ctypes.c_long(int(time.time()))
				ra = ctypes.c_double((native.indigo_lst(ctypes.byref(now), longitude) + offset_hours) % 24)
				dec = ctypes.c_double(latitude)
				native.indigo_jnow_to_j2k(ctypes.byref(ra), ctypes.byref(dec))
				return sexagesimal(ra.value, False) + " " + sexagesimal(dec.value, True)

			def library_loaded():
				run.control("START")
				client.wait(lambda: client.property("Scripting Agent", "SEQUENCE_STATE") is not None, 30, "Sequencer.js loaded by the scheduler")
				client.wait(lambda: client.state(AGENT, "AGENT_SCHEDULER_STATE") == "Busy", 10, "scheduler running")

			def calibration():
				# calibrate as on a real night: unparked, tracking and pointed at the target
				body = devices_prologue()
				body += "sequence.unpark();\n"
				body += "sequence.enable_tracking();\n"
				body += "sequence.slew(scheduler_task.ra, scheduler_task.dec);\n"
				body += "sequence.calibrate_guiding(0.05, 1);\n"
				body += "sequence.start();\n"
				run.upload("// @task Calibration\n// @priority high\n// @target " + zenith(0) + "\n// @duration 10\n\n" + body)
				run.wait_task("Calibration", "DONE", 240)
				assert client.message_count("Task 'Calibration' completed") == 1

			def guided_capture():
				# no @duration: the scheduler estimates it from the sequence, then measures the real run
				run.upload("// @task Zenith\n// @target " + zenith(0) + "\n// @altitude > 30\n\n" + capture_body(images, "zenith", 3, 0.5, True))
				client.wait(lambda: " estimated" in client.task_label("Zenith"), 30, "estimated duration (label '" + client.task_label("Zenith") + "')")
				run.wait_task("Zenith", "DONE", 180)
				assert " measured" in client.task_label("Zenith"), "no measured duration: " + client.task_label("Zenith")
				frames = run.frames("zenith")
				assert len(frames) == 3, "expected 3 frames, found %d" % len(frames)
				assert client.state("Guider Agent", "AGENT_START_PROCESS") != "Busy", "guiding still running"

			def preemption():
				run.upload("// @task Long\n// @target " + zenith(0) + "\n// @retry 1\n// @duration 30\n\n" + capture_body(images, "long", 40, 1, True))
				run.wait_task("Long", "RUNNING", 60)
				client.wait(lambda: client.state("Imager Agent", "AGENT_START_PROCESS") == "Busy" and client.state("Guider Agent", "AGENT_START_PROCESS") == "Busy", 120, "guided capture in progress")
				client.wait(lambda: len(run.frames("long")) >= 1, 60, "first long frame")
				client.change_text(AGENT, "AGENT_SCHEDULER_URGENT_TASK", {"TASK": "// @task Burst\n// @target " + zenith(0.5) + "\n// @duration 10\n\n" + capture_body(images, "burst", 2, 0.2, False)})
				client.wait(lambda: client.message_count("Task 'Long' preempted by an urgent task, it will be retried") == 1, 90, "preemption")
				assert client.state("Imager Agent", "AGENT_START_PROCESS") != "Busy", "exposure not aborted"
				assert client.state("Guider Agent", "AGENT_START_PROCESS") != "Busy", "guiding not aborted"
				long_frames = len(run.frames("long"))
				client.wait(lambda: client.message_count("Task 'Burst' completed") == 1, 120, "urgent task")
				assert len(run.frames("burst")) == 2, "expected 2 urgent frames, found %d" % len(run.frames("burst"))
				assert long_frames < 40, "the preempted capture was not interrupted"
				client.wait(lambda: client.message_count("Starting task 'Long'") == 2, 60, "preempted task restarted")
				assert "retries left 1" in client.task_label("Long"), "the preemption used a retry: " + client.task_label("Long")
				run.control("ABORT")
				run.wait_task("Long", "RETRY", 60)
				client.wait(lambda: client.state("Imager Agent", "AGENT_START_PROCESS") != "Busy", 60, "imager idle after abort")

			def below_horizon():
				client.change_text(AGENT, "AGENT_SCHEDULER_DELETE_TASK", {"NAME": "Long"})
				run.upload("// @task South\n// @target 06:00:00 " + ("-89:00:00" if latitude >= 0 else "+89:00:00") + "\n// @duration 10\n\n" + capture_body(images, "south", 1, 0.2, False))
				run.control("START")
				run.wait_task("South", "WAITING", 30)
				client.wait(lambda: "target below the horizon" in (client.value(AGENT, "AGENT_SCHEDULER_CURRENT", "REASON") or ""), 30, "reason")
				assert client.message_count("Starting task 'South'") == 0

			run.case(cases[0], library_loaded)
			run.case(cases[1], calibration)
			run.case(cases[2], guided_capture)
			run.case(cases[3], preemption)
			def shutdown_hook():
				body = devices_prologue() + "sequence.park();\nsequence.start();\n"
				run.upload("// @task Park\n\n" + body)
				client.change_text(AGENT, "AGENT_SCHEDULER_HOOKS", {"STARTUP": "", "SHUTDOWN": "Park", "IDLE": ""})
				client.wait(lambda: "SHUTDOWN HOOK" in client.task_label("Park"), 10, "hook configured")
				client.wait(lambda: client.state(AGENT, "AGENT_SCHEDULER_STATE") == "Busy", 10, "scheduler running")
				run.control("STOP")
				client.wait(lambda: client.message_count("Hook 'Park' completed") == 1, 120, "shutdown hook")
				client.wait(lambda: client.state(AGENT, "AGENT_SCHEDULER_STATE") == "Ok", 30, "scheduler stopped")
				assert client.value("Mount Simulator", "MOUNT_PARK", "PARKED") is True, "mount not parked"

			run.case(cases[4], below_horizon)
			run.case(cases[5], shutdown_hook)
	except (OSError, RuntimeError, TimeoutError, ValueError, StopIteration) as exception:
		error = str(exception)
		print(error, file=sys.stderr)
	finally:
		if client:
			client.connection.close()
		if process and process.poll() is None:
			process.terminate()
			try:
				process.wait(timeout=15)
			except subprocess.TimeoutExpired:
				process.kill()
				process.wait()
	results = run.results if run else []
	report = {"results": results, "error": error, "server_exit": process.returncode if process else None, "output": str(output)}
	(output / "results.json").write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n")
	passed = sum(r["status"] == "pass" for r in results)
	failed = len(cases) - passed
	print(f"{SUITE}: {passed} passed, {failed} failed; report: {output / 'results.json'}")
	if not failed and not error and not args.keep and not args.output:
		shutil.rmtree(output, ignore_errors=True)
	return 0 if not failed and not error else 1


if __name__ == "__main__":
	sys.exit(main())
