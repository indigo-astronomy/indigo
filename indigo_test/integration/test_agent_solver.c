// every case runs in its own process with a fresh bus, private home and cache directory
int main(int argc, char **argv) {
	const char *filter = argc > 1 ? argv[1] : NULL;
	int result = 0, executed = 0, passed = 0, selected = 0;
	for (int i = 0; i < (int)ARRAY_SIZE(tests); i++) {
		if (filter == NULL || strstr(tests[i].name, filter)) {
			selected++;
		}
	}
	indigo_test_plan(SUITE, selected, filter);
	for (int i = 0; i < (int)ARRAY_SIZE(tests); i++) {
		if (filter != NULL && !strstr(tests[i].name, filter)) {
			continue;
		}
		executed++;
		pid_t child = fork();
		if (child == 0) {
			alarm(300);
			snprintf(cache_base, sizeof(cache_base), "/tmp/indigo-agent-solver.XXXXXX");
			if (mkdtemp(cache_base) == NULL) {
				exit(1);
			}
			setenv("INDIGO_CACHE_BASE", cache_base, 1);
			if (!indigo_test_use_private_home()) {
				exit(1);
			}
			bool ready = setup();
			int status = ready ? indigo_run_tests(SUITE, tests + i, 1) : 1;
			cleanup();
			char dir[PATH_MAX];
			snprintf(dir, sizeof(dir), "%s/solver", cache_base);
			rmdir(dir);
			rmdir(cache_base);
			indigo_test_remove_private_home();
			exit(status || indigo_test_failures ? 1 : 0);
		}
		int status = -1;
		if (child < 0 || waitpid(child, &status, 0) != child || !WIFEXITED(status) || WEXITSTATUS(status)) {
			fprintf(stderr, "Failed case: %s (status %d)\n", tests[i].name, status);
			result = 1;
		} else {
			passed++;
		}
	}
	indigo_test_plan_recorded = false;
	fprintf(stderr, "%s: %d of %d cases passed\n", SUITE, passed, executed);
	return result;
}
