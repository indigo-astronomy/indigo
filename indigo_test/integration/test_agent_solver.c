static bool setup(void) {
	indigo_set_log_level(getenv("INDIGO_TEST_DEBUG") ? INDIGO_LOG_DEBUG : INDIGO_LOG_ERROR);
	char dir[PATH_MAX];
	snprintf(dir, sizeof(dir), "%s/solver", cache_base);
	mkdir(dir, 0755);
	indigo_solver_index_path(index_path, sizeof(index_path), dir, 5);
	REQUIRE(write_synthetic_index(index_path));
	REQUIRE(indigo_start() == INDIGO_OK);
	bus_started = true;
	INDIGO_COPY_NAME(observer.name, "Solver observer");
	observer.version = INDIGO_VERSION_CURRENT;
	observer.define_property = defined;
	observer.update_property = updated;
	observer.delete_property = deleted;
	observer.send_message = message_received;
	REQUIRE(indigo_attach_client(&observer) == INDIGO_OK);
	observer_attached = true;
	REQUIRE(indigo_agent_solver(INDIGO_DRIVER_INIT, NULL) == INDIGO_OK);
	solver_started = true;
	REQUIRE(WAIT_UNTIL(exists(INDEX_PROPERTY) && exists(AGENT_PLATESOLVER_USE_INDEX_PROPERTY_NAME) && exists(AGENT_PLATESOLVER_WCS_PROPERTY_NAME), 10));
	return true;
}

static void cleanup(void) {
	if (solver_started) {
		indigo_agent_solver(INDIGO_DRIVER_SHUTDOWN, NULL);
	}
	if (observer_attached) {
		indigo_detach_client(&observer);
	}
	if (bus_started) {
		indigo_stop();
	}
	unlink(index_path);
}

static bool select_use_index(void) {
	REQUIRE(has_item(AGENT_PLATESOLVER_USE_INDEX_PROPERTY_NAME, INDEX_ITEM));
	REQUIRE(indigo_change_switch_property_1(&observer, SOLVER, AGENT_PLATESOLVER_USE_INDEX_PROPERTY_NAME, INDEX_ITEM, true) == INDIGO_OK);
	REQUIRE(WAIT_UNTIL(switch_value(AGENT_PLATESOLVER_USE_INDEX_PROPERTY_NAME, INDEX_ITEM), 10));
	return true;
}

static bool solve_image(void *image, long size, const char *format) {
	unsigned ok_before = state_count(AGENT_PLATESOLVER_WCS_PROPERTY_NAME, INDIGO_OK_STATE);
	unsigned alert_before = state_count(AGENT_PLATESOLVER_WCS_PROPERTY_NAME, INDIGO_ALERT_STATE);
	REQUIRE(indigo_change_blob_property_1(&observer, SOLVER, AGENT_PLATESOLVER_IMAGE_PROPERTY_NAME, AGENT_PLATESOLVER_IMAGE_ITEM_NAME, image, size, format, "") == INDIGO_OK);
	REQUIRE(WAIT_UNTIL(state_count(AGENT_PLATESOLVER_WCS_PROPERTY_NAME, INDIGO_OK_STATE) > ok_before || state_count(AGENT_PLATESOLVER_WCS_PROPERTY_NAME, INDIGO_ALERT_STATE) > alert_before, 60));
	return true;
}

