// Angular distance in degrees, ra in hours
static double distance(double ra1, double dec1, double ra2, double dec2) {
	double d2r = M_PI / 180;
	double c = sin(dec1 * d2r) * sin(dec2 * d2r) + cos(dec1 * d2r) * cos(dec2 * d2r) * cos((ra1 - ra2) * 15 * d2r);
	return acos(fmax(-1, fmin(1, c))) / d2r;
}

// J2000 coordinates of the physical pointing the camera simulator renders
static void rendered_center_j2000(double *ra, double *dec) {
	*ra = number(CAMERA, "SIMULATION_SETUP", "RA");
	*dec = number(CAMERA, "SIMULATION_SETUP", "DEC");
	if (number(CAMERA, "SIMULATION_SETUP", "EPOCH") == 0) {
		indigo_jnow_to_j2k(ra, dec);
	}
}

// J2000 coordinates the mount physically points at, shared by the mount simulator; the camera
// simulator takes them over only when it exposes the next frame
static void physical_j2000(double *ra, double *dec) {
	indigo_simulated_mount_state state = { 0 };
	indigo_get_simulated_mount_state(&state);
	*ra = state.ra;
	*dec = state.dec;
	if (state.epoch == 0) {
		indigo_jnow_to_j2k(ra, dec);
	}
}

// J2000 coordinates the mount reports
static void mount_j2000(double *ra, double *dec) {
	*ra = mount_ra();
	*dec = mount_dec();
	if (number(MOUNT_DEVICE, MOUNT_EPOCH_PROPERTY_NAME, MOUNT_EPOCH_ITEM_NAME) == 0) {
		indigo_jnow_to_j2k(ra, dec);
	}
}

// Runs one Astrometry agent process and waits for its end in the expected state
static bool run_process(const char *operation, indigo_property_state expected, double timeout) {
	unsigned busy = state_count(ASTROMETRY, AGENT_START_PROCESS_PROPERTY_NAME, INDIGO_BUSY_STATE);
	REQUIRE(indigo_change_switch_property_1(&observer, ASTROMETRY, AGENT_START_PROCESS_PROPERTY_NAME, operation, true) == INDIGO_OK);
	REQUIRE(WAIT_UNTIL(state_count(ASTROMETRY, AGENT_START_PROCESS_PROPERTY_NAME, INDIGO_BUSY_STATE) > busy, 10));
	double start = indigo_monotonic_time();
	if (!WAIT_UNTIL(state(ASTROMETRY, AGENT_START_PROCESS_PROPERTY_NAME) != INDIGO_BUSY_STATE, timeout)) {
		fprintf(stderr, "%s did not finish in %g s\n", operation, timeout);
		dump_messages();
		return false;
	}
	printf("  %s finished in %.1f s\n", operation, indigo_monotonic_time() - start);
	if (state(ASTROMETRY, AGENT_START_PROCESS_PROPERTY_NAME) != (int)expected) {
		fprintf(stderr, "%s finished in state %d, expected %d\n", operation, state(ASTROMETRY, AGENT_START_PROCESS_PROPERTY_NAME), expected);
		dump_messages();
		return false;
	}
	return true;
}

// Moves the mount through the Mount Agent and waits until the slew finishes
static bool slew(double ra, double dec) {
	REQUIRE(change_numbers(MOUNT, AGENT_MOUNT_TARGET_COORDINATES_PROPERTY_NAME, 2, (const char *[]){ AGENT_MOUNT_TARGET_COORDINATES_RA_ITEM_NAME, AGENT_MOUNT_TARGET_COORDINATES_DEC_ITEM_NAME }, (double []){ ra, dec }));
	unsigned busy = state_count(MOUNT, AGENT_START_PROCESS_PROPERTY_NAME, INDIGO_BUSY_STATE);
	REQUIRE(indigo_change_switch_property_1(&observer, MOUNT, AGENT_START_PROCESS_PROPERTY_NAME, AGENT_MOUNT_START_SLEW_ITEM_NAME, true) == INDIGO_OK);
	REQUIRE(WAIT_UNTIL(state_count(MOUNT, AGENT_START_PROCESS_PROPERTY_NAME, INDIGO_BUSY_STATE) > busy, 10));
	if (!WAIT_UNTIL(state(MOUNT, AGENT_START_PROCESS_PROPERTY_NAME) != INDIGO_BUSY_STATE, 180)) {
		fprintf(stderr, "slew to %g %g did not finish\n", ra, dec);
		dump_messages();
		return false;
	}
	REQUIRE(state(MOUNT, AGENT_START_PROCESS_PROPERTY_NAME) == INDIGO_OK_STATE);
	return true;
}

// Syncs the mount simulator directly, so the coordinates it reports differ from its physical pointing
static bool mount_sync_directly(double ra, double dec) {
	REQUIRE(change_switch_and_wait(MOUNT_DEVICE, MOUNT_ON_COORDINATES_SET_PROPERTY_NAME, MOUNT_ON_COORDINATES_SET_SYNC_ITEM_NAME, true, INDIGO_OK_STATE, 10));
	REQUIRE(change_numbers(MOUNT_DEVICE, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, 2, (const char *[]){ MOUNT_EQUATORIAL_COORDINATES_RA_ITEM_NAME, MOUNT_EQUATORIAL_COORDINATES_DEC_ITEM_NAME }, (double []){ ra, dec }));
	REQUIRE(change_switch_and_wait(MOUNT_DEVICE, MOUNT_ON_COORDINATES_SET_PROPERTY_NAME, MOUNT_ON_COORDINATES_SET_TRACK_ITEM_NAME, true, INDIGO_OK_STATE, 10));
	REQUIRE(fabs(mount_ra() - ra) < 0.001 && fabs(mount_dec() - dec) < 0.01);
	return true;
}

// Solved field angle minus the rotation the camera simulator rendered. The simulator turns the field
// by 180° on the west side of the pier; solve-field reports IMAGE_ROTATION_ANGLE there and 180° more
// on the east side.
static double angle_error(void) {
	double rotation = number(CAMERA, "SIMULATION_SETUP", "IMAGE_ROTATION_ANGLE") + (number(CAMERA, "SIMULATION_SETUP", "SIDE_OF_PIER") == 1 ? 0 : 180);
	return remainder(wcs(AGENT_PLATESOLVER_WCS_ANGLE_ITEM_NAME) - rotation, 360);
}

// The mount reports coordinates shifted by the given offset from where it points, as after a wrong sync
static bool add_pointing_error(double ra_offset, double dec_offset) {
	return mount_sync_directly(fmod(mount_ra() + ra_offset + 24, 24), mount_dec() + dec_offset);
}

static void print_wcs(const char *label) {
	double ra, dec;
	rendered_center_j2000(&ra, &dec);
	printf("  %s: WCS RA %.4f h Dec %.4f° angle %.2f° scale %.2f\"/px parity %g index %g, rendered %.4f h %.4f° rotation %g°, mount %.4f h %.4f°\n", label, wcs(AGENT_PLATESOLVER_WCS_RA_ITEM_NAME), wcs(AGENT_PLATESOLVER_WCS_DEC_ITEM_NAME), wcs(AGENT_PLATESOLVER_WCS_ANGLE_ITEM_NAME), wcs(AGENT_PLATESOLVER_WCS_SCALE_ITEM_NAME) * 3600, wcs(AGENT_PLATESOLVER_WCS_PARITY_ITEM_NAME), wcs(AGENT_PLATESOLVER_WCS_INDEX_ITEM_NAME), ra, dec, number(CAMERA, "SIMULATION_SETUP", "IMAGE_ROTATION_ANGLE"), mount_ra(), mount_dec());
}

// The solution matches what the camera simulator rendered: its J2000 centre and its scale
static bool solution_matches_rendered_field(void) {
	double ra, dec;
	rendered_center_j2000(&ra, &dec);
	print_wcs("solution");
	REQUIRE(state(ASTROMETRY, AGENT_PLATESOLVER_WCS_PROPERTY_NAME) == INDIGO_OK_STATE);
	REQUIRE(wcs(AGENT_PLATESOLVER_WCS_EPOCH_ITEM_NAME) == 2000);
	REQUIRE(distance(wcs(AGENT_PLATESOLVER_WCS_RA_ITEM_NAME), wcs(AGENT_PLATESOLVER_WCS_DEC_ITEM_NAME), ra, dec) < 0.02);
	REQUIRE(fabs(wcs(AGENT_PLATESOLVER_WCS_SCALE_ITEM_NAME) / EXPECTED_SCALE - 1) < 0.02);
	REQUIRE(wcs(AGENT_PLATESOLVER_WCS_INDEX_ITEM_NAME) == atoi(INDEX));
	REQUIRE(fabs(angle_error()) < 0.1);
	return true;
}

// Downloads a Tycho-2 index through the agent into the cache shared by the run, or finds it there, and
// selects it: an index found on disk is offered unselected to a fresh configuration, only a downloaded one
// is selected
static bool install_index(const char *name) {
	REQUIRE(change_switch_and_wait(ASTROMETRY, INDEX_41, name, true, INDIGO_OK_STATE, 300));
	REQUIRE(WAIT_UNTIL(has_item(ASTROMETRY, AGENT_PLATESOLVER_USE_INDEX_PROPERTY_NAME, name), 10));
	if (!switch_value(ASTROMETRY, AGENT_PLATESOLVER_USE_INDEX_PROPERTY_NAME, name)) {
		REQUIRE(change_switch_and_wait(ASTROMETRY, AGENT_PLATESOLVER_USE_INDEX_PROPERTY_NAME, name, true, INDIGO_OK_STATE, 10));
	}
	return true;
}

static bool setup(void) {
	indigo_set_log_level(getenv("INDIGO_TEST_DEBUG") ? INDIGO_LOG_DEBUG : INDIGO_LOG_ERROR);
	REQUIRE(indigo_start() == INDIGO_OK);
	bus_started = true;
	INDIGO_COPY_NAME(observer.name, "Astrometry solver observer");
	observer.version = INDIGO_VERSION_CURRENT;
	observer.define_property = defined;
	observer.update_property = updated;
	observer.delete_property = deleted;
	observer.send_message = message_received;
	REQUIRE(indigo_attach_client(&observer) == INDIGO_OK);
	observer_attached = true;
	REQUIRE(indigo_ccd_simulator(INDIGO_DRIVER_INIT, NULL) == INDIGO_OK);
	ccd_started = true;
	REQUIRE(indigo_mount_simulator(INDIGO_DRIVER_INIT, NULL) == INDIGO_OK);
	mount_started = true;
	REQUIRE(indigo_agent_imager(INDIGO_DRIVER_INIT, NULL) == INDIGO_OK);
	imager_started = true;
	REQUIRE(indigo_agent_mount(INDIGO_DRIVER_INIT, NULL) == INDIGO_OK);
	mount_agent_started = true;
	REQUIRE(indigo_agent_astrometry(INDIGO_DRIVER_INIT, NULL) == INDIGO_OK);
	astrometry_started = true;
	REQUIRE(change_switch_and_wait(IMAGER, FILTER_CCD_LIST_PROPERTY_NAME, CAMERA, true, INDIGO_OK_STATE, 20));
	// the whole catalogue, it ends at magnitude 9.3
	REQUIRE(change_number(CAMERA, "SIMULATION_SETUP", "MAGNITUDE_LIMIT", 9.5));
	REQUIRE(change_switch_and_wait(MOUNT, FILTER_MOUNT_LIST_PROPERTY_NAME, MOUNT_DEVICE, true, INDIGO_OK_STATE, 20));
	REQUIRE(relate(ASTROMETRY, IMAGER));
	REQUIRE(relate(ASTROMETRY, MOUNT));
	// the site is set on the Mount Agent, as a user does; the agent passes it to the mount and the camera follows the mount
	REQUIRE(change_numbers(MOUNT, GEOGRAPHIC_COORDINATES_PROPERTY_NAME, 2, (const char *[]){ GEOGRAPHIC_COORDINATES_LATITUDE_ITEM_NAME, GEOGRAPHIC_COORDINATES_LONGITUDE_ITEM_NAME }, (double []){ SITE_LATITUDE, SITE_LONGITUDE }));
	REQUIRE(change_switch_and_wait(MOUNT_DEVICE, MOUNT_PARK_PROPERTY_NAME, MOUNT_PARK_UNPARKED_ITEM_NAME, true, INDIGO_OK_STATE, 60));
	REQUIRE(install_index(INDEX));
	REQUIRE(change_number(ASTROMETRY, AGENT_PLATESOLVER_EXPOSURE_SETTINGS_PROPERTY_NAME, AGENT_PLATESOLVER_EXPOSURE_SETTINGS_EXPOSURE_ITEM_NAME, 1));
	REQUIRE(change_number(ASTROMETRY, AGENT_PLATESOLVER_MOUNT_SETTLE_TIME_PROPERTY_NAME, AGENT_PLATESOLVER_MOUNT_SETTLE_TIME_ITEM_NAME, 0));
	return true;
}

static void cleanup(void) {
	if (astrometry_started) {
		indigo_agent_astrometry(INDIGO_DRIVER_SHUTDOWN, NULL);
	}
	if (mount_agent_started) {
		indigo_agent_mount(INDIGO_DRIVER_SHUTDOWN, NULL);
	}
	if (imager_started) {
		indigo_agent_imager(INDIGO_DRIVER_SHUTDOWN, NULL);
	}
	if (mount_started) {
		indigo_mount_simulator(INDIGO_DRIVER_SHUTDOWN, NULL);
	}
	if (ccd_started) {
		indigo_ccd_simulator(INDIGO_DRIVER_SHUTDOWN, NULL);
	}
	if (observer_attached) {
		indigo_detach_client(&observer);
	}
	if (bus_started) {
		indigo_stop();
	}
}

// A blind solve of a frame captured by the related Imager Agent finds the field the simulator rendered
static void solve_only(void) {
	ASSERT_TRUE(slew(18.6, 38.8));
	ASSERT_TRUE(run_process(AGENT_PLATESOLVER_START_SOLVE_ITEM_NAME, INDIGO_OK_STATE, 180));
	ASSERT_TRUE(solution_matches_rendered_field());
}

// The mount reports coordinates 1.5° off its pointing; solve and sync makes it report where it points
static void solve_and_sync(void) {
	ASSERT_TRUE(slew(18.6, 38.8));
	ASSERT_TRUE(add_pointing_error(0.05, -1));
	ASSERT_TRUE(run_process(AGENT_PLATESOLVER_START_SYNC_ITEM_NAME, INDIGO_OK_STATE, 180));
	ASSERT_TRUE(solution_matches_rendered_field());
	double ra, dec, synced_ra, synced_dec;
	rendered_center_j2000(&ra, &dec);
	mount_j2000(&synced_ra, &synced_dec);
	printf("  the mount reports %.4f h %.4f°, %.4f° from its pointing\n", synced_ra, synced_dec, distance(synced_ra, synced_dec, ra, dec));
	ASSERT_TRUE(distance(synced_ra, synced_dec, ra, dec) < 0.02);
}

// With the mount reporting coordinates off its pointing, center syncs it and slews to the coordinates
// it reported before, so that the field is centred on them
static void solve_sync_and_center(void) {
	ASSERT_TRUE(slew(18.6, 38.8));
	ASSERT_TRUE(add_pointing_error(-0.05, 1));
	double target_ra, target_dec, ra, dec;
	mount_j2000(&target_ra, &target_dec);
	physical_j2000(&ra, &dec);
	printf("  the mount reports %.4f h %.4f° pointing %.3f° away from it\n", target_ra, target_dec, distance(ra, dec, target_ra, target_dec));
	ASSERT_TRUE(run_process(AGENT_PLATESOLVER_START_CENTER_ITEM_NAME, INDIGO_OK_STATE, 300));
	physical_j2000(&ra, &dec);
	print_wcs("centered");
	printf("  the mount points %.4f° from the target\n", distance(ra, dec, target_ra, target_dec));
	ASSERT_TRUE(distance(ra, dec, target_ra, target_dec) < 0.02);
}

// The sparsest field of the sky. Its quads decide the index: with the field turned as IMAGE_ROTATION_ANGLE
// turns it (solve-field sees -36° or 144°) too few of the 2.8-4° quads of index 4113 fit in the 4° x 5.3° frame
// and it does not solve, the 2-2.8° quads of 4112 solve it at any angle.
static void south_galactic_pole(void) {
	ASSERT_TRUE(slew(0.85, -27.1));
	ASSERT_TRUE(run_process(AGENT_PLATESOLVER_START_SOLVE_ITEM_NAME, INDIGO_OK_STATE, 180));
	ASSERT_TRUE(solution_matches_rendered_field());
}

// Precise GOTO slews to the target, solves, syncs and slews again, so that the field is centred on
// the target although the mount reports coordinates off its pointing
static bool precise_goto_to(double target_ra, double target_dec, double ra_offset, double dec_offset) {
	REQUIRE(add_pointing_error(ra_offset, dec_offset));
	REQUIRE(change_numbers(ASTROMETRY, AGENT_PLATESOLVER_GOTO_SETTINGS_PROPERTY_NAME, 2, (const char *[]){ AGENT_PLATESOLVER_GOTO_SETTINGS_RA_ITEM_NAME, AGENT_PLATESOLVER_GOTO_SETTINGS_DEC_ITEM_NAME }, (double []){ target_ra, target_dec }));
	REQUIRE(run_process(AGENT_PLATESOLVER_START_PRECISE_GOTO_ITEM_NAME, INDIGO_OK_STATE, 300));
	double ra, dec;
	physical_j2000(&ra, &dec);
	print_wcs("goto");
	printf("  target %.4f h %+.4f°, the mount points %.4f° from it, angle error %+.2f°\n", target_ra, target_dec, distance(ra, dec, target_ra, target_dec), angle_error());
	REQUIRE(distance(ra, dec, target_ra, target_dec) < 0.02);
	// the last frame was taken before the final slew, the solution belongs to it
	REQUIRE(fabs(wcs(AGENT_PLATESOLVER_WCS_SCALE_ITEM_NAME) / EXPECTED_SCALE - 1) < 0.02);
	REQUIRE(fabs(angle_error()) < 0.1);
	return true;
}

static void precise_goto(void) {
	ASSERT_TRUE(slew(18.6, 38.8));
	ASSERT_TRUE(precise_goto_to(18.0, 30.0, 0.05, 0.5));
}

// Three point polar alignment, then the corrections a user makes: each step removes 70 % of the
// measured error on the simulator and recalculates, until the measured error is below 1'.
static void polar_alignment(void) {
	double alt_error = 0.8, az_error = -1.1;
	ASSERT_TRUE(change_numbers(CAMERA, "SIMULATION_SETUP", 2, (const char *[]){ "ALT_POLAR_ERROR", "AZ_POLAR_ERROR" }, (double []){ alt_error, az_error }));
	// The references follow the sidereal time; a longitude putting it at 9.35 h keeps them at RA 9.1, 7.8 and 6.4 h
	// (Hydra, Monoceros) at any time of the day, so that the case does not depend on the time it runs
	double pinned_lst = getenv("PA_LST") ? atof(getenv("PA_LST")) : 9.35;
	double longitude = remainder(SITE_LONGITUDE + (pinned_lst - indigo_lst(NULL, SITE_LONGITUDE)) * 15, 360);
	ASSERT_TRUE(change_numbers(MOUNT, GEOGRAPHIC_COORDINATES_PROPERTY_NAME, 2, (const char *[]){ GEOGRAPHIC_COORDINATES_LATITUDE_ITEM_NAME, GEOGRAPHIC_COORDINATES_LONGITUDE_ITEM_NAME }, (double []){ SITE_LATITUDE, longitude }));
	ASSERT_TRUE(WAIT_UNTIL(fabs(remainder(number(MOUNT, MOUNT_GEOGRAPHIC_COORDINATES_PROPERTY_NAME, MOUNT_GEOGRAPHIC_COORDINATES_LONGITUDE_ITEM_NAME) - longitude, 360)) < 1e-6, 10));
	// POLAR_ALIGNMENT.md: start just past the meridian at 35-50° altitude, the positive hour angle move goes west
	ASSERT_TRUE(slew(fmod(indigo_lst(NULL, longitude) - 0.25 + 24, 24), 5));
	ASSERT_TRUE(run_process(AGENT_PLATESOLVER_START_CALCULATE_PA_ERROR_ITEM_NAME, INDIGO_OK_STATE, 600));
	ASSERT_EQ_INT(INDIGO_POLAR_ALIGN_IN_PROGRESS, (int)pa_state(AGENT_PLATESOLVER_PA_STATE_ITEM_NAME));
	bool aligned = false;
	for (int step = 0; step <= 10; step++) {
		double measured_alt = pa_state(AGENT_PLATESOLVER_PA_STATE_ALT_ERROR_ITEM_NAME);
		double measured_az = pa_state(AGENT_PLATESOLVER_PA_STATE_AZ_ERROR_ITEM_NAME);
		double measured = pa_state(AGENT_PLATESOLVER_PA_STATE_POLAR_ERROR_ITEM_NAME);
		printf("  step %d: polar error %6.2f' (alt %+7.2f' az %+7.2f'), simulator %6.2f' (alt %+7.2f' az %+7.2f')\n", step, measured * 60, measured_alt * 60, measured_az * 60, hypot(alt_error, az_error) * 60, alt_error * 60, az_error * 60);
		// within half an arcminute of the error set on the simulator in every step
		ASSERT_TRUE(fabs(measured_alt - alt_error) < 0.5 / 60 && fabs(measured_az - az_error) < 0.5 / 60);
		if (measured < 1.0 / 60) {
			aligned = true;
			break;
		}
		alt_error -= 0.7 * measured_alt;
		az_error -= 0.7 * measured_az;
		ASSERT_TRUE(change_numbers(CAMERA, "SIMULATION_SETUP", 2, (const char *[]){ "ALT_POLAR_ERROR", "AZ_POLAR_ERROR" }, (double []){ alt_error, az_error }));
		ASSERT_TRUE(run_process(AGENT_PLATESOLVER_START_RECALCULATE_PA_ERROR_ITEM_NAME, INDIGO_OK_STATE, 300));
		ASSERT_EQ_INT(INDIGO_POLAR_ALIGN_IN_PROGRESS, (int)pa_state(AGENT_PLATESOLVER_PA_STATE_ITEM_NAME));
	}
	ASSERT_TRUE(aligned);
	ASSERT_TRUE(hypot(alt_error, az_error) < 1.0 / 60);
}

