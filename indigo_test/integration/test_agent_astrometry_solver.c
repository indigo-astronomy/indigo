// The production Astrometry agent with the real astrometry.net solver (solve-field, image2xy) and
// index 4112, which the agent downloads itself. The frames come from the related Imager Agent
// capturing with the CCD Guider Simulator, the only camera that renders catalogue stars (4° over
// 1200 px, about 12"/px), and the mount is the Mount Simulator behind a related Mount Agent. The
// camera follows the physical (raw) pointing of the mount, so a sync of the mount to wrong
// coordinates is a pointing error the solver has to find.
// Covered: solve only, solve and sync, solve, sync and center, precise GOTO, and the three point
// polar alignment with its recalculation against the polar error set on the simulator.
// Opt-in: it needs the solver installed and data.astrometry.net reachable.

