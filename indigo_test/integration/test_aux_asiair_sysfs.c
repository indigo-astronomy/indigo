/** Characterization suite for the ZWO ASIAIR power port AUX driver.
 \file test_aux_asiair_sysfs.c
 The driver drives four power ports on the Raspberry Pi header through the
 legacy sysfs GPIO and PWM interfaces, so the boundary is replaced by the
 shared fake in sysfs_gpio_fake.h. Unlike the Raspberry Pi GPIO driver it has
 no inputs, and its two PWM channels drive the first and the fourth output
 rather than the first two.
 */

