#include "serial_simulator_test_common.h"
#include "sysfs_gpio_fake.h"

#define ASIAIR_DEVICE_NAME "ZWO Power Ports ASIAIR"
#define ASIAIR_OUTPUT_COUNT 4

// Output #1 is PWM channel 0 and Output #4 is PWM channel 1.
static const int driver_output_pins[ASIAIR_OUTPUT_COUNT] = { 12, 13, 26, 18 };
static const int driver_plain_pins[2] = { 13, 26 };

static const simulator_driver_case driver = { "ZWO Power Ports ASIAIR", "indigo_aux_asiair", ASIAIR_DEVICE_NAME, indigo_aux_asiair, false, NULL, 0, NULL, 0, NULL, 0, NULL, 0 };

static bool driver_running;
static int failures_at_bring_up;

static bool bring_up_driver(int gpio_base, bool pwm_chip_present) {
	fake_reset(gpio_base, pwm_chip_present);
	failures_at_bring_up = indigo_test_failures;
	driver_running = bring_up_serial_driver(&driver);
	return driver_running;
}

static bool connect_driver(void) {
	return connect_serial_device(&driver, NULL);
}

static bool start_driver(int gpio_base, bool pwm_chip_present) {
	if (!bring_up_driver(gpio_base, pwm_chip_present)) {
		return false;
	}
	return connect_driver();
}

static void stop_driver(void) {
	if (indigo_test_failures != failures_at_bring_up || getenv("INDIGO_TEST_TRACE") != NULL) {
		fake_dump_trace(indigo_current_test_name);
	}
	if (driver_running) {
		stop_serial_driver(&driver);
		driver_running = false;
	}
}

static void assert_property_deleted(const char *name) {
	if (find_cached_property(name) != NULL) {
		fprintf(stderr, "Property %s is still defined\n", name);
	}
	ASSERT_TRUE(find_cached_property(name) == NULL);
}

// PWM is opt-in, so a scenario that exercises it has to ask for it before the
// device is connected.
static bool start_driver_with_pwm(int gpio_base) {
	if (!bring_up_driver(gpio_base, true)) {
		return false;
	}
	if (indigo_change_switch_property_1(&simulator_test_client, ASIAIR_DEVICE_NAME, "X_AUX_PWM", "ENABLED", true) != INDIGO_OK) {
		return false;
	}
	// The property is already in OK state before the change, so the state is
	// not a signal that the change has landed; the item value is.
	for (int i = 0; i < 50; i++) {
		indigo_item *item = find_cached_item("X_AUX_PWM", "ENABLED");
		if (item != NULL && item->sw.value) {
			return connect_driver();
		}
		indigo_usleep(100000);
	}
	printf("X_AUX_PWM did not switch to ENABLED\n");
	return false;
}

