// Code is generated by AI

// AUX SQM coverage for indigo_aux_astromechanics against the standalone LPM simulator over a real
// PTY. The LPM answers a single "V#" query with a sky brightness in mag/arcsec2; the driver polls it
// and derives the Bortle class locally. The protocol has no identity handshake, so the open only
// checks that the port itself can be opened.

#include <indigo_drivers/aux_astromechanics/indigo_aux_astromechanics.h>

#include "serial_simulator_test_common.h"

#ifndef AUX_ASTROMECHANICS_SIMULATOR_EXECUTABLE
#define AUX_ASTROMECHANICS_SIMULATOR_EXECUTABLE "build/integration/aux_astromechanics_simulator"
#endif

static const simulator_driver_case astromechanics_aux = {
	"ASTROMECHANICS LPM Sky Quality",
	"indigo_aux_astromechanics",
	"ASTROMECHANICS LPM",
	indigo_aux_astromechanics,
	false,
	NULL, 0, NULL, 0, NULL, 0, NULL, 0
};

static bool start_lpm(external_serial_simulator *simulator, const char *sky_brightness) {
	if (sky_brightness == NULL) {
		return start_external_serial_simulator(simulator, AUX_ASTROMECHANICS_SIMULATOR_EXECUTABLE);
	}
	const char *arguments[] = { "--sky-brightness", sky_brightness, NULL };
	return start_external_serial_simulator_with_args(simulator, AUX_ASTROMECHANICS_SIMULATOR_EXECUTABLE, arguments);
}

static double brightness(void) {
	return cached_number_value(AUX_WEATHER_PROPERTY_NAME, AUX_WEATHER_SKY_BRIGHTNESS_ITEM_NAME);
}

static double bortle(void) {
	return cached_number_value(AUX_WEATHER_PROPERTY_NAME, AUX_WEATHER_SKY_BORTLE_CLASS_ITEM_NAME);
}

// -------------------------------------------------------------------------------- metadata

static void metadata_and_property_completeness(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_lpm(&simulator, NULL));
	SERIAL_CHECK_TRUE(start_serial_driver(&astromechanics_aux, simulator.port));
	online = true;
	SERIAL_CHECK_TRUE(context.connected && context.last_connection_state == INDIGO_OK_STATE);
	assert_device_interface(INDIGO_INTERFACE_AUX_SQM);
	assert_defined_property(AUX_WEATHER_PROPERTY_NAME);
	assert_property_has_item(AUX_WEATHER_PROPERTY_NAME, AUX_WEATHER_SKY_BRIGHTNESS_ITEM_NAME);
	assert_property_has_item(AUX_WEATHER_PROPERTY_NAME, AUX_WEATHER_SKY_BORTLE_CLASS_ITEM_NAME);
	indigo_property *weather = find_cached_property(AUX_WEATHER_PROPERTY_NAME);
	SERIAL_CHECK_TRUE(weather != NULL && weather->perm == INDIGO_RO_PERM);
	// The LPM is a bare sensor: no light, no cover, no outlets.
	assert_not_defined_property(AUX_LIGHT_SWITCH_PROPERTY_NAME);
	assert_not_defined_property(AUX_LIGHT_INTENSITY_PROPERTY_NAME);
cleanup:
	if (online) { stop_serial_driver(&astromechanics_aux); }
	stop_external_serial_simulator(&simulator);
}

// -------------------------------------------------------------------------------- readings

// The simulator's default reading, and the Bortle class the driver derives from it.
static void default_reading_is_published_with_its_bortle_class(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_lpm(&simulator, NULL));
	SERIAL_CHECK_TRUE(start_serial_driver(&astromechanics_aux, simulator.port));
	online = true;
	SERIAL_CHECK_TRUE(wait_for_property_state(AUX_WEATHER_PROPERTY_NAME, INDIGO_OK_STATE));
	printf("Sky brightness %g, Bortle %g\n", brightness(), bortle());
	SERIAL_CHECK_TRUE(fabs(brightness() - 17.34) < .005);
	SERIAL_CHECK_TRUE(fabs(bortle() - 8) < .001);
cleanup:
	if (online) { stop_serial_driver(&astromechanics_aux); }
	stop_external_serial_simulator(&simulator);
}

// One reading per Bortle band, including both boundaries of the half class, so a change to the
// mapping or to the reply parsing shows up here.
static void bortle_class_follows_the_reported_brightness(void) {
	static const struct { const char *reading; double brightness; double bortle; } cases[] = {
		{ "22.00", 22.00, 1 },
		{ "21.70", 21.70, 2 },
		{ "21.40", 21.40, 3 },
		{ "21.00", 21.00, 4 },
		{ "20.50", 20.50, 4.5 },
		{ "19.50", 19.50, 5 },
		{ "18.75", 18.75, 6 },
		{ "18.25", 18.25, 7 },
		{ "17.50", 17.50, 8 },
		{ "16.00", 16.00, 9 }
	};
	for (int i = 0; i < ARRAY_SIZE(cases); i++) {
		external_serial_simulator simulator = { 0 };
		bool online = false;
		SERIAL_CHECK_TRUE(start_lpm(&simulator, cases[i].reading));
		SERIAL_CHECK_TRUE(start_serial_driver(&astromechanics_aux, simulator.port));
		online = true;
		SERIAL_CHECK_TRUE(wait_for_property_state(AUX_WEATHER_PROPERTY_NAME, INDIGO_OK_STATE));
		printf("Reading %s -> brightness %g, Bortle %g (expected %g)\n", cases[i].reading, brightness(), bortle(), cases[i].bortle);
		SERIAL_CHECK_TRUE(fabs(brightness() - cases[i].brightness) < .005);
		SERIAL_CHECK_TRUE(fabs(bortle() - cases[i].bortle) < .001);
		stop_serial_driver(&astromechanics_aux);
		online = false;
		stop_external_serial_simulator(&simulator);
		continue;
cleanup:
		if (online) { stop_serial_driver(&astromechanics_aux); }
		stop_external_serial_simulator(&simulator);
		return;
	}
}

// -------------------------------------------------------------------------------- lifecycle

static void reconnect_resumes_polling(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_lpm(&simulator, "20.10"));
	SERIAL_CHECK_TRUE(start_serial_driver(&astromechanics_aux, simulator.port));
	online = true;
	SERIAL_CHECK_TRUE(wait_for_property_state(AUX_WEATHER_PROPERTY_NAME, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(fabs(brightness() - 20.10) < .005);
	disconnect_serial_device(&astromechanics_aux);
	SERIAL_CHECK_TRUE(!context.connected);
	SERIAL_CHECK_TRUE(connect_serial_device(&astromechanics_aux, simulator.port));
	SERIAL_CHECK_TRUE(wait_for_property_state(AUX_WEATHER_PROPERTY_NAME, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(fabs(brightness() - 20.10) < .005);
cleanup:
	if (online) { stop_serial_driver(&astromechanics_aux); }
	stop_external_serial_simulator(&simulator);
}

static void repeated_disconnect_is_tolerated(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_lpm(&simulator, NULL));
	SERIAL_CHECK_TRUE(start_serial_driver(&astromechanics_aux, simulator.port));
	online = true;
	disconnect_serial_device(&astromechanics_aux);
	SERIAL_CHECK_TRUE(!context.connected);
	disconnect_serial_device(&astromechanics_aux);
	SERIAL_CHECK_TRUE(!context.connected);
	online = false;
	tear_down_serial_driver(&astromechanics_aux);
cleanup:
	if (online) { stop_serial_driver(&astromechanics_aux); }
	stop_external_serial_simulator(&simulator);
}

// The LPM protocol has no identity exchange, so astromechanics_open() only opens the port. Once the
// simulator is gone the pseudo terminal goes with it and the open itself has to fail rather than
// report a connected sensor that can never answer.
static void vanished_port_is_refused(void) {
	external_serial_simulator simulator = { 0 };
	SERIAL_CHECK_TRUE(start_lpm(&simulator, NULL));
	SERIAL_CHECK_TRUE(bring_up_serial_driver(&astromechanics_aux));
	stop_external_serial_simulator(&simulator);
	SERIAL_CHECK_TRUE(!connect_serial_device(&astromechanics_aux, simulator.port));
	SERIAL_CHECK_TRUE(!context.connected);
cleanup:
	tear_down_serial_driver(&astromechanics_aux);
}

