// The heater is a percentage on the bus and an 8 bit PWM on the wire, so the value read back is the
// nearest representable duty cycle, not the request.
static void heater_outlet_round_trips_through_pwm(void) {
	static const double requests[] = { 100.0, 50.0, 25.0, 13.0, 0.0 };
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_wbplusv3(&simulator, NULL));
	SERIAL_CHECK_TRUE(start_serial_driver(&wbplusv3_aux, simulator.port));
	online = true;
	SERIAL_CHECK_TRUE(wait_for_first_poll());
	// The percentage is quantised to an 8 bit PWM, so the value read back is the nearest
	// representable duty cycle. Asserting the nearest step rather than a one-step tolerance is what
	// keeps the conversion honest: truncating instead of rounding (DRV-205) lands a step low for
	// every request that does not fall exactly on a step, and this catches it.
	for (int i = 0; i < ARRAY_SIZE(requests); i++) {
		double expected = round(requests[i] * 255.0 / 100.0) / 255.0 * 100.0;
		SERIAL_CHECK_TRUE(set_number(AUX_HEATER_OUTLET_PROPERTY_NAME, AUX_HEATER_OUTLET_1_ITEM_NAME, requests[i]));
		SERIAL_CHECK_TRUE(wait_for_property_state(AUX_HEATER_OUTLET_PROPERTY_NAME, INDIGO_OK_STATE));
		SERIAL_CHECK_TRUE(wait_for_number(AUX_HEATER_OUTLET_PROPERTY_NAME, AUX_HEATER_OUTLET_1_ITEM_NAME, expected, .01));
		printf("Requested %.0f %%, device reports %.2f %% (nearest step %.2f %%)\n", requests[i], number_of(AUX_HEATER_OUTLET_PROPERTY_NAME, AUX_HEATER_OUTLET_1_ITEM_NAME), expected);
	}
	// The extremes are exactly representable and must not drift.
	SERIAL_CHECK_TRUE(set_number(AUX_HEATER_OUTLET_PROPERTY_NAME, AUX_HEATER_OUTLET_1_ITEM_NAME, 100));
	SERIAL_CHECK_TRUE(wait_for_number(AUX_HEATER_OUTLET_PROPERTY_NAME, AUX_HEATER_OUTLET_1_ITEM_NAME, 100, .001));
	SERIAL_CHECK_TRUE(set_number(AUX_HEATER_OUTLET_PROPERTY_NAME, AUX_HEATER_OUTLET_1_ITEM_NAME, 0));
	SERIAL_CHECK_TRUE(wait_for_number(AUX_HEATER_OUTLET_PROPERTY_NAME, AUX_HEATER_OUTLET_1_ITEM_NAME, 0, .001));
cleanup:
	if (online) { stop_serial_driver(&wbplusv3_aux); }
	stop_external_serial_simulator(&simulator);
}

