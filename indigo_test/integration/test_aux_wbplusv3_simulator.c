static void reconnect_resumes_polling(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_wbplusv3(&simulator, NULL));
	SERIAL_CHECK_TRUE(start_serial_driver(&wbplusv3_aux, simulator.port));
	online = true;
	SERIAL_CHECK_TRUE(wait_for_first_poll());
	SERIAL_CHECK_TRUE(set_switch(AUX_USB_PORT_PROPERTY_NAME, AUX_USB_PORT_1_ITEM_NAME, true));
	SERIAL_CHECK_TRUE(wait_for_switch(AUX_USB_PORT_PROPERTY_NAME, AUX_USB_PORT_1_ITEM_NAME, true));
	disconnect_serial_device(&wbplusv3_aux);
	SERIAL_CHECK_TRUE(!context.connected);
	SERIAL_CHECK_TRUE(connect_serial_device(&wbplusv3_aux, simulator.port));
	SERIAL_CHECK_TRUE(wait_for_first_poll());
	// The device kept the port on across the reconnect, and the driver has to report what it finds.
	SERIAL_CHECK_TRUE(wait_for_switch(AUX_USB_PORT_PROPERTY_NAME, AUX_USB_PORT_1_ITEM_NAME, true));
	SERIAL_CHECK_TRUE(!strcmp(info_text(INFO_DEVICE_MODEL_ITEM_NAME), "ZXWBPlusV3"));
cleanup:
	if (online) { stop_serial_driver(&wbplusv3_aux); }
	stop_external_serial_simulator(&simulator);
}

static void repeated_disconnect_is_tolerated(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_wbplusv3(&simulator, NULL));
	SERIAL_CHECK_TRUE(start_serial_driver(&wbplusv3_aux, simulator.port));
	online = true;
	disconnect_serial_device(&wbplusv3_aux);
	SERIAL_CHECK_TRUE(!context.connected);
	disconnect_serial_device(&wbplusv3_aux);
	SERIAL_CHECK_TRUE(!context.connected);
	online = false;
	tear_down_serial_driver(&wbplusv3_aux);
cleanup:
	if (online) { stop_serial_driver(&wbplusv3_aux); }
	stop_external_serial_simulator(&simulator);
}

// The open only succeeds once a status frame identifies the box, so a port with nothing behind it
// has to be refused rather than reported as a connected powerbox.
static void vanished_port_is_refused(void) {
	external_serial_simulator simulator = { 0 };
	SERIAL_CHECK_TRUE(start_wbplusv3(&simulator, NULL));
	SERIAL_CHECK_TRUE(bring_up_serial_driver(&wbplusv3_aux));
	stop_external_serial_simulator(&simulator);
	SERIAL_CHECK_TRUE(!connect_serial_device(&wbplusv3_aux, simulator.port));
	SERIAL_CHECK_TRUE(!context.connected);
cleanup:
	tear_down_serial_driver(&wbplusv3_aux);
}

