static bool start_wbplusv3(external_serial_simulator *simulator, const char * const *arguments) {
	if (arguments == NULL) {
		return start_external_serial_simulator(simulator, AUX_WBPLUSV3_SIMULATOR_EXECUTABLE);
	}
	return start_external_serial_simulator_with_args(simulator, AUX_WBPLUSV3_SIMULATOR_EXECUTABLE, arguments);
}

static double number_of(const char *property_name, const char *item_name) {
	return cached_number_value(property_name, item_name);
}

static const char *info_text(const char *item_name) {
	indigo_item *item = find_cached_item(INFO_PROPERTY_NAME, item_name);
	return item == NULL ? "" : item->text.value;
}

static const char *item_label(const char *property_name, const char *item_name) {
	indigo_item *item = find_cached_item(property_name, item_name);
	return item == NULL ? "" : item->label;
}

// AUX_INFO is defined with zeroed items at attach, so its state says nothing about whether a status
// frame has arrived. The supply voltage is only ever written by a completed poll.
static bool wait_for_first_poll(void) {
	for (int i = 0; i < 500; i++) {
		if (number_of(AUX_INFO_PROPERTY_NAME, AUX_INFO_VOLTAGE_ITEM_NAME) > 0) {
			return true;
		}
		indigo_usleep(10000);
	}
	return false;
}

// A command is only visible once the device has echoed it back in a status frame, and the poll
// refuses to touch a property that is still BUSY, so both conditions have to hold.
static bool wait_for_switch(const char *property_name, const char *item_name, bool value) {
	for (int i = 0; i < 500; i++) {
		indigo_property *property = find_cached_property(property_name);
		indigo_item *item = find_cached_item(property_name, item_name);
		if (property != NULL && property->state != INDIGO_BUSY_STATE && item != NULL && item->sw.value == value) {
			return true;
		}
		indigo_usleep(10000);
	}
	return false;
}

static bool wait_for_number(const char *property_name, const char *item_name, double value, double tolerance) {
	for (int i = 0; i < 500; i++) {
		indigo_property *property = find_cached_property(property_name);
		if (property != NULL && property->state != INDIGO_BUSY_STATE && fabs(number_of(property_name, item_name) - value) <= tolerance) {
			return true;
		}
		indigo_usleep(10000);
	}
	return false;
}

