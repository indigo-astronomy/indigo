// AUX powerbox coverage for indigo_aux_wbplusv3 against the standalone WandererBox Plus V3
// simulator over a real PTY. The device is write-only: it never acknowledges a command, it just
// broadcasts an "A"-separated status frame once a second. Every command therefore has to be
// verified through the next status frame rather than through a reply, which is what most of these
// scenarios do.

