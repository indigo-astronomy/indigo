static void out_of_range_requests_are_clamped_before_they_reach_the_device(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_wbplusv3(&simulator, NULL));
	SERIAL_CHECK_TRUE(start_serial_driver(&wbplusv3_aux, simulator.port));
	online = true;
	SERIAL_CHECK_TRUE(wait_for_first_poll());
	// The bus clamps a number change to the item range before the driver ever sees it, so an
	// over-range request has to arrive at the device as the limit, not as an out-of-range command.
	SERIAL_CHECK_TRUE(set_number(AUX_POWER_OUTLET_VOLTAGE_PROPERTY_NAME, AUX_POWER_OUTLET_VOLTAGE_1_ITEM_NAME, 15.0));
	SERIAL_CHECK_TRUE(wait_for_number(AUX_POWER_OUTLET_VOLTAGE_PROPERTY_NAME, AUX_POWER_OUTLET_VOLTAGE_1_ITEM_NAME, 13.2, .001));
	SERIAL_CHECK_TRUE(set_number(AUX_POWER_OUTLET_VOLTAGE_PROPERTY_NAME, AUX_POWER_OUTLET_VOLTAGE_1_ITEM_NAME, -1.0));
	SERIAL_CHECK_TRUE(wait_for_number(AUX_POWER_OUTLET_VOLTAGE_PROPERTY_NAME, AUX_POWER_OUTLET_VOLTAGE_1_ITEM_NAME, 0, .001));
	SERIAL_CHECK_TRUE(set_number(AUX_HEATER_OUTLET_PROPERTY_NAME, AUX_HEATER_OUTLET_1_ITEM_NAME, 120.0));
	SERIAL_CHECK_TRUE(wait_for_number(AUX_HEATER_OUTLET_PROPERTY_NAME, AUX_HEATER_OUTLET_1_ITEM_NAME, 100, .001));
	SERIAL_CHECK_TRUE(set_number(AUX_HEATER_OUTLET_PROPERTY_NAME, AUX_HEATER_OUTLET_1_ITEM_NAME, -5.0));
	SERIAL_CHECK_TRUE(wait_for_number(AUX_HEATER_OUTLET_PROPERTY_NAME, AUX_HEATER_OUTLET_1_ITEM_NAME, 0, .001));
cleanup:
	if (online) { stop_serial_driver(&wbplusv3_aux); }
	stop_external_serial_simulator(&simulator);
}

