static double distance(double ra1, double dec1, double ra2, double dec2) {
	double d2r = M_PI / 180;
	double sdd = sin((dec2 - dec1) * d2r / 2);
	double sdr = sin((ra2 - ra1) * 15 * d2r / 2);
	double a = sdd * sdd + cos(dec1 * d2r) * cos(dec2 * d2r) * sdr * sdr;
	return 2 * atan2(sqrt(a), sqrt(1 - a)) / d2r;
}

// Runs one Solver Agent process and waits for its end in the expected state
static bool run_process(const char *operation, indigo_property_state expected, double timeout) {
	unsigned busy = state_count(SOLVER, AGENT_START_PROCESS_PROPERTY_NAME, INDIGO_BUSY_STATE);
	REQUIRE(indigo_change_switch_property_1(&observer, SOLVER, AGENT_START_PROCESS_PROPERTY_NAME, operation, true) == INDIGO_OK);
	REQUIRE(WAIT_UNTIL(state_count(SOLVER, AGENT_START_PROCESS_PROPERTY_NAME, INDIGO_BUSY_STATE) > busy, 10));
	if (!WAIT_UNTIL(state(SOLVER, AGENT_START_PROCESS_PROPERTY_NAME) != INDIGO_BUSY_STATE, timeout)) {
		fprintf(stderr, "%s did not finish in %g s\n", operation, timeout);
		dump_messages();
		return false;
	}
	if (state(SOLVER, AGENT_START_PROCESS_PROPERTY_NAME) != (int)expected) {
		fprintf(stderr, "%s finished in state %d, expected %d\n", operation, state(SOLVER, AGENT_START_PROCESS_PROPERTY_NAME), expected);
		dump_messages();
		return false;
	}
	return true;
}

static void print_wcs(const char *label) {
	printf("  %s: WCS RA %.5f h Dec %.4f° angle %.2f° scale %.3f\"/px parity %g index %g° size %.3f x %.3f°\n", label, wcs(AGENT_PLATESOLVER_WCS_RA_ITEM_NAME), wcs(AGENT_PLATESOLVER_WCS_DEC_ITEM_NAME), wcs(AGENT_PLATESOLVER_WCS_ANGLE_ITEM_NAME), wcs(AGENT_PLATESOLVER_WCS_SCALE_ITEM_NAME) * 3600, wcs(AGENT_PLATESOLVER_WCS_PARITY_ITEM_NAME), wcs(AGENT_PLATESOLVER_WCS_INDEX_ITEM_NAME), wcs(AGENT_PLATESOLVER_WCS_WIDTH_ITEM_NAME), wcs(AGENT_PLATESOLVER_WCS_HEIGHT_ITEM_NAME));
}

// The solution matches the given J2000 centre, scale (degrees per unbinned pixel), angle and frame size
static bool solution_matches(double ra, double dec, double scale, double angle, int width, int height, double epoch) {
	print_wcs("solution");
	REQUIRE(state(SOLVER, AGENT_PLATESOLVER_WCS_PROPERTY_NAME) == INDIGO_OK_STATE);
	REQUIRE(wcs(AGENT_PLATESOLVER_WCS_EPOCH_ITEM_NAME) == epoch);
	double error = distance(wcs(AGENT_PLATESOLVER_WCS_RA_ITEM_NAME), wcs(AGENT_PLATESOLVER_WCS_DEC_ITEM_NAME), ra, dec);
	printf("  expected RA %.5f h Dec %.4f° angle %.2f° scale %.3f\"/px, centre error %.1f\"\n", ra, dec, angle, scale * 3600, error * 3600);
	REQUIRE(error < CENTER_TOLERANCE);
	REQUIRE(fabs(wcs(AGENT_PLATESOLVER_WCS_SCALE_ITEM_NAME) / scale - 1) < SCALE_TOLERANCE);
	REQUIRE(fabs(remainder(wcs(AGENT_PLATESOLVER_WCS_ANGLE_ITEM_NAME) - angle, 360)) < ANGLE_TOLERANCE);
	REQUIRE(fabs(wcs(AGENT_PLATESOLVER_WCS_WIDTH_ITEM_NAME) / (width * scale) - 1) < SCALE_TOLERANCE);
	REQUIRE(fabs(wcs(AGENT_PLATESOLVER_WCS_HEIGHT_ITEM_NAME) / (height * scale) - 1) < SCALE_TOLERANCE);
	REQUIRE(wcs(AGENT_PLATESOLVER_WCS_STATE_ITEM_NAME) == INDIGO_SOLVER_STATE_IDLE);
	return true;
}

// Selects an index in AGENT_PLATESOLVER_USE_INDEX; an index missing in the persistent cache is first
// downloaded by the agent through X_AGENT_SOLVER_INDEX, which selects it, an index present there is never downloaded
// again
static bool install_index(const char *name) {
	REQUIRE(WAIT_UNTIL(exists(SOLVER, INDEX_PROPERTY) && exists(SOLVER, AGENT_PLATESOLVER_USE_INDEX_PROPERTY_NAME), 10));
	if (!has_item(SOLVER, AGENT_PLATESOLVER_USE_INDEX_PROPERTY_NAME, name)) {
		printf("  index %s is not in %s/solver, downloading it once\n", name, cache_base);
		REQUIRE(change_switch_and_wait(SOLVER, INDEX_PROPERTY, name, true, INDIGO_OK_STATE, 1800));
		REQUIRE(WAIT_UNTIL(has_item(SOLVER, AGENT_PLATESOLVER_USE_INDEX_PROPERTY_NAME, name), 10));
		// a newly downloaded index is selected for use
		REQUIRE(switch_value(SOLVER, AGENT_PLATESOLVER_USE_INDEX_PROPERTY_NAME, name));
	}
	if (!switch_value(SOLVER, AGENT_PLATESOLVER_USE_INDEX_PROPERTY_NAME, name)) {
		REQUIRE(change_switch_and_wait(SOLVER, AGENT_PLATESOLVER_USE_INDEX_PROPERTY_NAME, name, true, INDIGO_OK_STATE, 10));
	}
	return true;
}

static bool use_only_index(const char *name) {
	const char *other = strcmp(name, INDEX_2) ? INDEX_2 : INDEX_5;
	REQUIRE(change_switch_and_wait(SOLVER, AGENT_PLATESOLVER_USE_INDEX_PROPERTY_NAME, other, false, INDIGO_OK_STATE, 10));
	REQUIRE(switch_value(SOLVER, AGENT_PLATESOLVER_USE_INDEX_PROPERTY_NAME, name));
	return true;
}

static bool set_hints(double epoch, double downsample, double scale) {
	const char *items[] = { AGENT_PLATESOLVER_HINTS_EPOCH_ITEM_NAME, AGENT_PLATESOLVER_HINTS_DOWNSAMPLE_ITEM_NAME, AGENT_PLATESOLVER_HINTS_SCALE_ITEM_NAME, AGENT_PLATESOLVER_HINTS_RADIUS_ITEM_NAME };
	double values[] = { epoch, downsample, scale, 0 };
	return change_numbers(SOLVER, AGENT_PLATESOLVER_HINTS_PROPERTY_NAME, 4, items, values);
}

// Configures the guider simulator for the current combination and tells what it renders
static bool render_combination(const sweep_combination *c) {
	const char *items[] = { "RA", "DEC", "IMAGE_ROTATION_ANGLE", "SIDE_OF_PIER", "IMAGE_WIDTH", "IMAGE_HEIGHT", "MAGNITUDE_LIMIT", "EPOCH", "IMAGE_NOISE_VAR", "IMAGE_GRADIENT", "IMAGE_HOTPIXELS", "IMAGE_HOTCOL", "IMAGE_HOTROW", "PER_ERR_VAL", "ALT_POLAR_ERROR", "AZ_POLAR_ERROR" };
	double values[] = { c->ra, c->dec, c->rotation, c->pier, c->width, c->height, c->magnitude, c->epoch, c->noise, c->gradient, c->hotpixels, c->hotcol, c->hotrow, 0, 0, 0 };
	printf("  rendering RA %.2f h Dec %+.1f° rotation %g° pier %d %d x %d mag %.1f epoch %d noise %g gradient %g hot %d/%d/%d\n", c->ra, c->dec, c->rotation, c->pier, c->width, c->height, c->magnitude, c->epoch, c->noise, c->gradient, c->hotpixels, c->hotcol, c->hotrow);
	REQUIRE(change_numbers(GUIDER_CAMERA, SETUP, (int)ARRAY_SIZE(items), items, values));
	REQUIRE(WAIT_UNTIL(number(GUIDER_CAMERA, CCD_FRAME_PROPERTY_NAME, CCD_FRAME_WIDTH_ITEM_NAME) == c->width && number(GUIDER_CAMERA, CCD_FRAME_PROPERTY_NAME, CCD_FRAME_HEIGHT_ITEM_NAME) == c->height, 10));
	return true;
}

// J2000 centre and the angle the guider simulator renders for a combination. A field rendered in JNow is
// turned against north of J2000 by the precession of the pole, so the angle of the WCS, which refers to
// J2000, is the rendered rotation plus the position angle of JNow north seen from the centre in J2000. The guider
// simulator renders the mirror image of the sky (parity 1), whose astrometry.net orientation is counted in the
// sense of the rendered rotation.
static void rendered_field(const sweep_combination *c, double *ra, double *dec, double *angle) {
	double north_offset = 0;
	*ra = c->ra;
	*dec = c->dec;
	if (c->epoch == 0) {
		double north_ra = c->ra, north_dec = c->dec + 0.1;
		indigo_jnow_to_j2k(ra, dec);
		indigo_jnow_to_j2k(&north_ra, &north_dec);
		float xi, eta;
		if (indigo_radec_to_tangent(*ra * 15 * M_PI / 180, *dec * M_PI / 180, north_ra * 15 * M_PI / 180, north_dec * M_PI / 180, &xi, &eta)) {
			north_offset = atan2(xi, eta) * 180 / M_PI;
		}
	}
	*angle = c->rotation + (c->pier == 1 ? 0 : 180) + north_offset;
}

static bool setup(void) {
	indigo_set_log_level(getenv("INDIGO_TEST_DEBUG") ? INDIGO_LOG_DEBUG : INDIGO_LOG_ERROR);
	REQUIRE(indigo_start() == INDIGO_OK);
	bus_started = true;
	INDIGO_COPY_NAME(observer.name, "Solver simulator observer");
	observer.version = INDIGO_VERSION_CURRENT;
	observer.define_property = defined;
	observer.update_property = updated;
	observer.delete_property = deleted;
	observer.send_message = message_received;
	REQUIRE(indigo_attach_client(&observer) == INDIGO_OK);
	observer_attached = true;
	REQUIRE(indigo_ccd_simulator(INDIGO_DRIVER_INIT, NULL) == INDIGO_OK);
	ccd_started = true;
	REQUIRE(indigo_agent_imager(INDIGO_DRIVER_INIT, NULL) == INDIGO_OK);
	imager_started = true;
	REQUIRE(indigo_agent_guider(INDIGO_DRIVER_INIT, NULL) == INDIGO_OK);
	guider_started = true;
	REQUIRE(indigo_agent_solver(INDIGO_DRIVER_INIT, NULL) == INDIGO_OK);
	solver_started = true;
	if (current_kind == ROSETTA || current_kind == NARROW) {
		REQUIRE(change_switch_and_wait(IMAGER, FILTER_CCD_LIST_PROPERTY_NAME, IMAGER_CAMERA, true, INDIGO_OK_STATE, 20));
		REQUIRE(change_switch_and_wait(IMAGER, CCD_IMAGE_FORMAT_PROPERTY_NAME, CCD_IMAGE_FORMAT_RAW_ITEM_NAME, true, INDIGO_OK_STATE, 10));
		REQUIRE(relate(SOLVER, IMAGER));
	} else if (current_kind == SWEEP || current_kind == SWEEP_FITS || current_kind == SWEEP_HINT) {
		REQUIRE(change_switch_and_wait(IMAGER, FILTER_CCD_LIST_PROPERTY_NAME, GUIDER_CAMERA, true, INDIGO_OK_STATE, 20));
		REQUIRE(change_switch_and_wait(IMAGER, CCD_IMAGE_FORMAT_PROPERTY_NAME, current_kind == SWEEP_FITS ? CCD_IMAGE_FORMAT_FITS_ITEM_NAME : CCD_IMAGE_FORMAT_RAW_ITEM_NAME, true, INDIGO_OK_STATE, 10));
		REQUIRE(relate(SOLVER, IMAGER));
	} else {
		REQUIRE(change_switch_and_wait(GUIDER, FILTER_CCD_LIST_PROPERTY_NAME, GUIDER_CAMERA, true, INDIGO_OK_STATE, 20));
		REQUIRE(relate(SOLVER, GUIDER));
	}
	REQUIRE(install_index(INDEX_2));
	REQUIRE(install_index(INDEX_5));
	REQUIRE(change_number(SOLVER, AGENT_PLATESOLVER_EXPOSURE_SETTINGS_PROPERTY_NAME, AGENT_PLATESOLVER_EXPOSURE_SETTINGS_EXPOSURE_ITEM_NAME, 1));
	REQUIRE(set_hints(2000, 1, 0));
	return true;
}

static void cleanup(void) {
	if (solver_started) {
		indigo_agent_solver(INDIGO_DRIVER_SHUTDOWN, NULL);
	}
	if (guider_started) {
		indigo_agent_guider(INDIGO_DRIVER_SHUTDOWN, NULL);
	}
	if (imager_started) {
		indigo_agent_imager(INDIGO_DRIVER_SHUTDOWN, NULL);
	}
	if (ccd_started) {
		indigo_ccd_simulator(INDIGO_DRIVER_SHUTDOWN, NULL);
	}
	if (observer_attached) {
		indigo_detach_client(&observer);
	}
	if (bus_started) {
		indigo_stop();
	}
}

