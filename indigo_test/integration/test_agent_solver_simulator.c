int main(int argc, char **argv) {
	setvbuf(stdout, NULL, _IONBF, 0);
	const char *filter = argc > 1 ? argv[1] : getenv("INDIGO_TEST_CASE_FILTER");
	int count = (int)ARRAY_SIZE(rosetta_tests) + SWEEP_COUNT;
	indigo_test_case *tests = calloc(count, sizeof(indigo_test_case));
	case_kind *kinds = calloc(count, sizeof(case_kind));
	char (*names)[128] = calloc(count, sizeof(*names));
	for (int i = 0; i < (int)ARRAY_SIZE(rosetta_tests); i++) {
		tests[i] = rosetta_tests[i];
		kinds[i] = strstr(tests[i].name, "index 0.") ? NARROW : ROSETTA;
	}
	for (int i = 0; i < SWEEP_COUNT; i++) {
		sweep_combination c = combination(i);
		bool guider_agent = (i % GUIDER_AGENT_EVERY) == GUIDER_AGENT_EVERY - 1;
		bool fits = !guider_agent && (i % FITS_EVERY) == FITS_EVERY / 2;
		bool hint = !guider_agent && !fits && (i % HINT_EVERY) == HINT_EVERY / 2;
		int n = (int)ARRAY_SIZE(rosetta_tests) + i;
		snprintf(names[n], sizeof(names[n]), "guider %03d RA %.2f h Dec %+.1f rot %g pier %d %dx%d mag %.1f epoch %d noise %g grad %g hot %d/%d/%d%s", i + 1, c.ra, c.dec, c.rotation, c.pier, c.width, c.height, c.magnitude, c.epoch, c.noise, c.gradient, c.hotpixels, c.hotcol, c.hotrow, guider_agent ? " via guider agent" : fits ? " as fits" : hint ? " with hint" : "");
		tests[n].name = names[n];
		tests[n].function = sweep_case;
		kinds[n] = guider_agent ? SWEEP_GUIDER_AGENT : fits ? SWEEP_FITS : hint ? SWEEP_HINT : SWEEP;
	}
	int selected = 0;
	for (int i = 0; i < count; i++) {
		if (filter == NULL || strstr(tests[i].name, filter)) {
			selected++;
		}
	}
	indigo_test_plan(SUITE, selected, filter);
	if (system("command -v curl >/dev/null") != 0) {
		fprintf(stderr, "curl is not installed, the solver agent needs it to download its indexes\n");
		return 1;
	}
	// the persistent index cache of the real home, shared with the user's own solver agent
	static char persistent_cache[PATH_MAX];
	if (getenv("INDIGO_CACHE_BASE") == NULL) {
		const char *home = getenv("HOME");
		if (home == NULL || !*home) {
			fprintf(stderr, "HOME is not set\n");
			return 1;
		}
		snprintf(persistent_cache, sizeof(persistent_cache), "%s/.indigo", home);
		setenv("INDIGO_CACHE_BASE", persistent_cache, 1);
	}
	cache_base = getenv("INDIGO_CACHE_BASE");
	printf("index cache: %s/solver\n", cache_base);
	int result = 0, executed = 0, passed = 0;
	for (int i = 0; i < count; i++) {
		if (filter != NULL && !strstr(tests[i].name, filter)) {
			continue;
		}
		executed++;
		current_kind = kinds[i];
		if (kinds[i] != ROSETTA) {
			current = combination(i - (int)ARRAY_SIZE(rosetta_tests));
		}
		pid_t child = fork();
		if (child == 0) {
			alarm(2400);
			if (!indigo_test_use_private_home()) {
				exit(1);
			}
			bool ready = setup();
			int status = ready ? indigo_run_tests(SUITE, tests + i, 1) : 1;
			cleanup();
			indigo_test_remove_private_home();
			exit(status || indigo_test_failures ? 1 : 0);
		}
		int status = -1;
		if (child < 0 || waitpid(child, &status, 0) != child || !WIFEXITED(status) || WEXITSTATUS(status)) {
			fprintf(stderr, "Failed case: %s (status %d)\n", tests[i].name, status);
			result = 1;
		} else {
			passed++;
		}
	}
	indigo_test_plan_recorded = false;
	printf(SUITE ": %d/%d cases passed (including cleanup)\n", passed, executed);
	free(tests);
	free(kinds);
	free(names);
	return executed ? result : 2;
}
