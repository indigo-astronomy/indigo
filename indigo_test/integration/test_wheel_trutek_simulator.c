// First, intermediate and last slot in both directions, including a single step move, which is the
// shortest path through the "still moving" reply and the completion poll.
static void moves_through_first_intermediate_and_last_slots(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	const char *arguments[] = { "--slots", "8", NULL };
	SERIAL_CHECK_TRUE(start_trutek(&simulator, arguments));
	SERIAL_CHECK_TRUE(start_serial_driver(&trutek_wheel, simulator.port));
	online = true;
	const double slots[] = { 4, 8, 1, 2 };
	for (int i = 0; i < ARRAY_SIZE(slots); i++) {
		SERIAL_CHECK_TRUE(request_slot(slots[i]));
		SERIAL_CHECK_TRUE(wait_for_property_state(WHEEL_SLOT_PROPERTY_NAME, INDIGO_BUSY_STATE));
		SERIAL_CHECK_TRUE(wait_for_property_state(WHEEL_SLOT_PROPERTY_NAME, INDIGO_OK_STATE));
		SERIAL_CHECK_TRUE(wait_for_number_item_value(WHEEL_SLOT_PROPERTY_NAME, WHEEL_SLOT_ITEM_NAME, slots[i], 0.001));
	}
cleanup:
	if (online) { stop_serial_driver(&trutek_wheel); }
	stop_external_serial_simulator(&simulator);
}

