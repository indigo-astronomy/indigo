static void metadata_and_property_completeness(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_trutek(&simulator, NULL));
	SERIAL_CHECK_TRUE(start_serial_driver(&trutek_wheel, simulator.port));
	online = true;
	SERIAL_CHECK_TRUE(context.connected && context.last_connection_state == INDIGO_OK_STATE);
	assert_device_interface(INDIGO_INTERFACE_WHEEL);
	assert_wheel_class_property_completeness();
	assert_property_has_item(WHEEL_SLOT_PROPERTY_NAME, WHEEL_SLOT_ITEM_NAME);
	assert_number_item_in_range(WHEEL_SLOT_PROPERTY_NAME, WHEEL_SLOT_ITEM_NAME);
	indigo_property *slot = find_cached_property(WHEEL_SLOT_PROPERTY_NAME);
	SERIAL_CHECK_TRUE(slot != NULL);
	printf("Slot range %g..%g\n", slot->items[0].number.min, slot->items[0].number.max);
	SERIAL_CHECK_TRUE(fabs(slot->items[0].number.min - 1) < .001);
	// open() reads the wheel's own position, so the initial slot is the device's.
	SERIAL_CHECK_TRUE(wait_for_number_item_value(WHEEL_SLOT_PROPERTY_NAME, WHEEL_SLOT_ITEM_NAME, 1, 0.001));
cleanup:
	if (online) { stop_serial_driver(&trutek_wheel); }
	stop_external_serial_simulator(&simulator);
}

