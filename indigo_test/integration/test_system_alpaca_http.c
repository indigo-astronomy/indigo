static double now_seconds(void) {
	struct timespec now;
	clock_gettime(CLOCK_MONOTONIC, &now);
	return now.tv_sec + now.tv_nsec / 1e9;
}

static void sleep_ms(int ms) {
	struct timespec delay = { ms / 1000, (ms % 1000) * 1000000L };
	nanosleep(&delay, NULL);
}

// ---- scripted loopback HTTP server ----

static bool server_wait_readable(int fd, int timeout) {
	struct pollfd descriptor = { fd, POLLIN, 0 };
	return poll(&descriptor, 1, timeout) > 0;
}

// Under memory pressure (several suites running in parallel) a blocking write() on a macOS loopback socket fails with ENOBUFS, and a large
// write fails that way after part of it was already sent, so it can be neither repeated nor continued. A write of one mbuf cluster either
// goes out completely or not at all, which makes the transient failure safe to retry. Measured: 256 KB writes duplicated data, 2 KB writes never did.
static bool server_send(int fd, const char *data, size_t size) {
	double deadline = now_seconds() + SERVER_IO_TIMEOUT / 1000.0;
	while (size > 0) {
		ssize_t count = write(fd, data, size < SERVER_WRITE_SIZE ? size : SERVER_WRITE_SIZE);
		if (count < 0 && (errno == ENOBUFS || errno == EAGAIN || errno == EINTR) && now_seconds() < deadline) {
			sleep_ms(1);
			continue;
		}
		if (count <= 0) {
			if (errno != EPIPE && errno != ECONNRESET) {
				fprintf(stderr, "test server: write failed (%s)\n", strerror(errno));
			}
			return false;
		}
		data += count;
		size -= (size_t)count;
	}
	return true;
}

static bool server_send_text(int fd, const char *text) {
	return server_send(fd, text, strlen(text));
}

// A complete response with Content-Length that leaves the connection open.
static bool server_reply(int fd, const char *status, const char *content_type, const char *body) {
	char head[512];
	snprintf(head, sizeof(head), "HTTP/1.1 %s\r\nContent-Type: %s\r\nContent-Length: %zu\r\n\r\n", status, content_type, strlen(body));
	return server_send_text(fd, head) && server_send_text(fd, body);
}

// Block until the client closes its end, which every client failure path does, bounded by SERVER_IO_TIMEOUT.
static void server_wait_for_close(int fd) {
	char scratch[256];
	double deadline = now_seconds() + SERVER_IO_TIMEOUT / 1000.0;
	while (now_seconds() < deadline) {
		if (server_wait_readable(fd, 100) && read(fd, scratch, sizeof(scratch)) <= 0) {
			break;
		}
	}
}

// Make the close that follows send a TCP reset instead of an orderly end of file.
static void server_reset_on_close(int fd) {
	struct linger linger = { 1, 0 };
	setsockopt(fd, SOL_SOCKET, SO_LINGER, &linger, sizeof(linger));
}

// Read one request (head and Content-Length body) and record it. False if the client closed the connection or sent nothing in time.
static bool server_read_request(http_server *server, int fd, int index, recorded_request *request) {
	char buffer[SERVER_HEAD_SIZE + SERVER_BODY_SIZE];
	size_t size = 0;
	char *end = NULL;
	memset(request, 0, sizeof(recorded_request));
	request->connection = index;
	while (end == NULL) {
		if (size >= sizeof(buffer) - 1 || !server_wait_readable(fd, SERVER_IO_TIMEOUT)) {
			return false;
		}
		ssize_t count = read(fd, buffer + size, sizeof(buffer) - 1 - size);
		if (count <= 0) {
			return false;
		}
		size += (size_t)count;
		buffer[size] = 0;
		end = strstr(buffer, "\r\n\r\n");
	}
	size_t head_size = (size_t)(end - buffer) + 4;
	if (head_size >= SERVER_HEAD_SIZE) {
		return false;
	}
	memcpy(request->head, buffer, head_size);
	const char *length = strstr(request->head, "Content-Length: ");
	size_t body_size = length != NULL ? strtoul(length + 16, NULL, 10) : 0;
	if (body_size >= SERVER_BODY_SIZE) {
		return false;
	}
	request->body_size = size - head_size;
	memcpy(request->body, buffer + head_size, request->body_size);
	while (request->body_size < body_size) {
		if (!server_wait_readable(fd, SERVER_IO_TIMEOUT)) {
			return false;
		}
		ssize_t count = read(fd, request->body + request->body_size, body_size - request->body_size);
		if (count <= 0) {
			return false;
		}
		request->body_size += (size_t)count;
	}
	pthread_mutex_lock(&server->mutex);
	if (server->request_count < SERVER_MAX_REQUESTS) {
		server->requests[server->request_count] = *request;
	}
	server->request_count++;
	pthread_mutex_unlock(&server->mutex);
	return true;
}

static void *server_worker_thread(void *data) {
	server_worker *worker = (server_worker *)data;
	http_server *server = worker->server;
	server->script(server, worker->fd, worker->index);
	pthread_mutex_lock(&server->mutex);
	close(worker->fd);
	worker->fd = -1;
	server->finished++;
	pthread_mutex_unlock(&server->mutex);
	return NULL;
}

static void *server_acceptor_thread(void *data) {
	http_server *server = (http_server *)data;
	while (true) {
		pthread_mutex_lock(&server->mutex);
		bool stop = server->stopping || server->connections == SERVER_MAX_CONNECTIONS;
		pthread_mutex_unlock(&server->mutex);
		if (stop) {
			break;
		}
		if (!server_wait_readable(server->listener, 20)) {
			continue;
		}
		int fd = accept(server->listener, NULL, NULL);
		if (fd < 0) {
			continue;
		}
		int enabled = 1;
		setsockopt(fd, IPPROTO_TCP, TCP_NODELAY, &enabled, sizeof(enabled));
		pthread_mutex_lock(&server->mutex);
		server_worker *worker = server->workers + server->connections;
		worker->server = server;
		worker->fd = fd;
		worker->index = server->connections;
		if (pthread_create(&worker->thread, NULL, server_worker_thread, worker) == 0) {
			server->connections++;
		} else {
			close(fd);
		}
		pthread_mutex_unlock(&server->mutex);
	}
	return NULL;
}

static int open_listener(int family, int backlog, int *port) {
	struct sockaddr_storage storage = { 0 };
	socklen_t length = family == AF_INET6 ? sizeof(struct sockaddr_in6) : sizeof(struct sockaddr_in);
	if (family == AF_INET6) {
		struct sockaddr_in6 *address = (struct sockaddr_in6 *)&storage;
		address->sin6_family = AF_INET6;
		address->sin6_addr = in6addr_loopback;
	} else {
		struct sockaddr_in *address = (struct sockaddr_in *)&storage;
		address->sin_family = AF_INET;
		address->sin_addr.s_addr = htonl(INADDR_LOOPBACK);
	}
	int fd = socket(family, SOCK_STREAM, 0);
	if (fd < 0 || bind(fd, (struct sockaddr *)&storage, length) < 0 || listen(fd, backlog) < 0 || getsockname(fd, (struct sockaddr *)&storage, &length) < 0) {
		if (fd >= 0) {
			close(fd);
		}
		return -1;
	}
	*port = ntohs(family == AF_INET6 ? ((struct sockaddr_in6 *)&storage)->sin6_port : ((struct sockaddr_in *)&storage)->sin_port);
	return fd;
}

static bool server_start(http_server *server, int family, server_script script, void *context) {
	memset(server, 0, sizeof(http_server));
	server->script = script;
	server->context = context;
	server->listener = open_listener(family, SERVER_MAX_CONNECTIONS, &server->port);
	if (server->listener < 0) {
		return false;
	}
	pthread_mutex_init(&server->mutex, NULL);
	if (pthread_create(&server->acceptor, NULL, server_acceptor_thread, server) != 0) {
		close(server->listener);
		pthread_mutex_destroy(&server->mutex);
		return false;
	}
	return true;
}

static void server_stop(http_server *server) {
	pthread_mutex_lock(&server->mutex);
	server->stopping = true;
	pthread_mutex_unlock(&server->mutex);
	pthread_join(server->acceptor, NULL);
	// wake up every script that is still blocked on its socket
	pthread_mutex_lock(&server->mutex);
	int connections = server->connections;
	for (int i = 0; i < connections; i++) {
		if (server->workers[i].fd >= 0) {
			shutdown(server->workers[i].fd, SHUT_RDWR);
		}
	}
	pthread_mutex_unlock(&server->mutex);
	for (int i = 0; i < connections; i++) {
		pthread_join(server->workers[i].thread, NULL);
	}
	close(server->listener);
	pthread_mutex_destroy(&server->mutex);
}

static int server_connections(http_server *server) {
	pthread_mutex_lock(&server->mutex);
	int result = server->connections;
	pthread_mutex_unlock(&server->mutex);
	return result;
}

static int server_request_count(http_server *server) {
	pthread_mutex_lock(&server->mutex);
	int result = server->request_count;
	pthread_mutex_unlock(&server->mutex);
	return result;
}

// A recorded request is written once, before the server answers it, so it is stable by the time the client call returned.
static const recorded_request *server_request(http_server *server, int index) {
	static const recorded_request none = { .connection = -1 };
	pthread_mutex_lock(&server->mutex);
	const recorded_request *result = index >= 0 && index < server->request_count && index < SERVER_MAX_REQUESTS ? server->requests + index : &none;
	pthread_mutex_unlock(&server->mutex);
	return result;
}

// Wait until the scripts of 'count' connections returned and their sockets are closed.
static bool server_wait_finished(http_server *server, int count) {
	double deadline = now_seconds() + 2;
	while (now_seconds() < deadline) {
		pthread_mutex_lock(&server->mutex);
		bool finished = server->finished >= count;
		pthread_mutex_unlock(&server->mutex);
		if (finished) {
			return true;
		}
		sleep_ms(1);
	}
	return false;
}

// ---- scripts ----

// Serve every request of every connection with a small JSON document and keep the connection open.
static void script_keep_alive(http_server *server, int fd, int index) {
	recorded_request request;
	while (server_read_request(server, fd, index, &request)) {
		if (!server_reply(fd, "200 OK", "application/json", "{\"Value\":1}")) {
			break;
		}
	}
}

// Answer with the request target, so a client can tell its own response from somebody else's.
static void script_echo(http_server *server, int fd, int index) {
	recorded_request request;
	while (server_read_request(server, fd, index, &request)) {
		char *target = strchr(request.head, ' ');
		char *end = target != NULL ? strchr(target + 1, ' ') : NULL;
		if (end == NULL) {
			break;
		}
		*end = 0;
		if (!server_reply(fd, "200 OK", "text/plain", target + 1)) {
			break;
		}
	}
}

// The context is an array of raw responses: the connection with index n reads one request, sends raw response n and closes.
static void script_raw(http_server *server, int fd, int index) {
	const char **replies = (const char **)server->context;
	recorded_request request;
	if (server_read_request(server, fd, index, &request)) {
		server_send_text(fd, replies[index]);
	}
}

// The context is one raw response that is sent one byte at a time for every request of the connection.
static void script_trickle(http_server *server, int fd, int index) {
	const char *reply = (const char *)server->context;
	recorded_request request;
	while (server_read_request(server, fd, index, &request)) {
		for (const char *byte = reply; *byte; byte++) {
			if (!server_send(fd, byte, 1)) {
				return;
			}
			usleep(300);
		}
	}
}

// The context is a raw prefix (possibly empty) that is sent before the server goes silent until the client gives up.
static void script_stall(http_server *server, int fd, int index) {
	recorded_request request;
	if (server_read_request(server, fd, index, &request)) {
		server_send_text(fd, (const char *)server->context);
		server_wait_for_close(fd);
	}
}

// A body that never stalls and never ends: one byte every 50 ms until the client gives up.
static void script_drip(http_server *server, int fd, int index) {
	recorded_request request;
	if (server_read_request(server, fd, index, &request)) {
		double deadline = now_seconds() + SERVER_IO_TIMEOUT / 1000.0;
		server_send_text(fd, "HTTP/1.1 200 OK\r\nContent-Length: 1000000\r\n\r\n");
		while (now_seconds() < deadline && server_send(fd, "x", 1) && !server_wait_readable(fd, 50)) {
		}
	}
}

// The context is a raw prefix (possibly empty) that is sent before the connection is reset.
static void script_reset(http_server *server, int fd, int index) {
	recorded_request request;
	if (server_read_request(server, fd, index, &request)) {
		server_send_text(fd, (const char *)server->context);
		server_reset_on_close(fd);
	}
}

typedef enum {
	STALE_CLOSE_IDLE,						// connection 0 is closed right after its first response
	STALE_CLOSE_ON_REQUEST,			// connection 0 reads the second request and closes without a response
	STALE_PARTIAL_ON_REQUEST,		// connection 0 answers the second request with half a header block and closes
	STALE_TWICE									// as STALE_CLOSE_ON_REQUEST, and connection 1 also closes without a response
} stale_mode;

// Connection 0 serves one request and then misbehaves as the mode says; later connections are well behaved.
static void script_stale(http_server *server, int fd, int index) {
	stale_mode mode = *(stale_mode *)server->context;
	recorded_request request;
	if (index > 0) {
		if (mode == STALE_TWICE) {
			server_read_request(server, fd, index, &request);
		} else {
			script_keep_alive(server, fd, index);
		}
		return;
	}
	if (!server_read_request(server, fd, index, &request) || !server_reply(fd, "200 OK", "application/json", "{\"Value\":1}") || mode == STALE_CLOSE_IDLE) {
		return;
	}
	if (server_read_request(server, fd, index, &request) && mode == STALE_PARTIAL_ON_REQUEST) {
		server_send_text(fd, "HTTP/1.1 200 OK\r\nContent-Le");
	}
}

typedef enum {
	LARGE_CONTENT_LENGTH,
	LARGE_CHUNKED,
	LARGE_TO_EOF
} large_mode;

typedef struct {
	const char *data;
	size_t size;
	large_mode mode;
} large_body;

static void script_large(http_server *server, int fd, int index) {
	large_body *large = (large_body *)server->context;
	recorded_request request;
	char head[256];
	if (!server_read_request(server, fd, index, &request)) {
		return;
	}
	if (large->mode == LARGE_CONTENT_LENGTH) {
		snprintf(head, sizeof(head), "HTTP/1.1 200 OK\r\nContent-Type: application/imagebytes\r\nContent-Length: %zu\r\n\r\n", large->size);
		if (server_send_text(fd, head) && server_send(fd, large->data, large->size)) {
			server_wait_for_close(fd);
		}
	} else if (large->mode == LARGE_CHUNKED) {
		bool ok = server_send_text(fd, "HTTP/1.1 200 OK\r\nContent-Type: application/imagebytes\r\nTransfer-Encoding: chunked\r\n\r\n");
		for (size_t offset = 0; ok && offset < large->size; offset += 65521) {
			size_t chunk = large->size - offset < 65521 ? large->size - offset : 65521;
			snprintf(head, sizeof(head), "%zx;offset=%zu\r\n", chunk, offset);
			ok = server_send_text(fd, head) && server_send(fd, large->data + offset, chunk) && server_send_text(fd, "\r\n");
		}
		if (ok && server_send_text(fd, "0\r\n\r\n")) {
			server_wait_for_close(fd);
		}
	} else {
		if (server_send_text(fd, "HTTP/1.1 200 OK\r\nContent-Type: application/imagebytes\r\nConnection: close\r\n\r\n")) {
			server_send(fd, large->data, large->size);
		}
	}
}

