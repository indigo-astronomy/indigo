static void buffer_limits(void) {
	alpaca_http_buffer buffer;
	alpaca_http_buffer_init(&buffer, 10);
	ASSERT_TRUE(alpaca_http_buffer_append(&buffer, "01234", 5));
	ASSERT_FALSE(alpaca_http_buffer_append(&buffer, "567890", 6));
	ASSERT_STREQ("01234", buffer.data);
	ASSERT_TRUE(alpaca_http_buffer_append(&buffer, "56789", 5));
	ASSERT_STREQ("0123456789", buffer.data);
	ASSERT_EQ_INT(10, (int)buffer.size);
	ASSERT_EQ_INT(11, (int)buffer.capacity);
	ASSERT_FALSE(alpaca_http_buffer_append(&buffer, "x", 1));
	ASSERT_TRUE(alpaca_http_buffer_append(&buffer, "", 0));
	ASSERT_FALSE(alpaca_http_buffer_reserve(&buffer, 11));
	ASSERT_TRUE(alpaca_http_buffer_reserve(&buffer, 10));
	alpaca_http_buffer_clear(&buffer);
	ASSERT_TRUE(alpaca_http_form_add_string(&buffer, "A", "1"));
	ASSERT_FALSE(alpaca_http_form_add_string(&buffer, "Name", "too long"));
	ASSERT_STREQ("A=1", buffer.data);
	ASSERT_EQ_INT(3, (int)buffer.size);
	ASSERT_FALSE(alpaca_http_buffer_append_encoded(&buffer, "    "));
	ASSERT_STREQ("A=1", buffer.data);
	ASSERT_TRUE(alpaca_http_buffer_append_encoded(&buffer, "  x"));
	ASSERT_STREQ("A=1%20%20x", buffer.data);
	alpaca_http_buffer_free(&buffer);
	alpaca_http_buffer_init(&buffer, 0);
	ASSERT_FALSE(alpaca_http_buffer_append(&buffer, "x", 1));
	ASSERT_TRUE(alpaca_http_buffer_append(&buffer, "", 0));
	ASSERT_STREQ("", buffer.data);
	alpaca_http_buffer_free(&buffer);
	alpaca_http_buffer_init(&buffer, SIZE_MAX);
	ASSERT_TRUE(alpaca_http_buffer_append(&buffer, "x", 1));
	ASSERT_FALSE(alpaca_http_buffer_reserve(&buffer, SIZE_MAX));
	alpaca_http_buffer_free(&buffer);
	// growth is geometric: appending one byte at a time must not reallocate every time
	alpaca_http_buffer_init(&buffer, 1 << 20);
	int allocations = 0;
	size_t capacity = 0;
	for (int i = 0; i < (1 << 20); i++) {
		alpaca_http_buffer_append(&buffer, "x", 1);
		if (buffer.capacity != capacity) {
			capacity = buffer.capacity;
			allocations++;
		}
	}
	size_t size = buffer.size;
	alpaca_http_buffer_free(&buffer);
	ASSERT_EQ_INT(1 << 20, (int)size);
	ASSERT_TRUE(allocations <= 14);
}

static bool check_double(double value, const char *expected) {
	char text[ALPACA_HTTP_DOUBLE_SIZE];
	if (!alpaca_http_format_double(text, sizeof(text), value)) {
		fprintf(stderr, "%.17g was not formatted\n", value);
		return false;
	}
	if (expected != NULL && strcmp(text, expected) != 0) {
		fprintf(stderr, "%.17g: expected \"%s\", got \"%s\"\n", value, expected, text);
		return false;
	}
	if (strspn(text, "0123456789.-+e") != strlen(text)) {
		fprintf(stderr, "%.17g: unexpected characters in \"%s\"\n", value, text);
		return false;
	}
	// read it back without the locale: the text must be the exact value
	char *saved = setlocale(LC_NUMERIC, NULL);
	char locale[64];
	snprintf(locale, sizeof(locale), "%s", saved != NULL ? saved : "C");
	setlocale(LC_NUMERIC, "C");
	double parsed = strtod(text, NULL);
	setlocale(LC_NUMERIC, locale);
	if (parsed != value) {
		fprintf(stderr, "%.17g: \"%s\" reads back as %.17g\n", value, text, parsed);
		return false;
	}
	return true;
}

static bool check_doubles(void) {
	bool ok = check_double(1.5, "1.5") && check_double(0, "0") && check_double(-12.25, "-12.25") && check_double(0.1, "0.1") && check_double(100, "100") && check_double(1234567.875, "1234567.875");
	ok = ok && check_double(1e-5, "1e-05") && check_double(1e21, "1e+21") && check_double(15.041068640261905, "15.041068640261905") && check_double(0.1 + 0.2, "0.30000000000000004") && check_double(-0.0041780746, "-0.0041780746");
	ok = ok && check_double(1.0 / 3.0, NULL) && check_double(M_PI, NULL) && check_double(1.7976931348623157e308, NULL) && check_double(-1.7976931348623157e308, NULL) && check_double(2.2250738585072014e-308, NULL) && check_double(4.9406564584124654e-324, NULL) && check_double(123456789012345678.0, NULL);
	uint64_t state = 0x2545F4914F6CDD1DULL;
	for (int i = 0; ok && i < 20000; i++) {
		state ^= state << 13;
		state ^= state >> 7;
		state ^= state << 17;
		double value;
		memcpy(&value, &state, sizeof(value));
		if (isfinite(value)) {
			ok = check_double(value, NULL);
		}
	}
	return ok;
}

static void double_formatting(void) {
	char text[ALPACA_HTTP_DOUBLE_SIZE];
	ASSERT_TRUE(check_doubles());
	ASSERT_FALSE(alpaca_http_format_double(text, sizeof(text), NAN));
	ASSERT_FALSE(alpaca_http_format_double(text, sizeof(text), INFINITY));
	ASSERT_FALSE(alpaca_http_format_double(text, sizeof(text), -INFINITY));
	ASSERT_FALSE(alpaca_http_format_double(text, ALPACA_HTTP_DOUBLE_SIZE - 1, 1.5));
	ASSERT_FALSE(alpaca_http_format_double(NULL, ALPACA_HTTP_DOUBLE_SIZE, 1.5));
}

// The decimal separator of the process locale must never reach the wire: Alpaca numbers are invariant.
static void double_formatting_ignores_locale(void) {
	const char *locales[] = { "de_DE.UTF-8", "de_DE", "cs_CZ.UTF-8", "sk_SK.UTF-8", "fr_FR.UTF-8" };
	char printed[32];
	const char *selected = NULL;
	for (int i = 0; selected == NULL && i < ARRAY_SIZE(locales); i++) {
		if (setlocale(LC_NUMERIC, locales[i]) != NULL) {
			selected = locales[i];
		}
	}
	if (selected == NULL) {
		printf("    SKIPPED double_formatting_ignores_locale: no locale with a decimal comma is installed\n");
		return;
	}
	snprintf(printed, sizeof(printed), "%g", 1.5);
	alpaca_http_buffer form;
	alpaca_http_buffer_init(&form, 256);
	bool added = alpaca_http_form_add_double(&form, "Duration", 1.5) && alpaca_http_form_add_double(&form, "Rate", -0.0041780746) && alpaca_http_form_add_double(&form, "Value", 1234567.875);
	char text[128];
	snprintf(text, sizeof(text), "%s", form.data != NULL ? form.data : "");
	alpaca_http_buffer_free(&form);
	bool doubles = check_doubles();
	setlocale(LC_NUMERIC, "C");
	printf("    locale %s prints 1.5 as \"%s\"\n", selected, printed);
	ASSERT_STREQ("1,5", printed);
	ASSERT_TRUE(added);
	ASSERT_STREQ("Duration=1.5&Rate=-0.0041780746&Value=1234567.875", text);
	ASSERT_TRUE(doubles);
}

