// Timeouts that keep a broken case from hanging and are far above anything a loopback exchange needs.
static alpaca_http_options bounded_options(void) {
	alpaca_http_options options = { 0 };
	options.timeouts.connect = 2000;
	options.timeouts.first_byte = 3000;
	options.timeouts.inter_byte = 3000;
	options.timeouts.total = 10000;
	return options;
}

