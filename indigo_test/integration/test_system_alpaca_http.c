// Tests of the HTTP/1.1 client of the system_alpaca driver (indigo_system_alpaca_http.c) against a scripted
// HTTP server that runs on a thread of this process and listens on an ephemeral loopback port. Every case
// installs its own script, which decides the exact bytes and the timing of what the server sends.
// The suite opens loopback sockets, so it is an opt-in driver test and not part of test-integration.
//
// ALPACA_HTTP_TEST_TRACE=1 switches the INDIGO log to trace level.
// ALPACA_HTTP_TEST_BLACKHOLE=<address> names a host that silently drops TCP SYN packets (e.g. 192.0.2.1 on
// most networks) and enables the connect timeout case on systems where it cannot be produced on loopback.

