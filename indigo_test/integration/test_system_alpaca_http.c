// ---- concurrency ----

#define CLIENT_THREADS	4
#define CLIENT_REQUESTS	50

typedef struct {
	pthread_t thread;
	int port;
	int id;
	int failures;
	unsigned connects;
} client_thread;

static void *client_thread_main(void *data) {
	client_thread *client = (client_thread *)data;
	alpaca_http_connection *connection = alpaca_http_connection_create("127.0.0.1", client->port);
	alpaca_http_response response;
	alpaca_http_options options = bounded_options();
	alpaca_http_buffer query;
	char path[64];
	char expected[128];
	alpaca_http_response_init(&response, DEFAULT_MAX_BODY);
	alpaca_http_buffer_init(&query, 256);
	snprintf(path, sizeof(path), "/api/v1/telescope/%d/tracking", client->id);
	for (int i = 0; i < CLIENT_REQUESTS; i++) {
		alpaca_http_buffer_clear(&query);
		alpaca_http_form_add_int(&query, "ClientID", client->id);
		alpaca_http_form_add_int(&query, "ClientTransactionID", i + 1);
		snprintf(expected, sizeof(expected), "%s?ClientID=%d&ClientTransactionID=%d", path, client->id, i + 1);
		alpaca_http_result result = alpaca_http_get(connection, path, query.data, &options, &response);
		if (result != ALPACA_HTTP_OK || response.status != 200 || strcmp(response.body.data, expected) != 0) {
			client->failures++;
		}
	}
	client->connects = alpaca_http_connection_connects(connection);
	alpaca_http_buffer_free(&query);
	alpaca_http_response_free(&response);
	alpaca_http_connection_free(connection);
	return NULL;
}

// Several connection objects to the same server, each used by its own thread, never see each other's responses.
static void connections_are_independent_across_threads(void) {
	static http_server server;
	client_thread clients[CLIENT_THREADS] = { 0 };
	ASSERT_TRUE(server_start(&server, AF_INET, script_echo, NULL));
	int started = 0;
	for (int i = 0; i < CLIENT_THREADS; i++) {
		clients[i].port = server.port;
		clients[i].id = i;
		if (pthread_create(&clients[i].thread, NULL, client_thread_main, clients + i) != 0) {
			break;
		}
		started++;
	}
	for (int i = 0; i < started; i++) {
		pthread_join(clients[i].thread, NULL);
	}
	int connections = server_connections(&server);
	int requests = server_request_count(&server);
	server_stop(&server);
	ASSERT_EQ_INT(CLIENT_THREADS, started);
	for (int i = 0; i < CLIENT_THREADS; i++) {
		ASSERT_EQ_INT(0, clients[i].failures);
		ASSERT_EQ_INT(1, (int)clients[i].connects);
	}
	ASSERT_EQ_INT(CLIENT_THREADS, connections);
	ASSERT_EQ_INT(CLIENT_THREADS * CLIENT_REQUESTS, requests);
}

