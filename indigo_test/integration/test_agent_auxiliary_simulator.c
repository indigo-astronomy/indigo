static bool start(bool with_standin) {
	reset_simulator_context(&agent);
	atomic_store(&weather_disconnected, true);
	pthread_mutex_lock(&message_mutex);
	*safety_message = 0;
	safety_message_count = 0;
	pthread_mutex_unlock(&message_mutex);
	if (indigo_start() != INDIGO_OK || indigo_attach_client(&simulator_test_client) != INDIGO_OK) {
		return false;
	}
	if (indigo_aux_simulator(INDIGO_DRIVER_INIT, NULL) != INDIGO_OK) {
		return false;
	}
	if (with_standin) {
		standin_safety = indigo_init_light_property(NULL, STANDIN_NAME, AUX_WEATHER_SAFETY_PROPERTY_NAME, "Main", "Weather safety", INDIGO_OK_STATE, 5);
		indigo_init_light_item(standin_safety->items + 0, AUX_WEATHER_SAFETY_SAFE_ITEM_NAME, "Safe", INDIGO_OK_STATE);
		indigo_init_light_item(standin_safety->items + 1, AUX_WEATHER_SAFETY_CLOUDS_ITEM_NAME, "Clouds", INDIGO_IDLE_STATE);
		indigo_init_light_item(standin_safety->items + 2, AUX_WEATHER_SAFETY_RAIN_ITEM_NAME, "Rain", INDIGO_OK_STATE);
		indigo_init_light_item(standin_safety->items + 3, AUX_WEATHER_SAFETY_WIND_ITEM_NAME, "Wind", INDIGO_IDLE_STATE);
		indigo_init_light_item(standin_safety->items + 4, AUX_WEATHER_SAFETY_HUMIDITY_ITEM_NAME, "Humidity", INDIGO_IDLE_STATE);
		if (indigo_attach_device(&standin) != INDIGO_OK) {
			return false;
		}
	}
	return indigo_agent_auxiliary(INDIGO_DRIVER_INIT, NULL) == INDIGO_OK;
}

static void stop(bool with_standin) {
	const char *lists[] = { FILTER_AUX_1_LIST_PROPERTY_NAME, FILTER_AUX_2_LIST_PROPERTY_NAME };
	for (int i = 0; i < ARRAY_SIZE(lists); i++) {
		indigo_change_switch_property_1(&simulator_test_client, AUX_AGENT_NAME, lists[i], FILTER_DEVICE_LIST_NONE_ITEM_NAME, true);
		wait_for_property_state(lists[i], INDIGO_OK_STATE);
	}
	indigo_agent_auxiliary(INDIGO_DRIVER_SHUTDOWN, NULL);
	indigo_change_switch_property_1(&simulator_test_client, WEATHER_NAME, CONNECTION_PROPERTY_NAME, CONNECTION_DISCONNECTED_ITEM_NAME, true);
	for (int i = 0; i < 50 && indigo_aux_simulator(INDIGO_DRIVER_SHUTDOWN, NULL) == INDIGO_BUSY; i++) {
		indigo_usleep(100000);
	}
	if (with_standin) {
		indigo_detach_device(&standin);
		indigo_release_property(standin_safety);
		standin_safety = NULL;
	}
	indigo_detach_client(&simulator_test_client);
	indigo_stop();
	release_cached_properties();
}

// Selects the device in the agent's list and waits until the selection is complete.
static bool select_source(const char *list, const char *name) {
	unsigned revision = property_revision(list);
	if (indigo_change_switch_property_1(&simulator_test_client, AUX_AGENT_NAME, list, name, true) != INDIGO_OK) {
		return false;
	}
	return wait_for_property_state_after(list, INDIGO_OK_STATE, revision);
}

static bool change_weather_number(const char *property, const char *item, double value) {
	return indigo_change_number_property_1(&simulator_test_client, WEATHER_NAME, property, item, value) == INDIGO_OK;
}

