static indigo_property *standin_safety;

static indigo_result standin_enumerate(indigo_device *device, indigo_client *client, indigo_property *property) {
	if (IS_CONNECTED && indigo_property_match(standin_safety, property)) {
		indigo_define_property(device, standin_safety, NULL);
	}
	return indigo_device_enumerate_properties(device, client, property);
}

static indigo_result standin_attach(indigo_device *device) {
	indigo_result result = indigo_device_attach(device, "agent_auxiliary_test_standin", 1, INDIGO_INTERFACE_AUX_WEATHER);
	indigo_device_enumerate_properties(device, NULL, NULL);
	return result;
}

static indigo_result standin_change(indigo_device *device, indigo_client *client, indigo_property *property) {
	if (indigo_property_match(CONNECTION_PROPERTY, property)) {
		indigo_property_copy_values(CONNECTION_PROPERTY, property, false);
		CONNECTION_PROPERTY->state = INDIGO_OK_STATE;
		if (IS_CONNECTED) {
			indigo_define_property(device, standin_safety, NULL);
		} else {
			indigo_delete_property(device, standin_safety, NULL);
		}
		indigo_update_property(device, CONNECTION_PROPERTY, NULL);
		return INDIGO_OK;
	}
	return indigo_device_change_property(device, client, property);
}

static indigo_result standin_detach(indigo_device *device) {
	indigo_delete_property(device, NULL, NULL);
	return indigo_device_detach(device);
}

static indigo_device standin = INDIGO_DEVICE_INITIALIZER(STANDIN_NAME, standin_attach, standin_enumerate, standin_change, NULL, standin_detach);

// Publishes the SAFE light and the RAIN light of the stand-in, with the reason as a weather driver does, or without a message for a NULL reason.
static void standin_set(indigo_property_state rain, const char *reason) {
	indigo_get_item(standin_safety, AUX_WEATHER_SAFETY_SAFE_ITEM_NAME)->light.value = rain;
	indigo_get_item(standin_safety, AUX_WEATHER_SAFETY_RAIN_ITEM_NAME)->light.value = rain;
	if (reason != NULL) {
		indigo_update_property(&standin, standin_safety, "%s", reason);
	} else {
		indigo_update_property(&standin, standin_safety, NULL);
	}
}

