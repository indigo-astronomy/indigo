// Auxiliary Agent integration tests with the Weather Station Simulator of aux_simulator as the AUX_WEATHER_SAFETY source:
// AGENT_AUX_SAFETY follows the selected source, passes on its reason with the device name appended, reports a lost source
// and combines several sources worst-wins. The second source is a minimal weather device of this test.

#include <pthread.h>
#include <unistd.h>

#include <indigo/indigo_driver.h>
#include <indigo_drivers/aux_simulator/indigo_aux_simulator.h>
