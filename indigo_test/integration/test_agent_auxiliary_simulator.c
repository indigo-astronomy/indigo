// Like ASSERT_*, but the case continues at its cleanup label, so a failure does not leave the bus running.
#define CHECK_TRUE(condition) do { \
	if (!(condition)) { \
		fprintf(stderr, "%s:%d: assertion failed: %s\n", __FILE__, __LINE__, #condition); \
		indigo_test_failures++; \
		goto cleanup; \
	} \
} while (0)

#define CHECK_EQ_INT(expected, actual) CHECK_TRUE((expected) == (actual))

#define WEATHER_NAME	"Weather Station Simulator"
#define STANDIN_NAME	"Weather Stand-in"

static const simulator_driver_case agent = { .label = AUX_AGENT_NAME, .driver_name = "indigo_agent_auxiliary", .device_name = AUX_AGENT_NAME, .entry = indigo_agent_auxiliary };

static pthread_mutex_t message_mutex = PTHREAD_MUTEX_INITIALIZER;
static char safety_message[INDIGO_VALUE_SIZE];
static int safety_message_count;

// Records the messages of AGENT_AUX_SAFETY; the bus delivers an update message right after the update itself.
static indigo_result recording_send_message(indigo_client *client, indigo_device *device, indigo_property *property, const char *message) {
	if (property != NULL && !strcmp(property->device, AUX_AGENT_NAME) && !strcmp(property->name, AGENT_AUX_SAFETY_PROPERTY_NAME) && message != NULL && *message) {
		pthread_mutex_lock(&message_mutex);
		INDIGO_COPY_VALUE(safety_message, message);
		safety_message_count++;
		pthread_mutex_unlock(&message_mutex);
	}
	return simulator_client_send_message(client, device, property, message);
}

static atomic_bool weather_disconnected;

// Tracks the connection of the Weather Station Simulator, which the agent connects and disconnects.
static indigo_result tracking_update_property(indigo_client *client, indigo_device *device, indigo_property *property, const char *message) {
	if (!strcmp(property->device, WEATHER_NAME) && !strcmp(property->name, CONNECTION_PROPERTY_NAME)) {
		indigo_item *item = indigo_get_item(property, CONNECTION_DISCONNECTED_ITEM_NAME);
		atomic_store(&weather_disconnected, property->state == INDIGO_OK_STATE && item != NULL && item->sw.value);
	}
	return simulator_client_update_property(client, device, property, message);
}

static bool wait_for_weather_disconnected(void) {
	for (int i = 0; i < 100 && !atomic_load(&weather_disconnected); i++) {
		indigo_usleep(50000);
	}
	return atomic_load(&weather_disconnected);
}

static int message_count(void) {
	pthread_mutex_lock(&message_mutex);
	int count = safety_message_count;
	pthread_mutex_unlock(&message_mutex);
	return count;
}

static bool wait_for_message(const char *expected) {
	char last[INDIGO_VALUE_SIZE] = "";
	for (int i = 0; i < 100; i++) {
		pthread_mutex_lock(&message_mutex);
		INDIGO_COPY_VALUE(last, safety_message);
		pthread_mutex_unlock(&message_mutex);
		if (!strcmp(last, expected)) {
			return true;
		}
		indigo_usleep(50000);
	}
	fprintf(stderr, "    %s message is '%s', expected '%s'\n", AGENT_AUX_SAFETY_PROPERTY_NAME, last, expected);
	return false;
}

static indigo_property_state safety_light(const char *item) {
	indigo_item *found = find_cached_item(AGENT_AUX_SAFETY_PROPERTY_NAME, item);
	return found != NULL ? found->light.value : -1;
}

static bool safety_matches(indigo_property_state state, const indigo_property_state *lights) {
	const char *items[] = { AGENT_AUX_SAFETY_SAFE_ITEM_NAME, AGENT_AUX_SAFETY_CLOUDS_ITEM_NAME, AGENT_AUX_SAFETY_RAIN_ITEM_NAME, AGENT_AUX_SAFETY_WIND_ITEM_NAME, AGENT_AUX_SAFETY_HUMIDITY_ITEM_NAME };
	indigo_property *property = find_cached_property(AGENT_AUX_SAFETY_PROPERTY_NAME);
	if (property == NULL || property->state != state) {
		return false;
	}
	for (int i = 0; i < ARRAY_SIZE(items); i++) {
		if (safety_light(items[i]) != lights[i]) {
			return false;
		}
	}
	return true;
}

// Waits for the property state and the lights SAFE, CLOUDS, RAIN, WIND, HUMIDITY of AGENT_AUX_SAFETY.
static bool wait_for_safety(indigo_property_state state, indigo_property_state safe, indigo_property_state clouds, indigo_property_state rain, indigo_property_state wind, indigo_property_state humidity) {
	indigo_property_state lights[] = { safe, clouds, rain, wind, humidity };
	for (int i = 0; i < 100; i++) {
		if (safety_matches(state, lights)) {
			return true;
		}
		indigo_usleep(50000);
	}
	indigo_property *property = find_cached_property(AGENT_AUX_SAFETY_PROPERTY_NAME);
	fprintf(stderr, "    %s is state %d, SAFE %d, CLOUDS %d, RAIN %d, WIND %d, HUMIDITY %d; expected %d, %d, %d, %d, %d, %d\n", AGENT_AUX_SAFETY_PROPERTY_NAME, property ? (int)property->state : -1, safety_light(AGENT_AUX_SAFETY_SAFE_ITEM_NAME), safety_light(AGENT_AUX_SAFETY_CLOUDS_ITEM_NAME), safety_light(AGENT_AUX_SAFETY_RAIN_ITEM_NAME), safety_light(AGENT_AUX_SAFETY_WIND_ITEM_NAME), safety_light(AGENT_AUX_SAFETY_HUMIDITY_ITEM_NAME), state, safe, clouds, rain, wind, humidity);
	return false;
}

