static void safety_follows_source(void) {
	CHECK_TRUE(start(false));
	// Without a selected source the agent has no safety information.
	CHECK_TRUE(wait_for_safety(INDIGO_IDLE_STATE, INDIGO_IDLE_STATE, INDIGO_IDLE_STATE, INDIGO_IDLE_STATE, INDIGO_IDLE_STATE, INDIGO_IDLE_STATE));
	CHECK_TRUE(select_source(FILTER_AUX_1_LIST_PROPERTY_NAME, WEATHER_NAME));
	CHECK_TRUE(wait_for_safety(INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_OK_STATE));
	CHECK_TRUE(wait_for_message("Safe: all conditions within limits (" WEATHER_NAME ")"));
	// A threshold moved under the reading makes the source and the agent unsafe, with the source's reason.
	CHECK_TRUE(change_weather_number(AUX_WIND_THRESHOLDS_PROPERTY_NAME, AUX_WIND_STRONG_ITEM_NAME, 0.5));
	CHECK_TRUE(change_weather_number("X_SIMULATION_PARAMETERS", AUX_WEATHER_WIND_SPEED_ITEM_NAME, 1));
	CHECK_TRUE(wait_for_safety(INDIGO_OK_STATE, INDIGO_ALERT_STATE, INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_ALERT_STATE, INDIGO_OK_STATE));
	CHECK_TRUE(wait_for_message("Unsafe: wind 1.0 m/s above 0.5 m/s (" WEATHER_NAME ")"));
	// Updates that leave the verdict and the unsafe sources alone carry no message.
	int messages = message_count();
	CHECK_TRUE(change_weather_number("X_SIMULATION_PARAMETERS", AUX_WEATHER_RAIN_ITEM_NAME, 3));
	CHECK_TRUE(wait_for_safety(INDIGO_OK_STATE, INDIGO_ALERT_STATE, INDIGO_OK_STATE, INDIGO_ALERT_STATE, INDIGO_ALERT_STATE, INDIGO_OK_STATE));
	CHECK_TRUE(change_weather_number("X_SIMULATION_PARAMETERS", AUX_WEATHER_RAIN_ITEM_NAME, 0));
	CHECK_TRUE(wait_for_safety(INDIGO_OK_STATE, INDIGO_ALERT_STATE, INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_ALERT_STATE, INDIGO_OK_STATE));
	CHECK_EQ_INT(messages, message_count());
	// The restored threshold makes it safe again.
	CHECK_TRUE(change_weather_number(AUX_WIND_THRESHOLDS_PROPERTY_NAME, AUX_WIND_STRONG_ITEM_NAME, 10));
	CHECK_TRUE(wait_for_safety(INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_OK_STATE));
	CHECK_TRUE(wait_for_message("Safe: all conditions within limits (" WEATHER_NAME ")"));
	CHECK_EQ_INT(messages + 1, message_count());
cleanup:
	stop(false);
}

static void source_lost_on_deselect(void) {
	CHECK_TRUE(start(false));
	CHECK_TRUE(select_source(FILTER_AUX_1_LIST_PROPERTY_NAME, WEATHER_NAME));
	CHECK_TRUE(wait_for_safety(INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_OK_STATE));
	CHECK_TRUE(select_source(FILTER_AUX_1_LIST_PROPERTY_NAME, FILTER_DEVICE_LIST_NONE_ITEM_NAME));
	CHECK_TRUE(wait_for_safety(INDIGO_ALERT_STATE, INDIGO_IDLE_STATE, INDIGO_IDLE_STATE, INDIGO_IDLE_STATE, INDIGO_IDLE_STATE, INDIGO_IDLE_STATE));
	CHECK_TRUE(wait_for_message("Weather safety source lost"));
	CHECK_TRUE(wait_for_weather_disconnected());
	// A newly selected source restores the safety information.
	CHECK_TRUE(select_source(FILTER_AUX_2_LIST_PROPERTY_NAME, WEATHER_NAME));
	CHECK_TRUE(wait_for_safety(INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_OK_STATE));
	CHECK_TRUE(wait_for_message("Safe: all conditions within limits (" WEATHER_NAME ")"));
cleanup:
	stop(false);
}

static void source_lost_on_disconnect(void) {
	CHECK_TRUE(start(false));
	CHECK_TRUE(select_source(FILTER_AUX_1_LIST_PROPERTY_NAME, WEATHER_NAME));
	CHECK_TRUE(change_weather_number("X_SIMULATION_PARAMETERS", AUX_WEATHER_WIND_SPEED_ITEM_NAME, 12.4));
	CHECK_TRUE(wait_for_safety(INDIGO_OK_STATE, INDIGO_ALERT_STATE, INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_ALERT_STATE, INDIGO_OK_STATE));
	CHECK_TRUE(wait_for_message("Unsafe: wind 12.4 m/s above 10.0 m/s (" WEATHER_NAME ")"));
	CHECK_EQ_INT(INDIGO_OK, indigo_change_switch_property_1(&simulator_test_client, WEATHER_NAME, CONNECTION_PROPERTY_NAME, CONNECTION_DISCONNECTED_ITEM_NAME, true));
	CHECK_TRUE(wait_for_safety(INDIGO_ALERT_STATE, INDIGO_IDLE_STATE, INDIGO_IDLE_STATE, INDIGO_IDLE_STATE, INDIGO_IDLE_STATE, INDIGO_IDLE_STATE));
	CHECK_TRUE(wait_for_message("Weather safety source lost"));
cleanup:
	stop(false);
}

static void two_sources_worst_wins(void) {
	CHECK_TRUE(start(true));
	CHECK_TRUE(select_source(FILTER_AUX_1_LIST_PROPERTY_NAME, WEATHER_NAME));
	CHECK_TRUE(select_source(FILTER_AUX_2_LIST_PROPERTY_NAME, STANDIN_NAME));
	// The stand-in has a rain sensor only, so the other conditions come from the simulator.
	CHECK_TRUE(wait_for_safety(INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_OK_STATE));
	// One unsafe source makes the agent unsafe and names that source only.
	CHECK_TRUE(change_weather_number("X_SIMULATION_PARAMETERS", AUX_WEATHER_WIND_SPEED_ITEM_NAME, 12.4));
	CHECK_TRUE(wait_for_safety(INDIGO_OK_STATE, INDIGO_ALERT_STATE, INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_ALERT_STATE, INDIGO_OK_STATE));
	CHECK_TRUE(wait_for_message("Unsafe: wind 12.4 m/s above 10.0 m/s (" WEATHER_NAME ")"));
	// A second unsafe source changes the set of unsafe sources, so both reasons are passed on.
	standin_set(INDIGO_ALERT_STATE, "Unsafe: rain");
	CHECK_TRUE(wait_for_safety(INDIGO_OK_STATE, INDIGO_ALERT_STATE, INDIGO_OK_STATE, INDIGO_ALERT_STATE, INDIGO_ALERT_STATE, INDIGO_OK_STATE));
	CHECK_TRUE(wait_for_message("Unsafe: wind 12.4 m/s above 10.0 m/s (" WEATHER_NAME "); Unsafe: rain (" STANDIN_NAME ")"));
	// The simulator turning safe leaves the agent unsafe because of the stand-in.
	CHECK_TRUE(change_weather_number("X_SIMULATION_PARAMETERS", AUX_WEATHER_WIND_SPEED_ITEM_NAME, 1));
	CHECK_TRUE(wait_for_safety(INDIGO_OK_STATE, INDIGO_ALERT_STATE, INDIGO_OK_STATE, INDIGO_ALERT_STATE, INDIGO_OK_STATE, INDIGO_OK_STATE));
	CHECK_TRUE(wait_for_message("Unsafe: rain (" STANDIN_NAME ")"));
	standin_set(INDIGO_OK_STATE, "Safe: all conditions within limits");
	CHECK_TRUE(wait_for_safety(INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_OK_STATE));
	CHECK_TRUE(wait_for_message("Safe: all conditions within limits (" WEATHER_NAME "); Safe: all conditions within limits (" STANDIN_NAME ")"));
	// Losing one of two sources keeps the safety information of the other.
	CHECK_TRUE(select_source(FILTER_AUX_2_LIST_PROPERTY_NAME, FILTER_DEVICE_LIST_NONE_ITEM_NAME));
	CHECK_TRUE(wait_for_safety(INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_OK_STATE));
cleanup:
	stop(true);
}

static void source_change_without_reason(void) {
	CHECK_TRUE(start(true));
	CHECK_TRUE(select_source(FILTER_AUX_1_LIST_PROPERTY_NAME, STANDIN_NAME));
	CHECK_TRUE(wait_for_safety(INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_IDLE_STATE, INDIGO_OK_STATE, INDIGO_IDLE_STATE, INDIGO_IDLE_STATE));
	// A change to ALERT without a reason is published at once, with a reason written by the agent.
	standin_set(INDIGO_ALERT_STATE, NULL);
	CHECK_TRUE(wait_for_safety(INDIGO_OK_STATE, INDIGO_ALERT_STATE, INDIGO_IDLE_STATE, INDIGO_ALERT_STATE, INDIGO_IDLE_STATE, INDIGO_IDLE_STATE));
	CHECK_TRUE(wait_for_message("Unsafe: rain (" STANDIN_NAME ")"));
	// A change back to OK without a reason is not held back either.
	standin_set(INDIGO_OK_STATE, NULL);
	CHECK_TRUE(wait_for_safety(INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_IDLE_STATE, INDIGO_OK_STATE, INDIGO_IDLE_STATE, INDIGO_IDLE_STATE));
	CHECK_TRUE(wait_for_message("Safe: all conditions within limits (" STANDIN_NAME ")"));
	// The source's own reason, sent after its update, follows the agent-written one.
	int messages = message_count();
	standin_set(INDIGO_ALERT_STATE, "Unsafe: rain 3.0 mm/h above 1.0 mm/h");
	CHECK_TRUE(wait_for_safety(INDIGO_OK_STATE, INDIGO_ALERT_STATE, INDIGO_IDLE_STATE, INDIGO_ALERT_STATE, INDIGO_IDLE_STATE, INDIGO_IDLE_STATE));
	CHECK_TRUE(wait_for_message("Unsafe: rain 3.0 mm/h above 1.0 mm/h (" STANDIN_NAME ")"));
	CHECK_EQ_INT(messages + 2, message_count());
	// A reason equal to the agent-written one is not repeated.
	standin_set(INDIGO_OK_STATE, "Safe: all conditions within limits");
	CHECK_TRUE(wait_for_safety(INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_IDLE_STATE, INDIGO_OK_STATE, INDIGO_IDLE_STATE, INDIGO_IDLE_STATE));
	CHECK_TRUE(wait_for_message("Safe: all conditions within limits (" STANDIN_NAME ")"));
	CHECK_EQ_INT(messages + 3, message_count());
	// A reason of an earlier ALERT is not reused for a later ALERT without a reason.
	standin_set(INDIGO_ALERT_STATE, "Unsafe: rain 3.0 mm/h above 1.0 mm/h");
	CHECK_TRUE(wait_for_message("Unsafe: rain 3.0 mm/h above 1.0 mm/h (" STANDIN_NAME ")"));
	standin_set(INDIGO_OK_STATE, NULL);
	CHECK_TRUE(wait_for_safety(INDIGO_OK_STATE, INDIGO_OK_STATE, INDIGO_IDLE_STATE, INDIGO_OK_STATE, INDIGO_IDLE_STATE, INDIGO_IDLE_STATE));
	CHECK_TRUE(wait_for_message("Safe: all conditions within limits (" STANDIN_NAME ")"));
	standin_set(INDIGO_ALERT_STATE, NULL);
	CHECK_TRUE(wait_for_safety(INDIGO_OK_STATE, INDIGO_ALERT_STATE, INDIGO_IDLE_STATE, INDIGO_ALERT_STATE, INDIGO_IDLE_STATE, INDIGO_IDLE_STATE));
	CHECK_TRUE(wait_for_message("Unsafe: rain (" STANDIN_NAME ")"));
cleanup:
	stop(true);
}

int main(void) {
	if (!indigo_test_use_private_home()) {
		return 1;
	}
	setvbuf(stdout, NULL, _IONBF, 0);
	alarm(120);
	simulator_test_client.send_message = recording_send_message;
	simulator_test_client.update_property = tracking_update_property;
	const indigo_test_case tests[] = {
		{ "safety_follows_source", safety_follows_source },
		{ "source_lost_on_deselect", source_lost_on_deselect },
		{ "source_lost_on_disconnect", source_lost_on_disconnect },
		{ "two_sources_worst_wins", two_sources_worst_wins },
		{ "source_change_without_reason", source_change_without_reason }
	};
	int result = indigo_run_tests("Auxiliary Agent safety integration tests", tests, ARRAY_SIZE(tests));
	indigo_test_remove_private_home();
	return result;
}
