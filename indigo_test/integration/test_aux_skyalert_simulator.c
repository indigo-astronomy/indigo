// A record the driver cannot parse must not connect the device: a non-"Data" header, a record that
// stops early, a field that is not a number and a field that is not finite.
static void unparseable_records_are_refused(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	static const struct { const char *action; const char *argument; } faults[] = {
		{ "drop", "*" },
		{ "header", "*" },
		{ "truncate", "5" },
		{ "truncate", "9" },
		{ "garbage", "3" },
		{ "infinite", "3" },
		{ "garbage", "9" }
	};
	SERIAL_CHECK_TRUE(start_skyalert(&simulator, NULL));
	SERIAL_CHECK_TRUE(bring_up_serial_driver(&skyalert));
	online = true;
	enumerate_simulator_device();
	for (int i = 0; i < ARRAY_SIZE(faults); i++) {
		printf("  refusing %s %s\n", faults[i].action, faults[i].argument);
		SERIAL_CHECK_TRUE(arm_fault(&simulator, faults[i].action, faults[i].argument));
		SERIAL_CHECK_TRUE(!connect_serial_device(&skyalert, simulator.port));
		SERIAL_CHECK_TRUE(wait_for_property_state(CONNECTION_PROPERTY_NAME, INDIGO_ALERT_STATE));
		SERIAL_CHECK_TRUE(!context.connected);
		assert_switch_item_value(CONNECTION_PROPERTY_NAME, CONNECTION_DISCONNECTED_ITEM_NAME, true);
		SERIAL_CHECK_TRUE(connected_properties_published(false));
		SERIAL_CHECK_TRUE(!strcmp(info_text(INFO_DEVICE_MODEL_ITEM_NAME), "Unknown"));
	}
	// The leftover of a truncated record must not be mistaken for the next one.
	SERIAL_CHECK_TRUE(connect_serial_device(&skyalert, simulator.port));
	SERIAL_CHECK_TRUE(weather_is(AUX_WEATHER_HUMIDITY_ITEM_NAME, 66.3));
cleanup:
	if (online) {
		disconnect_serial_device(&skyalert);
		tear_down_serial_driver(&skyalert);
	}
	stop_external_serial_simulator(&simulator);
}

// The device never reports on its own, so the driver has to keep asking. This is the case that
// fails against a driver whose only reading is the one taken inside its open helper.
static void readings_are_refreshed_by_polling(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_skyalert(&simulator, NULL));
	SERIAL_CHECK_TRUE(start_serial_driver(&skyalert, simulator.port));
	online = true;
	// One reading is taken while opening and one by the poll the connection handler queues.
	SERIAL_CHECK_TRUE(wait_for_events(&simulator, "send", 2, 5));
	unsigned int revision = property_revision(AUX_WEATHER_PROPERTY_NAME);
	unsigned int info_revision = property_state_revision(AUX_INFO_PROPERTY_NAME, INDIGO_OK_STATE);
	double first = cached_number_value(AUX_WEATHER_PROPERTY_NAME, AUX_WEATHER_TEMPERATURE_ITEM_NAME);
	// The third reading can only come from the rescheduled poll.
	SERIAL_CHECK_TRUE(wait_for_events(&simulator, "send", 3, SKYALERT_POLL_SECONDS + 5));
	SERIAL_CHECK_TRUE(wait_for_property_state_after(AUX_WEATHER_PROPERTY_NAME, INDIGO_OK_STATE, revision));
	double second = cached_number_value(AUX_WEATHER_PROPERTY_NAME, AUX_WEATHER_TEMPERATURE_ITEM_NAME);
	printf("  temperature %g -> %g over %d polls\n", first, second, event_count(&simulator, "send"));
	SERIAL_CHECK_TRUE(second > first);
	// Both published properties have to carry the new reading, not just the weather one.
	SERIAL_CHECK_TRUE(property_state_revision(AUX_INFO_PROPERTY_NAME, INDIGO_OK_STATE) > info_revision);
cleanup:
	if (online) {
		stop_serial_driver(&skyalert);
	}
	stop_external_serial_simulator(&simulator);
}

// A reading that fails has to be reported on both published properties, the poll has to survive it
// and pick the readings up again, and it has to stop once the device is disconnected.
static void a_failed_poll_is_reported_and_polling_stops_on_disconnect(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_skyalert(&simulator, NULL));
	SERIAL_CHECK_TRUE(start_serial_driver(&skyalert, simulator.port));
	online = true;
	SERIAL_CHECK_TRUE(wait_for_events(&simulator, "send", 2, 5));
	unsigned int weather_revision = property_revision(AUX_WEATHER_PROPERTY_NAME);
	unsigned int info_revision = property_revision(AUX_INFO_PROPERTY_NAME);
	SERIAL_CHECK_TRUE(arm_fault(&simulator, "header", "*"));
	SERIAL_CHECK_TRUE(wait_for_property_state_after(AUX_WEATHER_PROPERTY_NAME, INDIGO_ALERT_STATE, weather_revision));
	SERIAL_CHECK_TRUE(wait_for_property_state_after(AUX_INFO_PROPERTY_NAME, INDIGO_ALERT_STATE, info_revision));
	SERIAL_CHECK_TRUE(context.connected);
	weather_revision = property_revision(AUX_WEATHER_PROPERTY_NAME);
	SERIAL_CHECK_TRUE(wait_for_property_state_after(AUX_WEATHER_PROPERTY_NAME, INDIGO_OK_STATE, weather_revision));
	disconnect_serial_device(&skyalert);
	SERIAL_CHECK_TRUE(connected_properties_published(false));
	clear_events(&simulator);
	// Nothing may reach the device after the port is closed.
	indigo_usleep((SKYALERT_POLL_SECONDS + 2) * 1000000L);
	SERIAL_CHECK_EQ_INT(0, event_count(&simulator, "send"));
cleanup:
	if (online) {
		disconnect_serial_device(&skyalert);
		tear_down_serial_driver(&skyalert);
	}
	stop_external_serial_simulator(&simulator);
}

// A port that cannot be opened must leave the device disconnected and must not prevent a later
// connection from working.
static void failed_open_leaves_the_device_disconnected(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_skyalert(&simulator, NULL));
	SERIAL_CHECK_TRUE(bring_up_serial_driver(&skyalert));
	online = true;
	enumerate_simulator_device();
	SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_change_text_property_1_raw(&simulator_test_client, skyalert.device_name, DEVICE_PORT_PROPERTY_NAME, DEVICE_PORT_ITEM_NAME, "/dev/indigo-nonexistent-skyalert-test"));
	unsigned int revision = property_revision(CONNECTION_PROPERTY_NAME);
	SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_change_switch_property_1(&simulator_test_client, skyalert.device_name, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, true));
	SERIAL_CHECK_TRUE(wait_for_property_state_seen_after(CONNECTION_PROPERTY_NAME, INDIGO_ALERT_STATE, revision));
	SERIAL_CHECK_TRUE(!context.connected);
	SERIAL_CHECK_TRUE(connected_properties_published(false));
	SERIAL_CHECK_TRUE(connect_serial_device(&skyalert, simulator.port));
	SERIAL_CHECK_TRUE(connected_properties_published(true));
	SERIAL_CHECK_TRUE(weather_is(AUX_WEATHER_RAIN_ITEM_NAME, 1008));
cleanup:
	if (online) {
		disconnect_serial_device(&skyalert);
		tear_down_serial_driver(&skyalert);
	}
	stop_external_serial_simulator(&simulator);
}

