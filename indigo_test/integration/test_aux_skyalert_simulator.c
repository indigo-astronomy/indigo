// -------------------------------------------------------------------------------- simulator glue

static bool start_skyalert(external_serial_simulator *simulator, const char *firmware) {
	if (firmware == NULL) {
		return start_external_serial_simulator(simulator, AUX_SKYALERT_SIMULATOR_EXECUTABLE);
	}
	const char *arguments[] = { "--firmware", firmware, NULL };
	return start_external_serial_simulator_with_args(simulator, AUX_SKYALERT_SIMULATOR_EXECUTABLE, arguments);
}

static void simulator_path(const external_serial_simulator *simulator, const char *suffix, char *path, size_t size) {
	snprintf(path, size, "%s.%s", simulator->ready_file, suffix);
}

// One fault is armed at a time and consumed by the next record. The argument is the one-based
// index of the affected record line where the action takes one.
static bool arm_fault(const external_serial_simulator *simulator, const char *action, const char *argument) {
	char path[PATH_MAX];
	simulator_path(simulator, "control", path, sizeof(path));
	FILE *file = fopen(path, "w");
	if (file == NULL) {
		return false;
	}
	fprintf(file, "%s %s\n", action, argument);
	return fclose(file) == 0;
}

static void clear_events(const external_serial_simulator *simulator) {
	char path[PATH_MAX];
	simulator_path(simulator, "events", path, sizeof(path));
	unlink(path);
}

static int event_count(const external_serial_simulator *simulator, const char *command) {
	char path[PATH_MAX];
	char line[64];
	int count = 0;
	simulator_path(simulator, "events", path, sizeof(path));
	FILE *file = fopen(path, "r");
	if (file == NULL) {
		return 0;
	}
	while (fgets(line, sizeof(line), file) != NULL) {
		line[strcspn(line, "\r\n")] = '\0';
		if (!strcmp(line, command)) {
			count++;
		}
	}
	fclose(file);
	return count;
}

static bool wait_for_events(const external_serial_simulator *simulator, const char *command, int expected_count, int seconds) {
	for (int i = 0; i < seconds * 10; i++) {
		if (event_count(simulator, command) >= expected_count) {
			return true;
		}
		indigo_usleep(100000);
	}
	fprintf(stderr, "'%s' was recorded %d times in %ds, expected %d\n", command, event_count(simulator, command), seconds, expected_count);
	return false;
}

// -------------------------------------------------------------------------------- read helpers

static const char *info_text(const char *item_name) {
	indigo_item *item = find_cached_item(INFO_PROPERTY_NAME, item_name);
	return item == NULL ? "" : item->text.value;
}

static bool weather_is(const char *item_name, double expected) {
	double value = cached_number_value(AUX_WEATHER_PROPERTY_NAME, item_name);
	if (fabs(value - expected) > 1e-6) {
		fprintf(stderr, "%s is %g, expected %g\n", item_name, value, expected);
		return false;
	}
	return true;
}

static bool info_is(const char *item_name, double expected) {
	double value = cached_number_value(AUX_INFO_PROPERTY_NAME, item_name);
	if (fabs(value - expected) > 1e-6) {
		fprintf(stderr, "%s is %g, expected %g\n", item_name, value, expected);
		return false;
	}
	return true;
}

static bool connected_properties_published(bool expected) {
	for (int i = 0; i < ARRAY_SIZE(skyalert_connected_properties); i++) {
		if ((find_cached_property(skyalert_connected_properties[i]) != NULL) != expected) {
			fprintf(stderr, "%s is %spublished\n", skyalert_connected_properties[i], expected ? "not " : "");
			return false;
		}
	}
	return true;
}

