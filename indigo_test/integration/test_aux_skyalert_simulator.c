// Driver metadata, the published property inventory before and after connection, and every field
// of the record mapped to its item and unit.
static void identity_inventory_and_record_contract(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	indigo_driver_info info;
	memset(&info, 0, sizeof(info));
	assert_simulator_driver_info(&skyalert);
	SERIAL_CHECK_TRUE(start_skyalert(&simulator, NULL));
	SERIAL_CHECK_TRUE(bring_up_serial_driver(&skyalert));
	online = true;
	enumerate_simulator_device();
	assert_device_interface(INDIGO_INTERFACE_AUX_SQM);
	assert_defined_properties(skyalert_base_properties, ARRAY_SIZE(skyalert_base_properties));
	assert_not_defined_properties(skyalert_hidden_properties, ARRAY_SIZE(skyalert_hidden_properties));
	assert_not_defined_properties(skyalert_connected_properties, ARRAY_SIZE(skyalert_connected_properties));
	assert_defined_property_count(ARRAY_SIZE(skyalert_base_properties));
	SERIAL_CHECK_TRUE(!strcmp(info_text(INFO_DEVICE_MODEL_ITEM_NAME), "Unknown"));
	SERIAL_CHECK_TRUE(!strcmp(info_text(INFO_DEVICE_FW_REVISION_ITEM_NAME), "Unknown"));
	SERIAL_CHECK_TRUE(connect_serial_device(&skyalert, simulator.port));
	assert_serial_aux_class_property_completeness();
	assert_defined_properties(skyalert_connected_properties, ARRAY_SIZE(skyalert_connected_properties));
	assert_not_defined_properties(skyalert_hidden_properties, ARRAY_SIZE(skyalert_hidden_properties));
	assert_defined_property_count(ARRAY_SIZE(skyalert_base_properties) + ARRAY_SIZE(skyalert_connected_properties));
	indigo_property *weather = find_cached_property(AUX_WEATHER_PROPERTY_NAME);
	indigo_property *aux_info = find_cached_property(AUX_INFO_PROPERTY_NAME);
	SERIAL_CHECK_TRUE(weather != NULL && weather->type == INDIGO_NUMBER_VECTOR && weather->perm == INDIGO_RO_PERM && weather->count == 6);
	SERIAL_CHECK_TRUE(aux_info != NULL && aux_info->type == INDIGO_NUMBER_VECTOR && aux_info->perm == INDIGO_RO_PERM && aux_info->count == 2);
	static const char *weather_items[] = {
		AUX_WEATHER_TEMPERATURE_ITEM_NAME,
		AUX_WEATHER_HUMIDITY_ITEM_NAME,
		AUX_WEATHER_PRESSURE_ITEM_NAME,
		AUX_WEATHER_WIND_SPEED_ITEM_NAME,
		AUX_WEATHER_RAIN_ITEM_NAME,
		AUX_WEATHER_SKY_TEMPERATURE_ITEM_NAME
	};
	assert_property_has_items(AUX_WEATHER_PROPERTY_NAME, weather_items, ARRAY_SIZE(weather_items));
	assert_property_has_item(AUX_INFO_PROPERTY_NAME, AUX_WEATHER_SKY_BRIGHTNESS_ITEM_NAME);
	assert_property_has_item(AUX_INFO_PROPERTY_NAME, AUX_INFO_POWER_ITEM_NAME);
	// Every field of the simulated record except the temperature and the sky brightness, which the
	// simulator advances per reading so that each new record is published at all.
	SERIAL_CHECK_TRUE(weather_is(AUX_WEATHER_SKY_TEMPERATURE_ITEM_NAME, 1));
	SERIAL_CHECK_TRUE(weather_is(AUX_WEATHER_RAIN_ITEM_NAME, 1008));
	SERIAL_CHECK_TRUE(weather_is(AUX_WEATHER_HUMIDITY_ITEM_NAME, 66.3));
	SERIAL_CHECK_TRUE(weather_is(AUX_WEATHER_WIND_SPEED_ITEM_NAME, 415));
	// The record carries pascal, the item is documented in hectopascal.
	SERIAL_CHECK_TRUE(weather_is(AUX_WEATHER_PRESSURE_ITEM_NAME, 1017.9183));
	SERIAL_CHECK_TRUE(cached_number_value(AUX_INFO_PROPERTY_NAME, AUX_WEATHER_SKY_BRIGHTNESS_ITEM_NAME) >= 751);
	SERIAL_CHECK_TRUE(info_is(AUX_INFO_POWER_ITEM_NAME, 1));
	SERIAL_CHECK_TRUE(cached_number_value(AUX_WEATHER_PROPERTY_NAME, AUX_WEATHER_TEMPERATURE_ITEM_NAME) >= 20.3);
	SERIAL_CHECK_TRUE(!strcmp(info_text(INFO_DEVICE_MODEL_ITEM_NAME), "Interactive Astronomy SkyAlert"));
	SERIAL_CHECK_TRUE(!strcmp(info_text(INFO_DEVICE_FW_REVISION_ITEM_NAME), "1.8m"));
	SERIAL_CHECK_EQ_INT(INDIGO_OK, skyalert.entry(INDIGO_DRIVER_INFO, &info));
	SERIAL_CHECK_EQ_INT(INDIGO_DRIVER_API_3, INDIGO_DRIVER_API_GENERATION(info.version));
cleanup:
	if (online) {
		stop_serial_driver(&skyalert);
	}
	stop_external_serial_simulator(&simulator);
}

