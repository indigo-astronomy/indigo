// AUX weather coverage for indigo_aux_skyalert against the standalone SkyAlert simulator over a
// real PTY. The device answers "send" with a ten line record - the literal "Data", seven numbers,
// the firmware string and the pressure in pascal - and has no unsolicited output, so every reading
// is one request. The contract checked here is the field order and the units the driver derives
// from it, the refusal of every incomplete or unparseable record, and the ten second poll that
// keeps AUX_WEATHER and AUX_INFO current after connection.

#include <indigo_drivers/aux_skyalert/indigo_aux_skyalert.h>

#include "serial_simulator_test_common.h"

#ifndef AUX_SKYALERT_SIMULATOR_EXECUTABLE
#define AUX_SKYALERT_SIMULATOR_EXECUTABLE "build/integration/aux_skyalert_simulator"
#endif

// The driver reschedules its own poll with this period; cases that wait for a fresh reading have
// to outlast it.
#define SKYALERT_POLL_SECONDS 10

static const simulator_driver_case skyalert = {
	"Interactive Astronomy SkyAlert",
	"indigo_aux_skyalert",
	"Interactive Astronomy SkyAlert",
	indigo_aux_skyalert,
	false,
	NULL, 0, NULL, 0, NULL, 0, NULL, 0
};

