// sscanf() reports how many conversions succeeded, not whether the whole
// format matched, so "gpiochip571/ngpio" would satisfy a "gpiochip%d/label"
// format. Every indexed path is therefore matched exactly: literal prefix,
// number, literal suffix and nothing after it.
static bool fake_match(const char *path, const char *prefix, const char *suffix, int *value) {
	size_t length = strlen(prefix);
	if (strncmp(path, prefix, length)) {
		return false;
	}
	char *end = NULL;
	long parsed = strtol(path + length, &end, 10);
	if (end == path + length || strcmp(end, suffix)) {
		return false;
	}
	*value = (int)parsed;
	return true;
}

// A channel path carries two numbers, the chip and the channel, so the chip is
// tried explicitly rather than searched for in the string.
static bool fake_match_channel(const char *path, const char *suffix, int *channel) {
	char prefix[64];
	for (int chip = 0; chip < 8; chip++) {
		snprintf(prefix, sizeof(prefix), "/sys/class/pwm/pwmchip%d/pwm", chip);
		if (fake_match(path, prefix, suffix, channel)) {
			return true;
		}
	}
	return false;
}

static fake_node_kind fake_parse_path(const char *path, int *index) {
	int value = 0;
	*index = -1;
	if (fake_match(path, "/sys/class/gpio/gpiochip", "/label", &value)) {
		*index = fake_chip_index(value);
		return FAKE_NODE_CHIP_LABEL;
	}
	if (fake_match(path, "/sys/class/gpio/gpiochip", "/base", &value)) {
		*index = fake_chip_index(value);
		return FAKE_NODE_CHIP_BASE;
	}
	if (fake_match(path, "/sys/class/gpio/gpiochip", "/ngpio", &value)) {
		*index = fake_chip_index(value);
		return FAKE_NODE_CHIP_NGPIO;
	}
	if (fake_match(path, "/sys/class/pwm/pwmchip", "/npwm", &value)) {
		*index = value;
		return FAKE_NODE_PWM_NPWM;
	}
	if (!strcmp(path, "/sys/class/gpio/export")) {
		return FAKE_NODE_GPIO_EXPORT;
	}
	if (!strcmp(path, "/sys/class/gpio/unexport")) {
		return FAKE_NODE_GPIO_UNEXPORT;
	}
	if (fake_match(path, "/sys/class/gpio/gpio", "/direction", &value)) {
		*index = value;
		return FAKE_NODE_PIN_DIRECTION;
	}
	if (fake_match(path, "/sys/class/gpio/gpio", "/value", &value)) {
		*index = value;
		return FAKE_NODE_PIN_VALUE;
	}
	if (fake_match(path, "/sys/class/pwm/pwmchip", "/export", &value)) {
		return FAKE_NODE_PWM_EXPORT;
	}
	if (fake_match(path, "/sys/class/pwm/pwmchip", "/unexport", &value)) {
		return FAKE_NODE_PWM_UNEXPORT;
	}
	if (fake_match_channel(path, "/enable", &value)) {
		*index = value;
		return FAKE_NODE_PWM_ENABLE;
	}
	if (fake_match_channel(path, "/period", &value)) {
		*index = value;
		return FAKE_NODE_PWM_PERIOD;
	}
	if (fake_match_channel(path, "/duty_cycle", &value)) {
		*index = value;
		return FAKE_NODE_PWM_DUTY;
	}
	return FAKE_NODE_NONE;
}

static bool fake_node_exists(fake_node_kind kind, int index) {
	switch (kind) {
		case FAKE_NODE_GPIO_EXPORT:
		case FAKE_NODE_GPIO_UNEXPORT:
			return true;
		case FAKE_NODE_PIN_DIRECTION:
			if (index < 0 || index >= FAKE_MAX_PINS) {
				return false;
			}
			return fake.pins[index].exported && fake.pins[index].direction_present;
		case FAKE_NODE_PIN_VALUE:
			if (index < 0 || index >= FAKE_MAX_PINS) {
				return false;
			}
			return fake.pins[index].exported;
		case FAKE_NODE_PWM_EXPORT:
		case FAKE_NODE_PWM_UNEXPORT:
			return fake.pwm_chip_present;
		case FAKE_NODE_PWM_ENABLE:
		case FAKE_NODE_PWM_PERIOD:
		case FAKE_NODE_PWM_DUTY:
			if (!fake.pwm_chip_present || index < 0 || index >= FAKE_PWM_CHANNELS) {
				return false;
			}
			return fake.pwm[index].exported;
		case FAKE_NODE_CHIP_LABEL:
		case FAKE_NODE_CHIP_BASE:
		case FAKE_NODE_CHIP_NGPIO:
			return index >= 0 && index < fake.chip_count;
		case FAKE_NODE_PWM_NPWM:
			return fake.pwm_chip_present && index == 0;
		default:
			return false;
	}
}

int sysfs_test_open(const char *path, int flags, ...) {
	int index = 0;
	pthread_mutex_lock(&fake.mutex);
	fake_node_kind kind = fake_parse_path(path, &index);
	if (kind == FAKE_NODE_NONE || !fake_node_exists(kind, index)) {
		fake_trace("open-enoent %s", path);
		pthread_mutex_unlock(&fake.mutex);
		errno = ENOENT;
		return -1;
	}
	for (int i = 0; i < FAKE_MAX_FDS; i++) {
		if (!fake.descriptors[i].used) {
			fake.descriptors[i].used = true;
			fake.descriptors[i].kind = kind;
			fake.descriptors[i].index = index;
			fake.descriptors[i].flags = flags;
			fake.descriptors[i].read_offset = 0;
			pthread_mutex_unlock(&fake.mutex);
			return FAKE_FD_BASE + i;
		}
	}
	fake_trace("open-emfile %s", path);
	pthread_mutex_unlock(&fake.mutex);
	errno = EMFILE;
	return -1;
}

int sysfs_test_close(int fd) {
	int slot = fd - FAKE_FD_BASE;
	if (slot < 0 || slot >= FAKE_MAX_FDS) {
		errno = EBADF;
		return -1;
	}
	pthread_mutex_lock(&fake.mutex);
	fake.descriptors[slot].used = false;
	pthread_mutex_unlock(&fake.mutex);
	return 0;
}

static int fake_render(fake_descriptor *descriptor, char *buffer, int size) {
	switch (descriptor->kind) {
		case FAKE_NODE_PIN_DIRECTION:
			return snprintf(buffer, size, "%s\n", fake.pins[descriptor->index].is_input ? "in" : "out");
		case FAKE_NODE_PIN_VALUE:
			if (fake.value_read_empty) {
				return 0;
			}
			if (fake.value_read_unterminated) {
				return snprintf(buffer, size, "%d", fake.pins[descriptor->index].value);
			}
			return snprintf(buffer, size, "%d\n", fake.pins[descriptor->index].value);
		case FAKE_NODE_PWM_ENABLE:
			if (fake.pwm_read_fails) {
				return -1;
			}
			return snprintf(buffer, size, "%d\n", fake.pwm[descriptor->index].enable);
		case FAKE_NODE_PWM_PERIOD:
			if (fake.pwm_read_fails) {
				return -1;
			}
			return snprintf(buffer, size, "%d\n", fake.pwm_zero_period ? 0 : fake.pwm[descriptor->index].period);
		case FAKE_NODE_PWM_DUTY:
			if (fake.pwm_read_fails) {
				return -1;
			}
			return snprintf(buffer, size, "%d\n", fake.pwm[descriptor->index].duty_cycle);
		case FAKE_NODE_CHIP_LABEL:
			return snprintf(buffer, size, "%s\n", fake.chips[descriptor->index].label);
		case FAKE_NODE_CHIP_BASE:
			return snprintf(buffer, size, "%d\n", fake.chips[descriptor->index].base);
		case FAKE_NODE_CHIP_NGPIO:
			return snprintf(buffer, size, "%d\n", fake.chips[descriptor->index].lines);
		case FAKE_NODE_PWM_NPWM:
			return snprintf(buffer, size, "%d\n", FAKE_PWM_CHANNELS);
		default:
			return 0;
	}
}

ssize_t sysfs_test_read(int fd, void *buffer, size_t size) {
	int slot = fd - FAKE_FD_BASE;
	char rendered[64] = { 0 };
	if (slot < 0 || slot >= FAKE_MAX_FDS) {
		errno = EBADF;
		return -1;
	}
	pthread_mutex_lock(&fake.mutex);
	fake_descriptor *descriptor = fake.descriptors + slot;
	int length = fake_render(descriptor, rendered, sizeof(rendered));
	if (length < 0) {
		fake_trace("read-fail %d/%d", (int)descriptor->kind, descriptor->index);
		pthread_mutex_unlock(&fake.mutex);
		errno = EIO;
		return -1;
	}
	int remaining = length - descriptor->read_offset;
	if (remaining < 0) {
		remaining = 0;
	}
	int copied = remaining < (int)size ? remaining : (int)size;
	memcpy(buffer, rendered + descriptor->read_offset, copied);
	descriptor->read_offset += copied;
	switch (descriptor->kind) {
		case FAKE_NODE_PIN_DIRECTION:
			fake_trace("read direction %d -> %s", descriptor->index, fake.pins[descriptor->index].is_input ? "in" : "out");
			break;
		case FAKE_NODE_PIN_VALUE:
			fake_trace("read value %d -> %d", descriptor->index, fake.pins[descriptor->index].value);
			break;
		case FAKE_NODE_PWM_ENABLE:
			fake_trace("read pwm-enable %d -> %d", descriptor->index, fake.pwm[descriptor->index].enable);
			break;
		case FAKE_NODE_PWM_PERIOD:
			fake_trace("read pwm-period %d -> %d", descriptor->index, fake.pwm[descriptor->index].period);
			break;
		case FAKE_NODE_PWM_DUTY:
			fake_trace("read pwm-duty %d -> %d", descriptor->index, fake.pwm[descriptor->index].duty_cycle);
			break;
		case FAKE_NODE_CHIP_LABEL:
			fake_trace("read chip-label %d", descriptor->index);
			break;
		case FAKE_NODE_CHIP_BASE:
			fake_trace("read chip-base %d", descriptor->index);
			break;
		case FAKE_NODE_CHIP_NGPIO:
			fake_trace("read chip-ngpio %d", descriptor->index);
			break;
		default:
			break;
	}
	pthread_mutex_unlock(&fake.mutex);
	return copied;
}

ssize_t sysfs_test_write(int fd, const void *buffer, size_t size) {
	int slot = fd - FAKE_FD_BASE;
	char text[64] = { 0 };
	if (slot < 0 || slot >= FAKE_MAX_FDS) {
		errno = EBADF;
		return -1;
	}
	memcpy(text, buffer, size < sizeof(text) - 1 ? size : sizeof(text) - 1);
	pthread_mutex_lock(&fake.mutex);
	fake_descriptor *descriptor = fake.descriptors + slot;
	int index = descriptor->index;
	int value = atoi(text);
	switch (descriptor->kind) {
		case FAKE_NODE_GPIO_EXPORT:
			fake.export_writes++;
			if (fake.fail_export_after >= 0 && fake.export_writes > fake.fail_export_after) {
				fake_trace("export-fail %d", value);
				pthread_mutex_unlock(&fake.mutex);
				errno = EINVAL;
				return -1;
			}
			if (value < 0 || value >= FAKE_MAX_PINS || value < fake.gpio_base) {
				fake_trace("export-invalid %d", value);
				pthread_mutex_unlock(&fake.mutex);
				errno = EINVAL;
				return -1;
			}
			fake.pins[value].exported = true;
			fake.pins[value].direction_present = !fake.direction_appears_late;
			fake.pins[value].is_input = true;
			fake_trace("export %d", value);
			break;
		case FAKE_NODE_GPIO_UNEXPORT:
			if (value >= 0 && value < FAKE_MAX_PINS) {
				fake.pins[value].exported = false;
				fake.pins[value].direction_present = false;
			}
			fake_trace("unexport %d", value);
			break;
		case FAKE_NODE_PIN_DIRECTION:
			if (fake.fail_direction_write) {
				fake_trace("direction-fail %d", index);
				pthread_mutex_unlock(&fake.mutex);
				errno = EIO;
				return -1;
			}
			fake.pins[index].is_input = text[0] == 'i';
			fake_trace("direction %d %s", index, fake.pins[index].is_input ? "in" : "out");
			break;
		case FAKE_NODE_PIN_VALUE:
			if (fake.fail_value_write) {
				fake_trace("value-fail %d", index);
				pthread_mutex_unlock(&fake.mutex);
				errno = EIO;
				return -1;
			}
			fake.pins[index].value = text[0] == '1' ? 1 : 0;
			fake_trace("value %d %d", index, fake.pins[index].value);
			break;
		case FAKE_NODE_PWM_EXPORT:
			if (value >= 0 && value < FAKE_PWM_CHANNELS) {
				fake.pwm[value].exported = true;
			}
			fake_trace("pwm-export %d", value);
			break;
		case FAKE_NODE_PWM_UNEXPORT:
			if (value >= 0 && value < FAKE_PWM_CHANNELS) {
				fake.pwm[value].exported = false;
			}
			fake_trace("pwm-unexport %d", value);
			break;
		case FAKE_NODE_PWM_ENABLE:
			fake.pwm[index].enable = value ? 1 : 0;
			fake_trace("pwm-enable %d %d", index, fake.pwm[index].enable);
			break;
		case FAKE_NODE_PWM_PERIOD:
			fake.pwm[index].period = value;
			fake_trace("pwm-period %d %d", index, value);
			break;
		case FAKE_NODE_PWM_DUTY:
			fake.pwm[index].duty_cycle = value;
			fake_trace("pwm-duty %d %d", index, value);
			break;
		default:
			break;
	}
	pthread_mutex_unlock(&fake.mutex);
	return (ssize_t)size;
}

// Directory listing of the two sysfs classes the driver scans to resolve the
// header controller and the PWM chip.
typedef struct {
	bool used;
	bool pwm;
	int next;
	struct dirent entry;
} fake_directory;

