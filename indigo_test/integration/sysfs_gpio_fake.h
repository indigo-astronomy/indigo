/** Fake legacy sysfs GPIO and PWM boundary shared by the drivers that use it.
 \file sysfs_gpio_fake.h

 The Raspberry Pi GPIO and the ZWO ASIAIR power port drivers reach the hardware
 only through /sys/class/gpio and /sys/class/pwm, so a test replaces those
 system calls when the driver is compiled for it. The fake models the kernel
 side: a controller with a configurable base, export creating a pin node whose
 direction defaults to in, direction and value files, PWM channels, and an
 ordered timestamp-free trace of every interaction.

 Failure injection is set directly on the fake state after a reset.
 */

