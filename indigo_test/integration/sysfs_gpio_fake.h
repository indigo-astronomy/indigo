	fake.pwm_chip_present = pwm_chip_present;
	// Base 0 models a Raspberry Pi 4 and earlier, where the header controller
	// is the only one and starts at 0. Any other base models a Raspberry Pi 5,
	// where four gpio-brcmstb banks are published next to the header
	// controller and only the pinctrl one owns the 40-pin connector.
	if (gpio_base == 0) {
		fake.chips[0] = (fake_gpiochip){ 0, 54, "pinctrl-bcm2835" };
		fake.chip_count = 1;
	} else {
		fake.chips[0] = (fake_gpiochip){ 512, 17, "gpio-brcmstb@107d517c00" };
		fake.chips[1] = (fake_gpiochip){ 529, 6, "gpio-brcmstb@107d517c20" };
		fake.chips[2] = (fake_gpiochip){ 535, 32, "gpio-brcmstb@107d508500" };
		fake.chips[3] = (fake_gpiochip){ 567, 4, "gpio-brcmstb@107d508520" };
		fake.chips[4] = (fake_gpiochip){ gpio_base, 54, "pinctrl-rp1" };
		fake.chip_count = 5;
	}
	fake.fail_export_after = -1;
	fake.fail_direction_write = false;
	fake.fail_value_write = false;
	fake.value_read_empty = false;
	fake.value_read_unterminated = false;
