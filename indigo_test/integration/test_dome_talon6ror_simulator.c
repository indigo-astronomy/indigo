// ---------------------------------------------------------------------------- reference trace

static void trace_append(const char *line) {
	int written = snprintf(trace_text + trace_length, sizeof(trace_text) - trace_length, "%s\n", line);
	if (written > 0 && trace_length + written < sizeof(trace_text)) {
		trace_length += written;
	}
}

static bool wait_poll_boundary(void) {
	if (!wait_polls(1, 6)) {
		return false;
	}
	int count = load_events(), polls = 0;
	for (int i = 0; i < count; i++) {
		polls += !strcmp(events[i].kind, "RX") && !strcmp(events[i].text, STATUS_REQUEST);
	}
	trace_mark = poll_end_index(count, polls);
	return trace_mark >= 0;
}

static void trace_begin(bool polling) {
	if (polling) {
		wait_poll_boundary();
	} else {
		trace_mark = load_events();
	}
	pthread_mutex_lock(&observe_mutex);
	trace_pending_length = 0;
	*trace_pending = 0;
	for (int i = 0; i < observed_count; i++) {
		*observed[i].last_trace = 0;
	}
	pthread_mutex_unlock(&observe_mutex);
	atomic_store(&trace_active, true);
}

// a status poll is a request and its reply; the reply is reduced to the roof state and last action
static bool poll_at(int count, int index, char *line, size_t size) {
	if (index + 2 > count) {
		return false;
	}
	sim_event *request = events + index, *reply = request + 1;
	if (strcmp(request->kind, "RX") || strcmp(request->text, STATUS_REQUEST) || strcmp(reply->kind, "TX") || status_state(reply->text) < 0) {
		return false;
	}
	snprintf(line, size, "S POLL state=%d action=%d", status_state(reply->text), status_action(reply->text));
	return true;
}

static bool trace_end(const char *step, bool polling) {
	char line[512], previous_poll[256] = "";
	bool ok = polling ? wait_polls(1, 8) : (indigo_usleep(1500000), true);
	int count = load_events();
	if (polling) {
		int polls = 0;
		for (int i = 0; i < count; i++) {
			polls += !strcmp(events[i].kind, "RX") && !strcmp(events[i].text, STATUS_REQUEST);
		}
		int end = poll_end_index(count, polls);
		count = end >= 0 ? end : count;
	}
	snprintf(line, sizeof(line), "## %s", step);
	trace_append(line);
	for (int i = trace_mark; i < count; i++) {
		if (poll_at(count, i, line, sizeof(line))) {
			if (strcmp(line, previous_poll)) {
				trace_append(line);
				snprintf(previous_poll, sizeof(previous_poll), "%s", line);
			}
			i++;
			continue;
		}
		if (strcmp(events[i].kind, "RX") && strcmp(events[i].kind, "TX")) {
			continue;
		}
		*previous_poll = 0;
		snprintf(line, sizeof(line), "S %s %s", events[i].kind, events[i].text);
		trace_append(line);
	}
	atomic_store(&trace_active, false);
	pthread_mutex_lock(&observe_mutex);
	if (trace_length + trace_pending_length < sizeof(trace_text)) {
		memcpy(trace_text + trace_length, trace_pending, trace_pending_length);
		trace_length += trace_pending_length;
		trace_text[trace_length] = 0;
	}
	trace_pending_length = 0;
	pthread_mutex_unlock(&observe_mutex);
	if (!ok) {
		fprintf(stderr, "Trace step %s did not end with a status poll\n", step);
	}
	return ok;
}

#define TRACE_STEP(step, begin_polling, end_polling, action) do { \
	trace_begin(begin_polling); \
	CHECK(action); \
	CHECK(trace_end(step, end_polling)); \
} while (0)

static bool trace_connect(void) {
	unsigned before = revision_of(CONNECTION_PROPERTY_NAME);
	return request_switch(CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME) == INDIGO_OK && wait_settled(CONNECTION_PROPERTY_NAME, before, INDIGO_OK_STATE, 30) && wait_polls(1, 5);
}

static bool trace_abort_in_motion(void) {
	unsigned before = revision_of(DOME_SHUTTER_PROPERTY_NAME);
	return request_switch(DOME_SHUTTER_PROPERTY_NAME, DOME_SHUTTER_OPENED_ITEM_NAME) == INDIGO_OK && wait_rx("&O%#", 1, 5) && wait_polls(3, 5) && abort_motion(INDIGO_OK_STATE) && wait_settled(DOME_SHUTTER_PROPERTY_NAME, before, INDIGO_ALERT_STATE, 5) && wait_polls(1, 5);
}

static void reference_trace(void) {
	char *reference = NULL;
	trace_length = 0;
	*trace_text = 0;
	CHECK(driver_up());
	CHECK(set_port(simulator.port));
	TRACE_STEP("connect", false, true, trace_connect());
	TRACE_STEP("open", true, true, open_roof(INDIGO_OK_STATE, 20));
	TRACE_STEP("open again", true, true, open_roof(INDIGO_OK_STATE, 10));
	TRACE_STEP("close", true, true, close_roof(INDIGO_OK_STATE, 20));
	TRACE_STEP("abort idle", true, true, abort_motion(INDIGO_ALERT_STATE));
	TRACE_STEP("abort in motion", true, true, trace_abort_in_motion());
	TRACE_STEP("close after abort", true, true, close_roof(INDIGO_OK_STATE, 20));
	TRACE_STEP("motor configuration", true, true, change_number(X_MOTOR_CONF_PROPERTY_NAME, X_MOTOR_CONF_KP_ITEM_NAME, 190, INDIGO_OK_STATE, 10));
	TRACE_STEP("delay configuration", true, true, change_number(X_DELAY_CONF_PROPERTY_NAME, X_DELAY_CONF_WEATHER_ITEM_NAME, 90, INDIGO_OK_STATE, 10));
	TRACE_STEP("close conditions", true, true, change_switch(X_CLOSE_COND_PROPERTY_NAME, X_CLOSE_COND_POWER_ITEM_NAME, INDIGO_OK_STATE, 10));
	TRACE_STEP("unanswered configuration", true, true, inject("a", "silent", 1) && change_number(X_MOTOR_CONF_PROPERTY_NAME, X_MOTOR_CONF_KD_ITEM_NAME, 3, INDIGO_ALERT_STATE, 15));
	TRACE_STEP("checksum error", true, true, inject("G", "checksum", 1) && wait_state(DOME_SHUTTER_PROPERTY_NAME, INDIGO_ALERT_STATE, 5) && wait_state(DOME_SHUTTER_PROPERTY_NAME, INDIGO_OK_STATE, 5));
	TRACE_STEP("weather condition", true, true, control("weather", "1") && wait_light(X_SENSORS_PROPERTY_NAME, X_SENSORS_WEATHER_CONDITION_ITEM_NAME, INDIGO_ALERT_STATE, 5));
	TRACE_STEP("disconnect", true, false, disconnect());
	if (capture_path) {
		FILE *file = fopen(capture_path, "w");
		CHECK(file != NULL);
		fwrite(trace_text, 1, trace_length, file);
		fclose(file);
		printf("Reference trace written to %s\n", capture_path);
	} else {
		FILE *file = fopen(TALON6ROR_REFERENCE_TRACE_PATH, "r");
		CHECK(file != NULL);
		reference = calloc(1, TRACE_SIZE);
		size_t length = fread(reference, 1, TRACE_SIZE - 1, file);
		fclose(file);
		reference[length] = 0;
		if (strcmp(reference, trace_text)) {
			char path[PATH_MAX];
			snprintf(path, sizeof(path), "%s/actual_trace.txt", fixture_dir);
			file = fopen(path, "w");
			if (file) {
				fwrite(trace_text, 1, trace_length, file);
				fclose(file);
			}
			fprintf(stderr, "Reference trace mismatch; actual trace kept in %s (diff it against %s)\n", path, TALON6ROR_REFERENCE_TRACE_PATH);
			indigo_test_failures++;
		}
	}
cleanup:
	atomic_store(&trace_active, false);
	free(reference);
	driver_down();
}

