static void configuration_writes(void) {
	uint8_t bytes[64];
	CHECK(start_connected());
	CHECK(change_number(X_MOTOR_CONF_PROPERTY_NAME, X_MOTOR_CONF_KP_ITEM_NAME, 200, INDIGO_OK_STATE, 5));
	CHECK(wait_rx_prefix("&a", 1, 3));
	CHECK_EQ(59, frame_bytes(last_request_with_prefix("&a"), bytes, sizeof(bytes)));
	CHECK_EQ(200, ((bytes[2] & 0x7F) << 14) | ((bytes[3] & 0x7F) << 7) | (bytes[4] & 0x7F));
	// unrelated configuration bytes are preserved: communication delay 60, IP switch 120, TW time 120
	CHECK_EQ(60, ((bytes[29] & 0x7F) << 14) | ((bytes[30] & 0x7F) << 7) | (bytes[31] & 0x7F));
	CHECK_EQ(120, ((bytes[35] & 0x7F) << 14) | ((bytes[36] & 0x7F) << 7) | (bytes[37] & 0x7F));
	CHECK_EQ(120, ((bytes[53] & 0x7F) << 14) | ((bytes[54] & 0x7F) << 7) | (bytes[55] & 0x7F));
	int sum = 0;
	for (int i = 2; i < 56; i++) {
		sum += bytes[i];
	}
	CHECK_EQ((uint8_t)(0x80 | (-(sum % 128) & 0x7F)), bytes[56]);
	CHECK(change_number(X_DELAY_CONF_PROPERTY_NAME, X_DELAY_CONF_WEATHER_ITEM_NAME, 90, INDIGO_OK_STATE, 5));
	CHECK(wait_rx_prefix("&a", 2, 3));
	CHECK_EQ(59, frame_bytes(last_request_with_prefix("&a"), bytes, sizeof(bytes)));
	CHECK_EQ(90, ((bytes[23] & 0x7F) << 14) | ((bytes[24] & 0x7F) << 7) | (bytes[25] & 0x7F));
	CHECK_EQ(200, ((bytes[2] & 0x7F) << 14) | ((bytes[3] & 0x7F) << 7) | (bytes[4] & 0x7F));
	CHECK(change_switch(X_CLOSE_COND_PROPERTY_NAME, X_CLOSE_COND_POWER_ITEM_NAME, INDIGO_OK_STATE, 5));
	CHECK(wait_rx_prefix("&a", 3, 3));
	CHECK_EQ(59, frame_bytes(last_request_with_prefix("&a"), bytes, sizeof(bytes)));
	CHECK_EQ(0x01, bytes[49] & 0x07);
	CHECK(change_number(X_MOTOR_CONF_PROPERTY_NAME, X_MOTOR_CONF_ENC_FACTOR_ITEM_NAME, 2, INDIGO_OK_STATE, 5));
	CHECK(wait_rx_prefix("&a", 4, 3));
	CHECK_EQ(59, frame_bytes(last_request_with_prefix("&a"), bytes, sizeof(bytes)));
	CHECK_EQ(2, bytes[47] & 0x7F);
	CHECK_EQ(0x01, bytes[49] & 0x07);
	// the controller keeps the written values: they are read back after a reconnection
	CHECK(disconnect());
	CHECK(connect_to(simulator.port, INDIGO_OK_STATE, true));
	CHECK_EQ(200, value_of(X_MOTOR_CONF_PROPERTY_NAME, X_MOTOR_CONF_KP_ITEM_NAME));
	CHECK_EQ(90, value_of(X_DELAY_CONF_PROPERTY_NAME, X_DELAY_CONF_WEATHER_ITEM_NAME));
	CHECK_EQ(2, value_of(X_MOTOR_CONF_PROPERTY_NAME, X_MOTOR_CONF_ENC_FACTOR_ITEM_NAME));
	CHECK(switch_of(X_CLOSE_COND_PROPERTY_NAME, X_CLOSE_COND_POWER_ITEM_NAME));
	CHECK(!switch_of(X_CLOSE_COND_PROPERTY_NAME, X_CLOSE_COND_WEATHER_ITEM_NAME));
cleanup:
	driver_down();
}

