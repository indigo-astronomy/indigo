// index of the event following the reply of the n-th status request, or -1
static int poll_end_index(int count, int poll) {
	int seen = 0;
	for (int i = 0; i < count; i++) {
		if (!strcmp(events[i].kind, "RX") && !strcmp(events[i].text, STATUS_REQUEST) && ++seen == poll) {
			for (int j = i + 1; j < count && strcmp(events[j].kind, "RX"); j++) {
				if (!strcmp(events[j].kind, "TX")) {
					return j + 1;
				}
			}
			return -1;
		}
	}
	return -1;
}

static bool wait_polls(int polls, double timeout) {
	int target = rx_count(STATUS_REQUEST) + polls;
	double end = now() + timeout;
	do {
		int count = load_events();
		if (poll_end_index(count, target) >= 0) {
			return true;
		}
		indigo_usleep(20000);
	} while (now() < end);
	fprintf(stderr, "No %d status polls\n", polls);
	return false;
}

static bool rx_sequence(int mark, const char * const *expected, int expected_count, bool skip_polls, double timeout) {
	double end = now() + timeout;
	do {
		int count = load_events(), found = 0;
		bool matches = true;
		for (int i = mark; i < count && found < expected_count; i++) {
			if (strcmp(events[i].kind, "RX") || (skip_polls && !strcmp(events[i].text, STATUS_REQUEST) && strcmp(events[i].text, expected[found]))) {
				continue;
			}
			if (strcmp(events[i].text, expected[found])) {
				fprintf(stderr, "RX #%d: expected %s, got %s\n", found, expected[found], events[i].text);
				matches = false;
				break;
			}
			found++;
		}
		if (!matches) {
			return false;
		}
		if (found == expected_count) {
			return true;
		}
		indigo_usleep(20000);
	} while (now() < end);
	fprintf(stderr, "RX sequence incomplete\n");
	return false;
}

// decodes a logged frame ("&a 80 81 ...%#") back into bytes; returns the byte count
static int frame_bytes(const char *text, uint8_t *bytes, int max) {
	int count = 0;
	for (const char *pointer = text; *pointer && count < max; ) {
		if (*pointer == ' ') {
			unsigned value = 0;
			if (sscanf(pointer + 1, "%2x", &value) != 1) {
				return -1;
			}
			bytes[count++] = (uint8_t)value;
			pointer += 3;
		} else {
			bytes[count++] = (uint8_t)*pointer++;
		}
	}
	return count;
}

static int status_state(const char *reply) {
	uint8_t bytes[64];
	int count = frame_bytes(reply, bytes, sizeof(bytes));
	return count > 3 && bytes[1] == 'G' ? (bytes[2] & 0x70) >> 4 : -1;
}

static int status_action(const char *reply) {
	uint8_t bytes[64];
	int count = frame_bytes(reply, bytes, sizeof(bytes));
	return count > 3 && bytes[1] == 'G' ? bytes[2] & 0x0F : -1;
}

