// ---------------------------------------------------------------------------- driver lifecycle

static bool driver_up(void) {
	reset_observations();
	return bring_up_serial_driver(&talon6ror_dome);
}

static bool set_port(const char *port) {
	unsigned before = revision_of(DEVICE_PORT_PROPERTY_NAME);
	return indigo_change_text_property_1_raw(&simulator_test_client, context.driver_case->device_name, DEVICE_PORT_PROPERTY_NAME, DEVICE_PORT_ITEM_NAME, port) == INDIGO_OK && wait_settled(DEVICE_PORT_PROPERTY_NAME, before, strncmp(port, "/dev/indigo-", 12) ? INDIGO_OK_STATE : INDIGO_ALERT_STATE, 5);
}

static bool connect_to(const char *port, indigo_property_state expected, bool wait_first_poll) {
	if (!set_port(port)) {
		return false;
	}
	unsigned before = revision_of(CONNECTION_PROPERTY_NAME);
	// the connection flushes the controller banner for up to 5 s before the handshake
	if (request_switch(CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME) != INDIGO_OK || !wait_settled(CONNECTION_PROPERTY_NAME, before, expected, 30)) {
		return false;
	}
	if (expected != INDIGO_OK_STATE) {
		return !switch_of(CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME);
	}
	if (!switch_of(CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME)) {
		return false;
	}
	return !wait_first_poll || (wait_polls(1, 5) && wait_present(X_SENSORS_PROPERTY_NAME, true, 2));
}

static bool disconnect(void) {
	unsigned before = revision_of(CONNECTION_PROPERTY_NAME);
	return request_switch(CONNECTION_PROPERTY_NAME, CONNECTION_DISCONNECTED_ITEM_NAME) == INDIGO_OK && wait_settled(CONNECTION_PROPERTY_NAME, before, INDIGO_OK_STATE, 15) && switch_of(CONNECTION_PROPERTY_NAME, CONNECTION_DISCONNECTED_ITEM_NAME);
}

static bool start_connected(void) {
	return driver_up() && connect_to(simulator.port, INDIGO_OK_STATE, true);
}

static void driver_down(void) {
	DEFECT_EXIT();
	if (switch_of(CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME)) {
		disconnect();
	}
	indigo_result result = indigo_dome_talon6ror(INDIGO_DRIVER_SHUTDOWN, NULL);
	indigo_detach_client(&simulator_test_client);
	indigo_stop();
	pthread_mutex_lock(&observe_mutex);
	release_cached_properties();
	pthread_mutex_unlock(&observe_mutex);
	ASSERT_EQ_INT(INDIGO_OK, result);
}

// ---------------------------------------------------------------------------- simulator protocol

static bool exchange(indigo_uni_handle *handle, const char *request, uint8_t *reply, size_t size, long *length) {
	long written = indigo_uni_write(handle, request, (long)strlen(request));
	if (written != (long)strlen(request)) {
		return false;
	}
	long count = indigo_uni_read_section2(handle, (char *)reply, (long)size - 1, "#", "", INDIGO_DELAY(2), INDIGO_DELAY(1));
	if (count < 0) {
		return false;
	}
	reply[count] = 0;
	if (length) {
		*length = count;
	}
	return count > 0;
}

static int reply_position(const uint8_t *reply) {
	return ((reply[3] & 0x7F) << 14) | ((reply[4] & 0x7F) << 7) | (reply[5] & 0x7F);
}

static bool reply_checksum_valid(const uint8_t *reply, int payload) {
	int sum = 0;
	for (int i = 2; i < 2 + payload; i++) {
		sum += reply[i];
	}
	return reply[2 + payload] == (uint8_t)(0x80 | (-(sum % 128) & 0x7F));
}

static void simulator_protocol(void) {
	uint8_t reply[256];
	long length = 0;
	indigo_uni_handle *handle = indigo_uni_open_serial(simulator.port, INDIGO_LOG_DEBUG);
	CHECK(handle != NULL);
	CHECK(exchange(handle, "&V%#", reply, sizeof(reply), &length));
	CHECK_STR("&V3.20N--#", (const char *)reply);
	CHECK(exchange(handle, "&p%#", reply, sizeof(reply), &length));
	CHECK_EQ(58, length);
	CHECK(reply[1] == 'p' && reply_checksum_valid(reply, 54));
	CHECK(exchange(handle, "&G%#", reply, sizeof(reply), &length));
	CHECK_EQ(24, length);
	CHECK(reply[1] == 'G' && reply_checksum_valid(reply, 20));
	CHECK_EQ(1, (reply[2] & 0x70) >> 4);
	CHECK_EQ(0, reply_position(reply));
	CHECK_EQ(836, ((reply[6] & 0x7F) << 7) | (reply[7] & 0x7F));
	// closed sensor and mount at park
	CHECK_EQ(0x14, reply[16] & 0x7F);
	CHECK(exchange(handle, "&X%#", reply, sizeof(reply), &length));
	CHECK_STR("&ERROR#", (const char *)reply);
	// elapsed-time travel over the configured encoder ticks
	double started = now();
	CHECK(exchange(handle, "&O%#", reply, sizeof(reply), &length));
	CHECK_STR("&#", (const char *)reply);
	indigo_usleep(500000);
	CHECK(exchange(handle, "&G%#", reply, sizeof(reply), &length));
	CHECK_EQ(2, (reply[2] & 0x70) >> 4);
	CHECK_EQ(1, reply[2] & 0x0F);
	CHECK(reply_position(reply) > 1000 && reply_position(reply) < FULL_TRAVEL);
	for (int i = 0; i < 200 && (reply[2] & 0x70) != 0; i++) {
		indigo_usleep(20000);
		CHECK(exchange(handle, "&G%#", reply, sizeof(reply), &length));
	}
	CHECK_EQ(0, (reply[2] & 0x70) >> 4);
	CHECK_EQ(FULL_TRAVEL, reply_position(reply));
	CHECK(now() - started >= 1.8);
	// open sensor
	CHECK_EQ(0x0C, reply[16] & 0x7F);
	// stop between the end positions reports the error state
	CHECK(exchange(handle, "&P%#", reply, sizeof(reply), &length));
	indigo_usleep(600000);
	CHECK(exchange(handle, "&G%#", reply, sizeof(reply), &length));
	CHECK_EQ(3, (reply[2] & 0x70) >> 4);
	CHECK_EQ(2, reply[2] & 0x0F);
	CHECK(exchange(handle, "&S%#", reply, sizeof(reply), &length));
	CHECK(exchange(handle, "&G%#", reply, sizeof(reply), &length));
	CHECK_EQ(4, (reply[2] & 0x70) >> 4);
	CHECK_EQ(14, reply[2] & 0x0F);
	int stopped = reply_position(reply);
	indigo_usleep(300000);
	CHECK(exchange(handle, "&G%#", reply, sizeof(reply), &length));
	CHECK_EQ(stopped, reply_position(reply));
	// close without mount park
	CHECK(exchange(handle, "&C%#", reply, sizeof(reply), &length));
	for (int i = 0; i < 200 && (reply[2] & 0x70) != 0x10; i++) {
		indigo_usleep(20000);
		CHECK(exchange(handle, "&G%#", reply, sizeof(reply), &length));
	}
	CHECK_EQ(1, (reply[2] & 0x70) >> 4);
	CHECK_EQ(0, reply_position(reply));
	// close with mount park waits for the park sensor
	CHECK(control("parked", "0"));
	CHECK(exchange(handle, "&O%#", reply, sizeof(reply), &length));
	indigo_usleep(2100000);
	CHECK(exchange(handle, "&P%#", reply, sizeof(reply), &length));
	indigo_usleep(300000);
	CHECK(exchange(handle, "&G%#", reply, sizeof(reply), &length));
	CHECK_EQ(0, (reply[2] & 0x70) >> 4);
	CHECK_EQ(15, reply[2] & 0x0F);
	CHECK(control("parked", "1"));
	indigo_usleep(300000);
	CHECK(exchange(handle, "&G%#", reply, sizeof(reply), &length));
	CHECK_EQ(3, (reply[2] & 0x70) >> 4);
	CHECK_EQ(2, reply[2] & 0x0F);
	CHECK(exchange(handle, "&S%#", reply, sizeof(reply), &length));
	// safety conditions refuse opening
	CHECK(control("weather", "1"));
	CHECK(exchange(handle, "&O%#", reply, sizeof(reply), &length));
	CHECK_STR("&#", (const char *)reply);
	indigo_usleep(300000);
	CHECK(exchange(handle, "&G%#", reply, sizeof(reply), &length));
	CHECK_EQ(4, (reply[2] & 0x70) >> 4);
	CHECK_EQ(0x02, reply[16] & 0x02);
	CHECK(control("weather", "0"));
	// buttons and external control
	CHECK(control("position", "0"));
	CHECK(control("button", "open"));
	CHECK(exchange(handle, "&G%#", reply, sizeof(reply), &length));
	CHECK_EQ(2, (reply[2] & 0x70) >> 4);
	CHECK_EQ(0x20, reply[16] & 0x20);
	CHECK(control("stall", "1"));
	CHECK(exchange(handle, "&G%#", reply, sizeof(reply), &length));
	CHECK_EQ(4, (reply[2] & 0x70) >> 4);
	CHECK_EQ(13, reply[2] & 0x0F);
	CHECK(control("voltage", "700"));
	CHECK(exchange(handle, "&G%#", reply, sizeof(reply), &length));
	CHECK_EQ(700, ((reply[6] & 0x7F) << 7) | (reply[7] & 0x7F));
	// fault injection
	CHECK(inject("G", "error", 1));
	CHECK(exchange(handle, "&G%#", reply, sizeof(reply), &length));
	CHECK_STR("&ERROR#", (const char *)reply);
	CHECK(inject("G", "checksum", 1));
	CHECK(exchange(handle, "&G%#", reply, sizeof(reply), &length));
	CHECK(!reply_checksum_valid(reply, 20));
	CHECK(inject("G", "short", 1));
	CHECK(exchange(handle, "&G%#", reply, sizeof(reply), &length));
	CHECK(length < 24);
	CHECK(inject("G", "garbage", 1));
	CHECK(exchange(handle, "&G%#", reply, sizeof(reply), &length));
	CHECK_STR("x#", (const char *)reply);
	CHECK(exchange(handle, "", reply, sizeof(reply), &length));
	CHECK(inject("G", "silent", 1));
	CHECK(!exchange(handle, "&G%#", reply, sizeof(reply), &length));
	CHECK(inject_argument("G", "slow", 1, "300"));
	started = now();
	CHECK(exchange(handle, "&G%#", reply, sizeof(reply), &length));
	CHECK(now() - started >= 0.25);
	// configuration write validation
	CHECK(exchange(handle, "&p%#", reply, sizeof(reply), &length));
	uint8_t frame[64];
	frame[0] = '&';
	frame[1] = 'a';
	memcpy(frame + 2, reply + 2, 55);
	frame[3] = 0x81;
	frame[4] = 0xC8;
	int sum = 0;
	for (int i = 2; i < 56; i++) {
		sum += frame[i];
	}
	frame[56] = (uint8_t)(0x80 | (-(sum % 128) & 0x7F));
	frame[57] = '%';
	frame[58] = '#';
	CHECK(indigo_uni_write(handle, (const char *)frame, 59) == 59);
	CHECK(indigo_uni_read_section2(handle, (char *)reply, sizeof(reply) - 1, "#", "", INDIGO_DELAY(2), INDIGO_DELAY(1)) == 2);
	frame[56] ^= 0x01;
	CHECK(indigo_uni_write(handle, (const char *)frame, 59) == 59);
	length = indigo_uni_read_section2(handle, (char *)reply, sizeof(reply) - 1, "#", "", INDIGO_DELAY(2), INDIGO_DELAY(1));
	reply[length] = 0;
	CHECK_STR("&ERROR#", (const char *)reply);
	CHECK(exchange(handle, "&p%#", reply, sizeof(reply), &length));
	CHECK_EQ(200, ((reply[2] & 0x7F) << 14) | ((reply[3] & 0x7F) << 7) | (reply[4] & 0x7F));
cleanup:
	indigo_uni_close(&handle);
}

