// The Askar-WAF Wi-Fi port selection against a Wi-Fi focuser standing in for the real one: a UDP responder answers
// the WAF:discover broadcast with 127.0.0.1 and a TCP port, and a relay forwards that port to the serial simulator.
// It opens sockets, so it is an opt-in driver test, not part of test-integration.
//
// auto:// selects a serial port only, a discovered askar:// item never becomes auto://askar://...; askar:// without
// a host selects the first discovered Wi-Fi focuser at connect. A real Askar-WAF on the network answers the broadcast
// as well; the connection case does not connect to it and is skipped when such a focuser is listed first.

#include <indigo_drivers/focuser_askar/indigo_focuser_askar.h>

#include "serial_simulator_test_common.h"
