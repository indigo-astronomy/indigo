// Driver metadata, the published property inventory before and after connection, and the shape of
// both driver properties.
static void identity_inventory_and_property_contract(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	indigo_driver_info info;
	memset(&info, 0, sizeof(info));
	assert_simulator_driver_info(&arteskyflat_aux);
	SERIAL_CHECK_TRUE(start_external_serial_simulator(&simulator, AUX_ARTESKYFLAT_SIMULATOR_EXECUTABLE));
	SERIAL_CHECK_TRUE(bring_up_serial_driver(&arteskyflat_aux));
	online = true;
	enumerate_simulator_device();
	assert_device_interface(INDIGO_INTERFACE_AUX_LIGHTBOX);
	assert_defined_properties(arteskyflat_base_properties, ARRAY_SIZE(arteskyflat_base_properties));
	assert_not_defined_properties(arteskyflat_hidden_properties, ARRAY_SIZE(arteskyflat_hidden_properties));
	assert_not_defined_properties(arteskyflat_connected_properties, ARRAY_SIZE(arteskyflat_connected_properties));
	assert_defined_property_count(ARRAY_SIZE(arteskyflat_base_properties));
	SERIAL_CHECK_TRUE(connect_serial_device(&arteskyflat_aux, simulator.port));
	SERIAL_CHECK_TRUE(context.connected && context.last_connection_state == INDIGO_OK_STATE);
	assert_serial_aux_class_property_completeness();
	assert_defined_properties(arteskyflat_connected_properties, ARRAY_SIZE(arteskyflat_connected_properties));
	assert_not_defined_properties(arteskyflat_hidden_properties, ARRAY_SIZE(arteskyflat_hidden_properties));
	assert_defined_property_count(ARRAY_SIZE(arteskyflat_base_properties) + ARRAY_SIZE(arteskyflat_connected_properties));
	indigo_property *light_property = find_cached_property(AUX_LIGHT_SWITCH_PROPERTY_NAME);
	indigo_property *intensity_property = find_cached_property(AUX_LIGHT_INTENSITY_PROPERTY_NAME);
	indigo_item *intensity_item = find_cached_item(AUX_LIGHT_INTENSITY_PROPERTY_NAME, AUX_LIGHT_INTENSITY_ITEM_NAME);
	SERIAL_CHECK_TRUE(light_property != NULL && light_property->type == INDIGO_SWITCH_VECTOR && light_property->perm == INDIGO_RW_PERM && light_property->rule == INDIGO_ONE_OF_MANY_RULE && light_property->count == 2);
	assert_property_has_item(AUX_LIGHT_SWITCH_PROPERTY_NAME, AUX_LIGHT_SWITCH_ON_ITEM_NAME);
	assert_property_has_item(AUX_LIGHT_SWITCH_PROPERTY_NAME, AUX_LIGHT_SWITCH_OFF_ITEM_NAME);
	SERIAL_CHECK_TRUE(intensity_property != NULL && intensity_property->type == INDIGO_NUMBER_VECTOR && intensity_property->perm == INDIGO_RW_PERM && intensity_property->count == 1);
	SERIAL_CHECK_TRUE(intensity_item != NULL && intensity_item->number.min == 0 && intensity_item->number.max == 100 && intensity_item->number.step == 1 && intensity_item->number.value == 0 && !strcmp(intensity_item->number.format, "%.0f"));
	assert_number_item_in_range(AUX_LIGHT_INTENSITY_PROPERTY_NAME, AUX_LIGHT_INTENSITY_ITEM_NAME);
	assert_switch_item_value(AUX_LIGHT_SWITCH_PROPERTY_NAME, AUX_LIGHT_SWITCH_ON_ITEM_NAME, false);
	assert_switch_item_value(AUX_LIGHT_SWITCH_PROPERTY_NAME, AUX_LIGHT_SWITCH_OFF_ITEM_NAME, true);
	SERIAL_CHECK_EQ_INT(INDIGO_OK, arteskyflat_aux.entry(INDIGO_DRIVER_INFO, &info));
	SERIAL_CHECK_EQ_INT(INDIGO_DRIVER_API_3, INDIGO_DRIVER_API_GENERATION(info.version));
	// The driver opens the port without a handshake, so connecting sends nothing at all.
	SERIAL_CHECK_EQ_INT(0, event_count(&simulator, ">L000"));
	SERIAL_CHECK_EQ_INT(0, event_count(&simulator, ">D000"));
	SERIAL_CHECK_EQ_INT(0, event_count(&simulator, ">B000"));
cleanup:
	if (online) {
		stop_serial_driver(&arteskyflat_aux);
	}
	stop_external_serial_simulator(&simulator);
}

// AUX_LIGHT_INTENSITY is a percentage; the device takes 0-255 in ">Bxxx".
static void intensity_maps_percent_to_the_device_scale(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	static const struct { double percent; const char *command; } steps[] = {
		{ 0, ">B000" },
		{ 25, ">B063" },
		{ 50, ">B127" },
		{ 75, ">B191" },
		{ 100, ">B255" }
	};
	SERIAL_CHECK_TRUE(start_external_serial_simulator(&simulator, AUX_ARTESKYFLAT_SIMULATOR_EXECUTABLE));
	SERIAL_CHECK_TRUE(start_serial_driver(&arteskyflat_aux, simulator.port));
	online = true;
	clear_events(&simulator);
	for (int i = 0; i < ARRAY_SIZE(steps); i++) {
		SERIAL_CHECK_TRUE(change_intensity(steps[i].percent, INDIGO_OK_STATE));
		SERIAL_CHECK_TRUE(wait_for_event(&simulator, steps[i].command, 1));
		SERIAL_CHECK_TRUE(intensity_value() == steps[i].percent);
	}
cleanup:
	if (online) {
		stop_serial_driver(&arteskyflat_aux);
	}
	stop_external_serial_simulator(&simulator);
}

