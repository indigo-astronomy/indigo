// -------------------------------------------------------------------------------- simulator glue

static void simulator_path(const external_serial_simulator *simulator, const char *suffix, char *path, size_t size) {
	snprintf(path, size, "%s.%s", simulator->ready_file, suffix);
}

// The simulator consumes one armed fault with the first command whose operation matches selector.
static bool arm_fault(const external_serial_simulator *simulator, const char *action, const char *selector) {
	char path[PATH_MAX];
	simulator_path(simulator, "control", path, sizeof(path));
	FILE *file = fopen(path, "w");
	if (file == NULL) {
		return false;
	}
	fprintf(file, "%s %s\n", action, selector);
	return fclose(file) == 0;
}

static void clear_events(const external_serial_simulator *simulator) {
	char path[PATH_MAX];
	simulator_path(simulator, "events", path, sizeof(path));
	unlink(path);
}

static int event_count(const external_serial_simulator *simulator, const char *command) {
	char path[PATH_MAX];
	char line[64];
	int count = 0;
	simulator_path(simulator, "events", path, sizeof(path));
	FILE *file = fopen(path, "r");
	if (file == NULL) {
		return 0;
	}
	while (fgets(line, sizeof(line), file) != NULL) {
		line[strcspn(line, "\r\n")] = '\0';
		if (!strcmp(line, command)) {
			count++;
		}
	}
	fclose(file);
	return count;
}

static bool wait_for_event(const external_serial_simulator *simulator, const char *command, int expected_count) {
	for (int i = 0; i < 100; i++) {
		if (event_count(simulator, command) >= expected_count) {
			return true;
		}
		indigo_usleep(100000);
	}
	fprintf(stderr, "'%s' was recorded %d times, expected %d\n", command, event_count(simulator, command), expected_count);
	return false;
}

// -------------------------------------------------------------------------------- request helpers

static double intensity_value(void) {
	return cached_number_value(AUX_LIGHT_INTENSITY_PROPERTY_NAME, AUX_LIGHT_INTENSITY_ITEM_NAME);
}

static bool change_intensity(double percent, indigo_property_state expected_state) {
	unsigned int revision = property_revision(AUX_LIGHT_INTENSITY_PROPERTY_NAME);
	if (indigo_change_number_property_1(&simulator_test_client, arteskyflat_aux.device_name, AUX_LIGHT_INTENSITY_PROPERTY_NAME, AUX_LIGHT_INTENSITY_ITEM_NAME, percent) != INDIGO_OK) {
		return false;
	}
	return wait_for_property_state_seen_after(AUX_LIGHT_INTENSITY_PROPERTY_NAME, INDIGO_BUSY_STATE, revision) && wait_for_property_state_after(AUX_LIGHT_INTENSITY_PROPERTY_NAME, expected_state, revision);
}

static bool change_light(const char *item_name, indigo_property_state expected_state) {
	unsigned int revision = property_revision(AUX_LIGHT_SWITCH_PROPERTY_NAME);
	if (indigo_change_switch_property_1(&simulator_test_client, arteskyflat_aux.device_name, AUX_LIGHT_SWITCH_PROPERTY_NAME, item_name, true) != INDIGO_OK) {
		return false;
	}
	return wait_for_property_state_seen_after(AUX_LIGHT_SWITCH_PROPERTY_NAME, INDIGO_BUSY_STATE, revision) && wait_for_property_state_after(AUX_LIGHT_SWITCH_PROPERTY_NAME, expected_state, revision);
}

// The harness keeps an append-only list of every property it has seen defined, so live visibility
// is read from the property cache, which does follow deletion.
static bool connected_properties_published(bool expected) {
	for (int i = 0; i < ARRAY_SIZE(arteskyflat_connected_properties); i++) {
		if ((find_cached_property(arteskyflat_connected_properties[i]) != NULL) != expected) {
			fprintf(stderr, "%s is %spublished\n", arteskyflat_connected_properties[i], expected ? "not " : "");
			return false;
		}
	}
	return true;
}

// AUX_LIGHT_INTENSITY is persistent; leave the saved configuration at the attach-time default so a
// case that saved one cannot decide what the next case starts from.
static bool restore_saved_defaults(void) {
	return change_intensity(0, INDIGO_OK_STATE) && save_configuration();
}

