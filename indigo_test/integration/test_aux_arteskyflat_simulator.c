// AUX lightbox coverage for indigo_aux_arteskyflat against the standalone Artesky simulator over a
// real PTY. The Artesky Flat Box USB speaks the Alnitak generic command set documented in
// ../../indigo_drivers/aux_flipflat/Alnitak_GenericCommandsR4.pdf. Unlike the other Alnitak
// drivers in the tree this one validates the whole reply line - eight bytes, leading '*', echoed
// operation, two numeric id digits and the echoed three digit value - so reply framing is the
// central contract here, alongside the percent to 0-255 conversion and the rule that a rejected
// request leaves the last accepted intensity and light selection untouched.

