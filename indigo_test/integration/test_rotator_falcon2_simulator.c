// Sync redefines the angle without turning anything, so a far-away sync has to land immediately
// rather than travelling there.
static void sync_redefines_the_angle_without_moving(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_falcon(&simulator, NULL));
	SERIAL_CHECK_TRUE(start_serial_driver(&falcon_rotator, simulator.port));
	online = true;
	SERIAL_CHECK_TRUE(select_mode(ROTATOR_ON_POSITION_SET_GOTO_ITEM_NAME));
	SERIAL_CHECK_TRUE(goto_position(4));
	SERIAL_CHECK_TRUE(select_mode(ROTATOR_ON_POSITION_SET_SYNC_ITEM_NAME));
	// 300 degrees away: as a move this would take half a minute, as a sync it is immediate.
	time_t started = time(NULL);
	SERIAL_CHECK_TRUE(request_position(304));
	SERIAL_CHECK_TRUE(wait_for_property_not_busy(ROTATOR_POSITION_PROPERTY_NAME));
	SERIAL_CHECK_TRUE(wait_for_number_item_value(ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME, 304, .1));
	printf("Sync to 304 deg took %ld s\n", (long)(time(NULL) - started));
	SERIAL_CHECK_TRUE(time(NULL) - started < 10);
	// And the rotator moves normally from the synced angle afterwards.
	SERIAL_CHECK_TRUE(select_mode(ROTATOR_ON_POSITION_SET_GOTO_ITEM_NAME));
	SERIAL_CHECK_TRUE(goto_position(300));
cleanup:
	if (online) { stop_serial_driver(&falcon_rotator); }
	stop_external_serial_simulator(&simulator);
}

// A relative move is an absolute goto the driver computes itself, and the result has to stay inside
// one turn in both directions.
static void relative_move_wraps_around_the_turn(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_falcon(&simulator, NULL));
	SERIAL_CHECK_TRUE(start_serial_driver(&falcon_rotator, simulator.port));
	online = true;
	SERIAL_CHECK_TRUE(sync_to(355));

	// Past 360 the destination has to come back round to the low end, not saturate at the item
	// maximum. The rotator is then stopped: the simulator would crawl the long way round to get
	// there, which says nothing about the driver.
	SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_change_number_property_1(&simulator_test_client, falcon_rotator.device_name, ROTATOR_RELATIVE_MOVE_PROPERTY_NAME, ROTATOR_RELATIVE_MOVE_ITEM_NAME, 8));
	SERIAL_CHECK_TRUE(wait_for_position_target(3));
	indigo_item *item = find_cached_item(ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME);
	printf("355 + 8 aims at %.2f deg\n", item == NULL ? NAN : item->number.target);
	SERIAL_CHECK_TRUE(abort_and_settle());

	// And below zero it has to come back round to the high end.
	SERIAL_CHECK_TRUE(sync_to(3));
	SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_change_number_property_1(&simulator_test_client, falcon_rotator.device_name, ROTATOR_RELATIVE_MOVE_PROPERTY_NAME, ROTATOR_RELATIVE_MOVE_ITEM_NAME, -8));
	SERIAL_CHECK_TRUE(wait_for_position_target(355));
	item = find_cached_item(ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME);
	printf("3 - 8 aims at %.2f deg\n", item == NULL ? NAN : item->number.target);
	SERIAL_CHECK_TRUE(abort_and_settle());

	// A relative move that stays inside the turn completes normally.
	SERIAL_CHECK_TRUE(sync_to(10));
	SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_change_number_property_1(&simulator_test_client, falcon_rotator.device_name, ROTATOR_RELATIVE_MOVE_PROPERTY_NAME, ROTATOR_RELATIVE_MOVE_ITEM_NAME, 5));
	SERIAL_CHECK_TRUE(wait_for_property_state(ROTATOR_RELATIVE_MOVE_PROPERTY_NAME, INDIGO_OK_STATE));
	printf("10 + 5 reached %.2f deg\n", cached_number_value(ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME));
	SERIAL_CHECK_TRUE(fabs(cached_number_value(ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME) - 15) < .2);
cleanup:
	if (online) { abort_and_settle(); stop_serial_driver(&falcon_rotator); }
	stop_external_serial_simulator(&simulator);
}

// Aborting leaves the rotator wherever it stopped, so the move must not be reported as successful
// and the published angle has to be the one it actually reached.
static void abort_stops_a_move_short(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_falcon(&simulator, NULL));
	SERIAL_CHECK_TRUE(start_serial_driver(&falcon_rotator, simulator.port));
	online = true;
	SERIAL_CHECK_TRUE(sync_to(0));
	SERIAL_CHECK_TRUE(request_position(90));
	SERIAL_CHECK_TRUE(wait_for_property_state(ROTATOR_POSITION_PROPERTY_NAME, INDIGO_BUSY_STATE));
	indigo_usleep(1500000);
	SERIAL_CHECK_TRUE(set_switch(ROTATOR_ABORT_MOTION_PROPERTY_NAME, ROTATOR_ABORT_MOTION_ITEM_NAME));
	SERIAL_CHECK_TRUE(wait_for_property_not_busy(ROTATOR_POSITION_PROPERTY_NAME));
	printf("Aborted at %.2f deg on the way to 90\n", position());
	// It stopped somewhere short of the target, and the abort is not reported as an arrival.
	SERIAL_CHECK_TRUE(position() > 0 && position() < 89);
	indigo_property *property = find_cached_property(ROTATOR_POSITION_PROPERTY_NAME);
	SERIAL_CHECK_TRUE(property != NULL && property->state == INDIGO_ALERT_STATE);
	// The abort trigger is momentary and the rotator still takes commands.
	assert_switch_item_value(ROTATOR_ABORT_MOTION_PROPERTY_NAME, ROTATOR_ABORT_MOTION_ITEM_NAME, false);
	SERIAL_CHECK_TRUE(goto_position(2));
cleanup:
	if (online) { abort_and_settle(); stop_serial_driver(&falcon_rotator); }
	stop_external_serial_simulator(&simulator);
}

// The two motion properties drive the same motor, so each refuses to start while the other is
// running instead of interleaving two sets of goto commands.
static void the_two_motion_properties_refuse_to_overlap(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_falcon(&simulator, NULL));
	SERIAL_CHECK_TRUE(start_serial_driver(&falcon_rotator, simulator.port));
	online = true;
	SERIAL_CHECK_TRUE(sync_to(0));

	SERIAL_CHECK_TRUE(request_position(60));
	SERIAL_CHECK_TRUE(wait_for_property_state(ROTATOR_POSITION_PROPERTY_NAME, INDIGO_BUSY_STATE));
	// A relative move arriving mid-goto has to be refused, not queued behind it.
	SERIAL_CHECK_TRUE(assert_rejected_number_change(ROTATOR_RELATIVE_MOVE_PROPERTY_NAME, ROTATOR_RELATIVE_MOVE_ITEM_NAME, 5));
	SERIAL_CHECK_TRUE(abort_and_settle());
cleanup:
	if (online) { abort_and_settle(); stop_serial_driver(&falcon_rotator); }
	stop_external_serial_simulator(&simulator);
}

