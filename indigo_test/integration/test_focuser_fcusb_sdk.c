static void property_contract(void) {
	SERIAL_CHECK_TRUE(driver_up());
	reset_simulator_context(&focuser);
	enumerate_simulator_device();
	SERIAL_CHECK_TRUE(!has_defined_property(FOCUSER_STEPS_PROPERTY_NAME));
	SERIAL_CHECK_TRUE(connect_focuser());
	assert_property_has_item(FOCUSER_STEPS_PROPERTY_NAME, FOCUSER_STEPS_ITEM_NAME);
	assert_property_has_item(FOCUSER_DIRECTION_PROPERTY_NAME, FOCUSER_DIRECTION_MOVE_INWARD_ITEM_NAME);
	assert_property_has_item(FOCUSER_DIRECTION_PROPERTY_NAME, FOCUSER_DIRECTION_MOVE_OUTWARD_ITEM_NAME);
	assert_property_has_item(FOCUSER_ABORT_MOTION_PROPERTY_NAME, FOCUSER_ABORT_MOTION_ITEM_NAME);
	assert_property_has_item(FOCUSER_SPEED_PROPERTY_NAME, FOCUSER_SPEED_ITEM_NAME);
	assert_property_has_item(X_FOCUSER_FREQUENCY_PROPERTY_NAME, X_FOCUSER_FREQUENCY_1_ITEM_NAME);
	assert_property_has_item(X_FOCUSER_FREQUENCY_PROPERTY_NAME, X_FOCUSER_FREQUENCY_4_ITEM_NAME);
	assert_property_has_item(X_FOCUSER_FREQUENCY_PROPERTY_NAME, X_FOCUSER_FREQUENCY_16_ITEM_NAME);
	// The focuser has no encoder, so there is no position, no sync and no
	// temperature of any kind.
	SERIAL_CHECK_TRUE(!has_defined_property(FOCUSER_POSITION_PROPERTY_NAME));
	SERIAL_CHECK_TRUE(!has_defined_property(FOCUSER_ON_POSITION_SET_PROPERTY_NAME));
	SERIAL_CHECK_TRUE(!has_defined_property(FOCUSER_TEMPERATURE_PROPERTY_NAME));
	SERIAL_CHECK_TRUE(!has_defined_property(FOCUSER_BACKLASH_PROPERTY_NAME));
	// The speed item drives the motor power instead of a step rate.
	indigo_item *speed = find_cached_item(FOCUSER_SPEED_PROPERTY_NAME, FOCUSER_SPEED_ITEM_NAME);
	SERIAL_CHECK_TRUE(speed != NULL && speed->number.max == 255 && speed->number.value == 255);
	SERIAL_CHECK_TRUE(!strcmp(speed->label, "Power (0-255)"));
	SERIAL_CHECK_TRUE(switch_is(X_FOCUSER_FREQUENCY_PROPERTY_NAME, X_FOCUSER_FREQUENCY_1_ITEM_NAME, true));
	disconnect_serial_device(&focuser);
	for (int i = 0; i < 50 && find_cached_property(X_FOCUSER_FREQUENCY_PROPERTY_NAME) != NULL; i++) {
		indigo_usleep(100000);
	}
	SERIAL_CHECK_TRUE(find_cached_property(X_FOCUSER_FREQUENCY_PROPERTY_NAME) == NULL);
cleanup:
	driver_stop();
}

