static double now_seconds(void) {
	struct timeval tv;
	gettimeofday(&tv, NULL);
	return tv.tv_sec + tv.tv_usec / 1e6;
}

static void reset_fake(void) {
	atomic_store(&opened, 0);
	atomic_store(&closed, 0);
	atomic_store(&calls, 0);
	atomic_store(&calls_after_close, 0);
	atomic_store(&references, 0);
	atomic_store(&attached, 0);
	atomic_store(&fail_open, 0);
	atomic_store(&fail_power, 0);
	atomic_store(&fail_frequency, 0);
	atomic_store(&fail_move, 0);
	atomic_store(&fail_stop, 0);
	atomic_store(&power, -1);
	atomic_store(&frequency, -1);
	atomic_store(&direction, 0);
	atomic_store(&stops, 0);
	atomic_store(&moves, 0);
	atomic_store(&fail_queue, 0);
	atomic_store(&fail_register, 0);
	atomic_store(&fail_attach, 0);
	motion_started = motion_stopped = 0;
	hotplug = NULL;
}

static bool transfer(void) {
	atomic_fetch_add(&calls, 1);
	if (atomic_load(&opened) == atomic_load(&closed)) {
		atomic_fetch_add(&calls_after_close, 1);
		return false;
	}
	return true;
}

