static bool state_seen(const char *property, indigo_property_state state, unsigned int revision) {
	if (wait_for_property_state_seen_after(property, state, revision)) {
		return true;
	}
	indigo_property *cached = find_cached_property(property);
	fprintf(stderr, "%s never published state %d (current %d)\n", property, state, cached == NULL ? -1 : cached->state);
	return false;
}

static bool number_change(const char *property, const char *item, double value, indigo_property_state state) {
	unsigned int revision = property_state_revision(property, state);
	return indigo_change_number_property_1(&simulator_test_client, focuser.device_name, property, item, value) == INDIGO_OK && state_seen(property, state, revision);
}

static bool switch_change(const char *property, const char *item, indigo_property_state state) {
	unsigned int revision = property_state_revision(property, state);
	return indigo_change_switch_property_1(&simulator_test_client, focuser.device_name, property, item, true) == INDIGO_OK && state_seen(property, state, revision);
}

static bool switch_is(const char *property_name, const char *item_name, bool expected) {
	indigo_item *item = find_cached_item(property_name, item_name);
	if (item == NULL || item->sw.value != expected) {
		fprintf(stderr, "%s.%s: expected %s\n", property_name, item_name, expected ? "on" : "off");
		return false;
	}
	return true;
}

static bool wait_for_direction(int expected) {
	for (int i = 0; i < 400; i++) {
		if (atomic_load(&direction) == expected) {
			return true;
		}
		indigo_usleep(10000);
	}
	fprintf(stderr, "Motor direction never became %d, it is %d\n", expected, atomic_load(&direction));
	return false;
}

// A complete move: it starts in the requested direction and the finalizer stops
// the motor again. The driver moves inward by default, which is what most
// scenarios use, so -1 is the expected direction unless a scenario selects the
// other one.
static bool move_completes(double milliseconds, int expected_direction) {
	unsigned int done = property_state_revision(FOCUSER_STEPS_PROPERTY_NAME, INDIGO_OK_STATE);
	if (!number_change(FOCUSER_STEPS_PROPERTY_NAME, FOCUSER_STEPS_ITEM_NAME, milliseconds, INDIGO_BUSY_STATE) || !wait_for_direction(expected_direction)) {
		return false;
	}
	if (!state_seen(FOCUSER_STEPS_PROPERTY_NAME, INDIGO_OK_STATE, done)) {
		return false;
	}
	if (atomic_load(&direction) != 0) {
		fprintf(stderr, "Motor still running after the move\n");
		return false;
	}
	return true;
}

static bool driver_up(void) {
	reset_fake();
	if (!bring_up_serial_driver(&focuser)) {
		return false;
	}
	indigo_queue_drain(driver_queue);
	return true;
}

static bool connect_focuser(void) {
	return connect_serial_device(&focuser, NULL);
}

static bool driver_start(void) {
	return driver_up() && connect_focuser();
}

static void driver_stop(void) {
	if (context.connected) {
		disconnect_serial_device(&focuser);
	}
	tear_down_serial_driver(&focuser);
	ASSERT_EQ_INT(0, attached);
	ASSERT_EQ_INT(0, references);
	ASSERT_EQ_INT(opened, closed);
	ASSERT_EQ_INT(0, calls_after_close);
}

static void plug(void) {
	hotplug(NULL, (libusb_device *)(uintptr_t)1, LIBUSB_HOTPLUG_EVENT_DEVICE_ARRIVED, NULL);
	indigo_queue_drain(driver_queue);
}

static void unplug(void) {
	hotplug(NULL, (libusb_device *)(uintptr_t)1, LIBUSB_HOTPLUG_EVENT_DEVICE_LEFT, NULL);
	indigo_queue_drain(driver_queue);
}

