// ---------------------------------------------------------------------------- driver lifecycle

static bool driver_up(void) {
	pthread_mutex_lock(&observe_mutex);
	observed_count = 0;
	pthread_mutex_unlock(&observe_mutex);
	return bring_up_serial_driver(&dsd_focuser);
}

static bool set_port(const char *port) {
	unsigned before = revision_of(DEVICE_PORT_PROPERTY_NAME);
	return indigo_change_text_property_1_raw(&simulator_test_client, context.driver_case->device_name, DEVICE_PORT_PROPERTY_NAME, DEVICE_PORT_ITEM_NAME, port) == INDIGO_OK && wait_settled(DEVICE_PORT_PROPERTY_NAME, before, strncmp(port, "/dev/indigo-", 12) ? INDIGO_OK_STATE : INDIGO_ALERT_STATE, 5);
}

static bool connect_to(const char *port, indigo_property_state expected, bool wait_initial_poll) {
	if (!set_port(port)) {
		return false;
	}
	int polls = rx_count("[GMOV]");
	unsigned before = revision_of(CONNECTION_PROPERTY_NAME);
	if (indigo_change_switch_property_1(&simulator_test_client, context.driver_case->device_name, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, true) != INDIGO_OK || !wait_settled(CONNECTION_PROPERTY_NAME, before, expected, 20)) {
		return false;
	}
	if (expected != INDIGO_OK_STATE) {
		return !switch_of(CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME);
	}
	if (!switch_of(CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME)) {
		return false;
	}
	if (!wait_initial_poll) {
		return true;
	}
	unsigned position = revision_of(FOCUSER_POSITION_PROPERTY_NAME);
	return wait_rx("[GMOV]", polls + 1, 3) && wait_fresh_state(FOCUSER_POSITION_PROPERTY_NAME, position, INDIGO_OK_STATE, 3);
}

static bool disconnect(void) {
	unsigned before = revision_of(CONNECTION_PROPERTY_NAME);
	return indigo_change_switch_property_1(&simulator_test_client, context.driver_case->device_name, CONNECTION_PROPERTY_NAME, CONNECTION_DISCONNECTED_ITEM_NAME, true) == INDIGO_OK && wait_settled(CONNECTION_PROPERTY_NAME, before, INDIGO_OK_STATE, 15) && switch_of(CONNECTION_PROPERTY_NAME, CONNECTION_DISCONNECTED_ITEM_NAME);
}

static bool start_connected(void) {
	return driver_up() && connect_to(simulator.port, INDIGO_OK_STATE, true);
}

static void driver_down(void) {
	DEFECT_EXIT();
	if (switch_of(CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME)) {
		disconnect();
	}
	indigo_result result = indigo_focuser_dsd(INDIGO_DRIVER_SHUTDOWN, NULL);
	indigo_detach_client(&simulator_test_client);
	indigo_stop();
	pthread_mutex_lock(&observe_mutex);
	release_cached_properties();
	pthread_mutex_unlock(&observe_mutex);
	ASSERT_EQ_INT(INDIGO_OK, result);
}

// ---------------------------------------------------------------------------- simulator protocol

static bool exchange(indigo_uni_handle *handle, const char *request, const char *expected, char *reply, size_t size) {
	char buffer[128];
	if (indigo_uni_discard(handle) < 0 || indigo_uni_write(handle, request, (long)strlen(request)) != (long)strlen(request)) {
		return false;
	}
	if (expected == NULL && reply == NULL) {
		return true;
	}
	long count = indigo_uni_read_section2(handle, buffer, sizeof(buffer) - 1, ")", "", INDIGO_DELAY(1), INDIGO_DELAY(0.2));
	if (count < 0) {
		return false;
	}
	buffer[count] = 0;
	if (reply) {
		snprintf(reply, size, "%s", buffer);
	}
	if (expected && strcmp(buffer, expected)) {
		fprintf(stderr, "%s: expected %s, got %s\n", request, expected, buffer);
		return false;
	}
	return true;
}

