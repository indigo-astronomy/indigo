static void reference_trace(void) {
	char *reference = NULL;
	trace_length = 0;
	*trace_text = 0;
	trace_model("af1");
	CHECK(indigo_test_failures == 0);
	trace_model("af2");
	CHECK(indigo_test_failures == 0);
	trace_model("af3");
	CHECK(indigo_test_failures == 0);
	if (capture_path) {
		FILE *file = fopen(capture_path, "w");
		CHECK(file != NULL);
		fwrite(trace_text, 1, trace_length, file);
		fclose(file);
		printf("Reference trace written to %s\n", capture_path);
	} else {
		FILE *file = fopen(DSD_REFERENCE_TRACE_PATH, "r");
		CHECK(file != NULL);
		reference = calloc(1, TRACE_SIZE);
		size_t length = fread(reference, 1, TRACE_SIZE - 1, file);
		fclose(file);
		reference[length] = 0;
		if (strcmp(reference, trace_text)) {
			char path[PATH_MAX];
			snprintf(path, sizeof(path), "%s/actual_trace.txt", fixture_dir);
			file = fopen(path, "w");
			if (file) {
				fwrite(trace_text, 1, trace_length, file);
				fclose(file);
			}
			fprintf(stderr, "Reference trace mismatch; actual trace kept in %s (diff it against %s)\n", path, DSD_REFERENCE_TRACE_PATH);
			indigo_test_failures++;
		}
	}
cleanup:
	free(reference);
}

