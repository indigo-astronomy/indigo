static bool wait_quiet(double window, double timeout) {
	double end = now() + timeout, stable = now();
	int last_events = -1;
	unsigned last_revisions = 0;
	do {
		int count = load_events(), filtered = 0;
		for (int i = 0; i < count; i++) {
			if (!is_temperature_exchange(count, i) && strcmp(events[i].kind, "CONTROL")) {
				filtered++;
			}
		}
		unsigned revisions = atomic_load(&trace_revisions);
		if (filtered != last_events || revisions != last_revisions) {
			last_events = filtered;
			last_revisions = revisions;
			stable = now();
		} else if (now() - stable >= window) {
			return true;
		}
		indigo_usleep(50000);
	} while (now() < end);
	return false;
}

static void mask_digits(char *text) {
	char *output = text;
	for (char *input = text; *input; input++) {
		if (*input >= '0' && *input <= '9') {
			if (output == text || output[-1] != '#') {
				*output++ = '#';
			}
		} else {
			*output++ = *input;
		}
	}
	*output = 0;
}

static void trace_append(const char *line) {
	int written = snprintf(trace_text + trace_length, sizeof(trace_text) - trace_length, "%s\n", line);
	if (written > 0 && trace_length + written < sizeof(trace_text)) {
		trace_length += written;
	}
}

static void trace_begin(void) {
	wait_quiet(0.8, 10);
	pthread_mutex_lock(&observe_mutex);
	trace_pending_length = 0;
	*trace_pending = 0;
	pthread_mutex_unlock(&observe_mutex);
	trace_mark = load_events();
	atomic_store(&trace_active, true);
}

static bool trace_end(const char *step, bool mask) {
	bool quiet = wait_quiet(0.8, 20);
	char line[256];
	snprintf(line, sizeof(line), "## %s", step);
	trace_append(line);
	int count = load_events();
	bool polling = false, gpos_read = false, stopped = false;
	for (int i = trace_mark; i < count; i++) {
		if (is_temperature_exchange(count, i) || (strcmp(events[i].kind, "RX") && strcmp(events[i].kind, "TX") && strcmp(events[i].kind, "FAULT"))) {
			continue;
		}
		if (mask && !strcmp(events[i].kind, "RX") && (!strcmp(events[i].text, "[GMOV]") || !strcmp(events[i].text, "[GPOS]")) && i + 1 < count && !strcmp(events[i + 1].kind, "TX")) {
			// polls around an asynchronous abort are timing dependent: drop them, keep one position readback
			if (!strcmp(events[i].text, "[GPOS]") && stopped && !gpos_read) {
				trace_append("S RX [GPOS]");
				trace_append("S TX (#)");
			}
			gpos_read |= stopped && !strcmp(events[i].text, "[GPOS]");
			i++;
			continue;
		}
		if (!strcmp(events[i].kind, "RX") && !strcmp(events[i].text, "[GMOV]") && i + 3 < count && !strcmp(events[i + 1].text, "(1)") && !strcmp(events[i + 2].text, "[GPOS]")) {
			if (!polling) {
				trace_append("S POLL moving");
			}
			polling = true;
			i += 3;
			continue;
		}
		polling = false;
		stopped |= !strcmp(events[i].kind, "RX") && !strcmp(events[i].text, "[STOP]");
		snprintf(line, sizeof(line), "S %s %s", events[i].kind, events[i].text);
		if (mask && !strcmp(events[i].kind, "TX")) {
			mask_digits(line);
		}
		trace_append(line);
	}
	atomic_store(&trace_active, false);
	pthread_mutex_lock(&observe_mutex);
	if (mask) {
		mask_digits(trace_pending);
		trace_pending_length = strlen(trace_pending);
		// late poll publications around an asynchronous abort are timing dependent: keep first occurrences only
		static char unique[sizeof(trace_pending) + 1];
		size_t unique_length = 1;
		unique[0] = '\n';
		unique[1] = 0;
		for (char *line_start = trace_pending, *line_end; (line_end = strchr(line_start, '\n')) != NULL; line_start = line_end + 1) {
			char needle[520];
			snprintf(needle, sizeof(needle), "\n%.*s\n", (int)(line_end - line_start), line_start);
			if (strstr(unique, needle) == NULL) {
				unique_length += (size_t)snprintf(unique + unique_length, sizeof(unique) - unique_length, "%s", needle + 1);
			}
		}
		memcpy(trace_pending, unique + 1, unique_length);
		trace_pending_length = unique_length - 1;
	}
	if (trace_length + trace_pending_length < sizeof(trace_text)) {
		memcpy(trace_text + trace_length, trace_pending, trace_pending_length);
		trace_length += trace_pending_length;
		trace_text[trace_length] = 0;
	}
	trace_pending_length = 0;
	pthread_mutex_unlock(&observe_mutex);
	if (!quiet) {
		fprintf(stderr, "Trace step %s did not become quiet\n", step);
	}
	return quiet;
}

