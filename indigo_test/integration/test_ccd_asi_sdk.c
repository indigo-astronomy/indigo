ASI_ERROR_CODE ASIPulseGuideOn(int id, ASI_GUIDE_DIRECTION direction) {
	SDK_CHECK(id, true);
	if (camera(id)->guide_on_error) {
		return ASI_ERROR_GENERAL_ERROR;
	}
	pthread_mutex_lock(&pulse_mutex);
	pulse_measurement *sample = &pulse_measurements[camera(id) - cameras][direction];
	clock_gettime(CLOCK_MONOTONIC, &sample->started);
	sample->active = true;
	pthread_mutex_unlock(&pulse_mutex);
	atomic_fetch_or(&camera(id)->relays, 1 << direction);
	atomic_fetch_add(&pulse_writes, 1);
	return ASI_SUCCESS;
}

ASI_ERROR_CODE ASIPulseGuideOff(int id, ASI_GUIDE_DIRECTION direction) {
	SDK_CHECK(id, true);
	if (camera(id)->guide_off_error) {
		return ASI_ERROR_GENERAL_ERROR;
	}
	pthread_mutex_lock(&pulse_mutex);
	pulse_measurement *sample = &pulse_measurements[camera(id) - cameras][direction];
	if (sample->active) {
		struct timespec now;
		clock_gettime(CLOCK_MONOTONIC, &now);
		sample->duration_ms = (now.tv_sec - sample->started.tv_sec) * 1000.0 + (now.tv_nsec - sample->started.tv_nsec) / 1000000.0;
		sample->active = false;
		sample->completed++;
	}
	pthread_mutex_unlock(&pulse_mutex);
	atomic_fetch_and(&camera(id)->relays, ~(1 << direction));
	atomic_fetch_add(&pulse_writes, 1);
	return ASI_SUCCESS;
}

