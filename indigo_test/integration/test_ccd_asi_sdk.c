static const ASI_CONTROL_TYPE controls[] = { ASI_EXPOSURE, ASI_GAIN, ASI_GAMMA, ASI_OFFSET, ASI_BANDWIDTHOVERLOAD, ASI_TEMPERATURE, ASI_TARGET_TEMP, ASI_COOLER_ON, ASI_COOLER_POWER_PERC, ASI_WB_R, ASI_WB_B, ASI_GPS_SUPPORT, ASI_ROLLING_INTERVAL };
