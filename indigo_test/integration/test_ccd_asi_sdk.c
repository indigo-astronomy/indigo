static void guide_timing_measurements(void) {
	ASSERT_TRUE(connect_device(0, true));
	ASSERT_TRUE(connect_device(1, true));
	const int directions[] = { ASI_GUIDE_EAST, ASI_GUIDE_WEST, ASI_GUIDE_NORTH, ASI_GUIDE_SOUTH };
	const char *names[] = { "EAST", "WEST", "NORTH", "SOUTH" };
	const double durations[] = { 20, 100, 500 };
	for (int workload = 0; workload < 2; workload++) {
		if (workload) {
			ASSERT_EQ_INT(INDIGO_OK, indigo_change_number_property(&test_client, observed[0].name, "CCD_STREAMING", 2, (const char *[]){ "EXPOSURE", "COUNT" }, (double[]){ 0.05, -1 }));
			ASSERT_TRUE(wait_count(&cameras[0].video_starts, 1));
		}
		for (int direction = 0; direction < 4; direction++) {
			const char *property = direction < 2 ? "GUIDER_GUIDE_RA" : "GUIDER_GUIDE_DEC";
			for (int duration = 0; duration < 3; duration++) {
				double errors[4], sum = 0, squares = 0, maximum_absolute = 0;
				for (int trial = 0; trial < 5; trial++) {
					ASSERT_EQ_INT(INDIGO_OK, indigo_change_number_property_1(&test_client, observed[1].name, property, names[direction], durations[duration]));
					ASSERT_TRUE(wait_state(1, property, INDIGO_OK_STATE));
					pthread_mutex_lock(&pulse_mutex);
					double actual = pulse_measurements[0][directions[direction]].duration_ms;
					pthread_mutex_unlock(&pulse_mutex);
					ASSERT_TRUE(isfinite(actual) && actual >= 0 && actual < 4000);
					if (trial) {
						double error = actual - durations[duration];
						errors[trial - 1] = error;
						sum += error;
						squares += error * error;
						maximum_absolute = fmax(maximum_absolute, fabs(error));
					}
				}
				qsort(errors, 4, sizeof(double), compare_double);
				double mean = sum / 4;
				printf("TIMING %s %s requested_ms=%.0f n=4 warmup=1 actual_mean_ms=%.3f error_ms min=%.3f mean=%.3f median=%.3f p95=%.3f p99=%.3f max=%.3f sd=%.3f max_abs=%.3f error_mean_pct=%.3f\n", workload ? "streaming" : "idle", names[direction], durations[duration], durations[duration] + mean, errors[0], mean, (errors[1] + errors[2]) / 2, errors[3], errors[3], errors[3], sqrt(fmax(0, squares / 4 - mean * mean)), maximum_absolute, 100 * mean / durations[duration]);
			}
		}
		if (workload) {
			ASSERT_TRUE(set_switch(0, "CCD_ABORT_EXPOSURE", "ABORT_EXPOSURE", true));
			ASSERT_TRUE(wait_state(0, "CCD_ABORT_EXPOSURE", INDIGO_OK_STATE));
		}
	}
}

