ASI_ERROR_CODE ASIGetControlCaps(int id, int index, ASI_CONTROL_CAPS *caps) {
	SDK_CHECK(id, true);
	if (index < 0 || index >= ARRAY_SIZE(controls)) {
		return ASI_ERROR_INVALID_INDEX;
	}
	mock_camera *c = camera(id);
	if (c->caps_fail) {
		return ASI_ERROR_GENERAL_ERROR;
	}
	int selected = -1;
	for (int step = 0; step < ARRAY_SIZE(controls); step++) {
		int candidate = c->reverse_controls ? ARRAY_SIZE(controls) - 1 - step : step;
		if (control_available(c, controls[candidate]) && index-- == 0) {
			selected = candidate;
			break;
		}
	}
	index = selected;
	if (index < 0 || index >= ARRAY_SIZE(controls)) {
		return ASI_ERROR_INVALID_INDEX;
	}
	memset(caps, 0, sizeof(*caps));
	caps->ControlType = controls[index];
	strcpy(caps->Name, control_names[index]);
	caps->MaxValue = 100;
	caps->IsWritable = ASI_TRUE;
	if (caps->ControlType == ASI_EXPOSURE) {
		caps->MinValue = 100;
		caps->MaxValue = 120000000;
	} else if (caps->ControlType == ASI_TEMPERATURE || caps->ControlType == ASI_COOLER_POWER_PERC) {
		caps->IsWritable = ASI_FALSE;
	} else if (caps->ControlType == ASI_TARGET_TEMP) {
		caps->MinValue = -40;
		caps->MaxValue = 40;
	}
	if (caps->ControlType == ASI_TEMPERATURE) {
		caps->MinValue = -1000;
		caps->MaxValue = 1000;
	}
	if (caps->ControlType + 1 == c->readonly_control) {
		caps->IsWritable = ASI_FALSE;
	}
	if (c->malformed_caps == 1) {
		caps->MaxValue = caps->MinValue - 1;
	} else if (c->malformed_caps == 2) {
		memset(caps->Name, '%', sizeof(caps->Name));
	}
	return ASI_SUCCESS;
}

