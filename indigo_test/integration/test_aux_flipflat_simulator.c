// AUX lightbox coverage for indigo_aux_flipflat against the standalone Alnitak/FlipFlat simulator
// over a real PTY. The device id returned by >POOO decides which of AUX_COVER, AUX_LIGHT_SWITCH and
// AUX_LIGHT_INTENSITY the driver publishes, so the per-model property set is the main contract
// here, alongside the percent/0-255 intensity conversion and the cover's polled completion.

