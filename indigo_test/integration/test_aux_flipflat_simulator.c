// INDIGO publishes intensity as a percentage while the device takes 0..255, so both ends of the
// range and a mid value have to survive the round trip through a reconnect.
static void intensity_round_trips_through_the_device_scale(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_flipflat(&simulator, NULL));
	SERIAL_CHECK_TRUE(start_serial_driver(&flipflat, simulator.port));
	online = true;
	const double percents[] = { 0, 50, 100 };
	for (int i = 0; i < ARRAY_SIZE(percents); i++) {
		SERIAL_CHECK_TRUE(set_intensity(percents[i]));
		SERIAL_CHECK_TRUE(wait_for_property_state(AUX_LIGHT_INTENSITY_PROPERTY_NAME, INDIGO_OK_STATE));
		disconnect_serial_device(&flipflat);
		SERIAL_CHECK_TRUE(connect_serial_device(&flipflat, simulator.port));
		// on_connect re-reads >JOOO; one percent of tolerance covers the 0..255 quantisation.
		printf("Requested %g%% read back %g%%\n", percents[i], cached_number_value(AUX_LIGHT_INTENSITY_PROPERTY_NAME, AUX_LIGHT_INTENSITY_ITEM_NAME));
		SERIAL_CHECK_TRUE(fabs(cached_number_value(AUX_LIGHT_INTENSITY_PROPERTY_NAME, AUX_LIGHT_INTENSITY_ITEM_NAME) - percents[i]) <= 1);
	}
cleanup:
	if (online) { stop_serial_driver(&flipflat); }
	stop_external_serial_simulator(&simulator);
}

