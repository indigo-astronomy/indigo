#ifndef AUX_FLIPFLAT_SIMULATOR_EXECUTABLE
#define AUX_FLIPFLAT_SIMULATOR_EXECUTABLE "build/integration/aux_flipflat_simulator"
#endif

static const simulator_driver_case flipflat = {
	"FlipFlat",
	"indigo_aux_flipflat",
	"FlipFlat",
	indigo_aux_flipflat,
	false,
	NULL, 0, NULL, 0, NULL, 0, NULL, 0
};

static bool start_flipflat(external_serial_simulator *simulator, const char *device_id) {
	if (device_id == NULL) {
		return start_external_serial_simulator(simulator, AUX_FLIPFLAT_SIMULATOR_EXECUTABLE);
	}
	const char *arguments[] = { "--device-id", device_id, NULL };
	return start_external_serial_simulator_with_args(simulator, AUX_FLIPFLAT_SIMULATOR_EXECUTABLE, arguments);
}

static const char *info_text(const char *item_name) {
	indigo_item *item = find_cached_item(INFO_PROPERTY_NAME, item_name);
	return item == NULL ? "" : item->text.value;
}

static bool switch_on(const char *property, const char *item) {
	return indigo_change_switch_property_1(&simulator_test_client, flipflat.device_name, property, item, true) == INDIGO_OK;
}

static bool set_intensity(double percent) {
	return indigo_change_number_property_1(&simulator_test_client, flipflat.device_name, AUX_LIGHT_INTENSITY_PROPERTY_NAME, AUX_LIGHT_INTENSITY_ITEM_NAME, percent) == INDIGO_OK;
}

