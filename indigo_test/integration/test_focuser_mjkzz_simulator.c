typedef struct {
	const char *name;
	void (*run)(void);
	const char *profile, *key, *action;
} mjkzz_test;

static int run_cases(const mjkzz_test *cases, int count) {
	int failures = 0, executed = 0;
	setvbuf(stdout, NULL, _IOLBF, 0);
	const char *filter = getenv("MJKZZ_TEST_FILTER");
	if (!mkdtemp(fixture_dir)) {
		return 1;
	}
	snprintf(event_path, sizeof(event_path), "%s/events", fixture_dir);
	snprintf(fault_path, sizeof(fault_path), "%s/fault", fixture_dir);
	setenv("INDIGO_MJKZZ_EVENTS", event_path, 1);
	setenv("INDIGO_MJKZZ_FAULT", fault_path, 1);
	for (int i = 0; i < count; i++) {
		if (filter && !strstr(cases[i].name, filter)) {
			continue;
		}
		executed++;
		current_profile = cases[i].profile;
		current_key = cases[i].key;
		current_action = cases[i].action;
		unlink(fault_path);
		const char *simulator_profile = !strcmp(current_profile, "split") || !strcmp(current_profile, "alternate") ? current_profile : "normal";
		const char *args[] = { "--profile", simulator_profile, NULL };
		if (!start_external_serial_simulator_with_args(&fixture, FOCUSER_MJKZZ_SIMULATOR_EXECUTABLE, args)) {
			failures++;
			break;
		}
		if (!strcmp(cases[i].name, "instances")) {
			unsetenv("INDIGO_MJKZZ_EVENTS");
			unsetenv("INDIGO_MJKZZ_FAULT");
			const char *second_args[] = { "--profile", "alternate", NULL };
			bool ready = start_external_serial_simulator_with_args(&second_fixture, FOCUSER_MJKZZ_SIMULATOR_EXECUTABLE, second_args);
			setenv("INDIGO_MJKZZ_EVENTS", event_path, 1);
			setenv("INDIGO_MJKZZ_FAULT", fault_path, 1);
			if (!ready) {
				stop_external_serial_simulator(&fixture);
				failures++;
				break;
			}
		}
		fflush(NULL);
		pid_t child = fork();
		if (child == 0) {
			alarm(30);
			indigo_test_case test = { cases[i].name, cases[i].run };
			_exit(indigo_run_tests("MJKZZ", &test, 1));
		}
		int status = 0;
		if (child > 0) {
			while (waitpid(child, &status, 0) < 0 && errno == EINTR) {
			}
		}
		stop_external_serial_simulator(&fixture);
		stop_external_serial_simulator(&second_fixture);
		if (child < 0 || !WIFEXITED(status) || WEXITSTATUS(status)) {
			fprintf(stderr, "FAIL %s (status %d)\n", cases[i].name, status);
			failures++;
		}
	}
	unlink(fault_path);
	unlink(event_path);
	rmdir(fixture_dir);
	unsetenv("INDIGO_MJKZZ_EVENTS");
	unsetenv("INDIGO_MJKZZ_FAULT");
	printf("MJKZZ: %d/%d scenarios passed\n", executed - failures, executed);
	return failures ? 1 : 0;
}

