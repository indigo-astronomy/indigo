static bool start_ppb(external_serial_simulator *simulator, const char * const *arguments) {
	return start_external_serial_simulator_with_args(simulator, AUX_PPB_SIMULATOR_EXECUTABLE, arguments);
}

static bool wait_for_switch_item_value(const char *property_name, const char *item_name, bool expected) {
	for (int i = 0; i < 100; i++) {
		indigo_item *item = find_cached_item(property_name, item_name);
		if (item != NULL && item->sw.value == expected) {
			return true;
		}
		indigo_usleep(100000);
	}
	indigo_item *item = find_cached_item(property_name, item_name);
	fprintf(stderr, "Switch %s.%s is %s, expected %s\n", property_name, item_name, item == NULL ? "missing" : item->sw.value ? "on" : "off", expected ? "on" : "off");
	return false;
}

static bool wait_for_light_item_value(const char *property_name, const char *item_name, indigo_property_state expected) {
	for (int i = 0; i < 100; i++) {
		indigo_item *item = find_cached_item(property_name, item_name);
		if (item != NULL && item->light.value == expected) {
			return true;
		}
		indigo_usleep(100000);
	}
	indigo_item *item = find_cached_item(property_name, item_name);
	fprintf(stderr, "Light %s.%s is %d, expected %d\n", property_name, item_name, item == NULL ? -1 : item->light.value, expected);
	return false;
}

static int property_count(const char *property_name) {
	indigo_property *property = find_cached_property(property_name);
	if (property == NULL) {
		fprintf(stderr, "Property %s is not defined\n", property_name);
		return -1;
	}
	return property->count;
}

static bool set_switch(const char *property_name, const char *item_name, bool value) {
	return indigo_change_switch_property_1(&simulator_test_client, aux.device_name, property_name, item_name, value) == INDIGO_OK;
}

static bool set_number(const char *property_name, const char *item_name, double value) {
	return indigo_change_number_property_1(&simulator_test_client, aux.device_name, property_name, item_name, value) == INDIGO_OK;
}

