static void repeated_disconnect_is_tolerated(void) {
	external_serial_simulator simulator = { 0 };
	bool online = true;
	SERIAL_CHECK_TRUE(start_model(&simulator, "ppb"));
	disconnect_serial_device(&aux);
	SERIAL_CHECK_TRUE(!context.connected);
	disconnect_serial_device(&aux);
	SERIAL_CHECK_TRUE(!context.connected);
	online = false;
	tear_down_serial_driver(&aux);
cleanup:
	if (online) {
		stop_serial_driver(&aux);
	}
	stop_external_serial_simulator(&simulator);
}

static void shutdown_is_refused_while_connected(void) {
	external_serial_simulator simulator = { 0 };
	SERIAL_CHECK_TRUE(start_model(&simulator, "ppb"));
	SERIAL_CHECK_EQ_INT(INDIGO_BUSY, indigo_aux_ppb(INDIGO_DRIVER_SHUTDOWN, NULL));
	SERIAL_CHECK_TRUE(context.connected);
cleanup:
	stop_serial_driver(&aux);
	stop_external_serial_simulator(&simulator);
}

static void additional_instance_runs_beside_the_first(void) {
	external_serial_simulator first = { 0 }, second = { 0 };
	static const simulator_driver_case other = {
		"PegasusAstro Pocket Powerbox #2", "indigo_aux_ppb", "Pocket Powerbox #2", indigo_aux_ppb, false, NULL, 0, NULL, 0, NULL, 0, NULL, 0
	};
	const char *arguments[] = { "--model", "spb", NULL };
	SERIAL_CHECK_TRUE(start_model(&first, "ppba"));
	SERIAL_CHECK_TRUE(start_ppb(&second, arguments));
	SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_change_number_property_1(&simulator_test_client, aux.device_name, ADDITIONAL_INSTANCES_PROPERTY_NAME, ADDITIONAL_INSTANCES_COUNT_ITEM_NAME, 1));
	SERIAL_CHECK_TRUE(wait_for_number_item_value(ADDITIONAL_INSTANCES_PROPERTY_NAME, ADDITIONAL_INSTANCES_COUNT_ITEM_NAME, 1, 0.01));
	SERIAL_CHECK_TRUE(connect_serial_device(&other, second.port));
	// The second instance identifies its own model rather than inheriting the first one's.
	SERIAL_CHECK_EQ_INT(1, property_count(AUX_POWER_OUTLET_PROPERTY_NAME));
	disconnect_serial_device(&other);
	reset_simulator_context(&aux);
	enumerate_simulator_device();
	SERIAL_CHECK_TRUE(wait_for_property_state(CONNECTION_PROPERTY_NAME, INDIGO_OK_STATE));
	SERIAL_CHECK_EQ_INT(2, property_count(AUX_POWER_OUTLET_PROPERTY_NAME));
cleanup:
	indigo_change_number_property_1(&simulator_test_client, aux.device_name, ADDITIONAL_INSTANCES_PROPERTY_NAME, ADDITIONAL_INSTANCES_COUNT_ITEM_NAME, 0);
	stop_serial_driver(&aux);
	stop_external_serial_simulator(&second);
	stop_external_serial_simulator(&first);
}

