// This driver names only its heater outlets, and it republishes them with a delete
// and a define because a label change is not an update.
static void outlet_names_relabel_the_heaters(void) {
	external_serial_simulator simulator = { 0 };
	SERIAL_CHECK_TRUE(start_model(&simulator, "ppba"));
	SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_change_text_property_1_raw(&simulator_test_client, aux.device_name, AUX_OUTLET_NAMES_PROPERTY_NAME, AUX_HEATER_OUTLET_NAME_1_ITEM_NAME, "Secondary"));
	SERIAL_CHECK_TRUE(wait_for_property_state(AUX_OUTLET_NAMES_PROPERTY_NAME, INDIGO_OK_STATE));
	bool relabelled = false;
	for (int i = 0; i < 100 && !relabelled; i++) {
		indigo_item *item = find_cached_item(AUX_HEATER_OUTLET_PROPERTY_NAME, AUX_HEATER_OUTLET_1_ITEM_NAME);
		relabelled = item != NULL && !strcmp(item->label, "Secondary [%]");
		if (!relabelled) {
			indigo_usleep(100000);
		}
	}
	if (!relabelled) {
		indigo_item *item = find_cached_item(AUX_HEATER_OUTLET_PROPERTY_NAME, AUX_HEATER_OUTLET_1_ITEM_NAME);
		fprintf(stderr, "Heater label is '%s', expected 'Secondary [%%]'\n", item ? item->label : "missing");
	}
	SERIAL_CHECK_TRUE(relabelled);
cleanup:
	stop_serial_driver(&aux);
	stop_external_serial_simulator(&simulator);
}

