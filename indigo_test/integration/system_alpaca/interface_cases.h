// devicestate that fails with an answer of the server (HTTP 500, a reply that can not be read) must not freeze what a class polls:
// on_poll is called all the same and reads the members one by one, and a devicestate that keeps failing is not used any more.
static void interface_device_state_failures(void) {
	static const char *arguments[] = { "--device", "focuser", "--device", "focuser:number=1,name=Old Focuser,interface=legacy", NULL };
	char modern[INDIGO_NAME_SIZE];
	interface_reset();
	SA_CHECK(sa_begin(arguments));
	SA_CHECK(sa_attach("Focuser Simulator") && interface_run(sa_device, interface_install));
	snprintf(modern, sizeof(modern), "%s", sa_device);
	interface_poll_body = interface_state_poll;
	SA_CHECK(sa_connect(modern) && SA_WAIT(interface_polls >= 3, SA_TIMEOUT) && interface_freeze());
	SA_CHECK(interface_results[1] == ALPACA_OK && interface_integers[1] == 50000 && sa_request_count(0, "GET", "/api/v1/focuser/0/position") == 0);
	interface_frozen = false;
	// HTTP 500 in two ticks: the hook runs in both and reads the position of the device with a request of its own, nothing is said about it
	SA_CHECK(sa_device_state(0, "focuser", 0, "Position=1234") && sa_fault(0, "GET", "/api/v1/focuser/0/devicestate", "http-status", "Value=500&Count=2"));
	SA_CHECK(SA_WAIT(sa_faulted_count(0, "GET", "/api/v1/focuser/0/devicestate", "http-status") == 2, SA_TIMEOUT) && interface_wait_polls(3) && interface_freeze());
	SA_CHECK(sa_request_count(0, "GET", "/api/v1/focuser/0/position") == 2 && interface_results[1] == ALPACA_OK && interface_integers[1] == 1234);
	SA_CHECK(sa_is_connected(modern) && !sa_message_seen("DeviceState can not be read"));
	// devicestate works again: it is used again, the member is not asked for any more
	interface_frozen = false;
	int states = sa_request_count(0, "GET", "/api/v1/focuser/0/devicestate");
	SA_CHECK(interface_wait_polls(3) && interface_freeze() && sa_request_count(0, "GET", "/api/v1/focuser/0/position") == 2 && sa_request_count(0, "GET", "/api/v1/focuser/0/devicestate") >= states + 2);
	// a reply that can not be read, for good: after five ticks in a row the device is told to be polled member by member, and devicestate is not asked for any more
	interface_frozen = false;
	SA_CHECK(sa_fault(0, "GET", "/api/v1/focuser/0/devicestate", "malformed-json", "Count=-1"));
	SA_CHECK(SA_WAIT(sa_message_seen("DeviceState can not be read (invalid reply: Malformed JSON"), SA_TIMEOUT) && sa_faulted_count(0, "GET", "/api/v1/focuser/0/devicestate", "malformed-json") == 5);
	int connected = sa_request_count(0, "GET", "/api/v1/focuser/0/connected");
	SA_CHECK(sa_device_state(0, "focuser", 0, "Position=4321") && interface_wait_polls(3) && interface_freeze());
	SA_CHECK(interface_results[1] == ALPACA_OK && interface_integers[1] == 4321 && interface_results[0] == ALPACA_OK && interface_results[2] == ALPACA_OK);
	SA_CHECK(sa_faulted_count(0, "GET", "/api/v1/focuser/0/devicestate", "malformed-json") == 5 && sa_request_count(0, "GET", "/api/v1/focuser/0/connected") >= connected + 2 && sa_is_connected(modern));
	// the next connection tries devicestate again
	states = sa_request_count(0, "GET", "/api/v1/focuser/0/devicestate");
	interface_frozen = false;
	SA_CHECK(sa_clear_faults(0) && sa_disconnect(modern) && sa_connect(modern) && SA_WAIT(sa_request_count(0, "GET", "/api/v1/focuser/0/devicestate") >= states + 3, SA_TIMEOUT));
	SA_CHECK(interface_wait_polls(2) && interface_freeze() && interface_integers[1] == 4321);
	interface_poll_body = NULL;
	SA_CHECK(sa_disconnect(modern));
	// an older device is polled with "connected": an error of the server in its place does not keep the hook from running either
	SA_CHECK(sa_attach("Old Focuser") && interface_run(sa_device, interface_install));
	interface_polls = 0;
	interface_frozen = false;
	interface_poll_body = interface_state_poll;
	SA_CHECK(sa_connect(sa_device) && SA_WAIT(interface_polls >= 3, SA_TIMEOUT));
	SA_CHECK(sa_fault(0, "GET", "/api/v1/focuser/1/connected", "http-status", "Value=500&Count=-1") && sa_device_state(0, "focuser", 1, "Position=777"));
	SA_CHECK(SA_WAIT(sa_faulted_count(0, "GET", "/api/v1/focuser/1/connected", "http-status") >= 3, SA_TIMEOUT) && interface_wait_polls(2) && interface_freeze());
	SA_CHECK(interface_results[1] == ALPACA_OK && interface_integers[1] == 777 && sa_is_connected(sa_device));
	interface_poll_body = NULL;
	SA_CHECK(sa_clear_faults(0) && sa_disconnect(sa_device));
cleanup:
	interface_poll_body = NULL;
	sa_end();
}

static void interface_capability_body(indigo_device *device) {
	interface_results[0] = system_alpaca_probe_bool(device, "absolute", interface_flags + 0);
	interface_results[1] = system_alpaca_probe_bool(device, "Absolute", interface_flags + 1);
	interface_flags[2] = system_alpaca_can(device, "absolute");
	interface_results[3] = system_alpaca_probe_bool(device, "canfly", interface_flags + 3);
	interface_flags[4] = system_alpaca_can(device, "canfly");
	interface_flags[5] = system_alpaca_supported(device, "canfly");
	interface_results[6] = system_alpaca_probe_member(device, "temperature", interface_flags + 6);
	interface_results[7] = system_alpaca_probe_member(device, "position", interface_flags + 7);
	interface_results[8] = system_alpaca_state_int(device, "Position", interface_integers + 8);
	interface_results[9] = system_alpaca_probe_member(device, "stepsize", interface_flags + 9);
	interface_flags[10] = system_alpaca_supported(device, "halt");
	system_alpaca_set_unsupported(device, "halt");
	interface_flags[11] = system_alpaca_supported(device, "halt");
	interface_flags[12] = system_alpaca_can(device, "tempcompavailable");
	interface_results[13] = system_alpaca_probe_member(device, "maxincrement", interface_flags + 13);
	interface_results[14] = system_alpaca_probe_member(device, "maxincrement", interface_flags + 14);
	interface_results[15] = system_alpaca_probe_member(device, "temperature", interface_flags + 15);
}

static void interface_capability_cache(void) {
	interface_reset();
	SA_CHECK(sa_begin(core_focuser));
	// the hooks of the focuser class are replaced: its on_probe and on_poll read members of their own (absolute, position, temperature...),
	// and the case counts every request for a member, so the body below has to be the only code that asks the device for them
	SA_CHECK(sa_attach("Focuser Simulator") && interface_run(sa_device, interface_install) && sa_connect(sa_device));
	// the device has no position (a relative focuser answers NotImplemented), its stepsize fails for another reason
	SA_CHECK(sa_put(0, "/simulator/v1/focuser/0/error", "Member=position&ErrorNumber=1024") && sa_put(0, "/simulator/v1/focuser/0/error", "Member=stepsize&ErrorNumber=1279"));
	SA_CHECK(sa_fault(0, "GET", "/api/v1/focuser/0/maxincrement", "drop", "Count=3"));
	SA_CHECK(interface_run(sa_device, interface_capability_body));
	// a boolean capability is read once, whatever the casing of its name
	SA_CHECK(interface_results[0] == ALPACA_OK && interface_flags[0] && interface_results[1] == ALPACA_OK && interface_flags[1] && interface_flags[2]);
	SA_CHECK(sa_request_count(0, "GET", "/api/v1/focuser/0/absolute") == 1);
	// a capability the device does not know is false, and that is remembered as well
	SA_CHECK(interface_results[3] == ALPACA_OK && !interface_flags[3] && !interface_flags[4] && !interface_flags[5] && sa_request_count(0, "GET", "/api/v1/focuser/0/canfly") == 1);
	// optional members: NotImplemented means that the member is not there, any other error that it is
	SA_CHECK(interface_results[6] == ALPACA_OK && interface_flags[6] && interface_results[7] == ALPACA_OK && !interface_flags[7] && interface_results[9] == ALPACA_OK && interface_flags[9]);
	SA_CHECK(interface_results[8] == ALPACA_UNSUPPORTED && sa_request_count(0, "GET", "/api/v1/focuser/0/position") == 1);
	SA_CHECK(interface_flags[10] && !interface_flags[11] && !interface_flags[12]);
	// a transport error is no answer: it is returned and the member is asked for again
	SA_CHECK(interface_results[13] == ALPACA_CONNECTION_LOST && interface_results[14] == ALPACA_OK && interface_flags[14] && sa_request_count(0, "GET", "/api/v1/focuser/0/maxincrement") == 4);
	SA_CHECK(interface_results[15] == ALPACA_OK && interface_flags[15] && sa_request_count(0, "GET", "/api/v1/focuser/0/temperature") == 1);
	SA_CHECK(sa_is_connected(sa_device));
	// the cache lives as long as the connection
	SA_CHECK(sa_disconnect(sa_device) && sa_put(0, "/simulator/v1/focuser/0/error", "Member=position&ErrorNumber=0") && sa_connect(sa_device));
	SA_CHECK(interface_run(sa_device, interface_capability_body));
	SA_CHECK(interface_results[7] == ALPACA_OK && interface_flags[7] && interface_results[8] == ALPACA_OK && interface_integers[8] == 50000);
	SA_CHECK(sa_request_count(0, "GET", "/api/v1/focuser/0/absolute") == 2 && sa_request_count(0, "GET", "/api/v1/focuser/0/canfly") == 2);
	SA_CHECK(sa_disconnect(sa_device));
cleanup:
	sa_end();
}

// A move written the way indigo_system_alpaca_private.h tells a class module to write a long operation.
static void interface_move_finalizer(indigo_device *device) {
	bool moving = false;
	if (!system_alpaca_is_active(device)) {
		return;
	}
	interface_finalizers++;
	alpaca_result result = system_alpaca_get_bool(device, "ismoving", &moving);
	if (result == ALPACA_OK && moving && system_alpaca_operation_continue(device, &interface_operation, interface_move_finalizer)) {
		return;
	}
	system_alpaca_operation_end(device, &interface_operation);
	system_alpaca_finish(device, FOCUSER_POSITION_PROPERTY, result == ALPACA_OK && moving ? ALPACA_TIMED_OUT : result, "Move");
}

static void interface_move_handler(indigo_device *device) {
	alpaca_param params[] = { ALPACA_INT_PARAM("Position", interface_target) };
	system_alpaca_update(device, FOCUSER_POSITION_PROPERTY, INDIGO_BUSY_STATE, NULL);
	alpaca_result result = system_alpaca_put(device, "move", params, 1, ALPACA_WAIT_LONG);
	interface_results[0] = result;
	if (result == ALPACA_OK) {
		system_alpaca_operation_start(device, &interface_operation, interface_timeout, interface_move_finalizer);
	} else {
		system_alpaca_finish(device, FOCUSER_POSITION_PROPERTY, result, "Move");
	}
}

static void interface_operation_helpers(void) {
	interface_reset();
	SA_CHECK(sa_begin(core_focuser));
	SA_CHECK(sa_set_number("X_ALPACA_POLLING", "IDLE", 0.5) == INDIGO_OK_STATE && sa_set_number("X_ALPACA_POLLING", "ACTIVE", 0.05) == INDIGO_OK_STATE);
	SA_CHECK(sa_attach("Focuser Simulator") && interface_run(sa_device, interface_install) && sa_connect(sa_device));
	SA_CHECK(sa_defined(sa_device, FOCUSER_POSITION_PROPERTY_NAME));
	// an idle device is polled every 0.5 s
	SA_CHECK(SA_WAIT(interface_polls >= 1, SA_TIMEOUT));
	int polls = interface_polls;
	indigo_usleep(1200000);
	SA_CHECK(interface_polls - polls >= 1 && interface_polls - polls <= 4);
	// the move starts: the property is BUSY, the finalizer watches IsMoving and the device is polled every 0.05 s
	unsigned revision = sa_revision(sa_device, FOCUSER_POSITION_PROPERTY_NAME);
	SA_CHECK(interface_run(sa_device, interface_move_handler) && interface_results[0] == ALPACA_OK);
	SA_CHECK(sa_state_after(sa_device, FOCUSER_POSITION_PROPERTY_NAME, INDIGO_BUSY_STATE, revision));
	SA_CHECK(SA_WAIT(interface_finalizers >= 5, SA_TIMEOUT) && sa_state(sa_device, FOCUSER_POSITION_PROPERTY_NAME) == INDIGO_BUSY_STATE);
	indigo_usleep(600000);
	polls = interface_polls;
	indigo_usleep(1000000);
	SA_CHECK(interface_polls - polls >= 8 && sa_state(sa_device, FOCUSER_POSITION_PROPERTY_NAME) == INDIGO_BUSY_STATE);
	// the device time moves on, the move ends: the property is OK and the polling is slow again
	SA_CHECK(sa_advance(0, 5) && SA_WAIT(sa_state(sa_device, FOCUSER_POSITION_PROPERTY_NAME) == INDIGO_OK_STATE, SA_TIMEOUT));
	int finalizers = interface_finalizers;
	indigo_usleep(600000);
	polls = interface_polls;
	indigo_usleep(1200000);
	SA_CHECK(interface_polls - polls >= 1 && interface_polls - polls <= 4 && interface_finalizers == finalizers);
	// an operation that does not end in its time is given up with a timeout
	interface_target = 52000;
	interface_timeout = 0.4;
	revision = sa_revision(sa_device, FOCUSER_POSITION_PROPERTY_NAME);
	SA_CHECK(interface_run(sa_device, interface_move_handler) && interface_results[0] == ALPACA_OK);
	SA_CHECK(SA_WAIT(sa_state_after(sa_device, FOCUSER_POSITION_PROPERTY_NAME, INDIGO_ALERT_STATE, revision), SA_TIMEOUT));
	SA_CHECK(sa_message_seen("Move failed: timeout"));
	SA_CHECK(sa_advance(0, 5));
	// a start that the device refuses ends the request at once, with the message of the device
	interface_timeout = 60;
	SA_CHECK(sa_fault(0, "PUT", "/api/v1/focuser/0/move", "ascom-error", "Value=1025&Message=Too%20far"));
	revision = sa_revision(sa_device, FOCUSER_POSITION_PROPERTY_NAME);
	SA_CHECK(interface_run(sa_device, interface_move_handler) && interface_results[0] == ALPACA_INVALID_VALUE);
	SA_CHECK(sa_state_after(sa_device, FOCUSER_POSITION_PROPERTY_NAME, INDIGO_ALERT_STATE, revision) && sa_message_seen("Move failed: invalid value (Too far (0x401))"));
	// a start that is lost on the way is not repeated, and one lost request does not disconnect the device
	int moves = sa_request_count(0, "PUT", "/api/v1/focuser/0/move");
	SA_CHECK(sa_fault(0, "PUT", "/api/v1/focuser/0/move", "drop", NULL));
	SA_CHECK(interface_run(sa_device, interface_move_handler) && interface_results[0] == ALPACA_CONNECTION_LOST);
	SA_CHECK(sa_request_count(0, "PUT", "/api/v1/focuser/0/move") == moves + 1 && sa_message_seen("Move failed: connection lost"));
	polls = interface_polls;
	SA_CHECK(SA_WAIT(interface_polls >= polls + 2, SA_TIMEOUT) && sa_is_connected(sa_device));
	// a disconnect in the middle of an operation cancels its finalizer
	SA_CHECK(sa_advance(0, 60));
	interface_target = 53000;
	SA_CHECK(interface_run(sa_device, interface_move_handler) && interface_results[0] == ALPACA_OK && SA_WAIT(interface_finalizers > finalizers + 2, SA_TIMEOUT));
	SA_CHECK(sa_disconnect(sa_device));
	finalizers = interface_finalizers;
	indigo_usleep(300000);
	SA_CHECK(interface_finalizers == finalizers && !interface_operation.active);
	// the transport is lost in the middle of an operation: the operation fails, the device ends up disconnected with CONNECTION
	// in ALERT, on_disconnect ends the operation, nothing hangs and nothing is polled any more
	SA_CHECK(sa_advance(0, 60) && sa_connect(sa_device));
	interface_target = 54000;
	revision = sa_revision(sa_device, FOCUSER_POSITION_PROPERTY_NAME);
	int disconnects = interface_disconnects;
	SA_CHECK(interface_run(sa_device, interface_move_handler) && interface_results[0] == ALPACA_OK && SA_WAIT(interface_finalizers > finalizers + 2, SA_TIMEOUT));
	int step_mark = sa_message_mark();
	SA_CHECK(sa_fault(0, NULL, "/api/v1/focuser/0/*", "reset", "Count=-1"));
	double started = indigo_monotonic_time();
	SA_CHECK(SA_WAIT(core_alerted(sa_device), SA_TIMEOUT) && indigo_monotonic_time() - started < 5);
	SA_CHECK(sa_message_seen_since(step_mark, "Move failed: connection lost") && interface_disconnects == disconnects + 1 && !interface_operation.active);
	SA_CHECK(!sa_defined(sa_device, FOCUSER_POSITION_PROPERTY_NAME));
	finalizers = interface_finalizers;
	polls = interface_polls;
	indigo_usleep(300000);
	SA_CHECK(interface_finalizers == finalizers && interface_polls == polls);
	// and the device works again when the server is back
	SA_CHECK(sa_clear_faults(0) && sa_advance(0, 60) && sa_connect(sa_device));
	interface_target = 55000;
	revision = sa_revision(sa_device, FOCUSER_POSITION_PROPERTY_NAME);
	SA_CHECK(interface_run(sa_device, interface_move_handler) && interface_results[0] == ALPACA_OK);
	SA_CHECK(sa_advance(0, 60) && SA_WAIT(sa_state_after(sa_device, FOCUSER_POSITION_PROPERTY_NAME, INDIGO_OK_STATE, revision), SA_TIMEOUT));
	SA_CHECK(sa_disconnect(sa_device));
cleanup:
	sa_end();
}

static void interface_transfer_body(indigo_device *device) {
	alpaca_channel *transfer = system_alpaca_transfer_channel(device, 1024 * 1024);
	interface_flags[0] = transfer != NULL && transfer != system_alpaca_channel(device) && system_alpaca_channel(device) != NULL;
	interface_flags[1] = transfer == system_alpaca_transfer_channel(device, 1024 * 1024);
	interface_results[2] = system_alpaca_check(device, alpaca_get_int(transfer, "maxstep", NULL, 0, ALPACA_WAIT_LONG, interface_integers + 2));
	interface_results[3] = system_alpaca_get_int(device, "maxincrement", interface_integers + 3);
}

static void interface_offline_body(indigo_device *device) {
	interface_flags[4] = system_alpaca_channel(device) == NULL && system_alpaca_transfer_channel(device, 1024 * 1024) == NULL;
	interface_results[5] = system_alpaca_get_int(device, "maxstep", interface_integers + 5);
	interface_results[6] = system_alpaca_put(device, "halt", NULL, 0, ALPACA_REPLAYABLE);
}

static void interface_channels(void) {
	interface_reset();
	SA_CHECK(sa_begin(core_focuser));
	SA_CHECK(sa_attach("Focuser Simulator") && sa_connect(sa_device));
	// the transfer channel is a second connection to the same device
	SA_CHECK(interface_run(sa_device, interface_transfer_body));
	SA_CHECK(interface_flags[0] && interface_flags[1] && interface_results[2] == ALPACA_OK && interface_integers[2] == 100000 && interface_results[3] == ALPACA_OK && interface_integers[3] == 10000);
	SA_CHECK(strcmp(sa_field(sa_last_request(0, "GET", "/api/v1/focuser/0/maxstep"), "Connection"), sa_field(sa_last_request(0, "GET", "/api/v1/focuser/0/maxincrement"), "Connection")) != 0);
	SA_CHECK(SA_WAIT(sa_request_count(0, "GET", "/api/v1/focuser/0/devicestate") >= 1, SA_TIMEOUT));
	SA_CHECK(!strcmp(sa_field(sa_last_request(0, "GET", "/api/v1/focuser/0/devicestate"), "Connection"), sa_field(sa_last_request(0, "GET", "/api/v1/focuser/0/maxincrement"), "Connection")));
	// after the transport is lost there is no channel: requests fail at once instead of waiting for a dead server
	SA_CHECK(sa_fault(0, NULL, "/api/v1/focuser/0/*", "reset", "Count=-1"));
	SA_CHECK(SA_WAIT(core_alerted(sa_device), SA_TIMEOUT));
	int requests = sa_request_count(0, NULL, "/api/*");
	double started = indigo_monotonic_time();
	SA_CHECK(interface_run(sa_device, interface_offline_body));
	SA_CHECK(interface_flags[4] && interface_results[5] == ALPACA_UNREACHABLE && interface_results[6] == ALPACA_UNREACHABLE);
	SA_CHECK(indigo_monotonic_time() - started < 0.5 && sa_request_count(0, NULL, "/api/*") == requests);
	// a new connection starts with new channels
	SA_CHECK(sa_clear_faults(0) && sa_connect(sa_device));
	SA_CHECK(interface_run(sa_device, interface_transfer_body) && interface_flags[0] && interface_results[2] == ALPACA_OK);
	SA_CHECK(sa_disconnect(sa_device));
cleanup:
	sa_end();
}

