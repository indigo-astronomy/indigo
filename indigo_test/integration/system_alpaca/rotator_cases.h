	SA_CHECK(!strcmp(sa_text(sa_device, INFO_PROPERTY_NAME, INFO_DEVICE_HW_REVISION_ITEM_NAME), "3") && rotator_count("PUT", "connected") == 1 && rotator_count("PUT", "connect") == 0);
