static void switch_lifecycle(void) {
	char key[INDIGO_NAME_SIZE];
	SA_CHECK(sa_begin(switch_default));
	snprintf(key, sizeof(key), "%s", sa_device_key("Switch Simulator"));
	SA_CHECK(sa_attach("Switch Simulator") && sa_connect(sa_device));
	// a disconnect in the middle of an asynchronous change: the change is left to the device, its finalizer is cancelled
	SA_CHECK(switch_start_number(SWITCH_VALUES, "VALUE_1", 40) && SA_WAIT(switch_count("GET", "statechangecomplete") >= 2, SA_TIMEOUT));
	SA_CHECK(sa_disconnect(sa_device) && !sa_defined(sa_device, SWITCH_VALUES) && switch_count("PUT", "cancelasync") == 0);
	int requests = sa_request_count(0, NULL, "/api/*");
	indigo_usleep(300000);
	SA_CHECK(sa_request_count(0, NULL, "/api/*") == requests);
	// the device changes while the proxy is disconnected: more switches, another kind, other values. The next connection shows it.
	SA_CHECK(sa_advance(0, 5) && sa_device_state(0, "switch", 0, "Connected=true"));
	SA_CHECK(sa_device_state(0, "switch", 0, "MaxSwitch=10&Switch0.Value=1&Switch1.CanWrite=false&Switch5.Min=-5&Switch5.Max=5&Switch5.Step=0.5&Switch5.Value=2.5&Switch5.CanAsync=false&Connected=false"));
	SA_CHECK(sa_connect(sa_device));
	SA_CHECK(sa_item_count(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME) == 5 && sa_item_count(sa_device, SWITCH_VALUES) == 2 && sa_item_count(sa_device, AUX_GPIO_SENSORS_PROPERTY_NAME) == 3 && sa_item_count(sa_device, SWITCH_INFO) == 10);
	SA_CHECK(sa_state(sa_device, SWITCH_VALUES) == INDIGO_OK_STATE && sa_number(sa_device, SWITCH_VALUES, "VALUE_1") == 40 && switch_item_is(SWITCH_VALUES, "VALUE_2", "Dew heater B", -5, 5, 0.5) && sa_number(sa_device, SWITCH_VALUES, "VALUE_2") == 2.5);
	SA_CHECK(sa_switch(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_1") && switch_label_is(AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_2", "Power 3") && switch_label_is(AUX_GPIO_SENSORS_PROPERTY_NAME, "SENSOR_1", "Power 2"));
	SA_CHECK(switch_set_number(SWITCH_VALUES, "VALUE_2", -1.5) == INDIGO_OK_STATE && switch_last("PUT", "setswitchvalue", "Id=5&Value=-1.5&ClientID=") && switch_simulated("Switch5.Value") == -1.5);
	// fewer switches on the next connection
	SA_CHECK(sa_disconnect(sa_device) && sa_device_state(0, "switch", 0, "MaxSwitch=1") && sa_connect(sa_device));
	SA_CHECK(sa_item_count(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME) == 1 && !sa_defined(sa_device, SWITCH_VALUES) && !sa_defined(sa_device, AUX_GPIO_SENSORS_PROPERTY_NAME) && !sa_defined(sa_device, SWITCH_ABORT) && sa_item_count(sa_device, SWITCH_INFO) == 1);
	SA_CHECK(sa_disconnect(sa_device) && sa_device_state(0, "switch", 0, "MaxSwitch=8") && sa_connect(sa_device) && sa_item_count(sa_device, SWITCH_VALUES) == 2);
	// requests that overlap: each property takes one at a time and both end
	unsigned outlets = sa_revision(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME), names = sa_revision(sa_device, AUX_OUTLET_NAMES_PROPERTY_NAME);
	SA_CHECK(indigo_change_switch_property_1(&sa_client, sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_2", false) == INDIGO_OK && indigo_change_text_property_1_raw(&sa_client, sa_device, AUX_OUTLET_NAMES_PROPERTY_NAME, "GPIO_OUTLET_NAME_2", "Mount") == INDIGO_OK);
	SA_CHECK(indigo_change_switch_property_1(&sa_client, sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_1", false) == INDIGO_OK);
	SA_CHECK(switch_answer(AUX_GPIO_OUTLETS_PROPERTY_NAME, outlets) == INDIGO_OK_STATE && switch_answer(AUX_OUTLET_NAMES_PROPERTY_NAME, names) == INDIGO_OK_STATE);
	SA_CHECK(SA_WAIT(switch_label_is(AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_2", "Mount") && !sa_switch(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_2"), SA_TIMEOUT) && switch_simulated("Switch2.Value") == 0);
	// a disconnect right after a request
	SA_CHECK(indigo_change_switch_property_1(&sa_client, sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_2", true) == INDIGO_OK && sa_disconnect(sa_device));
	SA_CHECK(!sa_defined(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME) && sa_connect(sa_device));
	// the device is detached in the middle of an asynchronous change: it goes away without a hang, the Alpaca device is disconnected
	SA_CHECK(switch_start_number(SWITCH_VALUES, "VALUE_1", 3) && SA_WAIT(switch_count("GET", "statechangecomplete") >= 2, SA_TIMEOUT));
	double started = indigo_monotonic_time();
	SA_CHECK(sa_select(key, false) && SA_WAIT(!sa_device_defined(sa_device), SA_TIMEOUT) && indigo_monotonic_time() - started < 3);
	SA_CHECK(!strcmp(sa_status(0, SWITCH_STATE, "Connected"), "false"));
	requests = sa_request_count(0, NULL, "/api/*");
	indigo_usleep(300000);
	SA_CHECK(sa_request_count(0, NULL, "/api/*") == requests);
	// and attached again it is a working device with the switches the device has now: switch 1 can not be written since the change above
	SA_CHECK(sa_advance(0, 5) && sa_attach("Switch Simulator") && sa_connect(sa_device));
	SA_CHECK(sa_item_count(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME) == 3 && sa_item_count(sa_device, SWITCH_VALUES) == 2 && sa_item_count(sa_device, AUX_GPIO_SENSORS_PROPERTY_NAME) == 3 && sa_number(sa_device, SWITCH_VALUES, "VALUE_1") == 3);
	SA_CHECK(switch_set_switch(AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_1", true) == INDIGO_OK_STATE && switch_simulated("Switch0.Value") == 1);
cleanup:
	sa_end();
}

// Switches that do nothing publish nothing, however they are polled; a change of the device is published at once.
static void switch_steady_state_is_silent(void) {
	for (int legacy = 0; legacy < 2; legacy++) {
		SA_CHECK(switch_begin(legacy ? switch_legacy : switch_default));
		SA_CHECK(SA_WAIT(switch_count("GET", legacy ? "connected" : "devicestate") >= 3, SA_TIMEOUT) && sa_steady(0, sa_device, legacy ? SWITCH_API "connected" : SWITCH_API "devicestate", 25));
		SA_CHECK(sa_device_state(0, "switch", 0, "Switch0.Value=1") && SA_WAIT(sa_switch(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_1"), SA_TIMEOUT));
		SA_CHECK(sa_disconnect(sa_device));
		sa_end();
	}
	return;
cleanup:
	sa_end();
}

// HTTP 400 to SetSwitchName, a method with parameters, is a failed request and not a switch whose name can not be set: the server
// may not have liked the name. The next name is sent. (NotImplemented fixes the name, see switch_names.)
static void switch_rejected_name(void) {
	SA_CHECK(switch_begin(switch_default));
	SA_CHECK(sa_fault(0, "PUT", SWITCH_API "setswitchname", "http-status", "Value=400&Message=Name%20too%20long"));
	SA_CHECK(switch_set_text(AUX_OUTLET_NAMES_PROPERTY_NAME, "GPIO_OUTLET_NAME_1", "A name the server does not like") == INDIGO_ALERT_STATE && sa_message_seen("failed: request rejected by the server") && !sa_message_seen("The device does not allow to rename"));
	SA_CHECK(switch_count("PUT", "setswitchname") == 1 && strcmp(sa_text(sa_device, AUX_OUTLET_NAMES_PROPERTY_NAME, "GPIO_OUTLET_NAME_1"), "A name the server does not like") != 0);
	SA_CHECK(switch_set_text(AUX_OUTLET_NAMES_PROPERTY_NAME, "GPIO_OUTLET_NAME_1", "Camera") == INDIGO_OK_STATE && switch_count("PUT", "setswitchname") == 2 && !strcmp(sa_status(0, SWITCH_STATE, "Switch0.Name"), "Camera"));
	SA_CHECK(sa_disconnect(sa_device));
cleanup:
	sa_end();
}

