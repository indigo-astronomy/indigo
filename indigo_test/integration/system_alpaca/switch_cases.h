static void switch_request_failures(void) {
	static const char *arguments[] = { "--device", "switch:interface=legacy,Switch3.Stuck=true", NULL };
	SA_CHECK(switch_begin(arguments));
	// an error of the device: ALERT, its message, and the property shows the state of the device
	SA_CHECK(sa_fault(0, "PUT", SWITCH_API "setswitch", "ascom-error", "Value=1279&Message=Relay%20fault"));
	SA_CHECK(switch_set_switch(AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_1", true) == INDIGO_ALERT_STATE && sa_message_seen("Change of 'Power 1' failed: device error (Relay fault (0x4FF))"));
	SA_CHECK(!sa_switch(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_1") && switch_simulated("Switch0.Value") == 0 && switch_count("PUT", "setswitch") == 1 && sa_is_connected(sa_device));
	// the first failure ends a request for several outlets: the rest is not sent
	static const char *items[] = { "OUTLET_1", "OUTLET_2" };
	static const bool values[] = { true, true };
	SA_CHECK(sa_fault(0, "PUT", SWITCH_API "setswitch", "http-status", "Value=500&Message=Kaboom"));
	unsigned revision = sa_revision(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME);
	SA_CHECK(indigo_change_switch_property(&sa_client, sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME, 2, items, values) == INDIGO_OK && switch_answer(AUX_GPIO_OUTLETS_PROPERTY_NAME, revision) == INDIGO_ALERT_STATE);
	SA_CHECK(sa_message_seen("Change of 'Power 1' failed: server error (HTTP 500: Kaboom)") && switch_count("PUT", "setswitch") == 2);
	SA_CHECK(!sa_switch(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_1") && !sa_switch(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_2"));
	// a reply that can not be read: the device executed the request, and the read back shows it
	SA_CHECK(sa_fault(0, "PUT", SWITCH_API "setswitch", "malformed-json", NULL));
	SA_CHECK(switch_set_switch(AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_1", true) == INDIGO_ALERT_STATE && sa_message_seen("Change of 'Power 1' failed: invalid reply"));
	SA_CHECK(sa_switch(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_1") && switch_simulated("Switch0.Value") == 1 && switch_count("PUT", "setswitch") == 3);
	// the read back fails
	SA_CHECK(sa_fault(0, "GET", SWITCH_API "getswitch", "missing-value", NULL));
	SA_CHECK(switch_set_switch(AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_2", true) == INDIGO_ALERT_STATE && sa_message_seen("Reading 'Power 2' failed: invalid reply (Value is missing)"));
	SA_CHECK(SA_WAIT(sa_switch(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_2"), SA_TIMEOUT) && switch_simulated("Switch1.Value") == 1);
	// a switch that takes the request and does not change
	SA_CHECK(switch_set_switch(AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_4", false) == INDIGO_ALERT_STATE && sa_message_seen("Change of 'USB hub' failed: the device did not change it"));
	SA_CHECK(sa_switch(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_4") && switch_simulated("Switch3.Value") == 1);
	// a connection that breaks before the reply: setting a state twice has the effect of setting it once, so it is sent again
	int sets = switch_count("PUT", "setswitch");
	SA_CHECK(sa_fault(0, "PUT", SWITCH_API "setswitch", "drop", NULL));
	SA_CHECK(switch_set_switch(AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_3", false) == INDIGO_OK_STATE && switch_count("PUT", "setswitch") == sets + 2 && switch_simulated("Switch2.Value") == 0 && !sa_switch(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_3"));
	// a device that does not answer a synchronous change within the long timeout (1 s here): ALERT, one request, the device stays connected
	SA_CHECK(sa_set_number("X_ALPACA_TIMEOUTS", "LONG", 1) == INDIGO_OK_STATE);
	sets = switch_count("PUT", "setswitchvalue");
	SA_CHECK(sa_fault(0, "PUT", SWITCH_API "setswitchvalue", "stall-before", "Delay=1500"));
	double started = indigo_monotonic_time();
	SA_CHECK(switch_set_number(SWITCH_VALUES, "VALUE_1", 45) == INDIGO_ALERT_STATE && sa_message_seen("Change of 'Dew heater A' failed: timeout"));
	SA_CHECK(indigo_monotonic_time() - started > 0.8 && indigo_monotonic_time() - started < 4 && switch_count("PUT", "setswitchvalue") == sets + 1);
	SA_CHECK(SA_WAIT(sa_number(sa_device, SWITCH_VALUES, "VALUE_1") == 45, SA_TIMEOUT) && sa_is_connected(sa_device));
	// the device was disconnected on the server by someone else: the proxy is disconnected with CONNECTION in ALERT
	SA_CHECK(sa_device_state(0, "switch", 0, "Connected=false"));
	SA_CHECK(switch_set_switch(AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_1", false) != INDIGO_OK_STATE && SA_WAIT(core_alerted(sa_device), SA_TIMEOUT));
	SA_CHECK(sa_message_seen("device is not connected") && !sa_defined(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME));
	// and it works again after a new connect
	SA_CHECK(sa_connect(sa_device) && sa_state(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME) == INDIGO_OK_STATE && sa_switch(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_1"));
	SA_CHECK(switch_set_switch(AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_1", false) == INDIGO_OK_STATE && switch_simulated("Switch0.Value") == 0);
	SA_CHECK(sa_disconnect(sa_device));
cleanup:
	sa_end();
}

static void switch_transport_loss(void) {
	SA_CHECK(switch_begin(switch_default));
	// devicestate fails for a while: the device stays connected, nothing is published, and the polling goes on afterwards
	unsigned revision = sa_revision(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME);
	int ticks = switch_count("GET", "devicestate");
	SA_CHECK(sa_fault(0, "GET", SWITCH_API "devicestate", "http-status", "Value=500&Count=3"));
	SA_CHECK(SA_WAIT(switch_count("GET", "devicestate") >= ticks + 5, SA_TIMEOUT) && sa_is_connected(sa_device) && sa_revision(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME) == revision);
	SA_CHECK(sa_device_state(0, "switch", 0, "Switch0.Value=1") && SA_WAIT(sa_switch(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_1"), SA_TIMEOUT));
	// one request that gets no answer is not the end of the connection
	SA_CHECK(sa_fault(0, "GET", SWITCH_API "devicestate", "reset", NULL));
	ticks = switch_count("GET", "devicestate");
	SA_CHECK(SA_WAIT(switch_count("GET", "devicestate") >= ticks + 4, SA_TIMEOUT) && sa_is_connected(sa_device) && sa_defined(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME));
	// the server goes away while the device is idle: CONNECTION in ALERT, every property of the class is deleted, nothing is sent any more
	SA_CHECK(sa_fault(0, NULL, SWITCH_API "*", "reset", "Count=-1"));
	double started = indigo_monotonic_time();
	SA_CHECK(SA_WAIT(core_alerted(sa_device), SA_TIMEOUT) && indigo_monotonic_time() - started < 5 && sa_message_seen("connection to the Alpaca server lost"));
	SA_CHECK(!sa_defined(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME) && !sa_defined(sa_device, SWITCH_VALUES) && !sa_defined(sa_device, AUX_GPIO_SENSORS_PROPERTY_NAME) && !sa_defined(sa_device, AUX_OUTLET_NAMES_PROPERTY_NAME));
	SA_CHECK(!sa_defined(sa_device, AUX_SENSOR_NAMES_PROPERTY_NAME) && !sa_defined(sa_device, SWITCH_INFO) && !sa_defined(sa_device, SWITCH_ABORT));
	int requests = sa_request_count(0, NULL, "/api/*");
	indigo_usleep(300000);
	SA_CHECK(sa_request_count(0, NULL, "/api/*") == requests);
	// a connect while the server is still away fails and leaves nothing behind
	SA_CHECK(sa_request_connection(sa_device, true) && SA_WAIT(sa_request_count(0, NULL, "/api/*") > requests && core_alerted(sa_device), SA_TIMEOUT) && !sa_defined(sa_device, SWITCH_INFO));
	// the server is back with other values: the new connection shows them and takes requests
	SA_CHECK(sa_clear_faults(0) && sa_device_state(0, "switch", 0, "Switch3.Value=0&Switch5.Value=42") && sa_connect(sa_device));
	SA_CHECK(sa_state(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME) == INDIGO_OK_STATE && !sa_switch(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_4") && sa_switch(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_1") && sa_number(sa_device, SWITCH_VALUES, "VALUE_2") == 42);
	SA_CHECK(switch_set_switch(AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_4", true) == INDIGO_OK_STATE && switch_simulated("Switch3.Value") == 1);
	// the transport is lost during a synchronous change, before the request reaches the device: the device is disconnected at once,
	// and the next connection shows that the switch was not changed
	SA_CHECK(sa_fault(0, NULL, SWITCH_API "*", "reset", "Count=-1&Dispatch=false"));
	SA_CHECK(indigo_change_switch_property_1(&sa_client, sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_2", true) == INDIGO_OK);
	started = indigo_monotonic_time();
	SA_CHECK(SA_WAIT(core_alerted(sa_device), SA_TIMEOUT) && indigo_monotonic_time() - started < 5 && !sa_defined(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME));
	SA_CHECK(sa_clear_faults(0) && sa_connect(sa_device) && !sa_switch(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_2") && sa_state(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME) == INDIGO_OK_STATE);
	SA_CHECK(sa_disconnect(sa_device));
cleanup:
	sa_end();
}

static void switch_connect_failures(void) {
	SA_CHECK(sa_begin(switch_default) && sa_attach("Switch Simulator"));
	// a device that does not tell how many switches it has does not connect; nothing stays defined and the device is disconnected again
	SA_CHECK(sa_fault(0, "GET", SWITCH_API "maxswitch", "malformed-json", NULL));
	SA_CHECK(sa_request_connection(sa_device, true) && SA_WAIT(core_alerted(sa_device), SA_TIMEOUT));
	SA_CHECK(!sa_defined(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME) && !sa_defined(sa_device, SWITCH_INFO) && !strcmp(sa_status(0, SWITCH_STATE, "Connected"), "false"));
	// the transport breaks while the switches are read
	SA_CHECK(sa_fault(0, "GET", SWITCH_API "minswitchvalue", "reset", "Skip=3&Count=-1"));
	SA_CHECK(sa_request_connection(sa_device, true) && SA_WAIT(core_alerted(sa_device), SA_TIMEOUT));
	SA_CHECK(!sa_defined(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME) && !sa_defined(sa_device, SWITCH_INFO) && switch_count("GET", "getswitchname") == 4 && sa_clear_faults(0));
	// members a switch does not answer get defaults: a generated name, no description, read-only without CanWrite,
	// a boolean sensor without a usable range, no asynchronous set without CanAsync
	SA_CHECK(sa_put(0, "/simulator/v1/switch/0/error", "Member=getswitchdescription&ErrorNumber=1024"));
	SA_CHECK(sa_fault(0, "GET", SWITCH_API "getswitchname", "ascom-error", "Value=1279") && sa_fault(0, "GET", SWITCH_API "canwrite", "http-status", "Value=500&Skip=1"));
	SA_CHECK(sa_fault(0, "GET", SWITCH_API "maxswitchvalue", "null-value", "Skip=2") && sa_fault(0, "GET", SWITCH_API "canasync", "ascom-error", "Value=1024&Skip=4") && sa_fault(0, "GET", SWITCH_API "getswitchvalue", "ascom-error", "Value=1035&Skip=2"));
	SA_CHECK(sa_connect(sa_device));
	SA_CHECK(sa_item_count(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME) == 2 && sa_item_count(sa_device, SWITCH_VALUES) == 2 && sa_item_count(sa_device, AUX_GPIO_SENSORS_PROPERTY_NAME) == 4);
	SA_CHECK(switch_label_is(AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_1", "Switch 0") && switch_label_is(AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_2", "USB hub"));
	SA_CHECK(!strcmp(sa_text(sa_device, SWITCH_INFO, "SWITCH_0"), "AUX_GPIO_OUTLETS.OUTLET_1") && !strcmp(sa_text(sa_device, SWITCH_INFO, "SWITCH_1"), "AUX_GPIO_SENSORS.SENSOR_1") && !strcmp(sa_text(sa_device, SWITCH_INFO, "SWITCH_2"), "AUX_GPIO_SENSORS.SENSOR_2"));
	SA_CHECK(switch_item_is(AUX_GPIO_SENSORS_PROPERTY_NAME, "SENSOR_1", "Power 2", 0, 1, 1) && switch_item_is(AUX_GPIO_SENSORS_PROPERTY_NAME, "SENSOR_2", "Power 3", 0, 1, 1));
	// the heater whose CanAsync failed is set synchronously, the other one asynchronously
	SA_CHECK(switch_set_number(SWITCH_VALUES, "VALUE_1", 30) == INDIGO_OK_STATE && switch_count("PUT", "setswitchvalue") == 1 && switch_count("PUT", "setasyncvalue") == 0);
	// the sensor whose value could not be read starts in ALERT and recovers with the first good value
	SA_CHECK(SA_WAIT(sa_number(sa_device, AUX_GPIO_SENSORS_PROPERTY_NAME, "SENSOR_3") == 12.3 && sa_state(sa_device, AUX_GPIO_SENSORS_PROPERTY_NAME) == INDIGO_OK_STATE, SA_TIMEOUT));
	SA_CHECK(sa_disconnect(sa_device));
cleanup:
	sa_end();
}

