	SA_CHECK(!strcmp(sa_text(sa_device, AUX_OUTLET_NAMES_PROPERTY_NAME, "GPIO_OUTLET_NAME_28"), "Switch 31") && !strcmp(sa_text(sa_device, AUX_OUTLET_NAMES_PROPERTY_NAME, "VALUE_NAME_2"), "Dew heater B"));
