// SWITCH_POLL_BATCH switches, so the value of a switch may be older than a change the device made by itself; and a poll tick never reads
// the switches of a property that is BUSY. The device turns outlet 3 off while the queue is held (no poll tick can see it), the client
// asks for it on: before the fix nothing was sent, the property was OK with the outlet on and the outlet stayed off.
static void switch_request_after_device_change(void) {
	SA_CHECK(switch_begin(switch_legacy));
	SA_CHECK(SA_WAIT(sa_switch(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_3"), SA_TIMEOUT) && switch_simulated("Switch2.Value") == 1);
	SA_CHECK(sa_gate_close(sa_device) && sa_device_state(0, "switch", 0, "Switch2.Value=0"));
	int sets = switch_count("PUT", "setswitch");
	unsigned revision = sa_revision(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME);
	SA_CHECK(indigo_change_switch_property_1(&sa_client, sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_3", true) == INDIGO_OK && SA_WAIT(sa_state_after(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME, INDIGO_BUSY_STATE, revision), SA_TIMEOUT));
	sa_gate_open();
	SA_CHECK(switch_answer(AUX_GPIO_OUTLETS_PROPERTY_NAME, revision) == INDIGO_OK_STATE && switch_count("PUT", "setswitch") == sets + 1 && switch_last("PUT", "setswitch", "Id=2&State=True&ClientID="));
	SA_CHECK(switch_simulated("Switch2.Value") == 1 && sa_switch(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_3"));
	// the same for a value
	SA_CHECK(SA_WAIT(sa_number(sa_device, SWITCH_VALUES, "VALUE_2") == 25, SA_TIMEOUT) && sa_gate_close(sa_device) && sa_device_state(0, "switch", 0, "Switch5.Value=80"));
	sets = switch_count("PUT", "setswitchvalue");
	revision = sa_revision(sa_device, SWITCH_VALUES);
	SA_CHECK(indigo_change_number_property_1(&sa_client, sa_device, SWITCH_VALUES, "VALUE_2", 25) == INDIGO_OK && SA_WAIT(sa_state_after(sa_device, SWITCH_VALUES, INDIGO_BUSY_STATE, revision), SA_TIMEOUT));
	sa_gate_open();
	SA_CHECK(switch_answer(SWITCH_VALUES, revision) == INDIGO_OK_STATE && switch_count("PUT", "setswitchvalue") == sets + 1 && switch_last("PUT", "setswitchvalue", "Id=5&Value=25&ClientID="));
	SA_CHECK(switch_simulated("Switch5.Value") == 25 && sa_number(sa_device, SWITCH_VALUES, "VALUE_2") == 25);
	SA_CHECK(sa_disconnect(sa_device));
cleanup:
	sa_gate_open();
	sa_end();
}

static void switch_async_change(void) {
	static const char *arguments[] = { "--device", "switch:Switch0.CanAsync=true", NULL };
	SA_CHECK(switch_begin(arguments));
	// interface version 3, CanAsync: the change is started with setasyncvalue and completes when StateChangeComplete says so
	SA_CHECK(switch_start_number(SWITCH_VALUES, "VALUE_1", 40));
	SA_CHECK(switch_count("PUT", "setasyncvalue") == 1 && switch_last("PUT", "setasyncvalue", "Id=4&Value=40&ClientID=") && switch_count("PUT", "setswitchvalue") == 0);
	SA_CHECK(SA_WAIT(switch_count("GET", "statechangecomplete") >= 5, SA_TIMEOUT) && switch_last("GET", "statechangecomplete", "Id=4&ClientID="));
	SA_CHECK(sa_state(sa_device, SWITCH_VALUES) == INDIGO_BUSY_STATE && switch_simulated("Switch4.Value") == 0 && sa_number(sa_device, SWITCH_VALUES, "VALUE_1") != 40);
	// a request for a property that is BUSY is not accepted: nothing is sent for it
	SA_CHECK(indigo_change_number_property_1(&sa_client, sa_device, SWITCH_VALUES, "VALUE_2", 70) == INDIGO_OK);
	// the other property works meanwhile
	SA_CHECK(switch_set_switch(AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_2", true) == INDIGO_OK_STATE && switch_simulated("Switch1.Value") == 1);
	SA_CHECK(sa_state(sa_device, SWITCH_VALUES) == INDIGO_BUSY_STATE && switch_count("PUT", "setasyncvalue") == 1 && switch_simulated("Switch5.Value") == 25);
	// device time moves on: the change ends, the value is read back
	unsigned revision = sa_revision(sa_device, SWITCH_VALUES);
	int reads = switch_count("GET", "getswitchvalue");
	SA_CHECK(sa_advance(0, 2) && SA_WAIT(sa_state_after(sa_device, SWITCH_VALUES, INDIGO_OK_STATE, revision), SA_TIMEOUT));
	SA_CHECK(sa_number(sa_device, SWITCH_VALUES, "VALUE_1") == 40 && sa_number(sa_device, SWITCH_VALUES, "VALUE_2") == 25 && switch_simulated("Switch4.Value") == 40);
	SA_CHECK(switch_count("GET", "getswitchvalue") == reads + 1 && switch_last("GET", "getswitchvalue", "Id=4&ClientID="));
	// StateChangeComplete is not asked for any more
	int polls = switch_count("GET", "statechangecomplete");
	indigo_usleep(300000);
	SA_CHECK(switch_count("GET", "statechangecomplete") == polls);
	// two asynchronous changes in one request are one operation
	static const char *items[] = { "VALUE_1", "VALUE_2" };
	static const double values[] = { 5, 95 };
	revision = sa_revision(sa_device, SWITCH_VALUES);
	SA_CHECK(indigo_change_number_property(&sa_client, sa_device, SWITCH_VALUES, 2, items, values) == INDIGO_OK && SA_WAIT(switch_count("PUT", "setasyncvalue") == 3, SA_TIMEOUT));
	SA_CHECK(sa_advance(0, 1) && SA_WAIT(switch_count("GET", "statechangecomplete") >= polls + 4, SA_TIMEOUT) && sa_state(sa_device, SWITCH_VALUES) == INDIGO_BUSY_STATE);
	SA_CHECK(sa_advance(0, 1) && SA_WAIT(sa_state_after(sa_device, SWITCH_VALUES, INDIGO_OK_STATE, revision), SA_TIMEOUT));
	SA_CHECK(sa_number(sa_device, SWITCH_VALUES, "VALUE_1") == 5 && sa_number(sa_device, SWITCH_VALUES, "VALUE_2") == 95 && switch_simulated("Switch4.Value") == 5 && switch_simulated("Switch5.Value") == 95);
	// a boolean switch with CanAsync is set with setasync
	revision = sa_revision(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME);
	SA_CHECK(indigo_change_switch_property_1(&sa_client, sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_1", true) == INDIGO_OK && SA_WAIT(switch_count("PUT", "setasync") == 1, SA_TIMEOUT));
	SA_CHECK(switch_last("PUT", "setasync", "Id=0&State=True&ClientID=") && sa_state(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME) == INDIGO_BUSY_STATE && switch_simulated("Switch0.Value") == 0);
	SA_CHECK(sa_advance(0, 2) && SA_WAIT(sa_state_after(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME, INDIGO_OK_STATE, revision), SA_TIMEOUT));
	SA_CHECK(sa_switch(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_1") && switch_simulated("Switch0.Value") == 1 && switch_count("PUT", "setswitch") == 1);
	SA_CHECK(sa_disconnect(sa_device));
cleanup:
	sa_end();
}

static void switch_async_abort(void) {
	SA_CHECK(switch_begin(switch_default));
	// nothing is running: nothing is sent
	SA_CHECK(switch_set_switch(SWITCH_ABORT, "ABORT", true) == INDIGO_OK_STATE && !sa_switch(sa_device, SWITCH_ABORT, "ABORT") && switch_count("PUT", "cancelasync") == 0);
	SA_CHECK(switch_start_number(SWITCH_VALUES, "VALUE_1", 40) && SA_WAIT(switch_count("GET", "statechangecomplete") >= 2, SA_TIMEOUT));
	// cancelasync for the switch that is changing; the change ends in ALERT with the value the device has
	unsigned revision = sa_revision(sa_device, SWITCH_VALUES);
	SA_CHECK(switch_set_switch(SWITCH_ABORT, "ABORT", true) == INDIGO_OK_STATE && !sa_switch(sa_device, SWITCH_ABORT, "ABORT"));
	SA_CHECK(switch_count("PUT", "cancelasync") == 1 && switch_last("PUT", "cancelasync", "Id=4&ClientID="));
	SA_CHECK(SA_WAIT(sa_state_after(sa_device, SWITCH_VALUES, INDIGO_ALERT_STATE, revision), SA_TIMEOUT) && sa_message_seen("Change of 'Dew heater A' failed: operation cancelled"));
	SA_CHECK(sa_number(sa_device, SWITCH_VALUES, "VALUE_1") == 0 && sa_number_target(sa_device, SWITCH_VALUES, "VALUE_1") == 0 && switch_simulated("Switch4.Value") == 0);
	// the cancelled change does not happen later, and nothing is polled for it
	int polls = switch_count("GET", "statechangecomplete");
	SA_CHECK(sa_advance(0, 5));
	indigo_usleep(300000);
	SA_CHECK(switch_count("GET", "statechangecomplete") == polls && switch_simulated("Switch4.Value") == 0 && sa_number(sa_device, SWITCH_VALUES, "VALUE_1") == 0);
	// a new change works
	revision = sa_revision(sa_device, SWITCH_VALUES);
	SA_CHECK(switch_start_number(SWITCH_VALUES, "VALUE_1", 15));
	SA_CHECK(sa_advance(0, 2) && SA_WAIT(sa_state_after(sa_device, SWITCH_VALUES, INDIGO_OK_STATE, revision), SA_TIMEOUT));
	SA_CHECK(sa_number(sa_device, SWITCH_VALUES, "VALUE_1") == 15 && switch_count("PUT", "cancelasync") == 1);
	SA_CHECK(sa_disconnect(sa_device));
cleanup:
	sa_end();
}

static void switch_async_failures(void) {
	SA_CHECK(sa_begin(switch_default) && sa_set_number("X_ALPACA_TIMEOUTS", "LONG", 1) == INDIGO_OK_STATE && sa_attach("Switch Simulator") && sa_connect(sa_device));
	// the start is refused: the change did not start
	SA_CHECK(sa_fault(0, "PUT", SWITCH_API "setasyncvalue", "ascom-error", "Value=1035&Message=Heater%20fault"));
	SA_CHECK(switch_set_number(SWITCH_VALUES, "VALUE_1", 40) == INDIGO_ALERT_STATE && sa_message_seen("Change of 'Dew heater A' failed: invalid operation (Heater fault (0x40B))"));
	SA_CHECK(switch_count("GET", "statechangecomplete") == 0 && sa_number(sa_device, SWITCH_VALUES, "VALUE_1") == 0 && sa_number_target(sa_device, SWITCH_VALUES, "VALUE_1") == 0);
	// an error of the completion member means that the change failed after it started
	SA_CHECK(switch_start_number(SWITCH_VALUES, "VALUE_1", 40) && SA_WAIT(switch_count("GET", "statechangecomplete") >= 2, SA_TIMEOUT));
	unsigned revision = sa_revision(sa_device, SWITCH_VALUES);
	SA_CHECK(sa_fault(0, "GET", SWITCH_API "statechangecomplete", "ascom-error", "Value=1280&Message=Heater%20burnt"));
	SA_CHECK(SA_WAIT(sa_state_after(sa_device, SWITCH_VALUES, INDIGO_ALERT_STATE, revision), SA_TIMEOUT) && sa_message_seen("Change of 'Dew heater A' failed: device error (Heater burnt (0x500))"));
	SA_CHECK(sa_number(sa_device, SWITCH_VALUES, "VALUE_1") == 0 && sa_is_connected(sa_device));
	int polls = switch_count("GET", "statechangecomplete");
	indigo_usleep(300000);
	SA_CHECK(switch_count("GET", "statechangecomplete") == polls);
	// a reply that is no reply fails the change, too
	SA_CHECK(sa_advance(0, 5) && SA_WAIT(sa_number(sa_device, SWITCH_VALUES, "VALUE_1") == 40, SA_TIMEOUT));
	SA_CHECK(switch_start_number(SWITCH_VALUES, "VALUE_1", 50) && SA_WAIT(switch_count("GET", "statechangecomplete") >= polls + 2, SA_TIMEOUT));
	revision = sa_revision(sa_device, SWITCH_VALUES);
	SA_CHECK(sa_fault(0, "GET", SWITCH_API "statechangecomplete", "malformed-json", NULL));
	SA_CHECK(SA_WAIT(sa_state_after(sa_device, SWITCH_VALUES, INDIGO_ALERT_STATE, revision), SA_TIMEOUT) && sa_message_seen("Change of 'Dew heater A' failed: invalid reply"));
	SA_CHECK(sa_advance(0, 5) && SA_WAIT(sa_number(sa_device, SWITCH_VALUES, "VALUE_1") == 50, SA_TIMEOUT));
	// a change that does not end within the long timeout (1 s here) is given up
	SA_CHECK(switch_start_number(SWITCH_VALUES, "VALUE_2", 75));
	revision = sa_revision(sa_device, SWITCH_VALUES);
	double started = indigo_monotonic_time();
	SA_CHECK(SA_WAIT(sa_state_after(sa_device, SWITCH_VALUES, INDIGO_ALERT_STATE, revision), SA_TIMEOUT) && sa_message_seen("Change of 'Dew heater B' failed: timeout"));
	SA_CHECK(indigo_monotonic_time() - started > 0.7 && indigo_monotonic_time() - started < 3 && sa_number(sa_device, SWITCH_VALUES, "VALUE_2") == 25);
	SA_CHECK(sa_advance(0, 5) && SA_WAIT(sa_number(sa_device, SWITCH_VALUES, "VALUE_2") == 75, SA_TIMEOUT));
	// the transport is lost in the middle of a change: the change ends in ALERT, the device is disconnected, nothing hangs
	SA_CHECK(switch_start_number(SWITCH_VALUES, "VALUE_1", 90) && SA_WAIT(switch_last("GET", "statechangecomplete", "Id=4&"), SA_TIMEOUT));
	SA_CHECK(sa_fault(0, NULL, SWITCH_API "*", "reset", "Count=-1"));
	started = indigo_monotonic_time();
	SA_CHECK(SA_WAIT(core_alerted(sa_device), SA_TIMEOUT) && indigo_monotonic_time() - started < 5);
	SA_CHECK(sa_message_seen("Change of 'Dew heater A' failed: connection lost") && !sa_defined(sa_device, SWITCH_VALUES) && !sa_defined(sa_device, AUX_GPIO_OUTLETS_PROPERTY_NAME));
	int requests = sa_request_count(0, NULL, "/api/*");
	indigo_usleep(300000);
	SA_CHECK(sa_request_count(0, NULL, "/api/*") == requests);
	// the server is back: the device connects again and shows what the device did in the meantime
	SA_CHECK(sa_clear_faults(0) && sa_advance(0, 5) && sa_connect(sa_device));
	SA_CHECK(sa_state(sa_device, SWITCH_VALUES) == INDIGO_OK_STATE && sa_number(sa_device, SWITCH_VALUES, "VALUE_1") == 90 && sa_number(sa_device, SWITCH_VALUES, "VALUE_2") == 75);
	revision = sa_revision(sa_device, SWITCH_VALUES);
	SA_CHECK(switch_start_number(SWITCH_VALUES, "VALUE_1", 20) && sa_advance(0, 2) && SA_WAIT(sa_state_after(sa_device, SWITCH_VALUES, INDIGO_OK_STATE, revision), SA_TIMEOUT) && sa_number(sa_device, SWITCH_VALUES, "VALUE_1") == 20);
	SA_CHECK(sa_disconnect(sa_device));
cleanup:
	sa_end();
}

