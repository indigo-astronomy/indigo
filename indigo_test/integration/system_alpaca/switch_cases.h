	// at most eight requests in a poll tick, in turns
	int ticks = switch_count("GET", "devicestate"), reads = switch_reads();
	SA_CHECK(SA_WAIT(switch_count("GET", "devicestate") >= ticks + 10, SA_TIMEOUT));
	int ticks_after = switch_count("GET", "devicestate"), reads_after = switch_reads();
	SA_CHECK(reads_after - reads >= 8 * (ticks_after - ticks - 2) && reads_after - reads <= 8 * (ticks_after - ticks + 2));
	// a change on the device is seen for a switch of the snapshot and for one that is read by itself
	SA_CHECK(sa_device_state(0, "switch", 0, "Switch5.Value=66&Switch20.Value=1&Switch30.Value=1&Switch31.Value=0"));
