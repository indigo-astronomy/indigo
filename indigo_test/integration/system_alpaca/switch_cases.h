	SA_CHECK(switch_set_switch(AUX_GPIO_OUTLETS_PROPERTY_NAME, "OUTLET_28", true) == INDIGO_OK_STATE && switch_last("PUT", "setswitch", "Id=31&State=True&ClientID=") && switch_simulated("Switch31.Value") == 1);
