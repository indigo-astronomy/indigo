	SA_CHECK(sa_number(sa_device, SWITCH_VALUES, "VALUE_1") == 40 && sa_number_target(sa_device, SWITCH_VALUES, "VALUE_1") == 40 && SA_WAIT(sa_number(sa_device, SWITCH_VALUES, "VALUE_2") == 77, SA_TIMEOUT));
