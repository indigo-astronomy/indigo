// The device structure of an attached device of the driver under test, NULL if it is not attached. It is what the driver itself
// passes to its handlers, so a case can queue a handler of its own on the device with indigo_execute_handler().
static indigo_device *sa_device_pointer(const char *device) {
	indigo_device *result = NULL;
	pthread_mutex_lock(&sa_cache_mutex);
	for (int i = 0; i < SA_MAX_PROPERTIES && result == NULL; i++) {
		if (sa_cache[i].property != NULL && !strcmp(sa_cache[i].property->device, device)) {
			result = sa_cache[i].device;
		}
	}
	pthread_mutex_unlock(&sa_cache_mutex);
	return result;
}

// Number of attached devices whose name contains the text; with NULL all devices.
static int sa_device_count(const char *text) {
	char names[64][INDIGO_NAME_SIZE];
	int count = 0;
	pthread_mutex_lock(&sa_cache_mutex);
	for (int i = 0; i < SA_MAX_PROPERTIES; i++) {
		indigo_property *property = sa_cache[i].property;
		bool known = false;
		if (property == NULL || (text != NULL && strstr(property->device, text) == NULL)) {
			continue;
		}
		for (int j = 0; j < count && !known; j++) {
			known = !strcmp(names[j], property->device);
		}
		if (!known && count < 64) {
			strcpy(names[count++], property->device);
		}
	}
	pthread_mutex_unlock(&sa_cache_mutex);
	return count;
}

