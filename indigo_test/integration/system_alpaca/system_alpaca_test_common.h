typedef struct {
	indigo_property *property;
	indigo_device *device;								// the device that defined the property
	unsigned revision;										// value of the global counter at the last define or update
	unsigned state_revision[4];						// value of the global counter when the state was last seen
	unsigned define_count;
} sa_cache_entry;

static sa_cache_entry sa_cache[SA_MAX_PROPERTIES];
static pthread_mutex_t sa_cache_mutex = PTHREAD_MUTEX_INITIALIZER;
static unsigned sa_revision_counter = 0;
static int sa_stray_update_count = 0;
static char sa_messages[SA_MAX_MESSAGES][SA_TEXT_SIZE];
static int sa_message_count = 0;

static sa_cache_entry *sa_cache_find(const char *device, const char *name) {
	for (int i = 0; i < SA_MAX_PROPERTIES; i++) {
		indigo_property *property = sa_cache[i].property;
		if (property != NULL && !strcmp(property->device, device) && !strcmp(property->name, name)) {
			return sa_cache + i;
		}
	}
	return NULL;
}

static indigo_item *sa_cache_item(const char *device, const char *name, const char *item_name) {
	sa_cache_entry *entry = sa_cache_find(device, name);
	for (int i = 0; entry != NULL && i < entry->property->count; i++) {
		if (!strcmp(entry->property->items[i].name, item_name)) {
			return entry->property->items + i;
		}
	}
	return NULL;
}

static void sa_cache_message(const char *device, const char *message) {
	if (message != NULL && *message) {
		snprintf(sa_messages[sa_message_count++ % SA_MAX_MESSAGES], SA_TEXT_SIZE, "%s: %s", device, message);
	}
}

static indigo_result sa_client_define_property(indigo_client *client, indigo_device *device, indigo_property *property, const char *message) {
	(void)client;
	pthread_mutex_lock(&sa_cache_mutex);
	sa_cache_entry *entry = sa_cache_find(property->device, property->name);
	unsigned define_count = 0;
	if (entry != NULL) {
		define_count = entry->define_count;
		indigo_release_property(entry->property);
		entry->property = NULL;
	} else {
		for (int i = 0; i < SA_MAX_PROPERTIES && entry == NULL; i++) {
			if (sa_cache[i].property == NULL) {
				entry = sa_cache + i;
			}
		}
	}
	if (entry != NULL) {
		memset(entry, 0, sizeof(sa_cache_entry));
		entry->property = indigo_copy_property(NULL, property);
		entry->device = device;
		entry->define_count = define_count + 1;
		entry->revision = ++sa_revision_counter;
		entry->state_revision[property->state] = entry->revision;
	} else {
		fprintf(stderr, "property cache is full, %s.%s dropped\n", property->device, property->name);
		indigo_test_failures++;
	}
	sa_cache_message(property->device, message);
	pthread_mutex_unlock(&sa_cache_mutex);
	return INDIGO_OK;
}

static indigo_result sa_client_update_property(indigo_client *client, indigo_device *device, indigo_property *property, const char *message) {
	(void)client;
	(void)device;
	pthread_mutex_lock(&sa_cache_mutex);
	sa_cache_entry *entry = sa_cache_find(property->device, property->name);
	if (entry == NULL) {
		// an update of a property that is not defined is a protocol violation no client can make sense of
		sa_stray_update_count++;
		fprintf(stderr, "    %s.%s was updated without being defined\n", property->device, property->name);
	} else {
		entry->property->state = property->state;
		for (int i = 0; i < property->count; i++) {
			indigo_item *item = property->items + i;
			for (int j = 0; j < entry->property->count; j++) {
				indigo_item *cached = entry->property->items + j;
				if (strcmp(cached->name, item->name)) {
					continue;
				}
				switch (property->type) {
					case INDIGO_TEXT_VECTOR:
						indigo_set_text_item_value(cached, indigo_get_text_item_value(item));
						break;
					case INDIGO_NUMBER_VECTOR:
						cached->number = item->number;
						break;
					case INDIGO_SWITCH_VECTOR:
						cached->sw = item->sw;
						break;
					case INDIGO_LIGHT_VECTOR:
						cached->light = item->light;
						break;
					default:
						break;
				}
			}
		}
		entry->revision = ++sa_revision_counter;
		entry->state_revision[property->state] = entry->revision;
	}
	sa_cache_message(property->device, message);
	pthread_mutex_unlock(&sa_cache_mutex);
	return INDIGO_OK;
}

static indigo_result sa_client_delete_property(indigo_client *client, indigo_device *device, indigo_property *property, const char *message) {
	(void)client;
	(void)device;
	pthread_mutex_lock(&sa_cache_mutex);
	for (int i = 0; i < SA_MAX_PROPERTIES; i++) {
		indigo_property *cached = sa_cache[i].property;
		// a delete without a property name removes every property of the device
		if (cached != NULL && !strcmp(cached->device, property->device) && (*property->name == 0 || !strcmp(cached->name, property->name))) {
			indigo_release_property(cached);
			sa_cache[i].property = NULL;
		}
	}
	sa_cache_message(property->device, message);
	pthread_mutex_unlock(&sa_cache_mutex);
	return INDIGO_OK;
}

static indigo_result sa_client_send_message(indigo_client *client, indigo_device *device, indigo_property *property, const char *message) {
	(void)client;
	(void)property;
	pthread_mutex_lock(&sa_cache_mutex);
	sa_cache_message(device != NULL ? device->name : "", message);
	pthread_mutex_unlock(&sa_cache_mutex);
	return INDIGO_OK;
}

