// Name of the proxy device of a listed device, taken from its status ("..., device '<name>'"); "" if it has none. The buffer is static.
static const char *sa_proxy_name(const char *key) {
	static char name[INDIGO_NAME_SIZE];
	const char *status = sa_device_status(key);
	const char *start = strstr(status, ", device '");
	name[0] = 0;
	if (start != NULL) {
		snprintf(name, sizeof(name), "%s", start + 10);
		char *end = strrchr(name, '\'');
		if (end != NULL) {
			*end = 0;
		}
	}
	return name;
}

// Select or deselect a listed device by its key.
static bool sa_select(const char *key, bool selected) {
	return *key != 0 && indigo_change_switch_property_1(&sa_client, SA_BRIDGE, "X_ALPACA_DEVICES", key, selected) == INDIGO_OK;
}

// Select the device whose label in X_ALPACA_DEVICES contains the text and wait for its proxy device.
// The name of the proxy is left in sa_device.
static bool sa_attach(const char *label) {
	char key[INDIGO_NAME_SIZE];
	snprintf(key, sizeof(key), "%s", sa_device_key(label));
	sa_device[0] = 0;
	if (!sa_select(key, true) || !SA_WAIT(sa_device_status_is(key, "ATTACHED"), SA_TIMEOUT)) {
		fprintf(stderr, "'%s' (key '%s') was not attached: %s\n", label, key, sa_device_status(key));
		return false;
	}
	snprintf(sa_device, sizeof(sa_device), "%s", sa_proxy_name(key));
	return SA_WAIT(sa_defined(sa_device, CONNECTION_PROPERTY_NAME), SA_TIMEOUT);
}

// Wait until the device whose label in X_ALPACA_DEVICES contains the text has its proxy device, without switching anything: what a
// device that is on by default gets. The name of the proxy is left in sa_device.
static bool sa_wait_attached(const char *label) {
	char key[INDIGO_NAME_SIZE];
	sa_device[0] = 0;
	bool attached = SA_WAIT(sa_device_status_is(sa_device_key(label), "ATTACHED"), SA_TIMEOUT);
	snprintf(key, sizeof(key), "%s", sa_device_key(label));
	if (!attached) {
		fprintf(stderr, "'%s' (key '%s') has no proxy device: %s\n", label, key, sa_device_status(key));
		return false;
	}
	snprintf(sa_device, sizeof(sa_device), "%s", sa_proxy_name(key));
	return SA_WAIT(sa_defined(sa_device, CONNECTION_PROPERTY_NAME), SA_TIMEOUT);
}

// Switch the devices with the given UniqueIDs off in one request, whether they are listed or not, and wait for the answer.
static bool sa_switch_off(const char * const *unique_ids, int count) {
	static char keys[128][SA_KEY_SIZE];
	const char *items[128];
	bool values[128];
	if (count < 1 || count > 128) {
		return false;
	}
	for (int i = 0; i < count; i++) {
		sa_key(unique_ids[i], keys[i]);
		items[i] = keys[i];
		values[i] = false;
	}
	unsigned revision = sa_revision(SA_BRIDGE, "X_ALPACA_DEVICES");
	return indigo_change_switch_property(&sa_client, SA_BRIDGE, "X_ALPACA_DEVICES", count, items, values) == INDIGO_OK && SA_WAIT(sa_revision(SA_BRIDGE, "X_ALPACA_DEVICES") > revision && sa_state(SA_BRIDGE, "X_ALPACA_DEVICES") == INDIGO_OK_STATE, SA_TIMEOUT);
}

static bool sa_is_connected(const char *device) {
	return sa_state(device, CONNECTION_PROPERTY_NAME) == INDIGO_OK_STATE && sa_switch(device, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME);
}

static bool sa_is_disconnected(const char *device) {
	return sa_state(device, CONNECTION_PROPERTY_NAME) != INDIGO_BUSY_STATE && sa_switch(device, CONNECTION_PROPERTY_NAME, CONNECTION_DISCONNECTED_ITEM_NAME);
}

// Request the connection without waiting for the result.
static bool sa_request_connection(const char *device, bool connected) {
	return indigo_change_switch_property_1(&sa_client, device, CONNECTION_PROPERTY_NAME, connected ? CONNECTION_CONNECTED_ITEM_NAME : CONNECTION_DISCONNECTED_ITEM_NAME, true) == INDIGO_OK;
}

// Connect a proxy device and wait until it is connected. The simulated devices connect at once unless ConnectDelay is set.
static bool sa_connect(const char *device) {
	if (!sa_request_connection(device, true) || !SA_WAIT(sa_is_connected(device), SA_TIMEOUT)) {
		fprintf(stderr, "'%s' did not connect, CONNECTION state %d\n", device, sa_state(device, CONNECTION_PROPERTY_NAME));
		return false;
	}
	return true;
}

static bool sa_disconnect(const char *device) {
	if (!sa_request_connection(device, false) || !SA_WAIT(sa_state(device, CONNECTION_PROPERTY_NAME) == INDIGO_OK_STATE && sa_switch(device, CONNECTION_PROPERTY_NAME, CONNECTION_DISCONNECTED_ITEM_NAME), SA_TIMEOUT)) {
		fprintf(stderr, "'%s' did not disconnect, CONNECTION state %d\n", device, sa_state(device, CONNECTION_PROPERTY_NAME));
		return false;
	}
	return true;
}

// Disconnect a Platform 7 device of simulator 0 whose disconnect takes device time (ConnectDelay): CONNECTION stays BUSY while the
// device reports Connecting (state_path is its control API state, e.g. "/simulator/v1/focuser/0/state"), the given device time passes,
// and then the device is disconnected.
static bool sa_disconnect_after(const char *device, const char *state_path, double seconds) {
	if (!sa_request_connection(device, false) || !SA_WAIT(!strcmp(sa_status(0, state_path, "Connecting"), "true"), SA_TIMEOUT) || sa_state(device, CONNECTION_PROPERTY_NAME) != INDIGO_BUSY_STATE) {
		fprintf(stderr, "'%s' is not disconnecting, CONNECTION state %d\n", device, sa_state(device, CONNECTION_PROPERTY_NAME));
		return false;
	}
	if (!sa_advance(0, seconds) || !SA_WAIT(sa_state(device, CONNECTION_PROPERTY_NAME) == INDIGO_OK_STATE && sa_switch(device, CONNECTION_PROPERTY_NAME, CONNECTION_DISCONNECTED_ITEM_NAME), SA_TIMEOUT)) {
		fprintf(stderr, "'%s' did not disconnect, CONNECTION state %d\n", device, sa_state(device, CONNECTION_PROPERTY_NAME));
		return false;
	}
	return true;
}

// The usual start of a case: simulator 0 with the given arguments (NULL for one device of every type) and discovery,
// the driver with periodic discovery disabled, and one discovery cycle, after which the devices of the simulator are listed,
// switched off unless the case cleared sa_switch_off_devices (then they are attached by default).
static bool sa_begin(const char * const *arguments) {
	return sa_simulator_start(0, arguments, true) && sa_write_config(false, sa_targets(), NULL) && sa_driver_start() && sa_discover();
}

// The end of every case: disconnect whatever is connected, shut the driver down and stop the simulators.
// A shutdown that is refused or a property updated without being defined fails the case.
static void sa_end(void) {
	if (sa_driver_running) {
		char names[64][INDIGO_NAME_SIZE];
		int count = 0;
		pthread_mutex_lock(&sa_cache_mutex);
		for (int i = 0; i < SA_MAX_PROPERTIES && count < 64; i++) {
			indigo_property *property = sa_cache[i].property;
			if (property != NULL && !strcmp(property->name, CONNECTION_PROPERTY_NAME) && property->count == 2 && (property->items[0].sw.value || property->state == INDIGO_BUSY_STATE)) {
				strcpy(names[count++], property->device);
			}
		}
		pthread_mutex_unlock(&sa_cache_mutex);
		for (int i = 0; i < count; i++) {
			SA_WAIT(sa_state(names[i], CONNECTION_PROPERTY_NAME) != INDIGO_BUSY_STATE, SA_TIMEOUT);
			if (sa_defined(names[i], CONNECTION_PROPERTY_NAME) && !sa_is_disconnected(names[i])) {
				sa_request_connection(names[i], false);
				SA_WAIT(!sa_defined(names[i], CONNECTION_PROPERTY_NAME) || sa_is_disconnected(names[i]), SA_TIMEOUT);
			}
		}
		if (sa_stray_updates() != 0) {
			fprintf(stderr, "%d update(s) of properties that were not defined\n", sa_stray_updates());
			indigo_test_failures++;
		}
		indigo_result result = INDIGO_FAILED;
		if (!SA_WAIT((result = sa_driver_stop()) == INDIGO_OK, SA_TIMEOUT)) {
			fprintf(stderr, "driver shutdown failed with %d\n", result);
			indigo_test_failures++;
		}
	}
	for (int i = 0; i < SA_MAX_SIMULATORS; i++) {
		sa_simulator_stop(i);
	}
	sa_switch_off_devices = true;
}

