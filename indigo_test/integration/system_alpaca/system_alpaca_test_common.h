static void sa_cache_clear(void) {
	pthread_mutex_lock(&sa_cache_mutex);
	for (int i = 0; i < SA_MAX_PROPERTIES; i++) {
		if (sa_cache[i].property != NULL) {
			indigo_release_property(sa_cache[i].property);
		}
	}
	memset(sa_cache, 0, sizeof(sa_cache));
	sa_message_count = 0;
	pthread_mutex_unlock(&sa_cache_mutex);
}

