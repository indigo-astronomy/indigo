static bool sa_driver_running = false;

// Name of the proxy device attached by the last sa_attach().
static char sa_device[INDIGO_NAME_SIZE];

// sa_write_config() switches off every device of the running simulators (see the top of this file). sa_end() sets it again.
static bool sa_switch_off_devices = true;

// Key of a device, the name of its item in X_ALPACA_DEVICES: its UniqueID in lower case with everything that is not safe in an item
// name replaced by '_', and a hash of the whole UniqueID if a character was replaced or it is too long (as the driver documents it in
// indigo_docs/PROPERTIES.md; REV-18). key has room for SA_KEY_SIZE bytes.
#define SA_KEY_SIZE 64

static void sa_key(const char *unique_id, char *key) {
	size_t length = strlen(unique_id);
	uint32_t hash = 2166136261u;
	bool replaced = false;
	for (size_t i = 0; i < length; i++) {
		char c = unique_id[i] >= 'A' && unique_id[i] <= 'Z' ? (char)(unique_id[i] - 'A' + 'a') : unique_id[i];
		bool safe = (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c == '-' || c == '.' || c == '_';
		hash = (hash ^ (unsigned char)c) * 16777619u;
		replaced = replaced || !safe;
		if (i < SA_KEY_SIZE - 1) {
			key[i] = safe ? c : '_';
		}
	}
	if (length >= SA_KEY_SIZE - 10 && (replaced || length >= SA_KEY_SIZE)) {
		snprintf(key + SA_KEY_SIZE - 10, 10, "_%08x", (unsigned)hash);
	} else if (replaced) {
		snprintf(key + length, 10, "_%08x", (unsigned)hash);
	} else {
		key[length] = 0;
	}
}

// Write X_ALPACA_DEVICES with every device of the running simulators switched off, as a saved configuration has it. The devices are
// read from the control API of the simulators, which records nothing, so the request counts of a case do not change.
static void sa_write_devices_off(FILE *file) {
	char key[SA_KEY_SIZE];
	int count = 0;
	for (int i = 0; i < SA_MAX_SIMULATORS; i++) {
		const char *line = sa_simulators[i].control != NULL ? sa_get(i, "/simulator/v1/devices", NULL) : NULL;
		while (line != NULL && *line) {
			sa_key(sa_field(line, "UniqueID"), key);
			fprintf(file, "%s<oneSwitch name='%s'>Off</oneSwitch>\n", count++ == 0 ? "<newSwitchVector device='" SA_BRIDGE "' name='X_ALPACA_DEVICES'>\n" : "", key);
			line += strcspn(line, "\n");
			line += *line == '\n';
		}
	}
	if (count > 0) {
		fprintf(file, "</newSwitchVector>\n");
	}
}

// Write the configuration of the bridge device the driver restores at INIT. Discovery is always directed at explicit loopback
// targets (a broadcast would reach real Alpaca servers of the network the test machine is in), and timeouts and poll intervals
// are short. With discovery_enabled the driver runs a cycle with discovery every second. Without it the only cycle the driver
// runs by itself is the one at INIT (the interval is an hour), so a case decides with sa_discover() when a cycle runs.
// With sa_switch_off_devices every device of the running simulators is switched off. extra is appended after that, it may be NULL.
static FILE *sa_open_config(void) {
	char path[PATH_MAX];
	snprintf(path, sizeof(path), "%s/.indigo", getenv("HOME"));
	mkdir(path, 0700);
	snprintf(path, sizeof(path), "%s/.indigo/" SA_BRIDGE ".config", getenv("HOME"));
	FILE *file = fopen(path, "w");
	if (file == NULL) {
		perror(path);
	}
	return file;
}

static bool sa_write_config(bool discovery_enabled, const char *targets, const char *extra) {
	FILE *file = sa_open_config();
	if (file == NULL) {
		return false;
	}
	fprintf(file, "<newSwitchVector device='" SA_BRIDGE "' name='X_ALPACA_DISCOVERY'>\n<oneSwitch name='ENABLED'>%s</oneSwitch>\n<oneSwitch name='DISABLED'>%s</oneSwitch>\n</newSwitchVector>\n", discovery_enabled ? "On" : "Off", discovery_enabled ? "Off" : "On");
	fprintf(file, "<newNumberVector device='" SA_BRIDGE "' name='X_ALPACA_DISCOVERY_SETTINGS'>\n<oneNumber name='INTERVAL'>%d</oneNumber>\n<oneNumber name='TIMEOUT'>150</oneNumber>\n<oneNumber name='POLLS'>1</oneNumber>\n<oneNumber name='RETENTION'>2</oneNumber>\n</newNumberVector>\n", discovery_enabled ? 1 : 3600);
	fprintf(file, "<newTextVector device='" SA_BRIDGE "' name='X_ALPACA_DISCOVERY_TARGETS'>\n<oneText name='TARGETS'>%s</oneText>\n</newTextVector>\n", targets);
	fprintf(file, "<newNumberVector device='" SA_BRIDGE "' name='X_ALPACA_TIMEOUTS'>\n<oneNumber name='ESTABLISH'>2</oneNumber>\n<oneNumber name='STANDARD'>2</oneNumber>\n<oneNumber name='LONG'>5</oneNumber>\n</newNumberVector>\n");
	fprintf(file, "<newNumberVector device='" SA_BRIDGE "' name='X_ALPACA_POLLING'>\n<oneNumber name='IDLE'>0.1</oneNumber>\n<oneNumber name='ACTIVE'>0.05</oneNumber>\n</newNumberVector>\n");
	if (sa_switch_off_devices) {
		sa_write_devices_off(file);
	}
	if (extra != NULL) {
		fputs(extra, file);
	}
	fclose(file);
	return true;
}

// Discovery targets for the running simulators that answer discovery: "127.0.0.1:<port>,...". When there is none, the target is
// a loopback port nobody listens on, so the test never broadcasts.
static const char *sa_targets(void) {
	static char targets[256];
	size_t used = 0;
	targets[0] = 0;
	for (int i = 0; i < SA_MAX_SIMULATORS; i++) {
		if (sa_simulators[i].udp_port > 0) {
			used += (size_t)snprintf(targets + used, sizeof(targets) - used, "%s127.0.0.1:%d", used > 0 ? "," : "", sa_simulators[i].udp_port);
		}
	}
	if (used == 0) {
		snprintf(targets, sizeof(targets), "127.0.0.1:9");
	}
	return targets;
}

// Start the bus, the test client and the driver, and wait until the bridge device restored its configuration.
// The restore has to succeed, and promptly: a property the driver does not answer costs the restore five seconds and ends it in ALERT.
static bool sa_driver_start(void) {
	double started = indigo_monotonic_time();
	if (indigo_start() != INDIGO_OK) {
		return false;
	}
	if (indigo_attach_client(&sa_client) != INDIGO_OK || indigo_system_alpaca(INDIGO_DRIVER_INIT, NULL) != INDIGO_OK) {
		indigo_detach_client(&sa_client);
		indigo_stop();
		return false;
	}
	sa_driver_running = true;
	if (!SA_WAIT(sa_defined(SA_BRIDGE, "X_ALPACA_DEVICES") && sa_state(SA_BRIDGE, CONFIG_PROPERTY_NAME) != INDIGO_BUSY_STATE, SA_TIMEOUT) || sa_state(SA_BRIDGE, CONFIG_PROPERTY_NAME) != INDIGO_OK_STATE || indigo_monotonic_time() - started > 4) {
		fprintf(stderr, "configuration restore of the bridge ended in state %d after %.1f s\n", sa_state(SA_BRIDGE, CONFIG_PROPERTY_NAME), indigo_monotonic_time() - started);
		return false;
	}
	return true;
}

// Shut the driver down and stop the bus. Returns the result of INDIGO_DRIVER_SHUTDOWN; the bus is stopped only if it succeeded.
static indigo_result sa_driver_stop(void) {
	if (!sa_driver_running) {
		return INDIGO_OK;
	}
	indigo_result result = indigo_system_alpaca(INDIGO_DRIVER_SHUTDOWN, NULL);
	if (result == INDIGO_OK) {
		indigo_detach_client(&sa_client);
		indigo_stop();
		sa_cache_clear();
		sa_driver_running = false;
	}
	return result;
}

// Run one discovery cycle (X_ALPACA_DISCOVER) and wait until it is finished.
static bool sa_discover(void) {
	unsigned revision = sa_revision(SA_BRIDGE, "X_ALPACA_DISCOVER");
	if (indigo_change_switch_property_1(&sa_client, SA_BRIDGE, "X_ALPACA_DISCOVER", "DISCOVER", true) != INDIGO_OK) {
		return false;
	}
	return SA_WAIT(sa_state_after(SA_BRIDGE, "X_ALPACA_DISCOVER", INDIGO_OK_STATE, revision) && sa_state(SA_BRIDGE, "X_ALPACA_DISCOVER") == INDIGO_OK_STATE, 3 * SA_TIMEOUT);
}

// Item name of a simulator in X_ALPACA_SERVER_STATUS ("127.0.0.1:<port>") and its status text, which starts with the state:
// ONLINE, SILENT, OFFLINE, IGNORED or UNSUPPORTED.
static const char *sa_server_item(int index) {
	static char names[SA_MAX_SIMULATORS][64];
	snprintf(names[index], sizeof(names[index]), "127.0.0.1:%d", sa_simulators[index].http_port);
	return names[index];
}

static const char *sa_server_status(int index) {
	return sa_text(SA_BRIDGE, "X_ALPACA_SERVER_STATUS", sa_server_item(index));
}

// Number of listed devices whose status starts with the given state.
static int sa_status_count(const char *state) {
	int count = 0;
	size_t length = strlen(state);
	pthread_mutex_lock(&sa_cache_mutex);
	sa_cache_entry *entry = sa_cache_find(SA_BRIDGE, "X_ALPACA_DEVICE_STATUS");
	for (int i = 0; entry != NULL && i < entry->property->count; i++) {
		const char *status = indigo_get_text_item_value(entry->property->items + i);
		count += !strncmp(status, state, length) && status[length] == ':';
	}
	pthread_mutex_unlock(&sa_cache_mutex);
	return count;
}

// Change one item of a property of the bridge and wait until the driver answered with a state that is not BUSY. Returns that state, -1 on failure.
static int sa_set_text(const char *name, const char *item, const char *value) {
	unsigned revision = sa_revision(SA_BRIDGE, name);
	if (indigo_change_text_property_1_raw(&sa_client, SA_BRIDGE, name, item, value) != INDIGO_OK || !SA_WAIT(sa_revision(SA_BRIDGE, name) > revision && sa_state(SA_BRIDGE, name) != INDIGO_BUSY_STATE, SA_TIMEOUT)) {
		return -1;
	}
	return sa_state(SA_BRIDGE, name);
}

static int sa_set_number(const char *name, const char *item, double value) {
	unsigned revision = sa_revision(SA_BRIDGE, name);
	if (indigo_change_number_property_1(&sa_client, SA_BRIDGE, name, item, value) != INDIGO_OK || !SA_WAIT(sa_revision(SA_BRIDGE, name) > revision && sa_state(SA_BRIDGE, name) != INDIGO_BUSY_STATE, SA_TIMEOUT)) {
		return -1;
	}
	return sa_state(SA_BRIDGE, name);
}

static int sa_set_switch(const char *name, const char *item, bool value) {
	unsigned revision = sa_revision(SA_BRIDGE, name);
	if (indigo_change_switch_property_1(&sa_client, SA_BRIDGE, name, item, value) != INDIGO_OK || !SA_WAIT(sa_revision(SA_BRIDGE, name) > revision && sa_state(SA_BRIDGE, name) != INDIGO_BUSY_STATE, SA_TIMEOUT)) {
		return -1;
	}
	return sa_state(SA_BRIDGE, name);
}

