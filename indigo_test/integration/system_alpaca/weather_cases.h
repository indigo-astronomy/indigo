	char key[INDIGO_NAME_SIZE];
	SA_CHECK(sa_begin(weather_default));
	snprintf(key, sizeof(key), "%s", sa_device_key("ObservingConditions Simulator"));
	SA_CHECK(sa_attach("ObservingConditions Simulator"));
