	SA_CHECK(sa_put(0, CCD_ERROR, "Member=camerastate&ErrorNumber=0") && ccd_count("PUT", "abortexposure") == 1 && ccd_simulated_is("CameraState", "0") && sa_is_connected(sa_device) && ccd_images() == 0 && ccd_count("GET", "imagearray") == 0);
