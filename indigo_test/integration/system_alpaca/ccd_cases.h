	SA_CHECK(ccd_count("GET", "bayeroffset*") == 0 && ccd_count("GET", "gains") == 0 && ccd_count("GET", "offsets") == 0 && ccd_count("GET", "fastreadout") == 0 && ccd_count("GET", "imagearray*") == 0);
	SA_CHECK(ccd_count("PUT", "*") == 1 && ccd_count("PUT", "connect") == 1);
