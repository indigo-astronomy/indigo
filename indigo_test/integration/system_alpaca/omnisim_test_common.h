// Write the configuration of the bridge: discovery off and aimed at a loopback port nobody listens on (never a broadcast, other
// Alpaca servers of the network or agent_alpaca of another INDIGO session must not answer), timeouts for real time.
static bool omni_write_config(const char *targets) {
	FILE *file = sa_open_config();
	if (file == NULL) {
		return false;
	}
	fprintf(file, "<newSwitchVector device='" SA_BRIDGE "' name='X_ALPACA_DISCOVERY'>\n<oneSwitch name='ENABLED'>Off</oneSwitch>\n<oneSwitch name='DISABLED'>On</oneSwitch>\n</newSwitchVector>\n");
	fprintf(file, "<newNumberVector device='" SA_BRIDGE "' name='X_ALPACA_DISCOVERY_SETTINGS'>\n<oneNumber name='INTERVAL'>3600</oneNumber>\n<oneNumber name='TIMEOUT'>500</oneNumber>\n<oneNumber name='POLLS'>2</oneNumber>\n<oneNumber name='RETENTION'>2</oneNumber>\n</newNumberVector>\n");
	fprintf(file, "<newTextVector device='" SA_BRIDGE "' name='X_ALPACA_DISCOVERY_TARGETS'>\n<oneText name='TARGETS'>%s</oneText>\n</newTextVector>\n", targets);
	fprintf(file, "<newNumberVector device='" SA_BRIDGE "' name='X_ALPACA_TIMEOUTS'>\n<oneNumber name='ESTABLISH'>10</oneNumber>\n<oneNumber name='STANDARD'>5</oneNumber>\n<oneNumber name='LONG'>30</oneNumber>\n</newNumberVector>\n");
	fprintf(file, "<newNumberVector device='" SA_BRIDGE "' name='X_ALPACA_POLLING'>\n<oneNumber name='IDLE'>0.25</oneNumber>\n<oneNumber name='ACTIVE'>0.1</oneNumber>\n</newNumberVector>\n");
	fclose(file);
	return true;
}

// Every device is proxied unless it is switched off (decision D15). So that a case decides which proxy devices exist, every device
// OmniSim lists is switched off by its UniqueID before the driver finds OmniSim; sa_attach() then switches one on.
static bool omni_switch_off_all(void) {
	static char unique_ids[32][INDIGO_NAME_SIZE];
	const char *ids[32];
	int count = 0;
	sa_simulator *simulator = sa_simulators + 0;
	alpaca_http_result result = alpaca_http_get(simulator->control, "/management/v1/configureddevices", NULL, NULL, &simulator->response);
	const alpaca_json_value *list = result == ALPACA_HTTP_OK && simulator->response.status == 200 ? omni_parse(NULL) : NULL;
	for (const alpaca_json_value *entry = list != NULL ? alpaca_json_first(list) : NULL; entry != NULL && count < 32; entry = alpaca_json_next(entry)) {
		const char *unique_id = NULL;
		if (alpaca_json_get_string(alpaca_json_get(entry, "UniqueID"), &unique_id)) {
			snprintf(unique_ids[count], INDIGO_NAME_SIZE, "%s", unique_id);
			ids[count] = unique_ids[count];
			count++;
		}
	}
	if (count < 10 || !sa_switch_off(ids, count)) {
		fprintf(stderr, "    the devices of OmniSim were not switched off (%d listed)\n", count);
		return false;
	}
	return true;
}

// The usual start of a case: the driver with discovery off, the devices of OmniSim switched off, OmniSim added as a manual server
// and one cycle run, after which its devices are listed. The instance was started by the case runner.
static bool omni_begin(void) {
	omni_connect_control();
	if (!omni_write_config("127.0.0.1:9") || !sa_driver_start() || !omni_switch_off_all()) {
		return false;
	}
	if (sa_set_text("X_ALPACA_SERVERS", "ADD", omni_url) != INDIGO_OK_STATE || !sa_discover()) {
		fprintf(stderr, "    OmniSim at %s was not added: %s\n", omni_url, sa_text(SA_BRIDGE, "X_ALPACA_SERVER_STATUS", omni_url));
		return false;
	}
	return SA_WAIT(sa_status_count("AVAILABLE") >= 10, SA_TIMEOUT);
}

// Attach and connect the device whose label contains the text; its name is left in sa_device.
static bool omni_attach_connect(const char *label) {
	if (!sa_attach(label)) {
		return false;
	}
	if (!sa_request_connection(sa_device, true) || !SA_WAIT(sa_is_connected(sa_device), OMNI_TIMEOUT)) {
		fprintf(stderr, "    '%s' did not connect, CONNECTION state %d\n", sa_device, sa_state(sa_device, CONNECTION_PROPERTY_NAME));
		return false;
	}
	return true;
}

// Disconnect and switch off (detach) the device of the case, both checked.
static bool omni_disconnect_detach(const char *label) {
	char key[INDIGO_NAME_SIZE];
	snprintf(key, sizeof(key), "%s", sa_device_key(label));
	if (!sa_disconnect(sa_device)) {
		return false;
	}
	if (!sa_select(key, false) || !SA_WAIT(!sa_device_defined(sa_device) && sa_device_status_is(key, "AVAILABLE"), SA_TIMEOUT)) {
		fprintf(stderr, "    '%s' was not detached: %s\n", sa_device, sa_device_status(key));
		return false;
	}
	return true;
}

static void omni_end(void) {
	sa_end();
	alpaca_json_free(omni_reply);
	omni_reply = NULL;
}

// Wait for the answer to a request made after the given revision: a state that is not BUSY. Returns it, -1 if there was none in time.
static int omni_answer(const char *device, const char *property, unsigned revision, double seconds) {
	if (!SA_WAIT(sa_revision(device, property) > revision && sa_state(device, property) != INDIGO_BUSY_STATE, seconds)) {
		fprintf(stderr, "    %s.%s got no answer within %.0f s, state %d\n", device, property, seconds, sa_state(device, property));
		return -1;
	}
	return sa_state(device, property);
}

static int omni_set_number(const char *device, const char *property, const char *item, double value, double seconds) {
	unsigned revision = sa_revision(device, property);
	return indigo_change_number_property_1(&sa_client, device, property, item, value) == INDIGO_OK ? omni_answer(device, property, revision, seconds) : -1;
}

static int omni_set_numbers(const char *device, const char *property, int count, const char **items, const double *values, double seconds) {
	unsigned revision = sa_revision(device, property);
	return indigo_change_number_property(&sa_client, device, property, count, items, values) == INDIGO_OK ? omni_answer(device, property, revision, seconds) : -1;
}

static int omni_set_switch(const char *device, const char *property, const char *item, bool value, double seconds) {
	unsigned revision = sa_revision(device, property);
	return indigo_change_switch_property_1(&sa_client, device, property, item, value) == INDIGO_OK ? omni_answer(device, property, revision, seconds) : -1;
}

// The property went BUSY after the revision (the driver started an operation) and ended in the given state.
static bool omni_went_busy(const char *device, const char *property, unsigned revision) {
	return sa_state_after(device, property, INDIGO_BUSY_STATE, revision);
}

static void omni_print_messages(void) {
	pthread_mutex_lock(&sa_cache_mutex);
	for (int i = 0; i < SA_MAX_MESSAGES; i++) {
		if (*sa_messages[i]) {
			fprintf(stderr, "    message: %s\n", sa_messages[i]);
		}
	}
	pthread_mutex_unlock(&sa_cache_mutex);
}

// Number of the INFO item "Alpaca interface version" of the device.
static int omni_interface_version(const char *device) {
	return atoi(sa_text(device, INFO_PROPERTY_NAME, INFO_DEVICE_HW_REVISION_ITEM_NAME));
}

