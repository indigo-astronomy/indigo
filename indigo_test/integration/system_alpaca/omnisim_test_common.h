// Find the executable: INDIGO_TEST_OMNISIM, else omnisim/*/ascom.alpaca.simulators. False if there is none.
static bool omni_find(void) {
	const char *configured = getenv("INDIGO_TEST_OMNISIM");
	omni_executable[0] = 0;
	if (configured != NULL && *configured) {
		if (access(configured, X_OK) == 0) {
			snprintf(omni_executable, sizeof(omni_executable), "%s", configured);
			return true;
		}
		fprintf(stderr, "INDIGO_TEST_OMNISIM='%s' is not an executable\n", configured);
		return false;
	}
	glob_t found = { 0 };
	if (glob(SYSTEM_ALPACA_OMNISIM_DIR "/*/" OMNI_EXECUTABLE_NAME, 0, NULL, &found) == 0) {
		for (size_t i = 0; i < found.gl_pathc && !*omni_executable; i++) {
			if (access(found.gl_pathv[i], X_OK) == 0) {
				snprintf(omni_executable, sizeof(omni_executable), "%s", found.gl_pathv[i]);
			}
		}
	}
	globfree(&found);
	return *omni_executable != 0;
}

// Exclusive lock of the executable for the whole run, so two runs of this suite never start OmniSim at the same time.
// No file is created for it. Waits for another run for at most OMNI_LOCK_TIMEOUT.
static bool omni_lock_run(void) {
	omni_run_lock = open(omni_executable, O_RDONLY | O_CLOEXEC);
	if (omni_run_lock < 0) {
		perror(omni_executable);
		return false;
	}
	double deadline = indigo_monotonic_time() + OMNI_LOCK_TIMEOUT;
	bool told = false;
	while (flock(omni_run_lock, LOCK_EX | LOCK_NB) != 0) {
		if (errno != EWOULDBLOCK && errno != EINTR) {
			perror("flock");
			return false;
		}
		if (!told) {
			printf("waiting for another run of the OmniSim tier to finish\n");
			told = true;
		}
		if (indigo_monotonic_time() > deadline) {
			fprintf(stderr, "another run of the OmniSim tier holds %s for more than %.0f s\n", omni_executable, OMNI_LOCK_TIMEOUT);
			return false;
		}
		indigo_usleep(200000);
	}
	return true;
}

static void omni_unlock_run(void) {
	if (omni_run_lock >= 0) {
		flock(omni_run_lock, LOCK_UN);
		close(omni_run_lock);
		omni_run_lock = -1;
	}
}

// ---------------------------------------------------------------------------- one instance

// A port nobody listens on at the moment.
static int omni_free_port(void) {
	int handle = socket(AF_INET, SOCK_STREAM, 0);
	struct sockaddr_in address = { 0 };
	socklen_t length = sizeof(address);
	int port = 0;
	address.sin_family = AF_INET;
	address.sin_addr.s_addr = htonl(INADDR_LOOPBACK);
	if (handle >= 0 && bind(handle, (struct sockaddr *)&address, sizeof(address)) == 0 && getsockname(handle, (struct sockaddr *)&address, &length) == 0) {
		port = ntohs(address.sin_port);
	}
	if (handle >= 0) {
		close(handle);
	}
	return port;
}

// The reaper: starts OmniSim and ends it when the case closes its end of the pipe (or dies), or ends itself when OmniSim exits.
// Exit code 0 after it stopped OmniSim, 3 when OmniSim exited by itself.
static void omni_reaper_main(int pipe_end, int instance_lock, const char *home, const char *log) {
	char urls[64];
	snprintf(urls, sizeof(urls), "--urls=http://127.0.0.1:%d", omni_port);
	pid_t omnisim = fork();
	if (omnisim == 0) {
		close(pipe_end);
		int null = open("/dev/null", O_RDONLY);
		int output = open(log, O_WRONLY | O_CREAT | O_APPEND, 0600);
		if (null >= 0) {
			dup2(null, STDIN_FILENO);
		}
		if (output >= 0) {
			dup2(output, STDOUT_FILENO);
			dup2(output, STDERR_FILENO);
		}
		// OmniSim keeps the instance lock while it lives: the descriptor is inherited, not closed on exec
		(void)instance_lock;
		// HOME for .NET itself and for Linux; CFFIXED_USER_HOME for the folders .NET asks Foundation for on macOS (Application Support and
		// Documents ignore HOME there); ASCOM_LOGPATH for the logs on every Unix; no XDG folder may point out of the private HOME
		char logs[PATH_MAX];
		snprintf(logs, sizeof(logs), "%s/logs", home);
		unsetenv("XDG_CONFIG_HOME");
		unsetenv("XDG_DATA_HOME");
		if (chdir(home) != 0 || setenv("HOME", home, 1) != 0 || setenv("CFFIXED_USER_HOME", home, 1) != 0 || setenv("ASCOM_LOGPATH", logs, 1) != 0) {
			_exit(126);
		}
		execl(omni_executable, omni_executable, urls, (char *)NULL);
		_exit(127);
	}
	close(instance_lock);
	if (omnisim < 0) {
		_exit(2);
	}
	FILE *file = NULL;
	char pid_path[PATH_MAX];
	snprintf(pid_path, sizeof(pid_path), "%s.pid", omni_instance_lock);
	if ((file = fopen(pid_path, "w")) != NULL) {
		fprintf(file, "%d\n", (int)omnisim);
		fclose(file);
	}
	struct pollfd watch = { pipe_end, POLLIN, 0 };
	int status = 0;
	while (true) {
		if (waitpid(omnisim, &status, WNOHANG) == omnisim) {
			unlink(pid_path);
			_exit(3);
		}
		if (poll(&watch, 1, 100) > 0) {
			char byte;
			if (read(pipe_end, &byte, 1) <= 0) {
				break;
			}
		}
	}
	kill(omnisim, SIGTERM);
	for (int i = 0; i < 150; i++) {
		if (waitpid(omnisim, &status, WNOHANG) == omnisim) {
			unlink(pid_path);
			_exit(0);
		}
		usleep(100000);
	}
	kill(omnisim, SIGKILL);
	waitpid(omnisim, &status, 0);
	unlink(pid_path);
	_exit(0);
}

// The reaper is still there, i.e. OmniSim runs.
static bool omni_running(void) {
	int status = 0;
	if (omni_reaper <= 0) {
		return false;
	}
	if (waitpid(omni_reaper, &status, WNOHANG) == omni_reaper) {
		omni_reaper = 0;
		return false;
	}
	return true;
}

static bool omni_http_get(alpaca_http_connection *connection, const char *path, alpaca_http_response *response) {
	alpaca_http_options options = { { 1000, 2000, 2000, 3000 }, NULL, false };
	return alpaca_http_get(connection, path, NULL, &options, response) == ALPACA_HTTP_OK && response->status == 200;
}

// Start a fresh instance in directory (created if needed) and wait until it answers. Waits first until the instance of the
// previous case is gone. The version is read into omni_version on the way.
static bool omni_start(const char *directory) {
	char home[PATH_MAX], folder[PATH_MAX], log[PATH_MAX];
	snprintf(omni_directory, sizeof(omni_directory), "%s", directory);
	snprintf(home, sizeof(home), "%s/home", directory);
	snprintf(log, sizeof(log), "%s/omnisim.log", directory);
	mkdir(directory, 0700);
	mkdir(home, 0700);
	// the folder of the profiles: .NET returns "" for one that does not exist, and OmniSim then writes into the working directory
	snprintf(folder, sizeof(folder), "%s/.config", home);
	mkdir(folder, 0700);
	snprintf(folder, sizeof(folder), "%s/Library", home);
	mkdir(folder, 0700);
	snprintf(folder, sizeof(folder), "%s/Library/Application Support", home);
	mkdir(folder, 0700);
	int instance_lock = open(omni_instance_lock, O_RDWR | O_CREAT, 0600);
	if (instance_lock < 0) {
		perror(omni_instance_lock);
		return false;
	}
	double deadline = indigo_monotonic_time() + 30;
	while (flock(instance_lock, LOCK_EX | LOCK_NB) != 0) {
		if (indigo_monotonic_time() > deadline) {
			fprintf(stderr, "the OmniSim instance of the previous case did not end within 30 s\n");
			close(instance_lock);
			return false;
		}
		indigo_usleep(100000);
	}
	omni_port = omni_free_port();
	int pipe_ends[2];
	if (omni_port <= 0 || pipe(pipe_ends) != 0) {
		close(instance_lock);
		return false;
	}
	fflush(NULL);
	omni_reaper = fork();
	if (omni_reaper == 0) {
		close(pipe_ends[1]);
		omni_reaper_main(pipe_ends[0], instance_lock, home, log);
	}
	close(pipe_ends[0]);
	close(instance_lock);
	if (omni_reaper < 0) {
		close(pipe_ends[1]);
		return false;
	}
	fcntl(pipe_ends[1], F_SETFD, FD_CLOEXEC);
	omni_reaper_pipe = pipe_ends[1];
	snprintf(omni_url, sizeof(omni_url), "127.0.0.1:%d", omni_port);
	alpaca_http_connection *connection = alpaca_http_connection_create("127.0.0.1", omni_port);
	alpaca_http_response response;
	alpaca_http_response_init(&response, 65536);
	bool ready = false;
	double started = indigo_monotonic_time();
	while (!ready && omni_running() && indigo_monotonic_time() - started < OMNI_START_TIMEOUT) {
		ready = omni_http_get(connection, "/management/v1/description", &response);
		if (!ready) {
			indigo_usleep(100000);
		}
	}
	if (ready) {
		char error[128];
		alpaca_json_value *root = alpaca_json_parse(response.body.data, response.body.size, error, sizeof(error));
		const char *version = NULL;
		const char *server = NULL;
		if (root != NULL && alpaca_json_get_string(alpaca_json_get(alpaca_json_get(root, "Value"), "ManufacturerVersion"), &version) && alpaca_json_get_string(alpaca_json_get(alpaca_json_get(root, "Value"), "ServerName"), &server)) {
			snprintf(omni_version_full, sizeof(omni_version_full), "%s", version);
			snprintf(omni_version, sizeof(omni_version), "%.*s", (int)strcspn(version, "+"), version);
			if (strcmp(server, OMNI_SERVER_NAME)) {
				fprintf(stderr, "the server on port %d is '%s', not OmniSim\n", omni_port, server);
				ready = false;
			}
		} else {
			fprintf(stderr, "management/v1/description of OmniSim can not be read: %s\n", response.body.data != NULL ? response.body.data : "");
			ready = false;
		}
		alpaca_json_free(root);
	} else if (!omni_running()) {
		fprintf(stderr, "OmniSim exited right after the start; another instance probably runs on this host (it takes over every start)\n");
	} else {
		fprintf(stderr, "OmniSim did not answer on port %d within %.0f s\n", omni_port, OMNI_START_TIMEOUT);
	}
	alpaca_http_response_free(&response);
	alpaca_http_connection_free(connection);
	return ready;
}

// Stop the instance of this process and wait until it is gone.
static void omni_stop(void) {
	if (omni_reaper_pipe >= 0) {
		close(omni_reaper_pipe);
		omni_reaper_pipe = -1;
	}
	if (omni_reaper > 0) {
		int status = 0;
		double deadline = indigo_monotonic_time() + 30;
		while (waitpid(omni_reaper, &status, WNOHANG) == 0 && indigo_monotonic_time() < deadline) {
			indigo_usleep(50000);
		}
		omni_reaper = 0;
	}
	omni_port = 0;
}

// Last resort of the parent: the instance a killed case left behind (normally the reaper has ended it already).
static void omni_kill_leftover(void) {
	char pid_path[PATH_MAX];
	snprintf(pid_path, sizeof(pid_path), "%s.pid", omni_instance_lock);
	FILE *file = fopen(pid_path, "r");
	int pid = 0;
	if (file != NULL) {
		if (fscanf(file, "%d", &pid) != 1) {
			pid = 0;
		}
		fclose(file);
	}
	if (pid > 0 && kill(pid, 0) == 0) {
		fprintf(stderr, "stopping OmniSim %d left behind by a case\n", pid);
		kill(pid, SIGTERM);
		for (int i = 0; i < 100 && kill(pid, 0) == 0; i++) {
			indigo_usleep(100000);
		}
		kill(pid, SIGKILL);
	}
	int instance_lock = open(omni_instance_lock, O_RDWR);
	if (instance_lock >= 0) {
		for (int i = 0; i < 300 && flock(instance_lock, LOCK_EX | LOCK_NB) != 0; i++) {
			indigo_usleep(100000);
		}
		close(instance_lock);
	}
}

// ---------------------------------------------------------------------------- direct access to OmniSim

// The Alpaca API and the simulator API of the instance, through simulator slot 0 of the harness, so that sa_put() and sa_get()
// work too. Set up by omni_begin().
static alpaca_json_value *omni_reply = NULL;

static void omni_connect_control(void) {
	sa_simulator *simulator = sa_simulators + 0;
	memset(simulator, 0, sizeof(sa_simulator));
	simulator->http_port = omni_port;
	simulator->control = alpaca_http_connection_create("127.0.0.1", omni_port);
	alpaca_http_response_init(&simulator->response, 16 * 1024 * 1024);
	alpaca_http_buffer_init(&simulator->form, 65536);
}

// Parse the body of the last answer of slot 0. The value stays valid until the next request.
static const alpaca_json_value *omni_parse(int *error_number) {
	sa_simulator *simulator = sa_simulators + 0;
	char error[128];
	alpaca_json_free(omni_reply);
	omni_reply = NULL;
	if (simulator->response.body.data == NULL) {
		return NULL;
	}
	omni_reply = alpaca_json_parse(simulator->response.body.data, simulator->response.body.size, error, sizeof(error));
	int64_t number = -1;
	if (omni_reply == NULL || !alpaca_json_get_int(alpaca_json_get(omni_reply, "ErrorNumber"), &number)) {
		number = -1;
	}
	if (error_number != NULL) {
		*error_number = (int)number;
	}
	return omni_reply != NULL ? alpaca_json_get(omni_reply, "Value") : NULL;
}

// GET a member of the Alpaca API, e.g. omni_get("telescope", "declination", NULL). Returns the Value (NULL on failure) and
// the ErrorNumber (-1 without a valid answer); the HTTP status is left in omni_status.
static int omni_status = 0;

static const alpaca_json_value *omni_get(const char *type, const char *member, const char *query, int *error_number) {
	char path[256];
	sa_simulator *simulator = sa_simulators + 0;
	snprintf(path, sizeof(path), "/api/v1/%s/0/%s", type, member);
	alpaca_http_result result = alpaca_http_get(simulator->control, path, query, NULL, &simulator->response);
	omni_status = result == ALPACA_HTTP_OK ? simulator->response.status : 0;
	if (omni_status != 200) {
		if (error_number != NULL) {
			*error_number = -1;
		}
		return NULL;
	}
	return omni_parse(error_number);
}

// PUT to the Alpaca API, e.g. omni_put("rotator", "sync", "Position=10"). Returns the ErrorNumber, -1 without a valid answer.
static int omni_put(const char *type, const char *member, const char *form) {
	char path[256], body[1024];
	int error_number = -1;
	sa_simulator *simulator = sa_simulators + 0;
	snprintf(path, sizeof(path), "/api/v1/%s/0/%s", type, member);
	snprintf(body, sizeof(body), "%s%sClientID=4242&ClientTransactionID=1", form != NULL ? form : "", form != NULL && *form ? "&" : "");
	alpaca_http_result result = alpaca_http_put(simulator->control, path, NULL, body, NULL, &simulator->response);
	omni_status = result == ALPACA_HTTP_OK ? simulator->response.status : 0;
	if (omni_status == 200) {
		omni_parse(&error_number);
	}
	return error_number;
}

// Change a setting of the simulator API (/simulator/v1/<type>/0/<setting>), e.g. omni_setting("focuser", "interfaceversion", "InterfaceVersion=3").
static bool omni_setting(const char *type, const char *setting, const char *form) {
	char path[256];
	int error_number = -1;
	snprintf(path, sizeof(path), "/simulator/v1/%s/0/%s", type, setting);
	if (!sa_put(0, path, form)) {
		return false;
	}
	omni_parse(&error_number);
	if (error_number != 0) {
		fprintf(stderr, "    PUT %s %s answered ErrorNumber %d\n", path, form, error_number);
	}
	return error_number == 0;
}

static bool omni_get_double(const char *type, const char *member, double *value) {
	int error_number = -1;
	const alpaca_json_value *json = omni_get(type, member, NULL, &error_number);
	return error_number == 0 && alpaca_json_get_double(json, value);
}

static bool omni_get_bool(const char *type, const char *member, bool *value) {
	int error_number = -1;
	const alpaca_json_value *json = omni_get(type, member, NULL, &error_number);
	return error_number == 0 && alpaca_json_get_bool(json, value);
}

static bool omni_get_int(const char *type, const char *member, int *value) {
	int error_number = -1;
	int64_t number = 0;
	const alpaca_json_value *json = omni_get(type, member, NULL, &error_number);
	if (error_number == 0 && alpaca_json_get_int(json, &number)) {
		*value = (int)number;
		return true;
	}
	return false;
}

// Value of a member read directly from OmniSim, NAN if it can not be read.
static double omni_double(const char *type, const char *member) {
	double value = NAN;
	return omni_get_double(type, member, &value) ? value : NAN;
}

static int omni_int(const char *type, const char *member) {
	int value = -1;
	return omni_get_int(type, member, &value) ? value : -1;
}

static bool omni_bool(const char *type, const char *member) {
	bool value = false;
	return omni_get_bool(type, member, &value) && value;
}

// Names of the entries of the devicestate of a device, comma separated, "" on failure. The buffer is static.
static const char *omni_device_state_names(const char *type) {
	static char names[1024];
	int error_number = -1;
	size_t used = 0;
	names[0] = 0;
	const alpaca_json_value *value = omni_get(type, "devicestate", NULL, &error_number);
	for (const alpaca_json_value *entry = error_number == 0 && value != NULL ? alpaca_json_first(value) : NULL; entry != NULL; entry = alpaca_json_next(entry)) {
		const char *name = NULL;
		if (alpaca_json_get_string(alpaca_json_get(entry, "Name"), &name) && used < sizeof(names) - 1) {
			used += (size_t)snprintf(names + used, sizeof(names) - used, "%s%s", used > 0 ? "," : "", name);
		}
	}
	return names;
}

