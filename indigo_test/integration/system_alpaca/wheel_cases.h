	SA_CHECK(!sa_defined(sa_device, WHEEL_SLOT_PROPERTY_NAME) && !sa_defined(sa_device, WHEEL_SLOT_NAME_PROPERTY_NAME) && !sa_defined(sa_device, WHEEL_SLOT_OFFSET_PROPERTY_NAME));
