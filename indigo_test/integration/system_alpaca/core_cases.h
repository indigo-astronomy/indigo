	SA_CHECK(SA_WAIT(sa_request_count(0, "GET", "/api/v1/focuser/0/devicestate") >= 3, SA_TIMEOUT));
	SA_CHECK(sa_request_count(0, "GET", "/api/v1/focuser/0/connected") == 1);
