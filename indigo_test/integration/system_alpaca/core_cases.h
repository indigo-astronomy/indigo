static void core_transaction_id_policy(void) {
	static const char *second[] = { "--uid-prefix", "a1baca02", "--device", "focuser", NULL };
	char address[64];
	SA_CHECK(sa_simulator_start(0, core_focuser, true) && sa_simulator_start(1, second, false));
	SA_CHECK(sa_write_config(false, sa_targets(), NULL) && sa_driver_start() && sa_discover());
	SA_CHECK(sa_attach("Focuser Simulator"));
	// an answer with the ClientTransactionID of another request is refused, and a right answer in between starts the count again
	for (int round = 0; round < 2; round++) {
		SA_CHECK(sa_fault(0, NULL, "/api/v1/focuser/0/*", "wrong-transaction-id", "Count=2"));
		for (int i = 0; i < 2; i++) {
			unsigned revision = sa_revision(sa_device, CONNECTION_PROPERTY_NAME);
			SA_CHECK(sa_request_connection(sa_device, true) && SA_WAIT(sa_state_after(sa_device, CONNECTION_PROPERTY_NAME, INDIGO_ALERT_STATE, revision) && core_alerted(sa_device), SA_TIMEOUT));
		}
		SA_CHECK(sa_message_seen("does not match"));
		SA_CHECK(sa_connect(sa_device) && sa_disconnect(sa_device));
	}
	// a server that keeps answering with wrong values does not implement the echo: the third wrong answer in a row is accepted
	// and from then on the server is used without the check
	SA_CHECK(sa_fault(0, NULL, "/api/v1/focuser/0/*", "wrong-transaction-id", "Count=-1"));
	for (int i = 0; i < 2; i++) {
		unsigned revision = sa_revision(sa_device, CONNECTION_PROPERTY_NAME);
		SA_CHECK(sa_request_connection(sa_device, true) && SA_WAIT(sa_state_after(sa_device, CONNECTION_PROPERTY_NAME, INDIGO_ALERT_STATE, revision) && core_alerted(sa_device), SA_TIMEOUT));
	}
	SA_CHECK(sa_connect(sa_device));
	int requests = sa_request_count(0, "GET", "/api/v1/focuser/0/devicestate");
	SA_CHECK(SA_WAIT(sa_request_count(0, "GET", "/api/v1/focuser/0/devicestate") >= requests + 3, SA_TIMEOUT) && sa_is_connected(sa_device));
	SA_CHECK(sa_disconnect(sa_device));
	// a server that never echoed a right value is usable from its first cycle: the request is repeated until it is accepted
	SA_CHECK(sa_fault(1, NULL, "*", "wrong-transaction-id", "Count=-1"));
	snprintf(address, sizeof(address), "127.0.0.1:%d", sa_simulators[1].http_port);
	SA_CHECK(sa_set_text("X_ALPACA_SERVERS", "ADD", address) == INDIGO_OK_STATE);
	SA_CHECK(SA_WAIT(!strncmp(sa_server_status(1), "ONLINE:", 7), SA_TIMEOUT) && sa_item_count(SA_BRIDGE, "X_ALPACA_DEVICES") == 2);
	SA_CHECK(sa_request_count(1, "GET", "/management/apiversions") == 3 && sa_request_count(1, "GET", "/management/v1/configureddevices") == 1);
cleanup:
	sa_end();
}

static void core_request_record(void) {
	static const char *arguments[] = { "--device", "focuser", "--device", "rotator:interface=legacy", NULL };
	char focuser[INDIGO_NAME_SIZE];
	char host[64];
	long client_id = 0;
	long last_transaction_id = 0;
	int count = 0;
	int puts = 0;
	SA_CHECK(sa_begin(arguments));
	SA_CHECK(sa_attach("Focuser Simulator") && sa_connect(sa_device));
	snprintf(focuser, sizeof(focuser), "%s", sa_device);
	SA_CHECK(SA_WAIT(sa_request_count(0, "GET", "/api/v1/focuser/0/devicestate") >= 2, SA_TIMEOUT));
	SA_CHECK(sa_disconnect(focuser));
	SA_CHECK(sa_attach("Rotator Simulator") && sa_connect(sa_device));
	SA_CHECK(SA_WAIT(sa_request_count(0, "GET", "/api/v1/rotator/0/connected") >= 3, SA_TIMEOUT));
	SA_CHECK(sa_disconnect(sa_device) && sa_discover());
	snprintf(host, sizeof(host), "127.0.0.1:%d", sa_simulators[0].http_port);
	// every request the driver sent, in the order the server received them
	const char *line = sa_requests(0, NULL, "*");
	SA_CHECK(line != NULL);
	while (*line) {
		char method[8];
		char path[256];
		char parameters[SA_TEXT_SIZE];
		snprintf(method, sizeof(method), "%s", sa_field(line, "Method"));
		snprintf(path, sizeof(path), "%s", sa_field(line, "Path"));
		bool put = !strcmp(method, "PUT");
		// GET parameters travel in the query, PUT parameters in a form body
		snprintf(parameters, sizeof(parameters), "%s", sa_field(line, put ? "Body" : "Query"));
		SA_CHECK(*sa_field(line, put ? "Query" : "Body") == 0);
		SA_CHECK(!strcmp(sa_field(line, "ContentType"), put ? "application/x-www-form-urlencoded" : ""));
		SA_CHECK(!strcmp(sa_field(line, "UserAgent"), "indigo_system_alpaca") && !strcmp(sa_field(line, "Host"), host));
		for (const char *c = path; *c; c++) {
			SA_CHECK(*c < 'A' || *c > 'Z');
		}
		// ClientID is the same in every request to a server, ClientTransactionID grows from request to request; both with their exact casing
		long id = atol(sa_field(parameters, "ClientID"));
		long transaction_id = atol(sa_field(parameters, "ClientTransactionID"));
		SA_CHECK(id >= 1 && id <= 65535 && (client_id == 0 || id == client_id));
		SA_CHECK(transaction_id > last_transaction_id);
		SA_CHECK(count > 0 || transaction_id == 1);
		client_id = id;
		last_transaction_id = transaction_id;
		// the parameters of a method come first, written as the specification writes them
		if (put && !strcmp(path, "/api/v1/rotator/0/connected")) {
			SA_CHECK(!strncmp(parameters, "Connected=True&ClientID=", 24) || !strncmp(parameters, "Connected=False&ClientID=", 25));
		} else {
			SA_CHECK(!strncmp(parameters, "ClientID=", 9));
		}
		SA_CHECK(strstr(parameters, "&ClientTransactionID=") != NULL && !strcmp(sa_field(line, "Status"), "200") && *sa_field(line, "Fault") == 0);
		puts += put;
		count++;
		line += strcspn(line, "\n");
		line += *line == '\n';
	}
	// connect and disconnect of the focuser, Connected=True and Connected=False of the rotator, and nothing else was written
	SA_CHECK(puts == 4 && count > 15);
	SA_CHECK(sa_request_count(0, "PUT", "/api/v1/focuser/0/connect") == 1 && sa_request_count(0, "PUT", "/api/v1/focuser/0/disconnect") == 1 && sa_request_count(0, "PUT", "/api/v1/rotator/0/connected") == 2);
cleanup:
	sa_end();
}

