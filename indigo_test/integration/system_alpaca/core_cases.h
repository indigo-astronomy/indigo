static bool core_valid_utf8(const char *text) {
	const unsigned char *c = (const unsigned char *)text;
	while (*c) {
		int length = *c < 0x80 ? 1 : (*c & 0xE0) == 0xC0 ? 2 : (*c & 0xF0) == 0xE0 ? 3 : (*c & 0xF8) == 0xF0 ? 4 : 0;
		if (length == 0) {
			return false;
		}
		for (int i = 1; i < length; i++) {
			if ((c[i] & 0xC0) != 0x80) {
				return false;
			}
		}
		c += length;
	}
	return true;
}

