// D17: devices of the same name get a running number, " #2", " #3"..., in the order of their UniqueIDs among the devices of that name
// the servers list, whatever the order of the servers, of the listing or of attaching. So the names (and the configuration files of the
// proxies) are the same after a restart and in every later cycle, and a device switched off and on again gets its own name back.
// A proxy keeps its name while it is attached: when a device that comes first in the order appears while the others are attached, it
// takes the next free number, and the order is restored at the next start.
static void core_proxy_names_numbered(void) {
	static const char *first[] = { "--device", "focuser:number=0,name=Focuser,uid=c0ffee00-0003-4000-8000-000000000000", "--device", "focuser:number=1,name=Focuser,uid=c0ffee00-0001-4000-8000-000000000000", NULL };
	static const char *second[] = { "--uid-prefix", "a1baca02", "--device", "focuser:number=0,name=Alpaca Focuser,uid=c0ffee00-0004-4000-8000-000000000000", "--device", "focuser:number=1,name=Focuser,uid=c0ffee00-0002-4000-8000-000000000000", NULL };
	static const char *keys[] = { "c0ffee00-0001-4000-8000-000000000000", "c0ffee00-0002-4000-8000-000000000000", "c0ffee00-0003-4000-8000-000000000000", "c0ffee00-0004-4000-8000-000000000000" };
	static const char *names[] = { "ALPACA Focuser", "ALPACA Focuser #2", "ALPACA Focuser #3", "ALPACA Focuser #4" };
	sa_switch_off_devices = false;
	SA_CHECK(sa_simulator_start(0, first, true) && sa_simulator_start(1, second, true));
	SA_CHECK(sa_write_config(false, sa_targets(), NULL));
	for (int round = 0; round < 2; round++) {
		SA_CHECK(sa_driver_start() && sa_discover() && sa_discover());
		SA_CHECK(sa_status_count("ATTACHED") == 4 && sa_device_count("ALPACA ") == 4);
		for (int i = 0; i < 4; i++) {
			if (strcmp(sa_proxy_name(keys[i]), names[i])) {
				fprintf(stderr, "    round %d: %s is '%s' instead of '%s'\n", round, keys[i], sa_proxy_name(keys[i]), names[i]);
				SA_CHECK(false);
			}
		}
		SA_CHECK(sa_driver_stop() == INDIGO_OK);
	}
	SA_CHECK(sa_driver_start() && sa_discover());
	// switched off and on again, a device gets its own name back, the others keep theirs
	SA_CHECK(sa_select(keys[0], false) && SA_WAIT(!sa_device_defined(names[0]), SA_TIMEOUT));
	SA_CHECK(sa_discover() && !strcmp(sa_proxy_name(keys[1]), names[1]) && sa_device_count("ALPACA ") == 3);
	SA_CHECK(sa_select(keys[0], true) && SA_WAIT(sa_device_status_is(keys[0], "ATTACHED"), SA_TIMEOUT) && !strcmp(sa_proxy_name(keys[0]), names[0]));
	// the first device is gone at the next start: the others move up
	SA_CHECK(sa_put(0, "/simulator/v1/devices/remove", "Type=Focuser&Number=1"));
	SA_CHECK(sa_driver_stop() == INDIGO_OK && sa_driver_start() && sa_discover());
	SA_CHECK(!strcmp(sa_proxy_name(keys[1]), "ALPACA Focuser") && !strcmp(sa_proxy_name(keys[2]), "ALPACA Focuser #2") && !strcmp(sa_proxy_name(keys[3]), "ALPACA Focuser #3"));
	// it comes back while the others are attached: they keep their names, it takes the first number that is free
	SA_CHECK(sa_put(0, "/simulator/v1/devices", "Type=Focuser&Number=1&Name=Focuser&UniqueID=c0ffee00-0001-4000-8000-000000000000"));
	SA_CHECK(sa_discover() && sa_status_count("ATTACHED") == 4 && !strcmp(sa_proxy_name(keys[0]), "ALPACA Focuser #4") && !strcmp(sa_proxy_name(keys[1]), "ALPACA Focuser"));
	// and the next start restores the order
	SA_CHECK(sa_driver_stop() == INDIGO_OK && sa_driver_start() && sa_discover());
	for (int i = 0; i < 4; i++) {
		SA_CHECK(!strcmp(sa_proxy_name(keys[i]), names[i]));
	}
	SA_CHECK(sa_connect(names[3]) && sa_request_count(1, "PUT", "/api/v1/focuser/0/connect") == 1 && sa_disconnect(names[3]));
cleanup:
	sa_end();
}

