static void core_failed_attach(void) {
	char key[INDIGO_NAME_SIZE];
	// the cycle the driver runs by itself at INIT may come after the first one asked for (core_discovery_repeated_without_duplicates); since
	// every cycle tries the attach of a device that is on, a second cycle lets it pass before the attempts are counted
	SA_CHECK(sa_begin(core_focuser) && sa_discover());
	snprintf(key, sizeof(key), "%s", sa_device_key("Focuser Simulator"));
	// the device is listed, but it does not answer: no proxy device is attached and nothing is left behind
	SA_CHECK(sa_fault(0, "GET", "/api/v1/focuser/0/interfaceversion", "http-status", "Value=500&Count=2"));
	SA_CHECK(sa_select(key, true));
	if (!SA_WAIT(sa_device_status_is(key, "FAILED"), SA_TIMEOUT)) {
		fprintf(stderr, "    '%s' is %s, %d interfaceversion request(s)\n", key, sa_device_status(key), sa_request_count(0, "GET", "/api/v1/focuser/0/interfaceversion"));
		SA_CHECK(false);
	}
	SA_CHECK(strstr(sa_device_status(key), "the device does not answer") != NULL && strstr(sa_device_status(key), "HTTP 500") != NULL);
	SA_CHECK(sa_device_count(NULL) == 1 && sa_switch(SA_BRIDGE, "X_ALPACA_DEVICES", key));
	// the attach is tried again in every cycle
	SA_CHECK(sa_discover());
	SA_CHECK(sa_device_status_is(key, "FAILED") && sa_device_count(NULL) == 1);
	SA_CHECK(sa_discover());
	SA_CHECK(sa_device_status_is(key, "ATTACHED") && sa_device_count(NULL) == 2);
	SA_CHECK(sa_request_count(0, "GET", "/api/v1/focuser/0/interfaceversion") == 3);
	snprintf(sa_device, sizeof(sa_device), "%s", sa_proxy_name(key));
	SA_CHECK(sa_connect(sa_device) && sa_disconnect(sa_device));
	// a connection that is reset once is retried by the transport layer, so the attach succeeds
	SA_CHECK(sa_select(key, false) && SA_WAIT(sa_device_status_is(key, "AVAILABLE"), SA_TIMEOUT));
	SA_CHECK(sa_fault(0, "GET", "/api/v1/focuser/0/interfaceversion", "reset", NULL));
	SA_CHECK(sa_select(key, true) && SA_WAIT(sa_device_status_is(key, "ATTACHED"), SA_TIMEOUT));
	SA_CHECK(sa_request_count(0, "GET", "/api/v1/focuser/0/interfaceversion") == 6);
cleanup:
	sa_end();
}

static void core_capacity(void) {
	static const char *arguments[] = { "--no-devices", NULL };
	static char keys[40][INDIGO_NAME_SIZE];
	const char *items[40];
	bool values[40];
	char form[128];
	int failed = -1;
	int attached = -1;
	SA_CHECK(sa_simulator_start(0, arguments, true));
	for (int i = 0; i < 33; i++) {
		snprintf(form, sizeof(form), "Type=Focuser&Number=%d&Name=F%d", i, i);
		SA_CHECK(sa_put(0, "/simulator/v1/devices", form));
	}
	SA_CHECK(sa_write_config(false, sa_targets(), NULL) && sa_driver_start() && sa_discover());
	SA_CHECK(sa_item_count(SA_BRIDGE, "X_ALPACA_DEVICES") == 33);
	for (int i = 0; i < 33; i++) {
		snprintf(keys[i], INDIGO_NAME_SIZE, "%s", sa_item_name(SA_BRIDGE, "X_ALPACA_DEVICES", i));
		items[i] = keys[i];
		values[i] = true;
	}
	// 33 devices are switched on (the harness had switched them off), the driver has room for 32 proxy devices
	SA_CHECK(indigo_change_switch_property(&sa_client, SA_BRIDGE, "X_ALPACA_DEVICES", 33, items, values) == INDIGO_OK);
	SA_CHECK(SA_WAIT(sa_status_count("ATTACHED") == 32 && sa_status_count("FAILED") == 1, 3 * SA_TIMEOUT));
	SA_CHECK(sa_device_count("ALPACA ") == 32);
	for (int i = 0; i < 33; i++) {
		if (sa_device_status_is(keys[i], "FAILED")) {
			failed = i;
		} else if (attached < 0) {
			attached = i;
		}
	}
	SA_CHECK(failed >= 0 && attached >= 0 && strstr(sa_device_status(keys[failed]), "the limit of 32 proxy devices is reached") != NULL);
	SA_CHECK(sa_request_count(0, "GET", "/api/*/interfaceversion") == 32);
	// the device without a proxy stays on and gets its proxy as soon as there is room
	SA_CHECK(sa_discover() && sa_status_count("ATTACHED") == 32 && sa_status_count("FAILED") == 1);
	SA_CHECK(sa_select(keys[attached], false) && SA_WAIT(sa_device_status_is(keys[attached], "AVAILABLE"), SA_TIMEOUT));
	SA_CHECK(sa_discover());
	SA_CHECK(sa_status_count("ATTACHED") == 32 && sa_status_count("FAILED") == 0 && sa_device_status_is(keys[failed], "ATTACHED"));
	SA_CHECK(sa_device_count("ALPACA ") == 32);
	// every proxy device is a working device
	snprintf(sa_device, sizeof(sa_device), "%s", sa_proxy_name(keys[failed]));
	SA_CHECK(sa_connect(sa_device) && sa_disconnect(sa_device));
cleanup:
	sa_end();
}

