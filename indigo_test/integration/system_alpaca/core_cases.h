static void core_discovery_several_servers(void) {
	static const char *first[] = { "--uid-prefix", "a1baca01", "--device", "focuser", NULL };
	static const char *second[] = { "--uid-prefix", "a1baca02", "--device", "focuser", "--device", "rotator", NULL };
	char names[3][INDIGO_NAME_SIZE] = { { 0 } };
	SA_CHECK(sa_simulator_start(0, first, true) && sa_simulator_start(1, second, true));
	SA_CHECK(sa_write_config(false, sa_targets(), NULL) && sa_driver_start() && sa_discover());
	SA_CHECK(sa_item_count(SA_BRIDGE, "X_ALPACA_SERVER_STATUS") == 2);
	SA_CHECK(!strncmp(sa_server_status(0), "ONLINE:", 7) && strstr(sa_server_status(0), "1 device(s)") != NULL);
	SA_CHECK(!strncmp(sa_server_status(1), "ONLINE:", 7) && strstr(sa_server_status(1), "2 device(s)") != NULL);
	SA_CHECK(sa_item_count(SA_BRIDGE, "X_ALPACA_DEVICES") == 3);
	// both servers have the same name and a focuser of the same name: the proxy devices still get different names
	for (int i = 0; i < 3; i++) {
		const char *key = sa_item_name(SA_BRIDGE, "X_ALPACA_DEVICES", i);
		SA_CHECK(sa_select(key, true));
		SA_CHECK(SA_WAIT(sa_device_status_is(sa_item_name(SA_BRIDGE, "X_ALPACA_DEVICES", i), "ATTACHED"), SA_TIMEOUT));
		snprintf(names[i], INDIGO_NAME_SIZE, "%s", sa_proxy_name(sa_item_name(SA_BRIDGE, "X_ALPACA_DEVICES", i)));
		SA_CHECK(SA_WAIT(sa_defined(names[i], CONNECTION_PROPERTY_NAME), SA_TIMEOUT));
	}
	SA_CHECK(!strncmp(names[0], "Focuser Simulator @ " SA_SERVER_NAME " #", strlen("Focuser Simulator @ " SA_SERVER_NAME " #")));
	SA_CHECK(!strncmp(names[1], "Focuser Simulator @ " SA_SERVER_NAME " #", strlen("Focuser Simulator @ " SA_SERVER_NAME " #")));
	SA_CHECK(strcmp(names[0], names[1]) != 0);
	SA_CHECK(!strcmp(names[2], "Rotator Simulator @ " SA_SERVER_NAME));
	SA_CHECK(sa_device_count(NULL) == 4);
	// the names come from the identity of the devices, not from the order in which they are attached
	for (int i = 0; i < 2; i++) {
		SA_CHECK(sa_select(sa_item_name(SA_BRIDGE, "X_ALPACA_DEVICES", i), false));
		SA_CHECK(SA_WAIT(!sa_device_defined(names[i]), SA_TIMEOUT));
	}
	for (int i = 1; i >= 0; i--) {
		SA_CHECK(sa_select(sa_item_name(SA_BRIDGE, "X_ALPACA_DEVICES", i), true));
		SA_CHECK(SA_WAIT(sa_device_status_is(sa_item_name(SA_BRIDGE, "X_ALPACA_DEVICES", i), "ATTACHED"), SA_TIMEOUT));
		SA_CHECK(!strcmp(names[i], sa_proxy_name(sa_item_name(SA_BRIDGE, "X_ALPACA_DEVICES", i))));
		SA_CHECK(SA_WAIT(sa_defined(names[i], CONNECTION_PROPERTY_NAME), SA_TIMEOUT));
	}
	// every proxy talks to its own server
	SA_CHECK(sa_connect(names[0]) && sa_connect(names[1]) && sa_connect(names[2]));
	SA_CHECK(sa_request_count(0, "PUT", "/api/v1/focuser/0/connect") == 1 && sa_request_count(0, "PUT", "/api/v1/rotator/*") == 0);
	SA_CHECK(sa_request_count(1, "PUT", "/api/v1/focuser/0/connect") == 1 && sa_request_count(1, "PUT", "/api/v1/rotator/0/connect") == 1);
	SA_CHECK(sa_disconnect(names[0]) && sa_disconnect(names[1]) && sa_disconnect(names[2]));
cleanup:
	sa_end();
}

