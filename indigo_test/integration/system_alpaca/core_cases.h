// D16: without discovery targets the request is broadcast, and with the loopback network included the driver also sends it to
// 127.0.0.1, because macOS has no broadcast on lo0. A server of this machine that listens on 127.0.0.1 only (OmniSim started with
// --urls=http://127.0.0.1:<port>) is found that way. The discovery responder of the simulator listens on 127.0.0.1 only and on a port
// of its own, to which the driver is set, so no other responder of this machine or of the network can answer. Where a request to
// 127.255.255.255 reaches the responder as well (Linux), it answers twice: that is still one server.
static void core_broadcast_discovery_on_loopback(void) {
	static const char *arguments[] = { "--discovery-bind", "127.0.0.1", "--device", "focuser", NULL };
	char extra[512];
	SA_CHECK(sa_simulator_start(0, arguments, true));
	snprintf(extra, sizeof(extra), "<newNumberVector device='" SA_BRIDGE "' name='X_ALPACA_DISCOVERY_SETTINGS'>\n<oneNumber name='PORT'>%d</oneNumber>\n<oneNumber name='POLLS'>2</oneNumber>\n</newNumberVector>\n", sa_simulators[0].udp_port);
	SA_CHECK(sa_write_config(false, "", extra) && sa_driver_start());
	SA_CHECK(!strcmp(sa_text(SA_BRIDGE, "X_ALPACA_DISCOVERY_TARGETS", "TARGETS"), "") && sa_number(SA_BRIDGE, "X_ALPACA_DISCOVERY_SETTINGS", "PORT") == sa_simulators[0].udp_port);
	SA_CHECK(sa_discover());
	int requests = atoi(sa_status(0, "/simulator/v1/discovery", "Requests"));
	printf("    the responder on 127.0.0.1:%d got %d discovery request(s) in 2 polls\n", sa_simulators[0].udp_port, requests);
	SA_CHECK(requests >= 2);
	SA_CHECK(sa_item_count(SA_BRIDGE, "X_ALPACA_SERVER_STATUS") == 1 && !strncmp(sa_server_status(0), "ONLINE:", 7) && strstr(sa_server_status(0), "(discovered)") != NULL);
	SA_CHECK(sa_attach("Focuser Simulator") && sa_connect(sa_device) && sa_disconnect(sa_device));
	// the next cycle finds the same server again
	SA_CHECK(sa_discover() && atoi(sa_status(0, "/simulator/v1/discovery", "Requests")) >= 2 * requests && sa_item_count(SA_BRIDGE, "X_ALPACA_SERVER_STATUS") == 1 && sa_device_count(NULL) == 2);
cleanup:
	sa_end();
}

