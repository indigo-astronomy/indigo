static void core_connect_timeout(void) {
	static const char *arguments[] = { "--device", "focuser:ConnectDelay=100", NULL };
	SA_CHECK(sa_begin(arguments));
	SA_CHECK(sa_set_number("X_ALPACA_TIMEOUTS", "ESTABLISH", 1) == INDIGO_OK_STATE);
	SA_CHECK(sa_attach("Focuser Simulator"));
	// the device never finishes connecting: the establish timeout (1 s) bounds the wait, then the device is told to disconnect
	double started = indigo_monotonic_time();
	SA_CHECK(sa_request_connection(sa_device, true) && SA_WAIT(core_alerted(sa_device), SA_TIMEOUT));
	double elapsed = indigo_monotonic_time() - started;
	SA_CHECK(elapsed > 0.9 && elapsed < 5);
	SA_CHECK(sa_message_seen("the device did not finish connecting in time"));
	SA_CHECK(sa_request_count(0, "PUT", "/api/v1/focuser/0/connect") == 1 && sa_request_count(0, "PUT", "/api/v1/focuser/0/disconnect") == 1);
	SA_CHECK(sa_request_count(0, "GET", "/api/v1/focuser/0/connecting") >= 3);
	// the server accepts the request and does not answer: the request itself is bounded by the same timeout
	SA_CHECK(sa_put(0, "/simulator/v1/focuser/0/reset", NULL) && sa_device_state(0, "focuser", 0, "ConnectDelay=100"));
	SA_CHECK(sa_fault(0, "PUT", "/api/v1/focuser/0/connect", "stall-before", "Delay=3000"));
	started = indigo_monotonic_time();
	SA_CHECK(sa_request_connection(sa_device, true) && SA_WAIT(core_alerted(sa_device), SA_TIMEOUT));
	elapsed = indigo_monotonic_time() - started;
	SA_CHECK(elapsed > 0.9 && elapsed < 2.9);
	// no hang is left behind: the device connects as soon as it is able to
	SA_CHECK(sa_clear_faults(0));
	SA_CHECK(sa_request_connection(sa_device, true) && SA_WAIT(sa_request_count(0, "GET", "/api/v1/focuser/0/connecting") >= 5, SA_TIMEOUT));
	SA_CHECK(sa_advance(0, 100) && SA_WAIT(sa_is_connected(sa_device), SA_TIMEOUT));
	SA_CHECK(sa_disconnect_after(sa_device, "/simulator/v1/focuser/0/state", 100));
cleanup:
	sa_end();
}

