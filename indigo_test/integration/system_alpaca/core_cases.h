// The bus is used from the test thread while the driver queue rebuilds the lists of the bridge. Bus callbacks run with the bus
// locked, the driver queue publishes on the bus: if the two ever waited for each other, this case would hang and be killed.
static void core_bus_requests_during_list_changes(void) {
	static const char *arguments[] = { "--device", "focuser", NULL };
	char form[96];
	SA_CHECK(sa_begin(arguments));
	for (int round = 0; round < 30; round++) {
		// every cycle finds another list of devices, so every cycle deletes and defines the lists again
		snprintf(form, sizeof(form), "Type=Rotator&Number=%d", round / 2);
		SA_CHECK(sa_put(0, round % 2 == 0 ? "/simulator/v1/devices" : "/simulator/v1/devices/remove", form));
		unsigned revision = sa_revision(SA_BRIDGE, "X_ALPACA_DISCOVER");
		SA_CHECK(indigo_change_switch_property_1(&sa_client, SA_BRIDGE, "X_ALPACA_DISCOVER", "DISCOVER", true) == INDIGO_OK);
		while (!sa_state_after(SA_BRIDGE, "X_ALPACA_DISCOVER", INDIGO_OK_STATE, revision)) {
			indigo_property all = { 0 };
			strcpy(all.device, SA_BRIDGE);
			SA_CHECK(indigo_change_number_property_1(&sa_client, SA_BRIDGE, "X_ALPACA_POLLING", "IDLE", 0.1 + (round % 5) * 0.05) == INDIGO_OK);
			SA_CHECK(indigo_change_switch_property_1(&sa_client, SA_BRIDGE, "X_ALPACA_DEVICES", "c0ffee00-9999-4000-8000-000000000000", false) == INDIGO_OK);
			SA_CHECK(indigo_enumerate_properties(&sa_client, &all) == INDIGO_OK);
		}
		SA_CHECK(sa_item_count(SA_BRIDGE, "X_ALPACA_DEVICES") == (round % 2 == 0 ? 2 : 1));
	}
	SA_CHECK(sa_stray_updates() == 0);
cleanup:
	sa_end();
}

static indigo_result core_unloader_result = INDIGO_OK;

// What indigo_server does when a client unloads a driver: the shutdown is called from a change_property callback, with the bus locked.
static indigo_result core_unloader_change_property(indigo_device *device, indigo_client *client, indigo_property *property) {
	(void)device;
	(void)client;
	if (!strcmp(property->name, "UNLOAD")) {
		core_unloader_result = indigo_system_alpaca(INDIGO_DRIVER_SHUTDOWN, NULL);
	}
	return INDIGO_OK;
}

static void core_shutdown_from_bus_callback(void) {
	static indigo_device unloader = INDIGO_DEVICE_INITIALIZER("Unloader", NULL, NULL, core_unloader_change_property, NULL, NULL);
	indigo_driver_info info = { 0 };
	bool attached = false;
	SA_CHECK(sa_begin(core_focuser));
	SA_CHECK(indigo_attach_device(&unloader) == INDIGO_OK);
	attached = true;
	// a cycle is running (the server takes its time to answer) and will have to publish the lists, for which it needs the bus;
	// the shutdown arrives with the bus locked: it gives up after a bounded wait instead of hanging the bus for ever
	SA_CHECK(sa_put(0, "/simulator/v1/devices", "Type=Rotator&Number=0"));
	SA_CHECK(sa_fault(0, "GET", "/management/v1/configureddevices", "stall-before", "Delay=1000"));
	int requests = sa_request_count(0, "GET", "/management/v1/configureddevices");
	SA_CHECK(indigo_change_switch_property_1(&sa_client, SA_BRIDGE, "X_ALPACA_DISCOVER", "DISCOVER", true) == INDIGO_OK);
	SA_CHECK(SA_WAIT(sa_request_count(0, "GET", "/management/v1/configureddevices") > requests, SA_TIMEOUT));
	double started = indigo_monotonic_time();
	SA_CHECK(indigo_change_switch_property_1(&sa_client, "Unloader", "UNLOAD", "UNLOAD", true) == INDIGO_OK);
	double elapsed = indigo_monotonic_time() - started;
	SA_CHECK(core_unloader_result == INDIGO_BUSY && elapsed > 4 && elapsed < 8);
	// the driver is still loaded and the interrupted cycle finishes
	SA_CHECK(indigo_system_alpaca(INDIGO_DRIVER_INFO, &info) == INDIGO_OK && info.status == INDIGO_DRIVER_INIT);
	SA_CHECK(SA_WAIT(sa_item_count(SA_BRIDGE, "X_ALPACA_DEVICES") == 2 && sa_state(SA_BRIDGE, "X_ALPACA_DISCOVER") == INDIGO_OK_STATE, SA_TIMEOUT));
	// with the driver queue idle the same request unloads the driver
	SA_CHECK(indigo_change_switch_property_1(&sa_client, "Unloader", "UNLOAD", "UNLOAD", true) == INDIGO_OK);
	SA_CHECK(core_unloader_result == INDIGO_OK && indigo_system_alpaca(INDIGO_DRIVER_INFO, &info) == INDIGO_OK && info.status == INDIGO_DRIVER_SHUTDOWN);
	SA_CHECK(!sa_device_defined(SA_BRIDGE));
	indigo_detach_device(&unloader);
	attached = false;
	indigo_detach_client(&sa_client);
	indigo_stop();
	sa_cache_clear();
	sa_driver_running = false;
cleanup:
	if (attached) {
		indigo_detach_device(&unloader);
	}
	sa_end();
}

static void core_devices_do_not_block_each_other(void) {
	static const char *arguments[] = { "--device", "focuser", "--device", "rotator", NULL };
	char focuser[INDIGO_NAME_SIZE];
	SA_CHECK(sa_begin(arguments));
	SA_CHECK(sa_attach("Focuser Simulator") && sa_connect(sa_device));
	snprintf(focuser, sizeof(focuser), "%s", sa_device);
	SA_CHECK(sa_attach("Rotator Simulator") && sa_connect(sa_device));
	// a request to one device of a server takes long (a blocking method, an image download): the other device of the same server is
	// polled all the while, because every proxy device has its own connection and its own handler queue
	int requests = sa_request_count(0, "GET", "/api/v1/focuser/0/devicestate");
	SA_CHECK(sa_fault(0, "GET", "/api/v1/focuser/0/devicestate", "stall-before", "Delay=1200"));
	SA_CHECK(SA_WAIT(sa_request_count(0, "GET", "/api/v1/focuser/0/devicestate") > requests, SA_TIMEOUT));
	requests = sa_request_count(0, "GET", "/api/v1/focuser/0/devicestate");
	int others = sa_request_count(0, "GET", "/api/v1/rotator/0/devicestate");
	SA_CHECK(SA_WAIT(sa_request_count(0, "GET", "/api/v1/rotator/0/devicestate") >= others + 5, 1.0));
	SA_CHECK(sa_request_count(0, "GET", "/api/v1/focuser/0/devicestate") == requests);
	// neither does it keep the driver from discovering, nor the other device from disconnecting
	SA_CHECK(sa_discover() && sa_disconnect(sa_device));
	SA_CHECK(sa_request_count(0, "GET", "/api/v1/focuser/0/devicestate") == requests);
	SA_CHECK(SA_WAIT(sa_request_count(0, "GET", "/api/v1/focuser/0/devicestate") > requests, SA_TIMEOUT) && sa_is_connected(focuser));
	SA_CHECK(sa_disconnect(focuser));
cleanup:
	sa_end();
}

