// D15: a device the user switches off loses its proxy at once and stays off: the switch is saved with the configuration by UniqueID,
// is known after a restart before anything is discovered and holds through every later cycle; switched on again, the device is back.
static void core_switch_off_persists_across_restart(void) {
	static const char *arguments[] = { "--device", "focuser", "--device", "rotator", NULL };
	char focuser[INDIGO_NAME_SIZE];
	char rotator[INDIGO_NAME_SIZE];
	char path[PATH_MAX];
	char line[1024];
	bool saved_off = false, saved_on = false;
	sa_switch_off_devices = false;
	SA_CHECK(sa_begin(arguments));
	snprintf(focuser, sizeof(focuser), "%s", sa_device_key("Focuser Simulator"));
	snprintf(rotator, sizeof(rotator), "%s", sa_device_key("Rotator Simulator"));
	SA_CHECK(sa_wait_attached("Focuser Simulator") && sa_wait_attached("Rotator Simulator"));
	// switched off, the proxy goes away at once, without a cycle
	SA_CHECK(sa_select(focuser, false) && SA_WAIT(!sa_device_defined("ALPACA Focuser Simulator") && sa_device_status_is(focuser, "AVAILABLE"), SA_TIMEOUT));
	SA_CHECK(!sa_switch(SA_BRIDGE, "X_ALPACA_DEVICES", focuser) && sa_switch(SA_BRIDGE, "X_ALPACA_DEVICES", rotator) && sa_device_status_is(rotator, "ATTACHED"));
	SA_CHECK(sa_discover() && sa_device_status_is(focuser, "AVAILABLE") && sa_device_count(NULL) == 2);
	// the switch is saved by UniqueID
	SA_CHECK(sa_set_switch(CONFIG_PROPERTY_NAME, CONFIG_SAVE_ITEM_NAME, true) == INDIGO_OK_STATE);
	snprintf(path, sizeof(path), "%s/.indigo/Alpaca.config", getenv("HOME"));
	FILE *file = fopen(path, "r");
	SA_CHECK(file != NULL);
	while (fgets(line, sizeof(line), file) != NULL) {
		saved_off = saved_off || (strstr(line, focuser) != NULL && strstr(line, ">Off<") != NULL);
		saved_on = saved_on || (strstr(line, rotator) != NULL && strstr(line, ">On<") != NULL);
	}
	fclose(file);
	SA_CHECK(saved_off && saved_on);
	int requests = sa_request_count(0, "GET", "/api/v1/focuser/0/interfaceversion");
	SA_CHECK(requests == 1);
	// after a restart the device that is off is listed before anything is discovered (periodic discovery is disabled in this test)
	SA_CHECK(sa_driver_stop() == INDIGO_OK && sa_driver_start());
	SA_CHECK(SA_WAIT(sa_item_count(SA_BRIDGE, "X_ALPACA_DEVICES") == 1, SA_TIMEOUT) && !sa_switch(SA_BRIDGE, "X_ALPACA_DEVICES", focuser) && sa_device_status_is(focuser, "OFFLINE"));
	SA_CHECK(sa_device_count(NULL) == 1);
	// rediscovery: the rotator gets its proxy by default, the focuser does not, whatever the number of cycles
	SA_CHECK(sa_discover() && sa_discover());
	SA_CHECK(sa_item_count(SA_BRIDGE, "X_ALPACA_DEVICES") == 2 && sa_device_status_is(focuser, "AVAILABLE") && sa_device_status_is(rotator, "ATTACHED") && sa_device_count(NULL) == 2);
	SA_CHECK(sa_request_count(0, "GET", "/api/v1/focuser/0/interfaceversion") == requests);
	// the same when periodic discovery runs the first cycle by itself
	SA_CHECK(sa_set_switch("X_ALPACA_DISCOVERY", "ENABLED", true) == INDIGO_OK_STATE && sa_set_switch(CONFIG_PROPERTY_NAME, CONFIG_SAVE_ITEM_NAME, true) == INDIGO_OK_STATE);
	SA_CHECK(sa_driver_stop() == INDIGO_OK && sa_driver_start());
	SA_CHECK(sa_switch(SA_BRIDGE, "X_ALPACA_DISCOVERY", "ENABLED") && SA_WAIT(sa_device_status_is(rotator, "ATTACHED"), SA_TIMEOUT));
	SA_CHECK(sa_device_status_is(focuser, "AVAILABLE") && sa_device_count(NULL) == 2 && sa_request_count(0, "GET", "/api/v1/focuser/0/interfaceversion") == requests);
	// switched on again, the device gets its proxy at once, and that is saved as well
	SA_CHECK(sa_select(focuser, true) && SA_WAIT(sa_device_status_is(focuser, "ATTACHED") && sa_device_defined("ALPACA Focuser Simulator"), SA_TIMEOUT));
	SA_CHECK(sa_set_switch("X_ALPACA_DISCOVERY", "DISABLED", true) == INDIGO_OK_STATE && sa_set_switch(CONFIG_PROPERTY_NAME, CONFIG_SAVE_ITEM_NAME, true) == INDIGO_OK_STATE);
	SA_CHECK(sa_driver_stop() == INDIGO_OK && sa_driver_start());
	SA_CHECK(sa_item_count(SA_BRIDGE, "X_ALPACA_DEVICES") == 0 && sa_discover());
	SA_CHECK(sa_status_count("ATTACHED") == 2 && sa_device_count(NULL) == 3);
cleanup:
	sa_end();
}

