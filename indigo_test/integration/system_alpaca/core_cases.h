static void core_selection_attach_detach(void) {
	char key[INDIGO_NAME_SIZE];
	SA_CHECK(sa_begin(NULL));
	snprintf(key, sizeof(key), "%s", sa_device_key("Focuser Simulator"));
	SA_CHECK(sa_attach("Focuser Simulator"));
	SA_CHECK(!strcmp(sa_device, "Focuser Simulator @ " SA_SERVER_NAME));
	SA_CHECK(sa_switch(SA_BRIDGE, "X_ALPACA_DEVICES", key) && sa_status_count("ATTACHED") == 1 && sa_status_count("AVAILABLE") == 9);
	SA_CHECK(strstr(sa_device_status(key), "Focuser #0") != NULL);
	SA_CHECK(sa_device_count(NULL) == 2);
	SA_CHECK((core_interface(sa_device) & INDIGO_INTERFACE_FOCUSER) != 0);
	SA_CHECK(sa_is_disconnected(sa_device));
	// attaching asks the device for its interface version and nothing else: it is not connected
	SA_CHECK(sa_request_count(0, NULL, "/api/*") == 1 && sa_request_count(0, "GET", "/api/v1/focuser/0/interfaceversion") == 1);
	SA_CHECK(!strcmp(sa_status(0, "/simulator/v1/focuser/0/state", "Connected"), "false"));
	// selecting it again changes nothing
	unsigned defines = sa_define_count(sa_device, INFO_PROPERTY_NAME);
	SA_CHECK(sa_select(key, true) && sa_discover());
	SA_CHECK(sa_define_count(sa_device, INFO_PROPERTY_NAME) == defines && sa_device_count(NULL) == 2);
	// deselecting a device detaches it
	SA_CHECK(sa_select(key, false));
	SA_CHECK(SA_WAIT(!sa_device_defined(sa_device) && sa_device_status_is(key, "AVAILABLE"), SA_TIMEOUT));
	SA_CHECK(sa_device_count(NULL) == 1 && !sa_switch(SA_BRIDGE, "X_ALPACA_DEVICES", key));
	SA_CHECK(sa_request_count(0, "PUT", "/api/*") == 0);
	// deselecting a connected device disconnects it first (decision D5)
	SA_CHECK(sa_attach("Focuser Simulator") && sa_connect(sa_device));
	SA_CHECK(!strcmp(sa_status(0, "/simulator/v1/focuser/0/state", "Connected"), "true"));
	SA_CHECK(sa_select(key, false));
	SA_CHECK(SA_WAIT(!sa_device_defined(sa_device), SA_TIMEOUT));
	SA_CHECK(sa_request_count(0, "PUT", "/api/v1/focuser/0/disconnect") == 1);
	SA_CHECK(!strcmp(sa_status(0, "/simulator/v1/focuser/0/state", "Connected"), "false"));
	// and no request follows the disconnect
	int requests = sa_request_count(0, NULL, "/api/*");
	indigo_usleep(300000);
	SA_CHECK(sa_request_count(0, NULL, "/api/*") == requests);
	// UniqueIDs are compared without regard to case: the same device selected by its UniqueID in upper case
	SA_CHECK(!strcmp(key, "a1baca00-0005-4000-8000-000000000000") && sa_select("A1BACA00-0005-4000-8000-000000000000", true));
	SA_CHECK(SA_WAIT(sa_device_status_is(key, "ATTACHED"), SA_TIMEOUT) && sa_item_count(SA_BRIDGE, "X_ALPACA_DEVICES") == 10);
	// a device no server lists can be selected by its UniqueID: it is remembered, shown as offline, and forgotten when it is deselected
	SA_CHECK(sa_select("c0ffee00-9999-4000-8000-000000000000", true));
	SA_CHECK(SA_WAIT(sa_item_count(SA_BRIDGE, "X_ALPACA_DEVICES") == 11 && sa_device_status_is("c0ffee00-9999-4000-8000-000000000000", "OFFLINE"), SA_TIMEOUT));
	SA_CHECK(sa_switch(SA_BRIDGE, "X_ALPACA_DEVICES", "c0ffee00-9999-4000-8000-000000000000") && sa_device_count(NULL) == 2);
	SA_CHECK(sa_discover() && sa_item_count(SA_BRIDGE, "X_ALPACA_DEVICES") == 11);
	SA_CHECK(sa_select("c0ffee00-9999-4000-8000-000000000000", false) && SA_WAIT(sa_item_count(SA_BRIDGE, "X_ALPACA_DEVICES") == 10, SA_TIMEOUT));
cleanup:
	sa_end();
}

static void core_selection_persists_across_restart(void) {
	char focuser[INDIGO_NAME_SIZE];
	char rotator[INDIGO_NAME_SIZE];
	char path[PATH_MAX];
	char line[1024];
	bool saved = false;
	SA_CHECK(sa_begin(NULL));
	snprintf(focuser, sizeof(focuser), "%s", sa_device_key("Focuser Simulator"));
	snprintf(rotator, sizeof(rotator), "%s", sa_device_key("Rotator Simulator"));
	SA_CHECK(sa_attach("Focuser Simulator") && sa_attach("Rotator Simulator"));
	SA_CHECK(sa_set_switch(CONFIG_PROPERTY_NAME, CONFIG_SAVE_ITEM_NAME, true) == INDIGO_OK_STATE);
	// the selection is saved by UniqueID, which the simulator reports in upper or lower case as it likes
	snprintf(path, sizeof(path), "%s/.indigo/Alpaca.config", getenv("HOME"));
	FILE *file = fopen(path, "r");
	SA_CHECK(file != NULL);
	while (fgets(line, sizeof(line), file) != NULL) {
		saved = saved || (strstr(line, focuser) != NULL && strstr(line, ">On<") != NULL);
	}
	fclose(file);
	SA_CHECK(saved);
	SA_CHECK(sa_driver_stop() == INDIGO_OK);
	// after a restart the selection is known before anything is discovered (periodic discovery is disabled in this test)
	SA_CHECK(sa_driver_start());
	SA_CHECK(SA_WAIT(sa_item_count(SA_BRIDGE, "X_ALPACA_DEVICES") == 2, SA_TIMEOUT));
	SA_CHECK(sa_switch(SA_BRIDGE, "X_ALPACA_DEVICES", focuser) && sa_switch(SA_BRIDGE, "X_ALPACA_DEVICES", rotator));
	SA_CHECK(sa_device_status_is(focuser, "OFFLINE") && sa_device_status_is(rotator, "OFFLINE"));
	SA_CHECK(sa_device_count(NULL) == 1);
	// the first discovery attaches the selected devices and only them
	SA_CHECK(sa_discover());
	SA_CHECK(sa_item_count(SA_BRIDGE, "X_ALPACA_DEVICES") == 10 && sa_status_count("ATTACHED") == 2 && sa_status_count("AVAILABLE") == 8);
	SA_CHECK(sa_device_status_is(focuser, "ATTACHED") && sa_device_status_is(rotator, "ATTACHED"));
	SA_CHECK(sa_device_defined("Focuser Simulator @ " SA_SERVER_NAME) && sa_device_defined("Rotator Simulator @ " SA_SERVER_NAME) && sa_device_count(NULL) == 3);
	// with periodic discovery saved as enabled no request is needed at all
	SA_CHECK(sa_select(rotator, false) && SA_WAIT(sa_device_status_is(rotator, "AVAILABLE"), SA_TIMEOUT));
	SA_CHECK(sa_set_switch("X_ALPACA_DISCOVERY", "ENABLED", true) == INDIGO_OK_STATE);
	SA_CHECK(sa_set_switch(CONFIG_PROPERTY_NAME, CONFIG_SAVE_ITEM_NAME, true) == INDIGO_OK_STATE);
	SA_CHECK(sa_driver_stop() == INDIGO_OK);
	SA_CHECK(sa_driver_start());
	SA_CHECK(sa_switch(SA_BRIDGE, "X_ALPACA_DISCOVERY", "ENABLED"));
	SA_CHECK(SA_WAIT(sa_item_count(SA_BRIDGE, "X_ALPACA_DEVICES") == 10 && sa_status_count("ATTACHED") == 1, SA_TIMEOUT));
	SA_CHECK(sa_device_status_is(focuser, "ATTACHED") && sa_device_status_is(rotator, "AVAILABLE"));
	SA_CHECK(sa_device_defined("Focuser Simulator @ " SA_SERVER_NAME) && sa_device_count(NULL) == 2);
	SA_CHECK(sa_set_switch("X_ALPACA_DISCOVERY", "DISABLED", true) == INDIGO_OK_STATE);
cleanup:
	sa_end();
}

