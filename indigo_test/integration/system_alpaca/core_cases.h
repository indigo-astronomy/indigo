	SA_CHECK(sa_connect(camera) && SA_WAIT(sa_defined(guider, CONNECTION_PROPERTY_NAME), SA_TIMEOUT));
	SA_CHECK(sa_connect(guider));
	// detaching the connected camera with its connected guider leaves nothing behind
	SA_CHECK(sa_select(key, false) && SA_WAIT(!sa_device_defined(camera) && !sa_device_defined(guider), SA_TIMEOUT));
	SA_CHECK(sa_request_count(0, "PUT", "/api/v1/camera/0/disconnect") == 2 && sa_device_count(NULL) == 1);
