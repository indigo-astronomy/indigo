static void guider_replacement_and_axes(void) {
	static const char *single_axis[] = { "--device", "telescope:EquatorialSystem=2,Tracking=true,DualAxisPulseGuide=false", NULL };
	SA_CHECK(guider_begin(guider_telescope, false));
	double ra = mount_simulated("RightAscension"), dec = mount_simulated("Declination");
	// both axes at once: two pulses, each completed on its own. IsPulseGuiding is one flag for both, so the shorter pulse is over when its
	// duration has passed (in real time) while the longer one still runs, and completing it sends nothing that would stop the other one
	unsigned ra_revision = sa_revision(guider_device, GUIDER_GUIDE_RA_PROPERTY_NAME), dec_revision = sa_revision(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME);
	SA_CHECK(guider_start(GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME, 1500) && guider_start(GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_EAST_ITEM_NAME, 300) && guider_count("PUT", "pulseguide") == 2);
	SA_CHECK(guider_answer(GUIDER_GUIDE_RA_PROPERTY_NAME, ra_revision) == INDIGO_OK_STATE && guider_zero(GUIDER_GUIDE_RA_PROPERTY_NAME) && sa_state(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME) == INDIGO_BUSY_STATE && sa_number(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME) == 1500);
	SA_CHECK(guider_count("PUT", "pulseguide") == 2 && guider_count("GET", "ispulseguiding") == 0 && mount_simulated_is("IsPulseGuiding", "true") && !sa_state_after(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME, INDIGO_OK_STATE, dec_revision));
	// the longer one is completed by IsPulseGuiding
	SA_CHECK(guider_watched(0, 3) && sa_state(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME) == INDIGO_BUSY_STATE && sa_advance(0, 1.5) && guider_answer(GUIDER_GUIDE_DEC_PROPERTY_NAME, dec_revision) == INDIGO_OK_STATE && guider_zero(GUIDER_GUIDE_DEC_PROPERTY_NAME));
	SA_CHECK(mount_near(mount_simulated("Declination"), dec + 1.5 * GUIDER_RATE, 1e-9) && mount_near(mount_simulated("RightAscension"), ra + 0.3 * GUIDER_RATE / 15, 1e-12) && guider_count("PUT", "pulseguide") == 2 && guider_quiet());
	// a new request for an axis whose pulse runs replaces it: one more PulseGuide, the completion of the first pulse is forgotten
	dec = mount_simulated("Declination");
	dec_revision = sa_revision(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME);
	SA_CHECK(guider_start(GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME, 3000) && guider_start(GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME, 300) && guider_last("Direction=0&Duration=300&ClientID=") && guider_count("PUT", "pulseguide") == 4);
	SA_CHECK(sa_number(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME) == 300 && sa_advance(0, 0.3) && guider_answer(GUIDER_GUIDE_DEC_PROPERTY_NAME, dec_revision) == INDIGO_OK_STATE && guider_zero(GUIDER_GUIDE_DEC_PROPERTY_NAME) && mount_near(mount_simulated("Declination"), dec + 0.3 * GUIDER_RATE, 1e-9));
	// a reversal is a replacement, too; the old pulse does not complete the new one when its time comes (0.6 s after its start): the
	// queue runs its tasks in the order of their time, so once eight poll ticks of 0.1 s have run after the replacement, the finalizer of
	// the old pulse would have run as well
	dec_revision = sa_revision(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME);
	SA_CHECK(guider_start(GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME, 600) && guider_start(GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_SOUTH_ITEM_NAME, 5000) && guider_last("Direction=1&Duration=5000&ClientID=") && sa_number(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME) == 0 && sa_number(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_SOUTH_ITEM_NAME) == 5000);
	int ticks = mount_count("GET", "devicestate");
	SA_CHECK(SA_WAIT(mount_count("GET", "devicestate") >= ticks + 8, SA_TIMEOUT));
	SA_CHECK(sa_state(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME) == INDIGO_BUSY_STATE && !sa_state_after(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME, INDIGO_OK_STATE, dec_revision) && sa_number(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_SOUTH_ITEM_NAME) == 5000 && guider_count("PUT", "pulseguide") == 6);
	// a zero request ends the running pulse: PulseGuide with Duration 0 for its direction, OK at once
	int checks = guider_count("GET", "ispulseguiding");
	SA_CHECK(guider_pulse(GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_SOUTH_ITEM_NAME, 0) == INDIGO_OK_STATE && guider_last("Direction=1&Duration=0&ClientID=") && guider_zero(GUIDER_GUIDE_DEC_PROPERTY_NAME) && mount_simulated_is("IsPulseGuiding", "false") && guider_count("PUT", "pulseguide") == 7);
	SA_CHECK(guider_quiet() && guider_count("GET", "ispulseguiding") == checks && guider_pulse(GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_SOUTH_ITEM_NAME, 0) == INDIGO_OK_STATE && guider_count("PUT", "pulseguide") == 7);
	// a device that refuses to end a pulse leaves the stop in ALERT
	SA_CHECK(guider_start(GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_WEST_ITEM_NAME, 4000) && sa_fault(0, "PUT", MOUNT_API "pulseguide", "ascom-error", "Value=1025&Message=Duration%200%20is%20not%20allowed"));
	SA_CHECK(guider_pulse(GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_WEST_ITEM_NAME, 0) == INDIGO_ALERT_STATE && mount_message("Guiding stop failed: invalid value (Duration 0 is not allowed (0x401))") && guider_zero(GUIDER_GUIDE_RA_PROPERTY_NAME) && sa_advance(0, 4) && guider_quiet());
	// requests that pile up for one axis while the queue of the device is busy are coalesced: only the last one is sent
	int pulses = guider_count("PUT", "pulseguide");
	ra_revision = sa_revision(guider_device, GUIDER_GUIDE_RA_PROPERTY_NAME);
	SA_CHECK(mount_close_gate() && guider_request(GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_EAST_ITEM_NAME, 100) && guider_request(GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_WEST_ITEM_NAME, 200) && guider_request(GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_EAST_ITEM_NAME, 300));
	atomic_store(&mount_gate_open, true);
	SA_CHECK(SA_WAIT(guider_count("PUT", "pulseguide") == pulses + 1, SA_TIMEOUT) && guider_last("Direction=2&Duration=300&ClientID=") && sa_advance(0, 0.3) && guider_answer(GUIDER_GUIDE_RA_PROPERTY_NAME, ra_revision) == INDIGO_OK_STATE && guider_zero(GUIDER_GUIDE_RA_PROPERTY_NAME) && guider_count("PUT", "pulseguide") == pulses + 1);
	// the completion of a pulse and its replacement arrive in this order: the completion that finds a newer request waiting leaves the property to it,
	// so the new pulse is not reported as over by the old one
	dec_revision = sa_revision(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME);
	SA_CHECK(guider_start(GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME, 200) && mount_close_gate() && sa_advance(0, 0.2));
	indigo_usleep(400000);
	checks = guider_count("GET", "ispulseguiding");
	SA_CHECK(guider_request(GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_SOUTH_ITEM_NAME, 800));
	atomic_store(&mount_gate_open, true);
	SA_CHECK(SA_WAIT(guider_count("PUT", "pulseguide") == pulses + 3, SA_TIMEOUT) && guider_last("Direction=1&Duration=800&ClientID=") && guider_watched(checks, 3) && sa_state(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME) == INDIGO_BUSY_STATE && !sa_state_after(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME, INDIGO_OK_STATE, dec_revision));
	SA_CHECK(sa_number(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_SOUTH_ITEM_NAME) == 800 && sa_advance(0, 0.8) && guider_answer(GUIDER_GUIDE_DEC_PROPERTY_NAME, dec_revision) == INDIGO_OK_STATE && guider_zero(GUIDER_GUIDE_DEC_PROPERTY_NAME));
	SA_CHECK(sa_disconnect(sa_device));
	sa_end();
	// a telescope that guides one axis at a time refuses the second pulse; the first one is not disturbed
	SA_CHECK(guider_begin(single_axis, false));
	dec_revision = sa_revision(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME);
	SA_CHECK(guider_start(GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME, 1000) && guider_pulse(GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_EAST_ITEM_NAME, 300) == INDIGO_ALERT_STATE && mount_message("Guiding failed: invalid operation (PulseGuide in both axes at the same time is not supported (0x40B))"));
	SA_CHECK(guider_zero(GUIDER_GUIDE_RA_PROPERTY_NAME) && sa_state(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME) == INDIGO_BUSY_STATE && sa_advance(0, 1) && guider_answer(GUIDER_GUIDE_DEC_PROPERTY_NAME, dec_revision) == INDIGO_OK_STATE);
	SA_CHECK(guider_start(GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_EAST_ITEM_NAME, 300) && sa_advance(0, 0.3) && SA_WAIT(sa_state(guider_device, GUIDER_GUIDE_RA_PROPERTY_NAME) == INDIGO_OK_STATE, SA_TIMEOUT));
	SA_CHECK(sa_disconnect(sa_device));
cleanup:
	atomic_store(&mount_gate_open, true);
	sa_end();
}

