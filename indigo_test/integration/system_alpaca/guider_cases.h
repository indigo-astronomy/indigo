static void guider_properties(void) {
	static const char *no_guiding[] = { "--device", "telescope:CanPulseGuide=false", "--device", "camera:CanPulseGuide=false", NULL };
	for (int variant = 0; variant < 3; variant++) {
		bool camera = variant == 2;
		SA_CHECK(sa_begin(variant == 0 ? guider_telescope : variant == 1 ? mount_south_legacy : guider_camera) && sa_attach(camera ? "Camera Simulator" : MOUNT_LABEL));
		guider_api = camera ? "/api/v1/camera/0/" : "/api/v1/telescope/0/";
		snprintf(guider_device, sizeof(guider_device), "%s (guider)", sa_device);
		// the guider exists while its primary device is connected
		SA_CHECK(!sa_device_defined(guider_device) && sa_connect(sa_device) && SA_WAIT(sa_defined(guider_device, CONNECTION_PROPERTY_NAME), SA_TIMEOUT));
		SA_CHECK((core_interface(guider_device) & INDIGO_INTERFACE_GUIDER) == INDIGO_INTERFACE_GUIDER && sa_is_disconnected(guider_device) && guider_count("GET", "canpulseguide") == 1);
		SA_CHECK(!strcmp(sa_text(guider_device, INFO_PROPERTY_NAME, INFO_DEVICE_MODEL_ITEM_NAME), sa_text(sa_device, INFO_PROPERTY_NAME, INFO_DEVICE_MODEL_ITEM_NAME)));
		SA_CHECK(!sa_defined(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME) && !sa_defined(guider_device, GUIDER_GUIDE_RA_PROPERTY_NAME));
		// it shares the connection of the primary device: connecting it sends nothing
		int puts = sa_request_count(0, "PUT", "/api/*");
		SA_CHECK(sa_connect(guider_device) && sa_request_count(0, "PUT", "/api/*") == puts);
		SA_CHECK(sa_item_count(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME) == 2 && sa_has_item(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME) && sa_has_item(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_SOUTH_ITEM_NAME));
		SA_CHECK(sa_item_count(guider_device, GUIDER_GUIDE_RA_PROPERTY_NAME) == 2 && sa_has_item(guider_device, GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_EAST_ITEM_NAME) && sa_has_item(guider_device, GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_WEST_ITEM_NAME));
		SA_CHECK(sa_state(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME) == INDIGO_OK_STATE && sa_state(guider_device, GUIDER_GUIDE_RA_PROPERTY_NAME) == INDIGO_OK_STATE && sa_perm(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME) == INDIGO_RW_PERM && sa_perm(guider_device, GUIDER_GUIDE_RA_PROPERTY_NAME) == INDIGO_RW_PERM);
		SA_CHECK(guider_zero(GUIDER_GUIDE_DEC_PROPERTY_NAME) && guider_zero(GUIDER_GUIDE_RA_PROPERTY_NAME));
		// a camera has no guide rate and the guide rates of a telescope are MOUNT_GUIDE_RATE of the mount: no GUIDER_RATE
		SA_CHECK(!sa_defined(guider_device, GUIDER_RATE_PROPERTY_NAME) && (camera || sa_defined(sa_device, MOUNT_GUIDE_RATE_PROPERTY_NAME)));
		// nothing is asked of the device for an idle guider
		SA_CHECK(guider_quiet() && guider_count("PUT", "pulseguide") == 0 && guider_count("GET", "ispulseguiding") == 0);
		// disconnected and connected again on its own
		SA_CHECK(sa_disconnect(guider_device) && !sa_defined(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME) && sa_is_connected(sa_device) && sa_connect(guider_device) && sa_defined(guider_device, GUIDER_GUIDE_RA_PROPERTY_NAME) && sa_request_count(0, "PUT", "/api/*") == puts);
		SA_CHECK(sa_disconnect(sa_device) && SA_WAIT(!sa_device_defined(guider_device), SA_TIMEOUT));
		sa_end();
	}
	// devices that can not pulse guide have no guider, and PulseGuide and IsPulseGuiding are never asked for
	SA_CHECK(sa_begin(no_guiding) && sa_attach(MOUNT_LABEL) && sa_connect(sa_device));
	snprintf(guider_device, sizeof(guider_device), "%s (guider)", sa_device);
	SA_CHECK(mount_pause() && !sa_device_defined(guider_device) && mount_count("GET", "canpulseguide") == 1 && mount_count("GET", "ispulseguiding") == 0 && sa_disconnect(sa_device));
	SA_CHECK(sa_attach("Camera Simulator") && sa_connect(sa_device));
	snprintf(guider_device, sizeof(guider_device), "%s (guider)", sa_device);
	SA_CHECK(mount_pause() && !sa_device_defined(guider_device) && sa_request_count(0, "GET", "/api/v1/camera/0/canpulseguide") == 1 && sa_request_count(0, "GET", "/api/v1/camera/0/ispulseguiding") == 0 && sa_device_count("(guider)") == 0);
	SA_CHECK(sa_disconnect(sa_device));
cleanup:
	sa_end();
}

