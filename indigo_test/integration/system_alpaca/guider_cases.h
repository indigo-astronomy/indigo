static void guider_directions_and_units(void) {
	const char *items[] = { GUIDER_GUIDE_NORTH_ITEM_NAME, GUIDER_GUIDE_SOUTH_ITEM_NAME };
	const double both[] = { 100, 200 };
	SA_CHECK(guider_begin(guider_telescope, false));
	double ra = mount_simulated("RightAscension"), dec = mount_simulated("Declination");
	// north: Direction 0, Duration in whole milliseconds; BUSY with the requested duration while the pulse lasts, OK with zeros afterwards
	unsigned revision = sa_revision(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME);
	SA_CHECK(guider_start(GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME, 400) && guider_last("Direction=0&Duration=400&ClientID=") && sa_number(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME) == 400 && sa_number(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_SOUTH_ITEM_NAME) == 0);
	SA_CHECK(mount_simulated_is("IsPulseGuiding", "true") && sa_state(guider_device, GUIDER_GUIDE_RA_PROPERTY_NAME) == INDIGO_OK_STATE && sa_advance(0, 0.4) && guider_answer(GUIDER_GUIDE_DEC_PROPERTY_NAME, revision) == INDIGO_OK_STATE && guider_zero(GUIDER_GUIDE_DEC_PROPERTY_NAME));
	SA_CHECK(mount_near(mount_simulated("Declination"), dec + 0.4 * GUIDER_RATE, 1e-9) && mount_near(mount_simulated("RightAscension"), ra, 1e-12) && mount_simulated_is("IsPulseGuiding", "false"));
	// south: Direction 1
	SA_CHECK(guider_start(GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_SOUTH_ITEM_NAME, 250) && guider_last("Direction=1&Duration=250&ClientID=") && sa_number(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_SOUTH_ITEM_NAME) == 250 && sa_number(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME) == 0);
	SA_CHECK(sa_advance(0, 0.25) && SA_WAIT(sa_state(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME) == INDIGO_OK_STATE, SA_TIMEOUT) && guider_zero(GUIDER_GUIDE_DEC_PROPERTY_NAME) && mount_near(mount_simulated("Declination"), dec + 0.15 * GUIDER_RATE, 1e-9));
	// east: Direction 2, the right ascension grows
	SA_CHECK(guider_start(GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_EAST_ITEM_NAME, 300) && guider_last("Direction=2&Duration=300&ClientID=") && sa_number(guider_device, GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_EAST_ITEM_NAME) == 300 && sa_state(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME) == INDIGO_OK_STATE);
	SA_CHECK(sa_advance(0, 0.3) && SA_WAIT(sa_state(guider_device, GUIDER_GUIDE_RA_PROPERTY_NAME) == INDIGO_OK_STATE, SA_TIMEOUT) && guider_zero(GUIDER_GUIDE_RA_PROPERTY_NAME) && mount_near(mount_simulated("RightAscension"), ra + 0.3 * GUIDER_RATE / 15, 1e-12));
	// west: Direction 3
	SA_CHECK(guider_start(GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_WEST_ITEM_NAME, 150) && guider_last("Direction=3&Duration=150&ClientID=") && sa_number(guider_device, GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_WEST_ITEM_NAME) == 150);
	SA_CHECK(sa_advance(0, 0.15) && SA_WAIT(sa_state(guider_device, GUIDER_GUIDE_RA_PROPERTY_NAME) == INDIGO_OK_STATE, SA_TIMEOUT) && guider_zero(GUIDER_GUIDE_RA_PROPERTY_NAME) && mount_near(mount_simulated("RightAscension"), ra + 0.15 * GUIDER_RATE / 15, 1e-12) && mount_near(mount_simulated("Declination"), dec + 0.15 * GUIDER_RATE, 1e-9));
	SA_CHECK(guider_count("PUT", "pulseguide") == 4 && mount_count("PUT", "*") == 5);
	// a fraction of a millisecond is rounded to the nearest whole one
	SA_CHECK(guider_start(GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME, 123.6) && guider_last("Direction=0&Duration=124&ClientID=") && sa_advance(0, 0.124) && SA_WAIT(sa_state(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME) == INDIGO_OK_STATE, SA_TIMEOUT));
	SA_CHECK(guider_start(GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_WEST_ITEM_NAME, 20.4) && guider_last("Direction=3&Duration=20&ClientID=") && sa_advance(0, 0.02) && SA_WAIT(sa_state(guider_device, GUIDER_GUIDE_RA_PROPERTY_NAME) == INDIGO_OK_STATE, SA_TIMEOUT));
	// the longest pulse of the property
	SA_CHECK(guider_start(GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_SOUTH_ITEM_NAME, 10000) && guider_last("Direction=1&Duration=10000&ClientID=") && sa_advance(0, 10));
	// zero, and what rounds to zero, is a request to stop: without a pulse nothing is sent and the answer is OK
	int pulses = guider_count("PUT", "pulseguide");
	SA_CHECK(guider_pulse(GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_EAST_ITEM_NAME, 0) == INDIGO_OK_STATE && guider_pulse(GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_WEST_ITEM_NAME, 0.4) == INDIGO_OK_STATE && guider_zero(GUIDER_GUIDE_RA_PROPERTY_NAME) && guider_count("PUT", "pulseguide") == pulses);
	// the long pulse ends 10 s after it was started in real time at the earliest; then it is found over, because the device time is past it
	SA_CHECK(SA_WAIT(sa_state(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME) == INDIGO_OK_STATE, 15) && guider_zero(GUIDER_GUIDE_DEC_PROPERTY_NAME));
	// both items of a property in one request: the first one wins, the telescope can not guide north and south at once
	revision = sa_revision(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME);
	SA_CHECK(indigo_change_number_property(&sa_client, guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME, 2, items, both) == INDIGO_OK && SA_WAIT(guider_count("PUT", "pulseguide") == pulses + 1, SA_TIMEOUT) && guider_last("Direction=0&Duration=100&ClientID="));
	SA_CHECK(sa_advance(0, 0.1) && guider_answer(GUIDER_GUIDE_DEC_PROPERTY_NAME, revision) == INDIGO_OK_STATE && guider_zero(GUIDER_GUIDE_DEC_PROPERTY_NAME) && guider_count("PUT", "pulseguide") == pulses + 1);
	// the guide rates of the mount are the rates of the pulses: at 100 % of the sidereal rate a pulse moves twice as far
	dec = mount_simulated("Declination");
	SA_CHECK(mount_set_numbers(MOUNT_GUIDE_RATE_PROPERTY_NAME, MOUNT_GUIDE_RATE_RA_ITEM_NAME, 100, MOUNT_GUIDE_RATE_DEC_ITEM_NAME, 100) == INDIGO_OK_STATE && guider_start(GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME, 500));
	SA_CHECK(sa_advance(0, 0.5) && SA_WAIT(sa_state(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME) == INDIGO_OK_STATE, SA_TIMEOUT) && mount_near(mount_simulated("Declination"), dec + 0.5 * MOUNT_SIDEREAL, 1e-9));
	SA_CHECK(sa_disconnect(sa_device));
cleanup:
	sa_end();
}

static void guider_completion(void) {
	static const char *no_flag[] = { "--device", "telescope:interface=legacy,Tracking=true", NULL };
	SA_CHECK(guider_begin(guider_telescope, false));
	// IsPulseGuiding decides: not asked before the pulse can be over, then watched while it is true, and not asked any more when the pulse is over
	int checks = guider_count("GET", "ispulseguiding");
	unsigned revision = sa_revision(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME);
	double started = indigo_monotonic_time();
	SA_CHECK(guider_start(GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME, 400) && guider_count("GET", "ispulseguiding") == checks && guider_watched(checks, 1) && indigo_monotonic_time() - started >= 0.4);
	SA_CHECK(guider_watched(checks, 5) && sa_state(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME) == INDIGO_BUSY_STATE && !sa_state_after(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME, INDIGO_OK_STATE, revision) && sa_number(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME) == 400);
	SA_CHECK(sa_advance(0, 0.4) && guider_answer(GUIDER_GUIDE_DEC_PROPERTY_NAME, revision) == INDIGO_OK_STATE);
	// the coordinates of the mount already show the pulse when it is reported over: the end of a pulse is followed by a poll tick,
	// the regular one may be a second away and a client that reads the coordinates at once would see where the pulse started
	SA_CHECK(mount_near(sa_number(sa_device, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, MOUNT_EQUATORIAL_COORDINATES_DEC_ITEM_NAME), mount_simulated("Declination"), 1e-9));
	SA_CHECK(guider_zero(GUIDER_GUIDE_DEC_PROPERTY_NAME) && guider_quiet() && guider_count("PUT", "pulseguide") == 1);
	// the mount is not disturbed: its properties stay as they are
	SA_CHECK(sa_is_connected(sa_device) && sa_state(sa_device, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME) == INDIGO_OK_STATE && sa_switch(sa_device, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_ON_ITEM_NAME));
	// a pulse that is over when its duration has passed (device time ran ahead) completes with the first look
	checks = guider_count("GET", "ispulseguiding");
	SA_CHECK(guider_start(GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_EAST_ITEM_NAME, 300) && sa_advance(0, 0.3) && SA_WAIT(sa_state(guider_device, GUIDER_GUIDE_RA_PROPERTY_NAME) == INDIGO_OK_STATE, SA_TIMEOUT) && guider_count("GET", "ispulseguiding") == checks + 1);
	// the completion member fails: the pulse ends in ALERT with the reason, and is not watched any more
	checks = guider_count("GET", "ispulseguiding");
	revision = sa_revision(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME);
	SA_CHECK(sa_fault(0, "GET", MOUNT_API "ispulseguiding", "ascom-error", "Value=1279&Message=Guide%20port%20fault") && guider_start(GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_SOUTH_ITEM_NAME, 200));
	SA_CHECK(guider_answer(GUIDER_GUIDE_DEC_PROPERTY_NAME, revision) == INDIGO_ALERT_STATE && mount_message("Guiding failed: device error (Guide port fault (0x4FF))") && guider_zero(GUIDER_GUIDE_DEC_PROPERTY_NAME) && guider_count("GET", "ispulseguiding") == checks + 1 && guider_quiet());
	SA_CHECK(sa_advance(0, 1) && sa_fault(0, "GET", MOUNT_API "ispulseguiding", "malformed-json", NULL));
	SA_CHECK(guider_start(GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_WEST_ITEM_NAME, 200) && SA_WAIT(sa_state(guider_device, GUIDER_GUIDE_RA_PROPERTY_NAME) == INDIGO_ALERT_STATE, SA_TIMEOUT) && mount_message("Guiding failed: invalid reply") && guider_zero(GUIDER_GUIDE_RA_PROPERTY_NAME) && sa_advance(0, 1));
	// IsPulseGuiding does not become false: the pulse is given up 5 s after it should have ended
	revision = sa_revision(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME);
	started = indigo_monotonic_time();
	SA_CHECK(guider_start(GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME, 200) && guider_answer(GUIDER_GUIDE_DEC_PROPERTY_NAME, revision) == INDIGO_ALERT_STATE && mount_message("Guiding failed: timeout") && guider_zero(GUIDER_GUIDE_DEC_PROPERTY_NAME));
	SA_CHECK(indigo_monotonic_time() - started > 5 && indigo_monotonic_time() - started < 9 && guider_quiet() && sa_advance(0, 1) && sa_is_connected(guider_device));
	// a device whose PulseGuide returns only when the pulse is over (the reply comes 1.2 s after a pulse of 1 s was started): the pulse
	// is not waited for a second time, IsPulseGuiding is asked as soon as the reply is there
	SA_CHECK(sa_advance(0, 1) && sa_fault(0, "PUT", MOUNT_API "pulseguide", "stall-before", "Delay=1200"));
	revision = sa_revision(guider_device, GUIDER_GUIDE_RA_PROPERTY_NAME);
	checks = guider_count("PUT", "pulseguide");
	started = indigo_monotonic_time();
	SA_CHECK(guider_request(GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_EAST_ITEM_NAME, 1000) && SA_WAIT(guider_count("PUT", "pulseguide") == checks + 1, SA_TIMEOUT) && sa_advance(0, 1) && guider_answer(GUIDER_GUIDE_RA_PROPERTY_NAME, revision) == INDIGO_OK_STATE);
	SA_CHECK(indigo_monotonic_time() - started > 1.1 && indigo_monotonic_time() - started < 1.9 && guider_zero(GUIDER_GUIDE_RA_PROPERTY_NAME));
	// and the next pulse is OK
	SA_CHECK(guider_start(GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME, 100) && sa_advance(0, 0.1) && SA_WAIT(sa_state(guider_device, GUIDER_GUIDE_DEC_PROPERTY_NAME) == INDIGO_OK_STATE, SA_TIMEOUT) && guider_zero(GUIDER_GUIDE_DEC_PROPERTY_NAME));
	SA_CHECK(sa_disconnect(sa_device));
	sa_end();
	// a device without IsPulseGuiding: the member is asked once, and from then on a pulse is over when its duration has passed
	SA_CHECK(sa_begin(no_flag) && sa_attach(MOUNT_LABEL) && sa_put(0, MOUNT_ERROR, "Member=ispulseguiding&ErrorNumber=1024") && sa_connect(sa_device));
	snprintf(guider_device, sizeof(guider_device), "%s (guider)", sa_device);
	guider_api = MOUNT_API;
	SA_CHECK(SA_WAIT(sa_defined(guider_device, CONNECTION_PROPERTY_NAME), SA_TIMEOUT) && sa_connect(guider_device));
	for (int i = 0; i < 3; i++) {
		revision = sa_revision(guider_device, GUIDER_GUIDE_RA_PROPERTY_NAME);
		started = indigo_monotonic_time();
		SA_CHECK(guider_start(GUIDER_GUIDE_RA_PROPERTY_NAME, i == 1 ? GUIDER_GUIDE_WEST_ITEM_NAME : GUIDER_GUIDE_EAST_ITEM_NAME, 300) && guider_answer(GUIDER_GUIDE_RA_PROPERTY_NAME, revision) == INDIGO_OK_STATE && guider_zero(GUIDER_GUIDE_RA_PROPERTY_NAME));
		SA_CHECK(indigo_monotonic_time() - started >= 0.3 && indigo_monotonic_time() - started < 3 && guider_count("GET", "ispulseguiding") == 1 && guider_count("PUT", "pulseguide") == i + 1 && sa_advance(0, 0.3));
	}
	SA_CHECK(sa_disconnect(sa_device));
cleanup:
	sa_end();
}

