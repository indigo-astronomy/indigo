// Polar aligner coverage for indigo_polaralign_mlastro against the standalone
// MLAstro RPA simulator over a real PTY. The controller acknowledges every
// command with a single "ok\n"/"error: ...\n" line, pushes completion and
// error lines on its own, and reports live axis position in its '?'
// telemetry frame (AzPH/AlPH from home, Mpos since the last motion start);
// the driver decides a move is finished by polling that frame once a second
// until STATUS leaves MOVING/ALIGNING/HOMING, so most scenarios below wait
// across several polls rather than a single request/response round trip.
// Every command the simulator receives is recorded in <ready-file>.events,
// which the cases read to prove which protocol path the driver took.

