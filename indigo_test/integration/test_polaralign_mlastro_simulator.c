// The controller has one shared zero reference for both axes: SetH:1 zeros
// whichever POLARALIGN_RESET_POSITION_* fired it, but the simulator (like
// the real firmware) applies it to both axes at once.
static void reset_position_shares_the_home_reference(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_mlastro(&simulator, NULL));
	SERIAL_CHECK_TRUE(start_serial_driver(&mlastro_polaralign, simulator.port));
	online = true;
	SERIAL_CHECK_TRUE(move_to(60, -60));
	SERIAL_CHECK_TRUE(press(POLARALIGN_RESET_POSITION_ALT_PROPERTY_NAME, POLARALIGN_RESET_POSITION_ITEM_NAME));
	SERIAL_CHECK_TRUE(wait_for_property_state(POLARALIGN_RESET_POSITION_ALT_PROPERTY_NAME, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(expect_event(&simulator, "SetH:1", 1));
	SERIAL_CHECK_TRUE(wait_for_number_item_value(POLARALIGN_OFFSET_PROPERTY_NAME, POLARALIGN_OFFSET_ALT_ITEM_NAME, 0, .5));
	// the azimuth axis was zeroed too, by the same shared SetH:1
	SERIAL_CHECK_TRUE(wait_for_number_item_value(POLARALIGN_OFFSET_PROPERTY_NAME, POLARALIGN_OFFSET_AZ_ITEM_NAME, 0, .5));
	indigo_item *homed = find_cached_item(X_MLASTRO_HOMED_PROPERTY_NAME, X_MLASTRO_HOMED_ITEM_NAME);
	SERIAL_CHECK_TRUE(homed != NULL && homed->light.value == INDIGO_OK_STATE);
	// and the next move is measured from the new reference
	SERIAL_CHECK_TRUE(move_to(0, 30));
	SERIAL_CHECK_TRUE(expect_event(&simulator, "ReDe:0,ReAM:30,ReAS:0,MAzR:1", 1));
cleanup:
	if (online) { stop_serial_driver(&mlastro_polaralign); }
	stop_external_serial_simulator(&simulator);
}

// X_MLASTRO_GOTO_HOME (RetH:1) is refused until a home reference exists, and
// X_MLASTRO_CLEAR_HOME (RstH:1) forgets it again.
static void goto_home_requires_a_reference_and_clear_home_forgets_it(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_mlastro(&simulator, NULL));
	SERIAL_CHECK_TRUE(start_serial_driver(&mlastro_polaralign, simulator.port));
	online = true;
	SERIAL_CHECK_TRUE(press(X_MLASTRO_GOTO_HOME_PROPERTY_NAME, X_MLASTRO_GOTO_HOME_ITEM_NAME));
	SERIAL_CHECK_TRUE(wait_for_property_state(X_MLASTRO_GOTO_HOME_PROPERTY_NAME, INDIGO_ALERT_STATE));

	SERIAL_CHECK_TRUE(press(POLARALIGN_RESET_POSITION_AZ_PROPERTY_NAME, POLARALIGN_RESET_POSITION_ITEM_NAME));
	SERIAL_CHECK_TRUE(wait_for_property_state(POLARALIGN_RESET_POSITION_AZ_PROPERTY_NAME, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(move_to(60, 60));
	unsigned int revision = property_state_revision(POLARALIGN_OFFSET_PROPERTY_NAME, INDIGO_BUSY_STATE);
	SERIAL_CHECK_TRUE(press(X_MLASTRO_GOTO_HOME_PROPERTY_NAME, X_MLASTRO_GOTO_HOME_ITEM_NAME));
	SERIAL_CHECK_TRUE(wait_for_property_state(X_MLASTRO_GOTO_HOME_PROPERTY_NAME, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(wait_for_offset_state_after(INDIGO_BUSY_STATE, revision));
	SERIAL_CHECK_TRUE(wait_for_offset_settled());
	SERIAL_CHECK_TRUE(find_cached_property(POLARALIGN_OFFSET_PROPERTY_NAME)->state == INDIGO_OK_STATE);
	SERIAL_CHECK_TRUE(wait_for_number_item_value(POLARALIGN_OFFSET_PROPERTY_NAME, POLARALIGN_OFFSET_ALT_ITEM_NAME, 0, .5));
	SERIAL_CHECK_TRUE(wait_for_number_item_value(POLARALIGN_OFFSET_PROPERTY_NAME, POLARALIGN_OFFSET_AZ_ITEM_NAME, 0, .5));
	SERIAL_CHECK_TRUE(wait_for_status("HOME_COMPLETED"));

	SERIAL_CHECK_TRUE(press(X_MLASTRO_CLEAR_HOME_PROPERTY_NAME, X_MLASTRO_CLEAR_HOME_ITEM_NAME));
	SERIAL_CHECK_TRUE(wait_for_property_state(X_MLASTRO_CLEAR_HOME_PROPERTY_NAME, INDIGO_OK_STATE));
	indigo_item *homed = find_cached_item(X_MLASTRO_HOMED_PROPERTY_NAME, X_MLASTRO_HOMED_ITEM_NAME);
	SERIAL_CHECK_TRUE(homed != NULL && homed->light.value == INDIGO_IDLE_STATE);
cleanup:
	if (online) { stop_serial_driver(&mlastro_polaralign); }
	stop_external_serial_simulator(&simulator);
}

