static void simulator_path(const external_serial_simulator *simulator, const char *suffix, char *path, size_t size) {
	snprintf(path, size, "%s.%s", simulator->ready_file, suffix);
}

// Runtime actions are consumed by the simulator's next background tick.
static bool arm_control(const external_serial_simulator *simulator, const char *action) {
	char path[PATH_MAX];
	simulator_path(simulator, "control", path, sizeof(path));
	FILE *file = fopen(path, "w");
	if (file == NULL) {
		return false;
	}
	fprintf(file, "%s\n", action);
	return fclose(file) == 0;
}

// Counts recorded commands equal to command, or, with command NULL, every
// command other than the '?' telemetry poll.
static int event_count(const external_serial_simulator *simulator, const char *command) {
	char path[PATH_MAX];
	char line[256];
	int count = 0;
	simulator_path(simulator, "events", path, sizeof(path));
	FILE *file = fopen(path, "r");
	if (file == NULL) {
		return 0;
	}
	while (fgets(line, sizeof(line), file) != NULL) {
		line[strcspn(line, "\r\n")] = '\0';
		if (command == NULL ? strcmp(line, "?") != 0 : !strcmp(line, command)) {
			count++;
		}
	}
	fclose(file);
	return count;
}

static int event_count_containing(const external_serial_simulator *simulator, const char *fragment) {
	char path[PATH_MAX];
	char line[256];
	int count = 0;
	simulator_path(simulator, "events", path, sizeof(path));
	FILE *file = fopen(path, "r");
	if (file == NULL) {
		return 0;
	}
	while (fgets(line, sizeof(line), file) != NULL) {
		if (strstr(line, fragment) != NULL) {
			count++;
		}
	}
	fclose(file);
	return count;
}

static bool expect_event(const external_serial_simulator *simulator, const char *command, int expected_count) {
	int count = event_count(simulator, command);
	if (count != expected_count) {
		fprintf(stderr, "    '%s' was recorded %d times, expected %d\n", command, count, expected_count);
		return false;
	}
	return true;
}

// -------------------------------------------------------------------------------- property helpers

static double number_of(const char *property_name, const char *item_name) {
	return cached_number_value(property_name, item_name);
}

static const char *text_of(const char *property_name, const char *item_name) {
	indigo_item *item = find_cached_item(property_name, item_name);
	return item == NULL ? "" : item->text.value;
}

static const char *info_text(const char *item_name) {
	return text_of(INFO_PROPERTY_NAME, item_name);
}

static bool wait_for_switch_value(const char *property_name, const char *item_name, bool value) {
	for (int i = 0; i < 100; i++) {
		indigo_item *item = find_cached_item(property_name, item_name);
		if (item != NULL && item->sw.value == value) {
			return true;
		}
		indigo_usleep(100000);
	}
	return false;
}

static bool wait_for_status(const char *status) {
	for (int i = 0; i < 100; i++) {
		if (!strcmp(text_of(X_MLASTRO_STATUS_PROPERTY_NAME, X_MLASTRO_STATUS_ITEM_NAME), status)) {
			return true;
		}
		indigo_usleep(100000);
	}
	fprintf(stderr, "    controller status is '%s', expected '%s'\n", text_of(X_MLASTRO_STATUS_PROPERTY_NAME, X_MLASTRO_STATUS_ITEM_NAME), status);
	return false;
}

static bool change_offset(double alt_arcmin, double az_arcmin) {
	static const char *items[] = { POLARALIGN_OFFSET_ALT_ITEM_NAME, POLARALIGN_OFFSET_AZ_ITEM_NAME };
	const double values[] = { alt_arcmin, az_arcmin };
	return indigo_change_number_property(&simulator_test_client, mlastro_polaralign.device_name, POLARALIGN_OFFSET_PROPERTY_NAME, 2, items, values) == INDIGO_OK;
}

static bool press(const char *property_name, const char *item_name) {
	return indigo_change_switch_property_1(&simulator_test_client, mlastro_polaralign.device_name, property_name, item_name, true) == INDIGO_OK;
}

// A new offset request is answered with an ALERT or a BUSY state published
// after the given revision; waiting on the revision keeps a stale state from
// the previous request from satisfying the wait.
static bool wait_for_offset_state_after(indigo_property_state state, unsigned int revision) {
	return wait_for_property_state_seen_after(POLARALIGN_OFFSET_PROPERTY_NAME, state, revision);
}

// The simulated axes move at 0.6 deg/s at the default speed level; this
// bounds how long a wait may take for a move of up to a few degrees.
static bool wait_for_offset_settled(void) {
	for (int i = 0; i < 2000; i++) {
		indigo_property *property = find_cached_property(POLARALIGN_OFFSET_PROPERTY_NAME);
		if (property != NULL && property->state != INDIGO_BUSY_STATE) {
			return true;
		}
		indigo_usleep(10000);
	}
	return false;
}

static bool move_to(double alt_arcmin, double az_arcmin) {
	unsigned int revision = property_state_revision(POLARALIGN_OFFSET_PROPERTY_NAME, INDIGO_BUSY_STATE);
	if (!change_offset(alt_arcmin, az_arcmin) || !wait_for_offset_state_after(INDIGO_BUSY_STATE, revision) || !wait_for_offset_settled()) {
		return false;
	}
	indigo_property *property = find_cached_property(POLARALIGN_OFFSET_PROPERTY_NAME);
	return property != NULL && property->state == INDIGO_OK_STATE && wait_for_number_item_value(POLARALIGN_OFFSET_PROPERTY_NAME, POLARALIGN_OFFSET_ALT_ITEM_NAME, alt_arcmin, .5) && wait_for_number_item_value(POLARALIGN_OFFSET_PROPERTY_NAME, POLARALIGN_OFFSET_AZ_ITEM_NAME, az_arcmin, .5);
}

