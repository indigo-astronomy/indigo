// STOP:1 is a soft stop: the axes keep decelerating after the reply. The
// position they come to rest at must still reach the client, and it must be
// the position the driver computes the next move from.
static void abort_decelerates_and_publishes_final_position(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_mlastro(&simulator, NULL));
	SERIAL_CHECK_TRUE(start_serial_driver(&mlastro_polaralign, simulator.port));
	online = true;
	unsigned int revision = property_state_revision(POLARALIGN_OFFSET_PROPERTY_NAME, INDIGO_ALERT_STATE);
	SERIAL_CHECK_TRUE(change_offset(0, 480)); // 8 deg, ~13s of simulated travel
	SERIAL_CHECK_TRUE(wait_for_property_state(POLARALIGN_OFFSET_PROPERTY_NAME, INDIGO_BUSY_STATE));
	indigo_usleep(1500000); // let it get underway
	SERIAL_CHECK_TRUE(press(POLARALIGN_ABORT_MOTION_PROPERTY_NAME, POLARALIGN_ABORT_MOTION_ITEM_NAME));
	SERIAL_CHECK_TRUE(wait_for_offset_state_after(INDIGO_ALERT_STATE, revision));
	SERIAL_CHECK_TRUE(wait_for_property_state(POLARALIGN_ABORT_MOTION_PROPERTY_NAME, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(expect_event(&simulator, "STOP:1", 1));
	double aborted_az = number_of(POLARALIGN_OFFSET_PROPERTY_NAME, POLARALIGN_OFFSET_AZ_ITEM_NAME);
	SERIAL_CHECK_TRUE(wait_for_status("READY"));
	indigo_usleep(1500000);
	double stopped_az = number_of(POLARALIGN_OFFSET_PROPERTY_NAME, POLARALIGN_OFFSET_AZ_ITEM_NAME);
	printf("aborted at %.2f', came to rest at %.2f'\n", aborted_az, stopped_az);
	SERIAL_CHECK_TRUE(stopped_az > aborted_az + 1); // the deceleration was published
	SERIAL_CHECK_TRUE(stopped_az > 6 && stopped_az < 474); // stopped mid-flight, not at 0 or 480
	indigo_usleep(1500000);
	SERIAL_CHECK_TRUE(fabs(number_of(POLARALIGN_OFFSET_PROPERTY_NAME, POLARALIGN_OFFSET_AZ_ITEM_NAME) - stopped_az) < .01);
	// one degree from the published position is exactly one degree on the device
	SERIAL_CHECK_TRUE(move_to(0, stopped_az + 60));
	SERIAL_CHECK_TRUE(expect_event(&simulator, "ReDe:1,ReAM:0,ReAS:0,MAzR:1", 1));
cleanup:
	if (online) { stop_serial_driver(&mlastro_polaralign); }
	stop_external_serial_simulator(&simulator);
}

// A StallGuard hard limit stops the controller in ERROR: the move fails,
// further motion is refused as "System Locked" until X_MLASTRO_RESET_ERROR
// sends ReER:1, and afterwards only moves away from the limit are accepted.
static void hard_limit_alerts_until_error_is_reset(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	const char *arguments[] = { "--hard-limit-az", "1.0", NULL };
	SERIAL_CHECK_TRUE(start_mlastro(&simulator, arguments));
	SERIAL_CHECK_TRUE(start_serial_driver(&mlastro_polaralign, simulator.port));
	online = true;
	unsigned int revision = property_state_revision(POLARALIGN_OFFSET_PROPERTY_NAME, INDIGO_ALERT_STATE);
	SERIAL_CHECK_TRUE(change_offset(0, 120)); // 2 deg, the hard limit trips at 1 deg
	SERIAL_CHECK_TRUE(wait_for_offset_state_after(INDIGO_ALERT_STATE, revision));
	SERIAL_CHECK_TRUE(wait_for_status("ERROR"));
	SERIAL_CHECK_TRUE(wait_for_property_state(X_MLASTRO_STATUS_PROPERTY_NAME, INDIGO_ALERT_STATE));
	SERIAL_CHECK_TRUE(wait_for_number_item_value(POLARALIGN_OFFSET_PROPERTY_NAME, POLARALIGN_OFFSET_AZ_ITEM_NAME, 60, .5));

	revision = property_state_revision(POLARALIGN_OFFSET_PROPERTY_NAME, INDIGO_ALERT_STATE);
	SERIAL_CHECK_TRUE(change_offset(0, 0));
	SERIAL_CHECK_TRUE(wait_for_offset_state_after(INDIGO_ALERT_STATE, revision)); // System Locked
	SERIAL_CHECK_TRUE(wait_for_number_item_value(POLARALIGN_OFFSET_PROPERTY_NAME, POLARALIGN_OFFSET_AZ_ITEM_NAME, 60, .5));

	SERIAL_CHECK_TRUE(press(X_MLASTRO_RESET_ERROR_PROPERTY_NAME, X_MLASTRO_RESET_ERROR_ITEM_NAME));
	SERIAL_CHECK_TRUE(wait_for_property_state(X_MLASTRO_RESET_ERROR_PROPERTY_NAME, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(expect_event(&simulator, "ReER:1", 1));
	SERIAL_CHECK_TRUE(wait_for_status("READY"));
	SERIAL_CHECK_TRUE(wait_for_property_state(X_MLASTRO_STATUS_PROPERTY_NAME, INDIGO_OK_STATE));

	revision = property_state_revision(POLARALIGN_OFFSET_PROPERTY_NAME, INDIGO_ALERT_STATE);
	SERIAL_CHECK_TRUE(change_offset(0, 90));
	SERIAL_CHECK_TRUE(wait_for_offset_state_after(INDIGO_ALERT_STATE, revision)); // Hard Limit
	SERIAL_CHECK_TRUE(move_to(0, 0));
cleanup:
	if (online) { stop_serial_driver(&mlastro_polaralign); }
	stop_external_serial_simulator(&simulator);
}

