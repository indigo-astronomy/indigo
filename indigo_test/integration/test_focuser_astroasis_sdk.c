static bool remove_config_files(void) {
	DIR *directory = opendir(config_folder);
	if (directory == NULL) {
		return false;
	}
	struct dirent *entry;
	char path[PATH_MAX];
	while ((entry = readdir(directory)) != NULL) {
		if (entry->d_name[0] != '.') {
			snprintf(path, sizeof(path), "%s/%s", config_folder, entry->d_name);
			unlink(path);
		}
	}
	closedir(directory);
	return true;
}

