static int run_cases(const char *suite, const indigo_test_case *cases, int count) {
	if (!mkdtemp(config_folder)) {
		perror("mkdtemp");
		return 1;
	}
	indigo_set_log_level(INDIGO_LOG_ERROR);
	indigo_start();
	indigo_attach_client(&test_client);
	int result = indigo_run_tests(suite, cases, count);
	indigo_detach_client(&test_client);
	indigo_stop();
	remove_config_files();
	rmdir(config_folder);
	return result;
}

