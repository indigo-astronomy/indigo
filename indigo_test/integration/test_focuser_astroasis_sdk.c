static bool connect_focuser(int index, bool connect) {
	int before = revision(index, CONNECTION_PROPERTY_NAME);
	if (!change_switch(index, CONNECTION_PROPERTY_NAME, connect ? CONNECTION_CONNECTED_ITEM_NAME : CONNECTION_DISCONNECTED_ITEM_NAME)) {
		return false;
	}
	for (int i = 0; i < WAIT_STEPS; i++) {
		int current = state(index, CONNECTION_PROPERTY_NAME);
		if (revision(index, CONNECTION_PROPERTY_NAME) > before && current != INDIGO_BUSY_STATE) {
			return current == INDIGO_OK_STATE && switch_value(index, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME) == connect;
		}
		indigo_usleep(10000);
	}
	fprintf(stderr, "focuser %d connection %d timed out\n", index, connect);
	return false;
}

static bool wait_updates(int index, const char *name, int after, int count) {
	for (int i = 0; i < WAIT_STEPS; i++) {
		if (update_count(index, name) >= after + count) {
			return true;
		}
		indigo_usleep(10000);
	}
	fprintf(stderr, "focuser %d %s expected %d updates after %d, got %d\n", index, name, count, after, update_count(index, name));
	return false;
}

static bool connect_and_wait_position(int index) {
	int position = update_count(index, FOCUSER_POSITION_PROPERTY_NAME), temperature = update_count(index, FOCUSER_TEMPERATURE_PROPERTY_NAME);
	if (!connect_focuser(index, true) || !wait_updates(index, FOCUSER_POSITION_PROPERTY_NAME, position, 1) || !wait_updates(index, FOCUSER_TEMPERATURE_PROPERTY_NAME, temperature, 1)) {
		return false;
	}
	return state(index, FOCUSER_POSITION_PROPERTY_NAME) == INDIGO_OK_STATE;
}

