static void trace_property(int index, indigo_property *property) {
	static const char *states[] = { "IDLE", "OK", "BUSY", "ALERT" };
	if (!atomic_load(&trace_enabled) || !trace_selected(property->name)) {
		return;
	}
	char line[256];
	const char *name = strncmp(property->name, "X_", 2) ? property->name : property->name + 2;
	int length = snprintf(line, sizeof(line), "prop f%d %s %s", index, name, states[property->state & 3]);
	if (property->state != INDIGO_BUSY_STATE) {
		for (int i = 0; i < property->count && length < (int)sizeof(line); i++) {
			indigo_item *item = property->items + i;
			if (property->type == INDIGO_NUMBER_VECTOR) {
				length += snprintf(line + length, sizeof(line) - length, " %s=%g", item->name, item->number.value);
			} else if (property->type == INDIGO_SWITCH_VECTOR && item->sw.value) {
				length += snprintf(line + length, sizeof(line) - length, " %s", item->name);
			} else if (property->type == INDIGO_TEXT_VECTOR) {
				length += snprintf(line + length, sizeof(line) - length, " %s=\"%s\"", item->name, item->text.value);
			}
		}
	}
	trace_append(true, line);
}

static indigo_result observe_property(indigo_device *device, indigo_property *property, bool define) {
	pthread_mutex_lock(&observation_mutex);
	int index = focuser_by_name(property->device);
	if (index < 0) {
		pthread_mutex_unlock(&observation_mutex);
		return INDIGO_OK;
	}
	observed_property *slot = property_slot(index, property->name, true);
	if (slot == NULL) {
		pthread_mutex_unlock(&observation_mutex);
		return INDIGO_OK;
	}
	if (!define && !observed[index].connected && strcmp(property->name, CONNECTION_PROPERTY_NAME) && strcmp(property->name, CONFIG_PROPERTY_NAME) && strcmp(property->name, PROFILE_PROPERTY_NAME) && strcmp(property->name, PROFILE_NAME_PROPERTY_NAME)) {
		atomic_fetch_add(&late_updates, 1);
		fprintf(stderr, "late update of %s.%s\n", property->device, property->name);
	}
	indigo_release_property(slot->copy);
	slot->copy = indigo_copy_property(NULL, property);
	if (define) {
		slot->defined = true;
	}
	slot->revision++;
	if (!define) {
		slot->updates++;
	}
	slot->state_revisions[property->state & 3]++;
	if (!strcmp(property->name, CONNECTION_PROPERTY_NAME) && property->state == INDIGO_OK_STATE) {
		observed[index].connected = property->items[0].sw.value;
	}
	if (!define) {
		trace_property(index, property);
	}
	pthread_mutex_unlock(&observation_mutex);
	return INDIGO_OK;
}

