static void stop_driver(void) {
	atomic_store(&hold_status, false);
	for (int i = 0; i < FOCUSERS; i++) {
		pthread_mutex_lock(&sdk_mutex);
		memset(fakes[i].error, 0, sizeof(fakes[i].error));
		fakes[i].hold_motion = false;
		pthread_mutex_unlock(&sdk_mutex);
	}
	for (int i = 0; i < FOCUSERS; i++) {
		pthread_mutex_lock(&observation_mutex);
		bool connected = observed[i].name[0] && observed[i].connected;
		pthread_mutex_unlock(&observation_mutex);
		if (connected && !connect_focuser(i, false)) {
			fprintf(stderr, "cleanup failed to disconnect focuser %d\n", i);
			indigo_test_failures++;
		}
	}
	atomic_store(&trace_enabled, false);
	if (indigo_focuser_astroasis(INDIGO_DRIVER_SHUTDOWN, NULL) != INDIGO_OK) {
		fprintf(stderr, "cleanup shutdown failed\n");
		indigo_test_failures++;
	}
	atomic_store(&driver_stopped, true);
	indigo_usleep((useconds_t)(scaled(1.5) * 1000000));
	if (atomic_load(&attached) > 0) {
		atomic_store(&driver_stopped, false);
		indigo_focuser_astroasis(INDIGO_DRIVER_INIT, NULL);
		indigo_usleep((useconds_t)(scaled(1.5) * 1000000));
		indigo_focuser_astroasis(INDIGO_DRIVER_SHUTDOWN, NULL);
		atomic_store(&driver_stopped, true);
	}
}

