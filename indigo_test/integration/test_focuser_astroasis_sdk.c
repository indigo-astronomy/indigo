static bool wait_for(bool (*predicate)(void *), void *data, const char *what) {
	for (int i = 0; i < WAIT_STEPS; i++) {
		if (predicate(data)) {
			return true;
		}
		indigo_usleep(10000);
	}
	fprintf(stderr, "timeout waiting for %s\n", what);
	return false;
}

static bool wait_count(atomic_int *counter, int expected) {
	for (int i = 0; i < WAIT_STEPS; i++) {
		if (atomic_load(counter) == expected) {
			return true;
		}
		indigo_usleep(10000);
	}
	fprintf(stderr, "counter expected %d, got %d\n", expected, atomic_load(counter));
	return false;
}

