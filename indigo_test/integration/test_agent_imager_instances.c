// Coordination of several Imager Agent instances (the base agent and its ADDITIONAL_INSTANCES)
// over one in-process bus, each driving its own CCD simulator camera. Covered: the breakpoint
// barrier keeping members in lockstep, abort propagation from the leader, a member aborting while
// the others wait at the barrier, leader-only dithering through the real Guider Agent without
// member exposures overlapping the dither, and independent instances not interfering.

