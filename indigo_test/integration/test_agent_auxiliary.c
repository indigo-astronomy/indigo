// Code is generated by AI

// Auxiliary Agent integration tests: the AGENT_AUX_SAFETY light property is defined on attach, enumerated on request and
// deleted with the agent. Without a selected safety source the property and all its lights stay IDLE; the combination of
// the sources is covered by test_agent_auxiliary_simulator.c.

#include <unistd.h>

#include <indigo_drivers/agent_auxiliary/indigo_agent_auxiliary.h>

#include "simulator_test_common.h"

static const simulator_driver_case agent = { .label = AUX_AGENT_NAME, .driver_name = "indigo_agent_auxiliary", .device_name = AUX_AGENT_NAME, .entry = indigo_agent_auxiliary };

static atomic_int safety_delete_count;

// The bus deletes all properties of a detached device with one wildcard delete (empty name), which the shared cache can not match by name.
static indigo_result agent_client_delete_property(indigo_client *client, indigo_device *device, indigo_property *property, const char *message) {
	if (!strcmp(property->device, AUX_AGENT_NAME) && (*property->name == 0 || !strcmp(property->name, AGENT_AUX_SAFETY_PROPERTY_NAME))) {
		safety_delete_count++;
	}
	return simulator_client_delete_property(client, device, property, message);
}

static void assert_safety_property_shape(void) {
	indigo_property *property = find_cached_property(AGENT_AUX_SAFETY_PROPERTY_NAME);
	ASSERT_TRUE(property != NULL);
	if (property == NULL) {
		return;
	}
	ASSERT_EQ_INT(INDIGO_LIGHT_VECTOR, property->type);
	ASSERT_EQ_INT(INDIGO_RO_PERM, property->perm);
	ASSERT_EQ_INT(INDIGO_IDLE_STATE, property->state);
	ASSERT_STREQ(AGENT_MAIN_GROUP, property->group);
	const char *items[] = { AGENT_AUX_SAFETY_SAFE_ITEM_NAME, AGENT_AUX_SAFETY_CLOUDS_ITEM_NAME, AGENT_AUX_SAFETY_RAIN_ITEM_NAME, AGENT_AUX_SAFETY_WIND_ITEM_NAME, AGENT_AUX_SAFETY_HUMIDITY_ITEM_NAME };
	ASSERT_EQ_INT(ARRAY_SIZE(items), property->count);
	if (property->count == ARRAY_SIZE(items)) {
		for (int i = 0; i < ARRAY_SIZE(items); i++) {
			ASSERT_STREQ(items[i], property->items[i].name);
			ASSERT_EQ_INT(INDIGO_IDLE_STATE, property->items[i].light.value);
		}
	}
}

static void start_agent(void) {
	reset_simulator_context(&agent);
	atomic_store(&safety_delete_count, 0);
	simulator_test_client.delete_property = agent_client_delete_property;
	ASSERT_EQ_INT(INDIGO_OK, indigo_start());
	ASSERT_EQ_INT(INDIGO_OK, indigo_attach_client(&simulator_test_client));
	ASSERT_EQ_INT(INDIGO_OK, indigo_agent_auxiliary(INDIGO_DRIVER_INIT, NULL));
}

static void stop_agent(void) {
	ASSERT_EQ_INT(INDIGO_OK, indigo_agent_auxiliary(INDIGO_DRIVER_SHUTDOWN, NULL));
	ASSERT_EQ_INT(INDIGO_OK, indigo_detach_client(&simulator_test_client));
	ASSERT_EQ_INT(INDIGO_OK, indigo_stop());
	release_cached_properties();
}

static void safety_defined_on_attach(void) {
	start_agent();
	// The client is attached before the agent, so this is the definition published by attach, not by an enumeration.
	assert_safety_property_shape();
	assert_defined_property(FILTER_AUX_1_LIST_PROPERTY_NAME);
	stop_agent();
}

static void safety_enumerated_on_request(void) {
	start_agent();
	reset_simulator_context(&agent);
	indigo_property *selector = indigo_init_light_property(NULL, AUX_AGENT_NAME, AGENT_AUX_SAFETY_PROPERTY_NAME, "", "", INDIGO_IDLE_STATE, 0);
	ASSERT_TRUE(selector != NULL);
	ASSERT_EQ_INT(INDIGO_OK, indigo_enumerate_properties(&simulator_test_client, selector));
	indigo_release_property(selector);
	assert_safety_property_shape();
	assert_defined_property_count(1);
	reset_simulator_context(&agent);
	enumerate_simulator_device();
	assert_safety_property_shape();
	assert_defined_property(FILTER_AUX_1_LIST_PROPERTY_NAME);
	assert_defined_property(FILTER_RELATED_AGENT_LIST_PROPERTY_NAME);
	stop_agent();
}

static void safety_deleted_with_agent(void) {
	start_agent();
	ASSERT_TRUE(find_cached_property(AGENT_AUX_SAFETY_PROPERTY_NAME) != NULL);
	ASSERT_EQ_INT(0, atomic_load(&safety_delete_count));
	ASSERT_EQ_INT(INDIGO_OK, indigo_agent_auxiliary(INDIGO_DRIVER_SHUTDOWN, NULL));
	ASSERT_EQ_INT(1, atomic_load(&safety_delete_count));
	// A second start after the release defines the property again with the same shape.
	reset_simulator_context(&agent);
	ASSERT_EQ_INT(INDIGO_OK, indigo_agent_auxiliary(INDIGO_DRIVER_INIT, NULL));
	assert_safety_property_shape();
	stop_agent();
}

int main(void) {
	if (!indigo_test_use_private_home()) {
		return 1;
	}
	setvbuf(stdout, NULL, _IONBF, 0);
	alarm(60);
	const indigo_test_case tests[] = {
		{ "safety_defined_on_attach", safety_defined_on_attach },
		{ "safety_enumerated_on_request", safety_enumerated_on_request },
		{ "safety_deleted_with_agent", safety_deleted_with_agent }
	};
	int result = indigo_run_tests("Auxiliary Agent integration tests", tests, ARRAY_SIZE(tests));
	indigo_test_remove_private_home();
	return result;
}
