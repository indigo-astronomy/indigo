typedef struct { const char *name; void (*run)(void); const char *profile; } simulated_case;

static void copy_case_trace(const char *name) {
	const char *directory = getenv("INDIGO_SIMULATOR_TRACE_DIR");
	if (directory == NULL || *directory == 0) {
		return;
	}
	char target_path[PATH_MAX];
	if (snprintf(target_path, sizeof(target_path), "%s/%s.events", directory, name) >= (int)sizeof(target_path)) {
		return;
	}
	FILE *source = fopen(event_path, "r");
	if (source == NULL) {
		return;
	}
	FILE *target = fopen(target_path, "w");
	if (target != NULL) {
		char line[4096];
		while (fgets(line, sizeof(line), source) != NULL) {
			fputs(line, target);
		}
		fclose(target);
	}
	fclose(source);
}

int main(void) {
	const simulated_case cases[] = {
		{ "metadata", metadata, "normal" },
		{ "usb_match_pattern", usb_match_pattern, "normal" },
		{ "property_contract", property_contract, "normal" },
		{ "connect_closed", connect_closed, "closed" },
		{ "long_firmware", long_firmware, "long-firmware" },
		{ "unsupported_device", unsupported_device, "unsupported" },
		{ "handshake_timeout", handshake_timeout, "normal" },
		{ "needs_calibration", needs_calibration, "needs-calibration" },
		{ "uncalibrated", uncalibrated, "uncalibrated" },
		{ "repeated_init_shutdown", repeated_init_shutdown, "normal" },
		{ "shutdown_rejected_while_connected", shutdown_rejected_while_connected, "normal" },
		{ "reconnect", reconnect, "normal" },
		{ "close_and_open", close_and_open, "normal" },
		{ "partial_position", partial_position, "normal" },
		{ "abort_motion", abort_motion, "normal" },
		{ "abort_while_idle", abort_while_idle, "normal" },
		{ "abort_refused", abort_refused, "normal" },
		{ "move_refused", move_refused, "normal" },
		{ "stalled_move", stalled_move, "normal" },
		{ "motion_readback_failures", motion_readback_failures, "normal" },
		{ "external_motion_observed", external_motion_observed, "normal" },
		{ "request_versus_poll", request_versus_poll, "normal" },
		{ "overlap_refused", overlap_refused, "normal" },
		{ "disconnect_during_motion", disconnect_during_motion, "normal" },
		{ "poll_failure", poll_failure, "normal" },
		{ "environment_polled", environment_polled, "normal" },
		{ "presets", presets, "normal" },
		{ "leds", leds, "normal" },
		{ "calibration", calibration, "normal" },
		{ "wifi_credentials", wifi_credentials, "normal" },
		{ "wifi_modes", wifi_modes, "normal" },
		{ "wifi_restart_waits_for_the_cover", wifi_restart_waits_for_the_cover, "normal" },
		{ "transport_loss", transport_loss, "normal" }
	};
	setvbuf(stdout, NULL, _IOLBF, 0);
	simulator_test_client.send_message = record_message;
	simulator_test_client.define_property = observe_define;
	if (mkdtemp(fixture_directory) == NULL) {
		fprintf(stderr, "Cannot create fixture directory\n");
		return 1;
	}
	snprintf(event_path, sizeof(event_path), "%s/events.log", fixture_directory);
	snprintf(fault_path, sizeof(fault_path), "%s/fault", fixture_directory);
	setenv("INDIGO_ALTO_EVENTS", event_path, 1);
	setenv("INDIGO_ALTO_FAULT", fault_path, 1);
	const char *filter = getenv("ALTO_TEST_FILTER");
	int failures = 0;
	for (int i = 0; i < ARRAY_SIZE(cases); i++) {
		if (filter != NULL && strstr(cases[i].name, filter) == NULL) {
			continue;
		}
		unlink(fault_path);
		const char *arguments[] = { "--profile", cases[i].profile, NULL, NULL };
		if (getenv("ALTO_TEST_TRACE") != NULL) {
			arguments[2] = "--trace";
		}
		if (!start_external_serial_simulator_with_args(&fixture, AUX_ALTO_SIMULATOR_EXECUTABLE, arguments)) {
			fprintf(stderr, "Simulator startup failed\n");
			failures++;
			break;
		}
		fflush(NULL);
		pid_t child = fork();
		if (child == 0) {
			alarm(120);
			indigo_test_case test = { cases[i].name, cases[i].run };
			_exit(indigo_run_tests("PrimaluceLab ALTO", &test, 1));
		}
		int status = 0;
		if (child > 0) {
			while (waitpid(child, &status, 0) < 0) {
				if (errno != EINTR) {
					status = -1;
					break;
				}
			}
		}
		stop_external_serial_simulator(&fixture);
		copy_case_trace(cases[i].name);
		if (child < 0 || status == -1 || !WIFEXITED(status) || WEXITSTATUS(status)) {
			failures++;
			printf("FAIL: %s (exit=%d, signal=%d)\n", cases[i].name, WIFEXITED(status) ? WEXITSTATUS(status) : -1, WIFSIGNALED(status) ? WTERMSIG(status) : 0);
		}
	}
	unlink(fault_path);
	unlink(event_path);
	rmdir(fixture_directory);
	unsetenv("INDIGO_ALTO_EVENTS");
	unsetenv("INDIGO_ALTO_FAULT");
	printf("PrimaluceLab ALTO: %d failing scenarios\n", failures);
	return failures ? 1 : 0;
}
