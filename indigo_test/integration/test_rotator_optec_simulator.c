static int trace_command_count(const char *path, const char *expected) {
	FILE *file = fopen(path, "r");
	if (file == NULL) {
		return 0;
	}
	char line[128];
	char command[64];
	double timestamp;
	int count = 0;
	while (fgets(line, sizeof(line), file) != NULL) {
		if (sscanf(line, "%lf %63s", &timestamp, command) == 2 && !strcmp(command, expected)) {
			count++;
		}
	}
	fclose(file);
	return count;
}

