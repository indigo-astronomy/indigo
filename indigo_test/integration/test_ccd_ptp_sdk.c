int ptp_test_bulk(libusb_device_handle *handle, unsigned char ep, unsigned char *data, int size, int *length, unsigned timeout) {
	fake_camera *c = camera(handle);
	io_check(c);
	*length = 0;
	if (ep == 0x02 && size >= PTP_CONTAINER_HDR_SIZE && ((ptp_container *)data)->type == ptp_container_command && ((ptp_container *)data)->code == atomic_load(&gate_operation)) {
		atomic_store(&gate_entered, 1);
		double deadline = indigo_monotonic_time() + 5;
		while (!atomic_load(&gate_open) && indigo_monotonic_time() < deadline) {
			indigo_usleep(1000);
		}
		if (!atomic_load(&gate_open)) {
			return LIBUSB_ERROR_TIMEOUT;
		}
	}
	if (ep == 0x83) {
		if (c->vendor == 0x054c && atomic_load(&c->af_held) && !c->af_event && !atomic_load(&c->hold_focus)) {
			ptp_container event = { .length = PTP_CONTAINER_COMMAND_SIZE(1), .type = ptp_container_event, .code = ptp_event_sony_PropertyChanged };
			event.payload.params[0] = ptp_property_sony_FocusStatus;
			memcpy(data, &event, event.length);
			*length = event.length;
			c->af_event = true;
			return 0;
		}
		if (sony_dual_order && c->vendor == 0x054c && c->capturing && !c->event_sent) {
			ptp_container event = { .length = PTP_CONTAINER_COMMAND_SIZE(1), .type = ptp_container_event, .code = ptp_event_sony_PropertyChanged };
			memcpy(data, &event, event.length);
			*length = event.length;
			c->event_sent = true;
			return 0;
		}
		if (!sony_dual_order && c->vendor == 0x054c && c->capturing && !atomic_load(&c->hold_image)) {
			ptp_container event = { .length = PTP_CONTAINER_COMMAND_SIZE(1), .type = ptp_container_event, .code = ptp_event_sony_ObjectAdded };
			event.payload.params[0] = 0xffffc001;
			memcpy(data, &event, event.length);
			*length = event.length;
			c->event_sent = true;
			return 0;
		}
		if (olympus_native_events && c->vendor == 0x07b4 && (c->capturing || olympus_event_stage > 0) && olympus_event_stage < 4 && !c->bulb) {
			const uint16_t codes[] = { ptp_event_olympus_CaptureComplete, ptp_event_olympus_ObjectAdded, ptp_event_olympus_ObjectAddedLegacy, ptp_event_olympus_DevicePropChanged };
			ptp_container event = { .length = PTP_CONTAINER_COMMAND_SIZE(1), .type = ptp_container_event, .code = codes[olympus_event_stage] };
			event.payload.params[0] = olympus_event_stage == 0 ? 99 : olympus_event_stage == 3 ? ptp_property_olympus_Shutterspeed : olympus_event_stage;
			olympus_event_stage++;
			memcpy(data, &event, event.length);
			*length = event.length;
			return 0;
		}
		if (c->vendor == 0x07b4 && c->capturing && !c->bulb && !c->event_sent && !atomic_load(&c->hold_image)) {
			ptp_container event = { .length = PTP_CONTAINER_COMMAND_SIZE(1), .type = ptp_container_event, .code = ptp_event_ObjectAdded };
			event.payload.params[0] = 1;
			memcpy(data, &event, event.length);
			*length = event.length;
			c->event_sent = true;
			return 0;
		}
		return LIBUSB_ERROR_TIMEOUT;
	}
	if (ep == 0x02) {
		ptp_container *packet = (ptp_container *)data;
		if (packet->type == ptp_container_command) {
			memcpy(&c->command, packet, size);
			prepare(c);
		} else if (packet->type == ptp_container_data && c->response == ptp_response_OK) {
			uint32_t code = c->command.payload.params[0], v = 0;
			if (c->command.code == ptp_operation_canon_SetDevicePropValueEx) {
				memcpy(&code, packet->payload.data + 4, 4);
				memcpy(&v, packet->payload.data + 8, 4);
			} else {
				memcpy(&v, packet->payload.data, size - PTP_CONTAINER_HDR_SIZE < 4 ? size - PTP_CONTAINER_HDR_SIZE : 4);
			}
			uint32_t *target = value(c, code);
			if (c->command.code == ptp_operation_canon_SetDevicePropValueEx && code == ptp_property_canon_Artist) {
				unsigned length = size - PTP_CONTAINER_HDR_SIZE;
				memcpy(canon_text_payload, packet->payload.data, length < sizeof(canon_text_payload) ? length : sizeof(canon_text_payload));
				atomic_store(&canon_text_size, length);
			}
			if (c->command.code == ptp_operation_canon_SetDevicePropValueEx && code == ptp_property_canon_MirrorUpSetting) {
				atomic_fetch_add(&mirror_writes, 1);
				if (atomic_load(&mirror_reject) == 2 || (atomic_load(&mirror_reject) == 1 && target && *target == v)) {
					c->response = ptp_response_DeviceBusy;
					*length = size;
					return LIBUSB_SUCCESS;
				}
				atomic_store(&mirror_value, v);
			}
			// The ILCE-7RM4 acknowledges a SetControlDeviceA it drops while busy after a capture.
			if (c->command.code == ptp_operation_sony_SetControlDeviceA && atomic_load(&sony_dropped_writes) > 0) {
				atomic_fetch_sub(&sony_dropped_writes, 1);
				target = NULL;
			}
			// The X-T1, whose d208 actions lack BULB start and stop, rejects a Bulb ExposureTime.
			if (c->vendor == 0x04cb && code == ptp_property_ExposureTime && v == 0xffffffff && (fuji_action_profile == 1 || fuji_action_profile == 2)) {
				c->response = ptp_response_InvalidDevicePropValue;
				*length = size;
				return LIBUSB_SUCCESS;
			}
			if (target) {
				*target = v;
			}
			if (c->vendor == 0x04cb && code == ptp_property_fuji_AutoFocus) {
				if ((v == 0x0500 && fuji_reject_bulb) || (v == 0x0004 && fuji_reject_cancel)) {
					c->response = ptp_response_InvalidDevicePropValue;
					*length = size;
					return LIBUSB_SUCCESS;
				}
				c->fuji_mode = v;
				if (v == 0x0200) {
					atomic_store(&c->af_held, true);
				} else if (v == 0x0004 || v == 0x0304 || v == 0x0500) {
					atomic_store(&c->af_held, false);
				}
				if (v == 0x0500) {
					atomic_store(&fuji_bulb_started, 1);
				}
				if (v == 0x000c) {
					atomic_store(&c->held_us, (indigo_monotonic_time() - c->pressed_at) * 1000000);
					c->bulb = false;
				}
			}
			if (fuji_priority_profile && code == ptp_property_fuji_ControlPriority && v == 2) {
				*value(c, ptp_property_ExposureTime) = 32000000;
			}
			if (c->command.code == ptp_operation_sony_SetControlDeviceB && code == ptp_property_sony_NearFar) {
				atomic_store(&sony_focus_value, (int16_t)v);
			}
			if (c->command.code == ptp_operation_sony_SetControlDeviceB && code == ptp_property_sony_Autofocus) {
				atomic_store(&c->af_held, v == 2);
				c->af_event = false;
			}
			if (c->command.code == ptp_operation_sony_SetControlDeviceB && code == ptp_property_sony_Capture) {
				if (v == 2) {
					atomic_fetch_add(&sony_presses, 1);
					c->pressed_at = indigo_monotonic_time();
					if (atomic_load(&sony_object_queue) && atomic_load(&sony_ignored_presses) == 0) {
						atomic_fetch_add(&sony_queued_objects, 1);
					}
				}
				if (v == 2 && atomic_load(&sony_ignored_presses) > 0) {
					atomic_fetch_sub(&sony_ignored_presses, 1);
				} else if (v == 2) {
					c->capturing = true;
					c->event_sent = false;
					c->bulb = c->values[0] == 0;
					if (sony_dual_order) {
						sony_memory_objects = 2;
						c->values[3] = 0x8002;
					}
				} else {
					atomic_store(&c->held_us, (indigo_monotonic_time() - c->pressed_at) * 1000000);
					c->bulb = false;
				}
			}
		}
		*length = size;
		return 0;
	}
	if ((c->input_size || c->command.code == ptp_operation_canon_GetPartialObject) && !c->data_header_sent) {
		ptp_container packet = { .length = c->input_size + PTP_CONTAINER_HDR_SIZE, .type = ptp_container_data, .code = c->command.code, .transaction_id = c->command.transaction_id };
		unsigned chunk = c->input_size < (unsigned)(size - PTP_CONTAINER_HDR_SIZE) ? c->input_size : size - PTP_CONTAINER_HDR_SIZE;
		memcpy(packet.payload.data, c->input, chunk);
		memcpy(data, &packet, chunk + PTP_CONTAINER_HDR_SIZE);
		*length = chunk + PTP_CONTAINER_HDR_SIZE;
		c->input_offset = chunk;
		c->data_header_sent = true;
		return 0;
	}
	if (c->input_offset < c->input_size) {
		unsigned chunk = c->input_size - c->input_offset;
		if (chunk > (unsigned)size) {
			chunk = size;
		}
		memcpy(data, c->input + c->input_offset, chunk);
		*length = chunk;
		c->input_offset += chunk;
		return 0;
	}
	ptp_container packet = { .length = PTP_CONTAINER_HDR_SIZE, .type = ptp_container_response, .code = c->response, .transaction_id = c->command.transaction_id };
	if (atomic_load(&bad_response) && (c->command.code == ptp_operation_GetObject || c->command.code == ptp_operation_canon_GetObject)) {
		packet.transaction_id++;
	}
	memcpy(data, &packet, packet.length);
	*length = packet.length;
	return 0;
}

static bool valid_preview(indigo_item *item, bool histogram) {
	struct jpeg_decompress_struct info = { 0 };
	struct jpeg_error_mgr errors;
	info.err = jpeg_std_error(&errors);
	jpeg_create_decompress(&info);
	jpeg_mem_src(&info, item->blob.value, item->blob.size);
	bool valid = jpeg_read_header(&info, TRUE) == JPEG_HEADER_OK;
	valid = valid && !strcmp(item->blob.format, ".jpeg") && info.image_width > 0 && info.image_height > 0;
	if (histogram) {
		valid = valid && info.image_width == 256 && info.image_height == 128;
	}
	info.out_color_space = JCS_RGB;
	jpeg_start_decompress(&info);
	JSAMPARRAY row = (*info.mem->alloc_sarray)((j_common_ptr)&info, JPOOL_IMAGE, info.output_width * 3, 1);
	unsigned long sum = 0;
	while (info.output_scanline < info.output_height) {
		jpeg_read_scanlines(&info, row, 1);
		for (unsigned i = 0; i < info.output_width * 3; i++) {
			sum += row[0][i];
		}
	}
	jpeg_finish_decompress(&info);
	jpeg_destroy_decompress(&info);
	return valid && sum > 0;
}

static indigo_result image_update(indigo_client *client, indigo_device *device, indigo_property *property, const char *message) {
	if (device && device->master_device != device && !strcmp(property->name, CONNECTION_PROPERTY_NAME)) {
		atomic_store(&focus_connection_state, property->state);
	}
	if (device && device->master_device != device && !strcmp(property->name, FOCUSER_STEPS_PROPERTY_NAME)) {
		atomic_store(&focus_state, property->state);
	}
	if (device && device->master_device == device) {
		if (!strcmp(property->name, DSLR_LOCK_PROPERTY_NAME)) {
			atomic_store(&lock_state, property->state);
		} else if (!strcmp(property->name, DSLR_ZOOM_PREVIEW_PROPERTY_NAME)) {
			atomic_store(&zoom_state, property->state);
		} else if (!strcmp(property->name, DSLR_AF_PROPERTY_NAME)) {
			atomic_store(&af_state, property->state);
		} else if (!strcmp(property->name, DSLR_SET_HOST_TIME_PROPERTY_NAME)) {
			atomic_store(&host_time_state, property->state);
		}
		if (!strcmp(property->name, DSLR_SHUTTER_PROPERTY_NAME)) {
			atomic_store(&shutter_state, property->state);
		} else if (!strcmp(property->name, DSLR_ISO_PROPERTY_NAME)) {
			atomic_store(&iso_state, property->state);
		} else if (!strcmp(property->name, DSLR_CAPTURE_DESTINATION_PROPERTY_NAME)) {
			atomic_store(&destination_state, property->state);
		} else if (!strcmp(property->name, DSLR_EXPOSURE_COMPENSATION_PROPERTY_NAME)) {
			atomic_store(&bias_state, property->state);
		}
		if (!strcmp(property->name, CONNECTION_PROPERTY_NAME)) {
			atomic_store(&connection_state, property->state);
		} else if (!strcmp(property->name, CCD_EXPOSURE_PROPERTY_NAME)) {
			atomic_store(&exposure_state, property->state);
			if (property->state == INDIGO_BUSY_STATE) {
				atomic_store(&countdown_value, property->items->number.value);
			}
			atomic_fetch_add(&exposure_updates, 1);
		} else if (!strcmp(property->name, CCD_STREAMING_PROPERTY_NAME)) {
			atomic_store(&streaming_state, property->state);
			atomic_fetch_add(&streaming_updates, 1);
		}
	}
	if (!strcmp(property->name, CCD_IMAGE_FILE_PROPERTY_NAME)) {
		if (property->state == INDIGO_OK_STATE && atomic_load(&image_file_state) == INDIGO_BUSY_STATE && property->items->text.value[0]) {
			INDIGO_COPY_VALUE(saved_image_path, property->items->text.value);
			atomic_fetch_add(&saved_images, 1);
		}
		atomic_store(&image_file_state, property->state);
	}
	if (!strcmp(property->name, CCD_PREVIEW_HISTOGRAM_PROPERTY_NAME) && property->state == INDIGO_ALERT_STATE) {
		atomic_fetch_add(&histogram_alerts, 1);
	}
	if (!strcmp(property->name, CCD_PREVIEW_HISTOGRAM_PROPERTY_NAME) && property->state == INDIGO_OK_STATE && property->count && property->items->blob.value) {
		if (nikon_dual_profile && !valid_preview(property->items, true)) {
			atomic_fetch_add(&bad_preview, 1);
		}
		atomic_fetch_add(&histogram_blobs, 1);
	}
	if (!strcmp(property->name, CCD_PREVIEW_IMAGE_PROPERTY_NAME) && property->state == INDIGO_OK_STATE && property->count && property->items->blob.value) {
		if (nikon_dual_profile && !nikon_bad_jpeg && (!valid_preview(property->items, false) || (!nikon_raw_output && (property->items->blob.size != jpeg_size || memcmp(property->items->blob.value, jpeg, jpeg_size))))) {
			atomic_fetch_add(&bad_preview, 1);
		}
		atomic_fetch_add(&preview_blobs, 1);
	}
	if (!strcmp(property->name, CCD_IMAGE_PROPERTY_NAME) && property->state == INDIGO_OK_STATE && property->count && property->items->blob.value) {
		atomic_fetch_add(&blobs, 1);
		if (canon_transfer_event) {
			snprintf(canon_transfer_blob_format, sizeof(canon_transfer_blob_format), "%s", property->items->blob.format);
			if (atomic_load(command_count + ptp_operation_canon_TransferComplete) < atomic_load(&blobs)) {
				atomic_fetch_add(&canon_transfer_protocol_errors, 1);
			}
		}
		if (canon_transfer_large) {
			if (property->items->blob.size != 0x200000 + 17) {
				atomic_fetch_add(&bad_blob, 1);
			} else {
				const uint8_t *bytes = property->items->blob.value;
				for (unsigned i = 0; i < 0x200000 + 17; i++) {
					if (bytes[i] != (uint8_t)(i * 31 + 7)) {
						atomic_fetch_add(&bad_blob, 1);
						break;
					}
				}
			}
		} else if (nikon_dual_profile && nikon_raw_output) {
			indigo_raw_header *header = property->items->blob.value;
			if (property->items->blob.size < 64 * 64 * 2 + sizeof(indigo_raw_header) || property->items->blob.size > sizeof(captured_raw) || header->signature != INDIGO_RAW_MONO16 || header->width != 64 || header->height != 64) {
				atomic_fetch_add(&bad_blob, 1);
			} else {
				captured_raw_size = property->items->blob.size;
				memcpy(captured_raw, header, captured_raw_size);
				uint16_t *pixels = (uint16_t *)(header + 1);
				uint64_t actual = 0, expected = 0;
				for (unsigned i = 0; i < 64 * 64; i++) {
					actual += pixels[i];
					expected += ccd_test_noise(i, 0);
				}
				if (actual != expected) {
					atomic_fetch_add(&bad_blob, 1);
				}
			}
		} else if (property->items->blob.size != (nikon_dual_profile ? dng_size : jpeg_size) || memcmp(property->items->blob.value, nikon_dual_profile ? dng : jpeg, nikon_dual_profile ? dng_size : jpeg_size)) {
			atomic_fetch_add(&bad_blob, 1);
		}
	}
	return INDIGO_OK;
}

