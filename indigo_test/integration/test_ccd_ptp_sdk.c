static bool wait_not_busy(atomic_int *state) {
	double deadline = indigo_monotonic_time() + 10;
	while (atomic_load(state) == INDIGO_BUSY_STATE && indigo_monotonic_time() < deadline) {
		indigo_usleep(10000);
	}
	return atomic_load(state) != INDIGO_BUSY_STATE;
}

