static void metadata_identity_and_property_completeness(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_fbc(&simulator, "2.4.1"));
	SERIAL_CHECK_TRUE(start_serial_driver(&fbc_aux, simulator.port));
	online = true;
	SERIAL_CHECK_TRUE(context.connected && context.last_connection_state == INDIGO_OK_STATE);
	assert_device_interface(INDIGO_INTERFACE_AUX_LIGHTBOX);
	static const char *properties[] = {
		AUX_LIGHT_INTENSITY_PROPERTY_NAME,
		AUX_LIGHT_IMPULSE_PROPERTY_NAME,
		CCD_EXPOSURE_PROPERTY_NAME
	};
	assert_defined_properties(properties, ARRAY_SIZE(properties));
	assert_property_has_item(AUX_LIGHT_INTENSITY_PROPERTY_NAME, AUX_LIGHT_INTENSITY_ITEM_NAME);
	assert_property_has_item(AUX_LIGHT_IMPULSE_PROPERTY_NAME, AUX_LIGHT_IMPULSE_DURATION_ITEM_NAME);
	assert_property_has_item(CCD_EXPOSURE_PROPERTY_NAME, CCD_EXPOSURE_ITEM_NAME);
	assert_number_item_in_range(AUX_LIGHT_INTENSITY_PROPERTY_NAME, AUX_LIGHT_INTENSITY_ITEM_NAME);
	// The FBC has no on/off switch and no cover; only the intensity and the two triggers exist.
	assert_not_defined_property(AUX_LIGHT_SWITCH_PROPERTY_NAME);
	assert_not_defined_property(AUX_COVER_PROPERTY_NAME);
	printf("Model '%s' firmware '%s'\n", info_text(INFO_DEVICE_MODEL_ITEM_NAME), info_text(INFO_DEVICE_FW_REVISION_ITEM_NAME));
	SERIAL_CHECK_TRUE(!strcmp(info_text(INFO_DEVICE_FW_REVISION_ITEM_NAME), "2.4.1"));
cleanup:
	if (online) { stop_serial_driver(&fbc_aux); }
	stop_external_serial_simulator(&simulator);
}

