// AUX lightbox coverage for indigo_aux_fbc against the standalone Lacerta FBC simulator over a real
// PTY. The FBC exposes a flat panel plus a camera shutter trigger: AUX_LIGHT_IMPULSE and
// CCD_EXPOSURE both run a one second granularity countdown inside the handler, publishing the
// remaining duration until it reaches zero. Connecting requires the device to be in SerialMode.

#include <indigo_drivers/aux_fbc/indigo_aux_fbc.h>

#include "serial_simulator_test_common.h"

#ifndef AUX_FBC_SIMULATOR_EXECUTABLE
#define AUX_FBC_SIMULATOR_EXECUTABLE "build/integration/aux_fbc_simulator"
#endif

static const simulator_driver_case fbc_aux = {
	"Lacerta FBC Light",
	"indigo_aux_fbc",
	"Lacerta FBC",
	indigo_aux_fbc,
	false,
	NULL, 0, NULL, 0, NULL, 0, NULL, 0
};

static bool start_fbc(external_serial_simulator *simulator, const char *firmware) {
	if (firmware == NULL) {
		return start_external_serial_simulator(simulator, AUX_FBC_SIMULATOR_EXECUTABLE);
	}
	const char *arguments[] = { "--firmware", firmware, NULL };
	return start_external_serial_simulator_with_args(simulator, AUX_FBC_SIMULATOR_EXECUTABLE, arguments);
}

static const char *info_text(const char *item_name) {
	indigo_item *item = find_cached_item(INFO_PROPERTY_NAME, item_name);
	return item == NULL ? "" : item->text.value;
}

static bool set_number(const char *property, const char *item, double value) {
	return indigo_change_number_property_1(&simulator_test_client, fbc_aux.device_name, property, item, value) == INDIGO_OK;
}

