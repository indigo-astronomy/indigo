// Runs one Mount Agent process (SLEW or SYNC) on the given target and returns the state the agent ends it in.
static int agent_process(const char *operation, double ra, double dec) {
	REQUIRE(WAIT_UNTIL(exists(MOUNT, AGENT_MOUNT_TARGET_COORDINATES_PROPERTY_NAME), 10));
	unsigned before = revision(MOUNT, AGENT_MOUNT_TARGET_COORDINATES_PROPERTY_NAME);
	REQUIRE(indigo_change_number_property(&observer, MOUNT, AGENT_MOUNT_TARGET_COORDINATES_PROPERTY_NAME, 2, (const char *[]){ AGENT_MOUNT_TARGET_COORDINATES_RA_ITEM_NAME, AGENT_MOUNT_TARGET_COORDINATES_DEC_ITEM_NAME }, (double []){ ra, dec }) == INDIGO_OK);
	REQUIRE(WAIT_UNTIL(revision(MOUNT, AGENT_MOUNT_TARGET_COORDINATES_PROPERTY_NAME) > before, 10));
	before = revision(MOUNT, AGENT_START_PROCESS_PROPERTY_NAME);
	REQUIRE(change_switch(MOUNT, AGENT_START_PROCESS_PROPERTY_NAME, operation, true));
	REQUIRE(WAIT_UNTIL(revision(MOUNT, AGENT_START_PROCESS_PROPERTY_NAME) > before && state(MOUNT, AGENT_START_PROCESS_PROPERTY_NAME) == INDIGO_BUSY_STATE, 10));
	if (!WAIT_UNTIL(state(MOUNT, AGENT_START_PROCESS_PROPERTY_NAME) != INDIGO_BUSY_STATE, 180)) {
		fprintf(stderr, "Mount Agent %s did not finish\n", operation);
		dump_messages();
		return -1;
	}
	return state(MOUNT, AGENT_START_PROCESS_PROPERTY_NAME);
}

static bool slew_to(double ra, double dec) {
	int result = agent_process(AGENT_MOUNT_START_SLEW_ITEM_NAME, ra, dec);
	if (result != INDIGO_OK_STATE || state(MOUNT_DEVICE, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME) != INDIGO_OK_STATE || fabs(mount_dec() - dec) > 0.01) {
		fprintf(stderr, "slew to %g %g ended in state %d at %g %g (mount state %d)\n", ra, dec, result, mount_ra(), mount_dec(), state(MOUNT_DEVICE, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME));
		dump_messages();
		return false;
	}
	return true;
}

static bool setup(void) {
	indigo_set_log_level(getenv("INDIGO_TEST_DEBUG") ? INDIGO_LOG_DEBUG : INDIGO_LOG_ERROR);
	REQUIRE(indigo_start() == INDIGO_OK);
	bus_started = true;
	INDIGO_COPY_NAME(observer.name, "Mount Agent observer");
	observer.version = INDIGO_VERSION_CURRENT;
	observer.define_property = defined;
	observer.update_property = updated;
	observer.delete_property = deleted;
	observer.send_message = message_received;
	REQUIRE(indigo_attach_client(&observer) == INDIGO_OK);
	observer_attached = true;
	if (mount->simulator) {
		REQUIRE(start_external_serial_simulator(&serial_simulator, mount->simulator));
	}
	REQUIRE(mount->entry(INDIGO_DRIVER_INIT, NULL) == INDIGO_OK);
	mount_started = true;
	if (mount->simulator) {
		REQUIRE(change_text(MOUNT_DEVICE, DEVICE_PORT_PROPERTY_NAME, DEVICE_PORT_ITEM_NAME, serial_simulator.port));
	}
	REQUIRE(indigo_agent_mount(INDIGO_DRIVER_INIT, NULL) == INDIGO_OK);
	mount_agent_started = true;
	REQUIRE(WAIT_UNTIL(has_item(MOUNT, FILTER_MOUNT_LIST_PROPERTY_NAME, MOUNT_DEVICE), 10));
	REQUIRE(change_switch_and_wait(MOUNT, FILTER_MOUNT_LIST_PROPERTY_NAME, MOUNT_DEVICE, true, INDIGO_OK_STATE, 20));
	REQUIRE(WAIT_UNTIL(switch_value(MOUNT_DEVICE, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME) && exists(MOUNT, MOUNT_PARK_PROPERTY_NAME) && exists(MOUNT_DEVICE, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME) && switch_value(MOUNT, AGENT_MOUNT_FEATURES_PROPERTY_NAME, AGENT_MOUNT_FEATURES_CAN_SYNC_ITEM_NAME), 30));
	if (switch_value(MOUNT, MOUNT_PARK_PROPERTY_NAME, MOUNT_PARK_PARKED_ITEM_NAME)) {
		REQUIRE(change_switch_and_wait(MOUNT, MOUNT_PARK_PROPERTY_NAME, MOUNT_PARK_UNPARKED_ITEM_NAME, true, INDIGO_OK_STATE, 60));
	}
	// the pole refusal belongs to the INDIGO alignment model, a sync in CONTROLLER mode goes to the mount itself
	REQUIRE(change_switch_and_wait(MOUNT_DEVICE, MOUNT_ALIGNMENT_MODE_PROPERTY_NAME, MOUNT_ALIGNMENT_MODE_SINGLE_POINT_ITEM_NAME, true, INDIGO_OK_STATE, 10));
	return true;
}

static void cleanup(void) {
	if (mount_agent_started) {
		indigo_agent_mount(INDIGO_DRIVER_SHUTDOWN, NULL);
	}
	if (mount_started) {
		if (switch_value(MOUNT_DEVICE, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME)) {
			change_switch_and_wait(MOUNT_DEVICE, CONNECTION_PROPERTY_NAME, CONNECTION_DISCONNECTED_ITEM_NAME, true, INDIGO_OK_STATE, 20);
		}
		mount->entry(INDIGO_DRIVER_SHUTDOWN, NULL);
	}
	if (observer_attached) {
		indigo_detach_client(&observer);
	}
	if (bus_started) {
		indigo_stop();
	}
	stop_external_serial_simulator(&serial_simulator);
}

// The mount points at declination 87, where the mount base driver refuses a sync. A sync requested a few arc
// minutes from the real pointing, well within the agent's tolerance, is refused with MOUNT_EQUATORIAL_COORDINATES
// in ALERT and no alignment point; the agent must report the sync as failed and not as synced. The position polls of
// both drivers publish through indigo_update_coordinates(), which keeps the ALERT that ended the BUSY of the sync.
static void sync_refused_near_pole_is_reported_failed(void) {
	ASSERT_TRUE(slew_to(fmod(mount_ra() + 2, 24), 87));
	double ra = mount_ra(), dec = mount_dec();
	ASSERT_EQ_INT(0, alignment_points());
	clear_messages();
	int result = agent_process(AGENT_MOUNT_START_SYNC_ITEM_NAME, fmod(ra + 0.002, 24), dec + 0.05);
	if (result != INDIGO_ALERT_STATE) {
		dump_messages();
	}
	ASSERT_TRUE(has_message("Sync refused"));
	ASSERT_EQ_INT(INDIGO_ALERT_STATE, result);
	ASSERT_TRUE(has_message("Sync failed"));
	ASSERT_FALSE(has_message("Synced"));
	ASSERT_EQ_INT(0, alignment_points());
	// the mount keeps publishing its real pointing, not the refused coordinates
	ASSERT_TRUE(fabs(mount_dec() - dec) < 0.001);
}

// Away from the pole the same small sync is accepted: the agent reports it synced and the mount has an alignment point.
static void accepted_sync_is_reported_synced(void) {
	ASSERT_TRUE(slew_to(fmod(mount_ra() + 2, 24), 40));
	double ra = mount_ra(), dec = mount_dec();
	ASSERT_EQ_INT(0, alignment_points());
	clear_messages();
	int result = agent_process(AGENT_MOUNT_START_SYNC_ITEM_NAME, fmod(ra + 0.002, 24), dec + 0.05);
	if (result != INDIGO_OK_STATE) {
		dump_messages();
	}
	ASSERT_EQ_INT(INDIGO_OK_STATE, result);
	ASSERT_TRUE(has_message("Synced"));
	ASSERT_FALSE(has_message("Sync failed"));
	ASSERT_TRUE(WAIT_UNTIL(alignment_points() == 1, 10));
	ASSERT_TRUE(fabs(mount_dec() - (dec + 0.05)) < 0.001);
}

// The mount simulator keeps MOUNT_EQUATORIAL_COORDINATES in ALERT after a refused sync, and its position poll republishes
// that ALERT. A sync requested above declination 85 while the mount points below it is refused; the next sync, near the
// real pointing and without a slew in between, is accepted and must be reported synced although the request starts
// from the ALERT of the refusal.
static void accepted_sync_after_refused_sync_is_reported_synced(void) {
	ASSERT_TRUE(slew_to(fmod(mount_ra() + 2, 24), 80));
	double ra = mount_ra(), dec = mount_dec();
	ASSERT_EQ_INT(0, alignment_points());
	clear_messages();
	ASSERT_EQ_INT(INDIGO_ALERT_STATE, agent_process(AGENT_MOUNT_START_SYNC_ITEM_NAME, ra, 86));
	ASSERT_TRUE(has_message("Sync refused"));
	ASSERT_TRUE(has_message("Sync failed"));
	ASSERT_EQ_INT(INDIGO_ALERT_STATE, state(MOUNT_DEVICE, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME));
	ASSERT_EQ_INT(0, alignment_points());
	ASSERT_TRUE(fabs(mount_dec() - dec) < 0.001);
	clear_messages();
	int result = agent_process(AGENT_MOUNT_START_SYNC_ITEM_NAME, fmod(ra + 0.002, 24), dec + 0.05);
	if (result != INDIGO_OK_STATE) {
		dump_messages();
	}
	ASSERT_EQ_INT(INDIGO_OK_STATE, result);
	ASSERT_TRUE(has_message("Synced"));
	ASSERT_FALSE(has_message("Sync failed"));
	ASSERT_TRUE(WAIT_UNTIL(alignment_points() == 1, 10));
	ASSERT_TRUE(fabs(mount_dec() - (dec + 0.05)) < 0.001);
}

// Another client's GoTo reaches the mount between the agent's admission of a sync and its coordinates request: it is sent from the
// observer's callback on the agent's MOUNT_ON_COORDINATES_SET change, i.e. in the agent's thread right before the coordinates. The
// mount refuses the coordinates of the sync with a BUSY message and the foreign slew ends OK within the agent's tolerance of the sync
// coordinates. The agent must not take that OK for the result of the sync: the mount never published the sync coordinates as its
// targets, so the sync failed, and no alignment point was added.
static atomic_bool foreign_goto_armed;
static double foreign_goto_ra, foreign_goto_dec;

static indigo_result foreign_goto_updated(indigo_client *client, indigo_device *device, indigo_property *property, const char *message) {
	indigo_result result = updated(client, device, property, message);
	if (!strcmp(property->device, MOUNT_DEVICE) && !strcmp(property->name, MOUNT_ON_COORDINATES_SET_PROPERTY_NAME)) {
		for (int i = 0; i < property->count; i++) {
			if (!strcmp(property->items[i].name, MOUNT_ON_COORDINATES_SET_SYNC_ITEM_NAME) && property->items[i].sw.value && atomic_exchange(&foreign_goto_armed, false)) {
				indigo_change_switch_property_1(&observer, MOUNT_DEVICE, MOUNT_ON_COORDINATES_SET_PROPERTY_NAME, MOUNT_ON_COORDINATES_SET_TRACK_ITEM_NAME, true);
				indigo_change_number_property(&observer, MOUNT_DEVICE, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, 2, (const char *[]){ MOUNT_EQUATORIAL_COORDINATES_RA_ITEM_NAME, MOUNT_EQUATORIAL_COORDINATES_DEC_ITEM_NAME }, (double []){ foreign_goto_ra, foreign_goto_dec });
			}
		}
	}
	return result;
}

static void sync_refused_by_a_foreign_slew_is_reported_failed(void) {
	ASSERT_TRUE(slew_to(fmod(mount_ra() + 2, 24), 40));
	ASSERT_EQ_INT(0, alignment_points());
	foreign_goto_ra = fmod(mount_ra() + 1, 24);
	foreign_goto_dec = 30;
	clear_messages();
	observer.update_property = foreign_goto_updated;
	atomic_store(&foreign_goto_armed, true);
	int result = agent_process(AGENT_MOUNT_START_SYNC_ITEM_NAME, fmod(foreign_goto_ra + 0.002, 24), foreign_goto_dec + 0.05);
	observer.update_property = updated;
	if (result != INDIGO_ALERT_STATE) {
		dump_messages();
	}
	ASSERT_FALSE(atomic_load(&foreign_goto_armed));
	// the foreign client switched the mode to TRACK for its GoTo, so the mount refuses the coordinates as such
	ASSERT_TRUE(has_message("Mount is busy, the new coordinates are ignored"));
	ASSERT_EQ_INT(INDIGO_ALERT_STATE, result);
	ASSERT_TRUE(has_message("Mount did not accept the sync"));
	ASSERT_TRUE(has_message("Sync failed"));
	ASSERT_FALSE(has_message("Synced"));
	ASSERT_EQ_INT(0, alignment_points());
	// the mount reports where the foreign GoTo took it, not the refused coordinates
	ASSERT_TRUE(fabs(mount_dec() - foreign_goto_dec) < 0.001);
}

// A process requested while the mount is BUSY (here a GoTo of another client) is refused in ALERT with a message instead of being
// dropped without an answer; the agent never starts it.
static void process_requested_while_the_mount_is_busy_is_refused(void) {
	ASSERT_TRUE(slew_to(fmod(mount_ra() + 2, 24), 40));
	ASSERT_TRUE(change_switch(MOUNT_DEVICE, MOUNT_ON_COORDINATES_SET_PROPERTY_NAME, MOUNT_ON_COORDINATES_SET_TRACK_ITEM_NAME, true));
	ASSERT_EQ_INT(INDIGO_OK, indigo_change_number_property(&observer, MOUNT_DEVICE, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, 2, (const char *[]){ MOUNT_EQUATORIAL_COORDINATES_RA_ITEM_NAME, MOUNT_EQUATORIAL_COORDINATES_DEC_ITEM_NAME }, (double []){ fmod(mount_ra() + 3, 24), 10 }));
	ASSERT_TRUE(WAIT_UNTIL(state(MOUNT, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME) == INDIGO_BUSY_STATE, 10));
	indigo_usleep(100000);
	clear_messages();
	unsigned before = revision(MOUNT, AGENT_START_PROCESS_PROPERTY_NAME);
	unsigned busy = 0;
	pthread_mutex_lock(&cache_mutex);
	observation *entry = find_observation(MOUNT, AGENT_START_PROCESS_PROPERTY_NAME);
	busy = entry ? entry->states[INDIGO_BUSY_STATE] : 0;
	pthread_mutex_unlock(&cache_mutex);
	ASSERT_TRUE(change_switch(MOUNT, AGENT_START_PROCESS_PROPERTY_NAME, AGENT_MOUNT_START_SYNC_ITEM_NAME, true));
	bool answered = WAIT_UNTIL(revision(MOUNT, AGENT_START_PROCESS_PROPERTY_NAME) > before, 5);
	if (!answered) {
		dump_messages();
	}
	ASSERT_TRUE(answered);
	ASSERT_EQ_INT(INDIGO_ALERT_STATE, state(MOUNT, AGENT_START_PROCESS_PROPERTY_NAME));
	ASSERT_TRUE(has_message("Mount is busy"));
	ASSERT_FALSE(switch_value(MOUNT, AGENT_START_PROCESS_PROPERTY_NAME, AGENT_MOUNT_START_SYNC_ITEM_NAME));
	pthread_mutex_lock(&cache_mutex);
	entry = find_observation(MOUNT, AGENT_START_PROCESS_PROPERTY_NAME);
	unsigned busy_after = entry ? entry->states[INDIGO_BUSY_STATE] : 0;
	pthread_mutex_unlock(&cache_mutex);
	ASSERT_EQ_INT(busy, busy_after);
	ASSERT_TRUE(WAIT_UNTIL(state(MOUNT_DEVICE, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME) != INDIGO_BUSY_STATE, 60));
}

static const indigo_test_case tests[] = {
	{ "mount simulator: sync refused near pole is reported failed", sync_refused_near_pole_is_reported_failed },
	{ "mount simulator: accepted sync is reported synced", accepted_sync_is_reported_synced },
	{ "mount simulator: accepted sync after a refused sync is reported synced", accepted_sync_after_refused_sync_is_reported_synced },
	{ "mount simulator: sync refused by a foreign slew is reported failed", sync_refused_by_a_foreign_slew_is_reported_failed },
	{ "mount simulator: process requested while the mount is busy is refused", process_requested_while_the_mount_is_busy_is_refused },
	{ "synscan: sync refused near pole is reported failed", sync_refused_near_pole_is_reported_failed },
	{ "synscan: accepted sync is reported synced", accepted_sync_is_reported_synced }
};

int main(int argc, char **argv) {
	setvbuf(stdout, NULL, _IONBF, 0);
	// a case is selected by its name, given as the argument or through INDIGO_TEST_CASE_FILTER
	const char *filter = argc > 1 ? argv[1] : getenv("INDIGO_TEST_CASE_FILTER");
	int result = 0, executed = 0, passed = 0;
	for (int i = 0; i < (int)ARRAY_SIZE(tests); i++) {
		if (filter != NULL && !strstr(tests[i].name, filter)) {
			continue;
		}
		executed++;
	}
	indigo_test_plan("Mount Agent with the mount simulator", executed, filter);
	for (int i = 0; i < (int)ARRAY_SIZE(tests); i++) {
		if (filter != NULL && !strstr(tests[i].name, filter)) {
			continue;
		}
		pid_t child = fork();
		if (child == 0) {
			alarm(300);
			if (!indigo_test_use_private_home()) {
				exit(1);
			}
			mount = !strncmp(tests[i].name, "synscan:", 8) ? &mount_synscan_case : &mount_simulator_case;
			bool ready = setup();
			int status = ready ? indigo_run_tests("Mount Agent with the mount simulator", tests + i, 1) : 1;
			cleanup();
			indigo_test_remove_private_home();
			exit(status || indigo_test_failures ? 1 : 0);
		}
		int status = -1;
		if (child < 0 || waitpid(child, &status, 0) != child || !WIFEXITED(status) || WEXITSTATUS(status)) {
			fprintf(stderr, "Failed case: %s (status %d)\n", tests[i].name, status);
			result = 1;
		} else {
			passed++;
		}
	}
	indigo_test_plan_recorded = false;
	printf("Mount Agent with the mount simulator: %d/%d cases passed (including cleanup)\n", passed, executed);
	return executed ? result : 2;
}
