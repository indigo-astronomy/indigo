// Code is generated by AI

// The production Mount Agent driving a mount over one in-process bus, every case in a forked child with
// its own bus and a private HOME: the mount simulator driver, and the SynScan driver connected to its
// host-side simulator. These are the mounts whose syncs go through the alignment model of the mount base
// driver. Covered: the result the agent reports for a sync that the base driver refuses within 5 degrees
// of the celestial pole, with the requested coordinates within the agent's target tolerance of the real
// pointing, for an accepted sync, and for an accepted sync that follows a refused one on a mount that keeps
// the ALERT of the refusal. The SynScan refused-sync case reproduced the original defect (a refused sync
// reported as synced, because the driver's next position poll published OK again within the agent's wait);
// a sync now publishes BUSY and indigo_update_coordinates() keeps the ALERT that ends it. The other cases pin
// the behaviour that the fix must keep.

