	QSI_CHECK_TRUE(connect_device(&ccd_case));
	qsi_fake_camera *camera = qsi_fake_camera_at(0);
	camera->fail.disconnect = 1;
	QSI_CHECK_TRUE(disconnect_device(&ccd_case));
	// The SDK still holds the camera because the vendor call failed.
	QSI_CHECK_EQ(0, qsi_fake_connected_index());
