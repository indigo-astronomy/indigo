// Replays a fixed scenario with SDK tracing enabled so the ordered interaction
// sequence of the original driver can be compared against the migrated one.
static int capture_reference_trace(const char *path) {
	// Everything before the "# connect ccd" marker is the discovery phase.
	trace_discovery = true;
	if (!fixture_start(1)) {
		fixture_stop();
		return 1;
	}
	qsi_fake_trace_record("# connect ccd");
	if (!connect_device(&ccd_case)) {
		fixture_stop();
		return 1;
	}
	use_raw_format();
	qsi_fake_trace_record("# connect wheel");
	if (!connect_device(&wheel_case)) {
		fixture_stop();
		return 1;
	}
	qsi_fake_trace_record("# move wheel");
	move_wheel(3);
	qsi_fake_trace_record("# configure frame");
	set_bin(2);
	set_frame(16, 8, 32, 24);
	expected_left = 16;
	expected_top = 8;
	expected_bin = 2;
	expected_image_width = 16;
	expected_image_height = 12;
	qsi_fake_trace_record("# expose");
	expose(0.05);
	qsi_fake_trace_record("# controls");
	set_switch(&ccd_case, READOUT_SPEED_PROPERTY_NAME, "FAST_READOUT");
	set_switch(&ccd_case, ANTI_BLOOM_PROPERTY_NAME, "HIGH");
	set_switch(&ccd_case, PRE_EXPOSURE_FLUSH_PROPERTY_NAME, "MODEST");
	set_switch(&ccd_case, FAN_MODE_PROPERTY_NAME, "FULL_SPEED");
	set_switch(&ccd_case, CCD_COOLER_PROPERTY_NAME, CCD_COOLER_ON_ITEM_NAME);
	qsi_fake_trace_record("# disconnect");
	disconnect_device(&wheel_case);
	disconnect_device(&ccd_case);
	bool ok = qsi_fake_trace_write(path);
	fixture_stop();
	printf("reference trace written to %s\n", path);
	return ok ? 0 : 1;
}

