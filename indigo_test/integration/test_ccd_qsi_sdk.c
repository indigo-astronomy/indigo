// The original driver attaches the wheel only while the camera is connected,
// the migrated driver attaches it at discovery. Both are satisfied by this
// count, which is asserted per driver where the difference matters.
static bool fixture_start(int camera_count) {
	reset_fake(camera_count);
	qsi_fake_trace_enable(trace_discovery);
	reset_simulator_context(&ccd_case);
	simulator_test_client.update_property = observe_image;
	if (indigo_start() != INDIGO_OK || indigo_attach_client(&simulator_test_client) != INDIGO_OK || indigo_ccd_qsi(INDIGO_DRIVER_INIT, NULL) != INDIGO_OK) {
		return false;
	}
	fixture_running = true;
	for (int i = 0; i < 400; i++) {
		if (atomic_load(&attached_count) >= camera_count) {
			return true;
		}
		indigo_usleep(10000);
	}
	return false;
}

static void fixture_stop(void) {
	if (!fixture_running) {
		return;
	}
	qsi_fake_gate_release();
	for (int i = 0; i < (int)(sizeof(logical_devices) / sizeof(logical_devices[0])); i++) {
		if (logical_devices[i] != NULL) {
			indigo_change_switch_property_1(&simulator_test_client, logical_devices[i]->name, CONNECTION_PROPERTY_NAME, CONNECTION_DISCONNECTED_ITEM_NAME, true);
		}
	}
	indigo_usleep(200000);
	indigo_ccd_qsi(INDIGO_DRIVER_SHUTDOWN, NULL);
	indigo_detach_client(&simulator_test_client);
	indigo_stop();
	release_cached_properties();
	fixture_running = false;
}

