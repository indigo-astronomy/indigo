// A camera that arrives while another one is connected cannot be probed, so the
// wheel is attached optimistically and its connection handler validates it.
static void qsi_wheel_connect_fails_without_filter_wheel(void) {
	QSI_CHECK_TRUE(fixture_start(1));
	QSI_CHECK_TRUE(connect_device(&ccd_case));
	qsi_fake_camera *second = qsi_fake_add_camera(1, CAMERA_1_SERIAL, CAMERA_1_DESC, CAMERA_1_MODEL);
	second->has_filter_wheel = false;
	second->filter_count = 0;
	configure_usb(1, QSI_VENDOR_ID, QSI_PRODUCT_ID2);
	fire_usb_event(1, LIBUSB_HOTPLUG_EVENT_DEVICE_ARRIVED);
	QSI_CHECK_TRUE(wait_attached(4));
	QSI_CHECK_TRUE(disconnect_device(&ccd_case));
	QSI_CHECK_TRUE(connect_device(&second_ccd_case));
	const simulator_driver_case second_wheel_case = { "QSI Camera", "indigo_ccd_qsi", CAMERA_1_DESC " (wheel) #" CAMERA_1_SERIAL, indigo_ccd_qsi, true, NULL, 0, NULL, 0, NULL, 0, NULL, 0 };
	select_device(&second_wheel_case);
	indigo_change_switch_property_1(&simulator_test_client, second_wheel_case.device_name, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, true);
	QSI_CHECK_TRUE(wait_for_property_state(CONNECTION_PROPERTY_NAME, INDIGO_ALERT_STATE));
	// The rejected wheel must not have torn down the camera connection.
	QSI_CHECK_EQ(1, qsi_fake_connected_index());
	QSI_CHECK_TRUE(disconnect_device(&second_ccd_case));
cleanup:
	fixture_stop();
}

