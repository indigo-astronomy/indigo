// A short exposure can leave BUSY before a state poll observes it, so both
// transitions are asserted through their recorded revisions.
static bool expose(double duration) {
	unsigned busy_revision = property_state_revision(CCD_EXPOSURE_PROPERTY_NAME, INDIGO_BUSY_STATE);
	unsigned ok_revision = property_state_revision(CCD_EXPOSURE_PROPERTY_NAME, INDIGO_OK_STATE);
	if (indigo_change_number_property_1(&simulator_test_client, ccd_case.device_name, CCD_EXPOSURE_PROPERTY_NAME, CCD_EXPOSURE_ITEM_NAME, duration) != INDIGO_OK) {
		return false;
	}
	return wait_for_property_state_seen_after(CCD_EXPOSURE_PROPERTY_NAME, INDIGO_BUSY_STATE, busy_revision) && wait_for_property_state_seen_after(CCD_EXPOSURE_PROPERTY_NAME, INDIGO_OK_STATE, ok_revision);
}

