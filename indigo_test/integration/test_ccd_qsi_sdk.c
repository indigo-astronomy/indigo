static indigo_result observe_image(indigo_client *client, indigo_device *device, indigo_property *property, const char *message) {
	if (!strcmp(property->device, ccd_case.device_name) && !strcmp(property->name, CCD_IMAGE_PROPERTY_NAME) && property->state == INDIGO_OK_STATE && property->count > 0 && property->items[0].blob.size > 0) {
		indigo_item *item = property->items;
		bool valid = item->blob.value != NULL && !strcmp(item->blob.format, ".raw") && item->blob.size >= (long)sizeof(indigo_raw_header);
		if (valid) {
			indigo_raw_header header;
			memcpy(&header, item->blob.value, sizeof(header));
			valid = header.signature == INDIGO_RAW_MONO16 && header.width == (uint32_t)expected_image_width && header.height == (uint32_t)expected_image_height && item->blob.size >= (long)(sizeof(header) + (size_t)header.width * header.height * 2);
			if (valid) {
				uint16_t *pixels = (uint16_t *)((unsigned char *)item->blob.value + sizeof(header));
				for (uint32_t y = 0; y < header.height && valid; y++) {
					for (uint32_t x = 0; x < header.width; x++) {
						unsigned sensor_x = (unsigned)(expected_left + (int)x * expected_bin);
						unsigned sensor_y = (unsigned)(expected_top + (int)y * expected_bin);
						if (pixels[y * header.width + x] != ccd_test_noise(sensor_y * SENSOR_WIDTH + sensor_x, (unsigned)expected_bin)) {
							valid = false;
							break;
						}
					}
				}
			}
		}
		atomic_fetch_add(&blob_count, 1);
		if (!valid) {
			atomic_fetch_add(&bad_blob, 1);
		}
	}
	return simulator_client_update_property(client, device, property, message);
}

