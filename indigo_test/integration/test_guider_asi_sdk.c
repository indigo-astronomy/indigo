		int opposite = direction == USB2ST4_NORTH ? USB2ST4_SOUTH : direction == USB2ST4_SOUTH ? USB2ST4_NORTH : direction == USB2ST4_EAST ? USB2ST4_WEST : USB2ST4_EAST;
