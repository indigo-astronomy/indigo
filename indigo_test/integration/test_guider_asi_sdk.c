#define ASI_TIMING_SAMPLE_COUNT 5

static int compare_double(const void *left, const void *right) {
	double a = *(const double *)left;
	double b = *(const double *)right;
	return (a > b) - (a < b);
}

static bool measure_timing(int direction, int duration, double *error) {
	double previous_on = asi_on_time[direction];
	pulse(&guider7, direction, duration);
	for (int i = 0; i < 2000 && asi_on_time[direction] == previous_on; i++) {
		indigo_usleep(1000);
	}
	if (asi_on_time[direction] == previous_on || !wait_relays(0) || asi_off_time[direction] <= asi_on_time[direction]) {
		return false;
	}
	*error = (asi_off_time[direction] - asi_on_time[direction]) * 1000 - duration;
	return true;
}

static void report_timing(int direction, int duration, double *errors) {
	double sorted[ASI_TIMING_SAMPLE_COUNT];
	double minimum = errors[0], maximum = errors[0], total = 0, maximum_absolute = 0;
	for (int i = 0; i < ASI_TIMING_SAMPLE_COUNT; i++) {
		sorted[i] = errors[i];
		minimum = fmin(minimum, errors[i]);
		maximum = fmax(maximum, errors[i]);
		maximum_absolute = fmax(maximum_absolute, fabs(errors[i]));
		total += errors[i];
	}
	double mean = total / ASI_TIMING_SAMPLE_COUNT;
	double variance = 0;
	for (int i = 0; i < ASI_TIMING_SAMPLE_COUNT; i++) {
		variance += (errors[i] - mean) * (errors[i] - mean);
	}
	qsort(sorted, ASI_TIMING_SAMPLE_COUNT, sizeof(double), compare_double);
	double median = sorted[ASI_TIMING_SAMPLE_COUNT / 2];
	double p95 = sorted[(int)ceil(0.95 * ASI_TIMING_SAMPLE_COUNT) - 1];
	double p99 = sorted[(int)ceil(0.99 * ASI_TIMING_SAMPLE_COUNT) - 1];
	static const char *names[] = { "NORTH", "SOUTH", "EAST", "WEST" };
	printf("%s requested=%dms samples=%d error_ms min=%.3f mean=%.3f median=%.3f p95=%.3f p99=%.3f max=%.3f stddev=%.3f max_abs=%.3f mean_percent=%.3f%%\n", names[direction], duration, ASI_TIMING_SAMPLE_COUNT, minimum, mean, median, p95, p99, maximum, sqrt(variance / ASI_TIMING_SAMPLE_COUNT), maximum_absolute, mean * 100 / duration);
}

static void timing_measurements(void) {
	ASSERT_TRUE(begin_driver(&guider7, 1));
	ASSERT_TRUE(connect_device(&guider7));
	const int durations[] = { 20, 100, 250, 500 };
	for (int direction = 0; direction < 4; direction++) {
		for (int d = 0; d < ARRAY_SIZE(durations); d++) {
			double ignored;
			ASSERT_TRUE(measure_timing(direction, durations[d], &ignored));
			double errors[ASI_TIMING_SAMPLE_COUNT];
			for (int i = 0; i < ASI_TIMING_SAMPLE_COUNT; i++) {
				ASSERT_TRUE(measure_timing(direction, durations[d], errors + i));
			}
			report_timing(direction, durations[d], errors);
		}
	}
	cleanup_driver();
}

