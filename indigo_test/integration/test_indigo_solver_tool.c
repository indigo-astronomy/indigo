// A patch of random catalog stars around (97.9°, 5.1°), indexed like indigo_solver_indexer does: all quads with
// their code variants, stored as the 5° Tycho-2 index
static bool write_synthetic_index(const char *path) {
	indigo_solver_star catalog[CATALOG_STAR_COUNT];
	ra0 = 97.9 * DEG_TO_RAD;
	dec0 = 5.1 * DEG_TO_RAD;
	for (int i = 0; i < CATALOG_STAR_COUNT; i++) {
		memset(catalog + i, 0, sizeof(indigo_solver_star));
		catalog[i].id = i;
		catalog[i].ra = ra0 + (frand() - 0.5) * 3.2 * DEG_TO_RAD;
		catalog[i].dec = dec0 + (frand() - 0.5) * 2.4 * DEG_TO_RAD;
		REQUIRE(indigo_radec_to_xy(ra0, dec0 + 0.4 * DEG_TO_RAD, 0, CATALOG_SCALE, 1000, 1000, -1, catalog[i].ra, catalog[i].dec, &catalog[i].x, &catalog[i].y));
	}
	int capacity = 40000, count = 0;
	indigo_solver_quad *quads = malloc(capacity * sizeof(indigo_solver_quad));
	for (int i = 0; i < CATALOG_STAR_COUNT; i++) {
		for (int j = i + 1; j < CATALOG_STAR_COUNT; j++) {
			for (int k = j + 1; k < CATALOG_STAR_COUNT; k++) {
				for (int l = k + 1; l < CATALOG_STAR_COUNT; l++) {
					if (count + INDIGO_SOLVER_MAX_QUAD_VARIANTS > capacity) {
						capacity *= 2;
						quads = realloc(quads, capacity * sizeof(indigo_solver_quad));
					}
					count += indigo_solver_make_quad_variants(quads + count, INDIGO_SOLVER_MAX_QUAD_VARIANTS, catalog + i, catalog + j, catalog + k, catalog + l);
				}
			}
		}
	}
	indigo_solver_catalog index;
	bool ok = indigo_solver_catalog_build(catalog, CATALOG_STAR_COUNT, quads, count, 5, &index) && indigo_solver_write_index(path, &index);
	indigo_solver_free_catalog(&index);
	free(quads);
	REQUIRE(ok);
	return true;
}

// A 16 bit mono RAW frame of the catalog patch: flat background with noise and gaussian stars
static indigo_raw_header *render_image(const char *index_path, long *size) {
	*size = sizeof(indigo_raw_header) + IMAGE_WIDTH * IMAGE_HEIGHT * 2;
	indigo_raw_header *image = calloc(1, *size);
	image->signature = INDIGO_RAW_MONO16;
	image->width = IMAGE_WIDTH;
	image->height = IMAGE_HEIGHT;
	uint16_t *pixels = (uint16_t *)(image + 1);
	for (long i = 0; i < IMAGE_WIDTH * IMAGE_HEIGHT; i++) {
		pixels[i] = 1000 + (int)(frand() * 40);
	}
	image_ra = ra0 + 0.1 * DEG_TO_RAD;
	image_dec = dec0 - 0.05 * DEG_TO_RAD;
	indigo_solver_catalog index;
	if (!indigo_solver_load_index(index_path, &index) || index.star_count != CATALOG_STAR_COUNT) {
		indigo_solver_free_catalog(&index);
		free(image);
		return NULL;
	}
	indigo_solver_index_star stars[CATALOG_STAR_COUNT];
	memcpy(stars, index.stars, sizeof(stars));
	indigo_solver_free_catalog(&index);
	for (int i = 0; i < CATALOG_STAR_COUNT; i++) {
		float x, y;
		if (indigo_radec_to_xy(image_ra, image_dec, IMAGE_ANGLE, IMAGE_SCALE, IMAGE_WIDTH, IMAGE_HEIGHT, -1, stars[i].ra, stars[i].dec, &x, &y)) {
			for (int dy = -6; dy <= 6; dy++) {
				for (int dx = -6; dx <= 6; dx++) {
					int px = (int)rint(x) + dx, py = (int)rint(y) + dy;
					if (px >= 0 && px < IMAGE_WIDTH && py >= 0 && py < IMAGE_HEIGHT) {
						float r2 = (px - x) * (px - x) + (py - y) * (py - y);
						int value = pixels[py * IMAGE_WIDTH + px] + (int)(30000 * exp(-r2 / (2 * 1.5 * 1.5)));
						pixels[py * IMAGE_WIDTH + px] = value > 65535 ? 65535 : value;
					}
				}
			}
		}
	}
	return image;
}

static bool write_file(const char *path, const void *data, long size) {
	FILE *file = fopen(path, "wb");
	REQUIRE(file != NULL);
	bool ok = fwrite(data, 1, size, file) == (size_t)size;
	fclose(file);
	REQUIRE(ok);
	return true;
}

static bool copy_file(const char *from, const char *to) {
	FILE *file = fopen(from, "rb");
	REQUIRE(file != NULL);
	fseek(file, 0, SEEK_END);
	long size = ftell(file);
	fseek(file, 0, SEEK_SET);
	char *data = malloc(size);
	bool ok = fread(data, 1, size, file) == (size_t)size;
	fclose(file);
	ok = ok && write_file(to, data, size);
	free(data);
	REQUIRE(ok);
	return true;
}

// -------------------------------------------------------------------------------- running the tool

// Runs the tool with the arguments, stdout and stderr captured together; INDIGO_CACHE_BASE always points into the
// private directory, so the default index directory never reaches the user's own cache
static bool run_tool(tool_run *run, const char *cache_base, const char *format, ...) {
	char arguments[2048], command[4096];
	va_list args;
	va_start(args, format);
	vsnprintf(arguments, sizeof(arguments), format, args);
	va_end(args);
	snprintf(command, sizeof(command), "INDIGO_CACHE_BASE='%s' '%s' %s 2>&1", cache_base, INDIGO_SOLVER_EXECUTABLE, arguments);
	FILE *pipe = popen(command, "r");
	REQUIRE(pipe != NULL);
	size_t length = fread(run->output, 1, sizeof(run->output) - 1, pipe);
	run->output[length] = 0;
	int status = pclose(pipe);
	REQUIRE(WIFEXITED(status));
	run->exit_code = WEXITSTATUS(status);
	return true;
}

static bool output_contains(tool_run *run, const char *text) {
	if (strstr(run->output, text) == NULL) {
		fprintf(stderr, "Expected '%s' in the output:\n%s\n", text, run->output);
		return false;
	}
	return true;
}

// The value following a label at the start of an output line
static bool output_value(tool_run *run, const char *label, double *value) {
	for (const char *line = run->output; line != NULL && *line; line = strchr(line, '\n') ? strchr(line, '\n') + 1 : NULL) {
		size_t length = strlen(label);
		if (!strncmp(line, label, length) && sscanf(line + length, "%lf", value) == 1) {
			return true;
		}
	}
	fprintf(stderr, "No '%s' value in the output:\n%s\n", label, run->output);
	return false;
}

// The output contains the texts in this order, each after the previous one
static bool output_in_order(tool_run *run, const char **texts, int count) {
	const char *position = run->output;
	for (int i = 0; i < count && position != NULL; i++) {
		position = strstr(position, texts[i]);
		if (position != NULL) {
			position += strlen(texts[i]);
		}
	}
	return position != NULL;
}

static bool parse_solution(tool_run *run, tool_solution *solution) {
	double parity;
	REQUIRE(output_value(run, "RA:", &solution->ra));
	REQUIRE(output_value(run, "Dec:", &solution->dec));
	REQUIRE(output_value(run, "Angle:", &solution->angle));
	REQUIRE(output_value(run, "Scale:", &solution->scale));
	REQUIRE(output_value(run, "Field:", &solution->width));
	REQUIRE(sscanf(strstr(run->output, "Field:") + 6, "%*f° x %lf", &solution->height) == 1);
	REQUIRE(output_value(run, "Parity:", &parity));
	solution->parity = (int)parity;
	return true;
}

// The solved frame: centre within tolerance (arcseconds) of the rendered one, scale, size, angle and parity
static bool solution_matches_frame(tool_run *run, double tolerance, double scale_tolerance) {
	tool_solution solution;
	REQUIRE(run->exit_code == 0);
	REQUIRE(output_contains(run, "Solved in "));
	REQUIRE(output_contains(run, " stars matched, rms "));
	REQUIRE(output_contains(run, "Epoch:    J2000"));
	REQUIRE(output_contains(run, "Index:    5° Tycho-2 (FOV 4.5° - 10°)"));
	REQUIRE(parse_solution(run, &solution));
	double distance = indigo_angular_distance(solution.ra * 15 * DEG_TO_RAD, solution.dec * DEG_TO_RAD, image_ra, image_dec) / ARCSEC_TO_RAD;
	if (distance >= tolerance) {
		fprintf(stderr, "Solved centre %.1f\" from the frame centre\n", distance);
	}
	REQUIRE(distance < tolerance);
	REQUIRE(fabs(solution.scale / (IMAGE_SCALE * RAD_TO_DEG) - 1) < scale_tolerance);
	REQUIRE(fabs(solution.width - IMAGE_WIDTH * solution.scale) < 1e-3);
	REQUIRE(fabs(solution.height - IMAGE_HEIGHT * solution.scale) < 1e-3);
	REQUIRE(fabs(solution.angle - IMAGE_ANGLE * RAD_TO_DEG) < 0.3);
	REQUIRE(solution.parity == -1);
	return true;
}

