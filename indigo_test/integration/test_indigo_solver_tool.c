// The JNow epoch reads the position hint in JNow and reports the solution in JNow
static void jnow_epoch_hint_and_solution(void) {
	tool_run run;
	double ra = (ra0 + 0.5 * DEG_TO_RAD) * RAD_TO_DEG / 15, dec = dec0 * RAD_TO_DEG;
	indigo_j2k_to_jnow(&ra, &dec);
	ASSERT_TRUE(run_tool(&run, empty_dir, "-i '%s' -D 1 -e 0 -r %.6f -d %.6f -R 2 '%s'", index_dir, ra, dec, raw_path));
	ASSERT_EQ_INT(0, run.exit_code);
	ASSERT_TRUE(output_contains(&run, "Epoch:    JNow"));
	tool_solution solution;
	ASSERT_TRUE(parse_solution(&run, &solution));
	double solved_ra = solution.ra, solved_dec = solution.dec;
	indigo_jnow_to_j2k(&solved_ra, &solved_dec);
	ASSERT_TRUE(indigo_angular_distance(solved_ra * 15 * DEG_TO_RAD, solved_dec * DEG_TO_RAD, image_ra, image_dec) < 10 * ARCSEC_TO_RAD);
	// the JNow centre differs from the J2000 one by the precession since 2000
	ASSERT_TRUE(indigo_angular_distance(solution.ra * 15 * DEG_TO_RAD, solution.dec * DEG_TO_RAD, image_ra, image_dec) > 60 * ARCSEC_TO_RAD);
}

