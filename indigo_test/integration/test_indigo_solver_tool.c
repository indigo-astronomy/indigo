// Without the scale the largest index is searched first, stage by stage: the first stage on every index, then the
// next stage in the opposite order starting with the index loaded last. Only the 5° index matches the frame; the
// depth 4 leaves the first stage without quads, so the 0.5° index is searched in the second stage before the 5° one
static void blind_search_goes_stage_by_stage(void) {
	tool_run run;
	ASSERT_TRUE(run_tool(&run, empty_dir, "-v -i '%s' -D 1 '%s'", two_index_dir, raw_path));
	ASSERT_TRUE(solution_matches_frame(&run, 10, 0.003));
	const char *first[] = { "Solving with index 5° Tycho-2 (FOV 4.5° - 10°)...\nStage 1:", "Solved in " };
	ASSERT_TRUE(output_in_order(&run, first, 2));
	ASSERT_FALSE(strstr(run.output, "Solving with index 0.5° Gaia DR3 (FOV 0.45° - 1°)") != NULL);
	ASSERT_TRUE(run_tool(&run, empty_dir, "-v -i '%s' -D 1 -t 4 '%s'", two_index_dir, raw_path));
	ASSERT_TRUE(solution_matches_frame(&run, 10, 0.003));
	const char *order[] = { "Solving with index 5° Tycho-2 (FOV 4.5° - 10°)", "Solving with index 0.5° Gaia DR3 (FOV 0.45° - 1°)", "Solving with index 0.5° Gaia DR3 (FOV 0.45° - 1°)", "Solving with index 5° Tycho-2 (FOV 4.5° - 10°)", "Stage 2:", "Solved in " };
	if (!output_in_order(&run, order, 6)) {
		fprintf(stderr, "Unexpected search order:\n%s\n", run.output);
	}
	ASSERT_TRUE(output_in_order(&run, order, 6));
	const char *three_times[] = { "Solving with index 5° Tycho-2 (FOV 4.5° - 10°)", "Solving with index 5° Tycho-2 (FOV 4.5° - 10°)", "Solving with index 5° Tycho-2 (FOV 4.5° - 10°)" };
	ASSERT_FALSE(output_in_order(&run, three_times, 3));
}

// With the scale every stage starts with the index nearest to 0.7 x the 3.6° x 2.7° frame, then the next nearest: of
// 0.5°, 2° and 5° it is 2° (2.16), which matches nothing, then 5° (log distance 0.84 against 1.46 of 0.5°), then 0.5°.
// The depth 4 leaves the first stage without quads, so every index is tried in it, and the second stage solves the
// frame with the 5° index after the 2° one, before the 0.5° index is tried again
static void scaled_search_uses_fitting_index_first(void) {
	tool_run run;
	ASSERT_TRUE(run_tool(&run, empty_dir, "-v -i '%s' -D 1 -t 4 -s %.8f '%s'", three_index_dir, IMAGE_SCALE * RAD_TO_DEG, raw_path));
	ASSERT_TRUE(solution_matches_frame(&run, 10, 0.003));
	const char *order[] = { "Solving with index 2° Tycho-2 (FOV 2° - 4.5°)", "Solving with index 5° Tycho-2 (FOV 4.5° - 10°)", "Solving with index 0.5° Gaia DR3 (FOV 0.45° - 1°)", "Solving with index 2° Tycho-2 (FOV 2° - 4.5°)", "Stage 2:", "Solving with index 5° Tycho-2 (FOV 4.5° - 10°)", "Stage 2:", "Solved in " };
	if (!output_in_order(&run, order, 8)) {
		fprintf(stderr, "Unexpected search order:\n%s\n", run.output);
	}
	ASSERT_TRUE(output_in_order(&run, order, 8));
	const char *gaia_twice[] = { "Solving with index 0.5° Gaia DR3 (FOV 0.45° - 1°)", "Solving with index 0.5° Gaia DR3 (FOV 0.45° - 1°)" };
	ASSERT_FALSE(output_in_order(&run, gaia_twice, 2));
	const char *two_three_times[] = { "Solving with index 2° Tycho-2 (FOV 2° - 4.5°)", "Solving with index 2° Tycho-2 (FOV 2° - 4.5°)", "Solving with index 2° Tycho-2 (FOV 2° - 4.5°)" };
	ASSERT_FALSE(output_in_order(&run, two_three_times, 3));
}

// -x restricts the indexes, only uninstalled ones leave nothing to solve with; the CPU limit 0 means no limit
static void index_selection_and_cpu_limit(void) {
	tool_run run;
	ASSERT_TRUE(run_tool(&run, empty_dir, "-i '%s' -D 1 -x 5 -c 0 '%s'", index_dir, raw_path));
	ASSERT_TRUE(solution_matches_frame(&run, 10, 0.003));
	ASSERT_TRUE(run_tool(&run, empty_dir, "-i '%s' -x 10,20 '%s'", index_dir, raw_path));
	ASSERT_EQ_INT(1, run.exit_code);
	ASSERT_TRUE(output_contains(&run, "Not solved: No index files found"));
}

// Wrong switches and values are refused with exit code 2 before anything is read
static void invalid_arguments_are_refused(void) {
	static const struct {
		const char *arguments;
		const char *message;
	} cases[] = {
		{ "-p 2", "invalid value '2' for '-p'" },
		{ "-p 0.5", "invalid value '0.5' for '-p'" },
		{ "-D 0", "invalid value '0' for '-D'" },
		{ "-D 17", "invalid value '17' for '-D'" },
		{ "-t -1", "invalid value '-1' for '-t'" },
		{ "-s -0.1", "invalid value '-0.1' for '-s'" },
		{ "-s abc", "invalid value 'abc' for '-s'" },
		{ "-r 24", "invalid value '24' for '-r'" },
		{ "-r 1:x", "invalid value '1:x' for '-r'" },
		{ "-d 91", "invalid value '91' for '-d'" },
		{ "-R -1", "invalid value '-1' for '-R'" },
		{ "-e 1950", "invalid value '1950' for '-e'" },
		{ "-c -5", "invalid value '-5' for '-c'" },
		{ "-x 3", "unknown index scale '3'" },
		{ "-R 2", "the search radius needs both the RA and the Dec hint" },
		{ "-R 2 -r 6", "the search radius needs both the RA and the Dec hint" },
		{ "-q 1", "unknown option '-q'" },
	};
	tool_run run;
	for (unsigned i = 0; i < sizeof(cases) / sizeof(cases[0]); i++) {
		ASSERT_TRUE(run_tool(&run, empty_dir, "-i '%s' %s '%s'", index_dir, cases[i].arguments, raw_path));
		if (run.exit_code != 2) {
			fprintf(stderr, "Arguments '%s'\n", cases[i].arguments);
		}
		ASSERT_EQ_INT(2, run.exit_code);
		ASSERT_TRUE(output_contains(&run, cases[i].message));
	}
	ASSERT_TRUE(run_tool(&run, empty_dir, "-i '%s' '%s' '%s'", index_dir, raw_path, fits_path));
	ASSERT_EQ_INT(2, run.exit_code);
	ASSERT_TRUE(output_contains(&run, "only one image file can be solved"));
	ASSERT_TRUE(run_tool(&run, empty_dir, "-i '%s' '%s' -D", index_dir, raw_path));
	ASSERT_EQ_INT(2, run.exit_code);
	ASSERT_TRUE(output_contains(&run, "unknown option or missing value for '-D'"));
	ASSERT_TRUE(run_tool(&run, empty_dir, "-i '%s' -v", index_dir));
	ASSERT_EQ_INT(2, run.exit_code);
	ASSERT_TRUE(output_contains(&run, "no image file given"));
}

// A missing file and a file that is no image are not solved; the library log stays quiet without -v
static void unreadable_and_unsupported_files_fail(void) {
	tool_run run;
	char missing[PATH_MAX + 16];
	snprintf(missing, sizeof(missing), "%s/missing.raw", work_dir);
	ASSERT_TRUE(run_tool(&run, empty_dir, "-i '%s' '%s'", index_dir, missing));
	ASSERT_EQ_INT(1, run.exit_code);
	ASSERT_TRUE(output_contains(&run, "can't open"));
	ASSERT_TRUE(run_tool(&run, empty_dir, "-i '%s' '%s'", index_dir, text_path));
	ASSERT_EQ_INT(1, run.exit_code);
	ASSERT_TRUE(output_contains(&run, "Not solved: Unsupported image format"));
	ASSERT_FALSE(strstr(run.output, "libraw") != NULL);
	ASSERT_TRUE(run_tool(&run, empty_dir, "-v -i '%s' '%s'", index_dir, text_path));
	ASSERT_EQ_INT(1, run.exit_code);
	ASSERT_TRUE(output_contains(&run, "libraw"));
}

