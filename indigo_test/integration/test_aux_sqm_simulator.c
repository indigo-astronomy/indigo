static void simulator_path(const external_serial_simulator *simulator, const char *suffix, char *path, size_t size) {
	snprintf(path, size, "%s.%s", simulator->ready_file, suffix);
}

// One control line is armed at a time and consumed by the next command whose first character
// matches the selector, so a fault can be aimed at the reading without disturbing the handshake.
static bool arm_control(const external_serial_simulator *simulator, const char *action, const char *selector, const char *value) {
	char path[PATH_MAX];
	simulator_path(simulator, "control", path, sizeof(path));
	FILE *file = fopen(path, "w");
	if (file == NULL) {
		return false;
	}
	fprintf(file, "%s %s %s\n", action, selector, value == NULL ? "" : value);
	return fclose(file) == 0;
}

static void clear_events(const external_serial_simulator *simulator) {
	char path[PATH_MAX];
	simulator_path(simulator, "events", path, sizeof(path));
	unlink(path);
}

static int event_count(const external_serial_simulator *simulator, const char *command) {
	char path[PATH_MAX];
	char line[64];
	int count = 0;
	simulator_path(simulator, "events", path, sizeof(path));
	FILE *file = fopen(path, "r");
	if (file == NULL) {
		return 0;
	}
	while (fgets(line, sizeof(line), file) != NULL) {
		line[strcspn(line, "\r\n")] = '\0';
		if (!strcmp(line, command)) {
			count++;
		}
	}
	fclose(file);
	return count;
}

static bool wait_for_events(const external_serial_simulator *simulator, const char *command, int expected_count, int seconds) {
	for (int i = 0; i < seconds * 10; i++) {
		if (event_count(simulator, command) >= expected_count) {
			return true;
		}
		indigo_usleep(100000);
	}
	fprintf(stderr, "'%s' was recorded %d times in %ds, expected %d\n", command, event_count(simulator, command), seconds, expected_count);
	return false;
}

// The first command of the handshake and the first reading are recorded as "i" and "r", because
// the simulator strips the terminating 'x' of every SQM command.
static bool first_events_are(const external_serial_simulator *simulator, const char * const *commands, int count) {
	char path[PATH_MAX];
	char line[64];
	simulator_path(simulator, "events", path, sizeof(path));
	FILE *file = fopen(path, "r");
	if (file == NULL) {
		fprintf(stderr, "no command was recorded\n");
		return false;
	}
	bool matched = true;
	for (int i = 0; i < count; i++) {
		if (fgets(line, sizeof(line), file) == NULL) {
			fprintf(stderr, "command %d is missing, expected '%s'\n", i, commands[i]);
			matched = false;
			break;
		}
		line[strcspn(line, "\r\n")] = '\0';
		if (strcmp(line, commands[i])) {
			fprintf(stderr, "command %d is '%s', expected '%s'\n", i, line, commands[i]);
			matched = false;
			break;
		}
	}
	fclose(file);
	return matched;
}

