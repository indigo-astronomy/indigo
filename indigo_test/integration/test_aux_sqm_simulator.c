// Driver metadata, the published property inventory before and after connection, the handshake
// order, and every field of the documented record mapped to its item.
static void identity_inventory_and_reading_contract(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	indigo_driver_info info;
	memset(&info, 0, sizeof(info));
	assert_simulator_driver_info(&sqm_case);
	SERIAL_CHECK_TRUE(start_external_serial_simulator(&simulator, AUX_SQM_SIMULATOR_EXECUTABLE));
	SERIAL_CHECK_TRUE(bring_up_serial_driver(&sqm_case));
	online = true;
	enumerate_simulator_device();
	assert_device_interface(INDIGO_INTERFACE_AUX_SQM);
	assert_defined_properties(sqm_base_properties, ARRAY_SIZE(sqm_base_properties));
	assert_not_defined_properties(sqm_hidden_properties, ARRAY_SIZE(sqm_hidden_properties));
	assert_not_defined_properties(sqm_connected_properties, ARRAY_SIZE(sqm_connected_properties));
	assert_defined_property_count(ARRAY_SIZE(sqm_base_properties));
	clear_events(&simulator);
	SERIAL_CHECK_TRUE(connect_serial_device(&sqm_case, simulator.port));
	assert_serial_aux_class_property_completeness();
	assert_defined_properties(sqm_connected_properties, ARRAY_SIZE(sqm_connected_properties));
	assert_not_defined_properties(sqm_hidden_properties, ARRAY_SIZE(sqm_hidden_properties));
	assert_defined_property_count(ARRAY_SIZE(sqm_base_properties) + ARRAY_SIZE(sqm_connected_properties));
	SERIAL_CHECK_TRUE(wait_for_property_state(AUX_WEATHER_PROPERTY_NAME, INDIGO_OK_STATE));
	indigo_property *weather = find_cached_property(AUX_WEATHER_PROPERTY_NAME);
	indigo_property *aux_info = find_cached_property(AUX_INFO_PROPERTY_NAME);
	SERIAL_CHECK_TRUE(weather != NULL && weather->type == INDIGO_NUMBER_VECTOR && weather->perm == INDIGO_RO_PERM && weather->count == 3);
	SERIAL_CHECK_TRUE(aux_info != NULL && aux_info->type == INDIGO_NUMBER_VECTOR && aux_info->perm == INDIGO_RO_PERM && aux_info->count == 3);
	static const char *weather_items[] = {
		AUX_WEATHER_SKY_BRIGHTNESS_ITEM_NAME,
		AUX_WEATHER_SKY_TEMPERATURE_ITEM_NAME,
		AUX_WEATHER_SKY_BORTLE_CLASS_ITEM_NAME
	};
	static const char *info_items[] = {
		X_AUX_SENSOR_FREQUENCY_ITEM_NAME,
		X_AUX_SENSOR_COUNTS_ITEM_NAME,
		X_AUX_SENSOR_PERIOD_ITEM_NAME
	};
	assert_property_has_items(AUX_WEATHER_PROPERTY_NAME, weather_items, ARRAY_SIZE(weather_items));
	assert_property_has_items(AUX_INFO_PROPERTY_NAME, info_items, ARRAY_SIZE(info_items));
	// "ix" establishes the protocol, "rx" is the first reading; nothing else is sent.
	static const char *handshake[] = { "i", "r" };
	SERIAL_CHECK_TRUE(first_events_are(&simulator, handshake, ARRAY_SIZE(handshake)));
	// Table 8.3: " 20.70m,0000022921Hz,0000000020c,0000000.000s, 039.4C".
	SERIAL_CHECK_TRUE(number_is(AUX_WEATHER_PROPERTY_NAME, AUX_WEATHER_SKY_BRIGHTNESS_ITEM_NAME, 20.70, 0.011));
	SERIAL_CHECK_TRUE(number_is(AUX_WEATHER_PROPERTY_NAME, AUX_WEATHER_SKY_TEMPERATURE_ITEM_NAME, 39.4, 1e-6));
	SERIAL_CHECK_TRUE(number_is(AUX_WEATHER_PROPERTY_NAME, AUX_WEATHER_SKY_BORTLE_CLASS_ITEM_NAME, 4.5, 1e-6));
	SERIAL_CHECK_TRUE(number_is(AUX_INFO_PROPERTY_NAME, X_AUX_SENSOR_FREQUENCY_ITEM_NAME, 22921, 1e-6));
	SERIAL_CHECK_TRUE(number_is(AUX_INFO_PROPERTY_NAME, X_AUX_SENSOR_COUNTS_ITEM_NAME, 20, 1.01));
	SERIAL_CHECK_TRUE(number_is(AUX_INFO_PROPERTY_NAME, X_AUX_SENSOR_PERIOD_ITEM_NAME, 0, 1e-6));
	SERIAL_CHECK_EQ_INT(INDIGO_OK, sqm_case.entry(INDIGO_DRIVER_INFO, &info));
	SERIAL_CHECK_EQ_INT(INDIGO_DRIVER_API_3, INDIGO_DRIVER_API_GENERATION(info.version));
cleanup:
	if (online) {
		stop_serial_driver(&sqm_case);
	}
	stop_external_serial_simulator(&simulator);
}

// The Bortle class published alongside the reading has to be derived from the reading itself, at
// both ends of the scale and across a boundary, and a negative reading has to survive the record's
// sign column.
static void bortle_class_follows_the_reading(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	static const struct { const char *reading; double brightness; double bortle; } points[] = {
		{ "21.90", 21.90, 1 },
		{ "21.40", 21.40, 3 },
		{ "20.70", 20.70, 4.5 },
		{ "18.20", 18.20, 7 },
		{ "-5.20", -5.20, 9 }
	};
	SERIAL_CHECK_TRUE(start_external_serial_simulator(&simulator, AUX_SQM_SIMULATOR_EXECUTABLE));
	SERIAL_CHECK_TRUE(bring_up_serial_driver(&sqm_case));
	online = true;
	enumerate_simulator_device();
	for (int i = 0; i < ARRAY_SIZE(points); i++) {
		SERIAL_CHECK_TRUE(arm_control(&simulator, "reading", "r", points[i].reading));
		SERIAL_CHECK_TRUE(connect_serial_device(&sqm_case, simulator.port));
		SERIAL_CHECK_TRUE(wait_for_property_state(AUX_WEATHER_PROPERTY_NAME, INDIGO_OK_STATE));
		SERIAL_CHECK_TRUE(number_is(AUX_WEATHER_PROPERTY_NAME, AUX_WEATHER_SKY_BRIGHTNESS_ITEM_NAME, points[i].brightness, 1e-6));
		SERIAL_CHECK_TRUE(number_is(AUX_WEATHER_PROPERTY_NAME, AUX_WEATHER_SKY_BORTLE_CLASS_ITEM_NAME, points[i].bortle, 1e-6));
		disconnect_serial_device(&sqm_case);
	}
cleanup:
	if (online) {
		disconnect_serial_device(&sqm_case);
		tear_down_serial_driver(&sqm_case);
	}
	stop_external_serial_simulator(&simulator);
}

// A handshake the driver cannot accept must leave the device disconnected with the port released,
// and must not prevent a later connection from succeeding.
static void handshake_failures_leave_the_device_disconnected(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	static const char *faults[] = { "drop", "prefix", "short" };
	SERIAL_CHECK_TRUE(start_external_serial_simulator(&simulator, AUX_SQM_SIMULATOR_EXECUTABLE));
	SERIAL_CHECK_TRUE(bring_up_serial_driver(&sqm_case));
	online = true;
	enumerate_simulator_device();
	SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_change_text_property_1_raw(&simulator_test_client, sqm_case.device_name, DEVICE_PORT_PROPERTY_NAME, DEVICE_PORT_ITEM_NAME, "/dev/indigo-nonexistent-sqm-test"));
	unsigned int revision = property_revision(CONNECTION_PROPERTY_NAME);
	SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_change_switch_property_1(&simulator_test_client, sqm_case.device_name, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, true));
	SERIAL_CHECK_TRUE(wait_for_property_state_seen_after(CONNECTION_PROPERTY_NAME, INDIGO_ALERT_STATE, revision));
	SERIAL_CHECK_TRUE(!context.connected);
	SERIAL_CHECK_TRUE(connected_properties_published(false));
	for (int i = 0; i < ARRAY_SIZE(faults); i++) {
		printf("  refusing handshake %s\n", faults[i]);
		SERIAL_CHECK_TRUE(arm_control(&simulator, faults[i], "i", NULL));
		SERIAL_CHECK_TRUE(!connect_serial_device(&sqm_case, simulator.port));
		SERIAL_CHECK_TRUE(wait_for_property_state(CONNECTION_PROPERTY_NAME, INDIGO_ALERT_STATE));
		SERIAL_CHECK_TRUE(!context.connected);
		assert_switch_item_value(CONNECTION_PROPERTY_NAME, CONNECTION_DISCONNECTED_ITEM_NAME, true);
		SERIAL_CHECK_TRUE(connected_properties_published(false));
	}
	SERIAL_CHECK_TRUE(connect_serial_device(&sqm_case, simulator.port));
	SERIAL_CHECK_TRUE(wait_for_property_state(AUX_WEATHER_PROPERTY_NAME, INDIGO_OK_STATE));
cleanup:
	if (online) {
		disconnect_serial_device(&sqm_case);
		tear_down_serial_driver(&sqm_case);
	}
	stop_external_serial_simulator(&simulator);
}

// A reading the driver cannot parse must be reported on both published properties rather than
// accepted. The first poll runs immediately after connect, so each fault is aimed at it.
static void unparseable_readings_are_reported(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	static const char *faults[] = { "drop", "prefix", "short", "nan", "garbage" };
	SERIAL_CHECK_TRUE(start_external_serial_simulator(&simulator, AUX_SQM_SIMULATOR_EXECUTABLE));
	SERIAL_CHECK_TRUE(bring_up_serial_driver(&sqm_case));
	online = true;
	enumerate_simulator_device();
	for (int i = 0; i < ARRAY_SIZE(faults); i++) {
		printf("  reporting reading %s\n", faults[i]);
		SERIAL_CHECK_TRUE(arm_control(&simulator, faults[i], "r", NULL));
		// The handshake is untouched, so the device still connects.
		SERIAL_CHECK_TRUE(connect_serial_device(&sqm_case, simulator.port));
		SERIAL_CHECK_TRUE(wait_for_property_state(AUX_WEATHER_PROPERTY_NAME, INDIGO_ALERT_STATE));
		SERIAL_CHECK_TRUE(wait_for_property_state(AUX_INFO_PROPERTY_NAME, INDIGO_ALERT_STATE));
		SERIAL_CHECK_TRUE(context.connected);
		disconnect_serial_device(&sqm_case);
	}
	// The leftover of a truncated record must not be mistaken for the next one.
	SERIAL_CHECK_TRUE(connect_serial_device(&sqm_case, simulator.port));
	SERIAL_CHECK_TRUE(wait_for_property_state(AUX_WEATHER_PROPERTY_NAME, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(number_is(AUX_INFO_PROPERTY_NAME, X_AUX_SENSOR_FREQUENCY_ITEM_NAME, 22921, 1e-6));
cleanup:
	if (online) {
		disconnect_serial_device(&sqm_case);
		tear_down_serial_driver(&sqm_case);
	}
	stop_external_serial_simulator(&simulator);
}

// The meter never reports on its own, so the driver has to keep asking, and both published
// properties have to carry each new reading.
static void readings_are_refreshed_by_polling(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_external_serial_simulator(&simulator, AUX_SQM_SIMULATOR_EXECUTABLE));
	SERIAL_CHECK_TRUE(start_serial_driver(&sqm_case, simulator.port));
	online = true;
	SERIAL_CHECK_TRUE(wait_for_events(&simulator, "r", 1, 5));
	SERIAL_CHECK_TRUE(wait_for_property_state(AUX_WEATHER_PROPERTY_NAME, INDIGO_OK_STATE));
	unsigned int weather_revision = property_state_revision(AUX_WEATHER_PROPERTY_NAME, INDIGO_OK_STATE);
	unsigned int info_revision = property_state_revision(AUX_INFO_PROPERTY_NAME, INDIGO_OK_STATE);
	double first = cached_number_value(AUX_WEATHER_PROPERTY_NAME, AUX_WEATHER_SKY_BRIGHTNESS_ITEM_NAME);
	double first_counts = cached_number_value(AUX_INFO_PROPERTY_NAME, X_AUX_SENSOR_COUNTS_ITEM_NAME);
	// The second reading can only come from the rescheduled poll.
	SERIAL_CHECK_TRUE(wait_for_events(&simulator, "r", 2, SQM_POLL_SECONDS + 5));
	SERIAL_CHECK_TRUE(wait_for_property_state_after(AUX_WEATHER_PROPERTY_NAME, INDIGO_OK_STATE, weather_revision));
	SERIAL_CHECK_TRUE(property_state_revision(AUX_INFO_PROPERTY_NAME, INDIGO_OK_STATE) > info_revision);
	double second = cached_number_value(AUX_WEATHER_PROPERTY_NAME, AUX_WEATHER_SKY_BRIGHTNESS_ITEM_NAME);
	double second_counts = cached_number_value(AUX_INFO_PROPERTY_NAME, X_AUX_SENSOR_COUNTS_ITEM_NAME);
	printf("  brightness %g -> %g, counts %g -> %g\n", first, second, first_counts, second_counts);
	SERIAL_CHECK_TRUE(second < first && second_counts > first_counts);
	// One handshake for the whole session, whatever the number of readings.
	SERIAL_CHECK_EQ_INT(1, event_count(&simulator, "i"));
cleanup:
	if (online) {
		stop_serial_driver(&sqm_case);
	}
	stop_external_serial_simulator(&simulator);
}

// A failed reading must not stop the poll, and the poll must stop once the device is disconnected.
static void a_failed_poll_recovers_and_polling_stops_on_disconnect(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_external_serial_simulator(&simulator, AUX_SQM_SIMULATOR_EXECUTABLE));
	SERIAL_CHECK_TRUE(start_serial_driver(&sqm_case, simulator.port));
	online = true;
	SERIAL_CHECK_TRUE(wait_for_property_state(AUX_WEATHER_PROPERTY_NAME, INDIGO_OK_STATE));
	unsigned int revision = property_revision(AUX_WEATHER_PROPERTY_NAME);
	SERIAL_CHECK_TRUE(arm_control(&simulator, "garbage", "r", NULL));
	SERIAL_CHECK_TRUE(wait_for_property_state_after(AUX_WEATHER_PROPERTY_NAME, INDIGO_ALERT_STATE, revision));
	SERIAL_CHECK_TRUE(context.connected);
	revision = property_revision(AUX_WEATHER_PROPERTY_NAME);
	SERIAL_CHECK_TRUE(wait_for_property_state_after(AUX_WEATHER_PROPERTY_NAME, INDIGO_OK_STATE, revision));
	disconnect_serial_device(&sqm_case);
	SERIAL_CHECK_TRUE(connected_properties_published(false));
	clear_events(&simulator);
	// Nothing may reach the device after the port is closed.
	indigo_usleep((SQM_POLL_SECONDS + 2) * 1000000L);
	SERIAL_CHECK_EQ_INT(0, event_count(&simulator, "r"));
cleanup:
	if (online) {
		disconnect_serial_device(&sqm_case);
		tear_down_serial_driver(&sqm_case);
	}
	stop_external_serial_simulator(&simulator);
}

