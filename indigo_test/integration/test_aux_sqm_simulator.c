static bool number_is(const char *property_name, const char *item_name, double expected, double tolerance) {
	double value = cached_number_value(property_name, item_name);
	if (fabs(value - expected) > tolerance) {
		fprintf(stderr, "%s.%s is %g, expected %g\n", property_name, item_name, value, expected);
		return false;
	}
	return true;
}

static bool connected_properties_published(bool expected) {
	for (int i = 0; i < ARRAY_SIZE(sqm_connected_properties); i++) {
		if ((find_cached_property(sqm_connected_properties[i]) != NULL) != expected) {
			fprintf(stderr, "%s is %spublished\n", sqm_connected_properties[i], expected ? "not " : "");
			return false;
		}
	}
	return true;
}

