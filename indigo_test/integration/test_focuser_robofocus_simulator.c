static uint8_t frame_checksum(const uint8_t *frame) {
	unsigned sum = 0;
	for (int i = 0; i < 8; i++) sum += frame[i];
	return (uint8_t)sum;
}

static bool protocol_exchange(indigo_uni_handle *handle, const char payload[8], char expected, int *ticks) {
	uint8_t request[9], response[9];
	memcpy(request, payload, 8);
	request[8] = frame_checksum(request);
	if (indigo_uni_write(handle, (char *)request, 9) != 9) return false;
	for (;;) {
		if (indigo_uni_wait_for_data(handle, INDIGO_DELAY(2)) <= 0 || indigo_uni_read_available(handle, response, 1) != 1) return false;
		if (response[0] == 'I' || response[0] == 'O') {
			if (ticks) (*ticks)++;
			continue;
		}
		if (response[0] != 'F') return false;
		for (int i = 1; i < 9; i++) {
			if (indigo_uni_wait_for_data(handle, INDIGO_DELAY(.2)) <= 0 || indigo_uni_read_available(handle, response + i, 1) != 1) return false;
		}
		return response[1] == (uint8_t)expected && response[8] == frame_checksum(response);
	}
}

