static int request_count(char command, int value) {
	FILE *file = fopen(event_path, "r");
	if (!file) {
		return -1;
	}
	char line[512], kind[16];
	double timestamp;
	int count = 0;
	while (fgets(line, sizeof(line), file)) {
		unsigned byte[9];
		if (sscanf(line, "%lf %15s %x %x %x %x %x %x %x %x %x", &timestamp, kind, byte, byte + 1, byte + 2, byte + 3, byte + 4, byte + 5, byte + 6, byte + 7, byte + 8) == 11 && !strcmp(kind, "RX") && byte[0] == 'F' && byte[1] == (unsigned char)command) {
			int actual = 0;
			bool digits = true;
			for (int i = 2; i < 8; i++) {
				if (byte[i] < '0' || byte[i] > '9') {
					digits = false;
					break;
				}
				actual = actual * 10 + (int)byte[i] - '0';
			}
			if (value < 0 || (digits && actual == value)) {
				count++;
			}
		}
	}
	fclose(file);
	return count;
}

// Carriage returns are the stop command; the simulator logs every one, also while idle.
static int event_count(const char *wanted) {
	FILE *file = fopen(event_path, "r");
	if (!file) {
		return -1;
	}
	char line[512], kind[16];
	double timestamp;
	int count = 0;
	while (fgets(line, sizeof(line), file)) {
		if (sscanf(line, "%lf %15s", &timestamp, kind) == 2 && !strcmp(kind, wanted)) {
			count++;
		}
	}
	fclose(file);
	return count;
}

