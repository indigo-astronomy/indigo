static void mask_digits(char *text) {
	char *output = text;
	for (char *input = text; *input; input++) {
		if (*input >= '0' && *input <= '9') {
			if (output == text || output[-1] != '#') {
				*output++ = '#';
			}
		} else if (*input == '.' && output > text && output[-1] == '#' && input[1] >= '0' && input[1] <= '9') {
			// a stop azimuth may or may not have a fractional part
			continue;
		} else {
			*output++ = *input;
		}
	}
	*output = 0;
}

static void trace_append(const char *line) {
	int written = snprintf(trace_text + trace_length, sizeof(trace_text) - trace_length, "%s\n", line);
	if (written > 0 && trace_length + written < sizeof(trace_text)) {
		trace_length += written;
	}
}

static bool wait_poll_boundary(void) {
	if (!wait_polls(1, 5)) {
		return false;
	}
	int count = load_events();
	int polls = 0;
	for (int i = 0; i < count; i++) {
		polls += !strcmp(events[i].kind, "RX") && !strcmp(events[i].text, "d#get_eme");
	}
	trace_mark = poll_end_index(count, polls);
	return trace_mark >= 0;
}

static void trace_begin(bool polling) {
	if (polling) {
		wait_poll_boundary();
	} else {
		trace_mark = load_events();
	}
	pthread_mutex_lock(&observe_mutex);
	trace_pending_length = 0;
	*trace_pending = 0;
	for (int i = 0; i < observed_count; i++) {
		*observed[i].last_trace = 0;
	}
	pthread_mutex_unlock(&observe_mutex);
	atomic_store(&trace_active, true);
}

// A status poll is the reply sequence of d#getazim, d#getshut, d#getflap, d#get_eme; consecutive identical polls collapse
static bool poll_at(int count, int index, char *line, size_t size) {
	static const char * const requests[] = { "d#getazim", "d#getshut", "d#getflap", "d#get_eme" };
	if (index + 8 > count) {
		return false;
	}
	size_t length = (size_t)snprintf(line, size, "S POLL");
	for (int i = 0; i < 4; i++) {
		sim_event *request = events + index + 2 * i, *reply = request + 1;
		if (strcmp(request->kind, "RX") || strcmp(request->text, requests[i]) || strcmp(reply->kind, "TX")) {
			return false;
		}
		char text[64];
		snprintf(text, sizeof(text), "%s", reply->text);
		if (i < 2) {
			mask_digits(text);
		}
		length += (size_t)snprintf(line + length, size - length, " %s", text);
	}
	return true;
}

static bool trace_end(const char *step, bool polling, bool mask) {
	char line[256], previous_poll[256] = "";
	bool ok = polling ? wait_polls(1, 6) : (indigo_usleep(1500000), true);
	int count = load_events();
	if (polling) {
		int polls = 0;
		for (int i = 0; i < count; i++) {
			polls += !strcmp(events[i].kind, "RX") && !strcmp(events[i].text, "d#get_eme");
		}
		int end = poll_end_index(count, polls);
		count = end >= 0 ? end : count;
	}
	snprintf(line, sizeof(line), "## %s", step);
	trace_append(line);
	for (int i = trace_mark; i < count; i++) {
		if (poll_at(count, i, line, sizeof(line))) {
			if (strcmp(line, previous_poll)) {
				trace_append(line);
				snprintf(previous_poll, sizeof(previous_poll), "%s", line);
			}
			i += 7;
			continue;
		}
		if (strcmp(events[i].kind, "RX") && strcmp(events[i].kind, "TX") && strcmp(events[i].kind, "FAULT")) {
			continue;
		}
		if (mask && is_poll_request(events[i].text) && i + 1 < count && !strcmp(events[i + 1].kind, "TX")) {
			// incomplete polls around an asynchronous abort are timing dependent
			i++;
			continue;
		}
		*previous_poll = 0;
		snprintf(line, sizeof(line), "S %s %s", events[i].kind, events[i].text);
		if (mask && !strcmp(events[i].kind, "TX")) {
			mask_digits(line);
		}
		trace_append(line);
	}
	atomic_store(&trace_active, false);
	pthread_mutex_lock(&observe_mutex);
	if (mask) {
		// publications around an asynchronous abort are timing dependent: keep first occurrences only
		static char unique[sizeof(trace_pending) + 2];
		size_t unique_length = 1;
		mask_digits(trace_pending);
		unique[0] = '\n';
		unique[1] = 0;
		for (char *line_start = trace_pending, *line_end; (line_end = strchr(line_start, '\n')) != NULL; line_start = line_end + 1) {
			char needle[520];
			snprintf(needle, sizeof(needle), "\n%.*s\n", (int)(line_end - line_start), line_start);
			if (strstr(unique, needle) == NULL) {
				unique_length += (size_t)snprintf(unique + unique_length, sizeof(unique) - unique_length, "%s", needle + 1);
			}
		}
		memcpy(trace_pending, unique + 1, unique_length);
		trace_pending_length = unique_length - 1;
	}
	if (trace_length + trace_pending_length < sizeof(trace_text)) {
		memcpy(trace_text + trace_length, trace_pending, trace_pending_length);
		trace_length += trace_pending_length;
		trace_text[trace_length] = 0;
	}
	trace_pending_length = 0;
	pthread_mutex_unlock(&observe_mutex);
	if (!ok) {
		fprintf(stderr, "Trace step %s did not end with a status poll\n", step);
	}
	return ok;
}

#define TRACE_STEP(step, begin_polling, end_polling, mask, action) do { \
	trace_begin(begin_polling); \
	CHECK(action); \
	CHECK(trace_end(step, end_polling, mask)); \
} while (0)

static bool trace_abort_in_motion(void) {
	unsigned before = revision_of(DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME);
	return request_number(DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME, DOME_HORIZONTAL_COORDINATES_AZ_ITEM_NAME, 200) == INDIGO_OK && wait_rx("d#azi2000", 1, 5) && wait_polls(1, 5) && abort_motion(INDIGO_OK_STATE) && wait_settled(DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME, before, INDIGO_OK_STATE, 5) && wait_polls(1, 5);
}

static bool trace_connect(void) {
	unsigned before = revision_of(CONNECTION_PROPERTY_NAME);
	return request_switch(CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME) == INDIGO_OK && wait_settled(CONNECTION_PROPERTY_NAME, before, INDIGO_OK_STATE, 10) && wait_polls(1, 5);
}

static void reference_trace(void) {
	char *reference = NULL;
	trace_length = 0;
	*trace_text = 0;
	CHECK(driver_up());
	CHECK(set_port(simulator.port));
	TRACE_STEP("connect", false, true, false, trace_connect());
	TRACE_STEP("goto 180", true, true, false, goto_azimuth(180, INDIGO_OK_STATE, 15));
	TRACE_STEP("steps clockwise 30", true, true, false, move_steps(DOME_DIRECTION_MOVE_CLOCKWISE_ITEM_NAME, 30, INDIGO_OK_STATE, 15));
	TRACE_STEP("steps counterclockwise 40", true, true, false, move_steps(DOME_DIRECTION_MOVE_COUNTERCLOCKWISE_ITEM_NAME, 40, INDIGO_OK_STATE, 15));
	TRACE_STEP("direction clockwise", true, true, false, change_switch(DOME_DIRECTION_PROPERTY_NAME, DOME_DIRECTION_MOVE_CLOCKWISE_ITEM_NAME, INDIGO_OK_STATE, 5));
	TRACE_STEP("park", true, true, false, park(INDIGO_OK_STATE, 15));
	TRACE_STEP("goto while parked", true, true, false, goto_azimuth(90, INDIGO_ALERT_STATE, 5));
	TRACE_STEP("steps while parked", true, true, false, change_number(DOME_STEPS_PROPERTY_NAME, DOME_STEPS_ITEM_NAME, 10, INDIGO_ALERT_STATE, 5));
	TRACE_STEP("unpark", true, true, false, unpark());
	TRACE_STEP("abort in motion", true, true, true, trace_abort_in_motion());
	TRACE_STEP("goto 300 after abort", true, true, false, goto_azimuth(300, INDIGO_OK_STATE, 15));
	TRACE_STEP("abort idle", true, true, false, abort_motion(INDIGO_OK_STATE));
	TRACE_STEP("failed abort", true, true, false, inject("stopdom", "domerro", 1) && abort_motion(INDIGO_ALERT_STATE));
	TRACE_STEP("flap without shutter", true, true, false, change_switch(DOME_FLAP_PROPERTY_NAME, DOME_FLAP_OPENED_ITEM_NAME, INDIGO_ALERT_STATE, 5));
	TRACE_STEP("shutter open", true, true, false, change_switch(DOME_SHUTTER_PROPERTY_NAME, DOME_SHUTTER_OPENED_ITEM_NAME, INDIGO_OK_STATE, 10));
	TRACE_STEP("flap open", true, true, false, change_switch(DOME_FLAP_PROPERTY_NAME, DOME_FLAP_OPENED_ITEM_NAME, INDIGO_OK_STATE, 10));
	TRACE_STEP("flap close", true, true, false, change_switch(DOME_FLAP_PROPERTY_NAME, DOME_FLAP_CLOSED_ITEM_NAME, INDIGO_OK_STATE, 10));
	TRACE_STEP("shutter close", true, true, false, change_switch(DOME_SHUTTER_PROPERTY_NAME, DOME_SHUTTER_CLOSED_ITEM_NAME, INDIGO_OK_STATE, 10));
	TRACE_STEP("emergency rain", true, true, false, control("eme", "1000") && wait_polls(1, 5));
	TRACE_STEP("disconnect", true, false, false, disconnect());
	if (capture_path) {
		FILE *file = fopen(capture_path, "w");
		CHECK(file != NULL);
		fwrite(trace_text, 1, trace_length, file);
		fclose(file);
		printf("Reference trace written to %s\n", capture_path);
	} else {
		FILE *file = fopen(BAADER_REFERENCE_TRACE_PATH, "r");
		CHECK(file != NULL);
		reference = calloc(1, TRACE_SIZE);
		size_t length = fread(reference, 1, TRACE_SIZE - 1, file);
		fclose(file);
		reference[length] = 0;
		if (strcmp(reference, trace_text)) {
			char path[PATH_MAX];
			snprintf(path, sizeof(path), "%s/actual_trace.txt", fixture_dir);
			file = fopen(path, "w");
			if (file) {
				fwrite(trace_text, 1, trace_length, file);
				fclose(file);
			}
			fprintf(stderr, "Reference trace mismatch; actual trace kept in %s (diff it against %s)\n", path, BAADER_REFERENCE_TRACE_PATH);
			indigo_test_failures++;
		}
	}
cleanup:
	atomic_store(&trace_active, false);
	free(reference);
	driver_down();
}

