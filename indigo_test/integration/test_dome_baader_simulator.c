static indigo_result observe_message(indigo_client *client, indigo_device *device, indigo_property *property, const char *message) {
	pthread_mutex_lock(&observe_mutex);
	if (device != NULL && context.driver_case != NULL && !strcmp(device->name, context.driver_case->device_name) && message != NULL) {
		const char *name = property ? property->name : "";
		if (message_count < MESSAGES_MAX) {
			snprintf(messages[message_count].property, sizeof(messages[message_count].property), "%s", name);
			snprintf(messages[message_count].text, sizeof(messages[message_count].text), "%s", message);
			message_count++;
		}
		if (atomic_load(&trace_active)) {
			char line[512], text[INDIGO_VALUE_SIZE];
			snprintf(text, sizeof(text), "%s", message);
			char *port = strstr(text, " on /dev/");
			if (port) {
				strcpy(port, " on PORT");
			}
			snprintf(line, sizeof(line), "M %s \"%s\"", name, text);
			trace_pending_line(line);
		}
		if (getenv("BAADER_DEBUG")) {
			fprintf(stderr, "%.3f M %s %s\n", now(), name, message);
		}
	}
	pthread_mutex_unlock(&observe_mutex);
	return INDIGO_OK;
}

