static bool message_seen(const char *name, const char *text) {
	bool result = false;
	// a message follows its property update through a separate send_message callback
	for (int attempt = 0; attempt < 100 && !result; attempt++) {
		pthread_mutex_lock(&observe_mutex);
		for (int i = 0; i < message_count && !result; i++) {
			result = !strcmp(messages[i].property, name) && !strcmp(messages[i].text, text);
		}
		pthread_mutex_unlock(&observe_mutex);
		if (!result) {
			indigo_usleep(20000);
		}
	}
	if (!result) {
		fprintf(stderr, "No message \"%s\" for %s\n", text, name);
	}
	return result;
}

