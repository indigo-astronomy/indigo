// Code is generated by AI

// Dome coverage for indigo_dome_skyroof against the standalone Interactive Astronomy SkyRoof
// simulator over a real PTY. A roll-off roof has no azimuth: the only motion is the shutter, which
// the controller acknowledges with "0#" and then reports through "Status#" as "Safety#" while it is
// travelling and "RoofOpen#"/"RoofClosed#" once it has arrived. The driver therefore has no timer;
// it polls with a self-rescheduling finalizer for as long as the roof says it is moving, so the
// scenarios here are about that finalizer reaching the right terminal state.

#include <indigo_drivers/dome_skyroof/indigo_dome_skyroof.h>

#include "serial_simulator_test_common.h"
#include "abort_queue_test_common.h"

#ifndef DOME_SKYROOF_SIMULATOR_EXECUTABLE
#define DOME_SKYROOF_SIMULATOR_EXECUTABLE "build/integration/dome_skyroof_simulator"
#endif

#define DOME_SKYROOF_NAME                   "SkyRoof"
#define HEATER_CONTROL_PROPERTY_NAME        "HEATER_CONTROL"
#define HEATER_CONTROL_OFF_ITEM_NAME        "OFF"
#define HEATER_CONTROL_ON_ITEM_NAME         "ON"

static const simulator_driver_case skyroof_case = {
	DOME_SKYROOF_NAME,
	"indigo_dome_skyroof",
	DOME_SKYROOF_NAME,
	indigo_dome_skyroof,
	false,
	NULL, 0, NULL, 0, NULL, 0, NULL, 0
};

static bool set_switch(const char *property_name, const char *item_name, bool value) {
	return indigo_change_switch_property_1(&simulator_test_client, skyroof_case.device_name, property_name, item_name, value) == INDIGO_OK;
}

// A shutter move ends when the roof stops answering "Safety#", which the driver only notices from
// its own rescheduled poll.
static bool move_shutter(const char *item_name) {
	if (!set_switch(DOME_SHUTTER_PROPERTY_NAME, item_name, true)) {
		return false;
	}
	if (!wait_for_property_state(DOME_SHUTTER_PROPERTY_NAME, INDIGO_OK_STATE)) {
		return false;
	}
	indigo_item *item = find_cached_item(DOME_SHUTTER_PROPERTY_NAME, item_name);
	return item != NULL && item->sw.value;
}

// -------------------------------------------------------------------------------- metadata

static void metadata_and_property_completeness(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_external_serial_simulator(&simulator, DOME_SKYROOF_SIMULATOR_EXECUTABLE));
	SERIAL_CHECK_TRUE(start_serial_driver(&skyroof_case, simulator.port));
	online = true;
	SERIAL_CHECK_TRUE(context.connected && context.last_connection_state == INDIGO_OK_STATE);

	assert_device_interface(INDIGO_INTERFACE_DOME);
	assert_property_has_item(DOME_SHUTTER_PROPERTY_NAME, DOME_SHUTTER_OPENED_ITEM_NAME);
	assert_property_has_item(DOME_SHUTTER_PROPERTY_NAME, DOME_SHUTTER_CLOSED_ITEM_NAME);
	assert_property_has_item(DOME_ABORT_MOTION_PROPERTY_NAME, DOME_ABORT_MOTION_ITEM_NAME);
	assert_property_has_item(HEATER_CONTROL_PROPERTY_NAME, HEATER_CONTROL_OFF_ITEM_NAME);
	assert_property_has_item(HEATER_CONTROL_PROPERTY_NAME, HEATER_CONTROL_ON_ITEM_NAME);

	// A roll-off roof cannot rotate, park or slave, and the driver hides every property that would
	// suggest otherwise. Publishing any of them would make clients offer controls that do nothing.
	static const char *hidden[] = {
		DOME_SPEED_PROPERTY_NAME,
		DOME_DIRECTION_PROPERTY_NAME,
		DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME,
		DOME_STEPS_PROPERTY_NAME,
		DOME_PARK_PROPERTY_NAME,
		DOME_DIMENSION_PROPERTY_NAME,
		DOME_SLAVING_PARAMETERS_PROPERTY_NAME
	};
	assert_not_defined_properties(hidden, ARRAY_SIZE(hidden));
cleanup:
	if (online) { stop_serial_driver(&skyroof_case); }
	stop_external_serial_simulator(&simulator);
}

