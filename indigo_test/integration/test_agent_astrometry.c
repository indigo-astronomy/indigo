int main(int argc, char **argv) {
	setvbuf(stdout, NULL, _IONBF, 0);
	int failed = 0;
	int executed = 0;
	for (unsigned i = 0; i < ARRAY_SIZE(tests); i++) {
		if (argc > 1 && !strstr(tests[i].name, argv[1])) {
			continue;
		}
		executed++;
		strcpy(test_root, "/tmp/indigo_astrometry_test_XXXXXX");
		if (!mkdtemp(test_root)) {
			return 1;
		}
		snprintf(config_folder, sizeof(config_folder), "%s/config", test_root);
		snprintf(astrometry_folder, sizeof(astrometry_folder), "%s/cache/astrometry", test_root);
		snprintf(fake_bin, sizeof(fake_bin), "%s/bin", test_root);
		snprintf(fake_log, sizeof(fake_log), "%s/commands.log", test_root);
		mkdir(config_folder, 0700);
		char cache_base[320];
		snprintf(cache_base, sizeof(cache_base), "%s/cache", test_root);
		mkdir(cache_base, 0700);
		create_fake_tools();
		const char *old_path = getenv("PATH");
		char path[4096];
		snprintf(path, sizeof(path), "%s:%s", fake_bin, old_path ? old_path : "");
		setenv("PATH", path, 1);
		setenv("INDIGO_CACHE_BASE", cache_base, 1);
		setenv("ASTROMETRY_FAKE_LOG", fake_log, 1);
		setenv("ASTROMETRY_FAKE_MODE", "success", 1);
		pid_t child = fork();
		if (child == 0) {
			alarm(60);
			int status = setup() ? indigo_run_tests("Astrometry Agent integration", tests + i, 1) : 1;
			cleanup();
			exit(status || indigo_test_failures ? 1 : 0);
		}
		int status = -1;
		if (child < 0 || waitpid(child, &status, 0) != child || !WIFEXITED(status) || WEXITSTATUS(status)) {
			fprintf(stderr, "FAILED %s (status %d)\n", tests[i].name, status);
			failed++;
		}
		if (getenv("INDIGO_TEST_KEEP_OUTPUT")) {
			printf("Kept test output in %s\n", test_root);
		} else {
			remove_tree(test_root);
		}
	}
	printf("Astrometry Agent: %d/%d passed (including cleanup)\n", executed - failed, executed);
	return executed ? (failed ? 1 : 0) : 2;
}
