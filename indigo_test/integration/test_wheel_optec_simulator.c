static bool start_optec(external_serial_simulator *simulator, const char **arguments) {
	if (arguments == NULL) {
		return start_external_serial_simulator(simulator, WHEEL_OPTEC_SIMULATOR_EXECUTABLE);
	}
	return start_external_serial_simulator_with_args(simulator, WHEEL_OPTEC_SIMULATOR_EXECUTABLE, arguments);
}

static bool request_slot(double slot) {
	return indigo_change_number_property_1(&simulator_test_client, optec_wheel.device_name, WHEEL_SLOT_PROPERTY_NAME, WHEEL_SLOT_ITEM_NAME, slot) == INDIGO_OK;
}

static bool select_slot(double slot) {
	return request_slot(slot) && wait_for_property_state(WHEEL_SLOT_PROPERTY_NAME, INDIGO_OK_STATE) && wait_for_number_item_value(WHEEL_SLOT_PROPERTY_NAME, WHEEL_SLOT_ITEM_NAME, slot, 0.001);
}

static void assert_wheel_class_property_completeness(void) {
	static const char *properties[] = {
		WHEEL_SLOT_PROPERTY_NAME,
		WHEEL_SLOT_NAME_PROPERTY_NAME,
		WHEEL_SLOT_OFFSET_PROPERTY_NAME
	};
	assert_defined_properties(properties, ARRAY_SIZE(properties));
}

