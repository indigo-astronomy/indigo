// Wheel class coverage for indigo_wheel_optec against the standalone Optec simulator over a real
// PTY. The Optec protocol completes a move synchronously: WGOTO<n> answers '*' only once the wheel
// has arrived, so WHEEL_SLOT goes straight from the request to OK without an intermediate poll.
// The driver publishes a fixed eight slots regardless of the attached wheel, so slots beyond the
// device's real capacity are refused by the device rather than by the driver.

