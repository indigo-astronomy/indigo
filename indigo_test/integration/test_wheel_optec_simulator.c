#define WHEEL_OPTEC_SIMULATOR_EXECUTABLE "build/integration/wheel_optec_simulator"
#endif

static const simulator_driver_case optec_wheel = {
	"Optec Filter Wheel",
	"indigo_wheel_optec",
	"Optec Filter Wheel",
	indigo_wheel_optec,
	false,
	NULL, 0, NULL, 0, NULL, 0, NULL, 0
};

