static void abort_stops_motion_and_allows_a_fresh_move(void) {
	SERIAL_CHECK_TRUE(start_main());
	SERIAL_CHECK_TRUE(settle_after_connect(0));
	SERIAL_CHECK_TRUE(sync_to(&main_rotator, 0));
	SERIAL_CHECK_TRUE(select_goto_mode(&main_rotator));
	SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_change_number_property_1(&simulator_test_client, main_rotator.device_name, ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME, 170));
	SERIAL_CHECK_TRUE(wait_for_property_state(ROTATOR_POSITION_PROPERTY_NAME, INDIGO_BUSY_STATE));
	// The change branch publishes BUSY before the queued handler starts the move,
	// so the abort has to wait for the motion to be under way.
	SERIAL_CHECK_TRUE(lunatico_wait_for_command("!step goto 0 3500 0#"));
	SERIAL_CHECK_TRUE(wait_for_number_item_value(ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME, 5, 5));
	lunatico_forget_commands();
	SERIAL_CHECK_TRUE(lunatico_set_switch(&main_rotator, ROTATOR_ABORT_MOTION_PROPERTY_NAME, ROTATOR_ABORT_MOTION_ITEM_NAME, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(lunatico_sent("!step stop 0#"));
	SERIAL_CHECK_TRUE(wait_for_property_not_busy(ROTATOR_POSITION_PROPERTY_NAME));
	double stopped = cached_number_value(ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME);
	SERIAL_CHECK_TRUE(stopped > 0 && stopped < 170);
	// The rotator has to accept a fresh move after the abort.
	SERIAL_CHECK_TRUE(sync_to(&main_rotator, 0));
	SERIAL_CHECK_TRUE(select_goto_mode(&main_rotator));
	SERIAL_CHECK_TRUE(lunatico_set_number(&main_rotator, ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME, 10, INDIGO_BUSY_STATE));
	SERIAL_CHECK_TRUE(wait_for_number_item_value(ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME, 10, .11));
cleanup:
	stop();
}

