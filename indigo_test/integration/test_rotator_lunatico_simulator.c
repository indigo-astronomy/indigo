// Rotator limits are angles the driver converts into controller software limits,
// and it refuses a target outside them itself.
static void limits_are_written_and_enforced(void) {
	SERIAL_CHECK_TRUE(start_main());
	SERIAL_CHECK_TRUE(settle_after_connect(0));
	lunatico_forget_commands();
	SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_change_number_property_1(&simulator_test_client, main_rotator.device_name, ROTATOR_LIMITS_PROPERTY_NAME, ROTATOR_LIMITS_MIN_POSITION_ITEM_NAME, -90));
	SERIAL_CHECK_TRUE(wait_for_property_state(ROTATOR_LIMITS_PROPERTY_NAME, INDIGO_OK_STATE));
	lunatico_forget_commands();
	SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_change_number_property_1(&simulator_test_client, main_rotator.device_name, ROTATOR_LIMITS_PROPERTY_NAME, ROTATOR_LIMITS_MAX_POSITION_ITEM_NAME, 90));
	SERIAL_CHECK_TRUE(wait_for_property_state(ROTATOR_LIMITS_PROPERTY_NAME, INDIGO_OK_STATE));
	// With a -90 deg minimum, -90 deg is 0 steps and 90 deg is 1800 steps.
	SERIAL_CHECK_TRUE(lunatico_sent("!step setswlimits 0 0 1800#"));
	SERIAL_CHECK_TRUE(select_goto_mode(&main_rotator));
	// 200 deg is 2900 steps, outside the limits, and the driver rejects it
	// itself rather than letting the controller refuse it.
	lunatico_forget_commands();
	SERIAL_CHECK_TRUE(lunatico_set_number(&main_rotator, ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME, 200, INDIGO_ALERT_STATE));
	SERIAL_CHECK_TRUE(lunatico_not_sent("!step goto 0 2900 0#"));
	// A target inside the limits still works.
	SERIAL_CHECK_TRUE(lunatico_set_number(&main_rotator, ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME, 45, INDIGO_BUSY_STATE));
	SERIAL_CHECK_TRUE(lunatico_wait_for_command("!step goto 0 1350 0#"));
	SERIAL_CHECK_TRUE(wait_for_number_item_value(ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME, 45, .11));
cleanup:
	stop();
}

// A limits change only re-maps degrees to steps, so the reported angle must not
// move. Defect LU-08: the pre-migration driver re-synced the controller's counter
// to a step value computed from the old mapping, so changing the minimum limit
// alone made the reported angle jump by the difference without any motion.
static void limits_change_keeps_the_reported_angle(void) {
	SERIAL_CHECK_TRUE(start_main());
	SERIAL_CHECK_TRUE(settle_after_connect(0));
	SERIAL_CHECK_TRUE(sync_to(&main_rotator, 0));
	lunatico_forget_commands();
	SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_change_number_property_1(&simulator_test_client, main_rotator.device_name, ROTATOR_LIMITS_PROPERTY_NAME, ROTATOR_LIMITS_MIN_POSITION_ITEM_NAME, -90));
	SERIAL_CHECK_TRUE(wait_for_property_state(ROTATOR_LIMITS_PROPERTY_NAME, INDIGO_OK_STATE));
	// 0 deg is 900 steps once the minimum is -90 deg, so that is what the
	// controller's counter has to be re-synced to.
	SERIAL_CHECK_TRUE(lunatico_wait_for_command("!step setpos 0 900#"));
	indigo_usleep(1500000);
	SERIAL_CHECK_TRUE(wait_for_number_item_value(ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME, 0, .11));
cleanup:
	stop();
}

