// An absolute GOTO converts degrees to steps, reports BUSY, publishes measured
// progress and only then the final angle.
static void goto_on(const simulator_driver_case *device, int port) {
	SERIAL_CHECK_TRUE(lunatico_start(device, "ROTATOR"));
	assert_device_interface(INDIGO_INTERFACE_ROTATOR);
	SERIAL_CHECK_TRUE(settle_after_connect(port));
	// The angle has to be read back from the controller, not assumed: a port
	// whose counter is not at 0 deg used to have its first request swallowed
	// because connect never filled in the current angle (DRV-210).
	SERIAL_CHECK_TRUE(sync_to(device, 0));
	SERIAL_CHECK_TRUE(select_goto_mode(device));
	lunatico_forget_commands();
	unsigned int revision = property_revision(ROTATOR_POSITION_PROPERTY_NAME);
	SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_change_number_property_1(&simulator_test_client, device->device_name, ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME, 20));
	SERIAL_CHECK_TRUE(wait_for_property_state_seen_after(ROTATOR_POSITION_PROPERTY_NAME, INDIGO_BUSY_STATE, revision));
	SERIAL_CHECK_TRUE(wait_for_number_item_value(ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME, 20, .11));
	SERIAL_CHECK_TRUE(wait_for_property_state(ROTATOR_POSITION_PROPERTY_NAME, INDIGO_OK_STATE));
	// 20 deg is (20 + 180) * 10 = 2000 steps.
	char command[64];
	snprintf(command, sizeof(command), "!step goto %d 2000 0#", port);
	SERIAL_CHECK_TRUE(lunatico_wait_for_command(command));
cleanup:
	stop();
}

