// Steps of 0 deg at the default steps per revolution and minimum limit.
#define ZERO_DEGREE_STEPS 1800

static bool lunatico_wait_for_device(bool configurable) {
	if (!configurable) {
		enumerate_simulator_device();
		return has_defined_property(CONNECTION_PROPERTY_NAME);
	}
	for (int i = 0; i < 200; i++) {
		if (has_defined_property(CONNECTION_PROPERTY_NAME)) {
			return true;
		}
		indigo_usleep(50000);
	}
	fprintf(stderr, "port device did not appear\n");
	return false;
}

// See the equivalent helper in test_focuser_lunatico_simulator.c: the port
// configuration properties exist only before the generator migration, and only
// the Main device keeps a visible DEVICE_PORT after it.
static bool lunatico_start(const simulator_driver_case *device, const char *port_class) {
	selected = device;
	if (!bring_up_serial_driver(&main_rotator)) {
		return false;
	}
	bool configurable = has_defined_property("LUNATICO_MODEL");
	char url[PATH_MAX];
	lunatico_url(url, sizeof(url));
	if (device != &main_rotator) {
		reset_simulator_context(device);
		if (configurable) {
			indigo_change_switch_property_1(&simulator_test_client, main_rotator.device_name, "LUNATICO_MODEL", "PLATYPUS", true);
			const char *port_property = strstr(device->device_name, "(Exp)") ? "LUNATICO_PORT_EXP_CONFIG" : "LUNATICO_PORT_THIRD_CONFIG";
			indigo_change_switch_property_1(&simulator_test_client, main_rotator.device_name, port_property, port_class, true);
		}
		if (!lunatico_wait_for_device(configurable)) {
			return false;
		}
	}
	indigo_change_text_property_1_raw(&simulator_test_client, main_rotator.device_name, DEVICE_PORT_PROPERTY_NAME, DEVICE_PORT_ITEM_NAME, url);
	indigo_usleep(200000);
	return connect_serial_device(device, url);
}

static bool start_main(void) {
	return lunatico_start(&main_rotator, NULL);
}

static void stop(void) {
	if (selected != &main_rotator) {
		disconnect_serial_device(selected);
	}
	disconnect_serial_device(&main_rotator);
	aux_stop(&main_rotator);
}

// The connection handler arms a one-shot poll and publishes CONNECTION OK before
// it fires, so scenarios that are not about that overlap wait for it.
static bool settle_after_connect(int port) {
	char command[32];
	snprintf(command, sizeof(command), "!step ismoving %d#", port);
	return lunatico_wait_for_command(command);
}

static bool sync_to(const simulator_driver_case *device, double degrees) {
	if (!lunatico_set_switch(device, ROTATOR_ON_POSITION_SET_PROPERTY_NAME, ROTATOR_ON_POSITION_SET_SYNC_ITEM_NAME, INDIGO_OK_STATE)) {
		return false;
	}
	if (!lunatico_set_number(device, ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME, degrees, INDIGO_OK_STATE)) {
		return false;
	}
	return wait_for_number_item_value(ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME, degrees, .11);
}

static bool select_goto_mode(const simulator_driver_case *device) {
	return lunatico_set_switch(device, ROTATOR_ON_POSITION_SET_PROPERTY_NAME, ROTATOR_ON_POSITION_SET_GOTO_ITEM_NAME, INDIGO_OK_STATE);
}

