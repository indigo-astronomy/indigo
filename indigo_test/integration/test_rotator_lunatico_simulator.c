// The Main port must come up as a rotator, which is the only behavioural
// difference between this entry point and indigo_focuser_lunatico, and the
// connect sequence has to configure the controller and adopt its angle.
static void identity_and_inventory(void) {
	SERIAL_CHECK_TRUE(start_main());
	assert_device_interface(INDIGO_INTERFACE_ROTATOR);
	assert_serial_rotator_class_property_completeness();
	SERIAL_CHECK_TRUE(lunatico_sent("!seletek version#"));
	SERIAL_CHECK_TRUE(has_defined_property(ROTATOR_STEPS_PER_REVOLUTION_PROPERTY_NAME));
	SERIAL_CHECK_TRUE(has_defined_property(ROTATOR_DIRECTION_PROPERTY_NAME));
	SERIAL_CHECK_TRUE(has_defined_property(ROTATOR_BACKLASH_PROPERTY_NAME));
	SERIAL_CHECK_TRUE(has_defined_property(ROTATOR_LIMITS_PROPERTY_NAME));
	SERIAL_CHECK_TRUE(cached_number_value(ROTATOR_STEPS_PER_REVOLUTION_PROPERTY_NAME, ROTATOR_STEPS_PER_REVOLUTION_ITEM_NAME) == 3600);
	SERIAL_CHECK_TRUE(cached_number_value(ROTATOR_LIMITS_PROPERTY_NAME, ROTATOR_LIMITS_MIN_POSITION_ITEM_NAME) == -180);
	SERIAL_CHECK_TRUE(cached_number_value(ROTATOR_LIMITS_PROPERTY_NAME, ROTATOR_LIMITS_MAX_POSITION_ITEM_NAME) == 180);
	// The driver-specific motor settings are shared with the focuser device, but
	// the temperature sensor selection is focuser-only.
	SERIAL_CHECK_TRUE(has_defined_property(X_ROTATOR_STEP_MODE_PROPERTY_NAME));
	SERIAL_CHECK_TRUE(has_defined_property(X_ROTATOR_POWER_CONTROL_PROPERTY_NAME));
	SERIAL_CHECK_TRUE(has_defined_property(X_ROTATOR_MOTOR_WIRING_PROPERTY_NAME));
	SERIAL_CHECK_TRUE(has_defined_property(X_ROTATOR_MOTOR_TYPE_PROPERTY_NAME));
	SERIAL_CHECK_TRUE(find_cached_property(X_FOCUSER_TEMPERATURE_SENSOR_PROPERTY_NAME) == NULL);
	// The controller starts at 1800 steps, which is 0 deg, and connect re-syncs
	// the counter to the angle it just read.
	SERIAL_CHECK_TRUE(lunatico_sent("!step getpos 0#"));
	SERIAL_CHECK_TRUE(lunatico_sent("!step setpos 0 1800#"));
	SERIAL_CHECK_TRUE(lunatico_sent("!step speedrangeus 0 10000 10000#"));
	SERIAL_CHECK_TRUE(lunatico_sent("!step wiremode 0 0#"));
	// The default limits map onto the same step value, so no software limit is
	// written to the controller.
	SERIAL_CHECK_TRUE(lunatico_sent("!step delswlimits 0#"));
	SERIAL_CHECK_TRUE(lunatico_not_sent("!step setswlimits 0 0 0#"));
	SERIAL_CHECK_TRUE(wait_for_property_state(ROTATOR_POSITION_PROPERTY_NAME, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(wait_for_number_item_value(ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME, 0, .11));
cleanup:
	stop();
}

