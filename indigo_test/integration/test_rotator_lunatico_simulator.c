// Angle to step conversion of this driver, with the default 3600 steps per
// revolution and the default -180 deg minimum limit, is
// steps = (degrees - min) * steps_per_revolution / 360 wrapped into one
// revolution, so 0 deg is 1800 steps and 20 deg is 2000 steps.

