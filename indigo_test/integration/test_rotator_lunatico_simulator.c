	SERIAL_CHECK_TRUE(start_main());
	SERIAL_CHECK_TRUE(settle_after_connect(0));
	SERIAL_CHECK_TRUE(select_goto_mode(&main_rotator));
	SERIAL_CHECK_TRUE(lunatico_set_number(&main_rotator, ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME, 20, INDIGO_ALERT_STATE));
	// The failure has to survive a poll interval instead of being overwritten by
