	lunatico_forget_commands();
	SERIAL_CHECK_TRUE(lunatico_set_number(&exp_focuser, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, 1200, INDIGO_BUSY_STATE));
