"""Execute the JavaScript acceptance suite through an isolated Scripting Agent.

No existing server is used. The native JSON client transports scripts and
authenticated test requests and observes results; Sequence runs inside INDIGO.
"""

import argparse
import ctypes
import hashlib
import json
import os
from pathlib import Path
import secrets
import shutil
import socket
import subprocess
import sys
import tempfile
import time


class Client:

	def __init__(self, connection, events, token):
		self.connection = connection
		self.connection.settimeout(0.25)
		self.buffer = ""
		self.decoder = json.JSONDecoder()
		self.properties = {}
		self.events = events
		self.results = []
		self.heartbeat = time.monotonic()
		self.token = token
		self.rejections = set()
		self.relay_id = 0
		self.relay_count = 0
		self.records = os.environ.get("INDIGO_TEST_RESULTS")
		self.plan_recorded = False
		self.geometry = None
		self.geometry_count = 0

	def record(self, line):
		if self.records:
			with open(self.records, "a") as output:
				output.write(line + "\n")

	def send(self, operation, value):
		if operation.startswith("new"):
			value = dict(value, token=self.token)
		self.connection.sendall((json.dumps({operation: value}, ensure_ascii=False) + "\n").encode())

	def script(self, source):
		self.send("newTextVector", {"device": "Scripting Agent", "name": "AGENT_SCRIPTING_RUN_SCRIPT", "items": [{"name": "SCRIPT", "value": source}]})

	def transit_target(self, value):
		if self.geometry is None:
			repo = Path(__file__).resolve().parents[2]
			candidates = [repo / "build/lib" / name for name in ("libindigo.dylib", "libindigo.so", "indigo.dll")]
			library = next((p for p in candidates if p.is_file()), None)
			if library is None:
				raise RuntimeError("Native INDIGO geometry library is missing")
			self.geometry = ctypes.CDLL(str(library))
			self.geometry.indigo_jnow_to_j2k.argtypes = [ctypes.POINTER(ctypes.c_double), ctypes.POINTER(ctypes.c_double)]
			self.geometry.indigo_jnow_to_j2k.restype = None
		ra = ctypes.c_double(value["ra"])
		dec = ctypes.c_double(value["dec"])
		self.geometry.indigo_jnow_to_j2k(ctypes.byref(ra), ctypes.byref(dec))
		self.geometry_count += 1
		self.script("seqtest.transit_target=" + json.dumps({"ra": ra.value, "dec": dec.value}) + ";")

	def poll(self):
		if time.monotonic() - self.heartbeat > 1:
			self.send("getProperties", {"version": 0x300, "device": "Scripting Agent", "name": "X_SEQ_TEST_REPORT"})
			self.heartbeat = time.monotonic()
		try:
			data = self.connection.recv(1024 * 1024)
		except socket.timeout:
			return
		if not data:
			raise RuntimeError("INDIGO disconnected before completion")
		# Native JSON output is UTF-8; retain incomplete codepoints across reads.
		self.buffer += self.utf8.decode(data)
		while self.buffer.strip():
			self.buffer = self.buffer.lstrip()
			try:
				packet, end = self.decoder.raw_decode(self.buffer)
			except json.JSONDecodeError:
				break
			self.buffer = self.buffer[end:]
			for operation, value in packet.items():
				if operation.startswith(("def", "set")) and "device" in value:
					key = (value["device"], value.get("name"))
					previous = self.properties.get(key, {})
					items = {i["name"]: i.get("value") for i in previous.get("items", [])}
					items.update({i["name"]: i.get("value") for i in value.get("items", [])})
					merged = dict(previous, **value)
					merged["items"] = [{"name": k, "value": v} for k, v in items.items()]
					self.properties[key] = merged
					if key == ("Scripting Agent", "X_SEQ_TEST_REQUEST"):
						for item in value.get("items", []):
							if item["name"] == "JSON":
								request = json.loads(item["value"])
								if request.get("id", 0) > self.relay_id:
									if request["operation"] == "testTransitTarget":
										self.transit_target(request["value"])
									elif request["operation"] in ("newTextVector", "newNumberVector", "newSwitchVector"):
										self.send(request["operation"], request["value"])
									else:
										raise RuntimeError("Invalid test relay operation")
									self.relay_id = request["id"]
									self.relay_count += 1
				if operation == "message":
					message = value if isinstance(value, str) else value.get("message", "")
					if "protected or locked for exclusive access" in message:
						self.rejections.add(packet.get("device"))
					self.events.write(json.dumps(packet, ensure_ascii=False) + "\n")
					self.events.flush()
					if message.startswith("SEQTEST_PLAN ") and not self.plan_recorded:
						self.record("plan\t" + message.split()[1] + "\tSequencer simulator scripts")
						self.plan_recorded = True
					marker = message.find("SEQTEST ")
					if marker >= 0:
						result = json.loads(message[marker + 8:])
						self.results.append(result)
						self.record(result["status"] + "\tSequencer simulator scripts\t" + result["name"])
						print("{status}: {name}{detail}".format(status=result["status"].upper(), name=result["name"], detail=(" — " + result["error"]) if result.get("error") else ""), flush=True)

	def wait(self, predicate, timeout):
		deadline = time.monotonic() + timeout
		while time.monotonic() < deadline:
			if predicate():
				return
			self.poll()
		raise TimeoutError("Timed out waiting for Scripting Agent acceptance results")

	def report(self):
		p = self.properties.get(("Scripting Agent", "X_SEQ_TEST_REPORT"), {})
		return next((i["value"] for i in p.get("items", []) if i["name"] == "JSON"), None)


def verify_files(root, cases):
	"""Validate artifacts independently of the in-agent sequence state."""
	results = []
	expected_cases = {"batch_plain": "capture batch named=false", "batch_named": "capture batch named=true", "stream_plain": "capture stream named=false", "stream_named": "capture stream named=true", "header_present": "FITS custom header present", "header_removed": "FITS custom header removed"}
	for prefix, minimum in (("batch_plain", 2), ("batch_named", 2), ("stream_plain", 3), ("stream_named", 3), ("header_present", 1), ("header_removed", 1)):
		if expected_cases[prefix] not in cases:
			continue
		files = list(root.glob(prefix + "*"))
		ok = len(files) >= minimum and all(p.is_file() and p.stat().st_size > 2880 for p in files)
		if prefix.startswith("header_") and files:
			header = files[0].read_bytes()[:2880 * 10]
			cards = [header[i:i + 80] for i in range(0, len(header), 80)]
			end = next((i for i, card in enumerate(cards) if card.startswith(b"END     ")), len(cards))
			custom = [card for card in cards[:end] if card.startswith(b"SEQTEST ")]
			present = bool(custom)
			ok = ok and present == (prefix == "header_present")
			if prefix == "header_present":
				ok = ok and len(custom) == 1 and custom[0][10:30].strip() == b"'present'"
		results.append({"name": "artifacts/" + prefix, "status": "pass" if ok else "fail", "files": [p.name for p in files], "minimum": minimum})
	return results


def main():
	import codecs
	parser = argparse.ArgumentParser(description=__doc__)
	parser.add_argument("--output", type=Path, default=os.environ.get("INDIGO_SEQUENCER_OUTPUT"), help="New directory for retained logs, images and JSON results")
	parser.add_argument("--index-dir", type=Path, default=os.environ.get("INDIGO_SEQUENCER_INDEX_DIR"), help="Copy existing 2°/5° native solver indexes; no downloads")
	parser.add_argument("--timeout", type=float, default=1200)
	parser.add_argument("--case", help="Run case names containing any pipe-separated text fragment")
	parser.add_argument("--exclude", help="Exclude case names containing this text (recorded in results)")
	parser.add_argument("--native-bindings", action="store_true", help="Diagnose native scripting token failures without the authenticated test relay")
	args = parser.parse_args()
	repo = Path(__file__).resolve().parents[2]
	output = args.output.resolve() if args.output else Path(tempfile.mkdtemp(prefix="indigo-sequencer-results-"))
	if args.output:
		output.mkdir(parents=True, exist_ok=False)
	home = output / "home"
	images = output / "images"
	home.mkdir()
	images.mkdir()
	# Native JSON token parsing uses signed strtol; stay in its positive range.
	token = format(secrets.randbits(31) | 1, "x")
	acl = home / "test.acl"
	protected = ["Server", "Scripting Agent", "Configuration Agent", "Imager Agent", "Mount Agent", "Guider Agent", "Platesolver Agent", "CCD Imager Simulator", "CCD Guider Simulator", "CCD Bahtinov Mask Simulator", "DSLR Simulator", "CCD File Simulator", "CCD Imager Simulator (wheel)", "CCD Imager Simulator (focuser)", "CCD Guider Simulator (guider)", "CCD Guider Simulator (AO)", "Mount Simulator", "Mount Simulator (guider)", "Dome Simulator", "GPS Simulator", "Field Rotator Simulator", "PowerBox Simulator", "Weather Station Simulator", "SQM Simulator", "Flat Panel Simulator"]
	# A nonzero master is required as well as per-device ACLs by the native bus.
	acl.write_text(token + " @\n" + "".join(token + " " + name + "\n" for name in protected))
	acl.chmod(0o600)
	indexes = home / ".indigo" / "solver"
	indexes.mkdir(parents=True)
	copied = []
	if args.index_dir:
		for name in ("index-02deg-tyc2.isix", "index-05deg-tyc2.isix"):
			source = args.index_dir / name
			if source.is_file():
				shutil.copyfile(source, indexes / name)
				copied.append(name)
		if not copied:
			parser.error("--index-dir contains no supported existing indexes")
	with socket.socket() as reservation:
		reservation.bind(("127.0.0.1", 0))
		port = reservation.getsockname()[1]
	drivers = ["agent_scripting", "agent_imager", "agent_mount", "agent_guider", "agent_config", "agent_platesolver", "ccd_simulator", "mount_simulator", "dome_simulator", "gps_simulator", "rotator_simulator"]
	command = [str(repo / "build/bin/indigo_server"), "--", "-p", str(port), "-b-", "-c-", "-w-", "-a", str(acl)]
	env = dict(os.environ, HOME=str(home), INDIGO_CACHE_BASE=str(home / ".indigo"))
	metadata = {"command": command, "cwd": str(repo), "indexes": copied, "output": str(output), "source_revision": subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=repo, text=True).strip()}
	metadata["source_sha256"] = {str(p.relative_to(repo)): hashlib.sha256(p.read_bytes()).hexdigest() for p in (Path(__file__).resolve(), Path(__file__).with_name("sequencer_simulators.js"), repo / "indigo_drivers/agent_scripting/library/Sequencer.js")}
	process = None
	client = None
	report = None
	error = None
	try:
		with (output / "server.log").open("w") as log, (output / "messages.jsonl").open("w") as events:
			process = subprocess.Popen(command, cwd=repo, env=env, stdout=log, stderr=subprocess.STDOUT)
			deadline = time.monotonic() + 20
			while True:
				if process.poll() is not None:
					raise RuntimeError("Private INDIGO server exited; inspect server.log")
				try:
					connection = socket.create_connection(("127.0.0.1", port), timeout=0.5)
					break
				except OSError:
					if time.monotonic() >= deadline:
						raise TimeoutError("Private INDIGO server did not start")
					time.sleep(0.1)
			client = Client(connection, events, token)
			if args.case or args.exclude:
				client.record("filter\t" + json.dumps({"case": args.case, "exclude": args.exclude}))
			client.utf8 = codecs.getincrementaldecoder("utf-8")()
			client.send("getProperties", {"version": 0x300})
			client.wait(lambda: ("Server", "DRIVERS") in client.properties, 20)
			# Prove unauthenticated writes are refused before installing executable scripts.
			client.connection.sendall((json.dumps({"newSwitchVector": {"device": "Server", "name": "DRIVERS", "items": [{"name": "indigo_agent_scripting", "value": True}]}}) + "\n").encode())
			client.wait(lambda: "Server" in client.rejections, 5)
			client.send("newSwitchVector", {"device": "Server", "name": "DRIVERS", "items": [{"name": "indigo_" + name, "value": True} for name in drivers]})
			client.wait(lambda: ("Scripting Agent", "AGENT_SCRIPTING_RUN_SCRIPT") in client.properties and ("Platesolver Agent", "AGENT_START_PROCESS") in client.properties, 20)
			client.connection.sendall((json.dumps({"newTextVector": {"device": "Scripting Agent", "name": "AGENT_SCRIPTING_RUN_SCRIPT", "items": [{"name": "SCRIPT", "value": "indigo_send_message('Unauthorized probe executed')"}]}}) + "\n").encode())
			client.wait(lambda: "Scripting Agent" in client.rejections, 5)
			metadata["unauthenticated_write_rejected"] = sorted(client.rejections)
			client.script((repo / "indigo_drivers/agent_scripting/library/Sequencer.js").read_text())
			client.wait(lambda: ("Scripting Agent", "SEQUENCE_STATE") in client.properties, 20)
			options = {"directory": str(images) + "/", "solver": bool(copied), "only": args.case, "exclude": args.exclude, "authenticated_relay": not args.native_bindings}
			metadata["selection"] = options
			client.script("var seqtest_options=" + json.dumps(options) + ";\n" + Path(__file__).with_name("sequencer_simulators.js").read_text())
			client.wait(lambda: client.report() and json.loads(client.report()).get("done"), args.timeout)
			report = json.loads(client.report())
			# Drain final per-case messages after the property update.
			until = time.monotonic() + 0.5
			while time.monotonic() < until:
				client.poll()
	except (OSError, RuntimeError, TimeoutError, ValueError) as exc:
		error = str(exc)
		print(error, file=sys.stderr)
	finally:
		if client:
			client.connection.close()
		if process and process.poll() is None:
			process.terminate()
			try:
				process.wait(timeout=15)
			except subprocess.TimeoutExpired:
				process.kill()
				process.wait()
		metadata["server_exit"] = process.returncode if process else None
		metadata["relayed_requests"] = client.relay_count if client else 0
		metadata["native_geometry_conversions"] = client.geometry_count if client else 0
		acl.unlink(missing_ok=True)
	report = report or {"done": False, "results": client.results if client else []}
	report.update(metadata)
	report["error"] = error
	report["artifacts"] = verify_files(images, {r["name"] for r in report["results"]})
	if client and report["artifacts"]:
		client.record("plan\t" + str(len(report["artifacts"])) + "\tSequencer simulator artifacts")
		for result in report["artifacts"]:
			client.record(result["status"] + "\tSequencer simulator artifacts\t" + result["name"])
	(output / "results.json").write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n")
	passed = sum(r["status"] == "pass" for r in report["results"])
	failed = sum(r["status"] == "fail" for r in report["results"])
	print(f"Scripting Agent: {passed} passed, {failed} failed; report: {output / 'results.json'}")
	complete_coverage = bool(args.case or args.exclude) or not report.get("missing", ["incomplete report"])
	all_executed = report.get("total", 0) > 0 and len(report["results"]) == report["total"]
	return 0 if report["done"] and all_executed and not error and not failed and complete_coverage and all(r["status"] == "pass" for r in report["artifacts"]) else 1


if __name__ == "__main__":
	sys.exit(main())
