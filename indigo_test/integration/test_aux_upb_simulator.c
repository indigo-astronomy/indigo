// A status frame lost while polling is a transient fault: the connection stays up
// and the next poll has to publish the real readings rather than a partial parse.
static void status_fault_while_polling_is_survived(void) {
	external_serial_simulator simulator = { 0 };
	// The connect consumes the first PA, so the fault is aimed at the first poll.
	const char *arguments[] = { "--fault-after", "1", "PA", "short", NULL };
	SERIAL_CHECK_TRUE(start_upb(&simulator, arguments));
	SERIAL_CHECK_TRUE(start_serial_driver(&aux, simulator.port));
	SERIAL_CHECK_TRUE(context.connected);
	SERIAL_CHECK_TRUE(wait_for_number_item_value(AUX_INFO_PROPERTY_NAME, AUX_INFO_VOLTAGE_ITEM_NAME, 12.2, 0.01));
	SERIAL_CHECK_TRUE(wait_for_number_item_value(AUX_WEATHER_PROPERTY_NAME, AUX_WEATHER_TEMPERATURE_ITEM_NAME, 23.2, 0.01));
	SERIAL_CHECK_TRUE(wait_for_number_item_value(AUX_WEATHER_PROPERTY_NAME, AUX_WEATHER_HUMIDITY_ITEM_NAME, 59, 0.01));
	// The outlet mask survives the truncated frame rather than being cleared by it.
	SERIAL_CHECK_TRUE(wait_for_switch_item_value(AUX_POWER_OUTLET_PROPERTY_NAME, AUX_POWER_OUTLET_1_ITEM_NAME, true));
	// The device is still usable afterwards.
	SERIAL_CHECK_TRUE(set_switch(&aux, AUX_POWER_OUTLET_PROPERTY_NAME, AUX_POWER_OUTLET_4_ITEM_NAME, false));
	SERIAL_CHECK_TRUE(wait_for_switch_item_value(AUX_POWER_OUTLET_PROPERTY_NAME, AUX_POWER_OUTLET_4_ITEM_NAME, false));
cleanup:
	stop_serial_driver(&aux);
	stop_external_serial_simulator(&simulator);
}

