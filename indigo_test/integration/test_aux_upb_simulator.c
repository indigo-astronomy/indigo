static void each_power_outlet_switches_on_its_own(void) {
	external_serial_simulator simulator = { 0 };
	SERIAL_CHECK_TRUE(start_upb(&simulator, NULL));
	SERIAL_CHECK_TRUE(start_serial_driver(&aux, simulator.port));
	static const char * const items[] = { AUX_POWER_OUTLET_1_ITEM_NAME, AUX_POWER_OUTLET_2_ITEM_NAME, AUX_POWER_OUTLET_3_ITEM_NAME, AUX_POWER_OUTLET_4_ITEM_NAME };
	for (int i = 0; i < 4; i++) {
		SERIAL_CHECK_TRUE(set_switch(&aux, AUX_POWER_OUTLET_PROPERTY_NAME, items[i], false));
		SERIAL_CHECK_TRUE(wait_for_property_state(AUX_POWER_OUTLET_PROPERTY_NAME, INDIGO_OK_STATE));
		// The status poll reads the outlet mask back, so the value has to survive it.
		SERIAL_CHECK_TRUE(wait_for_switch_item_value(AUX_POWER_OUTLET_PROPERTY_NAME, items[i], false));
		for (int j = 0; j < 4; j++) {
			SERIAL_CHECK_TRUE(wait_for_switch_item_value(AUX_POWER_OUTLET_PROPERTY_NAME, items[j], j > i ? true : false));
		}
	}
	for (int i = 0; i < 4; i++) {
		// The change dispatch ignores a request that arrives while the property is still
		// BUSY, so each outlet has to settle before the next one is switched.
		SERIAL_CHECK_TRUE(wait_for_property_state(AUX_POWER_OUTLET_PROPERTY_NAME, INDIGO_OK_STATE));
		SERIAL_CHECK_TRUE(set_switch(&aux, AUX_POWER_OUTLET_PROPERTY_NAME, items[i], true));
		SERIAL_CHECK_TRUE(wait_for_switch_item_value(AUX_POWER_OUTLET_PROPERTY_NAME, items[i], true));
	}
cleanup:
	stop_serial_driver(&aux);
	stop_external_serial_simulator(&simulator);
}

