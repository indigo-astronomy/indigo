// The driver clamps a relative move against FOCUSER_LIMITS before it reaches the
// device, so the focuser stops at the limit rather than beyond it.
static void focuser_steps_are_clamped_by_the_limits(void) {
	external_serial_simulator simulator = { 0 };
	SERIAL_CHECK_TRUE(start_upb(&simulator, NULL));
	SERIAL_CHECK_TRUE(start_shared_serial_device(&focuser, aux.device_name, simulator.port));
	SERIAL_CHECK_TRUE(set_number(&focuser, FOCUSER_LIMITS_PROPERTY_NAME, FOCUSER_LIMITS_MAX_POSITION_ITEM_NAME, 300));
	SERIAL_CHECK_TRUE(wait_for_property_state(FOCUSER_LIMITS_PROPERTY_NAME, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(set_switch(&focuser, FOCUSER_DIRECTION_PROPERTY_NAME, FOCUSER_DIRECTION_MOVE_INWARD_ITEM_NAME, true));
	SERIAL_CHECK_TRUE(set_number(&focuser, FOCUSER_STEPS_PROPERTY_NAME, FOCUSER_STEPS_ITEM_NAME, 5000));
	SERIAL_CHECK_TRUE(wait_for_property_state(FOCUSER_STEPS_PROPERTY_NAME, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(wait_for_number_item_value(FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, 300, 0));
	// An absolute goto beyond the limit is clamped the same way.
	SERIAL_CHECK_TRUE(set_number(&focuser, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, 9000));
	SERIAL_CHECK_TRUE(wait_for_property_state(FOCUSER_POSITION_PROPERTY_NAME, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(wait_for_number_item_value(FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, 300, 0));
cleanup:
	// FOCUSER_LIMITS is persistent, so the narrowed range would be restored on the next
	// attach and silently shorten a later case's move.
	set_number(&focuser, FOCUSER_LIMITS_PROPERTY_NAME, FOCUSER_LIMITS_MAX_POSITION_ITEM_NAME, 9999999);
	wait_for_property_state(FOCUSER_LIMITS_PROPERTY_NAME, INDIGO_OK_STATE);
	stop_serial_driver(&focuser);
	stop_external_serial_simulator(&simulator);
}

