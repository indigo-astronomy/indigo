	CHECK(exchange(handle, "@OPS", ":OPS#"));
	CHECK(exchange(handle, NULL, ":open#"));
	CHECK(!strncmp(read_until(handle, "S", 1), "S", 1));
	CHECK(exchange(handle, "@SWS", ":SWS#"));
	status = read_until(handle, ":SES", 2);
	CHECK(sscanf(status, ":SES,%ld,46000,0,0#", &stopped) == 1 && stopped > 0);
	CHECK(exchange(handle, "@OPS", ":OPS#"));
	CHECK(exchange(handle, NULL, ":open#"));
	CHECK(!strcmp(read_until(handle, ":SES", 10), ":SES,46000,46000,1,0#"));
	CHECK(exchange(handle, "@OPS", ":OPS#"));
	CHECK(exchange(handle, "@SRS", ":SES,46000,46000,1,0#"));
	// rain closes the shutter
	CHECK(exchange(handle, "@StartRain", ":Rain#"));
