static void find_home(void) {
	CHECK(start_connected());
	unsigned before = revision_of(FIND_HOME_PROPERTY);
	CHECK_EQ(INDIGO_OK, request_switch(FIND_HOME_PROPERTY, FIND_HOME_ITEM));
	CHECK(wait_rx("GHR", 1, 3));
	CHECK(wait_message(FIND_HOME_PROPERTY, "Going home..."));
	CHECK(wait_fresh_state(FIND_HOME_PROPERTY, before, INDIGO_OK_STATE, 15));
	CHECK(wait_message(FIND_HOME_PROPERTY, "Dome is at home."));
	CHECK(busy_of(FIND_HOME_PROPERTY) > 0);
	CHECK(!switch_of(FIND_HOME_PROPERTY, FIND_HOME_ITEM));
	CHECK(motion_stopped());
	CHECK(wait_state(DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME, INDIGO_OK_STATE, 3));
	CHECK_NEAR(20, azimuth_value(), 1e-4);
	CHECK(busy_of(DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME) > 0);
	// already at home: the controller reports at once
	CHECK(change_switch(FIND_HOME_PROPERTY, FIND_HOME_ITEM, INDIGO_OK_STATE, 5));
	CHECK(wait_state(FIND_HOME_PROPERTY, INDIGO_OK_STATE, 5));
	for (int i = 0; i < 50 && message_total(FIND_HOME_PROPERTY, "Dome is at home.") < 2; i++) {
		indigo_usleep(20000);
	}
	CHECK_EQ(2, message_total(FIND_HOME_PROPERTY, "Dome is at home."));
	CHECK_EQ(2, rx_count("GHR"));
cleanup:
	driver_down();
}

static void abort_rotation(void) {
	CHECK(start_connected());
	unsigned before = revision_of(DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME);
	CHECK_EQ(INDIGO_OK, request_number(DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME, DOME_HORIZONTAL_COORDINATES_AZ_ITEM_NAME, 270));
	CHECK(wait_log("EV", ":right#", 1, 3));
	indigo_usleep(800000);
	CHECK_EQ(INDIGO_BUSY_STATE, state_of(DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME));
	CHECK(abort_motion(INDIGO_OK_STATE));
	static const char * const sequence[] = { "SWR", "SWS" };
	int count = load_events();
	CHECK(rx_sequence(rx_index(count, "SWR", 1), sequence, 2, 2));
	CHECK(!switch_of(DOME_ABORT_MOTION_PROPERTY_NAME, DOME_ABORT_MOTION_ITEM_NAME));
	CHECK(wait_settled(DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME, before, INDIGO_OK_STATE, 5));
	CHECK(wait_state(DOME_STEPS_PROPERTY_NAME, INDIGO_OK_STATE, 3));
	indigo_usleep(300000);
	double stopped = azimuth_value();
	CHECK(stopped > 90 && stopped < 270);
	CHECK_NEAR(simulator_azimuth(), stopped, 1e-4);
	CHECK(motion_stopped());
	CHECK_EQ(1, rx_prefix_count("GSR"));
	indigo_usleep(3000000);
	CHECK_EQ(INDIGO_OK_STATE, state_of(DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME));
	CHECK_NEAR(stopped, azimuth_value(), 1e-4);
	// abort while idle
	CHECK(abort_motion(INDIGO_OK_STATE));
	CHECK(wait_rx("SWS", 2, 2));
	indigo_usleep(500000);
	CHECK_EQ(INDIGO_OK_STATE, state_of(DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME));
	CHECK_EQ(INDIGO_OK_STATE, state_of(DOME_SHUTTER_PROPERTY_NAME));
cleanup:
	driver_down();
}

