// ---------------------------------------------------------------------------- reference trace

static void mask_digits(char *text) {
	char *output = text;
	for (char *input = text; *input; input++) {
		if (*input >= '0' && *input <= '9') {
			if (output == text || output[-1] != '#') {
				*output++ = '#';
			}
		} else if (*input == '.' && output > text && output[-1] == '#' && input[1] >= '0' && input[1] <= '9') {
			continue;
		} else {
			*output++ = *input;
		}
	}
	*output = 0;
}

static void trace_append(const char *line) {
	int written = snprintf(trace_text + trace_length, sizeof(trace_text) - trace_length, "%s\n", line);
	if (written > 0 && trace_length + written < sizeof(trace_text)) {
		trace_length += written;
	}
}

// periodic and position reports depend on timing
static bool periodic_output(const char *text) {
	return (text[0] == 'P' && (text[1] == '-' || (text[1] >= '0' && text[1] <= '9'))) || (text[0] == 'S' && text[1] >= '0' && text[1] <= '9') || !strncmp(text, ":BV", 3) || !strncmp(text, "XB->", 4) || !strncmp(text, "Diagnostic", 10);
}

static void trace_begin(void) {
	trace_mark = load_events();
	pthread_mutex_lock(&observe_mutex);
	trace_pending_length = 0;
	*trace_pending = 0;
	for (int i = 0; i < observed_count; i++) {
		*observed[i].last_trace = 0;
	}
	pthread_mutex_unlock(&observe_mutex);
	atomic_store(&trace_active, true);
}

static bool trace_end(const char *step, bool mask) {
	char line[2048];
	indigo_usleep(700000);
	int count = load_events();
	snprintf(line, sizeof(line), "## %s", step);
	trace_append(line);
	for (int i = trace_mark; i < count; i++) {
		if (strcmp(events[i].kind, "RX") && strcmp(events[i].kind, "TX") && strcmp(events[i].kind, "EV") && strcmp(events[i].kind, "FAULT")) {
			continue;
		}
		if (strcmp(events[i].kind, "RX") && periodic_output(events[i].text)) {
			continue;
		}
		snprintf(line, sizeof(line), "S %s %s", events[i].kind, events[i].text);
		// a position read while the dome moves depends on timing
		if ((mask && strcmp(events[i].kind, "RX")) || !strncmp(events[i].text, ":PRR", 4)) {
			mask_digits(line);
		}
		trace_append(line);
	}
	atomic_store(&trace_active, false);
	pthread_mutex_lock(&observe_mutex);
	if (mask) {
		// publications around an asynchronous abort are timing dependent: keep first occurrences only
		static char unique[sizeof(trace_pending) + 2];
		size_t unique_length = 1;
		mask_digits(trace_pending);
		unique[0] = '\n';
		unique[1] = 0;
		for (char *line_start = trace_pending, *line_end; (line_end = strchr(line_start, '\n')) != NULL; line_start = line_end + 1) {
			char needle[1100];
			snprintf(needle, sizeof(needle), "\n%.*s\n", (int)(line_end - line_start), line_start);
			if (strstr(unique, needle) == NULL) {
				unique_length += (size_t)snprintf(unique + unique_length, sizeof(unique) - unique_length, "%s", needle + 1);
			}
		}
		memcpy(trace_pending, unique + 1, unique_length);
		trace_pending_length = unique_length - 1;
	}
	if (trace_length + trace_pending_length < sizeof(trace_text)) {
		memcpy(trace_text + trace_length, trace_pending, trace_pending_length);
		trace_length += trace_pending_length;
		trace_text[trace_length] = 0;
	}
	trace_pending_length = 0;
	pthread_mutex_unlock(&observe_mutex);
	return true;
}

#define TRACE_STEP(step, mask, action) do { \
	trace_begin(); \
	CHECK(action); \
	CHECK(trace_end(step, mask)); \
} while (0)

