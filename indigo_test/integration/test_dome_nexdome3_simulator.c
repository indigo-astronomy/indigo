	CHECK_EQ(INDIGO_AT_MOST_ONE_RULE, rule_of(FIND_HOME_PROPERTY));
	CHECK(item_of(FIND_HOME_PROPERTY, FIND_HOME_ITEM, &item) && !strcmp(item.label, "Find home sensor") && !item.sw.value);
	CHECK_STR("Settings", group_of(HOME_POSITION_PROPERTY));
	CHECK(check_number_item(HOME_POSITION_PROPERTY, HOME_POSITION_ITEM, "Position (steps, ~153 steps/°)", 0, 100000, 0, "%.0f"));
	CHECK_STR("Settings", group_of(THRESHOLD_PROPERTY));
	CHECK(check_number_item(THRESHOLD_PROPERTY, THRESHOLD_ITEM, "Minimal move (steps, ~153 steps/°)", 0, 10000, 300, "%.0f"));
	CHECK_STR("Settings", group_of(POWER_PROPERTY));
	CHECK_EQ(INDIGO_RO_PERM, perm_of(POWER_PROPERTY));
	// the battery voltage is reported periodically
	CHECK(wait_value(POWER_PROPERTY, POWER_VOLTAGE_ITEM, 1000 * 0.01465, 1e-6, 3));
	CHECK(check_number_item(POWER_PROPERTY, POWER_VOLTAGE_ITEM, "Battery charge (Volts)", 0, 500, 1000 * 0.01465, "%.2f"));
	CHECK_STR("Settings", group_of(ACCELERATION_PROPERTY));
	CHECK(check_number_item(ACCELERATION_PROPERTY, ROTATOR_ITEM, "Rotator (ms)", 100, 10000, 1500, "%.0f"));
	CHECK(check_number_item(ACCELERATION_PROPERTY, SHUTTER_ITEM, "Shutter (ms)", 100, 10000, 1500, "%.0f"));
