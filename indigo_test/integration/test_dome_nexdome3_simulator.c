// simulator heading in degrees from the last position report or status
static double simulator_azimuth(void) {
	int count = load_events();
	double result = NAN;
	for (int i = 0; i < count; i++) {
		long position;
		if (strcmp(events[i].kind, "TX") && strcmp(events[i].kind, "EV")) {
			continue;
		}
		if (sscanf(events[i].text, ":SER,%ld,", &position) == 1 || sscanf(events[i].text, "P%ld", &position) == 1 || sscanf(events[i].text, ":PRR%ld#", &position) == 1) {
			result = position / STEPS_PER_DEGREE;
		}
	}
	return result;
}

