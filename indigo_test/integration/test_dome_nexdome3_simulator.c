	CHECK(check_number_item(VELOCITY_PROPERTY, SHUTTER_ITEM, "Shutter (steps/s)", 32, 5000, 800, "%.0f"));
	CHECK(check_number_item(RANGE_PROPERTY, ROTATOR_ITEM, "Dome circumference (steps)", 30000, 100000, 55080, "%.0f"));
	CHECK(check_number_item(RANGE_PROPERTY, SHUTTER_ITEM, "Shutter travel (steps)", 20000, 90000, 46000, "%.0f"));
	CHECK_STR("Settings", group_of(SETTINGS_PROPERTY));
	CHECK_EQ(3, count_of(SETTINGS_PROPERTY));
	CHECK_EQ(INDIGO_AT_MOST_ONE_RULE, rule_of(SETTINGS_PROPERTY));
