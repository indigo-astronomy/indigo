static bool trace_find_home(void) {
	unsigned before = revision_of(FIND_HOME_PROPERTY);
	return request_switch(FIND_HOME_PROPERTY, FIND_HOME_ITEM) == INDIGO_OK && wait_fresh_state(FIND_HOME_PROPERTY, before, INDIGO_OK_STATE, 15) && wait_state(DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME, INDIGO_OK_STATE, 3);
}

static bool trace_control(const char *key, const char *value, const char *output) {
	int count = log_count("EV", output);
	return control(key, value) && wait_log("EV", output, count + 1, 3) && (indigo_usleep(300000), true);
}

static bool trace_emit(const char *line) {
	return trace_control("emit", line, line);
}

static void reference_trace(void) {
	char *reference = NULL;
	trace_length = 0;
	*trace_text = 0;
	CHECK(driver_up());
	CHECK(set_port(simulator.port));
	TRACE_STEP("connect", false, trace_connect());
	TRACE_STEP("goto 180", false, goto_and_wait(180, INDIGO_OK_STATE, 10));
	TRACE_STEP("steps clockwise 30", false, steps_and_wait(DOME_DIRECTION_MOVE_CLOCKWISE_ITEM_NAME, 30, INDIGO_OK_STATE, 10));
	TRACE_STEP("steps counterclockwise 40", false, steps_and_wait(DOME_DIRECTION_MOVE_COUNTERCLOCKWISE_ITEM_NAME, 40, INDIGO_OK_STATE, 10));
	TRACE_STEP("goto within dead zone", false, goto_and_wait(171, INDIGO_OK_STATE, 10));
	TRACE_STEP("park", false, trace_park());
	TRACE_STEP("goto while parked", false, goto_azimuth(90, INDIGO_ALERT_STATE, 5));
	TRACE_STEP("steps while parked", false, change_number(DOME_STEPS_PROPERTY_NAME, DOME_STEPS_ITEM_NAME, 10, INDIGO_ALERT_STATE, 5));
	TRACE_STEP("unpark", false, unpark());
	TRACE_STEP("find home", false, trace_find_home());
	TRACE_STEP("goto 200", false, goto_and_wait(200, INDIGO_OK_STATE, 10));
	TRACE_STEP("abort in motion", true, trace_abort_in_motion());
	TRACE_STEP("abort idle", false, abort_motion(INDIGO_OK_STATE));
	TRACE_STEP("shutter open", false, shutter_and_wait(DOME_SHUTTER_OPENED_ITEM_NAME, INDIGO_OK_STATE, 15));
	TRACE_STEP("shutter close", false, shutter_and_wait(DOME_SHUTTER_CLOSED_ITEM_NAME, INDIGO_OK_STATE, 15));
	TRACE_STEP("shutter end switch", false, trace_emit(":SES,0,46000,0,0#"));
	TRACE_STEP("acceleration", false, change_pair(ACCELERATION_PROPERTY, 2000, 2500) && wait_log("TX", ":ARS2500#", 1, 3));
	TRACE_STEP("velocity", false, change_pair(VELOCITY_PROPERTY, 700, 900) && wait_log("TX", ":VRS900#", 1, 3));
	TRACE_STEP("range", false, change_pair(RANGE_PROPERTY, 55080, 40000) && wait_log("TX", ":RRS40000#", 1, 3));
	TRACE_STEP("home position", false, change_number(HOME_POSITION_PROPERTY, HOME_POSITION_ITEM, 1000, INDIGO_OK_STATE, 3) && wait_log("TX", ":HRR1000#", 1, 3));
	TRACE_STEP("rejected home position", false, change_number(HOME_POSITION_PROPERTY, HOME_POSITION_ITEM, 60000, INDIGO_OK_STATE, 3) && wait_log("TX", ":HRR1000#", 2, 3));
	TRACE_STEP("move threshold", false, change_number(THRESHOLD_PROPERTY, THRESHOLD_ITEM, 500, INDIGO_OK_STATE, 3) && wait_log("TX", ":DRR500#", 1, 3));
	TRACE_STEP("slaving threshold", false, change_number(DOME_SLAVING_PARAMETERS_PROPERTY_NAME, DOME_SLAVING_THRESHOLD_ITEM_NAME, 1, INDIGO_OK_STATE, 3));
	TRACE_STEP("save settings", false, change_switch(SETTINGS_PROPERTY, SETTINGS_SAVE_ITEM, INDIGO_OK_STATE, 3));
	TRACE_STEP("load defaults", false, change_switch(SETTINGS_PROPERTY, SETTINGS_DEFAULT_ITEM, INDIGO_OK_STATE, 3) && wait_log("TX", ":RRS46000#", 2, 3));
	TRACE_STEP("load settings", false, change_switch(SETTINGS_PROPERTY, SETTINGS_LOAD_ITEM, INDIGO_OK_STATE, 3) && wait_log("TX", ":RRS40000#", 2, 3));
	TRACE_STEP("rain", false, trace_control("rain", "1", ":Rain#"));
	TRACE_STEP("rain stopped", false, trace_control("rain", "0", ":RainStopped#"));
	TRACE_STEP("low battery", false, trace_control("battery", "500", ":BV500#"));
	TRACE_STEP("normal battery", false, trace_control("battery", "700", ":BV700#"));
	TRACE_STEP("xbee detect", false, trace_control("xb", "Detect", "XB->Detect"));
	TRACE_STEP("xbee online", false, trace_control("xb", "Online", "XB->Online"));
	TRACE_STEP("manual rotation", false, trace_control("rotate", "150", ":SER"));
	TRACE_STEP("disconnect", false, disconnect());
	if (capture_path) {
		FILE *file = fopen(capture_path, "w");
		CHECK(file != NULL);
		fwrite(trace_text, 1, trace_length, file);
		fclose(file);
		printf("Reference trace written to %s\n", capture_path);
	} else {
		FILE *file = fopen(NEXDOME3_REFERENCE_TRACE_PATH, "r");
		CHECK(file != NULL);
		reference = calloc(1, TRACE_SIZE);
		size_t length = fread(reference, 1, TRACE_SIZE - 1, file);
		fclose(file);
		reference[length] = 0;
		if (strcmp(reference, trace_text)) {
			char path[PATH_MAX];
			snprintf(path, sizeof(path), "%s/actual_trace.txt", fixture_dir);
			file = fopen(path, "w");
			if (file) {
				fwrite(trace_text, 1, trace_length, file);
				fclose(file);
			}
			fprintf(stderr, "Reference trace mismatch; actual trace kept in %s (diff it against %s)\n", path, NEXDOME3_REFERENCE_TRACE_PATH);
			indigo_test_failures++;
		}
	}
cleanup:
	atomic_store(&trace_active, false);
	free(reference);
	driver_down();
}

