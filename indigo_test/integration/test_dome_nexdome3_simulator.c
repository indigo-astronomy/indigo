// wait_settings waits for the reply to the last settings readback command of the connection
static bool connect_to(const char *port, indigo_property_state expected, bool wait_settings) {
	if (!set_port(port)) {
		return false;
	}
	int settings = log_count("TX", ":RRS");
	unsigned before = revision_of(CONNECTION_PROPERTY_NAME);
	if (request_switch(CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME) != INDIGO_OK || !wait_settled(CONNECTION_PROPERTY_NAME, before, expected, 45)) {
		return false;
	}
	if (expected != INDIGO_OK_STATE) {
		return !switch_of(CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME);
	}
	if (!switch_of(CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME)) {
		return false;
	}
	if (wait_settings) {
		if (!wait_log("TX", ":RRS", settings + 1, 5)) {
			return false;
		}
		indigo_usleep(300000);
	}
	return true;
}

static bool disconnect(void) {
	unsigned before = revision_of(CONNECTION_PROPERTY_NAME);
	return request_switch(CONNECTION_PROPERTY_NAME, CONNECTION_DISCONNECTED_ITEM_NAME) == INDIGO_OK && wait_settled(CONNECTION_PROPERTY_NAME, before, INDIGO_OK_STATE, 15) && switch_of(CONNECTION_PROPERTY_NAME, CONNECTION_DISCONNECTED_ITEM_NAME);
}

static bool start_connected(void) {
	return driver_up() && connect_to(simulator.port, INDIGO_OK_STATE, true);
}

static void driver_down(void) {
	DEFECT_EXIT();
	if (switch_of(CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME)) {
		disconnect();
	}
	indigo_result result = indigo_dome_nexdome3(INDIGO_DRIVER_SHUTDOWN, NULL);
	indigo_detach_client(&simulator_test_client);
	indigo_stop();
	pthread_mutex_lock(&observe_mutex);
	release_cached_properties();
	pthread_mutex_unlock(&observe_mutex);
	ASSERT_EQ_INT(INDIGO_OK, result);
}

