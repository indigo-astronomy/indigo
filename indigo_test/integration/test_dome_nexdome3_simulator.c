static void connection_failures_and_recovery(void) {
	CHECK(driver_up());
	CHECK(connect_to("/dev/indigo-nexdome3-nonexistent", INDIGO_ALERT_STATE, false));
	int descriptors = open_descriptors();
	CHECK(inject("FRR", "lost", 1));
	double started = now();
	CHECK(connect_to(simulator.port, INDIGO_ALERT_STATE, false));
	CHECK(now() - started < 12);
	CHECK(wait_message(CONNECTION_PROPERTY_NAME, "NexDome did not respond. Are you using the correct firmware?"));
	CHECK_EQ(descriptors, open_descriptors());
	CHECK(inject("FRR", "error", 1));
	CHECK(connect_to(simulator.port, INDIGO_ALERT_STATE, false));
	CHECK_EQ(2, rx_count("FRR"));
	CHECK_EQ(0, rx_count("SRR"));
	CHECK_EQ(descriptors, open_descriptors());
	CHECK(!present(POWER_PROPERTY) && !present(DOME_PARK_PROPERTY_NAME));
	CHECK(connect_to(simulator.port, INDIGO_OK_STATE, true));
	CHECK_STR("NexDome", text_of(INFO_PROPERTY_NAME, INFO_DEVICE_MODEL_ITEM_NAME));
	CHECK(disconnect());
	CHECK_EQ(descriptors, open_descriptors());
cleanup:
	driver_down();
}

static void goto_firmware_32(void) {
	CHECK(start_connected());
	unsigned busy = busy_of(DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME);
	double started = now();
	CHECK(goto_azimuth(180, INDIGO_OK_STATE, 10));
	CHECK(now() - started >= 1);
	CHECK_EQ(1, rx_count("GSR,27540"));
	CHECK(busy_of(DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME) > busy);
	CHECK(motion_stopped());
	CHECK_NEAR(180, azimuth_value(), 1e-4);
	CHECK(wait_state(DOME_STEPS_PROPERTY_NAME, INDIGO_OK_STATE, 2));
	// the status is requested 3 s after the request
	CHECK(wait_rx("SRR", 2, 4));
	int count = load_events();
	CHECK(events[rx_index(count, "SRR", 2)].time - events[rx_index(count, "GSR,27540", 1)].time >= 2.8);
	wait_status_request(started);
	CHECK(goto_and_wait(350, INDIGO_OK_STATE, 10));
	CHECK_EQ(1, rx_count("GSR,53550"));
	// the shortest way from 350 to 10 crosses zero clockwise
	int right = log_count("EV", ":right#");
	CHECK(goto_and_wait(10, INDIGO_OK_STATE, 10));
	CHECK_EQ(1, rx_count("GSR,1530"));
	CHECK_EQ(right + 1, log_count("EV", ":right#"));
	CHECK_NEAR(10, azimuth_value(), 1e-4);
	CHECK(goto_and_wait(12.4, INDIGO_OK_STATE, 10));
	CHECK_EQ(1, rx_count("GSR,1897"));
	CHECK_NEAR(1897 / STEPS_PER_DEGREE, azimuth_value(), 1e-4);
	// a target within the dead zone does not move: the status request completes it
	unsigned before = revision_of(DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME);
	started = now();
	CHECK_EQ(INDIGO_OK, request_number(DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME, DOME_HORIZONTAL_COORDINATES_AZ_ITEM_NAME, 13));
	CHECK(wait_rx("GSR,1989", 1, 3));
	indigo_usleep(1000000);
	CHECK_EQ(INDIGO_BUSY_STATE, state_of(DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME));
	CHECK(wait_settled(DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME, before, INDIGO_OK_STATE, 5));
	CHECK(now() - started >= 2.8);
	CHECK_NEAR(1897 / STEPS_PER_DEGREE, azimuth_value(), 1e-4);
	CHECK_EQ(0, rx_prefix_count("PWR"));
cleanup:
	driver_down();
}

