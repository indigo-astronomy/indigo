	CHECK(switch_of(DOME_ON_COORDINATES_SET_PROPERTY_NAME, DOME_ON_COORDINATES_SET_GOTO_ITEM_NAME));
	CHECK_EQ(INDIGO_RW_PERM, perm_of(DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME));
	CHECK(item_of(DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME, DOME_HORIZONTAL_COORDINATES_AZ_ITEM_NAME, &item));
	CHECK(item.number.min == 0 && item.number.max == 360);
	CHECK_NEAR(90, item.number.value, 1e-4);
	CHECK_EQ(INDIGO_OK_STATE, state_of(DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME));
	CHECK(item_of(DOME_STEPS_PROPERTY_NAME, DOME_STEPS_ITEM_NAME, &item));
	CHECK(item.number.min == 0 && item.number.max == 180 && !strcmp(item.label, "Relative move (°)"));
	CHECK(switch_of(DOME_PARK_PROPERTY_NAME, DOME_PARK_UNPARKED_ITEM_NAME));
	CHECK_EQ(INDIGO_OK_STATE, state_of(DOME_PARK_PROPERTY_NAME));
	CHECK(switch_of(DOME_SHUTTER_PROPERTY_NAME, DOME_SHUTTER_CLOSED_ITEM_NAME));
	CHECK_EQ(INDIGO_OK_STATE, state_of(DOME_SHUTTER_PROPERTY_NAME));
	CHECK(wait_message(DOME_SHUTTER_PROPERTY_NAME, "Shutter is closed."));
	// the slaving threshold is raised to the dead zone (300 steps)
	CHECK(wait_message(DOME_SLAVING_PARAMETERS_PROPERTY_NAME, "Dome synchrinization threshold updated as it can not be less than the dome minimal move."));
	CHECK_NEAR(300 / STEPS_PER_DEGREE, value_of(DOME_SLAVING_PARAMETERS_PROPERTY_NAME, DOME_SLAVING_THRESHOLD_ITEM_NAME), 1e-4);
