// The driver always advertises seven slots. On a five slot wheel the device ignores the request and
// reports nothing, so quantum_goto() must fail rather than hang, and the wheel must stay usable.
static void slot_beyond_the_device_capacity_is_refused(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	const char *arguments[] = { "--slots", "5", NULL };
	SERIAL_CHECK_TRUE(start_quantum(&simulator, arguments));
	SERIAL_CHECK_TRUE(start_serial_driver(&quantum_wheel, simulator.port));
	online = true;
	SERIAL_CHECK_TRUE(select_slot(5));
	SERIAL_CHECK_TRUE(request_slot(7));
	SERIAL_CHECK_TRUE(wait_for_property_state(WHEEL_SLOT_PROPERTY_NAME, INDIGO_ALERT_STATE));
	SERIAL_CHECK_TRUE(select_slot(3));
cleanup:
	if (online) { stop_serial_driver(&quantum_wheel); }
	stop_external_serial_simulator(&simulator);
}

