// Wheel class coverage for indigo_wheel_quantum against the standalone Quantum simulator over a
// real PTY. The Quantum protocol is zero based on the wire (G<slot-1>) and one based in INDIGO, and
// the wheel streams a P<position> line per step until it arrives, so quantum_goto() consumes the
// whole move before returning. The driver homes to slot 1 on connect and advertises seven slots.

#include <indigo_drivers/wheel_quantum/indigo_wheel_quantum.h>

#include "serial_simulator_test_common.h"

#ifndef WHEEL_QUANTUM_SIMULATOR_EXECUTABLE
#define WHEEL_QUANTUM_SIMULATOR_EXECUTABLE "build/integration/wheel_quantum_simulator"
#endif

static const simulator_driver_case quantum_wheel = {
	"Quantum Filter Wheel",
	"indigo_wheel_quantum",
	"Quantum Filter Wheel",
	indigo_wheel_quantum,
	false,
	NULL, 0, NULL, 0, NULL, 0, NULL, 0
};

static const char *const slot_name_items[] = {
	WHEEL_SLOT_NAME_1_ITEM_NAME, WHEEL_SLOT_NAME_2_ITEM_NAME, WHEEL_SLOT_NAME_3_ITEM_NAME,
	WHEEL_SLOT_NAME_4_ITEM_NAME, WHEEL_SLOT_NAME_5_ITEM_NAME, WHEEL_SLOT_NAME_6_ITEM_NAME,
	WHEEL_SLOT_NAME_7_ITEM_NAME
};

static const char *const slot_offset_items[] = {
	WHEEL_SLOT_OFFSET_1_ITEM_NAME, WHEEL_SLOT_OFFSET_2_ITEM_NAME, WHEEL_SLOT_OFFSET_3_ITEM_NAME,
	WHEEL_SLOT_OFFSET_4_ITEM_NAME, WHEEL_SLOT_OFFSET_5_ITEM_NAME, WHEEL_SLOT_OFFSET_6_ITEM_NAME,
	WHEEL_SLOT_OFFSET_7_ITEM_NAME
};

static bool start_quantum(external_serial_simulator *simulator, const char **arguments) {
	if (arguments == NULL) {
		return start_external_serial_simulator(simulator, WHEEL_QUANTUM_SIMULATOR_EXECUTABLE);
	}
	return start_external_serial_simulator_with_args(simulator, WHEEL_QUANTUM_SIMULATOR_EXECUTABLE, arguments);
}

static bool request_slot(double slot) {
	return indigo_change_number_property_1(&simulator_test_client, quantum_wheel.device_name, WHEEL_SLOT_PROPERTY_NAME, WHEEL_SLOT_ITEM_NAME, slot) == INDIGO_OK;
}

static bool select_slot(double slot) {
	return request_slot(slot) && wait_for_property_state(WHEEL_SLOT_PROPERTY_NAME, INDIGO_OK_STATE) && wait_for_number_item_value(WHEEL_SLOT_PROPERTY_NAME, WHEEL_SLOT_ITEM_NAME, slot, 0.001);
}

static void assert_wheel_class_property_completeness(void) {
	static const char *properties[] = {
		WHEEL_SLOT_PROPERTY_NAME,
		WHEEL_SLOT_NAME_PROPERTY_NAME,
		WHEEL_SLOT_OFFSET_PROPERTY_NAME
	};
	assert_defined_properties(properties, ARRAY_SIZE(properties));
}

