// Both ends of the range and a mid value, with the light on so the command actually reaches the
// panel. The published value stays in percent whatever the wire scale is.
static void intensity_is_accepted_across_the_range(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_flatmaster(&simulator, NULL));
	SERIAL_CHECK_TRUE(start_serial_driver(&flatmaster_aux, simulator.port));
	online = true;
	SERIAL_CHECK_TRUE(set_light(true));
	SERIAL_CHECK_TRUE(wait_for_property_state(AUX_LIGHT_SWITCH_PROPERTY_NAME, INDIGO_OK_STATE));
	const double percents[] = { 0, 1, 50, 99, 100 };
	for (int i = 0; i < ARRAY_SIZE(percents); i++) {
		SERIAL_CHECK_TRUE(set_intensity(percents[i]));
		SERIAL_CHECK_TRUE(wait_for_property_state(AUX_LIGHT_INTENSITY_PROPERTY_NAME, INDIGO_OK_STATE));
		SERIAL_CHECK_TRUE(wait_for_number_item_value(AUX_LIGHT_INTENSITY_PROPERTY_NAME, AUX_LIGHT_INTENSITY_ITEM_NAME, percents[i], 0.001));
	}
cleanup:
	if (online) { stop_serial_driver(&flatmaster_aux); }
	stop_external_serial_simulator(&simulator);
}

