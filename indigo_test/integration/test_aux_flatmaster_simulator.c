// Code is generated by AI

// AUX lightbox coverage for indigo_aux_flatmaster against the standalone FlatMaster simulator over
// a real PTY. The FlatMaster never reports its own light state, so the driver owns it: both
// properties are persistent, on_connect pushes them to the panel and on_disconnect darkens it.
// Intensity is inverted on the wire (100% maps to the lowest value) and is only sent while the
// light is on.

#include <indigo_drivers/aux_flatmaster/indigo_aux_flatmaster.h>

#include "serial_simulator_test_common.h"

#ifndef AUX_FLATMASTER_SIMULATOR_EXECUTABLE
#define AUX_FLATMASTER_SIMULATOR_EXECUTABLE "build/integration/aux_flatmaster_simulator"
#endif

static const simulator_driver_case flatmaster_aux = {
	"PegasusAstro FlatMaster Light",
	"indigo_aux_flatmaster",
	"PegasusAstro FlatMaster",
	indigo_aux_flatmaster,
	false,
	NULL, 0, NULL, 0, NULL, 0, NULL, 0
};

static bool start_flatmaster(external_serial_simulator *simulator, const char *firmware) {
	if (firmware == NULL) {
		return start_external_serial_simulator(simulator, AUX_FLATMASTER_SIMULATOR_EXECUTABLE);
	}
	const char *arguments[] = { "--firmware", firmware, NULL };
	return start_external_serial_simulator_with_args(simulator, AUX_FLATMASTER_SIMULATOR_EXECUTABLE, arguments);
}

static const char *info_text(const char *item_name) {
	indigo_item *item = find_cached_item(INFO_PROPERTY_NAME, item_name);
	return item == NULL ? "" : item->text.value;
}

static bool set_light(bool on) {
	return indigo_change_switch_property_1(&simulator_test_client, flatmaster_aux.device_name, AUX_LIGHT_SWITCH_PROPERTY_NAME, on ? AUX_LIGHT_SWITCH_ON_ITEM_NAME : AUX_LIGHT_SWITCH_OFF_ITEM_NAME, true) == INDIGO_OK;
}

static bool set_intensity(double percent) {
	return indigo_change_number_property_1(&simulator_test_client, flatmaster_aux.device_name, AUX_LIGHT_INTENSITY_PROPERTY_NAME, AUX_LIGHT_INTENSITY_ITEM_NAME, percent) == INDIGO_OK;
}

// -------------------------------------------------------------------------------- metadata

static void metadata_identity_and_property_completeness(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_flatmaster(&simulator, "2.7"));
	SERIAL_CHECK_TRUE(start_serial_driver(&flatmaster_aux, simulator.port));
	online = true;
	SERIAL_CHECK_TRUE(context.connected && context.last_connection_state == INDIGO_OK_STATE);
	assert_device_interface(INDIGO_INTERFACE_AUX_LIGHTBOX);
	static const char *properties[] = { AUX_LIGHT_SWITCH_PROPERTY_NAME, AUX_LIGHT_INTENSITY_PROPERTY_NAME };
	assert_defined_properties(properties, ARRAY_SIZE(properties));
	assert_property_has_item(AUX_LIGHT_SWITCH_PROPERTY_NAME, AUX_LIGHT_SWITCH_ON_ITEM_NAME);
	assert_property_has_item(AUX_LIGHT_SWITCH_PROPERTY_NAME, AUX_LIGHT_SWITCH_OFF_ITEM_NAME);
	assert_property_has_item(AUX_LIGHT_INTENSITY_PROPERTY_NAME, AUX_LIGHT_INTENSITY_ITEM_NAME);
	assert_number_item_in_range(AUX_LIGHT_INTENSITY_PROPERTY_NAME, AUX_LIGHT_INTENSITY_ITEM_NAME);
	// The panel has no cover, so AUX_COVER must not appear.
	assert_not_defined_property(AUX_COVER_PROPERTY_NAME);
	printf("Model '%s' firmware '%s'\n", info_text(INFO_DEVICE_MODEL_ITEM_NAME), info_text(INFO_DEVICE_FW_REVISION_ITEM_NAME));
	SERIAL_CHECK_TRUE(!strcmp(info_text(INFO_DEVICE_FW_REVISION_ITEM_NAME), "2.7"));
	SERIAL_CHECK_TRUE(strcmp(info_text(INFO_DEVICE_MODEL_ITEM_NAME), "Unknown") != 0);
cleanup:
	if (online) { stop_serial_driver(&flatmaster_aux); }
	stop_external_serial_simulator(&simulator);
}

// on_connect pushes the driver's own state to the panel, so both properties have to settle OK
// rather than stay in their attach-time state.
static void connect_publishes_both_controls_ok(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_flatmaster(&simulator, NULL));
	SERIAL_CHECK_TRUE(start_serial_driver(&flatmaster_aux, simulator.port));
	online = true;
	SERIAL_CHECK_TRUE(wait_for_property_state(AUX_LIGHT_INTENSITY_PROPERTY_NAME, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(wait_for_property_state(AUX_LIGHT_SWITCH_PROPERTY_NAME, INDIGO_OK_STATE));
	assert_switch_item_value(AUX_LIGHT_SWITCH_PROPERTY_NAME, AUX_LIGHT_SWITCH_OFF_ITEM_NAME, true);
cleanup:
	if (online) { stop_serial_driver(&flatmaster_aux); }
	stop_external_serial_simulator(&simulator);
}

