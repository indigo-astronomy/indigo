static void guide_duration_measurements(void) {
	ASSERT_TRUE(connect_device(0, true));
	ASSERT_TRUE(connect_device(1, true));
	const char *items[] = { "NORTH", "SOUTH", "EAST", "WEST" };
	const double durations[] = { 20, 50, 100, 250, 500 };
	double errors[80];
	int samples = 0;
	for (int workload = 0; workload < 2; workload++) {
		if (workload) {
			ASSERT_TRUE(number(0, "CCD_EXPOSURE", "EXPOSURE", 16.5, INDIGO_BUSY_STATE));
		}
		for (int direction = 0; direction < 4; direction++) {
			ASSERT_TRUE(number(1, direction < 2 ? "GUIDER_GUIDE_DEC" : "GUIDER_GUIDE_RA", items[direction], 20, INDIGO_OK_STATE));
			for (int sample = 0; sample < 10; sample++) {
				int j = sample % 5;
				ASSERT_TRUE(number(1, direction < 2 ? "GUIDER_GUIDE_DEC" : "GUIDER_GUIDE_RA", items[direction], durations[j], INDIGO_OK_STATE));
				double error = cameras[0].pulse_ms[direction] - durations[j];
				errors[samples++] = error;
				printf("pulse %s requested %.0f measured %.3f error %+.3f ms (%+.2f%%) workload=%d\n", items[direction], durations[j], cameras[0].pulse_ms[direction], error, error * 100 / durations[j], workload);
			}
		}
		if (workload) {
			ASSERT_TRUE(toggle(0, "CCD_ABORT_EXPOSURE", "ABORT_EXPOSURE", INDIGO_OK_STATE));
		}
	}
	double sum = 0, squares = 0, min = errors[0], max = errors[0];
	for (int i = 0; i < samples; i++) {
		sum += errors[i];
		squares += errors[i] * errors[i];
		min = fmin(min, errors[i]);
		max = fmax(max, errors[i]);
	}
	for (int i = 1; i < samples; i++) {
		double v = errors[i];
		int j = i;
		while (j > 0 && errors[j - 1] > v) {
			errors[j] = errors[j - 1];
			j--;
		}
		errors[j] = v;
	}
	printf("pulse signed errors n=%d min=%.3f mean=%.3f median=%.3f p95=%.3f p99=%.3f max=%.3f stddev=%.3f maxabs=%.3f ms\n", samples, min, sum / samples, (errors[39] + errors[40]) / 2, errors[75], errors[79], max, sqrt(fmax(0, squares / samples - sum * sum / samples / samples)), fmax(fabs(min), fabs(max)));
}

