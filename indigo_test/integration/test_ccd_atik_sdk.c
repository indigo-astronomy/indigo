int ArtemisGuidePort(ArtemisHandle h, int mask) {
	SDK_SCOPE;
	if (failed(__func__)) {
		return failed(__func__);
	}
	mock_camera *c = camera(h);
	double now = indigo_monotonic_time();
	for (int i = 0; i < 4; i++) {
		if ((mask & (1 << i)) && !(c->relay & (1 << i))) {
			c->pulse_on[i] = now;
		}
		if (!(mask & (1 << i)) && (c->relay & (1 << i))) {
			c->pulse_ms[i] = (now - c->pulse_on[i]) * 1000;
		}
	}
	c->relay = mask;
	return failed(__func__);
	}

