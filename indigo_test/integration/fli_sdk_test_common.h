indigo_result fli_test_attach(indigo_device *device) {
	atomic_fetch_add(&fli_attach_attempts, 1);
	for (int i = 0; i < FLI_TEST_DEVICES; i++) {
		if (fli_observed[i].name[0] == 0) {
			snprintf(fli_observed[i].name, sizeof(fli_observed[i].name), "%s", device->name);
			break;
		}
	}
	indigo_result result = indigo_attach_device(device);
	if (result == INDIGO_OK) {
		atomic_fetch_add(&fli_attached, 1);
	}
	return result;
}

indigo_result fli_test_detach(indigo_device *device) {
	indigo_result result = indigo_detach_device(device);
	for (int i = 0; i < FLI_TEST_DEVICES; i++) {
		if (!strcmp(fli_observed[i].name, device->name)) {
			pthread_mutex_lock(&fli_observation_mutex);
			for (int j = 0; j < FLI_TEST_PROPERTIES; j++) {
				indigo_release_property(fli_observed[i].properties[j]);
				fli_observed[i].properties[j] = NULL;
			}
			fli_observed[i].name[0] = 0;
			pthread_mutex_unlock(&fli_observation_mutex);
			break;
		}
	}
	atomic_fetch_sub(&fli_attached, 1);
	return result;
}

