// A connection change publishes BUSY before its handler runs, so the settled
// state is only meaningful once the driver has published again.
static bool fli_wait_connection(int index, bool connected, int before) {
	for (int i = 0; i < 400; i++) {
		if (fli_updates(index, CONNECTION_PROPERTY_NAME) > before) {
			indigo_property *property = fli_snapshot(index, CONNECTION_PROPERTY_NAME);
			indigo_item *item = fli_snapshot_item(property, connected ? CONNECTION_CONNECTED_ITEM_NAME : CONNECTION_DISCONNECTED_ITEM_NAME);
			bool settled = property != NULL && property->state != INDIGO_BUSY_STATE && item != NULL && item->sw.value;
			indigo_release_property(property);
			if (settled) {
				return true;
			}
		}
		indigo_usleep(25000);
	}
	return false;
}

static bool fli_connect_expect(int index, bool expected) {
	int before = fli_updates(index, CONNECTION_PROPERTY_NAME);
	if (!fli_set_switch(index, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, true)) {
		return false;
	}
	if (!fli_wait_connection(index, expected, before)) {
		fprintf(stderr, "Connection never settled %s (state %d)\n", expected ? "connected" : "disconnected", fli_property_state(index, CONNECTION_PROPERTY_NAME));
		return false;
	}
	return fli_property_state(index, CONNECTION_PROPERTY_NAME) == (expected ? INDIGO_OK_STATE : INDIGO_ALERT_STATE);
}

static bool fli_connect(int index) {
	return fli_connect_expect(index, true);
}

static bool fli_disconnect(int index) {
	int before = fli_updates(index, CONNECTION_PROPERTY_NAME);
	if (!fli_set_switch(index, CONNECTION_PROPERTY_NAME, CONNECTION_DISCONNECTED_ITEM_NAME, true)) {
		return false;
	}
	return fli_wait_connection(index, false, before);
}

static void fli_release_observations(void) {
	pthread_mutex_lock(&fli_observation_mutex);
	for (int i = 0; i < FLI_TEST_DEVICES; i++) {
		for (int j = 0; j < FLI_TEST_PROPERTIES; j++) {
			indigo_release_property(fli_observed[i].properties[j]);
			fli_observed[i].properties[j] = NULL;
			fli_observed[i].updates[j] = 0;
		}
		fli_observed[i].name[0] = 0;
	}
	pthread_mutex_unlock(&fli_observation_mutex);
}

typedef indigo_result (*fli_driver_entry)(indigo_driver_action action, indigo_driver_info *info);

static bool fli_driver_up(fli_driver_entry entry) {
	fli_release_observations();
	atomic_store(&fli_attached, 0);
	atomic_store(&fli_attach_attempts, 0);
	atomic_store(&fli_usb_refs, 0);
	atomic_store(&fli_invalid_usb_unref, 0);
	if (indigo_start() != INDIGO_OK || indigo_attach_client(&fli_test_client) != INDIGO_OK) {
		return false;
	}
	return entry(INDIGO_DRIVER_INIT, NULL) == INDIGO_OK;
}

// Every attached device has to be disconnected before the driver accepts
// SHUTDOWN, and the disconnect has to be observed, not just requested.
static void fli_driver_down(fli_driver_entry entry) {
	for (int i = 0; i < FLI_TEST_DEVICES; i++) {
		if (fli_observed[i].name[0] && fli_switch_is_quiet(i, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, true)) {
			fli_disconnect(i);
		}
	}
	ASSERT_EQ_INT(INDIGO_OK, entry(INDIGO_DRIVER_SHUTDOWN, NULL));
	indigo_detach_client(&fli_test_client);
	ASSERT_EQ_INT(INDIGO_OK, indigo_stop());
	fli_release_observations();
	ASSERT_EQ_INT(0, atomic_load(&fli_invalid_usb_unref));
}

