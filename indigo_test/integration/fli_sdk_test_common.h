static void fli_observe(const char * const *names, int count) {
	fli_observed_names = names;
	fli_observed_name_count = count;
}

static bool fli_is_observed(const char *name) {
	for (int i = 0; i < fli_observed_name_count; i++) {
		if (!strcmp(fli_observed_names[i], name)) {
			return true;
		}
	}
	return false;
}

static int fli_device_index(const char *name) {
	for (int i = 0; i < FLI_TEST_DEVICES; i++) {
		if (fli_observed[i].name[0] && !strcmp(fli_observed[i].name, name)) {
			return i;
		}
	}
	return -1;
}

static int fli_find_device(const char *prefix) {
	for (int i = 0; i < FLI_TEST_DEVICES; i++) {
		if (fli_observed[i].name[0] && !strncmp(fli_observed[i].name, prefix, strlen(prefix))) {
			return i;
		}
	}
	return -1;
}

static int fli_property_slot(int index, const char *name, bool create) {
	int empty = -1;
	for (int i = 0; i < FLI_TEST_PROPERTIES; i++) {
		if (fli_observed[index].properties[i] && !strcmp(fli_observed[index].properties[i]->name, name)) {
			return i;
		}
		if (fli_observed[index].properties[i] == NULL && empty < 0) {
			empty = i;
		}
	}
	return create ? empty : -1;
}

static indigo_result fli_observe_define(indigo_client *client, indigo_device *device, indigo_property *property, const char *message) {
	int index = fli_device_index(property->device);
	if (index < 0 || !fli_is_observed(property->name)) {
		return INDIGO_OK;
	}
	pthread_mutex_lock(&fli_observation_mutex);
	int slot = fli_property_slot(index, property->name, true);
	if (slot >= 0) {
		indigo_release_property(fli_observed[index].properties[slot]);
		fli_observed[index].properties[slot] = indigo_copy_property(NULL, property);
		fli_observed[index].updates[slot]++;
	}
	pthread_mutex_unlock(&fli_observation_mutex);
	return INDIGO_OK;
}

static indigo_result fli_observe_delete(indigo_client *client, indigo_device *device, indigo_property *property, const char *message) {
	int index = fli_device_index(property->device);
	if (index < 0) {
		return INDIGO_OK;
	}
	pthread_mutex_lock(&fli_observation_mutex);
	for (int i = 0; i < FLI_TEST_PROPERTIES; i++) {
		indigo_property *cached = fli_observed[index].properties[i];
		if (cached && (!property->name[0] || !strcmp(cached->name, property->name))) {
			indigo_release_property(cached);
			fli_observed[index].properties[i] = NULL;
		}
	}
	pthread_mutex_unlock(&fli_observation_mutex);
	return INDIGO_OK;
}

static indigo_client fli_test_client = {
	.name = "FLI fake SDK test",
	.version = INDIGO_VERSION_CURRENT,
	.define_property = fli_observe_define,
	.update_property = fli_observe_define,
	.delete_property = fli_observe_delete
};

static indigo_property *fli_snapshot(int index, const char *name) {
	if (index < 0 || index >= FLI_TEST_DEVICES) {
		return NULL;
	}
	pthread_mutex_lock(&fli_observation_mutex);
	int slot = fli_property_slot(index, name, false);
	indigo_property *copy = slot < 0 ? NULL : indigo_copy_property(NULL, fli_observed[index].properties[slot]);
	pthread_mutex_unlock(&fli_observation_mutex);
	return copy;
}

static indigo_item *fli_snapshot_item(indigo_property *property, const char *item_name) {
	for (int i = 0; property != NULL && i < property->count; i++) {
		if (!strcmp(property->items[i].name, item_name)) {
			return property->items + i;
		}
	}
	return NULL;
}

static int fli_property_state(int index, const char *name) {
	indigo_property *property = fli_snapshot(index, name);
	int state = property ? (int)property->state : -1;
	indigo_release_property(property);
	return state;
}

static bool fli_number_is(int index, const char *property_name, const char *item_name, double expected) {
	indigo_property *property = fli_snapshot(index, property_name);
	indigo_item *item = fli_snapshot_item(property, item_name);
	bool result = item != NULL && fabs(item->number.value - expected) < 0.001;
	if (!result) {
		fprintf(stderr, "%s.%s: expected %g, received %g\n", property_name, item_name, expected, item ? item->number.value : NAN);
	}
	indigo_release_property(property);
	return result;
}

