typedef struct {
	const char *name;
	void (*run)(void);
	const char *profile, *key, *action;
} moonlite_test;

static int run_cases(const moonlite_test *cases, int count) {
	int failures = 0, executed = 0;
	setvbuf(stdout, NULL, _IOLBF, 0);
	const char *filter = getenv("MOONLITE_TEST_FILTER");
	if (!mkdtemp(fixture_dir)) {
		return 1;
	}
	snprintf(event_path, sizeof(event_path), "%s/events", fixture_dir);
	snprintf(fault_path, sizeof(fault_path), "%s/fault", fixture_dir);
	setenv("INDIGO_MOONLITE_EVENTS", event_path, 1);
	setenv("INDIGO_MOONLITE_FAULT", fault_path, 1);
	for (int index = 0; index < count; index++) {
		if (filter && !strstr(cases[index].name, filter)) {
			continue;
		}
		executed++;
		current_profile = cases[index].profile;
		current_key = cases[index].key;
		current_action = cases[index].action;
		unlink(fault_path);
		const char *simulator_profile = !strcmp(current_profile, "split") || !strcmp(current_profile, "alternate") ? current_profile : "normal";
		const char *args[] = { "--profile", simulator_profile, NULL };
		if (!start_external_serial_simulator_with_args(&fixture, FOCUSER_MOONLITE_SIMULATOR_EXECUTABLE, args)) {
			failures++;
			break;
		}
		if (!strcmp(cases[index].name, "instances")) {
			unsetenv("INDIGO_MOONLITE_EVENTS");
			unsetenv("INDIGO_MOONLITE_FAULT");
			const char *second_args[] = { "--profile", "alternate", NULL };
			bool ready = start_external_serial_simulator_with_args(&second_fixture, FOCUSER_MOONLITE_SIMULATOR_EXECUTABLE, second_args);
			setenv("INDIGO_MOONLITE_EVENTS", event_path, 1);
			setenv("INDIGO_MOONLITE_FAULT", fault_path, 1);
			if (!ready) {
				stop_external_serial_simulator(&fixture);
				failures++;
				break;
			}
		}
		fflush(NULL);
		pid_t child = fork();
		if (child == 0) {
			alarm(30);
			indigo_test_case test = { cases[index].name, cases[index].run };
			_exit(indigo_run_tests("MoonLite", &test, 1));
		}
		int status = 0;
		if (child > 0) {
			while (waitpid(child, &status, 0) < 0 && errno == EINTR) {
			}
		}
		stop_external_serial_simulator(&fixture);
		stop_external_serial_simulator(&second_fixture);
		if (child < 0 || !WIFEXITED(status) || WEXITSTATUS(status)) {
			fprintf(stderr, "FAIL %s (status %d)\n", cases[index].name, status);
			FILE *events = fopen(event_path, "r");
			if (events) {
				char line[512];
				while (fgets(line, sizeof(line), events)) {
					fputs(line, stderr);
				}
				fclose(events);
			}
			failures++;
		}
	}
	unlink(fault_path);
	unlink(event_path);
	rmdir(fixture_dir);
	unsetenv("INDIGO_MOONLITE_EVENTS");
	unsetenv("INDIGO_MOONLITE_FAULT");
	printf("MoonLite: %d/%d scenarios passed\n", executed - failures, executed);
	return failures ? 1 : 0;
}

