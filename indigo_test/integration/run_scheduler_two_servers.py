class Interrupted(BaseException):
	"""SIGTERM or SIGHUP: like KeyboardInterrupt, it ends the run without recording the unfinished cases."""


def interrupt(signum, frame):
	# a second signal during the cleanup must not interrupt it
	signal.signal(signal.SIGTERM, signal.SIG_IGN)
	signal.signal(signal.SIGHUP, signal.SIG_IGN)
	raise Interrupted(signal.Signals(signum).name)


def free_port():
	with socket.socket() as reservation:
		reservation.bind(("127.0.0.1", 0))
		return reservation.getsockname()[1]


class Relay:
	"""A TCP relay between the servers; drop() cuts every connection and refuses new ones until restore()."""

	def __init__(self, target_port):
		self.target_port = target_port
		self.listener = socket.socket()
		self.listener.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
		self.listener.bind(("127.0.0.1", 0))
		self.listener.listen(8)
		self.port = self.listener.getsockname()[1]
		self.lock = threading.Lock()
		self.sockets = []
		self.blocked = False
		self.closed = False
		self.accepted = 0
		self.refused = 0
		self.thread = threading.Thread(target=self.accept, daemon=True)
		self.thread.start()

	def accept(self):
		while True:
			try:
				connection, _ = self.listener.accept()
			except OSError:
				return
			with self.lock:
				if self.closed or self.blocked:
					self.refused += 1
					connection.close()
					continue
			try:
				upstream = socket.create_connection(("127.0.0.1", self.target_port), timeout=5)
				upstream.settimeout(None)
			except OSError:
				connection.close()
				continue
			with self.lock:
				# a cut while the upstream connected must not let the pair through
				if self.closed or self.blocked:
					self.refused += 1
					connection.close()
					upstream.close()
					continue
				self.accepted += 1
				self.sockets += [connection, upstream]
			threading.Thread(target=self.pump, args=(connection, upstream), daemon=True).start()
			threading.Thread(target=self.pump, args=(upstream, connection), daemon=True).start()

	def pump(self, source, destination):
		try:
			while True:
				data = source.recv(65536)
				if not data:
					break
				destination.sendall(data)
		except OSError:
			pass
		for s in (source, destination):
			try:
				s.shutdown(socket.SHUT_RDWR)
			except OSError:
				pass

	def cut(self):
		with self.lock:
			sockets, self.sockets = self.sockets, []
		for s in sockets:
			try:
				s.shutdown(socket.SHUT_RDWR)
			except OSError:
				pass
			s.close()

	def drop(self):
		with self.lock:
			self.blocked = True
		self.cut()

	def restore(self):
		with self.lock:
			self.blocked = False

	def close(self):
		with self.lock:
			self.closed = True
		self.listener.close()
		self.cut()
		self.thread.join(5)


class Server:

	def __init__(self, name, repo, output, drivers, remote=None):
		self.name = name
		self.port = free_port()
		self.home = output / ("home_" + name)
		self.home.mkdir()
		self.log_path = output / ("server_" + name + ".log")
		command = [str(repo / "build/bin/indigo_server"), "--", "-p", str(self.port), "-b-", "-c-", "-w-"]
		if remote:
			command += ["-r", "localhost:%d" % remote]
		if os.environ.get("INDIGO_TEST_DEBUG"):
			command.append(os.environ["INDIGO_TEST_DEBUG"])
		# drivers by path, so that the test needs only the drivers it uses and not the list of the top-level build
		command += [str(repo / "build/drivers" / ("indigo_" + d + (".dylib" if sys.platform == "darwin" else ".so"))) for d in drivers]
		env = dict(os.environ, HOME=str(self.home), INDIGO_CACHE_BASE=str(self.home / ".indigo"))
		# the library of this checkout, also when the environment points at another build
		for variable in ("LD_LIBRARY_PATH", "DYLD_LIBRARY_PATH"):
			env[variable] = os.pathsep.join([str(repo / "build/lib")] + ([env[variable]] if env.get(variable) else []))
		self.log = self.log_path.open("w")
		# a session of its own, so that every process the server leaves behind can be found by its group
		self.process = subprocess.Popen(command, cwd=output, env=env, stdout=self.log, stderr=subprocess.STDOUT, start_new_session=True)
		self.group = self.process.pid

	def wait_listening(self, timeout=20):
		deadline = time.monotonic() + timeout
		while True:
			if self.process.poll() is not None:
				raise RuntimeError("indigo_server " + self.name + " exited, see " + str(self.log_path))
			try:
				return socket.create_connection(("127.0.0.1", self.port), timeout=0.5)
			except OSError:
				if time.monotonic() >= deadline:
					raise TimeoutError("indigo_server " + self.name + " did not start")
				time.sleep(0.1)

	def stop(self, timeout=20):
		"""SIGTERM and the exit code; kills the group when the server does not exit in time."""
		if self.process.poll() is None:
			self.process.send_signal(signal.SIGTERM)
			try:
				self.process.wait(timeout=timeout)
			except subprocess.TimeoutExpired:
				self.kill()
				return None
		self.log.close()
		return self.process.returncode

	def kill(self):
		try:
			os.killpg(self.group, signal.SIGKILL)
		except OSError:
			pass
		if self.process.poll() is None:
			self.process.wait()
		if not self.log.closed:
			self.log.close()

	def group_alive(self):
		try:
			os.killpg(self.group, 0)
			return True
		except ProcessLookupError:
			return False
		except PermissionError:
			return True


class Topology:

	def __init__(self, name, repo, output, records):
		self.name = name
		self.repo = repo
		self.output = output
		self.records = records
		self.images = output / "images"
		self.images.mkdir()
		self.results = []
		self.servers = []
		self.relay = None
		self.client = None
		self.log = None

	def record(self, line):
		if self.records:
			with open(self.records, "a") as out:
				out.write(line + "\n")

	def case(self, name, function):
		started = time.monotonic()
		full = self.name + ": " + name
		try:
			function()
			status, detail = "pass", ""
		except Exception as error:
			status, detail = "fail", type(error).__name__ + ": " + str(error)
		if status == "fail" and name not in (CASES[0], CASES[4]):
			self.recover()
		self.results.append({"name": full, "status": status, "detail": detail, "seconds": round(time.monotonic() - started, 1), "snapshot": self.snapshot() if status == "fail" else None})
		self.record(status + "\t" + SUITE + "\t" + full)
		print(("  PASS " if status == "pass" else "  FAIL ") + full + (" - " + detail if detail else "") + " (%.1f s)" % (time.monotonic() - started), flush=True)
		return status == "pass"

	def recover(self):
		"""After a failed case: abort, wait for the stop and delete the tasks, so that the next case starts clean."""
		try:
			self.relay.restore()
			self.control("ABORT")
			self.wait_stopped(90)
			self.delete_all()
		except Exception as error:
			print("    recovery after the failure failed: " + str(error), flush=True)

	def snapshot(self):
		if not self.client:
			return None
		keys = [(AGENT, "AGENT_SCHEDULER_TASK_STATE"), (AGENT, "AGENT_SCHEDULER_CURRENT"), (AGENT, "AGENT_SCHEDULER_STATE"), (self.scripting, "SEQUENCE_STATE"), (self.scripting, "SCHEDULER_RESULT"), (self.imager, "AGENT_START_PROCESS")]
		return {"/".join(k): self.client.property(*k) for k in keys}

	# ---------------------------------------------------------------------------- helpers

	def control(self, item):
		self.client.change_switch(AGENT, "AGENT_SCHEDULER_CONTROL", {item: True})

	def upload(self, text):
		key = (AGENT, "AGENT_SCHEDULER_ADD_TASK")
		before = self.client.updates.get(key, 0)
		self.client.change_text(AGENT, "AGENT_SCHEDULER_ADD_TASK", {"TASK": text})
		self.client.wait(lambda: self.client.updates.get(key, 0) > before and self.client.state(*key) != "Busy", 10, "upload result")
		assert self.client.state(*key) == "Ok", "upload rejected: " + str(self.client.messages[-1:])

	def task_items(self):
		return (self.client.property(AGENT, "AGENT_SCHEDULER_TASK_STATE") or {}).get("items", [])

	def task_state(self, name):
		label = self.client.task_label(name)
		columns = label.split(" | ")
		return columns[1] if len(columns) > 1 else None

	def wait(self, predicate, timeout, describe):
		"""Client.wait with a description made at the timeout, so that it shows the final state."""
		try:
			self.client.wait(predicate, timeout, "")
		except TimeoutError:
			raise TimeoutError("timed out waiting for " + (describe() if callable(describe) else describe)) from None

	def wait_task(self, name, state, timeout):
		self.wait(lambda: self.task_state(name) == state, timeout, lambda: "task " + name + " in " + state + " (label '" + self.client.task_label(name) + "')")

	def wait_tasks(self, names, state, timeout):
		self.wait(lambda: all(self.task_state(n) == state for n in names), timeout, lambda: "tasks in " + state + ": " + str({n: self.client.task_label(n) for n in names if self.task_state(n) != state}))

	def counter(self, item):
		return self.client.value(AGENT, "AGENT_SCHEDULER_STATE", item)

	def history(self, name):
		entries = []
		for i in (self.client.property(AGENT, "AGENT_SCHEDULER_HISTORY") or {}).get("items", []):
			columns = i.get("label", "").split(" | ")
			if len(columns) == 6 and columns[1] == name:
				entries.append((columns[3], columns[4], columns[5]))
		return entries

	def frames(self, name):
		# the folder of the task, named after it by the scheduler (FOLDER of AGENT_SCHEDULER_DATA)
		folder = self.images / name
		return sorted(p for p in folder.iterdir() if p.is_file() and p.suffix == ".fits" and p.stat().st_size > 2880) if folder.is_dir() else []

	def all_frames(self):
		return sorted(p for p in self.images.rglob("*.fits") if p.is_file())

	def assert_frames_belong(self, name):
		for frame in self.frames(name):
			header = fits_header(frame)
			assert header.get("SCHTASK") == name, "%s has SCHTASK %r, expected %r" % (frame, header.get("SCHTASK"), name)

	def busy(self, device, name):
		return self.client.state(device, name) == "Busy"

	def capture_task(self, name, count, exposure, extra=""):
		prefix = name.lower().replace(" ", "_")
		body = "var sequence = new Sequence(scheduler_task.name);\n"
		body += "sequence.select_imager_camera(" + json.dumps(CAMERA) + ");\n"
		body += "sequence.select_image_format(\"FITS\");\n"
		body += "sequence.select_frame_type(\"Light\");\n"
		body += "sequence.set_frame(0, 0, 320, 240);\n"
		body += "sequence.capture_batch(" + json.dumps(prefix + "_XXX") + ", " + str(count) + ", " + str(exposure) + ");\n"
		body += "sequence.start();\n"
		return "// @task " + name + "\n" + extra + "\n" + body

	def wait_stopped(self, timeout=60):
		self.wait(lambda: self.client.state(AGENT, "AGENT_SCHEDULER_STATE") != "Busy" and not (self.client.value(AGENT, "AGENT_SCHEDULER_CURRENT", "CURRENT") or ""), timeout, lambda: "scheduler stopped (state " + str(self.client.state(AGENT, "AGENT_SCHEDULER_STATE")) + ", current " + str(self.client.value(AGENT, "AGENT_SCHEDULER_CURRENT", "CURRENT")) + ")")

	def wait_idle_agents(self, timeout=60):
		self.client.wait(lambda: not self.busy(self.scripting, "SEQUENCE_STATE") and not self.busy(self.imager, "AGENT_START_PROCESS"), timeout, "sequence and imager idle")

	def assert_no_busy_task(self):
		busy = [i.get("label") for i in self.task_items() if i.get("value") == "Busy"]
		assert not busy, "tasks left Busy: " + str(busy)

	def delete_all(self):
		self.client.change_switch(AGENT, "AGENT_SCHEDULER_TASK_COMMAND", {"DELETE_ALL": True})
		self.client.wait(lambda: not self.task_items(), 10, "tasks deleted")

	# ---------------------------------------------------------------------------- run

	def run(self):
		remote = self.name == "scripting-remote"
		b_drivers = (["agent_scripting"] if remote else []) + ["agent_imager", "ccd_simulator"]
		a_drivers = ["agent_scheduler"] + ([] if remote else ["agent_scripting"])
		error = None
		interrupted = False
		try:
			self.log = (self.output / "messages.jsonl").open("w")
			server_b = Server("B", self.repo, self.output, b_drivers)
			self.servers.append(server_b)
			server_b.wait_listening().close()
			self.relay = Relay(server_b.port)
			server_a = Server("A", self.repo, self.output, a_drivers, remote=self.relay.port)
			self.servers.append(server_a)
			self.client = Client(server_a.wait_listening(), self.log)
			self.suffix = " @ localhost:%d" % self.relay.port
			self.scripting = "Scripting Agent" + (self.suffix if remote else "")
			self.imager = "Imager Agent" + self.suffix
			self.camera = CAMERA + self.suffix
			self.client.send("getProperties", {"version": 0x300})
			if not self.case(CASES[0], self.configure):
				raise RuntimeError("the topology could not be set up")
			self.case(CASES[1], self.queue)
			self.case(CASES[2], self.start_abort_restart)
			self.case(CASES[3], self.link_loss)
		except Exception as exception:
			error = type(exception).__name__ + ": " + str(exception)
			print(self.name + ": " + error, file=sys.stderr)
		except BaseException:
			# interrupted: the caller kills the servers, nothing unfinished is recorded
			interrupted = True
			raise
		finally:
			if not interrupted:
				self.case(CASES[4], self.clean_exit)
			if self.relay and interrupted:
				self.relay.close()
			if self.log:
				self.log.close()
		return error

	# ---------------------------------------------------------------------------- cases

	def configure(self):
		client = self.client
		client.wait(lambda: client.property(AGENT, "AGENT_SCHEDULER_AGENTS") is not None, 30, "Scheduler Agent")
		client.wait(lambda: client.property(self.scripting, "AGENT_SCRIPTING_RUN_SCRIPT") is not None and client.property(self.imager, "FILTER_CCD_LIST") is not None and client.property(self.camera, "CONNECTION") is not None, 30, "agents of server B on server A (" + self.suffix + ")")
		client.change_text(AGENT, "AGENT_SCHEDULER_AGENTS", {"SCRIPTING": self.scripting, "IMAGER": self.imager})
		client.wait(lambda: client.value(AGENT, "AGENT_SCHEDULER_AGENTS", "SCRIPTING") == self.scripting and client.value(AGENT, "AGENT_SCHEDULER_AGENTS", "IMAGER") == self.imager, 10, "agents configured")
		assert client.state(AGENT, "AGENT_SCHEDULER_AGENTS") == "Ok", "AGENT_SCHEDULER_AGENTS refused: " + str(client.messages[-1:])
		# the scheduler labels a run only when CCD_LOCAL_MODE of the Imager Agent is known, i.e. with a camera selected
		client.change_switch(self.imager, "FILTER_CCD_LIST", {CAMERA: True})
		client.wait(lambda: client.property(self.imager, "CCD_LOCAL_MODE") is not None, 30, "camera selected in " + self.imager)
		client.change_number(AGENT, "AGENT_SCHEDULER_SETTINGS", {"IDLE_CHECK_INTERVAL": 1, "STOP_TIMEOUT": 60, "START_TIMEOUT": 10})
		client.change_switch(AGENT, "AGENT_SCHEDULER_DATA", {"OBJECT": True, "FITS": True, "FOLDER": True})
		client.change_text(AGENT, "AGENT_SCHEDULER_DATA_DIR", {"BASE": str(self.images) + "/"})
		client.wait(lambda: client.value(AGENT, "AGENT_SCHEDULER_DATA", "FOLDER") is True and client.value(AGENT, "AGENT_SCHEDULER_DATA_DIR", "BASE") == str(self.images) + "/", 10, "data settings")
		# the selectors list the configured agents on the bus with their suffix
		client.wait(lambda: client.value(AGENT, "AGENT_SCHEDULER_SCRIPTING_AGENT_LIST", self.scripting) is True and client.value(AGENT, "AGENT_SCHEDULER_IMAGER_AGENT_LIST", self.imager) is True, 20, "configured agents selected in the lists")
		self.control("START")
		client.wait(lambda: client.state(AGENT, "AGENT_SCHEDULER_STATE") == "Busy", 10, "scheduler running")
		# the scheduler loads the library into the configured Scripting Agent
		client.wait(lambda: client.property(self.scripting, "SEQUENCE_STATE") is not None, 30, "Sequencer.js loaded into " + self.scripting)
		# the scheduler owns the sequencer with the agents as the Scripting Agent knows them
		local_imager = "Imager Agent" if self.name == "scripting-remote" else self.imager
		client.wait(lambda: client.value(self.scripting, "SEQUENCER_OWNER", "OWNER") == AGENT and client.value(self.scripting, "SEQUENCER_OWNER", "IMAGER") == local_imager, 20, "sequencer taken (" + str(client.property(self.scripting, "SEQUENCER_OWNER")) + ")")
		self.control("STOP")
		self.wait_stopped()

	def queue(self):
		client = self.client
		for name, count in QUEUE:
			self.upload(self.capture_task(name, count, EXPOSURE))
		names = [n for n, _ in QUEUE]
		self.control("START")
		self.wait_tasks(names, "DONE", 60 + 10 * len(QUEUE))
		# every result and estimate of the Scripting Agent reached the scheduler
		lost = [m for d, m in client.messages if d == AGENT and ("no result from the Scripting Agent" in m or "cannot be estimated" in m)]
		assert not lost, "results or estimates lost: " + str(lost[:3])
		# every task finished, the scheduler stops by itself
		self.wait_stopped()
		assert client.state(AGENT, "AGENT_SCHEDULER_STATE") == "Ok", "scheduler state " + str(client.state(AGENT, "AGENT_SCHEDULER_STATE"))
		assert self.counter("DONE") == len(QUEUE), "DONE %s, expected %s" % (self.counter("DONE"), len(QUEUE))
		assert self.counter("FAILED") == 0, "FAILED %s" % self.counter("FAILED")
		assert self.counter("TOTAL") == len(self.task_items()) == len(QUEUE), "TOTAL %s, %d items" % (self.counter("TOTAL"), len(self.task_items()))
		self.assert_no_busy_task()
		for name, count in QUEUE:
			assert client.message_count("Starting task '" + name + "'") == 1, "task %s started %d times" % (name, client.message_count("Starting task '" + name + "'"))
			assert client.message_count("Task '" + name + "' completed") == 1, "task %s completed %d times" % (name, client.message_count("Task '" + name + "' completed"))
			assert [r for _, r, _ in self.history(name)] == ["SUCCEEDED"], "history of %s: %s" % (name, self.history(name))
			assert len(self.frames(name)) == count, "task %s: expected %d frames, found %d" % (name, count, len(self.frames(name)))
			self.assert_frames_belong(name)
		total = sum(c for _, c in QUEUE)
		assert len(self.all_frames()) == total, "expected %d frames in all, found %d" % (total, len(self.all_frames()))
		assert not self.busy(self.imager, "AGENT_START_PROCESS") and not self.busy(self.scripting, "SEQUENCE_STATE"), "an agent is still Busy"
		self.delete_all()

	def start_abort_restart(self):
		client = self.client
		tasks = [("Cycle %d" % (i + 1), 6) for i in range(3)]
		for name, count in tasks:
			self.upload(self.capture_task(name, count, 0.3, "// @retry 2\n"))
		before = len(self.all_frames())
		cycles = 4
		for cycle in range(cycles):
			started = client.message_count("Starting task")
			self.control("START")
			client.wait(lambda: client.message_count("Starting task") > started, 30, "a task started in cycle %d" % (cycle + 1))
			client.wait(lambda: any(self.task_state(n) == "RUNNING" for n, _ in tasks), 30, "a running task in cycle %d" % (cycle + 1))
			running = next(n for n, _ in tasks if self.task_state(n) == "RUNNING")
			frames = len(self.frames(running))
			# abort while the exposures of the running task are in progress
			self.wait(lambda: len(self.frames(running)) > frames and self.busy(self.imager, "AGENT_START_PROCESS"), 30, lambda: "capture of %s in progress in cycle %d (SEQUENCE_STATE %s, step %s)" % (running, cycle + 1, client.state(self.scripting, "SEQUENCE_STATE"), client.value(self.scripting, "SEQUENCE_STATE", "PROGRESS")))
			self.control("ABORT")
			self.wait_stopped()
			assert client.state(AGENT, "AGENT_SCHEDULER_STATE") == "Alert", "state after ABORT " + str(client.state(AGENT, "AGENT_SCHEDULER_STATE"))
			# an abort does not consume a retry; RETRY returns to QUEUED at once without a retry delay
			self.wait(lambda: self.task_state(running) in ("RETRY", "QUEUED"), 30, lambda: "task " + running + " back in the queue (label '" + client.task_label(running) + "')")
			assert "retries left 2" in client.task_label(running), "the abort used a retry: " + client.task_label(running)
			self.wait_idle_agents()
			interrupted = len(self.frames(running))
			time.sleep(1)
			assert len(self.frames(running)) == interrupted, "frames of %s captured after the abort" % running
			self.assert_no_busy_task()
		# the last START runs every task to completion
		self.control("START")
		self.wait_tasks([n for n, _ in tasks], "DONE", 120)
		self.wait_stopped()
		assert client.state(AGENT, "AGENT_SCHEDULER_STATE") == "Ok"
		assert self.counter("DONE") == len(tasks), "DONE %s, expected %s" % (self.counter("DONE"), len(tasks))
		assert self.counter("FAILED") == 0, "FAILED %s" % self.counter("FAILED")
		self.assert_no_busy_task()
		for name, count in tasks:
			runs = self.history(name)
			assert runs and runs[-1][1] == "SUCCEEDED" and all(r == "ABORTED" for _, r, _ in runs[:-1]), "history of %s: %s" % (name, runs)
			assert client.message_count("Starting task '" + name + "'") == len(runs), "task %s: %d starts for %d runs" % (name, client.message_count("Starting task '" + name + "'"), len(runs))
			assert client.message_count("Task '" + name + "' completed") == 1, "task %s completed %d times" % (name, client.message_count("Task '" + name + "' completed"))
			assert "retries left 2" in client.task_label(name), "aborts used retries: " + client.task_label(name)
			# the aborted runs saved fewer frames than a full run, the completed run all of them
			frames = len(self.frames(name))
			aborted = len(runs) - 1
			assert count <= frames <= count + aborted * (count - 1), "task %s: %d frames for %d aborted runs and one full run of %d" % (name, frames, aborted, count)
			self.assert_frames_belong(name)
		assert sum(len(self.history(n)) - 1 for n, _ in tasks) == cycles, "aborted runs: " + str({n: self.history(n) for n, _ in tasks})
		assert len(self.all_frames()) > before
		self.delete_all()

	def link_loss(self):
		client = self.client
		frames = 20
		remote = self.name == "scripting-remote"
		self.upload(self.capture_task("Link", frames, 0.5, "// @retry 1\n"))
		self.upload(self.capture_task("After link", 2, EXPOSURE))
		self.control("START")
		self.wait_task("Link", "RUNNING", 30)
		self.wait(lambda: len(self.frames("Link")) >= 2 and self.busy(self.imager, "AGENT_START_PROCESS"), 60, "first frames of Link")
		starts = client.message_count("Starting task")
		refused = self.relay.refused
		self.relay.drop()
		self.wait(lambda: client.property(self.imager, "FILTER_CCD_LIST") is None and client.property(self.camera, "CONNECTION") is None, 20, "devices of server B deleted on server A")
		if remote:
			# the Scripting Agent disappeared with the link: the run fails and is retried, the scheduler waits for the agent
			self.wait(lambda: client.message_count("Task 'Link' failed: the Scripting Agent or Sequencer.js disappeared, it will be retried") == 1, 20, lambda: "failure of the run (" + str(client.messages[-3:]) + ")")
			self.wait(lambda: client.value(AGENT, "AGENT_SCHEDULER_CURRENT", "REASON") == "waiting for the Scripting Agent", 20, lambda: "reason (" + str(client.property(AGENT, "AGENT_SCHEDULER_CURRENT")) + ")")
			assert "retries left 0" in client.task_label("Link"), "the failure did not use the retry: " + client.task_label("Link")
		else:
			# the local Scripting Agent keeps the sequence, which waits for the Imager Agent
			assert self.task_state("Link") == "RUNNING", "the run ended with the link: " + client.task_label("Link")
		hold = time.monotonic() + 5
		self.wait(lambda: time.monotonic() >= hold, 10, "link down")
		assert client.state(AGENT, "AGENT_SCHEDULER_STATE") == "Busy", "the scheduler stopped while the link was down"
		assert client.message_count("Starting task") == starts, "a task started while the link was down"
		if not remote:
			assert self.task_state("Link") == "RUNNING", "the run ended while the link was down: " + client.task_label("Link")
		# server A tried to connect again while the link was cut, every attempt was refused
		assert self.relay.refused > refused, "server A did not try to reconnect while the link was down"
		accepted = self.relay.accepted
		self.relay.restore()
		self.wait(lambda: client.property(self.imager, "FILTER_CCD_LIST") is not None and client.property(self.scripting, "SEQUENCE_STATE") is not None, 30, "devices of server B back on server A")
		assert self.relay.accepted > accepted, "the devices came back without a new connection through the relay"
		self.wait_tasks(["Link", "After link"], "DONE", 120)
		self.wait_stopped()
		assert client.state(AGENT, "AGENT_SCHEDULER_STATE") == "Ok", "scheduler state " + str(client.state(AGENT, "AGENT_SCHEDULER_STATE"))
		# the counters count the tasks of the list, which holds only the two tasks of this case
		assert self.counter("DONE") == 2 and self.counter("FAILED") == 0, "DONE %s FAILED %s" % (self.counter("DONE"), self.counter("FAILED"))
		self.assert_no_busy_task()
		assert client.message_count("Task 'After link' completed") == 1 and len(self.frames("After link")) == 2, "After link: %d frames" % len(self.frames("After link"))
		if remote:
			assert [r for _, r, _ in self.history("Link")] == ["FAILED", "SUCCEEDED"], "history of Link: " + str(self.history("Link"))
			assert client.message_count("Starting task 'Link'") == 2, "Link started %d times" % client.message_count("Starting task 'Link'")
			# server B keeps running the old sequence, nobody can abort it; the retry starts after it, and both capture every frame
			assert len(self.frames("Link")) == 2 * frames, "Link: expected %d frames of the lost and the retried run, found %d" % (2 * frames, len(self.frames("Link")))
		else:
			assert [r for _, r, _ in self.history("Link")] == ["SUCCEEDED"], "history of Link: " + str(self.history("Link"))
			assert client.message_count("Starting task 'Link'") == 1, "Link started %d times" % client.message_count("Starting task 'Link'")
			assert "retries left 1" in client.task_label("Link"), "the link loss used a retry: " + client.task_label("Link")
			# the batch went on in server B during the loss and the sequence resumed with it
			assert len(self.frames("Link")) == frames, "Link: expected %d frames, found %d" % (frames, len(self.frames("Link")))
		self.assert_frames_belong("Link")
		self.assert_frames_belong("After link")
		assert not self.busy(self.imager, "AGENT_START_PROCESS") and not self.busy(self.scripting, "SEQUENCE_STATE"), "an agent is still Busy"
		self.delete_all()

	def clean_exit(self):
		if self.client:
			self.client.connection.close()
			self.client = None
		codes = {}
		# A first: its scheduler releases the sequencer of a remote Scripting Agent before the link goes
		for server in reversed(self.servers):
			codes[server.name] = server.stop()
		if self.relay:
			self.relay.close()
		for server in self.servers:
			assert codes[server.name] == 0, "indigo_server %s exit code %s, see %s" % (server.name, codes[server.name], server.log_path)
		deadline = time.monotonic() + 5
		while any(s.group_alive() for s in self.servers) and time.monotonic() < deadline:
			time.sleep(0.1)
		alive = [s.name for s in self.servers if s.group_alive()]
		for server in self.servers:
			if server.group_alive():
				server.kill()
		assert not alive, "processes left behind by indigo_server " + ", ".join(alive)
		for server in self.servers:
			with socket.socket() as probe:
				probe.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
				try:
					probe.bind(("127.0.0.1", server.port))
				except OSError:
					raise AssertionError("port %d of indigo_server %s still bound" % (server.port, server.name))
		# nothing but frames in the data folders: no partial or temporary files
		stale = [str(p) for p in self.images.rglob("*") if p.is_file() and (p.suffix != ".fits" or p.stat().st_size <= 2880)]
		assert not stale, "stale files: " + str(stale[:5])


def main():
	parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
	parser.add_argument("--output", type=Path, help="New directory for retained logs, frames and JSON results")
	parser.add_argument("--keep", action="store_true", help="Keep the output directory")
	args = parser.parse_args()
	repo = Path(__file__).resolve().parents[2]
	selected = [t.strip() for t in os.environ.get("SCHEDULER_TWO_SERVERS_TOPOLOGY", "").split(",") if t.strip()] or list(TOPOLOGIES)
	unknown = [t for t in selected if t not in TOPOLOGIES]
	if unknown:
		print("unknown topology: " + ", ".join(unknown) + "; known: " + ", ".join(TOPOLOGIES), file=sys.stderr)
		return 2
	missing = [d for d in ("agent_scheduler", "agent_scripting", "agent_imager", "ccd_simulator") if not (repo / "build/drivers" / ("indigo_" + d + (".dylib" if sys.platform == "darwin" else ".so"))).is_file()]
	if missing or not (repo / "build/bin/indigo_server").is_file():
		print("build indigo_server and the dynamic drivers " + ", ".join(missing or ["agent_scheduler", "agent_scripting", "agent_imager", "ccd_simulator"]) + " first", file=sys.stderr)
		return 2
	output = args.output.resolve() if args.output else Path(tempfile.mkdtemp(prefix="indigo-scheduler-two-servers-"))
	if args.output:
		output.mkdir(parents=True, exist_ok=False)
	records = os.environ.get("INDIGO_TEST_RESULTS")
	if records:
		with open(records, "a") as out:
			out.write("plan\t" + str(len(selected) * len(CASES)) + "\t" + SUITE + "\n")
	# the servers run in sessions of their own, so a kill of this script does not reach them; the handlers let the finally below stop them
	signal.signal(signal.SIGTERM, interrupt)
	signal.signal(signal.SIGHUP, interrupt)
	results = []
	errors = {}
	try:
		for name in selected:
			print(SUITE + ": " + name, flush=True)
			directory = output / name
			directory.mkdir()
			topology = Topology(name, repo, directory, records)
			try:
				error = topology.run()
			finally:
				for server in topology.servers:
					if server.process.poll() is None or server.group_alive():
						server.kill()
			results += topology.results
			if error:
				errors[name] = error
	except (Interrupted, KeyboardInterrupt) as interruption:
		print(SUITE + ": interrupted (" + (str(interruption) or "SIGINT") + "), servers stopped", file=sys.stderr, flush=True)
		if args.keep or args.output:
			(output / "results.json").write_text(json.dumps({"results": results, "errors": errors, "interrupted": True, "output": str(output)}, indent=2, ensure_ascii=False) + "\n")
		else:
			shutil.rmtree(output, ignore_errors=True)
		return 130
	report = {"results": results, "errors": errors, "output": str(output)}
	(output / "results.json").write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n")
	passed = sum(r["status"] == "pass" for r in results)
	failed = len(selected) * len(CASES) - passed
	print(f"{SUITE}: {passed} passed, {failed} failed; report: {output / 'results.json'}")
	if not failed and not errors and not args.keep and not args.output:
		shutil.rmtree(output, ignore_errors=True)
	return 0 if not failed and not errors else 1


if __name__ == "__main__":
	sys.exit(main())
