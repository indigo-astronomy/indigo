"""Stress the Scheduler Agent across two private indigo_server processes on the local host.

Server A runs the Scheduler Agent and connects to server B with the standard remote-server option
(-r), through a TCP relay of this script, so that the link between the servers can be cut and
restored while a task runs. The agents of B appear on A with the suffix ' @ localhost:<relay port>'
and the scheduler is configured with these names in AGENT_SCHEDULER_AGENTS.

  scripting-remote: A = Scheduler Agent; B = Scripting Agent, Imager Agent, CCD simulator
  scripting-local:  A = Scheduler Agent, Scripting Agent; B = Imager Agent, CCD simulator

For each topology a queue of short capture tasks is uploaded over the JSON protocol and run to
completion, the queue is started, aborted and started again while frames are captured, the link is
cut and restored during a run, and both servers are stopped and checked for a clean exit. Frames
are counted per task in the task folders the scheduler labels the runs with, and their SCHTASK
header must name the task. No existing server or configuration is used; every server gets a free
port and a private HOME.

SCHEDULER_TWO_SERVERS_TOPOLOGY selects one topology; by default both run.
"""

