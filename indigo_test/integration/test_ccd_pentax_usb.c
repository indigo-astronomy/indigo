static void test_hotplug_descriptor_names(void) {
	for (int mode = 0; mode < 3; mode++) {
		reset_usb();
		descriptor_mode = mode;
		process_plug_event((libusb_device *)&token);
		int attached = attach_calls;
		char name[INDIGO_NAME_SIZE];
		memcpy(name, attached_name, sizeof(name));
		process_unplug_event((libusb_device *)&token);
		ASSERT_EQ_INT(1, attached);
		ASSERT_EQ_INT(1, ref_calls);
		ASSERT_EQ_INT(1, unref_calls);
		ASSERT_EQ_INT(1, close_calls);
		ASSERT_EQ_INT(1, config_frees);
		ASSERT_EQ_INT(1, private_frees);
		ASSERT_EQ_INT(0, free_before_detach);
		if (mode < 2) {
			ASSERT_TRUE(strcmp(name, "PENTAX Camera") == 0);
		} else {
			ASSERT_EQ_INT(63, strlen(name));
			ASSERT_EQ_INT(' ', name[31]);
			for (int i = 0; i < 31; i++) {
				ASSERT_EQ_INT('V', name[i]);
				ASSERT_EQ_INT('P', name[i + 32]);
			}
		}
	}
}

