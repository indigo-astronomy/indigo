static void test_unplug(void) {
	for (int cycle = 0; cycle < 4; cycle++) {
		reset_usb();
		indigo_device *device = calloc(1, sizeof(*device));
		pentax_private_data *state = calloc(1, sizeof(*state));
		state->dev = (libusb_device *)&token;
		device->private_data = state;
		tracked_private = state;
		devices[0] = device;
		process_unplug_event((libusb_device *)&token);
		int released = private_frees;
		if (!released) {
			free(state);
		}
		tracked_private = NULL;
		ASSERT_EQ_INT(1, released);
		ASSERT_EQ_INT(1, detach_calls);
		ASSERT_EQ_INT(1, unref_calls);
		ASSERT_EQ_INT(0, free_before_detach);
		ASSERT_TRUE(devices[0] == NULL);
	}
}

