	SERIAL_CHECK_TRUE(record.client == NULL && record.generation == 0);
	SERIAL_CHECK_EQ_INT(INDIGO_NOT_FOUND, indigo_register_detach_abort(&registry_device, &record, release, release));
	record.client = &unattached_client;
	record.generation = indigo_current_client_ref(&owner_a).generation;
	SERIAL_CHECK_EQ_INT(INDIGO_NOT_FOUND, indigo_register_detach_abort(&registry_device, &record, release, release));
	record = indigo_current_client_ref(&owner_a);
	SERIAL_CHECK_EQ_INT(INDIGO_FAILED, indigo_register_detach_abort(NULL, &record, release, release));
	SERIAL_CHECK_EQ_INT(INDIGO_FAILED, indigo_register_detach_abort(&registry_device, NULL, release, release));
	SERIAL_CHECK_EQ_INT(INDIGO_FAILED, indigo_register_detach_abort(&registry_device, &record, NULL, release));
	SERIAL_CHECK_EQ_INT(INDIGO_FAILED, indigo_register_detach_abort(&registry_device, &record, release, NULL));
	SERIAL_CHECK_EQ_INT(INDIGO_FAILED, indigo_unregister_detach_abort(NULL, REGISTRY_PROPERTY));
	SERIAL_CHECK_EQ_INT(INDIGO_FAILED, indigo_unregister_detach_abort(&registry_device, NULL));
