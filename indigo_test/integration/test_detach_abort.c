static bool wait_server_clients(int count) {
	if (!WAIT_UNTIL(atomic_load(&server_client_count) == count, 10)) {
		fprintf(stderr, "    server has %d clients, expected %d\n", atomic_load(&server_client_count), count);
		return false;
	}
	return true;
}

static int connect_loopback(int port) {
	int fd = socket(AF_INET, SOCK_STREAM, 0);
	if (fd < 0) {
		return -1;
	}
	struct sockaddr_in address = { 0 };
	address.sin_family = AF_INET;
	address.sin_port = htons(port);
	address.sin_addr.s_addr = htonl(INADDR_LOOPBACK);
	if (connect(fd, (struct sockaddr *)&address, sizeof(address)) < 0) {
		close(fd);
		return -1;
	}
	int value = 1;
	setsockopt(fd, IPPROTO_TCP, TCP_NODELAY, &value, sizeof(value));
	return fd;
}

static void stop_test_server(void) {
	if (server_started) {
		wait_server_clients(0);
		int port = indigo_server_tcp_port;
		indigo_server_shutdown();
		if (!WAIT_UNTIL(atomic_load(&server_finished), 1)) {
			// the listener may stay in accept() after its socket is shut down, a connection wakes it
			int fd = connect_loopback(port);
			if (fd >= 0) {
				close(fd);
			}
		}
		if (WAIT_UNTIL(atomic_load(&server_finished), 5)) {
			pthread_join(server_thread, NULL);
		} else {
			fprintf(stderr, "    TCP server thread did not finish\n");
			indigo_test_failures++;
			pthread_detach(server_thread);
		}
		wait_server_clients(0);
		server_started = false;
	}
}

typedef struct {
	int fd;
	pthread_t reader;
	bool reader_started;
	atomic_bool stop;
	atomic_bool ready;
	atomic_bool eof;
	char marker[INDIGO_VALUE_SIZE];
} tcp_peer;

static void *tcp_peer_read(void *data) {
	tcp_peer *peer = data;
	char buffer[16384];
	size_t kept = 0, marker_length = strlen(peer->marker);
	while (!atomic_load(&peer->stop)) {
		struct pollfd descriptor = { peer->fd, POLLIN, 0 };
		int result = poll(&descriptor, 1, 20);
		if (result < 0 && errno != EINTR) {
			break;
		}
		if (result <= 0) {
			continue;
		}
		ssize_t length = recv(peer->fd, buffer + kept, sizeof(buffer) - kept - 1, 0);
		if (length <= 0) {
			break;
		}
		kept += length;
		buffer[kept] = 0;
		if (!atomic_load(&peer->ready) && strstr(buffer, peer->marker) != NULL) {
			atomic_store(&peer->ready, true);
		}
		if (kept > marker_length) {
			memmove(buffer, buffer + kept - marker_length, marker_length);
			kept = marker_length;
		}
	}
	atomic_store(&peer->eof, true);
	return NULL;
}

static bool tcp_peer_send(tcp_peer *peer, const char *format, ...) {
	char message[4096];
	va_list arguments;
	va_start(arguments, format);
	int length = vsnprintf(message, sizeof(message), format, arguments);
	va_end(arguments);
	if (length < 0 || length >= (int)sizeof(message)) {
		return false;
	}
	for (int sent = 0; sent < length;) {
		ssize_t result = send(peer->fd, message + sent, length - sent, 0);
		if (result <= 0) {
			return false;
		}
		sent += result;
	}
	return true;
}

// Connect an XML peer, ask for the properties and wait until the definition of the given property of
// the given device arrived, so the server's adapter is attached and the device is known to it.
static bool tcp_peer_open(tcp_peer *peer, int port, const char *device_name, const char *property_name) {
	memset(peer, 0, sizeof(*peer));
	peer->fd = connect_loopback(port);
	if (peer->fd < 0) {
		fprintf(stderr, "    can't connect to port %d (%s)\n", port, strerror(errno));
		return false;
	}
	snprintf(peer->marker, sizeof(peer->marker), "<defSwitchVector device='%s' name='%s'", device_name, property_name);
	if (pthread_create(&peer->reader, NULL, tcp_peer_read, peer) != 0) {
		return false;
	}
	peer->reader_started = true;
	if (!tcp_peer_send(peer, "<getProperties version='2.0' switch='2.0'/>\n")) {
		return false;
	}
	if (!WAIT_UNTIL(atomic_load(&peer->ready), 10)) {
		fprintf(stderr, "    no definition of '%s'.%s received\n", device_name, property_name);
		return false;
	}
	return true;
}

static bool tcp_peer_switch(tcp_peer *peer, const char *device_name, const char *property_name, const char *item_name, bool value) {
	return tcp_peer_send(peer, "<newSwitchVector device='%s' name='%s'><oneSwitch name='%s'>%s</oneSwitch></newSwitchVector>\n", device_name, property_name, item_name, value ? "On" : "Off");
}

// Close orderly (FIN) or abruptly (SO_LINGER 0, the peer sees a connection reset).
static void tcp_peer_close(tcp_peer *peer, bool abrupt) {
	if (peer->reader_started) {
		atomic_store(&peer->stop, true);
		pthread_join(peer->reader, NULL);
		peer->reader_started = false;
	}
	if (peer->fd > 0) {
		if (abrupt) {
			struct linger linger = { 1, 0 };
			setsockopt(peer->fd, SOL_SOCKET, SO_LINGER, &linger, sizeof(linger));
		}
		close(peer->fd);
		peer->fd = -1;
	}
}

// A proxy between one peer and the server. cut() ends the server side of the connection while the
// peer keeps its socket open, as a lost link looks to the server.
typedef struct {
	int listen_fd;
	int client_fd;
	int server_fd;
	int port;
	int upstream_port;
	pthread_t thread;
	bool started;
	atomic_bool stop;
} tcp_proxy;

static bool tcp_proxy_pump(int from, int to) {
	char buffer[16384];
	ssize_t length = recv(from, buffer, sizeof(buffer), 0);
	if (length <= 0) {
		return false;
	}
	for (ssize_t sent = 0; sent < length;) {
		ssize_t result = send(to, buffer + sent, length - sent, 0);
		if (result <= 0) {
			return false;
		}
		sent += result;
	}
	return true;
}

static void *tcp_proxy_run(void *data) {
	tcp_proxy *proxy = data;
	while (!atomic_load(&proxy->stop) && proxy->client_fd < 0) {
		struct pollfd descriptor = { proxy->listen_fd, POLLIN, 0 };
		if (poll(&descriptor, 1, 20) > 0) {
			proxy->client_fd = accept(proxy->listen_fd, NULL, NULL);
		}
	}
	if (proxy->client_fd < 0) {
		return NULL;
	}
	proxy->server_fd = connect_loopback(proxy->upstream_port);
	if (proxy->server_fd < 0) {
		return NULL;
	}
	bool open = true;
	while (open && !atomic_load(&proxy->stop)) {
		struct pollfd descriptors[2] = { { proxy->client_fd, POLLIN, 0 }, { proxy->server_fd, POLLIN, 0 } };
		if (poll(descriptors, 2, 20) <= 0) {
			continue;
		}
		if (descriptors[0].revents) {
			open = tcp_proxy_pump(proxy->client_fd, proxy->server_fd);
		}
		if (open && descriptors[1].revents) {
			open = tcp_proxy_pump(proxy->server_fd, proxy->client_fd);
		}
	}
	return NULL;
}

static bool tcp_proxy_start(tcp_proxy *proxy, int upstream_port) {
	memset(proxy, 0, sizeof(*proxy));
	proxy->client_fd = proxy->server_fd = -1;
	proxy->upstream_port = upstream_port;
	proxy->listen_fd = socket(AF_INET, SOCK_STREAM, 0);
	if (proxy->listen_fd < 0) {
		return false;
	}
	struct sockaddr_in address = { 0 };
	socklen_t length = sizeof(address);
	address.sin_family = AF_INET;
	address.sin_addr.s_addr = htonl(INADDR_LOOPBACK);
	if (bind(proxy->listen_fd, (struct sockaddr *)&address, sizeof(address)) < 0 || listen(proxy->listen_fd, 1) < 0 || getsockname(proxy->listen_fd, (struct sockaddr *)&address, &length) < 0) {
		close(proxy->listen_fd);
		proxy->listen_fd = -1;
		return false;
	}
	proxy->port = ntohs(address.sin_port);
	if (pthread_create(&proxy->thread, NULL, tcp_proxy_run, proxy) != 0) {
		return false;
	}
	proxy->started = true;
	return true;
}

static void tcp_proxy_cut(tcp_proxy *proxy) {
	if (proxy->server_fd >= 0) {
		shutdown(proxy->server_fd, SHUT_RDWR);
	}
}

static void tcp_proxy_stop(tcp_proxy *proxy) {
	if (proxy->started) {
		atomic_store(&proxy->stop, true);
		pthread_join(proxy->thread, NULL);
		proxy->started = false;
	}
	if (proxy->server_fd >= 0) {
		close(proxy->server_fd);
		proxy->server_fd = -1;
	}
	if (proxy->client_fd >= 0) {
		close(proxy->client_fd);
		proxy->client_fd = -1;
	}
	if (proxy->listen_fd > 0) {
		close(proxy->listen_fd);
		proxy->listen_fd = -1;
	}
}

