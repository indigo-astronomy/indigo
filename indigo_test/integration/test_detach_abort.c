#define REGISTRY_DEVICE_NAME  "Detach Abort Test Device"
#define REGISTRY_PROPERTY     "TEST_OPERATION"
#define REGISTRY_TOKEN        0x5eedULL
#define REGISTRY_MAX_PROBE    1024

