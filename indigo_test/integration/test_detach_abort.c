// A reference identifies one attachment: after the owner detached, a client attached at the same address (here the
// same indigo_client re-attached, as the allocator does with a freed XML adapter) does not match the old reference.
static void registry_stale_attachment_is_refused(void) {
	indigo_property *release = NULL;
	SERIAL_CHECK_TRUE(start_registry());
	indigo_client_ref record = indigo_current_client_ref(&owner_a);
	SERIAL_CHECK_TRUE(record.client == &owner_a && record.generation != 0);
	SERIAL_CHECK_TRUE(indigo_current_client_ref(&owner_b).generation != record.generation);
	SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_detach_client(&owner_a));
	SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_attach_client(&owner_a));
	indigo_client_ref current = indigo_current_client_ref(&owner_a);
	SERIAL_CHECK_TRUE(current.client == &owner_a && current.generation != 0 && current.generation != record.generation);
	release = registry_release(REGISTRY_PROPERTY);
	SERIAL_CHECK_EQ_INT(INDIGO_NOT_FOUND, indigo_register_detach_abort(&registry_device, &record, release, release));
	SERIAL_CHECK_EQ_INT(INDIGO_NOT_FOUND, indigo_unregister_detach_abort(&registry_device, REGISTRY_PROPERTY));
	// the current attachment registers, and its detach sends the release exactly once
	SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_register_detach_abort(&registry_device, &current, release, release));
	SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_detach_client(&owner_a));
	SERIAL_CHECK_EQ_INT(1, atomic_load(&registry_requests));
	SERIAL_CHECK_EQ_INT(1, count_markers("Aborting", REGISTRY_PROPERTY, OWNER_A_NAME));
	SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_attach_client(&owner_a));
cleanup:
	indigo_release_property(release);
	stop_registry();
}

