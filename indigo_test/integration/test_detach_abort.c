#pragma mark - Log markers

// The bus logs "Aborting '<device>'.<property> started by detached client '<client>'" when it sends a
// registered release, "Forgetting '<device>'.<property> left registered by detached device" when it
// drops an entry of a detached device, and the mount base class logs "Releasing '<device>'.<property>,
// ..." when it could not register a started motion and released it at once.

#define MAX_LOG_MARKERS 512

static pthread_mutex_t log_marker_mutex = PTHREAD_MUTEX_INITIALIZER;
static char log_markers[MAX_LOG_MARKERS][INDIGO_VALUE_SIZE];
static int log_marker_count = 0;
static char marker_device[INDIGO_NAME_SIZE];
static int failures_at_reset = 0;

static void capture_log_message(indigo_log_levels level, const char *message) {
	if (strstr(message, "Aborting '") != NULL || strstr(message, "Releasing '") != NULL || strstr(message, "Forgetting '") != NULL) {
		pthread_mutex_lock(&log_marker_mutex);
		if (log_marker_count < MAX_LOG_MARKERS) {
			snprintf(log_markers[log_marker_count++], INDIGO_VALUE_SIZE, "%s", message);
		}
		pthread_mutex_unlock(&log_marker_mutex);
	}
	if (debug_enabled || level == INDIGO_LOG_ERROR) {
		fprintf(stderr, "    log: %s\n", message);
	}
}

static void reset_log_markers(const char *device_name) {
	pthread_mutex_lock(&log_marker_mutex);
	log_marker_count = 0;
	snprintf(marker_device, sizeof(marker_device), "%s", device_name);
	failures_at_reset = indigo_test_failures;
	pthread_mutex_unlock(&log_marker_mutex);
}

// Markers of one verb for one property of the current device, optionally naming a client.
static int count_markers(const char *verb, const char *property_name, const char *client_name) {
	char needle[INDIGO_VALUE_SIZE];
	snprintf(needle, sizeof(needle), "%s '%s'.%s", verb, marker_device, property_name);
	size_t length = strlen(needle);
	int count = 0;
	pthread_mutex_lock(&log_marker_mutex);
	for (int i = 0; i < log_marker_count; i++) {
		const char *line = log_markers[i];
		if (!strncmp(line, needle, length) && (line[length] == ' ' || line[length] == ',') && (client_name == NULL || strstr(line + length, client_name) != NULL)) {
			count++;
		}
	}
	pthread_mutex_unlock(&log_marker_mutex);
	return count;
}

static int total_markers(void) {
	pthread_mutex_lock(&log_marker_mutex);
	int count = log_marker_count;
	pthread_mutex_unlock(&log_marker_mutex);
	return count;
}

// Print the markers seen since the last reset when the current case failed since then.
static void dump_markers(void) {
	if (indigo_test_failures == failures_at_reset) {
		return;
	}
	pthread_mutex_lock(&log_marker_mutex);
	for (int i = 0; i < log_marker_count; i++) {
		fprintf(stderr, "    marker: %s\n", log_markers[i]);
	}
	pthread_mutex_unlock(&log_marker_mutex);
}

