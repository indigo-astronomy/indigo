// The peer sends the request and closes at once, orderly or with a reset. The request is parsed before
// the end of the connection, so exactly one release is sent: the registered one or the handler's own.
// A reset may also discard the unread request in the server's receive buffer; then the motion never
// starts, which the unchanged revision of the property proves.
static void network_close_race_always_ends_motion(void) {
	int aborted = 0, released = 0, discarded = 0;
	tcp_peer peer = { .fd = -1 };
	SERIAL_CHECK_TRUE(start_network_simulator_mount());
	for (int i = 0; i < NETWORK_RACE_REPETITIONS; i++) {
		reset_log_markers(MOUNT_SIMULATOR_NAME);
		SERIAL_CHECK_TRUE(tcp_peer_open(&peer, indigo_server_tcp_port, MOUNT_SIMULATOR_NAME, MOUNT_MOTION_DEC_PROPERTY_NAME));
		SERIAL_CHECK_TRUE(wait_server_clients(1));
		unsigned int revision = property_revision(MOUNT_MOTION_DEC_PROPERTY_NAME);
		SERIAL_CHECK_TRUE(tcp_peer_switch(&peer, MOUNT_SIMULATOR_NAME, MOUNT_MOTION_DEC_PROPERTY_NAME, MOUNT_MOTION_NORTH_ITEM_NAME, true));
		tcp_peer_close(&peer, i % 2 == 1);
		SERIAL_CHECK_TRUE(wait_server_clients(0));
		SERIAL_CHECK_TRUE(drain_device_queue());
		SERIAL_CHECK_TRUE(motion_ended(MOUNT_MOTION_DEC_PROPERTY_NAME));
		SERIAL_CHECK_TRUE(total_markers() <= 1);
		if (total_markers() == 0) {
			SERIAL_CHECK_TRUE(i % 2 == 1);
			SERIAL_CHECK_EQ_INT(revision, property_revision(MOUNT_MOTION_DEC_PROPERTY_NAME));
			discarded++;
		}
		aborted += count_markers("Aborting", MOUNT_MOTION_DEC_PROPERTY_NAME, XML_ADAPTER_NAME);
		released += count_markers("Releasing", MOUNT_MOTION_DEC_PROPERTY_NAME, NULL);
		SERIAL_CHECK_TRUE(no_entry(MOUNT_MOTION_DEC_PROPERTY_NAME));
	}
	SERIAL_CHECK_EQ_INT(NETWORK_RACE_REPETITIONS, aborted + released + discarded);
	printf("    network race outcomes: registered then released on close %d, refused and released by the handler %d, request discarded by reset %d\n", aborted, released, discarded);
cleanup:
	dump_markers();
	tcp_peer_close(&peer, false);
	stop_test_server();
	stop_simulator_mount();
}

