	indigo_use_bonjour = false;
	indigo_server_tcp_port = 0;
	atomic_store(&server_client_count, 0);
	atomic_store(&server_listening, false);
	atomic_store(&server_finished, false);
	if (pthread_create(&server_thread, NULL, test_server_run, NULL) != 0) {
		return false;
	}
	server_started = true;
	if (!WAIT_UNTIL(atomic_load(&server_listening) && indigo_server_tcp_port != 0, 5)) {
		fprintf(stderr, "    TCP server did not start\n");
		return false;
	}
