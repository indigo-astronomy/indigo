#pragma mark - Device queue fence and gate

// A fence queued behind a request runs only after every handler queued before it has finished, so
// once it passed, the motion handler of that request and its commit are done. The gate occupies the
// device queue, so requests sent while it is closed are admitted by change_property() but their
// handlers run only after it opens.

static atomic_int fence_passes;
static atomic_bool gate_entered;
static atomic_bool gate_open = true;

static void fence_handler(indigo_device *device) {
	atomic_fetch_add(&fence_passes, 1);
}

static void gate_handler(indigo_device *device) {
	atomic_store(&gate_entered, true);
	double deadline = indigo_monotonic_time() + 30;
	while (!atomic_load(&gate_open) && indigo_monotonic_time() < deadline) {
		indigo_usleep(1000);
	}
}

static bool drain_device_queue(void) {
	indigo_device *device = atomic_load(&watched_device);
	if (device == NULL) {
		fprintf(stderr, "    no device pointer recorded for '%s'\n", watched_device_name);
		return false;
	}
	int before = atomic_load(&fence_passes);
	indigo_execute_handler(device, fence_handler);
	if (!WAIT_UNTIL(atomic_load(&fence_passes) > before, 15)) {
		fprintf(stderr, "    queue fence of '%s' did not pass\n", device->name);
		return false;
	}
	return true;
}

static bool close_gate(void) {
	indigo_device *device = atomic_load(&watched_device);
	if (device == NULL) {
		return false;
	}
	atomic_store(&gate_open, false);
	atomic_store(&gate_entered, false);
	indigo_execute_priority_handler_in(device, INDIGO_TASK_PRIORITY_URGENT, 0, gate_handler);
	return WAIT_UNTIL(atomic_load(&gate_entered), 10);
}

static void open_gate(void) {
	atomic_store(&gate_open, true);
}

// True when no entry is registered for the property of the watched device. The probe removes an entry
// it finds, which only happens when the assertion fails anyway.
static bool no_entry(const char *property_name) {
	indigo_device *device = atomic_load(&watched_device);
	return device != NULL && indigo_unregister_detach_abort(device, property_name) == INDIGO_NOT_FOUND;
}

static void detach_owners(void) {
	indigo_detach_client(&owner_a);
	indigo_detach_client(&owner_b);
}

static bool attach_owners(void) {
	return indigo_attach_client(&owner_a) == INDIGO_OK && indigo_attach_client(&owner_b) == INDIGO_OK;
}

// Request manual motion from an owner and wait until its handler and commit have run.
static bool owner_moves(indigo_client *owner, const char *property_name, const char *item_name) {
	if (indigo_change_switch_property_1(owner, watched_device_name, property_name, item_name, true) != INDIGO_OK) {
		return false;
	}
	if (!drain_device_queue()) {
		return false;
	}
	if (!switch_is(property_name, item_name, true) || state_of(property_name) == INDIGO_ALERT_STATE) {
		fprintf(stderr, "    %s.%s did not start (state %d)\n", property_name, item_name, state_of(property_name));
		return false;
	}
	return true;
}

// The motion ended: the items are off and not BUSY, and stay so after every queued handler finished.
static bool motion_ended(const char *property_name) {
	if (!WAIT_UNTIL(axis_stopped(property_name), 10)) {
		fprintf(stderr, "    %s did not stop\n", property_name);
		return false;
	}
	return drain_device_queue() && axis_stopped(property_name);
}

