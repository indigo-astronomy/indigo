// The owner detaches right after the request, racing the handler. Either the handler committed first
// (the detach sends the registered release) or it found the owner gone (it releases at once); in both
// cases exactly one release is sent and the motion ends.
static void simulator_detach_race_always_ends_motion(void) {
	int aborted = 0, released = 0;
	SERIAL_CHECK_TRUE(start_simulator_mount());
	// every repetition attaches the owner anew, a client attached twice would stay attached after one detach
	indigo_detach_client(&owner_a);
	for (int i = 0; i < RACE_REPETITIONS; i++) {
		reset_log_markers(MOUNT_SIMULATOR_NAME);
		SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_attach_client(&owner_a));
		SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_change_switch_property_1(&owner_a, MOUNT_SIMULATOR_NAME, MOUNT_MOTION_DEC_PROPERTY_NAME, i % 2 ? MOUNT_MOTION_SOUTH_ITEM_NAME : MOUNT_MOTION_NORTH_ITEM_NAME, true));
		SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_detach_client(&owner_a));
		SERIAL_CHECK_TRUE(WAIT_UNTIL(total_markers() >= 1, 10));
		SERIAL_CHECK_TRUE(motion_ended(MOUNT_MOTION_DEC_PROPERTY_NAME));
		SERIAL_CHECK_EQ_INT(1, total_markers());
		aborted += count_markers("Aborting", MOUNT_MOTION_DEC_PROPERTY_NAME, OWNER_A_NAME);
		released += count_markers("Releasing", MOUNT_MOTION_DEC_PROPERTY_NAME, NULL);
		SERIAL_CHECK_TRUE(no_entry(MOUNT_MOTION_DEC_PROPERTY_NAME));
	}
	SERIAL_CHECK_EQ_INT(RACE_REPETITIONS, aborted + released);
	printf("    race outcomes: registered then released on detach %d, refused and released by the handler %d\n", aborted, released);
cleanup:
	dump_markers();
	stop_simulator_mount();
}

