	SERIAL_CHECK_TRUE(settle(FOCUSER_STEPS_PROPERTY_NAME));
	SERIAL_CHECK_TRUE(set_switch(&focuser, FOCUSER_DIRECTION_PROPERTY_NAME, FOCUSER_DIRECTION_MOVE_OUTWARD_ITEM_NAME, true));
	SERIAL_CHECK_TRUE(set_number(&focuser, FOCUSER_STEPS_PROPERTY_NAME, FOCUSER_STEPS_ITEM_NAME, 200));
