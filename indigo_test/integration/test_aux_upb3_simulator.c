// The focuser opens the port through the powerbox, so the powerbox connection has
// to survive the focuser being closed.
static void focuser_shares_the_powerbox_connection(void) {
	external_serial_simulator simulator = { 0 };
	SERIAL_CHECK_TRUE(start_upb3(&simulator, NULL));
	SERIAL_CHECK_TRUE(start_serial_driver(&aux, simulator.port));
	reset_simulator_context(&focuser);
	enumerate_simulator_device();
	SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_change_switch_property_1(&simulator_test_client, focuser.device_name, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, true));
	SERIAL_CHECK_TRUE(wait_for_property_state(CONNECTION_PROPERTY_NAME, INDIGO_OK_STATE));
	disconnect_serial_device(&focuser);
	reset_simulator_context(&aux);
	enumerate_simulator_device();
	SERIAL_CHECK_TRUE(wait_for_property_state(CONNECTION_PROPERTY_NAME, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(settle(AUX_POWER_OUTLET_PROPERTY_NAME));
	SERIAL_CHECK_TRUE(set_switch(&aux, AUX_POWER_OUTLET_PROPERTY_NAME, AUX_POWER_OUTLET_5_ITEM_NAME, true));
	SERIAL_CHECK_TRUE(wait_for_switch_item_value(AUX_POWER_OUTLET_PROPERTY_NAME, AUX_POWER_OUTLET_5_ITEM_NAME, true));
cleanup:
	stop_serial_driver(&aux);
	stop_external_serial_simulator(&simulator);
}

