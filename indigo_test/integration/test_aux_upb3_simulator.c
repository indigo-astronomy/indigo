// The position property follows the device through the status poll, so a moved
// focuser needs a bounded wait rather than an immediate sample.
static bool wait_for_position_other_than(double value) {
	for (int i = 0; i < 100; i++) {
		double current = cached_number_value(FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME);
		if (current != value) {
			return true;
		}
		indigo_usleep(100000);
	}
	fprintf(stderr, "FOCUSER_POSITION never moved away from %g\n", value);
	return false;
}

static bool wait_for_position_below(double limit) {
	for (int i = 0; i < 100; i++) {
		double current = cached_number_value(FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME);
		if (current < limit) {
			return true;
		}
		indigo_usleep(100000);
	}
	fprintf(stderr, "FOCUSER_POSITION is %g, expected below %g\n", cached_number_value(FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME), limit);
	return false;
}

