	SERIAL_CHECK_TRUE(change_number_and_wait(&temma_guider, GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_EAST_ITEM_NAME, 0, INDIGO_OK_STATE));

	// A pulse arriving while another one on the same axis is still running replaces it, so the
	// elapsed time has to follow the second request. Measuring the duration is the point of these
	// two cases: waiting only for a state transition passes even when the driver keeps the
	// superseded pulse running to its own deadline.
	double started = indigo_monotonic_time();
	SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_change_number_property_1(&simulator_test_client, temma_guider.device_name, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME, 2000));
