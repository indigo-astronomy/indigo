// The bus delivers the message of an update through send_message, which the common test client does not
// set, so the messages of this driver are recorded here.
static pthread_mutex_t message_mutex = PTHREAD_MUTEX_INITIALIZER;
static char messages[4096];

// The device as the driver attached it, for the USB match pattern it registers.
static indigo_device *attached_giotto;

static indigo_result observe_define(indigo_client *client, indigo_device *device, indigo_property *property, const char *message) {
	if (!strcmp(property->device, GIOTTO_NAME)) {
		attached_giotto = device;
	}
	return simulator_client_define_property(client, device, property, message);
}

static indigo_result record_message(indigo_client *client, indigo_device *device, indigo_property *property, const char *message) {
	simulator_client_send_message(client, device, property, message);
	if (message != NULL && *message) {
		pthread_mutex_lock(&message_mutex);
		if (strlen(messages) + strlen(message) + 2 < sizeof(messages)) {
			strcat(messages, message);
			strcat(messages, "\n");
		}
		pthread_mutex_unlock(&message_mutex);
	}
	return INDIGO_OK;
}

static void clear_messages(void) {
	pthread_mutex_lock(&message_mutex);
	messages[0] = 0;
	pthread_mutex_unlock(&message_mutex);
}

static bool message_seen(const char *fragment) {
	for (int i = 0; i < 200; i++) {
		pthread_mutex_lock(&message_mutex);
		bool found = strstr(messages, fragment) != NULL;
		pthread_mutex_unlock(&message_mutex);
		if (found) {
			return true;
		}
		indigo_usleep(25000);
	}
	fprintf(stderr, "No message containing '%s'\n", fragment);
	return false;
}

// Each wait of the shared harness lasts up to 10 s.
static bool state_seen_within(const char *property, indigo_property_state state, unsigned int revision, int seconds) {
	for (int i = 0; i < (seconds + 9) / 10; i++) {
		if (wait_for_property_state_seen_after(property, state, revision)) {
			return true;
		}
	}
	indigo_property *cached = find_cached_property(property);
	fprintf(stderr, "%s never published state %d (current %d)\n", property, state, cached == NULL ? -1 : cached->state);
	return false;
}

static bool state_seen(const char *property, indigo_property_state state, unsigned int revision) {
	return state_seen_within(property, state, revision, 1);
}

static bool number_change(const char *property, const char *item, double value, indigo_property_state state) {
	unsigned int revision = property_state_revision(property, state);
	return indigo_change_number_property_1(&simulator_test_client, GIOTTO_NAME, property, item, value) == INDIGO_OK && state_seen(property, state, revision);
}

static bool switch_change(const char *property, const char *item, indigo_property_state state) {
	unsigned int revision = property_state_revision(property, state);
	return indigo_change_switch_property_1(&simulator_test_client, GIOTTO_NAME, property, item, true) == INDIGO_OK && state_seen(property, state, revision);
}

static bool text_change(const char *property, const char *item, const char *value, indigo_property_state state) {
	unsigned int revision = property_state_revision(property, state);
	return indigo_change_text_property_1_raw(&simulator_test_client, GIOTTO_NAME, property, item, value) == INDIGO_OK && state_seen(property, state, revision);
}

static bool number_is(const char *property_name, const char *item_name, double expected, double tolerance) {
	indigo_item *item = find_cached_item(property_name, item_name);
	if (item == NULL || fabs(item->number.value - expected) > tolerance) {
		fprintf(stderr, "%s.%s: expected %g, received %g\n", property_name, item_name, expected, item == NULL ? NAN : item->number.value);
		return false;
	}
	return true;
}

static bool switch_is(const char *property_name, const char *item_name, bool expected) {
	indigo_item *item = find_cached_item(property_name, item_name);
	if (item == NULL || item->sw.value != expected) {
		fprintf(stderr, "%s.%s: expected %s\n", property_name, item_name, expected ? "on" : "off");
		return false;
	}
	return true;
}

static bool text_is(const char *property_name, const char *item_name, const char *expected) {
	indigo_item *item = find_cached_item(property_name, item_name);
	if (item == NULL || strcmp(item->text.value, expected)) {
		fprintf(stderr, "%s.%s: expected \"%s\", received \"%s\"\n", property_name, item_name, expected, item == NULL ? "(none)" : item->text.value);
		return false;
	}
	return true;
}

static indigo_property_state property_state(const char *property_name) {
	indigo_property *property = find_cached_property(property_name);
	return property == NULL ? -1 : property->state;
}

// The light and intensity the driver publishes, both OK.
static bool light_is(bool on, double brightness) {
	for (int i = 0; i < 400; i++) {
		indigo_item *light = find_cached_item(AUX_LIGHT_SWITCH_PROPERTY_NAME, AUX_LIGHT_SWITCH_ON_ITEM_NAME);
		indigo_item *intensity = find_cached_item(AUX_LIGHT_INTENSITY_PROPERTY_NAME, AUX_LIGHT_INTENSITY_ITEM_NAME);
		if (light != NULL && intensity != NULL && light->sw.value == on && intensity->number.value == brightness && property_state(AUX_LIGHT_SWITCH_PROPERTY_NAME) == INDIGO_OK_STATE && property_state(AUX_LIGHT_INTENSITY_PROPERTY_NAME) == INDIGO_OK_STATE) {
			return true;
		}
		indigo_usleep(25000);
	}
	fprintf(stderr, "Light did not settle %s at %g\n", on ? "on" : "off", brightness);
	return false;
}

