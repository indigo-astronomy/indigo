// Arm a one-shot panel fault. The simulator applies it to the next request containing key and then removes
// the control file; 'external <light> <brightness>' changes the panel at the next request.
static bool fault(const char *key, const char *action) {
	char temporary[PATH_MAX + 8];
	snprintf(temporary, sizeof(temporary), "%s.tmp", fault_path);
	FILE *file = fopen(temporary, "w");
	if (file == NULL) {
		return false;
	}
	fprintf(file, "%s %s\n", key, action);
	fclose(file);
	return rename(temporary, fault_path) == 0;
}

static int requests(const char *fragment) {
	FILE *file = fopen(event_path, "r");
	if (file == NULL) {
		return -1;
	}
	char line[4096];
	int count = 0;
	while (fgets(line, sizeof(line), file) != NULL) {
		if (strstr(line, fragment) != NULL) {
			count++;
		}
	}
	fclose(file);
	return count;
}

static void print_journal(const char *reason) {
	fprintf(stderr, "%s, journal holds:\n", reason);
	FILE *file = fopen(event_path, "r");
	if (file == NULL) {
		fprintf(stderr, "  (no journal at %s)\n", event_path);
		return;
	}
	char line[4096];
	while (fgets(line, sizeof(line), file) != NULL) {
		fprintf(stderr, "  %s", line);
	}
	fclose(file);
}

static bool wait_for_requests_within(const char *fragment, int expected, int seconds) {
	for (int i = 0; i < seconds * 40; i++) {
		if (requests(fragment) >= expected) {
			return true;
		}
		indigo_usleep(25000);
	}
	char reason[128];
	snprintf(reason, sizeof(reason), "Fewer than %d requests containing '%s'", expected, fragment);
	print_journal(reason);
	return false;
}

static bool wait_for_requests(const char *fragment, int expected) {
	return wait_for_requests_within(fragment, expected, 5);
}

// The n-th request of the journal (0 based) contains fragment.
static bool journal_line_has(int index, const char *fragment) {
	FILE *file = fopen(event_path, "r");
	if (file == NULL) {
		return false;
	}
	char line[4096];
	bool found = false;
	for (int i = 0; fgets(line, sizeof(line), file) != NULL; i++) {
		if (i == index) {
			found = strstr(line, fragment) != NULL;
			break;
		}
	}
	fclose(file);
	if (!found) {
		print_journal("Unexpected request order");
	}
	return found;
}

