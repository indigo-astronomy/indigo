// The panel prefers a port of a CP2102N bridge with the Silicon Labs VID/PID (10c4:ea60), as the GIOTTO reports;
// a CP2102N name behind another VID/PID, or another bridge with the same VID/PID, does not match.
static void usb_match_pattern(void) {
	SERIAL_CHECK_TRUE(driver_up());
	SERIAL_CHECK_TRUE(attached_giotto != NULL);
	SERIAL_CHECK_EQ_INT(1, attached_giotto->match_patterns_count);
	indigo_serial_info ports[3] = { { 0 } };
	ports[0].vendor_id = 0x0403;
	ports[0].product_id = 0x6001;
	strcpy(ports[0].product_string, "CP2102N USB to UART Bridge Controller");
	ports[1].vendor_id = 0x10c4;
	ports[1].product_id = 0xea60;
	strcpy(ports[1].product_string, "CP2104 USB to UART Bridge Controller");
	ports[2].vendor_id = 0x10c4;
	ports[2].product_id = 0xea60;
	strcpy(ports[2].product_string, "CP2102N USB to UART Bridge Controller");
	SERIAL_CHECK_TRUE(indigo_usbserial_match(ports, 2, attached_giotto->match_patterns, attached_giotto->match_patterns_count) == NULL);
	SERIAL_CHECK_TRUE(indigo_usbserial_match(ports, 3, attached_giotto->match_patterns, attached_giotto->match_patterns_count) == &ports[2]);
cleanup:
	driver_stop();
}

