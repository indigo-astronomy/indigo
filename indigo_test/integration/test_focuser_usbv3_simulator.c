// Arm a one-shot controller fault. The simulator applies it to the next request
// whose text starts with command and then removes the control file.
static bool fault(const char *command, const char *action) {
	char temporary[PATH_MAX + 8];
	snprintf(temporary, sizeof(temporary), "%s.tmp", fault_path);
	FILE *file = fopen(temporary, "w");
	if (file == NULL) {
		return false;
	}
	fprintf(file, "%s %s\n", command, action);
	fclose(file);
	return rename(temporary, fault_path) == 0;
}

static int commands(const char *prefix) {
	FILE *file = fopen(event_path, "r");
	if (file == NULL) {
		return -1;
	}
	char line[256];
	int count = 0;
	while (fgets(line, sizeof(line), file) != NULL) {
		if (!strncmp(line, prefix, strlen(prefix))) {
			count++;
		}
	}
	fclose(file);
	return count;
}

static void print_journal(const char *reason) {
	fprintf(stderr, "%s, journal holds:\n", reason);
	FILE *file = fopen(event_path, "r");
	if (file == NULL) {
		fprintf(stderr, "  (no journal at %s)\n", event_path);
		return;
	}
	char line[256];
	while (fgets(line, sizeof(line), file) != NULL) {
		fprintf(stderr, "  %s", line);
	}
	fclose(file);
}

// The driver publishes a property state as soon as its transaction returns, so
// the controller may not have logged the request yet.
static bool wait_for_commands(const char *prefix, int expected) {
	for (int i = 0; i < 200; i++) {
		if (commands(prefix) >= expected) {
			return true;
		}
		indigo_usleep(25000);
	}
	char reason[80];
	snprintf(reason, sizeof(reason), "Fewer than %d '%s' requests", expected, prefix);
	print_journal(reason);
	return false;
}

// The exact six character request, so a test can assert the command and its
// argument as the driver put them on the wire.
static bool command_sent(const char *expected) {
	for (int attempt = 0; attempt < 200; attempt++) {
		FILE *file = fopen(event_path, "r");
		if (file != NULL) {
			char line[256];
			while (fgets(line, sizeof(line), file) != NULL) {
				line[strcspn(line, "\r\n")] = '\0';
				if (!strcmp(line, expected)) {
					fclose(file);
					return true;
				}
			}
			fclose(file);
		}
		indigo_usleep(25000);
	}
	char reason[80];
	snprintf(reason, sizeof(reason), "'%s' was never requested", expected);
	print_journal(reason);
	return false;
}

