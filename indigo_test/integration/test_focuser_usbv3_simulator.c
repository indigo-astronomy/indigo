// Losing the transport has to be reported instead of being published as
// success, and the driver must still release the dead handle.
static void transport_loss(void) {
	SERIAL_CHECK_TRUE(driver_start());
	SERIAL_CHECK_TRUE(position_is(1000));
	// The controller drops the line while answering the first readback of a
	// move, which is the gate that says the port is gone.
	SERIAL_CHECK_TRUE(fault("FPOSRO", "close"));
	SERIAL_CHECK_TRUE(number_change(FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, 1300, INDIGO_ALERT_STATE));
	SERIAL_CHECK_TRUE(number_change(FOCUSER_COMPENSATION_PROPERTY_NAME, FOCUSER_COMPENSATION_ITEM_NAME, 12, INDIGO_ALERT_STATE));
	SERIAL_CHECK_TRUE(switch_change(FOCUSER_MODE_PROPERTY_NAME, FOCUSER_MODE_AUTOMATIC_ITEM_NAME, INDIGO_ALERT_STATE));
	disconnect_serial_device(&usbv3_focuser);
	SERIAL_CHECK_TRUE(!context.connected);
cleanup:
	driver_stop();
}

// ----------------------------------------------------------------- runner

typedef struct { const char *name; void (*run)(void); const char *profile; } simulated_case;

int main(void) {
	const simulated_case cases[] = {
		{ "metadata", metadata, "normal" },
		{ "property_contract", property_contract, "normal" },
		{ "configured_readback", configured_readback, "configured" },
		{ "handshake_rejected", handshake_rejected, "no-handshake" },
		{ "handshake_timeout", handshake_timeout, "normal" },
		{ "config_query_failure", config_query_failure, "bad-config" },
		{ "repeated_init_shutdown", repeated_init_shutdown, "normal" },
		{ "shutdown_rejected_while_connected", shutdown_rejected_while_connected, "normal" },
		{ "reconnect", reconnect, "normal" },
		{ "absolute_move", absolute_move, "normal" },
		{ "relative_move", relative_move, "normal" },
		{ "reverse_motion", reverse_motion, "normal" },
		{ "limits_clamp", limits_clamp, "normal" },
		{ "abort_motion", abort_motion, "normal" },
		{ "abort_while_idle", abort_while_idle, "normal" },
		{ "overlap_rejected", overlap_rejected, "normal" },
		{ "motion_readback_failure", motion_readback_failure, "normal" },
		{ "external_motion_observed", external_motion_observed, "external-motion" },
		{ "disconnect_during_motion", disconnect_during_motion, "normal" },
		{ "controller_settings", controller_settings, "normal" },
		{ "negative_compensation", negative_compensation, "normal" },
		{ "settings_reported_failures", settings_reported_failures, "normal" },
		{ "focuser_mode", focuser_mode, "normal" },
		{ "configuration_roundtrip", configuration_roundtrip, "normal" },
		{ "temperature_polling", temperature_polling, "normal" },
		{ "transport_loss", transport_loss, "normal" }
	};
	setvbuf(stdout, NULL, _IOLBF, 0);
	if (mkdtemp(fixture_directory) == NULL || indigo_test_mkdtemp_home(config_folder) == NULL) {
		fprintf(stderr, "Cannot create fixture directory\n");
		return 1;
	}
	snprintf(event_path, sizeof(event_path), "%s/events.log", fixture_directory);
	snprintf(fault_path, sizeof(fault_path), "%s/fault", fixture_directory);
	setenv("INDIGO_USBV3_EVENTS", event_path, 1);
	setenv("INDIGO_USBV3_FAULT", fault_path, 1);
	const char *filter = getenv("USBV3_TEST_FILTER");
	int failures = 0;
	for (int i = 0; i < ARRAY_SIZE(cases); i++) {
		if (filter != NULL && strstr(cases[i].name, filter) == NULL) {
			continue;
		}
		unlink(fault_path);
		const char *arguments[] = { "--profile", cases[i].profile, NULL, NULL };
		if (getenv("USBV3_TEST_TRACE") != NULL) {
			arguments[2] = "--trace";
		}
		if (!start_external_serial_simulator_with_args(&fixture, FOCUSER_USBV3_SIMULATOR_EXECUTABLE, arguments)) {
			fprintf(stderr, "Simulator startup failed\n");
			failures++;
			break;
		}
		fflush(NULL);
		pid_t child = fork();
		if (child == 0) {
			alarm(120);
			indigo_test_case test = { cases[i].name, cases[i].run };
			_exit(indigo_run_tests("USB_Focus v3", &test, 1));
		}
		int status = 0;
		if (child > 0) {
			while (waitpid(child, &status, 0) < 0) {
				if (errno != EINTR) {
					status = -1;
					break;
				}
			}
		}
		stop_external_serial_simulator(&fixture);
		if (child < 0 || status == -1 || !WIFEXITED(status) || WEXITSTATUS(status)) {
			failures++;
			printf("FAIL: %s (exit=%d, signal=%d)\n", cases[i].name, WIFEXITED(status) ? WEXITSTATUS(status) : -1, WIFSIGNALED(status) ? WTERMSIG(status) : 0);
		}
	}
	unlink(fault_path);
	unlink(event_path);
	rmdir(fixture_directory);
	unsetenv("INDIGO_USBV3_EVENTS");
	unsetenv("INDIGO_USBV3_FAULT");
	printf("USB_Focus v3: %d failing scenarios\n", failures);
	return failures ? 1 : 0;
}
