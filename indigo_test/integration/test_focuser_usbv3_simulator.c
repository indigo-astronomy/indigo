// Automatic mode hands the focuser over to the controller and stops the driver
// polling; manual mode takes it back and reads the position again.
static void focuser_mode(void) {
	SERIAL_CHECK_TRUE(driver_start());
	SERIAL_CHECK_TRUE(switch_change(FOCUSER_MODE_PROPERTY_NAME, FOCUSER_MODE_AUTOMATIC_ITEM_NAME, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(wait_for_commands("FAUTOM", 1));
	int polls = commands("FTMPRO");
	indigo_usleep(2000000);
	SERIAL_CHECK_EQ_INT(polls, commands("FTMPRO"));
	int manual = commands("FMANUA");
	SERIAL_CHECK_TRUE(switch_change(FOCUSER_MODE_PROPERTY_NAME, FOCUSER_MODE_MANUAL_ITEM_NAME, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(wait_for_commands("FMANUA", manual + 1));
	SERIAL_CHECK_TRUE(wait_for_commands("FTMPRO", polls + 1));
	SERIAL_CHECK_TRUE(number_change(FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, 1200, INDIGO_BUSY_STATE));
	SERIAL_CHECK_TRUE(position_is(1200));
cleanup:
	driver_stop();
}

// FOCUSER_REVERSE_MOTION is the one setting the driver persists.
static void configuration_roundtrip(void) {
	SERIAL_CHECK_TRUE(driver_start());
	SERIAL_CHECK_TRUE(switch_change(FOCUSER_REVERSE_MOTION_PROPERTY_NAME, FOCUSER_REVERSE_MOTION_ENABLED_ITEM_NAME, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(save_configuration());
	disconnect_serial_device(&usbv3_focuser);
	tear_down_serial_driver(&usbv3_focuser);
	SERIAL_CHECK_TRUE(driver_start());
	SERIAL_CHECK_TRUE(switch_is(FOCUSER_REVERSE_MOTION_PROPERTY_NAME, FOCUSER_REVERSE_MOTION_DISABLED_ITEM_NAME, true));
	SERIAL_CHECK_TRUE(switch_change(CONFIG_PROPERTY_NAME, CONFIG_LOAD_ITEM_NAME, INDIGO_OK_STATE));
	for (int i = 0; i < 50 && !switch_is(FOCUSER_REVERSE_MOTION_PROPERTY_NAME, FOCUSER_REVERSE_MOTION_ENABLED_ITEM_NAME, true); i++) {
		indigo_usleep(100000);
	}
	SERIAL_CHECK_TRUE(switch_is(FOCUSER_REVERSE_MOTION_PROPERTY_NAME, FOCUSER_REVERSE_MOTION_ENABLED_ITEM_NAME, true));
	// The restored setting has to govern the next move.
	SERIAL_CHECK_TRUE(switch_change(FOCUSER_DIRECTION_PROPERTY_NAME, FOCUSER_DIRECTION_MOVE_OUTWARD_ITEM_NAME, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(number_change(FOCUSER_STEPS_PROPERTY_NAME, FOCUSER_STEPS_ITEM_NAME, 300, INDIGO_BUSY_STATE));
	SERIAL_CHECK_TRUE(command_sent("I00300"));
cleanup:
	driver_stop();
}

