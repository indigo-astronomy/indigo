static void controller_settings(void) {
	SERIAL_CHECK_TRUE(driver_start());
	SERIAL_CHECK_TRUE(number_change(FOCUSER_SPEED_PROPERTY_NAME, FOCUSER_SPEED_ITEM_NAME, 6, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(command_sent("SMO006"));
	SERIAL_CHECK_TRUE(switch_change(X_FOCUSER_STEP_SIZE_PROPERTY_NAME, X_FOCUSER_HALF_STEP_ITEM_NAME, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(wait_for_commands("SMSTPD", 1));
	SERIAL_CHECK_TRUE(number_change(FOCUSER_LIMITS_PROPERTY_NAME, FOCUSER_LIMITS_MAX_POSITION_ITEM_NAME, 40000, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(command_sent("M40000"));
	// A positive compensation writes the amount, the sign and the threshold.
	SERIAL_CHECK_TRUE(number_change(FOCUSER_COMPENSATION_PROPERTY_NAME, FOCUSER_COMPENSATION_ITEM_NAME, 42, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(command_sent("FLX042"));
	SERIAL_CHECK_TRUE(wait_for_commands("FZSIG1", 1));
	SERIAL_CHECK_TRUE(number_change(FOCUSER_COMPENSATION_PROPERTY_NAME, FOCUSER_COMPENSATION_THRESHOLD_ITEM_NAME, 4, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(command_sent("SMA004"));
	// The settings the driver reads back on the next connect must be the ones
	// it wrote.
	disconnect_serial_device(&usbv3_focuser);
	SERIAL_CHECK_TRUE(connect_serial_device(&usbv3_focuser, fixture.port));
	SERIAL_CHECK_TRUE(number_is(FOCUSER_SPEED_PROPERTY_NAME, FOCUSER_SPEED_ITEM_NAME, 6, 0));
	SERIAL_CHECK_TRUE(switch_is(X_FOCUSER_STEP_SIZE_PROPERTY_NAME, X_FOCUSER_HALF_STEP_ITEM_NAME, true));
	SERIAL_CHECK_TRUE(number_is(FOCUSER_LIMITS_PROPERTY_NAME, FOCUSER_LIMITS_MAX_POSITION_ITEM_NAME, 40000, 0));
	SERIAL_CHECK_TRUE(number_is(FOCUSER_COMPENSATION_PROPERTY_NAME, FOCUSER_COMPENSATION_ITEM_NAME, 42, 0));
	SERIAL_CHECK_TRUE(number_is(FOCUSER_COMPENSATION_PROPERTY_NAME, FOCUSER_COMPENSATION_THRESHOLD_ITEM_NAME, 4, 0));
cleanup:
	driver_stop();
}

