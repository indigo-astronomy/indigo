// WebSocket upgrade handshake of the production TCP server (FND-000045).
//
// The server appends the RFC 6455 GUID to the Sec-WebSocket-Key value in a 256-byte buffer before
// hashing it, so a key longer than 219 bytes used to overflow that buffer. These cases talk to the
// real server on a loopback ephemeral port. The sanitize build compiles indigo_server_tcp.c into the
// test with AddressSanitizer, so a write past the buffer aborts the run instead of passing silently.

