int QSICamera::get_ImageArray(unsigned short *pVal) {
	enter_call();
	wait_for_gate(QSI_FAKE_GATE_IMAGE_ARRAY);
	lock();
	qsi_fake_camera *camera = current();
	if (camera == NULL) {
		unlock();
		leave_call();
		return fail(QSI_NOTCONNECTED, "get_ImageArray");
	}
	if (consume(&camera->fail.image_array)) {
		unlock();
		leave_call();
		return fail(QSI_NOIMAGEAVAILABLE, "get_ImageArray");
	}
	// Deterministic, coordinate-addressable content so a test can verify the
	// ROI and binning mapping of every delivered pixel.
	long width = camera->width;
	short bin_x = camera->bin_x > 0 ? camera->bin_x : 1;
	short bin_y = camera->bin_y > 0 ? camera->bin_y : 1;
	for (long y = 0; y < camera->num_y; y++) {
		for (long x = 0; x < camera->num_x; x++) {
			long sensor_x = (camera->start_x + x) * bin_x;
			long sensor_y = (camera->start_y + y) * bin_y;
			pVal[y * camera->num_x + x] = ccd_test_noise((unsigned)(sensor_y * width + sensor_x), (unsigned)bin_x);
		}
	}
	camera->image_array_calls++;
	unlock();
	leave_call();
	record("get_ImageArray");
	return QSI_OK;
}

