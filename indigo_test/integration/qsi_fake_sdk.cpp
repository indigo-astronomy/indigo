// Recurring temperature polling is timing dependent, so a run of consecutive
// polling reads collapses into one normalized line and the trace stays
// comparable across hosts and driver revisions.
// A polling run always starts with the temperature read; the cooler-power
// capability query and reading only belong to it while such a run is open, so
// the one-off capability query issued during connection is preserved.
static bool starts_poll_run(const char *line) {
	return !strncmp(line, "get_CCDTemperature", 18);
}

static bool continues_poll_run(const char *line) {
	return starts_poll_run(line) || !strncmp(line, "get_CanGetCoolerPower", 21) || !strncmp(line, "get_CoolerPower", 15);
}

extern "C" bool qsi_fake_trace_write(const char *path) {
	lock();
	FILE *file = fopen(path, "w");
	if (file != NULL) {
		bool in_poll = false;
		for (int i = 0; i < trace_count; i++) {
			if (in_poll ? continues_poll_run(trace[i]) : starts_poll_run(trace[i])) {
				if (!in_poll) {
					fprintf(file, "[periodic temperature poll]\n");
					in_poll = true;
				}
				continue;
			}
			in_poll = false;
			fprintf(file, "%s\n", trace[i]);
		}
		fclose(file);
	}
	bool ok = file != NULL;
	unlock();
	return ok;
}

