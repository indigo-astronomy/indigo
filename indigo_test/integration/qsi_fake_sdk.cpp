int QSICamera::get_ImageReady(bool *pVal) {
	enter_call();
	wait_for_gate(QSI_FAKE_GATE_IMAGE_READY);
	lock();
	qsi_fake_camera *camera = current();
	if (camera == NULL) {
		unlock();
		leave_call();
		return fail(QSI_NOTCONNECTED, "get_ImageReady");
	}
	camera->image_ready_calls++;
	if (consume(&camera->fail.image_ready)) {
		unlock();
		leave_call();
		return fail(QSI_NOIMAGEAVAILABLE, "get_ImageReady");
	}
	bool ready = !camera->image_never_ready;
	if (ready && camera->not_ready_reads > 0) {
		camera->not_ready_reads--;
		ready = false;
	}
	*pVal = ready;
	unlock();
	leave_call();
	record("get_ImageReady=%s", ready ? "true" : "false");
	return QSI_OK;
}

