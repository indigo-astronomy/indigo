int QSICamera::put_Connected(bool newVal) {
	enter_call();
	record("put_Connected(%s)", newVal ? "true" : "false");
	wait_for_gate(QSI_FAKE_GATE_CONNECT);
	lock();
	int index = -1;
	for (int i = 0; i < QSI_FAKE_MAX_CAMERAS; i++) {
		if (camera_defined[i] && !strcmp(cameras[i].serial, selected_serial)) {
			index = i;
			break;
		}
	}
	bool failed = false;
	if (newVal) {
		if (index < 0 || !cameras[index].present || connected_index >= 0 || consume(&cameras[index].fail.connect)) {
			failed = true;
		} else {
			cameras[index].connect_calls++;
			connected_index = index;
		}
	} else {
		if (connected_index < 0) {
			calls_after_close++;
			failed = true;
		} else if (consume(&cameras[connected_index].fail.disconnect)) {
			failed = true;
		} else {
			cameras[connected_index].disconnect_calls++;
			connected_index = -1;
		}
	}
	unlock();
	leave_call();
	return failed ? fail(newVal ? QSI_NOTCONNECTED : QSI_UNRECOVERABLE, newVal ? "put_Connected(true)" : "put_Connected(false)") : QSI_OK;
}

// Every accessor below operates on the single connected camera, exactly like
// the vendor SDK's global object.
#define WITH_CAMERA(operation) \
	enter_call(); \
	lock(); \
	qsi_fake_camera *camera = current(); \
	if (camera == NULL) { \
		unlock(); \
		leave_call(); \
		return fail(QSI_NOTCONNECTED, operation); \
	}

#define RELEASE_CAMERA() \
	unlock(); \
	leave_call()

#define FAIL_CAMERA(injection, code, operation) \
	if (consume(&camera->fail.injection)) { \
		unlock(); \
		leave_call(); \
		return fail(code, operation); \
	}

