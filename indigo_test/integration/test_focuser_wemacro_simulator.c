typedef struct {
	const char *name;
	void (*run)(void);
	const char *profile;
} wemacro_test;

static int run_cases(const wemacro_test *cases, int count) {
	int failures = 0;
	setvbuf(stdout, NULL, _IOLBF, 0);
	if (mkdtemp(fixture_dir) == NULL) {
		return 1;
	}
	snprintf(event_path, sizeof(event_path), "%s/events", fixture_dir);
	snprintf(fault_path, sizeof(fault_path), "%s/fault", fixture_dir);
	setenv("INDIGO_WEMACRO_EVENTS", event_path, 1);
	setenv("INDIGO_WEMACRO_FAULT", fault_path, 1);
	const char *filter = getenv("WEMACRO_TEST_FILTER");
	for (int i = 0; i < count; i++) {
		if (filter != NULL && strstr(cases[i].name, filter) == NULL) {
			continue;
		}
		current_case = cases[i].name;
		current_profile = cases[i].profile;
		unlink(fault_path);
		const char *args[] = { "--profile", current_profile, NULL };
		if (!start_external_serial_simulator_with_args(&fixture, FOCUSER_WEMACRO_SIMULATOR_EXECUTABLE, args)) {
			failures++;
			break;
		}
		if (!strcmp(current_case, "shutdown_and_instances")) {
			unsetenv("INDIGO_WEMACRO_EVENTS");
			unsetenv("INDIGO_WEMACRO_FAULT");
			const char *second_args[] = { "--profile", "normal", NULL };
			bool ready = start_external_serial_simulator_with_args(&second_fixture, FOCUSER_WEMACRO_SIMULATOR_EXECUTABLE, second_args);
			setenv("INDIGO_WEMACRO_EVENTS", event_path, 1);
			setenv("INDIGO_WEMACRO_FAULT", fault_path, 1);
			if (!ready) {
				stop_external_serial_simulator(&fixture);
				failures++;
				break;
			}
		}
		fflush(NULL);
		pid_t child = fork();
		if (child == 0) {
			alarm(45);
			indigo_test_case test = { cases[i].name, cases[i].run };
			_exit(indigo_run_tests("WeMacro Rail", &test, 1));
		}
		int status = 0;
		if (child > 0) {
			while (waitpid(child, &status, 0) < 0 && errno == EINTR) { }
		}
		stop_external_serial_simulator(&fixture);
		stop_external_serial_simulator(&second_fixture);
		if (child < 0 || !WIFEXITED(status) || WEXITSTATUS(status)) {
			fprintf(stderr, "FAIL %s (status %d)\n", cases[i].name, status);
			failures++;
		}
	}
	unlink(fault_path);
	if (filter == NULL) {
		unlink(event_path);
	} else {
		fprintf(stderr, "WeMacro event journal: %s\n", event_path);
	}
	rmdir(fixture_dir);
	unsetenv("INDIGO_WEMACRO_EVENTS");
	unsetenv("INDIGO_WEMACRO_FAULT");
	printf("WeMacro Rail: %d failing scenarios\n", failures);
	return failures ? 1 : 0;
}

