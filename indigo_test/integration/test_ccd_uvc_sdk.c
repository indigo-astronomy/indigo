static void reference_trace_contract(void) {
	ASSERT_TRUE(begin(true));
	indigo_change_switch_property_1(&simulator_test_client, device_name, CCD_IMAGE_FORMAT_PROPERTY_NAME, CCD_IMAGE_FORMAT_RAW_ITEM_NAME, true);
	indigo_change_number_property_1(&simulator_test_client, device_name, CCD_EXPOSURE_PROPERTY_NAME, CCD_EXPOSURE_ITEM_NAME, .01);
	ASSERT_TRUE(wait_for_property_state(CCD_EXPOSURE_PROPERTY_NAME, INDIGO_OK_STATE));
	if (getenv("UVC_PRINT_TRACE")) {
		fprintf(stdout, "--- UVC REFERENCE TRACE ---\n%s\n--- END UVC REFERENCE TRACE ---\n", trace_buffer);
	}
	ASSERT_TRUE(strstr(trace_buffer, "uvc_open camera=0\nuvc_print_diag\nuvc_get_format_descs") != NULL);
	ASSERT_TRUE(strstr(trace_buffer, "uvc_set_ae_mode value=1\nuvc_set_exposure value=100\nuvc_set_gain value=10\nuvc_set_gamma value=100\nuvc_stream_open") != NULL);
	ASSERT_TRUE(strstr(trace_buffer, "property CCD_EXPOSURE state=2\nuvc_set_ae_mode value=1") != NULL);
	ASSERT_TRUE(strstr(trace_buffer, "uvc_stream_start flags=0\nuvc_stream_get_frame timeout=1000") != NULL);
	FILE *file = fopen(UVC_REFERENCE_TRACE_PATH, "r");
	ASSERT_TRUE(file != NULL);
	char expected[TRACE_SIZE];
	size_t length = fread(expected, 1, sizeof(expected) - 1, file);
	fclose(file);
	expected[length] = 0;
	while (length > 0 && (expected[length - 1] == '\n' || expected[length - 1] == '\r')) {
		expected[--length] = 0;
	}
	ASSERT_STREQ(expected, trace_buffer);
	end();
}

