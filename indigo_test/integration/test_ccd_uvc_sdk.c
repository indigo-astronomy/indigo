indigo_result uvc_test_attach(indigo_device *device) {
	if (atomic_load(&fail_attach)) {
		return INDIGO_FAILED;
	}
	indigo_result result = indigo_attach_device(device);
	if (result == INDIGO_OK) {
		for (int i = 0; i < CAMERAS; i++) {
			if (!logical[i]) {
				logical[i] = device;
				break;
			}
		}
		atomic_fetch_add(&attached, 1);
		trace("indigo_attach_device name=%s", device->name);
	}
	return result;
}

indigo_result uvc_test_detach(indigo_device *device) {
	trace("indigo_detach_device name=%s", device->name);
	indigo_result result = indigo_detach_device(device);
	for (int i = 0; i < CAMERAS; i++) {
		if (logical[i] == device) {
			logical[i] = NULL;
			break;
		}
	}
	atomic_fetch_sub(&attached, 1);
	return result;
}

static indigo_result observe_image(indigo_client *client, indigo_device *device, indigo_property *property, const char *message) {
	if ((!strcmp(property->name, CCD_EXPOSURE_PROPERTY_NAME) || !strcmp(property->name, CCD_STREAMING_PROPERTY_NAME) || !strcmp(property->name, CONNECTION_PROPERTY_NAME)) && property->state != INDIGO_IDLE_STATE) {
		trace("property %s state=%d", property->name, property->state);
	}
	if (!strcmp(property->name, CCD_IMAGE_PROPERTY_NAME) && property->state == INDIGO_OK_STATE && property->items[0].blob.size > 0) {
		bool valid = property->items[0].blob.value != NULL && !strcmp(property->items[0].blob.format, ".raw") && property->items[0].blob.size >= (long)sizeof(indigo_raw_header);
		if (valid) {
			indigo_raw_header header = { 0 };
			memcpy(&header, property->items[0].blob.value, sizeof(header));
			valid = header.width > 0 && header.height > 0 && (header.signature == INDIGO_RAW_MONO8 || header.signature == INDIGO_RAW_MONO16 || header.signature == INDIGO_RAW_RGB24);
		}
		atomic_fetch_add(&blobs, 1);
		if (!valid) {
			atomic_fetch_add(&bad_blobs, 1);
		}
	}
	return simulator_client_update_property(client, device, property, message);
}

static bool wait_atomic(atomic_int *value, int expected) {
	for (int i = 0; i < 500; i++) {
		if (atomic_load(value) == expected) {
			return true;
		}
		indigo_usleep(10000);
	}
	return false;
}

static indigo_result change_stream(double exposure, double count) {
	indigo_property *cached = find_cached_property(CCD_STREAMING_PROPERTY_NAME);
	if (!cached) {
		return INDIGO_FAILED;
	}
	indigo_property *request = indigo_copy_property(NULL, cached);
	for (int i = 0; i < request->count; i++) {
		if (!strcmp(request->items[i].name, CCD_STREAMING_EXPOSURE_ITEM_NAME)) {
			request->items[i].number.value = request->items[i].number.target = exposure;
		} else if (!strcmp(request->items[i].name, CCD_STREAMING_COUNT_ITEM_NAME)) {
			request->items[i].number.value = request->items[i].number.target = count;
		}
	}
	indigo_result result = indigo_change_property(&simulator_test_client, request);
	indigo_release_property(request);
	return result;
}

static bool begin(bool connect) {
	reset_fake();
	reset_simulator_context(&uvc_case);
	simulator_test_client.update_property = observe_image;
	if (indigo_start() != INDIGO_OK || indigo_attach_client(&simulator_test_client) != INDIGO_OK || indigo_ccd_uvc(INDIGO_DRIVER_INIT, NULL) != INDIGO_OK || !wait_atomic(&attached, 1)) {
		fprintf(stderr, "UVC begin failed, attached=%d trace:\n%s\n", atomic_load(&attached), trace_buffer);
		return false;
	}
	enumerate_simulator_device();
	if (connect) {
		indigo_change_switch_property_1(&simulator_test_client, device_name, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, true);
		bool connected = wait_for_simulator_connection_state(true);
		if (!connected) {
			fprintf(stderr, "UVC connect failed, trace:\n%s\n", trace_buffer);
		}
		return connected;
	}
	return true;
}

static void end(void) {
	if (context.connected) {
		indigo_change_switch_property_1(&simulator_test_client, device_name, CONNECTION_PROPERTY_NAME, CONNECTION_DISCONNECTED_ITEM_NAME, true);
		wait_for_simulator_connection_state(false);
	}
	indigo_ccd_uvc(INDIGO_DRIVER_SHUTDOWN, NULL);
	indigo_detach_client(&simulator_test_client);
	indigo_stop();
	release_cached_properties();
}

