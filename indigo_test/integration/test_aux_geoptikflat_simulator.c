// The harness keeps an append-only list of every property it has ever seen defined, so the live
// visibility of the connection-dependent properties is read from the property cache, which does
// follow deletion.
static bool connected_properties_published(bool expected) {
	for (int i = 0; i < ARRAY_SIZE(geoptikflat_connected_properties); i++) {
		if ((find_cached_property(geoptikflat_connected_properties[i]) != NULL) != expected) {
			fprintf(stderr, "%s is %spublished\n", geoptikflat_connected_properties[i], expected ? "not " : "");
			return false;
		}
	}
	return true;
}

static const char *info_text(const char *item_name) {
	indigo_item *item = find_cached_item(INFO_PROPERTY_NAME, item_name);
	return item == NULL ? "" : item->text.value;
}

static bool change_intensity(double percent, indigo_property_state expected_state) {
	unsigned int revision = property_revision(AUX_LIGHT_INTENSITY_PROPERTY_NAME);
	if (indigo_change_number_property_1(&simulator_test_client, geoptikflat.device_name, AUX_LIGHT_INTENSITY_PROPERTY_NAME, AUX_LIGHT_INTENSITY_ITEM_NAME, percent) != INDIGO_OK) {
		return false;
	}
	return wait_for_property_state_after(AUX_LIGHT_INTENSITY_PROPERTY_NAME, expected_state, revision);
}

static bool change_light(const char *item_name, indigo_property_state expected_state) {
	unsigned int revision = property_revision(AUX_LIGHT_SWITCH_PROPERTY_NAME);
	if (indigo_change_switch_property_1(&simulator_test_client, geoptikflat.device_name, AUX_LIGHT_SWITCH_PROPERTY_NAME, item_name, true) != INDIGO_OK) {
		return false;
	}
	return wait_for_property_state_after(AUX_LIGHT_SWITCH_PROPERTY_NAME, expected_state, revision);
}

// Leave the persistent AUX_LIGHT_SWITCH and AUX_LIGHT_INTENSITY at their attach-time defaults so a
// case that saved a configuration cannot decide what the next case connects with.
