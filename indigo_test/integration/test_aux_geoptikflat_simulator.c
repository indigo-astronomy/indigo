// A reply that does not echo the operation that was sent is not an answer to it. Every rejected
// request must be reported and must not stop the next one from succeeding.
static void unmatched_replies_fail_the_request(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	static const char *faults[] = { "drop", "malformed", "mismatch" };
	SERIAL_CHECK_TRUE(start_geoptikflat(&simulator, NULL, NULL));
	SERIAL_CHECK_TRUE(start_serial_driver(&geoptikflat, simulator.port));
	online = true;
	for (int i = 0; i < ARRAY_SIZE(faults); i++) {
		SERIAL_CHECK_TRUE(change_intensity(30, INDIGO_OK_STATE));
		SERIAL_CHECK_TRUE(arm_fault(&simulator, faults[i], "B"));
		SERIAL_CHECK_TRUE(change_intensity(60, INDIGO_ALERT_STATE));
		SERIAL_CHECK_TRUE(change_intensity(60, INDIGO_OK_STATE));
		SERIAL_CHECK_TRUE(change_light(AUX_LIGHT_SWITCH_OFF_ITEM_NAME, INDIGO_OK_STATE));
		SERIAL_CHECK_TRUE(arm_fault(&simulator, faults[i], "L"));
		SERIAL_CHECK_TRUE(change_light(AUX_LIGHT_SWITCH_ON_ITEM_NAME, INDIGO_ALERT_STATE));
		SERIAL_CHECK_TRUE(change_light(AUX_LIGHT_SWITCH_ON_ITEM_NAME, INDIGO_OK_STATE));
	}
cleanup:
	if (online) {
		stop_serial_driver(&geoptikflat);
	}
	stop_external_serial_simulator(&simulator);
}

