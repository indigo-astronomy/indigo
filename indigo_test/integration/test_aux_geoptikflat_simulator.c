// Both driver properties are persistent. A restored configuration has to reach the device, and the
// restored state has to be pushed again by the next connection rather than the attach-time default.
static void configuration_roundtrip_reaches_the_device(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_geoptikflat(&simulator, NULL, NULL));
	SERIAL_CHECK_TRUE(start_serial_driver(&geoptikflat, simulator.port));
	online = true;
	SERIAL_CHECK_TRUE(change_intensity(75, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(change_light(AUX_LIGHT_SWITCH_ON_ITEM_NAME, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(save_configuration());
	disconnect_serial_device(&geoptikflat);
	tear_down_serial_driver(&geoptikflat);
	online = false;
	clear_events(&simulator);
	SERIAL_CHECK_TRUE(start_serial_driver(&geoptikflat, simulator.port));
	online = true;
	// A freshly attached device connects with the attach-time defaults, not with the saved state.
	static const char *defaults[] = { ">POOO", ">VOOO", ">B127", ">DOOO" };
	SERIAL_CHECK_TRUE(wait_for_event(&simulator, ">DOOO", 1));
	SERIAL_CHECK_TRUE(events_start_with(&simulator, defaults, ARRAY_SIZE(defaults)));
	SERIAL_CHECK_TRUE(cached_number_value(AUX_LIGHT_INTENSITY_PROPERTY_NAME, AUX_LIGHT_INTENSITY_ITEM_NAME) == 50);
	clear_events(&simulator);
	unsigned int revision = property_revision(CONFIG_PROPERTY_NAME);
	SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_change_switch_property_1(&simulator_test_client, geoptikflat.device_name, CONFIG_PROPERTY_NAME, CONFIG_LOAD_ITEM_NAME, true));
	SERIAL_CHECK_TRUE(wait_for_property_state_after(CONFIG_PROPERTY_NAME, INDIGO_OK_STATE, revision));
	// The restore replays the saved values as ordinary change requests, so the device follows them.
	SERIAL_CHECK_TRUE(wait_for_event(&simulator, ">B191", 1));
	SERIAL_CHECK_TRUE(wait_for_event(&simulator, ">LOOO", 1));
	SERIAL_CHECK_TRUE(wait_for_number_item_value(AUX_LIGHT_INTENSITY_PROPERTY_NAME, AUX_LIGHT_INTENSITY_ITEM_NAME, 75, 0));
	assert_switch_item_value(AUX_LIGHT_SWITCH_PROPERTY_NAME, AUX_LIGHT_SWITCH_ON_ITEM_NAME, true);
	disconnect_serial_device(&geoptikflat);
	clear_events(&simulator);
	SERIAL_CHECK_TRUE(connect_serial_device(&geoptikflat, simulator.port));
	static const char *restored[] = { ">POOO", ">VOOO", ">B191", ">LOOO" };
	SERIAL_CHECK_TRUE(wait_for_event(&simulator, ">LOOO", 1));
	SERIAL_CHECK_TRUE(events_start_with(&simulator, restored, ARRAY_SIZE(restored)));
	SERIAL_CHECK_TRUE(restore_saved_defaults());
cleanup:
	if (online) {
		stop_serial_driver(&geoptikflat);
	}
	stop_external_serial_simulator(&simulator);
}

// A handshake that fails at any of its steps must leave the device disconnected with the serial
// port released, and must not prevent a later connection from succeeding.
static void handshake_failures_leave_the_device_disconnected(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_geoptikflat(&simulator, NULL, NULL));
	SERIAL_CHECK_TRUE(bring_up_serial_driver(&geoptikflat));
	online = true;
	enumerate_simulator_device();
	SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_change_text_property_1_raw(&simulator_test_client, geoptikflat.device_name, DEVICE_PORT_PROPERTY_NAME, DEVICE_PORT_ITEM_NAME, "/dev/indigo-nonexistent-geoptikflat-test"));
	unsigned int revision = property_revision(CONNECTION_PROPERTY_NAME);
	SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_change_switch_property_1(&simulator_test_client, geoptikflat.device_name, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, true));
	SERIAL_CHECK_TRUE(wait_for_property_state_seen_after(CONNECTION_PROPERTY_NAME, INDIGO_ALERT_STATE, revision));
	SERIAL_CHECK_TRUE(!context.connected);
	assert_switch_item_value(CONNECTION_PROPERTY_NAME, CONNECTION_DISCONNECTED_ITEM_NAME, true);
	SERIAL_CHECK_TRUE(connected_properties_published(false));
	static const char *steps[] = { "P", "V" };
	for (int i = 0; i < ARRAY_SIZE(steps); i++) {
		SERIAL_CHECK_TRUE(arm_fault(&simulator, "drop", steps[i]));
		SERIAL_CHECK_TRUE(!connect_serial_device(&geoptikflat, simulator.port));
		SERIAL_CHECK_TRUE(wait_for_property_state(CONNECTION_PROPERTY_NAME, INDIGO_ALERT_STATE));
		SERIAL_CHECK_TRUE(!context.connected);
		SERIAL_CHECK_TRUE(find_cached_property(AUX_LIGHT_SWITCH_PROPERTY_NAME) == NULL);
	}
	SERIAL_CHECK_TRUE(arm_fault(&simulator, "mismatch", "P"));
	SERIAL_CHECK_TRUE(!connect_serial_device(&geoptikflat, simulator.port));
	SERIAL_CHECK_TRUE(!context.connected);
	SERIAL_CHECK_TRUE(connect_serial_device(&geoptikflat, simulator.port));
	SERIAL_CHECK_TRUE(change_intensity(35, INDIGO_OK_STATE));
cleanup:
	if (online) {
		disconnect_serial_device(&geoptikflat);
		tear_down_serial_driver(&geoptikflat);
	}
	stop_external_serial_simulator(&simulator);
}

