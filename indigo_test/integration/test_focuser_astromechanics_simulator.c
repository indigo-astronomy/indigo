static void metadata_and_property_completeness(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	SERIAL_CHECK_TRUE(start_external_serial_simulator(&simulator, FOCUSER_ASTROMECHANICS_SIMULATOR_EXECUTABLE));
	SERIAL_CHECK_TRUE(start_serial_driver(&astromechanics_focuser, simulator.port));
	online = true;
	SERIAL_CHECK_TRUE(context.connected && context.last_connection_state == INDIGO_OK_STATE);

	assert_device_interface(INDIGO_INTERFACE_FOCUSER);
	assert_defined_property(FOCUSER_POSITION_PROPERTY_NAME);
	assert_defined_property(FOCUSER_STEPS_PROPERTY_NAME);
	assert_defined_property(FOCUSER_DIRECTION_PROPERTY_NAME);
	assert_property_has_item(FOCUSER_DIRECTION_PROPERTY_NAME, FOCUSER_DIRECTION_MOVE_INWARD_ITEM_NAME);
	assert_property_has_item(FOCUSER_DIRECTION_PROPERTY_NAME, FOCUSER_DIRECTION_MOVE_OUTWARD_ITEM_NAME);
	assert_property_has_item(X_FOCUSER_APERTURE_PROPERTY_NAME, X_FOCUSER_APERTURE_ITEM_NAME);

	// The lens has no stop command and no speed control, and the driver hides both rather than
	// offering a button that cannot do anything. This is the one focuser in the tree where the
	// class-standard completeness assertion does not apply.
	assert_not_defined_property(FOCUSER_ABORT_MOTION_PROPERTY_NAME);
	assert_not_defined_property(FOCUSER_SPEED_PROPERTY_NAME);
	// Nor does it read temperature or compensate for it.
	assert_not_defined_property(FOCUSER_TEMPERATURE_PROPERTY_NAME);
	assert_not_defined_property(FOCUSER_COMPENSATION_PROPERTY_NAME);
	assert_not_defined_property(FOCUSER_BACKLASH_PROPERTY_NAME);

	// The protocol encodes the position in four digits and the aperture in two.
	indigo_item *item = find_cached_item(FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME);
	SERIAL_CHECK_TRUE(item != NULL && item->number.min == 0 && item->number.max == FOCUSER_MAX_POSITION);
	item = find_cached_item(FOCUSER_STEPS_PROPERTY_NAME, FOCUSER_STEPS_ITEM_NAME);
	SERIAL_CHECK_TRUE(item != NULL && item->number.min == 0 && item->number.max == FOCUSER_MAX_POSITION);
	item = find_cached_item(X_FOCUSER_APERTURE_PROPERTY_NAME, X_FOCUSER_APERTURE_ITEM_NAME);
	SERIAL_CHECK_TRUE(item != NULL && item->number.min == 0 && item->number.max == 50);
	assert_number_item_in_range(FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME);
cleanup:
	if (online) { stop_serial_driver(&astromechanics_focuser); }
	stop_external_serial_simulator(&simulator);
}

