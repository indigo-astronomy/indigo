static double position(void) {
	return cached_number_value(FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME);
}

static bool set_switch(const char *property_name, const char *item_name) {
	return indigo_change_switch_property_1(&simulator_test_client, astromechanics_focuser.device_name, property_name, item_name, true) == INDIGO_OK;
}

static bool set_number(const char *property_name, const char *item_name, double value) {
	return indigo_change_number_property_1(&simulator_test_client, astromechanics_focuser.device_name, property_name, item_name, value) == INDIGO_OK;
}

// A move is finished only when the driver's own position poll agrees with the target, and both
// motion properties have to have left BUSY before the next request, otherwise the framework drops
// it while the previous one is still in flight.
static bool motion_settled(void) {
	return wait_for_property_not_busy(FOCUSER_POSITION_PROPERTY_NAME) && wait_for_property_not_busy(FOCUSER_STEPS_PROPERTY_NAME);
}

static bool goto_position(double value) {
	if (!set_number(FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, value) || !motion_settled()) {
		return false;
	}
	return wait_for_number_item_value(FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, value, .5);
}

static bool move_steps(const char *direction_item, double steps) {
	if (!set_switch(FOCUSER_DIRECTION_PROPERTY_NAME, direction_item) || !wait_for_property_state(FOCUSER_DIRECTION_PROPERTY_NAME, INDIGO_OK_STATE)) {
		return false;
	}
	return set_number(FOCUSER_STEPS_PROPERTY_NAME, FOCUSER_STEPS_ITEM_NAME, steps) && motion_settled();
}

