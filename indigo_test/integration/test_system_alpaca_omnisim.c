// OmniSim filter wheel: IFilterWheelV3, six slots Red, Green, Blue, Clear, Ha, OIII, Position 0, one second per slot (Position is -1
// on the way). Interface version 2 through the settings API.
static void omni_wheel_round_trip(int interface_version) {
	char item[INDIGO_NAME_SIZE];
	SA_CHECK(omni_begin());
	SA_CHECK(omni_attach_connect(WHEEL_LABEL));
	SA_CHECK(omni_interface_version(sa_device) == interface_version);
	SA_CHECK(sa_number(sa_device, WHEEL_SLOT_PROPERTY_NAME, WHEEL_SLOT_ITEM_NAME) == 1);
	SA_CHECK(sa_item_count(sa_device, WHEEL_SLOT_NAME_PROPERTY_NAME) == 6 && sa_item_count(sa_device, WHEEL_SLOT_OFFSET_PROPERTY_NAME) == 6);
	static const char *names[] = { "Red", "Green", "Blue", "Clear", "Ha", "OIII" };
	for (int i = 0; i < 6; i++) {
		snprintf(item, sizeof(item), WHEEL_SLOT_NAME_ITEM_NAME, i + 1);
		SA_CHECK(!strcmp(sa_text(sa_device, WHEEL_SLOT_NAME_PROPERTY_NAME, item), names[i]));
	}
	// the focus offsets of the device are the offsets of the slots
	int error_number = -1;
	const alpaca_json_value *offsets = omni_get("filterwheel", "focusoffsets", NULL, &error_number);
	SA_CHECK(error_number == 0 && alpaca_json_size(offsets) == 6);
	for (int i = 0; i < 6; i++) {
		int64_t offset = 0;
		SA_CHECK(alpaca_json_get_int(alpaca_json_array_get(offsets, i), &offset));
		snprintf(item, sizeof(item), WHEEL_SLOT_OFFSET_ITEM_NAME, i + 1);
		SA_CHECK(sa_number(sa_device, WHEEL_SLOT_OFFSET_PROPERTY_NAME, item) == (double)offset);
	}
	// a move ends when Position is no longer -1
	unsigned revision = sa_revision(sa_device, WHEEL_SLOT_PROPERTY_NAME);
	SA_CHECK(omni_set_number(sa_device, WHEEL_SLOT_PROPERTY_NAME, WHEEL_SLOT_ITEM_NAME, 4, OMNI_TIMEOUT) == INDIGO_OK_STATE);
	SA_CHECK(omni_went_busy(sa_device, WHEEL_SLOT_PROPERTY_NAME, revision));
	SA_CHECK(sa_number(sa_device, WHEEL_SLOT_PROPERTY_NAME, WHEEL_SLOT_ITEM_NAME) == 4 && omni_int("filterwheel", "position") == 3);
	SA_CHECK(omni_set_number(sa_device, WHEEL_SLOT_PROPERTY_NAME, WHEEL_SLOT_ITEM_NAME, 6, OMNI_TIMEOUT) == INDIGO_OK_STATE);
	SA_CHECK(sa_number(sa_device, WHEEL_SLOT_PROPERTY_NAME, WHEEL_SLOT_ITEM_NAME) == 6 && omni_int("filterwheel", "position") == 5);
	SA_CHECK(omni_set_number(sa_device, WHEEL_SLOT_PROPERTY_NAME, WHEEL_SLOT_ITEM_NAME, 1, OMNI_TIMEOUT) == INDIGO_OK_STATE);
	SA_CHECK(sa_number(sa_device, WHEEL_SLOT_PROPERTY_NAME, WHEEL_SLOT_ITEM_NAME) == 1 && omni_int("filterwheel", "position") == 0);
	// a move of another client is followed
	SA_CHECK(omni_put("filterwheel", "position", "Position=2") == 0);
	SA_CHECK(SA_WAIT(sa_number(sa_device, WHEEL_SLOT_PROPERTY_NAME, WHEEL_SLOT_ITEM_NAME) == 3 && sa_state(sa_device, WHEEL_SLOT_PROPERTY_NAME) == INDIGO_OK_STATE, OMNI_TIMEOUT));
	if (interface_version >= 3) {
		SA_CHECK(omni_state_has("filterwheel", "Position"));
	} else {
		SA_CHECK(omni_member_answers("filterwheel", "devicestate", OMNI_UNSPECIFIED));
	}
	SA_CHECK(omni_disconnect_detach(WHEEL_LABEL));
	SA_CHECK(SA_WAIT(!omni_bool("filterwheel", "connected"), OMNI_TIMEOUT));
cleanup:
	omni_end();
}

