static const char *case_filter = NULL;

static const char *case_name(int index) {
	return cases[index].name;
}

static bool case_selected(int index) {
	return case_filter == NULL || strstr(cases[index].name, case_filter) != NULL;
}

static unsigned case_timeout(int index) {
	(void)index;
	return CASE_TIMEOUT;
}

// One case in its forked child: a private HOME for the driver, a fresh OmniSim instance, the case, the instance stopped.
static int case_child(int index, const char *fixture) {
	char home[PATH_MAX], directory[PATH_MAX];
	snprintf(home, sizeof(home), "%s/home", fixture);
	snprintf(directory, sizeof(directory), "%s/omnisim", fixture);
	if (mkdir(home, 0700) != 0 || !indigo_test_set_private_home(home)) {
		perror(home);
		return 2;
	}
	if (getenv("SYSTEM_ALPACA_TEST_DEBUG") != NULL) {
		indigo_set_log_level(INDIGO_LOG_DEBUG);
	}
	if (!omni_start(directory)) {
		omni_stop();
		return 2;
	}
	int result = indigo_run_tests(SUITE_NAME, cases + index, 1);
	fflush(NULL);
	omni_stop();
	if (result != 0 || getenv("SYSTEM_ALPACA_OMNISIM_LOG") != NULL) {
		char log[PATH_MAX];
		snprintf(log, sizeof(log), "%s/omnisim.log", directory);
		printf("    OmniSim log of the case: %s (kept only with SYSTEM_ALPACA_OMNISIM_KEEP)\n", log);
	}
	return result;
}

static char fixture_root[PATH_MAX];

// Ctrl-C or a kill of the parent: the cases run in process groups of their own, so their reapers end OmniSim when they die;
// the parent stops the instance itself as well and leaves no directory behind.
static void omni_signal(int signal) {
	(void)signal;
	omni_kill_leftover();
	if (getenv("SYSTEM_ALPACA_OMNISIM_KEEP") == NULL) {
		indigo_test_remove_tree(fixture_root);
	}
	indigo_test_remove_private_home();
	_exit(130);
}

int main(void) {
	int run = 0, passed = 0, failed = 0;
	setvbuf(stdout, NULL, _IOLBF, 0);
	if (!omni_find()) {
		printf("%s: NOT RUN, no OmniSim executable (INDIGO_TEST_OMNISIM, or " SYSTEM_ALPACA_OMNISIM_DIR "/*/" OMNI_EXECUTABLE_NAME "; install it as REFACTOR.md 4.1 of system_alpaca says). No case was planned, nothing passed.\n", SUITE_NAME);
		return 0;
	}
	if (!indigo_test_use_private_home()) {
		return 1;
	}
	snprintf(fixture_root, sizeof(fixture_root), "/tmp/indigo-system-alpaca-omnisim.XXXXXX");
	if (mkdtemp(fixture_root) == NULL) {
		perror("mkdtemp");
		indigo_test_remove_private_home();
		return 1;
	}
	snprintf(omni_instance_lock, sizeof(omni_instance_lock), "%s/instance.lock", fixture_root);
	signal(SIGINT, omni_signal);
	signal(SIGTERM, omni_signal);
	signal(SIGHUP, omni_signal);
	int result = 1;
	char probe[PATH_MAX];
	snprintf(probe, sizeof(probe), "%s/probe", fixture_root);
	if (omni_lock_run()) {
		// one instance first, for the version and to fail early when OmniSim can not run here
		bool started = omni_start(probe);
		omni_stop();
		if (started) {
			printf("%s: OmniSim %s (%s), %s\n", SUITE_NAME, omni_version, omni_version_full, omni_executable);
			// what tools/run_driver_test.py records as the type of the run
			indigo_test_record("device\tindigo_system_alpaca\t0\tOmniSim\tOmniSim %s", omni_version);
			case_filter = getenv("INDIGO_TEST_CASE_FILTER");
			if (case_filter != NULL) {
				indigo_test_record("filter\t%s", case_filter);
			}
			const parallel_case_runner runner = {
				SUITE_NAME, fixture_root, ARRAY_SIZE(cases), 1, case_name, case_selected, case_timeout, case_child, NULL
			};
			run_parallel_cases(&runner, &run, &passed, &failed);
			printf("%s: %d run, %d passed, %d failed against OmniSim %s\n", SUITE_NAME, run, passed, failed, omni_version);
			result = failed != 0 || run == 0 ? 1 : 0;
		} else {
			fprintf(stderr, "%s: OmniSim could not be started, no case was run\n", SUITE_NAME);
		}
		omni_kill_leftover();
		omni_unlock_run();
	}
	if (getenv("SYSTEM_ALPACA_OMNISIM_KEEP") == NULL) {
		indigo_test_remove_tree(fixture_root);
	} else {
		printf("fixtures and OmniSim logs kept in %s\n", fixture_root);
	}
	indigo_test_remove_private_home();
	return result;
}
