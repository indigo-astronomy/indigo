// ---------------------------------------------------------------------------- telescope

// OmniSim telescope: ITelescopeV4, German equatorial (AlignmentMode 2), EquatorialSystem 1 (topocentric, so the driver converts
// J2000 on the bus to JNow), site 51.07861 N, 0.29444 W, starts unparked and not tracking at azimuth 180, altitude 38.9 (the
// celestial equator on the meridian), slews at up to 20 degrees per second, AxisRates [0, 6.67] and [10, 20] deg/s,
// TrackingRates sidereal, King, lunar, solar, guide rates 0.0041781 deg/s (one sidereal rate), CanPulseGuide.
#define MOUNT_CASE_TIMEOUT 90.0

static double omni_hours(double hours) {
	hours = fmod(hours, 24);
	return hours < 0 ? hours + 24 : hours;
}

// Difference of two right ascensions in hours, -12 ... 12.
static double omni_ra_difference(double a, double b) {
	double difference = omni_hours(a - b);
	return difference > 12 ? difference - 24 : difference;
}

// A goto of the mount device to J2000 coordinates; true when the driver published the arrival at them.
static bool omni_goto(double ra, double dec) {
	static const char *items[] = { MOUNT_EQUATORIAL_COORDINATES_RA_ITEM_NAME, MOUNT_EQUATORIAL_COORDINATES_DEC_ITEM_NAME };
	const double values[] = { ra, dec };
	unsigned revision = sa_revision(sa_device, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME);
	int state = omni_set_numbers(sa_device, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, 2, items, values, MOUNT_CASE_TIMEOUT);
	double published_ra = sa_number(sa_device, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, MOUNT_EQUATORIAL_COORDINATES_RA_ITEM_NAME);
	double published_dec = sa_number(sa_device, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, MOUNT_EQUATORIAL_COORDINATES_DEC_ITEM_NAME);
	printf("    goto %.4f %.4f ended in state %d at %.4f %.4f\n", ra, dec, state, published_ra, published_dec);
	if (state != INDIGO_OK_STATE || !omni_went_busy(sa_device, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, revision)) {
		omni_print_messages();
		return false;
	}
	return fabs(omni_ra_difference(published_ra, ra)) < 0.002 && fabs(published_dec - dec) < 0.03 && !omni_bool("telescope", "slewing");
}

// Local sidereal time as the driver publishes it.
static double omni_lst(void) {
	return sa_number(sa_device, MOUNT_LST_TIME_PROPERTY_NAME, MOUNT_LST_TIME_ITEM_NAME);
}

static void omnisim_mount_goto(void) {
	SA_CHECK(omni_begin());
	SA_CHECK(omni_attach_connect(TELESCOPE_LABEL));
	SA_CHECK(omni_interface_version(sa_device) == 4);
	SA_CHECK(omni_state_has("telescope", "Altitude,AtHome,AtPark,Azimuth,Declination,IsPulseGuiding,RightAscension,SideOfPier,SiderealTime,Slewing,Tracking,UTCDate"));
	// site and time of the telescope
	SA_CHECK(fabs(sa_number(sa_device, GEOGRAPHIC_COORDINATES_PROPERTY_NAME, GEOGRAPHIC_COORDINATES_LATITUDE_ITEM_NAME) - 51.07861) < 1e-6);
	SA_CHECK(fabs(sa_number(sa_device, GEOGRAPHIC_COORDINATES_PROPERTY_NAME, GEOGRAPHIC_COORDINATES_LONGITUDE_ITEM_NAME) - (360 - 0.29444)) < 1e-6);
	SA_CHECK(fabs(omni_ra_difference(omni_lst(), omni_double("telescope", "siderealtime"))) < 0.01);
	SA_CHECK(sa_number(sa_device, MOUNT_EPOCH_PROPERTY_NAME, MOUNT_EPOCH_ITEM_NAME) == 0);
	SA_CHECK(!sa_switch(sa_device, MOUNT_PARK_PROPERTY_NAME, MOUNT_PARK_PARKED_ITEM_NAME) && sa_switch(sa_device, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_OFF_ITEM_NAME));
	// goto east of the meridian: tracking is switched on for it, the telescope ends on pierWest
	double ra = omni_hours(omni_lst() + 2), dec = 20;
	SA_CHECK(omni_goto(ra, dec));
	SA_CHECK(omni_bool("telescope", "tracking") && sa_switch(sa_device, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_ON_ITEM_NAME));
	SA_CHECK(omni_int("telescope", "sideofpier") == 1 && SA_WAIT(sa_switch(sa_device, MOUNT_SIDE_OF_PIER_PROPERTY_NAME, MOUNT_SIDE_OF_PIER_WEST_ITEM_NAME), SA_TIMEOUT));
	// the telescope works in JNow: what it reports differs from the J2000 target by the precession since 2000
	double jnow_ra = omni_double("telescope", "rightascension"), jnow_dec = omni_double("telescope", "declination");
	double expected_ra = ra, expected_dec = dec;
	indigo_j2k_to_jnow(&expected_ra, &expected_dec);
	printf("    J2000 %.5f %.5f, telescope %.5f %.5f, expected JNow %.5f %.5f\n", ra, dec, jnow_ra, jnow_dec, expected_ra, expected_dec);
	SA_CHECK(fabs(omni_ra_difference(jnow_ra, expected_ra)) < 0.002 && fabs(jnow_dec - expected_dec) < 0.03);
	// sync to a nearby position
	SA_CHECK(omni_set_switch(sa_device, MOUNT_ON_COORDINATES_SET_PROPERTY_NAME, MOUNT_ON_COORDINATES_SET_SYNC_ITEM_NAME, true, SA_TIMEOUT) == INDIGO_OK_STATE);
	{
		static const char *items[] = { MOUNT_EQUATORIAL_COORDINATES_RA_ITEM_NAME, MOUNT_EQUATORIAL_COORDINATES_DEC_ITEM_NAME };
		const double values[] = { omni_hours(ra + 0.05), dec + 0.5 };
		SA_CHECK(omni_set_numbers(sa_device, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, 2, items, values, MOUNT_CASE_TIMEOUT) == INDIGO_OK_STATE);
		SA_CHECK(SA_WAIT(fabs(omni_ra_difference(sa_number(sa_device, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, MOUNT_EQUATORIAL_COORDINATES_RA_ITEM_NAME), values[0])) < 0.002 && fabs(sa_number(sa_device, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, MOUNT_EQUATORIAL_COORDINATES_DEC_ITEM_NAME) - values[1]) < 0.03, SA_TIMEOUT));
	}
	SA_CHECK(omni_set_switch(sa_device, MOUNT_ON_COORDINATES_SET_PROPERTY_NAME, MOUNT_ON_COORDINATES_SET_TRACK_ITEM_NAME, true, SA_TIMEOUT) == INDIGO_OK_STATE);
	// goto west of the meridian: the telescope flips to pierEast
	ra = omni_hours(omni_lst() - 2);
	dec = 35;
	SA_CHECK(omni_goto(ra, dec));
	SA_CHECK(omni_int("telescope", "sideofpier") == 0 && SA_WAIT(sa_switch(sa_device, MOUNT_SIDE_OF_PIER_PROPERTY_NAME, MOUNT_SIDE_OF_PIER_EAST_ITEM_NAME), SA_TIMEOUT));
	// abort a long slew: AbortSlew stops it, the request ends in ALERT
	{
		static const char *items[] = { MOUNT_EQUATORIAL_COORDINATES_RA_ITEM_NAME, MOUNT_EQUATORIAL_COORDINATES_DEC_ITEM_NAME };
		const double values[] = { omni_hours(omni_lst() + 3), -10 };
		unsigned revision = sa_revision(sa_device, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME);
		SA_CHECK(indigo_change_number_property(&sa_client, sa_device, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, 2, items, values) == INDIGO_OK);
		SA_CHECK(SA_WAIT(omni_bool("telescope", "slewing"), SA_TIMEOUT));
		SA_CHECK(omni_set_switch(sa_device, MOUNT_ABORT_MOTION_PROPERTY_NAME, MOUNT_ABORT_MOTION_ITEM_NAME, true, SA_TIMEOUT) == INDIGO_OK_STATE);
		SA_CHECK(SA_WAIT(sa_state(sa_device, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME) != INDIGO_BUSY_STATE, MOUNT_CASE_TIMEOUT));
		SA_CHECK(sa_state_after(sa_device, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, INDIGO_ALERT_STATE, revision) && !omni_bool("telescope", "slewing"));
		SA_CHECK(fabs(sa_number(sa_device, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, MOUNT_EQUATORIAL_COORDINATES_DEC_ITEM_NAME) + 10) > 0.5);
	}
	SA_CHECK(omni_disconnect_detach(TELESCOPE_LABEL));
	SA_CHECK(SA_WAIT(!omni_bool("telescope", "connected"), OMNI_TIMEOUT));
cleanup:
	omni_end();
}

static void omnisim_mount_park_home_tracking(void) {
	SA_CHECK(omni_begin());
	SA_CHECK(omni_attach_connect(TELESCOPE_LABEL));
	// tracking and the tracking rates of the telescope
	SA_CHECK(omni_set_switch(sa_device, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_ON_ITEM_NAME, true, SA_TIMEOUT) == INDIGO_OK_STATE && omni_bool("telescope", "tracking"));
	SA_CHECK(sa_has_item(sa_device, MOUNT_TRACK_RATE_PROPERTY_NAME, MOUNT_TRACK_RATE_SIDEREAL_ITEM_NAME) && sa_has_item(sa_device, MOUNT_TRACK_RATE_PROPERTY_NAME, MOUNT_TRACK_RATE_SOLAR_ITEM_NAME) && sa_has_item(sa_device, MOUNT_TRACK_RATE_PROPERTY_NAME, MOUNT_TRACK_RATE_LUNAR_ITEM_NAME) && sa_has_item(sa_device, MOUNT_TRACK_RATE_PROPERTY_NAME, MOUNT_TRACK_RATE_KING_ITEM_NAME));
	SA_CHECK(sa_switch(sa_device, MOUNT_TRACK_RATE_PROPERTY_NAME, MOUNT_TRACK_RATE_SIDEREAL_ITEM_NAME));
	SA_CHECK(omni_set_switch(sa_device, MOUNT_TRACK_RATE_PROPERTY_NAME, MOUNT_TRACK_RATE_LUNAR_ITEM_NAME, true, SA_TIMEOUT) == INDIGO_OK_STATE && omni_int("telescope", "trackingrate") == 1);
	SA_CHECK(omni_set_switch(sa_device, MOUNT_TRACK_RATE_PROPERTY_NAME, MOUNT_TRACK_RATE_KING_ITEM_NAME, true, SA_TIMEOUT) == INDIGO_OK_STATE && omni_int("telescope", "trackingrate") == 3);
	SA_CHECK(omni_set_switch(sa_device, MOUNT_TRACK_RATE_PROPERTY_NAME, MOUNT_TRACK_RATE_SIDEREAL_ITEM_NAME, true, SA_TIMEOUT) == INDIGO_OK_STATE && omni_int("telescope", "trackingrate") == 0);
	// guide rates in percent of the sidereal rate
	SA_CHECK(fabs(sa_number(sa_device, MOUNT_GUIDE_RATE_PROPERTY_NAME, MOUNT_GUIDE_RATE_RA_ITEM_NAME) - 100) < 0.01);
	{
		static const char *items[] = { MOUNT_GUIDE_RATE_RA_ITEM_NAME, MOUNT_GUIDE_RATE_DEC_ITEM_NAME };
		const double values[] = { 50, 75 };
		SA_CHECK(omni_set_numbers(sa_device, MOUNT_GUIDE_RATE_PROPERTY_NAME, 2, items, values, SA_TIMEOUT) == INDIGO_OK_STATE);
		SA_CHECK(fabs(omni_double("telescope", "guideraterightascension") - 0.5 * 15.0410686 / 3600) < 1e-7 && fabs(omni_double("telescope", "guideratedeclination") - 0.75 * 15.0410686 / 3600) < 1e-7);
	}
	// UTC of the telescope
	SA_CHECK(sa_text(sa_device, UTC_TIME_PROPERTY_NAME, UTC_TIME_ITEM_NAME)[0] != 0);
	// park: the telescope goes to its park position and reports AtPark; a parked telescope does not track
	SA_CHECK(omni_set_switch(sa_device, MOUNT_PARK_PROPERTY_NAME, MOUNT_PARK_PARKED_ITEM_NAME, true, MOUNT_CASE_TIMEOUT) == INDIGO_OK_STATE);
	SA_CHECK(omni_bool("telescope", "atpark") && sa_switch(sa_device, MOUNT_PARK_PROPERTY_NAME, MOUNT_PARK_PARKED_ITEM_NAME));
	SA_CHECK(SA_WAIT(sa_switch(sa_device, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_OFF_ITEM_NAME), SA_TIMEOUT) && !omni_bool("telescope", "tracking"));
	// a goto of a parked telescope is refused by the driver
	{
		static const char *items[] = { MOUNT_EQUATORIAL_COORDINATES_RA_ITEM_NAME, MOUNT_EQUATORIAL_COORDINATES_DEC_ITEM_NAME };
		const double values[] = { omni_hours(omni_lst() + 1), 10 };
		SA_CHECK(omni_set_numbers(sa_device, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, 2, items, values, SA_TIMEOUT) == INDIGO_ALERT_STATE && omni_bool("telescope", "atpark"));
	}
	SA_CHECK(omni_set_switch(sa_device, MOUNT_PARK_PROPERTY_NAME, MOUNT_PARK_UNPARKED_ITEM_NAME, true, MOUNT_CASE_TIMEOUT) == INDIGO_OK_STATE && !omni_bool("telescope", "atpark"));
	// FindHome: the telescope reports AtHome at the end
	SA_CHECK(omni_set_switch(sa_device, MOUNT_HOME_PROPERTY_NAME, MOUNT_HOME_ITEM_NAME, true, MOUNT_CASE_TIMEOUT) == INDIGO_OK_STATE);
	SA_CHECK(omni_bool("telescope", "athome"));
	// Platform 7 disconnect is asynchronous in OmniSim (Connecting is true for about a second): CONNECTION stays BUSY until Connecting
	// is false (REFACTOR.md 2.4, 2.7), so when the device is reported disconnected the telescope is neither connected nor connecting,
	// and a connect right after it ends connected and working
	double started = indigo_monotonic_time();
	SA_CHECK(sa_disconnect(sa_device));
	printf("    disconnect completed after %.2f s: Connected %d, Connecting %d\n", indigo_monotonic_time() - started, omni_bool("telescope", "connected"), omni_bool("telescope", "connecting"));
	SA_CHECK(!omni_bool("telescope", "connected") && !omni_bool("telescope", "connecting"));
	SA_CHECK(sa_request_connection(sa_device, true) && SA_WAIT(sa_is_connected(sa_device), OMNI_TIMEOUT));
	SA_CHECK(omni_bool("telescope", "connected") && !omni_bool("telescope", "connecting"));
	SA_CHECK(omni_set_switch(sa_device, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_ON_ITEM_NAME, true, SA_TIMEOUT) == INDIGO_OK_STATE && omni_bool("telescope", "tracking"));
	SA_CHECK(omni_disconnect_detach(TELESCOPE_LABEL));
cleanup:
	omni_end();
}

// MoveAxis through MOUNT_MOTION_DEC / _RA. Answers the open question of the sense: OmniSim moves the mechanical axes, so a positive
// rate of the secondary axis is north on pierEast and south on pierWest; a positive rate of the primary axis is west.
static bool omni_manual_motion(const char *property, const char *item, double seconds) {
	// the motion runs while the item is on; the telescope reports Slewing during MoveAxis
	if (indigo_change_switch_property_1(&sa_client, sa_device, property, item, true) != INDIGO_OK || !SA_WAIT(omni_bool("telescope", "slewing"), SA_TIMEOUT)) {
		fprintf(stderr, "    %s.%s did not start MoveAxis, state %d\n", property, item, sa_state(sa_device, property));
		omni_print_messages();
		return false;
	}
	SA_WAIT(false, seconds);
	return omni_set_switch(sa_device, property, item, false, SA_TIMEOUT) == INDIGO_OK_STATE;
}

// One manual motion of 1 s; the change of the declination or of the right ascension (hours, -12 ... 12) of the telescope is left in *change.
static bool omni_motion_change(const char *property, const char *item, const char *member, const char *where, double *change) {
	double before = omni_double("telescope", member);
	if (!omni_manual_motion(property, item, 1) || !SA_WAIT(!omni_bool("telescope", "slewing"), SA_TIMEOUT)) {
		return false;
	}
	double after = omni_double("telescope", member);
	*change = !strcmp(member, "rightascension") ? omni_ra_difference(after, before) : after - before;
	printf("    %s, %s.%s: %s %.5f -> %.5f\n", where, property, item, member, before, after);
	return true;
}

// MOUNT_MOTION_DEC.NORTH moves toward the north celestial pole on both sides of the pier and on a northern and a southern site; OmniSim turns
// the secondary axis the other way through the pole (pierWest), so the driver inverts the rate there (indigo_system_alpaca_mount.c, MANUAL
// MOTION). MOUNT_MOTION_RA.WEST makes the right ascension fall everywhere, the primary axis is never inverted.
static void omnisim_mount_manual_motion(void) {
	char where[64];
	double change = 0;
	SA_CHECK(omni_begin());
	SA_CHECK(omni_attach_connect(TELESCOPE_LABEL));
	// the rates of MOUNT_SLEW_RATE come from AxisRates [0, 6.67] and [10, 20]
	SA_CHECK(omni_set_switch(sa_device, MOUNT_SLEW_RATE_PROPERTY_NAME, MOUNT_SLEW_RATE_FIND_ITEM_NAME, true, SA_TIMEOUT) == INDIGO_OK_STATE);
	for (int site = 0; site < 2; site++) {
		// OmniSim's site is at 51.07861 N; the southern one is set on the telescope directly. OmniSim saves SiteLatitude in its profile, which
		// lives in the private home of this instance only (omnisim_test_common.h), so it is not put back
		if (site) {
			SA_CHECK(omni_put("telescope", "sitelatitude", "SiteLatitude=-30.2407") == 0 && fabs(omni_double("telescope", "sitelatitude") + 30.2407) < 1e-9);
		}
		for (int west = 0; west < 2; west++) {
			// 2 h east of the meridian the telescope points through the pole (pierWest), 2 h west of it it is on pierEast
			SA_CHECK(omni_goto(omni_hours(omni_lst() + (west ? 2 : -2)), 10));
			SA_CHECK(omni_int("telescope", "sideofpier") == west);
			snprintf(where, sizeof(where), "%s site, %s", site ? "southern" : "northern", west ? "pierWest" : "pierEast");
			SA_CHECK(omni_motion_change(MOUNT_MOTION_DEC_PROPERTY_NAME, MOUNT_MOTION_NORTH_ITEM_NAME, "declination", where, &change) && change > 0.1);
			SA_CHECK(omni_motion_change(MOUNT_MOTION_DEC_PROPERTY_NAME, MOUNT_MOTION_SOUTH_ITEM_NAME, "declination", where, &change) && change < -0.1);
			// west: the hour angle grows, the right ascension of the place the telescope points at falls
			SA_CHECK(omni_motion_change(MOUNT_MOTION_RA_PROPERTY_NAME, MOUNT_MOTION_WEST_ITEM_NAME, "rightascension", where, &change) && change < -0.01);
		}
	}
	SA_CHECK(omni_disconnect_detach(TELESCOPE_LABEL));
cleanup:
	omni_end();
}

// The guider of the telescope: PulseGuide on real time, completion by IsPulseGuiding.
static void omnisim_mount_guider(void) {
	char guider[INDIGO_NAME_SIZE];
	SA_CHECK(omni_begin());
	SA_CHECK(omni_attach_connect(TELESCOPE_LABEL));
	snprintf(guider, sizeof(guider), "%s (guider)", sa_device);
	SA_CHECK(SA_WAIT(sa_defined(guider, CONNECTION_PROPERTY_NAME), SA_TIMEOUT));
	SA_CHECK(sa_request_connection(guider, true) && SA_WAIT(sa_is_connected(guider), SA_TIMEOUT));
	SA_CHECK(omni_set_switch(sa_device, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_ON_ITEM_NAME, true, SA_TIMEOUT) == INDIGO_OK_STATE);
	double before = omni_double("telescope", "declination");
	unsigned revision = sa_revision(guider, GUIDER_GUIDE_DEC_PROPERTY_NAME);
	SA_CHECK(indigo_change_number_property_1(&sa_client, guider, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME, 2000) == INDIGO_OK);
	SA_CHECK(SA_WAIT(omni_bool("telescope", "ispulseguiding"), SA_TIMEOUT));
	SA_CHECK(SA_WAIT(sa_state_after(guider, GUIDER_GUIDE_DEC_PROPERTY_NAME, INDIGO_OK_STATE, revision) && sa_state(guider, GUIDER_GUIDE_DEC_PROPERTY_NAME) == INDIGO_OK_STATE, SA_TIMEOUT));
	SA_CHECK(!omni_bool("telescope", "ispulseguiding"));
	double after = omni_double("telescope", "declination");
	printf("    2 s north pulse at the guide rate: declination %.6f -> %.6f\n", before, after);
	SA_CHECK(after - before > 0.004 && after - before < 0.0125);
	// a pulse ended early: both items zero send PulseGuide Duration 0, which ends the pulse in OmniSim
	revision = sa_revision(guider, GUIDER_GUIDE_RA_PROPERTY_NAME);
	SA_CHECK(indigo_change_number_property_1(&sa_client, guider, GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_WEST_ITEM_NAME, 5000) == INDIGO_OK);
	SA_CHECK(SA_WAIT(omni_bool("telescope", "ispulseguiding"), SA_TIMEOUT));
	double started = indigo_monotonic_time();
	SA_CHECK(indigo_change_number_property_1(&sa_client, guider, GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_WEST_ITEM_NAME, 0) == INDIGO_OK);
	SA_CHECK(SA_WAIT(!omni_bool("telescope", "ispulseguiding"), SA_TIMEOUT));
	SA_CHECK(SA_WAIT(sa_state(guider, GUIDER_GUIDE_RA_PROPERTY_NAME) == INDIGO_OK_STATE, SA_TIMEOUT));
	printf("    a 5 s pulse ended by Duration 0 after %.2f s\n", indigo_monotonic_time() - started);
	SA_CHECK(indigo_monotonic_time() - started < 4);
	SA_CHECK(sa_disconnect(guider));
	SA_CHECK(omni_disconnect_detach(TELESCOPE_LABEL));
cleanup:
	omni_end();
}

