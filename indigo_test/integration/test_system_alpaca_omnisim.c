// The devicestate of the device contains every one of the comma separated names.
static bool omni_state_has(const char *type, const char *expected) {
	char names[1024], wanted[256];
	snprintf(names, sizeof(names), ",%s,", omni_device_state_names(type));
	printf("    %s devicestate: %s\n", type, names);
	for (const char *start = expected; *start; ) {
		size_t length = strcspn(start, ",");
		snprintf(wanted, sizeof(wanted), ",%.*s,", (int)length, start);
		if (strstr(names, wanted) == NULL) {
			fprintf(stderr, "    %s devicestate has no %.*s\n", type, (int)length, start);
			return false;
		}
		start += length + (start[length] == ',');
	}
	return true;
}

// A member of a newer interface version answers HTTP 200 with the given ErrorNumber (OmniSim's answer to a lower version).
static bool omni_member_answers(const char *type, const char *member, int expected) {
	int error_number = -1;
	omni_get(type, member, NULL, &error_number);
	if (omni_status != 200 || error_number != expected) {
		fprintf(stderr, "    GET %s/%s answered HTTP %d ErrorNumber 0x%X instead of HTTP 200 0x%X\n", type, member, omni_status, error_number, expected);
		return false;
	}
	return true;
}

