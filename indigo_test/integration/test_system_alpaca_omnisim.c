// ---------------------------------------------------------------------------- rotator

// OmniSim rotator: IRotatorV4, Position 0, about 8 degrees per second, CanReverse, StepSize 0.75. Interface version 2 through
// the settings API (no MechanicalPosition, MoveMechanical and Sync then).
static bool omni_rotator_settled(const char *property, unsigned revision) {
	return sa_state_after(sa_device, property, INDIGO_OK_STATE, revision) && sa_state(sa_device, ROTATOR_POSITION_PROPERTY_NAME) == INDIGO_OK_STATE && sa_state(sa_device, property) == INDIGO_OK_STATE;
}

static bool omni_rotator_move_to(double position) {
	unsigned revision = sa_revision(sa_device, ROTATOR_POSITION_PROPERTY_NAME);
	if (indigo_change_number_property_1(&sa_client, sa_device, ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME, position) != INDIGO_OK || !SA_WAIT(omni_rotator_settled(ROTATOR_POSITION_PROPERTY_NAME, revision), OMNI_TIMEOUT)) {
		fprintf(stderr, "    rotator move to %g ended in state %d\n", position, sa_state(sa_device, ROTATOR_POSITION_PROPERTY_NAME));
		omni_print_messages();
		return false;
	}
	return fabs(sa_number(sa_device, ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME) - position) < 1e-6 && fabs(omni_double("rotator", "position") - position) < 1e-6;
}

static void omni_rotator_round_trip(int interface_version) {
	bool mechanical = interface_version >= 3;
	SA_CHECK(omni_begin());
	SA_CHECK(omni_attach_connect(ROTATOR_LABEL));
	SA_CHECK(omni_interface_version(sa_device) == interface_version);
	SA_CHECK(sa_number(sa_device, ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME) == 0);
	SA_CHECK(sa_defined(sa_device, ROTATOR_DIRECTION_PROPERTY_NAME) && sa_defined(sa_device, ROTATOR_STEPS_PER_REVOLUTION_PROPERTY_NAME));
	SA_CHECK(sa_number(sa_device, ROTATOR_STEPS_PER_REVOLUTION_PROPERTY_NAME, ROTATOR_STEPS_PER_REVOLUTION_ITEM_NAME) == 480);
	SA_CHECK(sa_defined(sa_device, ROTATOR_RAW_POSITION_PROPERTY_NAME) == mechanical && sa_defined(sa_device, "X_ALPACA_MECHANICAL_POSITION") == mechanical && sa_defined(sa_device, ROTATOR_ON_POSITION_SET_PROPERTY_NAME) == mechanical);
	// absolute and relative moves, completion by IsMoving
	SA_CHECK(omni_rotator_move_to(30));
	unsigned revision = sa_revision(sa_device, ROTATOR_RELATIVE_MOVE_PROPERTY_NAME);
	SA_CHECK(indigo_change_number_property_1(&sa_client, sa_device, ROTATOR_RELATIVE_MOVE_PROPERTY_NAME, ROTATOR_RELATIVE_MOVE_ITEM_NAME, 15) == INDIGO_OK);
	SA_CHECK(SA_WAIT(omni_rotator_settled(ROTATOR_RELATIVE_MOVE_PROPERTY_NAME, revision), OMNI_TIMEOUT));
	SA_CHECK(fabs(sa_number(sa_device, ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME) - 45) < 1e-6 && fabs(omni_double("rotator", "position") - 45) < 1e-6);
	// Reverse is the setting of the device
	SA_CHECK(omni_set_switch(sa_device, ROTATOR_DIRECTION_PROPERTY_NAME, ROTATOR_DIRECTION_REVERSED_ITEM_NAME, true, SA_TIMEOUT) == INDIGO_OK_STATE && omni_bool("rotator", "reverse"));
	SA_CHECK(omni_set_switch(sa_device, ROTATOR_DIRECTION_PROPERTY_NAME, ROTATOR_DIRECTION_NORMAL_ITEM_NAME, true, SA_TIMEOUT) == INDIGO_OK_STATE && !omni_bool("rotator", "reverse"));
	if (mechanical) {
		// Sync: Position becomes the requested angle, the mechanical position stays
		SA_CHECK(omni_set_switch(sa_device, ROTATOR_ON_POSITION_SET_PROPERTY_NAME, ROTATOR_ON_POSITION_SET_SYNC_ITEM_NAME, true, SA_TIMEOUT) == INDIGO_OK_STATE);
		SA_CHECK(omni_set_number(sa_device, ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME, 100, SA_TIMEOUT) == INDIGO_OK_STATE);
		SA_CHECK(fabs(omni_double("rotator", "position") - 100) < 1e-6 && fabs(omni_double("rotator", "mechanicalposition") - 45) < 1e-6);
		SA_CHECK(SA_WAIT(sa_number(sa_device, ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME) == 100 && sa_number(sa_device, ROTATOR_RAW_POSITION_PROPERTY_NAME, ROTATOR_RAW_POSITION_ITEM_NAME) == 45, SA_TIMEOUT));
		SA_CHECK(omni_set_switch(sa_device, ROTATOR_ON_POSITION_SET_PROPERTY_NAME, ROTATOR_ON_POSITION_SET_GOTO_ITEM_NAME, true, SA_TIMEOUT) == INDIGO_OK_STATE);
		// a move to a sky angle while synced: the target of ROTATOR_POSITION is the requested sky angle all the way
		revision = sa_revision(sa_device, ROTATOR_POSITION_PROPERTY_NAME);
		SA_CHECK(indigo_change_number_property_1(&sa_client, sa_device, ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME, 160) == INDIGO_OK);
		SA_CHECK(SA_WAIT(omni_bool("rotator", "ismoving"), SA_TIMEOUT));
		printf("    OmniSim TargetPosition during MoveAbsolute 160 with a sync offset of 55: %g\n", omni_double("rotator", "targetposition"));
		SA_CHECK(SA_WAIT(sa_state(sa_device, ROTATOR_POSITION_PROPERTY_NAME) == INDIGO_BUSY_STATE, SA_TIMEOUT) && sa_number_target(sa_device, ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME) == 160);
		SA_CHECK(SA_WAIT(omni_rotator_settled(ROTATOR_POSITION_PROPERTY_NAME, revision), OMNI_TIMEOUT));
		SA_CHECK(sa_number(sa_device, ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME) == 160 && fabs(omni_double("rotator", "mechanicalposition") - 105) < 1e-6);
		// MoveMechanical: the mechanical angle is the request, the sky angle follows with the sync offset
		revision = sa_revision(sa_device, "X_ALPACA_MECHANICAL_POSITION");
		SA_CHECK(indigo_change_number_property_1(&sa_client, sa_device, "X_ALPACA_MECHANICAL_POSITION", "POSITION", 65) == INDIGO_OK);
		SA_CHECK(SA_WAIT(omni_bool("rotator", "ismoving"), SA_TIMEOUT));
		printf("    OmniSim TargetPosition during MoveMechanical 65: %g\n", omni_double("rotator", "targetposition"));
		SA_CHECK(SA_WAIT(omni_rotator_settled("X_ALPACA_MECHANICAL_POSITION", revision), OMNI_TIMEOUT));
		SA_CHECK(fabs(omni_double("rotator", "mechanicalposition") - 65) < 1e-6 && fabs(omni_double("rotator", "position") - 120) < 1e-6);
		SA_CHECK(SA_WAIT(sa_number(sa_device, ROTATOR_RAW_POSITION_PROPERTY_NAME, ROTATOR_RAW_POSITION_ITEM_NAME) == 65 && sa_number(sa_device, ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME) == 120, SA_TIMEOUT));
		SA_CHECK(omni_state_has("rotator", "IsMoving,MechanicalPosition,Position"));
	} else {
		SA_CHECK(omni_member_answers("rotator", "mechanicalposition", OMNI_UNSPECIFIED));
		SA_CHECK(omni_member_answers("rotator", "devicestate", OMNI_UNSPECIFIED));
	}
	// Halt during a move
	SA_CHECK(indigo_change_number_property_1(&sa_client, sa_device, ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME, mechanical ? 300 : 225) == INDIGO_OK);
	SA_CHECK(SA_WAIT(omni_bool("rotator", "ismoving"), SA_TIMEOUT));
	SA_CHECK(omni_set_switch(sa_device, ROTATOR_ABORT_MOTION_PROPERTY_NAME, ROTATOR_ABORT_MOTION_ITEM_NAME, true, SA_TIMEOUT) == INDIGO_OK_STATE);
	SA_CHECK(SA_WAIT(sa_state(sa_device, ROTATOR_POSITION_PROPERTY_NAME) != INDIGO_BUSY_STATE, OMNI_TIMEOUT) && !omni_bool("rotator", "ismoving"));
	SA_CHECK(SA_WAIT(fabs(sa_number(sa_device, ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME) - omni_double("rotator", "position")) < 1e-6, SA_TIMEOUT));
	printf("    halted at %g, OmniSim TargetPosition after Halt: %g\n", sa_number(sa_device, ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME), omni_double("rotator", "targetposition"));
	SA_CHECK(omni_disconnect_detach(ROTATOR_LABEL));
	SA_CHECK(SA_WAIT(!omni_bool("rotator", "connected"), OMNI_TIMEOUT));
cleanup:
	omni_end();
}

