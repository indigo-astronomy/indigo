// OmniSim focuser: IFocuserV4, absolute, MaxStep 50000, MaxIncrement 50000, Position 25000, StepSize 20, temperature
// compensation available. Interface version 3 through /simulator/v1/focuser/0/interfaceversion.
static bool omni_focuser_move(double position) {
	unsigned revision = sa_revision(sa_device, FOCUSER_POSITION_PROPERTY_NAME);
	int state = omni_set_number(sa_device, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, position, OMNI_TIMEOUT);
	if (state != INDIGO_OK_STATE || !omni_went_busy(sa_device, FOCUSER_POSITION_PROPERTY_NAME, revision)) {
		fprintf(stderr, "    move to %g ended in state %d\n", position, state);
		omni_print_messages();
		return false;
	}
	return sa_number(sa_device, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME) == position && omni_int("focuser", "position") == (int)position && !omni_bool("focuser", "ismoving");
}

static void omni_focuser_round_trip(int interface_version) {
	SA_CHECK(omni_begin());
	SA_CHECK(omni_attach_connect(FOCUSER_LABEL));
	SA_CHECK(omni_interface_version(sa_device) == interface_version);
	SA_CHECK(omni_bool("focuser", "connected"));
	// what the device reports
	SA_CHECK(sa_number(sa_device, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME) == 25000);
	SA_CHECK(sa_item_count(sa_device, FOCUSER_POSITION_PROPERTY_NAME) == 1);
	SA_CHECK(SA_WAIT(fabs(sa_number(sa_device, FOCUSER_TEMPERATURE_PROPERTY_NAME, FOCUSER_TEMPERATURE_ITEM_NAME) - omni_double("focuser", "temperature")) < 1, SA_TIMEOUT));
	SA_CHECK(sa_number(sa_device, "X_ALPACA_STEP_SIZE", "STEP_SIZE") == 20);
	SA_CHECK(sa_defined(sa_device, FOCUSER_MODE_PROPERTY_NAME));
	// absolute and relative moves on real time, completion by IsMoving
	SA_CHECK(omni_focuser_move(25600));
	SA_CHECK(omni_set_switch(sa_device, FOCUSER_DIRECTION_PROPERTY_NAME, FOCUSER_DIRECTION_MOVE_INWARD_ITEM_NAME, true, SA_TIMEOUT) == INDIGO_OK_STATE);
	SA_CHECK(omni_set_number(sa_device, FOCUSER_STEPS_PROPERTY_NAME, FOCUSER_STEPS_ITEM_NAME, 300, OMNI_TIMEOUT) == INDIGO_OK_STATE);
	SA_CHECK(SA_WAIT(sa_number(sa_device, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME) == 25300 && sa_state(sa_device, FOCUSER_POSITION_PROPERTY_NAME) == INDIGO_OK_STATE, SA_TIMEOUT));
	SA_CHECK(omni_int("focuser", "position") == 25300);
	// Halt during a long move: the move ends where the device stopped
	SA_CHECK(indigo_change_number_property_1(&sa_client, sa_device, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, 50000) == INDIGO_OK);
	SA_CHECK(SA_WAIT(omni_bool("focuser", "ismoving"), SA_TIMEOUT));
	SA_CHECK(omni_set_switch(sa_device, FOCUSER_ABORT_MOTION_PROPERTY_NAME, FOCUSER_ABORT_MOTION_ITEM_NAME, true, SA_TIMEOUT) == INDIGO_OK_STATE);
	SA_CHECK(SA_WAIT(sa_state(sa_device, FOCUSER_POSITION_PROPERTY_NAME) != INDIGO_BUSY_STATE, OMNI_TIMEOUT));
	// OmniSim stops at once but reports IsMoving for about one more second (its settle time); the stopped move is not shown as
	// a new motion of the device afterwards
	unsigned stopped = sa_revision(sa_device, FOCUSER_POSITION_PROPERTY_NAME);
	printf("    after Halt: FOCUSER_POSITION state %d, OmniSim IsMoving %d\n", sa_state(sa_device, FOCUSER_POSITION_PROPERTY_NAME), omni_bool("focuser", "ismoving"));
	SA_CHECK(SA_WAIT(!omni_bool("focuser", "ismoving"), OMNI_TIMEOUT));
	SA_WAIT(false, 1);
	SA_CHECK(!sa_state_after(sa_device, FOCUSER_POSITION_PROPERTY_NAME, INDIGO_BUSY_STATE, stopped));
	SA_CHECK(sa_state(sa_device, FOCUSER_POSITION_PROPERTY_NAME) == INDIGO_ALERT_STATE);
	SA_CHECK(SA_WAIT(sa_number(sa_device, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME) == omni_int("focuser", "position"), SA_TIMEOUT));
	printf("    halted at %g\n", sa_number(sa_device, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME));
	SA_CHECK(sa_number(sa_device, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME) < 50000);
	// temperature compensation is TempComp of the device
	SA_CHECK(omni_set_switch(sa_device, FOCUSER_MODE_PROPERTY_NAME, FOCUSER_MODE_AUTOMATIC_ITEM_NAME, true, SA_TIMEOUT) == INDIGO_OK_STATE && omni_bool("focuser", "tempcomp"));
	SA_CHECK(omni_set_switch(sa_device, FOCUSER_MODE_PROPERTY_NAME, FOCUSER_MODE_MANUAL_ITEM_NAME, true, SA_TIMEOUT) == INDIGO_OK_STATE && !omni_bool("focuser", "tempcomp"));
	SA_CHECK(omni_focuser_move(24000));
	// devicestate (Platform 7) or OmniSim's answer to it on the older interface
	if (interface_version >= 4) {
		SA_CHECK(omni_state_has("focuser", "IsMoving,Position"));
	} else {
		SA_CHECK(omni_member_answers("focuser", "devicestate", OMNI_UNSPECIFIED));
		SA_CHECK(omni_member_answers("focuser", "connecting", OMNI_UNSPECIFIED));
	}
	// D5: an INDIGO disconnect disconnects the Alpaca device
	SA_CHECK(omni_disconnect_detach(FOCUSER_LABEL));
	SA_CHECK(SA_WAIT(!omni_bool("focuser", "connected"), OMNI_TIMEOUT));
cleanup:
	omni_end();
}

