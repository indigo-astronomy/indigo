static bool start_xagyl(external_serial_simulator *simulator, const char **arguments) {
	if (arguments == NULL) {
		return start_external_serial_simulator(simulator, WHEEL_XAGYL_SIMULATOR_EXECUTABLE);
	}
	return start_external_serial_simulator_with_args(simulator, WHEEL_XAGYL_SIMULATOR_EXECUTABLE, arguments);
}

static const char *info_text(const char *item_name) {
	indigo_item *item = find_cached_item(INFO_PROPERTY_NAME, item_name);
	return item == NULL ? "" : item->text.value;
}

// The driver reports every move through wheel_move_finalizer, so a completed selection has to end
// OK with the requested slot read back from the device rather than echoed from the request.
static bool select_slot(double slot) {
	if (indigo_change_number_property_1(&simulator_test_client, xagyl_wheel.device_name, WHEEL_SLOT_PROPERTY_NAME, WHEEL_SLOT_ITEM_NAME, slot) != INDIGO_OK) {
		return false;
	}
	return wait_for_property_state(WHEEL_SLOT_PROPERTY_NAME, INDIGO_OK_STATE) && wait_for_number_item_value(WHEEL_SLOT_PROPERTY_NAME, WHEEL_SLOT_ITEM_NAME, slot, 0.001);
}

static void assert_wheel_class_property_completeness(void) {
	static const char *properties[] = {
		WHEEL_SLOT_PROPERTY_NAME,
		WHEEL_SLOT_NAME_PROPERTY_NAME,
		WHEEL_SLOT_OFFSET_PROPERTY_NAME
	};
	assert_defined_properties(properties, ARRAY_SIZE(properties));
}

