// First, one intermediate and last slot, in both directions: the simulator steps one position per
// exchange, so this also covers the multi-poll BUSY path in both rotation directions.
static void moves_through_first_intermediate_and_last_slots(void) {
	external_serial_simulator simulator = { 0 };
	bool online = false;
	const char *arguments[] = { "--slots", "7", NULL };
	SERIAL_CHECK_TRUE(start_xagyl(&simulator, arguments));
	SERIAL_CHECK_TRUE(start_serial_driver(&xagyl_wheel, simulator.port));
	online = true;
	SERIAL_CHECK_TRUE(wait_for_number_item_value(WHEEL_SLOT_PROPERTY_NAME, WHEEL_SLOT_ITEM_NAME, 1, 0.001));
	const double slots[] = { 4, 7, 1, 2 };
	for (int i = 0; i < ARRAY_SIZE(slots); i++) {
		SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_change_number_property_1(&simulator_test_client, xagyl_wheel.device_name, WHEEL_SLOT_PROPERTY_NAME, WHEEL_SLOT_ITEM_NAME, slots[i]));
		SERIAL_CHECK_TRUE(wait_for_property_state(WHEEL_SLOT_PROPERTY_NAME, INDIGO_BUSY_STATE));
		SERIAL_CHECK_TRUE(wait_for_property_state(WHEEL_SLOT_PROPERTY_NAME, INDIGO_OK_STATE));
		SERIAL_CHECK_TRUE(wait_for_number_item_value(WHEEL_SLOT_PROPERTY_NAME, WHEEL_SLOT_ITEM_NAME, slots[i], 0.001));
	}
cleanup:
	if (online) { stop_serial_driver(&xagyl_wheel); }
	stop_external_serial_simulator(&simulator);
}

