static void wa_timeout_recovery(void) {
	external_serial_simulator simulator = { 0 };
	SERIAL_CHECK_TRUE(start_external_serial_simulator(&simulator, ROTATOR_WA_SIMULATOR_EXECUTABLE));
	SERIAL_CHECK_TRUE(start_serial_driver(&wa_rotator, simulator.port));
	SERIAL_CHECK_TRUE(wa_control(&simulator, "completion:silent"));
	SERIAL_CHECK_TRUE(wa_number_change(ROTATOR_RELATIVE_MOVE_PROPERTY_NAME, ROTATOR_RELATIVE_MOVE_ITEM_NAME, 1, INDIGO_BUSY_STATE));
	double start = indigo_monotonic_time();
	while (find_cached_property(ROTATOR_RELATIVE_MOVE_PROPERTY_NAME)->state == INDIGO_BUSY_STATE && indigo_monotonic_time() - start < 35) {
		indigo_usleep(100000);
	}
	SERIAL_CHECK_TRUE(find_cached_property(ROTATOR_RELATIVE_MOVE_PROPERTY_NAME)->state == INDIGO_ALERT_STATE);
	SERIAL_CHECK_TRUE(indigo_monotonic_time() - start >= 29);
	SERIAL_CHECK_TRUE(wa_number_change(ROTATOR_RELATIVE_MOVE_PROPERTY_NAME, ROTATOR_RELATIVE_MOVE_ITEM_NAME, 1, INDIGO_OK_STATE));
cleanup:
	if (context.driver_case == &wa_rotator) {
		stop_serial_driver(&wa_rotator);
	}
	stop_external_serial_simulator(&simulator);
}

