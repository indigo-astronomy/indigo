import os
from pathlib import Path
import signal
import subprocess
import sys
import tempfile


SUITE = "Imager cleanup failure propagation"
CASES = (("CCD simulator shutdown", "CCD simulator shutdown", False), ("observer detach", "observer detach", False), ("bus stop", "bus stop", False), ("conflicting case filters", "bus stop", True))
CASE = "independent instances do not interfere"
BINARY = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else Path(__file__).with_name("test_agent_imager_instances")


def record(line):
	path = os.environ.get("INDIGO_TEST_RESULTS")
	if path:
		with open(path, "a", encoding="utf-8") as stream:
			stream.write(line + "\n")


def check_failure(operation, conflicting_filter):
	with tempfile.TemporaryDirectory(prefix="indigo-cleanup-regression-") as directory:
		result_file = Path(directory) / "results.tsv"
		environment = dict(os.environ)
		environment.pop("INDIGO_TEST_CASE_FILTER", None)
		if conflicting_filter:
			environment["INDIGO_TEST_CASE_FILTER"] = "no such case"
		environment["INDIGO_TEST_RESULTS"] = str(result_file)
		environment["INDIGO_TEST_FAIL_CLEANUP"] = operation
		process = subprocess.Popen([str(BINARY), CASE], env=environment, text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, start_new_session=True)
		try:
			output = process.communicate(timeout=60)[0]
		except subprocess.TimeoutExpired:
			try:
				os.killpg(process.pid, signal.SIGKILL)
			except ProcessLookupError:
				pass
			process.communicate()
			raise
		events = [line.split("\t") for line in result_file.read_text().splitlines()]
		plans = [event for event in events if event[0] == "plan"]
		failures = [event for event in events if event[0] == "fail"]
		passes = [event for event in events if event[0] == "pass"]
		checks = [
			process.returncode == 1,
			len(plans) == 1 and plans[0][1] == "1",
			failures == [["fail", "Imager Agent instance coordination", CASE]],
			not passes,
			"Injected cleanup failure: " + operation in output,
			"Cleanup failed: " + operation in output,
			"Cleanup check: bus stop (" + ("failed" if operation == "bus stop" else "OK") + ")" in output,
			"can't stop" not in output,
			"all tests passed" not in output,
		]
		if not all(checks):
			raise AssertionError(f"{operation}: checks={checks}, exit={process.returncode}, events={events}\n{output}")


def main():
	print("Running " + SUITE, flush=True)
	case_filter = os.environ.get("INDIGO_TEST_CASE_FILTER")
	selected = [case for case in CASES if case_filter is None or case_filter in case[0]]
	if case_filter is not None:
		record(f"filter\t{case_filter}")
	record(f"plan\t{len(selected)}\t{SUITE}")
	failures = 0
	for name, operation, conflicting_filter in selected:
		try:
			check_failure(operation, conflicting_filter)
		except (AssertionError, OSError, subprocess.SubprocessError) as error:
			print(str(error), file=sys.stderr)
			print("  FAIL " + name, flush=True)
			record(f"fail\t{SUITE}\t{name}")
			failures += 1
		else:
			print("  PASS " + name, flush=True)
			record(f"pass\t{SUITE}\t{name}")
	return 1 if failures else 0


if __name__ == "__main__":
	sys.exit(main())
