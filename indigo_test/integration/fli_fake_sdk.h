// Prepares count devices of one class and clears every counter and fault.
static void fli_fake_reset(flidomain_t device_class, int count) {
	pthread_mutex_lock(&fli_fake_mutex);
	memset(&fli_fake, 0, sizeof(fli_fake));
	for (int i = 0; i < FLI_FAKE_DEVICES; i++) {
		fli_fake_reset_device(i, device_class);
		fli_fake_devices[i].present = i < count;
	}
	fli_fake_list_count = fli_fake_list_index = 0;
	fli_fake_list_open = false;
	pthread_mutex_unlock(&fli_fake_mutex);
}

static int fli_fake_index(flidev_t dev) {
	int index = (int)dev - 1;
	if (index < 0 || index >= FLI_FAKE_DEVICES || !fli_fake_devices[index].present) {
		atomic_fetch_add(&fli_fake.invalid_handle_uses, 1);
		return -1;
	}
	return index;
}

