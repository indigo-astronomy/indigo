LIBFLIAPI FLIStepMotorAsync(flidev_t dev, long steps) {
	atomic_fetch_add(&fli_fake.step_motor_calls, 1);
	atomic_store(&fli_fake.last_steps, steps);
	FLI_FAKE_DEVICE(dev);
	if (fli_fake_take(&fli_fake.fail_step)) {
		return FLI_FAKE_ERROR;
	}
	if (steps == 0) {
		// A zero step command is how the SDK stops the motor.
		device->steps_remaining = 0;
		return 0;
	}
	if (device->step_hold > 0) {
		// The move starts, covers half the way and then stays outstanding.
		device->stepper_position += steps / 2;
		device->steps_remaining = device->step_hold;
		return 0;
	}
	device->stepper_position += steps;
	device->steps_remaining = 0;
	device->device_status = FLI_FOCUSER_STATUS_HOME;
	return 0;
}

