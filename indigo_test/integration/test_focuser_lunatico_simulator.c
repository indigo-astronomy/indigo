// One absolute GOTO on a given port, asserting the exact command, the BUSY
// window, the published progress and the final position.
static void absolute_move_on(const simulator_driver_case *device, int port, int home) {
	SERIAL_CHECK_TRUE(lunatico_start(device, "FOCUSER"));
	assert_device_interface(INDIGO_INTERFACE_FOCUSER);
	SERIAL_CHECK_TRUE(wait_for_property_state(FOCUSER_POSITION_PROPERTY_NAME, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(wait_for_number_item_value(FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, home, .1));
	SERIAL_CHECK_TRUE(select_goto_mode(device));
	lunatico_forget_commands();
	int target = home + 300;
	unsigned int revision = property_revision(FOCUSER_POSITION_PROPERTY_NAME);
	SERIAL_CHECK_EQ_INT(INDIGO_OK, indigo_change_number_property_1(&simulator_test_client, device->device_name, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, target));
	// The move is reported BUSY and the driver must publish measured progress,
	// never the requested target, before the controller confirms arrival.
	SERIAL_CHECK_TRUE(wait_for_property_state_seen_after(FOCUSER_POSITION_PROPERTY_NAME, INDIGO_BUSY_STATE, revision));
	char command[64];
	snprintf(command, sizeof(command), "!step goto %d %d 0#", port, target);
	SERIAL_CHECK_TRUE(lunatico_wait_for_command(command));
	SERIAL_CHECK_TRUE(wait_for_number_item_value(FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, target, .1));
	SERIAL_CHECK_TRUE(wait_for_property_state(FOCUSER_POSITION_PROPERTY_NAME, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(wait_for_property_state(FOCUSER_STEPS_PROPERTY_NAME, INDIGO_OK_STATE));
	snprintf(command, sizeof(command), "!step ismoving %d#", port);
	SERIAL_CHECK_TRUE(lunatico_sent(command));
cleanup:
	stop();
}

