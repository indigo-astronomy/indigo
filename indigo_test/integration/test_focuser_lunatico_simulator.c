// Home position of the three simulated ports. Port 0 starts at 1800 steps,
// which is also 0 deg for a rotator with the default steps per revolution.
#define HOME_MAIN   1800
#define HOME_OTHER  1000

static bool lunatico_wait_for_device(bool configurable) {
	if (!configurable) {
		// The migrated driver attaches every logical device during
		// INDIGO_DRIVER_INIT, so it is already there and only has to be
		// enumerated into the property cache.
		enumerate_simulator_device();
		return has_defined_property(CONNECTION_PROPERTY_NAME);
	}
	// configure_ports() is dispatched with INDIGO_ASYNC, so the change request
	// is acknowledged before the device exists. Wait on the definitions the new
	// device broadcasts as it attaches rather than enumerating into a device
	// whose attach is still in flight (LIB-012).
	for (int i = 0; i < 200; i++) {
		if (has_defined_property(CONNECTION_PROPERTY_NAME)) {
			return true;
		}
		indigo_usleep(50000);
	}
	fprintf(stderr, "port device did not appear\n");
	return false;
}

// Bring the driver up and connect one logical device.
//
// Before the generator migration the Exp and Third devices are created on
// demand by configure_ports() from LUNATICO_MODEL and LUNATICO_PORT_*_CONFIG,
// and every port device exposes its own DEVICE_PORT. The migrated driver
// declares all seven logical devices statically, has no port configuration
// properties, and hides DEVICE_PORT on everything but the Main device, whose
// DEVICE_PORT its slaves open through. Requesting the reconfiguration only when
// those properties exist, and always pointing the Main device's DEVICE_PORT at
// the simulator, keeps one suite valid on both sides of the migration.
static bool lunatico_start(const simulator_driver_case *device, const char *port_class) {
	selected = device;
	if (!bring_up_serial_driver(&main_focuser)) {
		return false;
	}
	bool configurable = has_defined_property("LUNATICO_MODEL");
	char url[PATH_MAX];
	lunatico_url(url, sizeof(url));
	if (device != &main_focuser) {
		reset_simulator_context(device);
		if (configurable) {
			indigo_change_switch_property_1(&simulator_test_client, main_focuser.device_name, "LUNATICO_MODEL", "PLATYPUS", true);
			const char *port_property = strstr(device->device_name, "(Exp)") ? "LUNATICO_PORT_EXP_CONFIG" : "LUNATICO_PORT_THIRD_CONFIG";
			indigo_change_switch_property_1(&simulator_test_client, main_focuser.device_name, port_property, port_class, true);
		}
		if (!lunatico_wait_for_device(configurable)) {
			return false;
		}
	}
	indigo_change_text_property_1_raw(&simulator_test_client, main_focuser.device_name, DEVICE_PORT_PROPERTY_NAME, DEVICE_PORT_ITEM_NAME, url);
	indigo_usleep(200000);
	return connect_serial_device(device, url);
}

static bool start_main(void) {
	return lunatico_start(&main_focuser, NULL);
}

// The driver refuses INDIGO_DRIVER_SHUTDOWN while any logical device is still
// connected, and the property cache tracks one device at a time.
static void stop(void) {
	if (selected != &main_focuser) {
		disconnect_serial_device(selected);
	}
	disconnect_serial_device(&main_focuser);
	aux_stop(&main_focuser);
}

static const char *cached_text_value(const char *property_name, const char *item_name) {
	indigo_item *item = find_cached_item(property_name, item_name);
	return item == NULL ? "" : item->text.value;
}

// Sync the focuser to a known position without moving it, so a scenario does
// not depend on the simulated power-up position.
static bool sync_to(const simulator_driver_case *device, int position) {
	if (!lunatico_set_switch(device, FOCUSER_ON_POSITION_SET_PROPERTY_NAME, FOCUSER_ON_POSITION_SET_SYNC_ITEM_NAME, INDIGO_OK_STATE)) {
		return false;
	}
	if (!lunatico_set_number(device, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, position, INDIGO_OK_STATE)) {
		return false;
	}
	return wait_for_number_item_value(FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, position, .1);
}

static bool select_goto_mode(const simulator_driver_case *device) {
	return lunatico_set_switch(device, FOCUSER_ON_POSITION_SET_PROPERTY_NAME, FOCUSER_ON_POSITION_SET_GOTO_ITEM_NAME, INDIGO_OK_STATE);
}

// The connect handler arms a one-shot completion poll and publishes CONNECTION
// OK before that poll fires, so a request issued immediately after connecting
// races it. Scenarios that are not about that race wait for the poll to have
// run; !step ismoving# is issued by nothing else at connect.
static bool settle_after_connect(int port) {
	char command[32];
	snprintf(command, sizeof(command), "!step ismoving %d#", port);
	return lunatico_wait_for_command(command);
}

