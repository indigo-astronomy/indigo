// The Main and Exp devices share one controller connection. Either order must
// work, a sibling must survive the other one disconnecting, and the last close
// owns the transport.
static void shared_connection_survives_sibling_disconnect(void) {
	selected = &exp_focuser;
	SERIAL_CHECK_TRUE(bring_up_serial_driver(&main_focuser));
	bool configurable = has_defined_property("LUNATICO_MODEL");
	char url[PATH_MAX];
	lunatico_url(url, sizeof(url));
	if (configurable) {
		indigo_change_switch_property_1(&simulator_test_client, main_focuser.device_name, "LUNATICO_MODEL", "PLATYPUS", true);
	}
	// Connect the Exp device first, so the secondary opens the transport.
	reset_simulator_context(&exp_focuser);
	SERIAL_CHECK_TRUE(lunatico_wait_for_device(configurable));
	indigo_change_text_property_1_raw(&simulator_test_client, main_focuser.device_name, DEVICE_PORT_PROPERTY_NAME, DEVICE_PORT_ITEM_NAME, url);
	indigo_usleep(200000);
	SERIAL_CHECK_TRUE(connect_serial_device(&exp_focuser, url));
	// Now the Main device joins the same connection.
	SERIAL_CHECK_TRUE(connect_serial_device(&main_focuser, url));
	SERIAL_CHECK_TRUE(wait_for_property_state(FOCUSER_POSITION_PROPERTY_NAME, INDIGO_OK_STATE));
	// Closing Main must leave Exp working on the still open transport.
	disconnect_serial_device(&main_focuser);
	reset_simulator_context(&exp_focuser);
	enumerate_simulator_device();
	SERIAL_CHECK_TRUE(context.connected || has_defined_property(FOCUSER_POSITION_PROPERTY_NAME));
	lunatico_forget_commands();
	SERIAL_CHECK_TRUE(sync_to(&exp_focuser, 1200));
	SERIAL_CHECK_TRUE(lunatico_sent("!step setpos 1 1200#"));
cleanup:
	disconnect_serial_device(&exp_focuser);
	disconnect_serial_device(&main_focuser);
	aux_stop(&main_focuser);
}

