// The powerbox device exposes the DB9 digital outputs and analog inputs. Both
// are horizontally flipped, so outlet item 1 writes pin 4 and sensor item 1
// reads pin 8; the simulator answers a distinct value per analog pin, which is
// what makes the mapping observable.
static void powerbox_outlets_and_sensors(void) {
	SERIAL_CHECK_TRUE(lunatico_start(&exp_aux, "AUX_POWERBOX"));
	assert_device_interface(INDIGO_INTERFACE_AUX_GPIO | INDIGO_INTERFACE_AUX_POWERBOX);
	SERIAL_CHECK_TRUE(has_defined_property(AUX_OUTLET_NAMES_PROPERTY_NAME));
	SERIAL_CHECK_TRUE(has_defined_property(AUX_SENSOR_NAMES_PROPERTY_NAME));
	SERIAL_CHECK_TRUE(has_defined_property(AUX_POWER_OUTLET_PROPERTY_NAME));
	SERIAL_CHECK_TRUE(has_defined_property(AUX_GPIO_SENSORS_PROPERTY_NAME));
	SERIAL_CHECK_TRUE(wait_for_property_state(AUX_GPIO_SENSORS_PROPERTY_NAME, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(wait_for_number_item_value(AUX_GPIO_SENSORS_PROPERTY_NAME, AUX_GPIO_SENSOR_NAME_1_ITEM_NAME, 508, .5));
	SERIAL_CHECK_TRUE(wait_for_number_item_value(AUX_GPIO_SENSORS_PROPERTY_NAME, AUX_GPIO_SENSOR_NAME_2_ITEM_NAME, 507, .5));
	SERIAL_CHECK_TRUE(wait_for_number_item_value(AUX_GPIO_SENSORS_PROPERTY_NAME, AUX_GPIO_SENSOR_NAME_3_ITEM_NAME, 506, .5));
	SERIAL_CHECK_TRUE(wait_for_number_item_value(AUX_GPIO_SENSORS_PROPERTY_NAME, AUX_GPIO_SENSOR_NAME_4_ITEM_NAME, 505, .5));
	lunatico_forget_commands();
	SERIAL_CHECK_TRUE(lunatico_set_switch(&exp_aux, AUX_POWER_OUTLET_PROPERTY_NAME, AUX_POWER_OUTLET_1_ITEM_NAME, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(aux_wait_switch(AUX_POWER_OUTLET_PROPERTY_NAME, AUX_POWER_OUTLET_1_ITEM_NAME, true));
	// Every outlet is written on each change, item 1 last of the four pins.
	SERIAL_CHECK_TRUE(lunatico_sent("!write dig 1 4 1#"));
	SERIAL_CHECK_TRUE(lunatico_sent("!write dig 1 3 0#"));
	SERIAL_CHECK_TRUE(lunatico_sent("!write dig 1 2 0#"));
	SERIAL_CHECK_TRUE(lunatico_sent("!write dig 1 1 0#"));
	// The powerbox port has no stepper, so the motor settings stay hidden.
	SERIAL_CHECK_TRUE(find_cached_property(X_FOCUSER_STEP_MODE_PROPERTY_NAME) == NULL);
	SERIAL_CHECK_TRUE(find_cached_property(X_FOCUSER_MOTOR_TYPE_PROPERTY_NAME) == NULL);
cleanup:
	stop();
}

// Renaming an outlet or a sensor relabels the corresponding item.
static void powerbox_names_relabel_items(void) {
	SERIAL_CHECK_TRUE(lunatico_start(&exp_aux, "AUX_POWERBOX"));
	SERIAL_CHECK_TRUE(lunatico_set_text(&exp_aux, AUX_OUTLET_NAMES_PROPERTY_NAME, AUX_POWER_OUTLET_NAME_1_ITEM_NAME, "Dew heater", INDIGO_OK_STATE));
	indigo_item *outlet = find_cached_item(AUX_POWER_OUTLET_PROPERTY_NAME, AUX_POWER_OUTLET_1_ITEM_NAME);
	SERIAL_CHECK_TRUE(outlet != NULL && !strcmp(outlet->label, "Dew heater"));
	SERIAL_CHECK_TRUE(lunatico_set_text(&exp_aux, AUX_SENSOR_NAMES_PROPERTY_NAME, AUX_GPIO_SENSOR_NAME_1_ITEM_NAME, "Rain", INDIGO_OK_STATE));
	indigo_item *sensor = find_cached_item(AUX_GPIO_SENSORS_PROPERTY_NAME, AUX_GPIO_SENSOR_NAME_1_ITEM_NAME);
	SERIAL_CHECK_TRUE(sensor != NULL && !strcmp(sensor->label, "Rain"));
cleanup:
	stop();
}

static void powerbox_outlet_failure_is_reported(void) {
	SERIAL_CHECK_TRUE(lunatico_start(&exp_aux, "AUX_POWERBOX"));
	SERIAL_CHECK_TRUE(lunatico_set_switch(&exp_aux, AUX_POWER_OUTLET_PROPERTY_NAME, AUX_POWER_OUTLET_1_ITEM_NAME, INDIGO_ALERT_STATE));
cleanup:
	stop();
}

static void powerbox_sensor_failure_is_reported(void) {
	SERIAL_CHECK_TRUE(lunatico_start(&exp_aux, "AUX_POWERBOX"));
	SERIAL_CHECK_TRUE(wait_for_property_state(AUX_GPIO_SENSORS_PROPERTY_NAME, INDIGO_ALERT_STATE));
cleanup:
	stop();
}

// --------------------------------------------------------------------------------- rotator on a secondary port

// The focuser entry point can still drive a rotator on a secondary port, which
// is the whole point of the configurable ports.
static void rotator_on_the_exp_port(void) {
	SERIAL_CHECK_TRUE(lunatico_start(&exp_rotator, "ROTATOR"));
	assert_device_interface(INDIGO_INTERFACE_ROTATOR);
	assert_serial_rotator_class_property_completeness();
	SERIAL_CHECK_TRUE(wait_for_property_state(ROTATOR_POSITION_PROPERTY_NAME, INDIGO_OK_STATE));
	// The temperature sensor selection is focuser-only.
	SERIAL_CHECK_TRUE(find_cached_property(X_FOCUSER_TEMPERATURE_SENSOR_PROPERTY_NAME) == NULL);
	SERIAL_CHECK_TRUE(has_defined_property(X_ROTATOR_MOTOR_TYPE_PROPERTY_NAME));
cleanup:
	stop();
}

