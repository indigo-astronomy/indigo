static const simulator_driver_case exp_focuser = { "Lunatico Exp", "indigo_focuser_lunatico", "Focuser Lunatico (Exp)", indigo_focuser_lunatico, false, NULL, 0, NULL, 0, NULL, 0, NULL, 0 };
static const simulator_driver_case *selected = &main_focuser;

static void simulator_url(char *url, size_t size) {
	if (!strncmp(aux_simulator.port, "udp://", 6)) {
		snprintf(url, size, "lunatico://%s", aux_simulator.port + 6);
	} else {
		snprintf(url, size, "%s", aux_simulator.port);
	}
}

// Only the Main port device owns the serial handle: PRIVATE_DATA->count_open gates the open and
// every port device opens through its own DEVICE_PORT, so a secondary port can only share a
// connection the Main device established first.
static bool start(const simulator_driver_case *device) {
	selected = device;
	if (!bring_up_serial_driver(&main_focuser)) { return false; }
	indigo_change_switch_property_1(&simulator_test_client, main_focuser.device_name, "LUNATICO_MODEL", "PLATYPUS", true);
	char url[PATH_MAX];
	simulator_url(url, sizeof(url));
	if (!connect_serial_device(&main_focuser, url)) { return false; }
	if (device == &main_focuser) { return true; }
	return connect_serial_device(device, url);
}

// aux_stop() only disconnects the device the property cache is pointing at, and the driver
// refuses INDIGO_DRIVER_SHUTDOWN while any device is still connected.
static void stop(const simulator_driver_case *device) {
	if (device != &main_focuser) {
		disconnect_serial_device(device);
	}
	disconnect_serial_device(&main_focuser);
	aux_stop(&main_focuser);
}

