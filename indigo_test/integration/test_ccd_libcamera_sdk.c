#define FAKE_CAMERAS		LCAM_MAX_CAMERAS

typedef struct {
	char id[LCAM_ID_SIZE];
	char model[LCAM_MODEL_SIZE];
	lcam_properties properties;
} fake_profile;

typedef struct {
	bool open, capturing, streaming;
	int mode;
	double exposure, gain, started;
	int frames;
} fake_state;

struct lcam_camera {
	int index;
};

static fake_profile profiles[FAKE_CAMERAS];
static int profile_count;
static fake_state states[FAKE_CAMERAS];
static struct lcam_camera handles[FAKE_CAMERAS];
static pthread_mutex_t fake_mutex = PTHREAD_MUTEX_INITIALIZER;
static atomic_int initialize_count, terminate_count, open_count, close_count, start_count, stop_count, calls_after_close;
static atomic_int fail_initialize, fail_open, fail_start, read_error, short_frame, hold_frames;
