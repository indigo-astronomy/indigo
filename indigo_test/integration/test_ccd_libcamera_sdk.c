static void disconnect_during_exposure_and_shutdown(void) {
	ASSERT_TRUE(begin(true, false));
	select_raw_format();
	ASSERT_EQ_INT(INDIGO_BUSY, indigo_ccd_libcamera(INDIGO_DRIVER_SHUTDOWN, NULL));
	ASSERT_TRUE(expose(0.01));
	atomic_store(&hold_frames, 1);
	unsigned revision = property_revision(CCD_EXPOSURE_PROPERTY_NAME);
	ASSERT_EQ_INT(INDIGO_OK, indigo_change_number_property_1(&simulator_test_client, device_name, CCD_EXPOSURE_PROPERTY_NAME, CCD_EXPOSURE_ITEM_NAME, 1));
	ASSERT_TRUE(wait_for_property_state_after(CCD_EXPOSURE_PROPERTY_NAME, INDIGO_BUSY_STATE, revision));
	ASSERT_TRUE(wait_capturing(true));
	indigo_change_switch_property_1(&simulator_test_client, device_name, CONNECTION_PROPERTY_NAME, CONNECTION_DISCONNECTED_ITEM_NAME, true);
	ASSERT_TRUE(wait_for_simulator_connection_state(false));
	ASSERT_TRUE(!states[0].open);
	ASSERT_EQ_INT(1, close_count);
	atomic_store(&hold_frames, 0);
	indigo_usleep(100000);
	ASSERT_EQ_INT(0, calls_after_close);
	ASSERT_EQ_INT(1, blobs);
	ASSERT_TRUE(connect_device());
	ASSERT_EQ_INT(INDIGO_OK_STATE, find_cached_property(CCD_EXPOSURE_PROPERTY_NAME)->state);
	select_raw_format();
	ASSERT_TRUE(expose(0.01));
	ASSERT_EQ_INT(2, blobs);
	// Disconnecting a running SER stream finalizes the video file and leaves no image property BUSY for the next session.
	ASSERT_EQ_INT(INDIGO_OK, indigo_change_switch_property_1(&simulator_test_client, device_name, CCD_UPLOAD_MODE_PROPERTY_NAME, CCD_UPLOAD_MODE_LOCAL_ITEM_NAME, true));
	ASSERT_TRUE(wait_for_property_state(CCD_UPLOAD_MODE_PROPERTY_NAME, INDIGO_OK_STATE));
	ASSERT_EQ_INT(INDIGO_OK, indigo_change_switch_property_1(&simulator_test_client, device_name, CCD_IMAGE_FORMAT_PROPERTY_NAME, CCD_IMAGE_FORMAT_RAW_SER_ITEM_NAME, true));
	ASSERT_TRUE(wait_for_property_state(CCD_IMAGE_FORMAT_PROPERTY_NAME, INDIGO_OK_STATE));
	const char *stream_items[] = { CCD_STREAMING_EXPOSURE_ITEM_NAME, CCD_STREAMING_COUNT_ITEM_NAME };
	const double values[] = { 0.01, -1 };
	revision = property_revision(CCD_STREAMING_PROPERTY_NAME);
	ASSERT_EQ_INT(INDIGO_OK, change_numbers(CCD_STREAMING_PROPERTY_NAME, 2, stream_items, values));
	ASSERT_TRUE(wait_for_property_state_after(CCD_STREAMING_PROPERTY_NAME, INDIGO_BUSY_STATE, revision));
	ASSERT_TRUE(wait_capturing(true));
	indigo_usleep(100000);
	char ser_path[INDIGO_VALUE_SIZE];
	snprintf(ser_path, sizeof(ser_path), "%s", find_cached_item(CCD_IMAGE_FILE_PROPERTY_NAME, CCD_IMAGE_FILE_ITEM_NAME)->text.value);
	ASSERT_TRUE(strstr(ser_path, ".ser") != NULL);
	indigo_change_switch_property_1(&simulator_test_client, device_name, CONNECTION_PROPERTY_NAME, CONNECTION_DISCONNECTED_ITEM_NAME, true);
	ASSERT_TRUE(wait_for_simulator_connection_state(false));
	ASSERT_TRUE(!states[0].open);
	// indigo_ser_close() writes the frame count into the header (offset 38); an abandoned stream leaves it 0.
	FILE *ser = fopen(ser_path, "rb");
	ASSERT_TRUE(ser != NULL);
	uint32_t ser_frames = 0;
	ASSERT_TRUE(fseek(ser, 38, SEEK_SET) == 0 && fread(&ser_frames, sizeof(ser_frames), 1, ser) == 1);
	fclose(ser);
	unlink(ser_path);
	ASSERT_TRUE(ser_frames > 0);
	ASSERT_TRUE(connect_device());
	ASSERT_TRUE(find_cached_property(CCD_STREAMING_PROPERTY_NAME)->state != INDIGO_BUSY_STATE);
	ASSERT_TRUE(find_cached_property(CCD_IMAGE_FILE_PROPERTY_NAME)->state != INDIGO_BUSY_STATE);
	ASSERT_EQ_INT(INDIGO_OK, indigo_change_switch_property_1(&simulator_test_client, device_name, CCD_UPLOAD_MODE_PROPERTY_NAME, CCD_UPLOAD_MODE_CLIENT_ITEM_NAME, true));
	ASSERT_TRUE(wait_for_property_state(CCD_UPLOAD_MODE_PROPERTY_NAME, INDIGO_OK_STATE));
	select_raw_format();
	ASSERT_TRUE(expose(0.01));
	end();
	ASSERT_EQ_INT(3, close_count);
	ASSERT_EQ_INT(0, calls_after_close);
}

