// Deterministic fake-bridge coverage for the production libcamera CCD driver. The fake implements
// the C bridge interface (indigo_ccd_libcamera_bridge.h) that the driver uses instead of libcamera,
// so the generated driver runs unchanged with the real framework, queues and image processing.

