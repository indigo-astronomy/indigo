// A camera that reports no gain range must not publish CCD_GAIN and captures with its default gain;
// the exposure limits fall back to the framework defaults when the camera reports none.
static void capability_profile_without_gain(void) {
	reset_fake(1, false);
	profiles[0].properties.gain_min = profiles[0].properties.gain_max = 0;
	profiles[0].properties.exposure_min = profiles[0].properties.exposure_max = 0;
	for (int i = 0; i < profiles[0].properties.mode_count; i++) {
		profiles[0].properties.modes[i].exposure_min = profiles[0].properties.modes[i].exposure_max = 0;
	}
	ASSERT_TRUE(start_driver(1));
	ASSERT_TRUE(connect_device());
	ASSERT_TRUE(find_cached_property(CCD_GAIN_PROPERTY_NAME) == NULL);
	indigo_item *exposure = find_cached_item(CCD_EXPOSURE_PROPERTY_NAME, CCD_EXPOSURE_ITEM_NAME);
	ASSERT_TRUE(exposure->number.max > exposure->number.min);
	select_raw_format();
	ASSERT_TRUE(expose(0.01));
	ASSERT_NEAR(profiles[0].properties.gain_default, states[0].gain, 1e-9);
	end();
}

