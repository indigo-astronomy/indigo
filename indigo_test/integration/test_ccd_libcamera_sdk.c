static void bridge_failures_and_recovery(void) {
	ASSERT_TRUE(begin(true, false));
	select_raw_format();
	atomic_store(&fail_start, 1);
	ASSERT_TRUE(expose_and_fail(0.01));
	ASSERT_EQ_INT(0, start_count);
	atomic_store(&fail_start, 0);
	ASSERT_TRUE(expose(0.01));
	atomic_store(&read_error, 1);
	ASSERT_TRUE(expose_and_fail(0.01));
	ASSERT_TRUE(!states[0].capturing);
	atomic_store(&read_error, 0);
	atomic_store(&short_frame, 1);
	ASSERT_TRUE(expose_and_fail(0.01));
	atomic_store(&short_frame, 0);
	// The camera never delivers: the exposure ends in ALERT once the readout timeout expires.
	atomic_store(&hold_frames, 1);
	ASSERT_TRUE(expose_and_fail(0.01));
	ASSERT_TRUE(!states[0].capturing);
	atomic_store(&hold_frames, 0);
	int before = atomic_load(&blobs);
	ASSERT_TRUE(expose(0.01));
	ASSERT_EQ_INT(before + 1, blobs);
	atomic_store(&fail_start, 1);
	const char *stream_items[] = { CCD_STREAMING_EXPOSURE_ITEM_NAME, CCD_STREAMING_COUNT_ITEM_NAME };
	const double values[] = { 0.01, 3 };
	unsigned revision = property_revision(CCD_STREAMING_PROPERTY_NAME);
	ASSERT_EQ_INT(INDIGO_OK, change_numbers(CCD_STREAMING_PROPERTY_NAME, 2, stream_items, values));
	ASSERT_TRUE(wait_for_property_state_after(CCD_STREAMING_PROPERTY_NAME, INDIGO_ALERT_STATE, revision));
	atomic_store(&fail_start, 0);
	atomic_store(&read_error, 1);
	revision = property_revision(CCD_STREAMING_PROPERTY_NAME);
	ASSERT_EQ_INT(INDIGO_OK, change_numbers(CCD_STREAMING_PROPERTY_NAME, 2, stream_items, values));
	ASSERT_TRUE(wait_for_property_state_after(CCD_STREAMING_PROPERTY_NAME, INDIGO_ALERT_STATE, revision));
	atomic_store(&read_error, 0);
	revision = property_revision(CCD_STREAMING_PROPERTY_NAME);
	ASSERT_EQ_INT(INDIGO_OK, change_numbers(CCD_STREAMING_PROPERTY_NAME, 2, stream_items, values));
	ASSERT_TRUE(wait_for_property_state_after(CCD_STREAMING_PROPERTY_NAME, INDIGO_OK_STATE, revision));
	end();
	ASSERT_EQ_INT(0, calls_after_close);
}

