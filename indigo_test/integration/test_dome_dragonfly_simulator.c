static bool abort_settled(void) {
	if (!wait_for_property_state(DOME_SHUTTER_PROPERTY_NAME, INDIGO_ALERT_STATE)) {
		return false;
	}
	if (!wait_for_property_state(DOME_ABORT_MOTION_PROPERTY_NAME, INDIGO_OK_STATE)) {
		return false;
	}
	assert_switch_item_value(DOME_ABORT_MOTION_PROPERTY_NAME, DOME_ABORT_MOTION_ITEM_NAME, false);
	return state_stays(DOME_SHUTTER_PROPERTY_NAME, INDIGO_ALERT_STATE, 20);
}

// Abort stops a roof that is still travelling and leaves the shutter in ALERT,
// because the roof is neither open nor closed. Accepting the request already
// publishes BUSY, so the abort waits for the second BUSY update, which the
// handler sends once the button has actually been pushed.
static void abort_while_opening(void) {
	unsigned int revision;

	SERIAL_CHECK_TRUE(start_serial_driver(&dome_case, aux_simulator.port));
	SERIAL_CHECK_TRUE(wait_for_shutter(DOME_SHUTTER_CLOSED_ITEM_NAME, INDIGO_OK_STATE));
	SERIAL_CHECK_TRUE(set_fast_roof_polling());
	revision = property_revision(DOME_SHUTTER_PROPERTY_NAME);
	SERIAL_CHECK_TRUE(set_shutter(DOME_SHUTTER_OPENED_ITEM_NAME));
	SERIAL_CHECK_TRUE(wait_for_property_state_after(DOME_SHUTTER_PROPERTY_NAME, INDIGO_BUSY_STATE, revision + 1));
	SERIAL_CHECK_TRUE(abort_motion());
	SERIAL_CHECK_TRUE(abort_settled());
cleanup:
	aux_stop(&dome_case);
}

