// The AUX device shares the controller with the dome, so the dome device is
// pointed at the simulator first; connect_serial_device() then also sets the
// AUX device's own DEVICE_PORT while that property is still published.
static bool connect_aux_device(void) {
	if (!bring_up_serial_driver(&aux_case)) {
		return false;
	}
	if (indigo_change_text_property_1_raw(&simulator_test_client, DOME_DEVICE_NAME, DEVICE_PORT_PROPERTY_NAME, DEVICE_PORT_ITEM_NAME, aux_simulator.port) != INDIGO_OK) {
		tear_down_serial_driver(&aux_case);
		return false;
	}
	indigo_usleep(100000);
	if (!connect_serial_device(&aux_case, aux_simulator.port)) {
		tear_down_serial_driver(&aux_case);
		return false;
	}
	return true;
}

