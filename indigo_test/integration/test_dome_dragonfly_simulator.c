static bool wait_for_shutter(const char *item, indigo_property_state state) {
	for (int i = 0; i < 300; i++) {
		indigo_property *property = find_cached_property(DOME_SHUTTER_PROPERTY_NAME);
		indigo_item *cached = find_cached_item(DOME_SHUTTER_PROPERTY_NAME, item);
		if (property != NULL && cached != NULL && property->state == state && cached->sw.value) {
			return true;
		}
		indigo_usleep(100000);
	}
	return false;
}

static bool shutter_switches_are_off(void) {
	indigo_item *opened = find_cached_item(DOME_SHUTTER_PROPERTY_NAME, DOME_SHUTTER_OPENED_ITEM_NAME);
	indigo_item *closed = find_cached_item(DOME_SHUTTER_PROPERTY_NAME, DOME_SHUTTER_CLOSED_ITEM_NAME);
	return opened != NULL && closed != NULL && !opened->sw.value && !closed->sw.value;
}

// Bounded negative check: the property must not leave the given state.
static bool state_stays(const char *property_name, indigo_property_state state, int deciseconds) {
	for (int i = 0; i < deciseconds; i++) {
		indigo_property *property = find_cached_property(property_name);
		if (property == NULL || property->state != state) {
			return false;
		}
		indigo_usleep(100000);
	}
	return true;
}

// Point the single device compliance context at another logical device of the
