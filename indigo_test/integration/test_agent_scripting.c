int main(int argc, char **argv) {
	setvbuf(stdout, NULL, _IONBF, 0);
	int failed = 0, executed = 0;
	for (unsigned i = 0; i < ARRAY_SIZE(tests); i++) {
		if (argc > 1 && !strstr(tests[i].name, argv[1])) {
			continue;
		}
		executed++;
		strcpy(test_root, "/tmp/indigo_scripting_test_XXXXXX");
		if (!mkdtemp(test_root)) {
			return 1;
		}
		snprintf(config_folder, sizeof(config_folder), "%s/.indigo", test_root);
		mkdir(config_folder, 0700);
		pid_t child = fork();
		if (child == 0) {
			alarm(90);
			int status = setup() ? indigo_run_tests("Scripting Agent integration", tests + i, 1) : 1;
			cleanup();
			exit(status || indigo_test_failures ? 1 : 0);
		}
		int status = -1;
		if (child < 0 || waitpid(child, &status, 0) != child || !WIFEXITED(status) || WEXITSTATUS(status)) {
			fprintf(stderr, "FAILED %s (status %d)\n", tests[i].name, status);
			failed++;
		}
		if (getenv("INDIGO_TEST_KEEP_OUTPUT")) {
			printf("Kept test output in %s\n", test_root);
		} else {
			remove_files(test_root);
		}
	}
	printf("Scripting Agent: %d/%d passed (including cleanup)\n", executed - failed, executed);
	return executed ? (failed ? 1 : 0) : 2;
}
