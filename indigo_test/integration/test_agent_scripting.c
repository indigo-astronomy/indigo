static void callback_exception_recovery(void) {
	ASSERT_TRUE(js("indigo_on_define_property=function(){throw new Error('define callback')}; indigo_on_update_property=function(){throw new Error('update callback')}; indigo_on_delete_property=function(){throw new Error('delete callback')}; indigo_on_send_message=function(){throw new Error('message callback')}; indigo_on_enumerate_properties=function(){throw new Error('enumerate callback')}; indigo_on_change_property=function(){throw new Error('change callback')};"));
	indigo_property *p = indigo_init_text_property(NULL, PEER, "CALLBACK", "Peer", "Callback", INDIGO_OK_STATE, INDIGO_RO_PERM, 1);
	indigo_init_text_item(p->items, "VALUE", "Value", "one");
	indigo_define_property(&peer, p, NULL);
	indigo_update_property(&peer, p, NULL);
	indigo_delete_property(&peer, p, NULL);
	indigo_send_message(&peer, OK_PROPERTY, "callback message");
	indigo_property selector = { 0 };
	indigo_enumerate_properties(&observer, &selector);
	indigo_change_text_property_1(&observer, AGENT, "CALLBACK_CHANGE", "VALUE", "x");
	indigo_release_property(p);
	ASSERT_TRUE(js("testValue = 10;"));
}

