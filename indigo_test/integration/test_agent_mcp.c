typedef struct {
	char *wire;
	const char *json;
	jsmntok_t *tokens;
	int count;
	int result;
	int structured;
} read_reply;

static int read_json_next(const jsmntok_t *tokens, int count, int index) {
	int next = index + 1;
	while (next < count && tokens[next].start < tokens[index].end) {
		next++;
	}
	return next;
}

static int read_json_member(const char *json, const jsmntok_t *tokens, int count, int object, const char *name) {
	if (object < 0 || tokens[object].type != JSMN_OBJECT) {
		return -1;
	}
	int key = object + 1;
	while (key + 1 < count && tokens[key].start < tokens[object].end) {
		if (tokens[key].type == JSMN_STRING && (size_t)(tokens[key].end - tokens[key].start) == strlen(name) && !memcmp(json + tokens[key].start, name, strlen(name))) {
			return key + 1;
		}
		key = read_json_next(tokens, count, key + 1);
	}
	return -1;
}

static bool read_json_is(const read_reply *reply, int index, const char *value) {
	return index >= 0 && (size_t)(reply->tokens[index].end - reply->tokens[index].start) == strlen(value) && !memcmp(reply->json + reply->tokens[index].start, value, strlen(value));
}

static int read_json_named(const read_reply *reply, int array, const char *key, const char *name) {
	if (array < 0 || reply->tokens[array].type != JSMN_ARRAY) {
		return -1;
	}
	for (int item = array + 1; item < reply->count && reply->tokens[item].start < reply->tokens[array].end; item = read_json_next(reply->tokens, reply->count, item)) {
		int field = read_json_member(reply->json, reply->tokens, reply->count, item, key);
		if (read_json_is(reply, field, name)) {
			return item;
		}
	}
	return -1;
}

static int read_json_parse(const char *json, jsmntok_t **tokens) {
	for (unsigned size = 128; size <= 32768; size *= 2) {
		jsmntok_t *next = realloc(*tokens, size * sizeof(jsmntok_t));
		if (!next) {
			return -1;
		}
		*tokens = next;
		jsmn_parser parser;
		jsmn_init(&parser);
		int count = jsmn_parse(&parser, json, strlen(json), *tokens, size);
		if (count != JSMN_ERROR_NOMEM) {
			return count;
		}
	}
	return -1;
}

static unsigned read_json_hex(const char *text) {
	unsigned value = 0;
	for (int i = 0; i < 4; i++) {
		unsigned c = (unsigned char)text[i];
		value = value * 16 + (c >= '0' && c <= '9' ? c - '0' : c >= 'a' && c <= 'f' ? c - 'a' + 10 : c - 'A' + 10);
	}
	return value;
}

static char *read_json_string(const char *json, const jsmntok_t *token) {
	if (token->type != JSMN_STRING) {
		return NULL;
	}
	char *result = malloc((size_t)(token->end - token->start) + 1);
	if (!result) {
		return NULL;
	}
	size_t used = 0;
	for (int i = token->start; i < token->end; i++) {
		unsigned c = (unsigned char)json[i];
		bool unicode = false;
		if (c == '\\') {
			c = (unsigned char)json[++i];
			if (c == 'u') {
				unicode = true;
				c = read_json_hex(json + i + 1);
				i += 4;
				if (c >= 0xd800 && c <= 0xdbff) {
					unsigned low = read_json_hex(json + i + 3);
					i += 6;
					c = 0x10000 + ((c - 0xd800) << 10) + low - 0xdc00;
				}
			} else if (c == 'b') {
				c = '\b';
			} else if (c == 'f') {
				c = '\f';
			} else if (c == 'n') {
				c = '\n';
			} else if (c == 'r') {
				c = '\r';
			} else if (c == 't') {
				c = '\t';
			}
		}
		if (!unicode || c < 0x80) {
			result[used++] = (char)c;
		} else if (c < 0x800) {
			result[used++] = (char)(0xc0 | (c >> 6));
			result[used++] = (char)(0x80 | (c & 63));
		} else if (c < 0x10000) {
			result[used++] = (char)(0xe0 | (c >> 12));
			result[used++] = (char)(0x80 | ((c >> 6) & 63));
			result[used++] = (char)(0x80 | (c & 63));
		} else if (c > 0xffff) {
			result[used++] = (char)(0xf0 | (c >> 18));
			result[used++] = (char)(0x80 | ((c >> 12) & 63));
			result[used++] = (char)(0x80 | ((c >> 6) & 63));
			result[used++] = (char)(0x80 | (c & 63));
		} else {
			result[used++] = (char)c;
		}
	}
	result[used] = 0;
	return result;
}

static char *read_json_compact(const char *text, size_t size) {
	char *result = malloc(size + 1);
	if (!result) {
		return NULL;
	}
	size_t used = 0;
	bool quoted = false, escaped = false;
	for (size_t i = 0; i < size; i++) {
		unsigned char c = text[i];
		if (quoted || (c != ' ' && c != '\n' && c != '\r' && c != '\t')) {
			result[used++] = (char)c;
		}
		if (c == '"' && !escaped) {
			quoted = !quoted;
		}
		escaped = quoted && c == '\\' && !escaped;
	}
	result[used] = 0;
	return result;
}

static void read_reply_free(read_reply *reply) {
	free(reply->tokens);
	free(reply->wire);
	memset(reply, 0, sizeof(*reply));
}

static bool read_rpc(const char *method, const char *params, read_reply *reply) {
	memset(reply, 0, sizeof(*reply));
	size_t capacity = strlen(params) + strlen(method) + 128;
	char *request = malloc(capacity);
	if (!request) {
		return false;
	}
	int length = snprintf(request, capacity, "{\"jsonrpc\":\"2.0\",\"id\":31,\"method\":\"%s\",\"params\":%s}", method, params);
	reply->wire = malloc(3 * 1024 * 1024);
	bool sent = reply->wire && post_body(request, length, MCP_HEADERS, reply->wire, 3 * 1024 * 1024);
	free(request);
	if (!sent || (response_status(reply->wire) != 200 && response_status(reply->wire) != 400)) {
		read_reply_free(reply);
		return false;
	}
	const char *body = strstr(reply->wire, "\r\n\r\n");
	if (!body) {
		read_reply_free(reply);
		return false;
	}
	const char *content_length = strstr(reply->wire, "\r\nContent-Length: ");
	if (!content_length || strtoull(content_length + 18, NULL, 10) != strlen(body + 4)) {
		read_reply_free(reply);
		return false;
	}
	reply->json = body + 4;
	reply->count = read_json_parse(reply->json, &reply->tokens);
	if (reply->count <= 0) {
		read_reply_free(reply);
		return false;
	}
	reply->result = read_json_member(reply->json, reply->tokens, reply->count, 0, "result");
	reply->structured = read_json_member(reply->json, reply->tokens, reply->count, reply->result, "structuredContent");
	return true;
}

static bool read_tool(const char *name, const char *arguments, read_reply *reply) {
	size_t capacity = strlen(name) + strlen(arguments) + 64;
	char *params = malloc(capacity);
	if (!params) {
		return false;
	}
	snprintf(params, capacity, "{\"name\":\"%s\",\"arguments\":%s}", name, arguments);
	bool result = read_rpc("tools/call", params, reply) && response_status(reply->wire) == 200;
	free(params);
	return result;
}

static bool read_success_is_consistent(const read_reply *reply) {
	if (reply->result < 0 || reply->structured < 0 || reply->tokens[reply->structured].type != JSMN_OBJECT) {
		return false;
	}
	int content = read_json_member(reply->json, reply->tokens, reply->count, reply->result, "content");
	if (content < 0 || reply->tokens[content].type != JSMN_ARRAY || reply->tokens[content].size != 1) {
		return false;
	}
	int type = read_json_member(reply->json, reply->tokens, reply->count, content + 1, "type");
	if (!read_json_is(reply, type, "text")) {
		return false;
	}
	int text = read_json_member(reply->json, reply->tokens, reply->count, content + 1, "text");
	if (text < 0 || reply->tokens[text].type != JSMN_STRING) {
		return false;
	}
	char *decoded = read_json_string(reply->json, reply->tokens + text);
	jsmntok_t *tokens = NULL;
	int parsed = decoded ? read_json_parse(decoded, &tokens) : -1;
	char *plain = decoded ? read_json_compact(decoded, strlen(decoded)) : NULL;
	char *structured = read_json_compact(reply->json + reply->tokens[reply->structured].start, (size_t)(reply->tokens[reply->structured].end - reply->tokens[reply->structured].start));
	bool same = parsed > 0 && plain && structured && !strcmp(plain, structured);
	free(tokens);
	free(decoded);
	free(plain);
	free(structured);
	return same;
}

static bool read_is_error(const read_reply *reply) {
	int field = read_json_member(reply->json, reply->tokens, reply->count, reply->result, "isError");
	return read_json_is(reply, field, "true");
}

static int read_field(const read_reply *reply, int object, const char *name) {
	return read_json_member(reply->json, reply->tokens, reply->count, object, name);
}

