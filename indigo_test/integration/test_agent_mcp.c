typedef struct {
	pthread_mutex_t mutex;
	pthread_cond_t condition;
	int requested;
	int finished;
	bool done;
	bool passed;
} read_race;

static void *read_snapshots_during_updates(void *data) {
	read_race *race = data;
	for (int i = 1; i <= 20; i++) {
		pthread_mutex_lock(&race->mutex);
		race->requested = i;
		pthread_cond_broadcast(&race->condition);
		pthread_mutex_unlock(&race->mutex);
		read_reply reply;
		bool passed = read_get("X_RACE_NUMBER", &reply);
		if (passed) {
			passed = read_success_is_consistent(&reply);
			int items = read_field(&reply, reply.structured, "items");
			int item = read_json_named(&reply, items, "name", "VALUE");
			int value = read_field(&reply, item, "value");
			passed = passed && value >= 0 && reply.tokens[value].type == JSMN_PRIMITIVE && read_json_is(&reply, read_field(&reply, item, "target"), "0");
			read_reply_free(&reply);
		}
		bool text_passed = read_get("X_RACE_TEXT", &reply);
		if (text_passed) {
			text_passed = read_success_is_consistent(&reply);
			int items = read_field(&reply, reply.structured, "items");
			int item = read_json_named(&reply, items, "name", "VALUE");
			int value = read_field(&reply, item, "value");
			text_passed = text_passed && value >= 0 && reply.tokens[value].type == JSMN_STRING;
			read_reply_free(&reply);
		}
		pthread_mutex_lock(&race->mutex);
		race->passed = race->passed && passed && text_passed;
		race->finished = i;
		pthread_cond_broadcast(&race->condition);
		pthread_mutex_unlock(&race->mutex);
	}
	pthread_mutex_lock(&race->mutex);
	race->done = true;
	pthread_cond_broadcast(&race->condition);
	pthread_mutex_unlock(&race->mutex);
	return NULL;
}

static void reads_are_consistent_during_bus_updates(void) {
	ASSERT_TRUE(read_fixture_begin());
	indigo_property *number = indigo_init_number_property(NULL, READ_FIXTURE_NAME, "X_RACE_NUMBER", "Read fixture", "Concurrent number", INDIGO_OK_STATE, INDIGO_RO_PERM, 1);
	indigo_init_number_item(number->items, "VALUE", "Value", 0, 100, 1, 0);
	indigo_property *text = read_text("X_RACE_TEXT", INDIGO_RO_PERM, "initial");
	ASSERT_TRUE(read_define(number));
	ASSERT_TRUE(read_define(text));
	read_race race = { .mutex = PTHREAD_MUTEX_INITIALIZER, .condition = PTHREAD_COND_INITIALIZER, .passed = true };
	pthread_t reader;
	ASSERT_EQ_INT(0, pthread_create(&reader, NULL, read_snapshots_during_updates, &race));
	bool changed = true;
	for (int i = 1; i <= 20; i++) {
		pthread_mutex_lock(&race.mutex);
		while (race.requested < i && !race.done) {
			pthread_cond_wait(&race.condition, &race.mutex);
		}
		pthread_mutex_unlock(&race.mutex);
		number->items[0].number.value = i;
		char value[32];
		snprintf(value, sizeof(value), "round-%d", i);
		indigo_set_text_item_value(text->items, value);
		changed = indigo_update_property(&read_fixture, number, NULL) == INDIGO_OK && indigo_update_property(&read_fixture, text, NULL) == INDIGO_OK && changed;
		pthread_mutex_lock(&race.mutex);
		while (race.finished < i && !race.done) {
			pthread_cond_wait(&race.condition, &race.mutex);
		}
		pthread_mutex_unlock(&race.mutex);
	}
	pthread_join(reader, NULL);
	pthread_cond_destroy(&race.condition);
	pthread_mutex_destroy(&race.mutex);
	ASSERT_TRUE(changed && race.passed && race.finished == 20);
	ASSERT_EQ_INT(0, atomic_load(&read_fixture_writes));
	read_fixture_end();
}

