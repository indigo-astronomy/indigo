static void cleanup_fixture(void) {
	read_fixture_end();
	if (agent_started) {
		indigo_agent_mcp(INDIGO_DRIVER_SHUTDOWN, NULL);
		agent_started = false;
	}
	if (server_started) {
		WAIT_UNTIL(atomic_load(&clients) == 0, 3);
		int port = indigo_server_tcp_port;
		indigo_server_shutdown();
		if (!WAIT_UNTIL(atomic_load(&server_finished), 1)) {
			int fd = connect_client();
			if (fd >= 0) {
				close(fd);
			}
		}
		if (WAIT_UNTIL(atomic_load(&server_finished), 3)) {
			pthread_join(server_thread, NULL);
		} else {
			fprintf(stderr, "TCP server did not finish on port %d\n", port);
			indigo_test_failures++;
			pthread_detach(server_thread);
		}
	}
	indigo_server_remove_resources();
	if (bus_started) {
		indigo_stop();
	}
}

