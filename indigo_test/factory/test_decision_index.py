"""Canonical decision metadata, deterministic rendering and read-only validation."""
import importlib.util
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

SCRIPT = Path(__file__).resolve().parents[2] / '.factory/scripts/decision_index.py'
spec = importlib.util.spec_from_file_location('decision_index', SCRIPT)
index = importlib.util.module_from_spec(spec)
spec.loader.exec_module(index)
TEXT = '''# ADR-001: Preserve autonomy | across hosts

- Status: accepted
- Date: 2026-10-21
- Decision owner: Project owner
- Related task: 001-example

## Decision and rationale
Use shared checks without additional human approval gates.
'''


class DecisionIndexTests(unittest.TestCase):
    def test_canonical_metadata_links_and_archive_exclusion(self):
        files = {'indigo_docs/decisions/ADR-001-autonomy.md': TEXT,
                 'indigo_docs/decisions/template.md': 'TODO',
                 '.factory/tasks/archive/old/ADR-002.md': 'not an input'}
        output = index.render(reversed(list(files)), files.__getitem__)
        self.assertIn('[ADR-001: Preserve autonomy &#124; across hosts](ADR-001-autonomy.md)', output)
        self.assertNotIn('TODO', output)
        self.assertEqual(output, index.render(files, files.__getitem__))

    def test_invalid_dates_duplicate_ids_missing_metadata_and_title_mismatch(self):
        for text in (TEXT.replace('2026-10-21', '2026-02-30'), TEXT.replace('accepted', 'TODO'),
                     TEXT.replace('ADR-001:', 'ADR-002:'), TEXT.replace('- Decision owner: Project owner', ''),
                     TEXT + '\n- Status: accepted\n'):
            with self.subTest(text=text), self.assertRaises(ValueError):
                index.render(['indigo_docs/decisions/ADR-001-x.md'], lambda _: text)
        with self.assertRaises(ValueError):
            index.render(['indigo_docs/decisions/ADR-001-a.md', 'indigo_docs/decisions/ADR-001-b.md'], lambda _: TEXT)
        with self.assertRaises(ValueError):
            index.render(['indigo_docs/decisions/ADR-bad.md'], lambda _: TEXT)

    def test_cli_stale_check_and_symlink_do_not_write(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / '.factory/scripts').mkdir(parents=True)
            script = root / '.factory/scripts/decision_index.py'
            script.write_bytes(SCRIPT.read_bytes())
            directory = root / 'indigo_docs/decisions'
            directory.mkdir(parents=True)
            adr = directory / 'ADR-001-autonomy.md'
            adr.write_text(TEXT)
            run = lambda *args: subprocess.run([sys.executable, str(script), *args], capture_output=True)
            self.assertEqual(run('--check').returncode, 1)
            self.assertFalse((directory / 'README.md').exists())
            self.assertEqual(run().returncode, 0)
            self.assertEqual(run('--check').returncode, 0)
            before = (directory / 'README.md').read_bytes()
            adr.unlink()
            adr.symlink_to(script)
            self.assertEqual(run().returncode, 2)
            self.assertEqual((directory / 'README.md').read_bytes(), before)
