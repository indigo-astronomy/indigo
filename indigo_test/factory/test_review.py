    def test_dirty_inputs_are_ignored_and_nested_instructions_loaded(self):
        self.put('app.py', 'DIRTY PRIVATE CONTENT\n')
        packet, _, _ = review.build_packet(self.root, self.task, 'verifier', self.base, self.head, [])
        self.assertEqual(packet['files']['app.py'], 'value = 2\n')
        self.put('docs/AGENTS.md', 'Nested documentation rules\n')
        self.put('docs/plan.md', 'Committed document\n')
        head = self.commit()
        packet, _, _ = review.build_packet(self.root, self.task, 'verifier', head, head, ['docs/plan.md'])
        self.assertIn('docs/AGENTS.md', packet['files'])
        self.assertNotIn('app.py', packet['selected'])

    def test_deletion_retains_before_content_and_rename_is_not_silently_omitted(self):
        (self.root / 'app.py').unlink()
        head = self.commit()
        packet, _, _ = review.build_packet(self.root, self.task, 'verifier', self.base, head, [])
        self.assertEqual(packet['sources']['app.py'], 'base')
        self.assertEqual(packet['before']['app.py'], 'value = 1\n')
        self.put('docs/new.md', 'new source\n')
        head = self.commit()
        packet, _, _ = review.build_packet(self.root, self.task, 'verifier', self.base, head, [])
        self.assertIn('docs/new.md', packet['selected'])
        self.assertIn('app.py', packet['selected'])

    def test_unapproved_private_archive_symlink_binary_and_large_inputs_rejected(self):
        cases = [('other.py','unapproved'), ('.env','secret'), ('.factory/findings/archive/private.json','private'),
                 ('docs/binary','\x00binary'), ('docs/large','x' * (1024 * 1024 + 1))]
        for path, text in cases:
            with self.subTest(path=path):
                self.put(path, text)
                head = self.commit()
                with self.assertRaises(ValueError):
                    review.build_packet(self.root, self.task, 'verifier', self.head, head, [path])
                (self.root / path).unlink()
                self.commit()
        link = self.root / 'docs/link'
        link.symlink_to('/private/never-read')
        head = self.commit()
        with self.assertRaisesRegex(ValueError, 'regular Git blob'):
            review.build_packet(self.root, self.task, 'verifier', head, head, ['docs/link'])

