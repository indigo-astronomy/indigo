class ReviewTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix='factory-review-test-')
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.git('init', '-q', '-b', 'main')
        self.git('config', 'user.name', 'Synthetic')
        self.git('config', 'user.email', 'synthetic@example.invalid')
        self.task = '001-review'
        self.policy = dict(version=1, allowed_reviewers=['codex', 'claude'], share_paths=['app.py', 'docs/*'],
                           required_roles=[], timeout_seconds=2, max_attempts=10)
        for path in review.CORE + ('.factory/roles/verifier.md', '.factory/roles/security-reviewer.md',
                                    '.factory/roles/quality-reviewer.md', '.factory/roles/repository-reviewer.md',
                                    '.factory/routines/quality-review.md', '.factory/routines/repository-review.md'):
            self.put(path, 'Synthetic shared instructions\n')
        for path in ('.factory/openai-model-policy.json', '.factory/antropic-model-policy.json'):
            provider = 'openai' if 'openai' in path else 'anthropic'
            self.put(path, json.dumps(dict(provider=provider, tiers={tier: dict(provider=provider, model='synthetic-model', reasoning_setting='high') for tier in ('balanced','strong')})))
        self.put(protocol.POLICY, json.dumps(self.policy))
        for name in review.TASK_DOCS:
            self.put('.factory/tasks/' + self.task + '/' + name, 'Synthetic acceptance criteria\n')
        self.put('.factory/state.json', json.dumps({'active_task': self.task}))
        self.put('.gitignore', '.factory/review.local.json\nfake cli-*\n')
        self.put('app.py', 'value = 1\n')
        self.base = self.commit()
        self.put('app.py', 'value = 2\n')
        self.head = self.commit()
        self.git('switch', '-qc', 'task/' + self.task)
        self.fake = self.root / 'fake cli-pass'
        self.fake.write_text(FAKE.replace('PYTHON', sys.executable))
        self.fake.chmod(0o755)
        self.configure(self.fake)

    def configure(self, executable):
        self.put('.factory/review.local.json', json.dumps({'executables': {'codex': str(executable), 'claude': str(executable)}}))

    def put(self, path, text):
        out = self.root / path
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text)
        return out

    def git(self, *args):
        run = subprocess.run(['git', *args], cwd=self.root, capture_output=True, text=True)
        self.assertEqual(run.returncode, 0, run.stderr)
        return run.stdout.strip()

    def commit(self):
        self.git('add', '-A')
        self.git('commit', '-qm', 'Synthetic commit')
        return self.git('rev-parse', 'HEAD')

    def launch(self, name='claude', mode='pass', role='verifier'):
        executable = self.root / ('fake cli-' + mode)
        if not executable.exists():
            shutil.copyfile(self.fake, executable)
            executable.chmod(0o755)
        self.configure(executable)
        args = argparse.Namespace(task=self.task, reviewer=name, role=role, tier='balanced',
                                  base=self.base, head=self.head, path=[])
        output = io.StringIO()
        with contextlib.redirect_stdout(output):
            code = review.run(self.root, args)
        directory = output.getvalue().strip()
        return code, directory, json.loads((self.root / directory / 'result.json').read_text())

    def test_quality_reviewer_role_runs_and_validates_evidence(self):
        for value, role in enumerate(('quality-reviewer', 'repository-reviewer'), start=3):
            with self.subTest(role=role):
                self.policy['required_roles'] = [role]
                self.put(protocol.POLICY, json.dumps(self.policy))
                self.base = self.commit()
                self.put('app.py', f'value = {value}\n')
                self.head = self.commit()
                code, directory, record = self.launch(role=role)
                self.assertEqual(code, 0, record)
                self.assertEqual(record['role'], role)
                packet = json.loads((self.root / directory / 'packet.json').read_text())
                self.assertEqual(packet['role'], role)
                self.assertIn('.factory/roles/' + role + '.md', packet['files'])
                self.assertIn('.factory/routines/quality-review.md', packet['files'])
                self.assertIn('.factory/routines/repository-review.md', packet['files'])
                review.check(self.root, directory, self.task, self.head)

    def test_both_adapters_pass_and_preserve_checkout(self):
        before = (self.root / 'app.py').read_text()
        state = (self.root / '.factory/state.json').read_bytes()
        for name in ('claude', 'codex'):
            with self.subTest(name=name):
                code, directory, record = self.launch(name)
                self.assertEqual(code, 0, record)
                self.assertEqual(record['observed_model'], None)
                review.check(self.root, directory, self.task, self.head)
        self.assertEqual((self.root / 'app.py').read_text(), before)
        self.assertEqual((self.root / '.factory/state.json').read_bytes(), state)

    def test_task_local_state_runs_fake_review_and_preserves_other_task(self):
        self.put('.factory/state.json', '{"version":2,"task_state":"per-task"}\n')
        self.put('.factory/tasks/' + self.task + '/state.json', json.dumps({'version': 2, 'active_task': self.task}))
        other = self.put('.factory/tasks/other/state.json', '{"version":2,"active_task":"other","status":"blocked"}\n')
        before = other.read_bytes()
        code, directory, record = self.launch()
        self.assertEqual(code, 0, record)
        review.check(self.root, directory, self.task, self.head)
        self.assertEqual(other.read_bytes(), before)
        self.put('.factory/tasks/' + self.task + '/state.json', '{"active_task":"wrong"}')
        with self.assertRaisesRegex(ValueError, 'select'):
            self.launch()

    def test_failures_never_pass_and_no_raw_secret_output(self):
        for mode in ('exit', 'bad', 'identity', 'incomplete', 'findings', 'mutation', 'overflow'):
            with self.subTest(mode=mode):
                code, directory, record = self.launch(mode=mode)
                self.assertEqual(code, 1)
                with self.assertRaises(ValueError):
                    review.check(self.root, directory, self.task, self.head)
                self.assertNotIn('PRIVATE TOKEN', (self.root / directory / 'result.json').read_text())
                self.assertTrue((self.root / directory / 'report.md').is_file())

