    def test_forged_packet_with_recomputed_hash_still_fails_git_binding(self):
        _, directory, _ = self.launch()
        root = self.root / directory
        packet = json.loads((root / 'packet.json').read_text())
        packet['files']['app.py'] = 'fabricated source\n'
        raw = protocol.encode(packet)
        (root / 'packet.json').write_bytes(raw)
        manifest = dict(version=1,packet_sha256=protocol.digest(raw),
                        files={p:protocol.digest(v.encode()) for p,v in packet['files'].items()})
        (root / 'manifest.json').write_bytes(protocol.encode(manifest))
        result = json.loads((root / 'result.json').read_text())
        result['packet_sha256'] = result['review']['packet_sha256'] = protocol.digest(raw)
        (root / 'result.json').write_bytes(protocol.encode(result))
        with self.assertRaisesRegex(ValueError, 'immutable Git inputs'):
            review.check(self.root,directory,self.task,self.head)

