    def prepare_process(self, required=True, role='verifier'):
        import decision_index
        self.policy['required_roles'] = [role] if required else []
        self.put(protocol.POLICY, json.dumps(self.policy))
        self.put('.factory/findings/active.json', json.dumps({'version':1,'next_id':1,'findings':[]}))
        self.put('.factory/findings/archive/.gitkeep', '')
        self.put(decision_index.INDEX, decision_index.render([], lambda _: ''))
        self.base = self.commit()
        self.put('app.py', 'value = 3\n')
        self.head = self.commit()
        code, directory, record = self.launch(role=role)
        self.assertEqual(code, 0, record)
        task_dir = '.factory/tasks/' + self.task
        for name in process_check.DOCS:
            if name not in review.TASK_DOCS:
                self.put(task_dir + '/' + name, 'Verdict: pass\nSynthetic acceptance evidence and limitations recorded.\n')
        data = dict(version=1,task=self.task,reviewed_revision=self.head,scope=['app.py'],
                    checks=[dict(command=['synthetic-check'],result='pass',evidence='verification.md')],
                    risk_reviews={},reviews=[dict(role=role,directory=directory)])
        self.put(task_dir + '/process.json',json.dumps(data))
        return data, directory

    def test_committed_gate_enforces_required_quality_role(self):
        data, directory = self.prepare_process(role='quality-reviewer')
        self.commit()
        self.assertEqual(process_check.inspect(self.root, self.base, 'HEAD', [])['errors'], [])
        data['reviews'] = []
        self.put('.factory/tasks/' + self.task + '/process.json', json.dumps(data))
        self.commit()
        errors = process_check.inspect(self.root, self.base, 'HEAD', [])['errors']
        self.assertTrue(any('required cross-review roles missing: quality-reviewer' in e for e in errors), errors)

    def test_committed_process_gate_requires_valid_fresh_review(self):
        data, directory = self.prepare_process()
        self.commit()
        self.assertEqual(process_check.inspect(self.root,self.base,'HEAD',[])['errors'],[])
        data['reviews'] = []
        self.put('.factory/tasks/' + self.task + '/process.json',json.dumps(data))
        self.commit()
        errors = process_check.inspect(self.root,self.base,'HEAD',[])['errors']
        self.assertTrue(any('required cross-review roles missing' in e for e in errors), errors)
        # Weakening candidate policy cannot waive the baseline's requirement.
        self.policy['required_roles'] = []
        self.put(protocol.POLICY,json.dumps(self.policy))
        self.commit()
        self.assertTrue(any('required cross-review roles missing' in e for e in
                            process_check.inspect(self.root,self.base,'HEAD',[])['errors']))

    def test_cross_review_survives_task_archival_and_template_pruning(self):
        self.prepare_process()
        self.commit()
        source = self.root / '.factory/tasks' / self.task
        archive = self.root / '.factory/tasks/archive' / self.task
        archive.parent.mkdir(parents=True)
        source.rename(archive)
        self.commit()
        self.assertEqual(process_check.inspect(self.root,self.base,'HEAD',[])['errors'],[])
        shutil.rmtree(archive)
        self.commit()
        self.assertEqual(process_check.inspect(self.root,self.base,'HEAD',[])['errors'],[])

    def test_committed_packet_tamper_and_source_changes_fail_gate(self):
        data, directory = self.prepare_process()
        self.put('app.py','value = 999\n')
        self.commit()
        self.assertTrue(any('differs from its reviewed revision' in e for e in
                            process_check.inspect(self.root,self.base,'HEAD',[])['errors']))
        packet_path = self.root / directory / 'packet.json'
        packet = json.loads(packet_path.read_text())
        packet['files']['app.py'] = 'fabricated source\n'
        packet_path.write_bytes(protocol.encode(packet))
        self.commit()
        self.assertTrue(any('integrity' in e for e in process_check.inspect(self.root,self.base,'HEAD',[])['errors']))


