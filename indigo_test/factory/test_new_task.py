"""Task creation must not follow linked inputs or write outside its checkout."""
import json
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[2]


class NewTaskBoundaryTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix='factory-new-task-')
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name) / 'project'
        (self.root / '.factory/scripts').mkdir(parents=True)
        shutil.copy2(ROOT / '.factory/scripts/new_task.py', self.root / '.factory/scripts/new_task.py')
        shutil.copytree(ROOT / '.factory/templates/task', self.root / '.factory/templates/task')
        (self.root / '.factory/tasks').mkdir()
        self.state = self.root / '.factory/state.json'
        self.state.write_text(json.dumps({'status': 'idle', 'custom': 'preserve'}))
        self.outside = Path(self.temp.name) / 'outside'
        self.outside.mkdir()

    def run_new(self):
        return subprocess.run([sys.executable, str(self.root / '.factory/scripts/new_task.py'), '001-new'],
                              cwd=self.root, capture_output=True, text=True)

    def assert_rejected(self):
        before_state = self.state.read_bytes()
        before_outside = {p.relative_to(self.outside): p.read_bytes() for p in self.outside.rglob('*') if p.is_file()}
        result = self.run_new()
        self.assertEqual(result.returncode, 2, result.stderr)
        self.assertEqual(result.stdout, '')
        self.assertEqual(self.state.read_bytes(), before_state)
        self.assertEqual({p.relative_to(self.outside): p.read_bytes() for p in self.outside.rglob('*') if p.is_file()}, before_outside)
        self.assertFalse((self.root / '.factory/tasks/001-new').exists())

    def test_new_task_creates_canonical_quality_report(self):
        result = self.run_new()
        self.assertEqual(result.returncode, 0, result.stderr)
        task = self.root / '.factory/tasks/001-new'
        self.assertTrue((task / 'quality-review.md').is_file())
        self.assertFalse((task / 'repository-review.md').exists())
        self.assertFalse((task / 'ai-slop.md').exists())
        evidence = json.loads((task / 'process.json').read_text())
        self.assertEqual(evidence['version'], 2)
        self.assertEqual(evidence['task'], '001-new')
        self.assertEqual(evidence['reviewed_content'], {})
        self.assertNotIn('reviewed_revision', evidence)
        self.assertEqual(json.loads(self.state.read_text())['active_task'], '001-new')

    def test_linked_task_parent_cannot_create_external_task(self):
        parent = self.root / '.factory/tasks'
        parent.rmdir()
        parent.symlink_to(self.outside, target_is_directory=True)
        self.assert_rejected()

    def test_linked_state_cannot_overwrite_external_file(self):
        external = self.outside / 'state.json'
        self.state.rename(external)
        self.state.symlink_to(external)
        self.assert_rejected()

    def test_linked_template_cannot_copy_external_content(self):
        external = self.outside / 'private.md'
        external.write_text('SYNTHETIC_PRIVATE_CONTENT')
        (self.root / '.factory/templates/task/private.md').symlink_to(external)
        self.assert_rejected()

    def test_nonfinite_state_rejected_before_creating_task(self):
        self.state.write_text('{"status":"idle","custom":NaN}')
        self.assert_rejected()

    def test_oversized_state_rejected_before_creating_task(self):
        self.state.write_text(json.dumps({'status': 'idle', 'custom': 'x' * (1024 * 1024)}))
        self.assert_rejected()

    def test_overflowing_json_number_rejected_before_creating_task(self):
        self.state.write_text('{"status":"idle","custom":1e999}')
        self.assert_rejected()
