    def test_each_provider_policy_can_be_exported_alone(self):
        policies = ("openai-model-policy.json", "antropic-model-policy.json")
        for name in policies:
            with self.subTest(policy=name):
                path = self.write(f".factory/{name}", f"POLICY_CONTENT_{name}\n")
                result = self.run_export()
                self.assertEqual(result.returncode, 0, result.stderr)
                self.assertIn(f"## File: .factory/{name}", result.stdout)
                self.assertIn(f"POLICY_CONTENT_{name}", result.stdout)
                for other in policies:
                    if other != name:
                        self.assertNotIn(f"## File: .factory/{other}", result.stdout)
                        self.assertIn(f"- .factory/{other}", result.stdout)
                path.unlink()

    def test_provider_policy_cannot_export_external_symlink(self):
        outside = Path(self.temp.name) / "private-policy.json"
        outside.write_text("EXTERNAL_POLICY_SECRET")
        for name in ("openai-model-policy.json", "antropic-model-policy.json"):
            with self.subTest(policy=name):
                path = self.root / ".factory" / name
                path.symlink_to(outside)
                result = self.run_export()
                self.assert_rejected(result)
                self.assertNotIn("EXTERNAL_POLICY_SECRET", result.stderr)
                path.unlink()

