"""Context-export behavior and data-boundary tests with synthetic repositories."""
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

TEMPLATE_ROOT = Path(__file__).resolve().parents[2]


class ContextExportTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix="factory-context-")
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name) / "project with spaces"
        self.root.mkdir()
        self.write(".factory/scripts/context_export.py", (TEMPLATE_ROOT / ".factory/scripts/context_export.py").read_text())
        self.write(".factory/scripts/task_store.py", (TEMPLATE_ROOT / ".factory/scripts/task_store.py").read_text())
        self.write(".factory/scripts/findings.py", (TEMPLATE_ROOT / ".factory/scripts/findings.py").read_text())
        self.required = [
            "AGENTS.md", ".factory/bootstrap.md", ".factory/project.md",
            ".factory/state.json", ".factory/workflow.md", ".factory/maintenance.json",
            ".factory/routines/git.md", ".factory/routines/quality-review.md", ".factory/routines/repository-review.md",
            ".factory/roles/coordinator.md", ".factory/roles/developer.md",
        ]
        self.required += [f".factory/tasks/001-demo/{name}.md" for name in ("brief", "specification", "plan", "handoff")]
        for path in self.required:
            self.write(path, f"Synthetic content for {path}\n")
        self.write(".factory/state.json", '{"active_task": "001-demo", "status": "active"}\n')

    def write(self, relative, content):
        path = self.root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        return path

    def run_export(self, *extra):
        return subprocess.run(
            [sys.executable, str(self.root / ".factory/scripts/context_export.py"), "--task", "001-demo", *extra],
            cwd=self.temp.name, capture_output=True, text=True,
        )

    def assert_rejected(self, result):
        self.assertEqual(result.returncode, 2, result.stderr)
        self.assertEqual(result.stdout, "")

    def test_default_role_and_missing_optional_reports(self):
        result = self.run_export()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("Role: coordinator", result.stdout)
        self.assertIn("Optional context files not present", result.stdout)
        self.assertIn("## File: .factory/tasks/001-demo/handoff.md", result.stdout)
        self.assertNotIn("## File: .factory/roles/developer.md", result.stdout)

    def test_selected_role_scope_and_no_source_export_or_mutation(self):
        self.write("lib/AGENTS.md", "LIB_RULE\n")
        self.write("lib/nested/AGENTS.md", "NESTED_RULE\n")
        self.write("lib/nested/module.py", "PRIVATE_SOURCE_SENTINEL\n")
        self.write(".env", "PRIVATE_SECRET_SENTINEL\n")
        self.write(".factory/tasks/001-demo/security.md", "REVIEW_EVIDENCE\n")
        before = {p.relative_to(self.root): p.read_bytes() for p in self.root.rglob("*") if p.is_file()}
        result = self.run_export("--role", "developer", "--path", "lib/nested/module.py", "--path", "lib/nested")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("Role: developer", result.stdout)
        self.assertIn("LIB_RULE", result.stdout)
        self.assertIn("NESTED_RULE", result.stdout)
        self.assertIn("REVIEW_EVIDENCE", result.stdout)
        self.assertLess(result.stdout.index("## File: lib/AGENTS.md"), result.stdout.index("## File: lib/nested/AGENTS.md"))
        self.assertEqual(result.stdout.count("## File: lib/AGENTS.md"), 1)
        self.assertNotIn("PRIVATE_SOURCE_SENTINEL", result.stdout)
        self.assertNotIn("PRIVATE_SECRET_SENTINEL", result.stdout)
        after = {p.relative_to(self.root): p.read_bytes() for p in self.root.rglob("*") if p.is_file()}
        self.assertEqual(before, after)

    def test_quality_reviewer_exports_canonical_role_and_report(self):
        self.write('.factory/roles/quality-reviewer.md', 'QUALITY_ROLE_SENTINEL\n')
        self.write('.factory/tasks/001-demo/quality-review.md', 'QUALITY_EVIDENCE_SENTINEL\n')
        result = self.run_export('--role', 'quality-reviewer')
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn('QUALITY_ROLE_SENTINEL', result.stdout)
        self.assertIn('QUALITY_EVIDENCE_SENTINEL', result.stdout)
        self.assertNotIn('## File: .factory/tasks/001-demo/repository-review.md', result.stdout)
        self.assertNotIn('## File: .factory/tasks/001-demo/ai-slop.md', result.stdout)

    def test_archived_legacy_quality_report_remains_readable(self):
        live = self.root / '.factory/tasks/001-demo'
        archive = self.root / '.factory/tasks/archive/001-demo'
        archive.parent.mkdir(parents=True)
        live.rename(archive)
        report = self.write('.factory/tasks/archive/001-demo/ai-slop.md', 'LEGACY_QUALITY_EVIDENCE\n')
        before = report.read_bytes()
        result = self.run_export('--archived')
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn('LEGACY_QUALITY_EVIDENCE', result.stdout)
        self.assertEqual(report.read_bytes(), before)

    def test_recurring_audit_role_and_report_remain_available(self):
        self.write('.factory/roles/repository-reviewer.md', 'AUDIT_ROLE_SENTINEL\n')
        self.write('.factory/tasks/001-demo/repository-review.md', 'FULL_AUDIT_SENTINEL\n')
        result = self.run_export('--role', 'repository-reviewer')
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn('AUDIT_ROLE_SENTINEL', result.stdout)
        self.assertIn('FULL_AUDIT_SENTINEL', result.stdout)
        archive = self.root / '.factory/tasks/archive/001-demo'
        archive.parent.mkdir(parents=True)
        (self.root / '.factory/tasks/001-demo').rename(archive)
        result = self.run_export('--archived', '--role', 'repository-reviewer')
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn('## File: .factory/tasks/archive/001-demo/repository-review.md', result.stdout)
        self.assertIn('FULL_AUDIT_SENTINEL', result.stdout)

