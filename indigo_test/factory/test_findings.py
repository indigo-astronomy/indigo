    def test_missing_pinned_tree_never_starts_lazy_fetch(self):
        self.add()
        revision = self.commit_report()
        self.active['findings'][0]['tasks'][0]['revision'] = revision
        self.save()
        tree = self.git('rev-parse', revision + '^{tree}')
        (self.root / '.git/objects' / tree[:2] / tree[2:]).unlink()
        self.git('remote', 'add', 'origin', 'file://' + str(self.root / 'unavailable'))
