"""Registry integrity, task pruning evidence and archive context boundaries."""
from copy import deepcopy
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[2]


class FindingsTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix="factory-findings-")
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        (self.root / ".factory/scripts").mkdir(parents=True)
        shutil.copy2(ROOT / ".factory/scripts/findings.py", self.root / ".factory/scripts/findings.py")
        (self.root / ".factory/findings/archive").mkdir(parents=True)
        self.active = {"version": 1, "next_id": 1, "findings": []}
        self.save()
        self.report = self.root / ".factory/tasks/001-demo/verification.md"
        self.report.parent.mkdir(parents=True)
        self.report.write_text("Synthetic verification evidence\n")
        self.record = {
            "id": "FND-000001", "title": "Observed defect", "category": "functional",
            "severity": "medium", "status": "open", "owner": "coordinator", "blocking": False,
            "tasks": [{"id": "001-demo", "report": "verification.md", "revision": None}],
            "summary": "Synthetic reproduction and next action", "evidence": "Synthetic evidence pointer", "resolution": None,
        }

    def save(self):
        (self.root / ".factory/findings/active.json").write_text(json.dumps(self.active))

    def run_findings(self, *args):
        return subprocess.run([sys.executable, str(self.root / ".factory/scripts/findings.py"), *args], cwd=self.root, capture_output=True, text=True)

    def rejected(self, *args):
        result = self.run_findings(*args)
        self.assertEqual(result.returncode, 2, result.stderr)
        self.assertEqual(result.stdout, "")
        return result

    def add(self, record=None):
        self.active["findings"].append(deepcopy(record or self.record))
        self.active["next_id"] = max(self.active["next_id"], int((record or self.record)["id"][4:]) + 1)
        self.save()

    def archive(self, record=None, **resolution):
        closed = deepcopy(record or self.record)
        closed["status"] = "closed"
        closed["resolution"] = {"kind": "fixed", "evidence": "Synthetic retest passes", "approved_by": None, "duplicate_of": None, **resolution}
        path = self.root / f".factory/findings/archive/{closed['id']}.json"
        path.write_text(json.dumps(closed))
        self.active["next_id"] = max(self.active["next_id"], int(closed["id"][4:]) + 1)
        self.save()
        return path

    def git(self, *args):
        result = subprocess.run(["git", "-c", "user.name=Fixture", "-c", "user.email=fixture@example.invalid", *args], cwd=self.root, capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)
        return result.stdout.strip()

    def commit_report(self):
        self.git("init", "-q")
        self.git("add", ".factory/tasks/001-demo/verification.md")
        self.git("commit", "-qm", "Synthetic task evidence")
        return self.git("rev-parse", "HEAD")

    def test_empty_register_and_id_suggestion_are_read_only(self):
        before = {p.relative_to(self.root): p.read_bytes() for p in self.root.rglob("*") if p.is_file()}
        self.assertEqual(self.run_findings("check").returncode, 0)
        self.assertEqual(json.loads(self.run_findings("list").stdout), [])
        self.assertEqual(self.run_findings("next-id").stdout.strip(), "FND-000001")
        after = {p.relative_to(self.root): p.read_bytes() for p in self.root.rglob("*") if p.is_file()}
        self.assertEqual(before, after)

    def test_close_archive_and_reopen_keep_id_and_counter(self):
        self.add()
        self.assertEqual(self.run_findings("check").returncode, 0)
        path = self.archive()
        self.rejected("check")  # Interrupted move preserves both copies, but is not a valid state.
        self.active["findings"] = []
        self.save()
        self.assertEqual(self.run_findings("check").returncode, 0)
        self.assertEqual(json.loads(self.run_findings("list").stdout), [])
        self.assertEqual(json.loads(self.run_findings("show", "FND-000001").stdout)["status"], "closed")
        self.add()
        path.unlink()  # Coordinator reopens same ID; Git retains the prior committed archive.
        self.assertEqual(self.run_findings("check").returncode, 0)
        self.assertEqual(self.run_findings("next-id").stdout.strip(), "FND-000002")

    def test_incomplete_or_invalid_active_entries_are_rejected(self):
        changes = [
            {"owner": ""}, {"severity": "urgent"}, {"status": "closed"}, {"id": "SEC-001"},
            {"id": "FND-000000"}, {"category": []}, {"blocking": "false"}, {"tasks": []},
            {"summary": ""}, {"private_payload": "PRIVATE_SENTINEL"}, {"resolution": {}},
            {"tasks": [{"id": "001-demo", "report": "../private.md", "revision": None}]},
            {"tasks": [{"id": "001-demo", "report": "verification.md", "revision": "123abcd"}]},
        ]
        for change in changes:
            with self.subTest(change=change):
                self.active = {"version": 1, "next_id": 2, "findings": [{**deepcopy(self.record), **change}]}
                self.save()
                result = self.rejected("check")
                self.assertNotIn("PRIVATE_SENTINEL", result.stderr)

    def test_duplicate_ids_and_reused_counter_are_rejected(self):
        self.add()
        self.add()
        self.rejected("check")
        self.active["findings"] = [deepcopy(self.record)]
        self.active["next_id"] = 1
        self.save()
        self.rejected("list")
        self.rejected("next-id")

    def test_risk_acceptance_and_duplicate_resolution_require_evidence(self):
        path = self.archive(kind="accepted_risk")
        self.rejected("check")
        self.archive(kind="accepted_risk", approved_by="Owner authorization reference, date and rationale")
        self.assertEqual(self.run_findings("check").returncode, 0)
        self.archive(kind="duplicate", duplicate_of="FND-000002")
        self.rejected("check")
        second = {**deepcopy(self.record), "id": "FND-000002"}
        self.add(second)
        self.assertEqual(self.run_findings("check").returncode, 0)
        self.active["findings"] = []
        self.archive(second, kind="duplicate", duplicate_of="FND-000001")
        self.rejected("check")  # Both records cannot close each other as the canonical target.
        path.unlink()

    def test_prune_requires_commit_pin_then_survives_report_deletion(self):
        self.add()
        self.rejected("check", "--prune-task", "001-demo")
        revision = self.commit_report()
        self.active["findings"][0]["tasks"][0]["revision"] = revision
        self.save()
        self.assertEqual(self.run_findings("check", "--prune-task", "001-demo").returncode, 0)
        self.report.unlink()
        self.assertEqual(self.run_findings("check").returncode, 0)
        self.assertEqual(self.run_findings("check", "--prune-task", "001-demo").returncode, 0)

    def test_logical_task_links_survive_archival_and_pins_in_both_locations(self):
        self.add()
        before_move = self.commit_report()
        destination = self.root / ".factory/tasks/archive/001-demo"
        destination.parent.mkdir()
        self.report.parent.rename(destination)
        self.assertEqual(self.run_findings("check").returncode, 0)
        self.rejected("check", "--prune-task", "001-demo")
        self.active["findings"][0]["tasks"][0]["revision"] = before_move
        self.save()
        self.assertEqual(self.run_findings("check").returncode, 0)
        self.git("add", ".factory/tasks")
        self.git("commit", "-qm", "Archive synthetic evidence")
        self.active["findings"][0]["tasks"][0]["revision"] = self.git("rev-parse", "HEAD")
        self.save()
        self.assertEqual(self.run_findings("check", "--prune-task", "001-demo").returncode, 0)
        self.archive(self.active["findings"][0])
        self.active["findings"] = []
        self.save()
        shutil.rmtree(destination)
        self.assertEqual(self.run_findings("check", "--prune-task", "001-demo").returncode, 0)

