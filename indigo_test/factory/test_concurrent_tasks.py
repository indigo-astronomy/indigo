class ConcurrentTaskTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix='factory-concurrent-')
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name) / 'project'
        self.root.mkdir()
        shutil.copytree(SCRIPTS, self.root / '.factory/scripts', ignore=shutil.ignore_patterns('__pycache__'))
        shutil.copytree(ROOT / '.factory/templates', self.root / '.factory/templates')
        (self.root / '.factory/tasks').mkdir()
        (self.root / '.factory/completions').mkdir()
        (self.root / '.factory/completions/.gitkeep').write_text('')
        for name in ('roles', 'routines'):
            shutil.copytree(ROOT / '.factory' / name, self.root / '.factory' / name)
        for name in ('bootstrap.md', 'project.md', 'workflow.md', 'maintenance.json'):
            shutil.copy2(ROOT / '.factory' / name, self.root / '.factory' / name)
        shutil.copy2(ROOT / 'AGENTS.md', self.root / 'AGENTS.md')
        self.state = self.root / '.factory/state.json'
        self.state.write_text('{"version":2,"task_state":"per-task","custom":"retained"}\n')
        self.git('init', '-b', 'main')
        self.git('config', 'gc.auto', '0')
        self.git('config', 'maintenance.auto', 'false')
        self.git('config', 'user.name', 'Synthetic Test')
        self.git('config', 'user.email', 'test@example.invalid')
        self.put('.gitignore', '__pycache__/\n')
        self.git('add', '.')
        self.git('commit', '-qm', 'Synthetic baseline')

    def git(self, *args):
        result = subprocess.run(['git', '-C', str(self.root), *args], capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)
        return result.stdout.strip()

    def put(self, name, text):
        path = self.root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        return path

    def call(self, script, *args, expected=0):
        result = subprocess.run([sys.executable, str(self.root / '.factory/scripts' / script), *args],
                                cwd=self.temp.name, capture_output=True, text=True)
        self.assertEqual(result.returncode, expected, result.stderr + result.stdout)
        return result

    def create(self, slug):
        result = self.call('new_task.py', slug)
        return Path(result.stdout.strip().replace('Created ', '', 1)).name

    def snapshot(self):
        return {str(p.relative_to(self.root)): p.read_bytes() for p in self.root.rglob('*')
                if p.is_file() and '.git' not in p.relative_to(self.root).parts and '__pycache__' not in p.parts}

    def legacy(self):
        self.state.write_text(json.dumps(dict(version=1, active_task='003-upgrade', phase='implementation',
                                             status='active', assigned_role='developer', next_action='Upgrade',
                                             blocker=None, custom='preserve')))
        for name in ('001-first', '002-second'):
            shutil.copytree(ROOT / '.factory/templates/task', self.root / '.factory/tasks/archive' / name)
            self.put('.factory/tasks/archive/' + name + '/brief.md', '# Task ' + name + '\n')
        shutil.copytree(ROOT / '.factory/templates/task', self.root / '.factory/tasks/003-upgrade')
        self.put('.factory/tasks/003-upgrade/brief.md', '# Upgrade\n')
        self.put('.factory/tasks/003-upgrade/process.json', json.dumps({
            'version': 2, 'task': '003-upgrade', 'reviewed_content': {'old.md': ['100644', 'blob', 'a' * 40]},
            'scope': ['.factory/tasks/archive/001-first/*']}))
        self.put('README.md', '[first](.factory/tasks/archive/001-first/brief.md)\nTask 003-upgrade\n'
                 '[pinned](https://example.invalid/' + 'a' * 40 + '/001-first/brief.md)\n')
        self.put('.factory/maintenance.json', '{"last_full_review_task":"001-first","custom":9}\n')
        self.put('.factory/findings/active.json', json.dumps({'next_id': 7, 'findings': [
            {'tasks': [{'id': '001-first', 'report': 'brief.md', 'revision': None},
                       {'id': '002-second', 'report': 'brief.md', 'revision': 'a' * 40}]}]}))
        self.put('.factory/tasks/archive/001-first/reviews/packet.json', '{"task":"001-first"}\n')
        self.git('add', '.')
        self.git('commit', '-qm', 'Retain legacy tasks')
        self.git('switch', '-c', 'task/003-upgrade')

    def test_time_order_and_random_identity_without_counter(self):
        earlier = store.allocate('fix', datetime(2026, 10, 22, 1, tzinfo=timezone.utc), 'a' * 4)
        later = store.allocate('fix', datetime(2026, 10, 22, 2, tzinfo=timezone.utc), '0' * 4)
        self.assertLess(earlier, later)
        self.assertRegex(earlier, store.ORDERED)
        with patch.object(store.secrets, 'token_hex', side_effect=['0001', '0002']):
            self.assertNotEqual(store.allocate('same-name'), store.allocate('same-name'))
        before = self.snapshot()
        self.assertRegex(self.call('new_task.py', 'fix', '--print-id').stdout.strip(), store.ORDERED)
        self.assertEqual(before, self.snapshot())

    def test_collision_retries_and_exhaustion_are_explicit(self):
        first = store.allocate('same', suffix='0001')
        second = store.allocate('same', suffix='0002')
        (self.root / '.factory/tasks' / first).mkdir()
        with patch.object(store, 'allocate', side_effect=[first, second]):
            self.assertEqual(store.unique_id(self.root, 'same'), second)
        with patch.object(store, 'allocate', return_value=first):
            with self.assertRaisesRegex(ValueError, '128 attempts'):
                store.unique_id(self.root, 'same')

    def test_two_creations_and_archive_preserve_other_task_state(self):
        global_before = self.state.read_bytes()
        first, second = self.create('camera'), self.create('mount')
        first_path = self.root / '.factory/tasks' / first / 'state.json'
        second_path = self.root / '.factory/tasks' / second / 'state.json'
        second_before = second_path.read_bytes()
        state = json.loads(first_path.read_text())
        self.assertEqual(state['active_task'], first)
        state.update(phase='complete', status='complete')
        first_path.write_text(json.dumps(state))
        self.call('archive_task.py', first)
        archived = self.root / '.factory/tasks/archive' / first
        self.assertEqual(json.loads((archived / 'state.json').read_text())['status'], 'complete')
        self.assertEqual(second_path.read_bytes(), second_before)
        self.assertEqual(self.state.read_bytes(), global_before)
        self.assertEqual(store.selected_state(self.root, second)[1]['active_task'], second)
        pack = self.call('context_export.py', '--task', second).stdout
        self.assertIn('.factory/tasks/' + second + '/state.json', pack)

    def test_held_lock_fails_without_writes_and_worktrees_share_lock(self):
        before = self.snapshot()
        with store.lifecycle_lock(self.root):
            self.call('new_task.py', 'blocked', expected=2)
            self.assertEqual(before, self.snapshot())
        other = Path(self.temp.name) / 'other'
        self.git('worktree', 'add', '-b', 'task/other', str(other))
        self.assertEqual(store.lock_path(other), store.lock_path(self.root))
        with store.lifecycle_lock(self.root):
            with self.assertRaisesRegex(ValueError, 'lock held'):
                with store.lifecycle_lock(other):
                    self.fail('lock must be exclusive')

    def test_parallel_creations_use_isolated_task_states(self):
        # Contenders either complete or fail with a held lock; retry after both exit.
        def create(index):
            return subprocess.run([sys.executable, str(self.root / '.factory/scripts/new_task.py'), 'same'],
                                  cwd=self.root, capture_output=True, text=True)
        with ThreadPoolExecutor(max_workers=2) as pool:
            results = list(pool.map(create, range(2)))
        for result in results:
            self.assertIn(result.returncode, (0, 2), result.stderr)
            if result.returncode == 2:
                self.assertIn('lock held', result.stderr)
                self.create('same')
        tasks = [p for p in (self.root / '.factory/tasks').iterdir() if p.is_dir()]
        self.assertEqual(len(tasks), 2)
        self.assertNotEqual(tasks[0].name, tasks[1].name)
        for task in tasks:
            self.assertEqual(json.loads((task / 'state.json').read_text())['active_task'], task.name)

    def test_upgrade_renames_archives_active_task_branch_and_mutable_references(self):
        self.legacy()
        before = self.snapshot()
        plan = upgrade.build_plan(self.root, '003-upgrade')
        self.assertEqual(before, self.snapshot())
        self.assertEqual(len(plan['mapping']), 3)
        ids = {Path(k).name: v['id'] for k, v in plan['mapping'].items()}
        new = upgrade.apply_plan(self.root, plan)
        self.assertEqual(self.git('branch', '--show-current'), 'task/' + new)
        self.assertFalse((self.root / '.factory/tasks/003-upgrade').exists())
        self.assertEqual(store.selected_state(self.root, new)[1]['custom'], 'preserve')
        self.assertEqual(json.loads(self.state.read_text()), {'version': 2, 'custom': 'preserve', 'task_state': 'per-task'})
        readme = (self.root / 'README.md').read_text()
        self.assertIn('/' + ids['001-first'] + '/brief.md', readme)
        self.assertIn('Task ' + new, readme)
        self.assertIn('a' * 40 + '/001-first/brief.md', readme)
        records = json.loads((self.root / '.factory/findings/active.json').read_text())
        self.assertEqual(records['next_id'], 7)
        refs = records['findings'][0]['tasks']
        self.assertEqual(refs[0]['id'], ids['001-first'])
        self.assertEqual(refs[1]['id'], '002-second')
        packet = self.root / '.factory/tasks/archive' / ids['001-first'] / 'reviews/packet.json'
        self.assertEqual(packet.read_text(), '{"task":"001-first"}\n')
        evidence = json.loads((self.root / '.factory/tasks' / new / 'process.json').read_text())
        self.assertEqual(evidence['task'], new)
        self.assertEqual(evidence['reviewed_content']['old.md'][2], 'a' * 40)
        self.assertEqual(json.loads((self.root / '.factory/maintenance.json').read_text())['last_full_review_task'], ids['001-first'])
        final = self.snapshot()
        again = upgrade.build_plan(self.root, new)
        self.assertEqual(again['mapping'], {})
        upgrade.apply_plan(self.root, again)
        self.assertEqual(final, self.snapshot())

    def test_large_binary_is_preserved_without_loading_as_migration_text(self):
        self.legacy()
        binary = self.root / '.factory/tasks/archive/001-first/capture.bin'
        with binary.open('wb') as stream:
            stream.truncate(2 * store.LIMIT)
        plan = upgrade.build_plan(self.root, '003-upgrade')
        self.assertNotIn('.factory/tasks/archive/001-first/capture.bin', plan['inputs'])
        new_id = plan['mapping']['.factory/tasks/archive/001-first']['id']
        upgrade.apply_plan(self.root, plan)
        moved = self.root / '.factory/tasks/archive' / new_id / 'capture.bin'
        self.assertEqual(moved.stat().st_size, 2 * store.LIMIT)
        self.assertEqual(moved.read_bytes(), b'\0' * (2 * store.LIMIT))

    def test_task_id_migration_refuses_already_migrated_legacy_completion(self):
        self.legacy()
        self.put('.factory/completions/003-upgrade.json', '{"task":"003-upgrade"}\n')
        before = self.snapshot()
        with self.assertRaisesRegex(ValueError, 'before migrating completion history'):
            upgrade.build_plan(self.root, '003-upgrade')
        self.assertEqual(before, self.snapshot())

    def test_stale_plan_and_symlink_are_rejected_without_migration(self):
        self.legacy()
        plan = upgrade.build_plan(self.root, '003-upgrade')
        value = json.loads(self.state.read_text())
        value['next_action'] = 'Changed after review'
        self.state.write_text(json.dumps(value))
        before = self.snapshot()
        with self.assertRaisesRegex(ValueError, 'stale'):
            upgrade.apply_plan(self.root, plan)
        self.assertEqual(before, self.snapshot())
        (self.root / '.factory/tasks/archive/alias').symlink_to(self.root / '.factory/tasks/archive/001-first', target_is_directory=True)
        with self.assertRaisesRegex(ValueError, 'symbolic'):
            upgrade.build_plan(self.root, '003-upgrade')

    def test_branch_rename_failure_rolls_back_moved_tasks_and_references(self):
        self.legacy()
        plan = upgrade.build_plan(self.root, '003-upgrade')
        before = self.snapshot()
        original = upgrade.git
        def fail_branch(root, *args):
            if args[0] == 'branch':
                raise ValueError('Synthetic branch failure')
            return original(root, *args)
        with patch.object(upgrade, 'git', side_effect=fail_branch):
            with self.assertRaisesRegex(ValueError, 'restored'):
                upgrade.apply_plan(self.root, plan)
        self.assertEqual(before, self.snapshot())
        self.assertEqual(self.git('branch', '--show-current'), 'task/003-upgrade')

    def test_write_failure_restores_all_original_bytes_and_paths(self):
        self.legacy()
        plan = upgrade.build_plan(self.root, '003-upgrade')
        before = self.snapshot()
        original = store.atomic
        failed = False
        def fail_once(path, raw):
            nonlocal failed
            if path == self.state and not failed:
                failed = True
                raise OSError('Synthetic disk failure')
            original(path, raw)
        with patch.object(store, 'atomic', side_effect=fail_once):
            with self.assertRaisesRegex(ValueError, 'restored'):
                upgrade.apply_plan(self.root, plan)
        self.assertEqual(before, self.snapshot())
        self.assertEqual(self.git('branch', '--show-current'), 'task/003-upgrade')


