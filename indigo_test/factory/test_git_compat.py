"""Git versions without --no-lazy-fetch: omit it only where no lazy fetch is possible."""
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / '.factory/scripts'))

import git_compat  # noqa: E402


class GitCompatTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix='factory-git-compat-')
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.git('init', '-q')
        self.git('config', 'user.email', 'test@example.invalid')
        self.git('config', 'user.name', 'Test')
        (self.root / 'file.txt').write_text('content\n')
        self.git('add', 'file.txt')
        self.git('commit', '-qm', 'Synthetic commit')

    def git(self, *args):
        return subprocess.run(['git', *args], cwd=self.root, check=True, capture_output=True, text=True).stdout.strip()

    def old_git(self):
        return patch.object(git_compat, 'git_version', return_value=(2, 43))

    def test_new_git_always_disables_lazy_fetch(self):
        with patch.object(git_compat, 'git_version', return_value=(2, 44)):
            self.assertEqual(git_compat.no_lazy_fetch(self.root), ['--no-lazy-fetch'])
            self.git('config', 'remote.origin.promisor', 'true')
            self.assertEqual(git_compat.no_lazy_fetch(self.root), ['--no-lazy-fetch'])

    def test_old_git_without_promisor_omits_the_flag(self):
        with self.old_git():
            self.assertEqual(git_compat.no_lazy_fetch(self.root), [])
            self.git('config', 'remote.origin.promisor', 'false')
            self.assertEqual(git_compat.no_lazy_fetch(self.root), [])

    def test_old_git_in_partial_clone_fails_closed(self):
        with self.old_git():
            self.git('config', 'remote.origin.promisor', 'true')
            with self.assertRaises(ValueError):
                git_compat.no_lazy_fetch(self.root)
            self.git('config', '--unset', 'remote.origin.promisor')
            self.git('config', 'extensions.partialClone', 'origin')
            with self.assertRaises(ValueError):
                git_compat.no_lazy_fetch(self.root)
            self.git('config', '--unset', 'extensions.partialClone')
            self.git('config', 'remote.my.origin.partialCloneFilter', 'blob:none')
            with self.assertRaises(ValueError):
                git_compat.no_lazy_fetch(self.root)

    def test_old_git_with_invalid_promisor_value_fails_closed(self):
        with self.old_git():
            self.git('config', 'remote.origin.promisor', 'maybe')
            with self.assertRaises(ValueError):
                git_compat.no_lazy_fetch(self.root)

    def test_old_git_never_lazy_fetches_from_a_filtered_clone(self):
        source = self.root / 'source'
        source.mkdir()
        subprocess.run(['git', 'init', '-q'], cwd=source, check=True)
        subprocess.run(['git', 'config', 'uploadpack.allowFilter', 'true'], cwd=source, check=True)
        (source / 'blob.txt').write_text('hello\n')
        subprocess.run(['git', 'add', 'blob.txt'], cwd=source, check=True)
        subprocess.run(['git', '-c', 'user.email=t@example.invalid', '-c', 'user.name=T', 'commit', '-qm', 'blob'], cwd=source, check=True)
        clone = self.root / 'clone'
        subprocess.run(['git', 'clone', '-q', '--no-checkout', '--filter=blob:none', 'file://' + str(source), str(clone)], check=True, capture_output=True)
        subprocess.run(['git', 'config', '--unset', 'remote.origin.promisor'], cwd=clone, capture_output=True)
        with self.old_git():
            with self.assertRaises(ValueError):
                git_compat.no_lazy_fetch(clone)

    def test_unknown_git_version_is_treated_as_old(self):
        with patch.object(git_compat, 'git_version', return_value=None):
            self.assertFalse(git_compat.supports_no_lazy_fetch())
            self.assertEqual(git_compat.no_lazy_fetch(self.root), [])

    def test_version_parsing(self):
        cases = {'git version 2.43.0\n': (2, 43), 'git version 2.44.0.windows.1\n': (2, 44), 'git version 3.0\n': (3, 0), 'unexpected\n': None}
        for output, expected in cases.items():
            git_compat.git_version.cache_clear()
            completed = subprocess.CompletedProcess(['git', '--version'], 0, output, '')
            with patch.object(git_compat.subprocess, 'run', return_value=completed):
                self.assertEqual(git_compat.git_version(), expected, output)
        git_compat.git_version.cache_clear()

    def test_installed_git_accepts_the_returned_options(self):
        args = git_compat.no_lazy_fetch(self.root)
        result = subprocess.run(['git', '--no-replace-objects', *args, '--no-optional-locks', 'rev-parse', 'HEAD'], cwd=self.root, capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)


if __name__ == '__main__':
    unittest.main()
