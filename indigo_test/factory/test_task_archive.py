    def test_write_failure_rolls_back_move_links_and_state(self):
        self.put('README.md', '[evidence](.factory/tasks/001-demo/brief.md)\n')
        before = self.snapshot()
        atomic = archiver.atomic
        failed = False

        def injected(path, data):
            nonlocal failed
            if path == self.state and not failed:
                failed = True
                raise OSError('Synthetic disk failure')
            return atomic(path, data)

        with patch.object(archiver, 'ROOT', self.root), patch.object(archiver, 'atomic', side_effect=injected):
            with self.assertRaisesRegex(ValueError, 'original task and edited files restored'):
                archiver.archive(TASK)
        self.assertEqual(before, self.snapshot())
        self.assertFalse(self.archived.parent.exists())

