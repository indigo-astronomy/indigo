ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / '.factory/scripts'))
spec = importlib.util.spec_from_file_location('archive_task', ROOT / '.factory/scripts/archive_task.py')
archiver = importlib.util.module_from_spec(spec)
spec.loader.exec_module(archiver)
TASK = '001-demo'


class TaskArchiveTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix='factory-archive-')
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name) / 'project with spaces'
        self.root.mkdir()
        self.git('init', '-q')
        for name in ('task_store.py', 'maintenance.py', 'archive_task.py', 'new_task.py', 'context_export.py', 'findings.py'):
            self.put('.factory/scripts/' + name, (ROOT / '.factory/scripts' / name).read_bytes())
        shutil.copytree(ROOT / '.factory/templates/task', self.root / '.factory/templates/task')
        self.state = self.put('.factory/state.json', json.dumps({
            'version': 1, 'active_task': TASK, 'phase': 'complete', 'status': 'complete',
            'assigned_role': 'coordinator', 'next_action': 'Archive after verified delivery.',
            'blocker': None, 'custom': 'keep',
        }))
        self.live = self.root / '.factory/tasks' / TASK
        self.archived = self.root / '.factory/tasks/archive' / TASK
        for name in ('brief.md', 'handoff.md', 'verification.md', 'specification.md', 'plan.md'):
            self.put('.factory/tasks/' + TASK + '/' + name, '# Synthetic evidence\n')
        self.put('.factory/maintenance.json', json.dumps({'repository_review': {'completed_non_audit_tasks_since_full_review': 8}}))
        self.put('.factory/findings/active.json', '{"version":1,"next_id":1,"findings":[]}\n')
        self.put('.factory/findings/archive/.gitkeep', '')

    def put(self, path, value):
        target = self.root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(value.encode() if isinstance(value, str) else value)
        return target

    def git(self, *args):
        result = subprocess.run(['git', '-c', 'user.name=Synthetic', '-c', 'user.email=test@example.invalid', *args], cwd=self.root, capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)
        return result.stdout.strip()

    def run_script(self, name, *args):
        return subprocess.run([sys.executable, str(self.root / '.factory/scripts' / name), *args], cwd=self.root, capture_output=True, text=True)

    def snapshot(self):
        return {p.relative_to(self.root): p.read_bytes() for p in self.root.rglob('*') if p.is_file() and '.git' not in p.parts}

    def rejected(self, *args):
        before = self.snapshot()
        result = self.run_script('archive_task.py', *args)
        self.assertEqual(result.returncode, 2, result.stderr)
        self.assertEqual(result.stdout, '')
        self.assertEqual(before, self.snapshot())

    def test_complete_archive_preserves_reports_and_tracking_and_clears_pointer(self):
        self.put('.factory/tasks/' + TASK + '/custom.bin', b'\x00\xff')
        before = {p.name: p.read_bytes() for p in self.live.iterdir()}
        tracking = (self.root / '.factory/maintenance.json').read_bytes()
        registry = (self.root / '.factory/findings/active.json').read_bytes()
        result = self.run_script('archive_task.py', TASK)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertFalse(self.live.exists())
        self.assertEqual(before, {p.name: p.read_bytes() for p in self.archived.iterdir()})
        state = json.loads(self.state.read_text())
        self.assertIsNone(state['active_task'])
        self.assertEqual(state['phase'], 'idle')
        self.assertEqual(state['status'], 'idle')
        self.assertEqual(state['custom'], 'keep')
        self.assertEqual((self.root / '.factory/maintenance.json').read_bytes(), tracking)
        self.assertEqual((self.root / '.factory/findings/active.json').read_bytes(), registry)
        self.assertEqual(self.run_script('new_task.py', '002-next').returncode, 0)
        self.assertEqual(json.loads(self.state.read_text())['custom'], 'keep')

    def test_dry_run_is_read_only_and_reports_link_plan(self):
        self.put('README.md', '[evidence](.factory/tasks/001-demo/verification.md)\n')
        before = self.snapshot()
        result = self.run_script('archive_task.py', TASK, '--dry-run')
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn('updates: 1', result.stdout)
        self.assertEqual(before, self.snapshot())
        self.assertFalse(self.archived.parent.exists())

    def test_real_move_preserves_finding_links_without_rewriting_registry(self):
        record = {
            'id': 'FND-000001', 'title': 'Synthetic issue', 'category': 'quality',
            'severity': 'low', 'status': 'deferred', 'owner': 'coordinator', 'blocking': False,
            'tasks': [{'id': TASK, 'report': 'verification.md', 'revision': None}],
            'summary': 'Synthetic follow-up', 'evidence': 'Synthetic test', 'resolution': None,
        }
        registry = self.put('.factory/findings/active.json', json.dumps({'version': 1, 'next_id': 2, 'findings': [record]}))
        original = registry.read_bytes()
        self.assertEqual(self.run_script('findings.py', 'check').returncode, 0)
        result = self.run_script('archive_task.py', TASK)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(registry.read_bytes(), original)
        result = self.run_script('findings.py', 'check')
        self.assertEqual(result.returncode, 0, result.stderr)

    def test_incoming_outgoing_internal_and_reference_links_survive(self):
        self.put('README.md', '[report](.factory/tasks/001-demo/verification.md#result)\n[e]: .factory/tasks/001-demo/brief.md "Brief"\n[web](https://example.invalid/.factory/tasks/001-demo/)\n')
        self.put('docs/a file.md', 'Synthetic target\n')
