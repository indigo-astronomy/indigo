    def test_same_task_local_contention_never_reuses_a_sequence(self):
        self.task()
        record = Path(self.temp.name) / 'finding.json'
        record.write_text(json.dumps(self.finding()))

        def call(_):
            return subprocess.run([sys.executable, str(self.root / '.factory/scripts/findings.py'), 'create', '--task', A, '--record', str(record)], capture_output=True, text=True)
        with ThreadPoolExecutor(max_workers=2) as pool:
            results = list(pool.map(call, range(2)))
        ids = []
        for result in results:
            if result.returncode:
                self.assertIn('lock held', result.stderr)
                ids.append(self.create())
            else:
                ids.append(result.stdout.strip())
        self.assertEqual(set(ids), {'FND-' + A + '-001', 'FND-' + A + '-002'})

