    def content_review(self):
        self.data['version'] = 2
        self.data.pop('reviewed_revision', None)
        self.git('add', '-A')
        self.data['reviewed_content'] = {
            path: list(identity) if identity is not None else None
            for path, identity in process.staged_content(self.root, self.base).items()
            if process.matches_scope(path, self.data['scope'])}
        self.save()

