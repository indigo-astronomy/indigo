class ProcessCheckTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix='factory-process-')
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.git('init', '-q', '-b', 'main')
        self.git('config', 'user.name', 'Synthetic Reviewer')
        self.git('config', 'user.email', 'reviewer@example.invalid')
        self.put('.factory/findings/active.json', json.dumps({'version': 1, 'next_id': 1, 'findings': []}))
        self.put('.factory/findings/archive/.gitkeep', '')
        self.put(decision_index.INDEX, decision_index.render([], lambda _: ''))
        self.put('app.py', 'value = 1\n')
        self.base = self.commit()
        self.task = '001-example'
        self.directory = '.factory/tasks/' + self.task
        self.data = {'version': 1, 'task': self.task, 'reviewed_revision': self.base, 'scope': ['app.py', '.factory/**', 'docs/decisions/**'],
                     'checks': [{'command': ['python3', '-m', 'unittest'], 'result': 'pass', 'evidence': 'verification.md'}],
                     'risk_reviews': {}}
        for name in process.DOCS:
            self.put(self.directory + '/' + name,
                     '# Synthetic task record\n\n' + ('Verdict: pass\n\n' if name in process.REPORTS else '') +
                     'Reviewed the acceptance criteria using isolated regression fixtures. '
                     'Exact command, environment and observed results are recorded here.\n')
        self.save()

    def git(self, *args):
        result = subprocess.run(['git', *args], cwd=self.root, capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)
        return result.stdout.strip()

    def put(self, path, text):
        output = self.root / path
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(text)

    def save(self):
        self.put(self.directory + '/process.json', json.dumps(self.data))

    def commit(self):
        self.git('add', '-A')
        self.git('commit', '--allow-empty', '-qm', 'Synthetic candidate')
        return self.git('rev-parse', 'HEAD')

    def check(self, base=None):
        return process.inspect(self.root, base or self.base, 'HEAD', [])

    def test_committed_evidence_is_readonly_and_never_executes_recorded_commands(self):
        self.data['checks'][0]['command'] = ['sh', '-c', 'touch SHOULD_NOT_EXIST']
        self.save()
        head = self.commit()
        with patch.object(process.findings, 'ROOT', self.root):
            self.assertEqual(self.check()['errors'], [])
        # Neither dirty evidence nor untracked ADRs may influence a committed result.
        self.put(self.directory + '/verification.md', 'Verdict: fail\n')
        self.put('docs/decisions/ADR-001-x.md', 'malformed untracked decision')
        result = self.check()
        self.assertEqual(result['errors'], [])
        self.assertEqual(result['head'], head)
        self.assertFalse((self.root / 'SHOULD_NOT_EXIST').exists())
        # Candidate findings validation must not resolve even a dirty archive symlink.
        archive = self.root / '.factory/findings/archive'
        (archive / '.gitkeep').unlink()
        archive.rmdir()
        archive.symlink_to('/private/never-read')
        with patch.object(process.findings, 'ROOT', self.root):
            self.assertEqual(self.check()['errors'], [])

    def test_missing_failed_placeholder_reports_and_checks_fail_closed(self):
        self.commit()
        cases = [lambda: self.put(self.directory + '/security.md', 'Verdict: fail\n' + 'review evidence ' * 5),
                 lambda: self.put(self.directory + '/plan.md', '# Plan\nTODO\n'),
                 lambda: (self.root / (self.directory + '/verification.md')).unlink()]
        for change in cases:
            with self.subTest(change=change):
                change()
                self.commit()
                self.assertTrue(self.check()['errors'])

    def test_canonical_quality_report_is_required_and_must_pass(self):
        legacy = self.root / self.directory / 'ai-slop.md'
        if legacy.exists():
            legacy.unlink()
        quality = self.root / self.directory / 'quality-review.md'
        self.put(str(quality.relative_to(self.root)), 'Verdict: pass\nInspected final diff for concrete quality defects.\n')
        self.commit()
        self.assertEqual(self.check()['errors'], [])
        # A passing historical report cannot substitute for the current gate.
        self.put(str(legacy.relative_to(self.root)), 'Verdict: pass\nRetained historical quality evidence.\n')
        quality.unlink()
        self.commit()
        self.assertTrue(self.check()['errors'])
        self.put(str(quality.relative_to(self.root)), 'Verdict: fail\nUnresolved quality defect.\n')
        self.commit()
        self.assertTrue(self.check()['errors'])

