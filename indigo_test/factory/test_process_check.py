        self.reviewed()
        script = self.root / '.factory/scripts/process_check.py'
        run = lambda *args: subprocess.run([sys.executable, str(script), *args], capture_output=True, text=True)
        good = run('--base', self.base)
        self.assertEqual(good.returncode, 1)  # Gate code changes require process-policy review.
        self.data['risk_reviews'] = {'process-policy': 'security.md'}
        self.save()
        self.commit()
        self.assertEqual(run('--base', self.base).returncode, 0)
        bad = run('--base', '--malformed')
        self.assertEqual(bad.returncode, 2)
        self.assertEqual(bad.stdout, '')
        (self.root / '.git/shallow').write_text(self.base + '\n')
        shallow = run('--base', self.base)
        self.assertEqual(shallow.returncode, 2)
        self.assertIn('complete local history', shallow.stderr)

