    @staticmethod
    def git(root, *args):
        return subprocess.run(['git', '-C', str(root), *args], check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE).stdout.decode().strip()

    @staticmethod
    def put(root, name, text):
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)

    def commit(self, root):
        self.git(root, 'add', '.')
        self.git(root, 'commit', '--allow-empty', '-qm', 'Synthetic fixture')
        return self.git(root, 'rev-parse', 'HEAD')

    def call(self, command, sha, *args, expected=0):
        result = subprocess.run([
            'python3', str(SCRIPT), command, '--project', str(self.project),
            '--source', str(self.source), '--revision', sha, '--task', TASK, *args,
        ], stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
        self.assertEqual(result.returncode, expected, result.stderr + result.stdout)
        return result

    def snapshot(self):
        return {str(p.relative_to(self.project)): (p.read_bytes(), p.stat().st_mode & 0o777)
                for p in self.project.rglob('*') if p.is_file() and '.git' not in p.parts}

