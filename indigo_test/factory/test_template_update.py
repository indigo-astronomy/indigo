    def test_write_failure_rolls_back_without_advancing_lock(self):
        first = self.project / 'custom/rules.md'
        lockpath = self.project / update.LOCK
        before = {'custom/rules.md': update.read(first), update.LOCK: update.read(lockpath)}
        after = {'custom/rules.md': (b'New\n', '100644'), update.LOCK: (b'New lock\n', '100644')}
        atomic = update.atomic
        failed = False

        def injected(path, item):
            nonlocal failed
            if path == lockpath and not failed:
                failed = True
                raise OSError('Synthetic disk failure')
            return atomic(path, item)

        with patch.object(update, 'atomic', side_effect=injected):
            with self.assertRaisesRegex(ValueError, 'original file contents restored'):
                update.apply_files(self.project, before, after)
        self.assertEqual(update.read(first), before['custom/rules.md'])
        self.assertEqual(update.read(lockpath), before[update.LOCK])

