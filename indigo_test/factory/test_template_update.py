    def script_relocation(self, local_text=None, new_text=None):
        old_path = 'scripts/run_checks.py'
        new_path = '.factory/scripts/run_checks.py'
        self.put(self.source, old_path, self.base_text)
        old = self.commit(self.source)
        self.put(self.project, new_path, local_text or self.base_text)
        self.put(self.project, 'scripts/application-only', 'Keep native project helper\n')
        lockpath = self.project / update.LOCK
        lock = json.loads(lockpath.read_text())
        lock['revision'] = old
        lock['files'][old_path] = new_path
        lockpath.write_text(json.dumps(lock))
        self.commit(self.project)
        (self.source / old_path).unlink()
        self.put(self.source, new_path, new_text or self.base_text.replace('Omega', 'New Omega'))
        (self.source / new_path).chmod(0o755)
        new = self.commit(self.source)
        return old_path, new_path, old, new

