// Comparison of the COMPACT and VISIBILITY strategies of the Scheduler Agent
// on seeded random nights.
//
// This is a measurement tool, not a pass/fail test. It always exits 0 and is
// kept out of the `test` target. Every night is executed as the scheduler
// runs it: the plan is computed, its first run (task or hook) is made at its
// planned time, every run takes its duration and succeeds, and the plan is
// computed again after it; VISIBILITY is seeded with the rest of its last plan.
//
// Usage:
//   build/benchmark/bench_scheduler_plan [label [nights [runs]]]
//
//   label   free-form name printed in the header, e.g. a branch name
//   nights  random nights per run (default 1000)
//   runs    repetitions of the whole set, for the plan timing (default 1)
//
// The nights are at latitude 42, longitude 23 on 2026-11-19, with 3 to 10
// tasks of 10 to 150 minutes, a quarter of them repeated twice every 60
// minutes and a fifth of high priority, a night start hook of 2 minutes and
// a night end hook. The random numbers come from a fixed generator, so every
// platform plans the same nights. Reported per strategy: task runs, mean run
// quality, run quality weighted by the run duration (quality is the mean
// altitude in percent of the transit altitude), nights with fewer runs than
// COMPACT, nights with the same runs and a lower weighted quality than
// COMPACT, constraint violations of the executed runs (eligibility over the
// whole run, delays, repeat spacing, overlaps), plan changes (the remaining
// runs moved by more than 15 minutes or reordered) and, for VISIBILITY, how
// each plan was decided, the plan time (min, mean, median, p95, p99, max and
// standard deviation, warm-up plans of the first night excluded) and the
// largest work of one plan. VISIBILITY F=10 is VISIBILITY with the meridian
// flip enabled at OFFSET 0 and the default flip penalty of 10 minutes; the
// meridian flips of the executed runs (a run starting before the meridian and
// reaching it) are counted for every strategy. The owner's night of 2026-11-19
// is printed run by run first.

#include <math.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>

#include <indigo/indigo_bus.h>

#include "indigo_drivers/agent_scheduler/indigo_agent_scheduler_header.h"
#include "indigo_drivers/agent_scheduler/indigo_agent_scheduler_plan.h"

#define T_START			1795092480	// 2026-11-19 09:28 UTC
#define T_NIGHT_START	1795104480	// 2026-11-19 12:48 UTC, the night start hook
#define T_END				1795148340	// 2026-11-20 04:19 UTC, the night end hook
#define LATITUDE		42
#define LONGITUDE		23

#define MAX_TASKS		16
#define MAX_RUNS		256
#define MAX_SAMPLES	200000

typedef enum {
	STRATEGY_COMPACT,
	STRATEGY_VISIBILITY,
	STRATEGY_VISIBILITY_FLIP
} strategy;

#define STRATEGY_COUNT	3

static const char *strategy_names[STRATEGY_COUNT] = { "COMPACT", "VISIBILITY", "VISIBILITY F=10" };

// the meridian flip of VISIBILITY F=10, also used to count the flips of every strategy
static const scheduler_flip penalty_flip = { true, 0, 10 / 60.0 };

typedef struct {
	int runs;
	double quality, weighted, duration;
	int violations, changes;
	int flips;
} night_result;

static scheduler_sky_grid sky;
static scheduler_header headers[MAX_TASKS];
static scheduler_target_grid targets[MAX_TASKS];
static scheduler_task_points points[MAX_TASKS];
static scheduler_plan_task tasks[MAX_TASKS];
static int task_count;
static double samples[MAX_SAMPLES];
static int sample_count;
static long worst_work;
static int results[4];
static bool verbose;

static unsigned long long random_state;

static unsigned random_next(void) {
	random_state = random_state * 6364136223846793005ULL + 1442695040888963407ULL;
	return (unsigned)(random_state >> 33);
}

static void add_task(const char *text, int minutes) {
	int i = task_count++;
	char error[128];
	size_t offset;
	if (!indigo_scheduler_parse_header(text, &headers[i], &offset, error, sizeof(error))) {
		printf("%s\n%s\n", text, error);
		exit(0);
	}
	memset(&targets[i], 0, sizeof(targets[i]));
	indigo_scheduler_target_build(&sky, &headers[i], &targets[i]);
	indigo_scheduler_points_build(&sky, &targets[i], &headers[i], &points[i]);
	memset(&tasks[i], 0, sizeof(tasks[i]));
	tasks[i].header = &headers[i];
	tasks[i].target = &targets[i];
	tasks[i].points = &points[i];
	tasks[i].selectable = true;
	tasks[i].duration = minutes * 60;
	tasks[i].runs_left = headers[i].repeat;
}

static void random_night(void) {
	task_count = 0;
	int count = 3 + random_next() % 8;
	for (int i = 0; i < count; i++) {
		char text[256];
		double ra = (random_next() % 2400) / 100.0, dec = -10 + (random_next() % 8000) / 100.0;
		int altitude = 10 + random_next() % 25;
		bool repeated = random_next() % 4 == 0, high = random_next() % 5 == 0;
		snprintf(text, sizeof(text), "// @task T%d\n// @target %.3f %.2f\n// @altitude > %d\n// @twilight astronomical\n%s%sx();\n", i, ra, dec, altitude, repeated ? "// @repeat 2 every 60\n" : "", high ? "// @priority high\n" : "");
		add_task(text, 10 + random_next() % 141);
	}
}

static void owner_night(void) {
	static const char *texts[] = {
		"// @task Orion\n// @priority high\n// @target 05:35:17 -05:23:28\n// @altitude > 20\n// @twilight astronomical\nx();\n",
		"// @task Rosette\n// @target 06:33:45 +04:59:54\n// @altitude > 20\n// @twilight astronomical\nx();\n",
		"// @task Jellyfish\n// @target 06:17:00 +22:31:00\n// @altitude > 20\n// @twilight astronomical\nx();\n",
		"// @task Pleiades\n// @target 03:47:24 +24:07:00\n// @altitude > 10\n// @twilight astronomical\nx();\n",
		"// @task Elephant\n// @target 21:34:57 +57:30:00\n// @altitude > 20\n// @twilight astronomical\nx();\n",
		"// @task Soul\n// @target 02:51:00 +60:24:00\n// @altitude > 10\n// @twilight astronomical\nx();\n"
	};
	static const int minutes[] = { 31, 21, 121, 21, 121, 28 };
	task_count = 0;
	for (int i = 0; i < 6; i++) {
		add_task(texts[i], minutes[i]);
	}
}

static double quality(int i, time_t start) {
	double result = indigo_scheduler_run_quality(&sky, &targets[i], &headers[i], start, tasks[i].duration);
	return result > 0 ? result : 0;
}

static double elapsed(struct timespec *from, struct timespec *to) {
	return (to->tv_sec - from->tv_sec) + (to->tv_nsec - from->tv_nsec) / 1e9;
}

static void hhmm(time_t t, char *text) {
	struct tm tm;
	gmtime_r(&t, &tm);
	sprintf(text, "%02d:%02d", tm.tm_hour, tm.tm_min);
}

// the remaining task runs of a plan moved by more than 15 minutes or reordered
static bool changed(const scheduler_plan_run *previous, int previous_count, const scheduler_plan_run *plan, int count) {
	int a = 0, b = 0;
	for (;;) {
		while (a < previous_count && previous[a].task < 0) {
			a++;
		}
		while (b < count && (plan[b].task < 0 || plan[b].running)) {
			b++;
		}
		if (a >= previous_count || b >= count) {
			return (a < previous_count) != (b < count);
		}
		if (previous[a].task != plan[b].task || labs((long)(previous[a].start - plan[b].start)) > 15 * 60) {
			return true;
		}
		a++;
		b++;
	}
}

static night_result run_night(strategy kind, bool timed) {
	night_result result = { 0 };
	scheduler_plan_task state[MAX_TASKS];
	memcpy(state, tasks, sizeof(tasks));
	scheduler_plan_hook all_hooks[2] = { { T_NIGHT_START, 120, false }, { T_END, 120, false } };
	bool hook_done[2] = { false, false };
	static scheduler_plan_run plan[MAX_RUNS], previous[MAX_RUNS];
	int previous_count = 0;
	bool have_previous = false;
	time_t last_end[MAX_TASKS];
	bool ran[MAX_TASKS] = { false };
	time_t t = T_START;
	for (int step = 0; step < 200; step++) {
		scheduler_plan_hook hooks[2];
		int hook_index[2], hook_count = 0;
		for (int h = 0; h < 2; h++) {
			if (!hook_done[h]) {
				hook_index[hook_count] = h;
				hooks[hook_count++] = all_hooks[h];
			}
		}
		int count;
		if (kind == STRATEGY_COMPACT) {
			count = indigo_scheduler_plan_with_hooks(&sky, state, task_count, hooks, hook_count, t, T_END + 1, 1, 1, plan, MAX_RUNS);
		} else {
			scheduler_plan_info info;
			struct timespec from, to;
			clock_gettime(CLOCK_MONOTONIC, &from);
			count = indigo_scheduler_plan_visibility(&sky, state, task_count, hooks, hook_count, t, T_END + 1, 1, 1, kind == STRATEGY_VISIBILITY_FLIP ? &penalty_flip : NULL, have_previous ? previous : NULL, previous_count, plan, MAX_RUNS, &info);
			clock_gettime(CLOCK_MONOTONIC, &to);
			// the timing and the decisions are those of plain VISIBILITY
			if (kind == STRATEGY_VISIBILITY) {
				if (timed && sample_count < MAX_SAMPLES) {
					samples[sample_count++] = elapsed(&from, &to) * 1000;
				}
				if (info.work > worst_work) {
					worst_work = info.work;
				}
				results[info.result]++;
			}
		}
		if (have_previous && changed(previous, previous_count, plan, count)) {
			result.changes++;
		}
		// the first run of the plan is made, task or hook
		int first = 0;
		while (first < count && plan[first].running) {
			first++;
		}
		bool any_task = false;
		for (int r = first; r < count; r++) {
			any_task = any_task || plan[r].task >= 0;
		}
		if (!any_task) {
			break;
		}
		const scheduler_plan_run *run = plan + first;
		if (run->task < 0) {
			hook_done[hook_index[run->hook]] = true;
			t = run->end;
		} else {
			int i = run->task;
			time_t start = run->start;
			const char *reason;
			bool ok = start >= t && start < T_END + 1 && start >= state[i].available_from && indigo_scheduler_points_ok(&sky, &points[i], &headers[i], start, start + tasks[i].duration, &reason);
			if (ran[i] && start < last_end[i] + headers[i].repeat_every * 60) {
				ok = false;
			}
			if (!ok) {
				result.violations++;
			}
			ran[i] = true;
			last_end[i] = start + tasks[i].duration;
			bool flips = indigo_scheduler_run_flips(&sky, &targets[i], &headers[i], start, tasks[i].duration, &penalty_flip);
			if (flips) {
				result.flips++;
			}
			if (verbose) {
				char a[8], b[8];
				hhmm(start, a);
				hhmm(start + tasks[i].duration, b);
				printf("    %s-%s %-10s %5.1f %%%s\n", a, b, headers[i].name, quality(i, start), flips ? "  FLIP" : "");
			}
			result.runs++;
			result.quality += quality(i, start);
			result.weighted += quality(i, start) * tasks[i].duration;
			result.duration += tasks[i].duration;
			t = start + tasks[i].duration;
			state[i].runs_left--;
			state[i].available_from = t + headers[i].repeat_every * 60;
			// a hook due while the run was in progress runs after it, as in the plan
		}
		previous_count = 0;
		for (int r = first + 1; r < count; r++) {
			previous[previous_count++] = plan[r];
		}
		have_previous = true;
	}
	return result;
}

static int compare(const void *a, const void *b) {
	double x = *(const double *)a, y = *(const double *)b;
	return x < y ? -1 : x > y ? 1 : 0;
}

static void print_timing(void) {
	if (sample_count == 0) {
		return;
	}
	qsort(samples, sample_count, sizeof(double), compare);
	double sum = 0, squares = 0;
	for (int i = 0; i < sample_count; i++) {
		sum += samples[i];
	}
	double mean = sum / sample_count;
	for (int i = 0; i < sample_count; i++) {
		squares += (samples[i] - mean) * (samples[i] - mean);
	}
	printf("VISIBILITY plan time (ms, %d plans): min %.2f mean %.2f median %.2f p95 %.2f p99 %.2f max %.2f stddev %.2f\n", sample_count, samples[0], mean, samples[sample_count / 2], samples[(int)(sample_count * 0.95)], samples[(int)(sample_count * 0.99)], samples[sample_count - 1], sqrt(squares / sample_count));
	printf("VISIBILITY largest work of one plan: %ld cells (budget %ld)\n", worst_work, SCHEDULER_VISIBILITY_BUDGET);
}

static void print_line(const char *name, const night_result *total, int fewer, int worse) {
	printf("%-15s runs %5d  mean quality %5.1f %%  weighted quality %5.1f %%  nights with fewer runs than COMPACT %d  same runs and worse %d  violations %d  plan changes %d\n", name, total->runs, total->runs > 0 ? total->quality / total->runs : 0, total->duration > 0 ? total->weighted / total->duration : 0, fewer, worse, total->violations, total->changes);
}

static void print_flips(const char *name, const night_result *total, int nights) {
	printf("%-15s meridian flips %5d  flips per night %.2f  runs %5d  weighted quality %5.1f %%\n", name, total->flips, nights > 0 ? (double)total->flips / nights : 0, total->runs, total->duration > 0 ? total->weighted / total->duration : 0);
}

int main(int argc, char **argv) {
	const char *label = argc > 1 ? argv[1] : "current";
	int nights = argc > 2 ? atoi(argv[2]) : 1000;
	int repeats = argc > 3 ? atoi(argv[3]) : 1;
	if (nights <= 0) {
		nights = 1000;
	}
	if (repeats <= 0) {
		repeats = 1;
	}
	indigo_scheduler_sky_build(&sky, T_START, LATITUDE, LONGITUDE, 0);
	printf("Scheduler plan benchmark: %s, %d random nights x %d, latitude %d, longitude %d, 2026-11-19\n", label, nights, repeats, LATITUDE, LONGITUDE);
	owner_night();
	verbose = true;
	for (int kind = STRATEGY_COMPACT; kind < STRATEGY_COUNT; kind++) {
		printf("  owner's night, %s:\n", strategy_names[kind]);
		night_result result = run_night(kind, false);
		printf("    %d runs, mean quality %.1f %%, weighted quality %.1f %%, meridian flips %d\n", result.runs, result.quality / result.runs, result.weighted / result.duration, result.flips);
	}
	verbose = false;
	memset(results, 0, sizeof(results));
	night_result totals[STRATEGY_COUNT];
	int fewer[STRATEGY_COUNT] = { 0 }, worse[STRATEGY_COUNT] = { 0 };
	for (int repeat = 0; repeat < repeats; repeat++) {
		memset(totals, 0, sizeof(totals));
		memset(fewer, 0, sizeof(fewer));
		memset(worse, 0, sizeof(worse));
		for (int night = 0; night < nights; night++) {
			random_state = (unsigned long long)night * 2654435761ULL + 1;
			random_night();
			night_result compact = run_night(STRATEGY_COMPACT, false);
			// the plans of the first night are warm-up
			night_result visibility = run_night(STRATEGY_VISIBILITY, repeat > 0 || night > 0);
			night_result visibility_flip = run_night(STRATEGY_VISIBILITY_FLIP, false);
			night_result *each[STRATEGY_COUNT] = { &compact, &visibility, &visibility_flip };
			for (int kind = 0; kind < STRATEGY_COUNT; kind++) {
				night_result *result = each[kind];
				totals[kind].runs += result->runs;
				totals[kind].quality += result->quality;
				totals[kind].weighted += result->weighted;
				totals[kind].duration += result->duration;
				totals[kind].violations += result->violations;
				totals[kind].changes += result->changes;
				totals[kind].flips += result->flips;
				if (result->runs < compact.runs) {
					fewer[kind]++;
				} else if (result->runs == compact.runs && result->duration > 0 && compact.duration > 0 && result->weighted / result->duration < compact.weighted / compact.duration - 1e-9) {
					worse[kind]++;
				}
			}
		}
	}
	for (int kind = 0; kind < STRATEGY_COUNT; kind++) {
		print_line(strategy_names[kind], totals + kind, fewer[kind], worse[kind]);
	}
	for (int kind = 0; kind < STRATEGY_COUNT; kind++) {
		print_flips(strategy_names[kind], totals + kind, nights);
	}
	printf("VISIBILITY plans: %d planned, %d COMPACT not worse, %d no arrangement, %d too large\n", results[SCHEDULER_VISIBILITY_PLANNED], results[SCHEDULER_VISIBILITY_NOT_BETTER], results[SCHEDULER_VISIBILITY_NO_ARRANGEMENT], results[SCHEDULER_VISIBILITY_TOO_LARGE]);
	print_timing();
	return 0;
}
