// Opt-in acceptance test for a physically connected AstroGadget FocusDreamPro controller, or any
// controller sharing its command set such as the Astrojolo focuser. It runs the focuser hardware
// acceptance checklist of DRIVER_TESTING_RULES.md against the real unit: the identity handshake,
// the published property contract, the temperature probe and its polling, absolute and relative
// motion with position readback, SYNC as a coordinate update, the travel limit, the overlapping
// request, abort while moving and while idle, the six speeds, the duty cycle, a disconnect during
// a move, reconnect and driver INIT/SHUTDOWN.
//
// THE MOTOR PHYSICALLY RUNS. Every move is relative to the position the controller reported when
// the session started, the longest single move is FOCUSDREAMPRO_HW_TRAVEL steps outward (default
// 300), every scenario moves back, and the session restores the starting position before it
// disconnects, so the drawtube ends up where it was found and no end stop is approached.
//
// The controller is single threaded and steps at roughly 0.151 ms + 0.044 ms per unit of the S:
// delay, so the slowest speed index needs about 23 ms per step. MOVE_TIMEOUT is sized for the
// default travel at that speed; raise it along with FOCUSDREAMPRO_HW_TRAVEL.
//
// The port comes from FOCUSDREAMPRO_HW_PORT. When it is not set the port the driver itself
// detected through its CP2102 match pattern is used.

#include <math.h>
#include <stdlib.h>
#include <indigo_drivers/focuser_focusdreampro/indigo_focuser_focusdreampro.h>
#include "hardware_test_common.h"

#define DEVICE_NAME "FocusDreamPro"

// One serialized transaction over the 9600 baud link plus the driver's own connection work.
#define SHORT_TIMEOUT 15.0
// The default travel at the slowest speed index, plus the completion poll and a wide margin.
#define MOVE_TIMEOUT 90.0
// The idle polling period is 1 s, so two of them are enough to observe a fresh publication.
#define POLL_TIMEOUT 10.0

// The driver-defined property is declared in the generated source rather than in the header, so
// the test names it the way the simulator integration test does.
#define X_FOCUSER_DUTY_CYCLE_PROPERTY_NAME "X_FOCUSER_DUTY_CYCLE"
#define X_FOCUSER_DUTY_CYCLE_ITEM_NAME "DUTY_CYCLE"

// The controller's speed indices, 0 slowest and 5 fastest.
#define SLOWEST_SPEED 0
#define FASTEST_SPEED 5

static int focuser = -1;
static const char *serial_port = NULL;
static double travel = 300;
// What the controller reported when the session connected. Every scenario restores what it
// changes and the session restores the position at the end.
static double initial_position, initial_speed, initial_duty_cycle, initial_limit_min, initial_limit_max;
static bool state_captured = false;

static bool select_port(void) {
	if (serial_port == NULL || !*serial_port) {
		char detected[INDIGO_VALUE_SIZE] = "";
		if (hw_text_item(focuser, DEVICE_PORT_PROPERTY_NAME, DEVICE_PORT_ITEM_NAME, detected, sizeof(detected)) && *detected) {
			printf("Using the port the driver detected: %s\n", detected);
			return true;
		}
		fprintf(stderr, "    no serial port was detected, set FOCUSDREAMPRO_HW_PORT\n");
		return false;
	}
	printf("Using port %s\n", serial_port);
	return hw_set_text(focuser, DEVICE_PORT_PROPERTY_NAME, DEVICE_PORT_ITEM_NAME, serial_port, INDIGO_OK_STATE, SHORT_TIMEOUT);
}

static double position(void) {
	double value = -1;
	hw_number_item(focuser, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, &value);
	return value;
}

// An absolute move, waited out to its published completion. The controller reports the step count
// it actually executed, so the final position has to match the target exactly.
static bool move_to(double target) {
	unsigned before = hw_revision(focuser, FOCUSER_POSITION_PROPERTY_NAME);
	hw_request_number(focuser, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, target);
	if (!hw_wait_state(focuser, FOCUSER_POSITION_PROPERTY_NAME, before, INDIGO_OK_STATE, MOVE_TIMEOUT)) {
		return false;
	}
	if (!hw_wait_number(focuser, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, target, 0, POLL_TIMEOUT)) {
		return false;
	}
	return true;
}

// A relative move in the given direction, waited out to its published completion.
static bool move_by(const char *direction, double steps) {
	if (!hw_set_switch(focuser, FOCUSER_DIRECTION_PROPERTY_NAME, direction, INDIGO_OK_STATE, SHORT_TIMEOUT)) {
		return false;
	}
	unsigned before = hw_revision(focuser, FOCUSER_STEPS_PROPERTY_NAME);
	hw_request_number(focuser, FOCUSER_STEPS_PROPERTY_NAME, FOCUSER_STEPS_ITEM_NAME, steps);
	return hw_wait_state(focuser, FOCUSER_STEPS_PROPERTY_NAME, before, INDIGO_OK_STATE, MOVE_TIMEOUT);
}

static bool set_speed(double index) {
	return hw_set_number(focuser, FOCUSER_SPEED_PROPERTY_NAME, FOCUSER_SPEED_ITEM_NAME, index, INDIGO_OK_STATE, SHORT_TIMEOUT);
}

static bool capture_initial_state(void) {
	if (!hw_number_item(focuser, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, &initial_position)) {
		return false;
	}
	if (!hw_number_item(focuser, FOCUSER_SPEED_PROPERTY_NAME, FOCUSER_SPEED_ITEM_NAME, &initial_speed)) {
		return false;
	}
	if (!hw_number_item(focuser, X_FOCUSER_DUTY_CYCLE_PROPERTY_NAME, X_FOCUSER_DUTY_CYCLE_ITEM_NAME, &initial_duty_cycle)) {
		return false;
	}
	if (!hw_number_item(focuser, FOCUSER_LIMITS_PROPERTY_NAME, FOCUSER_LIMITS_MIN_POSITION_ITEM_NAME, &initial_limit_min)) {
		return false;
	}
	if (!hw_number_item(focuser, FOCUSER_LIMITS_PROPERTY_NAME, FOCUSER_LIMITS_MAX_POSITION_ITEM_NAME, &initial_limit_max)) {
		return false;
	}
	state_captured = true;
	return true;
}

// Whatever happened above, put the controller back the way the session found it.
static void restore_initial_state(void) {
	if (focuser < 0 || !state_captured || !hw_connected(focuser)) {
		return;
	}
	hw_set_switch(focuser, FOCUSER_ABORT_MOTION_PROPERTY_NAME, FOCUSER_ABORT_MOTION_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT);
	hw_set_switch(focuser, FOCUSER_ON_POSITION_SET_PROPERTY_NAME, FOCUSER_ON_POSITION_SET_GOTO_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT);
	indigo_change_number_property_1(&hw_client, hw_device_name(focuser), FOCUSER_LIMITS_PROPERTY_NAME, FOCUSER_LIMITS_MIN_POSITION_ITEM_NAME, initial_limit_min);
	hw_set_number(focuser, FOCUSER_LIMITS_PROPERTY_NAME, FOCUSER_LIMITS_MAX_POSITION_ITEM_NAME, initial_limit_max, INDIGO_OK_STATE, SHORT_TIMEOUT);
	set_speed(FASTEST_SPEED);
	if (move_to(initial_position)) {
		printf("Restored the starting position %g\n", initial_position);
	}
	set_speed(initial_speed);
	hw_set_number(focuser, X_FOCUSER_DUTY_CYCLE_PROPERTY_NAME, X_FOCUSER_DUTY_CYCLE_ITEM_NAME, initial_duty_cycle, INDIGO_OK_STATE, SHORT_TIMEOUT);
}

