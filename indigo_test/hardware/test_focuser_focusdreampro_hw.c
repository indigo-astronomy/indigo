// The probe is optional: a controller that answers T:false hides the property, and this run says
// which of the two it is instead of failing on a controller without a probe.
static void focusdreampro_reads_the_temperature(void) {
	double temperature = 0;
	if (!hw_property_defined(focuser, FOCUSER_TEMPERATURE_PROPERTY_NAME)) {
		printf("    the controller reports no temperature probe, FOCUSER_TEMPERATURE stays hidden\n");
		return;
	}
	ASSERT_EQ_INT(INDIGO_OK_STATE, hw_property_state(focuser, FOCUSER_TEMPERATURE_PROPERTY_NAME));
	ASSERT_TRUE(hw_number_item(focuser, FOCUSER_TEMPERATURE_PROPERTY_NAME, FOCUSER_TEMPERATURE_ITEM_NAME, &temperature));
	// A probe that is not wired up reads as a rail value, so require something a room can produce.
	ASSERT_TRUE(temperature > -40 && temperature < 80);
	printf("    temperature %.2f C\n", temperature);
	// The polling callback republishes it every second, which is the only evidence that the timer
	// is running at all.
	unsigned before = hw_revision(focuser, FOCUSER_TEMPERATURE_PROPERTY_NAME);
	ASSERT_TRUE(hw_wait_state(focuser, FOCUSER_TEMPERATURE_PROPERTY_NAME, before, INDIGO_OK_STATE, POLL_TIMEOUT));
}

static void focusdreampro_moves_to_an_absolute_position(void) {
	double target = initial_position + travel;
	ASSERT_TRUE(set_speed(FASTEST_SPEED));
	hw_forget_states();
	ASSERT_TRUE(move_to(target));
	// The move must have been published as BUSY before it settled, otherwise a client has no way
	// to tell a running move from a finished one.
	ASSERT_TRUE((hw_states_seen(focuser, FOCUSER_POSITION_PROPERTY_NAME) & (1u << INDIGO_BUSY_STATE)) != 0);
	ASSERT_TRUE(move_to(initial_position));
	ASSERT_NEAR(initial_position, position(), 0);
}

static void focusdreampro_moves_relative_in_both_directions(void) {
	ASSERT_TRUE(set_speed(FASTEST_SPEED));
	ASSERT_TRUE(move_by(FOCUSER_DIRECTION_MOVE_OUTWARD_ITEM_NAME, travel));
	ASSERT_TRUE(hw_wait_number(focuser, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, initial_position + travel, 0, POLL_TIMEOUT));
	ASSERT_TRUE(move_by(FOCUSER_DIRECTION_MOVE_INWARD_ITEM_NAME, travel));
	ASSERT_TRUE(hw_wait_number(focuser, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, initial_position, 0, POLL_TIMEOUT));
	// A zero step request is a no-op that still has to be answered.
	ASSERT_TRUE(move_by(FOCUSER_DIRECTION_MOVE_OUTWARD_ITEM_NAME, 0));
	ASSERT_NEAR(initial_position, position(), 0);
}

// SYNC redefines the coordinate without moving the motor, so the position has to follow the
// request while the drawtube stays put.
static void focusdreampro_syncs_the_position(void) {
	double synced = initial_position + 12345;
	ASSERT_TRUE(hw_set_switch(focuser, FOCUSER_ON_POSITION_SET_PROPERTY_NAME, FOCUSER_ON_POSITION_SET_SYNC_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	unsigned before = hw_revision(focuser, FOCUSER_POSITION_PROPERTY_NAME);
	hw_request_number(focuser, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, synced);
	ASSERT_TRUE(hw_wait_state(focuser, FOCUSER_POSITION_PROPERTY_NAME, before, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(hw_wait_number(focuser, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, synced, 0, POLL_TIMEOUT));
	// Sync back, so the coordinate means what it meant before and nothing has moved either way.
	before = hw_revision(focuser, FOCUSER_POSITION_PROPERTY_NAME);
	hw_request_number(focuser, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, initial_position);
	ASSERT_TRUE(hw_wait_state(focuser, FOCUSER_POSITION_PROPERTY_NAME, before, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(hw_wait_number(focuser, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, initial_position, 0, POLL_TIMEOUT));
	ASSERT_TRUE(hw_set_switch(focuser, FOCUSER_ON_POSITION_SET_PROPERTY_NAME, FOCUSER_ON_POSITION_SET_GOTO_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
}

// The driver clamps an absolute target to FOCUSER_LIMITS before it sends M:, so a target beyond
// the limit has to stop at the limit.
static void focusdreampro_applies_the_travel_limit(void) {
	double limit = initial_position + travel / 2;
	ASSERT_TRUE(set_speed(FASTEST_SPEED));
	indigo_change_number_property_1(&hw_client, hw_device_name(focuser), FOCUSER_LIMITS_PROPERTY_NAME, FOCUSER_LIMITS_MIN_POSITION_ITEM_NAME, initial_limit_min);
	ASSERT_TRUE(hw_set_number(focuser, FOCUSER_LIMITS_PROPERTY_NAME, FOCUSER_LIMITS_MAX_POSITION_ITEM_NAME, limit, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(move_to(limit));
	// Asking for more than the limit must stop at the limit, not at the requested target.
	unsigned before = hw_revision(focuser, FOCUSER_POSITION_PROPERTY_NAME);
	hw_request_number(focuser, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, initial_position + travel);
	ASSERT_TRUE(hw_wait_state(focuser, FOCUSER_POSITION_PROPERTY_NAME, before, INDIGO_OK_STATE, MOVE_TIMEOUT));
	ASSERT_NEAR(limit, position(), 0);
	indigo_change_number_property_1(&hw_client, hw_device_name(focuser), FOCUSER_LIMITS_PROPERTY_NAME, FOCUSER_LIMITS_MIN_POSITION_ITEM_NAME, initial_limit_min);
	ASSERT_TRUE(hw_set_number(focuser, FOCUSER_LIMITS_PROPERTY_NAME, FOCUSER_LIMITS_MAX_POSITION_ITEM_NAME, initial_limit_max, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(move_to(initial_position));
}

// The framework refuses a change while the property is BUSY, so the second request is dropped and
// the focuser has to finish the first move instead of the second one.
static void focusdreampro_rejects_an_overlapping_move(void) {
	double first = initial_position + travel;
	double second = initial_position + travel / 3;
	ASSERT_TRUE(set_speed(SLOWEST_SPEED));
	unsigned before = hw_revision(focuser, FOCUSER_POSITION_PROPERTY_NAME);
	hw_request_number(focuser, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, first);
	ASSERT_TRUE(hw_wait_state(focuser, FOCUSER_POSITION_PROPERTY_NAME, before, INDIGO_BUSY_STATE, SHORT_TIMEOUT));
	hw_request_number(focuser, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, second);
	ASSERT_TRUE(hw_wait_settled(focuser, FOCUSER_POSITION_PROPERTY_NAME, INDIGO_OK_STATE, MOVE_TIMEOUT));
	ASSERT_TRUE(hw_wait_number(focuser, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, first, 0, POLL_TIMEOUT));
	ASSERT_TRUE(set_speed(FASTEST_SPEED));
	ASSERT_TRUE(move_to(initial_position));
}

// Abort has to stop the motor where it is, settle both motion properties to OK rather than alert,
// publish the real stop point and leave the driver able to take a fresh move.
static void focusdreampro_aborts_a_move(void) {
	double target = initial_position + travel;
	ASSERT_TRUE(set_speed(SLOWEST_SPEED));
	unsigned before = hw_revision(focuser, FOCUSER_POSITION_PROPERTY_NAME);
	hw_request_number(focuser, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, target);
	ASSERT_TRUE(hw_wait_state(focuser, FOCUSER_POSITION_PROPERTY_NAME, before, INDIGO_BUSY_STATE, SHORT_TIMEOUT));
	// Let the motor get demonstrably under way before the abort, so a stop point strictly inside
	// the travel proves the abort interrupted a running move.
	indigo_usleep(1500000);
	ASSERT_TRUE(hw_set_switch(focuser, FOCUSER_ABORT_MOTION_PROPERTY_NAME, FOCUSER_ABORT_MOTION_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_EQ_INT(INDIGO_OK_STATE, hw_property_state(focuser, FOCUSER_POSITION_PROPERTY_NAME));
	ASSERT_EQ_INT(INDIGO_OK_STATE, hw_property_state(focuser, FOCUSER_STEPS_PROPERTY_NAME));
	double stopped = position();
	printf("    aborted at %g, between %g and %g\n", stopped, initial_position, target);
	ASSERT_TRUE(stopped > initial_position && stopped < target);
	// The motor really is stopped: the position must not drift over two polling periods.
	indigo_usleep(2500000);
	ASSERT_NEAR(stopped, position(), 0);
	ASSERT_EQ_INT(INDIGO_OK_STATE, hw_property_state(focuser, FOCUSER_POSITION_PROPERTY_NAME));
	// A fresh move after the abort has to be accepted.
	ASSERT_TRUE(set_speed(FASTEST_SPEED));
	ASSERT_TRUE(move_to(initial_position));
}

static void focusdreampro_accepts_an_abort_while_idle(void) {
	ASSERT_NEAR(initial_position, position(), 0);
	ASSERT_TRUE(hw_set_switch(focuser, FOCUSER_ABORT_MOTION_PROPERTY_NAME, FOCUSER_ABORT_MOTION_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_EQ_INT(INDIGO_OK_STATE, hw_property_state(focuser, FOCUSER_POSITION_PROPERTY_NAME));
	ASSERT_EQ_INT(INDIGO_OK_STATE, hw_property_state(focuser, FOCUSER_STEPS_PROPERTY_NAME));
	ASSERT_NEAR(initial_position, position(), 0);
}

// Every speed index has to reach the controller, and the two ends of the table have to differ in
// the time the same move takes, which is the only proof the S: value did anything.
static void focusdreampro_changes_the_speed(void) {
	for (int index = SLOWEST_SPEED; index <= FASTEST_SPEED; index++) {
		ASSERT_TRUE(set_speed(index));
	}
	double distance = travel / 3;
	ASSERT_TRUE(set_speed(FASTEST_SPEED));
	double started = indigo_monotonic_time();
	ASSERT_TRUE(move_to(initial_position + distance));
	double fast = indigo_monotonic_time() - started;
	ASSERT_TRUE(move_to(initial_position));
	ASSERT_TRUE(set_speed(SLOWEST_SPEED));
	started = indigo_monotonic_time();
	ASSERT_TRUE(move_to(initial_position + distance));
	double slow = indigo_monotonic_time() - started;
	printf("    %g steps took %.2f s at index %d and %.2f s at index %d\n", distance, fast, FASTEST_SPEED, slow, SLOWEST_SPEED);
	ASSERT_TRUE(slow > fast);
	ASSERT_TRUE(set_speed(FASTEST_SPEED));
	ASSERT_TRUE(move_to(initial_position));
}

static void focusdreampro_changes_the_duty_cycle(void) {
	double value = 0;
	double changed = initial_duty_cycle >= 50 ? 30 : 70;
	ASSERT_TRUE(hw_set_number(focuser, X_FOCUSER_DUTY_CYCLE_PROPERTY_NAME, X_FOCUSER_DUTY_CYCLE_ITEM_NAME, changed, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(hw_number_item(focuser, X_FOCUSER_DUTY_CYCLE_PROPERTY_NAME, X_FOCUSER_DUTY_CYCLE_ITEM_NAME, &value));
	ASSERT_NEAR(changed, value, 0);
	// The controller has no readback for D:, so the proof that the value survives is that the
	// focuser still moves with it applied.
	ASSERT_TRUE(set_speed(FASTEST_SPEED));
	ASSERT_TRUE(move_to(initial_position + travel / 3));
	ASSERT_TRUE(move_to(initial_position));
	ASSERT_TRUE(hw_set_number(focuser, X_FOCUSER_DUTY_CYCLE_PROPERTY_NAME, X_FOCUSER_DUTY_CYCLE_ITEM_NAME, initial_duty_cycle, INDIGO_OK_STATE, SHORT_TIMEOUT));
}

// Disconnecting while the motor runs has to halt it and tear the connection down cleanly, and the
// driver has to come back and move again afterwards.
static void focusdreampro_survives_a_disconnect_during_a_move(void) {
	ASSERT_TRUE(set_speed(SLOWEST_SPEED));
	unsigned before = hw_revision(focuser, FOCUSER_POSITION_PROPERTY_NAME);
	hw_request_number(focuser, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, initial_position + travel);
	ASSERT_TRUE(hw_wait_state(focuser, FOCUSER_POSITION_PROPERTY_NAME, before, INDIGO_BUSY_STATE, SHORT_TIMEOUT));
	indigo_usleep(1000000);
	ASSERT_TRUE(hw_disconnect(focuser, MOVE_TIMEOUT));
	// The connection-dependent property has to be withdrawn with the connection.
	ASSERT_TRUE(hw_property_hidden(focuser, X_FOCUSER_DUTY_CYCLE_PROPERTY_NAME));
	ASSERT_TRUE(hw_connect(focuser, SHORT_TIMEOUT));
	ASSERT_TRUE(hw_property_defined(focuser, X_FOCUSER_DUTY_CYCLE_PROPERTY_NAME));
	// The disconnect halted the motor, so the controller is somewhere inside the travel and the
	// driver has to have read that position back at connect.
	double stopped = position();
	printf("    the disconnect stopped the motor at %g\n", stopped);
	ASSERT_TRUE(stopped > initial_position && stopped <= initial_position + travel);
	ASSERT_TRUE(set_speed(FASTEST_SPEED));
	ASSERT_TRUE(move_to(initial_position));
}

static void focusdreampro_reconnects(void) {
	ASSERT_TRUE(hw_disconnect(focuser, SHORT_TIMEOUT));
	ASSERT_TRUE(hw_property_hidden(focuser, X_FOCUSER_DUTY_CYCLE_PROPERTY_NAME));
	ASSERT_TRUE(hw_connect(focuser, SHORT_TIMEOUT));
	ASSERT_TRUE(hw_property_defined(focuser, X_FOCUSER_DUTY_CYCLE_PROPERTY_NAME));
	ASSERT_EQ_INT(INDIGO_OK_STATE, hw_property_state(focuser, FOCUSER_POSITION_PROPERTY_NAME));
	ASSERT_NEAR(initial_position, position(), 0);
	ASSERT_TRUE(set_speed(FASTEST_SPEED));
	ASSERT_TRUE(move_to(initial_position + travel / 3));
	ASSERT_TRUE(move_to(initial_position));
}

// A full driver teardown and bring-up, which is what a server does when the driver is unloaded and
// loaded again. It has to leave no device behind and find the controller a second time.
static void focusdreampro_reinitializes(void) {
	ASSERT_TRUE(hw_disconnect(focuser, SHORT_TIMEOUT));
	ASSERT_EQ_INT(INDIGO_OK, indigo_focuser_focusdreampro(INDIGO_DRIVER_SHUTDOWN, NULL));
	ASSERT_EQ_INT(-1, hw_device_index(DEVICE_NAME));
	ASSERT_EQ_INT(INDIGO_OK, indigo_focuser_focusdreampro(INDIGO_DRIVER_INIT, NULL));
	focuser = hw_wait_for_device(DEVICE_NAME, SHORT_TIMEOUT);
	ASSERT_TRUE(focuser >= 0);
	ASSERT_TRUE(select_port());
	ASSERT_TRUE(hw_connect(focuser, SHORT_TIMEOUT));
	ASSERT_NEAR(initial_position, position(), 0);
}

int main(int argc, char **argv) {
	if (argc < 2 || strcmp(argv[1], "--run")) {
		fprintf(stderr, "Physical AstroGadget FocusDreamPro test: run explicitly with --run (or make test-focuser-focusdreampro-hw).\n");
		return 2;
	}
	setvbuf(stdout, NULL, _IONBF, 0);
	for (int i = 2; i < argc; i++) {
		if (!strcmp(argv[i], "--debug")) {
			indigo_set_log_level(INDIGO_LOG_DEBUG);
		}
	}
	// X_FOCUSER_DUTY_CYCLE is persistent, so the session keeps its configuration out of the user's
	// own folder.
	if (!indigo_test_use_private_home()) {
		return 1;
	}
	serial_port = getenv("FOCUSDREAMPRO_HW_PORT");
	const char *requested_travel = getenv("FOCUSDREAMPRO_HW_TRAVEL");
	if (requested_travel != NULL && atoi(requested_travel) > 0) {
		travel = atoi(requested_travel);
	}
	const indigo_test_case tests[] = {
		{ "focusdreampro_reports_identity_and_capabilities", focusdreampro_reports_identity_and_capabilities },
		{ "focusdreampro_publishes_the_property_contract", focusdreampro_publishes_the_property_contract },
		{ "focusdreampro_reads_the_temperature", focusdreampro_reads_the_temperature },
		{ "focusdreampro_moves_to_an_absolute_position", focusdreampro_moves_to_an_absolute_position },
		{ "focusdreampro_moves_relative_in_both_directions", focusdreampro_moves_relative_in_both_directions },
		{ "focusdreampro_syncs_the_position", focusdreampro_syncs_the_position },
		{ "focusdreampro_applies_the_travel_limit", focusdreampro_applies_the_travel_limit },
		{ "focusdreampro_rejects_an_overlapping_move", focusdreampro_rejects_an_overlapping_move },
		{ "focusdreampro_aborts_a_move", focusdreampro_aborts_a_move },
		{ "focusdreampro_accepts_an_abort_while_idle", focusdreampro_accepts_an_abort_while_idle },
		{ "focusdreampro_changes_the_speed", focusdreampro_changes_the_speed },
		{ "focusdreampro_changes_the_duty_cycle", focusdreampro_changes_the_duty_cycle },
		{ "focusdreampro_survives_a_disconnect_during_a_move", focusdreampro_survives_a_disconnect_during_a_move },
		{ "focusdreampro_reconnects", focusdreampro_reconnects },
		{ "focusdreampro_reinitializes", focusdreampro_reinitializes }
	};
	int result = 1;
	bool started = false, initialized = false;
	HW_CHECK(indigo_start() == INDIGO_OK);
	started = true;
	HW_CHECK(hw_attach_client("FocusDreamPro hardware test") == INDIGO_OK);
	HW_CHECK(indigo_focuser_focusdreampro(INDIGO_DRIVER_INIT, NULL) == INDIGO_OK);
	initialized = true;
	focuser = hw_wait_for_device(DEVICE_NAME, SHORT_TIMEOUT);
	HW_CHECK(focuser >= 0);
	HW_CHECK(select_port());
	HW_CHECK(hw_connect(focuser, SHORT_TIMEOUT));
	HW_CHECK(capture_initial_state());
	printf("Starting position %g, speed index %g, duty cycle %g%%, travel %g steps\n", initial_position, initial_speed, initial_duty_cycle, travel);
	result = indigo_run_tests("AstroGadget FocusDreamPro hardware", tests, ARRAY_SIZE(tests));
cleanup:
	// Leave the controller exactly as the session found it, whatever happened above.
	restore_initial_state();
	if (!hw_disconnect(focuser, MOVE_TIMEOUT)) {
		indigo_test_failures++;
	}
	if (initialized && indigo_focuser_focusdreampro(INDIGO_DRIVER_SHUTDOWN, NULL) != INDIGO_OK) {
		indigo_test_failures++;
	}
	indigo_detach_client(&hw_client);
	if (started) {
		indigo_stop();
	}
	hw_release_properties();
	indigo_test_remove_private_home();
	return indigo_test_failures ? 1 : result;
}
