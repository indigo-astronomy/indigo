// Code is generated by AI

// Opt-in acceptance test for a physically connected PegasusAstro DMFC, or for the Arduino sketch
// focuser_dmfc_simulator.ino running on a board. It checks the status line read at the connection, moves to
// absolute positions and by steps both ways, aborts a move, syncs the position, and sets and reads back the
// speed, backlash, direction, LED, encoder and motor type; then it reconnects and runs driver INIT/SHUTDOWN.
//
// THE FOCUSER MOVES. Speed, backlash and motor type are stored in the controller's EEPROM; the session writes back
// every setting and the position it found.
//
// The port comes from DMFC_HW_PORT.

#include <math.h>
#include <stdlib.h>
#include <indigo_drivers/focuser_dmfc/indigo_focuser_dmfc.h>
#include "focuser_hw_common.h"

#define DEVICE_NAME "Pegasus DMFC"

#define SHORT_TIMEOUT 15.0
#define MOVE_TIMEOUT 120.0
#define TRAVEL 2000

static int focuser = -1;
static const char *serial_port = NULL;
static bool state_captured = false, reversed = false, led_on = false, encoder_off = false, stepper = true;
static double initial_position = 0, initial_speed = 0, initial_backlash = 0, base = 0;

static bool select_port(void) {
	if (serial_port == NULL || !*serial_port) {
		fprintf(stderr, "    set DMFC_HW_PORT to the controller's port\n");
		return false;
	}
	printf("Using port %s\n", serial_port);
	return hw_set_text(focuser, DEVICE_PORT_PROPERTY_NAME, DEVICE_PORT_ITEM_NAME, serial_port, INDIGO_OK_STATE, SHORT_TIMEOUT);
}

static bool sync_to(double value) {
	return focuser_hw_set_switch(focuser, FOCUSER_ON_POSITION_SET_PROPERTY_NAME, FOCUSER_ON_POSITION_SET_SYNC_ITEM_NAME, SHORT_TIMEOUT) && focuser_hw_goto(focuser, value, INDIGO_OK_STATE, SHORT_TIMEOUT) && focuser_hw_set_switch(focuser, FOCUSER_ON_POSITION_SET_PROPERTY_NAME, FOCUSER_ON_POSITION_SET_GOTO_ITEM_NAME, SHORT_TIMEOUT);
}

static bool set_number(const char *property, const char *item, double value) {
	return focuser_hw_set_number(focuser, property, item, value, INDIGO_OK_STATE, SHORT_TIMEOUT) && focuser_hw_value(focuser, property, item) == value;
}

static void restore_initial_state(void) {
	if (focuser < 0 || !state_captured || !hw_connected(focuser)) {
		return;
	}
	focuser_hw_idle(focuser, FOCUSER_POSITION_PROPERTY_NAME, MOVE_TIMEOUT);
	if (focuser_hw_switch_is(focuser, FOCUSER_ON_POSITION_SET_PROPERTY_NAME, FOCUSER_ON_POSITION_SET_SYNC_ITEM_NAME)) {
		focuser_hw_set_switch(focuser, FOCUSER_ON_POSITION_SET_PROPERTY_NAME, FOCUSER_ON_POSITION_SET_GOTO_ITEM_NAME, SHORT_TIMEOUT);
	}
	focuser_hw_set_switch(focuser, FOCUSER_REVERSE_MOTION_PROPERTY_NAME, reversed ? FOCUSER_REVERSE_MOTION_ENABLED_ITEM_NAME : FOCUSER_REVERSE_MOTION_DISABLED_ITEM_NAME, SHORT_TIMEOUT);
	focuser_hw_set_switch(focuser, "X_FOCUSER_LED", led_on ? "ENABLED" : "DISABLED", SHORT_TIMEOUT);
	focuser_hw_set_switch(focuser, "X_FOCUSER_ENCODER", encoder_off ? "DISABLED" : "ENABLED", SHORT_TIMEOUT);
	focuser_hw_set_switch(focuser, "X_FOCUSER_MOTOR_TYPE", stepper ? "STEPPER" : "DC", SHORT_TIMEOUT);
	set_number(FOCUSER_BACKLASH_PROPERTY_NAME, FOCUSER_BACKLASH_ITEM_NAME, initial_backlash);
	set_number(FOCUSER_SPEED_PROPERTY_NAME, FOCUSER_SPEED_ITEM_NAME, initial_speed);
	focuser_hw_goto(focuser, initial_position, INDIGO_OK_STATE, MOVE_TIMEOUT);
}

static void dmfc_publishes_the_status(void) {
	char model[INDIGO_VALUE_SIZE] = "", firmware[INDIGO_VALUE_SIZE] = "";
	ASSERT_TRUE((hw_device_interface(focuser) & INDIGO_INTERFACE_FOCUSER) != 0);
	ASSERT_TRUE(hw_text_item(focuser, INFO_PROPERTY_NAME, INFO_DEVICE_MODEL_ITEM_NAME, model, sizeof(model)));
	ASSERT_TRUE(hw_text_item(focuser, INFO_PROPERTY_NAME, INFO_DEVICE_FW_REVISION_ITEM_NAME, firmware, sizeof(firmware)));
	double temperature = focuser_hw_value(focuser, FOCUSER_TEMPERATURE_PROPERTY_NAME, FOCUSER_TEMPERATURE_ITEM_NAME);
	printf("    %s firmware %s, position %g, speed %g, backlash %g, %.1f C, %s motor, LED %s, encoder %s, %s\n", model, firmware, initial_position, initial_speed, initial_backlash, temperature, stepper ? "stepper" : "DC", led_on ? "on" : "off", encoder_off ? "off" : "on", reversed ? "reversed" : "normal");
	ASSERT_TRUE(*model && *firmware && strcmp(firmware, "Unknown"));
	ASSERT_TRUE(initial_speed >= 100 && initial_speed <= 1000);
	// -127 or an out-of-range value marks a missing probe, which leaves the property in ALERT.
	ASSERT_TRUE(hw_property_state(focuser, FOCUSER_TEMPERATURE_PROPERTY_NAME) == INDIGO_ALERT_STATE || (temperature > -55 && temperature < 125));
	static const char *properties[] = { "X_FOCUSER_MOTOR_TYPE", "X_FOCUSER_ENCODER", "X_FOCUSER_LED", FOCUSER_BACKLASH_PROPERTY_NAME, FOCUSER_REVERSE_MOTION_PROPERTY_NAME, FOCUSER_SPEED_PROPERTY_NAME, FOCUSER_ABORT_MOTION_PROPERTY_NAME, FOCUSER_LIMITS_PROPERTY_NAME };
	for (int i = 0; i < ARRAY_SIZE(properties); i++) {
		ASSERT_TRUE(hw_property_defined(focuser, properties[i]));
	}
}

static void dmfc_moves_to_absolute_positions(void) {
	ASSERT_TRUE(set_number(FOCUSER_SPEED_PROPERTY_NAME, FOCUSER_SPEED_ITEM_NAME, 1000));
	ASSERT_TRUE(focuser_hw_goto(focuser, base + TRAVEL, INDIGO_OK_STATE, MOVE_TIMEOUT));
	ASSERT_TRUE(focuser_hw_goto(focuser, base + 13, INDIGO_OK_STATE, MOVE_TIMEOUT));
	ASSERT_TRUE(focuser_hw_goto(focuser, base, INDIGO_OK_STATE, MOVE_TIMEOUT));
	ASSERT_TRUE(focuser_hw_goto(focuser, base, INDIGO_OK_STATE, SHORT_TIMEOUT));
}

// The Pegasus drivers count an inward move as increasing the position (G:+n), the opposite of most focusers, so
// the steps are checked by distance and by the way back.
static void dmfc_moves_by_steps(void) {
	ASSERT_TRUE(focuser_hw_steps(focuser, true, 300, INDIGO_OK_STATE, MOVE_TIMEOUT));
	double outward = focuser_hw_position(focuser);
	ASSERT_EQ_INT(300, abs((int)(outward - base)));
	ASSERT_TRUE(focuser_hw_steps(focuser, false, 300, INDIGO_OK_STATE, MOVE_TIMEOUT));
	ASSERT_EQ_INT((int)base, (int)focuser_hw_position(focuser));
	ASSERT_TRUE(focuser_hw_steps(focuser, false, 300, INDIGO_OK_STATE, MOVE_TIMEOUT));
	ASSERT_EQ_INT((int)(2 * base - outward), (int)focuser_hw_position(focuser));
	ASSERT_TRUE(focuser_hw_goto(focuser, base, INDIGO_OK_STATE, MOVE_TIMEOUT));
}

static void dmfc_aborts_a_move(void) {
	ASSERT_TRUE(set_number(FOCUSER_SPEED_PROPERTY_NAME, FOCUSER_SPEED_ITEM_NAME, 100));
	ASSERT_TRUE(focuser_hw_start_goto(focuser, base + TRAVEL, SHORT_TIMEOUT));
	indigo_usleep(2500000);
	ASSERT_TRUE(focuser_hw_abort(focuser, SHORT_TIMEOUT));
	ASSERT_TRUE(focuser_hw_idle(focuser, FOCUSER_POSITION_PROPERTY_NAME, SHORT_TIMEOUT));
	indigo_usleep(1500000);
	double stopped = focuser_hw_position(focuser);
	printf("    stopped at %g on the way from %g to %g, state %d\n", stopped, base, base + TRAVEL, hw_property_state(focuser, FOCUSER_POSITION_PROPERTY_NAME));
	ASSERT_TRUE(stopped > base && stopped < base + TRAVEL);
	indigo_usleep(1500000);
	ASSERT_EQ_INT((int)stopped, (int)focuser_hw_position(focuser));
	// the idle polls keep the requested target
	double target = NAN;
	ASSERT_TRUE(hw_number_item_target(focuser, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, &target));
	ASSERT_EQ_INT((int)(base + TRAVEL), (int)target);
	ASSERT_TRUE(set_number(FOCUSER_SPEED_PROPERTY_NAME, FOCUSER_SPEED_ITEM_NAME, 1000));
	ASSERT_TRUE(focuser_hw_goto(focuser, base, INDIGO_OK_STATE, MOVE_TIMEOUT));
}

static void dmfc_syncs_the_position(void) {
	ASSERT_TRUE(sync_to(base + 500));
	ASSERT_EQ_INT((int)base + 500, (int)focuser_hw_position(focuser));
	indigo_usleep(1500000);
	ASSERT_EQ_INT((int)base + 500, (int)focuser_hw_position(focuser));
	ASSERT_TRUE(sync_to(base));
}

