	ASSERT_EQ_INT(0, (int)focuser_hw_value(focuser, FOCUSER_BACKLASH_PROPERTY_NAME, FOCUSER_BACKLASH_ITEM_NAME));
	ASSERT_TRUE(focuser_hw_switch_is(focuser, FOCUSER_REVERSE_MOTION_PROPERTY_NAME, reversed ? FOCUSER_REVERSE_MOTION_DISABLED_ITEM_NAME : FOCUSER_REVERSE_MOTION_ENABLED_ITEM_NAME));
	ASSERT_TRUE(focuser_hw_switch_is(focuser, "X_FOCUSER_LED", led_on ? "DISABLED" : "ENABLED"));
	ASSERT_TRUE(focuser_hw_switch_is(focuser, "X_FOCUSER_ENCODER", encoder_off ? "ENABLED" : "DISABLED"));
	ASSERT_TRUE(focuser_hw_switch_is(focuser, "X_FOCUSER_MOTOR_TYPE", stepper ? "DC" : "STEPPER"));
	ASSERT_TRUE(focuser_hw_set_switch(focuser, "X_FOCUSER_MOTOR_TYPE", stepper ? "STEPPER" : "DC", SHORT_TIMEOUT));
	ASSERT_TRUE(focuser_hw_set_switch(focuser, "X_FOCUSER_ENCODER", encoder_off ? "DISABLED" : "ENABLED", SHORT_TIMEOUT));
	ASSERT_TRUE(focuser_hw_set_switch(focuser, "X_FOCUSER_LED", led_on ? "ENABLED" : "DISABLED", SHORT_TIMEOUT));
	ASSERT_TRUE(focuser_hw_set_switch(focuser, FOCUSER_REVERSE_MOTION_PROPERTY_NAME, reversed ? FOCUSER_REVERSE_MOTION_ENABLED_ITEM_NAME : FOCUSER_REVERSE_MOTION_DISABLED_ITEM_NAME, SHORT_TIMEOUT));
