static bool fresh_site_readback(void) {
	pthread_mutex_lock(&edge_mutex);
	unsigned before = site_queries;
	pthread_mutex_unlock(&edge_mutex);
	double deadline = indigo_monotonic_time() + 15;
	while (indigo_monotonic_time() < deadline) {
		pthread_mutex_lock(&edge_mutex);
		bool completed = site_queries >= before + 2;
		pthread_mutex_unlock(&edge_mutex);
		if (completed) {
			return true;
		}
		indigo_usleep(20000);
	}
	return false;
}

