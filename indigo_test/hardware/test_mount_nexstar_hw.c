static void nexstar_current_park_and_unpark(void) {
	double ra, dec, ha, park_dec;
	ASSERT_TRUE(fresh_position(&ra, &dec));
	ASSERT_TRUE(hw_set_switch(mount, MOUNT_PARK_SET_PROPERTY_NAME, MOUNT_PARK_SET_CURRENT_ITEM_NAME, INDIGO_OK_STATE, 10));
	ASSERT_TRUE(hw_number_item(mount, MOUNT_PARK_POSITION_PROPERTY_NAME, MOUNT_PARK_POSITION_HA_ITEM_NAME, &ha));
	ASSERT_TRUE(hw_number_item(mount, MOUNT_PARK_POSITION_PROPERTY_NAME, MOUNT_PARK_POSITION_DEC_ITEM_NAME, &park_dec));
	ASSERT_TRUE(hw_disconnect(mount, 20));
	int descriptor = open_telescope(getenv("MOUNT_NEXSTAR_HW_PORT"));
	ASSERT_TRUE(descriptor >= 0);
	double axis_ra, axis_dec;
	int status = _tc_get_azalt(descriptor, &axis_ra, &axis_dec, 1);
	close_telescope(descriptor);
	ASSERT_EQ_INT(0, status);
	ASSERT_TRUE(hw_connect(mount, 30));
	printf("Current park encoded axes %.6f %.6f controller axes %.6f %.6f\n", (ha + 12) * 15, park_dec, axis_ra, axis_dec);
	// Refuse an unexpected large park movement: CURRENT must describe the current axes.
	ASSERT_TRUE(fabs(remainder((ha + 12) * 15 - axis_ra, 360)) < 3);
	ASSERT_TRUE(fabs(remainder(park_dec - axis_dec, 360)) < 3);
	unsigned before = hw_revision(mount, MOUNT_PARK_PROPERTY_NAME);
	hw_request_switch(mount, MOUNT_PARK_PROPERTY_NAME, MOUNT_PARK_PARKED_ITEM_NAME, true);
	ASSERT_TRUE(hw_wait_state(mount, MOUNT_PARK_PROPERTY_NAME, before, INDIGO_OK_STATE, 90));
	ASSERT_TRUE(selected(mount, MOUNT_PARK_PROPERTY_NAME, MOUNT_PARK_PARKED_ITEM_NAME));
	ASSERT_TRUE(selected(mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_OFF_ITEM_NAME));
	ASSERT_TRUE(hw_set_switch(mount, MOUNT_PARK_PROPERTY_NAME, MOUNT_PARK_UNPARKED_ITEM_NAME, INDIGO_OK_STATE, 10));
	ASSERT_TRUE(hw_disconnect(mount, 20));
	descriptor = open_telescope(getenv("MOUNT_NEXSTAR_HW_PORT"));
	ASSERT_TRUE(descriptor >= 0);
	double parked_ra, parked_dec;
	status = _tc_get_azalt(descriptor, &parked_ra, &parked_dec, 1);
	close_telescope(descriptor);
	ASSERT_EQ_INT(0, status);
	printf("Park arrival axes %.6f %.6f\n", parked_ra, parked_dec);
	ASSERT_TRUE(fabs(remainder(parked_ra - axis_ra, 360)) < 0.15);
	ASSERT_TRUE(fabs(remainder(parked_dec - axis_dec, 360)) < 0.15);
	ASSERT_TRUE(hw_connect(mount, 30));
	ASSERT_TRUE(hw_set_switch(mount, "TRACKING_MODE", "EQ", INDIGO_OK_STATE, 10));
	ASSERT_TRUE(hw_set_switch(mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_ON_ITEM_NAME, INDIGO_OK_STATE, 10));
	ASSERT_TRUE(fresh_position(&ra, &dec));
}

static void nexstar_gps_presence_and_sibling_survival(void) {
	gps = hw_wait_for_device("Mount Nexstar (gps)", 10);
	ASSERT_TRUE(gps >= 0);
	unsigned before = hw_revision(gps, CONNECTION_PROPERTY_NAME);
	hw_request_switch(gps, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, true);
	double deadline = indigo_monotonic_time() + 20;
	while (indigo_monotonic_time() < deadline && (hw_revision(gps, CONNECTION_PROPERTY_NAME) <= before || hw_property_state(gps, CONNECTION_PROPERTY_NAME) == INDIGO_BUSY_STATE)) {
		indigo_usleep(20000);
	}
	if (hw_connected(gps)) {
		ASSERT_TRUE(hw_device_interface(gps) & INDIGO_INTERFACE_GPS);
		ASSERT_TRUE(hw_property_defined(gps, GPS_STATUS_PROPERTY_NAME));
		char firmware[INDIGO_VALUE_SIZE];
		ASSERT_TRUE(hw_text_item(gps, INFO_PROPERTY_NAME, INFO_DEVICE_FW_REVISION_ITEM_NAME, firmware, sizeof(firmware)));
		ASSERT_TRUE(firmware[0] && strcmp(firmware, "N/A"));
		indigo_property_state no_fix = INDIGO_IDLE_STATE, fix_3d = INDIGO_IDLE_STATE;
		deadline = indigo_monotonic_time() + 15;
		do {
			hw_light_item(gps, GPS_STATUS_PROPERTY_NAME, GPS_STATUS_NO_FIX_ITEM_NAME, &no_fix);
			hw_light_item(gps, GPS_STATUS_PROPERTY_NAME, GPS_STATUS_3D_FIX_ITEM_NAME, &fix_3d);
			if (no_fix == INDIGO_ALERT_STATE || fix_3d == INDIGO_OK_STATE) {
				break;
			}
			indigo_usleep(20000);
		} while (indigo_monotonic_time() < deadline);
		ASSERT_TRUE(no_fix == INDIGO_ALERT_STATE || fix_3d == INDIGO_OK_STATE);
		printf("GPS accessory detected: firmware %s, status %s; fix accuracy not tested\n", firmware, fix_3d == INDIGO_OK_STATE ? "3D fix" : "no fix");
		ASSERT_TRUE(hw_disconnect(gps, 15));
	} else {
		ASSERT_EQ_INT(INDIGO_ALERT_STATE, hw_property_state(gps, CONNECTION_PROPERTY_NAME));
		printf("GPS accessory absent: rejection verified, fix acquisition not applicable\n");
		ASSERT_TRUE(!gps_only);
	}
	double ra, dec;
	ASSERT_TRUE(fresh_position(&ra, &dec));
}

static void nexstar_refused_port_and_driver_reinitialization(void) {
	ASSERT_TRUE(hw_disconnect(mount, 20));
	ASSERT_TRUE(hw_set_text(mount, DEVICE_PORT_PROPERTY_NAME, DEVICE_PORT_ITEM_NAME, "/dev/null", INDIGO_OK_STATE, 10));
	ASSERT_TRUE(hw_set_switch(mount, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, INDIGO_ALERT_STATE, 15));
	ASSERT_TRUE(!hw_connected(mount));
	ASSERT_TRUE(hw_set_text(mount, DEVICE_PORT_PROPERTY_NAME, DEVICE_PORT_ITEM_NAME, getenv("MOUNT_NEXSTAR_HW_PORT"), INDIGO_OK_STATE, 10));
	ASSERT_TRUE(hw_connect(mount, 30));
	double ra, dec;
	ASSERT_TRUE(fresh_position(&ra, &dec));
	ASSERT_TRUE(hw_disconnect(mount, 20));
	ASSERT_EQ_INT(INDIGO_OK, indigo_mount_nexstar(INDIGO_DRIVER_SHUTDOWN, NULL));
	ASSERT_EQ_INT(INDIGO_OK, indigo_mount_nexstar(INDIGO_DRIVER_INIT, NULL));
	mount = hw_wait_for_device("Mount Nexstar", 10);
	ASSERT_TRUE(mount >= 0);
	ASSERT_TRUE(hw_set_text(mount, DEVICE_PORT_PROPERTY_NAME, DEVICE_PORT_ITEM_NAME, getenv("MOUNT_NEXSTAR_HW_PORT"), INDIGO_OK_STATE, 10));
	ASSERT_TRUE(hw_connect(mount, 30));
	ASSERT_TRUE(fresh_position(&ra, &dec));
}

int main(int argc, char **argv) {
	if (argc != 2 || (strcmp(argv[1], "--identity") && strcmp(argv[1], "--run") && strcmp(argv[1], "--gps"))) {
		fprintf(stderr, "Use --identity, --gps or --run with MOUNT_NEXSTAR_HW_PORT set.\n");
		return 2;
	}
	const char *port = getenv("MOUNT_NEXSTAR_HW_PORT");
	if (port == NULL || !indigo_test_use_private_home()) {
		return 2;
	}
	gps_only = !strcmp(argv[1], "--gps");
	setvbuf(stdout, NULL, _IONBF, 0);
	indigo_set_log_level(INDIGO_LOG_DEBUG);
	tc_debug = protocol_log;
	bool started = false, initialized = false, attached = false;
	int result = 1;
	HW_CHECK(indigo_start() == INDIGO_OK);
	started = true;
	HW_CHECK(hw_attach_client("NexStar hardware acceptance") == INDIGO_OK);
	attached = true;
	HW_CHECK(indigo_mount_nexstar(INDIGO_DRIVER_INIT, NULL) == INDIGO_OK);
	initialized = true;
	mount = hw_wait_for_device("Mount Nexstar", 10);
	HW_CHECK(mount >= 0);
	HW_CHECK(hw_set_text(mount, DEVICE_PORT_PROPERTY_NAME, DEVICE_PORT_ITEM_NAME, port, INDIGO_OK_STATE, 10));
	HW_CHECK(hw_connect(mount, 45));
	const indigo_test_case tests[] = {
		{ "nexstar_identity_and_readback", nexstar_identity_and_readback },
		{ "nexstar_wedge_mode_and_property_contract", nexstar_wedge_mode_and_property_contract },
		{ "nexstar_site_clock_and_tracking", nexstar_site_clock_and_tracking },
		{ "nexstar_sync_and_small_goto", nexstar_sync_and_small_goto },
		{ "nexstar_manual_rates_directions_and_abort", nexstar_manual_rates_directions_and_abort },
		{ "nexstar_goto_abort_and_recovery", nexstar_goto_abort_and_recovery },
		{ "nexstar_guider_directions_replacement_and_axes", nexstar_guider_directions_replacement_and_axes },
		{ "nexstar_shared_connection_orders_and_pending_disconnect", nexstar_shared_connection_orders_and_pending_disconnect },
		{ "nexstar_guider_transport_timing", nexstar_guider_transport_timing },
		{ "nexstar_current_park_and_unpark", nexstar_current_park_and_unpark },
		{ "nexstar_gps_presence_and_sibling_survival", nexstar_gps_presence_and_sibling_survival },
		{ "nexstar_refused_port_and_driver_reinitialization", nexstar_refused_port_and_driver_reinitialization }
	};
	result = 0;
	int count = !strcmp(argv[1], "--identity") ? 1 : ARRAY_SIZE(tests);
	for (int i = 0; i < count; i++) {
		if (gps_only && tests[i].function != nexstar_gps_presence_and_sibling_survival) {
			continue;
		}
		result = indigo_run_tests("NexStar physical hardware", tests + i, 1);
		if (result) {
			break;
		}
	}
cleanup:
	if (gps >= 0 && !hw_disconnect(gps, 20)) {
		indigo_test_failures++;
	}
	if (guider >= 0 && !hw_disconnect(guider, 20)) {
		indigo_test_failures++;
	}
	if (!strcmp(argv[1], "--run") && mount >= 0 && hw_connected(mount)) {
		if (!hw_set_switch(mount, MOUNT_ABORT_MOTION_PROPERTY_NAME, MOUNT_ABORT_MOTION_ITEM_NAME, INDIGO_OK_STATE, 15)) {
			indigo_test_failures++;
		}
	}
	if (site_captured && mount >= 0 && hw_connected(mount)) {
		unsigned before = hw_revision(mount, GEOGRAPHIC_COORDINATES_PROPERTY_NAME);
		indigo_change_number_property(&hw_client, hw_device_name(mount), GEOGRAPHIC_COORDINATES_PROPERTY_NAME, 2, (const char *[]){ GEOGRAPHIC_COORDINATES_LATITUDE_ITEM_NAME, GEOGRAPHIC_COORDINATES_LONGITUDE_ITEM_NAME }, original_site);
		if (!hw_wait_state(mount, GEOGRAPHIC_COORDINATES_PROPERTY_NAME, before, INDIGO_OK_STATE, 10)) {
			indigo_test_failures++;
		}
	}
	if (mount >= 0 && !hw_disconnect(mount, 45)) {
		indigo_test_failures++;
	}
	if (initialized && indigo_mount_nexstar(INDIGO_DRIVER_SHUTDOWN, NULL) != INDIGO_OK) {
		indigo_test_failures++;
	}
	if (attached) {
		indigo_detach_client(&hw_client);
	}
	if (started) {
		indigo_stop();
	}
	hw_release_properties();
	indigo_test_remove_private_home();
	return indigo_test_failures ? 1 : result;
}
