static void protocol_log(const char *format, ...) {
	double timestamp = indigo_monotonic_time();
	va_list arguments;
	va_start(arguments, format);
	char line[1024];
	vsnprintf(line, sizeof(line), format, arguments);
	fprintf(stderr, "%s", line);
	unsigned bytes[8];
	if (sscanf(line, "libnexstar: write %x %x %x %x %x %x %x %x", bytes, bytes + 1, bytes + 2, bytes + 3, bytes + 4, bytes + 5, bytes + 6, bytes + 7) == 8 && bytes[0] == 0x50 && bytes[1] == 2 && (bytes[2] == 16 || bytes[2] == 17) && (bytes[3] == 0x24 || bytes[3] == 0x25)) {
		int axis = bytes[2] - 16;
		pthread_mutex_lock(&edge_mutex);
		if (bytes[4]) {
			edge_on[axis] = timestamp;
		} else if (edge_on[axis] && !edge_off[axis]) {
			edge_off[axis] = timestamp;
		}
		pthread_mutex_unlock(&edge_mutex);
	}
	if (!strcmp(line, "libnexstar: write 77")) {
		pthread_mutex_lock(&edge_mutex);
		site_queries++;
		pthread_mutex_unlock(&edge_mutex);
	}
	va_end(arguments);
	fputc('\n', stderr);
}

