static bool coordinates(double ra, double dec, bool sync) {
	if (!hw_set_switch(mount, MOUNT_ON_COORDINATES_SET_PROPERTY_NAME, sync ? MOUNT_ON_COORDINATES_SET_SYNC_ITEM_NAME : MOUNT_ON_COORDINATES_SET_TRACK_ITEM_NAME, INDIGO_OK_STATE, 10)) {
		return false;
	}
	unsigned before = hw_revision(mount, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME);
	indigo_change_number_property(&hw_client, hw_device_name(mount), MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, 2, (const char *[]){ MOUNT_EQUATORIAL_COORDINATES_RA_ITEM_NAME, MOUNT_EQUATORIAL_COORDINATES_DEC_ITEM_NAME }, (double[]){ ra, dec });
	if (!hw_wait_state(mount, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, before, INDIGO_OK_STATE, 90)) {
		return false;
	}
	double actual_ra, actual_dec;
	if (!fresh_position(&actual_ra, &actual_dec)) {
		return false;
	}
	double error = hypot(remainder(actual_ra - ra, 24) * 15 * cos(dec * M_PI / 180), actual_dec - dec);
	printf("Arrival requested %.7f %.7f readback %.7f %.7f error_deg %.6f\n", ra, dec, actual_ra, actual_dec, error);
	return error < 0.15;
}

