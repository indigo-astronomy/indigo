static int compare_error(const void *a, const void *b) {
	double left = *(const double *)a, right = *(const double *)b;
	return (left > right) - (left < right);
}

static void nexstar_guider_transport_timing(void) {
	ASSERT_TRUE(hw_connect(guider, 20));
	const int durations[] = { 20, 100, 500 };
	for (int workload = 0; workload < 2; workload++) {
		ASSERT_TRUE(hw_set_switch(mount, MOUNT_TRACKING_PROPERTY_NAME, workload ? MOUNT_TRACKING_ON_ITEM_NAME : MOUNT_TRACKING_OFF_ITEM_NAME, INDIGO_OK_STATE, 10));
		for (int direction = 0; direction < 4; direction++) {
			for (int duration = 0; duration < ARRAY_SIZE(durations); duration++) {
				double errors[4], sum = 0, squares = 0, absolute = 0;
				for (int repeat = -1; repeat < 4; repeat++) {
					pthread_mutex_lock(&edge_mutex);
					edge_on[direction / 2] = edge_off[direction / 2] = 0;
					pthread_mutex_unlock(&edge_mutex);
					ASSERT_TRUE(pulse(direction, durations[duration], true));
					pthread_mutex_lock(&edge_mutex);
					double on = edge_on[direction / 2], off = edge_off[direction / 2];
					pthread_mutex_unlock(&edge_mutex);
					ASSERT_TRUE(on > 0 && off >= on);
					if (repeat >= 0) {
						double error = 1000 * (off - on) - durations[duration];
						errors[repeat] = error;
						sum += error;
						squares += error * error;
						absolute = fmax(absolute, fabs(error));
					}
				}
				qsort(errors, 4, sizeof(double), compare_error);
				double mean = sum / 4;
				printf("GUIDE_TIMING tracking=%d direction=%s requested_ms=%d n=4 actual_mean_ms=%.3f signed_error_ms min=%.3f mean=%.3f median=%.3f p95=%.3f p99=%.3f max=%.3f sd=%.3f max_abs=%.3f mean_percent=%.3f\n", workload, guide_directions[direction], durations[duration], durations[duration] + mean, errors[0], mean, (errors[1] + errors[2]) / 2, errors[3], errors[3], errors[3], sqrt(fmax(0, squares / 4 - mean * mean)), absolute, mean * 100 / durations[duration]);
			}
		}
	}
	ASSERT_TRUE(hw_set_switch(mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_ON_ITEM_NAME, INDIGO_OK_STATE, 10));
	ASSERT_TRUE(hw_disconnect(guider, 20));
}

