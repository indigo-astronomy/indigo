static void synscan_tracking_and_rates(void) {
	ASSERT_TRUE(prepare_mount());
	ASSERT_TRUE(set_switch(mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_ON_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	indigo_property_state tracking_light = INDIGO_IDLE_STATE;
	pthread_mutex_lock(&mutex);
	int p = slot(mount, MOUNT_STATE_PROPERTY_NAME);
	if (p >= 0) {
		indigo_property *property = devices[mount].properties[p];
		for (int i = 0; i < property->count; i++) {
			if (!strcmp(property->items[i].name, MOUNT_STATE_TRACKING_ITEM_NAME)) {
				tracking_light = property->items[i].light.value;
			}
		}
	}
	pthread_mutex_unlock(&mutex);
	ASSERT_TRUE(tracking_light == INDIGO_BUSY_STATE || tracking_light == INDIGO_OK_STATE);
	// A tracking RA axis holds the sky, so the reported right ascension must stand still.
	double tracking_drift = 0, idle_drift = 0;
	ASSERT_TRUE(measure_ra_drift(12.0, &tracking_drift));
	printf("    tracking for 12 s: RA moved %.5f degrees\n", tracking_drift);
	ASSERT_TRUE(fabs(tracking_drift) < 0.01);
	ASSERT_TRUE(set_switch(mount, MOUNT_TRACK_RATE_PROPERTY_NAME, MOUNT_TRACK_RATE_SOLAR_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(set_switch(mount, MOUNT_TRACK_RATE_PROPERTY_NAME, MOUNT_TRACK_RATE_LUNAR_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(set_switch(mount, MOUNT_TRACK_RATE_PROPERTY_NAME, MOUNT_TRACK_RATE_SIDEREAL_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(set_switch(mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_OFF_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	// A stopped RA axis holds its hour angle instead, so the sky runs away at the sidereal rate
	// of 0.05 degrees over 12 s.
	ASSERT_TRUE(measure_ra_drift(12.0, &idle_drift));
	printf("    idle for 12 s: RA moved %.5f degrees, sidereal is 0.050\n", idle_drift);
	ASSERT_NEAR(0.050, fabs(idle_drift), 0.02);
	static const char *guide_items[] = { MOUNT_GUIDE_RATE_RA_ITEM_NAME, MOUNT_GUIDE_RATE_DEC_ITEM_NAME };
	double guide_values[] = { 30, 70 };
	unsigned before = revision(mount, MOUNT_GUIDE_RATE_PROPERTY_NAME);
	indigo_change_number_property(&client, devices[mount].name, MOUNT_GUIDE_RATE_PROPERTY_NAME, 2, guide_items, guide_values);
	ASSERT_TRUE(wait_state(mount, MOUNT_GUIDE_RATE_PROPERTY_NAME, before, INDIGO_OK_STATE, SHORT_TIMEOUT));
	double ra_rate = 0, dec_rate = 0;
	ASSERT_TRUE(number_item(mount, MOUNT_GUIDE_RATE_PROPERTY_NAME, MOUNT_GUIDE_RATE_RA_ITEM_NAME, &ra_rate));
	ASSERT_TRUE(number_item(mount, MOUNT_GUIDE_RATE_PROPERTY_NAME, MOUNT_GUIDE_RATE_DEC_ITEM_NAME, &dec_rate));
	ASSERT_NEAR(30, ra_rate, 0.5);
	ASSERT_NEAR(70, dec_rate, 0.5);
	guide_values[0] = initial_guide_ra;
	guide_values[1] = initial_guide_dec;
	before = revision(mount, MOUNT_GUIDE_RATE_PROPERTY_NAME);
	indigo_change_number_property(&client, devices[mount].name, MOUNT_GUIDE_RATE_PROPERTY_NAME, 2, guide_items, guide_values);
	ASSERT_TRUE(wait_state(mount, MOUNT_GUIDE_RATE_PROPERTY_NAME, before, INDIGO_OK_STATE, SHORT_TIMEOUT));
	if (property_defined(mount, MOUNT_POLARSCOPE_PROPERTY_NAME)) {
		ASSERT_TRUE(set_number(mount, MOUNT_POLARSCOPE_PROPERTY_NAME, MOUNT_POLARSCOPE_BRIGHTNESS_ITEM_NAME, 128, INDIGO_OK_STATE, SHORT_TIMEOUT));
		ASSERT_TRUE(set_number(mount, MOUNT_POLARSCOPE_PROPERTY_NAME, MOUNT_POLARSCOPE_BRIGHTNESS_ITEM_NAME, 0, INDIGO_OK_STATE, SHORT_TIMEOUT));
	}
}

// Manual motion is checked in both directions on both axes at a rate that is fast enough to move
// measurably within a couple of seconds but slow enough to stay within a few degrees.
static bool manual_motion_moves(const char *property, const char *item, bool use_ra, double *travel) {
	double before_ra = 0, before_dec = 0, after_ra = 0, after_dec = 0;
	if (!number_item(mount, MOUNT_RAW_COORDINATES_PROPERTY_NAME, MOUNT_RAW_COORDINATES_RA_ITEM_NAME, &before_ra) || !number_item(mount, MOUNT_RAW_COORDINATES_PROPERTY_NAME, MOUNT_RAW_COORDINATES_DEC_ITEM_NAME, &before_dec)) {
		return false;
	}
	if (!set_switch(mount, property, item, INDIGO_OK_STATE, SHORT_TIMEOUT)) {
		return false;
	}
	indigo_usleep(3000000);
	bool stopped = set_switch(mount, property, use_ra ? MOUNT_MOTION_WEST_ITEM_NAME : MOUNT_MOTION_NORTH_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT);
	// Releasing both direction switches is what stops the axis; INDIGO_AT_MOST_ONE_OF_MANY_RULE
	// lets the same item be sent with value false.
	indigo_change_switch_property_1(&client, devices[mount].name, property, use_ra ? MOUNT_MOTION_WEST_ITEM_NAME : MOUNT_MOTION_NORTH_ITEM_NAME, false);
	stopped = wait_settled(mount, property, INDIGO_OK_STATE, SHORT_TIMEOUT) && stopped;
	indigo_usleep(1000000);
	if (!number_item(mount, MOUNT_RAW_COORDINATES_PROPERTY_NAME, MOUNT_RAW_COORDINATES_RA_ITEM_NAME, &after_ra) || !number_item(mount, MOUNT_RAW_COORDINATES_PROPERTY_NAME, MOUNT_RAW_COORDINATES_DEC_ITEM_NAME, &after_dec)) {
		return false;
	}
	*travel = use_ra ? ra_difference(after_ra, before_ra) * 15.0 : after_dec - before_dec;
	printf("    %s %s moved %.4f degrees\n", property, item, *travel);
	return stopped;
}

static void synscan_manual_motion(void) {
	ASSERT_TRUE(prepare_mount());
	ASSERT_TRUE(slew_to_test_pointing());
	ASSERT_TRUE(set_switch(mount, MOUNT_SLEW_RATE_PROPERTY_NAME, MOUNT_SLEW_RATE_CENTERING_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	double west = 0, east = 0, north = 0, south = 0;
	ASSERT_TRUE(manual_motion_moves(MOUNT_MOTION_RA_PROPERTY_NAME, MOUNT_MOTION_WEST_ITEM_NAME, true, &west));
	ASSERT_TRUE(manual_motion_moves(MOUNT_MOTION_RA_PROPERTY_NAME, MOUNT_MOTION_EAST_ITEM_NAME, true, &east));
	ASSERT_TRUE(manual_motion_moves(MOUNT_MOTION_DEC_PROPERTY_NAME, MOUNT_MOTION_NORTH_ITEM_NAME, false, &north));
	ASSERT_TRUE(manual_motion_moves(MOUNT_MOTION_DEC_PROPERTY_NAME, MOUNT_MOTION_SOUTH_ITEM_NAME, false, &south));
	// Each direction must move measurably and the two directions of an axis must be opposite.
	ASSERT_TRUE(fabs(west) > 0.002 && fabs(east) > 0.002 && fabs(north) > 0.002 && fabs(south) > 0.002);
	ASSERT_TRUE(west * east < 0);
	ASSERT_TRUE(north * south < 0);
	// Away from the pole the declination directions have a defined sign: north raises it.
	ASSERT_TRUE(north > 0);
	ASSERT_TRUE(south < 0);
	// West moves the telescope towards increasing hour angle, which lowers the reported right
	// ascension once the sidereal drift of the stopped axis is taken out.
	ASSERT_TRUE(west < 0);
	ASSERT_TRUE(east > 0);
	ASSERT_TRUE(set_switch(mount, MOUNT_SLEW_RATE_PROPERTY_NAME, MOUNT_SLEW_RATE_FIND_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(set_switch(mount, MOUNT_SLEW_RATE_PROPERTY_NAME, MOUNT_SLEW_RATE_MAX_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(set_switch(mount, MOUNT_SLEW_RATE_PROPERTY_NAME, MOUNT_SLEW_RATE_GUIDE_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	// Manual motion must be abortable, and the aborted property must not stay BUSY.
	ASSERT_TRUE(set_switch(mount, MOUNT_SLEW_RATE_PROPERTY_NAME, MOUNT_SLEW_RATE_CENTERING_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(set_switch(mount, MOUNT_MOTION_DEC_PROPERTY_NAME, MOUNT_MOTION_NORTH_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(set_switch(mount, MOUNT_ABORT_MOTION_PROPERTY_NAME, MOUNT_ABORT_MOTION_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(property_state(mount, MOUNT_MOTION_DEC_PROPERTY_NAME) != INDIGO_BUSY_STATE);
	double stopped_dec = 0, settled_dec = 0;
	ASSERT_TRUE(number_item(mount, MOUNT_RAW_COORDINATES_PROPERTY_NAME, MOUNT_RAW_COORDINATES_DEC_ITEM_NAME, &stopped_dec));
	indigo_usleep(3000000);
	ASSERT_TRUE(number_item(mount, MOUNT_RAW_COORDINATES_PROPERTY_NAME, MOUNT_RAW_COORDINATES_DEC_ITEM_NAME, &settled_dec));
	printf("    DEC after abort: %.5f -> %.5f\n", stopped_dec, settled_dec);
	ASSERT_TRUE(fabs(settled_dec - stopped_dec) < 0.02);
	// A fresh command must be accepted right after the abort.
	double travel = 0;
	ASSERT_TRUE(manual_motion_moves(MOUNT_MOTION_DEC_PROPERTY_NAME, MOUNT_MOTION_SOUTH_ITEM_NAME, false, &travel));
	ASSERT_TRUE(fabs(travel) > 0.002);
	ASSERT_TRUE(set_switch(mount, MOUNT_SLEW_RATE_PROPERTY_NAME, MOUNT_SLEW_RATE_GUIDE_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
}

static void synscan_syncs_and_slews(void) {
	double ra = 0, dec = 0, target_ra = 0, target_dec = 0, reached_ra = 0, reached_dec = 0;
	ASSERT_TRUE(prepare_mount());
	ASSERT_TRUE(slew_to_test_pointing());
	ASSERT_TRUE(set_switch(mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_ON_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(current_coordinates(&ra, &dec));
	// SYNC must not move the mount, so it is checked against the pointing it already has.
	ASSERT_TRUE(set_switch(mount, MOUNT_ON_COORDINATES_SET_PROPERTY_NAME, MOUNT_ON_COORDINATES_SET_SYNC_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	double raw_before = 0, raw_after = 0;
	ASSERT_TRUE(number_item(mount, MOUNT_RAW_COORDINATES_PROPERTY_NAME, MOUNT_RAW_COORDINATES_DEC_ITEM_NAME, &raw_before));
	ASSERT_TRUE(set_coordinates(mount, ra, dec, INDIGO_OK_STATE, SHORT_TIMEOUT));
	indigo_usleep(2000000);
	ASSERT_TRUE(number_item(mount, MOUNT_RAW_COORDINATES_PROPERTY_NAME, MOUNT_RAW_COORDINATES_DEC_ITEM_NAME, &raw_after));
	ASSERT_TRUE(current_coordinates(&reached_ra, &reached_dec));
	printf("    sync to RA %.5f DEC %.5f reports RA %.5f DEC %.5f, raw DEC %.5f -> %.5f\n", ra, dec, reached_ra, reached_dec, raw_before, raw_after);
	ASSERT_TRUE(fabs(raw_after - raw_before) < 0.02);
	ASSERT_NEAR(dec, reached_dec, 0.2);
	ASSERT_TRUE(fabs(ra_difference(reached_ra, ra)) < 0.02);
	// A small slew with tracking requested afterwards.
	ASSERT_TRUE(set_switch(mount, MOUNT_ON_COORDINATES_SET_PROPERTY_NAME, MOUNT_ON_COORDINATES_SET_TRACK_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(current_coordinates(&ra, &dec));
	nearby_target(ra, dec, &target_ra, &target_dec);
	printf("    slewing from RA %.5f DEC %.5f to RA %.5f DEC %.5f\n", ra, dec, target_ra, target_dec);
	// This slew also proves the accepted request is not reported as finished before it starts.
	ASSERT_TRUE(slew_reports_busy_until_arrival(mount, target_ra, target_dec, MOTION_TIMEOUT));
	ASSERT_TRUE(slew_coordinates(mount, target_ra, target_dec, MOTION_TIMEOUT));
	ASSERT_TRUE(current_coordinates(&reached_ra, &reached_dec));
	printf("    arrived at RA %.5f DEC %.5f\n", reached_ra, reached_dec);
	ASSERT_NEAR(target_dec, reached_dec, 0.3);
	ASSERT_TRUE(fabs(ra_difference(reached_ra, target_ra)) < 0.05);
	// MOUNT_ON_COORDINATES_SET.TRACK must leave the mount tracking after the slew.
	bool tracking = false;
	ASSERT_TRUE(switch_item(mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_ON_ITEM_NAME, &tracking));
	ASSERT_TRUE(tracking);
	// Slewing back must work as a fresh operation.
	ASSERT_TRUE(slew_coordinates(mount, ra, dec, MOTION_TIMEOUT));
	ASSERT_TRUE(current_coordinates(&reached_ra, &reached_dec));
	ASSERT_NEAR(dec, reached_dec, 0.3);
	ASSERT_TRUE(fabs(ra_difference(reached_ra, ra)) < 0.05);
}

static void synscan_aborts_slew_and_recovers(void) {
	double ra = 0, dec = 0, target_ra = 0, target_dec = 0, aborted_dec = 0, settled_dec = 0;
	ASSERT_TRUE(prepare_mount());
	ASSERT_TRUE(slew_to_test_pointing());
	ASSERT_TRUE(current_coordinates(&ra, &dec));
	// A long declination excursion, aborted as soon as the slew is reported as started. The
	// controller reaches several degrees per second, so a shorter target would be reached before
	// the abort arrives.
	target_dec = dec - 40.0;
	target_ra = ra;
	ASSERT_TRUE(set_switch(mount, MOUNT_ON_COORDINATES_SET_PROPERTY_NAME, MOUNT_ON_COORDINATES_SET_SLEW_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	static const char *items[] = { MOUNT_EQUATORIAL_COORDINATES_RA_ITEM_NAME, MOUNT_EQUATORIAL_COORDINATES_DEC_ITEM_NAME };
	double values[] = { target_ra, target_dec };
	indigo_change_number_property(&client, devices[mount].name, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, 2, items, values);
	ASSERT_TRUE(wait_settled(mount, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, INDIGO_BUSY_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(set_switch(mount, MOUNT_ABORT_MOTION_PROPERTY_NAME, MOUNT_ABORT_MOTION_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	// The aborted slew must report ALERT rather than a silent OK, and must not stay BUSY.
	ASSERT_TRUE(wait_settled(mount, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, INDIGO_ALERT_STATE, SHORT_TIMEOUT));
	// The axis coasts to a stop after the instant-stop command, so the check is that it comes to
	// rest, not that it froze in place at the moment of the abort.
	indigo_usleep(2000000);
	ASSERT_TRUE(number_item(mount, MOUNT_RAW_COORDINATES_PROPERTY_NAME, MOUNT_RAW_COORDINATES_DEC_ITEM_NAME, &aborted_dec));
	indigo_usleep(4000000);
	ASSERT_TRUE(number_item(mount, MOUNT_RAW_COORDINATES_PROPERTY_NAME, MOUNT_RAW_COORDINATES_DEC_ITEM_NAME, &settled_dec));
	printf("    aborted slew stopped the DEC axis: %.5f -> %.5f\n", aborted_dec, settled_dec);
	ASSERT_TRUE(fabs(settled_dec - aborted_dec) < 0.02);
	// The mount must not have reached the abandoned target.
	double reached_ra = 0, reached_dec = 0;
	ASSERT_TRUE(current_coordinates(&reached_ra, &reached_dec));
	printf("    abandoned target DEC %.5f, stopped at DEC %.5f\n", target_dec, reached_dec);
	ASSERT_TRUE(fabs(reached_dec - target_dec) > 0.5);
	// A fresh slew back to the starting pointing must succeed right after the abort.
	ASSERT_TRUE(slew_coordinates(mount, ra, dec, MOTION_TIMEOUT));
	ASSERT_TRUE(current_coordinates(&reached_ra, &reached_dec));
	printf("    recovered to RA %.5f DEC %.5f\n", reached_ra, reached_dec);
	ASSERT_NEAR(dec, reached_dec, 0.3);
	ASSERT_TRUE(set_switch(mount, MOUNT_ON_COORDINATES_SET_PROPERTY_NAME, MOUNT_ON_COORDINATES_SET_TRACK_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
}

static void synscan_parks_and_unparks(void) {
	double ra = 0, dec = 0, drift = 0, park_ha = 0, park_dec = 0;
	ASSERT_TRUE(prepare_mount());
	ASSERT_TRUE(slew_to_test_pointing());
	ASSERT_TRUE(current_coordinates(&ra, &dec));
	// Park where the mount already is, so the park workflow is exercised with a short slew.
	ASSERT_TRUE(set_switch(mount, MOUNT_PARK_SET_PROPERTY_NAME, MOUNT_PARK_SET_CURRENT_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(number_item(mount, MOUNT_PARK_POSITION_PROPERTY_NAME, MOUNT_PARK_POSITION_HA_ITEM_NAME, &park_ha));
	ASSERT_TRUE(number_item(mount, MOUNT_PARK_POSITION_PROPERTY_NAME, MOUNT_PARK_POSITION_DEC_ITEM_NAME, &park_dec));
	printf("    park position set to HA %.5f DEC %.5f\n", park_ha, park_dec);
	ASSERT_NEAR(dec, park_dec, 0.3);
	ASSERT_TRUE(set_switch(mount, MOUNT_PARK_PROPERTY_NAME, MOUNT_PARK_PARKED_ITEM_NAME, INDIGO_OK_STATE, MOTION_TIMEOUT));
	bool parked = false, tracking = true;
	ASSERT_TRUE(switch_item(mount, MOUNT_PARK_PROPERTY_NAME, MOUNT_PARK_PARKED_ITEM_NAME, &parked));
	ASSERT_TRUE(parked);
	// A completed park stops tracking, and must say so before anything else touches the property.
	// The rejected requests below leave their requested values in MOUNT_TRACKING, so this is the
	// only point at which the published tracking state can be checked.
	ASSERT_TRUE(switch_item(mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_ON_ITEM_NAME, &tracking));
	ASSERT_FALSE(tracking);
	// A parked mount must refuse motion, tracking and goto requests.
	ASSERT_TRUE(set_switch(mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_ON_ITEM_NAME, INDIGO_ALERT_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(set_switch(mount, MOUNT_MOTION_RA_PROPERTY_NAME, MOUNT_MOTION_WEST_ITEM_NAME, INDIGO_ALERT_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(set_switch(mount, MOUNT_MOTION_DEC_PROPERTY_NAME, MOUNT_MOTION_NORTH_ITEM_NAME, INDIGO_ALERT_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(set_coordinates(mount, ra, dec, INDIGO_ALERT_STATE, SHORT_TIMEOUT));
	// Parking must stop the RA axis, so the reported right ascension has to run away at the
	// sidereal rate of 0.05 degrees over 12 s instead of standing still.
	ASSERT_TRUE(measure_ra_drift(12.0, &drift));
	printf("    parked RA axis: reported RA moved %.5f degrees in 12 s, sidereal is 0.050\n", drift);
	ASSERT_NEAR(0.050, fabs(drift), 0.02);
	ASSERT_TRUE(set_switch(mount, MOUNT_PARK_PROPERTY_NAME, MOUNT_PARK_UNPARKED_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	// Everything refused above must be accepted again once the mount is unparked.
	ASSERT_TRUE(set_switch(mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_ON_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(set_switch(mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_OFF_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
}

