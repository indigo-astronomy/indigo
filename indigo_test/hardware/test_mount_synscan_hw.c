// Measures how long a guide pulse keeps GUIDER_GUIDE_* busy, from issuing the request to the
// completion update. This is public-property completion timing over the network transport and the
// driver's finalizer, not an electrical measurement of the ST4 relay output.
static bool measure_pulse(const char *property, const char *item, double request_ms, double *error_ms) {
	unsigned before = revision(guider, property);
	double started = indigo_monotonic_time();
	indigo_change_number_property_1(&client, devices[guider].name, property, item, request_ms);
	if (!wait_state(guider, property, before, INDIGO_BUSY_STATE, SHORT_TIMEOUT)) {
		return false;
	}
	if (!wait_settled(guider, property, INDIGO_OK_STATE, SHORT_TIMEOUT)) {
		return false;
	}
	*error_ms = (indigo_monotonic_time() - started) * 1000.0 - request_ms;
	return true;
}

static void synscan_guides(void) {
	ASSERT_TRUE(prepare_mount());
	ASSERT_TRUE(slew_to_test_pointing());
	ASSERT_TRUE(set_number(guider, GUIDER_RATE_PROPERTY_NAME, GUIDER_RATE_ITEM_NAME, 50, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(set_number(guider, GUIDER_RATE_PROPERTY_NAME, GUIDER_DEC_RATE_ITEM_NAME, 50, INDIGO_OK_STATE, SHORT_TIMEOUT));
	// An RA pulse needs the RA axis to be tracking; the driver must refuse it otherwise.
	ASSERT_TRUE(set_switch(mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_OFF_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(set_number(guider, GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_WEST_ITEM_NAME, 300, INDIGO_ALERT_STATE, SHORT_TIMEOUT));
	// A DEC pulse does not require tracking.
	double error_ms = 0;
	ASSERT_TRUE(measure_pulse(GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME, 300, &error_ms));
	ASSERT_TRUE(set_switch(mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_ON_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	// A pulse while tracking runs the RA axis off the tracking rate for its duration, which shows
	// as a shift of the reported right ascension. One pulse moves less than the resolution the
	// mount reports positions at, so the effect is accumulated over a train of pulses and checked
	// in both directions. At the 50 % guide rate in use here one second of pulse is worth about
	// 0.002 degrees, so eight pulses have to clear the noise of a tracking axis comfortably.
	double raw_before = 0, raw_after = 0, west_travel = 0, east_travel = 0;
	ASSERT_TRUE(number_item(mount, MOUNT_RAW_COORDINATES_PROPERTY_NAME, MOUNT_RAW_COORDINATES_RA_ITEM_NAME, &raw_before));
	for (int i = 0; i < 8; i++) {
		ASSERT_TRUE(measure_pulse(GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_WEST_ITEM_NAME, 1000, &error_ms));
	}
	ASSERT_TRUE(number_item(mount, MOUNT_RAW_COORDINATES_PROPERTY_NAME, MOUNT_RAW_COORDINATES_RA_ITEM_NAME, &raw_after));
	west_travel = ra_difference(raw_after, raw_before) * 15.0;
	raw_before = raw_after;
	for (int i = 0; i < 8; i++) {
		ASSERT_TRUE(measure_pulse(GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_EAST_ITEM_NAME, 1000, &error_ms));
	}
	ASSERT_TRUE(number_item(mount, MOUNT_RAW_COORDINATES_PROPERTY_NAME, MOUNT_RAW_COORDINATES_RA_ITEM_NAME, &raw_after));
	east_travel = ra_difference(raw_after, raw_before) * 15.0;
	// Compare the two trains against each other rather than against zero. Both are measured on a
	// tracking axis whose rate is not exact, and that common tracking error cancels in the
	// difference while the guide correction does not. Eight pulses of one second at the 50 % guide
	// rate are worth about 0.017 degrees each way, so the two trains should differ by about 0.033
	// degrees, with west lowering the reported right ascension and east raising it.
	double differential = west_travel - east_travel;
	printf("    8 x 1000 ms west pulses moved the reported RA by %.5f degrees, 8 x east by %.5f, differential %.5f\n", west_travel, east_travel, differential);
	ASSERT_TRUE(differential < 0);
	ASSERT_NEAR(0.033, fabs(differential), 0.020);
	// The RA axis must be tracking again once the pulse finished, which shows as a reported right
	// ascension that stands still.
	bool tracking = false;
	ASSERT_TRUE(switch_item(mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_ON_ITEM_NAME, &tracking));
	ASSERT_TRUE(tracking);
	double drift = 0;
	ASSERT_TRUE(measure_ra_drift(12.0, &drift));
	printf("    RA drift over 12 s after the pulse: %.5f degrees, a stopped axis would show 0.050\n", drift);
	ASSERT_TRUE(fabs(drift) < 0.01);
	// A same-direction pulse issued while another is running replaces it, so the axis stops one
	// new duration after the second request, not at the first pulse's deadline. The second pulse
	// is deliberately shorter than what is left of the first: replacing finishes at about
	// 500 + 600 ms, whereas extending or keeping the longer deadline would run the full 2000 ms,
	// so the two behaviours cannot be confused.
	unsigned before = revision(guider, GUIDER_GUIDE_DEC_PROPERTY_NAME);
	double started = indigo_monotonic_time();
	indigo_change_number_property_1(&client, devices[guider].name, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME, 2000);
	ASSERT_TRUE(wait_state(guider, GUIDER_GUIDE_DEC_PROPERTY_NAME, before, INDIGO_BUSY_STATE, SHORT_TIMEOUT));
	indigo_usleep(500000);
	indigo_change_number_property_1(&client, devices[guider].name, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME, 600);
	ASSERT_TRUE(wait_settled(guider, GUIDER_GUIDE_DEC_PROPERTY_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	double replaced = (indigo_monotonic_time() - started) * 1000.0;
	printf("    2000 ms north pulse replaced after 500 ms by a 600 ms north pulse finished in %.0f ms\n", replaced);
	ASSERT_TRUE(replaced > 900 && replaced < 1600);
	// An opposite-direction pulse on the same axis replaces the active pulse the same way, so it
	// completes on the new, shorter schedule rather than the one it superseded.
	before = revision(guider, GUIDER_GUIDE_DEC_PROPERTY_NAME);
	started = indigo_monotonic_time();
	indigo_change_number_property_1(&client, devices[guider].name, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME, 2500);
	ASSERT_TRUE(wait_state(guider, GUIDER_GUIDE_DEC_PROPERTY_NAME, before, INDIGO_BUSY_STATE, SHORT_TIMEOUT));
	indigo_usleep(500000);
	indigo_change_number_property_1(&client, devices[guider].name, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_SOUTH_ITEM_NAME, 500);
	ASSERT_TRUE(wait_settled(guider, GUIDER_GUIDE_DEC_PROPERTY_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	double cancelled = (indigo_monotonic_time() - started) * 1000.0;
	printf("    2500 ms north pulse cancelled by a 500 ms south pulse finished in %.0f ms\n", cancelled);
	ASSERT_TRUE(cancelled > 800 && cancelled < 1600);
	// A shorter pulse in the same direction is what separates replacing the running pulse from
	// extending it: replacing ends on the new, earlier deadline, extending would keep the original
	// one. A 3000 ms pulse replaced after 500 ms by a 500 ms pulse must finish near 1000 ms, not
	// near 3000 ms.
	before = revision(guider, GUIDER_GUIDE_DEC_PROPERTY_NAME);
	started = indigo_monotonic_time();
	indigo_change_number_property_1(&client, devices[guider].name, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME, 3000);
	ASSERT_TRUE(wait_state(guider, GUIDER_GUIDE_DEC_PROPERTY_NAME, before, INDIGO_BUSY_STATE, SHORT_TIMEOUT));
	indigo_usleep(500000);
	indigo_change_number_property_1(&client, devices[guider].name, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME, 500);
	ASSERT_TRUE(wait_settled(guider, GUIDER_GUIDE_DEC_PROPERTY_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	double shortened = (indigo_monotonic_time() - started) * 1000.0;
	printf("    3000 ms north pulse replaced after 500 ms by a 500 ms north pulse finished in %.0f ms\n", shortened);
	ASSERT_TRUE(shortened > 800 && shortened < 1600);
}

// Required by the guider standard: a duration accuracy measurement over a range of pulse lengths.
static void synscan_guide_pulse_accuracy(void) {
	static const double durations[] = { 100, 250, 500, 1000, 2000 };
	static const char *axes[] = { GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_DEC_PROPERTY_NAME };
	static const char *items[] = { GUIDER_GUIDE_WEST_ITEM_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME };
	ASSERT_TRUE(prepare_mount());
	ASSERT_TRUE(set_switch(mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_ON_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	for (int a = 0; a < ARRAY_SIZE(axes); a++) {
		for (int d = 0; d < ARRAY_SIZE(durations); d++) {
			double sum = 0, sum_absolute = 0, worst = 0, minimum = 0, maximum = 0;
			int samples = 5;
			for (int i = 0; i < samples; i++) {
				double error_ms = 0;
				if (!measure_pulse(axes[a], items[a], durations[d], &error_ms)) {
					indigo_test_failures++;
					return;
				}
				sum += error_ms;
				sum_absolute += fabs(error_ms);
				if (fabs(error_ms) > worst) {
					worst = fabs(error_ms);
				}
				if (i == 0 || error_ms < minimum) {
					minimum = error_ms;
				}
				if (i == 0 || error_ms > maximum) {
					maximum = error_ms;
				}
				indigo_usleep(400000);
			}
			printf("    %s %.0f ms x%d: mean %+.1f ms, mean |error| %.1f ms, min %+.1f ms, max %+.1f ms\n", axes[a], durations[d], samples, sum / samples, sum_absolute / samples, minimum, maximum);
			// The finalizer runs on the shared mount queue and each stop is one UDP transaction,
			// so a pulse is expected to overrun slightly, never to end early.
			ASSERT_TRUE(minimum > -20.0);
			ASSERT_TRUE(worst < 400.0);
		}
	}
}

static void synscan_reconnects(void) {
	// The guider and the aux device share the mount connection; disconnecting the mount must not
	// break a later connection in either order.
	ASSERT_TRUE(disconnect_device(aux));
	ASSERT_TRUE(disconnect_device(guider));
	ASSERT_TRUE(disconnect_device(mount));
	ASSERT_TRUE(connect_device(mount, MOTION_TIMEOUT));
	ASSERT_TRUE(connect_device(guider, SHORT_TIMEOUT));
	ASSERT_TRUE(connect_aux());
	double ra = 0, dec = 0;
	ASSERT_TRUE(current_coordinates(&ra, &dec));
	printf("    reconnected, RA %.5f DEC %.5f\n", ra, dec);
	// Connecting a shared device first must open the transport through the master.
	ASSERT_TRUE(disconnect_device(aux));
	ASSERT_TRUE(disconnect_device(guider));
	ASSERT_TRUE(disconnect_device(mount));
	ASSERT_TRUE(connect_device(guider, MOTION_TIMEOUT));
	ASSERT_TRUE(connect_device(mount, SHORT_TIMEOUT));
	ASSERT_TRUE(current_coordinates(&ra, &dec));
	printf("    guider-first connection succeeded, RA %.5f DEC %.5f\n", ra, dec);
	// Disconnecting the master while a slave is still connected must leave the slave usable.
	ASSERT_TRUE(disconnect_device(mount));
	ASSERT_TRUE(set_number(guider, GUIDER_RATE_PROPERTY_NAME, GUIDER_RATE_ITEM_NAME, 50, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(disconnect_device(guider));
	ASSERT_TRUE(connect_device(mount, MOTION_TIMEOUT));
	ASSERT_TRUE(connect_device(guider, SHORT_TIMEOUT));
	ASSERT_TRUE(connect_aux());
}

// The UDP transport has no session to drop, so an unreachable mount is the reachable failure mode
// on this connection: the driver has to give up within its command timeout and leave the
// connection property in a clean refused state rather than hanging or staying busy.
static void synscan_reports_unreachable_mount(void) {
	ASSERT_TRUE(disconnect_device(aux));
	ASSERT_TRUE(disconnect_device(guider));
	ASSERT_TRUE(disconnect_device(mount));
	// 203.0.113.0/24 is the TEST-NET-3 range, reserved for documentation and never routed.
	ASSERT_TRUE(set_text(mount, DEVICE_PORT_PROPERTY_NAME, DEVICE_PORT_ITEM_NAME, "synscan://203.0.113.1:11880", INDIGO_OK_STATE, SHORT_TIMEOUT));
	unsigned before = revision(mount, CONNECTION_PROPERTY_NAME);
	double started = indigo_monotonic_time();
	indigo_change_switch_property_1(&client, devices[mount].name, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, true);
	ASSERT_TRUE(wait_state(mount, CONNECTION_PROPERTY_NAME, before, INDIGO_ALERT_STATE, MOTION_TIMEOUT));
	printf("    unreachable mount refused after %.1f s\n", indigo_monotonic_time() - started);
	bool connected = true;
	ASSERT_TRUE(switch_item(mount, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, &connected));
	ASSERT_FALSE(connected);
	// The real mount must still be usable afterwards.
	ASSERT_TRUE(select_mount_url());
	ASSERT_TRUE(connect_device(mount, MOTION_TIMEOUT));
	ASSERT_TRUE(connect_device(guider, SHORT_TIMEOUT));
	ASSERT_TRUE(connect_aux());
	double ra = 0, dec = 0;
	ASSERT_TRUE(current_coordinates(&ra, &dec));
	printf("    recovered on the real mount, RA %.5f DEC %.5f\n", ra, dec);
}

static void synscan_reinitializes(void) {
	ASSERT_TRUE(disconnect_device(aux));
	ASSERT_TRUE(disconnect_device(guider));
	ASSERT_TRUE(disconnect_device(mount));
	ASSERT_TRUE(indigo_mount_synscan(INDIGO_DRIVER_SHUTDOWN, NULL) == INDIGO_OK);
	ASSERT_TRUE(indigo_mount_synscan(INDIGO_DRIVER_INIT, NULL) == INDIGO_OK);
	ASSERT_TRUE(wait_presence(SHORT_TIMEOUT));
	ASSERT_TRUE(select_mount_url());
	ASSERT_TRUE(connect_device(mount, MOTION_TIMEOUT));
	double ra = 0, dec = 0;
	ASSERT_TRUE(current_coordinates(&ra, &dec));
	printf("    driver reinitialized, RA %.5f DEC %.5f\n", ra, dec);
	// The session teardown restores the mount, so leave the shared connection up.
	ASSERT_TRUE(connect_device(guider, SHORT_TIMEOUT));
	ASSERT_TRUE(connect_aux());
}

int main(int argc, char **argv) {
	if (argc < 2 || strcmp(argv[1], "--run")) {
		fprintf(stderr, "Physical SynScan mount test: run explicitly with --run (or make test-mount-synscan-hw).\n");
		return 2;
	}
	setvbuf(stdout, NULL, _IONBF, 0);
	if (getenv("SYNSCAN_HW_DEBUG")) {
		indigo_set_log_level(INDIGO_LOG_DEBUG);
	}
	const char *url = getenv("SYNSCAN_HW_URL");
	if (url && *url) {
		mount_url = url;
	}
	const char *latitude = getenv("SYNSCAN_HW_LATITUDE");
	if (latitude && *latitude) {
		site_latitude = atof(latitude);
	}
	const char *longitude = getenv("SYNSCAN_HW_LONGITUDE");
	if (longitude && *longitude) {
		site_longitude = atof(longitude);
	}
	const char *declination = getenv("SYNSCAN_HW_DECLINATION");
	if (declination && *declination) {
		test_declination = atof(declination);
	}
	if (indigo_test_mkdtemp_home(park_folder) == NULL) {
		perror("mkdtemp");
		return 2;
	}
	printf("Connecting to %s\n", mount_url);
	client = (indigo_client){ .name = "SynScan hardware test", .version = INDIGO_VERSION_CURRENT, .define_property = define_property, .update_property = update_property, .delete_property = delete_property, .send_message = report_message };
	const indigo_test_case tests[] = {
		{ "synscan_discovers_and_connects", synscan_discovers_and_connects },
		{ "synscan_reports_identity_and_capabilities", synscan_reports_identity_and_capabilities },
		{ "synscan_reads_coordinates_and_state", synscan_reads_coordinates_and_state },
		{ "synscan_tracking_and_rates", synscan_tracking_and_rates },
		{ "synscan_manual_motion", synscan_manual_motion },
		{ "synscan_syncs_and_slews", synscan_syncs_and_slews },
		{ "synscan_aborts_slew_and_recovers", synscan_aborts_slew_and_recovers },
		{ "synscan_parks_and_unparks", synscan_parks_and_unparks },
		{ "synscan_homes", synscan_homes },
		{ "synscan_runs_autohome", synscan_runs_autohome },
		{ "synscan_controls_snap_port", synscan_controls_snap_port },
		{ "synscan_guides", synscan_guides },
		{ "synscan_guide_pulse_accuracy", synscan_guide_pulse_accuracy },
		{ "synscan_reconnects", synscan_reconnects },
		{ "synscan_reports_unreachable_mount", synscan_reports_unreachable_mount },
		{ "synscan_reinitializes", synscan_reinitializes }
	};
	int result = 1;
	bool started = false, initialized = false;
	CHECK(indigo_start() == INDIGO_OK);
	started = true;
	CHECK(indigo_attach_client(&client) == INDIGO_OK);
	CHECK(indigo_mount_synscan(INDIGO_DRIVER_INIT, NULL) == INDIGO_OK);
	initialized = true;
	CHECK(wait_presence(SHORT_TIMEOUT));
	CHECK(select_mount_url());
	CHECK(connect_device(mount, MOTION_TIMEOUT));
	CHECK(connect_device(guider, SHORT_TIMEOUT));
	aux_has_snap_port = connect_device(aux, SHORT_TIMEOUT);
	if (!aux_has_snap_port) {
		printf("The aux device was refused, the controller has no snap port\n");
	}
	CHECK(clear_alignment_model());
	CHECK(set_site());
	CHECK(capture_initial_settings());
	printf("Starting pointing: RA %.5f, DEC %.5f, tracking %s\n", initial_ra, initial_dec, initial_tracking ? "on" : "off");
	result = indigo_run_tests("SynScan mount hardware", tests, ARRAY_SIZE(tests));
cleanup:
	if (mount >= 0 && devices[mount].present) {
		stop_all_motion();
		restore_initial_settings();
		// Put the mount back where the session found it.
		if (settings_captured && slew_coordinates(mount, initial_ra, initial_dec, MOTION_TIMEOUT)) {
			printf("Restored the starting pointing RA %.5f, DEC %.5f\n", initial_ra, initial_dec);
		}
		set_switch(mount, MOUNT_TRACKING_PROPERTY_NAME, initial_tracking ? MOUNT_TRACKING_ON_ITEM_NAME : MOUNT_TRACKING_OFF_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT);
	}
	if (!disconnect_device(aux) || !disconnect_device(guider) || !disconnect_device(mount)) {
		indigo_test_failures++;
	}
	if (initialized && indigo_mount_synscan(INDIGO_DRIVER_SHUTDOWN, NULL) != INDIGO_OK) {
		indigo_test_failures++;
	}
	indigo_detach_client(&client);
	if (started) {
		indigo_stop();
	}
	for (int d = 0; d < MAX_DEVICES; d++) {
		for (int p = 0; p < MAX_PROPERTIES; p++) {
			indigo_release_property(devices[d].properties[p]);
		}
	}
	remove_park_files();
	indigo_test_remove_tree(park_folder);
	return indigo_test_failures ? 1 : result;
}
