// Right ascension difference in hours, normalized to the shortest way around the circle. The
// offset added before the modulo must be a whole number of days so that a zero difference stays
// zero.
static double ra_difference(double a, double b) {
	double difference = fmod(a - b + 48.0, 24.0);
	if (difference > 12.0) {
		difference -= 24.0;
	}
	return difference;
}

