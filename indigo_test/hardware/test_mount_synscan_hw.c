// Waits for a newer revision of the property in the requested state. A revision gate is required
// because the mount keeps republishing polled properties, so a stale OK must not satisfy a wait.
static bool wait_state(int d, const char *name, unsigned after, indigo_property_state state, double timeout) {
	double deadline = indigo_monotonic_time() + timeout;
	while (indigo_monotonic_time() < deadline) {
		pthread_mutex_lock(&mutex);
		int p = slot(d, name);
		bool ready = p >= 0 && devices[d].revisions[p] > after && devices[d].properties[p]->state == state;
		pthread_mutex_unlock(&mutex);
		if (ready) {
			return true;
		}
		indigo_usleep(20000);
	}
	// Report what the property actually settled on. A mount that stopped answering reports ALERT
	// on every request, which must not be mistaken for a property stuck in BUSY.
	fprintf(stderr, "    timeout: %s %s expected state %d, last published state %d\n", devices[d].name, name, state, property_state(d, name));
	return false;
}

// Waits for the property to settle out of BUSY, then reports the state it settled in. Coordinate
// and park properties are published by the poll handler while an operation runs, so the terminal
// state is the first non-BUSY revision after the request was accepted.
static bool wait_settled(int d, const char *name, indigo_property_state state, double timeout) {
	double deadline = indigo_monotonic_time() + timeout;
	while (indigo_monotonic_time() < deadline) {
		if (property_state(d, name) == state) {
			return true;
		}
		indigo_usleep(50000);
	}
	fprintf(stderr, "    timeout: %s %s did not settle in state %d (state %d)\n", devices[d].name, name, state, property_state(d, name));
	return false;
}

