// Degrees of right ascension the reported pointing travelled over the given interval. A stopped
// RA axis keeps its hour angle, so its reported right ascension runs away at the sidereal rate of
// about 0.0042 degrees per second; a tracking axis keeps its right ascension instead.
static bool measure_ra_drift(double seconds, double *degrees) {
	double before = 0, after = 0;
	if (!number_item(mount, MOUNT_RAW_COORDINATES_PROPERTY_NAME, MOUNT_RAW_COORDINATES_RA_ITEM_NAME, &before)) {
		return false;
	}
	indigo_usleep((unsigned long)(seconds * 1000000));
	if (!number_item(mount, MOUNT_RAW_COORDINATES_PROPERTY_NAME, MOUNT_RAW_COORDINATES_RA_ITEM_NAME, &after)) {
		return false;
	}
	*degrees = ra_difference(after, before) * 15.0;
	return true;
}

// A target a few degrees away from the current pointing, kept away from the pole so the DEC axis
// can move in both directions and the RA axis does not have to cross the meridian.
static void nearby_target(double ra, double dec, double *target_ra, double *target_dec) {
	*target_ra = fmod(ra + 0.2 + 24.0, 24.0);
	*target_dec = dec > 0 ? dec - 3.0 : dec + 3.0;
	if (*target_dec > 85.0) {
		*target_dec = 85.0;
	}
	if (*target_dec < -85.0) {
		*target_dec = -85.0;
	}
}

static bool stop_all_motion(void) {
	bool ok = set_switch(mount, MOUNT_ABORT_MOTION_PROPERTY_NAME, MOUNT_ABORT_MOTION_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT);
	return wait_settled(mount, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, INDIGO_OK_STATE, MOTION_TIMEOUT) && ok;
}

// Brings the mount back to a known idle state. An assertion aborts its test case where it stands,
// so a scenario must never inherit a parked, tracking or still moving mount from the one before.
static bool prepare_mount(void) {
	bool ok = stop_all_motion();
	ok = set_switch(mount, MOUNT_PARK_PROPERTY_NAME, MOUNT_PARK_UNPARKED_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT) && ok;
	ok = set_switch(mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_OFF_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT) && ok;
	ok = set_switch(mount, MOUNT_SLEW_RATE_PROPERTY_NAME, MOUNT_SLEW_RATE_GUIDE_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT) && ok;
	ok = set_switch(mount, MOUNT_ON_COORDINATES_SET_PROPERTY_NAME, MOUNT_ON_COORDINATES_SET_TRACK_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT) && ok;
	return ok;
}

// The mount starts at its home position on the celestial pole, where a declination direction has
// no meaning and the hour angle is degenerate. Every motion scenario therefore runs from a
// defined pointing well away from the pole.
static bool slew_to_test_pointing(void) {
	double lst = 0;
	if (!number_item(mount, MOUNT_LST_TIME_PROPERTY_NAME, MOUNT_LST_TIME_ITEM_NAME, &lst)) {
		return false;
	}
	double ra = fmod(lst - 1.0 + 24.0, 24.0);
	printf("Slewing to the test pointing RA %.5f, DEC %.5f\n", ra, test_declination);
	return slew_coordinates(mount, ra, test_declination, MOTION_TIMEOUT);
}

static bool capture_initial_settings(void) {
	bool ok = current_coordinates(&initial_ra, &initial_dec);
	ok = ok && number_item(mount, MOUNT_GUIDE_RATE_PROPERTY_NAME, MOUNT_GUIDE_RATE_RA_ITEM_NAME, &initial_guide_ra);
	ok = ok && number_item(mount, MOUNT_GUIDE_RATE_PROPERTY_NAME, MOUNT_GUIDE_RATE_DEC_ITEM_NAME, &initial_guide_dec);
	ok = ok && number_item(mount, MOUNT_PARK_POSITION_PROPERTY_NAME, MOUNT_PARK_POSITION_HA_ITEM_NAME, &initial_park_ha);
	ok = ok && number_item(mount, MOUNT_PARK_POSITION_PROPERTY_NAME, MOUNT_PARK_POSITION_DEC_ITEM_NAME, &initial_park_dec);
	ok = ok && number_item(mount, MOUNT_HOME_POSITION_PROPERTY_NAME, MOUNT_HOME_POSITION_HA_ITEM_NAME, &initial_home_ha);
	ok = ok && number_item(mount, MOUNT_HOME_POSITION_PROPERTY_NAME, MOUNT_HOME_POSITION_DEC_ITEM_NAME, &initial_home_dec);
	ok = ok && switch_item(mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_ON_ITEM_NAME, &initial_tracking);
	settings_captured = ok;
	return ok;
}

static void restore_initial_settings(void) {
	if (!settings_captured) {
		return;
	}
	static const char *guide_items[] = { MOUNT_GUIDE_RATE_RA_ITEM_NAME, MOUNT_GUIDE_RATE_DEC_ITEM_NAME };
	double guide_values[] = { initial_guide_ra, initial_guide_dec };
	static const char *park_items[] = { MOUNT_PARK_POSITION_HA_ITEM_NAME, MOUNT_PARK_POSITION_DEC_ITEM_NAME };
	double park_values[] = { initial_park_ha, initial_park_dec };
	static const char *home_items[] = { MOUNT_HOME_POSITION_HA_ITEM_NAME, MOUNT_HOME_POSITION_DEC_ITEM_NAME };
	double home_values[] = { initial_home_ha, initial_home_dec };
	indigo_change_number_property(&client, devices[mount].name, MOUNT_GUIDE_RATE_PROPERTY_NAME, 2, guide_items, guide_values);
	indigo_change_number_property(&client, devices[mount].name, MOUNT_PARK_POSITION_PROPERTY_NAME, 2, park_items, park_values);
	indigo_change_number_property(&client, devices[mount].name, MOUNT_HOME_POSITION_PROPERTY_NAME, 2, home_items, home_values);
	set_switch(mount, MOUNT_PARK_PROPERTY_NAME, MOUNT_PARK_UNPARKED_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT);
	set_switch(mount, MOUNT_TRACK_RATE_PROPERTY_NAME, MOUNT_TRACK_RATE_SIDEREAL_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT);
	set_switch(mount, MOUNT_SLEW_RATE_PROPERTY_NAME, MOUNT_SLEW_RATE_GUIDE_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT);
	set_switch(mount, MOUNT_ON_COORDINATES_SET_PROPERTY_NAME, MOUNT_ON_COORDINATES_SET_TRACK_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT);
	set_switch(mount, MOUNT_TRACKING_PROPERTY_NAME, initial_tracking ? MOUNT_TRACKING_ON_ITEM_NAME : MOUNT_TRACKING_OFF_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT);
}

