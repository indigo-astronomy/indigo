// A coordinate slew is complete when the mount is actually pointing at the target, so that is what
// this waits for. Waiting only for the property to reach OK is not enough: the coordinates are
// republished by the poll handler about once a second and a poll that was already in flight when
// the request was accepted can land after it, so the state alone can say OK while the mount has
// not moved. Requiring the reported pointing to match the request makes the wait independent of
// that ordering.
static bool slew_coordinates(int d, double ra, double dec, double timeout) {
	static const char *items[] = { MOUNT_EQUATORIAL_COORDINATES_RA_ITEM_NAME, MOUNT_EQUATORIAL_COORDINATES_DEC_ITEM_NAME };
	double values[] = { ra, dec };
	indigo_change_number_property(&client, devices[d].name, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, 2, items, values);
	double deadline = indigo_monotonic_time() + timeout, reached_ra = 0, reached_dec = 0;
	while (indigo_monotonic_time() < deadline) {
		if (property_state(d, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME) == INDIGO_OK_STATE && number_item(d, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, MOUNT_EQUATORIAL_COORDINATES_RA_ITEM_NAME, &reached_ra) && number_item(d, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, MOUNT_EQUATORIAL_COORDINATES_DEC_ITEM_NAME, &reached_dec) && fabs(reached_dec - dec) < 0.3 && fabs(ra_difference(reached_ra, ra)) < 0.05) {
			return true;
		}
		indigo_usleep(50000);
	}
	fprintf(stderr, "    timeout: %s did not reach RA %.5f DEC %.5f, stopped at RA %.5f DEC %.5f in state %d\n", MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, ra, dec, reached_ra, reached_dec, property_state(d, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME));
	return false;
}

// Proves a just-accepted slew is not reported as finished before it starts. The change branch
// publishes BUSY, and no update may downgrade that to OK until the mount has actually arrived.
static bool slew_reports_busy_until_arrival(int d, double ra, double dec, double timeout) {
	static const char *items[] = { MOUNT_EQUATORIAL_COORDINATES_RA_ITEM_NAME, MOUNT_EQUATORIAL_COORDINATES_DEC_ITEM_NAME };
	double values[] = { ra, dec };
	indigo_change_number_property(&client, devices[d].name, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, 2, items, values);
	if (!wait_settled(d, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, INDIGO_BUSY_STATE, SHORT_TIMEOUT)) {
		return false;
	}
	// Sample across several poll cycles; a spurious OK appears within the first second.
	for (int i = 0; i < 40; i++) {
		double reached_ra = 0, reached_dec = 0;
		if (property_state(d, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME) == INDIGO_OK_STATE) {
			if (!number_item(d, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, MOUNT_EQUATORIAL_COORDINATES_DEC_ITEM_NAME, &reached_dec) || fabs(reached_dec - dec) > 0.3) {
				number_item(d, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, MOUNT_EQUATORIAL_COORDINATES_RA_ITEM_NAME, &reached_ra);
				fprintf(stderr, "    slew reported OK before arrival: at RA %.5f DEC %.5f, target RA %.5f DEC %.5f\n", reached_ra, reached_dec, ra, dec);
				return false;
			}
			return true;
		}
		indigo_usleep(50000);
	}
	return wait_settled(d, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, INDIGO_OK_STATE, timeout);
}

// The mount is reached over Wi-Fi and powers its radio down when idle, so a connection attempt can
// be refused because a single UDP exchange was lost rather than because the driver mishandled it.
// One retry is allowed and is reported, so a genuine connect defect still fails the test while a
// dropped packet does not. A refused attempt must still leave the device disconnected and usable.
static bool connect_device(int d, double timeout) {
	if (d < 0) {
		return false;
	}
	for (int attempt = 0; attempt < 2; attempt++) {
		unsigned before = revision(d, CONNECTION_PROPERTY_NAME);
		indigo_change_switch_property_1(&client, devices[d].name, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, true);
		bool value = false;
		if (wait_state(d, CONNECTION_PROPERTY_NAME, before, INDIGO_OK_STATE, timeout) && switch_item(d, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, &value) && value) {
			if (attempt > 0) {
				printf("    note: %s connected on the second attempt after a lost UDP exchange\n", devices[d].name);
			}
			return true;
		}
		if (property_state(d, CONNECTION_PROPERTY_NAME) != INDIGO_ALERT_STATE) {
			return false;
		}
		indigo_usleep(2000000);
	}
	return false;
}

// Connects the aux device where the controller has a snap port. Where it has none, the driver has
// to refuse the device cleanly: ALERT, left disconnected, and without disturbing the connection
// the mount and guider share.
static bool connect_aux(void) {
	if (aux_has_snap_port) {
		return connect_device(aux, SHORT_TIMEOUT);
	}
	if (aux < 0) {
		return false;
	}
	unsigned before = revision(aux, CONNECTION_PROPERTY_NAME);
	indigo_change_switch_property_1(&client, devices[aux].name, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, true);
	bool connected = true;
	return wait_state(aux, CONNECTION_PROPERTY_NAME, before, INDIGO_ALERT_STATE, SHORT_TIMEOUT) && switch_item(aux, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, &connected) && !connected;
}

static bool disconnect_device(int d) {
	if (d < 0 || !devices[d].present) {
		return true;
	}
	bool connected = false;
	if (!switch_item(d, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, &connected) || !connected) {
		return true;
	}
	unsigned before = revision(d, CONNECTION_PROPERTY_NAME);
	indigo_change_switch_property_1(&client, devices[d].name, CONNECTION_PROPERTY_NAME, CONNECTION_DISCONNECTED_ITEM_NAME, true);
	return wait_state(d, CONNECTION_PROPERTY_NAME, before, INDIGO_OK_STATE, SHORT_TIMEOUT);
}

static bool wait_presence(double timeout) {
	double deadline = indigo_monotonic_time() + timeout;
	while (indigo_monotonic_time() < deadline) {
		mount = device_index(MOUNT_DEVICE_NAME);
		guider = device_index(GUIDER_DEVICE_NAME);
		aux = device_index(AUX_DEVICE_NAME);
		if (mount >= 0 && guider >= 0 && aux >= 0 && property_defined(mount, CONNECTION_PROPERTY_NAME)) {
			return true;
		}
		indigo_usleep(20000);
	}
	fprintf(stderr, "    timeout waiting for the SynScan devices to be defined\n");
	return false;
}

