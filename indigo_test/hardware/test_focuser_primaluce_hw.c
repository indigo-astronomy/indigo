static void primaluce_applies_a_run_preset(void) {
	if (!property_defined(focuser, X_RUNPRESET_PROPERTY_NAME)) {
		printf("    the controller has no run presets\n");
		return;
	}
	static const char *config_items[] = { X_CONFIG_M1ACC_ITEM_NAME, X_CONFIG_M1SPD_ITEM_NAME, X_CONFIG_M1DEC_ITEM_NAME, X_CONFIG_M1CACC_ITEM_NAME, X_CONFIG_M1CSPD_ITEM_NAME, X_CONFIG_M1CDEC_ITEM_NAME, X_CONFIG_M1HOLD_ITEM_NAME };
	unsigned config_before = revision(focuser, X_CONFIG_PROPERTY_NAME);
	ASSERT_TRUE(set_switch(focuser, X_RUNPRESET_PROPERTY_NAME, X_RUNPRESET_M_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	// Applying a preset copies its stored values into the live run configuration, so X_CONFIG must
	// be republished with exactly the values X_RUNPRESET_M reports.
	ASSERT_TRUE(wait_revision(focuser, X_CONFIG_PROPERTY_NAME, config_before, SHORT_TIMEOUT));
	ASSERT_TRUE(property_state(focuser, X_CONFIG_PROPERTY_NAME) == INDIGO_OK_STATE);
	for (unsigned i = 0; i < ARRAY_SIZE(config_items); i++) {
		double stored = 0, live = 0;
		ASSERT_TRUE(number_item(focuser, X_RUNPRESET_M_PROPERTY_NAME, config_items[i], &stored));
		ASSERT_TRUE(number_item(focuser, X_CONFIG_PROPERTY_NAME, config_items[i], &live));
		if (fabs(stored - live) > 0.001) {
			fprintf(stderr, "    X_CONFIG.%s is %.0f but the medium preset stores %.0f\n", config_items[i], live, stored);
		}
		ASSERT_TRUE(fabs(stored - live) < 0.001);
	}
	// A move must still work with the preset applied.
	ASSERT_TRUE(move_to(initial_position + short_travel, MOTION_TIMEOUT));
	ASSERT_TRUE(move_to(initial_position, MOTION_TIMEOUT));
	restore_initial_settings();
	for (unsigned i = 0; i < ARRAY_SIZE(config_items); i++) {
		double live = 0;
		ASSERT_TRUE(number_item(focuser, X_CONFIG_PROPERTY_NAME, config_items[i], &live));
		ASSERT_TRUE(fabs(live - initial_config[i]) < 0.001);
	}
}

