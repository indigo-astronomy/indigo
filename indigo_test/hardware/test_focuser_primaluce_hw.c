static bool connect_device(int d, double timeout) {
	if (d < 0) {
		fprintf(stderr, "    device not present\n");
		return false;
	}
	if (!set_switch(d, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, INDIGO_OK_STATE, timeout)) {
		return false;
	}
	bool connected = false;
	return switch_item(d, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, &connected) && connected;
}

static bool disconnect_device(int d) {
	if (d < 0 || !devices[d].present) {
		return true;
	}
	bool connected = false;
	if (!switch_item(d, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, &connected) || !connected) {
		return true;
	}
	return set_switch(d, CONNECTION_PROPERTY_NAME, CONNECTION_DISCONNECTED_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT);
}

static bool wait_presence(double timeout) {
	double deadline = indigo_monotonic_time() + timeout;
	while (indigo_monotonic_time() < deadline) {
		focuser = device_index(FOCUSER_DEVICE_NAME);
		rotator = device_index(ROTATOR_DEVICE_NAME);
		if (focuser >= 0 && rotator >= 0 && property_defined(focuser, CONNECTION_PROPERTY_NAME) && property_defined(rotator, CONNECTION_PROPERTY_NAME)) {
			return true;
		}
		indigo_usleep(20000);
	}
	fprintf(stderr, "    the driver did not publish both logical devices\n");
	return false;
}

// Points the focuser at the requested port. Without an explicit port the driver's own CP2102N match
// pattern selection is kept, which is what a normal client sees.
static bool select_port(void) {
	if (serial_port == NULL || !*serial_port) {
		char detected[INDIGO_VALUE_SIZE] = "";
		if (text_item(focuser, DEVICE_PORT_PROPERTY_NAME, DEVICE_PORT_ITEM_NAME, detected, sizeof(detected)) && *detected) {
			printf("Using the port the driver detected: %s\n", detected);
			return true;
		}
		fprintf(stderr, "    no serial port was detected, set PRIMALUCE_HW_PORT\n");
		return false;
	}
	printf("Using port %s\n", serial_port);
	unsigned before = revision(focuser, DEVICE_PORT_PROPERTY_NAME);
	indigo_change_text_property_1(&client, FOCUSER_DEVICE_NAME, DEVICE_PORT_PROPERTY_NAME, DEVICE_PORT_ITEM_NAME, serial_port);
	return wait_state(focuser, DEVICE_PORT_PROPERTY_NAME, before, INDIGO_OK_STATE, SHORT_TIMEOUT);
}

// Moves the focuser to an absolute position and waits until the driver reports it arrived there.
static bool move_to(double position, double timeout) {
	unsigned before = revision(focuser, FOCUSER_POSITION_PROPERTY_NAME);
	indigo_change_number_property_1(&client, FOCUSER_DEVICE_NAME, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, position);
	if (!wait_state(focuser, FOCUSER_POSITION_PROPERTY_NAME, before, INDIGO_OK_STATE, timeout)) {
		return false;
	}
	double reached = 0;
	if (!number_item(focuser, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, &reached)) {
		return false;
	}
	if (fabs(reached - position) > 0.5) {
		fprintf(stderr, "    focuser reported OK at %.0f but %.0f was requested\n", reached, position);
		return false;
	}
	return true;
}

// Brings the focuser back to the position the session started from, waiting out a motion an earlier
// scenario may have left running. Keeps one failing scenario from cascading into the next.
static double cached_position(void) {
	double position = 0;
	number_item(focuser, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, &position);
	return position;
}

static bool settle_at_start(void) {
	double deadline = indigo_monotonic_time() + MOTION_TIMEOUT;
	while (indigo_monotonic_time() < deadline && (property_state(focuser, FOCUSER_POSITION_PROPERTY_NAME) == INDIGO_BUSY_STATE || property_state(focuser, FOCUSER_STEPS_PROPERTY_NAME) == INDIGO_BUSY_STATE)) {
		indigo_usleep(20000);
	}
	forget_messages();
	double position = 0;
	if (number_item(focuser, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, &position) && fabs(position - initial_position) < 0.5) {
		return true;
	}
	return move_to(initial_position, MOTION_TIMEOUT);
}

static bool capture_initial_settings(void) {
	static const char *config_items[] = { X_CONFIG_M1ACC_ITEM_NAME, X_CONFIG_M1SPD_ITEM_NAME, X_CONFIG_M1DEC_ITEM_NAME, X_CONFIG_M1CACC_ITEM_NAME, X_CONFIG_M1CSPD_ITEM_NAME, X_CONFIG_M1CDEC_ITEM_NAME, X_CONFIG_M1HOLD_ITEM_NAME };
	if (!number_item(focuser, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, &initial_position)) {
		return false;
	}
	if (!number_item(focuser, FOCUSER_BACKLASH_PROPERTY_NAME, FOCUSER_BACKLASH_ITEM_NAME, &initial_backlash)) {
		return false;
	}
	for (unsigned i = 0; i < ARRAY_SIZE(config_items); i++) {
		if (!number_item(focuser, X_CONFIG_PROPERTY_NAME, config_items[i], initial_config + i)) {
			return false;
		}
	}
	if (!selected_switch(focuser, X_HOLD_CURR_PROPERTY_NAME, initial_hold_current, sizeof(initial_hold_current))) {
		return false;
	}
	if (!selected_switch(focuser, X_LEDS_PROPERTY_NAME, initial_leds, sizeof(initial_leds))) {
		return false;
	}
	settings_captured = true;
	return true;
}

// Restores the controller settings the session changed. The run configuration is restored through
// the preset whose stored values match the configuration found at startup, because X_CONFIG itself
// is read-only.
static void restore_initial_settings(void) {
	static const char *config_items[] = { X_CONFIG_M1ACC_ITEM_NAME, X_CONFIG_M1SPD_ITEM_NAME, X_CONFIG_M1DEC_ITEM_NAME, X_CONFIG_M1CACC_ITEM_NAME, X_CONFIG_M1CSPD_ITEM_NAME, X_CONFIG_M1CDEC_ITEM_NAME, X_CONFIG_M1HOLD_ITEM_NAME };
	if (!settings_captured) {
		return;
	}
	set_number(focuser, FOCUSER_BACKLASH_PROPERTY_NAME, FOCUSER_BACKLASH_ITEM_NAME, initial_backlash, INDIGO_OK_STATE, SHORT_TIMEOUT);
	set_switch(focuser, X_HOLD_CURR_PROPERTY_NAME, initial_hold_current, INDIGO_OK_STATE, SHORT_TIMEOUT);
	set_switch(focuser, X_LEDS_PROPERTY_NAME, initial_leds, INDIGO_OK_STATE, SHORT_TIMEOUT);
	bool restored = true;
	for (unsigned i = 0; i < ARRAY_SIZE(config_items); i++) {
		double value = 0;
		if (!number_item(focuser, X_CONFIG_PROPERTY_NAME, config_items[i], &value) || fabs(value - initial_config[i]) > 0.001) {
			restored = false;
		}
	}
	if (restored) {
		return;
	}
	static const struct { const char *property, *item; } presets[] = {
		{ X_RUNPRESET_L_PROPERTY_NAME, X_RUNPRESET_L_ITEM_NAME },
		{ X_RUNPRESET_M_PROPERTY_NAME, X_RUNPRESET_M_ITEM_NAME },
		{ X_RUNPRESET_S_PROPERTY_NAME, X_RUNPRESET_S_ITEM_NAME }
	};
	for (unsigned p = 0; p < ARRAY_SIZE(presets); p++) {
		bool match = true;
		for (unsigned i = 0; i < ARRAY_SIZE(config_items) && match; i++) {
			double value = 0;
			if (!number_item(focuser, presets[p].property, config_items[i], &value) || fabs(value - initial_config[i]) > 0.001) {
				match = false;
			}
		}
		if (match) {
			if (set_switch(focuser, X_RUNPRESET_PROPERTY_NAME, presets[p].item, INDIGO_OK_STATE, SHORT_TIMEOUT)) {
				printf("Restored the run configuration through preset %s\n", presets[p].property);
			}
			return;
		}
	}
	fprintf(stderr, "    no stored preset matches the run configuration found at startup, it was left as the test set it\n");
}

