	ASSERT_TRUE(number_item(focuser, X_STATE_PROPERTY_NAME, X_STATE_VIN_12V_ITEM_NAME, &vin_12v));
	ASSERT_TRUE(vin_12v >= 0 && vin_12v < 50);
