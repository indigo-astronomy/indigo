static indigo_property_state property_state(int d, const char *name) {
	pthread_mutex_lock(&mutex);
	int p = slot(d, name);
	indigo_property_state state = p < 0 ? INDIGO_IDLE_STATE : devices[d].properties[p]->state;
	pthread_mutex_unlock(&mutex);
	return state;
}

// Waits for a newer revision of the property in the requested state. The revision gate is required
// because the driver republishes the position property from its movement finalizer, so a state the
// property already had before the request must not satisfy the wait.
static bool wait_state(int d, const char *name, unsigned after, indigo_property_state state, double timeout) {
	double deadline = indigo_monotonic_time() + timeout;
	while (indigo_monotonic_time() < deadline) {
		pthread_mutex_lock(&mutex);
		int p = slot(d, name);
		bool ready = p >= 0 && devices[d].revisions[p] > after && devices[d].properties[p]->state == state;
		pthread_mutex_unlock(&mutex);
		if (ready) {
			return true;
		}
		indigo_usleep(20000);
	}
	fprintf(stderr, "    timeout: %s %s expected state %d, last published state %d\n", devices[d].name, name, state, property_state(d, name));
	return false;
}

// Waits for the property to settle in the requested state regardless of how many revisions it took
// to get there. Used where the driver publishes BUSY first and the scenario only cares about the
// terminal state.
static bool wait_settled(int d, const char *name, indigo_property_state state, double timeout) {
	double deadline = indigo_monotonic_time() + timeout;
	while (indigo_monotonic_time() < deadline) {
		if (property_state(d, name) == state) {
			return true;
		}
		indigo_usleep(20000);
	}
	fprintf(stderr, "    timeout: %s %s did not settle in state %d (state %d)\n", devices[d].name, name, state, property_state(d, name));
	return false;
}

static bool wait_revision(int d, const char *name, unsigned after, double timeout) {
	double deadline = indigo_monotonic_time() + timeout;
	while (indigo_monotonic_time() < deadline) {
		if (revision(d, name) > after) {
			return true;
		}
		indigo_usleep(20000);
	}
	fprintf(stderr, "    timeout: %s %s was not republished\n", devices[d].name, name);
	return false;
}

static bool wait_for_message(const char *fragment, double timeout) {
	double deadline = indigo_monotonic_time() + timeout;
	while (indigo_monotonic_time() < deadline) {
		pthread_mutex_lock(&mutex);
		bool found = strstr(last_message_text, fragment) != NULL;
		pthread_mutex_unlock(&mutex);
		if (found) {
			return true;
		}
		indigo_usleep(20000);
	}
	fprintf(stderr, "    timeout: no message containing \"%s\", last message \"%s\"\n", fragment, last_message_text);
	return false;
}

