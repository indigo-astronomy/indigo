// The rotator is a separate logical device sharing the focuser's connection. Connecting it enables
// the controller's ARCO port, and disconnecting it must disable that port again; otherwise the
// controller is left in a different state than the session found it in.
static void primaluce_connects_the_rotator(void) {
	ASSERT_TRUE(settle_at_start());
	double position = 0;
	ASSERT_TRUE(property_defined(rotator, CONNECTION_PROPERTY_NAME));
	ASSERT_TRUE(connect_device(rotator, SHORT_TIMEOUT));
	ASSERT_TRUE((devices[rotator].interface & INDIGO_INTERFACE_ROTATOR) != 0);
	ASSERT_TRUE(property_defined(rotator, ROTATOR_POSITION_PROPERTY_NAME));
	ASSERT_TRUE(property_defined(rotator, ROTATOR_ABORT_MOTION_PROPERTY_NAME));
	ASSERT_TRUE(property_defined(rotator, X_CALIBRATE_R_PROPERTY_NAME));
	ASSERT_TRUE(property_hidden(rotator, ROTATOR_ON_POSITION_SET_PROPERTY_NAME));
	ASSERT_TRUE(number_item(rotator, ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME, &position));
	printf("    rotator reports %.2f degrees\n", position);
	ASSERT_TRUE(disconnect_device(rotator));
	// The focuser must be unaffected by the rotator session: the shared connection stays open and
	// the focuser position code path must still be the one the focuser motor needs.
	ASSERT_TRUE(property_state(focuser, CONNECTION_PROPERTY_NAME) == INDIGO_OK_STATE);
	ASSERT_TRUE(move_to(initial_position + short_travel, MOTION_TIMEOUT));
	ASSERT_TRUE(move_to(initial_position, MOTION_TIMEOUT));
}

static void primaluce_reconnects(void) {
	ASSERT_TRUE(settle_at_start());
	double position = 0;
	ASSERT_TRUE(disconnect_device(focuser));
	ASSERT_TRUE(connect_device(focuser, SHORT_TIMEOUT));
	ASSERT_TRUE(number_item(focuser, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, &position));
	ASSERT_TRUE(fabs(position - initial_position) < 0.5);
	ASSERT_TRUE(move_to(initial_position + short_travel, MOTION_TIMEOUT));
	ASSERT_TRUE(move_to(initial_position, MOTION_TIMEOUT));
}

static void primaluce_reinitializes(void) {
	ASSERT_TRUE(disconnect_device(focuser));
	ASSERT_TRUE(indigo_focuser_primaluce(INDIGO_DRIVER_SHUTDOWN, NULL) == INDIGO_OK);
	ASSERT_TRUE(indigo_focuser_primaluce(INDIGO_DRIVER_INIT, NULL) == INDIGO_OK);
	ASSERT_TRUE(wait_presence(SHORT_TIMEOUT));
	ASSERT_TRUE(select_port());
	ASSERT_TRUE(connect_device(focuser, SHORT_TIMEOUT));
}

int main(int argc, char **argv) {
	if (argc < 2 || strcmp(argv[1], "--run")) {
		fprintf(stderr, "Physical PrimaluceLab focuser test: run explicitly with --run (or make test-focuser-primaluce-hw).\n");
		return 2;
	}
	setvbuf(stdout, NULL, _IONBF, 0);
	if (getenv("PRIMALUCE_HW_DEBUG")) {
		indigo_set_log_level(INDIGO_LOG_DEBUG);
	}
	serial_port = getenv("PRIMALUCE_HW_PORT");
	const char *travel = getenv("PRIMALUCE_HW_TRAVEL");
	if (travel && *travel) {
		long_travel = atof(travel);
		short_travel = long_travel / 10 < 10 ? 10 : long_travel / 10;
	}
	run_calibration = getenv("PRIMALUCE_HW_CALIBRATE") != NULL;
	client = (indigo_client){ .name = "PrimaluceLab hardware test", .version = INDIGO_VERSION_CURRENT, .define_property = define_property, .update_property = update_property, .delete_property = delete_property, .send_message = report_message };
	const indigo_test_case tests[] = {
		{ "primaluce_reports_identity_and_capabilities", primaluce_reports_identity_and_capabilities },
		{ "primaluce_publishes_the_property_contract", primaluce_publishes_the_property_contract },
		{ "primaluce_reads_controller_state", primaluce_reads_controller_state },
		{ "primaluce_polls_controller_state", primaluce_polls_controller_state },
		{ "primaluce_moves_to_an_absolute_position", primaluce_moves_to_an_absolute_position },
		{ "primaluce_moves_by_relative_steps", primaluce_moves_by_relative_steps },
		{ "primaluce_refuses_an_overlapping_request", primaluce_refuses_an_overlapping_request },
		{ "primaluce_aborts_a_move_and_recovers", primaluce_aborts_a_move_and_recovers },
		{ "primaluce_accepts_an_abort_while_idle", primaluce_accepts_an_abort_while_idle },
		{ "primaluce_sets_backlash", primaluce_sets_backlash },
		{ "primaluce_sets_hold_current", primaluce_sets_hold_current },
		{ "primaluce_applies_a_run_preset", primaluce_applies_a_run_preset },
		{ "primaluce_sets_led_modes", primaluce_sets_led_modes },
		{ "primaluce_reads_wifi_settings", primaluce_reads_wifi_settings },
		{ "primaluce_calibrates_the_focuser", primaluce_calibrates_the_focuser },
		{ "primaluce_connects_the_rotator", primaluce_connects_the_rotator },
		{ "primaluce_reconnects", primaluce_reconnects },
		{ "primaluce_reinitializes", primaluce_reinitializes }
	};
	int result = 1;
	bool started = false, initialized = false;
	CHECK(indigo_start() == INDIGO_OK);
	started = true;
	CHECK(indigo_attach_client(&client) == INDIGO_OK);
	CHECK(indigo_focuser_primaluce(INDIGO_DRIVER_INIT, NULL) == INDIGO_OK);
	initialized = true;
	CHECK(wait_presence(SHORT_TIMEOUT));
	CHECK(select_port());
	CHECK(connect_device(focuser, SHORT_TIMEOUT));
	CHECK(capture_initial_settings());
	printf("Starting position %.0f, backlash %.0f, hold current %s, LEDs %s\n", initial_position, initial_backlash, initial_hold_current, initial_leds);
	result = indigo_run_tests("PrimaluceLab focuser hardware", tests, ARRAY_SIZE(tests));
cleanup:
	if (focuser >= 0 && devices[focuser].present) {
		set_switch(focuser, FOCUSER_ABORT_MOTION_PROPERTY_NAME, FOCUSER_ABORT_MOTION_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT);
		restore_initial_settings();
		// Put the draw tube back where the session found it.
		if (settings_captured && move_to(initial_position, MOTION_TIMEOUT)) {
			printf("Restored the starting position %.0f\n", initial_position);
		}
	}
	if (!disconnect_device(rotator) || !disconnect_device(focuser)) {
		indigo_test_failures++;
	}
	if (initialized && indigo_focuser_primaluce(INDIGO_DRIVER_SHUTDOWN, NULL) != INDIGO_OK) {
		indigo_test_failures++;
	}
	indigo_detach_client(&client);
	if (started) {
		indigo_stop();
	}
	for (int d = 0; d < MAX_DEVICES; d++) {
		for (int p = 0; p < MAX_PROPERTIES; p++) {
			indigo_release_property(devices[d].properties[p]);
		}
	}
	return indigo_test_failures ? 1 : result;
}
