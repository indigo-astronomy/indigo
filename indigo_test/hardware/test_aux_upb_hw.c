// Code is generated by AI

// Opt-in acceptance test for a physically connected Pegasus Ultimate Powerbox. It runs the AUX
// acceptance checklist of DRIVER_TESTING_RULES.md against the real box: connection, identity and
// model dependent inventory, the sensor readings and their polling, every power outlet, the heater
// outlets, dew control, the USB control the model provides, outlet naming, reconnect and driver
// reinitialization.
//
// THE POWER OUTLETS ARE PHYSICALLY SWITCHED. Every outlet this test touches is switched back to
// the state it had when the session started, and the session restores the heaters, the dew mode
// and the USB control as well, but anything powered through the box loses power for the duration
// of its scenario. Run it only on a box whose outlets are free.
//
// The serial port comes from UPB_HW_PORT. When it is not set the port the driver itself detected
// is used.

#include <limits.h>
#include <math.h>
#include <pthread.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
#include <indigo/indigo_bus.h>
#include <indigo/indigo_client.h>
#include <indigo/indigo_driver.h>
#include <indigo/indigo_names.h>
#include <indigo/indigo_timer.h>
#include <indigo_drivers/aux_upb/indigo_aux_upb.h>
#include "../test_runner.h"

#define ARRAY_SIZE(a) (sizeof(a) / sizeof((a)[0]))
#define MAX_DEVICES 4
#define MAX_PROPERTIES 64

#define AUX_DEVICE_NAME "Ultimate Powerbox"
#define FOCUSER_DEVICE_NAME "Ultimate Powerbox (focuser)"

// Driver-defined property names, declared in the generated source rather than in the header.
#define X_AUX_HUB_PROPERTY_NAME "X_AUX_HUB"
#define X_AUX_HUB_ENABLED_ITEM_NAME "ENABLED"
#define X_AUX_HUB_DISABLED_ITEM_NAME "DISABLED"
#define X_AUX_VARIABLE_PROPERTY_NAME "X_AUX_VARIABLE_POWER_OUTLET"
#define X_AUX_VARIABLE_ITEM_NAME "OUTLET_1"

// One serialized request over the link plus the box's own reply latency.
#define SHORT_TIMEOUT 15.0
// The status handler runs every few seconds, so this covers two periods.
#define POLL_TIMEOUT 25.0

#define CHECK(condition) do { if (!(condition)) { fprintf(stderr, "%s:%d: %s\n", __FILE__, __LINE__, #condition); indigo_test_failures++; goto cleanup; } } while (0)

typedef struct {
	char name[INDIGO_NAME_SIZE];
	indigo_device *device;
	unsigned interface;
	bool present;
	indigo_property *properties[MAX_PROPERTIES];
	unsigned revisions[MAX_PROPERTIES];
} observed_device;

static observed_device devices[MAX_DEVICES];
static pthread_mutex_t mutex = PTHREAD_MUTEX_INITIALIZER;
static int aux = -1, focuser = -1;
static indigo_client client;
static const char *serial_port = NULL;

// The box state captured once it is connected. Every scenario works relative to these values and
// the session restores them before it disconnects.
static bool outlets_initial[4];
static double heaters_initial[3];
static char dew_initial[INDIGO_NAME_SIZE], hub_initial[INDIGO_NAME_SIZE];
static double variable_initial;
static int outlet_count, heater_count;
static bool has_hub, has_variable, has_usb_ports;
static bool settings_captured;

static int slot(int d, const char *name) {
	for (int p = 0; p < MAX_PROPERTIES; p++) {
		if (devices[d].properties[p] && !strcmp(devices[d].properties[p]->name, name)) {
			return p;
		}
	}
	return -1;
}

static indigo_result observe(indigo_device *device, indigo_property *property, const char *message) {
	pthread_mutex_lock(&mutex);
	int d;
	for (d = 0; d < MAX_DEVICES; d++) {
		if (!*devices[d].name || !strcmp(devices[d].name, property->device)) {
			break;
		}
	}
	if (d < MAX_DEVICES) {
		snprintf(devices[d].name, INDIGO_NAME_SIZE, "%s", property->device);
		devices[d].device = device;
		devices[d].present = true;
		if (!strcmp(property->name, INFO_PROPERTY_NAME)) {
			for (int i = 0; i < property->count; i++) {
				if (!strcmp(property->items[i].name, INFO_DEVICE_INTERFACE_ITEM_NAME)) {
					devices[d].interface = (unsigned)strtoul(property->items[i].text.value, NULL, 10);
				}
			}
		}
		int p = slot(d, property->name);
		if (p < 0) {
			for (p = 0; p < MAX_PROPERTIES && devices[d].properties[p]; p++) { }
		}
		if (p < MAX_PROPERTIES) {
			indigo_release_property(devices[d].properties[p]);
			devices[d].properties[p] = indigo_copy_property(NULL, property);
			devices[d].revisions[p]++;
		}
	}
	pthread_mutex_unlock(&mutex);
	if (message && *message) {
		fprintf(stderr, "    %s %s: %s\n", property->device, property->name, message);
	}
	return INDIGO_OK;
}

static indigo_result define_property(indigo_client *client, indigo_device *device, indigo_property *property, const char *message) {
	return observe(device, property, message);
}

static indigo_result update_property(indigo_client *client, indigo_device *device, indigo_property *property, const char *message) {
	return observe(device, property, message);
}

static indigo_result report_message(indigo_client *client, indigo_device *device, indigo_property *property, const char *message) {
	if (message && *message) {
		fprintf(stderr, "    message: %s\n", message);
	}
	return INDIGO_OK;
}

static indigo_result delete_property(indigo_client *client, indigo_device *device, indigo_property *property, const char *message) {
	pthread_mutex_lock(&mutex);
	for (int d = 0; d < MAX_DEVICES; d++) {
		if (strcmp(devices[d].name, property->device)) {
			continue;
		}
		if (*property->name) {
			int p = slot(d, property->name);
			if (p >= 0) {
				indigo_release_property(devices[d].properties[p]);
				devices[d].properties[p] = NULL;
				devices[d].revisions[p] = 0;
			}
		} else {
			devices[d].present = false;
			for (int p = 0; p < MAX_PROPERTIES; p++) {
				indigo_release_property(devices[d].properties[p]);
				devices[d].properties[p] = NULL;
				devices[d].revisions[p] = 0;
			}
		}
	}
	pthread_mutex_unlock(&mutex);
	return INDIGO_OK;
}

static int device_index(const char *name) {
	pthread_mutex_lock(&mutex);
	int result = -1;
	for (int d = 0; d < MAX_DEVICES; d++) {
		if (!strcmp(devices[d].name, name)) {
			result = d;
		}
	}
	pthread_mutex_unlock(&mutex);
	return result;
}

static unsigned revision(int d, const char *name) {
	pthread_mutex_lock(&mutex);
	int p = slot(d, name);
	unsigned result = p < 0 ? 0 : devices[d].revisions[p];
	pthread_mutex_unlock(&mutex);
	return result;
}

static bool property_defined(int d, const char *name) {
	pthread_mutex_lock(&mutex);
	bool found = slot(d, name) >= 0;
	pthread_mutex_unlock(&mutex);
	return found;
}

static int property_count(int d, const char *name) {
	pthread_mutex_lock(&mutex);
	int p = slot(d, name);
	int result = p < 0 ? -1 : devices[d].properties[p]->count;
	pthread_mutex_unlock(&mutex);
	return result;
}

static bool number_item(int d, const char *name, const char *item, double *value) {
	pthread_mutex_lock(&mutex);
	bool found = false;
	int p = slot(d, name);
	if (p >= 0) {
		indigo_property *property = devices[d].properties[p];
		for (int i = 0; i < property->count; i++) {
			if (!strcmp(property->items[i].name, item)) {
				*value = property->items[i].number.value;
				found = true;
			}
		}
	}
	pthread_mutex_unlock(&mutex);
	if (!found) {
		fprintf(stderr, "    %s.%s is missing\n", name, item);
	}
	return found;
}

static bool switch_item(int d, const char *name, const char *item, bool *value) {
	pthread_mutex_lock(&mutex);
	bool found = false;
	int p = slot(d, name);
	if (p >= 0) {
		indigo_property *property = devices[d].properties[p];
		for (int i = 0; i < property->count; i++) {
			if (!strcmp(property->items[i].name, item)) {
				*value = property->items[i].sw.value;
				found = true;
			}
		}
	}
	pthread_mutex_unlock(&mutex);
	if (!found) {
		fprintf(stderr, "    %s.%s is missing\n", name, item);
	}
	return found;
}

static bool selected_switch(int d, const char *name, char *item, size_t size) {
	pthread_mutex_lock(&mutex);
	bool found = false;
	int p = slot(d, name);
	if (p >= 0) {
		indigo_property *property = devices[d].properties[p];
		for (int i = 0; i < property->count; i++) {
			if (property->items[i].sw.value) {
				snprintf(item, size, "%s", property->items[i].name);
				found = true;
			}
		}
	}
	pthread_mutex_unlock(&mutex);
	return found;
}

static bool item_name_at(int d, const char *name, int index, char *item, size_t size) {
	pthread_mutex_lock(&mutex);
	bool found = false;
	int p = slot(d, name);
	if (p >= 0 && index < devices[d].properties[p]->count) {
		snprintf(item, size, "%s", devices[d].properties[p]->items[index].name);
		found = true;
	}
	pthread_mutex_unlock(&mutex);
	return found;
}

static bool wait_settled(int d, const char *name, indigo_property_state state, double timeout) {
	double deadline = indigo_monotonic_time() + timeout;
	while (indigo_monotonic_time() < deadline) {
		pthread_mutex_lock(&mutex);
		int p = slot(d, name);
		bool done = p >= 0 && devices[d].properties[p]->state == state;
		pthread_mutex_unlock(&mutex);
		if (done) {
			return true;
		}
		indigo_usleep(100000);
	}
	fprintf(stderr, "    %s did not settle in state %d\n", name, state);
	return false;
}

static bool wait_revision(int d, const char *name, unsigned after, double timeout) {
	double deadline = indigo_monotonic_time() + timeout;
	while (indigo_monotonic_time() < deadline) {
		if (revision(d, name) > after) {
			return true;
		}
		indigo_usleep(100000);
	}
	fprintf(stderr, "    %s was not published again\n", name);
	return false;
}

static bool wait_switch_item(int d, const char *name, const char *item, bool expected, double timeout) {
	double deadline = indigo_monotonic_time() + timeout;
	while (indigo_monotonic_time() < deadline) {
		bool value = false;
		if (switch_item(d, name, item, &value) && value == expected) {
			return true;
		}
		indigo_usleep(100000);
	}
	fprintf(stderr, "    %s.%s did not become %s\n", name, item, expected ? "on" : "off");
	return false;
}

static bool wait_number_item(int d, const char *name, const char *item, double expected, double tolerance, double timeout) {
	double deadline = indigo_monotonic_time() + timeout;
	while (indigo_monotonic_time() < deadline) {
		double value = 0;
		if (number_item(d, name, item, &value) && fabs(value - expected) <= tolerance) {
			return true;
		}
		indigo_usleep(100000);
	}
	fprintf(stderr, "    %s.%s did not reach %g\n", name, item, expected);
	return false;
}

// Every request waits for the property to settle first, because the change dispatch drops a
// request that arrives while the property is still BUSY.
static bool set_switch(int d, const char *name, const char *item, bool value, double timeout) {
	if (!wait_settled(d, name, INDIGO_OK_STATE, timeout)) {
		return false;
	}
	if (indigo_change_switch_property_1(&client, devices[d].name, name, item, value) != INDIGO_OK) {
		return false;
	}
	return wait_settled(d, name, INDIGO_OK_STATE, timeout);
}

static bool set_number(int d, const char *name, const char *item, double value, double timeout) {
	if (!wait_settled(d, name, INDIGO_OK_STATE, timeout)) {
		return false;
	}
	if (indigo_change_number_property_1(&client, devices[d].name, name, item, value) != INDIGO_OK) {
		return false;
	}
	return wait_settled(d, name, INDIGO_OK_STATE, timeout);
}

static bool connect_device(int d, double timeout) {
	if (d < 0) {
		return false;
	}
	bool connected = false;
	if (switch_item(d, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, &connected) && connected) {
		return true;
	}
	unsigned before = revision(d, CONNECTION_PROPERTY_NAME);
	indigo_change_switch_property_1(&client, devices[d].name, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, true);
	if (!wait_revision(d, CONNECTION_PROPERTY_NAME, before, timeout) || !wait_settled(d, CONNECTION_PROPERTY_NAME, INDIGO_OK_STATE, timeout)) {
		return false;
	}
	return switch_item(d, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, &connected) && connected;
}

static bool disconnect_device(int d) {
	if (d < 0 || !devices[d].present) {
		return true;
	}
	bool connected = false;
	if (switch_item(d, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, &connected) && !connected) {
		return true;
	}
	indigo_change_switch_property_1(&client, devices[d].name, CONNECTION_PROPERTY_NAME, CONNECTION_DISCONNECTED_ITEM_NAME, true);
	return wait_settled(d, CONNECTION_PROPERTY_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT);
}

static bool wait_presence(double timeout) {
	double deadline = indigo_monotonic_time() + timeout;
	while (indigo_monotonic_time() < deadline) {
		aux = device_index(AUX_DEVICE_NAME);
		focuser = device_index(FOCUSER_DEVICE_NAME);
		if (aux >= 0) {
			return true;
		}
		indigo_usleep(100000);
	}
	fprintf(stderr, "    %s never appeared\n", AUX_DEVICE_NAME);
	return false;
}

static bool select_port(void) {
	if (serial_port == NULL) {
		char detected[INDIGO_VALUE_SIZE] = "";
		pthread_mutex_lock(&mutex);
		int p = slot(aux, DEVICE_PORT_PROPERTY_NAME);
		if (p >= 0 && devices[aux].properties[p]->count > 0) {
			snprintf(detected, sizeof(detected), "%s", devices[aux].properties[p]->items[0].text.value);
		}
		pthread_mutex_unlock(&mutex);
		if (*detected) {
			printf("    using the detected port %s\n", detected);
			return true;
		}
		fprintf(stderr, "    no port was detected; set UPB_HW_PORT\n");
		return false;
	}
	unsigned before = revision(aux, DEVICE_PORT_PROPERTY_NAME);
	indigo_change_text_property_1(&client, AUX_DEVICE_NAME, DEVICE_PORT_PROPERTY_NAME, DEVICE_PORT_ITEM_NAME, serial_port);
	return wait_revision(aux, DEVICE_PORT_PROPERTY_NAME, before, SHORT_TIMEOUT);
}

// Capture what the box looked like when the session started, so every scenario can put it back.
static bool capture_initial_settings(void) {
	outlet_count = property_count(aux, AUX_POWER_OUTLET_PROPERTY_NAME);
	heater_count = property_count(aux, AUX_HEATER_OUTLET_PROPERTY_NAME);
	has_hub = property_defined(aux, X_AUX_HUB_PROPERTY_NAME);
	has_variable = property_defined(aux, X_AUX_VARIABLE_PROPERTY_NAME);
	has_usb_ports = property_defined(aux, AUX_USB_PORT_PROPERTY_NAME);
	if (outlet_count < 1 || heater_count < 1) {
		return false;
	}
	for (int i = 0; i < outlet_count && i < 4; i++) {
		char item[INDIGO_NAME_SIZE];
		if (!item_name_at(aux, AUX_POWER_OUTLET_PROPERTY_NAME, i, item, sizeof(item)) || !switch_item(aux, AUX_POWER_OUTLET_PROPERTY_NAME, item, outlets_initial + i)) {
			return false;
		}
	}
	for (int i = 0; i < heater_count && i < 3; i++) {
		char item[INDIGO_NAME_SIZE];
		if (!item_name_at(aux, AUX_HEATER_OUTLET_PROPERTY_NAME, i, item, sizeof(item)) || !number_item(aux, AUX_HEATER_OUTLET_PROPERTY_NAME, item, heaters_initial + i)) {
			return false;
		}
	}
	if (!selected_switch(aux, AUX_DEW_CONTROL_PROPERTY_NAME, dew_initial, sizeof(dew_initial))) {
		return false;
	}
	if (has_hub && !selected_switch(aux, X_AUX_HUB_PROPERTY_NAME, hub_initial, sizeof(hub_initial))) {
		return false;
	}
	if (has_variable && !number_item(aux, X_AUX_VARIABLE_PROPERTY_NAME, X_AUX_VARIABLE_ITEM_NAME, &variable_initial)) {
		return false;
	}
	settings_captured = true;
	return true;
}

static void restore_initial_settings(void) {
	if (!settings_captured) {
		return;
	}
	for (int i = 0; i < heater_count && i < 3; i++) {
		char item[INDIGO_NAME_SIZE];
		if (item_name_at(aux, AUX_HEATER_OUTLET_PROPERTY_NAME, i, item, sizeof(item))) {
			set_number(aux, AUX_HEATER_OUTLET_PROPERTY_NAME, item, heaters_initial[i], SHORT_TIMEOUT);
		}
	}
	for (int i = 0; i < outlet_count && i < 4; i++) {
		char item[INDIGO_NAME_SIZE];
		if (item_name_at(aux, AUX_POWER_OUTLET_PROPERTY_NAME, i, item, sizeof(item))) {
			set_switch(aux, AUX_POWER_OUTLET_PROPERTY_NAME, item, outlets_initial[i], SHORT_TIMEOUT);
		}
	}
	if (*dew_initial) {
		set_switch(aux, AUX_DEW_CONTROL_PROPERTY_NAME, dew_initial, true, SHORT_TIMEOUT);
	}
	if (has_hub && *hub_initial) {
		set_switch(aux, X_AUX_HUB_PROPERTY_NAME, hub_initial, true, SHORT_TIMEOUT);
	}
	if (has_variable) {
		set_number(aux, X_AUX_VARIABLE_PROPERTY_NAME, X_AUX_VARIABLE_ITEM_NAME, variable_initial, SHORT_TIMEOUT);
	}
}

