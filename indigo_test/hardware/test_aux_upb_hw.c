static void upb_reports_identity_and_capabilities(void) {
	char model[INDIGO_VALUE_SIZE] = "", revision_text[INDIGO_VALUE_SIZE] = "";
	pthread_mutex_lock(&mutex);
	int p = slot(aux, INFO_PROPERTY_NAME);
	if (p >= 0) {
		indigo_property *info = devices[aux].properties[p];
		for (int i = 0; i < info->count; i++) {
			if (!strcmp(info->items[i].name, INFO_DEVICE_MODEL_ITEM_NAME)) {
				snprintf(model, sizeof(model), "%s", info->items[i].text.value);
			} else if (!strcmp(info->items[i].name, INFO_DEVICE_FW_REVISION_ITEM_NAME)) {
				snprintf(revision_text, sizeof(revision_text), "%s", info->items[i].text.value);
			}
		}
	}
	pthread_mutex_unlock(&mutex);
	printf("    model '%s', firmware '%s', %d outlets, %d heaters, hub %s, usb ports %s, variable %s\n", model, revision_text, outlet_count, heater_count, has_hub ? "yes" : "no", has_usb_ports ? "yes" : "no", has_variable ? "yes" : "no");
	ASSERT_TRUE(devices[aux].interface & INDIGO_INTERFACE_AUX_POWERBOX);
	// The identified model has to replace the placeholder the attach handler seeds.
	ASSERT_TRUE(*model && strcmp(model, "Unknown"));
	ASSERT_TRUE(*revision_text && strcmp(revision_text, "Unknown"));
	ASSERT_EQ_INT(4, outlet_count);
	// The v1 box has two heaters and no variable voltage output, the v2 has three of each.
	ASSERT_TRUE(heater_count == 2 || heater_count == 3);
	ASSERT_EQ_INT(heater_count == 3, has_variable);
	// The hub switch belongs to the v1 box; the v2 switches its ports individually.
	ASSERT_TRUE(heater_count == 3 || has_hub);
}

static void upb_publishes_the_property_contract(void) {
	ASSERT_TRUE(property_defined(aux, AUX_POWER_OUTLET_PROPERTY_NAME));
	ASSERT_TRUE(property_defined(aux, AUX_POWER_OUTLET_STATE_PROPERTY_NAME));
	ASSERT_TRUE(property_defined(aux, AUX_POWER_OUTLET_CURRENT_PROPERTY_NAME));
	ASSERT_TRUE(property_defined(aux, AUX_HEATER_OUTLET_PROPERTY_NAME));
	ASSERT_TRUE(property_defined(aux, AUX_HEATER_OUTLET_STATE_PROPERTY_NAME));
	ASSERT_TRUE(property_defined(aux, AUX_HEATER_OUTLET_CURRENT_PROPERTY_NAME));
	ASSERT_TRUE(property_defined(aux, AUX_DEW_CONTROL_PROPERTY_NAME));
	ASSERT_TRUE(property_defined(aux, AUX_WEATHER_PROPERTY_NAME));
	ASSERT_TRUE(property_defined(aux, AUX_INFO_PROPERTY_NAME));
	ASSERT_TRUE(property_defined(aux, AUX_OUTLET_NAMES_PROPERTY_NAME));
	ASSERT_TRUE(property_defined(aux, AUX_SAVE_OUTLET_STATES_AS_DEFAULT_PROPERTY_NAME));
	ASSERT_EQ_INT(outlet_count, property_count(aux, AUX_POWER_OUTLET_STATE_PROPERTY_NAME));
	ASSERT_EQ_INT(outlet_count, property_count(aux, AUX_POWER_OUTLET_CURRENT_PROPERTY_NAME));
	ASSERT_EQ_INT(heater_count, property_count(aux, AUX_HEATER_OUTLET_STATE_PROPERTY_NAME));
	ASSERT_EQ_INT(heater_count, property_count(aux, AUX_HEATER_OUTLET_CURRENT_PROPERTY_NAME));
}

static void upb_reads_its_sensors(void) {
	double voltage = 0, current = 0, temperature = 0, humidity = 0, dewpoint = 0;
	ASSERT_TRUE(number_item(aux, AUX_INFO_PROPERTY_NAME, AUX_INFO_VOLTAGE_ITEM_NAME, &voltage));
	ASSERT_TRUE(number_item(aux, AUX_INFO_PROPERTY_NAME, AUX_INFO_CURRENT_ITEM_NAME, &current));
	ASSERT_TRUE(number_item(aux, AUX_WEATHER_PROPERTY_NAME, AUX_WEATHER_TEMPERATURE_ITEM_NAME, &temperature));
	ASSERT_TRUE(number_item(aux, AUX_WEATHER_PROPERTY_NAME, AUX_WEATHER_HUMIDITY_ITEM_NAME, &humidity));
	ASSERT_TRUE(number_item(aux, AUX_WEATHER_PROPERTY_NAME, AUX_WEATHER_DEWPOINT_ITEM_NAME, &dewpoint));
	printf("    %.1f V, %.2f A, %.1f C, %.0f %%RH, dewpoint %.1f C\n", voltage, current, temperature, humidity, dewpoint);
	// A powered box reads a plausible supply voltage; the sensors are on the same frame.
	ASSERT_TRUE(voltage > 5 && voltage < 30);
	ASSERT_TRUE(current >= 0 && current < 30);
	ASSERT_TRUE(humidity >= 0 && humidity <= 100);
}

static void upb_polls_its_sensors(void) {
	unsigned before = revision(aux, AUX_INFO_PROPERTY_NAME);
	ASSERT_TRUE(wait_revision(aux, AUX_INFO_PROPERTY_NAME, before, POLL_TIMEOUT));
}

// Each outlet is switched to the opposite of what it was, read back, and put back.
static void upb_switches_every_power_outlet(void) {
	for (int i = 0; i < outlet_count && i < 4; i++) {
		char item[INDIGO_NAME_SIZE];
		ASSERT_TRUE(item_name_at(aux, AUX_POWER_OUTLET_PROPERTY_NAME, i, item, sizeof(item)));
		bool target = !outlets_initial[i];
		ASSERT_TRUE(set_switch(aux, AUX_POWER_OUTLET_PROPERTY_NAME, item, target, SHORT_TIMEOUT));
		// The status poll reads the outlet mask back, so the new state has to survive it.
		ASSERT_TRUE(wait_switch_item(aux, AUX_POWER_OUTLET_PROPERTY_NAME, item, target, POLL_TIMEOUT));
		ASSERT_TRUE(set_switch(aux, AUX_POWER_OUTLET_PROPERTY_NAME, item, outlets_initial[i], SHORT_TIMEOUT));
		ASSERT_TRUE(wait_switch_item(aux, AUX_POWER_OUTLET_PROPERTY_NAME, item, outlets_initial[i], POLL_TIMEOUT));
	}
}

// A switched outlet draws through the box's own shunt, so its state light follows the switch.
static void upb_reports_outlet_state_and_current(void) {
	char item[INDIGO_NAME_SIZE], current_item[INDIGO_NAME_SIZE];
	ASSERT_TRUE(item_name_at(aux, AUX_POWER_OUTLET_PROPERTY_NAME, 0, item, sizeof(item)));
	ASSERT_TRUE(item_name_at(aux, AUX_POWER_OUTLET_CURRENT_PROPERTY_NAME, 0, current_item, sizeof(current_item)));
	double current = 0;
	ASSERT_TRUE(number_item(aux, AUX_POWER_OUTLET_CURRENT_PROPERTY_NAME, current_item, &current));
	ASSERT_TRUE(current >= 0);
	ASSERT_TRUE(set_switch(aux, AUX_POWER_OUTLET_PROPERTY_NAME, item, true, SHORT_TIMEOUT));
	// The state light is republished only when a flag actually changes, so the value is what
	// matters: a healthy switched-on outlet is OK rather than ALERT.
	double state_value = 0;
	ASSERT_TRUE(wait_settled(aux, AUX_POWER_OUTLET_STATE_PROPERTY_NAME, INDIGO_OK_STATE, POLL_TIMEOUT));
	pthread_mutex_lock(&mutex);
	int sp = slot(aux, AUX_POWER_OUTLET_STATE_PROPERTY_NAME);
	if (sp >= 0 && devices[aux].properties[sp]->count > 0) {
		state_value = devices[aux].properties[sp]->items[0].light.value;
	}
	pthread_mutex_unlock(&mutex);
	printf("    outlet 1 state light %g, current %.2f A\n", state_value, current);
	ASSERT_TRUE(state_value != INDIGO_ALERT_STATE);
	ASSERT_TRUE(set_switch(aux, AUX_POWER_OUTLET_PROPERTY_NAME, item, outlets_initial[0], SHORT_TIMEOUT));
}

static void upb_sets_heater_duty_cycles(void) {
	for (int i = 0; i < heater_count && i < 3; i++) {
		char item[INDIGO_NAME_SIZE];
		ASSERT_TRUE(item_name_at(aux, AUX_HEATER_OUTLET_PROPERTY_NAME, i, item, sizeof(item)));
		ASSERT_TRUE(set_number(aux, AUX_HEATER_OUTLET_PROPERTY_NAME, item, 20, SHORT_TIMEOUT));
		// The box stores the duty cycle as 0..255, so the readback is rounded.
		ASSERT_TRUE(wait_number_item(aux, AUX_HEATER_OUTLET_PROPERTY_NAME, item, 20, 1, POLL_TIMEOUT));
		ASSERT_TRUE(set_number(aux, AUX_HEATER_OUTLET_PROPERTY_NAME, item, heaters_initial[i], SHORT_TIMEOUT));
		ASSERT_TRUE(wait_number_item(aux, AUX_HEATER_OUTLET_PROPERTY_NAME, item, heaters_initial[i], 1, POLL_TIMEOUT));
	}
}

static void upb_switches_dew_control(void) {
	ASSERT_TRUE(set_switch(aux, AUX_DEW_CONTROL_PROPERTY_NAME, AUX_DEW_CONTROL_AUTOMATIC_ITEM_NAME, true, SHORT_TIMEOUT));
	ASSERT_TRUE(wait_switch_item(aux, AUX_DEW_CONTROL_PROPERTY_NAME, AUX_DEW_CONTROL_AUTOMATIC_ITEM_NAME, true, POLL_TIMEOUT));
	ASSERT_TRUE(set_switch(aux, AUX_DEW_CONTROL_PROPERTY_NAME, AUX_DEW_CONTROL_MANUAL_ITEM_NAME, true, SHORT_TIMEOUT));
	ASSERT_TRUE(wait_switch_item(aux, AUX_DEW_CONTROL_PROPERTY_NAME, AUX_DEW_CONTROL_MANUAL_ITEM_NAME, true, POLL_TIMEOUT));
	ASSERT_TRUE(set_switch(aux, AUX_DEW_CONTROL_PROPERTY_NAME, dew_initial, true, SHORT_TIMEOUT));
}

static void upb_switches_the_usb_control(void) {
	if (has_usb_ports) {
		// The v2 box switches its ports itself.
		char item[INDIGO_NAME_SIZE];
		ASSERT_TRUE(item_name_at(aux, AUX_USB_PORT_PROPERTY_NAME, 0, item, sizeof(item)));
		bool initial = false;
		ASSERT_TRUE(switch_item(aux, AUX_USB_PORT_PROPERTY_NAME, item, &initial));
		ASSERT_TRUE(set_switch(aux, AUX_USB_PORT_PROPERTY_NAME, item, !initial, SHORT_TIMEOUT));
		ASSERT_TRUE(wait_switch_item(aux, AUX_USB_PORT_PROPERTY_NAME, item, !initial, POLL_TIMEOUT));
		ASSERT_TRUE(set_switch(aux, AUX_USB_PORT_PROPERTY_NAME, item, initial, SHORT_TIMEOUT));
	} else if (has_hub) {
		ASSERT_TRUE(set_switch(aux, X_AUX_HUB_PROPERTY_NAME, X_AUX_HUB_DISABLED_ITEM_NAME, true, SHORT_TIMEOUT));
		ASSERT_TRUE(set_switch(aux, X_AUX_HUB_PROPERTY_NAME, X_AUX_HUB_ENABLED_ITEM_NAME, true, SHORT_TIMEOUT));
		ASSERT_TRUE(set_switch(aux, X_AUX_HUB_PROPERTY_NAME, hub_initial, true, SHORT_TIMEOUT));
	} else {
		printf("    no USB control on this model\n");
	}
}

static void upb_sets_the_variable_outlet(void) {
	if (!has_variable) {
		printf("    no variable voltage outlet on this model\n");
		return;
	}
	ASSERT_TRUE(set_number(aux, X_AUX_VARIABLE_PROPERTY_NAME, X_AUX_VARIABLE_ITEM_NAME, 5, SHORT_TIMEOUT));
	ASSERT_TRUE(set_number(aux, X_AUX_VARIABLE_PROPERTY_NAME, X_AUX_VARIABLE_ITEM_NAME, variable_initial, SHORT_TIMEOUT));
}

static void upb_renames_an_outlet(void) {
	char original[INDIGO_VALUE_SIZE] = "";
	pthread_mutex_lock(&mutex);
	int p = slot(aux, AUX_OUTLET_NAMES_PROPERTY_NAME);
	if (p >= 0 && devices[aux].properties[p]->count > 0) {
		snprintf(original, sizeof(original), "%s", devices[aux].properties[p]->items[0].text.value);
	}
	pthread_mutex_unlock(&mutex);
	ASSERT_TRUE(*original);
	char item[INDIGO_NAME_SIZE];
	ASSERT_TRUE(item_name_at(aux, AUX_OUTLET_NAMES_PROPERTY_NAME, 0, item, sizeof(item)));
	indigo_change_text_property_1(&client, AUX_DEVICE_NAME, AUX_OUTLET_NAMES_PROPERTY_NAME, item, "HW test");
	ASSERT_TRUE(wait_settled(aux, AUX_OUTLET_NAMES_PROPERTY_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	indigo_change_text_property_1(&client, AUX_DEVICE_NAME, AUX_OUTLET_NAMES_PROPERTY_NAME, item, original);
	ASSERT_TRUE(wait_settled(aux, AUX_OUTLET_NAMES_PROPERTY_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
}

// The focuser shares the box's connection. It is exercised only as far as a box without a motor
// allows: it has to come up, publish its contract and read its position back.
static void upb_connects_the_focuser(void) {
	if (focuser < 0) {
		focuser = device_index(FOCUSER_DEVICE_NAME);
	}
	if (focuser < 0) {
		printf("    the focuser device is not published\n");
		return;
	}
	ASSERT_TRUE(connect_device(focuser, SHORT_TIMEOUT));
	ASSERT_TRUE(devices[focuser].interface & INDIGO_INTERFACE_FOCUSER);
	ASSERT_TRUE(property_defined(focuser, FOCUSER_POSITION_PROPERTY_NAME));
	ASSERT_TRUE(property_defined(focuser, FOCUSER_STEPS_PROPERTY_NAME));
	ASSERT_TRUE(property_defined(focuser, FOCUSER_ABORT_MOTION_PROPERTY_NAME));
	double position = 0, temperature = 0;
	ASSERT_TRUE(number_item(focuser, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, &position));
	ASSERT_TRUE(number_item(focuser, FOCUSER_TEMPERATURE_PROPERTY_NAME, FOCUSER_TEMPERATURE_ITEM_NAME, &temperature));
	printf("    focuser position %.0f, temperature %.1f C\n", position, temperature);
	// An abort while the motor is idle is harmless and must be accepted.
	ASSERT_TRUE(set_switch(focuser, FOCUSER_ABORT_MOTION_PROPERTY_NAME, FOCUSER_ABORT_MOTION_ITEM_NAME, true, SHORT_TIMEOUT));
	ASSERT_TRUE(disconnect_device(focuser));
	// Closing the focuser must not take the powerbox connection down with it.
	bool connected = false;
	ASSERT_TRUE(switch_item(aux, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, &connected) && connected);
}

static void upb_reconnects(void) {
	ASSERT_TRUE(disconnect_device(aux));
	ASSERT_TRUE(connect_device(aux, SHORT_TIMEOUT));
	double voltage = 0;
	ASSERT_TRUE(wait_settled(aux, AUX_INFO_PROPERTY_NAME, INDIGO_OK_STATE, POLL_TIMEOUT));
	ASSERT_TRUE(number_item(aux, AUX_INFO_PROPERTY_NAME, AUX_INFO_VOLTAGE_ITEM_NAME, &voltage));
	ASSERT_TRUE(voltage > 5);
}

static void upb_reinitializes(void) {
	ASSERT_TRUE(disconnect_device(aux));
	ASSERT_TRUE(indigo_aux_upb(INDIGO_DRIVER_SHUTDOWN, NULL) == INDIGO_OK);
	ASSERT_TRUE(indigo_aux_upb(INDIGO_DRIVER_INIT, NULL) == INDIGO_OK);
	ASSERT_TRUE(wait_presence(SHORT_TIMEOUT));
	ASSERT_TRUE(select_port());
	ASSERT_TRUE(connect_device(aux, SHORT_TIMEOUT));
}

int main(int argc, char **argv) {
	if (argc < 2 || strcmp(argv[1], "--run")) {
		fprintf(stderr, "Physical Pegasus Ultimate Powerbox test: run explicitly with --run (or make test-aux-upb-hw).\n");
		fprintf(stderr, "IT SWITCHES THE POWER OUTLETS. Run it only on a box whose outlets are free.\n");
		return 2;
	}
	setvbuf(stdout, NULL, _IONBF, 0);
	if (getenv("UPB_HW_DEBUG")) {
		indigo_set_log_level(INDIGO_LOG_DEBUG);
	}
	serial_port = getenv("UPB_HW_PORT");
	client = (indigo_client){ .name = "Ultimate Powerbox hardware test", .version = INDIGO_VERSION_CURRENT, .define_property = define_property, .update_property = update_property, .delete_property = delete_property, .send_message = report_message };
	const indigo_test_case tests[] = {
		{ "upb_reports_identity_and_capabilities", upb_reports_identity_and_capabilities },
		{ "upb_publishes_the_property_contract", upb_publishes_the_property_contract },
		{ "upb_reads_its_sensors", upb_reads_its_sensors },
		{ "upb_polls_its_sensors", upb_polls_its_sensors },
		{ "upb_switches_every_power_outlet", upb_switches_every_power_outlet },
		{ "upb_reports_outlet_state_and_current", upb_reports_outlet_state_and_current },
		{ "upb_sets_heater_duty_cycles", upb_sets_heater_duty_cycles },
		{ "upb_switches_dew_control", upb_switches_dew_control },
		{ "upb_switches_the_usb_control", upb_switches_the_usb_control },
		{ "upb_sets_the_variable_outlet", upb_sets_the_variable_outlet },
		{ "upb_renames_an_outlet", upb_renames_an_outlet },
		{ "upb_connects_the_focuser", upb_connects_the_focuser },
		{ "upb_reconnects", upb_reconnects },
		{ "upb_reinitializes", upb_reinitializes }
	};
	int result = 1;
	bool started = false, initialized = false;
	if (!indigo_test_use_private_home()) {
		return 1;
	}
	CHECK(indigo_start() == INDIGO_OK);
	started = true;
	CHECK(indigo_attach_client(&client) == INDIGO_OK);
	CHECK(indigo_aux_upb(INDIGO_DRIVER_INIT, NULL) == INDIGO_OK);
	initialized = true;
	CHECK(wait_presence(SHORT_TIMEOUT));
	CHECK(select_port());
	CHECK(connect_device(aux, SHORT_TIMEOUT));
	CHECK(capture_initial_settings());
	result = indigo_run_tests("Ultimate Powerbox hardware", tests, ARRAY_SIZE(tests));
cleanup:
	if (aux >= 0 && devices[aux].present) {
		restore_initial_settings();
		printf("Restored the outlet, heater, dew and USB state the session started with\n");
	}
	if (!disconnect_device(focuser) || !disconnect_device(aux)) {
		indigo_test_failures++;
	}
	if (initialized && indigo_aux_upb(INDIGO_DRIVER_SHUTDOWN, NULL) != INDIGO_OK) {
		indigo_test_failures++;
	}
	indigo_detach_client(&client);
	if (started) {
		indigo_stop();
	}
	for (int d = 0; d < MAX_DEVICES; d++) {
		for (int p = 0; p < MAX_PROPERTIES; p++) {
			indigo_release_property(devices[d].properties[p]);
		}
	}
	indigo_test_remove_private_home();
	return indigo_test_failures ? 1 : result;
}
