static void hw_weather_sensors(hw_device *device) {
	int count = 0;
	for (int i = 0; i < (int)ARRAY_SIZE(hw_sensors); i++) {
		const hw_sensor *sensor = hw_sensors + i;
		double value = NAN;
		if (!hw_read_double(device, sensor->member, &value)) {
			HW_CHECK(!sa_has_item(device->proxy, AUX_WEATHER_PROPERTY_NAME, sensor->item));
			continue;
		}
		count++;
		HW_CHECK(sa_has_item(device->proxy, AUX_WEATHER_PROPERTY_NAME, sensor->item));
		printf("    %s %g, %s %g ('%s')\n", sensor->member, value, sensor->item, sa_number(device->proxy, AUX_WEATHER_PROPERTY_NAME, sensor->item), sa_text(device->proxy, "X_ALPACA_WEATHER_SENSORS", sensor->item));
		if (value < sensor->min || value > sensor->max) {
			fprintf(stderr, "    %s %g is outside the plausible range %g .. %g\n", sensor->member, value, sensor->min, sensor->max);
			HW_CHECK(false);
		}
		HW_CHECK(SA_WAIT(fabs(sa_number(device->proxy, AUX_WEATHER_PROPERTY_NAME, sensor->item) - hw_double(device, sensor->member)) <= 0.05 * fabs(value) + 0.5, HW_ANSWER));
	}
	printf("    %d sensor(s) implemented\n", count);
	HW_CHECK(count > 0);
	HW_CHECK(SA_WAIT(sa_state(device->proxy, AUX_WEATHER_PROPERTY_NAME) == INDIGO_OK_STATE, HW_ANSWER));
	if (sa_defined(device->proxy, "X_ALPACA_WEATHER_AGE")) {
		printf("    X_ALPACA_WEATHER_AGE %g s\n", sa_number(device->proxy, "X_ALPACA_WEATHER_AGE", "AGE"));
	}
cleanup:
	return;
}

static void hw_weather_average_period(hw_device *device) {
	double found = hw_double(device, "averageperiod");
	HW_CHECK(!isnan(found));
	HW_CHECK(SA_WAIT(fabs(sa_number(device->proxy, "X_ALPACA_WEATHER_AVERAGE_PERIOD", "PERIOD") - hw_double(device, "averageperiod")) < 1e-6, HW_ANSWER));
	double other = found == 0 ? 0.5 : 0;
	int mark = sa_message_mark();
	int state = hw_set_number(device->proxy, "X_ALPACA_WEATHER_AVERAGE_PERIOD", "PERIOD", other, HW_ANSWER);
	double read = hw_double(device, "averageperiod");
	printf("    AveragePeriod %g -> %g: state %d, AveragePeriod %g\n", found, other, state, read);
	if (state == INDIGO_ALERT_STATE && fabs(read - found) < 1e-6 && found == 0) {
		// a device without averaging accepts only 0 (InvalidValue for anything else), which the driver reports
		hw_print_messages(mark);
		printf("    the device accepts only an AveragePeriod of 0\n");
	} else {
		HW_CHECK(state == INDIGO_OK_STATE && fabs(read - other) < 1e-6);
		HW_CHECK(hw_set_number(device->proxy, "X_ALPACA_WEATHER_AVERAGE_PERIOD", "PERIOD", found, HW_ANSWER) == INDIGO_OK_STATE);
		HW_CHECK(fabs(hw_double(device, "averageperiod") - found) < 1e-6);
	}
cleanup:
	return;
}

