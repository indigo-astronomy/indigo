static const alpaca_json_value *hw_get(hw_device *device, const char *member, const char *query, int *error_number) {
	char path[256], error[128];
	hw_server *server = device->server;
	alpaca_http_options options = { { 5000, 15000, 10000, 20000 }, NULL, false };
	int64_t number = -1;
	snprintf(path, sizeof(path), "/api/v1/%s/%d/%s", device->url_type, device->number, member);
	alpaca_json_free(hw_reply);
	hw_reply = NULL;
	*error_number = -1;
	if (alpaca_http_get(server->http, path, query, &options, &server->response) != ALPACA_HTTP_OK || server->response.status != 200 || server->response.body.data == NULL) {
		return NULL;
	}
	hw_reply = alpaca_json_parse(server->response.body.data, server->response.body.size, error, sizeof(error));
	if (hw_reply == NULL || !alpaca_json_get_int(alpaca_json_get(hw_reply, "ErrorNumber"), &number)) {
		return NULL;
	}
	*error_number = (int)number;
	return alpaca_json_get(hw_reply, "Value");
}

// PUT to the Alpaca device directly; used only to give a device back to the clients it was connected for. Returns the ErrorNumber, -1 without a valid answer.
static int hw_put(hw_device *device, const char *member, const char *form) {
	char path[256], body[512], error[128];
	hw_server *server = device->server;
	alpaca_http_options options = { { 5000, 30000, 10000, 40000 }, NULL, true };
	int64_t number = -1;
	snprintf(path, sizeof(path), "/api/v1/%s/%d/%s", device->url_type, device->number, member);
	snprintf(body, sizeof(body), "%s&ClientID=4243&ClientTransactionID=1", form);
	if (alpaca_http_put(server->http, path, NULL, body, &options, &server->response) != ALPACA_HTTP_OK || server->response.status != 200 || server->response.body.data == NULL) {
		return -1;
	}
	alpaca_json_free(hw_reply);
	hw_reply = alpaca_json_parse(server->response.body.data, server->response.body.size, error, sizeof(error));
	if (hw_reply == NULL || !alpaca_json_get_int(alpaca_json_get(hw_reply, "ErrorNumber"), &number)) {
		return -1;
	}
	return (int)number;
}

