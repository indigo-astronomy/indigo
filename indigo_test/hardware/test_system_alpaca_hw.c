static void hw_camera_readout_modes(hw_device *device) {
	char item[INDIGO_NAME_SIZE];
	int found = hw_int(device, "readoutmode");
	int count = hw_array_size(device, "readoutmodes");
	HW_CHECK(count > 1 && found >= 0);
	for (int i = 0; i <= count; i++) {
		int mode = i < count ? i : found;
		snprintf(item, sizeof(item), "MODE_%d", mode);
		HW_CHECK(sa_has_item(device->proxy, CCD_MODE_PROPERTY_NAME, item));
		HW_CHECK(hw_set_switch(device->proxy, CCD_MODE_PROPERTY_NAME, item, true, HW_ANSWER) == INDIGO_OK_STATE && SA_WAIT(hw_int(device, "readoutmode") == mode, HW_ANSWER));
		printf("    CCD_MODE.%s: ReadoutMode %d\n", item, mode);
	}
cleanup:
	return;
}

