// ---------------------------------------------------------------------------- focuser

static bool hw_focuser_settled(hw_device *device, const char *property, unsigned revision) {
	return sa_state_after(device->proxy, property, INDIGO_OK_STATE, revision) && sa_state(device->proxy, property) == INDIGO_OK_STATE && (!device->focuser.absolute || sa_state(device->proxy, FOCUSER_POSITION_PROPERTY_NAME) == INDIGO_OK_STATE);
}

static bool hw_focuser_move_to(hw_device *device, int position) {
	int mark = sa_message_mark();
	unsigned revision = sa_revision(device->proxy, FOCUSER_POSITION_PROPERTY_NAME);
	double started = indigo_monotonic_time();
	if (indigo_change_number_property_1(&sa_client, device->proxy, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, position) != INDIGO_OK || !SA_WAIT(hw_focuser_settled(device, FOCUSER_POSITION_PROPERTY_NAME, revision), HW_MOTION)) {
		fprintf(stderr, "    move to %d ended in state %d\n", position, sa_state(device->proxy, FOCUSER_POSITION_PROPERTY_NAME));
		hw_print_messages(mark);
		return false;
	}
	printf("    move to %d: FOCUSER_POSITION %g, Position %d, IsMoving %d after %.1f s\n", position, sa_number(device->proxy, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME), hw_int(device, "position"), hw_bool(device, "ismoving"), indigo_monotonic_time() - started);
	return sa_number(device->proxy, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME) == position && hw_int(device, "position") == position && !hw_bool(device, "ismoving");
}

static int hw_focuser_delta(hw_device *device) {
	int range = device->focuser.max_increment < device->focuser.max_step ? device->focuser.max_increment : device->focuser.max_step;
	return range / 50 > 10 ? range / 50 : 10;
}

// A focuser in the automatic (temperature compensation) mode has no motion properties: it is switched to manual for the motion cases.
static bool hw_focuser_manual(hw_device *device) {
	if (!sa_defined(device->proxy, FOCUSER_MODE_PROPERTY_NAME) || sa_switch(device->proxy, FOCUSER_MODE_PROPERTY_NAME, FOCUSER_MODE_MANUAL_ITEM_NAME)) {
		return true;
	}
	return hw_set_switch(device->proxy, FOCUSER_MODE_PROPERTY_NAME, FOCUSER_MODE_MANUAL_ITEM_NAME, true, HW_ANSWER) == INDIGO_OK_STATE && SA_WAIT(sa_defined(device->proxy, FOCUSER_STEPS_PROPERTY_NAME), HW_ANSWER);
}

static void hw_focuser_readback(hw_device *device) {
	hw_focuser *focuser = &device->focuser;
	printf("    Absolute %d, MaxStep %d, MaxIncrement %d, Position %d, StepSize %g, TempCompAvailable %d, TempComp %d\n", focuser->absolute, focuser->max_step, focuser->max_increment, hw_int(device, "position"), hw_double(device, "stepsize"), focuser->temp_comp_available, hw_bool(device, "tempcomp"));
	if (focuser->absolute) {
		HW_CHECK(SA_WAIT(sa_number(device->proxy, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME) == hw_int(device, "position"), HW_ANSWER));
		HW_CHECK(sa_number(device->proxy, FOCUSER_LIMITS_PROPERTY_NAME, FOCUSER_LIMITS_MAX_POSITION_ITEM_NAME) == focuser->max_step);
	} else {
		HW_CHECK(!sa_defined(device->proxy, FOCUSER_POSITION_PROPERTY_NAME));
	}
	if (!isnan(hw_double(device, "stepsize"))) {
		HW_CHECK(fabs(sa_number(device->proxy, "X_ALPACA_STEP_SIZE", "STEP_SIZE") - hw_double(device, "stepsize")) < 1e-6);
	}
cleanup:
	return;
}

static void hw_focuser_absolute(hw_device *device) {
	hw_focuser *focuser = &device->focuser;
	HW_CHECK(hw_focuser_manual(device));
	int position = hw_int(device, "position"), delta = hw_focuser_delta(device);
	int target = position + delta <= focuser->max_step ? position + delta : position - delta;
	HW_CHECK(hw_focuser_move_to(device, target));
	HW_CHECK(hw_focuser_move_to(device, position));
cleanup:
	return;
}

static bool hw_focuser_steps(hw_device *device, bool inward, int steps) {
	int mark = sa_message_mark();
	if (hw_set_switch(device->proxy, FOCUSER_DIRECTION_PROPERTY_NAME, inward ? FOCUSER_DIRECTION_MOVE_INWARD_ITEM_NAME : FOCUSER_DIRECTION_MOVE_OUTWARD_ITEM_NAME, true, HW_ANSWER) != INDIGO_OK_STATE) {
		return false;
	}
	unsigned revision = sa_revision(device->proxy, FOCUSER_STEPS_PROPERTY_NAME);
	if (indigo_change_number_property_1(&sa_client, device->proxy, FOCUSER_STEPS_PROPERTY_NAME, FOCUSER_STEPS_ITEM_NAME, steps) != INDIGO_OK || !SA_WAIT(hw_focuser_settled(device, FOCUSER_STEPS_PROPERTY_NAME, revision), HW_MOTION)) {
		fprintf(stderr, "    %d steps %s ended in state %d\n", steps, inward ? "in" : "out", sa_state(device->proxy, FOCUSER_STEPS_PROPERTY_NAME));
		hw_print_messages(mark);
		return false;
	}
	return SA_WAIT(!hw_bool(device, "ismoving"), HW_ANSWER);
}

static void hw_focuser_relative(hw_device *device) {
	hw_focuser *focuser = &device->focuser;
	HW_CHECK(hw_focuser_manual(device));
	int delta = hw_focuser_delta(device);
	if (focuser->absolute) {
		int position = hw_int(device, "position");
		bool inward = position - delta >= 0;
		HW_CHECK(hw_focuser_steps(device, inward, delta));
		printf("    %d steps %s: Position %d -> %d\n", delta, inward ? "in" : "out", position, hw_int(device, "position"));
		HW_CHECK(hw_int(device, "position") == position + (inward ? -delta : delta));
		HW_CHECK(SA_WAIT(sa_number(device->proxy, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME) == hw_int(device, "position"), HW_ANSWER));
		HW_CHECK(hw_focuser_steps(device, !inward, delta));
		HW_CHECK(hw_int(device, "position") == position);
	} else {
		HW_CHECK(hw_focuser_steps(device, false, delta));
		HW_CHECK(hw_focuser_steps(device, true, delta));
		printf("    %d steps out and in\n", delta);
	}
cleanup:
	return;
}

static void hw_focuser_halt(hw_device *device) {
	hw_focuser *focuser = &device->focuser;
	HW_CHECK(hw_focuser_manual(device));
	int position = hw_int(device, "position");
	unsigned revision = 0;
	if (focuser->absolute) {
		int target = position < focuser->max_step / 2 ? position + focuser->max_increment : position - focuser->max_increment;
		target = target < 0 ? 0 : target > focuser->max_step ? focuser->max_step : target;
		revision = sa_revision(device->proxy, FOCUSER_POSITION_PROPERTY_NAME);
		HW_CHECK(indigo_change_number_property_1(&sa_client, device->proxy, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME, target) == INDIGO_OK);
	} else {
		HW_CHECK(hw_set_switch(device->proxy, FOCUSER_DIRECTION_PROPERTY_NAME, FOCUSER_DIRECTION_MOVE_OUTWARD_ITEM_NAME, true, HW_ANSWER) == INDIGO_OK_STATE);
		revision = sa_revision(device->proxy, FOCUSER_STEPS_PROPERTY_NAME);
		HW_CHECK(indigo_change_number_property_1(&sa_client, device->proxy, FOCUSER_STEPS_PROPERTY_NAME, FOCUSER_STEPS_ITEM_NAME, focuser->max_increment) == INDIGO_OK);
	}
	if (!SA_WAIT(hw_bool(device, "ismoving"), HW_ANSWER)) {
		fprintf(stderr, "    the focuser was never seen moving, Halt can not be exercised\n");
		HW_CHECK(false);
	}
	HW_CHECK(hw_set_switch(device->proxy, FOCUSER_ABORT_MOTION_PROPERTY_NAME, FOCUSER_ABORT_MOTION_ITEM_NAME, true, HW_ANSWER) == INDIGO_OK_STATE);
	HW_CHECK(SA_WAIT(!hw_bool(device, "ismoving"), HW_ANSWER));
	const char *property = focuser->absolute ? FOCUSER_POSITION_PROPERTY_NAME : FOCUSER_STEPS_PROPERTY_NAME;
	HW_CHECK(SA_WAIT(sa_state(device->proxy, property) != INDIGO_BUSY_STATE, HW_ANSWER));
	printf("    halted: %s state %d", property, sa_state(device->proxy, property));
	if (focuser->absolute) {
		printf(", Position %d (from %d)", hw_int(device, "position"), position);
		HW_CHECK(SA_WAIT(sa_number(device->proxy, FOCUSER_POSITION_PROPERTY_NAME, FOCUSER_POSITION_ITEM_NAME) == hw_int(device, "position"), HW_ANSWER));
	}
	printf("\n");
	HW_CHECK(sa_state_after(device->proxy, property, INDIGO_ALERT_STATE, revision));
	if (focuser->absolute) {
		HW_CHECK(hw_focuser_move_to(device, position));
	}
cleanup:
	return;
}

static void hw_focuser_temperature(hw_device *device) {
	double temperature = hw_double(device, "temperature");
	printf("    Temperature %.2f, FOCUSER_TEMPERATURE %.2f\n", temperature, sa_number(device->proxy, FOCUSER_TEMPERATURE_PROPERTY_NAME, FOCUSER_TEMPERATURE_ITEM_NAME));
	HW_CHECK(temperature > -60 && temperature < 70);
	HW_CHECK(SA_WAIT(fabs(sa_number(device->proxy, FOCUSER_TEMPERATURE_PROPERTY_NAME, FOCUSER_TEMPERATURE_ITEM_NAME) - hw_double(device, "temperature")) < 0.5, HW_ANSWER));
cleanup:
	return;
}

static void hw_focuser_temp_comp(hw_device *device) {
	bool found = hw_bool(device, "tempcomp");
	for (int i = 0; i < 2; i++) {
		bool on = i == 0 ? !found : found;
		HW_CHECK(hw_set_switch(device->proxy, FOCUSER_MODE_PROPERTY_NAME, on ? FOCUSER_MODE_AUTOMATIC_ITEM_NAME : FOCUSER_MODE_MANUAL_ITEM_NAME, true, HW_ANSWER) == INDIGO_OK_STATE);
		HW_CHECK(SA_WAIT(hw_bool(device, "tempcomp") == on, HW_ANSWER));
		printf("    TempComp %d\n", on);
	}
cleanup:
	return;
}

static void hw_focuser_restore(hw_device *device) {
	hw_focuser *focuser = &device->focuser;
	if (focuser->absolute && hw_int(device, "position") != focuser->found_position) {
		HW_CHECK(hw_focuser_manual(device));
		HW_CHECK(hw_focuser_move_to(device, focuser->found_position));
	}
	if (focuser->temp_comp_available && hw_bool(device, "tempcomp") != focuser->found_temp_comp) {
		HW_CHECK(hw_set_switch(device->proxy, FOCUSER_MODE_PROPERTY_NAME, focuser->found_temp_comp ? FOCUSER_MODE_AUTOMATIC_ITEM_NAME : FOCUSER_MODE_MANUAL_ITEM_NAME, true, HW_ANSWER) == INDIGO_OK_STATE);
	}
	printf("    position %d, TempComp %d, as found\n", hw_int(device, "position"), hw_bool(device, "tempcomp"));
cleanup:
	return;
}

static void hw_probe_focuser(hw_device *device) {
	hw_focuser *focuser = &device->focuser;
	focuser->absolute = hw_bool(device, "absolute");
	focuser->max_step = hw_int(device, "maxstep");
	focuser->max_increment = hw_int(device, "maxincrement");
	focuser->temp_comp_available = hw_bool(device, "tempcompavailable");
	focuser->found_temp_comp = hw_bool(device, "tempcomp");
	focuser->found_position = hw_int(device, "position");
	focuser->has_temperature = !isnan(hw_double(device, "temperature"));
	printf("    Absolute %d, MaxStep %d, MaxIncrement %d, TempCompAvailable %d, Temperature %s\n", focuser->absolute, focuser->max_step, focuser->max_increment, focuser->temp_comp_available, focuser->has_temperature ? "implemented" : "not implemented");
	hw_add(device, "connect", hw_connect);
	hw_add(device, "readback", hw_focuser_readback);
	hw_add_if(device, focuser->absolute, "absolute_move", hw_focuser_absolute, "relative focuser (Absolute is false)");
	hw_add(device, "relative_move", hw_focuser_relative);
	hw_add_if(device, sa_defined(device->proxy, FOCUSER_ABORT_MOTION_PROPERTY_NAME) || focuser->found_temp_comp, "halt", hw_focuser_halt, "Halt not implemented");
	hw_add_if(device, focuser->has_temperature, "temperature", hw_focuser_temperature, "Temperature not implemented");
	hw_add_if(device, focuser->temp_comp_available, "temp_comp", hw_focuser_temp_comp, "TempCompAvailable is false");
	hw_add(device, "restore", hw_focuser_restore);
	hw_add(device, "disconnect", hw_disconnect);
}

// ---------------------------------------------------------------------------- filter wheel

static void hw_wheel_names(hw_device *device) {
	char item[INDIGO_NAME_SIZE];
	int error_number = -1;
	const alpaca_json_value *names = hw_get(device, "names", NULL, &error_number);
	HW_CHECK(error_number == 0 && alpaca_json_size(names) == device->wheel.slots);
	HW_CHECK(sa_item_count(device->proxy, WHEEL_SLOT_NAME_PROPERTY_NAME) == device->wheel.slots);
	for (int i = 0; i < device->wheel.slots; i++) {
		const char *name = NULL;
		HW_CHECK(alpaca_json_get_string(alpaca_json_array_get(names, i), &name));
		snprintf(item, sizeof(item), WHEEL_SLOT_NAME_ITEM_NAME, i + 1);
		printf("    slot %d: '%s'", i + 1, name);
		HW_CHECK(!strcmp(sa_text(device->proxy, WHEEL_SLOT_NAME_PROPERTY_NAME, item), name));
	}
	printf("\n");
	const alpaca_json_value *offsets = hw_get(device, "focusoffsets", NULL, &error_number);
	if (error_number == 0 && alpaca_json_size(offsets) == device->wheel.slots) {
		for (int i = 0; i < device->wheel.slots; i++) {
			int64_t offset = 0;
			HW_CHECK(alpaca_json_get_int(alpaca_json_array_get(offsets, i), &offset));
			snprintf(item, sizeof(item), WHEEL_SLOT_OFFSET_ITEM_NAME, i + 1);
			printf("    offset %d: %lld", i + 1, (long long)offset);
			HW_CHECK(sa_number(device->proxy, WHEEL_SLOT_OFFSET_PROPERTY_NAME, item) == (double)offset);
		}
		printf("\n");
	} else {
		printf("    FocusOffsets not usable (ErrorNumber %d)\n", error_number);
	}
cleanup:
	return;
}

static bool hw_wheel_move(hw_device *device, int slot) {
	int mark = sa_message_mark();
	unsigned revision = sa_revision(device->proxy, WHEEL_SLOT_PROPERTY_NAME);
	double started = indigo_monotonic_time();
	int state = hw_set_number(device->proxy, WHEEL_SLOT_PROPERTY_NAME, WHEEL_SLOT_ITEM_NAME, slot, HW_MOTION);
	int position = hw_int(device, "position");
	printf("    slot %d: state %d, Position %d, %.1f s\n", slot, state, position, indigo_monotonic_time() - started);
	if (state != INDIGO_OK_STATE || !sa_state_after(device->proxy, WHEEL_SLOT_PROPERTY_NAME, INDIGO_OK_STATE, revision)) {
		hw_print_messages(mark);
		return false;
	}
	return position == slot - 1 && sa_number(device->proxy, WHEEL_SLOT_PROPERTY_NAME, WHEEL_SLOT_ITEM_NAME) == slot;
}

static void hw_wheel_slots(hw_device *device) {
	for (int slot = 1; slot <= device->wheel.slots; slot++) {
		HW_CHECK(hw_wheel_move(device, slot));
	}
	HW_CHECK(hw_wheel_move(device, device->wheel.found_slot + 1));
cleanup:
	return;
}

static void hw_probe_wheel(hw_device *device) {
	device->wheel.found_slot = hw_int(device, "position");
	device->wheel.slots = hw_array_size(device, "names");
	if (device->wheel.slots <= 0) {
		device->wheel.slots = hw_array_size(device, "focusoffsets");
	}
	printf("    %d slots, Position %d\n", device->wheel.slots, device->wheel.found_slot);
	hw_add(device, "connect", hw_connect);
	hw_add_if(device, hw_array_size(device, "names") > 0, "names_offsets", hw_wheel_names, "Names not usable");
	hw_add_if(device, device->wheel.slots > 1 && device->wheel.found_slot >= 0, "every_slot", hw_wheel_slots, "fewer than two slots or no position");
	hw_add(device, "disconnect", hw_disconnect);
}

// ---------------------------------------------------------------------------- rotator

static bool hw_rotator_settled(hw_device *device, const char *property, unsigned revision) {
	return sa_state_after(device->proxy, property, INDIGO_OK_STATE, revision) && sa_state(device->proxy, property) == INDIGO_OK_STATE && sa_state(device->proxy, ROTATOR_POSITION_PROPERTY_NAME) == INDIGO_OK_STATE;
}

static bool hw_rotator_request(hw_device *device, const char *property, const char *item, double value, double expected) {
	int mark = sa_message_mark();
	unsigned revision = sa_revision(device->proxy, property);
	double tolerance = fmax(0.1, hw_double(device, "stepsize"));
	if (indigo_change_number_property_1(&sa_client, device->proxy, property, item, value) != INDIGO_OK || !SA_WAIT(hw_rotator_settled(device, property, revision), HW_MOTION)) {
		fprintf(stderr, "    %s %g ended in state %d\n", property, value, sa_state(device->proxy, property));
		hw_print_messages(mark);
		return false;
	}
	double position = hw_double(device, "position");
	printf("    %s %g: Position %.3f, ROTATOR_POSITION %.3f, MechanicalPosition %.3f\n", property, value, position, sa_number(device->proxy, ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME), hw_double(device, "mechanicalposition"));
	return fabs(hw_angle_difference(position, expected)) < tolerance && SA_WAIT(fabs(hw_angle_difference(sa_number(device->proxy, ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME), hw_double(device, "position"))) < 0.01, HW_ANSWER) && !hw_bool(device, "ismoving");
}

static void hw_rotator_readback(hw_device *device) {
	printf("    Position %.3f, MechanicalPosition %.3f, StepSize %g, Reverse %d, CanReverse %d\n", hw_double(device, "position"), hw_double(device, "mechanicalposition"), hw_double(device, "stepsize"), hw_bool(device, "reverse"), device->rotator.can_reverse);
	HW_CHECK(SA_WAIT(fabs(hw_angle_difference(sa_number(device->proxy, ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME), hw_double(device, "position"))) < 0.01, HW_ANSWER));
	if (device->rotator.has_mechanical) {
		HW_CHECK(SA_WAIT(fabs(hw_angle_difference(sa_number(device->proxy, ROTATOR_RAW_POSITION_PROPERTY_NAME, ROTATOR_RAW_POSITION_ITEM_NAME), hw_double(device, "mechanicalposition"))) < 0.01, HW_ANSWER));
	}
cleanup:
	return;
}

static void hw_rotator_moves(hw_device *device) {
	double position = hw_double(device, "position");
	HW_CHECK(hw_rotator_request(device, ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME, hw_angle(position + 10), hw_angle(position + 10)));
	HW_CHECK(hw_rotator_request(device, ROTATOR_RELATIVE_MOVE_PROPERTY_NAME, ROTATOR_RELATIVE_MOVE_ITEM_NAME, -5, hw_angle(position + 5)));
	HW_CHECK(hw_rotator_request(device, ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME, position, position));
cleanup:
	return;
}

static void hw_rotator_mechanical(hw_device *device) {
	double mechanical = hw_double(device, "mechanicalposition"), position = hw_double(device, "position");
	HW_CHECK(!isnan(mechanical));
	HW_CHECK(hw_rotator_request(device, "X_ALPACA_MECHANICAL_POSITION", "POSITION", hw_angle(mechanical + 10), hw_angle(position + 10)));
	HW_CHECK(fabs(hw_angle_difference(hw_double(device, "mechanicalposition"), mechanical + 10)) < fmax(0.1, hw_double(device, "stepsize")));
	HW_CHECK(hw_rotator_request(device, "X_ALPACA_MECHANICAL_POSITION", "POSITION", mechanical, position));
cleanup:
	return;
}

static void hw_rotator_reverse(hw_device *device) {
	bool found = hw_bool(device, "reverse");
	for (int i = 0; i < 2; i++) {
		bool reverse = i == 0 ? !found : found;
		HW_CHECK(hw_set_switch(device->proxy, ROTATOR_DIRECTION_PROPERTY_NAME, reverse ? ROTATOR_DIRECTION_REVERSED_ITEM_NAME : ROTATOR_DIRECTION_NORMAL_ITEM_NAME, true, HW_ANSWER) == INDIGO_OK_STATE);
		HW_CHECK(SA_WAIT(hw_bool(device, "reverse") == reverse, HW_ANSWER));
		printf("    Reverse %d\n", reverse);
	}
cleanup:
	return;
}

// Sync to 10 degrees more, then back: the mechanical position does not change.
static void hw_rotator_sync(hw_device *device) {
	double position = hw_double(device, "position"), mechanical = hw_double(device, "mechanicalposition");
	HW_CHECK(hw_set_switch(device->proxy, ROTATOR_ON_POSITION_SET_PROPERTY_NAME, ROTATOR_ON_POSITION_SET_SYNC_ITEM_NAME, true, HW_ANSWER) == INDIGO_OK_STATE);
	for (int i = 0; i < 2; i++) {
		double target = i == 0 ? hw_angle(position + 10) : position;
		HW_CHECK(hw_set_number(device->proxy, ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME, target, HW_ANSWER) == INDIGO_OK_STATE);
		printf("    sync to %.3f: Position %.3f, MechanicalPosition %.3f\n", target, hw_double(device, "position"), hw_double(device, "mechanicalposition"));
		HW_CHECK(fabs(hw_angle_difference(hw_double(device, "position"), target)) < 0.01 && fabs(hw_angle_difference(hw_double(device, "mechanicalposition"), mechanical)) < 0.01);
		HW_CHECK(SA_WAIT(fabs(hw_angle_difference(sa_number(device->proxy, ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME), target)) < 0.01, HW_ANSWER));
	}
cleanup:
	hw_set_switch(device->proxy, ROTATOR_ON_POSITION_SET_PROPERTY_NAME, ROTATOR_ON_POSITION_SET_GOTO_ITEM_NAME, true, HW_ANSWER);
	return;
}

static void hw_rotator_halt(hw_device *device) {
	double position = hw_double(device, "position");
	unsigned revision = sa_revision(device->proxy, ROTATOR_POSITION_PROPERTY_NAME);
	HW_CHECK(indigo_change_number_property_1(&sa_client, device->proxy, ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME, hw_angle(position + 170)) == INDIGO_OK);
	if (!SA_WAIT(hw_bool(device, "ismoving"), HW_ANSWER)) {
		fprintf(stderr, "    the rotator was never seen moving, Halt can not be exercised\n");
		HW_CHECK(false);
	}
	HW_CHECK(hw_set_switch(device->proxy, ROTATOR_ABORT_MOTION_PROPERTY_NAME, ROTATOR_ABORT_MOTION_ITEM_NAME, true, HW_ANSWER) == INDIGO_OK_STATE);
	HW_CHECK(SA_WAIT(sa_state(device->proxy, ROTATOR_POSITION_PROPERTY_NAME) != INDIGO_BUSY_STATE, HW_MOTION) && SA_WAIT(!hw_bool(device, "ismoving"), HW_ANSWER));
	printf("    halted at %.3f (from %.3f toward %.3f), ROTATOR_POSITION state %d\n", hw_double(device, "position"), position, hw_angle(position + 170), sa_state(device->proxy, ROTATOR_POSITION_PROPERTY_NAME));
	HW_CHECK(sa_state_after(device->proxy, ROTATOR_POSITION_PROPERTY_NAME, INDIGO_ALERT_STATE, revision));
	HW_CHECK(fabs(hw_angle_difference(hw_double(device, "position"), position + 170)) > 1);
	HW_CHECK(SA_WAIT(fabs(hw_angle_difference(sa_number(device->proxy, ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME), hw_double(device, "position"))) < 0.01, HW_ANSWER));
	HW_CHECK(hw_rotator_request(device, ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME, position, position));
cleanup:
	return;
}

static void hw_rotator_restore(hw_device *device) {
	hw_rotator *rotator = &device->rotator;
	if (rotator->can_reverse && hw_bool(device, "reverse") != rotator->found_reverse) {
		HW_CHECK(hw_set_switch(device->proxy, ROTATOR_DIRECTION_PROPERTY_NAME, rotator->found_reverse ? ROTATOR_DIRECTION_REVERSED_ITEM_NAME : ROTATOR_DIRECTION_NORMAL_ITEM_NAME, true, HW_ANSWER) == INDIGO_OK_STATE);
	}
	if (fabs(hw_angle_difference(hw_double(device, "position"), rotator->found_position)) >= 0.01) {
		HW_CHECK(hw_rotator_request(device, ROTATOR_POSITION_PROPERTY_NAME, ROTATOR_POSITION_ITEM_NAME, rotator->found_position, rotator->found_position));
	}
	printf("    position %.3f, Reverse %d, as found\n", hw_double(device, "position"), hw_bool(device, "reverse"));
cleanup:
	return;
}

static void hw_probe_rotator(hw_device *device) {
	hw_rotator *rotator = &device->rotator;
	rotator->can_reverse = hw_bool(device, "canreverse");
	rotator->found_reverse = hw_bool(device, "reverse");
	rotator->found_position = hw_double(device, "position");
	rotator->has_mechanical = device->interface_version >= 3 && !isnan(hw_double(device, "mechanicalposition"));
	printf("    CanReverse %d, MechanicalPosition %s, Position %.3f\n", rotator->can_reverse, rotator->has_mechanical ? "implemented" : "not implemented", rotator->found_position);
	hw_add(device, "connect", hw_connect);
	hw_add(device, "readback", hw_rotator_readback);
	hw_add(device, "moves", hw_rotator_moves);
	hw_add_if(device, rotator->can_reverse, "reverse", hw_rotator_reverse, "CanReverse is false");
	hw_add_if(device, sa_defined(device->proxy, "X_ALPACA_MECHANICAL_POSITION"), "mechanical_move", hw_rotator_mechanical, "MoveMechanical needs interface version 3 and MechanicalPosition");
	hw_add_if(device, sa_defined(device->proxy, ROTATOR_ON_POSITION_SET_PROPERTY_NAME), "sync", hw_rotator_sync, "Sync needs interface version 3");
	hw_add_if(device, sa_defined(device->proxy, ROTATOR_ABORT_MOTION_PROPERTY_NAME), "halt", hw_rotator_halt, "Halt not implemented");
	hw_add(device, "restore", hw_rotator_restore);
	hw_add(device, "disconnect", hw_disconnect);
}

// ---------------------------------------------------------------------------- dome

static bool hw_dome_azimuth(hw_device *device, double azimuth) {
	int mark = sa_message_mark();
	unsigned revision = sa_revision(device->proxy, DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME);
	double started = indigo_monotonic_time();
	int state = hw_set_number(device->proxy, DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME, DOME_HORIZONTAL_COORDINATES_AZ_ITEM_NAME, azimuth, HW_MOTION);
	printf("    azimuth %.1f: state %d, Azimuth %.2f after %.1f s\n", azimuth, state, hw_double(device, "azimuth"), indigo_monotonic_time() - started);
	if (state != INDIGO_OK_STATE || !sa_state_after(device->proxy, DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME, INDIGO_BUSY_STATE, revision)) {
		hw_print_messages(mark);
		return false;
	}
	return fabs(hw_angle_difference(hw_double(device, "azimuth"), azimuth)) < 1 && SA_WAIT(fabs(hw_angle_difference(sa_number(device->proxy, DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME, DOME_HORIZONTAL_COORDINATES_AZ_ITEM_NAME), hw_double(device, "azimuth"))) < 1, HW_ANSWER);
}

// The driver refuses slews of a parked dome; DOME_PARK UNPARKED sends nothing (Alpaca has no unpark) and lets the next slew leave the park position.
static bool hw_dome_unparked(hw_device *device) {
	if (!device->dome.can_park || !sa_switch(device->proxy, DOME_PARK_PROPERTY_NAME, DOME_PARK_PARKED_ITEM_NAME)) {
		return true;
	}
	return hw_set_switch(device->proxy, DOME_PARK_PROPERTY_NAME, DOME_PARK_UNPARKED_ITEM_NAME, true, HW_ANSWER) == INDIGO_OK_STATE;
}

static void hw_dome_readback(hw_device *device) {
	int shutter = hw_int(device, "shutterstatus");
	printf("    Azimuth %.2f, Altitude %.2f, ShutterStatus %d, AtPark %d, AtHome %d, Slewing %d, Slaved %d\n", hw_double(device, "azimuth"), hw_double(device, "altitude"), shutter, hw_bool(device, "atpark"), hw_bool(device, "athome"), hw_bool(device, "slewing"), hw_bool(device, "slaved"));
	if (device->dome.can_set_azimuth) {
		HW_CHECK(SA_WAIT(fabs(hw_angle_difference(sa_number(device->proxy, DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME, DOME_HORIZONTAL_COORDINATES_AZ_ITEM_NAME), hw_double(device, "azimuth"))) < 1, HW_ANSWER));
	}
	if (device->dome.can_set_shutter && (shutter == 0 || shutter == 1)) {
		HW_CHECK(SA_WAIT(sa_switch(device->proxy, DOME_SHUTTER_PROPERTY_NAME, hw_int(device, "shutterstatus") == 0 ? DOME_SHUTTER_OPENED_ITEM_NAME : DOME_SHUTTER_CLOSED_ITEM_NAME), HW_ANSWER));
	}
	if (device->dome.can_park) {
		HW_CHECK(SA_WAIT(sa_switch(device->proxy, DOME_PARK_PROPERTY_NAME, DOME_PARK_PARKED_ITEM_NAME) == hw_bool(device, "atpark"), HW_ANSWER));
	}
	if (device->dome.can_slave) {
		HW_CHECK(SA_WAIT(sa_switch(device->proxy, "X_ALPACA_DOME_SLAVED", "ENABLED") == hw_bool(device, "slaved"), HW_ANSWER));
	}
cleanup:
	return;
}

static void hw_dome_slews(hw_device *device) {
	double azimuth = hw_double(device, "azimuth");
	HW_CHECK(hw_dome_unparked(device));
	HW_CHECK(hw_dome_azimuth(device, hw_angle(azimuth + 30)));
	HW_CHECK(hw_dome_azimuth(device, hw_angle(azimuth)));
cleanup:
	return;
}

static void hw_dome_altitude(hw_device *device) {
	static const char *items[] = { DOME_HORIZONTAL_COORDINATES_AZ_ITEM_NAME, DOME_HORIZONTAL_COORDINATES_ALT_ITEM_NAME };
	double azimuth = hw_double(device, "azimuth"), altitude = hw_double(device, "altitude");
	HW_CHECK(hw_dome_unparked(device));
	for (int i = 0; i < 2; i++) {
		double values[] = { azimuth, i == 0 ? (altitude > 45 ? altitude - 20 : altitude + 20) : altitude };
		HW_CHECK(hw_set_numbers(device->proxy, DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME, 2, items, values, HW_MOTION) == INDIGO_OK_STATE);
		printf("    altitude %.1f: Altitude %.2f\n", values[1], hw_double(device, "altitude"));
		HW_CHECK(fabs(hw_double(device, "altitude") - values[1]) < 1);
	}
cleanup:
	return;
}

static void hw_dome_abort(hw_device *device) {
	double azimuth = hw_double(device, "azimuth");
	HW_CHECK(hw_dome_unparked(device));
	unsigned revision = sa_revision(device->proxy, DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME);
	HW_CHECK(indigo_change_number_property_1(&sa_client, device->proxy, DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME, DOME_HORIZONTAL_COORDINATES_AZ_ITEM_NAME, hw_angle(azimuth + 170)) == INDIGO_OK);
	HW_CHECK(SA_WAIT(hw_bool(device, "slewing"), HW_ANSWER));
	HW_CHECK(hw_set_switch(device->proxy, DOME_ABORT_MOTION_PROPERTY_NAME, DOME_ABORT_MOTION_ITEM_NAME, true, HW_ANSWER) == INDIGO_OK_STATE);
	HW_CHECK(SA_WAIT(sa_state(device->proxy, DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME) != INDIGO_BUSY_STATE, HW_MOTION) && SA_WAIT(!hw_bool(device, "slewing"), HW_ANSWER));
	printf("    AbortSlew: Azimuth %.2f (from %.2f toward %.2f), state %d\n", hw_double(device, "azimuth"), azimuth, hw_angle(azimuth + 170), sa_state(device->proxy, DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME));
	HW_CHECK(sa_state_after(device->proxy, DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME, INDIGO_ALERT_STATE, revision));
	HW_CHECK(fabs(hw_angle_difference(hw_double(device, "azimuth"), azimuth + 170)) > 1);
	HW_CHECK(hw_dome_azimuth(device, azimuth));
cleanup:
	return;
}

static void hw_dome_find_home(hw_device *device) {
	HW_CHECK(hw_dome_unparked(device));
	HW_CHECK(hw_set_switch(device->proxy, DOME_HOME_PROPERTY_NAME, DOME_HOME_ITEM_NAME, true, HW_MOTION) == INDIGO_OK_STATE);
	HW_CHECK(SA_WAIT(hw_bool(device, "athome"), HW_ANSWER));
	printf("    FindHome: AtHome, Azimuth %.2f\n", hw_double(device, "azimuth"));
cleanup:
	return;
}

static void hw_dome_park(hw_device *device) {
	HW_CHECK(hw_dome_unparked(device));
	if (device->dome.can_set_azimuth) {
		HW_CHECK(hw_dome_azimuth(device, hw_angle(hw_double(device, "azimuth") + 20)));
	}
	HW_CHECK(hw_set_switch(device->proxy, DOME_PARK_PROPERTY_NAME, DOME_PARK_PARKED_ITEM_NAME, true, HW_MOTION) == INDIGO_OK_STATE);
	HW_CHECK(SA_WAIT(hw_bool(device, "atpark") && sa_switch(device->proxy, DOME_PARK_PROPERTY_NAME, DOME_PARK_PARKED_ITEM_NAME), HW_ANSWER));
	printf("    Park: AtPark, Azimuth %.2f\n", hw_double(device, "azimuth"));
	if (device->dome.can_set_azimuth) {
		// a slew leaves the park position (Alpaca has no unpark)
		HW_CHECK(hw_dome_unparked(device));
		HW_CHECK(hw_dome_azimuth(device, hw_angle(hw_double(device, "azimuth") + 20)));
		HW_CHECK(SA_WAIT(!hw_bool(device, "atpark"), HW_ANSWER));
	}
cleanup:
	return;
}

static void hw_dome_set_park(hw_device *device) {
	double original = NAN;
	HW_CHECK(hw_set_switch(device->proxy, DOME_PARK_PROPERTY_NAME, DOME_PARK_PARKED_ITEM_NAME, true, HW_MOTION) == INDIGO_OK_STATE);
	original = hw_double(device, "azimuth");
	HW_CHECK(hw_dome_unparked(device));
	HW_CHECK(hw_dome_azimuth(device, hw_angle(original + 40)));
	HW_CHECK(hw_set_switch(device->proxy, "X_ALPACA_DOME_PARK_SET", "CURRENT", true, HW_ANSWER) == INDIGO_OK_STATE);
	HW_CHECK(hw_dome_azimuth(device, hw_angle(original)));
	HW_CHECK(hw_set_switch(device->proxy, DOME_PARK_PROPERTY_NAME, DOME_PARK_PARKED_ITEM_NAME, true, HW_MOTION) == INDIGO_OK_STATE);
	HW_CHECK(SA_WAIT(hw_bool(device, "atpark"), HW_ANSWER));
	printf("    parked at the new park position: Azimuth %.2f (park was %.2f)\n", hw_double(device, "azimuth"), original);
	HW_CHECK(fabs(hw_angle_difference(hw_double(device, "azimuth"), original + 40)) < 1);
cleanup:
	if (!isnan(original)) {
		if (!hw_dome_unparked(device) || !hw_dome_azimuth(device, original) || hw_set_switch(device->proxy, "X_ALPACA_DOME_PARK_SET", "CURRENT", true, HW_ANSWER) != INDIGO_OK_STATE) {
			fprintf(stderr, "    the park position could not be set back to %.2f\n", original);
			indigo_test_failures++;
		} else {
			printf("    park position set back to %.2f\n", original);
		}
	}
	return;
}

static void hw_dome_sync(hw_device *device) {
	double azimuth = hw_double(device, "azimuth");
	HW_CHECK(hw_dome_unparked(device));
	HW_CHECK(hw_set_switch(device->proxy, DOME_ON_COORDINATES_SET_PROPERTY_NAME, DOME_ON_COORDINATES_SET_SYNC_ITEM_NAME, true, HW_ANSWER) == INDIGO_OK_STATE);
	for (int i = 0; i < 2; i++) {
		double target = i == 0 ? hw_angle(azimuth + 5) : azimuth;
		HW_CHECK(hw_set_number(device->proxy, DOME_HORIZONTAL_COORDINATES_PROPERTY_NAME, DOME_HORIZONTAL_COORDINATES_AZ_ITEM_NAME, target, HW_ANSWER) == INDIGO_OK_STATE);
		printf("    sync to %.2f: Azimuth %.2f\n", target, hw_double(device, "azimuth"));
		HW_CHECK(fabs(hw_angle_difference(hw_double(device, "azimuth"), target)) < 0.5);
	}
cleanup:
	hw_set_switch(device->proxy, DOME_ON_COORDINATES_SET_PROPERTY_NAME, DOME_ON_COORDINATES_SET_GOTO_ITEM_NAME, true, HW_ANSWER);
	return;
}

static bool hw_dome_shutter_to(hw_device *device, bool open) {
	int mark = sa_message_mark();
	int state = hw_set_switch(device->proxy, DOME_SHUTTER_PROPERTY_NAME, open ? DOME_SHUTTER_OPENED_ITEM_NAME : DOME_SHUTTER_CLOSED_ITEM_NAME, true, HW_MOTION);
	printf("    shutter %s: state %d, ShutterStatus %d\n", open ? "open" : "closed", state, hw_int(device, "shutterstatus"));
	if (state != INDIGO_OK_STATE) {
		hw_print_messages(mark);
		return false;
	}
	return hw_int(device, "shutterstatus") == (open ? 0 : 1);
}

static void hw_dome_shutter(hw_device *device) {
	bool open = device->dome.found_shutter == 0;
	HW_CHECK(hw_dome_shutter_to(device, !open));
	HW_CHECK(hw_dome_shutter_to(device, open));
cleanup:
	return;
}

static void hw_dome_restore(hw_device *device) {
	hw_dome *dome = &device->dome;
	if (dome->can_set_shutter && (dome->found_shutter == 0 || dome->found_shutter == 1) && hw_int(device, "shutterstatus") != dome->found_shutter) {
		HW_CHECK(hw_dome_shutter_to(device, dome->found_shutter == 0));
	}
	if (dome->found_parked && dome->can_park) {
		if (!hw_bool(device, "atpark")) {
			HW_CHECK(hw_set_switch(device->proxy, DOME_PARK_PROPERTY_NAME, DOME_PARK_PARKED_ITEM_NAME, true, HW_MOTION) == INDIGO_OK_STATE);
		}
	} else if (dome->can_set_azimuth && fabs(hw_angle_difference(hw_double(device, "azimuth"), dome->found_azimuth)) > 1) {
		HW_CHECK(hw_dome_unparked(device));
		HW_CHECK(hw_dome_azimuth(device, dome->found_azimuth));
	}
	printf("    Azimuth %.2f, AtPark %d, ShutterStatus %d, as found\n", hw_double(device, "azimuth"), hw_bool(device, "atpark"), hw_int(device, "shutterstatus"));
cleanup:
	return;
}

static void hw_probe_dome(hw_device *device) {
	hw_dome *dome = &device->dome;
	dome->can_set_azimuth = hw_bool(device, "cansetazimuth");
	dome->can_set_altitude = hw_bool(device, "cansetaltitude");
	dome->can_sync = hw_bool(device, "cansyncazimuth");
	dome->can_park = hw_bool(device, "canpark");
	dome->can_set_park = hw_bool(device, "cansetpark");
	dome->can_find_home = hw_bool(device, "canfindhome");
	dome->can_set_shutter = hw_bool(device, "cansetshutter");
	dome->can_slave = hw_bool(device, "canslave");
	dome->found_azimuth = hw_double(device, "azimuth");
	dome->found_shutter = hw_int(device, "shutterstatus");
	dome->found_parked = hw_bool(device, "atpark");
	printf("    CanSetAzimuth %d, CanSetAltitude %d, CanSyncAzimuth %d, CanPark %d, CanSetPark %d, CanFindHome %d, CanSetShutter %d, CanSlave %d; found Azimuth %.2f, ShutterStatus %d, AtPark %d\n", dome->can_set_azimuth, dome->can_set_altitude, dome->can_sync, dome->can_park, dome->can_set_park, dome->can_find_home, dome->can_set_shutter, dome->can_slave, dome->found_azimuth, dome->found_shutter, dome->found_parked);
	hw_add(device, "connect", hw_connect);
	hw_add(device, "readback", hw_dome_readback);
	hw_add_if(device, dome->can_set_azimuth, "azimuth", hw_dome_slews, "CanSetAzimuth is false");
	hw_add_if(device, dome->can_set_altitude, "altitude", hw_dome_altitude, "CanSetAltitude is false");
	hw_add_if(device, dome->can_set_azimuth, "abort", hw_dome_abort, "needs an azimuth slew to abort (CanSetAzimuth)");
	hw_add_if(device, dome->can_find_home, "find_home", hw_dome_find_home, "CanFindHome is false");
	hw_add_if(device, dome->can_park, "park", hw_dome_park, "CanPark is false");
	hw_add_if(device, dome->can_set_park && dome->can_park && dome->can_set_azimuth, "set_park", hw_dome_set_park, dome->can_set_park ? "needs CanPark and CanSetAzimuth to set the park position back" : "CanSetPark is false");
	hw_add_if(device, dome->can_sync, "sync", hw_dome_sync, "CanSyncAzimuth is false");
	hw_add_if(device, dome->can_set_shutter && (dome->found_shutter == 0 || dome->found_shutter == 1), "shutter", hw_dome_shutter, dome->can_set_shutter ? "the shutter is neither open nor closed" : "CanSetShutter is false");
	hw_add(device, "restore", hw_dome_restore);
	hw_add(device, "disconnect", hw_disconnect);
}

