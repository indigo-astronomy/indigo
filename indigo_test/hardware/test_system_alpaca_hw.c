// The property and item of the proxy that shows Alpaca switch id, from X_ALPACA_SWITCH_INFO ("<property>.<item>: <description>").
static bool hw_switch_item(hw_device *device, int id, char *property, char *item) {
	char name[INDIGO_NAME_SIZE], text[SA_TEXT_SIZE];
	snprintf(name, sizeof(name), "SWITCH_%d", id);
	snprintf(text, sizeof(text), "%s", sa_text(device->proxy, "X_ALPACA_SWITCH_INFO", name));
	char *dot = strchr(text, '.'), *colon = strstr(text, ": ");
	if (dot == NULL) {
		return false;
	}
	*dot = 0;
	if (colon != NULL) {
		*colon = 0;
	}
	snprintf(property, INDIGO_NAME_SIZE, "%s", text);
	snprintf(item, INDIGO_NAME_SIZE, "%s", dot + 1);
	return true;
}

static bool hw_switch_value(hw_device *device, int id, double *value) {
	char query[32];
	snprintf(query, sizeof(query), "Id=%d", id);
	return hw_read_double_q(device, "getswitchvalue", query, value);
}

// The proxy shows the value of the switch: a boolean outlet as its switch item, anything else as a number.
static bool hw_switch_shows(hw_device *device, const char *property, const char *item, double value) {
	if (!strcmp(property, AUX_GPIO_OUTLETS_PROPERTY_NAME)) {
		return sa_switch(device->proxy, property, item) == (value != 0);
	}
	return fabs(sa_number(device->proxy, property, item) - value) < 1e-6;
}

static void hw_switch_read(hw_device *device) {
	char property[INDIGO_NAME_SIZE], item[INDIGO_NAME_SIZE], name[INDIGO_VALUE_SIZE];
	for (int id = 0; id < device->sw.max_switch; id++) {
		double value = NAN;
		bool can_write = false;
		char query[32];
		snprintf(query, sizeof(query), "Id=%d", id);
		hw_read_bool_q(device, "canwrite", query, &can_write);
		int error_number = -1;
		const char *text = "";
		const alpaca_json_value *json = hw_get(device, "getswitchname", query, &error_number);
		if (error_number != 0 || !alpaca_json_get_string(json, &text)) {
			text = "";
		}
		snprintf(name, sizeof(name), "%s", text);
		HW_CHECK(hw_switch_value(device, id, &value));
		HW_CHECK(hw_switch_item(device, id, property, item));
		printf("    switch %d '%s' (%s): %g, %s.%s\n", id, name, can_write ? "writable" : "read only", value, property, item);
		HW_CHECK(SA_WAIT(hw_switch_value(device, id, &value) && hw_switch_shows(device, property, item, value), HW_ANSWER));
	}
cleanup:
	return;
}

static bool hw_switch_set(hw_device *device, int id, const char *property, const char *item, double value) {
	int mark = sa_message_mark();
	int state = !strcmp(property, AUX_GPIO_OUTLETS_PROPERTY_NAME) ? hw_set_switch(device->proxy, property, item, value != 0, HW_MOTION) : hw_set_number(device->proxy, property, item, value, HW_MOTION);
	double read = NAN;
	bool done = state == INDIGO_OK_STATE && SA_WAIT(hw_switch_value(device, id, &read) && fabs(read - value) < 1e-6, HW_ANSWER) && SA_WAIT(hw_switch_shows(device, property, item, value), HW_ANSWER);
	printf("    switch %d set to %g: state %d, GetSwitchValue %g\n", id, value, state, read);
	if (!done) {
		hw_print_messages(mark);
	}
	return done;
}

static void hw_switch_write(hw_device *device) {
	char property[INDIGO_NAME_SIZE], item[INDIGO_NAME_SIZE], query[32];
	int written = 0;
	for (int id = 0; id < device->sw.max_switch; id++) {
		bool can_write = false, can_async = false;
		double value = NAN, min = 0, max = 1, step = 1;
		snprintf(query, sizeof(query), "Id=%d", id);
		if (!hw_read_bool_q(device, "canwrite", query, &can_write) || !can_write) {
			continue;
		}
		if (device->interface_version >= 3) {
			hw_read_bool_q(device, "canasync", query, &can_async);
		}
		HW_CHECK(hw_switch_value(device, id, &value) && hw_switch_item(device, id, property, item));
		hw_read_double_q(device, "minswitchvalue", query, &min);
		hw_read_double_q(device, "maxswitchvalue", query, &max);
		hw_read_double_q(device, "switchstep", query, &step);
		double other = !strcmp(property, AUX_GPIO_OUTLETS_PROPERTY_NAME) ? (value != 0 ? 0 : 1) : (value + step <= max ? value + step : value - step);
		printf("    switch %d (%s.%s, %g .. %g step %g%s): %g -> %g -> %g\n", id, property, item, min, max, step, can_async ? ", asynchronous" : "", value, other, value);
		HW_CHECK(hw_switch_set(device, id, property, item, other));
		HW_CHECK(hw_switch_set(device, id, property, item, value));
		if (can_async) {
			bool complete = false;
			HW_CHECK(hw_read_bool_q(device, "statechangecomplete", query, &complete) && complete);
		}
		written++;
	}
	printf("    %d writable switch(es) changed and restored\n", written);
	HW_CHECK(written > 0);
cleanup:
	return;
}

static void hw_probe_switch(hw_device *device) {
	char query[32];
	int writable = 0;
	device->sw.max_switch = hw_int(device, "maxswitch");
	for (int id = 0; id < device->sw.max_switch; id++) {
		bool can_write = false;
		snprintf(query, sizeof(query), "Id=%d", id);
		writable += hw_read_bool_q(device, "canwrite", query, &can_write) && can_write;
	}
	printf("    MaxSwitch %d, %d writable\n", device->sw.max_switch, writable);
	hw_add(device, "connect", hw_connect);
	hw_add_if(device, device->sw.max_switch > 0, "read_all", hw_switch_read, "MaxSwitch is 0");
	hw_add_if(device, writable > 0, "write", hw_switch_write, "no switch is writable");
	hw_add(device, "disconnect", hw_disconnect);
}

