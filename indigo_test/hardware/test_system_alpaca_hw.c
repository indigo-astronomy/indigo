static pthread_mutex_t hw_image_mutex = PTHREAD_MUTEX_INITIALIZER;
static char hw_image_device[INDIGO_NAME_SIZE];
static unsigned char *hw_image = NULL;
static size_t hw_image_size = 0;
static unsigned hw_image_count = 0;

static indigo_result hw_image_update(indigo_client *client, indigo_device *device, indigo_property *property, const char *message) {
	(void)client;
	(void)device;
	(void)message;
	pthread_mutex_lock(&hw_image_mutex);
	if (!strcmp(property->device, hw_image_device) && !strcmp(property->name, CCD_IMAGE_PROPERTY_NAME) && property->state == INDIGO_OK_STATE && property->items[0].blob.value != NULL) {
		hw_image = indigo_safe_realloc(hw_image, property->items[0].blob.size);
		memcpy(hw_image, property->items[0].blob.value, property->items[0].blob.size);
		hw_image_size = property->items[0].blob.size;
		hw_image_count++;
	}
	pthread_mutex_unlock(&hw_image_mutex);
	return INDIGO_OK;
}

static indigo_client hw_image_client = {
	"system_alpaca hardware image client", false, NULL, INDIGO_OK, INDIGO_VERSION_CURRENT, NULL, NULL, NULL, hw_image_update, NULL, NULL, NULL, false, false
};

static unsigned hw_images(void) {
	pthread_mutex_lock(&hw_image_mutex);
	unsigned result = hw_image_count;
	pthread_mutex_unlock(&hw_image_mutex);
	return result;
}

// The last image is a raw image of width x height whose pixels are not all the same.
static bool hw_image_is(int width, int height) {
	bool result = false;
	pthread_mutex_lock(&hw_image_mutex);
	indigo_raw_header header = { 0 };
	if (hw_image != NULL && hw_image_size >= sizeof(header)) {
		memcpy(&header, hw_image, sizeof(header));
		int bytes = header.signature == INDIGO_RAW_MONO16 ? 2 : header.signature == INDIGO_RAW_MONO8 ? 1 : header.signature == INDIGO_RAW_RGB24 ? 3 : header.signature == INDIGO_RAW_RGB48 ? 6 : 0;
		size_t count = (size_t)header.width * (size_t)header.height;
		unsigned minimum = UINT32_MAX, maximum = 0;
		double sum = 0;
		if (bytes > 0 && hw_image_size >= sizeof(header) + count * (size_t)bytes) {
			const unsigned char *pixel = hw_image + sizeof(header);
			int step = bytes == 6 ? 2 : bytes == 3 ? 1 : bytes;
			for (size_t i = 0; i < count * (size_t)(bytes / step); i++, pixel += step) {
				unsigned value = step == 2 ? (unsigned)(pixel[0] | pixel[1] << 8) : pixel[0];
				minimum = value < minimum ? value : minimum;
				maximum = value > maximum ? value : maximum;
				sum += value;
			}
			printf("    image %08x %u x %u, %d byte(s) per pixel, min %u, max %u, mean %.1f\n", header.signature, header.width, header.height, bytes, minimum, maximum, sum / (double)(count * (size_t)(bytes / step)));
			result = (int)header.width == width && (int)header.height == height && maximum > minimum;
		} else {
			fprintf(stderr, "    image of %lu bytes, signature %08x, %u x %u is not a raw image\n", (unsigned long)hw_image_size, header.signature, header.width, header.height);
		}
	} else {
		fprintf(stderr, "    no image\n");
	}
	pthread_mutex_unlock(&hw_image_mutex);
	return result;
}

// Expose and wait for exactly one image.
static bool hw_expose(hw_device *device, double duration) {
	unsigned images = hw_images();
	int mark = sa_message_mark();
	unsigned revision = sa_revision(device->proxy, CCD_EXPOSURE_PROPERTY_NAME);
	double started = indigo_monotonic_time();
	if (indigo_change_number_property_1(&sa_client, device->proxy, CCD_EXPOSURE_PROPERTY_NAME, CCD_EXPOSURE_ITEM_NAME, duration) != INDIGO_OK) {
		return false;
	}
	if (!SA_WAIT(sa_state_after(device->proxy, CCD_EXPOSURE_PROPERTY_NAME, INDIGO_OK_STATE, revision) && sa_state(device->proxy, CCD_EXPOSURE_PROPERTY_NAME) == INDIGO_OK_STATE && hw_images() == images + 1, duration + HW_MOTION)) {
		fprintf(stderr, "    exposure of %g s ended with CCD_EXPOSURE in state %d, %u image(s)\n", duration, sa_state(device->proxy, CCD_EXPOSURE_PROPERTY_NAME), hw_images() - images);
		hw_print_messages(mark);
		return false;
	}
	printf("    exposure of %g s: image after %.2f s\n", duration, indigo_monotonic_time() - started);
	return sa_state_after(device->proxy, CCD_EXPOSURE_PROPERTY_NAME, INDIGO_BUSY_STATE, revision) && sa_state(device->proxy, CCD_IMAGE_PROPERTY_NAME) == INDIGO_OK_STATE;
}

static double hw_exposure_time(hw_device *device) {
	return fmax(device->camera.exposure_min, fmin(1.0, device->camera.exposure_max));
}

static void hw_camera_geometry(hw_device *device) {
	hw_camera *camera = &device->camera;
	printf("    CameraXSize %d, CameraYSize %d, MaxBinX %d, MaxBinY %d, PixelSizeX %g, PixelSizeY %g, MaxADU %d, SensorName '%s'\n", camera->width, camera->height, camera->max_bin_x, camera->max_bin_y, hw_double(device, "pixelsizex"), hw_double(device, "pixelsizey"), hw_int(device, "maxadu"), sa_text(device->proxy, "X_ALPACA_SENSOR", "NAME"));
	HW_CHECK(sa_number(device->proxy, CCD_INFO_PROPERTY_NAME, CCD_INFO_WIDTH_ITEM_NAME) == camera->width && sa_number(device->proxy, CCD_INFO_PROPERTY_NAME, CCD_INFO_HEIGHT_ITEM_NAME) == camera->height);
	HW_CHECK(sa_number(device->proxy, CCD_INFO_PROPERTY_NAME, CCD_INFO_MAX_HORIZONTAL_BIN_ITEM_NAME) == camera->max_bin_x && sa_number(device->proxy, CCD_INFO_PROPERTY_NAME, CCD_INFO_MAX_VERTICAL_BIN_ITEM_NAME) == camera->max_bin_y);
	HW_CHECK(fabs(sa_number(device->proxy, CCD_INFO_PROPERTY_NAME, CCD_INFO_PIXEL_WIDTH_ITEM_NAME) - hw_double(device, "pixelsizex")) < 0.01);
	HW_CHECK(sa_number(device->proxy, CCD_FRAME_PROPERTY_NAME, CCD_FRAME_WIDTH_ITEM_NAME) > 0 && sa_number(device->proxy, CCD_FRAME_PROPERTY_NAME, CCD_FRAME_WIDTH_ITEM_NAME) <= camera->width);
	HW_CHECK(sa_number(device->proxy, CCD_BIN_PROPERTY_NAME, CCD_BIN_HORIZONTAL_ITEM_NAME) == hw_int(device, "binx") && sa_number(device->proxy, CCD_BIN_PROPERTY_NAME, CCD_BIN_VERTICAL_ITEM_NAME) == hw_int(device, "biny"));
cleanup:
	return;
}

static bool hw_camera_bin(hw_device *device, double x, double y) {
	static const char *items[] = { CCD_BIN_HORIZONTAL_ITEM_NAME, CCD_BIN_VERTICAL_ITEM_NAME };
	const double values[] = { x, y };
	// the driver sends the binning to the camera with the next exposure; the camera is checked after it
	return hw_set_numbers(device->proxy, CCD_BIN_PROPERTY_NAME, 2, items, values, HW_ANSWER) == INDIGO_OK_STATE && sa_number(device->proxy, CCD_BIN_PROPERTY_NAME, CCD_BIN_HORIZONTAL_ITEM_NAME) == x && sa_number(device->proxy, CCD_BIN_PROPERTY_NAME, CCD_BIN_VERTICAL_ITEM_NAME) == y;
}

static bool hw_camera_full_frame(hw_device *device) {
	static const char *items[] = { CCD_FRAME_LEFT_ITEM_NAME, CCD_FRAME_TOP_ITEM_NAME, CCD_FRAME_WIDTH_ITEM_NAME, CCD_FRAME_HEIGHT_ITEM_NAME };
	const double values[] = { 0, 0, device->camera.width, device->camera.height };
	return hw_set_numbers(device->proxy, CCD_FRAME_PROPERTY_NAME, 4, items, values, HW_ANSWER) == INDIGO_OK_STATE;
}

static void hw_camera_exposure(hw_device *device) {
	HW_CHECK(hw_set_switch(device->proxy, CCD_IMAGE_FORMAT_PROPERTY_NAME, CCD_IMAGE_FORMAT_RAW_ITEM_NAME, true, HW_ANSWER) == INDIGO_OK_STATE);
	HW_CHECK(hw_set_switch(device->proxy, CCD_FRAME_TYPE_PROPERTY_NAME, CCD_FRAME_TYPE_LIGHT_ITEM_NAME, true, HW_ANSWER) == INDIGO_OK_STATE);
	HW_CHECK(hw_camera_bin(device, 1, 1));
	HW_CHECK(hw_camera_full_frame(device));
	double duration = hw_exposure_time(device);
	HW_CHECK(hw_expose(device, duration));
	HW_CHECK(hw_image_is(device->camera.width, device->camera.height));
	HW_CHECK(hw_int(device, "binx") == 1 && hw_int(device, "biny") == 1 && hw_int(device, "numx") == device->camera.width && hw_int(device, "numy") == device->camera.height);
	printf("    LastExposureDuration %g s\n", hw_double(device, "lastexposureduration"));
	// a second exposure right after the first one
	HW_CHECK(hw_expose(device, duration));
cleanup:
	return;
}

// Binning 2 x 2 (or 2 x 1, 1 x 2 for a camera that has it only on one axis) and a subframe: the image has the binned size.
static void hw_camera_binning(hw_device *device) {
	hw_camera *camera = &device->camera;
	static const char *items[] = { CCD_FRAME_LEFT_ITEM_NAME, CCD_FRAME_TOP_ITEM_NAME, CCD_FRAME_WIDTH_ITEM_NAME, CCD_FRAME_HEIGHT_ITEM_NAME };
	int x = camera->max_bin_x >= 2 ? 2 : 1, y = camera->max_bin_y >= 2 ? 2 : 1;
	if (!camera->can_asymmetric && x != y) {
		x = y = 1;
	}
	HW_CHECK(hw_set_switch(device->proxy, CCD_IMAGE_FORMAT_PROPERTY_NAME, CCD_IMAGE_FORMAT_RAW_ITEM_NAME, true, HW_ANSWER) == INDIGO_OK_STATE);
	HW_CHECK(x > 1 || y > 1);
	HW_CHECK(hw_camera_bin(device, x, y));
	// a centred subframe of half the sensor, on whole binned pixels
	int width = (camera->width / 2) / (2 * x) * (2 * x), height = (camera->height / 2) / (2 * y) * (2 * y);
	int left = (camera->width / 4) / x * x, top = (camera->height / 4) / y * y;
	const double values[] = { left, top, width, height };
	HW_CHECK(hw_set_numbers(device->proxy, CCD_FRAME_PROPERTY_NAME, 4, items, values, HW_ANSWER) == INDIGO_OK_STATE);
	HW_CHECK(hw_expose(device, hw_exposure_time(device)));
	printf("    binning %d x %d, subframe %d, %d, %d x %d: BinX %d, BinY %d, StartX %d, StartY %d, NumX %d, NumY %d\n", x, y, left, top, width, height, hw_int(device, "binx"), hw_int(device, "biny"), hw_int(device, "startx"), hw_int(device, "starty"), hw_int(device, "numx"), hw_int(device, "numy"));
	HW_CHECK(hw_int(device, "binx") == x && hw_int(device, "biny") == y && hw_int(device, "startx") == left / x && hw_int(device, "starty") == top / y && hw_int(device, "numx") == width / x && hw_int(device, "numy") == height / y);
	HW_CHECK(hw_image_is(width / x, height / y));
cleanup:
	if (!hw_camera_bin(device, camera->found_bin_x, camera->found_bin_y) || !hw_camera_full_frame(device)) {
		fprintf(stderr, "    binning and frame could not be restored\n");
		indigo_test_failures++;
	}
	return;
}

static void hw_camera_abort(hw_device *device) {
	unsigned images = hw_images();
	double duration = fmin(20, device->camera.exposure_max);
	unsigned revision = sa_revision(device->proxy, CCD_EXPOSURE_PROPERTY_NAME);
	HW_CHECK(indigo_change_number_property_1(&sa_client, device->proxy, CCD_EXPOSURE_PROPERTY_NAME, CCD_EXPOSURE_ITEM_NAME, duration) == INDIGO_OK);
	HW_CHECK(SA_WAIT(hw_int(device, "camerastate") == 2, HW_ANSWER));
	HW_CHECK(hw_set_switch(device->proxy, CCD_ABORT_EXPOSURE_PROPERTY_NAME, CCD_ABORT_EXPOSURE_ITEM_NAME, true, HW_ANSWER) == INDIGO_OK_STATE);
	HW_CHECK(SA_WAIT(sa_state(device->proxy, CCD_EXPOSURE_PROPERTY_NAME) != INDIGO_BUSY_STATE, HW_ANSWER));
	HW_CHECK(sa_state_after(device->proxy, CCD_EXPOSURE_PROPERTY_NAME, INDIGO_ALERT_STATE, revision));
	HW_CHECK(SA_WAIT(hw_int(device, "camerastate") == 0, HW_ANSWER));
	printf("    %g s exposure aborted: CameraState idle, ImageReady %d\n", duration, hw_bool(device, "imageready"));
	HW_CHECK(hw_images() == images);
	// the camera takes the next exposure
	HW_CHECK(hw_expose(device, hw_exposure_time(device)));
cleanup:
	return;
}

