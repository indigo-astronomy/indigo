// Code is generated by AI

// Hardware suite of the system_alpaca driver (ASCOM Alpaca client): it finds out which Alpaca devices are reachable from this
// machine and tests every function each of them advertises, through the INDIGO proxy devices exactly as a client would, and
// verifies the effect on the real device by reading it back through the proxy and directly through the Alpaca HTTP API.
//
// SELECTION
//
// - SYSTEM_ALPACA_HW_PORT (or INDIGO_TEST_PORT, which 'run_driver_test.py --port' sets) names one Alpaca server "host:port" or
//   several separated by commas. The servers are added to X_ALPACA_SERVERS and nothing is broadcast. Without it the suite runs one
//   broadcast discovery (UDP 32227) and tests what answers. INDIGO bridges (agent_alpaca) are ignored by the driver itself.
// - SYSTEM_ALPACA_HW_DEVICES restricts the run to the devices whose DeviceName or UniqueID contains one of its comma separated
//   texts (case-insensitive); the other devices are switched off in X_ALPACA_DEVICES and never connected.
//
// CASES
//
// Every tested device gets its own group of cases "<class>_<device>_<function>", <class> being the Alpaca DeviceType in lower case
// and <device> the proxy name without "ALPACA ". Which functions a device has is decided from what it advertises (the Can* flags,
// the interface version, the optional members it implements) after it was connected once; a function it does not advertise is not
// a case: it is listed as SKIP with the reason, and the summary at the end shows per device which functions passed, failed or were
// skipped.
//
// WHAT IS CHANGED AND RESTORED
//
// Every setting a case changes is put back: tracking, tracking and guide rates, slew rate, the site, focuser position and
// temperature compensation, filter slot, rotator position and reverse, dome azimuth and shutter, cover and calibrator, switches,
// the averaging period, camera binning, cooler, set point, gain, offset and readout mode. A telescope found parked is parked again,
// one found unparked is left unparked where the last case pointed it (above the horizon) with its tracking state restored. A device
// that was connected for another client before the run is connected again at the end, because an INDIGO disconnect disconnects the
// Alpaca device for every client (D5).
//
// There are no opt-ins: a hardware run is made on devices that can not be damaged, so sync, set park, the dome shutter and switch
// writes are tested like everything else, and restored: a sync is followed by a sync back to the position read before it, the park
// position is set back to the original one (as closely as a slew can reach it), every switch gets its original value back.
//
// THE TELESCOPE MOVES. Slews go to targets computed from the site and local sidereal time of the telescope, about 50 degrees above
// the horizon, an hour and a half either side of the meridian; manual motion moves a few tenths of a degree; park and find home go
// to the positions stored in the telescope.
//
// The configuration of the driver lives in a private HOME, never in the user's own (indigo_test_use_private_home()).

