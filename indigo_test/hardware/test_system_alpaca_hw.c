	double started = indigo_monotonic_time();
	int state = hw_set_switch(device->proxy, AUX_COVER_PROPERTY_NAME, open ? AUX_COVER_OPEN_ITEM_NAME : AUX_COVER_CLOSE_ITEM_NAME, true, HW_MOTION);
	printf("    cover %s: state %d, CoverState %d after %.1f s\n", open ? "open" : "closed", state, hw_int(device, "coverstate"), indigo_monotonic_time() - started);
