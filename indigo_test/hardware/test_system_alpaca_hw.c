typedef void (*hw_function)(hw_device *device);

typedef struct {
	char name[INDIGO_NAME_SIZE + 64];
	char function[64];
	char reason[256];
	hw_device *device;
	hw_function run;
	int result;
} hw_step;

static hw_step hw_steps[HW_MAX_STEPS];
static int hw_step_count = 0;

static void hw_add(hw_device *device, const char *function, hw_function run) {
	if (hw_step_count < HW_MAX_STEPS) {
		hw_step *step = hw_steps + hw_step_count++;
		snprintf(step->name, sizeof(step->name), "%s_%s", device->prefix, function);
		snprintf(step->function, sizeof(step->function), "%s", function);
		step->device = device;
		step->run = run;
	}
}

static void hw_skip(hw_device *device, const char *function, const char *format, ...) {
	if (hw_step_count < HW_MAX_STEPS) {
		va_list args;
		hw_step *step = hw_steps + hw_step_count++;
		snprintf(step->name, sizeof(step->name), "%s_%s", device->prefix, function);
		snprintf(step->function, sizeof(step->function), "%s", function);
		step->device = device;
		va_start(args, format);
		vsnprintf(step->reason, sizeof(step->reason), format, args);
		va_end(args);
	}
}

// Add the case when the condition holds, list it as skipped with the reason otherwise.
static void hw_add_if(hw_device *device, bool condition, const char *function, hw_function run, const char *reason) {
	if (condition) {
		hw_add(device, function, run);
	} else {
		hw_skip(device, function, "%s", reason);
	}
}

// The function every registered case runs: it finds its step by the name of the case, so a filtered run still runs the right one.
static void hw_run_step(void) {
	for (int i = 0; i < hw_step_count; i++) {
		hw_step *step = hw_steps + i;
		if (step->run != NULL && indigo_current_test_name != NULL && !strcmp(step->name, indigo_current_test_name)) {
			int before = indigo_test_failures;
			printf("  ---- %s\n", step->name);
			if (strcmp(step->function, "connect") && strcmp(step->function, "disconnect") && sa_defined(step->device->proxy, CONNECTION_PROPERTY_NAME) && !sa_is_connected(step->device->proxy)) {
				fprintf(stderr, "    '%s' is not connected, connecting it for the case\n", step->device->proxy);
				if (!hw_connect_proxy(step->device->proxy)) {
					indigo_test_failures++;
					step->result = -1;
					return;
				}
			}
			step->run(step->device);
			step->result = indigo_test_failures == before ? 1 : -1;
			return;
		}
	}
	fprintf(stderr, "    no step named %s\n", indigo_current_test_name);
	indigo_test_failures++;
}

