// Wait for the answer to a request made after the given revision: a state that is not BUSY. Returns it, -1 if there was none in time.
static int hw_answer(const char *device, const char *property, unsigned revision, double seconds) {
	if (!SA_WAIT(sa_revision(device, property) > revision && sa_state(device, property) != INDIGO_BUSY_STATE, seconds)) {
		fprintf(stderr, "    %s.%s got no answer within %.0f s, state %d\n", device, property, seconds, sa_state(device, property));
		return -1;
	}
	return sa_state(device, property);
}

