// Name of the item that is on in a switch property, "" if none. The buffer is static.
static const char *hw_selected(const char *device, const char *name) {
	static char buffer[INDIGO_NAME_SIZE];
	buffer[0] = 0;
	pthread_mutex_lock(&sa_cache_mutex);
	sa_cache_entry *entry = sa_cache_find(device, name);
	for (int i = 0; entry != NULL && i < entry->property->count; i++) {
		if (entry->property->items[i].sw.value) {
			snprintf(buffer, sizeof(buffer), "%s", entry->property->items[i].name);
			break;
		}
	}
	pthread_mutex_unlock(&sa_cache_mutex);
	return buffer;
}

static bool hw_connect_proxy(const char *device) {
	if (!sa_request_connection(device, true) || !SA_WAIT(sa_is_connected(device), HW_CONNECT)) {
		fprintf(stderr, "    '%s' did not connect, CONNECTION state %d\n", device, sa_state(device, CONNECTION_PROPERTY_NAME));
		return false;
	}
	return true;
}

static bool hw_disconnect_proxy(const char *device) {
	if (!sa_request_connection(device, false) || !SA_WAIT(sa_state(device, CONNECTION_PROPERTY_NAME) == INDIGO_OK_STATE && sa_switch(device, CONNECTION_PROPERTY_NAME, CONNECTION_DISCONNECTED_ITEM_NAME), HW_CONNECT)) {
		fprintf(stderr, "    '%s' did not disconnect, CONNECTION state %d\n", device, sa_state(device, CONNECTION_PROPERTY_NAME));
		return false;
	}
	return true;
}

