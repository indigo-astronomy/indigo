static bool connect_device(int d, double timeout) {
	if (d < 0) {
		fprintf(stderr, "    device not present\n");
		return false;
	}
	bool connected = false;
	if (switch_item(d, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, &connected) && connected) {
		return true;
	}
	if (!set_switch(d, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, INDIGO_OK_STATE, timeout)) {
		return false;
	}
	return switch_item(d, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, &connected) && connected;
}

static bool disconnect_device(int d) {
	if (d < 0 || !devices[d].present) {
		return true;
	}
	bool connected = false;
	if (!switch_item(d, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, &connected) || !connected) {
		return true;
	}
	return set_switch(d, CONNECTION_PROPERTY_NAME, CONNECTION_DISCONNECTED_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT);
}

static bool wait_presence(double timeout) {
	double deadline = indigo_monotonic_time() + timeout;
	while (indigo_monotonic_time() < deadline) {
		ao = device_index(AO_DEVICE_NAME);
		guider = device_index(GUIDER_DEVICE_NAME);
		if (ao >= 0 && guider >= 0 && property_defined(ao, CONNECTION_PROPERTY_NAME) && property_defined(guider, CONNECTION_PROPERTY_NAME)) {
			return true;
		}
		indigo_usleep(20000);
	}
	fprintf(stderr, "    the driver did not publish both logical devices\n");
	return false;
}

// Points the AO at the requested port. Without an explicit port the port the driver enumerated is
// kept, which is what a normal client sees.
static bool select_port(void) {
	if (serial_port == NULL || !*serial_port) {
		char detected[INDIGO_VALUE_SIZE] = "";
		if (text_item(ao, DEVICE_PORT_PROPERTY_NAME, DEVICE_PORT_ITEM_NAME, detected, sizeof(detected)) && *detected) {
			printf("Using the port the driver detected: %s\n", detected);
			return true;
		}
		fprintf(stderr, "    no serial port was detected, set AO_SX_HW_PORT\n");
		return false;
	}
	printf("Using port %s\n", serial_port);
	unsigned before = revision(ao, DEVICE_PORT_PROPERTY_NAME);
	indigo_change_text_property_1(&client, AO_DEVICE_NAME, DEVICE_PORT_PROPERTY_NAME, DEVICE_PORT_ITEM_NAME, serial_port);
	return wait_state(ao, DEVICE_PORT_PROPERTY_NAME, before, INDIGO_OK_STATE, SHORT_TIMEOUT);
}

static bool center(void) {
	return set_switch(ao, AO_RESET_PROPERTY_NAME, AO_CENTER_ITEM_NAME, INDIGO_OK_STATE, RESET_TIMEOUT);
}

// Brings the AO back to a known starting point for a scenario: connected, centred and with no
// leftover state from a scenario that failed halfway through.
static bool ready(void) {
	if (!connect_device(ao, SHORT_TIMEOUT)) {
		return false;
	}
	if (!wait_settled(ao, AO_RESET_PROPERTY_NAME, INDIGO_OK_STATE, RESET_TIMEOUT)) {
		return false;
	}
	forget_states();
	return center();
}

static bool correct(const char *property, const char *item, double steps) {
	return set_number(ao, property, item, steps, INDIGO_OK_STATE, CORRECTION_TIMEOUT);
}

// A correction leaves the handled item at zero, so the next request for the same item is a genuine
// change and not a repeat of the value the property already holds.
static bool corrected_item_is_cleared(const char *property, const char *item) {
	double value = -1;
	if (!number_item(ao, property, item, &value)) {
		return false;
	}
	if (value != 0) {
		fprintf(stderr, "    %s.%s is %g after the correction, expected 0\n", property, item, value);
		return false;
	}
	return true;
}

static void sx_ao_reports_identity_and_capabilities(void) {
	char model[INDIGO_VALUE_SIZE] = "", firmware[INDIGO_VALUE_SIZE] = "";
	ASSERT_TRUE((devices[ao].interface & INDIGO_INTERFACE_AO) != 0);
	ASSERT_TRUE(text_item(ao, INFO_PROPERTY_NAME, INFO_DEVICE_MODEL_ITEM_NAME, model, sizeof(model)));
	ASSERT_TRUE(!strcmp(model, "StarlightXpress AO"));
	ASSERT_TRUE(text_item(ao, INFO_PROPERTY_NAME, INFO_DEVICE_FW_REVISION_ITEM_NAME, firmware, sizeof(firmware)));
	// The handshake reply is V followed by three firmware digits; anything still at the attach-time
	// placeholder means the identity was never read from the unit.
	ASSERT_TRUE(*firmware && strcmp(firmware, "Unknown"));
	ASSERT_EQ_INT(3, (int)strlen(firmware));
	snprintf(initial_firmware, sizeof(initial_firmware), "%s", firmware);
	printf("    model %s, firmware %s\n", model, firmware);
}

static void sx_ao_publishes_the_property_contract(void) {
	static const struct { const char *property, *item; } corrections[] = {
		{ AO_GUIDE_DEC_PROPERTY_NAME, AO_GUIDE_NORTH_ITEM_NAME },
		{ AO_GUIDE_DEC_PROPERTY_NAME, AO_GUIDE_SOUTH_ITEM_NAME },
		{ AO_GUIDE_RA_PROPERTY_NAME, AO_GUIDE_EAST_ITEM_NAME },
		{ AO_GUIDE_RA_PROPERTY_NAME, AO_GUIDE_WEST_ITEM_NAME }
	};
	ASSERT_TRUE(property_defined(ao, AO_GUIDE_RA_PROPERTY_NAME));
	ASSERT_TRUE(property_defined(ao, AO_GUIDE_DEC_PROPERTY_NAME));
	ASSERT_TRUE(property_defined(ao, AO_RESET_PROPERTY_NAME));
	ASSERT_TRUE(property_defined(ao, DEVICE_PORT_PROPERTY_NAME));
	ASSERT_TRUE(property_defined(ao, DEVICE_PORTS_PROPERTY_NAME));
	// The unit is not a simulator and has no authentication of its own.
	ASSERT_TRUE(property_hidden(ao, SIMULATION_PROPERTY_NAME));
	ASSERT_TRUE(property_hidden(ao, AUTHENTICATION_PROPERTY_NAME));
	for (unsigned i = 0; i < ARRAY_SIZE(corrections); i++) {
		double value = -1, max = -1;
		ASSERT_TRUE(number_item(ao, corrections[i].property, corrections[i].item, &value));
		ASSERT_TRUE(value == 0);
		// The AO base driver allows 100 steps, the SX mechanism only 50, and the driver narrows the
		// range at attach time so a client cannot request a correction the unit cannot make.
		ASSERT_TRUE(number_item_max(ao, corrections[i].property, corrections[i].item, &max));
		ASSERT_TRUE(max == ITEM_MAXIMUM);
	}
	bool center_on = true, unjam_on = true;
	ASSERT_TRUE(switch_item(ao, AO_RESET_PROPERTY_NAME, AO_CENTER_ITEM_NAME, &center_on));
	ASSERT_TRUE(!center_on);
	ASSERT_TRUE(switch_item(ao, AO_RESET_PROPERTY_NAME, AO_UNJAM_ITEM_NAME, &unjam_on));
	ASSERT_TRUE(!unjam_on);
	// The guider is a separate logical device of the same driver and must be published before it is
	// connected, with its own connection property.
	ASSERT_TRUE(property_defined(guider, CONNECTION_PROPERTY_NAME));
}

static void sx_ao_reports_initial_limit_status(void) {
	// The connection handler reads the L status byte and marks the axis that sits at its travel
	// limit. A centred unit has to come up with both axes in OK.
	ASSERT_TRUE(center());
	ASSERT_TRUE(disconnect_device(ao));
	ASSERT_TRUE(connect_device(ao, SHORT_TIMEOUT));
	ASSERT_EQ_INT(INDIGO_OK_STATE, property_state(ao, AO_GUIDE_RA_PROPERTY_NAME));
	ASSERT_EQ_INT(INDIGO_OK_STATE, property_state(ao, AO_GUIDE_DEC_PROPERTY_NAME));
}

static void sx_ao_corrects_in_all_four_directions(void) {
	static const struct { const char *property, *item, *back; } directions[] = {
		{ AO_GUIDE_DEC_PROPERTY_NAME, AO_GUIDE_NORTH_ITEM_NAME, AO_GUIDE_SOUTH_ITEM_NAME },
		{ AO_GUIDE_DEC_PROPERTY_NAME, AO_GUIDE_SOUTH_ITEM_NAME, AO_GUIDE_NORTH_ITEM_NAME },
		{ AO_GUIDE_RA_PROPERTY_NAME, AO_GUIDE_EAST_ITEM_NAME, AO_GUIDE_WEST_ITEM_NAME },
		{ AO_GUIDE_RA_PROPERTY_NAME, AO_GUIDE_WEST_ITEM_NAME, AO_GUIDE_EAST_ITEM_NAME }
	};
	ASSERT_TRUE(ready());
	for (unsigned i = 0; i < ARRAY_SIZE(directions); i++) {
		// Each direction is walked out and back, so the element ends up where it started and the
		// opposite item of the same property is exercised from a non-centre position.
		ASSERT_TRUE(correct(directions[i].property, directions[i].item, SMALL_CORRECTION));
		ASSERT_TRUE(corrected_item_is_cleared(directions[i].property, directions[i].item));
		ASSERT_TRUE(correct(directions[i].property, directions[i].back, SMALL_CORRECTION));
		ASSERT_TRUE(corrected_item_is_cleared(directions[i].property, directions[i].back));
	}
	ASSERT_TRUE(center());
}

static void sx_ao_accepts_boundary_and_zero_corrections(void) {
	ASSERT_TRUE(ready());
	// The smallest correction the item range allows, and the largest one the mechanism makes without
	// reaching its travel limit, each followed by a centre so the next one starts from the same
	// place.
	ASSERT_TRUE(correct(AO_GUIDE_DEC_PROPERTY_NAME, AO_GUIDE_NORTH_ITEM_NAME, 1));
	ASSERT_TRUE(correct(AO_GUIDE_DEC_PROPERTY_NAME, AO_GUIDE_SOUTH_ITEM_NAME, 1));
	ASSERT_TRUE(center());
	ASSERT_TRUE(correct(AO_GUIDE_RA_PROPERTY_NAME, AO_GUIDE_EAST_ITEM_NAME, BOUNDARY_CORRECTION));
	ASSERT_TRUE(center());
	ASSERT_TRUE(correct(AO_GUIDE_DEC_PROPERTY_NAME, AO_GUIDE_NORTH_ITEM_NAME, BOUNDARY_CORRECTION));
	ASSERT_TRUE(center());
	// A request with every item at zero is a no-op the driver still has to accept and complete; that
	// it sends no command to the unit is asserted by the faked-transport suite, which can count
	// commands.
	ASSERT_TRUE(correct(AO_GUIDE_RA_PROPERTY_NAME, AO_GUIDE_WEST_ITEM_NAME, 0));
	ASSERT_TRUE(correct(AO_GUIDE_DEC_PROPERTY_NAME, AO_GUIDE_SOUTH_ITEM_NAME, 0));
	ASSERT_EQ_INT(INDIGO_OK_STATE, property_state(ao, AO_GUIDE_RA_PROPERTY_NAME));
	ASSERT_EQ_INT(INDIGO_OK_STATE, property_state(ao, AO_GUIDE_DEC_PROPERTY_NAME));
}

static void sx_ao_publishes_busy_then_ok(void) {
	ASSERT_TRUE(ready());
	forget_states();
	ASSERT_TRUE(correct(AO_GUIDE_DEC_PROPERTY_NAME, AO_GUIDE_NORTH_ITEM_NAME, BOUNDARY_CORRECTION));
	// A correction has to be advertised as in progress and then completed, never reported OK
	// straight away and never left in ALERT by a unit that answered correctly.
	ASSERT_TRUE(states_seen(ao, AO_GUIDE_DEC_PROPERTY_NAME) & (1u << INDIGO_BUSY_STATE));
	ASSERT_TRUE(!(states_seen(ao, AO_GUIDE_DEC_PROPERTY_NAME) & (1u << INDIGO_ALERT_STATE)));
	ASSERT_TRUE(corrected_item_is_cleared(AO_GUIDE_DEC_PROPERTY_NAME, AO_GUIDE_NORTH_ITEM_NAME));
	forget_states();
	ASSERT_TRUE(center());
	ASSERT_TRUE(states_seen(ao, AO_RESET_PROPERTY_NAME) & (1u << INDIGO_BUSY_STATE));
	bool on = true;
	ASSERT_TRUE(switch_item(ao, AO_RESET_PROPERTY_NAME, AO_CENTER_ITEM_NAME, &on));
	ASSERT_TRUE(!on);
}

static void sx_ao_drops_an_overlapping_request(void) {
	ASSERT_TRUE(ready());
	// Centring occupies the queue for seconds, which is long enough to observe what happens to a
	// second request for the same property.
	unsigned before = revision(ao, AO_RESET_PROPERTY_NAME);
	indigo_change_switch_property_1(&client, AO_DEVICE_NAME, AO_RESET_PROPERTY_NAME, AO_CENTER_ITEM_NAME, true);
	ASSERT_TRUE(wait_state(ao, AO_RESET_PROPERTY_NAME, before, INDIGO_BUSY_STATE, SHORT_TIMEOUT));
	unsigned busy = revision(ao, AO_RESET_PROPERTY_NAME);
	indigo_change_switch_property_1(&client, AO_DEVICE_NAME, AO_RESET_PROPERTY_NAME, AO_UNJAM_ITEM_NAME, true);
	// The framework guard drops the second request without copying its values, so nothing new is
	// published while the first one is still running.
	indigo_usleep(300000);
	ASSERT_EQ_INT(busy, revision(ao, AO_RESET_PROPERTY_NAME));
	ASSERT_EQ_INT(INDIGO_BUSY_STATE, property_state(ao, AO_RESET_PROPERTY_NAME));
	ASSERT_TRUE(wait_state(ao, AO_RESET_PROPERTY_NAME, busy, INDIGO_OK_STATE, RESET_TIMEOUT));
	// The dropped request must not have left its item set, otherwise the next centre would unjam.
	bool unjam = true;
	ASSERT_TRUE(switch_item(ao, AO_RESET_PROPERTY_NAME, AO_UNJAM_ITEM_NAME, &unjam));
	ASSERT_TRUE(!unjam);
	// The unit is still usable after the dropped request.
	ASSERT_TRUE(correct(AO_GUIDE_RA_PROPERTY_NAME, AO_GUIDE_EAST_ITEM_NAME, SMALL_CORRECTION));
	ASSERT_TRUE(center());
}

static void sx_ao_queues_a_correction_behind_a_reset(void) {
	ASSERT_TRUE(ready());
	unsigned reset_before = revision(ao, AO_RESET_PROPERTY_NAME);
	indigo_change_switch_property_1(&client, AO_DEVICE_NAME, AO_RESET_PROPERTY_NAME, AO_CENTER_ITEM_NAME, true);
	ASSERT_TRUE(wait_state(ao, AO_RESET_PROPERTY_NAME, reset_before, INDIGO_BUSY_STATE, SHORT_TIMEOUT));
	// A different property is not covered by the busy guard, so this request is accepted and has to
	// wait its turn on the device queue instead of being interleaved with the reset transaction.
	unsigned correction_before = revision(ao, AO_GUIDE_RA_PROPERTY_NAME);
	indigo_change_number_property_1(&client, AO_DEVICE_NAME, AO_GUIDE_RA_PROPERTY_NAME, AO_GUIDE_WEST_ITEM_NAME, SMALL_CORRECTION);
	ASSERT_TRUE(wait_state(ao, AO_GUIDE_RA_PROPERTY_NAME, correction_before, INDIGO_BUSY_STATE, SHORT_TIMEOUT));
	unsigned correction_busy = revision(ao, AO_GUIDE_RA_PROPERTY_NAME);
	bool serialized = true;
	double deadline = indigo_monotonic_time() + RESET_TIMEOUT;
	while (property_state(ao, AO_RESET_PROPERTY_NAME) == INDIGO_BUSY_STATE && indigo_monotonic_time() < deadline) {
		// While the reset owns the queue the correction cannot have been carried out. The reset
		// publishes OK for both guide properties when it completes, so only a revision newer than
		// the correction's own BUSY publication would mean the two transactions overlapped.
		if (revision(ao, AO_GUIDE_RA_PROPERTY_NAME) != correction_busy) {
			serialized = false;
			break;
		}
		indigo_usleep(2000);
	}
	ASSERT_TRUE(serialized);
	ASSERT_TRUE(wait_settled(ao, AO_RESET_PROPERTY_NAME, INDIGO_OK_STATE, RESET_TIMEOUT));
	ASSERT_TRUE(wait_settled(ao, AO_GUIDE_RA_PROPERTY_NAME, INDIGO_OK_STATE, CORRECTION_TIMEOUT));
	ASSERT_TRUE(corrected_item_is_cleared(AO_GUIDE_RA_PROPERTY_NAME, AO_GUIDE_WEST_ITEM_NAME));
	ASSERT_TRUE(center());
}

static void sx_ao_centers_and_corrects_again(void) {
	ASSERT_TRUE(ready());
	ASSERT_TRUE(correct(AO_GUIDE_DEC_PROPERTY_NAME, AO_GUIDE_SOUTH_ITEM_NAME, SMALL_CORRECTION * 2));
	ASSERT_TRUE(center());
	// The guide properties are republished as OK by a completed reset, which is how a client learns
	// that an axis that was reported at its limit has been recovered.
	ASSERT_EQ_INT(INDIGO_OK_STATE, property_state(ao, AO_GUIDE_RA_PROPERTY_NAME));
	ASSERT_EQ_INT(INDIGO_OK_STATE, property_state(ao, AO_GUIDE_DEC_PROPERTY_NAME));
	ASSERT_TRUE(correct(AO_GUIDE_DEC_PROPERTY_NAME, AO_GUIDE_NORTH_ITEM_NAME, SMALL_CORRECTION * 2));
	ASSERT_TRUE(center());
}

static void sx_ao_unjams_and_corrects_again(void) {
	ASSERT_TRUE(ready());
	// Unjam is the unit's own recovery sweep; it is run from a centred, unjammed mechanism, which is
	// the only way the class standard allows it to be exercised.
	ASSERT_TRUE(set_switch(ao, AO_RESET_PROPERTY_NAME, AO_UNJAM_ITEM_NAME, INDIGO_OK_STATE, RESET_TIMEOUT));
	ASSERT_EQ_INT(INDIGO_OK_STATE, property_state(ao, AO_GUIDE_RA_PROPERTY_NAME));
	ASSERT_EQ_INT(INDIGO_OK_STATE, property_state(ao, AO_GUIDE_DEC_PROPERTY_NAME));
	ASSERT_TRUE(correct(AO_GUIDE_RA_PROPERTY_NAME, AO_GUIDE_WEST_ITEM_NAME, SMALL_CORRECTION));
	ASSERT_TRUE(center());
}

static void sx_guider_pulses_in_all_four_directions(void) {
	static const struct { const char *property, *item; } pulses[] = {
		{ GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME },
		{ GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_SOUTH_ITEM_NAME },
		{ GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_EAST_ITEM_NAME },
		{ GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_WEST_ITEM_NAME }
	};
	ASSERT_TRUE(ready());
	ASSERT_TRUE(connect_device(guider, SHORT_TIMEOUT));
	ASSERT_TRUE((devices[guider].interface & INDIGO_INTERFACE_GUIDER) != 0);
	ASSERT_TRUE(property_defined(guider, GUIDER_GUIDE_RA_PROPERTY_NAME));
	ASSERT_TRUE(property_defined(guider, GUIDER_GUIDE_DEC_PROPERTY_NAME));
	// The guider opens the port through its master, so it has no port of its own to offer.
	ASSERT_TRUE(property_hidden(guider, DEVICE_PORT_PROPERTY_NAME));
	for (unsigned i = 0; i < ARRAY_SIZE(pulses); i++) {
		double value = -1;
		ASSERT_TRUE(set_number(guider, pulses[i].property, pulses[i].item, 200, INDIGO_OK_STATE, SHORT_TIMEOUT));
		ASSERT_TRUE(number_item(guider, pulses[i].property, pulses[i].item, &value));
		ASSERT_TRUE(value == 0);
	}
	// A pulse shorter than the unit's 10 ms resolution is still a request the driver has to accept
	// and complete rather than fail.
	ASSERT_TRUE(set_number(guider, GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_EAST_ITEM_NAME, 5, INDIGO_OK_STATE, SHORT_TIMEOUT));
	// The AO half of the shared connection keeps working while the guider is connected.
	ASSERT_TRUE(correct(AO_GUIDE_RA_PROPERTY_NAME, AO_GUIDE_EAST_ITEM_NAME, SMALL_CORRECTION));
	ASSERT_TRUE(center());
	ASSERT_TRUE(disconnect_device(guider));
	// Disconnecting the guider must not take the shared port away from the AO.
	ASSERT_EQ_INT(INDIGO_OK_STATE, property_state(ao, CONNECTION_PROPERTY_NAME));
	ASSERT_TRUE(correct(AO_GUIDE_RA_PROPERTY_NAME, AO_GUIDE_WEST_ITEM_NAME, SMALL_CORRECTION));
	ASSERT_TRUE(center());
}

// The guiding-pulse duration measurement required by indigo_drivers/AGENTS.override.md. The unit
// acknowledges the M command in about 15 ms and times the relay pulse itself, so what is measured
// here is the driver command path from the bus request to the public completion, reported both as
// the raw latency and as the signed error against the requested duration. It is explicitly not
// physical ST4 relay-output accuracy, which needs an instrument on the port.
static void sx_ao_measures_guide_pulse_duration(void) {
	static const double durations[] = { 100, 250, 500, 1000 };
	static const struct { const char *property, *item; } axes[] = {
		{ GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_EAST_ITEM_NAME },
		{ GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME }
	};
	const int repeats = 5;
	double signed_sum = 0, absolute_sum = 0, worst = 0, latency_sum = 0, latency_worst = 0;
	int samples = 0;
	ASSERT_TRUE(ready());
	ASSERT_TRUE(connect_device(guider, SHORT_TIMEOUT));
	for (unsigned d = 0; d < ARRAY_SIZE(durations); d++) {
		for (unsigned a = 0; a < ARRAY_SIZE(axes); a++) {
			for (int r = 0; r < repeats; r++) {
				unsigned before = revision(guider, axes[a].property);
				double started = indigo_monotonic_time();
				indigo_change_number_property_1(&client, GUIDER_DEVICE_NAME, axes[a].property, axes[a].item, durations[d]);
				ASSERT_TRUE(wait_state(guider, axes[a].property, before, INDIGO_OK_STATE, SHORT_TIMEOUT));
				double latency = (indigo_monotonic_time() - started) * 1000;
				double error = latency - durations[d];
				signed_sum += error;
				absolute_sum += fabs(error);
				latency_sum += latency;
				if (fabs(error) > fabs(worst)) {
					worst = error;
				}
				if (latency > latency_worst) {
					latency_worst = latency;
				}
				samples++;
			}
		}
	}
	ASSERT_EQ_INT((int)(ARRAY_SIZE(durations) * ARRAY_SIZE(axes) * repeats), samples);
	printf("    %d samples over 100, 250, 500 and 1000 ms on both axes\n", samples);
	printf("    command path latency: mean %.1f ms, max %.1f ms\n", latency_sum / samples, latency_worst);
	printf("    against the requested duration: signed mean %.1f ms, absolute mean %.1f ms, worst %.1f ms\n", signed_sum / samples, absolute_sum / samples, worst);
	printf("    the AO acknowledges immediately and times the pulse in firmware, so this is driver command path timing, not ST4 relay output timing\n");
	// The driver must return as soon as the unit acknowledges; a completion that tracked the pulse
	// would mean it was blocking its queue for the whole guide exposure.
	ASSERT_TRUE(latency_worst < durations[0]);
	ASSERT_TRUE(disconnect_device(guider));
}

static void sx_ao_shares_the_connection_in_both_orders(void) {
	// Guider first: the slave opens the port through its master, and the AO joining afterwards must
	// reuse the same handle rather than open a second one.
	ASSERT_TRUE(disconnect_device(guider));
	ASSERT_TRUE(disconnect_device(ao));
	ASSERT_TRUE(connect_device(guider, SHORT_TIMEOUT));
	ASSERT_TRUE(set_number(guider, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_SOUTH_ITEM_NAME, 200, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(connect_device(ao, SHORT_TIMEOUT));
	ASSERT_TRUE(correct(AO_GUIDE_DEC_PROPERTY_NAME, AO_GUIDE_NORTH_ITEM_NAME, SMALL_CORRECTION));
	// The sibling that is left behind keeps the port open and keeps working.
	ASSERT_TRUE(disconnect_device(guider));
	ASSERT_TRUE(correct(AO_GUIDE_DEC_PROPERTY_NAME, AO_GUIDE_SOUTH_ITEM_NAME, SMALL_CORRECTION));
	ASSERT_TRUE(center());
	// AO first, guider second, and this time the AO is the one that leaves.
	ASSERT_TRUE(connect_device(guider, SHORT_TIMEOUT));
	ASSERT_TRUE(disconnect_device(ao));
	ASSERT_TRUE(set_number(guider, GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_WEST_ITEM_NAME, 200, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(connect_device(ao, SHORT_TIMEOUT));
	ASSERT_TRUE(correct(AO_GUIDE_RA_PROPERTY_NAME, AO_GUIDE_EAST_ITEM_NAME, SMALL_CORRECTION));
	ASSERT_TRUE(center());
	ASSERT_TRUE(disconnect_device(guider));
}

static void sx_ao_clears_identity_on_last_close(void) {
	char model[INDIGO_VALUE_SIZE] = "", firmware[INDIGO_VALUE_SIZE] = "";
	ASSERT_TRUE(connect_device(ao, SHORT_TIMEOUT));
	ASSERT_TRUE(connect_device(guider, SHORT_TIMEOUT));
	// The AO leaves first, so the last reference on the shared port is released by the guider. The
	// identity belongs to the connection, so whichever logical device closes it, the AO has to stop
	// advertising the unit it is no longer talking to.
	ASSERT_TRUE(disconnect_device(ao));
	ASSERT_TRUE(text_item(ao, INFO_PROPERTY_NAME, INFO_DEVICE_MODEL_ITEM_NAME, model, sizeof(model)));
	ASSERT_TRUE(disconnect_device(guider));
	ASSERT_TRUE(text_item(ao, INFO_PROPERTY_NAME, INFO_DEVICE_MODEL_ITEM_NAME, model, sizeof(model)));
	ASSERT_TRUE(text_item(ao, INFO_PROPERTY_NAME, INFO_DEVICE_FW_REVISION_ITEM_NAME, firmware, sizeof(firmware)));
	if (strcmp(model, "Unknown") || strcmp(firmware, "Unknown")) {
		fprintf(stderr, "    after the last close SX AO still reports model \"%s\", firmware \"%s\"\n", model, firmware);
	}
	ASSERT_TRUE(!strcmp(model, "Unknown"));
	ASSERT_TRUE(!strcmp(firmware, "Unknown"));
	// Connecting again has to read the identity back from the unit.
	ASSERT_TRUE(connect_device(ao, SHORT_TIMEOUT));
	ASSERT_TRUE(text_item(ao, INFO_PROPERTY_NAME, INFO_DEVICE_FW_REVISION_ITEM_NAME, firmware, sizeof(firmware)));
	ASSERT_TRUE(!strcmp(firmware, initial_firmware));
}

static void sx_ao_reconnects(void) {
	char firmware[INDIGO_VALUE_SIZE] = "";
	ASSERT_TRUE(ready());
	ASSERT_TRUE(disconnect_device(ao));
	ASSERT_TRUE(connect_device(ao, SHORT_TIMEOUT));
	ASSERT_TRUE(text_item(ao, INFO_PROPERTY_NAME, INFO_DEVICE_FW_REVISION_ITEM_NAME, firmware, sizeof(firmware)));
	ASSERT_TRUE(!strcmp(firmware, initial_firmware));
	ASSERT_TRUE(correct(AO_GUIDE_DEC_PROPERTY_NAME, AO_GUIDE_NORTH_ITEM_NAME, SMALL_CORRECTION));
	ASSERT_TRUE(center());
}

static void sx_ao_reinitializes(void) {
	ASSERT_TRUE(ready());
	// A driver with a connected device must refuse to shut down instead of pulling the port out from
	// under its client.
	ASSERT_EQ_INT(INDIGO_BUSY, indigo_ao_sx(INDIGO_DRIVER_SHUTDOWN, NULL));
	ASSERT_TRUE(disconnect_device(ao));
	ASSERT_EQ_INT(INDIGO_OK, indigo_ao_sx(INDIGO_DRIVER_SHUTDOWN, NULL));
	ASSERT_EQ_INT(INDIGO_OK, indigo_ao_sx(INDIGO_DRIVER_INIT, NULL));
	ASSERT_TRUE(wait_presence(SHORT_TIMEOUT));
	ASSERT_TRUE(select_port());
	ASSERT_TRUE(connect_device(ao, SHORT_TIMEOUT));
	ASSERT_TRUE(correct(AO_GUIDE_RA_PROPERTY_NAME, AO_GUIDE_EAST_ITEM_NAME, SMALL_CORRECTION));
	ASSERT_TRUE(center());
}

int main(int argc, char **argv) {
	if (argc < 2 || strcmp(argv[1], "--run")) {
		fprintf(stderr, "Physical Starlight Xpress AO test: run explicitly with --run (or make test-ao-sx-hw).\n");
		return 2;
	}
	setvbuf(stdout, NULL, _IONBF, 0);
	for (int i = 2; i < argc; i++) {
		if (!strcmp(argv[i], "--debug")) {
			indigo_set_log_level(INDIGO_LOG_DEBUG);
		}
	}
	serial_port = getenv("AO_SX_HW_PORT");
	client = (indigo_client){ .name = "Starlight Xpress AO hardware test", .version = INDIGO_VERSION_CURRENT, .define_property = define_property, .update_property = update_property, .delete_property = delete_property, .send_message = report_message };
	const indigo_test_case tests[] = {
		{ "sx_ao_reports_identity_and_capabilities", sx_ao_reports_identity_and_capabilities },
		{ "sx_ao_publishes_the_property_contract", sx_ao_publishes_the_property_contract },
		{ "sx_ao_reports_initial_limit_status", sx_ao_reports_initial_limit_status },
		{ "sx_ao_corrects_in_all_four_directions", sx_ao_corrects_in_all_four_directions },
		{ "sx_ao_accepts_boundary_and_zero_corrections", sx_ao_accepts_boundary_and_zero_corrections },
		{ "sx_ao_publishes_busy_then_ok", sx_ao_publishes_busy_then_ok },
		{ "sx_ao_drops_an_overlapping_request", sx_ao_drops_an_overlapping_request },
		{ "sx_ao_queues_a_correction_behind_a_reset", sx_ao_queues_a_correction_behind_a_reset },
		{ "sx_ao_centers_and_corrects_again", sx_ao_centers_and_corrects_again },
		{ "sx_ao_unjams_and_corrects_again", sx_ao_unjams_and_corrects_again },
		{ "sx_guider_pulses_in_all_four_directions", sx_guider_pulses_in_all_four_directions },
		{ "sx_ao_measures_guide_pulse_duration", sx_ao_measures_guide_pulse_duration },
		{ "sx_ao_shares_the_connection_in_both_orders", sx_ao_shares_the_connection_in_both_orders },
		{ "sx_ao_clears_identity_on_last_close", sx_ao_clears_identity_on_last_close },
		{ "sx_ao_reconnects", sx_ao_reconnects },
		{ "sx_ao_reinitializes", sx_ao_reinitializes }
	};
	int result = 1;
	bool started = false, initialized = false;
	CHECK(indigo_start() == INDIGO_OK);
	started = true;
	CHECK(indigo_attach_client(&client) == INDIGO_OK);
	CHECK(indigo_ao_sx(INDIGO_DRIVER_INIT, NULL) == INDIGO_OK);
	initialized = true;
	CHECK(wait_presence(SHORT_TIMEOUT));
	CHECK(select_port());
	CHECK(connect_device(ao, SHORT_TIMEOUT));
	CHECK(center());
	result = indigo_run_tests("Starlight Xpress AO hardware", tests, ARRAY_SIZE(tests));
cleanup:
	// Leave the optical element centred whatever happened above.
	if (ao >= 0 && devices[ao].present && connect_device(ao, SHORT_TIMEOUT) && center()) {
		printf("Centred the AO\n");
	}
	if (!disconnect_device(guider) || !disconnect_device(ao)) {
		indigo_test_failures++;
	}
	if (initialized && indigo_ao_sx(INDIGO_DRIVER_SHUTDOWN, NULL) != INDIGO_OK) {
		indigo_test_failures++;
	}
	indigo_detach_client(&client);
	if (started) {
		indigo_stop();
	}
	for (int d = 0; d < MAX_DEVICES; d++) {
		for (int p = 0; p < MAX_PROPERTIES; p++) {
			indigo_release_property(devices[d].properties[p]);
		}
	}
	return indigo_test_failures ? 1 : result;
}
