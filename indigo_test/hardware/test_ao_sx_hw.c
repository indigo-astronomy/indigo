// Opt-in acceptance test for a physically connected Starlight Xpress AO unit (AO, AO-LF or
// AO-LF USB). It implements the AO hardware acceptance checklist of DRIVER_TESTING_RULES.md against
// the real unit: discovery and connection, identity readback, the published property contract, the
// initial limit status, corrections in all four directions, the step boundaries and the zero
// request, the BUSY/OK publication of a correction, the request the framework drops while another
// one runs, a correction queued behind a reset, centre, the supported unjam, the embedded ST4
// guider on its own and alongside the AO, both connection orders, last-close ownership, reconnect
// and driver INIT/SHUTDOWN.
//
// The optical element physically moves. Every correction stays inside the step range the driver
// itself advertises and every scenario centres the unit afterwards, so the mechanism is never
// driven into a jam or an end stop. The travel-limit reply is therefore not exercised here; it is
// covered by the simulator and the faked-transport suites.
//
// sx_ao_measures_guide_pulse_duration is the guiding-pulse measurement required by
// indigo_drivers/AGENTS.override.md. The AO acknowledges the guide command immediately and times
// the relay pulse in its own firmware, so this measures the driver command path, not the physical
// ST4 output. See indigo_drivers/ao_sx/REFACTOR.md.
//
// The serial port comes from AO_SX_HW_PORT. When it is not set the port the driver itself detected
// is used.

