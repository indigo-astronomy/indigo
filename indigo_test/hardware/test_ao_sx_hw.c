// Waits for a newer revision of the property in the requested state. The revision gate is required
// because a correction leaves its property in the same OK state it had before the request, so a
// state that was already published must not satisfy the wait.
static bool wait_state(int d, const char *name, unsigned after, indigo_property_state state, double timeout) {
	double deadline = indigo_monotonic_time() + timeout;
	while (indigo_monotonic_time() < deadline) {
		pthread_mutex_lock(&mutex);
		int p = slot(d, name);
		bool ready = p >= 0 && devices[d].revisions[p] > after && devices[d].properties[p]->state == state;
		pthread_mutex_unlock(&mutex);
		if (ready) {
			return true;
		}
		indigo_usleep(2000);
	}
	fprintf(stderr, "    timeout: %s %s expected state %d, last published state %d\n", devices[d].name, name, state, property_state(d, name));
	return false;
}

static bool wait_settled(int d, const char *name, indigo_property_state state, double timeout) {
	double deadline = indigo_monotonic_time() + timeout;
	while (indigo_monotonic_time() < deadline) {
		if (property_state(d, name) == state) {
			return true;
		}
		indigo_usleep(2000);
	}
	fprintf(stderr, "    timeout: %s %s did not settle in state %d (state %d)\n", devices[d].name, name, state, property_state(d, name));
	return false;
}

