// Code is generated by AI

// Opt-in acceptance test for the RTS-on-COM shutter release against a physical serial loopback:
// two USB serial adapters joined by a serial cable. The driver drives RTS on the first adapter,
// which is the whole device interaction, and the second adapter reads that line back. The shutter
// is therefore measured electrically, on a clock that is not the driver's own, which is the one
// thing indigo_test/integration/test_aux_rts_shutter.c structurally cannot do: it replaces
// indigo_uni_open_serial(), indigo_uni_close() and indigo_uni_set_rts() at compile time, so it
// sees only the calls the driver makes and never what the serial port actually does.
//
// No shutter release is wired to the adapter. What the driver opens and closes here is a modem
// control line, which is exactly what it would do with a camera on the other end.
//
// The two ports come from AUX_RTS_HW_PORT and AUX_RTS_HW_MONITOR_PORT and both are required. The
// suite never goes looking for them on its own: finding a loopback by toggling RTS on every
// serial port of the host would also toggle it on a mount or a focuser that happens to be
// plugged in. Prefer the stable /dev/serial/by-id/... names, because the unplug scenario relies
// on the port coming back under the name it left.
//
// Which input of the monitor carries the driver's RTS depends on the cable, so the suite works it
// out before the driver owns the port rather than assuming a wiring. A full-handshake null modem
// puts RTS on CTS; the cable this was developed against puts it on DCD. A straight-through
// extension cable joins two outputs and carries nothing, and the calibration says so instead of
// failing later as a timeout.
//
// The monitor side reads the line with a raw TIOCMGET. indigo_uni_io exposes indigo_uni_get_cts()
// only, which cannot see a line the cable delivers as DCD, and extending the portable I/O layer
// for a test host belongs to a separate change. This is test code on the observing side of the
// cable, never driver code: the driver under test keeps using the portable API throughout.
//
// The unplug scenario is opt-in through --hotplug. It pulls the driver's adapter in the middle of
// an exposure, which is the one failure a shutter release must not answer by latching the shutter
// open.

#include <fcntl.h>
#include <termios.h>
#include <sys/ioctl.h>
#include <indigo_drivers/aux_rts/indigo_aux_rts.h>
#include "hardware_test_common.h"

#define DEVICE_NAME "RTS-on-COM shutter"

// Opening a serial port plus the driver's own connection work.
#define SHORT_TIMEOUT 15.0
// The longest exposure a scenario starts, plus the completion latency.
#define EXPOSURE_TIMEOUT 30.0
// How long a scenario waits for the line to follow a request that has already been accepted.
#define LINE_TIMEOUT 2.0
// Waiting for a human or a script to pull the adapter and put it back.
#define HOTPLUG_TIMEOUT 120.0
// The exposure the unplug scenario interrupts. It has to outlast the unplug itself and then still
// reach its own deadline, because the deadline is the only moment the driver touches the line
// again and therefore the only moment it can find out that the adapter is gone.
#define UNPLUG_EXPOSURE 15.0

// The monitor is polled rather than woken: TIOCMIWAIT is Linux-only and macOS has no equivalent,
// and a poll keeps the same source running on both. Setting RTS on an FTDI adapter is a USB
// control transfer that takes about 0.85 ms to reach the wire, which dominates this interval, so
// an edge is timestamped to about a millisecond either way.
#define MONITOR_POLL_US 500
// Opening the port puts a pulse of a few milliseconds on the line, and the monitoring adapter
// reports a change up to one latency timer period late - 16 ms on an unconfigured FTDI. A request
// timed immediately after a connect would otherwise find the tail of that pulse in its own edge
// log, which is how this suite first mistook a correct connect for an open shutter.
#define MONITOR_SETTLE 0.05
// What the connection itself may leave on the line: the operating system asserts RTS when the port
// is opened and the driver lowers it again, so the camera sees a blip, never an open shutter.
#define CONNECT_PULSE_LIMIT 0.05

// The driver times the exposure itself and the line is read back over USB, so the budget covers
// the driver's own scheduling plus two adapter round trips.
#define HOLD_TOLERANCE 0.1

#define MAX_EDGES 128
#define MAX_COUNTDOWN 64

typedef struct {
	double at;
	bool level;
} rts_edge;

