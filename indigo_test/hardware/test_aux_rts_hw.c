// Connecting a shutter release must not fire it. The driver only ever lowers RTS on disconnect, on
// abort and at the end of an exposure, so this is where an asserted line survives into the session.
static void rts_leaves_the_shutter_closed_on_connect(void) {
	ASSERT_TRUE(hw_disconnect(shutter, SHORT_TIMEOUT));
	ASSERT_TRUE(monitor_wait(false, LINE_TIMEOUT, NULL));
	monitor_reset();
	ASSERT_TRUE(hw_connect(shutter, SHORT_TIMEOUT));
	double connected = indigo_monotonic_time();
	monitor_settle();
	rts_edge edges[MAX_EDGES];
	int count = monitor_snapshot(edges, MAX_EDGES);
	printf("    connecting produced %d edge(s):", count);
	for (int i = 0; i < count; i++) {
		printf(" %s@%+.3fs", edges[i].level ? "up" : "down", edges[i].at - connected);
	}
	printf("\n    the line is %s after connecting\n", monitor_level() ? "HIGH - the shutter is open" : "low");
	ASSERT_FALSE(monitor_level());
	// Either the monitor missed the pulse altogether or it saw exactly one rise and one fall. A
	// lone rise would mean the shutter stayed open, which the level check above already caught.
	ASSERT_TRUE(count == 0 || count == 2);
	if (count == 2) {
		printf("    the connection pulse lasted %.1f ms\n", (edges[1].at - edges[0].at) * 1000);
		ASSERT_TRUE(edges[0].level && !edges[1].level);
		ASSERT_TRUE(edges[1].at - edges[0].at < CONNECT_PULSE_LIMIT);
	}
	exposure_result result;
	ASSERT_TRUE(run_exposure(1.0, &result));
	ASSERT_FALSE(result.level_before);
	ASSERT_TRUE(result.saw_rise);
	ASSERT_TRUE(result.saw_fall);
	ASSERT_NEAR(1.0, result.held, HOLD_TOLERANCE);
}

static void rts_holds_the_line_for_the_requested_time(void) {
	const double durations[] = { 0.3, 1.0, 2.5 };
	for (unsigned i = 0; i < ARRAY_SIZE(durations); i++) {
		exposure_result result;
		ASSERT_TRUE(run_exposure(durations[i], &result));
		ASSERT_EQ_INT(INDIGO_OK_STATE, result.final_state);
		ASSERT_FALSE(result.level_before);
		ASSERT_TRUE(result.saw_rise);
		ASSERT_TRUE(result.saw_fall);
		ASSERT_NEAR(durations[i], result.held, HOLD_TOLERANCE);
		ASSERT_FALSE(monitor_level());
	}
}

// The published countdown is a display of whole seconds; the shutter is timed separately from it.
static void rts_publishes_a_whole_second_countdown(void) {
	double seen[MAX_COUNTDOWN];
	int count = 0;
	monitor_reset();
	unsigned before = hw_revision(shutter, CCD_EXPOSURE_PROPERTY_NAME);
	hw_request_number(shutter, CCD_EXPOSURE_PROPERTY_NAME, CCD_EXPOSURE_ITEM_NAME, 2.5);
	double deadline = indigo_monotonic_time() + EXPOSURE_TIMEOUT;
	while (indigo_monotonic_time() < deadline) {
		double value = 0;
		if (hw_number_item(shutter, CCD_EXPOSURE_PROPERTY_NAME, CCD_EXPOSURE_ITEM_NAME, &value)) {
			if (count == 0 || fabs(seen[count - 1] - value) > 0.0001) {
				if (count < MAX_COUNTDOWN) {
					seen[count++] = value;
				}
			}
		}
		if (hw_revision(shutter, CCD_EXPOSURE_PROPERTY_NAME) != before && hw_property_state(shutter, CCD_EXPOSURE_PROPERTY_NAME) == INDIGO_OK_STATE) {
			break;
		}
		indigo_usleep(20000);
	}
	printf("    published countdown:");
	for (int i = 0; i < count; i++) {
		printf(" %g", seen[i]);
	}
	printf("\n");
	ASSERT_TRUE(count >= 3);
	// seen[0] is the request the framework echoed back with BUSY and is the exact duration asked
	// for; every later value is the driver's own countdown and has to be a whole second.
	for (int i = 1; i < count; i++) {
		ASSERT_NEAR(seen[i], floor(seen[i] + 0.5), 0.0001);
		ASSERT_TRUE(seen[i] < seen[i - 1]);
	}
	ASSERT_NEAR(0, seen[count - 1], 0.0001);
	ASSERT_TRUE(monitor_wait(false, LINE_TIMEOUT, NULL));
}

static void rts_aborts_and_closes_the_shutter(void) {
	monitor_reset();
	unsigned before = hw_revision(shutter, CCD_EXPOSURE_PROPERTY_NAME);
	hw_request_number(shutter, CCD_EXPOSURE_PROPERTY_NAME, CCD_EXPOSURE_ITEM_NAME, 20.0);
	ASSERT_TRUE(monitor_wait(true, LINE_TIMEOUT, NULL));
	indigo_usleep(1000000);
	double requested = indigo_monotonic_time();
	hw_request_switch(shutter, CCD_ABORT_EXPOSURE_PROPERTY_NAME, CCD_ABORT_EXPOSURE_ITEM_NAME, true);
	double closed = 0;
	ASSERT_TRUE(monitor_wait(false, LINE_TIMEOUT, &closed));
	printf("    the shutter closed %.3f s after the abort was requested\n", closed - requested);
	ASSERT_TRUE(hw_wait_state(shutter, CCD_EXPOSURE_PROPERTY_NAME, before, INDIGO_ALERT_STATE, SHORT_TIMEOUT));
	double remaining = 0;
	ASSERT_TRUE(hw_number_item(shutter, CCD_EXPOSURE_PROPERTY_NAME, CCD_EXPOSURE_ITEM_NAME, &remaining));
	ASSERT_NEAR(0, remaining, 0.0001);
	indigo_usleep(2000000);
	ASSERT_FALSE(monitor_level());
	exposure_result result;
	ASSERT_TRUE(run_exposure(1.0, &result));
	ASSERT_NEAR(1.0, result.held, HOLD_TOLERANCE);
}

// Disconnecting with the shutter open must release it rather than leave the camera exposing.
static void rts_releases_the_line_on_disconnect(void) {
	monitor_reset();
	hw_request_number(shutter, CCD_EXPOSURE_PROPERTY_NAME, CCD_EXPOSURE_ITEM_NAME, 20.0);
	ASSERT_TRUE(monitor_wait(true, LINE_TIMEOUT, NULL));
	indigo_usleep(500000);
	ASSERT_TRUE(hw_disconnect(shutter, SHORT_TIMEOUT));
	ASSERT_TRUE(monitor_wait(false, LINE_TIMEOUT, NULL));
	ASSERT_FALSE(hw_property_defined(shutter, CCD_EXPOSURE_PROPERTY_NAME));
	ASSERT_FALSE(hw_property_defined(shutter, CCD_ABORT_EXPOSURE_PROPERTY_NAME));
	ASSERT_TRUE(hw_connect(shutter, SHORT_TIMEOUT));
	ASSERT_TRUE(hw_property_defined(shutter, CCD_EXPOSURE_PROPERTY_NAME));
}

static void rts_reconnects(void) {
	ASSERT_TRUE(hw_disconnect(shutter, SHORT_TIMEOUT));
	ASSERT_TRUE(hw_disconnect(shutter, SHORT_TIMEOUT));
	ASSERT_TRUE(hw_connect(shutter, SHORT_TIMEOUT));
	exposure_result result;
	ASSERT_TRUE(run_exposure(0.5, &result));
	ASSERT_EQ_INT(INDIGO_OK_STATE, result.final_state);
	ASSERT_NEAR(0.5, result.held, HOLD_TOLERANCE);
}

static bool wait_for_port(bool present, double timeout) {
	double deadline = indigo_monotonic_time() + timeout;
	while (indigo_monotonic_time() < deadline) {
		if ((access(driver_port, F_OK) == 0) == present) {
			return true;
		}
		indigo_usleep(100000);
	}
	fprintf(stderr, "    %s did not %s within %.0f s\n", driver_port, present ? "come back" : "disappear", timeout);
	return false;
}

// The adapter is pulled while the shutter is open. A shutter release has no readback of any kind,
// so the driver has nothing to poll and cannot learn that the adapter is gone until it next drives
// the line, which is when the exposure reaches its deadline. What is asserted is that it reports
// the failure there instead of publishing an exposure it never managed to end, that it tears down
// without hanging, and that it works again once the adapter is back.
static void rts_survives_the_adapter_unplug(void) {
	monitor_reset();
	unsigned before = hw_revision(shutter, CCD_EXPOSURE_PROPERTY_NAME);
	hw_request_number(shutter, CCD_EXPOSURE_PROPERTY_NAME, CCD_EXPOSURE_ITEM_NAME, UNPLUG_EXPOSURE);
	ASSERT_TRUE(monitor_wait(true, LINE_TIMEOUT, NULL));
	printf("HOTPLUG_READY\n");
	ASSERT_TRUE(wait_for_port(false, HOTPLUG_TIMEOUT));
	printf("HOTPLUG_REMOVED\n");
	printf("    the line went %s when the adapter lost power\n", monitor_wait(false, LINE_TIMEOUT, NULL) ? "down" : "NOWHERE - the shutter stayed open");
	ASSERT_TRUE(hw_wait_state(shutter, CCD_EXPOSURE_PROPERTY_NAME, before, INDIGO_ALERT_STATE, UNPLUG_EXPOSURE + EXPOSURE_TIMEOUT));
	ASSERT_TRUE(hw_disconnect(shutter, SHORT_TIMEOUT));
	ASSERT_TRUE(wait_for_port(true, HOTPLUG_TIMEOUT));
	printf("HOTPLUG_RECOVERED\n");
	// udev recreates the by-id symlink a moment before the node is usable.
	indigo_usleep(1000000);
	ASSERT_TRUE(hw_connect(shutter, SHORT_TIMEOUT));
	exposure_result result;
	ASSERT_TRUE(run_exposure(1.0, &result));
	ASSERT_EQ_INT(INDIGO_OK_STATE, result.final_state);
	ASSERT_NEAR(1.0, result.held, HOLD_TOLERANCE);
}

int main(int argc, char **argv) {
	if (argc < 2 || strcmp(argv[1], "--run")) {
		fprintf(stderr, "Physical RTS-on-COM loopback test: run explicitly with --run (or make test-aux-rts-hw).\n");
		return 2;
	}
	setvbuf(stdout, NULL, _IONBF, 0);
	for (int i = 2; i < argc; i++) {
		if (!strcmp(argv[i], "--debug")) {
			indigo_set_log_level(INDIGO_LOG_DEBUG);
		} else if (!strcmp(argv[i], "--hotplug")) {
			hotplug = true;
		}
	}
	driver_port = getenv("AUX_RTS_HW_PORT");
	monitor_port = getenv("AUX_RTS_HW_MONITOR_PORT");
	if (driver_port == NULL || !*driver_port || monitor_port == NULL || !*monitor_port) {
		fprintf(stderr, "Set AUX_RTS_HW_PORT to the port the driver drives and AUX_RTS_HW_MONITOR_PORT to the\n");
		fprintf(stderr, "port at the other end of the serial cable. Prefer the /dev/serial/by-id/... names.\n");
		return 2;
	}
	printf("Driver port  %s\nMonitor port %s\n", driver_port, monitor_port);
	if (!indigo_test_use_private_home()) {
		return 1;
	}
	const indigo_test_case tests[] = {
		{ "rts_reports_identity_and_capabilities", rts_reports_identity_and_capabilities },
		{ "rts_publishes_the_property_contract", rts_publishes_the_property_contract },
		{ "rts_leaves_the_shutter_closed_on_connect", rts_leaves_the_shutter_closed_on_connect },
		{ "rts_holds_the_line_for_the_requested_time", rts_holds_the_line_for_the_requested_time },
		{ "rts_publishes_a_whole_second_countdown", rts_publishes_a_whole_second_countdown },
		{ "rts_aborts_and_closes_the_shutter", rts_aborts_and_closes_the_shutter },
		{ "rts_releases_the_line_on_disconnect", rts_releases_the_line_on_disconnect },
		{ "rts_reconnects", rts_reconnects },
		{ "rts_survives_the_adapter_unplug", rts_survives_the_adapter_unplug }
	};
	int count = ARRAY_SIZE(tests) - (hotplug ? 0 : 1);
	int result = 1;
	bool started = false, initialized = false, monitoring = false;
	HW_CHECK(monitor_start());
	monitoring = true;
	HW_CHECK(indigo_start() == INDIGO_OK);
	started = true;
	HW_CHECK(hw_attach_client("RTS-on-COM hardware test") == INDIGO_OK);
	HW_CHECK(indigo_aux_rts(INDIGO_DRIVER_INIT, NULL) == INDIGO_OK);
	initialized = true;
	shutter = hw_wait_for_device(DEVICE_NAME, SHORT_TIMEOUT);
	HW_CHECK(shutter >= 0);
	printf("Found %s\n", hw_device_name(shutter));
	HW_CHECK(!hw_property_defined(shutter, CCD_EXPOSURE_PROPERTY_NAME));
	HW_CHECK(hw_set_text(shutter, DEVICE_PORT_PROPERTY_NAME, DEVICE_PORT_ITEM_NAME, driver_port, INDIGO_OK_STATE, SHORT_TIMEOUT));
	HW_CHECK(hw_connect(shutter, SHORT_TIMEOUT));
	result = indigo_run_tests("RTS-on-COM shutter hardware", tests, count);
cleanup:
	if (!hw_disconnect(shutter, SHORT_TIMEOUT)) {
		indigo_test_failures++;
	}
	if (initialized && indigo_aux_rts(INDIGO_DRIVER_SHUTDOWN, NULL) != INDIGO_OK) {
		indigo_test_failures++;
	}
	indigo_detach_client(&hw_client);
	if (started) {
		indigo_stop();
	}
	hw_release_properties();
	if (monitoring) {
		monitor_stop();
	}
	indigo_test_remove_private_home();
	return indigo_test_failures ? 1 : result;
}
