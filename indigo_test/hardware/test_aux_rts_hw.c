static bool monitor_failed = false;

// Opens a port the way indigo_uni_io.c opens one, so the line states this suite observes are the
// ones the driver's own open() produces rather than an artefact of different termios settings.
static int line_open(const char *name) {
	int fd = open(name, O_RDWR | O_NOCTTY | O_SYNC);
	if (fd < 0) {
		fprintf(stderr, "    cannot open %s (%s)\n", name, strerror(errno));
		return -1;
	}
	struct termios options;
	memset(&options, 0, sizeof(options));
	options.c_cflag = CS8 | CLOCAL | CREAD;
	options.c_iflag = IGNPAR;
	options.c_cc[VMIN] = 0;
	options.c_cc[VTIME] = 50;
	cfsetispeed(&options, B9600);
	cfsetospeed(&options, B9600);
	if (tcsetattr(fd, TCSANOW, &options) == -1) {
		fprintf(stderr, "    cannot configure %s (%s)\n", name, strerror(errno));
		close(fd);
		return -1;
	}
	return fd;
}

static bool line_status(int fd, int *status) {
	return ioctl(fd, TIOCMGET, status) >= 0;
}

static void line_set(int fd, int bit, bool on) {
	int flag = bit;
	if (ioctl(fd, on ? TIOCMBIS : TIOCMBIC, &flag) < 0) {
		fprintf(stderr, "    cannot change modem line (%s)\n", strerror(errno));
	}
}

static void describe_mask(int mask, char *buffer, size_t size) {
	snprintf(buffer, size, "%s%s%s%s", (mask & TIOCM_CTS) ? "CTS " : "", (mask & TIOCM_DSR) ? "DSR " : "", (mask & TIOCM_CAR) ? "DCD " : "", (mask & TIOCM_RNG) ? "RI " : "");
	size_t used = strlen(buffer);
	if (used > 0 && buffer[used - 1] == ' ') {
		buffer[used - 1] = 0;
	}
}

static void *monitor_poll(void *data) {
	(void)data;
	while (monitor_running) {
		int status = 0;
		if (!line_status(monitor_fd, &status)) {
			pthread_mutex_lock(&monitor_mutex);
			monitor_failed = true;
			pthread_mutex_unlock(&monitor_mutex);
			indigo_usleep(MONITOR_POLL_US);
			continue;
		}
		bool level = (status & monitor_mask) != 0;
		double at = indigo_monotonic_time();
		pthread_mutex_lock(&monitor_mutex);
		if (level != monitor_level_now) {
			monitor_level_now = level;
			if (monitor_count < MAX_EDGES) {
				monitor_log[monitor_count].at = at;
				monitor_log[monitor_count].level = level;
				monitor_count++;
			}
		}
		pthread_mutex_unlock(&monitor_mutex);
		indigo_usleep(MONITOR_POLL_US);
	}
	return NULL;
}

// Works out which input of the monitor follows the driver's RTS, while the driver port is still
// free. Both of the monitor's own outputs are parked low first, because a cable that crosses them
// back would otherwise make the monitor observe itself.
static bool monitor_calibrate(void) {
	int probe = line_open(driver_port);
	if (probe < 0) {
		return false;
	}
	line_set(monitor_fd, TIOCM_RTS, false);
	line_set(monitor_fd, TIOCM_DTR, false);
	line_set(probe, TIOCM_RTS, false);
	line_set(probe, TIOCM_DTR, false);
	indigo_usleep(200000);
	int low = 0, high = 0;
	bool read_low = line_status(monitor_fd, &low);
	line_set(probe, TIOCM_RTS, true);
	indigo_usleep(200000);
	bool read_high = line_status(monitor_fd, &high);
	line_set(probe, TIOCM_RTS, false);
	indigo_usleep(200000);
	close(probe);
	if (!read_low || !read_high) {
		fprintf(stderr, "    cannot read the modem lines of %s\n", monitor_port);
		return false;
	}
	monitor_mask = (low ^ high) & (TIOCM_CTS | TIOCM_DSR | TIOCM_CAR | TIOCM_RNG);
	if (monitor_mask == 0) {
		fprintf(stderr, "    RTS on %s does not reach any input of %s.\n", driver_port, monitor_port);
		fprintf(stderr, "    A straight-through cable joins two outputs and carries nothing; this needs a\n");
		fprintf(stderr, "    null-modem cable or a null-modem adapter, and both adapters must wire the\n");
		fprintf(stderr, "    handshake lines out.\n");
		return false;
	}
	describe_mask(monitor_mask, monitor_mask_name, sizeof(monitor_mask_name));
	printf("The cable delivers RTS of %s as %s on %s\n", driver_port, monitor_mask_name, monitor_port);
	return true;
}

static bool monitor_start(void) {
	monitor_fd = line_open(monitor_port);
	if (monitor_fd < 0) {
		return false;
	}
	if (!monitor_calibrate()) {
		close(monitor_fd);
		monitor_fd = -1;
		return false;
	}
	int status = 0;
	line_status(monitor_fd, &status);
	monitor_level_now = (status & monitor_mask) != 0;
	monitor_running = true;
	if (pthread_create(&monitor_thread, NULL, monitor_poll, NULL) != 0) {
		fprintf(stderr, "    cannot start the line monitor\n");
		monitor_running = false;
		close(monitor_fd);
		monitor_fd = -1;
		return false;
	}
	return true;
}

static void monitor_stop(void) {
	if (monitor_running) {
		monitor_running = false;
		pthread_join(monitor_thread, NULL);
	}
	if (monitor_fd >= 0) {
		close(monitor_fd);
		monitor_fd = -1;
	}
}

static void monitor_reset(void) {
	pthread_mutex_lock(&monitor_mutex);
	monitor_count = 0;
	monitor_failed = false;
	pthread_mutex_unlock(&monitor_mutex);
}

// Waits until the line has held its level long enough for the monitoring adapter to have reported
// everything that already happened on it. Bounded, and never asserts: a line that is steadily high
// settles just as fast as one that is steadily low, so a caller can still report which it was.
static void monitor_settle(void) {
	double deadline = indigo_monotonic_time() + LINE_TIMEOUT;
	double quiet = indigo_monotonic_time();
	int last = -1;
	while (indigo_monotonic_time() < deadline) {
		pthread_mutex_lock(&monitor_mutex);
		int count = monitor_count;
		pthread_mutex_unlock(&monitor_mutex);
		if (count != last) {
			last = count;
			quiet = indigo_monotonic_time();
		} else if (indigo_monotonic_time() - quiet >= MONITOR_SETTLE) {
			return;
		}
		indigo_usleep(MONITOR_POLL_US);
	}
}

// True once the monitoring adapter has stopped answering, which makes every measurement taken
// since meaningless. A suite that reported confident numbers off a dead adapter would be worse
// than one that failed.
static bool monitor_lost(void) {
	pthread_mutex_lock(&monitor_mutex);
	bool lost = monitor_failed;
	pthread_mutex_unlock(&monitor_mutex);
	return lost;
}

static bool monitor_level(void) {
	pthread_mutex_lock(&monitor_mutex);
	bool level = monitor_level_now;
	pthread_mutex_unlock(&monitor_mutex);
	return level;
}

static int monitor_snapshot(rts_edge *edges, int max) {
	pthread_mutex_lock(&monitor_mutex);
	int count = monitor_count < max ? monitor_count : max;
	memcpy(edges, monitor_log, count * sizeof(rts_edge));
	pthread_mutex_unlock(&monitor_mutex);
	return count;
}

static bool monitor_wait(bool level, double timeout, double *at) {
	double deadline = indigo_monotonic_time() + timeout;
	while (indigo_monotonic_time() < deadline) {
		if (monitor_level() == level) {
			if (at != NULL) {
				*at = indigo_monotonic_time();
			}
			return true;
		}
		indigo_usleep(MONITOR_POLL_US);
	}
	fprintf(stderr, "    the line did not go %s within %.1f s\n", level ? "up" : "down", timeout);
	return false;
}

// Requests an exposure and reports what the cable saw while it ran, next to what the property did.
static bool run_exposure(double seconds, exposure_result *result) {
	memset(result, 0, sizeof(*result));
	result->held = -1;
	monitor_settle();
	monitor_reset();
	result->level_before = monitor_level();
	unsigned before = hw_revision(shutter, CCD_EXPOSURE_PROPERTY_NAME);
	double started = indigo_monotonic_time();
	hw_request_number(shutter, CCD_EXPOSURE_PROPERTY_NAME, CCD_EXPOSURE_ITEM_NAME, seconds);
	if (!hw_wait_state(shutter, CCD_EXPOSURE_PROPERTY_NAME, before, INDIGO_OK_STATE, EXPOSURE_TIMEOUT)) {
		result->final_state = hw_property_state(shutter, CCD_EXPOSURE_PROPERTY_NAME);
		return false;
	}
	result->completed = indigo_monotonic_time() - started;
	result->final_state = hw_property_state(shutter, CCD_EXPOSURE_PROPERTY_NAME);
	if (monitor_lost()) {
		fprintf(stderr, "    %s stopped answering; this measurement is not valid\n", monitor_port);
		return false;
	}
	// The falling edge can land a poll interval after the property was published, so give the
	// monitor that long before the log is read.
	indigo_usleep(3 * MONITOR_POLL_US);
	rts_edge edges[MAX_EDGES];
	int count = monitor_snapshot(edges, MAX_EDGES);
	for (int i = 0; i < count; i++) {
		if (edges[i].level && !result->saw_rise) {
			result->saw_rise = true;
			result->rise_at = edges[i].at;
		} else if (!edges[i].level && result->saw_rise && !result->saw_fall) {
			result->saw_fall = true;
			result->fall_at = edges[i].at;
		}
	}
	if (result->saw_rise && result->saw_fall) {
		result->held = result->fall_at - result->rise_at;
	}
	printf("    %.3f s requested: line %s before the request, %s, completed in %.3f s\n", seconds, result->level_before ? "HIGH" : "low", result->held >= 0 ? "held for" : "no rise/fall pair seen", result->completed);
	if (result->level_before) {
		printf("      edges after the reset:");
		for (int i = 0; i < count; i++) {
			printf(" %s@%+.3fs", edges[i].level ? "up" : "down", edges[i].at - started);
		}
		printf("\n");
	}
	if (result->held >= 0) {
		printf("      measured hold %.3f s, error %+.3f s\n", result->held, result->held - seconds);
	}
	return true;
}

