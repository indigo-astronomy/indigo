// RAW+JPEG: the RAW is the main image and the JPEG of the same shot the preview, twice in a row.
static void raw_jpeg_with_preview(void) {
	CHECK(camera >= 0);
	char name[INDIGO_NAME_SIZE];
	if (!find_compression(true, true, name)) {
		printf("    RAW+JPEG is not offered, skipped\n");
		return;
	}
	CHECK(select_name(DSLR_COMPRESSION_PROPERTY_NAME, name));
	CHECK(select_name(CCD_PREVIEW_PROPERTY_NAME, CCD_PREVIEW_ENABLED_ITEM_NAME));
	CHECK(use_fixed_shutter());
	for (int i = 0; i < 2; i++) {
		observed_device before = state_copy();
		CHECK(acquire(0.01, 120));
		for (int iteration = 0; iteration < 1000 && state_copy().previews == before.previews; iteration++) {
			indigo_usleep(10000);
		}
		observed_device after = state_copy();
		printf("    preview %s %ld bytes, %u x %u\n", after.preview.format, after.preview.size, after.preview.width, after.preview.height);
		CHECK(strcmp(after.image.format, ".jpeg") && after.image.complete);
		CHECK(after.previews == before.previews + 1);
		CHECK(!strcmp(after.preview.format, ".jpeg") && after.preview.valid);
	}
	// The pair must be fully drained: a following JPEG shot delivers its own single image.
	CHECK(select_name(CCD_PREVIEW_PROPERTY_NAME, CCD_PREVIEW_DISABLED_ITEM_NAME));
	CHECK(select_jpeg());
	CHECK(acquire(0.01, 60));
	CHECK(!strcmp(state_copy().image.format, ".jpeg"));
cleanup:
	select_name(CCD_PREVIEW_PROPERTY_NAME, CCD_PREVIEW_DISABLED_ITEM_NAME);
	return;
}

// The decoded RAW format turns the camera JPEG into an RGB24 image of the same size.
static void decoded_jpeg(void) {
	CHECK(camera >= 0);
	CHECK(select_jpeg());
	CHECK(use_fixed_shutter());
	CHECK(acquire(0.01, 60));
	observed_device native = state_copy();
	CHECK(change_switch(camera, CCD_IMAGE_FORMAT_PROPERTY_NAME, CCD_IMAGE_FORMAT_RAW_ITEM_NAME, INDIGO_OK_STATE));
	CHECK(acquire(0.01, 60));
	observed_device decoded = state_copy();
	printf("    native %u x %u, decoded %s %u x %u\n", native.image.width, native.image.height, decoded.image.format, decoded.image.width, decoded.image.height);
	CHECK(!strcmp(decoded.image.format, ".raw") && decoded.image.valid);
	CHECK(decoded.image.width == native.image.width && decoded.image.height == native.image.height);
cleanup:
	change_switch(camera, CCD_IMAGE_FORMAT_PROPERTY_NAME, CCD_IMAGE_FORMAT_NATIVE_ITEM_NAME, INDIGO_OK_STATE);
	return;
}

// Upload BOTH saves the native file next to the client copy; the file must hold exactly the BLOB.
static void local_save(void) {
	CHECK(camera >= 0);
	CHECK(select_jpeg());
	CHECK(use_fixed_shutter());
	unsigned before = property_revision(camera, CCD_LOCAL_MODE_PROPERTY_NAME);
	indigo_change_text_property_1_raw(&client, devices[camera].name, CCD_LOCAL_MODE_PROPERTY_NAME, CCD_LOCAL_MODE_DIR_ITEM_NAME, image_dir);
	CHECK(wait_state(camera, CCD_LOCAL_MODE_PROPERTY_NAME, before, INDIGO_OK_STATE, 10));
	CHECK(change_switch(camera, CCD_UPLOAD_MODE_PROPERTY_NAME, CCD_UPLOAD_MODE_BOTH_ITEM_NAME, INDIGO_OK_STATE));
	unsigned files = state_copy().saved_files;
	CHECK(acquire(0.01, 60));
	for (int iteration = 0; iteration < 500 && state_copy().saved_files == files; iteration++) {
		indigo_usleep(10000);
	}
	observed_device state = state_copy();
	struct stat file_info = { 0 };
	bool saved = state.saved_files == files + 1 && !stat(state.saved_file, &file_info);
	printf("    saved %s, %lld bytes, BLOB %ld bytes\n", state.saved_file, (long long)file_info.st_size, state.image.size);
	if (saved) {
		remove(state.saved_file);
	}
	CHECK(saved);
	CHECK(file_info.st_size == state.image.size);
	CHECK(strncmp(state.saved_file, image_dir, strlen(image_dir)) == 0);
cleanup:
	change_switch(camera, CCD_UPLOAD_MODE_PROPERTY_NAME, CCD_UPLOAD_MODE_CLIENT_ITEM_NAME, INDIGO_OK_STATE);
	return;
}

// BULB timing as seen on the bus: completion not before the requested duration.
static void bulb_exposures(void) {
	CHECK(camera >= 0);
	char bulb[INDIGO_NAME_SIZE];
	if (!find_label(DSLR_SHUTTER_PROPERTY_NAME, "Bulb", bulb)) {
		printf("    Bulb is not offered (mode dial not in M, or no USB BULB), skipped\n");
		return;
	}
	CHECK(select_jpeg());
	CHECK(select_name(DSLR_SHUTTER_PROPERTY_NAME, bulb));
	double durations[] = { 1.25, 2.5 };
	for (unsigned i = 0; i < sizeof(durations) / sizeof(durations[0]); i++) {
		double started = indigo_monotonic_time();
		CHECK(acquire(durations[i], durations[i] + 60));
		double elapsed = indigo_monotonic_time() - started;
		printf("    bulb %g s completed after %.3f s\n", durations[i], elapsed);
		CHECK(elapsed >= durations[i]);
	}
cleanup:
	return;
}

static void abort_and_reacquire(void) {
	CHECK(camera >= 0);
	char bulb[INDIGO_NAME_SIZE];
	CHECK(select_jpeg());
	bool has_bulb = find_label(DSLR_SHUTTER_PROPERTY_NAME, "Bulb", bulb);
	if (has_bulb) {
		CHECK(select_name(DSLR_SHUTTER_PROPERTY_NAME, bulb));
	} else {
		CHECK(use_fixed_shutter());
	}
	unsigned images = state_copy().images;
	unsigned revision = property_revision(camera, CCD_EXPOSURE_PROPERTY_NAME);
	indigo_change_number_property_1(&client, devices[camera].name, CCD_EXPOSURE_PROPERTY_NAME, CCD_EXPOSURE_ITEM_NAME, 10);
	CHECK(wait_state(camera, CCD_EXPOSURE_PROPERTY_NAME, revision, INDIGO_BUSY_STATE, 10));
	indigo_usleep(2000000);
	revision = property_revision(camera, CCD_EXPOSURE_PROPERTY_NAME);
	double started = indigo_monotonic_time();
	indigo_change_switch_property_1(&client, devices[camera].name, CCD_ABORT_EXPOSURE_PROPERTY_NAME, CCD_ABORT_EXPOSURE_ITEM_NAME, true);
	if (has_bulb) {
		CHECK(wait_state(camera, CCD_EXPOSURE_PROPERTY_NAME, revision, INDIGO_ALERT_STATE, 30));
	} else {
		// Without BULB the camera's own shutter ends the frame, possibly before the abort arrives.
		indigo_property_state state = INDIGO_BUSY_STATE;
		for (int iteration = 0; iteration < 3000 && state == INDIGO_BUSY_STATE; iteration++) {
			indigo_property *exposure = snapshot(camera, CCD_EXPOSURE_PROPERTY_NAME);
			state = exposure ? exposure->state : INDIGO_ALERT_STATE;
			indigo_release_property(exposure);
			if (state == INDIGO_BUSY_STATE) {
				indigo_usleep(10000);
			}
		}
		printf("    timed exposure %s\n", state == INDIGO_OK_STATE ? "completed before the abort" : state == INDIGO_ALERT_STATE ? "aborted" : "still busy");
		CHECK(state == INDIGO_OK_STATE || state == INDIGO_ALERT_STATE);
	}
	printf("    abort completed after %.3f s\n", indigo_monotonic_time() - started);
	// A BULB abort closes the shutter, and the camera may still store and hand over that frame.
	indigo_usleep(5000000);
	unsigned late = state_copy().images - images;
	printf("    images after abort: %u\n", late);
	CHECK(late <= 1);
	CHECK(use_fixed_shutter());
	CHECK(acquire(0.01, 60));
	CHECK(!strcmp(state_copy().image.format, ".jpeg"));
cleanup:
	return;
}

static void finite_liveview(void) {
	CHECK(camera >= 0);
	CHECK(use_fixed_shutter());
	unsigned before = state_copy().images;
	unsigned revision = property_revision(camera, CCD_STREAMING_PROPERTY_NAME);
	double started = indigo_monotonic_time();
	indigo_change_number_property(&client, devices[camera].name, CCD_STREAMING_PROPERTY_NAME, 2, (const char *[]){ CCD_STREAMING_EXPOSURE_ITEM_NAME, CCD_STREAMING_COUNT_ITEM_NAME }, (double []){ 0.01, 5 });
	CHECK(wait_state(camera, CCD_STREAMING_PROPERTY_NAME, revision, INDIGO_OK_STATE, 60));
	observed_device state = state_copy();
	printf("    5 live view frames in %.3f s, last %u x %u\n", indigo_monotonic_time() - started, state.image.width, state.image.height);
	CHECK(state.images == before + 5);
	CHECK(!strcmp(state.image.format, ".jpeg") && state.image.valid);
	CHECK(number_value(camera, CCD_STREAMING_PROPERTY_NAME, 1) == 0);
cleanup:
	return;
}

static void indefinite_liveview_abort_and_restart(void) {
	CHECK(camera >= 0);
	CHECK(use_fixed_shutter());
	unsigned before = state_copy().images;
	unsigned revision = property_revision(camera, CCD_STREAMING_PROPERTY_NAME);
	indigo_change_number_property(&client, devices[camera].name, CCD_STREAMING_PROPERTY_NAME, 2, (const char *[]){ CCD_STREAMING_EXPOSURE_ITEM_NAME, CCD_STREAMING_COUNT_ITEM_NAME }, (double []){ 0.01, -1 });
	CHECK(wait_state(camera, CCD_STREAMING_PROPERTY_NAME, revision, INDIGO_BUSY_STATE, 10));
	double started = indigo_monotonic_time();
	for (int iteration = 0; iteration < 6000 && state_copy().images < before + 30; iteration++) {
		indigo_usleep(10000);
	}
	double elapsed = indigo_monotonic_time() - started;
	unsigned frames = state_copy().images - before;
	printf("    indefinite live view: %u frames in %.3f s\n", frames, elapsed);
	CHECK(frames >= 30);
	revision = property_revision(camera, CCD_STREAMING_PROPERTY_NAME);
	indigo_change_switch_property_1(&client, devices[camera].name, CCD_ABORT_EXPOSURE_PROPERTY_NAME, CCD_ABORT_EXPOSURE_ITEM_NAME, true);
	CHECK(wait_state(camera, CCD_STREAMING_PROPERTY_NAME, revision, INDIGO_OK_STATE, 30) || wait_state(camera, CCD_STREAMING_PROPERTY_NAME, revision, INDIGO_ALERT_STATE, 1));
	indigo_usleep(1000000);
	unsigned stopped = state_copy().images;
	indigo_usleep(2000000);
	CHECK(state_copy().images == stopped);
	CHECK(state_copy().image.valid);
	before = state_copy().images;
	revision = property_revision(camera, CCD_STREAMING_PROPERTY_NAME);
	indigo_change_number_property(&client, devices[camera].name, CCD_STREAMING_PROPERTY_NAME, 2, (const char *[]){ CCD_STREAMING_EXPOSURE_ITEM_NAME, CCD_STREAMING_COUNT_ITEM_NAME }, (double []){ 0.01, 2 });
	CHECK(wait_state(camera, CCD_STREAMING_PROPERTY_NAME, revision, INDIGO_OK_STATE, 60));
	CHECK(state_copy().images == before + 2);
	CHECK(acquire(0.01, 60));
cleanup:
	return;
}

// Relative lens focus through the logical focuser, in manual focus (the camera answers DeviceBusy
// to focus steps in AF-S). A state machine check only: lens travel is not observable here.
static void lens_focuser(void) {
	CHECK(camera >= 0);
	find_focuser();
	if (focuser < 0) {
		printf("    no focuser device, skipped\n");
		return;
	}
	char manual[INDIGO_NAME_SIZE] = "1";
	indigo_property *focus_mode = snapshot(camera, DSLR_FOCUS_MODE_PROPERTY_NAME);
	bool has_manual = focus_mode && indigo_get_item(focus_mode, manual) && focus_mode->perm == INDIGO_RW_PERM;
	printf("    focus mode %s: %s\n", manual, has_manual ? indigo_get_item(focus_mode, manual)->label : "not offered");
	indigo_release_property(focus_mode);
	if (has_manual) {
		CHECK(select_name(DSLR_FOCUS_MODE_PROPERTY_NAME, manual));
	}
	CHECK(change_switch(focuser, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, INDIGO_OK_STATE));
	CHECK(change_switch(focuser, FOCUSER_DIRECTION_PROPERTY_NAME, FOCUSER_DIRECTION_MOVE_INWARD_ITEM_NAME, INDIGO_OK_STATE));
	CHECK(change_number(focuser, FOCUSER_STEPS_PROPERTY_NAME, FOCUSER_STEPS_ITEM_NAME, 3, INDIGO_OK_STATE, 60));
	CHECK(change_switch(focuser, FOCUSER_DIRECTION_PROPERTY_NAME, FOCUSER_DIRECTION_MOVE_OUTWARD_ITEM_NAME, INDIGO_OK_STATE));
	CHECK(change_number(focuser, FOCUSER_STEPS_PROPERTY_NAME, FOCUSER_STEPS_ITEM_NAME, 3, INDIGO_OK_STATE, 60));
	CHECK(disconnect_device(focuser));
	CHECK(use_fixed_shutter());
	CHECK(acquire(0.01, 60));
cleanup:
	if (focuser >= 0) {
		disconnect_device(focuser);
	}
	return;
}

static void reconnect(void) {
	CHECK(camera >= 0);
	for (int i = 0; i < 3; i++) {
		CHECK(disconnect_device(camera));
		CHECK(connect_camera());
		CHECK(use_fixed_shutter());
		CHECK(acquire(0.01, 60));
	}
cleanup:
	return;
}

// Restores the initial settings before the driver is shut down, so the last case leaves the camera
// as it was found.
static void shutdown_and_reinit(void) {
	CHECK(camera >= 0);
	CHECK(restore_settings());
	CHECK(indigo_ccd_ptp(INDIGO_DRIVER_SHUTDOWN, NULL) == INDIGO_BUSY);
	CHECK(disconnect_device(camera));
	CHECK(indigo_ccd_ptp(INDIGO_DRIVER_SHUTDOWN, NULL) == INDIGO_OK);
	initialized = false;
	CHECK(indigo_ccd_ptp(INDIGO_DRIVER_INIT, NULL) == INDIGO_OK);
	initialized = true;
	CHECK(wait_presence());
	CHECK(connect_camera());
	CHECK(use_fixed_shutter());
	CHECK(acquire(0.01, 60));
	CHECK(restore_settings());
cleanup:
	return;
}

