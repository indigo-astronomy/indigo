// Every image size must deliver a JPEG of its own, smaller sizes fewer pixels.
static void image_sizes(void) {
	char names[8][INDIGO_NAME_SIZE], labels[8][INDIGO_VALUE_SIZE];
	unsigned long pixels[8] = { 0 };
	int count = 0;
	CHECK(camera >= 0);
	CHECK(select_jpeg());
	CHECK(use_fixed_shutter());
	indigo_property *mode = snapshot(camera, CCD_MODE_PROPERTY_NAME);
	if (mode == NULL || mode->perm != INDIGO_RW_PERM) {
		printf("    image size is not writable, skipped\n");
		indigo_release_property(mode);
		return;
	}
	for (int i = 0; i < mode->count && count < 8; i++, count++) {
		snprintf(names[count], INDIGO_NAME_SIZE, "%s", mode->items[i].name);
		snprintf(labels[count], INDIGO_VALUE_SIZE, "%s", mode->items[i].label);
	}
	indigo_release_property(mode);
	int kept = 0;
	for (int i = 0; i < count; i++) {
		bool selected = select_name(CCD_MODE_PROPERTY_NAME, names[i]);
		printf("    size %s (%s): %s\n", labels[i], names[i], selected ? "kept" : "not kept by the camera");
		kept += selected;
	}
	CHECK(kept == count);
	for (int i = 0; i < count; i++) {
		CHECK(select_name(CCD_MODE_PROPERTY_NAME, names[i]));
		CHECK(acquire(0.01, 60));
		observed_device state = state_copy();
		pixels[i] = (unsigned long)state.image.width * state.image.height;
		printf("    size %s: %u x %u\n", labels[i], state.image.width, state.image.height);
		CHECK(pixels[i] > 0);
	}
	for (int i = 0; i < count; i++) {
		for (int j = 0; j < count; j++) {
			// Labels name the size first (L/M/S); equal labels would compare equal sizes.
			if (labels[i][0] == 'L' && (labels[j][0] == 'M' || labels[j][0] == 'S')) {
				CHECK(pixels[i] > pixels[j]);
			}
			if (labels[i][0] == 'M' && labels[j][0] == 'S') {
				CHECK(pixels[i] > pixels[j]);
			}
		}
	}
cleanup:
	return;
}

