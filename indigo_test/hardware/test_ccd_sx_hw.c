static void shared_lifecycle_and_rejected_shutdown(void) {
	CHECK(start_driver());
	for (int c = 0; c < camera_count; c++) {
		int ccd = cameras[c].ccd, guider = cameras[c].guider;
		bool star2k = cameras[c].caps->star2k;
		for (int first = 0; first < 2; first++) {
			int order[] = { first ? guider : ccd, first ? ccd : guider };
			if (first && !star2k) {
				continue;
			}
			CHECK(connect_device(order[0]));
			CHECK(star2k ? connect_device(order[1]) : true);
			CHECK(indigo_ccd_sx(INDIGO_DRIVER_SHUTDOWN, NULL) == INDIGO_BUSY);
			CHECK(prepare_client_raw(ccd));
			CHECK(acquire(ccd, 0.05));
			CHECK(disconnect_device(order[0]));
			if (star2k) {
				if (order[0] == ccd) {
					CHECK(set_number(guider, GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_EAST_ITEM_NAME, 100, INDIGO_BUSY_STATE, 5));
					CHECK(wait_state(guider, GUIDER_GUIDE_RA_PROPERTY_NAME, revision(guider, GUIDER_GUIDE_RA_PROPERTY_NAME) - 1, INDIGO_OK_STATE, 5));
				} else {
					CHECK(acquire(ccd, 0.05));
				}
				CHECK(disconnect_device(order[1]));
			}
		}
		if (!star2k) {
			CHECK(connect_device(guider) == false);
			CHECK(state_of(guider, CONNECTION_PROPERTY_NAME) == INDIGO_ALERT_STATE);
			CHECK(!switch_of(guider, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME));
			CHECK(disconnect_device(guider));
		}
		for (int cycle = 0; cycle < 3; cycle++) {
			CHECK(connect_device(ccd));
			CHECK(prepare_client_raw(ccd));
			CHECK(acquire(ccd, 0.05));
			CHECK(disconnect_device(ccd));
		}
	}
	CHECK(indigo_ccd_sx(INDIGO_DRIVER_SHUTDOWN, NULL) == INDIGO_OK);
	driver_initialized = false;
cleanup:
	stop_driver();
}

static void acquisition_units_types_bins_and_roi(void) {
	CHECK(start_driver());
	for (int c = 0; c < camera_count; c++) {
		int ccd = cameras[c].ccd;
		int width = cameras[c].caps->width, height = cameras[c].caps->height;
		CHECK(connect_device(ccd));
		CHECK(prepare_client_raw(ccd));
		CHECK(acquire(ccd, 0.05));
		CHECK(devices[ccd].frame_width == (unsigned)width && devices[ccd].frame_height == (unsigned)height);
		const char *types[] = { CCD_FRAME_TYPE_LIGHT_ITEM_NAME, CCD_FRAME_TYPE_FLAT_ITEM_NAME, CCD_FRAME_TYPE_DARK_ITEM_NAME, CCD_FRAME_TYPE_DARKFLAT_ITEM_NAME, CCD_FRAME_TYPE_BIAS_ITEM_NAME };
		for (int i = 0; i < ARRAY_SIZE(types); i++) {
			CHECK(set_switch(ccd, CCD_FRAME_TYPE_PROPERTY_NAME, types[i], INDIGO_OK_STATE, 5));
			CHECK(acquire(ccd, 0.05));
			if (!strcmp(types[i], CCD_FRAME_TYPE_BIAS_ITEM_NAME)) {
				CHECK(number_of(ccd, CCD_EXPOSURE_PROPERTY_NAME, CCD_EXPOSURE_ITEM_NAME) == 0 || number_of(ccd, CCD_EXPOSURE_PROPERTY_NAME, CCD_EXPOSURE_ITEM_NAME) < 0.05);
			}
		}
		CHECK(set_switch(ccd, CCD_FRAME_TYPE_PROPERTY_NAME, CCD_FRAME_TYPE_LIGHT_ITEM_NAME, INDIGO_OK_STATE, 5));
		for (int bin = 1; bin <= 4; bin *= 2) {
			char mode[16];
			snprintf(mode, sizeof(mode), "BIN_%dx%d", bin, bin);
			CHECK(set_switch(ccd, CCD_MODE_PROPERTY_NAME, mode, INDIGO_OK_STATE, 5));
			CHECK(number_of(ccd, CCD_BIN_PROPERTY_NAME, CCD_BIN_HORIZONTAL_ITEM_NAME) == bin && number_of(ccd, CCD_BIN_PROPERTY_NAME, CCD_BIN_VERTICAL_ITEM_NAME) == bin);
			CHECK(acquire(ccd, 0.05));
			CHECK(devices[ccd].frame_width == (unsigned)(width / bin) && devices[ccd].frame_height == (unsigned)(height / bin));
		}
		const double invalid[][2] = { { 3, 3 }, { 1, 2 }, { 5, 5 } };
		const char *bin_items[] = { CCD_BIN_HORIZONTAL_ITEM_NAME, CCD_BIN_VERTICAL_ITEM_NAME };
		const double accepted[] = { 2, 2 }, restored[] = { 1, 1 };
		CHECK(set_switch(ccd, CCD_MODE_PROPERTY_NAME, "BIN_1x1", INDIGO_OK_STATE, 5));
		// An accepted binning commits value and target together; that committed pair is what a refused one has to keep.
		CHECK(set_numbers(ccd, CCD_BIN_PROPERTY_NAME, 2, bin_items, accepted, INDIGO_OK_STATE, 5));
		CHECK(number_of(ccd, CCD_BIN_PROPERTY_NAME, CCD_BIN_HORIZONTAL_ITEM_NAME) == 2 && target_of(ccd, CCD_BIN_PROPERTY_NAME, CCD_BIN_HORIZONTAL_ITEM_NAME) == 2);
		CHECK(number_of(ccd, CCD_BIN_PROPERTY_NAME, CCD_BIN_VERTICAL_ITEM_NAME) == 2 && target_of(ccd, CCD_BIN_PROPERTY_NAME, CCD_BIN_VERTICAL_ITEM_NAME) == 2);
		CHECK(set_numbers(ccd, CCD_BIN_PROPERTY_NAME, 2, bin_items, restored, INDIGO_OK_STATE, 5));
		for (int i = 0; i < ARRAY_SIZE(invalid); i++) {
			CHECK(set_numbers(ccd, CCD_BIN_PROPERTY_NAME, 2, bin_items, invalid[i], INDIGO_ALERT_STATE, 5));
			// The refusal precedes every copy, so both the published values and the targets stay on the last accepted pair.
			CHECK(number_of(ccd, CCD_BIN_PROPERTY_NAME, CCD_BIN_HORIZONTAL_ITEM_NAME) == 1 && number_of(ccd, CCD_BIN_PROPERTY_NAME, CCD_BIN_VERTICAL_ITEM_NAME) == 1);
			CHECK(target_of(ccd, CCD_BIN_PROPERTY_NAME, CCD_BIN_HORIZONTAL_ITEM_NAME) == 1 && target_of(ccd, CCD_BIN_PROPERTY_NAME, CCD_BIN_VERTICAL_ITEM_NAME) == 1);
		}
		// The property has to work again after the refusals.
		CHECK(set_numbers(ccd, CCD_BIN_PROPERTY_NAME, 2, bin_items, accepted, INDIGO_OK_STATE, 5));
		CHECK(acquire(ccd, 0.05));
		CHECK(devices[ccd].frame_width == (unsigned)(width / 2) && devices[ccd].frame_height == (unsigned)(height / 2));
		CHECK(set_numbers(ccd, CCD_BIN_PROPERTY_NAME, 2, bin_items, restored, INDIGO_OK_STATE, 5));
		const char *frame_items[] = { CCD_FRAME_LEFT_ITEM_NAME, CCD_FRAME_TOP_ITEM_NAME, CCD_FRAME_WIDTH_ITEM_NAME, CCD_FRAME_HEIGHT_ITEM_NAME };
		const double roi[] = { 64, 60, 256, 192 };
		CHECK(set_numbers(ccd, CCD_FRAME_PROPERTY_NAME, 4, frame_items, roi, INDIGO_OK_STATE, 5));
		CHECK(acquire(ccd, 0.05));
		CHECK(devices[ccd].frame_width == 256 && devices[ccd].frame_height == 192);
		const double overflow[] = { (double)(width - 16), (double)(height - 16), 256, 192 };
		CHECK(set_numbers(ccd, CCD_FRAME_PROPERTY_NAME, 4, frame_items, overflow, INDIGO_ALERT_STATE, 5));
		CHECK(number_of(ccd, CCD_FRAME_PROPERTY_NAME, CCD_FRAME_WIDTH_ITEM_NAME) == 16 && number_of(ccd, CCD_FRAME_PROPERTY_NAME, CCD_FRAME_HEIGHT_ITEM_NAME) == 16);
		CHECK(acquire(ccd, 0.05));
		const double full[] = { 0, 0, (double)width, (double)height };
		CHECK(set_numbers(ccd, CCD_FRAME_PROPERTY_NAME, 4, frame_items, full, INDIGO_OK_STATE, 5));
		CHECK(acquire(ccd, 1.5));
		CHECK(acquire(ccd, 4));
		CHECK(acquire(ccd, 0.05));
		CHECK(invalid_frames_of(ccd) == 0);
		CHECK(devices[ccd].uniform_frames < devices[ccd].frames);
		printf("    %s: %u frames, %u invalid, %u uniform\n", devices[ccd].name, devices[ccd].frames, devices[ccd].invalid_frames, devices[ccd].uniform_frames);
		CHECK(disconnect_device(ccd));
	}
cleanup:
	stop_driver();
}

static void abort_and_reacquisition(void) {
	CHECK(start_driver());
	for (int c = 0; c < camera_count; c++) {
		int ccd = cameras[c].ccd;
		CHECK(connect_device(ccd));
		CHECK(prepare_client_raw(ccd));
		unsigned before = frames_of(ccd);
		CHECK(set_number(ccd, CCD_EXPOSURE_PROPERTY_NAME, CCD_EXPOSURE_ITEM_NAME, 20, INDIGO_BUSY_STATE, 5));
		indigo_usleep(1500000);
		CHECK(state_of(ccd, CCD_EXPOSURE_PROPERTY_NAME) == INDIGO_BUSY_STATE);
		CHECK(set_switch(ccd, CCD_ABORT_EXPOSURE_PROPERTY_NAME, CCD_ABORT_EXPOSURE_ITEM_NAME, INDIGO_OK_STATE, 10));
		CHECK(wait_state(ccd, CCD_EXPOSURE_PROPERTY_NAME, 0, INDIGO_ALERT_STATE, 5));
		indigo_usleep(500000);
		CHECK(frames_of(ccd) == before);
		CHECK(acquire(ccd, 0.05));
		before = frames_of(ccd);
		CHECK(set_number(ccd, CCD_EXPOSURE_PROPERTY_NAME, CCD_EXPOSURE_ITEM_NAME, 0.05, INDIGO_BUSY_STATE, 5));
		indigo_usleep(150000);
		double issued = indigo_monotonic_time();
		indigo_change_switch_property_1(&client, devices[ccd].name, CCD_ABORT_EXPOSURE_PROPERTY_NAME, CCD_ABORT_EXPOSURE_ITEM_NAME, true);
		bool settled = false;
		for (double waited = 0; waited < 60 && !settled; waited += 0.01) {
			settled = state_of(ccd, CCD_EXPOSURE_PROPERTY_NAME) != INDIGO_BUSY_STATE && state_of(ccd, CCD_ABORT_EXPOSURE_PROPERTY_NAME) != INDIGO_BUSY_STATE;
			if (!settled) {
				indigo_usleep(10000);
			}
		}
		indigo_usleep(500000);
		printf("    %s: abort during readout -> exposure %d, abort %d, frames %+d, latency %.3f s\n", devices[ccd].name, state_of(ccd, CCD_EXPOSURE_PROPERTY_NAME), state_of(ccd, CCD_ABORT_EXPOSURE_PROPERTY_NAME), (int)(frames_of(ccd) - before), indigo_monotonic_time() - issued);
		CHECK(settled);
		CHECK(frames_of(ccd) - before <= 1);
		CHECK(acquire(ccd, 0.05));
		CHECK(set_switch(ccd, CCD_ABORT_EXPOSURE_PROPERTY_NAME, CCD_ABORT_EXPOSURE_ITEM_NAME, INDIGO_ALERT_STATE, 5));
		CHECK(acquire(ccd, 0.05));
		CHECK(disconnect_device(ccd));
	}
cleanup:
	stop_driver();
}

static void cooling_profile(void) {
	CHECK(start_driver());
	for (int c = 0; c < camera_count; c++) {
		int ccd = cameras[c].ccd;
		CHECK(connect_device(ccd));
		if (!cameras[c].caps->cooler) {
			printf("    %s: uncooled, CCD_COOLER and CCD_TEMPERATURE hidden\n", devices[ccd].name);
			CHECK(!exists(ccd, CCD_COOLER_PROPERTY_NAME) && !exists(ccd, CCD_TEMPERATURE_PROPERTY_NAME) && !exists(ccd, CCD_COOLER_POWER_PROPERTY_NAME));
			CHECK(prepare_client_raw(ccd));
			CHECK(acquire(ccd, 0.05));
			CHECK(disconnect_device(ccd));
			continue;
		}
		bool cooler_was_on = switch_of(ccd, CCD_COOLER_PROPERTY_NAME, CCD_COOLER_ON_ITEM_NAME);
		double initial_temperature = number_of(ccd, CCD_TEMPERATURE_PROPERTY_NAME, CCD_TEMPERATURE_ITEM_NAME);
		double initial_target = number_of(ccd, CCD_TEMPERATURE_PROPERTY_NAME, CCD_TEMPERATURE_ITEM_NAME);
		printf("    %s: initial temperature %.1f C, cooler %s\n", devices[ccd].name, initial_temperature, cooler_was_on ? "on" : "off");
		CHECK(initial_temperature > -60 && initial_temperature < 60);
		double target = floor(initial_temperature) - 5;
		CHECK(set_number(ccd, CCD_TEMPERATURE_PROPERTY_NAME, CCD_TEMPERATURE_ITEM_NAME, target, INDIGO_BUSY_STATE, 10));
		CHECK(wait_switch(ccd, CCD_COOLER_PROPERTY_NAME, CCD_COOLER_ON_ITEM_NAME, true, 5));
		CHECK(number_of(ccd, CCD_TEMPERATURE_PROPERTY_NAME, CCD_TEMPERATURE_ITEM_NAME) != target);
		double started = indigo_monotonic_time(), last = initial_temperature;
		unsigned updates = 0;
		while (indigo_monotonic_time() - started < 30) {
			unsigned mark = revision(ccd, CCD_TEMPERATURE_PROPERTY_NAME);
			if (!wait_revision(ccd, CCD_TEMPERATURE_PROPERTY_NAME, mark, 12)) {
				break;
			}
			CHECK(state_of(ccd, CCD_TEMPERATURE_PROPERTY_NAME) != INDIGO_ALERT_STATE && state_of(ccd, CCD_COOLER_PROPERTY_NAME) != INDIGO_ALERT_STATE);
			last = number_of(ccd, CCD_TEMPERATURE_PROPERTY_NAME, CCD_TEMPERATURE_ITEM_NAME);
			updates++;
		}
		printf("    %s: target %.1f C, %u temperature updates, last %.1f C, cooler state %d\n", devices[ccd].name, target, updates, last, state_of(ccd, CCD_COOLER_PROPERTY_NAME));
		CHECK(updates >= 2);
		CHECK(last > -60 && last < 60);
		CHECK(last <= initial_temperature - 0.5);
		CHECK(prepare_client_raw(ccd));
		CHECK(acquire(ccd, 0.05));
		CHECK(set_switch(ccd, CCD_COOLER_PROPERTY_NAME, CCD_COOLER_OFF_ITEM_NAME, INDIGO_OK_STATE, 10));
		CHECK(wait_switch(ccd, CCD_COOLER_PROPERTY_NAME, CCD_COOLER_ON_ITEM_NAME, false, 10));
		CHECK(acquire(ccd, 0.05));
		CHECK(disconnect_device(ccd));
		CHECK(connect_device(ccd));
		printf("    %s: temperature after reconnect %.1f C\n", devices[ccd].name, number_of(ccd, CCD_TEMPERATURE_PROPERTY_NAME, CCD_TEMPERATURE_ITEM_NAME));
		if (cooler_was_on) {
			CHECK(set_number(ccd, CCD_TEMPERATURE_PROPERTY_NAME, CCD_TEMPERATURE_ITEM_NAME, initial_target, INDIGO_BUSY_STATE, 10));
		}
		CHECK(disconnect_device(ccd));
	}
cleanup:
	stop_driver();
}

static bool pulse(int guider, const char *property, const char *direction, double milliseconds, indigo_property_state state) {
	return set_number(guider, property, direction, milliseconds, state, 10);
}

static void guider_pulses_and_shared_acquisition(void) {
	CHECK(start_driver());
	for (int c = 0; c < camera_count; c++) {
		int ccd = cameras[c].ccd, guider = cameras[c].guider;
		if (!cameras[c].caps->star2k) {
			printf("    %s: no Star2K, guider connection refused\n", devices[ccd].name);
			continue;
		}
		CHECK(connect_device(ccd));
		CHECK(connect_device(guider));
		CHECK(prepare_client_raw(ccd));
		const char *properties[] = { GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_DEC_PROPERTY_NAME };
		const char *items[] = { GUIDER_GUIDE_EAST_ITEM_NAME, GUIDER_GUIDE_WEST_ITEM_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME, GUIDER_GUIDE_SOUTH_ITEM_NAME };
		for (int i = 0; i < 4; i++) {
			unsigned before = revision(guider, properties[i]);
			CHECK(pulse(guider, properties[i], items[i], 200, INDIGO_BUSY_STATE));
			CHECK(wait_state(guider, properties[i], before + 1, INDIGO_OK_STATE, 5));
			CHECK(number_of(guider, properties[i], items[i]) == 0);
		}
		double started = indigo_monotonic_time();
		CHECK(pulse(guider, GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_EAST_ITEM_NAME, 800, INDIGO_BUSY_STATE));
		indigo_usleep(200000);
		CHECK(pulse(guider, GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_WEST_ITEM_NAME, 200, INDIGO_BUSY_STATE));
		CHECK(wait_state(guider, GUIDER_GUIDE_RA_PROPERTY_NAME, revision(guider, GUIDER_GUIDE_RA_PROPERTY_NAME) - 1, INDIGO_OK_STATE, 10));
		double replaced = indigo_monotonic_time() - started;
		printf("    %s: 800 ms pulse replaced after 200 ms by a 200 ms pulse, the axis finished in %.3f s\n", devices[guider].name, replaced);
		CHECK(replaced > 0.3 && replaced < 0.7);
		CHECK(number_of(guider, GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_EAST_ITEM_NAME) == 0 && number_of(guider, GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_WEST_ITEM_NAME) == 0);
		started = indigo_monotonic_time();
		CHECK(pulse(guider, GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_EAST_ITEM_NAME, 3000, INDIGO_BUSY_STATE));
		indigo_usleep(300000);
		CHECK(pulse(guider, GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_EAST_ITEM_NAME, 0, INDIGO_OK_STATE));
		double cancelled = indigo_monotonic_time() - started;
		printf("    %s: zero request cancelled the running 3000 ms pulse after %.3f s\n", devices[guider].name, cancelled);
		CHECK(cancelled < 1.5);
		CHECK(pulse(guider, GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_EAST_ITEM_NAME, 300, INDIGO_BUSY_STATE));
		CHECK(pulse(guider, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME, 600, INDIGO_BUSY_STATE));
		CHECK(wait_state(guider, GUIDER_GUIDE_RA_PROPERTY_NAME, revision(guider, GUIDER_GUIDE_RA_PROPERTY_NAME) - 1, INDIGO_OK_STATE, 5));
		CHECK(state_of(guider, GUIDER_GUIDE_DEC_PROPERTY_NAME) == INDIGO_BUSY_STATE || state_of(guider, GUIDER_GUIDE_DEC_PROPERTY_NAME) == INDIGO_OK_STATE);
		CHECK(wait_state(guider, GUIDER_GUIDE_DEC_PROPERTY_NAME, 0, INDIGO_OK_STATE, 5));
		unsigned before_frames = frames_of(ccd);
		expect_geometry(ccd, (unsigned)number_of(ccd, CCD_FRAME_PROPERTY_NAME, CCD_FRAME_WIDTH_ITEM_NAME), (unsigned)number_of(ccd, CCD_FRAME_PROPERTY_NAME, CCD_FRAME_HEIGHT_ITEM_NAME));
		CHECK(set_number(ccd, CCD_EXPOSURE_PROPERTY_NAME, CCD_EXPOSURE_ITEM_NAME, 6, INDIGO_BUSY_STATE, 5));
		for (int i = 0; i < 4; i++) {
			unsigned before = revision(guider, properties[i]);
			CHECK(pulse(guider, properties[i], items[i], 250, INDIGO_BUSY_STATE));
			CHECK(wait_state(guider, properties[i], before + 1, INDIGO_OK_STATE, 10));
		}
		CHECK(state_of(ccd, CCD_EXPOSURE_PROPERTY_NAME) == INDIGO_BUSY_STATE);
		CHECK(wait_state(ccd, CCD_EXPOSURE_PROPERTY_NAME, 0, INDIGO_OK_STATE, 60));
		CHECK(wait_frames(ccd, before_frames + 1, 10));
		CHECK(invalid_frames_of(ccd) == 0);
		CHECK(pulse(guider, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_SOUTH_ITEM_NAME, 700, INDIGO_BUSY_STATE));
		CHECK(disconnect_device(guider));
		CHECK(acquire(ccd, 0.05));
		CHECK(connect_device(guider));
		CHECK(pulse(guider, GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_WEST_ITEM_NAME, 100, INDIGO_BUSY_STATE));
		CHECK(wait_state(guider, GUIDER_GUIDE_RA_PROPERTY_NAME, 0, INDIGO_OK_STATE, 5));
		CHECK(disconnect_device(guider));
		CHECK(disconnect_device(ccd));
	}
cleanup:
	stop_driver();
}

static int compare_samples(const void *left, const void *right) {
	double a = *(const double *)left, b = *(const double *)right;
	return (a > b) - (a < b);
}

static void guider_pulse_timing(void) {
	CHECK(start_driver());
	for (int c = 0; c < camera_count; c++) {
		int ccd = cameras[c].ccd, guider = cameras[c].guider;
		if (!cameras[c].caps->star2k) {
			continue;
		}
		CHECK(connect_device(ccd));
		CHECK(connect_device(guider));
		CHECK(prepare_client_raw(ccd));
		INDIGO_COPY_NAME(timed_guider, devices[guider].name);
		const char *properties[] = { GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_RA_PROPERTY_NAME };
		const char *directions[] = { GUIDER_GUIDE_WEST_ITEM_NAME, GUIDER_GUIDE_SOUTH_ITEM_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME, GUIDER_GUIDE_EAST_ITEM_NAME };
		const int durations[] = { 20, 50, 100, 250, 500 };
		double errors[80], absolute[80], total = 0, squares = 0;
		int count = 0;
		for (int workload = 0; workload < 2; workload++) {
			if (workload) {
				expect_geometry(ccd, (unsigned)number_of(ccd, CCD_FRAME_PROPERTY_NAME, CCD_FRAME_WIDTH_ITEM_NAME), (unsigned)number_of(ccd, CCD_FRAME_PROPERTY_NAME, CCD_FRAME_HEIGHT_ITEM_NAME));
				CHECK(set_number(ccd, CCD_EXPOSURE_PROPERTY_NAME, CCD_EXPOSURE_ITEM_NAME, 60, INDIGO_BUSY_STATE, 5));
			}
			for (int direction = 0; direction < 4; direction++) {
				int axis = !strcmp(properties[direction], GUIDER_GUIDE_DEC_PROPERTY_NAME);
				for (int sample = -1; sample < 5; sample++) {
					int requested = sample < 0 ? 20 : durations[sample];
					unsigned before = guide_completions[axis];
					guide_started[axis] = 0;
					CHECK(pulse(guider, properties[direction], directions[direction], requested, INDIGO_BUSY_STATE));
					CHECK(wait_state(guider, properties[direction], revision(guider, properties[direction]) - 1, INDIGO_OK_STATE, 10));
					CHECK(guide_completions[axis] == before + 1);
					if (sample < 0) {
						continue;
					}
					double actual = (guide_finished[axis] - guide_started[axis]) * 1000;
					double error = actual - requested;
					CHECK(isfinite(actual) && actual > 0);
					printf("    %s %s %s requested=%d ms observed=%.3f ms error=%+.3f ms (%+.2f%%)\n", devices[guider].name, workload ? "exposing" : "idle", directions[direction], requested, actual, error, error / requested * 100);
					errors[count] = error;
					absolute[count++] = fabs(error);
					total += error;
					squares += error * error;
				}
			}
			if (workload) {
				CHECK(set_switch(ccd, CCD_ABORT_EXPOSURE_PROPERTY_NAME, CCD_ABORT_EXPOSURE_ITEM_NAME, INDIGO_OK_STATE, 10));
			}
		}
		CHECK(guide_nonzero_completions == 0);
		qsort(errors, count, sizeof(double), compare_samples);
		qsort(absolute, count, sizeof(double), compare_samples);
		double mean = total / count;
		printf("    %s BUSY-to-OK pulse error n=%d min=%+.3f mean=%+.3f median=%+.3f p95=%+.3f p99=%+.3f max=%+.3f stddev=%.3f max_abs=%.3f ms\n", devices[guider].name, count, errors[0], mean, (errors[count / 2 - 1] + errors[count / 2]) / 2, errors[(int)ceil(count * 0.95) - 1], errors[(int)ceil(count * 0.99) - 1], errors[count - 1], sqrt(fmax(0, squares / count - mean * mean)), absolute[count - 1]);
		*timed_guider = 0;
		CHECK(disconnect_device(guider));
		CHECK(disconnect_device(ccd));
	}
cleanup:
	*timed_guider = 0;
	stop_driver();
}

static void flood_led_contract(void) {
	CHECK(start_driver());
	for (int c = 0; c < camera_count; c++) {
		int ccd = cameras[c].ccd;
		CHECK(connect_device(ccd));
		if (!cameras[c].caps->flood_led) {
			printf("    %s: no flood LED, X_CCD_FLOOD_LED hidden\n", devices[ccd].name);
			CHECK(!exists(ccd, "X_CCD_FLOOD_LED"));
			CHECK(disconnect_device(ccd));
			continue;
		}
		CHECK(switch_of(ccd, "X_CCD_FLOOD_LED", "OFF"));
		CHECK(set_switch(ccd, "X_CCD_FLOOD_LED", "ON", INDIGO_OK_STATE, 5));
		CHECK(prepare_client_raw(ccd));
		CHECK(acquire(ccd, 0.05));
		CHECK(set_switch(ccd, "X_CCD_FLOOD_LED", "OFF", INDIGO_OK_STATE, 5));
		CHECK(set_switch(ccd, "X_CCD_FLOOD_LED", "ON", INDIGO_OK_STATE, 5));
		CHECK(disconnect_device(ccd));
		CHECK(connect_device(ccd));
		CHECK(switch_of(ccd, "X_CCD_FLOOD_LED", "OFF"));
		CHECK(disconnect_device(ccd));
	}
cleanup:
	stop_driver();
}

static void teardown_and_reload(void) {
	for (int cycle = 0; cycle < 2; cycle++) {
		CHECK(start_driver());
		for (int c = 0; c < camera_count; c++) {
			int ccd = cameras[c].ccd;
			CHECK(connect_device(ccd));
			CHECK(prepare_client_raw(ccd));
			CHECK(acquire(ccd, 0.05));
			CHECK(disconnect_device(ccd));
		}
		CHECK(indigo_ccd_sx(INDIGO_DRIVER_SHUTDOWN, NULL) == INDIGO_OK);
		driver_initialized = false;
		stop_driver();
	}
	return;
cleanup:
	stop_driver();
}

static void prompt(const char *action, const char *name, const char *context) {
	printf("\n\a================================================================\n");
	printf(">>> %s the USB cable of '%s' NOW (%s)\n", action, name, context);
	printf("================================================================\n");
}

static bool wait_presence(int d, bool present, double timeout) {
	double reported = 0;
	for (double waited = 0; waited < timeout; waited += 0.1) {
		pthread_mutex_lock(&mutex);
		bool current = devices[d].present;
		pthread_mutex_unlock(&mutex);
		if (current == present) {
			printf("    '%s' %s\n", devices[d].name, present ? "is back" : "is gone");
			return true;
		}
		if (waited - reported >= 10) {
			reported = waited;
			printf("    still waiting for '%s' to %s ... %.0f s\n", devices[d].name, present ? "come back" : "disappear", waited);
		}
		indigo_usleep(100000);
	}
	printf("    TIMEOUT waiting for '%s' to %s\n", devices[d].name, present ? "come back" : "disappear");
	return false;
}

static void physical_hotplug(void) {
	CHECK(start_driver());
	for (int c = 0; c < camera_count; c++) {
		int ccd = cameras[c].ccd, guider = cameras[c].guider;
		if (camera_filter != NULL && strstr(devices[ccd].name, camera_filter) == NULL) {
			continue;
		}
		CHECK(connect_device(ccd));
		CHECK(prepare_client_raw(ccd));
		printf("\n    camera '%s' is connected and idle\n", devices[ccd].name);
		prompt("UNPLUG", devices[ccd].name, "camera is connected and idle");
		CHECK(wait_presence(ccd, false, 420));
		prompt("PLUG BACK IN", devices[ccd].name, "idle removal was detected");
		CHECK(wait_presence(ccd, true, 420));
		indigo_usleep(1500000);
		CHECK(connect_device(ccd));
		CHECK(prepare_client_raw(ccd));
		CHECK(acquire(ccd, 0.05));
		CHECK(set_number(ccd, CCD_EXPOSURE_PROPERTY_NAME, CCD_EXPOSURE_ITEM_NAME, 60, INDIGO_BUSY_STATE, 5));
		prompt("UNPLUG", devices[ccd].name, "a 60 second exposure is running now");
		CHECK(wait_presence(ccd, false, 420));
		prompt("PLUG BACK IN", devices[ccd].name, "removal during exposure was detected");
		CHECK(wait_presence(ccd, true, 420));
		indigo_usleep(1500000);
		CHECK(connect_device(ccd));
		CHECK(prepare_client_raw(ccd));
		CHECK(acquire(ccd, 0.05));
		if (cameras[c].caps->star2k) {
			CHECK(connect_device(guider));
			CHECK(pulse(guider, GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_EAST_ITEM_NAME, 200, INDIGO_BUSY_STATE));
			CHECK(wait_state(guider, GUIDER_GUIDE_RA_PROPERTY_NAME, 0, INDIGO_OK_STATE, 5));
			CHECK(disconnect_device(guider));
		}
		CHECK(disconnect_device(ccd));
		for (int other = 0; other < camera_count; other++) {
			if (other == c) {
				continue;
			}
			printf("\n    DO NOT TOUCH ANY CABLE - checking that '%s' still works\n", devices[cameras[other].ccd].name);
			CHECK(connect_device(cameras[other].ccd));
			CHECK(prepare_client_raw(cameras[other].ccd));
			CHECK(acquire(cameras[other].ccd, 0.05));
			CHECK(disconnect_device(cameras[other].ccd));
		}
	}
cleanup:
	stop_driver();
}

int main(int argc, char **argv) {
	bool run = false, hotplug = false, debug = false;
	const char *filter = NULL;
	for (int i = 1; i < argc; i++) {
		if (!strcmp(argv[i], "--run")) {
			run = true;
		} else if (!strcmp(argv[i], "--hotplug")) {
			hotplug = true;
		} else if (!strcmp(argv[i], "--debug")) {
			debug = true;
		} else if (!strcmp(argv[i], "--camera") && i + 1 < argc) {
			camera_filter = argv[++i];
		} else {
			filter = argv[i];
		}
	}
	if (!run) {
		fprintf(stderr, "This test operates physical Starlight Xpress cameras. Run with --run [--hotplug] [--debug] [--camera <substring>] [name filter].\n");
		return 2;
	}
	setvbuf(stdout, NULL, _IONBF, 0);
	indigo_set_log_level(debug ? INDIGO_LOG_DEBUG : INDIGO_LOG_ERROR);
	const indigo_test_case tests[] = {
		{ "Identity, discovery and property contract", identity_and_property_contract },
		{ "Shared lifecycle and rejected shutdown", shared_lifecycle_and_rejected_shutdown },
		{ "Acquisition units, frame types, bins and ROI", acquisition_units_types_bins_and_roi },
		{ "Abort orders and reacquisition", abort_and_reacquisition },
		{ "Cooling profile", cooling_profile },
		{ "Guider pulses and shared acquisition", guider_pulses_and_shared_acquisition },
		{ "Guider pulse timing", guider_pulse_timing },
		{ "Flood LED contract", flood_led_contract },
		{ "Teardown and reload", teardown_and_reload }
	};
	const indigo_test_case hotplug_test[] = { { "Physical idle and active hot-plug", physical_hotplug } };
	pthread_t watchdog_thread;
	pthread_create(&watchdog_thread, NULL, watchdog, NULL);
	pthread_detach(watchdog_thread);
	int result = 0, matched = 0;
	for (int i = 0; i < ARRAY_SIZE(tests); i++) {
		if (filter == NULL || strstr(tests[i].name, filter)) {
			matched++;
			snprintf(running_test, sizeof(running_test), "%s", tests[i].name);
			atomic_store(&test_deadline, indigo_monotonic_time() + 600);
			result |= indigo_run_tests("SX hardware", tests + i, 1);
			atomic_store(&test_deadline, 0);
		}
	}
	if (hotplug) {
		matched++;
		snprintf(running_test, sizeof(running_test), "%s", hotplug_test[0].name);
		atomic_store(&test_deadline, indigo_monotonic_time() + 5400);
		result |= indigo_run_tests("SX hardware", hotplug_test, 1);
		atomic_store(&test_deadline, 0);
	}
	for (int d = 0; d < MAX_DEVICES; d++) {
		for (int p = 0; p < MAX_PROPERTIES; p++) {
			indigo_release_property(devices[d].properties[p]);
			devices[d].properties[p] = NULL;
		}
	}
	return matched ? result : 1;
}
