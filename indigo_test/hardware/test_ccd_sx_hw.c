static void note_image(int d, indigo_property *property) {
	indigo_item *item = property->items;
	indigo_raw_header header = { 0 };
	bool valid = item->blob.value != NULL && !strcmp(item->blob.format, ".raw") && item->blob.size >= sizeof(header);
	if (valid) {
		memcpy(&header, item->blob.value, sizeof(header));
		valid = header.signature == INDIGO_RAW_MONO16 && item->blob.size >= sizeof(header) + (unsigned long)header.width * header.height * 2;
	}
	if (valid && devices[d].expected_width != 0) {
		valid = header.width == devices[d].expected_width && header.height == devices[d].expected_height;
	}
	if (valid) {
		uint16_t min = 0xFFFF, max = 0;
		unsigned long count = (unsigned long)header.width * header.height;
		for (unsigned long i = 0; i < count; i += 7) {
			uint16_t value;
			memcpy(&value, (char *)item->blob.value + sizeof(header) + 2 * i, 2);
			if (value < min) {
				min = value;
			}
			if (value > max) {
				max = value;
			}
		}
		if (max == min) {
			devices[d].uniform_frames++;
		}
		printf("    frame %u: %u x %u, %lu bytes, pixel range %u..%u\n", devices[d].frames + 1, header.width, header.height, (unsigned long)item->blob.size, min, max);
	} else {
		devices[d].invalid_frames++;
		printf("    frame %u: INVALID (%u x %u, %lu bytes, signature %u, expected %u x %u)\n", devices[d].frames + 1, header.width, header.height, (unsigned long)item->blob.size, header.signature, devices[d].expected_width, devices[d].expected_height);
	}
	devices[d].frame_width = header.width;
	devices[d].frame_height = header.height;
	devices[d].frame_size = (unsigned long)item->blob.size;
	devices[d].frames++;
}

static void note_guide(indigo_property *property) {
	if (strcmp(property->device, timed_guider)) {
		return;
	}
	int axis = !strcmp(property->name, GUIDER_GUIDE_DEC_PROPERTY_NAME);
	if (property->state == INDIGO_BUSY_STATE) {
		guide_started[axis] = indigo_monotonic_time();
	} else if (property->state == INDIGO_OK_STATE && guide_started[axis] > 0) {
		guide_finished[axis] = indigo_monotonic_time();
		guide_completions[axis]++;
		for (int i = 0; i < property->count; i++) {
			if (property->items[i].number.value != 0) {
				guide_nonzero_completions++;
			}
		}
	}
}

static indigo_result observe(indigo_property *property, bool update) {
	pthread_mutex_lock(&mutex);
	int d = find_device(property->device);
	if (d < 0) {
		pthread_mutex_unlock(&mutex);
		return INDIGO_OK;
	}
	int slot = property_slot(d, property->name);
	if (slot < 0) {
		for (slot = 0; slot < MAX_PROPERTIES && devices[d].properties[slot] != NULL; slot++) {
		}
	}
	if (slot < MAX_PROPERTIES) {
		indigo_release_property(devices[d].properties[slot]);
		devices[d].properties[slot] = indigo_copy_property(NULL, property);
		devices[d].revisions[slot]++;
	}
	if (!strcmp(property->name, INFO_PROPERTY_NAME)) {
		devices[d].present = true;
		for (int i = 0; i < property->count; i++) {
			if (!strcmp(property->items[i].name, INFO_DEVICE_INTERFACE_ITEM_NAME)) {
				devices[d].interface = (unsigned)atoi(property->items[i].text.value);
			}
		}
	}
	if (update && !strcmp(property->name, CCD_IMAGE_PROPERTY_NAME) && property->state == INDIGO_OK_STATE && property->count > 0 && property->items[0].blob.size > 0 && property->items[0].blob.value != NULL) {
		note_image(d, property);
	}
	if (!strcmp(property->name, GUIDER_GUIDE_RA_PROPERTY_NAME) || !strcmp(property->name, GUIDER_GUIDE_DEC_PROPERTY_NAME)) {
		note_guide(property);
	}
	pthread_mutex_unlock(&mutex);
	return INDIGO_OK;
}

