static bool probe_camera(int c) {
	sx_capabilities *caps = cameras[c].caps;
	if (caps->probed) {
		return true;
	}
	int ccd = cameras[c].ccd, guider = cameras[c].guider;
	if (!connect_device(ccd)) {
		return false;
	}
	caps->width = (int)number_of(ccd, CCD_INFO_PROPERTY_NAME, CCD_INFO_WIDTH_ITEM_NAME);
	caps->height = (int)number_of(ccd, CCD_INFO_PROPERTY_NAME, CCD_INFO_HEIGHT_ITEM_NAME);
	caps->pixel_width = number_of(ccd, CCD_INFO_PROPERTY_NAME, CCD_INFO_PIXEL_WIDTH_ITEM_NAME);
	caps->pixel_height = number_of(ccd, CCD_INFO_PROPERTY_NAME, CCD_INFO_PIXEL_HEIGHT_ITEM_NAME);
	caps->cooler = exists(ccd, CCD_COOLER_PROPERTY_NAME);
	caps->flood_led = exists(ccd, "X_CCD_FLOOD_LED");
	caps->star2k = guider >= 0 && set_switch(guider, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, INDIGO_OK_STATE, 20) && switch_of(guider, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME);
	if (guider >= 0) {
		disconnect_device(guider);
	}
	disconnect_device(ccd);
	caps->probed = true;
	printf("    %s: %d x %d, pixel %.2f x %.2f um, cooler %s, Star2K %s, flood LED %s\n", caps->name, caps->width, caps->height, caps->pixel_width, caps->pixel_height, caps->cooler ? "yes" : "no", caps->star2k ? "yes" : "no", caps->flood_led ? "yes" : "no");
	return true;
}

static bool discover(void) {
	for (int i = 0; i < 1500; i++) {
		int found = 0;
		pthread_mutex_lock(&mutex);
		for (int d = 0; d < MAX_DEVICES; d++) {
			if (devices[d].present && property_slot(d, CONNECTION_PROPERTY_NAME) >= 0) {
				found++;
			}
		}
		pthread_mutex_unlock(&mutex);
		if (found >= 2) {
			indigo_usleep(1500000);
			break;
		}
		indigo_usleep(10000);
	}
	camera_count = 0;
	pthread_mutex_lock(&mutex);
	for (int d = 0; d < MAX_DEVICES && camera_count < MAX_CAMERAS; d++) {
		if (!devices[d].present || !(devices[d].interface & INDIGO_INTERFACE_CCD)) {
			continue;
		}
		char guider_name[INDIGO_NAME_SIZE];
		snprintf(guider_name, sizeof(guider_name), "%s (guider)", devices[d].name);
		int guider = -1;
		for (int g = 0; g < MAX_DEVICES; g++) {
			if (devices[g].present && !strcmp(devices[g].name, guider_name)) {
				guider = g;
			}
		}
		cameras[camera_count].ccd = d;
		cameras[camera_count].guider = guider;
		camera_count++;
	}
	pthread_mutex_unlock(&mutex);
	for (int c = 0; c < camera_count; c++) {
		cameras[c].caps = capabilities_of(devices[cameras[c].ccd].name);
		if (cameras[c].caps == NULL) {
			return false;
		}
	}
	return camera_count > 0;
}

static bool start_driver(void) {
	pthread_mutex_lock(&mutex);
	for (int d = 0; d < MAX_DEVICES; d++) {
		for (int p = 0; p < MAX_PROPERTIES; p++) {
			indigo_release_property(devices[d].properties[p]);
			devices[d].properties[p] = NULL;
			devices[d].revisions[p] = 0;
		}
		memset(devices + d, 0, sizeof(observed_device));
	}
	pthread_mutex_unlock(&mutex);
	if (indigo_start() != INDIGO_OK || indigo_attach_client(&client) != INDIGO_OK) {
		return false;
	}
	if (indigo_ccd_sx(INDIGO_DRIVER_INIT, NULL) != INDIGO_OK) {
		return false;
	}
	driver_initialized = true;
	if (!discover()) {
		return false;
	}
	for (int c = 0; c < camera_count; c++) {
		if (!probe_camera(c)) {
			return false;
		}
	}
	return true;
}

static void stop_driver(void) {
	for (int d = 0; d < MAX_DEVICES; d++) {
		if (*devices[d].name && switch_of(d, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME)) {
			disconnect_device(d);
		}
	}
	if (driver_initialized) {
		indigo_ccd_sx(INDIGO_DRIVER_SHUTDOWN, NULL);
		driver_initialized = false;
	}
	indigo_detach_client(&client);
	indigo_stop();
}

