static bool select_slew_rate(const char *item) {
	return hw_set_switch(mount, MOUNT_SLEW_RATE_PROPERTY_NAME, item, INDIGO_OK_STATE, SHORT_TIMEOUT);
}

static bool manual_motion(const char *property, const char *item, double *moved_ha, double *moved_dec) {
	if (!fresh_coordinates()) {
		return false;
	}
	double start_ha = current_hour_angle(), start_dec = current_dec();
	unsigned before = hw_revision(mount, property);
	indigo_change_switch_property_1(&hw_client, MOUNT_DEVICE_NAME, property, item, true);
	if (!hw_wait_state(mount, property, before, INDIGO_BUSY_STATE, SHORT_TIMEOUT)) {
		return false;
	}
	double until = indigo_monotonic_time() + MANUAL_MOTION_SECONDS;
	while (indigo_monotonic_time() < until) {
		indigo_usleep(100000);
	}
	before = hw_revision(mount, property);
	indigo_change_switch_property_1(&hw_client, MOUNT_DEVICE_NAME, property, item, false);
	if (!hw_wait_state(mount, property, before, INDIGO_OK_STATE, SHORT_TIMEOUT)) {
		return false;
	}
	if (!fresh_coordinates() || !fresh_coordinates()) {
		return false;
	}
	*moved_ha = ra_difference(current_hour_angle(), start_ha);
	*moved_dec = current_dec() - start_dec;
	return true;
}

