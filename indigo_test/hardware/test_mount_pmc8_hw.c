static double number_of(int device, const char *property, const char *item) {
	double value = 0;
	hw_number_item(device, property, item, &value);
	return value;
}

static double current_ra(void) {
	return number_of(mount, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, MOUNT_EQUATORIAL_COORDINATES_RA_ITEM_NAME);
}

static double current_dec(void) {
	return number_of(mount, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, MOUNT_EQUATORIAL_COORDINATES_DEC_ITEM_NAME);
}

static double current_lst(void) {
	return number_of(mount, MOUNT_LST_TIME_PROPERTY_NAME, MOUNT_LST_TIME_ITEM_NAME);
}

static double normalized_ra(double ra) {
	while (ra < 0) {
		ra += 24;
	}
	return fmod(ra, 24);
}

static double ra_difference(double a, double b) {
	double difference = normalized_ra(a) - normalized_ra(b);
	if (difference > 12) {
		difference -= 24;
	}
	if (difference < -12) {
		difference += 24;
	}
	return difference;
}

// What the right ascension axis itself stands at: the published right ascension moves with the sky
// whenever the mount is not tracking, so a motion scenario measures the hour angle instead.
static double current_hour_angle(void) {
	return ra_difference(current_lst(), current_ra());
}

static double separation(double ra1, double dec1, double ra2, double dec2) {
	double delta_ra = ra_difference(ra1, ra2) * 15 * M_PI / 180;
	double d1 = dec1 * M_PI / 180, d2 = dec2 * M_PI / 180;
	double cosine = sin(d1) * sin(d2) + cos(d1) * cos(d2) * cos(delta_ra);
	if (cosine > 1) {
		cosine = 1;
	}
	if (cosine < -1) {
		cosine = -1;
	}
	return acos(cosine) * 180 / M_PI;
}

// Waits for a coordinate readback that was polled after this call, so a scenario never judges the
// mount by the position it had before the request.
static bool fresh_coordinates(void) {
	unsigned before = hw_revision(mount, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME);
	double deadline = indigo_monotonic_time() + POLL_TIMEOUT;
	while (indigo_monotonic_time() < deadline) {
		if (hw_revision(mount, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME) > before + 1) {
			return true;
		}
		indigo_usleep(10000);
	}
	fprintf(stderr, "    the mount stopped publishing its coordinates\n");
	return false;
}

static bool pointing_is_usable(void) {
	double dec = current_dec(), ra = current_ra();
	if (dec < -90.5 || dec > 90.5 || ra < 0 || ra >= 24) {
		fprintf(stderr, "    the mount reports RA %g h, DEC %g deg, which is not a position to move from\n", ra, dec);
		return false;
	}
	return true;
}

static void request_equatorial(double ra, double dec) {
	static const char *items[] = { MOUNT_EQUATORIAL_COORDINATES_RA_ITEM_NAME, MOUNT_EQUATORIAL_COORDINATES_DEC_ITEM_NAME };
	double values[2];
	values[0] = ra;
	values[1] = dec;
	indigo_change_number_property(&hw_client, MOUNT_DEVICE_NAME, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, 2, items, values);
}

static bool on_coordinates_set(const char *item) {
	return hw_set_switch(mount, MOUNT_ON_COORDINATES_SET_PROPERTY_NAME, item, INDIGO_OK_STATE, SHORT_TIMEOUT);
}

static bool sync_to(double ra, double dec) {
	if (!on_coordinates_set(MOUNT_ON_COORDINATES_SET_SYNC_ITEM_NAME)) {
		return false;
	}
	unsigned before = hw_revision(mount, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME);
	request_equatorial(ra, dec);
	if (!hw_wait_state(mount, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, before, INDIGO_OK_STATE, SHORT_TIMEOUT)) {
		return false;
	}
	return fresh_coordinates();
}

static bool wait_for_busy(const char *property, double timeout) {
	double deadline = indigo_monotonic_time() + timeout;
	while (indigo_monotonic_time() < deadline) {
		if (hw_states_seen(mount, property) & (1u << INDIGO_BUSY_STATE)) {
			return true;
		}
		indigo_usleep(5000);
	}
	fprintf(stderr, "    %s was never reported busy\n", property);
	return false;
}

// A GOTO has to be seen as BUSY before it is waited out, otherwise the OK the last poll published
// would satisfy the wait before the mount has even started.
static bool slew_to(double ra, double dec, double timeout) {
	if (dec < -90 || dec > 90 || ra < 0 || ra >= 24) {
		fprintf(stderr, "    refusing to slew to RA %g h, DEC %g deg\n", ra, dec);
		return false;
	}
	if (!on_coordinates_set(MOUNT_ON_COORDINATES_SET_TRACK_ITEM_NAME)) {
		return false;
	}
	hw_forget_states();
	request_equatorial(ra, dec);
	if (!wait_for_busy(MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, POLL_TIMEOUT)) {
		return false;
	}
	return hw_wait_settled(mount, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, INDIGO_OK_STATE, timeout);
}

static bool slew_to_work_position(void) {
	if (!fresh_coordinates()) {
		return false;
	}
	double ra = normalized_ra(current_lst() - WORK_HOUR_ANGLE);
	if (!slew_to(ra, WORK_DEC, MOTION_TIMEOUT)) {
		return false;
	}
	if (!fresh_coordinates()) {
		return false;
	}
	double off = separation(current_ra(), current_dec(), ra, WORK_DEC);
	if (off > 0.5) {
		fprintf(stderr, "    the mount stopped %.3f deg from the work position (RA %.5f DEC %.4f)\n", off, current_ra(), current_dec());
		return false;
	}
	return true;
}

// A target a few degrees from wherever the mount is pointing now, towards the equator, so both
// axes have to turn and the mount stays on its side of the pier.
static void nearby_target(double dec_offset, double *ra, double *dec) {
	*dec = current_dec() - dec_offset;
	*ra = normalized_ra(current_ra() + RA_OFFSET);
}

static bool set_tracking(bool on) {
	return hw_set_switch(mount, MOUNT_TRACKING_PROPERTY_NAME, on ? MOUNT_TRACKING_ON_ITEM_NAME : MOUNT_TRACKING_OFF_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT);
}

static bool tracking_is_on(void) {
	bool on = false;
	return hw_switch_item(mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_ON_ITEM_NAME, &on) && on;
}

static bool switch_is_on(int device, const char *property, const char *item) {
	bool on = false;
	return hw_switch_item(device, property, item, &on) && on;
}

static bool right_ascension_drift(double seconds, double *drift) {
	if (!fresh_coordinates()) {
		return false;
	}
	double start = current_ra();
	double until = indigo_monotonic_time() + seconds;
	while (indigo_monotonic_time() < until) {
		indigo_usleep(200000);
	}
	if (!fresh_coordinates()) {
		return false;
	}
	*drift = fabs(ra_difference(current_ra(), start));
	return true;
}

static double sidereal_loss(double seconds) {
	return seconds / 3600.0 * 1.0027379;
}

static indigo_property_perm property_perm(int device, const char *name) {
	pthread_mutex_lock(&hw_mutex);
	int p = device < 0 ? -1 : hw_slot(device, name);
	indigo_property_perm perm = p < 0 ? INDIGO_RO_PERM : hw_devices[device].properties[p]->perm;
	pthread_mutex_unlock(&hw_mutex);
	return perm;
}

static const char *guide_directions[] = { GUIDER_GUIDE_NORTH_ITEM_NAME, GUIDER_GUIDE_SOUTH_ITEM_NAME, GUIDER_GUIDE_EAST_ITEM_NAME, GUIDER_GUIDE_WEST_ITEM_NAME };

static const char *guide_axis_of(int direction) {
	return direction < 2 ? GUIDER_GUIDE_DEC_PROPERTY_NAME : GUIDER_GUIDE_RA_PROPERTY_NAME;
}

// One pulse, measured from the request to the completion the driver publishes. This is software
// completion timing over the serial transport, not the motor timing of the mount.
static bool guide_pulse(int direction, double milliseconds, double *elapsed) {
	const char *axis = guide_axis_of(direction);
	unsigned before = hw_revision(guider, axis);
	double started = indigo_monotonic_time();
	indigo_change_number_property_1(&hw_client, GUIDER_DEVICE_NAME, axis, guide_directions[direction], milliseconds);
	if (!hw_wait_state(guider, axis, before, INDIGO_OK_STATE, PULSE_TIMEOUT)) {
		return false;
	}
	*elapsed = (indigo_monotonic_time() - started) * 1000;
	double value = 0;
	if (!hw_number_item(guider, axis, guide_directions[direction], &value)) {
		return false;
	}
	if (value != 0) {
		fprintf(stderr, "    %s.%s was left at %g instead of 0\n", axis, guide_directions[direction], value);
		return false;
	}
	return true;
}

static int compare_doubles(const void *a, const void *b) {
	double left = *(const double *)a, right = *(const double *)b;
	return left < right ? -1 : left > right ? 1 : 0;
}

static double percentile(double *sorted, int count, double fraction) {
	int index = (int)(fraction * (count - 1) + 0.5);
	if (index < 0) {
		index = 0;
	}
	if (index >= count) {
		index = count - 1;
	}
	return sorted[index];
}

static bool establish_site(void) {
	static const char *items[] = { GEOGRAPHIC_COORDINATES_LATITUDE_ITEM_NAME, GEOGRAPHIC_COORDINATES_LONGITUDE_ITEM_NAME };
	double values[2];
	values[0] = site_latitude;
	values[1] = site_longitude;
	unsigned before = hw_revision(mount, GEOGRAPHIC_COORDINATES_PROPERTY_NAME);
	indigo_change_number_property(&hw_client, MOUNT_DEVICE_NAME, GEOGRAPHIC_COORDINATES_PROPERTY_NAME, 2, items, values);
	return hw_wait_state(mount, GEOGRAPHIC_COORDINATES_PROPERTY_NAME, before, INDIGO_OK_STATE, SHORT_TIMEOUT);
}

// The driver starts in UDP mode with the default WiFi address, so a serial session has to select
// the serial mode first and the port second: selecting the mode rewrites the port.
static bool select_serial_port(void) {
	if (!hw_set_switch(mount, CONNECTION_MODE_PROPERTY_NAME, CONNECTION_MODE_SERIAL_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT)) {
		return false;
	}
	return hw_set_text(mount, DEVICE_PORT_PROPERTY_NAME, DEVICE_PORT_ITEM_NAME, serial_port, INDIGO_OK_STATE, SHORT_TIMEOUT);
}

static bool connect_both(void) {
	return hw_connect(mount, CONNECT_TIMEOUT) && establish_site() && hw_connect(guider, CONNECT_TIMEOUT) && hw_wait_settled(mount, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, INDIGO_OK_STATE, POLL_TIMEOUT);
}

static bool disconnect_both(void) {
	return hw_disconnect(guider, SHORT_TIMEOUT) && hw_disconnect(mount, CONNECT_TIMEOUT);
}

