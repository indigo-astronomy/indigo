// ----------------------------------------------------------------- SYNC

static bool sync_readback(double target_ra, double target_dec, double *read_ra, double *read_dec) {
	if (!fresh_coordinates()) {
		return false;
	}
	double base_ra = current_ra(), base_dec = current_dec();
	if (!sync_to(target_ra, target_dec)) {
		return false;
	}
	*read_ra = current_ra();
	*read_dec = current_dec();
	printf("    synced to RA %.5f DEC %.4f, the mount reports RA %.5f DEC %.4f\n", target_ra, target_dec, *read_ra, *read_dec);
	if (!sync_to(base_ra, base_dec)) {
		fprintf(stderr, "    the mount's own position could not be synced back\n");
		return false;
	}
	if (separation(current_ra(), current_dec(), base_ra, base_dec) > 0.05) {
		fprintf(stderr, "    the sync back left the mount at RA %.5f DEC %.4f instead of RA %.5f DEC %.4f\n", current_ra(), current_dec(), base_ra, base_dec);
		return false;
	}
	return true;
}

static void pmc8_syncs_to_a_nearby_position(void) {
	double read_ra = 0, read_dec = 0;
	ASSERT_TRUE(pointing_is_usable());
	ASSERT_TRUE(set_tracking(true));
	ASSERT_TRUE(fresh_coordinates());
	double target_ra = normalized_ra(current_ra() + 0.2), target_dec = current_dec() - 2;
	ASSERT_TRUE(sync_readback(target_ra, target_dec, &read_ra, &read_dec));
	ASSERT_NEAR(target_dec, read_dec, 0.01);
	ASSERT_NEAR(0, ra_difference(read_ra, target_ra), 0.002);
}

// A declination south of the equator is the range the signed 24 bit position has to carry.
