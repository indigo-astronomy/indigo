#include <stdlib.h>
#include <string.h>
#include <indigo_drivers/mount_pmc8/indigo_mount_pmc8.h>
#include "hardware_test_common.h"

#define MOUNT_DEVICE_NAME "Mount PMC Eight"
#define GUIDER_DEVICE_NAME "Mount PMC Eight (guider)"
#define CONNECTION_MODE_PROPERTY_NAME "CONNECTION_MODE"
#define CONNECTION_MODE_SERIAL_ITEM_NAME "SERIAL"
#define MOUNT_TYPE_PROPERTY_NAME "MOUNT_TYPE"
#define MOUNT_TYPE_AUTO_ITEM_NAME "AUTO"

// The mount is polled once a second, so a readback that has to come from a fresh poll needs a few
// cycles of room.
#define SHORT_TIMEOUT 15.0
#define CONNECT_TIMEOUT 45.0
// The iEXOS-100 slews at a few degrees a second after a long ramp.
#define MOTION_TIMEOUT 240.0
#define POLL_TIMEOUT 12.0
#define PULSE_TIMEOUT 15.0

// The work position every motion scenario starts from: close enough to the pole to keep both axes
// in a small arc of the park position, far enough from it for the right ascension readback to
// mean something.
#define WORK_DEC 80.0
#define WORK_HOUR_ANGLE -5.0
#define DEC_OFFSET 3.0
#define RA_OFFSET 0.1
#define ABORT_DEC_OFFSET 10.0
#define MANUAL_MOTION_SECONDS 3.0
#define MOTION_EPSILON 0.004
#define TRACKING_SECONDS 30.0
#define TRACKING_HELD_RA 0.0025

#define GUIDE_SAMPLES 3
#define GUIDE_WARMUP 2

static int mount = -1, guider = -1;
static const char *serial_port = NULL;
static double site_latitude = 48.15, site_longitude = 17.11;
static bool initial_captured = false;
static bool initial_tracking = false;

