// Code is generated by AI

// Opt-in acceptance test for a physically connected Explore Scientific PMC-Eight mount, written
// against an iEXOS-100 on its serial (PGMR/USB) interface. It runs the mount hardware acceptance
// checklist of DRIVER_TESTING_RULES.md plus the guider standard for the guider logical device, one
// small scenario per case: identity and model detection, the property contract, coordinate
// polling, tracking and tracking rates, a GOTO to a work position near the pole, manual motion in
// both axes, abort, SYNC, a small GOTO, park and unpark, guide pulses including a duration
// measurement and a real axis displacement, the shared connection, a refused port, reconnect and
// driver INIT/SHUTDOWN.
//
// THE MOUNT PHYSICALLY MOVES. The session expects the mount in its park position (counterweight
// down, telescope at the pole), which is where the PMC-Eight counts both axes from zero. The first
// GOTO takes it to a work position 10 degrees from the pole and five hours east of the meridian,
// one hour from the counterweight-down park, which turns the right ascension axis by 15 degrees; every later GOTO is a few degrees
// from wherever the mount stands. The session ends with a park, which gives the mount back the
// position it was found in.
//
// SYNC OVERWRITES THE MOUNT'S POSITION REGISTERS. Each scenario that uses it syncs the original
// position back afterwards. The CONNECTION_MODE commands ESX and ESY are never sent: ESX moves the
// controller's primary interface to WiFi, after which the serial port no longer answers until the
// interface is switched back over the network.
//
// MOUNT_PMC8_HW_PORT names the serial port and is required. MOUNT_PMC8_HW_LATITUDE and
// MOUNT_PMC8_HW_LONGITUDE give the observing site; the driver has no site command, so the values
// only have to be real for the hour angle arithmetic to describe the real sky.

