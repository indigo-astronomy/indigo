// ------------------------------------------------------------------- readback

// The session starts in the park position, where both axes count zero: the telescope stands at
// the pole of the configured hemisphere.
static void pmc8_polls_the_park_position(void) {
	ASSERT_TRUE(fresh_coordinates());
	double ra = current_ra(), dec = current_dec();
	printf("    the mount reports RA %.5f h, DEC %.4f deg, hour angle %.4f h\n", ra, dec, current_hour_angle());
	ASSERT_TRUE(ra >= 0 && ra < 24);
	ASSERT_NEAR(site_latitude >= 0 ? 90 : -90, dec, 0.1);
	// The counterweight down position is six hours from the meridian.
	ASSERT_NEAR(-6, current_hour_angle(), 0.05);
	double altitude = number_of(mount, MOUNT_HORIZONTAL_COORDINATES_PROPERTY_NAME, MOUNT_HORIZONTAL_COORDINATES_ALT_ITEM_NAME);
	ASSERT_NEAR(fabs(site_latitude), altitude, 0.2);
}

static void pmc8_publishes_the_sidereal_time(void) {
	double first = current_lst();
	ASSERT_TRUE(first >= 0 && first < 24);
	double deadline = indigo_monotonic_time() + 20.0;
	while (indigo_monotonic_time() < deadline) {
		if (fabs(ra_difference(current_lst(), first)) > 0.001) {
			return;
		}
		indigo_usleep(200000);
	}
	fprintf(stderr, "    the sidereal time stayed at %.6f\n", first);
	ASSERT_TRUE(false);
}

// ------------------------------------------------------------------ GOTO

static void pmc8_slews_to_the_work_position(void) {
	ASSERT_TRUE(pointing_is_usable());
	ASSERT_TRUE(slew_to_work_position());
	printf("    at RA %.5f h, DEC %.4f deg, hour angle %.4f h\n", current_ra(), current_dec(), current_hour_angle());
	// A completed GOTO leaves the mount tracking the target.
	ASSERT_TRUE(tracking_is_on());
	// East of the meridian with the counterweight down, the telescope is west of the pier.
	ASSERT_TRUE(switch_is_on(mount, MOUNT_SIDE_OF_PIER_PROPERTY_NAME, MOUNT_SIDE_OF_PIER_WEST_ITEM_NAME));
}

static void pmc8_tracks_after_a_slew(void) {
	double drift = 0, idle = 0;
	ASSERT_TRUE(tracking_is_on());
	ASSERT_TRUE(right_ascension_drift(TRACKING_SECONDS, &drift));
	ASSERT_TRUE(set_tracking(false));
	ASSERT_TRUE(right_ascension_drift(TRACKING_SECONDS, &idle));
	printf("    the mount lost %.5f h tracking and %.5f h standing over %.0f s\n", drift, idle, TRACKING_SECONDS);
	ASSERT_TRUE(drift < TRACKING_HELD_RA);
	ASSERT_TRUE(idle > 0.9 * sidereal_loss(TRACKING_SECONDS));
	ASSERT_TRUE(set_tracking(true));
}

static void pmc8_slews_to_a_nearby_target(void) {
	double target_ra = 0, target_dec = 0;
	ASSERT_TRUE(pointing_is_usable());
	ASSERT_TRUE(fresh_coordinates());
	double start_ra = current_ra(), start_dec = current_dec();
	nearby_target(DEC_OFFSET, &target_ra, &target_dec);
	ASSERT_TRUE(slew_to(target_ra, target_dec, MOTION_TIMEOUT));
	ASSERT_TRUE(fresh_coordinates());
	double arrived = separation(current_ra(), current_dec(), target_ra, target_dec);
	printf("    slewed %.3f deg and arrived %.4f deg from the target\n", separation(start_ra, start_dec, target_ra, target_dec), arrived);
	ASSERT_TRUE(arrived < 0.1);
	ASSERT_TRUE(tracking_is_on());
	ASSERT_TRUE(slew_to_work_position());
}

// The abort has to reach the mount while the GOTO is still running, not after it arrived.
static void pmc8_aborts_a_slew_and_accepts_a_fresh_one(void) {
	double target_ra = 0, target_dec = 0;
	ASSERT_TRUE(pointing_is_usable());
	ASSERT_TRUE(fresh_coordinates());
	double start_ra = current_ra(), start_dec = current_dec();
	nearby_target(ABORT_DEC_OFFSET, &target_ra, &target_dec);
	ASSERT_TRUE(on_coordinates_set(MOUNT_ON_COORDINATES_SET_TRACK_ITEM_NAME));
	hw_forget_states();
	request_equatorial(target_ra, target_dec);
	ASSERT_TRUE(wait_for_busy(MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, POLL_TIMEOUT));
	indigo_usleep(2000000);
	double requested = indigo_monotonic_time();
	ASSERT_TRUE(hw_set_switch(mount, MOUNT_ABORT_MOTION_PROPERTY_NAME, MOUNT_ABORT_MOTION_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	printf("    the abort was answered after %.2f s\n", indigo_monotonic_time() - requested);
	ASSERT_TRUE(hw_wait_settled(mount, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, INDIGO_ALERT_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(fresh_coordinates());
	double first = current_dec();
	ASSERT_TRUE(fresh_coordinates());
	ASSERT_TRUE(fresh_coordinates());
	double stopped = separation(current_ra(), current_dec(), target_ra, target_dec);
	printf("    the abort left the mount %.3f deg short of the target\n", stopped);
	ASSERT_TRUE(stopped > 1.0);
	ASSERT_NEAR(first, current_dec(), 0.02);
	// A fresh GOTO is accepted straight after the abort.
	ASSERT_TRUE(slew_to(start_ra, start_dec, MOTION_TIMEOUT));
	ASSERT_TRUE(fresh_coordinates());
	ASSERT_TRUE(separation(current_ra(), current_dec(), start_ra, start_dec) < 0.1);
}

