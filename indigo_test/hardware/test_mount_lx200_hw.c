// Turning tracking on and off has to reach the controller, come back through its own status, and
// carry the MOUNT_STATE light with it. The light is asserted on the publication the request
// itself produces: MOUNT_PARK and MOUNT_HOME publish MOUNT_STATE from their handlers, and
// MOUNT_TRACKING owes a client the same.
static bool toggle_tracking(const char *item, indigo_property_state expected_light) {
	unsigned before = hw_revision(mount, MOUNT_STATE_PROPERTY_NAME);
	if (!hw_set_switch(mount, MOUNT_TRACKING_PROPERTY_NAME, item, INDIGO_OK_STATE, SHORT_TIMEOUT)) {
		return false;
	}
	// The handler publishes MOUNT_STATE before the generator publishes MOUNT_TRACKING, so the
	// wait above has already seen it. A driver that only assigns the light leaves the revision
	// where it was until the next polling cycle a second later.
	if (hw_revision(mount, MOUNT_STATE_PROPERTY_NAME) == before) {
		fprintf(stderr, "    %s did not publish %s\n", MOUNT_TRACKING_PROPERTY_NAME, MOUNT_STATE_PROPERTY_NAME);
		return false;
	}
	if (!switch_on(mount, MOUNT_TRACKING_PROPERTY_NAME, item)) {
		fprintf(stderr, "    %s.%s did not stay selected\n", MOUNT_TRACKING_PROPERTY_NAME, item);
		return false;
	}
	if (state_light(MOUNT_STATE_TRACKING_ITEM_NAME) != expected_light) {
		fprintf(stderr, "    %s.%s is %d, expected %d\n", MOUNT_STATE_PROPERTY_NAME, MOUNT_STATE_TRACKING_ITEM_NAME, state_light(MOUNT_STATE_TRACKING_ITEM_NAME), expected_light);
		return false;
	}
	return true;
}

static void lx200_toggles_tracking(void) {
	if (skip_without(MOUNT_TRACKING_PROPERTY_NAME, "tracking switch")) {
		return;
	}
	// The light only moves when the request changes it, and INDIGO publishes nothing about a
	// property that says exactly what it said before. A mount found with tracking already off
	// would therefore produce no MOUNT_STATE publication at all for the first request, so the
	// scenario puts the mount into the other state before it measures anything.
	ASSERT_TRUE(hw_set_switch(mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_ON_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(toggle_tracking(MOUNT_TRACKING_OFF_ITEM_NAME, INDIGO_IDLE_STATE));
	// The controller's own status has to agree after a full polling cycle, so a driver that only
	// remembers the request cannot pass.
	ASSERT_TRUE(wait_for_poll());
	ASSERT_TRUE(switch_on(mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_OFF_ITEM_NAME));
	ASSERT_EQ_INT(INDIGO_IDLE_STATE, state_light(MOUNT_STATE_TRACKING_ITEM_NAME));
	ASSERT_TRUE(toggle_tracking(MOUNT_TRACKING_ON_ITEM_NAME, INDIGO_OK_STATE));
	ASSERT_TRUE(wait_for_poll());
	ASSERT_TRUE(switch_on(mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_ON_ITEM_NAME));
	ASSERT_EQ_INT(INDIGO_OK_STATE, state_light(MOUNT_STATE_TRACKING_ITEM_NAME));
}

// Every rate the property offers has to be accepted, and the one the controller reports back has
// to be the one that was asked for. The readback matters more than the acknowledgement: the
// driver decodes the rate from a frequency the firmware reports.
static void lx200_selects_tracking_rates(void) {
	static const char *rates[] = { MOUNT_TRACK_RATE_SOLAR_ITEM_NAME, MOUNT_TRACK_RATE_LUNAR_ITEM_NAME, MOUNT_TRACK_RATE_KING_ITEM_NAME, MOUNT_TRACK_RATE_SIDEREAL_ITEM_NAME };
	if (skip_without(MOUNT_TRACK_RATE_PROPERTY_NAME, "tracking rate")) {
		return;
	}
	ASSERT_TRUE(switch_on(mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_ON_ITEM_NAME));
	for (unsigned i = 0; i < ARRAY_SIZE(rates); i++) {
		if (!hw_item_defined(mount, MOUNT_TRACK_RATE_PROPERTY_NAME, rates[i])) {
			continue;
		}
		ASSERT_TRUE(hw_set_switch(mount, MOUNT_TRACK_RATE_PROPERTY_NAME, rates[i], INDIGO_OK_STATE, SHORT_TIMEOUT));
		// The rate command only changes the rate the controller uses once tracking is armed with
		// it, so the scenario re-arms tracking and then checks that neither request was refused.
		ASSERT_TRUE(hw_set_switch(mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_ON_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
		ASSERT_TRUE(wait_for_poll());
		ASSERT_TRUE(switch_on(mount, MOUNT_TRACK_RATE_PROPERTY_NAME, rates[i]));
		ASSERT_TRUE(switch_on(mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_ON_ITEM_NAME));
		printf("    %s accepted\n", rates[i]);
	}
}

// The rate the mount is actually using has to survive a new session, and a controller that
// reports no rate at all because tracking is disabled must not be decoded as one of them. The
// NYX answers :GT# with 0 while tracking is off and carries the real rate in its status string
// instead, so a driver that trusts :GT# comes back reporting the lunar rate.
static void lx200_reports_the_tracking_rate_from_the_mount(void) {
	if (skip_without(MOUNT_TRACK_RATE_PROPERTY_NAME, "tracking rate")) {
		return;
	}
	if (!hw_item_defined(mount, MOUNT_TRACK_RATE_PROPERTY_NAME, MOUNT_TRACK_RATE_LUNAR_ITEM_NAME)) {
		printf("    the detected model publishes no lunar rate\n");
		return;
	}
	// Every rate the mount is given has to survive the next status readback, which is what tells
	// a rate the driver only remembers from a rate the controller confirms.
	static const char *rates[] = { MOUNT_TRACK_RATE_SOLAR_ITEM_NAME, MOUNT_TRACK_RATE_LUNAR_ITEM_NAME, MOUNT_TRACK_RATE_KING_ITEM_NAME, MOUNT_TRACK_RATE_SIDEREAL_ITEM_NAME };
	for (unsigned i = 0; i < ARRAY_SIZE(rates); i++) {
		if (!hw_item_defined(mount, MOUNT_TRACK_RATE_PROPERTY_NAME, rates[i])) {
			continue;
		}
		ASSERT_TRUE(hw_set_switch(mount, MOUNT_TRACK_RATE_PROPERTY_NAME, rates[i], INDIGO_OK_STATE, SHORT_TIMEOUT));
		ASSERT_TRUE(hw_set_switch(mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_ON_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
		ASSERT_TRUE(wait_for_poll());
		ASSERT_TRUE(wait_for_poll());
		printf("    %s survives the status readback\n", rates[i]);
		ASSERT_TRUE(switch_on(mount, MOUNT_TRACK_RATE_PROPERTY_NAME, rates[i]));
	}
	// Now stop tracking and open a new session. The mount is still configured for the sidereal
	// rate, so that is what the fresh session has to report.
	ASSERT_TRUE(hw_set_switch(mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_OFF_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(disconnect_secondary_devices());
	ASSERT_TRUE(hw_disconnect(mount, CONNECT_TIMEOUT));
	ASSERT_TRUE(hw_connect(mount, CONNECT_TIMEOUT));
	ASSERT_TRUE(connect_secondary_devices());
	ASSERT_TRUE(hw_wait_settled(mount, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, INDIGO_OK_STATE, POLL_TIMEOUT));
	ASSERT_TRUE(!switch_on(mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_ON_ITEM_NAME));
	ASSERT_TRUE(switch_on(mount, MOUNT_TRACK_RATE_PROPERTY_NAME, MOUNT_TRACK_RATE_SIDEREAL_ITEM_NAME));
	ASSERT_TRUE(hw_set_switch(mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_ON_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
}

