// A secondary logical device the detected controller cannot serve has to refuse the connection
// and leave the shared serial session alone, instead of coming up with properties that answer
// nothing. The aux device carries the NYX sensors and the OnStep outlets and has nothing for any
// other controller; the guider needs the LX200 pulse guiding commands, and an aGotino ignores
// them, so a guider that came up would report every pulse as completed while the mount stood
// still.
static void lx200_refuses_the_unsupported_devices(void) {
	if (!aux_supported()) {
		ASSERT_TRUE(!hw_connected(aux));
		ASSERT_TRUE(hw_set_switch(aux, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, INDIGO_ALERT_STATE, CONNECT_TIMEOUT));
		ASSERT_TRUE(!hw_connected(aux));
		ASSERT_TRUE(hw_property_hidden(aux, AUX_WEATHER_PROPERTY_NAME));
		ASSERT_TRUE(hw_property_hidden(aux, AUX_POWER_OUTLET_PROPERTY_NAME));
		ASSERT_TRUE(hw_property_hidden(aux, AUX_HEATER_OUTLET_PROPERTY_NAME));
		printf("    the aux device refused the connection\n");
	} else {
		ASSERT_TRUE(hw_connected(aux));
	}
	if (!guiding_supported()) {
		ASSERT_TRUE(!hw_connected(guider));
		ASSERT_TRUE(hw_set_switch(guider, CONNECTION_PROPERTY_NAME, CONNECTION_CONNECTED_ITEM_NAME, INDIGO_ALERT_STATE, CONNECT_TIMEOUT));
		ASSERT_TRUE(!hw_connected(guider));
		ASSERT_TRUE(hw_property_hidden(guider, GUIDER_GUIDE_RA_PROPERTY_NAME));
		ASSERT_TRUE(hw_property_hidden(guider, GUIDER_GUIDE_DEC_PROPERTY_NAME));
		printf("    the guider device refused the connection\n");
	} else {
		ASSERT_TRUE(hw_connected(guider));
	}
	// A refusal may not take the shared session down with it.
	ASSERT_TRUE(hw_connected(mount));
	ASSERT_TRUE(hw_wait_settled(mount, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, INDIGO_OK_STATE, POLL_TIMEOUT));
}

// ------------------------------------------------------------------- guider

static bool skip_without_guiding(void) {
	if (guiding_supported()) {
		return false;
	}
	printf("    not applicable: the detected model has no pulse guiding\n");
	return true;
}

static bool guide_pulse(int direction, double milliseconds, double *elapsed) {
	const char *property = guide_axis_of(direction);
	unsigned before = hw_revision(guider, property);
	double started = indigo_monotonic_time();
	hw_request_number(guider, property, guide_directions[direction], milliseconds);
	if (!hw_wait_state(guider, property, before, INDIGO_OK_STATE, PULSE_TIMEOUT)) {
		return false;
	}
	if (elapsed != NULL) {
		*elapsed = (indigo_monotonic_time() - started) * 1000;
	}
	return true;
}

static bool guide_item_cleared(int direction) {
	double value = -1;
	if (!hw_number_item(guider, guide_axis_of(direction), guide_directions[direction], &value)) {
		return false;
	}
	if (value != 0) {
		fprintf(stderr, "    %s.%s is %g after the pulse, expected 0\n", guide_axis_of(direction), guide_directions[direction], value);
		return false;
	}
	return true;
}

static int compare_double(const void *a, const void *b) {
	double left = *(const double *)a, right = *(const double *)b;
	return left < right ? -1 : (left > right ? 1 : 0);
}

static double percentile(double *sorted, int count, double fraction) {
	int index = (int)(fraction * (count - 1) + 0.5);
	return sorted[index < 0 ? 0 : (index >= count ? count - 1 : index)];
}

static void report_statistics(const char *label, double requested, double *samples, int count) {
	double sorted[64], sum = 0, sum_squares = 0, max_absolute = 0;
	for (int i = 0; i < count; i++) {
		sorted[i] = samples[i];
		sum += samples[i];
		if (fabs(samples[i] - requested) > max_absolute) {
			max_absolute = fabs(samples[i] - requested);
		}
	}
	double mean = sum / count;
	for (int i = 0; i < count; i++) {
		sum_squares += (samples[i] - mean) * (samples[i] - mean);
	}
	qsort(sorted, count, sizeof(double), compare_double);
	double deviation = count > 1 ? sqrt(sum_squares / (count - 1)) : 0;
	printf("    %-6s requested %6.1f ms  n=%d  min %7.2f  mean %7.2f  median %7.2f  p95 %7.2f  p99 %7.2f  max %7.2f  sd %6.2f  error %+6.2f ms (%+5.2f %%)  max |error| %6.2f ms\n", label, requested, count, sorted[0], mean, percentile(sorted, count, 0.5), percentile(sorted, count, 0.95), percentile(sorted, count, 0.99), sorted[count - 1], deviation, mean - requested, 100 * (mean - requested) / requested, max_absolute);
}

static void lx200_guides_in_all_four_directions(void) {
	if (skip_without_guiding()) {
		return;
	}
	ASSERT_TRUE(hw_connected(guider));
	ASSERT_TRUE(hw_property_defined(guider, GUIDER_GUIDE_RA_PROPERTY_NAME));
	ASSERT_TRUE(hw_property_defined(guider, GUIDER_GUIDE_DEC_PROPERTY_NAME));
	for (int i = 0; i < 4; i++) {
		double elapsed = 0;
		hw_forget_states();
		ASSERT_TRUE(guide_pulse(i, 300, &elapsed));
		ASSERT_TRUE((hw_states_seen(guider, guide_axis_of(i)) & (1u << INDIGO_BUSY_STATE)) != 0);
		ASSERT_TRUE(guide_item_cleared(i));
		printf("    %s %s completed in %.1f ms\n", guide_axis_of(i), guide_directions[i], elapsed);
		ASSERT_TRUE(elapsed > 250 && elapsed < 2000);
	}
}

static void lx200_guides_both_axes_at_once(void) {
	if (skip_without_guiding()) {
		return;
	}
	unsigned ra_before = hw_revision(guider, GUIDER_GUIDE_RA_PROPERTY_NAME);
	unsigned dec_before = hw_revision(guider, GUIDER_GUIDE_DEC_PROPERTY_NAME);
	hw_forget_states();
	double started = indigo_monotonic_time();
	hw_request_number(guider, GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_EAST_ITEM_NAME, 600);
	hw_request_number(guider, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME, 600);
	// Each axis has its own pulse in the controller, so completing one may not end the other.
	ASSERT_TRUE(hw_wait_state(guider, GUIDER_GUIDE_RA_PROPERTY_NAME, ra_before, INDIGO_OK_STATE, PULSE_TIMEOUT));
	ASSERT_TRUE(hw_wait_state(guider, GUIDER_GUIDE_DEC_PROPERTY_NAME, dec_before, INDIGO_OK_STATE, PULSE_TIMEOUT));
	double elapsed = (indigo_monotonic_time() - started) * 1000;
	printf("    both axes completed in %.1f ms\n", elapsed);
	ASSERT_TRUE(elapsed > 550 && elapsed < 3000);
	for (int i = 0; i < 4; i++) {
		ASSERT_TRUE(guide_item_cleared(i));
	}
}

// A pulse that arrives while another one on the same axis is still running replaces it, and the
// replaced pulse's deadline may not end the new one early.
static void lx200_replaces_a_guide_pulse_on_the_same_axis(void) {
	if (skip_without_guiding()) {
		return;
	}
	unsigned before = hw_revision(guider, GUIDER_GUIDE_RA_PROPERTY_NAME);
	double started = indigo_monotonic_time();
	hw_request_number(guider, GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_WEST_ITEM_NAME, 2000);
	ASSERT_TRUE(hw_wait_state(guider, GUIDER_GUIDE_RA_PROPERTY_NAME, before, INDIGO_BUSY_STATE, PULSE_TIMEOUT));
	indigo_usleep(500000);
	before = hw_revision(guider, GUIDER_GUIDE_RA_PROPERTY_NAME);
	hw_request_number(guider, GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_EAST_ITEM_NAME, 600);
	ASSERT_TRUE(hw_wait_state(guider, GUIDER_GUIDE_RA_PROPERTY_NAME, before, INDIGO_OK_STATE, PULSE_TIMEOUT));
	double elapsed = (indigo_monotonic_time() - started) * 1000;
	printf("    a 2000 ms pulse replaced after 500 ms by a 600 ms pulse ended after %.1f ms\n", elapsed);
	// Roughly 500 + 600 ms, and in any case well short of the 2000 ms of the replaced pulse.
	ASSERT_TRUE(elapsed > 900 && elapsed < 1800);
	ASSERT_TRUE(guide_item_cleared(2) && guide_item_cleared(3));
}

// The required guiding-pulse duration measurement. The mount terminates the pulse itself, so the
// endpoints a client can see are the request and the completion of the public property: this is
// software completion timing over the real serial path, not an electrical measurement.
static void lx200_measures_guide_pulse_duration(void) {
	static const double durations[] = { 20, 100, 500 };
	if (skip_without_guiding()) {
		return;
	}
	for (unsigned d = 0; d < ARRAY_SIZE(durations); d++) {
		double samples[4 * GUIDE_SAMPLES];
		int count = 0;
		for (int i = 0; i < 4; i++) {
			for (int repeat = 0; repeat < GUIDE_SAMPLES + GUIDE_WARMUP; repeat++) {
				double elapsed = 0;
				ASSERT_TRUE(guide_pulse(i, durations[d], &elapsed));
				ASSERT_TRUE(guide_item_cleared(i));
				if (repeat >= GUIDE_WARMUP) {
					samples[count++] = elapsed;
				}
			}
		}
		report_statistics("pulse", durations[d], samples, count);
	}
}

// Guiding has to keep working while the mount is doing something else on the same serial link.
static void lx200_guides_while_the_mount_slews(void) {
	if (skip_without_guiding()) {
		return;
	}
	double origin_dec = current_dec(), elapsed = 0;
	double dec = origin_dec > 0 ? origin_dec - ABORT_DEC_OFFSET : origin_dec + ABORT_DEC_OFFSET;
	// The slew has to be under way before the pulse: a NYX-101 counts a running pulse as motion
	// and answers a goto issued during one with "already in motion". The busy state the change
	// branch publishes says only that the request was accepted, so the scenario waits until the
	// controller itself reports the slew.
	ASSERT_TRUE(wait_for_poll());
	ASSERT_TRUE(hw_wait_settled(mount, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, INDIGO_OK_STATE, POLL_TIMEOUT));
	request_equatorial(current_ra(), dec);
	ASSERT_TRUE(wait_for_slew_started());
	ASSERT_TRUE(guide_pulse(0, 300, &elapsed));
	printf("    a guide pulse during a slew completed in %.1f ms\n", elapsed);
	ASSERT_TRUE(guide_item_cleared(0));
	ASSERT_TRUE(hw_wait_settled(mount, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, INDIGO_OK_STATE, MOTION_TIMEOUT));
	ASSERT_TRUE(guide_pulse(1, 300, &elapsed));
	ASSERT_TRUE(guide_item_cleared(1));
	// Put the mount back where this scenario found it.
	ASSERT_TRUE(wait_for_poll());
	ASSERT_TRUE(slew_to(current_ra(), origin_dec));
}

// ------------------------------------------------------------------- park and home

// The home slew and the home-set command. MOUNT_HOME_SET is issued only after the mount has
// reached its home position, so the position it stores is the one the mount already had.
static void lx200_goes_home(void) {
	unsigned before = 0;
	if (!hw_property_defined(mount, MOUNT_HOME_PROPERTY_NAME)) {
		printf("    the detected model publishes no home control\n");
		return;
	}
	before = hw_revision(mount, MOUNT_HOME_PROPERTY_NAME);
	hw_request_switch(mount, MOUNT_HOME_PROPERTY_NAME, MOUNT_HOME_ITEM_NAME, true);
	ASSERT_TRUE(hw_wait_state(mount, MOUNT_HOME_PROPERTY_NAME, before, INDIGO_BUSY_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(hw_wait_settled(mount, MOUNT_HOME_PROPERTY_NAME, INDIGO_OK_STATE, HOME_TIMEOUT));
	ASSERT_TRUE(switch_on(mount, MOUNT_HOME_PROPERTY_NAME, MOUNT_HOME_ITEM_NAME));
	ASSERT_EQ_INT(INDIGO_OK_STATE, state_light(MOUNT_STATE_HOME_ITEM_NAME));
	printf("    at home, RA %.4f DEC %.4f\n", current_ra(), current_dec());
	// Homing again from the home position is refused by the driver's own admission guard, and the
	// refusal may not leave the property busy.
	before = hw_revision(mount, MOUNT_HOME_PROPERTY_NAME);
	hw_request_switch(mount, MOUNT_HOME_PROPERTY_NAME, MOUNT_HOME_ITEM_NAME, true);
	indigo_usleep(2000000);
	ASSERT_TRUE(hw_property_state(mount, MOUNT_HOME_PROPERTY_NAME) != INDIGO_BUSY_STATE);
	// MOUNT_HOME_SET is deliberately not exercised here. On the NYX it sends :hF#, which the
	// manufacturer documents as a reset that "simulates a cold Start": the controller drops into
	// a standby in which it refuses to park until tracking is enabled again, and the stored park
	// position no longer applies. There is no command to read the previous state back, so the
	// write path stays with the simulator, where it costs nothing to undo.
}

// Park, the refusals a parked mount owes a client, unpark, and the park-set command issued while
// the mount is standing on the park position it would store.
static void lx200_parks_and_unparks(void) {
	if (!hw_property_defined(mount, MOUNT_PARK_PROPERTY_NAME)) {
		printf("    the detected model publishes no park control\n");
		return;
	}
	ASSERT_TRUE(set_parked(true));
	ASSERT_EQ_INT(INDIGO_OK_STATE, state_light(MOUNT_STATE_PARK_ITEM_NAME));
	printf("    parked at RA %.4f DEC %.4f\n", current_ra(), current_dec());
	// A parked mount refuses motion and tracking, and the refused property has to end in ALERT
	// holding the driver's own state rather than the rejected request.
	unsigned before = 0;
	if (hw_property_defined(mount, MOUNT_MOTION_RA_PROPERTY_NAME)) {
		before = hw_revision(mount, MOUNT_MOTION_RA_PROPERTY_NAME);
		hw_request_switch(mount, MOUNT_MOTION_RA_PROPERTY_NAME, MOUNT_MOTION_WEST_ITEM_NAME, true);
		ASSERT_TRUE(hw_wait_state(mount, MOUNT_MOTION_RA_PROPERTY_NAME, before, INDIGO_ALERT_STATE, SHORT_TIMEOUT));
		ASSERT_TRUE(!switch_on(mount, MOUNT_MOTION_RA_PROPERTY_NAME, MOUNT_MOTION_WEST_ITEM_NAME));
	}
	if (hw_property_defined(mount, MOUNT_TRACKING_PROPERTY_NAME)) {
		before = hw_revision(mount, MOUNT_TRACKING_PROPERTY_NAME);
		hw_request_switch(mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_ON_ITEM_NAME, true);
		ASSERT_TRUE(hw_wait_state(mount, MOUNT_TRACKING_PROPERTY_NAME, before, INDIGO_ALERT_STATE, SHORT_TIMEOUT));
	}
	// Unparking has to work straight after the refusals and the mount has to move again.
	ASSERT_TRUE(set_parked(false));
	ASSERT_EQ_INT(INDIGO_IDLE_STATE, state_light(MOUNT_STATE_PARK_ITEM_NAME));
	// Unparking releases the mount without moving it, so it is still standing on the position it
	// parked at: storing that as the park position writes back the position the mount already
	// had. The NYX refuses :hQ# while it is parked, which is why this cannot be done above.
	if (hw_property_defined(mount, MOUNT_PARK_SET_PROPERTY_NAME)) {
		ASSERT_TRUE(hw_set_switch(mount, MOUNT_PARK_SET_PROPERTY_NAME, MOUNT_PARK_SET_CURRENT_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
		ASSERT_TRUE(!switch_on(mount, MOUNT_PARK_SET_PROPERTY_NAME, MOUNT_PARK_SET_CURRENT_ITEM_NAME));
	}
	if (hw_property_defined(mount, MOUNT_MOTION_DEC_PROPERTY_NAME)) {
		// Off the park position first. A mount parks against a mechanical reference, and on a
		// controller whose declination travel is measured from that reference the axis is
		// standing on its own limit there: the move is accepted and the axis does not turn,
		// because the limit it is sent to is where it already is. An OpenAstroTracker built
		// with the default DEC_LIMIT_UP and DEC_LIMIT_DOWN of zero does exactly that.
		double moved = 0, ra = 0, dec = 0;
		nearby_target(&ra, &dec);
		ASSERT_TRUE(hw_set_switch(mount, MOUNT_ON_COORDINATES_SET_PROPERTY_NAME, MOUNT_ON_COORDINATES_SET_TRACK_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
		ASSERT_TRUE(slew_to(ra, dec));
		ASSERT_TRUE(manual_move(MOUNT_MOTION_DEC_PROPERTY_NAME, MOUNT_MOTION_SOUTH_ITEM_NAME, 1.5, &moved));
		ASSERT_TRUE(moved > 0.001);
	}
}

