static const char *guide_axis_of(int direction) {
	return direction < 2 ? GUIDER_GUIDE_DEC_PROPERTY_NAME : GUIDER_GUIDE_RA_PROPERTY_NAME;
}

static double equatorial(const char *item) {
	double value = 0;
	hw_number_item(mount, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, item, &value);
	return value;
}

static double current_ra(void) {
	return equatorial(MOUNT_EQUATORIAL_COORDINATES_RA_ITEM_NAME);
}

static double current_dec(void) {
	return equatorial(MOUNT_EQUATORIAL_COORDINATES_DEC_ITEM_NAME);
}

static double normalized_ra(double ra) {
	while (ra < 0) {
		ra += 24;
	}
	return fmod(ra, 24);
}

// The separation of two equatorial positions in degrees, which is what a motion scenario has to
// judge instead of comparing the coordinates one by one: right ascension wraps and its arc
// shrinks with the cosine of the declination.
static double separation(double ra1, double dec1, double ra2, double dec2) {
	double delta_ra = (normalized_ra(ra1) - normalized_ra(ra2)) * 15 * M_PI / 180;
	double d1 = dec1 * M_PI / 180, d2 = dec2 * M_PI / 180;
	double cosine = sin(d1) * sin(d2) + cos(d1) * cos(d2) * cos(delta_ra);
	if (cosine > 1) {
		cosine = 1;
	}
	if (cosine < -1) {
		cosine = -1;
	}
	return acos(cosine) * 180 / M_PI;
}

// A target a few degrees from wherever the mount is pointing now, kept away from the pole so the
// readback of both axes stays meaningful and away from the horizon so the controller accepts it.
static void nearby_target(double *ra, double *dec) {
	double base_dec = current_dec();
	*dec = base_dec > 0 ? base_dec - DEC_OFFSET : base_dec + DEC_OFFSET;
	if (*dec > 89) {
		*dec = 89;
	}
	if (*dec < 0) {
		*dec = 0;
	}
	*ra = normalized_ra(current_ra() + RA_OFFSET);
}

static void request_equatorial(double ra, double dec) {
	static const char *items[] = { MOUNT_EQUATORIAL_COORDINATES_RA_ITEM_NAME, MOUNT_EQUATORIAL_COORDINATES_DEC_ITEM_NAME };
	double values[] = { ra, dec };
	indigo_change_number_property(&hw_client, MOUNT_DEVICE_NAME, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, 2, items, values);
}

// A slew is accepted, published BUSY and finished by the polling callback, so the completion is
// the settled OK state and not the first update the request produces.
static bool slew_to(double ra, double dec) {
	printf("    slewing to RA %.4f DEC %.4f from RA %.4f DEC %.4f\n", ra, dec, current_ra(), current_dec());
	hw_forget_states();
	request_equatorial(ra, dec);
	if (!hw_wait_settled(mount, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, INDIGO_OK_STATE, MOTION_TIMEOUT)) {
		return false;
	}
	printf("    arrived at RA %.4f DEC %.4f, %.3f deg from the target\n", current_ra(), current_dec(), separation(current_ra(), current_dec(), ra, dec));
	return true;
}

static bool switch_on(int device, const char *property, const char *item) {
	bool value = false;
	return hw_switch_item(device, property, item, &value) && value;
}

// Waits for the next publication of a property in any state. INDIGO suppresses an update that
// says nothing new, so this only works on a property whose value actually moves.
static bool wait_for_publication(int device, const char *property, double timeout) {
	unsigned before = hw_revision(device, property);
	double deadline = indigo_monotonic_time() + timeout;
	while (indigo_monotonic_time() < deadline) {
		if (hw_revision(device, property) > before) {
			return true;
		}
		indigo_usleep(2000);
	}
	fprintf(stderr, "    timeout: %s was not published again within %g s\n", property, timeout);
	return false;
}

// Waits for the driver to read the controller again. UTC_TIME carries the mount clock, so it is
// the one property the polling callback republishes on every cycle; a property that did not
// change is not published at all, which is why a scenario cannot wait on the one it is asserting.
// A model whose controller has no clock publishes no UTC_TIME, and then the local sidereal time
// is the property that moves on its own with every cycle.
static bool wait_for_poll(void) {
	if (hw_property_defined(mount, UTC_TIME_PROPERTY_NAME)) {
		return wait_for_publication(mount, UTC_TIME_PROPERTY_NAME, POLL_TIMEOUT);
	}
	return wait_for_publication(mount, MOUNT_LST_TIME_PROPERTY_NAME, POLL_TIMEOUT);
}

static indigo_property_state state_light(const char *item) {
	indigo_property_state value = INDIGO_IDLE_STATE;
	hw_light_item(mount, MOUNT_STATE_PROPERTY_NAME, item, &value);
	return value;
}

// Waits until the controller reports a slew of its own, which is the only moment a client knows
// the goto command has been accepted by the mount rather than only by the driver.
static bool wait_for_slew_started(void) {
	double deadline = indigo_monotonic_time() + SHORT_TIMEOUT;
	while (indigo_monotonic_time() < deadline) {
		if (state_light(MOUNT_STATE_SLEW_ITEM_NAME) == INDIGO_BUSY_STATE) {
			return true;
		}
		if (hw_property_state(mount, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME) == INDIGO_ALERT_STATE) {
			fprintf(stderr, "    the slew was refused\n");
			return false;
		}
		indigo_usleep(2000);
	}
	fprintf(stderr, "    timeout: the mount did not report a slew within %g s\n", SHORT_TIMEOUT);
	return false;
}

// Parks and unparks through MOUNT_PARK, which stays BUSY until the controller reports the final
// state through its own status command.
static bool set_parked(bool parked) {
	unsigned before = hw_revision(mount, MOUNT_PARK_PROPERTY_NAME);
	hw_request_switch(mount, MOUNT_PARK_PROPERTY_NAME, parked ? MOUNT_PARK_PARKED_ITEM_NAME : MOUNT_PARK_UNPARKED_ITEM_NAME, true);
	if (!hw_wait_state(mount, MOUNT_PARK_PROPERTY_NAME, before, INDIGO_BUSY_STATE, SHORT_TIMEOUT) && !hw_wait_settled(mount, MOUNT_PARK_PROPERTY_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT)) {
		return false;
	}
	if (!hw_wait_settled(mount, MOUNT_PARK_PROPERTY_NAME, INDIGO_OK_STATE, MOTION_TIMEOUT)) {
		return false;
	}
	return switch_on(mount, MOUNT_PARK_PROPERTY_NAME, parked ? MOUNT_PARK_PARKED_ITEM_NAME : MOUNT_PARK_UNPARKED_ITEM_NAME);
}

static bool select_port(void) {
	if (serial_port == NULL || !*serial_port) {
		char detected[INDIGO_VALUE_SIZE] = "";
		if (hw_text_item(mount, DEVICE_PORT_PROPERTY_NAME, DEVICE_PORT_ITEM_NAME, detected, sizeof(detected)) && *detected) {
			printf("Using the port the driver detected: %s\n", detected);
			return true;
		}
		fprintf(stderr, "    no serial port was detected, set MOUNT_LX200_HW_PORT\n");
		return false;
	}
	printf("Using port %s\n", serial_port);
	return hw_set_text(mount, DEVICE_PORT_PROPERTY_NAME, DEVICE_PORT_ITEM_NAME, serial_port, INDIGO_OK_STATE, SHORT_TIMEOUT);
}

static bool skip_unless_nyx(const char *what) {
	if (is_nyx) {
		return false;
	}
	printf("    not applicable: %s is specific to the Pegasus NYX, which is not the detected model\n", what);
	return true;
}

// The property the aux logical device of the detected model publishes and keeps fresh: the
// environment sensors on the NYX, an auxiliary feature outlet on OnStep. A controller whose
// firmware offers neither publishes none of them, and then there is nothing to wait for.
static const char *aux_live_property(void) {
	if (hw_property_defined(aux, AUX_WEATHER_PROPERTY_NAME)) {
		return AUX_WEATHER_PROPERTY_NAME;
	}
	if (hw_property_defined(aux, AUX_POWER_OUTLET_PROPERTY_NAME)) {
		return AUX_POWER_OUTLET_PROPERTY_NAME;
	}
	if (hw_property_defined(aux, AUX_HEATER_OUTLET_PROPERTY_NAME)) {
		return AUX_HEATER_OUTLET_PROPERTY_NAME;
	}
	return NULL;
}

static bool skip_unless_onstep(const char *what) {
	if (is_onstep) {
		return false;
	}
	printf("    not applicable: %s is specific to OnStep, which is not the detected model\n", what);
	return true;
}

// A controller that implements only a part of the LX200 command set gets only the properties the
// driver can serve with it, so a scenario that needs one of the others has nothing to exercise.
static bool skip_without(const char *property, const char *what) {
	if (hw_property_defined(mount, property)) {
		return false;
	}
	printf("    not applicable: the detected model publishes no %s\n", what);
	return true;
}

// Which secondary logical devices the detected model can serve. The aux device carries the
// environment sensors of a NYX and the feature outlets of an OnStep and has nothing to offer for
// any other controller; the guider needs the LX200 pulse guiding commands, which an aGotino does
// not implement. Both have to refuse the connection rather than come up empty, which is what
// lx200_refuses_the_unsupported_devices asserts.
static bool aux_supported(void) {
	return is_nyx || is_onstep;
}

static bool guiding_supported(void) {
	return !is_agotino;
}

// Whether the controller can say where an interrupted slew actually stopped. An aGotino sets its
// position to the goto target as soon as its slew loop exits, whether the loop reached the target
// or :Q# broke out of it, which the sketch marks as a known limitation of its own. There the
// abort is judged by the time it saved instead of by the arc it left unfinished, and the mount is
// left pointing short of what it reports until the operator syncs it again.
static bool reports_the_aborted_position(void) {
	return !is_agotino;
}

// Which model the driver autodetected. Read from the controller itself, so the capability of the
// secondary devices is known before the first scenario runs.
static void detect_model(void) {
	is_nyx = switch_on(mount, X_MOUNT_TYPE_PROPERTY_NAME, X_MOUNT_TYPE_NYX_ITEM_NAME);
	is_onstep = switch_on(mount, X_MOUNT_TYPE_PROPERTY_NAME, X_MOUNT_TYPE_ONSTEP_ITEM_NAME);
	is_agotino = switch_on(mount, X_MOUNT_TYPE_PROPERTY_NAME, X_MOUNT_TYPE_AGOTINO_ITEM_NAME);
	is_oat = switch_on(mount, X_MOUNT_TYPE_PROPERTY_NAME, X_MOUNT_TYPE_OAT_ITEM_NAME);
}

// The secondary devices this model can serve, brought up and taken down together with the mount.
// The lifecycle scenarios cycle the whole session, so they go through these instead of naming the
// devices one by one.
static bool connect_secondary_devices(void) {
	if (guiding_supported() && !hw_connect(guider, CONNECT_TIMEOUT)) {
		return false;
	}
	if (aux_supported() && !hw_connect(aux, CONNECT_TIMEOUT)) {
		return false;
	}
	return true;
}

// Whatever is connected goes, not only what this model was expected to bring up: a device that
// came up although it should have refused still holds the shared serial session open, and the
// lifecycle scenarios that follow would then exercise a session nobody closed.
static bool disconnect_secondary_devices(void) {
	if (hw_connected(aux) && !hw_disconnect(aux, SHORT_TIMEOUT)) {
		return false;
	}
	if (hw_connected(guider) && !hw_disconnect(guider, SHORT_TIMEOUT)) {
		return false;
	}
	return true;
}

