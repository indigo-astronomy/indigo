// ------------------------------------------------------------------- motion

// Moves one axis for a while and returns how far that axis actually travelled: degrees for the
// declination axis, hours of right ascension for the other one. A command that is acknowledged
// but never reaches the motors is the failure this has to catch, so the judgement is the change
// of the published coordinates and not the state of the switch. The travel is measured per axis
// rather than as an angular separation, because the arc a right ascension move covers shrinks
// with the cosine of the declination and vanishes next to the pole.
static bool manual_move(const char *property, const char *item, double seconds, double *moved) {
	double ra = current_ra(), dec = current_dec();
	unsigned before = hw_revision(mount, property);
	hw_request_switch(mount, property, item, true);
	if (!hw_wait_state(mount, property, before, INDIGO_BUSY_STATE, SHORT_TIMEOUT)) {
		return false;
	}
	indigo_usleep((unsigned long)(seconds * 1000000));
	before = hw_revision(mount, property);
	hw_request_switch(mount, property, item, false);
	if (!hw_wait_state(mount, property, before, INDIGO_OK_STATE, SHORT_TIMEOUT)) {
		return false;
	}
	// One more polling cycle, so the coordinates describe the pose after the axis stopped.
	unsigned coordinates = hw_revision(mount, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME);
	if (!hw_wait_state(mount, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, coordinates, INDIGO_OK_STATE, POLL_TIMEOUT)) {
		return false;
	}
	double delta_ra = fabs(normalized_ra(current_ra() - ra + 12) - 12);
	double delta_dec = fabs(current_dec() - dec);
	*moved = strcmp(property, MOUNT_MOTION_RA_PROPERTY_NAME) ? delta_dec : delta_ra;
	printf("    %s %s for %.1f s moved %.5f h in RA and %.5f deg in DEC\n", property, item, seconds, delta_ra, delta_dec);
	return true;
}

static void lx200_moves_both_axes_manually(void) {
	double moved = 0;
	if (skip_without(MOUNT_MOTION_RA_PROPERTY_NAME, "manual motion")) {
		return;
	}
	ASSERT_TRUE(manual_move(MOUNT_MOTION_DEC_PROPERTY_NAME, MOUNT_MOTION_SOUTH_ITEM_NAME, 2.0, &moved));
	ASSERT_TRUE(moved > 0.001);
	ASSERT_TRUE(manual_move(MOUNT_MOTION_DEC_PROPERTY_NAME, MOUNT_MOTION_NORTH_ITEM_NAME, 2.0, &moved));
	ASSERT_TRUE(moved > 0.001);
	ASSERT_TRUE(manual_move(MOUNT_MOTION_RA_PROPERTY_NAME, MOUNT_MOTION_WEST_ITEM_NAME, 2.0, &moved));
	ASSERT_TRUE(moved > 0.001);
	ASSERT_TRUE(manual_move(MOUNT_MOTION_RA_PROPERTY_NAME, MOUNT_MOTION_EAST_ITEM_NAME, 2.0, &moved));
	ASSERT_TRUE(moved > 0.001);
	// Neither axis may be left running or left claiming to run.
	ASSERT_EQ_INT(INDIGO_OK_STATE, hw_property_state(mount, MOUNT_MOTION_RA_PROPERTY_NAME));
	ASSERT_EQ_INT(INDIGO_OK_STATE, hw_property_state(mount, MOUNT_MOTION_DEC_PROPERTY_NAME));
	ASSERT_TRUE(!switch_on(mount, MOUNT_MOTION_RA_PROPERTY_NAME, MOUNT_MOTION_WEST_ITEM_NAME));
	ASSERT_TRUE(!switch_on(mount, MOUNT_MOTION_RA_PROPERTY_NAME, MOUNT_MOTION_EAST_ITEM_NAME));
	ASSERT_TRUE(!switch_on(mount, MOUNT_MOTION_DEC_PROPERTY_NAME, MOUNT_MOTION_NORTH_ITEM_NAME));
	ASSERT_TRUE(!switch_on(mount, MOUNT_MOTION_DEC_PROPERTY_NAME, MOUNT_MOTION_SOUTH_ITEM_NAME));
}

// Both axes are started, then aborted together. The abort has to stop the mount and complete both
// motion properties, and the mount has to accept a fresh movement straight afterwards.
static void lx200_aborts_manual_motion(void) {
	if (skip_without(MOUNT_MOTION_RA_PROPERTY_NAME, "manual motion")) {
		return;
	}
	unsigned ra_before = hw_revision(mount, MOUNT_MOTION_RA_PROPERTY_NAME);
	unsigned dec_before = hw_revision(mount, MOUNT_MOTION_DEC_PROPERTY_NAME);
	double moved = 0;
	hw_request_switch(mount, MOUNT_MOTION_RA_PROPERTY_NAME, MOUNT_MOTION_WEST_ITEM_NAME, true);
	hw_request_switch(mount, MOUNT_MOTION_DEC_PROPERTY_NAME, MOUNT_MOTION_NORTH_ITEM_NAME, true);
	ASSERT_TRUE(hw_wait_state(mount, MOUNT_MOTION_RA_PROPERTY_NAME, ra_before, INDIGO_BUSY_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(hw_wait_state(mount, MOUNT_MOTION_DEC_PROPERTY_NAME, dec_before, INDIGO_BUSY_STATE, SHORT_TIMEOUT));
	ra_before = hw_revision(mount, MOUNT_MOTION_RA_PROPERTY_NAME);
	dec_before = hw_revision(mount, MOUNT_MOTION_DEC_PROPERTY_NAME);
	ASSERT_TRUE(hw_set_switch(mount, MOUNT_ABORT_MOTION_PROPERTY_NAME, MOUNT_ABORT_MOTION_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(hw_wait_state(mount, MOUNT_MOTION_RA_PROPERTY_NAME, ra_before, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(hw_wait_state(mount, MOUNT_MOTION_DEC_PROPERTY_NAME, dec_before, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(!switch_on(mount, MOUNT_MOTION_RA_PROPERTY_NAME, MOUNT_MOTION_WEST_ITEM_NAME));
	ASSERT_TRUE(!switch_on(mount, MOUNT_MOTION_DEC_PROPERTY_NAME, MOUNT_MOTION_NORTH_ITEM_NAME));
	// Aborting an idle mount is a no-op that still has to answer.
	ASSERT_TRUE(hw_set_switch(mount, MOUNT_ABORT_MOTION_PROPERTY_NAME, MOUNT_ABORT_MOTION_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(manual_move(MOUNT_MOTION_DEC_PROPERTY_NAME, MOUNT_MOTION_SOUTH_ITEM_NAME, 1.5, &moved));
	ASSERT_TRUE(moved > 0.001);
}

