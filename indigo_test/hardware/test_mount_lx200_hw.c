// One serial transaction plus the driver's own 50 ms settle, with room for a retry.
#define SHORT_TIMEOUT 20.0
// A connection opens the port, autodetects the model and reads the whole initial state.
#define CONNECT_TIMEOUT 45.0
// A small slew or a park slew including the driver's own completion polling.
#define MOTION_TIMEOUT 180.0
// A home slew is the one motion that can cross the whole range of both axes. An OnStepX reports
// one degree per second for its maximum slew rate, so half a turn of the right ascension axis
// alone is three minutes and the ordinary motion timeout is not enough for it.
#define HOME_TIMEOUT 600.0
// The mount is polled once a second while idle and twice a second while slewing, so two polling
// cycles plus one transaction is the longest an honest readback can take.
#define POLL_TIMEOUT 15.0
// The longest guide pulse a scenario starts, plus the completion latency of the serial path.
#define PULSE_TIMEOUT 10.0

// Where the motion scenarios work and how far they move. A mount that starts parked at the
// celestial pole is first sent to WORK_DEC, because right ascension has almost no arc next to the
// pole and a motion scenario could not tell a moving axis from a stopped one there. The offsets
// from that position are deliberately small; ABORT_DEC_OFFSET is the one exception, large enough
// that the abort scenario can interrupt a slew that is genuinely still running.
#define WORK_DEC 75.0
#define DEC_OFFSET 5.0
#define ABORT_DEC_OFFSET 12.0
// What the abort scenario uses on a controller that cannot report where an interrupted slew
// stopped. There the mount is left pointing short of the position it reports by whatever the
// abort cut off, so the arc is kept small on purpose while staying long enough to interrupt.
#define BLIND_ABORT_DEC_OFFSET 6.0
#define RA_OFFSET 0.05
// How much shorter an aborted slew has to be than the same slew run to completion, in seconds.
// It is what says the motors were stopped rather than that the goto simply ran out.
#define ABORT_MARGIN 2.0

#define GUIDE_SAMPLES 3
#define GUIDE_WARMUP 1

