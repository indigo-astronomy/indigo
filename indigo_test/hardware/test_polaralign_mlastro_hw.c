	printf("    speed %g, steps/deg alt %g az %g, limits alt [%g, %g] az [%g, %g] arcmin, backlash %s %g/%g\n", initial_speed, initial_steps_alt, initial_steps_az, initial_limits[0], initial_limits[1], initial_limits[2], initial_limits[3], initial_backlash_enabled ? "on" : "off", initial_backlash_alt, initial_backlash_az);
