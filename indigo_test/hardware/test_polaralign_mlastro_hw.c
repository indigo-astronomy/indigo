// A board without TMC2209 drivers reports ERROR (driver not connected) as soon as control is
// taken; the driver has to publish that as an alert rather than as a usable controller.
static void mlastro_reports_the_locked_controller(void) {
	char value[INDIGO_VALUE_SIZE];
	status(value, sizeof(value));
	printf("    controller status '%s'\n", value);
	ASSERT_STREQ("ERROR", value);
	ASSERT_EQ_INT(INDIGO_ALERT_STATE, hw_property_state(rpa, X_MLASTRO_STATUS_PROPERTY_NAME));
	// The poll keeps running: the status is republished, not just set once at connect.
	indigo_usleep(1500000);
	ASSERT_TRUE(hw_connected(rpa));
	ASSERT_TRUE(wait_status("ERROR", POLL_TIMEOUT));
}

static void mlastro_changes_the_speed_level(void) {
	for (int level = 1; level <= 5; level++) {
		ASSERT_TRUE(hw_set_number(rpa, X_MLASTRO_SPEED_PROPERTY_NAME, X_MLASTRO_SPEED_ITEM_NAME, level, INDIGO_OK_STATE, SHORT_TIMEOUT));
	}
	double changed = initial_speed == 2 ? 4 : 2;
	ASSERT_TRUE(hw_set_number(rpa, X_MLASTRO_SPEED_PROPERTY_NAME, X_MLASTRO_SPEED_ITEM_NAME, changed, INDIGO_OK_STATE, SHORT_TIMEOUT));
	let_the_telemetry_read_back();
	ASSERT_NEAR(changed, number(X_MLASTRO_SPEED_PROPERTY_NAME, X_MLASTRO_SPEED_ITEM_NAME), 0);
	ASSERT_TRUE(hw_set_number(rpa, X_MLASTRO_SPEED_PROPERTY_NAME, X_MLASTRO_SPEED_ITEM_NAME, initial_speed, INDIGO_OK_STATE, SHORT_TIMEOUT));
	let_the_telemetry_read_back();
	ASSERT_NEAR(initial_speed, number(X_MLASTRO_SPEED_PROPERTY_NAME, X_MLASTRO_SPEED_ITEM_NAME), 0);
}

