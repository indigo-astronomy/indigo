static void status(char *value, size_t size) {
	*value = '\0';
	hw_text_item(rpa, X_MLASTRO_STATUS_PROPERTY_NAME, X_MLASTRO_STATUS_ITEM_NAME, value, size);
}

static bool wait_status(const char *expected, double timeout) {
	char value[INDIGO_VALUE_SIZE];
	double deadline = indigo_monotonic_time() + timeout;
	while (indigo_monotonic_time() < deadline) {
		status(value, sizeof(value));
		if (!strcmp(value, expected)) {
			return true;
		}
		indigo_usleep(20000);
	}
	fprintf(stderr, "    timeout: status is '%s', expected '%s'\n", value, expected);
	return false;
}

static bool wait_homed(indigo_property_state expected, double timeout) {
	indigo_property_state value = INDIGO_IDLE_STATE;
	double deadline = indigo_monotonic_time() + timeout;
	while (indigo_monotonic_time() < deadline) {
		if (hw_light_item(rpa, X_MLASTRO_HOMED_PROPERTY_NAME, X_MLASTRO_HOMED_ITEM_NAME, &value) && value == expected) {
			return true;
		}
		indigo_usleep(20000);
	}
	fprintf(stderr, "    timeout: HOMED is %d, expected %d\n", value, expected);
	return false;
}

// A multi-item change carries every item, so the driver sends the values the test means rather
// than whatever the untouched items' targets happen to be.
static bool set_numbers(const char *property, int count, const char **items, const double *values) {
	unsigned before = hw_revision(rpa, property);
	indigo_change_number_property(&hw_client, hw_device_name(rpa), property, count, items, values);
	return hw_wait_state(rpa, property, before, INDIGO_OK_STATE, SHORT_TIMEOUT);
}

