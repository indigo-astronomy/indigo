// Code is generated by AI

// Opt-in acceptance test for the MLAstro RPA firmware running on a bare ESP32 board, without the
// TMC2209 motor drivers of a real RPA controller. It covers what such a bench board can prove: the
// serial handshake through the boot log and the firmware's unsolicited log lines, identity, the
// published property contract, telemetry polling, every setting with its readback from the
// controller's own telemetry, the home reference, the controller ERROR state and its reset,
// motion requests rejected by the locked controller without losing reply synchronization, abort,
// reconnect and driver INIT/SHUTDOWN.
//
// NOTHING MOVES. Without motor drivers the firmware reports ERROR (AzNC/AlNC, driver not
// connected) and rejects every motion command with "error: System Locked"; the suite asserts that
// state and fails on a controller that is not locked, so it is never run against a real RPA with
// motors attached. Settings are changed only in controller memory (Save&Reboot is never sent) and
// are restored at the end.
//
// The port comes from MLASTRO_HW_PORT.

