// SetH:1 is accepted even while the controller is locked; RstH:1 forgets it again. The telemetry
// Home key has to agree with the driver's own bookkeeping after several polls.
static void mlastro_sets_and_clears_the_home_reference(void) {
	ASSERT_TRUE(hw_set_switch(rpa, POLARALIGN_RESET_POSITION_AZ_PROPERTY_NAME, POLARALIGN_RESET_POSITION_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(wait_homed(INDIGO_OK_STATE, POLL_TIMEOUT));
	let_the_telemetry_read_back();
	ASSERT_TRUE(wait_homed(INDIGO_OK_STATE, 0.1));
	ASSERT_NEAR(0, number(POLARALIGN_OFFSET_PROPERTY_NAME, POLARALIGN_OFFSET_AZ_ITEM_NAME), 1e-6);
	ASSERT_TRUE(hw_set_switch(rpa, X_MLASTRO_CLEAR_HOME_PROPERTY_NAME, X_MLASTRO_CLEAR_HOME_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(wait_homed(INDIGO_IDLE_STATE, POLL_TIMEOUT));
	let_the_telemetry_read_back();
	ASSERT_TRUE(wait_homed(INDIGO_IDLE_STATE, 0.1));
	// The altitude reset zeroes the same shared reference.
	ASSERT_TRUE(hw_set_switch(rpa, POLARALIGN_RESET_POSITION_ALT_PROPERTY_NAME, POLARALIGN_RESET_POSITION_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(wait_homed(INDIGO_OK_STATE, POLL_TIMEOUT));
	let_the_telemetry_read_back();
	ASSERT_TRUE(wait_homed(INDIGO_OK_STATE, 0.1));
}

// A locked controller rejects the move. The request must end in ALERT with the target put back on
// the position, and the next command must still get its own reply: the firmware answers a
// rejected chained command with "error: System Locked" followed by an extra "ok".
static void rejected_move(const char *label, double alt, double az) {
	unsigned before = hw_revision(rpa, POLARALIGN_OFFSET_PROPERTY_NAME);
	const char *items[] = { POLARALIGN_OFFSET_ALT_ITEM_NAME, POLARALIGN_OFFSET_AZ_ITEM_NAME };
	const double values[] = { alt, az };
	indigo_change_number_property(&hw_client, hw_device_name(rpa), POLARALIGN_OFFSET_PROPERTY_NAME, 2, items, values);
	ASSERT_TRUE(hw_wait_state(rpa, POLARALIGN_OFFSET_PROPERTY_NAME, before, INDIGO_ALERT_STATE, SHORT_TIMEOUT));
	double target = NAN;
	ASSERT_TRUE(hw_number_item_target(rpa, POLARALIGN_OFFSET_PROPERTY_NAME, POLARALIGN_OFFSET_AZ_ITEM_NAME, &target));
	ASSERT_NEAR(0, target, 1e-6);
	ASSERT_TRUE(hw_number_item_target(rpa, POLARALIGN_OFFSET_PROPERTY_NAME, POLARALIGN_OFFSET_ALT_ITEM_NAME, &target));
	ASSERT_NEAR(0, target, 1e-6);
	ASSERT_NEAR(0, number(POLARALIGN_OFFSET_PROPERTY_NAME, POLARALIGN_OFFSET_AZ_ITEM_NAME), 1e-6);
	ASSERT_NEAR(0, number(POLARALIGN_OFFSET_PROPERTY_NAME, POLARALIGN_OFFSET_ALT_ITEM_NAME), 1e-6);
	double changed = initial_speed == 1 ? 5 : 1;
	ASSERT_TRUE(hw_set_number(rpa, X_MLASTRO_SPEED_PROPERTY_NAME, X_MLASTRO_SPEED_ITEM_NAME, changed, INDIGO_OK_STATE, SHORT_TIMEOUT));
	let_the_telemetry_read_back();
	ASSERT_NEAR(changed, number(X_MLASTRO_SPEED_PROPERTY_NAME, X_MLASTRO_SPEED_ITEM_NAME), 0);
	ASSERT_TRUE(hw_set_number(rpa, X_MLASTRO_SPEED_PROPERTY_NAME, X_MLASTRO_SPEED_ITEM_NAME, initial_speed, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(hw_connected(rpa));
	printf("    %s rejected, replies stay in step\n", label);
}

static void mlastro_rejects_a_single_axis_move_while_locked(void) {
	rejected_move("azimuth move", 0, 10);
	rejected_move("altitude move", -7.5, 0);
}

static void mlastro_rejects_a_two_axis_move_while_locked(void) {
	rejected_move("two-axis alignment", 5, -12);
}

static void mlastro_rejects_return_to_home_while_locked(void) {
	ASSERT_TRUE(wait_homed(INDIGO_OK_STATE, 0.1));
	ASSERT_TRUE(hw_set_switch(rpa, X_MLASTRO_GOTO_HOME_PROPERTY_NAME, X_MLASTRO_GOTO_HOME_ITEM_NAME, INDIGO_ALERT_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(hw_property_state(rpa, POLARALIGN_OFFSET_PROPERTY_NAME) != INDIGO_BUSY_STATE);
	ASSERT_TRUE(hw_set_number(rpa, X_MLASTRO_SPEED_PROPERTY_NAME, X_MLASTRO_SPEED_ITEM_NAME, initial_speed, INDIGO_OK_STATE, SHORT_TIMEOUT));
}

static void mlastro_accepts_an_abort_while_idle(void) {
	ASSERT_TRUE(hw_set_switch(rpa, POLARALIGN_ABORT_MOTION_PROPERTY_NAME, POLARALIGN_ABORT_MOTION_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	ASSERT_TRUE(hw_property_state(rpa, POLARALIGN_OFFSET_PROPERTY_NAME) != INDIGO_BUSY_STATE);
	ASSERT_NEAR(0, number(POLARALIGN_OFFSET_PROPERTY_NAME, POLARALIGN_OFFSET_AZ_ITEM_NAME), 1e-6);
	ASSERT_TRUE(hw_connected(rpa));
}

// ReER:1 is acknowledged and the controller re-detects the missing drivers at once, so the reset
// succeeds and the status goes back to ERROR on the next polls.
static void mlastro_resets_the_controller_error(void) {
	ASSERT_TRUE(hw_set_switch(rpa, X_MLASTRO_RESET_ERROR_PROPERTY_NAME, X_MLASTRO_RESET_ERROR_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
	let_the_telemetry_read_back();
	ASSERT_TRUE(wait_status("ERROR", POLL_TIMEOUT));
	ASSERT_EQ_INT(INDIGO_ALERT_STATE, hw_property_state(rpa, X_MLASTRO_STATUS_PROPERTY_NAME));
	ASSERT_TRUE(hw_connected(rpa));
}

// Opening the port resets the ESP32, so a reconnect has to handshake through the boot log again
// and read the identity back.
static void mlastro_reconnects(void) {
	ASSERT_TRUE(hw_disconnect(rpa, SHORT_TIMEOUT));
	ASSERT_TRUE(hw_property_hidden(rpa, X_MLASTRO_STATUS_PROPERTY_NAME));
	double started = indigo_monotonic_time();
	ASSERT_TRUE(hw_connect(rpa, CONNECT_TIMEOUT));
	printf("    reconnected in %.1f s\n", indigo_monotonic_time() - started);
	ASSERT_TRUE(hw_property_defined(rpa, X_MLASTRO_STATUS_PROPERTY_NAME));
	char firmware[INDIGO_VALUE_SIZE] = "";
	ASSERT_TRUE(hw_text_item(rpa, INFO_PROPERTY_NAME, INFO_DEVICE_FW_REVISION_ITEM_NAME, firmware, sizeof(firmware)));
	ASSERT_TRUE(!strncmp(firmware, "firmware ", 9));
	ASSERT_TRUE(wait_status("ERROR", POLL_TIMEOUT));
	ASSERT_TRUE(hw_set_number(rpa, X_MLASTRO_SPEED_PROPERTY_NAME, X_MLASTRO_SPEED_ITEM_NAME, initial_speed, INDIGO_OK_STATE, SHORT_TIMEOUT));
}

// Repeated connect/disconnect cycles, each of which resets the board, must all come up.
static void mlastro_survives_repeated_reconnects(void) {
	for (int cycle = 0; cycle < 3; cycle++) {
		ASSERT_TRUE(hw_disconnect(rpa, SHORT_TIMEOUT));
		ASSERT_TRUE(hw_connect(rpa, CONNECT_TIMEOUT));
		ASSERT_TRUE(wait_status("ERROR", POLL_TIMEOUT));
	}
}

// A full driver teardown and bring-up, which is what a server does when the driver is unloaded and
// loaded again. It has to leave no device behind and find the controller a second time.
static void mlastro_reinitializes(void) {
	ASSERT_TRUE(hw_disconnect(rpa, SHORT_TIMEOUT));
	ASSERT_EQ_INT(INDIGO_OK, indigo_polaralign_mlastro(INDIGO_DRIVER_SHUTDOWN, NULL));
	ASSERT_EQ_INT(-1, hw_device_index(DEVICE_NAME));
	ASSERT_EQ_INT(INDIGO_OK, indigo_polaralign_mlastro(INDIGO_DRIVER_INIT, NULL));
	rpa = hw_wait_for_device(DEVICE_NAME, SHORT_TIMEOUT);
	ASSERT_TRUE(rpa >= 0);
	ASSERT_TRUE(select_port());
	ASSERT_TRUE(hw_connect(rpa, CONNECT_TIMEOUT));
	ASSERT_TRUE(wait_status("ERROR", POLL_TIMEOUT));
}

int main(int argc, char **argv) {
	if (argc < 2 || strcmp(argv[1], "--run")) {
		fprintf(stderr, "Physical MLAstro RPA firmware test: run explicitly with --run (or make test-polaralign-mlastro-hw).\n");
		return 2;
	}
	setvbuf(stdout, NULL, _IONBF, 0);
	for (int i = 2; i < argc; i++) {
		if (!strcmp(argv[i], "--debug")) {
			indigo_set_log_level(INDIGO_LOG_DEBUG);
		}
	}
	// POLARALIGN_LIMITS is persistent, so the session keeps its configuration out of the user's own
	// folder.
	if (!indigo_test_use_private_home()) {
		return 1;
	}
	serial_port = getenv("MLASTRO_HW_PORT");
	const indigo_test_case tests[] = {
		{ "mlastro_reports_identity", mlastro_reports_identity },
		{ "mlastro_publishes_the_property_contract", mlastro_publishes_the_property_contract },
		{ "mlastro_reads_the_configuration", mlastro_reads_the_configuration },
		{ "mlastro_reports_the_locked_controller", mlastro_reports_the_locked_controller },
		{ "mlastro_changes_the_speed_level", mlastro_changes_the_speed_level },
		{ "mlastro_changes_the_steps_per_degree", mlastro_changes_the_steps_per_degree },
		{ "mlastro_reverses_each_axis", mlastro_reverses_each_axis },
		{ "mlastro_changes_the_soft_limits", mlastro_changes_the_soft_limits },
		{ "mlastro_changes_the_backlash", mlastro_changes_the_backlash },
		{ "mlastro_sets_and_clears_the_home_reference", mlastro_sets_and_clears_the_home_reference },
		{ "mlastro_rejects_a_single_axis_move_while_locked", mlastro_rejects_a_single_axis_move_while_locked },
		{ "mlastro_rejects_a_two_axis_move_while_locked", mlastro_rejects_a_two_axis_move_while_locked },
		{ "mlastro_rejects_return_to_home_while_locked", mlastro_rejects_return_to_home_while_locked },
		{ "mlastro_accepts_an_abort_while_idle", mlastro_accepts_an_abort_while_idle },
		{ "mlastro_resets_the_controller_error", mlastro_resets_the_controller_error },
		{ "mlastro_reconnects", mlastro_reconnects },
		{ "mlastro_survives_repeated_reconnects", mlastro_survives_repeated_reconnects },
		{ "mlastro_reinitializes", mlastro_reinitializes }
	};
	int result = 1;
	bool started = false, initialized = false;
	HW_CHECK(indigo_start() == INDIGO_OK);
	started = true;
	HW_CHECK(hw_attach_client("MLAstro RPA hardware test") == INDIGO_OK);
	HW_CHECK(indigo_polaralign_mlastro(INDIGO_DRIVER_INIT, NULL) == INDIGO_OK);
	initialized = true;
	rpa = hw_wait_for_device(DEVICE_NAME, SHORT_TIMEOUT);
	HW_CHECK(rpa >= 0);
	HW_CHECK(select_port());
	HW_CHECK(hw_connect(rpa, CONNECT_TIMEOUT));
	HW_CHECK(capture_initial_state());
	result = indigo_run_tests("MLAstro RPA hardware", tests, ARRAY_SIZE(tests));
cleanup:
	// Leave the controller's settings exactly as the session found them, whatever happened above.
	restore_initial_state();
	if (!hw_disconnect(rpa, SHORT_TIMEOUT)) {
		indigo_test_failures++;
	}
	if (initialized && indigo_polaralign_mlastro(INDIGO_DRIVER_SHUTDOWN, NULL) != INDIGO_OK) {
		indigo_test_failures++;
	}
	indigo_detach_client(&hw_client);
	if (started) {
		indigo_stop();
	}
	hw_release_properties();
	indigo_test_remove_private_home();
	return indigo_test_failures ? 1 : result;
}
