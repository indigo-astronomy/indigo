// One AUX transaction is a few milliseconds, but the mount is only polled once a second, so a
// readback that has to come from a fresh poll needs several cycles of room.
#define SHORT_TIMEOUT 15.0
// A connection can spend three seconds in passive discovery before the handshake starts.
#define CONNECT_TIMEOUT 45.0
// A GOTO is a fast approach followed by a slow one, both polled at 0.5 s.
#define MOTION_TIMEOUT 240.0
// The park slew starts wherever the mount happens to point and ends at the pole.
#define PARK_TIMEOUT 420.0
// Two polling cycles plus one transaction, which is the longest an honest readback can take.
#define POLL_TIMEOUT 12.0
// The longest guide pulse a scenario starts plus the completion latency of the network path.
#define PULSE_TIMEOUT 15.0

// How far the motion scenarios move. The GOTO offsets are small on purpose; the abort offset is
// the one that has to be long enough for a slew to still be running when it is interrupted.
#define DEC_OFFSET 3.0
#define RA_OFFSET 0.05
#define ABORT_DEC_OFFSET 10.0
// How long a manual motion runs before it is stopped, and the rate it runs at. MOUNT_SLEW_RATE
// CENTERING is rate 2 of the motor controller, four times sidereal, so a second of it is an arc
// the coordinate readback resolves comfortably without the mount travelling anywhere.
#define MANUAL_MOTION_SECONDS 3.0
// The smallest displacement a motion scenario accepts as "the axis really turned", in degrees.
// Four times sidereal for three seconds is 0.0167 degrees, and the readback resolves 2.1e-5.
#define MOTION_EPSILON 0.004
// How long the tracking scenarios watch the right ascension readback. A mount that is not
// tracking lets the sky run away at the sidereal rate, which is 0.00836 h over this interval,
// while a tracking mount holds its right ascension.
#define TRACKING_SECONDS 30.0
#define TRACKING_HELD_RA 0.0025
#define TRACKING_LOST_RA 0.0050

