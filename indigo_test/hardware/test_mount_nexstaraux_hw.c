	bool started = false, initialized = false;
	HW_CHECK(indigo_start() == INDIGO_OK);
	started = true;
	HW_CHECK(hw_attach_client("NexStar AUX mount hardware test") == INDIGO_OK);
	HW_CHECK(indigo_mount_nexstaraux(INDIGO_DRIVER_INIT, NULL) == INDIGO_OK);
	initialized = true;
	mount = hw_wait_for_device(MOUNT_DEVICE_NAME, SHORT_TIMEOUT);
	guider = hw_wait_for_device(GUIDER_DEVICE_NAME, SHORT_TIMEOUT);
	HW_CHECK(mount >= 0 && guider >= 0);
	HW_CHECK(select_address());
	HW_CHECK(hw_connect(mount, CONNECT_TIMEOUT));
	// GEOGRAPHIC_COORDINATES is a connected property of the mount class, so the site can only be
	// given to the driver once the session is up.
	HW_CHECK(establish_site());
