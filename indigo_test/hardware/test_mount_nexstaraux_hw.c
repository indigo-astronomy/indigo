static void nexstaraux_reinitializes(void) {
	ASSERT_TRUE(hw_disconnect(guider, SHORT_TIMEOUT));
	ASSERT_TRUE(hw_disconnect(mount, CONNECT_TIMEOUT));
	ASSERT_EQ_INT(INDIGO_OK, indigo_mount_nexstaraux(INDIGO_DRIVER_SHUTDOWN, NULL));
	ASSERT_EQ_INT(-1, hw_device_index(MOUNT_DEVICE_NAME));
	ASSERT_EQ_INT(-1, hw_device_index(GUIDER_DEVICE_NAME));
	ASSERT_EQ_INT(INDIGO_OK, indigo_mount_nexstaraux(INDIGO_DRIVER_INIT, NULL));
	mount = hw_wait_for_device(MOUNT_DEVICE_NAME, SHORT_TIMEOUT);
	guider = hw_wait_for_device(GUIDER_DEVICE_NAME, SHORT_TIMEOUT);
	ASSERT_TRUE(mount >= 0 && guider >= 0);
	// A fresh driver instance starts from the driver's own default address, which is the passive
	// discovery of whatever mount is on the network. A run told which mount to use has to say so
	// again, or the new instance reaches for a different one.
	ASSERT_TRUE(select_address());
	ASSERT_TRUE(reconnect_mount(CONNECT_TIMEOUT));
	// A fresh driver instance starts from the base driver's own site, so the session has to give
	// it the observing site again before any coordinate is judged against the earlier ones.
	ASSERT_TRUE(establish_site());
	ASSERT_TRUE(reconnect_guider(CONNECT_TIMEOUT));
	ASSERT_TRUE(hw_wait_settled(mount, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, INDIGO_OK_STATE, POLL_TIMEOUT));
}

