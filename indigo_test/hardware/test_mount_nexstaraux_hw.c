// Opt-in acceptance test for a physically connected Celestron mount reached over the NexStar AUX
// protocol, normally through a SkyPortal or StarSense WiFi module. It runs the mount hardware
// acceptance checklist of DRIVER_TESTING_RULES.md plus the guider standard for the guider logical
// device, one small scenario per case: network autodiscovery, identity, the property contract,
// coordinate polling, tracking and tracking rates, slew rates, manual motion in both axes, abort,
// SYNC, a small reachable GOTO, park and unpark, the guide rates, guide pulses including a
// duration measurement and a real axis displacement, the shared connection, a refused URL,
// reconnect and driver INIT/SHUTDOWN.
//
// THE MOUNT PHYSICALLY MOVES. Every GOTO is computed from the pointing the mount has when the
// scenario starts, never from a fixed sky position, and the offsets are a few degrees. The park
// scenario is the one exception: the driver's park is a slew to the celestial pole, so it can
// cross whatever arc separates the current pointing from the pole. The session restores the
// tracking state, the slew rate, the autoguide rates and the pointing it found.
//
// SYNC OVERWRITES THE MOUNT'S POSITION REGISTERS. The scenarios that need it record the position
// the mount reports first and sync it back afterwards, so the session gives back the alignment it
// found. Nothing else in the mount is written: the driver has no site, time or park position
// command of its own, and the autoguide rate is the only persistent motor controller setting it
// touches, which the guide rate scenarios restore.
//
// MOUNT_NEXSTARAUX_HW_URL names the mount, in the nexstar://host[:port] form the driver accepts.
// When it is not set the driver's own default is used, which is passive discovery on UDP 55555,
// and the discovery scenario asserts that it found the mount. MOUNT_NEXSTARAUX_HW_LATITUDE and
// MOUNT_NEXSTARAUX_HW_LONGITUDE give the observing site; the driver has no site command, so the
// values only have to be the real ones for the hour angle arithmetic to describe the real sky.

