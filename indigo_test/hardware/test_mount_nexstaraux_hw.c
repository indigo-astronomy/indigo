// The local sidereal time is published from the polling callback, so it has to keep moving while
// the mount is connected. The AUX protocol has no clock command of its own outside the optional
// GPS module, so UTC_TIME stays hidden and the mount reports no time.
static void nexstaraux_publishes_the_sidereal_time(void) {
	double first = number_of(mount, MOUNT_LST_TIME_PROPERTY_NAME, MOUNT_LST_TIME_ITEM_NAME);
	ASSERT_TRUE(first >= 0 && first < 24);
	ASSERT_TRUE(hw_property_hidden(mount, UTC_TIME_PROPERTY_NAME));
	double deadline = indigo_monotonic_time() + 20.0;
	while (indigo_monotonic_time() < deadline) {
		if (fabs(ra_difference(number_of(mount, MOUNT_LST_TIME_PROPERTY_NAME, MOUNT_LST_TIME_ITEM_NAME), first)) > 0.001) {
			return;
		}
		indigo_usleep(200000);
	}
	fprintf(stderr, "    the sidereal time stayed at %.6f\n", first);
	ASSERT_TRUE(false);
}

