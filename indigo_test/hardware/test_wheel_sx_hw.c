// Code is generated by AI

// Opt-in acceptance test for a physically connected Starlight Xpress filter wheel. It implements
// the wheel hardware acceptance checklist of DRIVER_TESTING_RULES.md against the real wheel:
// discovery and connection, the published property contract, the slot count the wheel reports,
// selection of every slot, the boundary slots and the wrap between them, reselection of the slot
// the wheel already sits on, the BUSY/OK publication of a turn, the overlapping request the
// framework drops, disconnect while the wheel is turning, reconnect, INIT/SHUTDOWN and the
// SHUTDOWN refusal while a device is still connected.
//
// The wheel physically turns. Every scenario is bounded by the slot count the wheel itself
// reports and the session returns the wheel to the slot it was on when the test started, so no
// filter is left in an unexpected position.
//
// The wheel has no calibration or reset command, so that row of the class standard does not apply.
//
// --hotplug adds the transport loss scenarios. They need an operator: the test asks for the USB
// cable to be pulled while the wheel is idle and again while it is turning, and for it to be
// plugged back in afterwards.

