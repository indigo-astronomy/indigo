// Starts a relative move and waits for its BUSY, without waiting for the completion.
static bool start_move(const char *direction, double steps) {
	if (!set_direction(direction)) {
		return false;
	}
	unsigned before = hw_revision(focuser, FOCUSER_STEPS_PROPERTY_NAME);
	hw_request_number(focuser, FOCUSER_STEPS_PROPERTY_NAME, FOCUSER_STEPS_ITEM_NAME, steps);
	return hw_wait_state(focuser, FOCUSER_STEPS_PROPERTY_NAME, before, INDIGO_BUSY_STATE, SHORT_TIMEOUT);
}

// A relative move waited out to its completion, which the driver publishes only when the
// controller reported the status of the requested direction. Returns the duration, or -1.
static double move_by(const char *direction, double steps) {
	if (!set_direction(direction)) {
		return -1;
	}
	unsigned before = hw_revision(focuser, FOCUSER_STEPS_PROPERTY_NAME);
	double started = indigo_monotonic_time();
	hw_request_number(focuser, FOCUSER_STEPS_PROPERTY_NAME, FOCUSER_STEPS_ITEM_NAME, steps);
	if (!hw_wait_state(focuser, FOCUSER_STEPS_PROPERTY_NAME, before, INDIGO_OK_STATE, MOVE_TIMEOUT)) {
		return -1;
	}
	return indigo_monotonic_time() - started;
}

// After an abort or a disconnect the rail stopped somewhere along an outward move, so move back by
// what the measured rate says it covered in the time it ran.
static void compensate_outward_run(double seconds, double rate) {
	double steps = round(seconds * rate);
	if (steps > travel) {
		steps = travel;
	}
	if (steps >= 1) {
		printf("    moving back an estimated %g steps (%.2f s at %.0f steps/s)\n", steps, seconds, rate);
		move_by(FOCUSER_DIRECTION_MOVE_INWARD_ITEM_NAME, steps);
	}
}

static bool set_rail_config(bool back, bool beep) {
	static const char *names[] = { X_RAIL_CONFIG_BACK_ITEM_NAME, X_RAIL_CONFIG_BEEP_ITEM_NAME };
	bool values[] = { back, beep };
	unsigned before = hw_revision(focuser, X_RAIL_CONFIG_PROPERTY_NAME);
	indigo_change_switch_property(&hw_client, DEVICE_NAME, X_RAIL_CONFIG_PROPERTY_NAME, 2, names, values);
	if (!hw_wait_state(focuser, X_RAIL_CONFIG_PROPERTY_NAME, before, INDIGO_OK_STATE, SHORT_TIMEOUT)) {
		return false;
	}
	bool back_value = !back, beep_value = !beep;
	return hw_switch_item(focuser, X_RAIL_CONFIG_PROPERTY_NAME, X_RAIL_CONFIG_BACK_ITEM_NAME, &back_value) && hw_switch_item(focuser, X_RAIL_CONFIG_PROPERTY_NAME, X_RAIL_CONFIG_BEEP_ITEM_NAME, &beep_value) && back_value == back && beep_value == beep;
}

// Sends a complete batch request without waiting for anything.
