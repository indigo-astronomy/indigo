// Opt-in acceptance test for a physically connected WeMacro Rail controller. It runs the focuser
// hardware acceptance checklist of DRIVER_TESTING_RULES.md for a relative focuser without position
// readback: the published property contract, relative moves in both directions at both speeds,
// reversal, the overlapping request and the controls refused during a move, abort while moving and
// while idle, the shutter, the rail configuration, batches with and without return, abort of a
// batch, a disconnect during a move, reconnect and driver INIT/SHUTDOWN.
//
// THE RAIL PHYSICALLY MOVES. The longest single move is WEMACRO_HW_TRAVEL steps (default 2000) and
// every scenario moves back by the same amount. The controller has no position readback, so a move
// cut short by an abort or a disconnect is compensated from the step rate the suite measured, and
// the rail may end up a few steps away from where it was found. Batches move by a tenth of the
// travel and return. The shutter output fires during the shutter and batch scenarios.
//
// The port comes from WEMACRO_HW_PORT. When it is not set the port the driver itself detected
// through its CH340 match pattern is used.

