# Helper: Check if a property exists, optionally check for specific items
# Usage: property_exists "device.property" ["item1,item2,..."]
# Returns: 0 if exists (and all items if specified), 1 otherwise
property_exists() {
	local property="$1"
	local items="${2:-}"
	local output
	if ! output=$(run_prop_tool list -w ANY "$property"); then
		print_test_result "Query $property" "FAIL" "Property query failed" >&2
		return 3
	fi
	local names
	names=$(printf '%s\n' "$output" | _property_items "$property") || return 1
	if [ -n "$items" ]; then
		local item
		local item_array
		IFS=',' read -ra item_array <<< "$items"
		for item in "${item_array[@]}"; do
			item=$(printf '%s' "$item" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')
			printf '%s\n' "$names" | grep -Fxq -- "$item" || return 1
		done
	fi
	return 0
}
# Helper: Get minimum value from property item range
# Usage: get_item_min "device.property.item"
# Returns: Echoes min value for numeric properties with range, empty string otherwise
# Example: For output "32227.000000 [0.000000,65535.000000]" returns "0.000000"
_get_item_bound() {
	local property_item="$1"
	local output
	output=$(run_prop_tool list -e -w ANY "${property_item%.*}") || return 3
	local values
	values=$(printf '%s\n' "$output" | _item_values "$property_item") || return 1
	INDIGO_RANGE_BOUND="$2" awk '
		{ value = $0 }
		END {
			number = "[-+]?([0-9]+(\\.[0-9]*)?|\\.[0-9]+)([eE][-+]?[0-9]+)?"
			if (value !~ ("^" number "[ \\t]+\\[[ \\t]*" number "[ \\t]*,[ \\t]*" number "[ \\t]*\\][ \\t]*$")) exit 1
			sub(/^[^[]*\[/, "", value); sub(/\][ \t]*$/, "", value)
			split(value, limits, ",")
			for (i = 1; i <= 2; i++) if (tolower(sprintf("%g", limits[i] + 0)) ~ /inf|nan/) exit 1
			result = limits[ENVIRON["INDIGO_RANGE_BOUND"]]
			gsub(/^[ \t]+|[ \t]+$/, "", result); print result
		}
	' <<< "$values"
}

get_item_min() {
	_get_item_bound "$1" 1
}

# Helper: Get maximum value from property item range
# Usage: get_item_max "device.property.item"
# Returns: Echoes max value for numeric properties with range, empty string otherwise
# Example: For output "32227.000000 [0.000000,65535.000000]" returns "65535.000000"
get_item_max() {
	_get_item_bound "$1" 2
}
