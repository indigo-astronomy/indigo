# Test: Standard connection test battery for all devices
# Performs comprehensive connection/disconnection tests
# Usage: test_connection_battery "device_name" timeout
# Returns the original state: 1 if originally connected, 0 otherwise
test_connection_battery() {
	local device="$1"
	local timeout="${2:-10}"

	echo "--- Connection Test Battery ---"

	local was_connected=0
	local initial_state
	if ! initial_state=$(get_item_value "$device.CONNECTION.CONNECTED" ANY); then
		print_test_result "Connection battery" "FAIL" "Could not read initial connection state"
		return 3
	fi
	if [ "$initial_state" != ON ] && [ "$initial_state" != OFF ]; then
		print_test_result "Connection battery" "FAIL" "Unknown initial connection state"
		return 3
	fi
	if [ "$initial_state" = ON ]; then
		echo "Device is connected"
		was_connected=1

		# Test connect when already connected
		test_connect_when_connected "$device" "$timeout"

		# Disconnect
		test_disconnect "$device" "$timeout"

		# Test disconnect when already disconnected
		test_disconnect_when_disconnected "$device" "$timeout"
	else
		echo "Device is disconnected"

		# Test disconnect when already disconnected
		test_disconnect_when_disconnected "$device" "$timeout"
	fi

	# Connect with full state transition check
	test_connect "$device" "$timeout"
	test_connect_when_connected "$device" "$timeout"

	return $was_connected
}

# Helper: Get property item value with optional state filter
# Usage: get_item_value "device.property.item" [state]
# Parameters:
#   property_item - Full path to property item (e.g., "Device.PROPERTY.ITEM")
#   state        - Optional property state to wait for (default: "ANY")
#                  Valid states: OK, BUSY, ALERT, IDLE, ANY
# Returns: Prints the item value to stdout
# Example: value=$(get_item_value "CCD Imager.CCD_INFO.WIDTH" "OK")
get_item_value() {
	local output
	output=$(run_prop_tool get -w "${2:-ANY}" "$1") || return 3
	printf '%s\n' "$output"
}

# Helper: Check if device is connected
is_device_connected() {
	local connected
	connected=$(get_item_value "$1.CONNECTION.CONNECTED" ANY) || return 3
	case "$connected" in
		ON) return 0 ;;
		OFF) return 1 ;;
		*) return 3 ;;
	esac
}

# Helper: Get device interface bitmask
# Usage: get_device_interface "device_name"
# Returns: Prints interface value as integer, or empty if not available
get_device_interface() {
	get_item_value "$1.INFO.DEVICE_INTERFACE" ANY
}

# Helper: Check if device has specific interface (bitmask check)
# Usage: has_interface "device_name" bitmask
# Returns: 0 if device has the interface, 1 otherwise
has_interface() {
	local device="$1"
	local required_mask="$2"
	local device_interface

	device_interface=$(get_device_interface "$device") || return 3

	case "$device_interface" in
		""|*[!0-9]*) return 1 ;;
	esac

	# Perform bitwise AND to check if interface bit is set
	local result
	result=$(( device_interface & required_mask ))

	if [ "$result" -ne 0 ]; then
		return 0
	else
		return 1
	fi
}

