# Entry points own these traps after a validated connection snapshot.
preserve_connection_state() {
	local device="$1"
	local timeout="${2:-10}"
	local connected
	if ! connected=$(get_item_value "$device.CONNECTION.CONNECTED" ANY); then
		print_test_result "Save original connection state" "FAIL" "Connection query failed"
		return 1
	fi
	case "$connected" in
		ON) WAS_CONNECTED=1 ;;
		OFF) WAS_CONNECTED=0 ;;
		*) print_test_result "Save original connection state" "FAIL" "Unknown connection state"; return 1 ;;
	esac
	CONNECTION_RESTORE_DEVICE="$device"
	CONNECTION_RESTORE_VALUE="$connected"
	CONNECTION_RESTORE_TIMEOUT="$timeout"
	CONNECTION_RESTORE_ACTIVE=1
	CONNECTION_RESTORE_SUBSHELL="${BASH_SUBSHELL:-0}"
	trap '_connection_exit $?' EXIT
	trap 'exit 130' INT
	trap 'exit 143' TERM
	return 0
}

restore_connection_state() {
	if [ "${CONNECTION_RESTORE_ACTIVE:-0}" -eq 0 ]; then
		return 0
	fi
	local connected
	local item=DISCONNECTED
	if [ "$CONNECTION_RESTORE_VALUE" = ON ]; then
		item=CONNECTED
	fi
	connected=$(get_item_value "$CONNECTION_RESTORE_DEVICE.CONNECTION.CONNECTED" ANY)
	if [ "$?" -ne 0 ] || [ "$connected" != "$CONNECTION_RESTORE_VALUE" ]; then
		if ! run_prop_tool set -w OK -t "$CONNECTION_RESTORE_TIMEOUT" "$CONNECTION_RESTORE_DEVICE.CONNECTION.$item=ON" >/dev/null; then
			print_test_result "Restore original connection state" "FAIL" "Connection restore command failed"
			return 1
		fi
		if ! connected=$(get_item_value "$CONNECTION_RESTORE_DEVICE.CONNECTION.CONNECTED" ANY); then
			print_test_result "Restore original connection state" "FAIL" "Could not verify restored connection"
			return 1
		fi
	fi
	if [ "$connected" != "$CONNECTION_RESTORE_VALUE" ]; then
		print_test_result "Restore original connection state" "FAIL" "Expected $CONNECTION_RESTORE_VALUE, got $connected"
		return 1
	fi
	CONNECTION_RESTORE_ACTIVE=0
	if [ "$CONNECTION_RESTORE_VALUE" = ON ]; then
		echo "Device was originally connected, leaving it connected"
	fi
	print_test_result "Restore original connection state" "PASS"
	return 0
}

_connection_exit() {
	local status="$1"
	if [ "${BASH_SUBSHELL:-0}" -ne "${CONNECTION_RESTORE_SUBSHELL:-0}" ]; then
		return "$status"
	fi
	trap - EXIT INT TERM
	if ! restore_connection_state && [ "$status" -eq 0 ]; then
		status=1
	fi
	exit "$status"
}

# Observe a bounded synchronous start, then abort immediately while still BUSY.
# No background tool process is started or left for the caller to reap.
test_abort_motion() {
	local test_name="$1"
	local move_query="$2"
	local motion_property="$3"
	local abort_query="$4"
	local timeout="${5:-10}"
	local abort_property="${abort_query%%=*}"
	abort_property="${abort_property%.*}"
	_require_property "$motion_property" "$test_name" || return $?
	_require_property "$abort_property" "$test_name" || return $?
	local states
	if ! states=$(_capture_set_states "$move_query" BUSY "$timeout"); then
		print_test_result "$test_name" "FAIL" "Motion start failed or timed out"
		return 1
	fi
	if ! printf '%s\n' "$states" | grep -Fxq BUSY; then
		print_test_result "$test_name" "FAIL" "Motion did not report BUSY"
		return 1
	fi
	local current_state
	if ! current_state=$(run_prop_tool get_state -w ANY -t "$timeout" "$motion_property"); then
		print_test_result "$test_name" "FAIL" "Could not verify active motion"
		return 1
	fi
	if [ "$current_state" = OK ]; then
		print_test_result "$test_name" "SKIP" "Motion completed before abort could be exercised"
		return 2
	fi
	if [ "$current_state" != BUSY ]; then
		print_test_result "$test_name" "FAIL" "Expected active motion, got [$current_state]"
		return 1
	fi
	if ! states=$(_capture_set_states "$abort_query" OK "$timeout"); then
		print_test_result "$test_name" "FAIL" "Abort command failed or timed out"
		return 1
	fi
	if [ "$(printf '%s\n' "$states" | tail -1)" != OK ]; then
		print_test_result "$test_name" "FAIL" "Abort did not finish OK"
		return 1
	fi
	if ! printf '%s\n' "$states" | grep -Fxq BUSY; then
		if current_state=$(run_prop_tool get_state -w ANY -t "$timeout" "$motion_property") && [ "$current_state" = OK ]; then
			print_test_result "$test_name" "SKIP" "Motion completed before the abort transition was observed"
			return 2
		fi
		print_test_result "$test_name" "FAIL" "Missing abort BUSY state"
		return 1
	fi
	print_test_result "$test_name" "PASS"
	return 0
}

# Capture a required read without losing its status in a caller assignment.
capture_property_value() {
	local _indigo_capture_destination="$1"
	local _indigo_capture_getter="$2"
	local _indigo_capture_query="$3"
	local _indigo_capture_value
	local _indigo_capture_pattern='^[A-Za-z_][A-Za-z0-9_]*$'
	case "$_indigo_capture_destination" in
		_indigo_capture_*) print_test_result "Read $_indigo_capture_query" "FAIL" "Reserved capture destination"; return 1 ;;
	esac
	if ! [[ "$_indigo_capture_destination" =~ $_indigo_capture_pattern ]]; then
		print_test_result "Read $_indigo_capture_query" "FAIL" "Invalid capture destination"
		return 1
	fi
	case "$_indigo_capture_getter" in
		get_item_value|get_item_number|get_item_min|get_item_max) ;;
		*) print_test_result "Read $_indigo_capture_query" "FAIL" "Unsupported getter"; return 1 ;;
	esac
	if ! _indigo_capture_value=$("$_indigo_capture_getter" "$_indigo_capture_query" "${4:-ANY}"); then
		print_test_result "Read $_indigo_capture_query" "FAIL" "Required property read failed"
		return 1
	fi
	printf -v "$_indigo_capture_destination" '%s' "$_indigo_capture_value"
}

# Numeric readbacks must not turn an empty/malformed reply into arithmetic zero.
get_item_number() {
	local value
	value=$(get_item_value "$1" "${2:-ANY}") || return 3
	_number_is_finite "$value" || return 3
	printf '%s\n' "$value"
}
