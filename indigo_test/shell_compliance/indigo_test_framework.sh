# Keep the executable and every option as a separate argument.
run_prop_tool() {
	local operation="$1"
	shift
	case "$INDIGO_PROP_TOOL_DELAY" in
		""|0|0.0) ;;
		*) sleep "$INDIGO_PROP_TOOL_DELAY" || return $? ;;
	esac
	"$INDIGO_PROP_TOOL" "$operation" "${REMOTE_SERVER[@]}" "$@"
}

# Select exact full item paths, preserving literal device-name characters.
_property_items() {
	INDIGO_QUERY_PROPERTY="$1" awk '
		BEGIN { prefix = ENVIRON["INDIGO_QUERY_PROPERTY"] "."; found = 0 }
		{
			line = $0
			equal = index(line, "="); if (!equal) next
			path = substr(line, 1, equal - 1); sub(/[ \t]+$/, "", path)
			if (index(path, prefix) != 1) next
			item = substr(path, length(prefix) + 1)
			if (item == "" || index(item, ".")) next
			print item; found = 1
		}
		END { if (!found) exit 1 }
	'
}

_item_values() {
	INDIGO_QUERY_ITEM="$1" awk '
		BEGIN { requested = ENVIRON["INDIGO_QUERY_ITEM"]; found = 0 }
		{
			line = $0
			equal = index(line, "="); if (!equal) next
			path = substr(line, 1, equal - 1); sub(/[ \t]+$/, "", path)
			if (path != requested) next
			value = substr(line, equal + 1); sub(/^[ \t]+/, "", value)
			print value; found = 1
		}
		END { if (!found) exit 1 }
	'
}

_property_states() {
	INDIGO_QUERY_PROPERTY="$1" awk '
		BEGIN { prefix = ENVIRON["INDIGO_QUERY_PROPERTY"] "." }
		{
			line = $0
			if (line !~ /^\[(OK|BUSY|ALERT|IDLE)\][ \t]/) next
			state = line; sub(/^\[/, "", state); sub(/\].*$/, "", state)
			sub(/^\[[^]]+\][ \t]*/, "", line)
			equal = index(line, "="); if (!equal) next
			path = substr(line, 1, equal - 1); sub(/[ \t]+$/, "", path)
			if (index(path, prefix) != 1) next
			item = substr(path, length(prefix) + 1)
			if (item != "" && !index(item, ".")) print state
		}
	'
}

_require_property() {
	property_exists "$1"
	local result=$?
	if [ "$result" -eq 0 ]; then
		return 0
	fi
	if [ "$result" -eq 1 ]; then
		print_test_result "$2" "SKIP" "Property $1 does not exist"
		return 2
	fi
	return 1
}

_capture_set_states() {
	local query="$1"
	local property="${query%%=*}"
	property="${property%.*}"
	local output
	output=$(run_prop_tool set -w "$2" -s -t "$3" "$query") || return 1
	printf '%s\n' "$output" | _property_states "$property"
}

# Print test result
print_test_result() {
	local test_name="$1"
	local result="$2"
	local description="$3"

	if [ "$result" = "PASS" ]; then
		echo -e "${GREEN}[PASS]${NC} $test_name"
		((TESTS_PASSED++))
	elif [ "$result" = "SKIP" ]; then
		echo -e "${GRAY}[SKIP]${NC} $test_name"
		if [ -n "$description" ]; then
			echo -e "       ${GRAY}Reason:${NC} $description"
		fi
		((TESTS_SKIPPED++))
	else
		echo -e "${RED}[FAIL]${NC} $test_name"
		if [ -n "$description" ]; then
			echo -e "       ${YELLOW}Reason:${NC} $description"
		fi
		((TESTS_FAILED++))
	fi
}

# Print test summary
print_test_summary() {
	local total=$((TESTS_PASSED + TESTS_FAILED + TESTS_SKIPPED))
	echo ""
	echo "========================================"
	echo "Test Summary: $TESTS_PASSED passed, $TESTS_FAILED failed, $TESTS_SKIPPED skipped out of $total tests"
	if [ "$TESTS_FAILED" -eq 0 ] && [ "$TESTS_SKIPPED" -gt 0 ]; then
		echo -e "${GREEN}No tests failed; skipped cases are not verified.${NC}"
	elif [ "$TESTS_FAILED" -eq 0 ]; then
		echo -e "${GREEN}All tests passed!${NC}"
	else
		echo -e "${RED}Some tests failed!${NC}"
	fi
	echo "========================================"
}

# Accept finite numeric data, never calculator-language expressions.
_number_is_finite() {
	local value="$1"
	local number_pattern='^[-+]?([0-9]+(\.[0-9]*)?|\.[0-9]+)([eE][-+]?[0-9]+)?$'
	[[ "$value" =~ $number_pattern ]] || return 1
	INDIGO_NUMBER_VALUE="$value" awk 'BEGIN { value = ENVIRON["INDIGO_NUMBER_VALUE"] + 0; text = tolower(sprintf("%g", value)); exit (text ~ /inf|nan/) }'
}

