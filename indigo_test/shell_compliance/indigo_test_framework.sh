# Helper: Get driver information from INFO property
# Usage: get_driver_info "device_name"
# Returns: Prints "driver_name driver_version" to stdout, or empty if not available
get_driver_info() {
	local driver_name
	local driver_version
	driver_name=$(get_item_value "$1.INFO.DEVICE_DRIVER" OK) || return 3
	driver_version=$(get_item_value "$1.INFO.DEVICE_VERSION" OK) || return 3
	driver_name=$(printf '%s' "$driver_name" | tr -d '"')
	driver_version=$(printf '%s' "$driver_version" | tr -d '"')
	if [ -n "$driver_name" ] && [ -n "$driver_version" ]; then
		printf '%s v.%s\n' "$driver_name" "$driver_version"
	fi
}

