"""Run indigo_server with the simulator drivers under Valgrind memcheck and report memory leaks.

The server starts under Valgrind with a private HOME, every simulator device is connected,
exercised through indigo_prop_tool (exposures, guiding, slews, dome, rotator, wheel, focuser,
flat panel) and disconnected again, --cycles times. The server is then stopped with SIGINT so
that it detaches its drivers, and Valgrind reports the memory nobody freed.

The report groups the loss records by the first INDIGO frame that allocated the memory. A leak
that grows with --cycles happens on every connect or operation; one that does not is a single
allocation at load or start. The exit code is 1 when definitely or indirectly lost memory is
found, 0 when none is, and 2 when the check could not run (no Valgrind, the server did not start
or stop). Possibly lost blocks are listed but do not fail the check.
"""
import argparse
import os
from pathlib import Path
import shutil
import signal
import socket
import subprocess
import sys
import tempfile
import time
import xml.etree.ElementTree as ElementTree

DRIVERS = ["indigo_ccd_simulator", "indigo_mount_simulator", "indigo_dome_simulator", "indigo_gps_simulator", "indigo_rotator_simulator", "indigo_aux_simulator", "indigo_polaralign_simulator"]

# Per device, the changes that exercise it while connected: (property.item=value, state to wait for).
OPERATIONS = {
	"CCD Imager Simulator": [("CCD_EXPOSURE.EXPOSURE=0.2", "OK")],
	"CCD Guider Simulator": [("CCD_EXPOSURE.EXPOSURE=0.2", "OK")],
	"CCD Guider Simulator (guider)": [("GUIDER_GUIDE_DEC.GUIDE_NORTH=100", "OK"), ("GUIDER_GUIDE_RA.GUIDE_EAST=100", "OK")],
	"CCD Imager Simulator (wheel)": [("WHEEL_SLOT.SLOT=2", "OK"), ("WHEEL_SLOT.SLOT=1", "OK")],
	"CCD Imager Simulator (focuser)": [("FOCUSER_STEPS.STEPS=100", "OK")],
	# The mount and the dome start parked and refuse to move until unparked.
	"Mount Simulator": [("MOUNT_PARK.UNPARKED=ON", "OK"), ("MOUNT_TRACKING.ON=ON", "OK"), ("MOUNT_EQUATORIAL_COORDINATES.RA=6;DEC=20", "OK"), ("MOUNT_PARK.PARKED=ON", "OK")],
	"Mount Simulator (guider)": [("GUIDER_GUIDE_DEC.GUIDE_SOUTH=100", "OK")],
	"Dome Simulator": [("DOME_PARK.UNPARKED=ON", "OK"), ("DOME_HORIZONTAL_COORDINATES.AZ=10", "OK"), ("DOME_PARK.PARKED=ON", "OK")],
	"Field Rotator Simulator": [("ROTATOR_POSITION.POSITION=10", "OK")],
	"Flat Panel Simulator": [("AUX_LIGHT_SWITCH.ON=ON", "OK"), ("AUX_LIGHT_SWITCH.OFF=ON", "OK")],
}

# Frames that only pass the allocation on; the report names the first frame after them.
ALLOCATORS = ("malloc", "calloc", "realloc", "strdup", "strndup", "posix_memalign", "aligned_alloc", "operator new", "indigo_safe_malloc", "indigo_safe_realloc", "indigo_safe_malloc_copy", "indigo_alloc_blob_buffer")


def free_port():
	with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as probe:
		probe.bind(("127.0.0.1", 0))
		return probe.getsockname()[1]


class Server:
	def __init__(self, root, port, home, xml_path, log_path):
		self.prop_tool = str(root / "build/bin/indigo_prop_tool")
		self.port = port
		self.environment = dict(os.environ, HOME=str(home))
		# --do-not-fork: by default the server runs in a child it supervises, and both processes would write one report.
		# --keep-debuginfo: the drivers are unloaded at shutdown, before Valgrind names the frames of the leaks.
		command = ["valgrind", "--tool=memcheck", "--leak-check=full", "--show-leak-kinds=definite,indirect,possible", "--num-callers=40", "--keep-debuginfo=yes", "--xml=yes", "--xml-file=" + str(xml_path), str(root / "build/bin/indigo_server"), "--do-not-fork", "-p", str(port)] + DRIVERS
		self.log = open(log_path, "w")
		self.process = subprocess.Popen(command, cwd=str(root), env=self.environment, stdout=self.log, stderr=subprocess.STDOUT)

	def tool(self, *arguments, timeout=120):
		command = [self.prop_tool, arguments[0], "-p", str(self.port)] + list(arguments[1:])
		result = subprocess.run(command, env=self.environment, capture_output=True, text=True, timeout=timeout)
		return result.stdout

	def devices(self):
		return sorted({line.split(".")[0] for line in self.tool("list", "-t", "10").splitlines() if ".CONNECTION.CONNECTED" in line})

	def set(self, device, change, state, wait):
		return self.tool("set", "-w", state, "-t", str(wait), "%s.%s" % (device, change), timeout=wait + 30)

	def stop(self, timeout):
		self.process.send_signal(signal.SIGINT)
		try:
			self.process.wait(timeout)
		except subprocess.TimeoutExpired:
			self.process.kill()
			self.process.wait()
			return False
		finally:
			self.log.close()
		return True


def exercise(server, devices, cycles, wait):
	for cycle in range(cycles):
		print("cycle %d of %d" % (cycle + 1, cycles), flush=True)
		for device in devices:
			server.set(device, "CONNECTION.CONNECTED=ON", "OK", wait)
		for device in devices:
			defined = server.tool("list", "-t", "5", device)
			for change, state in OPERATIONS.get(device, []):
				# A device without the property (e.g. a model without a focuser) is only connected.
				if "%s.%s." % (device, change.split(".")[0]) in defined:
					server.set(device, change, state, wait)
		for device in reversed(devices):
			server.set(device, "CONNECTION.DISCONNECTED=ON", "OK", wait)


def origin(frames):
	"""The first frame that is not an allocator and belongs to INDIGO code (a file or object under the repository)."""
	named = [frame for frame in frames if frame.get("fn")]
	for frame in named:
		if any(frame["fn"].startswith(allocator) for allocator in ALLOCATORS):
			continue
		if frame.get("file") or "indigo" in frame.get("obj", ""):
			return frame
	return named[0] if named else {"fn": "?"}


def describe(frame):
	where = "%s:%s" % (frame["file"], frame["line"]) if frame.get("file") else os.path.basename(frame.get("obj", "?"))
	return "%s (%s)" % (frame.get("fn", "?"), where)


def parse(xml_path):
	records = []
	tree = ElementTree.parse(xml_path)
	for error in tree.getroot().iter("error"):
		kind = error.findtext("kind", "")
		if not kind.startswith("Leak_"):
			continue
		what = error.find("xwhat")
		frames = [{child.tag: child.text for child in frame} for frame in error.find("stack").iter("frame")]
		records.append({"kind": kind[5:], "bytes": int(what.findtext("leakedbytes", "0")), "blocks": int(what.findtext("leakedblocks", "0")), "frames": frames})
	return records


def report(records):
	totals = {}
	groups = {}
	for record in records:
		totals[record["kind"]] = totals.get(record["kind"], 0) + record["bytes"]
		frame = origin(record["frames"])
		key = (record["kind"], describe(frame))
		group = groups.setdefault(key, {"bytes": 0, "blocks": 0, "stack": record["frames"]})
		group["bytes"] += record["bytes"]
		group["blocks"] += record["blocks"]
	print("\nLeak totals:")
	for kind in ("DefinitelyLost", "IndirectlyLost", "PossiblyLost"):
		print("  %-15s %10d bytes" % (kind, totals.get(kind, 0)))
	print("\nLoss records by allocating INDIGO frame:")
	for (kind, where), group in sorted(groups.items(), key=lambda entry: (entry[0][0], -entry[1]["bytes"])):
		print("  %-15s %8d bytes in %5d blocks  %s" % (kind, group["bytes"], group["blocks"], where))
		for frame in [frame for frame in group["stack"] if frame.get("fn")][:6]:
			print("      at %s" % describe(frame))
	return totals


def main():
	parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
	parser.add_argument("--cycles", type=int, default=1, help="connect, exercise and disconnect every device this many times (default 1)")
	parser.add_argument("--wait", type=int, default=120, help="seconds to wait for each change under Valgrind (default 120)")
	parser.add_argument("--keep", metavar="DIR", help="keep the Valgrind XML and server log in DIR")
	options = parser.parse_args()
	root = Path(__file__).resolve().parents[2]
	if shutil.which("valgrind") is None:
		print("valgrind is not installed; the leak check did not run", file=sys.stderr)
		return 2
	for path in ["build/bin/indigo_server", "build/bin/indigo_prop_tool"]:
		if not (root / path).exists():
			print("%s is missing; run 'make all' in the repository root first" % path, file=sys.stderr)
			return 2
	with tempfile.TemporaryDirectory(prefix="indigo-leak-check-") as temporary:
		directory = Path(options.keep) if options.keep else Path(temporary)
		directory.mkdir(parents=True, exist_ok=True)
		home = Path(temporary) / "home"
		home.mkdir()
		xml_path = directory / "valgrind.xml"
		server = Server(root, free_port(), home, xml_path, directory / "server.log")
		devices = []
		for _ in range(60):
			if server.process.poll() is not None:
				break
			devices = server.devices()
			if len(devices) >= len(DRIVERS):
				break
			time.sleep(5)
		if not devices:
			print("the server did not start; see %s" % (directory / "server.log"), file=sys.stderr)
			server.stop(60)
			return 2
		print("devices: %s" % ", ".join(devices), flush=True)
		exercise(server, devices, options.cycles, options.wait)
		if not server.stop(300):
			print("the server did not stop on SIGINT; Valgrind reported nothing", file=sys.stderr)
			return 2
		totals = report(parse(xml_path))
		if options.keep:
			print("\nValgrind XML and server log kept in %s" % directory)
	return 1 if totals.get("DefinitelyLost", 0) or totals.get("IndirectlyLost", 0) else 0


if __name__ == "__main__":
	raise SystemExit(main())
