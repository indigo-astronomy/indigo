"""Run any INDIGO mount acceptance binary against an isolated MountSim app.

The binary supports --list and one case name; it receives MOUNTSIM_PTY and
MOUNTSIM_TRACE. The relay never fabricates responses. --terminator affects only
the TX trace, not forwarding; omit it for raw binary protocols. Full duplex raw
traffic is always retained. Each case has fresh app preferences and a watchdog.
"""
import argparse
import contextlib
import fcntl
import json
import os
from pathlib import Path
import pty
import select
import signal
import socket
import subprocess
import tempfile
import sys
import time
import tty


@contextlib.contextmanager
def exclusive_mountsim(model, timeout):
    # Keep one inode across runs: unlinking a flock file can split the mutex.
    lock_path = Path('/tmp') / f'indigo-mountsim-{os.getuid()}.lock'
    with lock_path.open('a+') as lock:
        deadline = time.monotonic() + timeout
        waiting = False
        while True:
            try:
                fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
                break
            except BlockingIOError:
                if not waiting:
                    print(f'Waiting for MountSim lock: {lock_path}', flush=True)
                    waiting = True
                if time.monotonic() >= deadline:
                    raise RuntimeError(f'MountSim lock timeout: {lock_path}')
                time.sleep(.2)
        try:
            lock.seek(0)
            lock.truncate()
            lock.write(f'pid={os.getpid()} model={model}\n')
            lock.flush()
            yield
        finally:
            fcntl.flock(lock, fcntl.LOCK_UN)


def control(port, **request):
    with socket.create_connection(('127.0.0.1', port), timeout=2) as sock:
        sock.settimeout(3)
        sock.sendall(json.dumps(request).encode() + b'\n')
        with sock.makefile('rb') as stream:
            result = json.loads(stream.readline(8193))
        if not result.get('ok'):
            raise RuntimeError(result)
        return result


def stop(process):
    if process is not None and process.poll() is None:
        os.killpg(process.pid, signal.SIGTERM)
        try:
            process.wait(timeout=5)
        except subprocess.TimeoutExpired:
            os.killpg(process.pid, signal.SIGKILL)
            process.wait(timeout=5)


def run_case(args, case, directory):
    app = test = None
    descriptors = []
    with tempfile.TemporaryDirectory(prefix='indigo-mountsim-') as private, contextlib.ExitStack() as stack:
        private = Path(private)
        preferences = private / 'preferences'
        preferences.mkdir()
        # LaunchServices must not reuse or alter a user's running app instance.
        with socket.socket() as reservation:
            reservation.bind(('127.0.0.1', 0))
            port = reservation.getsockname()[1]
        env = os.environ.copy()
        env['MOUNTSIM_CONTROL_PORT'] = str(port)
        env['MOUNTSIM_PREFERENCES_DIR'] = str(preferences)
        log = stack.enter_context((directory / 'app.log').open('wb'))
        raw = stack.enter_context((directory / 'serial.raw').open('w', buffering=1))
        trace_path = directory / 'commands.events'
        trace = stack.enter_context(trace_path.open('w', buffering=1))
        output = stack.enter_context((directory / 'test.log').open('wb'))
        try:
            app = subprocess.Popen([str(args.app / 'Contents/MacOS/MountSim')], env=env, stdout=log, stderr=log, start_new_session=True)
            deadline = time.monotonic() + 20
            while True:
                if app.poll() is not None:
                    raise RuntimeError('MountSim exited before control server startup')
                try:
                    status = control(port, command='status')
                    break
                except (OSError, ValueError):
                    if time.monotonic() >= deadline:
                        raise RuntimeError('MountSim control startup timeout')
                    time.sleep(.05)
            if status['running']:
                raise RuntimeError('New isolated MountSim instance unexpectedly running')
            session = control(port, command='start', mount=args.mount)
            (directory / 'session.json').write_text(json.dumps(session, indent=2) + '\n')
            actual = os.open(session['pty'], os.O_RDWR | os.O_NOCTTY | os.O_NONBLOCK)
            descriptors.append(actual)
            tty.setraw(actual)
            master, slave = pty.openpty()
            descriptors.extend((master, slave))
            tty.setraw(slave)
            os.set_blocking(master, False)
            env['MOUNTSIM_PTY'] = os.ttyname(slave)
            env['MOUNTSIM_TRACE'] = str(trace_path)
            env['MOUNTSIM_MODEL'] = session['mount']
            env['MOUNTSIM_VERSION'] = session['version']
            control_file = private / 'transport'
            env['MOUNTSIM_TRANSPORT_CONTROL'] = str(control_file)
            # Keep base-suite case filters out: every named case must really run.
            env.pop('INDIGO_TEST_CASE_FILTER', None)
            test = subprocess.Popen([str(args.test), case], env=env, stdout=output, stderr=subprocess.STDOUT, start_new_session=True)
            pending = {actual: bytearray(), master: bytearray()}
            command = bytearray()
            deadline = time.monotonic() + args.timeout
            while test.poll() is None:
                if app.poll() is not None:
                    raise RuntimeError('MountSim exited during the test')
                if time.monotonic() >= deadline:
                    raise RuntimeError('Case watchdog expired')
                if control_file.exists():
                    action = control_file.read_text().strip()
                    control_file.unlink()
                    response = 'error'
                    if action == 'disconnect' and descriptors:
                        for fd in descriptors:
                            os.close(fd)
                        descriptors.clear()
                        pending.clear()
                        response = 'disconnected'
                    elif action == 'reconnect' and not descriptors:
                        actual = os.open(session['pty'], os.O_RDWR | os.O_NOCTTY | os.O_NONBLOCK)
                        descriptors.append(actual)
                        tty.setraw(actual)
                        master, slave = pty.openpty()
                        descriptors.extend((master, slave))
                        tty.setraw(slave)
                        os.set_blocking(master, False)
                        pending = {actual: bytearray(), master: bytearray()}
                        command.clear()
                        response = os.ttyname(slave)
                    raw.write(f'{time.clock_gettime(time.CLOCK_MONOTONIC):.9f} TRANSPORT {action} {response}\n')
                    control_file.with_suffix('.reply').write_text(response + '\n')
                readable, writable, _ = select.select([master, actual] if descriptors else [], [fd for fd, data in pending.items() if data], [], .02)
                for source in readable:
                    try:
                        data = os.read(source, 65536)
                    except BlockingIOError:
                        continue
                    if not data:
                        raise RuntimeError('PTY closed unexpectedly')
                    destination = actual if source == master else master
                    stamp = time.clock_gettime(time.CLOCK_MONOTONIC)
                    raw.write(f'{stamp:.9f} {"TX" if source == master else "RX"} {data.hex(" ")}\n')
                    pending[destination].extend(data)
                    if len(pending[destination]) > 1048576:
                        raise RuntimeError('Serial relay backpressure exceeded 1 MiB')
                for destination in writable:
                    try:
                        count = os.write(destination, pending[destination])
                    except BlockingIOError:
                        continue
                    forwarded = bytes(pending[destination][:count])
                    del pending[destination][:count]
                    if destination == actual:
                        stamp = time.clock_gettime(time.CLOCK_MONOTONIC)
                        if args.terminator:
                            command.extend(forwarded)
                            while args.terminator in command:
                                frame, _, remaining = command.partition(args.terminator)
                                command[:] = remaining
                                trace.write(f'{stamp:.9f} {frame.hex(" ")}\n')
                            if len(command) > 65536:
                                raise RuntimeError('Unterminated trace frame exceeds 64 KiB')
                        else:
                            trace.write(f'{stamp:.9f} {forwarded.hex(" ")}\n')
            return test.returncode
        finally:
            stop(test)
            for fd in descriptors:
                os.close(fd)
            if app is not None and app.poll() is None:
                try:
                    control(port, command='stop')
                except (OSError, ValueError, RuntimeError):
                    pass
            stop(app)


def main():
    # Unwind run_case's cleanup before releasing the shared application lock.
    def terminate(signum, frame):
        raise SystemExit(128 + signum)
    signal.signal(signal.SIGTERM, terminate)
    signal.signal(signal.SIGHUP, terminate)
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--app', type=Path, required=True)
    parser.add_argument('--mount', required=True)
    parser.add_argument('--test', type=Path, required=True)
    parser.add_argument('--terminator', default='', help='TX trace frame terminator in hex; never changes wire bytes')
    parser.add_argument('--case', help='Run one exact case name')
    parser.add_argument('--timeout', type=float, default=120)
    parser.add_argument('--lock-timeout', type=float, default=3600, help='Maximum seconds waiting for exclusive MountSim access')
    parser.add_argument('--output', type=Path, default=Path('build/mountsim-results'))
    args = parser.parse_args()
    if sys.platform != "darwin":
        parser.error("MountSim acceptance requires macOS and a GUI session")
    args.app = args.app.resolve()
    args.test = args.test.resolve()
    args.terminator = bytes.fromhex(args.terminator)
    args.output = args.output.resolve()
    cases = subprocess.check_output([str(args.test), '--list'], text=True, env=dict(os.environ, MOUNTSIM_MODEL=args.mount)).splitlines()
    if args.case:
        if args.case not in cases:
            parser.error('Unknown case: ' + args.case)
        cases = [args.case]
    if not cases or len(set(cases)) != len(cases):
        parser.error('Empty or duplicate test registry')
    with exclusive_mountsim(args.mount, args.lock_timeout):
        return run_cases(args, cases, parser)


def run_cases(args, cases, parser):
    passed = 0
    for case in cases:
        if Path(case).name != case:
            parser.error('Invalid test case name')
        directory = args.output / case
        directory.mkdir(parents=True, exist_ok=True)
        try:
            result = run_case(args, case, directory)
        except (OSError, ValueError, RuntimeError, subprocess.SubprocessError) as error:
            print(f'ERROR {case}: {error}', flush=True)
            result = 1
        test_log = directory / 'test.log'
        text = test_log.read_text(errors='replace') if test_log.exists() else ''
        print(text, end='', flush=True)
        if result == 0 and f'PASS {case}' in text:
            passed += 1
        else:
            print(f'FAIL {case}; artifacts: {directory}', flush=True)
    print(f'MountSim ({args.mount}): {passed}/{len(cases)} passed; artifacts: {args.output}', flush=True)
    return 0 if passed == len(cases) else 1


if __name__ == '__main__':
    raise SystemExit(main())
