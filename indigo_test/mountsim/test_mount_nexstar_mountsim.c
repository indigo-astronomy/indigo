// BUSY may precede queued transport work. Observe a complete forwarded command
// before tests create conflicts, cancellation or a transport loss.
static bool await_wire_start(double after, unsigned char opcode, int axis) {
	nexstar_frame *frames = calloc(32768, sizeof(*frames));
	if (frames == NULL) {
		return false;
	}
	bool found = false;
	for (int attempt = 0; attempt < 1000 && !found; attempt++) {
		int count = nexstar_read_frames(frames, 32768);
		if (count < 0) {
			fprintf(stderr, "Wire parser returned %d after=%g\n", count, after);
			break;
		}
		for (int i = 0; i < count; i++) {
			nexstar_frame *frame = frames + i;
			if (frame->timestamp >= after && frame->bytes[0] == opcode && (opcode != 'P' || (frame->size == 8 && frame->bytes[2] == axis && (frame->bytes[3] == 0x24 || frame->bytes[3] == 0x25) && frame->bytes[4] != 0))) {
				found = true;
				break;
			}
		}
		if (!found) {
			indigo_usleep(10000);
		}
	}
	if (!found) {
		int count = nexstar_read_frames(frames, 32768);
		fprintf(stderr, "No wire command opcode=%u axis=%d after=%.9f count=%d\n", opcode, axis, after, count);
		if (count > 0) {
			fprintf(stderr, "Last wire command %.9f %02x %02x %02x %02x %02x size=%zu\n", frames[count - 1].timestamp, frames[count - 1].bytes[0], frames[count - 1].bytes[1], frames[count - 1].bytes[2], frames[count - 1].bytes[3], frames[count - 1].bytes[4], frames[count - 1].size);
		}
	}
	free(frames);
	return found;
}

