	SERIAL_CHECK_TRUE(change_numbers(MOUNT_PARK_POSITION_PROPERTY_NAME, MOUNT_PARK_POSITION_HA_ITEM_NAME, -1, MOUNT_PARK_POSITION_DEC_ITEM_NAME, 35));
