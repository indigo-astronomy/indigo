// Observation stays independent of whichever logical device the shared cache selects.
// Preserve the prior callback pointer exactly; never restore a presumed generic callback.
static indigo_result (*previous_update)(indigo_client *, indigo_device *, indigo_property *, const char *);
static atomic_uint guide_updates[2], guide_states[2][4];
static indigo_result observe_update(indigo_client *client, indigo_device *device, indigo_property *property, const char *message) {
	printf("PROPERTY %s %s %d", property->device, property->name, property->state);
	for (int i = 0; i < property->count; i++) {
		if (property->type == INDIGO_NUMBER_VECTOR) {
			printf(" %s=%g", property->items[i].name, property->items[i].number.value);
		} else if (property->type == INDIGO_SWITCH_VECTOR) {
			printf(" %s=%d", property->items[i].name, property->items[i].sw.value);
		}
	}
	puts("");
	if (!strcmp(property->device, nexstar_mount.device_name) && !strcmp(property->name, MOUNT_LST_TIME_PROPERTY_NAME)) {
		atomic_fetch_add(&observed_lst_updates, 1);
	}
	if (!strcmp(property->device, nexstar_mount.device_name) && !strcmp(property->name, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME)) {
		pthread_mutex_lock(&observation_mutex);
		for (int i = 0; i < property->count; i++) {
			if (!strcmp(property->items[i].name, MOUNT_EQUATORIAL_COORDINATES_RA_ITEM_NAME)) {
				observed_ra = property->items[i].number.value;
			} else if (!strcmp(property->items[i].name, MOUNT_EQUATORIAL_COORDINATES_DEC_ITEM_NAME)) {
				observed_dec = property->items[i].number.value;
			}
		}
		coordinate_updates++;
		observed_coordinate_state = property->state;
		pthread_mutex_unlock(&observation_mutex);
	}
	if (!strcmp(property->device, nexstar_guider.device_name)) {
		int axis = !strcmp(property->name, GUIDER_GUIDE_RA_PROPERTY_NAME) ? 0 : !strcmp(property->name, GUIDER_GUIDE_DEC_PROPERTY_NAME) ? 1 : -1;
		if (axis >= 0) {
			unsigned int revision = atomic_fetch_add(guide_updates + axis, 1) + 1;
			atomic_store(&guide_states[axis][property->state], revision);
		}
	}
	return previous_update(client, device, property, message);
}

static unsigned int snapshot_coordinates(double *ra, double *dec, indigo_property_state *state) {
	pthread_mutex_lock(&observation_mutex);
	*ra = observed_ra;
	*dec = observed_dec;
	if (state != NULL) {
		*state = observed_coordinate_state;
	}
	unsigned int revision = coordinate_updates;
	pthread_mutex_unlock(&observation_mutex);
	return revision;
}

static bool await_guiding_state(int axis, indigo_property_state state, unsigned int revision) {
	for (int i = 0; i < 1000; i++) {
		if (atomic_load(&guide_states[axis][state]) > revision) {
			return true;
		}
		indigo_usleep(10000);
	}
	return false;
}

static bool await_coordinates(double ra, double dec, unsigned int revision, double tolerance) {
	for (int i = 0; i < 600; i++) {
		double current_ra, current_dec;
		indigo_property_state state;
		unsigned int current = snapshot_coordinates(&current_ra, &current_dec, &state);
		if (current > revision && state == INDIGO_OK_STATE && fabs(remainder(current_ra - ra, 24) * 15) < tolerance && fabs(current_dec - dec) < tolerance) {
			return true;
		}
		indigo_usleep(100000);
	}
	return false;
}

static bool change_numbers(const char *property, const char *first, double first_value, const char *second, double second_value) {
	unsigned int revision = property_revision(property);
	const char *items[] = { first, second };
	double values[] = { first_value, second_value };
	return indigo_change_number_property(&simulator_test_client, nexstar_mount.device_name, property, second ? 2 : 1, items, values) == INDIGO_OK && wait_for_property_state_seen_after(property, INDIGO_OK_STATE, revision);
}

static bool start_case(external_serial_simulator *session) {
	if (!mountsim_attach(session) || !start_mount_fixture(session->port)) {
		return false;
	}
	if (model->altaz && (!change_switch("TRACKING_MODE", "EQ", true, INDIGO_OK_STATE) || !find_cached_item("TRACKING_MODE", "EQ")->sw.value)) {
		return false;
	}
	return change_switch(MOUNT_PARK_PROPERTY_NAME, MOUNT_PARK_UNPARKED_ITEM_NAME, true, INDIGO_OK_STATE) && fresh_coordinates();
}

static bool reachable_goto(double offset, double declination) {
	double lst = number_value(MOUNT_LST_TIME_PROPERTY_NAME, MOUNT_LST_TIME_ITEM_NAME);
	double ra = fmod(lst + offset + 24, 24);
	double old_ra, old_dec;
	unsigned int revision = snapshot_coordinates(&old_ra, &old_dec, NULL);
	return isfinite(lst) && change_switch(MOUNT_ON_COORDINATES_SET_PROPERTY_NAME, MOUNT_ON_COORDINATES_SET_TRACK_ITEM_NAME, true, INDIGO_OK_STATE) && change_coordinates(ra, declination, INDIGO_BUSY_STATE) && await_coordinates(ra, declination, revision, 0.05) && wait_for_property_state(MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, INDIGO_OK_STATE);
}

static bool coordinates_move(int axis, double sign, double minimum, int milliseconds) {
	double ra, dec;
	unsigned int revision = snapshot_coordinates(&ra, &dec, NULL);
	for (int elapsed = 0; elapsed < milliseconds; elapsed += 100) {
		indigo_usleep(100000);
		double next_ra, next_dec;
		unsigned int next = snapshot_coordinates(&next_ra, &next_dec, NULL);
		double change = axis == 0 ? remainder(next_ra - ra, 24) * 15 : next_dec - dec;
		if (next > revision && sign * change > minimum) {
			return true;
		}
	}
	return false;
}

static bool coordinates_change(int axis, double minimum, int milliseconds) {
	double ra, dec;
	unsigned int revision = snapshot_coordinates(&ra, &dec, NULL);
	for (int elapsed = 0; elapsed < milliseconds; elapsed += 100) {
		indigo_usleep(100000);
		double next_ra, next_dec;
		unsigned int next = snapshot_coordinates(&next_ra, &next_dec, NULL);
		double change = axis == 0 ? remainder(next_ra - ra, 24) * 15 : next_dec - dec;
		if (next > revision && fabs(change) > minimum) {
			return true;
		}
	}
	return false;
}

static bool coordinates_stable(int axis, double tolerance, int milliseconds) {
	double ra, dec;
	snapshot_coordinates(&ra, &dec, NULL);
	unsigned int lst_revision = atomic_load(&observed_lst_updates);
	for (int elapsed = 0; elapsed < milliseconds; elapsed += 100) {
		indigo_usleep(100000);
		double next_ra, next_dec;
		snapshot_coordinates(&next_ra, &next_dec, NULL);
		double change = axis == 0 ? remainder(next_ra - ra, 24) * 15 : next_dec - dec;
		if (fabs(change) > tolerance) {
			return false;
		}
	}
	return atomic_load(&observed_lst_updates) > lst_revision;
}

static bool pulse(int axis, const char *direction, double duration, bool finish) {
	const char *property = axis == 0 ? GUIDER_GUIDE_RA_PROPERTY_NAME : GUIDER_GUIDE_DEC_PROPERTY_NAME;
	unsigned int revision = atomic_load(guide_updates + axis);
	double after = wire_now();
	if (indigo_change_number_property_1(&simulator_test_client, nexstar_guider.device_name, property, direction, duration) != INDIGO_OK) {
		return false;
	}
	bool busy = duration == 0 || await_guiding_state(axis, INDIGO_BUSY_STATE, revision);
	bool wire = duration == 0 || (busy && await_wire_start(after, 'P', axis ? 17 : 16));
	bool done = !finish || await_guiding_state(axis, INDIGO_OK_STATE, revision);
	if (!busy || !wire || !done) {
		fprintf(stderr, "Guide pulse %s %g ms: busy=%d wire=%d done=%d revision=%u updates=%u\n", direction, duration, busy, wire, done, revision, atomic_load(guide_updates + axis));
	}
	return busy && wire && done;
}

