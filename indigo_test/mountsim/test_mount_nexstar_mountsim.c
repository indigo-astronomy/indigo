	int frame_count = nexstar_read_frames(frames, 32768);
	SERIAL_CHECK_TRUE(frame_count >= 0);
	double target_polar = NAN, target_dec = NAN;
	for (int i = 0; i < frame_count; i++) {
		if (frames[i].timestamp >= park_after && frames[i].size == 18 && frames[i].bytes[0] == 'b') {
			char encoded[19];
			memcpy(encoded, frames[i].bytes + 1, 17);
			encoded[17] = '#';
			encoded[18] = 0;
			SERIAL_CHECK_TRUE(nexstar_decode_axis_reply(encoded, 8, &target_polar, &target_dec));
		}
	}
	SERIAL_CHECK_TRUE(isfinite(target_polar) && isfinite(target_dec));
	SERIAL_CHECK_TRUE(fixture_disconnect(&nexstar_mount));
	raw_fd = open(session.port, O_RDWR | O_NOCTTY | O_NONBLOCK);
	SERIAL_CHECK_TRUE(raw_fd >= 0);
