static int compare_sample(const void *left, const void *right) {
	double a = *(const double *)left, b = *(const double *)right;
	return (a > b) - (a < b);
}

static void timing_report(const char *workload, const char *direction, double requested, double *errors, int count) {
	double sum = 0, squared = 0, maximum_absolute = 0;
	for (int i = 0; i < count; i++) {
		sum += errors[i];
		squared += errors[i] * errors[i];
		maximum_absolute = fmax(maximum_absolute, fabs(errors[i]));
	}
	qsort(errors, count, sizeof(*errors), compare_sample);
	double mean = sum / count, median = (errors[(count - 1) / 2] + errors[count / 2]) / 2;
	printf("GUIDE_TIMING workload=%s direction=%s requested_ms=%g n=%d signed_ms min=%g mean=%g median=%g p95=%g p99=%g max=%g sd=%g max_abs_ms=%g mean_percent=%g mean_actual_ms=%g\n", workload, direction, requested, count, errors[0], mean, median, errors[(int)ceil(count * .95) - 1], errors[(int)ceil(count * .99) - 1], errors[count - 1], sqrt(fmax(0, squared / count - mean * mean)), maximum_absolute, 100 * mean / requested, requested + mean);
}

static void nexstar_guider_transport_edge_timing(void) {
	external_serial_simulator session = { 0 };
	nexstar_frame *frames = calloc(32768, sizeof(*frames));
	SERIAL_CHECK_TRUE(frames != NULL);
	SERIAL_CHECK_TRUE(start_case(&session));
	SERIAL_CHECK_TRUE(fixture_connect(&nexstar_guider, NULL));
	static const char *directions[] = { GUIDER_GUIDE_EAST_ITEM_NAME, GUIDER_GUIDE_WEST_ITEM_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME, GUIDER_GUIDE_SOUTH_ITEM_NAME };
	static const int durations[] = { 20, 100, 500 };
	// Mapping is production baseline only, not a claim that sky direction is correct.
	static const int baseline_commands[] = { 0x24, 0x25, 0x24, 0x25 };
	for (int workload = 0; workload < 2; workload++) {
		reset_simulator_context(&nexstar_mount);
		enumerate_simulator_device();
		SERIAL_CHECK_TRUE(change_switch(MOUNT_TRACKING_PROPERTY_NAME, workload ? MOUNT_TRACKING_ON_ITEM_NAME : MOUNT_TRACKING_OFF_ITEM_NAME, true, INDIGO_OK_STATE));
		SERIAL_CHECK_TRUE(fresh_coordinates());
		indigo_item *tracking = find_cached_item(MOUNT_TRACKING_PROPERTY_NAME, workload ? MOUNT_TRACKING_ON_ITEM_NAME : MOUNT_TRACKING_OFF_ITEM_NAME);
		SERIAL_CHECK_TRUE(tracking != NULL && tracking->sw.value);
		reset_simulator_context(&nexstar_guider);
		enumerate_simulator_device();
		for (int direction = 0; direction < ARRAY_SIZE(directions); direction++) {
			for (int duration = 0; duration < ARRAY_SIZE(durations); duration++) {
				double errors[4];
				for (int repeat = -1; repeat < 4; repeat++) {
					double after = wire_now();
					SERIAL_CHECK_TRUE(pulse(direction / 2, directions[direction], durations[duration], true));
					double on = 0, off = 0;
					bool edges = false;
					for (int attempt = 0; attempt < 50 && !edges; attempt++) {
						int count = nexstar_read_frames(frames, 32768);
						SERIAL_CHECK_TRUE(count >= 0);
						edges = nexstar_guide_edges(frames, count, after, direction / 2 ? 17 : 16, baseline_commands[direction], &on, &off);
						if (!edges) {
							indigo_usleep(10000);
						}
					}
					SERIAL_CHECK_TRUE(edges);
					SERIAL_CHECK_TRUE(isfinite(on) && isfinite(off));
					if (repeat >= 0) {
						errors[repeat] = 1000 * (off - on) - durations[duration];
					}
				}
				timing_report(workload ? "tracking-and-coordinate-polling" : "tracking-off-and-coordinate-polling", directions[direction], durations[duration], errors, ARRAY_SIZE(errors));
			}
		}
	}
cleanup:
	free(frames);
	stop_mount_fixture();
}

