// Read forwarding records, reconstruct fragmented/coalesced commands, retain
// timestamp of the final byte so edges mean a complete forwarded command.
// Trailing partial frames are legitimate during a live read and are omitted.
static int nexstar_read_frames(nexstar_frame *frames, size_t capacity) {
	char path[PATH_MAX], line[200000];
	if (!mountsim_trace_path(path, sizeof(path))) {
		return -1;
	}
	FILE *file = fopen(path, "r");
	if (file == NULL) {
		return -1;
	}
	nexstar_frame pending = { 0 };
	size_t wanted = 0, count = 0;
	while (fgets(line, sizeof(line), file)) {
		char *cursor, *end;
		double timestamp = strtod(line, &cursor);
		if (cursor == line || !isfinite(timestamp)) {
			fclose(file);
			return -1;
		}
		for (;;) {
			unsigned long byte = strtoul(cursor, &end, 16);
			if (end == cursor) {
				break;
			}
			cursor = end;
			if (byte > 255 || (pending.size == 0 && (wanted = nexstar_command_size(byte)) == 0)) {
				fclose(file);
				return -1;
			}
			pending.bytes[pending.size++] = byte;
			if (pending.size == wanted) {
				if (count >= capacity) {
					fclose(file);
					return -1;
				}
				pending.timestamp = timestamp;
				frames[count++] = pending;
				pending.size = 0;
			}
		}
	}
	fclose(file);
	return (int)count;
}

