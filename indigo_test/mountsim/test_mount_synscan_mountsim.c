static bool initialize(void) {
	memset(devices, 0, sizeof(devices));
	memset(&session, 0, sizeof(session));
	bus_started = client_attached = driver_initialized = false;
	event_epoch = 0;
	mount = guider = aux = -1;
	last_message_text[0] = 0;
	client = (indigo_client){ .name = "EQMOD MountSim acceptance", .version = INDIGO_VERSION_CURRENT, .define_property = define_property, .update_property = update_property, .delete_property = delete_property, .send_message = report_message };
	if (!mountsim_attach(&session) || indigo_start() != INDIGO_OK) { return false; }
	bus_started = true;
	if (indigo_attach_client(&client) != INDIGO_OK) { return false; }
	client_attached = true;
	if (indigo_mount_synscan(INDIGO_DRIVER_INIT, NULL) != INDIGO_OK) { return false; }
	driver_initialized = true;
	double deadline = wire_now() + SHORT_TIMEOUT;
	while (wire_now() < deadline) {
		mount = device_index(MOUNT_DEVICE_NAME);
		guider = device_index(GUIDER_DEVICE_NAME);
		aux = device_index(AUX_DEVICE_NAME);
		if (mount >= 0 && guider >= 0 && aux >= 0) {
			return set_text(mount, DEVICE_PORT_PROPERTY_NAME, DEVICE_PORT_ITEM_NAME, session.port, INDIGO_OK_STATE, SHORT_TIMEOUT);
		}
		indigo_usleep(20000);
	}
	return false;
}

static void cleanup_session(void) {
	if (connected(mount)) {
		set_switch(mount, MOUNT_ABORT_MOTION_PROPERTY_NAME, MOUNT_ABORT_MOTION_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT);
		set_switch(mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_OFF_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT);
	}
	if (!disconnect_device(aux)) { indigo_test_failures++; }
	if (!disconnect_device(guider)) { indigo_test_failures++; }
	if (!disconnect_device(mount)) { indigo_test_failures++; }
	if (driver_initialized && indigo_mount_synscan(INDIGO_DRIVER_SHUTDOWN, NULL) != INDIGO_OK) { indigo_test_failures++; }
	driver_initialized = false;
	if (client_attached) { indigo_detach_client(&client); }
	client_attached = false;
	if (bus_started) { indigo_stop(); }
	bus_started = false;
	for (int d = 0; d < MAX_DEVICES; d++) {
		for (int p = 0; p < MAX_PROPERTIES; p++) {
			indigo_release_property(devices[d].properties[p]);
			devices[d].properties[p] = NULL;
		}
	}
}

