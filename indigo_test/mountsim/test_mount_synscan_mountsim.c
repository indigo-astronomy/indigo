static bool arrive(double ra, double dec) {
	if (!set_coordinates(mount, ra, dec, INDIGO_BUSY_STATE, SHORT_TIMEOUT)) { return false; }
	unsigned before = revision(mount, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME);
	double deadline = wire_now() + MOTION_TIMEOUT;
	while (wire_now() < deadline) {
		double actual_ra = NAN, actual_dec = NAN;
		if (revision(mount, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME) > before && property_state(mount, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME) == INDIGO_OK_STATE && number_item(mount, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, MOUNT_EQUATORIAL_COORDINATES_RA_ITEM_NAME, &actual_ra) && number_item(mount, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, MOUNT_EQUATORIAL_COORDINATES_DEC_ITEM_NAME, &actual_dec) && fabs(ra_difference(actual_ra, ra)) < .02 && fabs(actual_dec - dec) < .1) { return true; }
		indigo_usleep(20000);
	}
	double actual_ra = NAN, actual_dec = NAN;
	number_item(mount, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, MOUNT_EQUATORIAL_COORDINATES_RA_ITEM_NAME, &actual_ra);
	number_item(mount, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME, MOUNT_EQUATORIAL_COORDINATES_DEC_ITEM_NAME, &actual_dec);
	fprintf(stderr, "GOTO did not arrive: target RA %.6f DEC %.6f, actual RA %.6f DEC %.6f, state %d\n", ra, dec, actual_ra, actual_dec, property_state(mount, MOUNT_EQUATORIAL_COORDINATES_PROPERTY_NAME));
	return false;
}

