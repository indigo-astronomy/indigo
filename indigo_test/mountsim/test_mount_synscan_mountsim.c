static void statistics(const char *name, double *values, int count) {
	double sum = 0, square = 0, maximum_absolute = 0;
	for (int i = 0; i < count; i++) {
		sum += values[i];
		square += values[i] * values[i];
		maximum_absolute = fmax(maximum_absolute, fabs(values[i]));
	}
	for (int i = 0; i < count; i++) {
		for (int j = i + 1; j < count; j++) {
			if (values[j] < values[i]) { double temporary = values[i]; values[i] = values[j]; values[j] = temporary; }
		}
	}
	double median = count % 2 ? values[count / 2] : (values[count / 2 - 1] + values[count / 2]) / 2;
	printf("TIMING %s n=%d min=%.6f mean=%.6f median=%.6f p95=%.6f p99=%.6f max=%.6f stddev=%.6f max_abs=%.6f\n", name, count, values[0], sum / count, median, values[(int)ceil(.95 * count) - 1], values[(int)ceil(.99 * count) - 1], values[count - 1], sqrt(fmax(0, square / count - sum * sum / count / count)), maximum_absolute);
}

static void eqmod_guider_timing_mode(int workload) {
	double ra;
	const char *properties[] = { GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_RA_PROPERTY_NAME, GUIDER_GUIDE_DEC_PROPERTY_NAME, GUIDER_GUIDE_DEC_PROPERTY_NAME };
	const char *items[] = { GUIDER_GUIDE_EAST_ITEM_NAME, GUIDER_GUIDE_WEST_ITEM_NAME, GUIDER_GUIDE_NORTH_ITEM_NAME, GUIDER_GUIDE_SOUTH_ITEM_NAME };
	const int durations[] = { 20, 100, 500 };
	CHECK(setup_pointing(&ra));
	CHECK(connect_device(guider));
	CHECK(set_switch(mount, MOUNT_TRACKING_PROPERTY_NAME, MOUNT_TRACKING_ON_ITEM_NAME, INDIGO_OK_STATE, SHORT_TIMEOUT));
		for (int direction = 0; direction < 4; direction++) {
			double errors[9], percentages[9], restoration[9];
			for (int sample = -1; sample < 9; sample++) {
				int duration = sample < 0 ? 100 : durations[sample % 3];
				const char *other_property = direction < 2 ? GUIDER_GUIDE_DEC_PROPERTY_NAME : GUIDER_GUIDE_RA_PROPERTY_NAME;
				const char *other_item = direction < 2 ? GUIDER_GUIDE_NORTH_ITEM_NAME : GUIDER_GUIDE_EAST_ITEM_NAME;
				unsigned other_before = revision(guider, other_property);
				if (workload) {
					double other_started_after = wire_now();
					CHECK(set_number(guider, other_property, other_item, 1000, INDIGO_BUSY_STATE, SHORT_TIMEOUT));
					CHECK(wait_command_after(direction < 2 ? ":J2" : ":J1", other_started_after));
				}
				double before = wire_now();
				CHECK(pulse(properties[direction], items[direction], duration));
				double started = command_after(direction < 2 ? ":J1" : ":J2", before, false);
				double stopped = command_after(direction < 2 ? ":K1" : ":K2", started, false);
				CHECK(started > before && stopped >= started && stopped - started < SHORT_TIMEOUT);
				double restored = direction < 2 ? command_after(":J1", stopped, false) : stopped;
				CHECK(restored >= stopped);
				if (sample >= 0) {
					errors[sample] = (stopped - started) * 1000 - duration;
					percentages[sample] = errors[sample] * 100 / duration;
					restoration[sample] = (restored - stopped) * 1000;
					CHECK(isfinite(errors[sample]) && isfinite(percentages[sample]) && isfinite(restoration[sample]));
					printf("PULSE workload=%s direction=%s requested_ms=%d command_edge_ms=%.6f error_ms=%.6f error_percent=%.6f tracking_restore_ms=%.6f\n", workload ? "tracking+other-axis-guide+polling" : "tracking+idle-polling", items[direction], duration, (stopped - started) * 1000, errors[sample], percentages[sample], restoration[sample]);
				}
				if (workload) { CHECK(wait_state(guider, other_property, other_before, INDIGO_OK_STATE, SHORT_TIMEOUT)); }
			}
			printf("ENDPOINTS direction=%s workload=%d explicit J-to-K forwarded software transport edges; host/relay scheduling included; no physical pulse claim\n", items[direction], workload);
			statistics("signed-error-ms", errors, 9);
			statistics("signed-error-percent", percentages, 9);
			if (direction < 2) { statistics("tracking-restoration-ms", restoration, 9); }
	}
cleanup:
	cleanup_session();
}

static void eqmod_guider_timing_idle(void) { eqmod_guider_timing_mode(0); }

static void eqmod_guider_timing_overlap(void) { eqmod_guider_timing_mode(1); }

static void eqmod_raw_controller_contract(void) {
	int fd = -1;
	char reply[64], first[2][64];
	CHECK(mountsim_attach(&session));
	fd = open(session.port, O_RDWR | O_NOCTTY | O_NONBLOCK);
	CHECK(fd >= 0);
	struct termios options;
	CHECK(tcgetattr(fd, &options) == 0);
	cfmakeraw(&options);
	CHECK(tcsetattr(fd, TCSANOW, &options) == 0);
	CHECK(raw_command(fd, ":s1", reply, sizeof(reply)) && !strcmp(reply, "!00"));
	CHECK(raw_command(fd, ":s2", reply, sizeof(reply)) && !strcmp(reply, "!00"));
	CHECK(raw_command(fd, ":x1", reply, sizeof(reply)) && !strcmp(reply, "!00"));
	CHECK(raw_command(fd, ":I1", reply, sizeof(reply)) && !strcmp(reply, "!01"));
	CHECK(raw_command(fd, ":P19", reply, sizeof(reply)) && !strcmp(reply, "!03"));
	for (int axis = 1; axis <= 2; axis++) {
		char command[16];
		snprintf(command, sizeof(command), ":F%d", axis);
		CHECK(raw_command(fd, command, reply, sizeof(reply)) && !strcmp(reply, "="));
		snprintf(command, sizeof(command), ":f%d", axis);
		CHECK(raw_command(fd, command, first[axis - 1], sizeof(first[0])) && first[axis - 1][0] == '=');
	}
	CHECK(raw_command(fd, ":q1010000", reply, sizeof(reply)) && !strcmp(reply, "=000000"));
	for (int axis = 1; axis <= 2; axis++) {
		char command[16];
		snprintf(command, sizeof(command), ":f%d", axis);
		CHECK(raw_command(fd, command, reply, sizeof(reply)) && !strcmp(reply, first[axis - 1]));
	}
	CHECK(raw_command(fd, ":E1341280", reply, sizeof(reply)) && !strcmp(reply, "="));
	CHECK(raw_command(fd, ":j1", reply, sizeof(reply)) && !strcmp(reply, "=341280"));
	CHECK(raw_command(fd, ":E2FEFFFF", reply, sizeof(reply)) && !strcmp(reply, "="));
	CHECK(raw_command(fd, ":j2", reply, sizeof(reply)) && !strcmp(reply, "=FEFFFF"));
	CHECK(raw_command(fd, ":G100", reply, sizeof(reply)) && !strcmp(reply, "="));
	CHECK(raw_command(fd, ":H1400D03", reply, sizeof(reply)) && !strcmp(reply, "="));
	CHECK(raw_command(fd, ":M1F40100", reply, sizeof(reply)) && !strcmp(reply, "="));
	CHECK(raw_command(fd, ":J1", reply, sizeof(reply)) && !strcmp(reply, "="));
	CHECK(raw_command(fd, ":E1000080", reply, sizeof(reply)) && !strcmp(reply, "!02"));
	indigo_usleep(200000);
	CHECK(raw_command(fd, ":j1", reply, sizeof(reply)) && strcmp(reply, "=341280") && strcmp(reply, "=741F83"));
	double deadline = wire_now() + 10;
	do {
		CHECK(raw_command(fd, ":f1", reply, sizeof(reply)) && reply[0] == '=');
		if (reply[2] == '0') { break; }
		indigo_usleep(20000);
	} while (wire_now() < deadline);
	CHECK(wire_now() < deadline);
	CHECK(raw_command(fd, ":j1", reply, sizeof(reply)) && !strcmp(reply, "=741F83"));
	CHECK(raw_command(fd, ":G210", reply, sizeof(reply)) && !strcmp(reply, "="));
	CHECK(raw_command(fd, ":I26C0200", reply, sizeof(reply)) && !strcmp(reply, "="));
	CHECK(raw_command(fd, ":J2", reply, sizeof(reply)) && !strcmp(reply, "="));
	indigo_usleep(500000);
	CHECK(raw_command(fd, ":j2", reply, sizeof(reply)) && strcmp(reply, "=FEFFFF"));
	CHECK(raw_command(fd, ":K2", reply, sizeof(reply)) && !strcmp(reply, "="));
cleanup:
	if (fd >= 0) { close(fd); }
}

