static bool raw_command(int fd, const char *request, char *reply, size_t capacity) {
	char command[32];
	int length = snprintf(command, sizeof(command), "%s\r", request);
	if (length <= 0 || length >= sizeof(command) || write(fd, command, length) != length) { return false; }
	size_t used = 0;
	double deadline = wire_now() + 3;
	while (wire_now() < deadline && used + 1 < capacity) {
		char byte;
		ssize_t count = read(fd, &byte, 1);
		if (count == 1) {
			if (byte == '\r') { reply[used] = 0; return true; }
			reply[used++] = byte;
		} else if (count < 0 && errno != EAGAIN && errno != EINTR) {
			return false;
		} else {
			indigo_usleep(1000);
		}
	}
	return false;
}

