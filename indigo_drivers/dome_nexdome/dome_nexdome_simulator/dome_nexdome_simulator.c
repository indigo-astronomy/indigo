static void event(const char *kind, const char *format, ...) __attribute__((format(printf, 2, 3)));

static void event(const char *kind, const char *format, ...) {
	if (!events) {
		return;
	}
	fprintf(events, "%.6f %s ", serial_motion_time(), kind);
	va_list args;
	va_start(args, format);
	vfprintf(events, format, args);
	va_end(args);
	fputc('\n', events);
	fflush(events);
}

static void stop_signal(int signal) {
	(void)signal;
	running = 0;
}

static double normalize(double azimuth) {
	double result = fmod(azimuth, 360);
	return result < 0 ? result + 360 : result;
}

static double distance(double a, double b) {
	double delta = fabs(normalize(a) - normalize(b));
	return delta > 180 ? 360 - delta : delta;
}

static bool at_home(void) {
	return distance(serial_motion_update(&rotation), home_azimuth) < 0.5;
}

// advances rotation, marks home as seen when the sensor is reached and ends motion states
static void update_rotation(void) {
	serial_motion_update(&rotation);
	if (rotation.duration > 0) {
		return;
	}
	if (dome_mode) {
		if (rotation_passes_home || at_home()) {
			has_been_home = true;
		}
		event("STATE", "rotation mode=%d stopped at=%.1f home_seen=%d", dome_mode, normalize(rotation.position), has_been_home);
		dome_mode = 0;
		rotation_passes_home = false;
	}
}

static double heading(void) {
	update_rotation();
	return normalize(rotation.position);
}

static void rotate_to(double target, int mode, const char *origin) {
	double current = serial_motion_update(&rotation);
	double delta = normalize(target) - normalize(current);
	if (delta > 180) {
		delta -= 360;
	} else if (delta < -180) {
		delta += 360;
	}
	double to_home = normalize(home_azimuth) - normalize(current);
	if (delta >= 0) {
		to_home = to_home < 0 ? to_home + 360 : to_home;
		rotation_passes_home = to_home <= delta;
	} else {
		to_home = to_home > 0 ? to_home - 360 : to_home;
		rotation_passes_home = to_home >= delta;
	}
	serial_motion_start(&rotation, current + delta, rotation_speed);
	dome_mode = rotation.duration > 0 ? mode : 0;
	event("MOVE", "%s rotation from=%.1f to=%.1f delta=%.1f mode=%d", origin, normalize(current), normalize(target), delta, dome_mode);
}

static void stop_rotation(const char *origin) {
	serial_motion_update(&rotation);
	if (rotation.duration > 0) {
		serial_motion_stop(&rotation);
		event("STATE", "%s rotation stopped at=%.1f mode=%d", origin, normalize(rotation.position), dome_mode);
	}
	dome_mode = 0;
	rotation_passes_home = false;
}

static void start_shutter(double target) {
	shutter_start_time = -1;
	serial_motion_start(&shutter, target, 100 / shutter_time);
	shutter_state = target > shutter.origin ? SHUTTER_OPENING : target < shutter.origin ? SHUTTER_CLOSING : shutter_state;
	event("MOVE", "shutter from=%d to=%d", (int)lround(shutter.origin), (int)target);
}

static void update_shutter(void) {
	if (shutter_start_time >= 0 && serial_motion_time() >= shutter_start_time) {
		start_shutter(shutter_start_target);
	}
	serial_motion_update(&shutter);
	if (shutter.duration == 0 && shutter_start_time < 0 && (shutter_state == SHUTTER_OPENING || shutter_state == SHUTTER_CLOSING)) {
		shutter_state = shutter.position <= 0 ? SHUTTER_CLOSED : SHUTTER_OPEN;
		event("STATE", "shutter state=%d position=%d", shutter_state, (int)lround(shutter.position));
	}
	if (raining && shutter_state == SHUTTER_OPEN) {
		event("STATE", "rain closes shutter");
		start_shutter(0);
		shutter_state = SHUTTER_CLOSING;
	}
}

static int reported_shutter_state(void) {
	update_shutter();
	if (!shutter_connected) {
		return SHUTTER_NOT_CONNECTED;
	}
	return forced_shutter_state >= 0 ? forced_shutter_state : shutter_state;
}

// requests shutter motion; the controller learns the new state after the wireless latency
static void request_shutter(double target) {
	if (!shutter_connected) {
		event("REJECT", "shutter not connected");
		return;
	}
	forced_shutter_state = -1;
	if (target <= 0) {
		// the firmware reports closing as soon as it accepts the command
		shutter_state = SHUTTER_CLOSING;
	}
	if (shutter_latency > 0) {
		shutter_start_time = serial_motion_time() + shutter_latency;
		shutter_start_target = target;
		event("MOVE", "shutter to=%d after=%.3f", (int)target, shutter_latency);
	} else {
		start_shutter(target);
		if (shutter.duration == 0) {
			shutter_state = shutter.position <= 0 ? SHUTTER_CLOSED : SHUTTER_OPEN;
		}
	}
}

static void stop_shutter(const char *origin) {
	shutter_start_time = -1;
	serial_motion_stop(&shutter);
	if (shutter_state == SHUTTER_OPENING || shutter_state == SHUTTER_CLOSING) {
		shutter_state = shutter.position <= 0 ? SHUTTER_CLOSED : SHUTTER_OPEN;
		event("STATE", "%s shutter stopped at=%d state=%d", origin, (int)lround(shutter.position), shutter_state);
	}
}

// writes one reply line; the firmware ends most replies with CR LF and m, p, q with LF only
static void write_reply(const char *text, const char *terminator) {
	char reply[REPLY_SIZE + 4], logged[REPLY_SIZE];
	snprintf(logged, sizeof(logged), "%s", text);
	// an embedded line break (version with shutter version) is logged on one line
	for (char *c = logged; *c; c++) {
		*c = *c == '\r' || *c == '\n' ? '|' : *c;
	}
	event("TX", "%s", logged);
	serial_simulator_trace_line(trace, "<-", logged);
	snprintf(reply, sizeof(reply), "%s%s", text, terminator);
	serial_simulator_write_all(reply_fd, reply, strlen(reply));
}

// executes one command; returns the reply text or NULL when the firmware does not answer
static const char *execute(const char *command, const char **terminator) {
	static char result[REPLY_SIZE];
	const char *argument = command + 1;
	bool has_argument = *argument == ' ';
	double value = atof(argument);
	*terminator = "\r\n";
	update_rotation();
	update_shutter();
	switch (*command) {
		case 'a':
			stop_rotation("abort");
			if (shutter_connected) {
				stop_shutter("abort");
			}
			return "A";
		case 'b':
			snprintf(result, sizeof(result), "B %.2f", serial_motion_update(&shutter) * 0.9);
			return result;
		case 'c':
			if (!at_home() || rotation.duration > 0) {
				event("REJECT", "calibration not at home");
				return "E";
			}
			serial_motion_start(&rotation, rotation.position + 360, rotation_speed);
			dome_mode = 3;
			event("MOVE", "calibration from=%.1f", heading());
			return "C";
		case 'd':
			if (raining) {
				event("REJECT", "open while raining");
				return "E";
			}
			request_shutter(100);
			return "D";
		case 'e':
			request_shutter(0);
			return "D";
		case 'f':
			request_shutter(value / 0.9);
			return "F";
		case 'g':
			if (value < 0 || value > 360) {
				event("REJECT", "goto %s", command);
				return "E";
			}
			rotate_to(value, 1, "goto");
			return "G";
		case 'h':
			if (at_home()) {
				has_been_home = true;
				event("STATE", "find home at home");
			} else {
				rotate_to(home_azimuth, 2, "home");
			}
			return "H";
		case 'i':
			snprintf(result, sizeof(result), "I %.2f", home_azimuth);
			return result;
		case 'j':
			if (has_argument && value >= 0 && value < 360) {
				home_azimuth = value;
			}
			snprintf(result, sizeof(result), "I %.2f", home_azimuth);
			return result;
		case 'k':
			snprintf(result, sizeof(result), "K %d %d %d", rotator_volts, shutter_volts, cutoff_volts);
			return result;
		case 'l':
			if (value >= 0 && value < 360) {
				park_azimuth = value;
			}
			snprintf(result, sizeof(result), "N %.2f", park_azimuth);
			return result;
		case 'm':
			*terminator = "\n";
			snprintf(result, sizeof(result), "M %d", rotation.duration > 0 ? dome_mode : 0);
			return result;
		case 'n':
			snprintf(result, sizeof(result), "N %.2f", park_azimuth);
			return result;
		case 'o':
			return "O 0.00";
		case 'p':
			*terminator = "\n";
			snprintf(result, sizeof(result), "P %ld", lround(heading() / 360 * STEPS_PER_TURN));
			return result;
		case 'q':
			*terminator = "\n";
			snprintf(result, sizeof(result), "Q %.1f", normalize(round(heading() * 10) / 10));
			return result;
		case 'r':
			if (has_argument) {
				hibernate_timer = strtoul(argument, NULL, 10);
			}
			snprintf(result, sizeof(result), "R %lu", hibernate_timer);
			return result;
		case 's':
			if (value < 0 || value >= 360) {
				event("REJECT", "sync %s", command);
				return "E ";
			}
			if (has_been_home) {
				home_azimuth = normalize(home_azimuth + value - heading());
			}
			stop_rotation("sync");
			serial_motion_sync(&rotation, value);
			event("STATE", "synced heading=%.2f home=%.2f", value, home_azimuth);
			snprintf(result, sizeof(result), "S %.2f", value);
			return result;
		case 't':
			snprintf(result, sizeof(result), "T %ld", STEPS_PER_TURN);
			return result;
		case 'u':
			snprintf(result, sizeof(result), "U %d %d", reported_shutter_state(), raining ? 0 : 1);
			return result;
		case 'v':
			if (*shutter_version) {
				// println of the shutter version is followed by an empty println
				snprintf(result, sizeof(result), "VNexDome V %s NexShutter V %s\r\n", version, shutter_version);
			} else {
				snprintf(result, sizeof(result), "VNexDome V %s", version);
			}
			return result;
		case 'w':
			blocked_until = serial_motion_time() + wireless_delay;
			event("STATE", "wireless reset blocks for %.3f", wireless_delay);
			return "W";
		case 'x':
			return "X";
		case 'y':
			if (has_argument) {
				reversed = argument[1] == '1';
			}
			snprintf(result, sizeof(result), "Y %d", reversed);
			return result;
		case 'z':
			snprintf(result, sizeof(result), "Z %d", at_home() ? 1 : has_been_home ? 0 : -1);
			return result;
		default:
			event("REJECT", "unknown %s", command);
			return NULL;
	}
}

static bool fault(const char *command, char *action, char *argument) {
	if (!fault_file) {
		return false;
	}
	FILE *file = fopen(fault_file, "r");
	if (!file) {
		return false;
	}
	char line[256] = "", prefix[64] = "";
	int count = 1, consumed = 0;
	bool read = fgets(line, sizeof(line), file) != NULL;
	fclose(file);
	if (!read || sscanf(line, "%15s %d %63s %n", action, &count, argument, &consumed) < 3) {
		return false;
	}
	snprintf(prefix, sizeof(prefix), "%s", line + consumed);
	prefix[strcspn(prefix, "\n")] = 0;
	if (strcmp(prefix, "ANY") && strncmp(command, prefix, strlen(prefix))) {
		return false;
	}
	if (--count <= 0) {
		unlink(fault_file);
	} else {
		char temporary[PATH_MAX];
		snprintf(temporary, sizeof(temporary), "%s.sim", fault_file);
		file = fopen(temporary, "w");
		if (file) {
			fprintf(file, "%s %d %s %s\n", action, count, argument, prefix);
			fclose(file);
			rename(temporary, fault_file);
		}
	}
	for (char *c = argument; *c; c++) {
		*c = *c == '_' ? ' ' : *c;
	}
	event("FAULT", "%s %s", command, action);
	return true;
}

static void dispatch(const char *command) {
	char action[16], argument[64];
	const char *terminator = "\r\n", *reply;
	event("RX", "%s", command);
	serial_simulator_trace_line(trace, "->", command);
	if (fault(command, action, argument)) {
		if (!strcmp(action, "silent")) {
			return;
		} else if (!strcmp(action, "close")) {
			running = 0;
			return;
		} else if (!strcmp(action, "raw")) {
			event("TX", "%s", argument);
			serial_simulator_write_all(reply_fd, argument, strlen(argument));
			return;
		}
		// a rejected command is not executed, other faults alter the reply of an executed command
		reply = !strcmp(action, "error") ? "E" : execute(command, &terminator);
		if (!strcmp(action, "reply")) {
			reply = argument;
		} else if (!strcmp(action, "slow")) {
			usleep((useconds_t)(atoi(argument) > 0 ? atoi(argument) : 1000) * 1000);
		} else if (!strcmp(action, "partial")) {
			terminator = "";
		}
		if (reply) {
			write_reply(reply, terminator);
		}
		return;
	}
	reply = execute(command, &terminator);
	if (reply) {
		write_reply(reply, terminator);
	}
}

static void apply_control(void) {
	if (!control_file) {
		return;
	}
	FILE *file = fopen(control_file, "r");
	if (!file) {
		return;
	}
	char key[32], value[64];
	while (fscanf(file, "%31s %63s", key, value) == 2) {
		update_rotation();
		update_shutter();
		if (!strcmp(key, "azimuth")) {
			stop_rotation("control");
			serial_motion_sync(&rotation, normalize(atof(value)));
		} else if (!strcmp(key, "rotate")) {
			rotate_to(atof(value), 1, "control");
		} else if (!strcmp(key, "stall")) {
			stop_rotation("stall");
		} else if (!strcmp(key, "shutter")) {
			shutter_start_time = -1;
			serial_motion_sync(&shutter, !strcmp(value, "open") ? 100 : !strcmp(value, "closed") ? 0 : atof(value));
			shutter_state = shutter.position <= 0 ? SHUTTER_CLOSED : SHUTTER_OPEN;
		} else if (!strcmp(key, "shutterstate")) {
			forced_shutter_state = atoi(value);
		} else if (!strcmp(key, "connected")) {
			shutter_connected = atoi(value) != 0;
		} else if (!strcmp(key, "rain")) {
			raining = atoi(value) != 0;
		} else if (!strcmp(key, "volts")) {
			sscanf(value, "%d,%d", &rotator_volts, &shutter_volts);
		} else if (!strcmp(key, "park")) {
			park_azimuth = normalize(atof(value));
		} else if (!strcmp(key, "home")) {
			home_azimuth = normalize(atof(value));
		} else if (!strcmp(key, "beenhome")) {
			has_been_home = atoi(value) != 0;
		} else if (!strcmp(key, "version")) {
			snprintf(version, sizeof(version), "%s", value);
		} else if (!strcmp(key, "shutterversion")) {
			snprintf(shutter_version, sizeof(shutter_version), "%s", strcmp(value, "-") ? value : "");
		} else if (!strcmp(key, "latency")) {
			shutter_latency = atof(value);
		} else if (!strcmp(key, "drop") && tcp_source.fd >= 0) {
			close(tcp_source.fd);
			tcp_source.fd = -1;
			tcp_source.used = 0;
		}
		event("CONTROL", "%s %s", key, value);
	}
	fclose(file);
	unlink(control_file);
}

static bool parse_arguments(int argc, char **argv) {
	for (int i = 1; i < argc; i++) {
		if (!strcmp(argv[i], "--headless")) {
			headless = true;
		} else if (!strcmp(argv[i], "--trace")) {
			trace = true;
		} else if (!strcmp(argv[i], "--no-shutter")) {
			shutter_connected = false;
		} else if (!strcmp(argv[i], "--rain")) {
			raining = true;
		} else if (!strcmp(argv[i], "--reversed")) {
			reversed = true;
		} else if (!strcmp(argv[i], "--been-home")) {
			has_been_home = true;
		} else if (i + 1 < argc && !strcmp(argv[i], "--ready-file")) {
			ready_file = argv[++i];
		} else if (i + 1 < argc && !strcmp(argv[i], "--azimuth")) {
			serial_motion_sync(&rotation, normalize(atof(argv[++i])));
		} else if (i + 1 < argc && !strcmp(argv[i], "--shutter")) {
			i++;
			serial_motion_sync(&shutter, !strcmp(argv[i], "open") ? 100 : !strcmp(argv[i], "closed") ? 0 : atof(argv[i]));
			shutter_state = shutter.position <= 0 ? SHUTTER_CLOSED : SHUTTER_OPEN;
		} else if (i + 1 < argc && !strcmp(argv[i], "--park")) {
			park_azimuth = normalize(atof(argv[++i]));
		} else if (i + 1 < argc && !strcmp(argv[i], "--home")) {
			home_azimuth = normalize(atof(argv[++i]));
		} else if (i + 1 < argc && !strcmp(argv[i], "--volts")) {
			sscanf(argv[++i], "%d,%d", &rotator_volts, &shutter_volts);
		} else if (i + 1 < argc && !strcmp(argv[i], "--version")) {
			snprintf(version, sizeof(version), "%s", argv[++i]);
		} else if (i + 1 < argc && !strcmp(argv[i], "--shutter-version")) {
			snprintf(shutter_version, sizeof(shutter_version), "%s", argv[++i]);
		} else if (i + 1 < argc && !strcmp(argv[i], "--rotation-speed")) {
			rotation_speed = atof(argv[++i]);
		} else if (i + 1 < argc && !strcmp(argv[i], "--shutter-time")) {
			shutter_time = atof(argv[++i]);
		} else if (i + 1 < argc && !strcmp(argv[i], "--shutter-latency")) {
			shutter_latency = atof(argv[++i]);
		} else if (i + 1 < argc && !strcmp(argv[i], "--wireless-delay")) {
			wireless_delay = atof(argv[++i]);
		} else if (i + 1 < argc && !strcmp(argv[i], "--tcp-port")) {
			tcp_port = atoi(argv[++i]);
		} else if (!strcmp(argv[i], "--help") || !strcmp(argv[i], "-h")) {
			printf("Usage: %s [--headless] [--trace] [--ready-file PATH] [--azimuth DEG] [--park DEG] [--home DEG] [--been-home] [--shutter open|closed|PERCENT] [--no-shutter] [--rain] [--reversed] [--volts ROTATOR_CV,SHUTTER_CV] [--version TEXT] [--shutter-version TEXT] [--rotation-speed DEG_PER_S] [--shutter-time S] [--shutter-latency S] [--wireless-delay S] [--tcp-port PORT]\n", argv[0]);
			exit(0);
		} else {
			fprintf(stderr, "Unknown/incomplete option '%s'\n", argv[i]);
			return false;
		}
	}
	if (rotation_speed <= 0 || shutter_time <= 0 || shutter_latency < 0 || wireless_delay < 0) {
		fprintf(stderr, "Rates must be positive\n");
		return false;
	}
	return true;
}

static bool open_tcp_listener(void) {
	struct sockaddr_in address = { 0 };
	int reuse = 1;
	socklen_t length = sizeof(address);
	tcp_listen_fd = socket(AF_INET, SOCK_STREAM, 0);
	if (tcp_listen_fd < 0) {
		perror("socket");
		return false;
	}
	setsockopt(tcp_listen_fd, SOL_SOCKET, SO_REUSEADDR, &reuse, sizeof(reuse));
	address.sin_family = AF_INET;
	address.sin_addr.s_addr = htonl(INADDR_LOOPBACK);
	address.sin_port = htons(tcp_port);
	if (bind(tcp_listen_fd, (struct sockaddr *)&address, sizeof(address)) < 0 || listen(tcp_listen_fd, 1) < 0 || getsockname(tcp_listen_fd, (struct sockaddr *)&address, &length) < 0) {
		perror("tcp listener");
		close(tcp_listen_fd);
		tcp_listen_fd = -1;
		return false;
	}
	tcp_port = ntohs(address.sin_port);
	return true;
}

static bool write_ready_file(const char *port) {
	if (tcp_listen_fd < 0) {
		return serial_simulator_write_ready_file(ready_file, "dome_nexdome_simulator", port);
	}
	char temporary[PATH_MAX];
	snprintf(temporary, sizeof(temporary), "%s.tmp.%ld", ready_file, (long)getpid());
	FILE *file = fopen(temporary, "w");
	if (file == NULL) {
		perror("fopen ready file");
		return false;
	}
	fprintf(file, "INDIGO_SIMULATOR=dome_nexdome_simulator\n");
	fprintf(file, "INDIGO_SIMULATOR_PORT=%s\n", port);
	fprintf(file, "INDIGO_SIMULATOR_TCP_URL=tcp://127.0.0.1:%d\n", tcp_port);
	fprintf(file, "INDIGO_SIMULATOR_PID=%ld\n", (long)getpid());
	if (fclose(file) != 0 || rename(temporary, ready_file) != 0) {
		perror("ready file");
		unlink(temporary);
		return false;
	}
	return true;
}

// reads one available byte of a source and dispatches complete commands; returns false when the source is closed
static bool read_source(command_source *source) {
	char byte;
	ssize_t count = read(source->fd, &byte, 1);
	if (count == 0 || (count < 0 && errno != EAGAIN && errno != EINTR && errno != EIO)) {
		return source == &serial_source;
	}
	if (count < 0) {
		usleep(1000);
		return true;
	}
	if (byte == '\n' || byte == '\r') {
		if (source->overflow) {
			event("REJECT", "%s command too long", source->name);
		} else if (source->used) {
			source->command[source->used] = 0;
			reply_fd = source->fd;
			dispatch(source->command);
		}
		source->used = 0;
		source->overflow = false;
		return true;
	}
	// the firmware discards its 20 character buffer when it fills up
	if (source->used == COMMAND_SIZE - 1) {
		source->used = 0;
		source->overflow = true;
	}
	source->command[source->used++] = byte;
	return true;
}

int main(int argc, char **argv) {
	if (!parse_arguments(argc, argv)) {
		return 1;
	}
	fault_file = getenv("INDIGO_NEXDOME_FAULT");
	control_file = getenv("INDIGO_NEXDOME_CONTROL");
	const char *event_file = getenv("INDIGO_NEXDOME_EVENTS");
	events = event_file ? fopen(event_file, "a") : NULL;
	signal(SIGTERM, stop_signal);
	signal(SIGINT, stop_signal);
	signal(SIGPIPE, SIG_IGN);
	char port[PATH_MAX];
	serial_fd = serial_simulator_open_pty(port, sizeof(port));
	if (serial_fd < 0 || (tcp_port >= 0 && !open_tcp_listener()) || (ready_file && !write_ready_file(port))) {
		return 1;
	}
	serial_source.fd = serial_fd;
	event("OPEN", "azimuth=%.1f park=%.1f home=%.1f shutter=%d connected=%d rain=%d version=%s tcp_port=%d", heading(), park_azimuth, home_azimuth, (int)lround(shutter.position), shutter_connected, raining, version, tcp_port);
	if (!headless) {
		printf("NexDome simulator is listening on %s\n", port);
		if (tcp_listen_fd >= 0) {
			printf("NexDome simulator is listening on tcp://127.0.0.1:%d\n", tcp_port);
		}
		fflush(stdout);
	}
	while (running) {
		apply_control();
		update_rotation();
		update_shutter();
		fd_set fds;
		FD_ZERO(&fds);
		int max_fd = -1;
		// the controller does not read commands while the wireless link is reinitialized
		bool blocked = serial_motion_time() < blocked_until;
		if (!blocked) {
			FD_SET(serial_fd, &fds);
			max_fd = serial_fd;
			if (tcp_source.fd >= 0) {
				FD_SET(tcp_source.fd, &fds);
				max_fd = tcp_source.fd > max_fd ? tcp_source.fd : max_fd;
			}
		}
		if (tcp_listen_fd >= 0) {
			FD_SET(tcp_listen_fd, &fds);
			max_fd = tcp_listen_fd > max_fd ? tcp_listen_fd : max_fd;
		}
		struct timeval timeout = { 0, 20000 };
		if (max_fd < 0) {
			usleep(20000);
			continue;
		}
		if (select(max_fd + 1, &fds, NULL, NULL, &timeout) <= 0) {
			continue;
		}
		if (tcp_listen_fd >= 0 && FD_ISSET(tcp_listen_fd, &fds)) {
			int client = accept(tcp_listen_fd, NULL, NULL);
			if (client >= 0) {
				if (tcp_source.fd >= 0) {
					close(tcp_source.fd);
				}
				tcp_source.fd = client;
				tcp_source.used = 0;
				event("STATE", "tcp client connected");
			}
		}
		if (!blocked && tcp_source.fd >= 0 && FD_ISSET(tcp_source.fd, &fds) && !read_source(&tcp_source)) {
			event("STATE", "tcp client closed");
			close(tcp_source.fd);
			tcp_source.fd = -1;
			tcp_source.used = 0;
		}
		if (!blocked && FD_ISSET(serial_fd, &fds)) {
			read_source(&serial_source);
		}
	}
	event("STATE", "azimuth=%.1f shutter=%d", heading(), (int)lround(serial_motion_update(&shutter)));
	event("CLOSE", "simulator");
	if (tcp_source.fd >= 0) {
		close(tcp_source.fd);
	}
	if (tcp_listen_fd >= 0) {
		close(tcp_listen_fd);
	}
	close(serial_fd);
	if (events) {
		fclose(events);
	}
	return 0;
}
