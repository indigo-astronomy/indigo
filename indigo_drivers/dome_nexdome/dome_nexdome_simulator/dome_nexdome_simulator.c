static command_source serial_source = { -1, "", 0, false, "serial" }, tcp_source = { -1, "", 0, false, "tcp" };
static char version[32] = "1.10", shutter_version[32] = "";
static double rotation_speed = 4, shutter_time = 20, shutter_latency = 0, wireless_delay = 1.1;
static double park_azimuth = 180, home_azimuth = 0, blocked_until;
