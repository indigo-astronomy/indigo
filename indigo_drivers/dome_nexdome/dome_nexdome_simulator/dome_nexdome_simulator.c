// Code is generated by AI

// Protocol (nexdome_protocol.txt and dome_nexdome_simulator.ino, NexDome
// firmware 1.10 by Gerry Rozema): a command is a letter with optional arguments
// terminated by CR or LF; a command of 20 or more characters is discarded and
// an unknown command is not answered. Replies end with CR LF except m, p and q
// which end with LF. Implemented commands: a (abort), b/f (shutter position),
// c (calibrate, only at home), d/e (open/close shutter, d refused with E while
// raining), g (goto 0..360), h (find home), i/j (home azimuth), k (voltages in
// hundredths of volt and cutoff), l/n (park azimuth), m (motion state 0 stopped,
// 1 goto, 2 finding home, 3 calibrating), o (heading error), p (raw position),
// q (heading with one decimal), r (hibernate timer), s (sync 0..<360, moves the
// home azimuth once home has been seen), t (steps per turn), u (shutter state
// and rain flag), v (version, with the shutter version and an extra empty line
// when known), w (reset wireless, the controller is blocked afterwards),
// x (wake shutter), y (reversed flag), z (at home 1, 0, -1 before home was seen).
// Simulator assumptions (undocumented): rotation and shutter move linearly with
// configurable rates, rotation takes the shortest way, the home sensor is 0.5
// degree wide, calibration turns one revolution and stops at home, abort stops
// the shutter and reports it open unless fully closed, the shutter reports its
// state change after a configurable wireless latency except that e reports
// closing at once (as the firmware does), rain closes an open shutter, and
// without a connected shutter u reports 0 and d/e are answered without motion.
//
// Test hooks (all optional, named by environment variables):
//   INDIGO_NEXDOME_EVENTS   event log: "<time> RX|TX|STATE|MOVE|FAULT|CONTROL|REJECT|OPEN|CLOSE <text>"
//   INDIGO_NEXDOME_FAULT    "<silent|error|reply|raw|partial|slow|close> <count> <argument|-> <command prefix|ANY>"
//                           (error answers E without executing, '_' in an argument is a space)
//   INDIGO_NEXDOME_CONTROL  lines "<azimuth|rotate|stall|shutter|shutterstate|connected|rain|volts|park|home|beenhome|version|shutterversion|latency|drop> <value>"
// With --tcp-port the same protocol is also served to one TCP client on
// 127.0.0.1 (0 selects a free port); the ready file then contains
// INDIGO_SIMULATOR_TCP_URL. The "drop" control closes that client connection.

