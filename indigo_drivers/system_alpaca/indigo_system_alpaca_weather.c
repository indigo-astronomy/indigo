// X_ALPACA_WEATHER_AVERAGE_PERIOD: the period is set and read back; after a failure the property shows the period of the device.
static void weather_average_period_handler(indigo_device *device) {
	char message[INDIGO_VALUE_SIZE] = { 0 };
	double value = 0;
	if (!system_alpaca_is_active(device)) {
		return;
	}
	alpaca_param params[] = { ALPACA_DOUBLE_PARAM("AveragePeriod", X_ALPACA_WEATHER_AVERAGE_PERIOD_ITEM->number.target) };
	alpaca_result result = system_alpaca_put(device, "averageperiod", params, 1, ALPACA_REPLAYABLE);
	if (result != ALPACA_OK) {
		weather_failure(device, result, "Setting the averaging period", message, sizeof(message));
	}
	if (!alpaca_is_transport_error(result)) {
		alpaca_result read_result = system_alpaca_get_double(device, "averageperiod", &value);
		if (read_result == ALPACA_OK) {
			WEATHER_DATA->average_period = value;
		} else if (*message == 0) {
			weather_failure(device, read_result, "Reading the averaging period", message, sizeof(message));
		}
	}
	X_ALPACA_WEATHER_AVERAGE_PERIOD_ITEM->number.value = X_ALPACA_WEATHER_AVERAGE_PERIOD_ITEM->number.target = WEATHER_DATA->average_period;
	weather_finish(device, X_ALPACA_WEATHER_AVERAGE_PERIOD_PROPERTY, message);
}

// X_ALPACA_WEATHER_REFRESH: Refresh, then everything is read again. A device without Refresh loses the property for the
// rest of the connection.
static void weather_refresh_handler(indigo_device *device) {
	char message[INDIGO_VALUE_SIZE] = { 0 };
	if (!system_alpaca_is_active(device)) {
		return;
	}
	if (!X_ALPACA_WEATHER_REFRESH_ITEM->sw.value) {
		// a request that switches the item off asks for nothing
		weather_finish(device, X_ALPACA_WEATHER_REFRESH_PROPERTY, NULL);
		return;
	}
	alpaca_result result = system_alpaca_put(device, "refresh", NULL, 0, ALPACA_REPLAYABLE);
	X_ALPACA_WEATHER_REFRESH_ITEM->sw.value = false;
	if (system_alpaca_not_implemented(result, 0)) {
		system_alpaca_set_unsupported(device, "refresh");
		indigo_delete_property(device, X_ALPACA_WEATHER_REFRESH_PROPERTY, "Refresh is not implemented by the device");
		X_ALPACA_WEATHER_REFRESH_PROPERTY->hidden = true;
		return;
	}
	if (result == ALPACA_OK) {
		weather_read(device, false, true, message, sizeof(message));
		weather_publish(device, message);
		weather_read_settings(device);
		*message = 0;
	} else {
		weather_failure(device, result, "Refresh", message, sizeof(message));
	}
	weather_finish(device, X_ALPACA_WEATHER_REFRESH_PROPERTY, message);
}

// Find out which sensors the device has and read everything once. Only a transport error fails the connection.
static bool weather_on_probe(indigo_device *device) {
	WEATHER_DATA->sensor_count = 0;
	WEATHER_DATA->has_average_period = WEATHER_DATA->has_age = WEATHER_DATA->alert = false;
	for (int i = 0; i < WEATHER_SENSOR_COUNT; i++) {
		alpaca_result result = system_alpaca_get_double(device, weather_sensors[i].member, WEATHER_DATA->values + i);
		if (alpaca_is_transport_error(result)) {
			return false;
		}
		WEATHER_DATA->supported[i] = !alpaca_is_unsupported(result);
		WEATHER_DATA->failed[i] = WEATHER_DATA->supported[i] && result != ALPACA_OK;
		WEATHER_DATA->descriptions[i][0] = 0;
		if (!WEATHER_DATA->supported[i]) {
			system_alpaca_set_unsupported(device, weather_sensors[i].member);
			continue;
		}
		if (result != ALPACA_OK) {
			WEATHER_DATA->values[i] = 0;
		}
		WEATHER_DATA->sensor_count++;
		alpaca_param params[] = { ALPACA_STRING_PARAM("SensorName", weather_sensors[i].member) };
		result = system_alpaca_check(device, alpaca_get_string(system_alpaca_channel(device), "sensordescription", params, 1, ALPACA_WAIT_STANDARD, WEATHER_DATA->descriptions[i], ALPACA_TEXT_SIZE));
		if (alpaca_is_transport_error(result)) {
			return false;
		}
		if (result != ALPACA_OK) {
			WEATHER_DATA->descriptions[i][0] = 0;
		}
	}
	alpaca_result result = system_alpaca_get_double(device, "averageperiod", &WEATHER_DATA->average_period);
	if (alpaca_is_transport_error(result)) {
		return false;
	}
	WEATHER_DATA->has_average_period = result == ALPACA_OK;
	if (WEATHER_DATA->sensor_count > 0) {
		result = weather_read_age(device, &WEATHER_DATA->age);
		if (alpaca_is_transport_error(result)) {
			return false;
		}
		WEATHER_DATA->has_age = result == ALPACA_OK;
	}
	return true;
}

// Set up the properties for the sensors the device has. The items of the missing ones are left out before anything is defined.
static bool weather_on_connect(indigo_device *device) {
	int count = 0;
	for (int i = 0; i < WEATHER_SENSOR_COUNT; i++) {
		const weather_sensor *sensor = weather_sensors + i;
		if (!WEATHER_DATA->supported[i]) {
			continue;
		}
		WEATHER_DATA->alert = WEATHER_DATA->alert || WEATHER_DATA->failed[i];
		WEATHER_DATA->items[i] = count;
		indigo_init_number_item(AUX_WEATHER_PROPERTY->items + count, sensor->item_name, sensor->label, sensor->min, sensor->max, 0, WEATHER_DATA->values[i]);
		INDIGO_COPY_VALUE(AUX_WEATHER_PROPERTY->items[count].number.format, sensor->format);
		count++;
		if (i == WEATHER_SKY_QUALITY) {
			indigo_init_number_item(AUX_WEATHER_PROPERTY->items + count, AUX_WEATHER_SKY_BORTLE_CLASS_ITEM_NAME, "Sky Bortle class", 1, 9, 0, indigo_aux_sky_bortle(WEATHER_DATA->values[i]));
			INDIGO_COPY_VALUE(AUX_WEATHER_PROPERTY->items[count].number.format, "%.1f");
			count++;
		}
	}
	AUX_WEATHER_PROPERTY->count = count;
	AUX_WEATHER_PROPERTY->hidden = count == 0;
	AUX_WEATHER_PROPERTY->state = WEATHER_DATA->alert ? INDIGO_ALERT_STATE : INDIGO_OK_STATE;
	count = 0;
	for (int i = 0; i < WEATHER_SENSOR_COUNT; i++) {
		if (WEATHER_DATA->supported[i]) {
			indigo_init_text_item_raw(X_ALPACA_WEATHER_SENSORS_PROPERTY->items + count++, weather_sensors[i].item_name, weather_sensors[i].label, WEATHER_DATA->descriptions[i]);
		}
	}
	X_ALPACA_WEATHER_SENSORS_PROPERTY->count = count;
	X_ALPACA_WEATHER_SENSORS_PROPERTY->hidden = count == 0;
	X_ALPACA_WEATHER_AVERAGE_PERIOD_ITEM->number.value = X_ALPACA_WEATHER_AVERAGE_PERIOD_ITEM->number.target = WEATHER_DATA->average_period;
	X_ALPACA_WEATHER_AVERAGE_PERIOD_PROPERTY->hidden = !WEATHER_DATA->has_average_period;
	X_ALPACA_WEATHER_AVERAGE_PERIOD_PROPERTY->state = INDIGO_OK_STATE;
	X_ALPACA_WEATHER_REFRESH_ITEM->sw.value = false;
	X_ALPACA_WEATHER_REFRESH_PROPERTY->hidden = count == 0;
	X_ALPACA_WEATHER_REFRESH_PROPERTY->state = INDIGO_OK_STATE;
	X_ALPACA_WEATHER_AGE_ITEM->number.value = WEATHER_DATA->age;
	X_ALPACA_WEATHER_AGE_PROPERTY->hidden = !WEATHER_DATA->has_age;
	X_ALPACA_WEATHER_AGE_PROPERTY->state = INDIGO_OK_STATE;
	WEATHER_DATA->tick = 0;
	indigo_define_property(device, AUX_WEATHER_PROPERTY, NULL);
	indigo_define_property(device, X_ALPACA_WEATHER_SENSORS_PROPERTY, NULL);
	indigo_define_property(device, X_ALPACA_WEATHER_AVERAGE_PERIOD_PROPERTY, NULL);
	indigo_define_property(device, X_ALPACA_WEATHER_REFRESH_PROPERTY, NULL);
	indigo_define_property(device, X_ALPACA_WEATHER_AGE_PROPERTY, NULL);
	return true;
}

static void weather_on_disconnect(indigo_device *device) {
	indigo_delete_property(device, AUX_WEATHER_PROPERTY, NULL);
	indigo_delete_property(device, X_ALPACA_WEATHER_SENSORS_PROPERTY, NULL);
	indigo_delete_property(device, X_ALPACA_WEATHER_AVERAGE_PERIOD_PROPERTY, NULL);
	indigo_delete_property(device, X_ALPACA_WEATHER_REFRESH_PROPERTY, NULL);
	indigo_delete_property(device, X_ALPACA_WEATHER_AGE_PROPERTY, NULL);
}

static void weather_on_poll(indigo_device *device) {
	char message[INDIGO_VALUE_SIZE] = { 0 };
	bool with_requests = ++WEATHER_DATA->tick % WEATHER_POLL_DIVIDER == 0;
	weather_read(device, true, with_requests, message, sizeof(message));
	weather_publish(device, message);
	if (with_requests) {
		weather_read_settings(device);
	}
}

