// Text of a failed request in the form system_alpaca_finish() uses, taken before a following request replaces the error of the channel.
static void weather_failure(indigo_device *device, alpaca_result result, const char *action, char *message, size_t size) {
	char reason[INDIGO_VALUE_SIZE];
	system_alpaca_reason(device, result, reason, sizeof(reason));
	snprintf(message, size, "%s failed: %s%s%s%s", action, alpaca_result_text(result), *reason ? " (" : "", reason, *reason ? ")" : "");
}

// Handler queue: end a request. The state is set under the lock, the property is published without it.
static void weather_finish(indigo_device *device, indigo_property *property, const char *message) {
	system_alpaca_set_state(device, property, message != NULL && *message ? INDIGO_ALERT_STATE : INDIGO_OK_STATE);
	if (message != NULL && *message) {
		indigo_update_property(device, property, "%s", message);
	} else {
		indigo_update_property(device, property, NULL);
	}
}

// TimeSinceLastUpdate of the sensor that was updated last (an empty SensorName).
static alpaca_result weather_read_age(indigo_device *device, double *age) {
	alpaca_param params[] = { ALPACA_STRING_PARAM("SensorName", "") };
	return system_alpaca_check(device, alpaca_get_double(system_alpaca_channel(device), "timesincelastupdate", params, 1, ALPACA_WAIT_STANDARD, age));
}

// Read the sensors: from the devicestate snapshot of the running poll tick if from_state is set, and with a request for every
// sensor that is not there if with_requests is set. The text of the first new failure is left in message.
static void weather_read(indigo_device *device, bool from_state, bool with_requests, char *message, size_t size) {
	alpaca_result result = ALPACA_OK;
	for (int i = 0; i < WEATHER_SENSOR_COUNT && !alpaca_is_transport_error(result); i++) {
		double value = 0;
		if (!WEATHER_DATA->supported[i]) {
			continue;
		}
		if (from_state && alpaca_state_double(&PRIVATE_DATA->state, weather_sensors[i].member, &value)) {
			WEATHER_DATA->values[i] = value;
			WEATHER_DATA->failed[i] = false;
		} else if (with_requests) {
			result = system_alpaca_get_double(device, weather_sensors[i].member, &value);
			if (result == ALPACA_OK) {
				WEATHER_DATA->values[i] = value;
			} else if (!WEATHER_DATA->failed[i] && *message == 0) {
				char action[64];
				snprintf(action, sizeof(action), "Reading %s", weather_sensors[i].member);
				weather_failure(device, result, action, message, size);
			}
			WEATHER_DATA->failed[i] = result != ALPACA_OK;
		}
	}
}

// Copy the values of the sensors to AUX_WEATHER and publish it if a value or the state changed.
static void weather_publish(indigo_device *device, const char *message) {
	bool changed = false, alert = false;
	for (int i = 0; i < WEATHER_SENSOR_COUNT; i++) {
		if (WEATHER_DATA->supported[i]) {
			indigo_item *item = AUX_WEATHER_PROPERTY->items + WEATHER_DATA->items[i];
			changed = changed || item->number.value != WEATHER_DATA->values[i];
			item->number.value = WEATHER_DATA->values[i];
			alert = alert || WEATHER_DATA->failed[i];
			if (i == WEATHER_SKY_QUALITY) {
				item[1].number.value = indigo_aux_sky_bortle(WEATHER_DATA->values[i]);
			}
		}
	}
	if (alert != WEATHER_DATA->alert) {
		WEATHER_DATA->alert = alert;
		AUX_WEATHER_PROPERTY->state = alert ? INDIGO_ALERT_STATE : INDIGO_OK_STATE;
		changed = true;
	}
	if (changed && alert && message != NULL && *message) {
		indigo_update_property(device, AUX_WEATHER_PROPERTY, "%s", message);
	} else if (changed) {
		indigo_update_property(device, AUX_WEATHER_PROPERTY, NULL);
	}
}

// Read and publish what is polled with requests of its own besides the sensors: TimeSinceLastUpdate and AveragePeriod.
static void weather_read_settings(indigo_device *device) {
	double value = 0;
	if (WEATHER_DATA->has_age && system_alpaca_channel(device) != NULL) {
		alpaca_result result = weather_read_age(device, &value);
		if (result == ALPACA_OK) {
			X_ALPACA_WEATHER_AGE_ITEM->number.value = WEATHER_DATA->age = value;
		}
		X_ALPACA_WEATHER_AGE_PROPERTY->state = system_alpaca_property_state(result);
		indigo_update_property(device, X_ALPACA_WEATHER_AGE_PROPERTY, NULL);
	}
	if (WEATHER_DATA->has_average_period && system_alpaca_channel(device) != NULL) {
		if (system_alpaca_get_double(device, "averageperiod", &value) == ALPACA_OK && value != WEATHER_DATA->average_period) {
			// a period that was requested since is kept: the property is BUSY then, and its handler reads the period back
			system_alpaca_lock(device);
			bool busy = X_ALPACA_WEATHER_AVERAGE_PERIOD_PROPERTY->state == INDIGO_BUSY_STATE;
			if (!busy) {
				X_ALPACA_WEATHER_AVERAGE_PERIOD_ITEM->number.value = X_ALPACA_WEATHER_AVERAGE_PERIOD_ITEM->number.target = WEATHER_DATA->average_period = value;
				X_ALPACA_WEATHER_AVERAGE_PERIOD_PROPERTY->state = INDIGO_OK_STATE;
			}
			system_alpaca_unlock(device);
			if (!busy) {
				indigo_update_property(device, X_ALPACA_WEATHER_AVERAGE_PERIOD_PROPERTY, NULL);
			}
		}
	}
}

