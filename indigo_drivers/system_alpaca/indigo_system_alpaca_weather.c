/** INDIGO ASCOM Alpaca client driver, ObservingConditions device class: Alpaca ObservingConditions as an INDIGO weather device
 \file indigo_system_alpaca_weather.c

 Every sensor of an Alpaca ObservingConditions device is optional. The sensors are read once when the device is connected; a sensor
 that answers "not implemented" gets no item, and without any sensor AUX_WEATHER is not defined at all. The Alpaca units are the
 units INDIGO uses, so no value is converted:

   Temperature -> AUX_WEATHER.TEMPERATURE [C]              WindDirection -> AUX_WEATHER.WIND_DIRECTION [degrees, as reported]
   Humidity -> AUX_WEATHER.HUMIDITY [%]                    RainRate -> AUX_WEATHER.X_RAIN_RATE [mm/h]
   DewPoint -> AUX_WEATHER.DEWPOINT [C]                    CloudCover -> AUX_WEATHER.X_CLOUD_COVER [%]
   Pressure -> AUX_WEATHER.ATMOSPHERIC_PRESSURE [hPa]      SkyTemperature -> AUX_WEATHER.SKY_TEMPERATURE [C]
   WindSpeed -> AUX_WEATHER.WIND_SPEED [m/s]               SkyQuality -> AUX_WEATHER.SKY_BRIGHTNESS [mag/arcsec2]
   WindGust -> AUX_WEATHER.X_WIND_GUST [m/s]               SkyBrightness -> AUX_WEATHER.X_SKY_ILLUMINANCE [lux]
   StarFWHM -> AUX_WEATHER.X_STAR_FWHM [arcsec]

 The INDIGO item SKY_BRIGHTNESS is a sky quality in mag/arcsec2, which is the Alpaca SkyQuality; the Alpaca SkyBrightness is an
 illuminance in lux and has no standard item. AUX_WEATHER.SKY_BORTLE_CLASS is derived from SkyQuality like in the SQM drivers.
 The standard item RAIN is a raw dampness, not a rain rate, so it is not used.

 X_ALPACA_WEATHER_SENSORS holds SensorDescription of every sensor, X_ALPACA_WEATHER_AVERAGE_PERIOD is AveragePeriod (hours),
 X_ALPACA_WEATHER_REFRESH calls Refresh and X_ALPACA_WEATHER_AGE is TimeSinceLastUpdate of the most recently updated sensor.

 Polling: on a Platform 7 device the values come with the devicestate snapshot of every tick and cost no request. Everything
 that needs a request of its own (sensors that are not in the snapshot, all sensors of an older device, AveragePeriod and
 TimeSinceLastUpdate) is read on every WEATHER_POLL_DIVIDER-th tick only: weather does not change within a second.

 Threads: change_property runs on a bus thread, everything else on the handler queue of the device. A request is accepted
 with system_alpaca_accept() and the poll publishes the averaging period of the device under the lock of the device, so a poll
 tick never replaces a period that was just requested with the one the device still has.
 */

