/** Descriptor of a device class module.
 */
typedef struct {
	/** Alpaca DeviceType the class is a proxy of, compared without regard to case, e.g. "Focuser". NULL for a class that is only used for secondary devices. */
	const char *device_type;
	/** Suffix of the name of a secondary device, e.g. " (guider)". NULL for the class of a primary device. */
	const char *name_suffix;
	/** First InterfaceVersion of the device type that has the Platform 7 members connect, disconnect, connecting and devicestate. Not used for secondary devices. */
	int platform7_version;
	/** Size of the class data in bytes, 0 if the class has none. */
	size_t data_size;
	/** Device callbacks, see the description at the top of this file. */
	indigo_result (*attach)(indigo_device *device);
	indigo_result (*enumerate_properties)(indigo_device *device, indigo_client *client, indigo_property *property);
	indigo_result (*change_property)(indigo_device *device, indigo_client *client, indigo_property *property);
	indigo_result (*detach)(indigo_device *device);
	/** change_property of the INDIGO base class, e.g. indigo_focuser_change_property. The core calls it to finish every change of CONNECTION. */
	indigo_result (*base_change_property)(indigo_device *device, indigo_client *client, indigo_property *property);
	/** Hooks, any of them may be NULL. */
	bool (*on_probe)(indigo_device *device);
	bool (*on_connect)(indigo_device *device);
	void (*on_disconnect)(indigo_device *device);
	void (*on_poll)(indigo_device *device);
} alpaca_class;

/** One entry of the capability cache: the result of reading a member once per connection.
 */
typedef struct {
	char member[ALPACA_MEMBER_SIZE];
	bool supported;			///< false if the device answered "not implemented" or HTTP 400
	bool value;					///< value of a boolean capability, false if it is not supported
} alpaca_capability;

/** Options of system_alpaca_accept().
 */
#define ALPACA_ACCEPT_VALUES							0x00		///< copy the values of the request (INDIGO_COPY_VALUES_PROCESS_CHANGE)
#define ALPACA_ACCEPT_TARGETS							0x01		///< copy the targets of the request (INDIGO_COPY_TARGETS_PROCESS_CHANGE)
#define ALPACA_ACCEPT_ANYTIME							0x02		///< accept the request while the property is BUSY as well
#define ALPACA_ACCEPT_URGENT							0x04		///< run the handler before the other handlers of the device (an abort)

/** Condition under which system_alpaca_accept() refuses a request: returns the message of the refusal, NULL to accept it.
 Called on the bus thread with the lock of the device held, so it may only read properties and class data.
 */
typedef const char *(*alpaca_refusal)(indigo_device *device);

/** State of one long operation of a class, see system_alpaca_operation_start().
 */
typedef struct {
	bool active;
	double deadline;
} alpaca_operation;

/** Private data of one Alpaca device. Class modules read the members marked "read only" and never write the others.
 */
typedef struct {
	// identity, set before attach (read only)
	alpaca_server *server;										///< record of the server the device belongs to
	const alpaca_class *device_class;					///< class of the primary device
	char device_type[ALPACA_TYPE_SIZE];				///< DeviceType as reported by the server, e.g. "Focuser"
	int device_number;												///< DeviceNumber
	char device_name[ALPACA_TEXT_SIZE];				///< DeviceName as reported by the server
	char unique_id[ALPACA_TEXT_SIZE];					///< UniqueID
	indigo_device *device;										///< primary INDIGO device
	indigo_device *secondary;									///< secondary INDIGO device (guider), NULL if there is none
	const alpaca_class *secondary_class;			///< class of the secondary device
	void *class_data;													///< class data of the primary device, use CLASS_DATA
	void *secondary_data;											///< class data of the secondary device, use CLASS_DATA
	// connection (read only)
	int interface_version;										///< InterfaceVersion, read when the device is attached and again on every connect
	bool platform7;														///< the device has connect, disconnect, connecting and devicestate
	// owned by the core
	pthread_mutex_t mutex;										///< lock of the device, use system_alpaca_lock()
	alpaca_channel *channel;									///< connection used for all ordinary requests, use system_alpaca_channel()
	alpaca_channel *transfer;									///< connection for long transfers, use system_alpaca_transfer_channel()
	int count;																///< logical devices (primary, secondary) that hold the connection to the Alpaca device open; guarded by mutex
	bool session;															///< on_connect of the primary class succeeded and on_disconnect was not called yet; guarded by mutex, use system_alpaca_is_active()
	bool secondary_session;										///< the same for the secondary class
	bool offline;															///< the transport is lost: requests fail at once until the next connect
	bool detaching;														///< the device is being detached, no handler may start or queue anything; written with the lock of the device of the framework held, which every handler and finalizer runs with
	int state_failures;												///< consecutive poll ticks whose devicestate got an answer that is no snapshot
	int transport_errors;											///< consecutive requests that failed with a transport error
	bool not_connected;												///< the device answered NotConnected
	double connect_deadline;									///< end of the time a Platform 7 connect may take
	int operations;														///< running operations, see system_alpaca_operation_start()
	bool polling;															///< a devicestate snapshot is being served to on_poll
	bool has_device_state;										///< devicestate is usable on this device
	alpaca_device_state state;								///< devicestate snapshot of the current poll tick
	int capability_count;
	alpaca_capability capabilities[ALPACA_MAX_CAPABILITIES];
} alpaca_private_data;

#pragma mark - lifecycle helpers, called from the device callbacks of a class

/** Common part of attach. Call it after the attach of the base class and after the properties of the class are created.
 It fills INFO, hides the properties that make no sense for a proxy and logs the attach. Returns INDIGO_OK.
 */
extern indigo_result system_alpaca_attach(indigo_device *device);

/** Common part of change_property. Call it first; if it returns true the request was a change of CONNECTION and is handled.
 The connection is established on the handler queue of the device: InterfaceVersion is read, the device is connected
 (Platform 7: PUT connect and a finalizer on "connecting" bounded by the establish timeout; older devices: PUT connected),
 INFO is filled, on_probe and on_connect are called, polling starts. A disconnect calls on_disconnect, detaches the
 secondary device and sends disconnect / Connected=False to the Alpaca device.
 */
extern bool system_alpaca_change_property(indigo_device *device, indigo_property *property);

/** Common part of detach. Call it first. A device that is still connected is disconnected here.
 */
extern void system_alpaca_detach(indigo_device *device);

/** Create and attach a secondary device of the given class for the primary device, e.g. system_alpaca_attach_secondary(device, &system_alpaca_guider_class)
 from on_connect of a camera or a telescope that can pulse guide. The secondary device is named "<primary name><name_suffix>", shares the
 private data and the handler queue of the primary one and exists while the primary device is connected: the core detaches and releases it
 on disconnect. Returns false if the device already has a secondary device or the attach failed.
 */
extern bool system_alpaca_attach_secondary(indigo_device *device, const alpaca_class *secondary_class);

#pragma mark - threads

/** True while the session of the device (the primary or the secondary one) is open: from the end of a successful on_connect until
 on_disconnect is called. Every handler and finalizer starts with "if (!system_alpaca_is_active(device)) return;", because it may
 have been queued just before a disconnect, and enumerate_properties uses it to tell whether the X_ properties of the class are defined.
 Unlike IS_CONNECTED it reads nothing a bus thread writes (INDIGO_PROCESS_CONNECT changes CONNECTION on the bus thread), and it may be
 called from any thread.
 */
extern bool system_alpaca_is_active(indigo_device *device);

/** Read the state of the primary device now and serve it to its on_poll, on its handler queue (the queue the caller runs on, for the
 secondary device too). The regular ticks go on as before, and a lost connection is noted and left to them. For an operation whose
 end changes what the primary device polls, so that the state is published before the operation is reported as finished (the guider
 reads the coordinates of the telescope after a pulse).
 */
extern void system_alpaca_poll_now(indigo_device *device);

/** Lock of the device, shared by the primary and the secondary device. It guards what a bus thread (change_property) and the handler
 queue of the device both touch: the state and the requested values of the properties a client can change, and the class data a
 bus callback reads or writes. It is recursive. It is never held across a request to the device or a call of the bus
 (indigo_update_property(), indigo_define_property(), indigo_delete_property()...): set the properties under the lock and publish
 them after it is released.
 */
extern void system_alpaca_lock(indigo_device *device);
extern void system_alpaca_unlock(indigo_device *device);

/** change_property (bus thread): the steps of INDIGO_COPY_VALUES_PROCESS_CHANGE / INDIGO_COPY_TARGETS_PROCESS_CHANGE with the BUSY
 guard, the copy of the requested values and the BUSY state under the lock of the device, so that a poll tick that publishes the
 state of the device under the same lock never replaces a request that was just accepted.
 A request for a property that is BUSY is dropped unless ALPACA_ACCEPT_ANYTIME is given. Otherwise refusal (may be NULL) is asked:
 if it returns a message the request is rejected with it (system_alpaca_reject(): the property goes to ALERT, a BUSY one only gets a BUSY message). An accepted request
 is published as BUSY and handler (may be NULL) is queued on the handler queue of the device. Returns true if the request was accepted.
 */
extern bool system_alpaca_accept(indigo_device *device, indigo_property *property, indigo_property *request, int options, alpaca_refusal refusal, indigo_timer_callback handler);

/** change_property (bus thread): refuse a request with a message, like indigo_reject_change(), but with the state written under the lock of
 the device. A property that is BUSY because an earlier request waits for its handler is not changed; the refusal is only a BUSY message.
 */
extern void system_alpaca_reject(indigo_device *device, indigo_property *property, const char *message);

/** Handler queue: set the state of a property a client can change, under the lock of the device, without publishing it.
 */
extern void system_alpaca_set_state(indigo_device *device, indigo_property *property, indigo_property_state state);

/** Handler queue: system_alpaca_set_state() and indigo_update_property() with an optional message (format may be NULL).
 It takes the place of INDIGO_UPDATE_PROPERTY_STATE.
 */
extern void system_alpaca_update(indigo_device *device, indigo_property *property, indigo_property_state state, const char *format, ...);

#pragma mark - requests

/** Channel for the ordinary requests to the Alpaca device, for direct calls of the transport layer. NULL while the transport is lost;
 the transport layer answers ALPACA_UNREACHABLE to a NULL channel, so the result can be used without a check.
 */
extern alpaca_channel *system_alpaca_channel(indigo_device *device);

/** Second channel to the same Alpaca device with its own socket and buffers, for long transfers (imagearray) that must not delay the
 ordinary requests. It is created by the first call with the given limit of the reply body and closed on disconnect. NULL while the transport is lost.
 */
extern alpaca_channel *system_alpaca_transfer_channel(indigo_device *device, size_t max_body_size);

/** Record the result of a request made directly through the transport layer and return it unchanged. Transport errors are counted
 (two in a row mark the transport as lost; the next poll tick then takes the device to the disconnected state) and NotConnected is noted.
 */
extern alpaca_result system_alpaca_check(indigo_device *device, alpaca_result result);

/** GET a member without parameters with the standard timeout. The result is already passed through system_alpaca_check().
 */
extern alpaca_result system_alpaca_get_bool(indigo_device *device, const char *member, bool *value);
extern alpaca_result system_alpaca_get_int(indigo_device *device, const char *member, int *value);
extern alpaca_result system_alpaca_get_double(indigo_device *device, const char *member, double *value);
extern alpaca_result system_alpaca_get_string(indigo_device *device, const char *member, char *value, size_t size);

/** PUT a method or a setter, see alpaca_put(). The result is already passed through system_alpaca_check().
 */
extern alpaca_result system_alpaca_put(indigo_device *device, const char *member, const alpaca_param *params, int count, int options);

/** Text of the failure of the last request on the ordinary channel: the ErrorMessage of the device or a description of the transport failure.
 */
extern const char *system_alpaca_error(indigo_device *device);

/** Timeout of the long requests of the server of the device in seconds (X_ALPACA_TIMEOUTS.LONG of the bridge device). A class derives
 the time an operation may take from it.
 */
extern double system_alpaca_long_timeout(indigo_device *device);

/** Copy the reason of the failure of the request that was just made, as system_alpaca_finish() reports it: the ErrorMessage of the
 device or the description of the failure, empty for ALPACA_OK, ALPACA_FAILED and a transport error (the name of the result says it all).
 Take it right after the request whenever another request (a read back of IsMoving, Slewing, a position...) follows before the
 property is finished, because the channel only keeps the text of its last request; pass it to system_alpaca_finish_with().
 */
extern void system_alpaca_reason(indigo_device *device, alpaca_result result, char *reason, size_t size);

/** The device does not implement the member: it answered NotImplemented (ALPACA_UNSUPPORTED), or HTTP 400 (ALPACA_REJECTED) to a
 request without parameters. HTTP 400 to a request with parameters may as well mean that the server did not like a value, so it
 is an ordinary failure then. Use it for the result of a method or a setter; alpaca_is_unsupported() is for probing a member with a GET.
 */
extern bool system_alpaca_not_implemented(alpaca_result result, int parameter_count);

#pragma mark - state

/** Read one value of the operational state by its ASCOM name, e.g. system_alpaca_state_bool(device, "IsMoving", &moving).
 Inside on_poll the value comes from the devicestate snapshot the core read for this tick (Platform 7). If the snapshot has no such
 entry, on older devices and outside on_poll the member is read with a GET of its own. A member the device does not implement is
 remembered in the capability cache and answered with ALPACA_UNSUPPORTED without a request from then on.
 */
extern alpaca_result system_alpaca_state_bool(indigo_device *device, const char *name, bool *value);
extern alpaca_result system_alpaca_state_int(indigo_device *device, const char *name, int *value);
extern alpaca_result system_alpaca_state_double(indigo_device *device, const char *name, double *value);
extern alpaca_result system_alpaca_state_string(indigo_device *device, const char *name, char *value, size_t size);

#pragma mark - capabilities

/** Read a boolean capability (canpark, absolute, tempcompavailable...) once per connection. A member the device does not implement
 gives false and ALPACA_OK, and is cached like a real answer. Any other failure is returned and not cached.
 */
extern alpaca_result system_alpaca_probe_bool(indigo_device *device, const char *member, bool *value);

/** Find out once per connection whether the device implements an optional member that has no Can* flag (temperature, position of a
 relative focuser, a weather sensor...). *supported is false if the device answers "not implemented" (ErrorNumber 0x400 or HTTP 400)
 and true for a value and for any other ErrorNumber of the device. When there is no usable answer (a transport error,
 ALPACA_PROTOCOL_ERROR, ALPACA_SERVER_ERROR) that result is returned and nothing is cached.
 */
extern alpaca_result system_alpaca_probe_member(indigo_device *device, const char *member, bool *supported);

/** Cached value of a boolean capability; false if it was not probed, is not supported or is false.
 */
extern bool system_alpaca_can(indigo_device *device, const char *member);

/** False if the member is known not to be implemented by the device, true otherwise.
 */
extern bool system_alpaca_supported(indigo_device *device, const char *member);

/** Remember that the device does not implement a member, e.g. after a PUT answered with ALPACA_UNSUPPORTED.
 */
extern void system_alpaca_set_unsupported(indigo_device *device, const char *member);

#pragma mark - operations and property states

/** Start watching a long operation: remember that it has to end within timeout seconds, switch the polling of the device to the
 faster rhythm (the next tick comes one active interval from now) and schedule the finalizer on the handler queue of the device.
 Like all helpers it is called from a handler, a finalizer or a hook of the device, never from a bus callback.
 */
extern void system_alpaca_operation_start(indigo_device *device, alpaca_operation *operation, double timeout, indigo_timer_callback finalizer);

/** Called by a finalizer that found the operation still running: schedule the finalizer again and return true, or return false if the
 time of the operation is over (the caller then ends the operation and reports a timeout).
 */
extern bool system_alpaca_operation_continue(indigo_device *device, alpaca_operation *operation, indigo_timer_callback finalizer);

/** Stop watching an operation; the polling returns to the idle rhythm when no operation is left. Safe to call for an operation that
 is not active. The core cancels the pending finalizers on disconnect; on_disconnect calls this for the operations of the class.
 */
extern void system_alpaca_operation_end(indigo_device *device, alpaca_operation *operation);

/** Property state for a result: INDIGO_OK_STATE for ALPACA_OK, INDIGO_ALERT_STATE for everything else.
 */
extern indigo_property_state system_alpaca_property_state(alpaca_result result);

/** Finish a request of a client: set the state of the property from the result (under the lock of the device) and publish it, on
 failure with the message "<action> failed: <result> (<reason>)" where the reason is the one of the last request on the ordinary
 channel. action may be NULL. If another request was made since the one that failed, use system_alpaca_finish_with().
 */
extern void system_alpaca_finish(indigo_device *device, indigo_property *property, alpaca_result result, const char *action);

/** system_alpaca_finish() with the reason taken by system_alpaca_reason() right after the request that failed.
 reason may be NULL, then it is taken from the last request like in system_alpaca_finish().
 */
extern void system_alpaca_finish_with(indigo_device *device, indigo_property *property, alpaca_result result, const char *action, const char *reason);

/** Publish a property whose state the caller has set already (under the lock, together with its other properties), on failure with
 the message of system_alpaca_finish_with(). reason may be NULL.
 */
extern void system_alpaca_report(indigo_device *device, indigo_property *property, alpaca_result result, const char *action, const char *reason);

/** Poll interval in seconds: the idle one, or the one used while an operation runs (X_ALPACA_POLLING of the bridge device).
 */
extern double system_alpaca_poll_interval(bool active);

