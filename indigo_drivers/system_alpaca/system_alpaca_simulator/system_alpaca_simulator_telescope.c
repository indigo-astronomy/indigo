static void telescope_put_sideofpier(alpaca_device *device, alpaca_request *request) {
	telescope_state *state = device->state;
	int side = 0;
	if (!alpaca_param_int(request, "SideOfPier", &side) || !telescope_ready(device, request, state->can_set_pier_side, TRACKING_ANY)) {
		return;
	}
	if (side != 0 && side != 1) {
		alpaca_reply_error(request, ALPACA_ERROR_INVALID_VALUE, "SideOfPier %d is not 0 or 1", side);
		return;
	}
	bool flip = side != telescope_side_of_pier(state, state->right_ascension.position);
	if (flip != state->pier_flip || state->slew_active) {
		telescope_stop(state);
		state->pulse_until[0] = state->pulse_until[1] = 0;
		state->at_home = false;
		state->flip_target = flip;
		state->goal = GOAL_FLIP;
		state->slew_active = true;
		state->slew_until = alpaca_now() + state->flip_time;
		alpaca_event("MOVE", "telescope/%d flip side=%d duration=%.3f", device->number, side, state->flip_time);
		telescope_update(device);
	}
	alpaca_reply_void(request);
}

