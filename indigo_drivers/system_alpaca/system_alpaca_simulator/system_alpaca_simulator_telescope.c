// The rate setters differ only in the capability that guards them.
static void telescope_put_rate(alpaca_device *device, alpaca_request *request) {
	telescope_state *state = device->state;
	size_t offset = request->member->offset;
	bool capability = offset == offsetof(telescope_state, declination_rate) ? state->can_set_declination_rate : offset == offsetof(telescope_state, right_ascension_rate) ? state->can_set_right_ascension_rate : state->can_set_guide_rates;
	bool offset_rate = offset == offsetof(telescope_state, declination_rate) || offset == offsetof(telescope_state, right_ascension_rate);
	double rate = 0;
	if (!alpaca_param_double(request, request->member->name, &rate) || !telescope_can(request, capability)) {
		return;
	}
	if (offset_rate && state->tracking_rate != 0) {
		alpaca_reply_error(request, ALPACA_ERROR_INVALID_OPERATION, "%s needs TrackingRate to be driveSidereal", request->member->name);
		return;
	}
	if (!offset_rate && (rate <= 0 || rate > 1)) {
		alpaca_reply_error(request, ALPACA_ERROR_INVALID_VALUE, "%s %g is out of range", request->member->name, rate);
		return;
	}
	*(double *)((char *)state + offset) = rate;
	if (!offset_rate && state->linked_guide_rates) {
		state->guide_rate_declination = state->guide_rate_right_ascension = rate;
	}
	alpaca_reply_void(request);
}

