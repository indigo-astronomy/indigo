static void telescope_update(alpaca_device *device) {
	telescope_state *state = device->state;
	double now = alpaca_now();
	double elapsed = now - state->last_update;
	alpaca_motion_update(&state->right_ascension);
	alpaca_motion_update(&state->declination);
	if (!state->right_ascension.moving && !state->declination.moving && elapsed > 0) {
		double right_ascension = state->right_ascension.position;
		double declination = state->declination.position;
		bool offsets = state->tracking && !state->at_park && state->tracking_rate == 0;
		if (state->axis_rate[0] != 0) {
			right_ascension += elapsed * SIDEREAL_RATIO / 3600 + (state->sky_axes ? 1 : -1) * state->axis_rate[0] * elapsed / 15;
		} else if (!state->tracking) {
			right_ascension += elapsed * SIDEREAL_RATIO / 3600;
		} else if (offsets) {
			right_ascension += state->right_ascension_rate * elapsed * SIDEREAL_RATIO / 3600;
		} else {
			right_ascension += (telescope_drive_rates[0] - telescope_drive_rates[state->tracking_rate]) / 15 * elapsed / 3600;
		}
		if (state->axis_rate[1] != 0) {
			if (state->sky_axes) {
				declination -= state->axis_rate[1] * elapsed;
			} else {
				declination += ((telescope_side_of_pier(state, state->right_ascension.position) ^ (state->pier_flip ? 1 : 0)) ? -1 : 1) * state->axis_rate[1] * elapsed;
			}
		} else if (offsets) {
			declination += state->declination_rate * elapsed / 3600;
		}
		for (int axis = 0; axis < 2; axis++) {
			double active = fmin(now, state->pulse_until[axis]) - state->last_update;
			if (active > 0 && axis == 0) {
				right_ascension += state->pulse_rate[axis] * active / 15;
			} else if (active > 0) {
				declination += state->pulse_rate[axis] * active;
			}
		}
		alpaca_motion_set(&state->right_ascension, telescope_wrap(right_ascension, 24));
		alpaca_motion_set(&state->declination, fmax(-90, fmin(90, declination)));
	}
	if (state->slew_active && alpaca_reached(state->slew_until)) {
		state->slew_active = false;
		state->slew_ended = state->slew_until;
		switch (state->goal) {
			case GOAL_PARK:
				state->at_park = true;
				state->slewing_until = state->slew_until + state->late_slewing;
				state->tracking = false;
				alpaca_motion_set(&state->right_ascension, telescope_wrap(telescope_sidereal_time(state) - state->park_hour_angle, 24));
				state->pier_flip = false;
				break;
			case GOAL_HOME:
				state->at_home = true;
				state->slewing_until = state->slew_until + state->late_slewing;
				alpaca_motion_set(&state->right_ascension, telescope_wrap(telescope_sidereal_time(state) - state->home_hour_angle, 24));
				state->pier_flip = false;
				break;
			case GOAL_UNPARK:
				state->at_park = false;
				break;
			case GOAL_FLIP:
				state->pier_flip = state->flip_target;
				break;
			default:
				state->pier_flip = false;
				break;
		}
		state->goal = GOAL_NONE;
		alpaca_event("STATE", "telescope/%d slew done ra=%.6f dec=%.6f at_park=%d at_home=%d", device->number, state->right_ascension.position, state->declination.position, state->at_park, state->at_home);
	}
	if (state->pending_goal != GOAL_NONE && alpaca_reached(state->pending_until)) {
		int goal = state->pending_goal;
		state->pending_goal = GOAL_NONE;
		state->last_update = now;
		alpaca_event("STATE", "telescope/%d delayed start goal=%d", device->number, goal);
		if (goal == GOAL_PARK) {
			telescope_start_slew(device, telescope_wrap(telescope_sidereal_time(state) - state->park_hour_angle, 24), state->park_declination, GOAL_PARK, false);
		} else {
			telescope_start_slew(device, telescope_wrap(telescope_sidereal_time(state) - state->home_hour_angle, 24), state->home_declination, GOAL_HOME, false);
		}
		return;
	}
	state->slewing = telescope_slewing(state);
	state->is_pulse_guiding = !alpaca_reached(state->pulse_until[0]) || !alpaca_reached(state->pulse_until[1]);
	state->last_update = now;
}

