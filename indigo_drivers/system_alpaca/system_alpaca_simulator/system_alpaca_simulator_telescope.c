// The conditions every method that moves the mount has to meet; answers the error itself.
static bool telescope_ready(alpaca_device *device, alpaca_request *request, bool capability, int tracking) {
	telescope_state *state = device->state;
	if (!telescope_can(request, capability)) {
		return false;
	}
	if (state->at_park) {
		alpaca_reply_error(request, ALPACA_ERROR_INVALID_WHILE_PARKED, "%s is not allowed while the telescope is parked", request->member->name);
		return false;
	}
	if ((tracking == TRACKING_ON && !state->tracking) || (tracking == TRACKING_OFF && state->tracking)) {
		alpaca_reply_error(request, ALPACA_ERROR_INVALID_OPERATION, "%s needs Tracking to be %s", request->member->name, tracking == TRACKING_ON ? "true" : "false");
		return false;
	}
	return true;
}

