static void camera_put_startexposure(alpaca_device *device, alpaca_request *request) {
	camera_state *state = device->state;
	double duration = 0;
	bool light = false;
	if (!alpaca_param_double(request, "Duration", &duration) || !alpaca_param_bool(request, "Light", &light)) {
		return;
	}
	if (state->camera_state != CAMERA_IDLE) {
		alpaca_reply_error(request, ALPACA_ERROR_INVALID_OPERATION, "An exposure is already in progress");
		return;
	}
	if (duration < 0 || duration > state->exposure_max || (light && duration < state->exposure_min)) {
		alpaca_reply_error(request, ALPACA_ERROR_INVALID_VALUE, "Duration %g is out of range %g..%g", duration, state->exposure_min, state->exposure_max);
		return;
	}
	if (state->num_x < 1 || state->start_x < 0 || state->start_x + state->num_x > state->camera_x_size / state->bin_x) {
		alpaca_reply_error(request, ALPACA_ERROR_INVALID_VALUE, "StartX %d and NumX %d do not fit %d binned pixels", state->start_x, state->num_x, state->camera_x_size / state->bin_x);
		return;
	}
	if (state->num_y < 1 || state->start_y < 0 || state->start_y + state->num_y > state->camera_y_size / state->bin_y) {
		alpaca_reply_error(request, ALPACA_ERROR_INVALID_VALUE, "StartY %d and NumY %d do not fit %d binned pixels", state->start_y, state->num_y, state->camera_y_size / state->bin_y);
		return;
	}
	alpaca_format_utc(alpaca_utc(), state->last_exposure_start_time, sizeof(state->last_exposure_start_time));
	state->last_exposure_start_time[23] = '\0';
	state->image_ready = false;
	state->percent_completed = 0;
	state->exposure_start = alpaca_now();
	state->exposure_duration = duration;
	state->frame_light = light;
	state->frame_start_x = state->start_x;
	state->frame_start_y = state->start_y;
	state->frame_num_x = state->num_x;
	state->frame_num_y = state->num_y;
	state->frame_bin_x = state->bin_x;
	state->frame_bin_y = state->bin_y;
	state->camera_state = CAMERA_EXPOSING;
	alpaca_event("STATE", "camera/%d exposure duration=%.6f light=%d frame=%d,%d %dx%d bin=%dx%d", device->number, duration, light, state->start_x, state->start_y, state->num_x, state->num_y, state->bin_x, state->bin_y);
	if (duration == 0) {
		camera_update(device);
	}
	alpaca_reply_void(request);
}

