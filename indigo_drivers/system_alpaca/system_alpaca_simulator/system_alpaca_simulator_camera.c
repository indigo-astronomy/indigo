// SensorType: 0 Monochrome, 1 Color (three planes), 2 RGGB and higher: a colour
// filter array on a single plane.
//
// Test pattern. The image is no picture, every pixel is a function of where it
// is on the sensor, so a client that swaps the axes, flips the image, reads
// the wrong subframe or mixes up the colour planes gets wrong values:
//
//   value = (3 * sensor_x + 7 * sensor_y + 31 * colour) % (MaxADU + 1)
//
// sensor_x = (StartX + x) * BinX and sensor_y = (StartY + y) * BinY are the
// unbinned coordinates of the top left corner of the binned pixel (x, y),
// origin top left. colour is the plane (0 R, 1 G, 2 B) of a Color sensor, the
// colour of the filter over the pixel of a colour filter array sensor
// ((sensor_x + BayerOffsetX) % 2 + (sensor_y + BayerOffsetY) % 2, so RGGB gives
// 0 R, 1 G, 2 B) and 0 for a monochrome sensor. A dark frame (Light=false)
// holds value % 16.
//
