static void control_add_device(http_exchange *exchange, const alpaca_param *params, int count) {
	char settings[1024] = { 0 };
	char error[256] = { 0 };
	size_t used = 0;
	const char *type_name = plain_param(params, count, "Type");
	const alpaca_type *type = type_name ? find_type(type_name, false) : NULL;
	if (type == NULL) {
		control_error(exchange, "Type is required and must be an Alpaca device type");
		return;
	}
	for (int i = 0; i < count; i++) {
		if (strcmp(params[i].name, "Type")) {
			int written = snprintf(settings + used, sizeof(settings) - used, "%s%s=%s", used ? "," : "", params[i].name, params[i].value);
			if (written < 0 || (size_t)written >= sizeof(settings) - used || strchr(params[i].value, ',') != NULL) {
				control_error(exchange, "Settings are too long or contain a comma");
				return;
			}
			used += (size_t)written;
		}
	}
	alpaca_device *device = device_create(type, settings, error, sizeof(error));
	if (device == NULL) {
		control_error(exchange, "%s", error);
		return;
	}
	alpaca_buffer_field(&exchange->response, "Type", "%s", device->type->name);
	alpaca_buffer_field(&exchange->response, "Number", "%d", device->number);
	alpaca_buffer_field(&exchange->response, "UniqueID", "%s", device->unique_id);
}

static alpaca_device *control_find_device(http_exchange *exchange, const char *type_name, const char *number_text) {
	int number = 0;
	const alpaca_type *type = type_name ? find_type(type_name, false) : NULL;
	if (type == NULL || number_text == NULL || !alpaca_parse_int(number_text, &number) || find_device(type, number) == NULL) {
		control_error(exchange, "No device %s/%s", type_name ? type_name : "?", number_text ? number_text : "?");
		return NULL;
	}
	return find_device(type, number);
}

static void control_remove_device(http_exchange *exchange, const alpaca_param *params, int count) {
	alpaca_device *device = control_find_device(exchange, plain_param(params, count, "Type"), plain_param(params, count, "Number"));
	if (device == NULL) {
		return;
	}
	for (int i = 0; i < device_count; i++) {
		if (devices[i] == device) {
			memmove(devices + i, devices + i + 1, (size_t)(device_count - i - 1) * sizeof(devices[0]));
			device_count--;
			break;
		}
	}
	alpaca_event("CONTROL", "removed %s/%d", device->type->name, device->number);
	device_free(device);
	control_ok(exchange);
}

