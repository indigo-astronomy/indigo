	alpaca_buffer_field(buffer, "UniqueID", "%s", device->unique_id);
	alpaca_buffer_field(buffer, "InterfaceVersion", "%d", device->interface_version);
	alpaca_buffer_field(buffer, "Description", "%s", device->description);
	alpaca_buffer_field(buffer, "DriverInfo", "%s", device->driver_info);
