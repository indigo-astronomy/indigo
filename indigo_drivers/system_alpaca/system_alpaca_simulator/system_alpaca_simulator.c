// Sleeps in real time, but returns early (false) when the simulator shuts down.
static bool interruptible_sleep(int milliseconds) {
	double deadline = monotonic_time() + milliseconds / 1000.0;
	while (running) {
		int remaining = (int)ceil((deadline - monotonic_time()) * 1000);
		if (remaining <= 0) {
			return true;
		}
		struct pollfd wake = { .fd = wake_pipe[0], .events = POLLIN };
		if (poll(&wake, 1, remaining) > 0) {
			return false;
		}
	}
	return false;
}

