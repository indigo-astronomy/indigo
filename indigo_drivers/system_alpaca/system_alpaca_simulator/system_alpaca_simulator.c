static void handle_management(http_exchange *exchange) {
	alpaca_request request = { .method = ALPACA_GET, .status = 200 };
	if (strcmp(exchange->method, "GET")) {
		respond_text(exchange, 400, "Invalid method %s", exchange->method);
		return;
	}
	alpaca_buffer value = { 0 };
	if (!strcmp(exchange->path, "/management/apiversions")) {
		alpaca_buffer_printf(&value, "[1]");
	} else if (!strcmp(exchange->path, "/management/v1/description")) {
		alpaca_buffer_printf(&value, "{\"ServerName\":");
		alpaca_buffer_json_string(&value, options.server_name);
		alpaca_buffer_printf(&value, ",\"Manufacturer\":");
		alpaca_buffer_json_string(&value, options.manufacturer);
		alpaca_buffer_printf(&value, ",\"ManufacturerVersion\":");
		alpaca_buffer_json_string(&value, options.manufacturer_version);
		alpaca_buffer_printf(&value, ",\"Location\":");
		alpaca_buffer_json_string(&value, options.location);
		alpaca_buffer_printf(&value, "}");
	} else if (!strcmp(exchange->path, "/management/v1/configureddevices")) {
		alpaca_buffer_printf(&value, "[");
		for (int i = 0; i < device_count; i++) {
			alpaca_buffer_printf(&value, "%s{\"DeviceName\":", i ? "," : "");
			alpaca_buffer_json_string(&value, devices[i]->name);
			alpaca_buffer_printf(&value, ",\"DeviceType\":\"%s\",\"DeviceNumber\":%d,\"UniqueID\":", devices[i]->type->name, devices[i]->number);
			alpaca_buffer_json_string(&value, devices[i]->unique_id);
			alpaca_buffer_printf(&value, "}");
		}
		alpaca_buffer_printf(&value, "]");
	} else {
		respond_text(exchange, 400, "Unknown management path %s", exchange->path);
		return;
	}
	request.param_count = parse_params(exchange->query, request.params, ALPACA_MAX_PARAMS);
	bool wrong_case = false;
	unsigned client_transaction_id = parse_transaction_id(find_param(&request, "ClientTransactionID", &wrong_case));
	exchange->status = 200;
	exchange->response_type = "application/json; charset=utf-8";
	alpaca_buffer_append(&exchange->response, "{", 1);
	if (has_fault(exchange, FAULT_NULL_VALUE)) {
		alpaca_buffer_printf(&exchange->response, "\"Value\":null,");
	} else if (!has_fault(exchange, FAULT_MISSING_VALUE)) {
		alpaca_buffer_printf(&exchange->response, "\"Value\":%s,", value.data);
	}
	append_transaction_ids(exchange, client_transaction_id, ++server_transaction_id);
	alpaca_buffer_append(&exchange->response, "}", 1);
	free(value.data);
}

