	alpaca_buffer_field(buffer, "SupportedActions", "%s", device->supported_actions);
	alpaca_buffer_field(buffer, "Commands", "%s", device->commands ? "true" : "false");
	alpaca_buffer_field(buffer, "MissingMember", "%d", device->missing_member);
