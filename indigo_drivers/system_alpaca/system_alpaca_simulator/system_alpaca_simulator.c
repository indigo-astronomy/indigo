#pragma mark - motion

void alpaca_motion_set(alpaca_motion *motion, double position) {
	motion->position = motion->origin = motion->target = position;
	motion->duration = 0;
	motion->moving = false;
}

double alpaca_motion_update(alpaca_motion *motion) {
	if (motion->moving) {
		double fraction = (alpaca_now() - motion->started) / motion->duration;
		if (alpaca_reached(motion->started + motion->duration)) {
			motion->position = motion->target;
			motion->moving = false;
		} else {
			motion->position = motion->origin + (motion->target - motion->origin) * fraction;
		}
	}
	return motion->position;
}

void alpaca_motion_start_timed(alpaca_motion *motion, double target, double duration) {
	alpaca_motion_update(motion);
	motion->origin = motion->position;
	motion->target = target;
	motion->started = alpaca_now();
	motion->duration = duration;
	motion->moving = duration > 0;
	if (!motion->moving) {
		motion->position = target;
	}
}

void alpaca_motion_start(alpaca_motion *motion, double target, double rate) {
	alpaca_motion_update(motion);
	alpaca_motion_start_timed(motion, target, rate > 0 ? fabs(target - motion->position) / rate : 0);
}

void alpaca_motion_stop(alpaca_motion *motion) {
	alpaca_motion_set(motion, alpaca_motion_update(motion));
}

