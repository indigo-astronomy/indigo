#pragma mark - request recording

static recorded_request *record_request(const http_exchange *exchange) {
	if (records == NULL) {
		records = calloc(MAX_RECORDS, sizeof(recorded_request));
		if (records == NULL) {
			perror("calloc");
			abort();
		}
	}
	if (record_count == MAX_RECORDS) {
		// keep the newer half, the sequence numbers keep counting
		for (int i = 0; i < MAX_RECORDS / 2; i++) {
			free(records[i].path);
			free(records[i].query);
			free(records[i].body);
		}
		memmove(records, records + MAX_RECORDS / 2, (MAX_RECORDS / 2) * sizeof(recorded_request));
		record_count = MAX_RECORDS / 2;
	}
	recorded_request *record = records + record_count++;
	memset(record, 0, sizeof(*record));
	record->sequence = ++record_sequence;
	record->real_time = monotonic_time();
	record->simulated_time = alpaca_now();
	record->connection = exchange->connection;
	copy_text(record->method, sizeof(record->method), exchange->method);
	record->path = strdup(exchange->path);
	record->query = strdup(exchange->query);
	record->body = strdup(exchange->body);
	copy_text(record->accept, sizeof(record->accept), exchange->accept);
	copy_text(record->content_type, sizeof(record->content_type), exchange->content_type);
	copy_text(record->connection_header, sizeof(record->connection_header), exchange->connection_header);
	copy_text(record->host, sizeof(record->host), exchange->host);
	copy_text(record->user_agent, sizeof(record->user_agent), exchange->user_agent);
	record->content_length = exchange->content_length;
	if (record->path == NULL || record->query == NULL || record->body == NULL) {
		perror("strdup");
		abort();
	}
	return record;
}

static void clear_records(void) {
	for (int i = 0; i < record_count; i++) {
		free(records[i].path);
		free(records[i].query);
		free(records[i].body);
	}
	record_count = 0;
}

