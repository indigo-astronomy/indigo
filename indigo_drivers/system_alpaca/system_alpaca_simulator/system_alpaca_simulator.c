static void control_error(http_exchange *exchange, const char *format, ...) {
	char text[1024];
	va_list args;
	va_start(args, format);
	vsnprintf(text, sizeof(text), format, args);
	va_end(args);
	exchange->status = 400;
	exchange->response.length = 0;
	alpaca_buffer_field(&exchange->response, "Error", "%s", text);
}

static void control_ok(http_exchange *exchange) {
	alpaca_buffer_field(&exchange->response, "Result", "OK");
}

static bool control_int(http_exchange *exchange, const alpaca_param *params, int count, const char *name, int *value) {
	const char *text = plain_param(params, count, name);
	if (text != NULL && !alpaca_parse_int(text, value)) {
		control_error(exchange, "%s=%s is not an integer", name, text);
		return false;
	}
	return true;
}

static void control_status(http_exchange *exchange) {
	int active = 0;
	pthread_mutex_lock(&connection_lock);
	for (int i = 0; i < MAX_CONNECTIONS; i++) {
		active += connections[i].active && !connections[i].finished;
	}
	pthread_mutex_unlock(&connection_lock);
	alpaca_buffer_field(&exchange->response, "Simulator", "%s", SIMULATOR_NAME);
	alpaca_buffer_field(&exchange->response, "Version", "%s", SIMULATOR_VERSION);
	alpaca_buffer_field(&exchange->response, "PID", "%ld", (long)getpid());
	alpaca_buffer_field(&exchange->response, "Port", "%d", http_port);
	alpaca_buffer_field(&exchange->response, "DiscoveryPort", "%d", discovery_port);
	alpaca_buffer_field(&exchange->response, "Clock", "%s", options.real_clock ? "real" : "manual");
	alpaca_buffer_field(&exchange->response, "Time", "%.6f", alpaca_now());
	alpaca_buffer_field(&exchange->response, "Devices", "%d", device_count);
	alpaca_buffer_field(&exchange->response, "Requests", "%d", record_sequence);
	alpaca_buffer_field(&exchange->response, "ServerTransactionID", "%u", server_transaction_id);
	alpaca_buffer_field(&exchange->response, "Connections", "%d", active);
	alpaca_buffer_field(&exchange->response, "ConnectionsAccepted", "%d", connection_sequence);
	alpaca_buffer_field(&exchange->response, "Faults", "%d", fault_count);
}

static void set_clock_mode(bool real) {
	clock_microseconds = llround(alpaca_now() * 1e6);
	clock_real_start = monotonic_time();
	options.real_clock = real;
}

static void control_clock(http_exchange *exchange, const alpaca_param *params, int count, bool put) {
	char timestamp[64];
	if (put) {
		const char *mode = plain_param(params, count, "Mode");
		const char *advance = plain_param(params, count, "Advance");
		const char *step = plain_param(params, count, "TickPerRequest");
		const char *utc = plain_param(params, count, "UTC");
		double seconds = 0;
		double tick = options.tick_per_request;
		double base = 0;
		if (mode != NULL && strcmp(mode, "manual") && strcmp(mode, "real")) {
			control_error(exchange, "Mode=%s is not manual or real", mode);
			return;
		}
		if (advance != NULL && (!alpaca_parse_double(advance, &seconds) || seconds < 0)) {
			control_error(exchange, "Advance=%s is not a positive number of seconds", advance);
			return;
		}
		if (step != NULL && (!alpaca_parse_double(step, &tick) || tick < 0)) {
			control_error(exchange, "TickPerRequest=%s is not a positive number of seconds", step);
			return;
		}
		if (utc != NULL && !alpaca_parse_utc(utc, &base)) {
			control_error(exchange, "UTC=%s is not an ISO 8601 date", utc);
			return;
		}
		if (mode != NULL) {
			set_clock_mode(!strcmp(mode, "real"));
		}
		if (utc != NULL) {
			utc_base = base - alpaca_now();
		}
		clock_microseconds += llround(seconds * 1e6);
		options.tick_per_request = tick;
		alpaca_event("CONTROL", "clock mode=%s advance=%.6f time=%.6f tick_per_request=%.6f", options.real_clock ? "real" : "manual", seconds, alpaca_now(), options.tick_per_request);
		for (int i = 0; i < device_count; i++) {
			device_update(devices[i]);
		}
	}
	alpaca_format_utc(alpaca_utc(), timestamp, sizeof(timestamp));
	alpaca_buffer_field(&exchange->response, "Mode", "%s", options.real_clock ? "real" : "manual");
	alpaca_buffer_field(&exchange->response, "Time", "%.6f", alpaca_now());
	alpaca_buffer_field(&exchange->response, "UTC", "%s", timestamp);
	alpaca_buffer_field(&exchange->response, "TickPerRequest", "%.6f", options.tick_per_request);
}

static void reset_discovery(void) {
	long requests = discovery.requests;
	long replies = discovery.replies;
	memset(&discovery, 0, sizeof(discovery));
	discovery.copies = 1;
	discovery.count = -1;
	discovery.requests = requests;
	discovery.replies = replies;
}

static void control_reset(http_exchange *exchange, const alpaca_param *params, int count) {
	char error[256] = { 0 };
	const char *scope = plain_param(params, count, "Scope");
	bool all = scope == NULL || !strcmp(scope, "all");
	if (!all && strcmp(scope, "devices") && strcmp(scope, "faults") && strcmp(scope, "requests") && strcmp(scope, "discovery") && strcmp(scope, "clock")) {
		control_error(exchange, "Scope=%s is not all, devices, faults, requests, discovery or clock", scope);
		return;
	}
	if (all || !strcmp(scope, "clock")) {
		clock_microseconds = 0;
		clock_real_start = monotonic_time();
		utc_base = options.real_clock ? (double)time(NULL) : MANUAL_CLOCK_UTC;
	}
	if (all || !strcmp(scope, "devices")) {
		for (int i = 0; i < device_count; i++) {
			device_init(devices[i], error, sizeof(error));
		}
	}
	if (all || !strcmp(scope, "faults")) {
		fault_count = 0;
	}
	if (all || !strcmp(scope, "requests")) {
		clear_records();
	}
	if (all || !strcmp(scope, "discovery")) {
		reset_discovery();
		pending_reply_count = 0;
	}
	alpaca_event("CONTROL", "reset scope=%s", all ? "all" : scope);
	control_ok(exchange);
}

static void control_requests(http_exchange *exchange, const alpaca_param *params, int count) {
	const char *method = plain_param(params, count, "Method");
	const char *path = plain_param(params, count, "Path");
	int since = 0;
	int limit = INT_MAX;
	if (!control_int(exchange, params, count, "Since", &since) || !control_int(exchange, params, count, "Limit", &limit)) {
		return;
	}
	for (int i = 0; i < record_count && limit > 0; i++) {
		const recorded_request *record = records + i;
		if (record->sequence <= since || (method != NULL && strcmp(method, record->method)) || (path != NULL && !glob_match(path, record->path))) {
			continue;
		}
		alpaca_buffer *line = &exchange->response;
		buffer_pair(line, "Sequence", '&', "%d", record->sequence);
		buffer_pair(line, "Time", '&', "%.6f", record->simulated_time);
		buffer_pair(line, "RealTime", '&', "%.6f", record->real_time);
		buffer_pair(line, "Connection", '&', "%d", record->connection);
		buffer_pair(line, "Method", '&', "%s", record->method);
		buffer_pair(line, "Path", '&', "%s", record->path);
		buffer_pair(line, "Query", '&', "%s", record->query);
		buffer_pair(line, "Body", '&', "%s", record->body);
		buffer_pair(line, "ContentType", '&', "%s", record->content_type);
		buffer_pair(line, "ContentLength", '&', "%ld", record->content_length);
		buffer_pair(line, "Accept", '&', "%s", record->accept);
		buffer_pair(line, "ConnectionHeader", '&', "%s", record->connection_header);
		buffer_pair(line, "Host", '&', "%s", record->host);
		buffer_pair(line, "UserAgent", '&', "%s", record->user_agent);
		buffer_pair(line, "Status", '&', "%d", record->status);
		buffer_pair(line, "ErrorNumber", '&', "%d", record->error_number);
		buffer_pair(line, "Fault", '\n', "%s", record->fault);
		limit--;
	}
}

