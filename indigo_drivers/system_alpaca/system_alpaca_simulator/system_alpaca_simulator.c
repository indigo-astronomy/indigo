static void control_set_state(http_exchange *exchange, alpaca_device *device, const alpaca_param *params, int count) {
	for (int i = 0; i < count; i++) {
		if (!strcmp(params[i].name, "Number") || !strcmp(params[i].name, "number")) {
			control_error(exchange, "The device number can not be changed");
			return;
		}
		if (!device_set(device, params[i].name, params[i].value)) {
			control_error(exchange, "%s does not accept %s=%s", device->type->name, params[i].name, params[i].value);
			return;
		}
		alpaca_event("CONTROL", "%s/%d %s=%s", device->type->name, device->number, params[i].name, params[i].value);
	}
	device_update(device);
	control_ok(exchange);
}

static void control_set_error(http_exchange *exchange, alpaca_device *device, const alpaca_param *params, int count) {
	const char *member = plain_param(params, count, "Member");
	const char *message = plain_param(params, count, "ErrorMessage");
	int error_number = ALPACA_ERROR_NOT_IMPLEMENTED;
	int repeat = -1;
	alpaca_override *slot = NULL;
	if (member == NULL || strlen(member) >= sizeof(slot->member) || !control_int(exchange, params, count, "ErrorNumber", &error_number) || !control_int(exchange, params, count, "Count", &repeat)) {
		if (exchange->status != 400) {
			control_error(exchange, "Member is required");
		}
		return;
	}
	for (int i = 0; i < ALPACA_MAX_OVERRIDES; i++) {
		if (!strcasecmp(device->overrides[i].member, member)) {
			slot = device->overrides + i;
			break;
		}
		if (slot == NULL && device->overrides[i].count == 0) {
			slot = device->overrides + i;
		}
	}
	if (slot == NULL) {
		control_error(exchange, "Too many member errors on one device");
		return;
	}
	memset(slot, 0, sizeof(*slot));
	if (error_number != 0) {
		copy_text(slot->member, sizeof(slot->member), member);
		for (char *cursor = slot->member; *cursor; cursor++) {
			*cursor = (char)tolower((unsigned char)*cursor);
		}
		copy_text(slot->error_message, sizeof(slot->error_message), message ? message : "Injected error");
		slot->error_number = error_number;
		slot->count = repeat;
	}
	alpaca_event("CONTROL", "%s/%d member=%s error=%d count=%d", device->type->name, device->number, member, error_number, repeat);
	control_ok(exchange);
}

static void control_device(http_exchange *exchange, char *rest, const alpaca_param *params, int count, bool put) {
	char error[256] = { 0 };
	char *number_text = strchr(rest, '/');
	char *action = number_text ? strchr(number_text + 1, '/') : NULL;
	if (action == NULL) {
		control_error(exchange, "Unknown control path %s", exchange->path);
		return;
	}
	*number_text++ = '\0';
	*action++ = '\0';
	alpaca_device *device = control_find_device(exchange, rest, number_text);
	if (device == NULL) {
		return;
	}
	device_update(device);
	if (!strcmp(action, "state") && put) {
		control_set_state(exchange, device, params, count);
	} else if (!strcmp(action, "state")) {
		control_report_state(exchange, device);
	} else if (!strcmp(action, "reset") && put) {
		device_init(device, error, sizeof(error));
		alpaca_event("CONTROL", "reset %s/%d", device->type->name, device->number);
		control_ok(exchange);
	} else if (!strcmp(action, "error") && put) {
		control_set_error(exchange, device, params, count);
	} else {
		control_error(exchange, "Unknown control path %s %s", exchange->method, exchange->path);
	}
}

// path is everything after /simulator/v1/
static void handle_control(http_exchange *exchange) {
	alpaca_param params[ALPACA_MAX_PARAMS];
	char path[256];
	bool put = !strcmp(exchange->method, "PUT");
	exchange->status = 200;
	exchange->response_type = "text/plain; charset=utf-8";
	if (!put && strcmp(exchange->method, "GET")) {
		control_error(exchange, "Invalid method %s", exchange->method);
		return;
	}
	copy_text(path, sizeof(path), strlen(exchange->path) > 14 ? exchange->path + 14 : "");
	int count = parse_params(put ? exchange->body : exchange->query, params, ALPACA_MAX_PARAMS);
	if (!strcmp(path, "status") && !put) {
		control_status(exchange);
	} else if (!strcmp(path, "clock")) {
		control_clock(exchange, params, count, put);
	} else if (!strcmp(path, "reset") && put) {
		control_reset(exchange, params, count);
	} else if (!strcmp(path, "requests") && !put) {
		control_requests(exchange, params, count);
	} else if (!strcmp(path, "requests/clear") && put) {
		clear_records();
		control_ok(exchange);
	} else if (!strcmp(path, "faults") && put) {
		control_add_fault(exchange, params, count);
	} else if (!strcmp(path, "faults")) {
		control_list_faults(exchange);
	} else if (!strcmp(path, "faults/clear") && put) {
		fault_count = 0;
		alpaca_event("CONTROL", "faults cleared");
		control_ok(exchange);
	} else if (!strcmp(path, "discovery")) {
		control_discovery(exchange, params, count, put);
	} else if (!strcmp(path, "server")) {
		control_server(exchange, params, count, put);
	} else if (!strcmp(path, "devices") && put) {
		control_add_device(exchange, params, count);
	} else if (!strcmp(path, "devices")) {
		control_list_devices(exchange);
	} else if (!strcmp(path, "devices/remove") && put) {
		control_remove_device(exchange, params, count);
	} else if (!strcmp(path, "shutdown") && put) {
		exchange->shutdown = true;
		alpaca_event("CONTROL", "shutdown");
		control_ok(exchange);
	} else {
		control_device(exchange, path, params, count, put);
	}
}

#pragma mark - HTTP

static const char *status_reason(int status) {
	switch (status) {
		case 200:
			return "OK";
		case 400:
			return "Bad Request";
		case 401:
			return "Unauthorized";
		case 403:
			return "Forbidden";
		case 404:
			return "Not Found";
		case 411:
			return "Length Required";
		case 413:
			return "Payload Too Large";
		case 431:
			return "Request Header Fields Too Large";
		case 500:
			return "Internal Server Error";
		case 503:
			return "Service Unavailable";
		default:
			return "Status";
	}
}

static void corrupt_json(http_exchange *exchange) {
	if (strncmp(exchange->response_type, "application/json", 16)) {
		return;
	}
	if (has_fault(exchange, FAULT_TRUNCATED_JSON)) {
		exchange->response.length /= 2;
		exchange->response.data[exchange->response.length] = '\0';
	} else if (has_fault(exchange, FAULT_MALFORMED_JSON) && exchange->response.length > 1) {
		alpaca_buffer corrupted = { 0 };
		alpaca_buffer_printf(&corrupted, "{]%s", exchange->response.data + 1);
		free(exchange->response.data);
		exchange->response = corrupted;
	}
}

// The Alpaca API reference requires the parameters of a PUT in a form body, application/x-www-form-urlencoded. A body of another type is
// refused like the ASP.NET servers refuse it; a PUT without a body (a method without parameters, no ClientID) needs no type.
// --any-content-type turns the check off for servers that read any body as a form.
static bool put_content_type_accepted(const http_exchange *exchange) {
	if (strcmp(exchange->method, "PUT") || options.any_content_type || (exchange->body_length == 0 && !*exchange->content_type)) {
		return true;
	}
	size_t length = strcspn(exchange->content_type, "; \t");
	return length == 33 && !strncasecmp(exchange->content_type, "application/x-www-form-urlencoded", length);
}

// Runs with the simulator lock held: turns a parsed request into a response and picks the fault to apply to it.
static void process_exchange(http_exchange *exchange) {
	char path[1024];
	if (!strcmp(exchange->path, "/simulator/v1") || !strncmp(exchange->path, "/simulator/v1/", 14)) {
		handle_control(exchange);
		return;
	}
	recorded_request *record = record_request(exchange);
	alpaca_event("RX", "#%d c%d %s %s%s%s %s", record->sequence, exchange->connection, exchange->method, exchange->path, *exchange->query ? "?" : "", exchange->query, exchange->body);
	exchange->has_fault = match_fault(exchange->method, exchange->path, &exchange->fault);
	if (exchange->has_fault) {
		copy_text(record->fault, sizeof(record->fault), fault_names[exchange->fault.action]);
		alpaca_event("FAULT", "#%d id=%d %s value=%d delay=%d bytes=%d", record->sequence, exchange->fault.id, fault_names[exchange->fault.action], exchange->fault.value, exchange->fault.delay, exchange->fault.bytes);
	}
	copy_text(path, sizeof(path), exchange->path);
	if (has_fault(exchange, FAULT_HTTP_STATUS)) {
		respond_text(exchange, exchange->fault.has_value ? exchange->fault.value : 500, "%s", *exchange->fault.message ? exchange->fault.message : "Injected HTTP error");
	} else if (exchange->has_fault && !exchange->fault.dispatch && exchange->fault.action != FAULT_ASCOM_ERROR) {
		respond_text(exchange, 200, "%s", "");
	} else if (!strncmp(path, "/api/v1/", 8) && !put_content_type_accepted(exchange)) {
		respond_text(exchange, 400, "PUT parameters have to be sent as application/x-www-form-urlencoded, not '%s'", exchange->content_type);
	} else if (!strncmp(path, "/api/v1/", 8)) {
		handle_device_api(exchange, path + 8);
	} else if (!strncmp(path, "/api/", 5) || !strcmp(path, "/api")) {
		respond_text(exchange, 400, "Unknown API version in %s", exchange->path);
	} else if (!strncmp(path, "/management/", 12)) {
		handle_management(exchange);
	} else if (!strcmp(path, "/setup") || !strncmp(path, "/setup/", 7)) {
		handle_setup(exchange);
	} else {
		respond_text(exchange, 404, "Not found: %s", exchange->path);
	}
	corrupt_json(exchange);
	record->status = exchange->status;
	record->error_number = exchange->error_number;
	if (!strncmp(exchange->response_type, "application/imagebytes", 22) || exchange->response.length > 200) {
		alpaca_event("TX", "#%d %d %s %zu bytes", record->sequence, exchange->status, exchange->response_type, exchange->response.length);
	} else {
		alpaca_event("TX", "#%d %d %s", record->sequence, exchange->status, exchange->response.data ? exchange->response.data : "");
	}
}

// Writes in pieces and carries on after a partial write. A loopback socket under load can also refuse a
// write for a moment (ENOBUFS on macOS); that is waited out, it is no reason to cut the body.
static bool send_all(int fd, const char *data, size_t length) {
	while (length > 0) {
		ssize_t written = write(fd, data, length < MAX_WRITE_SIZE ? length : MAX_WRITE_SIZE);
		if (written > 0) {
			data += written;
			length -= (size_t)written;
		} else if (written < 0 && errno == EINTR) {
			continue;
		} else if (written < 0 && (errno == ENOBUFS || errno == EAGAIN || errno == EWOULDBLOCK)) {
			if (!interruptible_sleep(1)) {
				return false;
			}
		} else {
			return false;
		}
	}
	return true;
}

static bool send_chunked(int fd, const char *data, size_t length, size_t chunk_size) {
	char header[32];
	while (length > 0) {
		size_t size = length < chunk_size ? length : chunk_size;
		int header_length = snprintf(header, sizeof(header), "%zx\r\n", size);
		if (!send_all(fd, header, (size_t)header_length) || !send_all(fd, data, size) || !send_all(fd, "\r\n", 2)) {
			return false;
		}
		data += size;
		length -= size;
	}
	return send_all(fd, "0\r\n\r\n", 5);
}

// Sends the response the way the selected fault asks for. Returns false when the connection has to be closed.
static bool send_exchange(int fd, http_exchange *exchange) {
	char header[512];
	const fault_rule *fault = &exchange->fault;
	fault_action action = exchange->has_fault ? fault->action : FAULT_NONE;
	const char *body = exchange->response.data ? exchange->response.data : "";
	size_t body_length = exchange->response.length;
	size_t partial = fault->bytes >= 0 && (size_t)fault->bytes < body_length ? (size_t)fault->bytes : body_length / 2;
	bool keep = exchange->keep_alive && action != FAULT_CONNECTION_CLOSE && action != FAULT_SILENT_CLOSE && !exchange->shutdown;
	bool announce_close = !exchange->keep_alive || action == FAULT_CONNECTION_CLOSE || exchange->shutdown;
	int header_length = snprintf(header, sizeof(header), "HTTP/1.1 %d %s\r\nServer: system_alpaca_simulator/%s\r\nContent-Type: %s\r\n", exchange->status, status_reason(exchange->status), SIMULATOR_VERSION, exchange->response_type);
	if (action == FAULT_CHUNKED) {
		header_length += snprintf(header + header_length, sizeof(header) - (size_t)header_length, "Transfer-Encoding: chunked\r\n");
	} else {
		header_length += snprintf(header + header_length, sizeof(header) - (size_t)header_length, "Content-Length: %zu\r\n", body_length);
	}
	header_length += snprintf(header + header_length, sizeof(header) - (size_t)header_length, "%s\r\n", announce_close ? "Connection: close\r\n" : "");
	switch (action) {
		case FAULT_DROP:
			return false;
		case FAULT_RESET: {
			struct linger linger = { .l_onoff = 1, .l_linger = 0 };
			if (fault->bytes > 0) {
				size_t from_header = (size_t)fault->bytes < (size_t)header_length ? (size_t)fault->bytes : (size_t)header_length;
				size_t from_body = (size_t)fault->bytes - from_header < body_length ? (size_t)fault->bytes - from_header : body_length;
				send_all(fd, header, from_header);
				send_all(fd, body, from_body);
				interruptible_sleep(50);
			}
			setsockopt(fd, SOL_SOCKET, SO_LINGER, &linger, sizeof(linger));
			return false;
		}
		case FAULT_STALL_BEFORE:
			if (!interruptible_sleep(fault->delay)) {
				return false;
			}
			break;
		case FAULT_STALL_WITHIN:
			if (!send_all(fd, header, (size_t)header_length) || !send_all(fd, body, partial) || !interruptible_sleep(fault->delay)) {
				return false;
			}
			return send_all(fd, body + partial, body_length - partial) && keep;
		case FAULT_TRUNCATED_BODY:
			send_all(fd, header, (size_t)header_length);
			send_all(fd, body, partial);
			return false;
		case FAULT_CHUNKED:
			return send_all(fd, header, (size_t)header_length) && send_chunked(fd, body, body_length, fault->bytes > 0 ? (size_t)fault->bytes : 1024) && keep;
		default:
			break;
	}
	return send_all(fd, header, (size_t)header_length) && send_all(fd, body, body_length) && keep;
}

static void send_simple(int fd, int status, const char *text) {
	char response[512];
	int length = snprintf(response, sizeof(response), "HTTP/1.1 %d %s\r\nContent-Type: text/plain; charset=utf-8\r\nContent-Length: %zu\r\nConnection: close\r\n\r\n%s", status, status_reason(status), strlen(text), text);
	send_all(fd, response, (size_t)length);
}

static bool read_more(int fd, alpaca_buffer *input) {
	char chunk[8192];
	for (;;) {
		ssize_t count = read(fd, chunk, sizeof(chunk));
		if (count > 0) {
			alpaca_buffer_append(input, chunk, (size_t)count);
			return true;
		}
		if (count < 0 && errno == EINTR && running) {
			continue;
		}
		return false;
	}
}

static void copy_header(char *target, size_t size, const char *value) {
	while (*value == ' ' || *value == '\t') {
		value++;
	}
	snprintf(target, size, "%s", value);
}

// Reads one request from the connection. Returns false when the connection is finished; *status is then
// either 0 (closed by the client) or the HTTP status to answer with before closing.
static bool read_exchange(int fd, alpaca_buffer *input, http_exchange *exchange, int *status) {
	char *end = NULL;
	char target[2048] = { 0 };
	char version[16] = { 0 };
	char transfer_encoding[64] = { 0 };
	char expect[64] = { 0 };
	*status = 0;
	while (input->data == NULL || (end = strstr(input->data, "\r\n\r\n")) == NULL) {
		if (input->length > MAX_HEADER_SIZE) {
			*status = 431;
			return false;
		}
		if (!read_more(fd, input)) {
			return false;
		}
	}
	size_t header_length = (size_t)(end - input->data) + 4;
	*end = '\0';
	char *line = strstr(input->data, "\r\n");
	if (line != NULL) {
		*line = '\0';
		line += 2;
	}
	if (sscanf(input->data, "%15s %2047s %15s", exchange->method, target, version) != 3 || strncmp(version, "HTTP/1.", 7) || *target != '/') {
		*status = 400;
		return false;
	}
	exchange->keep_alive = strcmp(version, "HTTP/1.0") != 0;
	while (line != NULL && *line) {
		char *next = strstr(line, "\r\n");
		if (next != NULL) {
			*next = '\0';
			next += 2;
		}
		char *value = strchr(line, ':');
		if (value != NULL) {
			*value++ = '\0';
			if (!strcasecmp(line, "Content-Length")) {
				exchange->content_length = strtol(value, NULL, 10);
			} else if (!strcasecmp(line, "Accept")) {
				copy_header(exchange->accept, sizeof(exchange->accept), value);
			} else if (!strcasecmp(line, "Content-Type")) {
				copy_header(exchange->content_type, sizeof(exchange->content_type), value);
			} else if (!strcasecmp(line, "Connection")) {
				copy_header(exchange->connection_header, sizeof(exchange->connection_header), value);
			} else if (!strcasecmp(line, "Host")) {
				copy_header(exchange->host, sizeof(exchange->host), value);
			} else if (!strcasecmp(line, "User-Agent")) {
				copy_header(exchange->user_agent, sizeof(exchange->user_agent), value);
			} else if (!strcasecmp(line, "Transfer-Encoding")) {
				copy_header(transfer_encoding, sizeof(transfer_encoding), value);
			} else if (!strcasecmp(line, "Expect")) {
				copy_header(expect, sizeof(expect), value);
			}
		}
		line = next;
	}
	if (strcasestr(exchange->connection_header, "close") != NULL) {
		exchange->keep_alive = false;
	} else if (strcasestr(exchange->connection_header, "keep-alive") != NULL) {
		exchange->keep_alive = true;
	}
	if (*transfer_encoding && strcasecmp(transfer_encoding, "identity")) {
		*status = 411;
		return false;
	}
	if (exchange->content_length < 0 || exchange->content_length > MAX_BODY_SIZE) {
		*status = 413;
		return false;
	}
	if (strcasestr(expect, "100-continue") != NULL && !send_all(fd, "HTTP/1.1 100 Continue\r\n\r\n", 25)) {
		return false;
	}
	char *query = strchr(target, '?');
	if (query != NULL) {
		*query++ = '\0';
	}
	exchange->path = strdup(target);
	exchange->query = strdup(query ? query : "");
	exchange->body_length = (size_t)exchange->content_length;
	while (input->length < header_length + exchange->body_length) {
		if (!read_more(fd, input)) {
			return false;
		}
	}
	exchange->body = calloc(1, exchange->body_length + 1);
	if (exchange->path == NULL || exchange->query == NULL || exchange->body == NULL) {
		perror("malloc");
		abort();
	}
	memcpy(exchange->body, input->data + header_length, exchange->body_length);
	size_t consumed = header_length + exchange->body_length;
	memmove(input->data, input->data + consumed, input->length - consumed);
	input->length -= consumed;
	input->data[input->length] = '\0';
	return true;
}

static void free_exchange(http_exchange *exchange) {
	free(exchange->path);
	free(exchange->query);
	free(exchange->body);
	free(exchange->response.data);
}

static void request_shutdown(void) {
	running = 0;
	if (wake_pipe[1] >= 0 && write(wake_pipe[1], "x", 1) < 0) {
		return;
	}
}

static void *connection_thread(void *argument) {
	http_connection *connection = argument;
	alpaca_buffer input = { 0 };
	bool keep = true;
	while (keep && running) {
		http_exchange exchange = { .connection = connection->id, .response_type = "text/plain; charset=utf-8", .status = 200 };
		int status = 0;
		if (!read_exchange(connection->fd, &input, &exchange, &status)) {
			if (status != 0) {
				send_simple(connection->fd, status, status_reason(status));
			}
			free_exchange(&exchange);
			break;
		}
		pthread_mutex_lock(&simulator_lock);
		process_exchange(&exchange);
		pthread_mutex_unlock(&simulator_lock);
		keep = send_exchange(connection->fd, &exchange);
		if (exchange.shutdown) {
			request_shutdown();
		}
		free_exchange(&exchange);
	}
	free(input.data);
	pthread_mutex_lock(&connection_lock);
	close(connection->fd);
	connection->fd = -1;
	connection->finished = true;
	pthread_mutex_unlock(&connection_lock);
	return NULL;
}

// Joins the threads of closed connections. With all set it first unblocks and then joins every connection.
static void reap_connections(bool all) {
	for (int i = 0; i < MAX_CONNECTIONS; i++) {
		pthread_mutex_lock(&connection_lock);
		bool join = connections[i].active && (connections[i].finished || all);
		if (join && !connections[i].finished) {
			shutdown(connections[i].fd, SHUT_RDWR);
		}
		pthread_mutex_unlock(&connection_lock);
		if (join) {
			pthread_join(connections[i].thread, NULL);
			pthread_mutex_lock(&connection_lock);
			connections[i].active = false;
			pthread_mutex_unlock(&connection_lock);
		}
	}
}

static void accept_connection(void) {
	int one = 1;
	int fd = accept(http_fd, NULL, NULL);
	if (fd < 0) {
		return;
	}
	fcntl(fd, F_SETFL, fcntl(fd, F_GETFL, 0) & ~O_NONBLOCK);
	setsockopt(fd, IPPROTO_TCP, TCP_NODELAY, &one, sizeof(one));
	reap_connections(false);
	for (int i = 0; i < MAX_CONNECTIONS; i++) {
		if (!connections[i].active) {
			pthread_mutex_lock(&connection_lock);
			connections[i].fd = fd;
			connections[i].id = ++connection_sequence;
			connections[i].finished = false;
			connections[i].active = true;
			pthread_mutex_unlock(&connection_lock);
			if (pthread_create(&connections[i].thread, NULL, connection_thread, connections + i) != 0) {
				perror("pthread_create");
				connections[i].active = false;
				close(fd);
			}
			return;
		}
	}
	send_simple(fd, 503, "Too many connections");
	close(fd);
}

#pragma mark - discovery

static void send_discovery_reply(const pending_reply *reply) {
	char address[INET_ADDRSTRLEN] = { 0 };
	inet_ntop(AF_INET, &reply->address.sin_addr, address, sizeof(address));
	sendto(discovery_fd, reply->payload, reply->length, 0, (const struct sockaddr *)&reply->address, sizeof(reply->address));
	alpaca_event("DISCOVERY", "reply to=%s:%d %.*s", address, ntohs(reply->address.sin_port), (int)reply->length, reply->payload);
}

static void handle_discovery(void) {
	char request[64] = { 0 };
	char address[INET_ADDRSTRLEN] = { 0 };
	pending_reply reply = { 0 };
	socklen_t length = sizeof(reply.address);
	ssize_t count = recvfrom(discovery_fd, request, sizeof(request) - 1, 0, (struct sockaddr *)&reply.address, &length);
	if (count < 0) {
		return;
	}
	inet_ntop(AF_INET, &reply.address.sin_addr, address, sizeof(address));
	pthread_mutex_lock(&simulator_lock);
	if ((size_t)count < strlen(DISCOVERY_REQUEST) || memcmp(request, DISCOVERY_REQUEST, strlen(DISCOVERY_REQUEST))) {
		alpaca_event("DISCOVERY", "ignored from=%s:%d %zd bytes", address, ntohs(reply.address.sin_port), count);
		pthread_mutex_unlock(&simulator_lock);
		return;
	}
	discovery.requests++;
	alpaca_event("DISCOVERY", "request from=%s:%d", address, ntohs(reply.address.sin_port));
	for (int port = 0; discovery.mode != DISCOVERY_SILENT && port < (discovery.alpaca_port_count ? discovery.alpaca_port_count : 1); port++) {
		if (*discovery.reply) {
			copy_text(reply.payload, sizeof(reply.payload), discovery.reply);
		} else if (discovery.mode == DISCOVERY_MALFORMED) {
			copy_text(reply.payload, sizeof(reply.payload), "{\"AlpacaPort\":");
		} else {
			snprintf(reply.payload, sizeof(reply.payload), "{\"AlpacaPort\":%d}", discovery.alpaca_port_count ? discovery.alpaca_ports[port] : http_port);
		}
		reply.length = strlen(reply.payload);
		reply.due = monotonic_time() + discovery.delay / 1000.0;
		for (int i = 0; i < discovery.copies; i++) {
			discovery.replies++;
			if (discovery.delay == 0) {
				send_discovery_reply(&reply);
			} else if (pending_reply_count < MAX_PENDING_REPLIES) {
				pending_replies[pending_reply_count++] = reply;
			}
		}
	}
	if (discovery.count > 0 && --discovery.count == 0) {
		reset_discovery();
	}
	pthread_mutex_unlock(&simulator_lock);
}

// Sends the delayed replies that are due and returns the poll timeout until the next one.
static int flush_pending_replies(void) {
	int timeout = 500;
	double now = monotonic_time();
	pthread_mutex_lock(&simulator_lock);
	for (int i = 0; i < pending_reply_count;) {
		if (pending_replies[i].due <= now) {
			send_discovery_reply(pending_replies + i);
			memmove(pending_replies + i, pending_replies + i + 1, (size_t)(pending_reply_count - i - 1) * sizeof(pending_reply));
			pending_reply_count--;
		} else {
			int remaining = (int)ceil((pending_replies[i].due - now) * 1000);
			timeout = remaining < timeout ? remaining : timeout;
			i++;
		}
	}
	pthread_mutex_unlock(&simulator_lock);
	return timeout < 1 ? 1 : timeout;
}

#pragma mark - runtime

static void signal_handler(int signal_number) {
	(void)signal_number;
	running = 0;
	if (wake_pipe[1] >= 0 && write(wake_pipe[1], "x", 1) < 0) {
		return;
	}
}

static int open_socket(int type, const char *address_text, int port, int *bound_port) {
	struct sockaddr_in address = { 0 };
	socklen_t length = sizeof(address);
	int one = 1;
	int fd = socket(AF_INET, type, 0);
	if (fd < 0) {
		perror("socket");
		return -1;
	}
	setsockopt(fd, SOL_SOCKET, SO_REUSEADDR, &one, sizeof(one));
	if (type == SOCK_DGRAM) {
		// several simulators may answer discovery on one port, like several Alpaca servers on one host
		setsockopt(fd, SOL_SOCKET, SO_REUSEPORT, &one, sizeof(one));
		setsockopt(fd, SOL_SOCKET, SO_BROADCAST, &one, sizeof(one));
	}
	address.sin_family = AF_INET;
	address.sin_port = htons((uint16_t)port);
	if (inet_pton(AF_INET, address_text, &address.sin_addr) != 1) {
		fprintf(stderr, "'%s' is not an IPv4 address\n", address_text);
		close(fd);
		return -1;
	}
	if (bind(fd, (struct sockaddr *)&address, sizeof(address)) < 0 || (type == SOCK_STREAM && listen(fd, 32) < 0) || getsockname(fd, (struct sockaddr *)&address, &length) < 0) {
		fprintf(stderr, "%s %s:%d: %s\n", type == SOCK_STREAM ? "tcp" : "udp", address_text, port, strerror(errno));
		close(fd);
		return -1;
	}
	fcntl(fd, F_SETFL, fcntl(fd, F_GETFL, 0) | O_NONBLOCK);
	*bound_port = ntohs(address.sin_port);
	return fd;
}

// Same convention as serial_simulator_write_ready_file(): written to a temporary file and renamed, so a reader never sees half of it.
static bool write_ready_file(void) {
	char temporary[PATH_MAX];
	snprintf(temporary, sizeof(temporary), "%s.tmp.%ld", options.ready_file, (long)getpid());
	FILE *file = fopen(temporary, "w");
	if (file == NULL) {
		perror("fopen ready file");
		return false;
	}
	fprintf(file, "INDIGO_SIMULATOR=%s\n", SIMULATOR_NAME);
	fprintf(file, "INDIGO_SIMULATOR_PORT=%s:%d\n", options.bind_address, http_port);
	fprintf(file, "INDIGO_SIMULATOR_HOST=%s\n", options.bind_address);
	fprintf(file, "INDIGO_SIMULATOR_TCP_PORT=%d\n", http_port);
	fprintf(file, "INDIGO_SIMULATOR_TCP_URL=http://%s:%d\n", options.bind_address, http_port);
	if (options.discovery) {
		fprintf(file, "INDIGO_SIMULATOR_UDP_PORT=%d\n", discovery_port);
		fprintf(file, "INDIGO_SIMULATOR_UDP_URL=udp://%s:%d\n", options.discovery_bind, discovery_port);
	}
	fprintf(file, "INDIGO_SIMULATOR_PID=%ld\n", (long)getpid());
	if (fclose(file) != 0 || rename(temporary, options.ready_file) != 0) {
		perror("ready file");
		unlink(temporary);
		return false;
	}
	return true;
}

