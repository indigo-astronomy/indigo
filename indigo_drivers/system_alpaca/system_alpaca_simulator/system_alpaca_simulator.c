static void format_field(alpaca_device *device, const alpaca_member *member, char *text, size_t size) {
	void *field = (char *)device->state + member->offset;
	switch (member->kind) {
		case ALPACA_BOOL:
			snprintf(text, size, "%s", *(bool *)field ? "true" : "false");
			break;
		case ALPACA_INT:
			snprintf(text, size, "%d", *(int *)field);
			break;
		case ALPACA_DOUBLE:
			snprintf(text, size, "%.15g", *(double *)field);
			break;
		case ALPACA_STRING:
			snprintf(text, size, "%s", (char *)field);
			break;
		case ALPACA_MOTION:
			snprintf(text, size, "%.15g", alpaca_motion_update((alpaca_motion *)field));
			break;
		case ALPACA_MOTION_INT:
			snprintf(text, size, "%ld", lround(alpaca_motion_update((alpaca_motion *)field)));
			break;
		default:
			*text = '\0';
			break;
	}
}

// Returns 0 when stored, 1 when the text can not be parsed and 2 when the value is out of the range of the member.
static int store_field(alpaca_device *device, const alpaca_member *member, const char *text, bool check_range) {
	void *field = (char *)device->state + member->offset;
	bool has_range = check_range && member->min != member->max;
	bool flag = false;
	int integer = 0;
	double number = 0;
	switch (member->kind) {
		case ALPACA_BOOL:
			if (!alpaca_parse_bool(text, &flag)) {
				return 1;
			}
			*(bool *)field = flag;
			return 0;
		case ALPACA_INT:
			if (!alpaca_parse_int(text, &integer)) {
				return 1;
			}
			if (has_range && (integer < member->min || integer > member->max)) {
				return 2;
			}
			*(int *)field = integer;
			return 0;
		case ALPACA_DOUBLE:
		case ALPACA_MOTION:
		case ALPACA_MOTION_INT:
			if (!alpaca_parse_double(text, &number)) {
				return 1;
			}
			if (has_range && (number < member->min || number > member->max)) {
				return 2;
			}
			if (member->kind == ALPACA_DOUBLE) {
				*(double *)field = number;
			} else {
				alpaca_motion_set((alpaca_motion *)field, number);
			}
			return 0;
		case ALPACA_STRING:
			snprintf((char *)field, ALPACA_TEXT_SIZE, "%s", text);
			return 0;
		default:
			return 1;
	}
}

void alpaca_reply_member(alpaca_device *device, alpaca_request *request) {
	char text[ALPACA_TEXT_SIZE];
	format_field(device, request->member, text, sizeof(text));
	if (request->member->kind == ALPACA_STRING) {
		alpaca_reply_string(request, text);
	} else {
		alpaca_reply_json(request, "%s", text);
	}
}

bool alpaca_store_member(alpaca_device *device, alpaca_request *request) {
	const char *text = required_param(request, request->member->name);
	if (text == NULL) {
		return false;
	}
	switch (store_field(device, request->member, text, true)) {
		case 0:
			return true;
		case 2:
			alpaca_reply_error(request, ALPACA_ERROR_INVALID_VALUE, "%s=%s is out of range %g..%g", request->member->name, text, request->member->min, request->member->max);
			return false;
		default:
			alpaca_reply_bad_request(request, "Parameter '%s' has an invalid value: '%s'", request->member->name, text);
			return false;
	}
}

