void alpaca_format_utc(double utc, char *text, size_t size) {
	time_t seconds = (time_t)floor(utc);
	int fraction = (int)((utc - floor(utc)) * 1e7);
	struct tm parts = { 0 };
	gmtime_r(&seconds, &parts);
	snprintf(text, size, "%04d-%02d-%02dT%02d:%02d:%02d.%07dZ", parts.tm_year + 1900, parts.tm_mon + 1, parts.tm_mday, parts.tm_hour, parts.tm_min, parts.tm_sec, fraction);
}

bool alpaca_parse_utc(const char *text, double *utc) {
	struct tm parts = { 0 };
	double seconds = 0;
	int consumed = 0;
	if (sscanf(text, "%d-%d-%dT%d:%d:%lf%n", &parts.tm_year, &parts.tm_mon, &parts.tm_mday, &parts.tm_hour, &parts.tm_min, &seconds, &consumed) != 6) {
		return false;
	}
	if (strcmp(text + consumed, "Z") && text[consumed] != '\0') {
		return false;
	}
	if (parts.tm_mon < 1 || parts.tm_mon > 12 || parts.tm_mday < 1 || parts.tm_mday > 31 || parts.tm_hour < 0 || parts.tm_hour > 23 || parts.tm_min < 0 || parts.tm_min > 59 || seconds < 0 || seconds >= 61) {
		return false;
	}
	parts.tm_year -= 1900;
	parts.tm_mon -= 1;
	*utc = (double)timegm(&parts) + seconds;
	return true;
}

