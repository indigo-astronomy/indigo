static bool has_action(const alpaca_device *device, const char *action) {
	size_t length = strlen(action);
	const char *cursor = device->supported_actions;
	while (length > 0 && *cursor) {
		size_t item = strcspn(cursor, ",");
		if (item == length && !strncasecmp(cursor, action, length)) {
			return true;
		}
		cursor += item;
		cursor += *cursor == ',';
	}
	return false;
}

static void common_get_supportedactions(alpaca_device *device, alpaca_request *request) {
	const char *cursor = device->supported_actions;
	alpaca_buffer_append(&request->value, "[", 1);
	while (*cursor) {
		char item[ALPACA_TEXT_SIZE];
		size_t length = strcspn(cursor, ",");
		snprintf(item, sizeof(item), "%.*s", (int)length, cursor);
		if (request->value.length > 1) {
			alpaca_buffer_append(&request->value, ",", 1);
		}
		alpaca_buffer_json_string(&request->value, item);
		cursor += length;
		cursor += *cursor == ',';
	}
	alpaca_buffer_append(&request->value, "]", 1);
	alpaca_reply_void(request);
}

static void common_put_action(alpaca_device *device, alpaca_request *request) {
	const char *action = NULL;
	const char *parameters = NULL;
	char result[ALPACA_TEXT_SIZE];
	if (!alpaca_param_string(request, "Action", &action) || !alpaca_param_string(request, "Parameters", &parameters)) {
		return;
	}
	if (!has_action(device, action)) {
		alpaca_reply_error(request, ALPACA_ERROR_ACTION_NOT_IMPLEMENTED, "Action '%s' is not implemented", action);
		return;
	}
	snprintf(result, sizeof(result), "%s(%s)", action, parameters);
	alpaca_reply_string(request, result);
}

static bool common_command(alpaca_device *device, alpaca_request *request, const char **command) {
	bool raw = false;
	if (!alpaca_param_string(request, "Command", command) || !alpaca_param_bool(request, "Raw", &raw)) {
		return false;
	}
	if (!device->commands) {
		alpaca_reply_error(request, ALPACA_ERROR_NOT_IMPLEMENTED, "%s is not implemented", request->member->name);
		return false;
	}
	return true;
}

