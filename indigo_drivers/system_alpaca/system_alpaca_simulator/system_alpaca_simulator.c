#define COMMON_MEMBER_COUNT ((int)(sizeof(common_members) / sizeof(common_members[0])))

static bool member_available(const alpaca_device *device, const alpaca_member *member) {
	if (member->flags & ALPACA_CONFIG) {
		return false;
	}
	return member->since < 0 ? is_platform7(device) : device->interface_version >= member->since;
}

static const alpaca_member *find_member(const alpaca_device *device, const char *element) {
	for (int i = 0; i < COMMON_MEMBER_COUNT; i++) {
		if (matches_lower(common_members[i].name, element)) {
			return member_available(device, common_members + i) ? common_members + i : NULL;
		}
	}
	for (int i = 0; i < device->type->member_count; i++) {
		if (matches_lower(device->type->members[i].name, element)) {
			return member_available(device, device->type->members + i) ? device->type->members + i : NULL;
		}
	}
	return NULL;
}

// The error armed for a member through PUT /simulator/v1/<type>/<n>/error, if any.
static alpaca_override *find_override(alpaca_device *device, const alpaca_member *member) {
	for (int i = 0; i < ALPACA_MAX_OVERRIDES; i++) {
		if (device->overrides[i].count != 0 && matches_lower(member->name, device->overrides[i].member)) {
			return device->overrides + i;
		}
	}
	return NULL;
}

static void call_getter(alpaca_device *device, alpaca_request *request) {
	if (request->member->get != NULL) {
		request->member->get(device, request);
	} else {
		alpaca_reply_member(device, request);
	}
}

// DeviceState is built from the getters of the ALPACA_STATE members, so it can never disagree with them.
static void common_get_devicestate(alpaca_device *device, alpaca_request *request) {
	char timestamp[64];
	bool first = true;
	alpaca_buffer_append(&request->value, "[", 1);
	for (int i = 0; i < device->type->member_count; i++) {
		const alpaca_member *member = device->type->members + i;
		if ((member->flags & ALPACA_STATE) && member_available(device, member) && find_override(device, member) == NULL) {
			alpaca_request probe = { .method = ALPACA_GET, .member = member, .status = 200 };
			call_getter(device, &probe);
			if (probe.status == 200 && probe.error_number == 0 && probe.value.length > 0) {
				alpaca_buffer_printf(&request->value, "%s{\"Name\":\"%s\",\"Value\":%s}", first ? "" : ",", member->name, probe.value.data);
				first = false;
			}
			free(probe.value.data);
		}
	}
	if (device->type->device_state != NULL) {
		device->type->device_state(device, &request->value, &first);
	}
	alpaca_format_utc(alpaca_utc(), timestamp, sizeof(timestamp));
	alpaca_buffer_printf(&request->value, "%s{\"Name\":\"TimeStamp\",\"Value\":\"%s\"}]", first ? "" : ",", timestamp);
	alpaca_reply_void(request);
}

#pragma mark - faults

static bool match_fault(const char *method, const char *path, fault_rule *fault) {
	for (int i = 0; i < fault_count; i++) {
		fault_rule *rule = faults + i;
		if (rule->count == 0 || (strcmp(rule->method, "*") && strcmp(rule->method, method)) || !glob_match(rule->path, path)) {
			continue;
		}
		if (rule->skip > 0) {
			rule->skip--;
			continue;
		}
		rule->hits++;
		if (rule->count > 0) {
			rule->count--;
		}
		*fault = *rule;
		return true;
	}
	return false;
}

static bool has_fault(const http_exchange *exchange, fault_action action) {
	return exchange->has_fault && exchange->fault.action == action;
}

#pragma mark - responses

static void respond_text(http_exchange *exchange, int status, const char *format, ...) {
	char text[1024];
	va_list args;
	va_start(args, format);
	vsnprintf(text, sizeof(text), format, args);
	va_end(args);
	exchange->status = status;
	exchange->response_type = "text/plain; charset=utf-8";
	exchange->response.length = 0;
	alpaca_buffer_append(&exchange->response, text, strlen(text));
}

static void append_transaction_ids(http_exchange *exchange, unsigned client_transaction_id, unsigned transaction_id) {
	if (has_fault(exchange, FAULT_WRONG_TRANSACTION_ID)) {
		client_transaction_id = exchange->fault.has_value ? (unsigned)exchange->fault.value : client_transaction_id + 1000;
	}
	if (has_fault(exchange, FAULT_MISSING_TRANSACTION_ID)) {
		// a server that does not implement the echo at all
		alpaca_buffer_printf(&exchange->response, "\"ServerTransactionID\":%u", transaction_id);
		return;
	}
	alpaca_buffer_printf(&exchange->response, "\"ClientTransactionID\":%u,\"ServerTransactionID\":%u", client_transaction_id, transaction_id);
}

// The value the ASCOM .NET servers put next to a non-zero ErrorNumber: the default of the type of the member.
static void append_error_value(alpaca_buffer *buffer, const alpaca_member *member) {
	switch (member != NULL ? member->kind : ALPACA_NONE) {
		case ALPACA_BOOL:
			alpaca_buffer_printf(buffer, "\"Value\":false,");
			break;
		case ALPACA_STRING:
			alpaca_buffer_printf(buffer, "\"Value\":\"\",");
			break;
		default:
			alpaca_buffer_printf(buffer, "\"Value\":0,");
			break;
	}
}

static void append_element(alpaca_buffer *buffer, int element_type, int32_t value) {
	unsigned char bytes[8] = { 0 };
	uint64_t bits = (uint64_t)(int64_t)value;
	size_t size = 4;
	float single = (float)value;
	double real = (double)value;
	uint32_t single_bits = 0;
	switch (element_type) {
		case ALPACA_ELEMENT_BYTE:
			size = 1;
			break;
		case ALPACA_ELEMENT_INT16:
		case ALPACA_ELEMENT_UINT16:
			size = 2;
			break;
		case ALPACA_ELEMENT_INT64:
		case ALPACA_ELEMENT_UINT64:
			size = 8;
			break;
		case ALPACA_ELEMENT_SINGLE:
			memcpy(&single_bits, &single, sizeof(single_bits));
			bits = single_bits;
			break;
		case ALPACA_ELEMENT_DOUBLE:
			memcpy(&bits, &real, sizeof(bits));
			size = 8;
			break;
		default:
			break;
	}
	for (size_t i = 0; i < size; i++) {
		bytes[i] = (unsigned char)(bits >> (8 * i));
	}
	alpaca_buffer_append(buffer, bytes, size);
}

static void append_int32(alpaca_buffer *buffer, int32_t value) {
	append_element(buffer, ALPACA_ELEMENT_INT32, value);
}

// ImageBytes: 44 byte little-endian header, then the pixels or, on error, the UTF-8 message.
static void respond_imagebytes(http_exchange *exchange, alpaca_request *request, unsigned client_transaction_id, unsigned transaction_id) {
	const alpaca_image *image = &request->image;
	const fault_rule *fault = &exchange->fault;
	int error_number = request->error_number;
	const char *error_message = request->error_message;
	int version = 1;
	int data_start = IMAGEBYTES_HEADER_SIZE;
	int transmission_type = image->transmission_type;
	int rank = image->planes > 1 ? 3 : 2;
	int width = image->width;
	size_t count = (size_t)image->width * (size_t)image->height * (size_t)(image->planes > 1 ? image->planes : 1);
	if (has_fault(exchange, FAULT_IMAGEBYTES_ERROR)) {
		error_number = fault->has_value ? fault->value : ALPACA_ERROR_INVALID_OPERATION;
		error_message = *fault->message ? fault->message : "Injected ImageBytes error";
	} else if (has_fault(exchange, FAULT_IMAGEBYTES_VERSION)) {
		version = fault->has_value ? fault->value : 2;
	} else if (has_fault(exchange, FAULT_IMAGEBYTES_DATASTART)) {
		data_start = fault->has_value ? fault->value : 8;
	} else if (has_fault(exchange, FAULT_IMAGEBYTES_TYPE)) {
		transmission_type = fault->has_value ? fault->value : 99;
	} else if (has_fault(exchange, FAULT_IMAGEBYTES_RANK)) {
		rank = fault->has_value ? fault->value : 5;
	} else if (has_fault(exchange, FAULT_IMAGEBYTES_DIMENSIONS)) {
		width += fault->has_value ? fault->value : 1;
	} else if (has_fault(exchange, FAULT_IMAGEBYTES_SHORT)) {
		count /= 2;
	}
	if (has_fault(exchange, FAULT_WRONG_TRANSACTION_ID)) {
		client_transaction_id = fault->has_value ? (unsigned)fault->value : client_transaction_id + 1000;
	}
	exchange->status = 200;
	exchange->response_type = "application/imagebytes";
	exchange->error_number = error_number;
	append_int32(&exchange->response, version);
	append_int32(&exchange->response, error_number);
	append_int32(&exchange->response, (int32_t)client_transaction_id);
	append_int32(&exchange->response, (int32_t)transaction_id);
	append_int32(&exchange->response, data_start);
	if (error_number != 0 || image->pixels == NULL) {
		for (int i = 0; i < 6; i++) {
			append_int32(&exchange->response, 0);
		}
	} else {
		append_int32(&exchange->response, image->element_type);
		append_int32(&exchange->response, transmission_type);
		append_int32(&exchange->response, rank);
		append_int32(&exchange->response, width);
		append_int32(&exchange->response, image->height);
		append_int32(&exchange->response, image->planes > 1 ? image->planes : 0);
	}
	for (int i = IMAGEBYTES_HEADER_SIZE; i < data_start; i++) {
		alpaca_buffer_append(&exchange->response, "", 1);
	}
	if (error_number != 0 || image->pixels == NULL) {
		alpaca_buffer_append(&exchange->response, error_message, strlen(error_message));
		return;
	}
	buffer_reserve(&exchange->response, count * 8);
	for (size_t i = 0; i < count; i++) {
		append_element(&exchange->response, image->transmission_type, image->pixels[i]);
	}
}

static void append_json_image(alpaca_buffer *buffer, const alpaca_image *image) {
	char text[16];
	const int32_t *pixel = image->pixels;
	const char *suffix = image->element_type == ALPACA_ELEMENT_DOUBLE ? ".0" : "";
	int planes = image->planes > 1 ? image->planes : 1;
	buffer_reserve(buffer, (size_t)image->width * (size_t)image->height * (size_t)planes * 8);
	alpaca_buffer_append(buffer, "[", 1);
	for (int x = 0; x < image->width; x++) {
		alpaca_buffer_append(buffer, x ? ",[" : "[", x ? 2 : 1);
		for (int y = 0; y < image->height; y++) {
			if (y) {
				alpaca_buffer_append(buffer, ",", 1);
			}
			if (image->planes > 1) {
				alpaca_buffer_append(buffer, "[", 1);
			}
			for (int plane = 0; plane < planes; plane++) {
				int length = snprintf(text, sizeof(text), "%s%d%s", plane ? "," : "", (int)*pixel++, suffix);
				alpaca_buffer_append(buffer, text, (size_t)length);
			}
			if (image->planes > 1) {
				alpaca_buffer_append(buffer, "]", 1);
			}
		}
		alpaca_buffer_append(buffer, "]", 1);
	}
	alpaca_buffer_append(buffer, "]", 1);
}

static void respond_alpaca(http_exchange *exchange, alpaca_request *request, unsigned client_transaction_id) {
	if (request->status != 200) {
		respond_text(exchange, request->status, "%s", request->status_text);
		return;
	}
	unsigned transaction_id = ++server_transaction_id;
	bool image_member = request->member != NULL && (request->member->flags & ALPACA_IMAGE);
	bool has_image = request->image.pixels != NULL && request->error_number == 0;
	if (image_member && request->accepts_imagebytes && !has_fault(exchange, FAULT_IMAGEBYTES_JSON)) {
		respond_imagebytes(exchange, request, client_transaction_id, transaction_id);
		return;
	}
	exchange->status = 200;
	exchange->response_type = "application/json; charset=utf-8";
	exchange->error_number = request->error_number;
	alpaca_buffer_append(&exchange->response, "{", 1);
	if (has_image) {
		alpaca_buffer_printf(&exchange->response, "\"Type\":%d,\"Rank\":%d,", request->image.element_type, request->image.planes > 1 ? 3 : 2);
	}
	if (has_fault(exchange, FAULT_NULL_VALUE)) {
		alpaca_buffer_printf(&exchange->response, "\"Value\":null,");
	} else if (request->error_number != 0 && options.error_value && request->method == ALPACA_GET && !has_fault(exchange, FAULT_MISSING_VALUE)) {
		append_error_value(&exchange->response, request->member);
	} else if (request->error_number == 0 && !has_fault(exchange, FAULT_MISSING_VALUE)) {
		if (has_image) {
			alpaca_buffer_printf(&exchange->response, "\"Value\":");
			append_json_image(&exchange->response, &request->image);
			alpaca_buffer_append(&exchange->response, ",", 1);
		} else if (request->value.length > 0) {
			alpaca_buffer_printf(&exchange->response, "\"Value\":%s,", request->value.data);
		}
	}
	append_transaction_ids(exchange, client_transaction_id, transaction_id);
	alpaca_buffer_printf(&exchange->response, ",\"ErrorNumber\":%d,\"ErrorMessage\":", request->error_number);
	alpaca_buffer_json_string(&exchange->response, request->error_number ? request->error_message : "");
	alpaca_buffer_append(&exchange->response, "}", 1);
}

#pragma mark - device API

static void dispatch_member(alpaca_device *device, alpaca_request *request) {
	const alpaca_member *member = request->member;
	alpaca_override *override = find_override(device, member);
	if (override != NULL) {
		if (override->count > 0) {
			override->count--;
		}
		alpaca_reply_error(request, override->error_number, "%s", override->error_message);
		return;
	}
	if (!device->connected && !(member->flags & ALPACA_OFFLINE)) {
		alpaca_reply_error(request, ALPACA_ERROR_NOT_CONNECTED, "%s is not connected", device->name);
		return;
	}
	if (request->method == ALPACA_GET) {
		call_getter(device, request);
	} else if (member->put != NULL) {
		member->put(device, request);
	} else if (alpaca_store_member(device, request)) {
		alpaca_reply_void(request);
	}
	if (!request->replied) {
		alpaca_reply_error(request, ALPACA_ERROR_UNSPECIFIED, "%s did not answer", member->name);
	}
}

// rest is "<type>/<number>/<member>" of /api/v1/<type>/<number>/<member>
static void handle_device_api(http_exchange *exchange, char *rest) {
	alpaca_request request = { .status = 200 };
	char *number_text = strchr(rest, '/');
	char *member_text = number_text ? strchr(number_text + 1, '/') : NULL;
	int number = 0;
	if (number_text == NULL || member_text == NULL || strchr(member_text + 1, '/') != NULL) {
		respond_text(exchange, 400, "Bad path, expected /api/v1/{device_type}/{device_number}/{member}");
		return;
	}
	*number_text++ = '\0';
	*member_text++ = '\0';
	const alpaca_type *type = find_type(rest, true);
	if (type == NULL) {
		respond_text(exchange, 400, "Unknown device type '%s'", rest);
		return;
	}
	if (!isdigit((unsigned char)*number_text) || !alpaca_parse_int(number_text, &number)) {
		respond_text(exchange, 400, "Invalid device number '%s'", number_text);
		return;
	}
	alpaca_device *device = find_device(type, number);
	if (device == NULL) {
		respond_text(exchange, 400, "No %s device number %d", type->name, number);
		return;
	}
	if (!strcmp(exchange->method, "GET")) {
		request.method = ALPACA_GET;
		request.param_count = parse_params(exchange->query, request.params, ALPACA_MAX_PARAMS);
	} else if (!strcmp(exchange->method, "PUT")) {
		request.method = ALPACA_PUT;
		request.param_count = parse_params(exchange->body, request.params, ALPACA_MAX_PARAMS);
	} else {
		respond_text(exchange, 400, "Invalid method %s", exchange->method);
		return;
	}
	bool wrong_case = false;
	unsigned client_transaction_id = parse_transaction_id(find_param(&request, "ClientTransactionID", &wrong_case));
	request.accepts_imagebytes = strcasestr(exchange->accept, "application/imagebytes") != NULL;
	request.member = find_member(device, member_text);
	device_update(device);
	if (request.member == NULL && device->missing_member == ALPACA_ERROR_NOT_IMPLEMENTED) {
		alpaca_reply_error(&request, ALPACA_ERROR_NOT_IMPLEMENTED, "%s is not implemented", member_text);
	} else if (request.member == NULL) {
		respond_text(exchange, device->missing_member, "Unknown %s member '%s'", type->name, member_text);
		return;
	} else if (request.method == ALPACA_GET ? request.member->get == NULL && !(request.member->flags & ALPACA_R) : request.member->put == NULL && !(request.member->flags & ALPACA_W)) {
		respond_text(exchange, 400, "Invalid method %s for %s", exchange->method, member_text);
		return;
	} else if (has_fault(exchange, FAULT_ASCOM_ERROR)) {
		alpaca_reply_error(&request, exchange->fault.has_value ? exchange->fault.value : ALPACA_ERROR_UNSPECIFIED, "%s", *exchange->fault.message ? exchange->fault.message : "Injected error");
	} else {
		dispatch_member(device, &request);
	}
	respond_alpaca(exchange, &request, client_transaction_id);
	clock_microseconds += llround(options.tick_per_request * 1e6);
	free(request.value.data);
	free(request.image.pixels);
}

