static int hex_digit(int c) {
	return isdigit(c) ? c - '0' : tolower(c) - 'a' + 10;
}

static void url_decode(char *text) {
	char *target = text;
	for (char *cursor = text; *cursor; cursor++) {
		if (*cursor == '+') {
			*target++ = ' ';
		} else if (*cursor == '%' && isxdigit((unsigned char)cursor[1]) && isxdigit((unsigned char)cursor[2])) {
			*target++ = (char)(hex_digit((unsigned char)cursor[1]) * 16 + hex_digit((unsigned char)cursor[2]));
			cursor += 2;
		} else {
			*target++ = *cursor;
		}
	}
	*target = '\0';
}

// Splits "a=1&b=2" in place and decodes names and values.
static int parse_params(char *text, alpaca_param *params, int max) {
	int count = 0;
	char *cursor = text;
	while (cursor != NULL && *cursor && count < max) {
		char *next = strchr(cursor, '&');
		if (next != NULL) {
			*next++ = '\0';
		}
		if (*cursor) {
			char *value = strchr(cursor, '=');
			if (value != NULL) {
				*value++ = '\0';
			} else {
				value = cursor + strlen(cursor);
			}
			url_decode(cursor);
			url_decode(value);
			params[count].name = cursor;
			params[count].value = value;
			count++;
		}
		cursor = next;
	}
	return count;
}

