// Accepts "--name value" and "--name=value".
static bool option_value(int argc, char *argv[], int *index, const char *name, const char **value) {
	size_t length = strlen(name);
	if (strncmp(argv[*index], name, length)) {
		return false;
	}
	if (argv[*index][length] == '=') {
		*value = argv[*index] + length + 1;
		return true;
	}
	if (argv[*index][length] != '\0') {
		return false;
	}
	if (*index + 1 == argc) {
		fprintf(stderr, "%s requires a value\n", name);
		exit(2);
	}
	*value = argv[++*index];
	return true;
}

static bool parse_args(int argc, char *argv[], const char **device_options, int *device_option_count) {
	const char *value = NULL;
	for (int i = 1; i < argc; i++) {
		if (!strcmp(argv[i], "-h") || !strcmp(argv[i], "--help")) {
			usage(argv[0]);
			exit(0);
		} else if (!strcmp(argv[i], "--headless")) {
			options.headless = true;
		} else if (!strcmp(argv[i], "--trace")) {
			options.trace = true;
		} else if (!strcmp(argv[i], "--indigo-bridge")) {
			copy_text(options.server_name, sizeof(options.server_name), "INDIGO-Alpaca Bridge");
			copy_text(options.manufacturer, sizeof(options.manufacturer), "The INDIGO Initiative");
			copy_text(options.manufacturer_version, sizeof(options.manufacturer_version), "3.0-8");
			copy_text(options.location, sizeof(options.location), "");
		} else if (!strcmp(argv[i], "--no-devices")) {
			options.default_devices = false;
		} else if (!strcmp(argv[i], "--no-parent-watch")) {
			options.parent_watch = false;
		} else if (!strcmp(argv[i], "--error-value")) {
			options.error_value = true;
		} else if (!strcmp(argv[i], "--any-content-type")) {
			options.any_content_type = true;
		} else if (option_value(argc, argv, &i, "--ready-file", &value)) {
			options.ready_file = value;
		} else if (option_value(argc, argv, &i, "--event-file", &value)) {
			options.event_file = value;
		} else if (option_value(argc, argv, &i, "--bind", &value)) {
			options.bind_address = value;
		} else if (option_value(argc, argv, &i, "--port", &value)) {
			if (!alpaca_parse_int(value, &options.port) || options.port < 0 || options.port > 65535) {
				fprintf(stderr, "--port %s is not a port\n", value);
				return false;
			}
		} else if (option_value(argc, argv, &i, "--discovery-port", &value)) {
			options.discovery = true;
			if (!alpaca_parse_int(value, &options.discovery_port) || options.discovery_port < 0 || options.discovery_port > 65535) {
				fprintf(stderr, "--discovery-port %s is not a port\n", value);
				return false;
			}
		} else if (option_value(argc, argv, &i, "--discovery-bind", &value)) {
			options.discovery_bind = value;
		} else if (option_value(argc, argv, &i, "--clock", &value)) {
			if (strcmp(value, "manual") && strcmp(value, "real")) {
				fprintf(stderr, "--clock %s is not manual or real\n", value);
				return false;
			}
			options.real_clock = !strcmp(value, "real");
		} else if (option_value(argc, argv, &i, "--tick-per-request", &value)) {
			if (!alpaca_parse_double(value, &options.tick_per_request) || options.tick_per_request < 0) {
				fprintf(stderr, "--tick-per-request %s is not a positive number\n", value);
				return false;
			}
		} else if (option_value(argc, argv, &i, "--connect-delay", &value)) {
			if (!alpaca_parse_double(value, &options.connect_delay) || options.connect_delay < 0) {
				fprintf(stderr, "--connect-delay %s is not a positive number\n", value);
				return false;
			}
		} else if (option_value(argc, argv, &i, "--server-name", &value)) {
			copy_text(options.server_name, sizeof(options.server_name), value);
		} else if (option_value(argc, argv, &i, "--manufacturer-version", &value)) {
			copy_text(options.manufacturer_version, sizeof(options.manufacturer_version), value);
		} else if (option_value(argc, argv, &i, "--manufacturer", &value)) {
			copy_text(options.manufacturer, sizeof(options.manufacturer), value);
		} else if (option_value(argc, argv, &i, "--location", &value)) {
			copy_text(options.location, sizeof(options.location), value);
		} else if (option_value(argc, argv, &i, "--uid-prefix", &value)) {
			copy_text(options.uid_prefix, sizeof(options.uid_prefix), value);
		} else if (option_value(argc, argv, &i, "--interface", &value)) {
			if (strcmp(value, "p7") && strcmp(value, "legacy")) {
				fprintf(stderr, "--interface %s is not p7 or legacy\n", value);
				return false;
			}
			options.legacy_interface = !strcmp(value, "legacy");
		} else if (option_value(argc, argv, &i, "--device", &value)) {
			if (*device_option_count == MAX_DEVICE_OPTIONS) {
				fprintf(stderr, "Too many --device options\n");
				return false;
			}
			device_options[(*device_option_count)++] = value;
		} else {
			fprintf(stderr, "Unknown option '%s'\n", argv[i]);
			return false;
		}
	}
	return true;
}

static bool create_devices(const char **device_options, int device_option_count) {
	char error[256] = { 0 };
	if (device_option_count == 0 && options.default_devices) {
		for (int i = 0; i < ALPACA_TYPE_COUNT; i++) {
			if (device_create(alpaca_types[i], "", error, sizeof(error)) == NULL) {
				fprintf(stderr, "%s: %s\n", alpaca_types[i]->name, error);
				return false;
			}
		}
	}
	for (int i = 0; i < device_option_count; i++) {
		char type_name[64];
		const char *settings = strchr(device_options[i], ':');
		snprintf(type_name, sizeof(type_name), "%.*s", settings ? (int)(settings - device_options[i]) : (int)strlen(device_options[i]), device_options[i]);
		const alpaca_type *type = find_type(type_name, false);
		if (type == NULL) {
			fprintf(stderr, "--device %s: unknown device type '%s'\n", device_options[i], type_name);
			return false;
		}
		if (device_create(type, settings ? settings + 1 : "", error, sizeof(error)) == NULL) {
			fprintf(stderr, "--device %s: %s\n", device_options[i], error);
			return false;
		}
	}
	return true;
}

static void close_all(void) {
	reap_connections(true);
	if (http_fd >= 0) {
		close(http_fd);
	}
	if (discovery_fd >= 0) {
		close(discovery_fd);
	}
	close(wake_pipe[0]);
	close(wake_pipe[1]);
	clear_records();
	free(records);
	for (int i = 0; i < device_count; i++) {
		device_free(devices[i]);
	}
	device_count = 0;
	alpaca_event("CLOSE", "simulator");
	if (events != NULL) {
		fclose(events);
		events = NULL;
	}
}

int main(int argc, char *argv[]) {
	const char *device_options[MAX_DEVICE_OPTIONS];
	char event_file[PATH_MAX] = { 0 };
	int device_option_count = 0;
	pid_t parent = getppid();
	if (!parse_args(argc, argv, device_options, &device_option_count)) {
		return 2;
	}
	if (options.event_file != NULL) {
		copy_text(event_file, sizeof(event_file), options.event_file);
	} else if (getenv("INDIGO_SYSTEM_ALPACA_EVENTS") != NULL) {
		copy_text(event_file, sizeof(event_file), getenv("INDIGO_SYSTEM_ALPACA_EVENTS"));
	} else if (options.ready_file != NULL) {
		snprintf(event_file, sizeof(event_file), "%s.events", options.ready_file);
	}
	events = *event_file ? fopen(event_file, "a") : NULL;
	clock_real_start = monotonic_time();
	utc_base = options.real_clock ? (double)time(NULL) : MANUAL_CLOCK_UTC;
	if (pipe(wake_pipe) != 0) {
		perror("pipe");
		return 1;
	}
	signal(SIGPIPE, SIG_IGN);
	signal(SIGINT, signal_handler);
	signal(SIGTERM, signal_handler);
	if (!create_devices(device_options, device_option_count)) {
		close_all();
		return 2;
	}
	http_fd = open_socket(SOCK_STREAM, options.bind_address, options.port, &http_port);
	if (http_fd >= 0 && options.discovery) {
		discovery_fd = open_socket(SOCK_DGRAM, options.discovery_bind, options.discovery_port, &discovery_port);
	}
	if (http_fd < 0 || (options.discovery && discovery_fd < 0)) {
		close_all();
		return 1;
	}
	alpaca_event("OPEN", "http=%s:%d discovery=%d clock=%s devices=%d", options.bind_address, http_port, discovery_port, options.real_clock ? "real" : "manual", device_count);
	if (options.ready_file != NULL && !write_ready_file()) {
		close_all();
		return 1;
	}
	if (!options.headless) {
		printf("Alpaca simulator ready on http://%s:%d, discovery port %d, %d devices\n", options.bind_address, http_port, discovery_port, device_count);
		fflush(stdout);
	}
	while (running) {
		struct pollfd fds[3] = { { .fd = wake_pipe[0], .events = POLLIN }, { .fd = http_fd, .events = POLLIN }, { .fd = discovery_fd, .events = POLLIN } };
		int timeout = flush_pending_replies();
		int ready = poll(fds, discovery_fd >= 0 ? 3 : 2, timeout);
		if (ready < 0 && errno != EINTR) {
			break;
		}
		if (options.parent_watch && getppid() != parent) {
			// the test that started the simulator is gone, nobody is left to stop it
			alpaca_event("STATE", "parent process exited");
			break;
		}
		if (ready <= 0) {
			reap_connections(false);
			continue;
		}
		if (fds[0].revents) {
			break;
		}
		if (fds[1].revents & POLLIN) {
			accept_connection();
		}
		if (discovery_fd >= 0 && (fds[2].revents & POLLIN)) {
			handle_discovery();
		}
	}
	request_shutdown();
	close_all();
	return 0;
}
