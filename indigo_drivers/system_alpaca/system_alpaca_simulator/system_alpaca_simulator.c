static const alpaca_type *find_type(const char *name, bool lower_case_only) {
	for (int i = 0; i < ALPACA_TYPE_COUNT; i++) {
		if (lower_case_only ? matches_lower(alpaca_types[i]->name, name) : !strcasecmp(alpaca_types[i]->name, name)) {
			return alpaca_types[i];
		}
	}
	return NULL;
}

static int type_index(const alpaca_type *type) {
	for (int i = 0; i < ALPACA_TYPE_COUNT; i++) {
		if (alpaca_types[i] == type) {
			return i;
		}
	}
	return -1;
}

static alpaca_device *find_device(const alpaca_type *type, int number) {
	for (int i = 0; i < device_count; i++) {
		if (devices[i]->type == type && devices[i]->number == number) {
			return devices[i];
		}
	}
	return NULL;
}

static bool is_platform7(const alpaca_device *device) {
	return device->interface_version >= device->type->interface_version;
}

static const alpaca_member *find_field(const alpaca_device *device, const char *name) {
	for (int i = 0; i < device->type->member_count; i++) {
		if (device->type->members[i].kind != ALPACA_NONE && !strcmp(device->type->members[i].name, name)) {
			return device->type->members + i;
		}
	}
	return NULL;
}

// Sets one setting of a device: used by --device, by PUT .../state and by PUT /simulator/v1/devices.
static bool device_set(alpaca_device *device, const char *key, const char *value) {
	bool flag = false;
	int integer = 0;
	double number = 0;
	if (!strcmp(key, "Number") || !strcmp(key, "number")) {
		if (!alpaca_parse_int(value, &integer) || integer < 0) {
			return false;
		}
		device->number = integer;
	} else if (!strcmp(key, "Name") || !strcmp(key, "name")) {
		copy_text(device->name, sizeof(device->name), value);
	} else if (!strcmp(key, "UniqueID") || !strcmp(key, "uid")) {
		copy_text(device->unique_id, sizeof(device->unique_id), value);
	} else if (!strcmp(key, "InterfaceVersion") || !strcmp(key, "interface")) {
		if (!strcasecmp(value, "p7")) {
			device->interface_version = device->type->interface_version;
		} else if (!strcasecmp(value, "legacy")) {
			device->interface_version = device->type->legacy_interface_version;
		} else if (alpaca_parse_int(value, &integer) && integer > 0) {
			device->interface_version = integer;
		} else {
			return false;
		}
	} else if (!strcmp(key, "Description")) {
		copy_text(device->description, sizeof(device->description), value);
	} else if (!strcmp(key, "DriverInfo")) {
		copy_text(device->driver_info, sizeof(device->driver_info), value);
	} else if (!strcmp(key, "DriverVersion")) {
		copy_text(device->driver_version, sizeof(device->driver_version), value);
	} else if (!strcmp(key, "SupportedActions")) {
		copy_text(device->supported_actions, sizeof(device->supported_actions), value);
	} else if (!strcmp(key, "Commands")) {
		if (!alpaca_parse_bool(value, &flag)) {
			return false;
		}
		device->commands = flag;
	} else if (!strcmp(key, "MissingMember")) {
		if (!alpaca_parse_int(value, &integer) || (integer != 400 && integer != 404 && integer != ALPACA_ERROR_NOT_IMPLEMENTED)) {
			return false;
		}
		device->missing_member = integer;
	} else if (!strcmp(key, "Connected")) {
		if (!alpaca_parse_bool(value, &flag)) {
			return false;
		}
		device->connected = flag;
		device->connecting = false;
	} else if (!strcmp(key, "ConnectDelay")) {
		if (!alpaca_parse_double(value, &number) || number < 0) {
			return false;
		}
		device->connect_delay = number;
	} else if (device->type->control != NULL && device->type->control(device, key, value)) {
		return true;
	} else {
		const alpaca_member *member = find_field(device, key);
		return member != NULL && store_field(device, member, value, false) == 0;
	}
	return true;
}

// Applies "key=value,key=value"; a failure names the offending setting in error.
static bool device_configure(alpaca_device *device, const char *settings, char *error, size_t error_size) {
	char text[sizeof(device->options)];
	copy_text(text, sizeof(text), settings);
	char *cursor = text;
	while (cursor != NULL && *cursor) {
		char *next = strchr(cursor, ',');
		if (next != NULL) {
			*next++ = '\0';
		}
		char *value = strchr(cursor, '=');
		if (value == NULL) {
			snprintf(error, error_size, "'%s' is not key=value", cursor);
			return false;
		}
		*value++ = '\0';
		if (!device_set(device, cursor, value)) {
			snprintf(error, error_size, "%s does not accept %s=%s", device->type->name, cursor, value);
			return false;
		}
		cursor = next;
	}
	return true;
}

// Defaults, then the settings the device was created with: this is the state a reset returns to.
static bool device_init(alpaca_device *device, char *error, size_t error_size) {
	const alpaca_type *type = device->type;
	memset(device->state, 0, type->state_size);
	memset(device->overrides, 0, sizeof(device->overrides));
	if (device->number == 0) {
		snprintf(device->name, sizeof(device->name), "%s Simulator", type->name);
	} else {
		snprintf(device->name, sizeof(device->name), "%s Simulator %d", type->name, device->number);
	}
	snprintf(device->unique_id, sizeof(device->unique_id), "%s-%04x-4000-8000-%012x", options.uid_prefix, type_index(type) + 1, (unsigned)device->number);
	snprintf(device->description, sizeof(device->description), "INDIGO Alpaca %s simulator", type->name);
	snprintf(device->driver_info, sizeof(device->driver_info), "system_alpaca_simulator %s device", type->name);
	copy_text(device->driver_version, sizeof(device->driver_version), SIMULATOR_VERSION);
	*device->supported_actions = '\0';
	device->commands = false;
	device->interface_version = options.legacy_interface ? type->legacy_interface_version : type->interface_version;
	device->missing_member = 400;
	device->connected = false;
	device->connecting = false;
	device->connect_delay = options.connect_delay;
	type->reset(device);
	return device_configure(device, device->options, error, error_size);
}

static void device_free(alpaca_device *device) {
	free(device->state);
	free(device);
}

static alpaca_device *device_create(const alpaca_type *type, const char *settings, char *error, size_t error_size) {
	if (device_count == MAX_DEVICES) {
		snprintf(error, error_size, "too many devices");
		return NULL;
	}
	if (strlen(settings) >= sizeof(((alpaca_device *)NULL)->options)) {
		snprintf(error, error_size, "device settings are too long");
		return NULL;
	}
	alpaca_device *device = calloc(1, sizeof(alpaca_device));
	void *state = calloc(1, type->state_size ? type->state_size : 1);
	if (device == NULL || state == NULL) {
		perror("calloc");
		abort();
	}
	device->type = type;
	device->state = state;
	while (find_device(type, device->number) != NULL) {
		device->number++;
	}
	copy_text(device->options, sizeof(device->options), settings);
	int number = device->number;
	if (!device_init(device, error, error_size)) {
		device_free(device);
		return NULL;
	}
	if (device->number != number) {
		// the number is part of the default name and UniqueID, so the defaults are built again around it
		if (find_device(type, device->number) != NULL) {
			snprintf(error, error_size, "%s %d already exists", type->name, device->number);
			device_free(device);
			return NULL;
		}
		device_init(device, error, error_size);
	}
	devices[device_count++] = device;
	alpaca_event("STATE", "device %s/%d name='%s' uid=%s interface=%d", type->name, device->number, device->name, device->unique_id, device->interface_version);
	return device;
}

static void device_update(alpaca_device *device) {
	if (device->connecting && alpaca_reached(device->connect_deadline)) {
		device->connecting = false;
		device->connected = device->connect_target;
		alpaca_event("STATE", "%s/%d connected=%d", device->type->name, device->number, device->connected);
	}
	if (device->type->update != NULL) {
		device->type->update(device);
	}
}

