static void control_add_fault(http_exchange *exchange, const alpaca_param *params, int count) {
	fault_rule rule = { .method = "*", .count = 1, .bytes = -1, .dispatch = true };
	const char *method = plain_param(params, count, "Method");
	const char *path = plain_param(params, count, "Path");
	const char *action = plain_param(params, count, "Action");
	const char *message = plain_param(params, count, "Message");
	const char *dispatch = plain_param(params, count, "Dispatch");
	if (path == NULL || action == NULL) {
		control_error(exchange, "Path and Action are required");
		return;
	}
	if (fault_count == MAX_FAULTS) {
		control_error(exchange, "Too many fault rules, clear them first");
		return;
	}
	for (int i = 1; i < FAULT_ACTION_COUNT; i++) {
		if (!strcmp(action, fault_names[i])) {
			rule.action = (fault_action)i;
		}
	}
	if (rule.action == FAULT_NONE) {
		control_error(exchange, "Unknown Action=%s", action);
		return;
	}
	if (method != NULL && strcmp(method, "*") && strcmp(method, "GET") && strcmp(method, "PUT")) {
		control_error(exchange, "Method=%s is not GET, PUT or *", method);
		return;
	}
	rule.has_value = plain_param(params, count, "Value") != NULL;
	rule.dispatch = rule.action != FAULT_HTTP_STATUS && rule.action != FAULT_ASCOM_ERROR;
	if (dispatch != NULL && !alpaca_parse_bool(dispatch, &rule.dispatch)) {
		control_error(exchange, "Dispatch=%s is not a boolean", dispatch);
		return;
	}
	if (!control_int(exchange, params, count, "Skip", &rule.skip) || !control_int(exchange, params, count, "Count", &rule.count) || !control_int(exchange, params, count, "Value", &rule.value) || !control_int(exchange, params, count, "Delay", &rule.delay) || !control_int(exchange, params, count, "Bytes", &rule.bytes)) {
		return;
	}
	if (rule.skip < 0 || rule.delay < 0 || rule.count == 0) {
		control_error(exchange, "Skip and Delay can not be negative and Count can not be 0");
		return;
	}
	if ((rule.action == FAULT_STALL_BEFORE || rule.action == FAULT_STALL_WITHIN) && rule.delay == 0) {
		control_error(exchange, "%s needs Delay in milliseconds", action);
		return;
	}
	if (rule.action == FAULT_HTTP_STATUS && rule.has_value && (rule.value < 100 || rule.value > 599)) {
		control_error(exchange, "Value=%d is not an HTTP status", rule.value);
		return;
	}
	copy_text(rule.method, sizeof(rule.method), method ? method : "*");
	copy_text(rule.path, sizeof(rule.path), path);
	copy_text(rule.message, sizeof(rule.message), message ? message : "");
	rule.id = ++fault_sequence;
	faults[fault_count++] = rule;
	alpaca_event("CONTROL", "fault id=%d method=%s path=%s action=%s skip=%d count=%d value=%d delay=%d bytes=%d", rule.id, rule.method, rule.path, action, rule.skip, rule.count, rule.value, rule.delay, rule.bytes);
	alpaca_buffer_field(&exchange->response, "Id", "%d", rule.id);
}

// AlpacaPort is a list separated by '|': one reply is sent for every port, as if that many servers shared the host.
static bool parse_discovery_ports(const char *text, discovery_state *state) {
	char list[128];
	copy_text(list, sizeof(list), text);
	char *cursor = list;
	while (cursor != NULL && *cursor) {
		char *next = strchr(cursor, '|');
		if (next != NULL) {
			*next++ = '\0';
		}
		if (state->alpaca_port_count == MAX_DISCOVERY_PORTS || !alpaca_parse_int(cursor, state->alpaca_ports + state->alpaca_port_count) || state->alpaca_ports[state->alpaca_port_count] < 0 || state->alpaca_ports[state->alpaca_port_count] > 65535) {
			return false;
		}
		state->alpaca_port_count++;
		cursor = next;
	}
	return true;
}

static void control_discovery(http_exchange *exchange, const alpaca_param *params, int count, bool put) {
	static const char *modes[] = { "normal", "silent", "malformed" };
	alpaca_buffer ports = { 0 };
	if (put) {
		discovery_state next = { .copies = 1, .count = -1, .requests = discovery.requests, .replies = discovery.replies };
		const char *mode = plain_param(params, count, "Mode");
		const char *reply = plain_param(params, count, "Reply");
		const char *port_list = plain_param(params, count, "AlpacaPort");
		if (mode == NULL || !strcmp(mode, "normal")) {
			next.mode = DISCOVERY_NORMAL;
		} else if (!strcmp(mode, "silent")) {
			next.mode = DISCOVERY_SILENT;
		} else if (!strcmp(mode, "malformed")) {
			next.mode = DISCOVERY_MALFORMED;
		} else if (!strcmp(mode, "duplicate")) {
			next.copies = 2;
		} else if (!strcmp(mode, "delayed")) {
			next.delay = 500;
		} else {
			control_error(exchange, "Mode=%s is not normal, silent, malformed, duplicate or delayed", mode);
			return;
		}
		if (!control_int(exchange, params, count, "Copies", &next.copies) || !control_int(exchange, params, count, "Delay", &next.delay) || !control_int(exchange, params, count, "Count", &next.count)) {
			return;
		}
		if (port_list != NULL && !parse_discovery_ports(port_list, &next)) {
			control_error(exchange, "AlpacaPort=%s is not a list of at most %d ports separated by '|'", port_list, MAX_DISCOVERY_PORTS);
			return;
		}
		if (next.copies < 1 || next.copies > 16 || next.delay < 0 || next.count == 0) {
			control_error(exchange, "Copies must be 1..16, Delay can not be negative and Count can not be 0");
			return;
		}
		copy_text(next.reply, sizeof(next.reply), reply ? reply : "");
		discovery = next;
		alpaca_event("CONTROL", "discovery mode=%s copies=%d delay=%d count=%d alpaca_port=%s reply='%s'", modes[discovery.mode], discovery.copies, discovery.delay, discovery.count, port_list ? port_list : "", discovery.reply);
	}
	for (int i = 0; i < discovery.alpaca_port_count; i++) {
		alpaca_buffer_printf(&ports, "%s%d", i ? "|" : "", discovery.alpaca_ports[i]);
	}
	if (discovery.alpaca_port_count == 0) {
		alpaca_buffer_printf(&ports, "%d", http_port);
	}
	alpaca_buffer_field(&exchange->response, "Port", "%d", discovery_port);
	alpaca_buffer_field(&exchange->response, "Mode", "%s", modes[discovery.mode]);
	alpaca_buffer_field(&exchange->response, "Copies", "%d", discovery.copies);
	alpaca_buffer_field(&exchange->response, "Delay", "%d", discovery.delay);
	alpaca_buffer_field(&exchange->response, "Count", "%d", discovery.count);
	alpaca_buffer_field(&exchange->response, "AlpacaPort", "%s", ports.data);
	free(ports.data);
	alpaca_buffer_field(&exchange->response, "Reply", "%s", discovery.reply);
	alpaca_buffer_field(&exchange->response, "Requests", "%ld", discovery.requests);
	alpaca_buffer_field(&exchange->response, "Replies", "%ld", discovery.replies);
}

