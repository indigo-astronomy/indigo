static void buffer_reserve(alpaca_buffer *buffer, size_t extra) {
	if (buffer->length + extra + 1 > buffer->capacity) {
		size_t capacity = buffer->capacity ? buffer->capacity * 2 : 256;
		while (capacity < buffer->length + extra + 1) {
			capacity *= 2;
		}
		char *data = realloc(buffer->data, capacity);
		if (data == NULL) {
			perror("realloc");
			abort();
		}
		buffer->data = data;
		buffer->capacity = capacity;
	}
}

void alpaca_buffer_append(alpaca_buffer *buffer, const void *data, size_t length) {
	buffer_reserve(buffer, length);
	memcpy(buffer->data + buffer->length, data, length);
	buffer->length += length;
	buffer->data[buffer->length] = '\0';
}

void alpaca_buffer_printf(alpaca_buffer *buffer, const char *format, ...) {
	va_list args;
	va_start(args, format);
	int length = vsnprintf(NULL, 0, format, args);
	va_end(args);
	if (length < 0) {
		return;
	}
	buffer_reserve(buffer, (size_t)length);
	va_start(args, format);
	vsnprintf(buffer->data + buffer->length, (size_t)length + 1, format, args);
	va_end(args);
	buffer->length += (size_t)length;
}

void alpaca_buffer_json_string(alpaca_buffer *buffer, const char *text) {
	alpaca_buffer_append(buffer, "\"", 1);
	for (const unsigned char *cursor = (const unsigned char *)text; *cursor; cursor++) {
		if (*cursor == '"' || *cursor == '\\') {
			alpaca_buffer_printf(buffer, "\\%c", *cursor);
		} else if (*cursor < 0x20) {
			alpaca_buffer_printf(buffer, "\\u%04x", *cursor);
		} else {
			alpaca_buffer_append(buffer, cursor, 1);
		}
	}
	alpaca_buffer_append(buffer, "\"", 1);
}

static void buffer_url_encoded(alpaca_buffer *buffer, const char *text) {
	for (const unsigned char *cursor = (const unsigned char *)text; *cursor; cursor++) {
		if (isalnum(*cursor) || *cursor == '-' || *cursor == '_' || *cursor == '.' || *cursor == '~' || *cursor == '/' || *cursor == ':' || *cursor == ',') {
			alpaca_buffer_append(buffer, cursor, 1);
		} else {
			alpaca_buffer_printf(buffer, "%%%02X", *cursor);
		}
	}
}

