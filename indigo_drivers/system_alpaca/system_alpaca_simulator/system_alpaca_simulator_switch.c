// The default device has eight switches that cover the cases a client has to
// tell apart: writable boolean (0..3), writable analog with asynchronous set
// (4, 5), read-only analog sensor (6) and read-only boolean (7).
// Control keys beyond the table: Switch<n>.Name, .Description, .Min, .Max,
// .Step, .Value, .CanWrite, .CanAsync, .FixedName and .Stuck, e.g. Switch4.Value=35.
// A device can only have the values MinSwitchValue + n * SwitchStep (ISwitchV2:
// SwitchStep is "the difference between successive values of the device"), so a
// value that is set is rounded to the nearest of them; Switch<n>.Value of the
// control API is the raw state of the device and is stored as it is.
// SetSwitchName is NotImplemented for the whole device (CanSetName=false) or for
// single switches (Switch<n>.FixedName=true): ISwitchV2 documents the exception
// for a "device name [that] cannot be set", and drivers fix the names of some of
// their switches only.
// Switch<n>.Stuck=true models an output that accepts a change without an error
// and stays as it is (a tripped or interlocked outlet).
// Simulator assumptions: an asynchronous set takes AsyncTime and changes the
// value at its end; after CancelAsync the value is unchanged and
// StateChangeComplete answers OperationCancelled until the next set.

