static bool switch_control(alpaca_device *device, const char *key, const char *value) {
	switch_state *state = device->state;
	char field[32] = { 0 };
	int id = 0;
	int count = 0;
	if (!strcmp(key, "MaxSwitch")) {
		if (!alpaca_parse_int(value, &count) || count < 0 || count > SWITCH_MAX) {
			return false;
		}
		state->max_switch = count;
		return true;
	}
	if (sscanf(key, "Switch%d.%31s", &id, field) != 2 || id < 0 || id >= SWITCH_MAX) {
		return false;
	}
	switch_item *item = state->items + id;
	if (!strcmp(field, "Name")) {
		snprintf(item->name, sizeof(item->name), "%s", value);
		return true;
	}
	if (!strcmp(field, "Description")) {
		snprintf(item->description, sizeof(item->description), "%s", value);
		return true;
	}
	if (!strcmp(field, "Min")) {
		return alpaca_parse_double(value, &item->min);
	}
	if (!strcmp(field, "Max")) {
		return alpaca_parse_double(value, &item->max);
	}
	if (!strcmp(field, "Step")) {
		return alpaca_parse_double(value, &item->step);
	}
	if (!strcmp(field, "Value")) {
		item->pending = false;
		return alpaca_parse_double(value, &item->value);
	}
	if (!strcmp(field, "CanWrite")) {
		return alpaca_parse_bool(value, &item->can_write);
	}
	if (!strcmp(field, "CanAsync")) {
		return alpaca_parse_bool(value, &item->can_async);
	}
	if (!strcmp(field, "FixedName")) {
		return alpaca_parse_bool(value, &item->fixed_name);
	}
	if (!strcmp(field, "Stuck")) {
		return alpaca_parse_bool(value, &item->stuck);
	}
	return false;
}

