// Applies a new value, at once or after AsyncTime. The parameters have been read by the caller.
static void switch_set(alpaca_device *device, alpaca_request *request, switch_item *item, double value, bool async) {
	switch_state *state = device->state;
	if (!item->can_write || (async && !item->can_async)) {
		alpaca_reply_error(request, ALPACA_ERROR_NOT_IMPLEMENTED, "%s is not implemented for '%s'", request->member->name, item->name);
		return;
	}
	if (value < item->min || value > item->max) {
		alpaca_reply_error(request, ALPACA_ERROR_INVALID_VALUE, "Value %g is out of range %g..%g", value, item->min, item->max);
		return;
	}
	if (item->step > 0) {
		value = item->min + round((value - item->min) / item->step) * item->step;
		if (value > item->max) {
			value = item->max;
		}
	}
	if (item->stuck) {
		value = item->value;
	}
	item->cancelled = false;
	item->pending = async && state->async_time > 0;
	item->pending_value = value;
	item->pending_until = alpaca_now() + state->async_time;
	if (!item->pending) {
		item->value = value;
	}
	alpaca_event("STATE", "switch/%d id=%d value=%g async=%d", device->number, (int)(item - state->items), value, item->pending);
	alpaca_reply_void(request);
}

