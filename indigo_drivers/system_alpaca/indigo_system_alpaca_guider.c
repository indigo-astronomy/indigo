/** INDIGO ASCOM Alpaca client driver, guider device class: secondary guider device of an Alpaca Camera or Telescope that can pulse guide
 \file indigo_system_alpaca_guider.c

 GUIDER_GUIDE_DEC and GUIDER_GUIDE_RA are PulseGuide of the primary device: Direction 0 north, 1 south, 2 east, 3 west, Duration in whole
 milliseconds. The request is never sent twice: a pulse that may or may not have reached the device ends in ALERT.

 COMPLETION

 PulseGuide returns when the pulse has started (or, with older devices, when it is over) and IsPulseGuiding tells when it is over.
 The finalizer of an axis runs when the duration has passed since PulseGuide returned, which is the earliest time at which the pulse
 is certainly over, and then reads IsPulseGuiding; a PulseGuide that took at least as long as the pulse is checked at once.
 While IsPulseGuiding is true the finalizer repeats in the rhythm of the active polling, for at most GUIDER_GRACE seconds.
 A pulse that is over is followed by a poll tick of the primary device (system_alpaca_poll_now()) before the property is completed,
 so the coordinates of a telescope already show the pulse when a client sees it end.
 A device without IsPulseGuiding completes by the duration alone. IsPulseGuiding is one flag for both axes: while the pulse of the
 other axis still has time to run it says nothing about this axis, so the axis completes by its duration.

 REPLACEMENT

 A request for an axis whose pulse still runs replaces it, as in the other INDIGO guiders: the pending finalizer is cancelled and the
 new PulseGuide is sent; what the device does with a pulse that overlaps the previous one is up to the device. Requests that queue up
 for one axis are coalesced, only the last one is sent. A finalizer that finds a newer request waiting leaves the property to it.
 A request with both items zero ends the running pulse with PulseGuide of Duration 0 (the ASCOM simulators end a pulse that way;
 a device that refuses it leaves the request in ALERT) and is a no-op when no pulse runs. The same is sent, as a courtesy, for the
 pulses that are still running when the device disconnects.

 GUIDER_RATE is not used: a camera has no guide rate, and the guide rates of a telescope are MOUNT_GUIDE_RATE of the mount device.

 Threads: change_property runs on a bus thread, everything else on the handler queue of the primary device. A request is accepted
 while its property is BUSY as well, so the items and the state of GUIDER_GUIDE_DEC and GUIDER_GUIDE_RA are written by both sides;
 both do it under the lock of the device, together with the count of the requests that wait for their handler. A finalizer ends
 a pulse (the items back to zero, the state of the result) in one step under that lock and only if no request waits, so the end
 of a pulse never takes the place of a request that was just accepted.
 */

