#pragma mark - helpers

static char alpaca_lower(char c) {
	return c >= 'A' && c <= 'Z' ? (char)(c - 'A' + 'a') : c;
}

static bool alpaca_same_name(const char *name, const char *other) {
	while (*name && alpaca_lower(*name) == alpaca_lower(*other)) {
		name++;
		other++;
	}
	return *name == 0 && *other == 0;
}

// Copy text into a buffer of size bytes; text that does not fit is cut at a UTF-8 character boundary.
static void alpaca_copy_text(char *target, size_t size, const char *source) {
	size_t length = source == NULL ? 0 : strlen(source);
	if (length >= size) {
		length = size - 1;
		while (length > 0 && ((unsigned char)source[length] & 0xC0) == 0x80) {
			length--;
		}
	}
	if (length > 0) {
		memcpy(target, source, length);
	}
	target[length] = 0;
}

// ClientID: random and never 0. The range 1 - 65535 is the one used by ASCOMLibrary, so it is safe for servers that parse the value as a 16 or signed 32 bit integer.
static uint32_t alpaca_random_client_id(const void *seed) {
	static uint32_t counter = 0;
	uint64_t value = (uint64_t)time(NULL) ^ (uint64_t)(indigo_monotonic_time() * 1e9) ^ (uint64_t)(uintptr_t)seed ^ ((uint64_t)++counter << 32);
	value ^= value >> 33;
	value *= 0xFF51AFD7ED558CCDULL;
	value ^= value >> 33;
	value *= 0xC4CEB9FE1A85EC53ULL;
	value ^= value >> 33;
	return (uint32_t)(value % 65535) + 1;
}

