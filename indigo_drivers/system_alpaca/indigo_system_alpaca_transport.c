bool alpaca_parse_discovery_reply(const char *reply, long length, int *port) {
	int64_t value = 0;
	if (reply == NULL || length <= 0) {
		return false;
	}
	alpaca_json_value *document = alpaca_json_parse(reply, (size_t)length, NULL, 0);
	bool result = alpaca_json_get_type(document) == ALPACA_JSON_OBJECT && alpaca_json_get_int(alpaca_json_get(document, "AlpacaPort"), &value) && value >= 1 && value <= 65535;
	alpaca_json_free(document);
	if (result && port != NULL) {
		*port = (int)value;
	}
	return result;
}

bool alpaca_parse_endpoint(const char *text, int default_port, char *host, size_t host_size, int *port) {
	const char *port_text = NULL;
	size_t host_length = 0;
	long value = default_port;
	char *end = NULL;
	if (text == NULL || host == NULL || host_size == 0 || port == NULL) {
		return false;
	}
	while (*text == ' ') {
		text++;
	}
	if (!strncmp(text, "http://", 7)) {
		text += 7;
	}
	size_t length = strlen(text);
	while (length > 0 && (text[length - 1] == ' ' || text[length - 1] == '/')) {
		length--;
	}
	if (*text == '[') {
		const char *bracket = memchr(text, ']', length);
		if (bracket == NULL) {
			return false;
		}
		host_length = (size_t)(bracket - text - 1);
		text++;
		length -= host_length + 2;
		if (length > 0) {
			if (bracket[1] != ':') {
				return false;
			}
			port_text = bracket + 2;
			length--;
		}
	} else {
		const char *colon = memchr(text, ':', length);
		// more than one colon is an IPv6 address without brackets, which can not carry a port
		if (colon != NULL && memchr(colon + 1, ':', length - (size_t)(colon + 1 - text)) == NULL) {
			host_length = (size_t)(colon - text);
			port_text = colon + 1;
			length -= host_length + 1;
		} else {
			host_length = length;
			length = 0;
		}
	}
	if (host_length == 0 || host_length >= host_size || host_length >= ALPACA_HOST_SIZE) {
		return false;
	}
	for (size_t i = 0; i < host_length; i++) {
		if ((unsigned char)text[i] <= ' ' || text[i] == '/' || text[i] == '?' || text[i] == '#' || text[i] == '@') {
			return false;
		}
	}
	if (port_text != NULL) {
		if (length == 0 || length > 5 || *port_text < '0' || *port_text > '9') {
			return false;
		}
		value = strtol(port_text, &end, 10);
		if (end != port_text + length) {
			return false;
		}
	}
	if (value < 1 || value > 65535) {
		return false;
	}
	memcpy(host, text, host_length);
	host[host_length] = 0;
	*port = (int)value;
	return true;
}
