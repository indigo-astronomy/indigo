alpaca_server *alpaca_server_create(const char *host, int port) {
	if (host == NULL || *host == 0 || strlen(host) >= ALPACA_HOST_SIZE || port < 1 || port > 65535) {
		return NULL;
	}
	alpaca_server *server = indigo_safe_malloc(sizeof(alpaca_server));
	alpaca_copy_text(server->host, sizeof(server->host), host);
	server->port = port;
	server->client_id = alpaca_random_client_id(server);
	server->transaction_id = 0;
	server->establish_timeout = ALPACA_ESTABLISH_TIMEOUT;
	server->standard_timeout = ALPACA_STANDARD_TIMEOUT;
	server->long_timeout = ALPACA_LONG_TIMEOUT;
	pthread_mutex_init(&server->mutex, NULL);
	return server;
}

