/** INDIGO ASCOM Alpaca client driver, Dome device class: Alpaca Dome as an INDIGO dome
 \file indigo_system_alpaca_dome.c

 What is exposed depends on the capabilities of the device, read on every connect:

 - CanSetAzimuth: DOME_HORIZONTAL_COORDINATES (AZ; ALT as well with CanSetAltitude), DOME_STEPS and DOME_DIRECTION (a relative
   move is a slew to the azimuth computed from the current one), DOME_ON_COORDINATES_SET (SYNC with CanSyncAzimuth),
   DOME_DIMENSION and DOME_SLAVING_PARAMETERS. Without it the device is a roll-off roof and all of them are hidden.
 - CanSetShutter: DOME_SHUTTER. CanPark: DOME_PARK. CanFindHome: DOME_HOME. CanSetPark: X_ALPACA_DOME_PARK_SET.
   CanSlave: X_ALPACA_DOME_SLAVED.
 - DOME_ABORT_MOTION and DOME_STATE always. DOME_SPEED is hidden, Alpaca has no dome speed.

 Completion follows the Alpaca specification: an azimuth or altitude slew, Park and FindHome end when Slewing becomes false
 (Park and FindHome succeeded if AtPark / AtHome is true then), a shutter move ends when ShutterStatus leaves Opening / Closing.
 All of them use the handler + finalizer pattern; nothing waits in a handler.

 Slaving. INDIGO slaves a dome from the mount agent, which writes DOME_HORIZONTAL_COORDINATES; the INDIGO dome class has no
 slaving of its own. Alpaca "Slaved" is something else: the dome hardware follows a telescope by itself and refuses SlewToAzimuth,
 SlewToAltitude, Park and FindHome with InvalidWhileSlaved. The driver exposes it as X_ALPACA_DOME_SLAVED and never changes it
 on its own (AbortSlew, sent for DOME_ABORT_MOTION, switches it off in the device, as the specification says). While it is on,
 the motion of the dome is only reported: DOME_HORIZONTAL_COORDINATES is BUSY while the device reports Slewing and follows
 its azimuth, and a request to move the dome is sent once, refused by the device and ends in ALERT with its message. So the two
 kinds of slaving can not move the dome against each other; the user enables one of them.

 Parking. Alpaca has no unpark: AtPark is cleared by the next slew. DOME_PARK.UNPARKED therefore sends nothing; it only lets
 the driver accept motion requests again, which it refuses with "Dome is parked" while the dome is parked, as INDIGO domes do.

 Nothing is stopped on disconnect: a dome that is closing its shutter or parking finishes that when INDIGO disconnects.
 */

