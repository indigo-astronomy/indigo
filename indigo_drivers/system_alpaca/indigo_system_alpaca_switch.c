	if (strcmp(INFO_DEVICE_INTERFACE_ITEM->text.value, text)) {
		INDIGO_COPY_VALUE(INFO_DEVICE_INTERFACE_ITEM->text.value, text);
		indigo_update_property(device, INFO_PROPERTY, NULL);
	}
