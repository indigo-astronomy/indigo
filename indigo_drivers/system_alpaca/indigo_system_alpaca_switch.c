// Value of a switch in the devicestate snapshot of the running poll tick; false if the snapshot does not have it.
static bool switch_state_value(indigo_device *device, int id, double *value) {
	char name[ALPACA_MEMBER_SIZE];
	bool state = false;
	if (SWITCH_DATA->switches[id].boolean) {
		snprintf(name, sizeof(name), "GetSwitch%d", id);
		if (!alpaca_state_bool(&PRIVATE_DATA->state, name, &state)) {
			return false;
		}
		*value = state ? 1 : 0;
		return true;
	}
	snprintf(name, sizeof(name), "GetSwitchValue%d", id);
	return alpaca_state_double(&PRIVATE_DATA->state, name, value);
}

// Read the value of a switch from the device and remember it.
static alpaca_result switch_read(indigo_device *device, int id) {
	switch_record *record = SWITCH_DATA->switches + id;
	double value = 0;
	bool state = false;
	alpaca_result result = record->boolean ? switch_get_bool(device, "getswitch", id, &state) : switch_get_double(device, "getswitchvalue", id, &value);
	if (result == ALPACA_OK) {
		record->value = record->boolean ? (state ? 1 : 0) : value;
	}
	record->read_failed = result != ALPACA_OK;
	return result;
}

// Start the change of a switch. A synchronous change may take as long as the device needs, so it gets the long timeout.
// Setting a value twice has the effect of setting it once, so every variant may be sent again after a socket error.
static alpaca_result switch_write(indigo_device *device, int id, double value) {
	switch_record *record = SWITCH_DATA->switches + id;
	if (record->boolean) {
		alpaca_param params[] = { ALPACA_INT_PARAM("Id", id), ALPACA_BOOL_PARAM("State", value != 0) };
		return system_alpaca_put(device, record->can_async ? "setasync" : "setswitch", params, 2, (record->can_async ? ALPACA_WAIT_STANDARD : ALPACA_WAIT_LONG) | ALPACA_REPLAYABLE);
	}
	alpaca_param params[] = { ALPACA_INT_PARAM("Id", id), ALPACA_DOUBLE_PARAM("Value", value) };
	return system_alpaca_put(device, record->can_async ? "setasyncvalue" : "setswitchvalue", params, 2, (record->can_async ? ALPACA_WAIT_STANDARD : ALPACA_WAIT_LONG) | ALPACA_REPLAYABLE);
}

// Text of a failed request in the form system_alpaca_finish() uses. It is taken right after the request, because the read back
// that follows replaces the error of the channel.
static void switch_failure(indigo_device *device, alpaca_result result, const char *action, const char *name, char *message, size_t size) {
	char reason[INDIGO_VALUE_SIZE];
	system_alpaca_reason(device, result, reason, sizeof(reason));
	snprintf(message, size, "%s '%s' failed: %s%s%s%s", action, name, alpaca_result_text(result), *reason ? " (" : "", reason, *reason ? ")" : "");
}

static indigo_item *switch_name_item(indigo_device *device, const switch_record *record) {
	if (record->kind == SWITCH_SENSOR) {
		return AUX_SENSOR_NAMES_PROPERTY->items + record->index;
	}
	return AUX_OUTLET_NAMES_PROPERTY->items + (record->kind == SWITCH_VALUE ? SWITCH_DATA->kind_count[SWITCH_OUTLET] : 0) + record->index;
}

// Copy the values read from the device to the items of the property of the given kind. Returns true if an item changed.
static bool switch_copy_values(indigo_device *device, switch_kind kind) {
	bool changed = false;
	for (int id = 0; id < SWITCH_DATA->count; id++) {
		switch_record *record = SWITCH_DATA->switches + id;
		if (record->kind != kind) {
			continue;
		}
		indigo_item *item = SWITCH_DATA->properties[kind]->items + record->index;
		if (kind == SWITCH_OUTLET) {
			changed = changed || item->sw.value != (record->value != 0);
			item->sw.value = record->value != 0;
		} else {
			changed = changed || item->number.value != record->value || item->number.target != record->value;
			item->number.value = item->number.target = record->value;
		}
	}
	return changed;
}

