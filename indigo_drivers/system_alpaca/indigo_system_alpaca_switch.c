/** INDIGO ASCOM Alpaca client driver, Switch device class: Alpaca Switch as an INDIGO GPIO device
 \file indigo_system_alpaca_switch.c

 An Alpaca Switch is a list of MaxSwitch numbered "switch devices". Each of them is read once per connection (name, description,
 CanWrite, MinSwitchValue, MaxSwitchValue, SwitchStep, on interface version 3 CanAsync) and becomes one item of one of three properties:

 - a writable boolean switch (minimum 0, maximum 1, step 1) is an item of AUX_GPIO_OUTLETS, set with setswitch;
 - any other writable switch is an item of X_ALPACA_SWITCH_VALUES with the range and step of the device, set with setswitchvalue;
 - a switch that can not be written is an item of AUX_GPIO_SENSORS, a boolean one with the values 0 and 1.

 The items are numbered from 1 within their property (OUTLET_1, VALUE_1, SENSOR_1...) in the order of the Alpaca switch numbers and
 are labelled with the Alpaca names. X_ALPACA_SWITCH_INFO tells which item an Alpaca switch number became and holds its description.
 AUX_OUTLET_NAMES (outlets and values) and AUX_SENSOR_NAMES hold the names of the device. A changed name is sent with setswitchname;
 a switch whose name the device does not let the client set (NotImplemented) keeps the name of the device and is not asked again.
 The names are not saved by INDIGO, the device is the only place they are kept in.

 A switch with CanAsync is set with setasync / setasyncvalue: the property stays BUSY while a finalizer polls statechangecomplete,
 for no longer than the long timeout of the server, and X_ALPACA_SWITCH_ABORT sends cancelasync for the changes that are running.

 Polling: on a Platform 7 device the values come from the devicestate snapshot of the tick (GetSwitch<n> / GetSwitchValue<n>).
 What the snapshot does not have (older devices, or more switches than the snapshot holds) is read switch by switch, at most
 SWITCH_POLL_BATCH requests per tick, in turns.

 Threads: change_property runs on a bus thread, everything else on the handler queue of the device. A request is accepted
 with system_alpaca_accept() and the poll publishes the values of the device under the lock of the device, so a poll tick never
 replaces a request that was just accepted with the old state of the device.
 */

