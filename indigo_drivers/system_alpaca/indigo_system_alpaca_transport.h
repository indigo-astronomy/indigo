/** Request options, combined with '|'.

 The timeout class selects how long the reply may take (time to the first byte of the response):
 ALPACA_WAIT_STANDARD for ordinary members, ALPACA_WAIT_ESTABLISH for the members used to establish a
 connection (connect, connected, connecting, disconnect, interfaceversion) and for the management API,
 ALPACA_WAIT_LONG for methods that may block in the device (synchronous slews, park, findhome, move,
 pulseguide, action, command*, imagearray).

 ALPACA_REPLAYABLE marks a PUT that is idempotent: sending it twice has the same effect as sending it once
 (setting a value, connect, disconnect, abort, halt). Only such a PUT is sent again after a socket error.
 A PUT without the flag (relative move, pulse guide, start of an exposure, sync) is never repeated once
 it may have reached the server; see alpaca_may_have_executed(). GET requests are always replayable.
 */
