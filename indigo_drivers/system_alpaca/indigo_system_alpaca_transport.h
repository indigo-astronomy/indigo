/** INDIGO ASCOM Alpaca client driver, Alpaca transport layer
 \file indigo_system_alpaca_transport.h

 The layer sits on top of the HTTP client (indigo_system_alpaca_http.h) and the JSON parser
 (indigo_system_alpaca_json.h) and knows the Alpaca protocol, but nothing about INDIGO devices:

 - alpaca_server is the record of one Alpaca server (host:port). It owns what is common to every request
   sent to that server: the random ClientID, the ClientTransactionID counter and the timeouts.
 - alpaca_channel is one HTTP connection to a server together with its reusable request and response
   buffers. A channel is bound either to one device of the server (device type + device number) or to
   the management API. Each channel has a lock, so a channel can be shared by threads, and different
   channels of the same server work independently: a long transfer on one channel does not block the
   status requests on another one.

 Every request function returns an alpaca_result. ALPACA_OK means that the server answered with HTTP 200,
 a well formed envelope, ErrorNumber 0 and (for getters) a Value of the expected type.
 A request on a NULL channel does nothing and returns ALPACA_UNREACHABLE, so a caller that has no channel
 (because its server is known to be unreachable) needs no special case.
 */

