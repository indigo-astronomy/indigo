// The device answered, with a value or with an error of its own. False means that there is no usable answer and the connection has to be given up.
static bool mount_usable(alpaca_result result) {
	return !alpaca_is_transport_error(result) && result != ALPACA_PROTOCOL_ERROR && result != ALPACA_SERVER_ERROR && result != ALPACA_FAILED;
}

// Right ascension in hours within 0 <= ra < 24. A value that is in the range already is returned bit by bit, so that a target is sent as it was requested.
static double mount_wrap_hours(double ra) {
	if (ra >= 0 && ra < 24) {
		return ra;
	}
	ra = fmod(ra, 24);
	return ra < 0 ? ra + 24 : ra;
}

static double mount_nearest_rate(const double *minimum, const double *maximum, int count, double rate) {
	double nearest = 0;
	double distance = -1;
	for (int i = 0; i < count; i++) {
		double candidate = fmax(minimum[i], fmin(maximum[i], rate));
		if (distance < 0 || fabs(candidate - rate) < distance) {
			nearest = candidate;
			distance = fabs(candidate - rate);
		}
	}
	return nearest;
}

// CanMoveAxis and AxisRates of one axis: the rates of the four items of MOUNT_SLEW_RATE are the allowed rates nearest to the usual ones.
static bool mount_probe_axis(indigo_device *device, int axis) {
	mount_data *data = MOUNT_DATA;
	alpaca_channel *channel = system_alpaca_channel(device);
	alpaca_param params[] = { ALPACA_INT_PARAM("Axis", axis) };
	const alpaca_json_value *value = NULL;
	double minimum[MOUNT_MAX_RATE_RANGES];
	double maximum[MOUNT_MAX_RATE_RANGES];
	double fastest = 0;
	int count = 0;
	bool can_move = false;
	data->can_move_axis[axis] = false;
	alpaca_result result = system_alpaca_check(device, alpaca_get_bool(channel, "canmoveaxis", params, 1, ALPACA_WAIT_STANDARD, &can_move));
	if (result != ALPACA_OK || !can_move) {
		return mount_usable(result);
	}
	result = system_alpaca_check(device, alpaca_get_value(channel, "axisrates", params, 1, ALPACA_WAIT_STANDARD, &value));
	if (result != ALPACA_OK) {
		return mount_usable(result);
	}
	for (const alpaca_json_value *range = value != NULL ? alpaca_json_first(value) : NULL; range != NULL && count < MOUNT_MAX_RATE_RANGES; range = alpaca_json_next(range)) {
		if (alpaca_json_get_double(alpaca_json_get(range, "Minimum"), minimum + count) && alpaca_json_get_double(alpaca_json_get(range, "Maximum"), maximum + count) && maximum[count] > 0 && maximum[count] >= minimum[count]) {
			fastest = fmax(fastest, maximum[count]);
			count++;
		}
	}
	alpaca_end(channel);
	if (count > 0) {
		data->can_move_axis[axis] = true;
		data->slew_rates[axis][0] = mount_nearest_rate(minimum, maximum, count, MOUNT_GUIDE_SLEW_RATE);
		data->slew_rates[axis][1] = mount_nearest_rate(minimum, maximum, count, MOUNT_CENTERING_SLEW_RATE);
		data->slew_rates[axis][2] = mount_nearest_rate(minimum, maximum, count, MOUNT_FIND_SLEW_RATE);
		data->slew_rates[axis][3] = fastest;
		INDIGO_DRIVER_DEBUG(DRIVER_NAME, "'%s' axis %d rates %g, %g, %g, %g deg/s", device->name, axis, data->slew_rates[axis][0], data->slew_rates[axis][1], data->slew_rates[axis][2], data->slew_rates[axis][3]);
	}
	return true;
}

// TrackingRates in the order of the items of MOUNT_TRACK_RATE: sidereal, solar, lunar, king.
static bool mount_probe_tracking_rates(indigo_device *device) {
	static const int order[] = { 0, 2, 1, 3 };
	mount_data *data = MOUNT_DATA;
	int rates[16];
	int count = 0;
	data->track_rate_count = 0;
	alpaca_result result = system_alpaca_check(device, alpaca_get_int_array(system_alpaca_channel(device), "trackingrates", NULL, 0, ALPACA_WAIT_STANDARD, rates, 16, &count));
	for (int i = 0; result == ALPACA_OK && i < 4; i++) {
		for (int j = 0; j < count; j++) {
			if (rates[j] == order[i]) {
				data->track_rates[data->track_rate_count++] = order[i];
				break;
			}
		}
	}
	return mount_usable(result);
}

// Read the operational state of the telescope: from the DeviceState snapshot inside on_poll, with a request for every member otherwise.
// A value that can not be read keeps its last value. Returns false if the telescope gave no usable answer.
static bool mount_read_state(indigo_device *device) {
	mount_data *data = MOUNT_DATA;
	char utc[INDIGO_NAME_SIZE] = { 0 };
	double right_ascension = 0;
	double declination = 0;
	alpaca_result result = system_alpaca_state_double(device, "RightAscension", &right_ascension);
	if (result == ALPACA_OK) {
		result = system_alpaca_state_double(device, "Declination", &declination);
	}
	if (result == ALPACA_OK) {
		data->right_ascension = right_ascension;
		data->declination = declination;
	}
	data->coordinates = result;
	bool usable = mount_usable(result);
	usable = mount_usable(system_alpaca_state_double(device, "Altitude", &data->altitude)) && usable;
	usable = mount_usable(system_alpaca_state_double(device, "Azimuth", &data->azimuth)) && usable;
	usable = mount_usable(system_alpaca_state_double(device, "SiderealTime", &data->sidereal_time)) && usable;
	usable = mount_usable(system_alpaca_state_bool(device, "Slewing", &data->slewing)) && usable;
	usable = mount_usable(system_alpaca_state_bool(device, "AtPark", &data->at_park)) && usable;
	usable = mount_usable(system_alpaca_state_bool(device, "AtHome", &data->at_home)) && usable;
	usable = mount_usable(system_alpaca_state_bool(device, "Tracking", &data->tracking)) && usable;
	result = system_alpaca_state_int(device, "SideOfPier", &data->side_of_pier);
	if (result != ALPACA_OK) {
		data->side_of_pier = -1;
	}
	usable = mount_usable(result) && usable;
	result = system_alpaca_state_string(device, "UTCDate", utc, sizeof(utc));
	if (result == ALPACA_OK && strlen(utc) >= 19) {
		utc[19] = 0;
		strcpy(data->utc, utc);
	}
	return mount_usable(result) && usable;
}

