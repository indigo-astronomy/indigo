static void mount_motion_finalizer(indigo_device *device);
static void mount_equatorial_coordinates_handler(indigo_device *device);
static void mount_park_handler(indigo_device *device);
static void mount_home_handler(indigo_device *device);
static void mount_side_of_pier_handler(indigo_device *device);
static void mount_motion_ra_handler(indigo_device *device);
static void mount_motion_dec_handler(indigo_device *device);

// HW-4: some telescopes accept a slew, a park, a search for home or a MoveAxis that arrives too soon after the end of a slew, answer
// success and do nothing (the NYX-101, firmware 1.32.1, measured on 2026-10-03: ignored 0 and 1 s after the end, executed 2 s after it).
// A handler is therefore run again once X_ALPACA_SETTLE_TIME has passed since the end of the last motion; the property stays BUSY
// meanwhile and MOUNT_ABORT_MOTION cancels the waiting handler. True when the handler was postponed.
static bool mount_postponed(indigo_device *device, indigo_timer_callback handler) {
	mount_data *data = MOUNT_DATA;
	system_alpaca_lock(device);
	double settle = X_ALPACA_SETTLE_TIME_ITEM->number.value;
	system_alpaca_unlock(device);
	if (settle <= 0 || data->motion_ended == 0) {
		return false;
	}
	double remaining = data->motion_ended + settle - indigo_monotonic_time();
	if (remaining <= 0) {
		return false;
	}
	INDIGO_DRIVER_DEBUG(DRIVER_NAME, "'%s' the last motion ended %.2f s ago, the request waits %.2f s", device->name, settle - remaining, remaining);
	indigo_execute_handler_in(device, remaining, handler);
	return true;
}

// The telescope accepted a method that makes it move: watch it. The coordinates are BUSY during a slew only (slew is true), see MOTION.
static void mount_motion_start(indigo_device *device, const char *action, bool slew) {
	mount_data *data = MOUNT_DATA;
	indigo_cancel_pending_handler(device, mount_motion_finalizer);
	// HW-2: the coordinates may be BUSY for a slew of the telescope this driver did not request (mount_apply_state()); a slew takes the BUSY
	// state over, any other motion ends it, because only the polling that is now suspended for the motion would have ended it
	bool external = data->external_slew;
	data->action = action;
	data->external_slew = data->aborted = false;
	if (external && !slew) {
		system_alpaca_lock(device);
		bool busy = MOUNT_EQUATORIAL_COORDINATES_PROPERTY->state == INDIGO_BUSY_STATE;
		if (busy) {
			MOUNT_EQUATORIAL_COORDINATES_PROPERTY->state = INDIGO_OK_STATE;
		}
		system_alpaca_unlock(device);
		if (busy) {
			mount_update_coordinates(device);
		}
	}
	data->stall_since = 0;
	data->slew_requested = data->slew_requested || slew;
	system_alpaca_operation_start(device, &data->motion, MOUNT_MOTION_TIMEOUT, mount_motion_finalizer);
	if (slew) {
		system_alpaca_lock(device);
		bool idle = MOUNT_EQUATORIAL_COORDINATES_PROPERTY->state != INDIGO_BUSY_STATE;
		MOUNT_EQUATORIAL_COORDINATES_PROPERTY->state = INDIGO_BUSY_STATE;
		system_alpaca_unlock(device);
		if (idle) {
			mount_update_coordinates(device);
		}
	}
}

// A park, an unpark or a search for home that is not at its goal: true once the telescope neither slewed nor moved for MOUNT_STALL_TIME.
// The position is the one of the last poll tick (the polling runs at the active rhythm meanwhile), from Altitude and Azimuth of the
// telescope or computed from its equatorial coordinates.
static bool mount_stalled(indigo_device *device, bool slewing) {
	mount_data *data = MOUNT_DATA;
	double now = indigo_monotonic_time();
	double altitude = MOUNT_HORIZONTAL_COORDINATES_ALT_ITEM->number.value;
	double azimuth = MOUNT_HORIZONTAL_COORDINATES_AZ_ITEM->number.value;
	double azimuth_change = fmod(fabs(azimuth - data->stall_azimuth), 360);
	if (azimuth_change > 180) {
		azimuth_change = 360 - azimuth_change;
	}
	bool progress = fabs(altitude - data->stall_altitude) > MOUNT_PROGRESS || azimuth_change * cos(altitude * M_PI / 180) > MOUNT_PROGRESS;
	if (slewing || progress || data->stall_since == 0) {
		data->stall_since = now;
		data->stall_altitude = altitude;
		data->stall_azimuth = azimuth;
		return false;
	}
	return now - data->stall_since >= MOUNT_STALL_TIME;
}

// The telescope stopped after AbortSlew: every property that waited for the end of a motion ends in ALERT with what the telescope reports now.
static void mount_settle_aborted(indigo_device *device) {
	system_alpaca_lock(device);
	bool home = MOUNT_HOME_PROPERTY->state == INDIGO_BUSY_STATE;
	if (MOUNT_PARK_PROPERTY->state == INDIGO_BUSY_STATE) {
		MOUNT_PARK_PROPERTY->state = INDIGO_ALERT_STATE;
	}
	if (home) {
		MOUNT_HOME_ITEM->sw.value = false;
		MOUNT_HOME_PROPERTY->state = INDIGO_ALERT_STATE;
	}
	if (MOUNT_SIDE_OF_PIER_PROPERTY->state == INDIGO_BUSY_STATE) {
		MOUNT_SIDE_OF_PIER_PROPERTY->state = INDIGO_ALERT_STATE;
	}
	if (MOUNT_EQUATORIAL_COORDINATES_PROPERTY->state == INDIGO_BUSY_STATE) {
		MOUNT_EQUATORIAL_COORDINATES_PROPERTY->state = INDIGO_ALERT_STATE;
	}
	system_alpaca_unlock(device);
	if (home) {
		indigo_update_property(device, MOUNT_HOME_PROPERTY, NULL);
	}
	mount_apply_state(device);
	mount_update_state(device);
}

// The motion is over, with the given result of watching it: read where the telescope is and settle every property that waited for it.
static void mount_motion_done(indigo_device *device, alpaca_result result) {
	mount_data *data = MOUNT_DATA;
	data->motion_ended = indigo_monotonic_time();
	if (data->aborted) {
		data->aborted = false;
		mount_read_state(device);
		mount_settle_aborted(device);
		return;
	}
	if (result == ALPACA_OK && data->stop_tracking) {
		result = mount_put_tracking(device, false);
	}
	if (result == ALPACA_OK) {
		mount_read_state(device);
		result = data->coordinates;
	}
	if (data->park_requested || data->unpark_requested) {
		bool achieved = data->at_park == data->park_requested;
		mount_set_park(device);
		mount_finish(device, MOUNT_PARK_PROPERTY, result, achieved, data->park_requested ? "Park" : "Unpark", data->park_requested ? "the telescope stopped and does not report AtPark" : "the telescope still reports AtPark");
		// a late arrival at the goal ends MOUNT_PARK in OK, see mount_apply_state()
		data->park_alert = result == ALPACA_OK && achieved ? -1 : data->park_requested ? 1 : 0;
	}
	if (data->home_requested) {
		mount_finish(device, MOUNT_HOME_PROPERTY, result, data->at_home, "Find home", "the telescope stopped and does not report AtHome");
		data->home_alert = result != ALPACA_OK || !data->at_home;
	}
	if (data->flip_requested) {
		mount_set_side_of_pier(device);
		system_alpaca_finish(device, MOUNT_SIDE_OF_PIER_PROPERTY, result, "Pier flip");
	}
	bool slew = data->slew_requested;
	data->park_requested = data->unpark_requested = data->home_requested = data->flip_requested = data->stop_tracking = data->slew_requested = false;
	mount_apply_state(device);
	if (slew) {
		mount_finish_coordinates(device, result, "Slew");
	}
	mount_update_state(device);
	if (data->goto_waits) {
		// the goto that was requested behind the unpark: its handler finds the telescope unparked, or refuses the goto
		data->goto_waits = false;
		indigo_execute_handler(device, mount_equatorial_coordinates_handler);
	}
}

// A slew and a pier flip end when Slewing is false. A park and a search for home end when AtPark / AtHome is true and an unpark when AtPark and
// Slewing are false (the completion members of the standard); without them they end when the telescope stalls, see MOTION.
static void mount_motion_finalizer(indigo_device *device) {
	mount_data *data = MOUNT_DATA;
	bool slewing = false;
	if (!system_alpaca_is_active(device)) {
		return;
	}
	alpaca_result result = system_alpaca_state_bool(device, "Slewing", &slewing);
	bool waiting = result == ALPACA_OK && slewing;
	if (result == ALPACA_OK && !data->aborted && (data->park_requested || data->unpark_requested || data->home_requested)) {
		bool at_goal = false;
		result = system_alpaca_state_bool(device, data->park_requested || data->unpark_requested ? "AtPark" : "AtHome", &at_goal);
		if (result == ALPACA_OK) {
			bool reached = data->unpark_requested && !data->park_requested ? !at_goal && !slewing : at_goal;
			waiting = !reached && !mount_stalled(device, slewing);
		}
	}
	if (waiting && system_alpaca_operation_continue(device, &data->motion, mount_motion_finalizer)) {
		return;
	}
	system_alpaca_operation_end(device, &data->motion);
	mount_motion_done(device, waiting ? ALPACA_TIMED_OUT : result);
}

static void mount_equatorial_coordinates_handler(indigo_device *device) {
	mount_data *data = MOUNT_DATA;
	if (!system_alpaca_is_active(device)) {
		return;
	}
	if (data->motion.active && data->unpark_requested) {
		// accepted behind an unpark: mount_motion_done() runs this handler again when the unpark is over; the coordinates stay BUSY meanwhile
		data->goto_waits = true;
		return;
	}
	if (mount_is_parked(device)) {
		indigo_send_message(device, MOUNT_EQUATORIAL_COORDINATES_PROPERTY, "Mount is parked!");
		system_alpaca_update(device, MOUNT_EQUATORIAL_COORDINATES_PROPERTY, INDIGO_ALERT_STATE, NULL);
		return;
	}
	if (!indigo_get_switch(MOUNT_ON_COORDINATES_SET_PROPERTY, MOUNT_ON_COORDINATES_SET_SYNC_ITEM_NAME) && mount_postponed(device, mount_equatorial_coordinates_handler)) {
		return;
	}
	double ra = MOUNT_EQUATORIAL_COORDINATES_RA_ITEM->number.target;
	double dec = MOUNT_EQUATORIAL_COORDINATES_DEC_ITEM->number.target;
	indigo_j2k_to_eq(MOUNT_EPOCH_ITEM->number.value, &ra, &dec);
	alpaca_param params[] = { ALPACA_DOUBLE_PARAM("RightAscension", mount_wrap_hours(ra)), ALPACA_DOUBLE_PARAM("Declination", dec) };
	if (indigo_get_switch(MOUNT_ON_COORDINATES_SET_PROPERTY, MOUNT_ON_COORDINATES_SET_SYNC_ITEM_NAME)) {
		alpaca_result result = system_alpaca_put(device, "synctocoordinates", params, 2, ALPACA_WAIT_STANDARD);
		mount_check_parked(device, result);
		if (result == ALPACA_OK) {
			// no request between a failed one and its message: the message quotes the last answer of the telescope
			mount_read_state(device);
			mount_set_coordinates(device);
		}
		mount_finish_coordinates(device, result, "Sync");
	} else {
		alpaca_result result = ALPACA_OK;
		if (!data->tracking && system_alpaca_can(device, "cansettracking")) {
			result = mount_put_tracking(device, true);
		}
		if (result == ALPACA_OK) {
			result = mount_started(device, system_alpaca_put(device, "slewtocoordinatesasync", params, 2, ALPACA_WAIT_LONG | ALPACA_REPLAYABLE));
		}
		if (result == ALPACA_OK) {
			data->stop_tracking = indigo_get_switch(MOUNT_ON_COORDINATES_SET_PROPERTY, MOUNT_ON_COORDINATES_SET_SLEW_ITEM_NAME);
			mount_motion_start(device, "Slew", true);
		} else {
			mount_check_parked(device, result);
			mount_finish_coordinates(device, result, "Slew");
		}
	}
}

static void mount_park_handler(indigo_device *device) {
	mount_data *data = MOUNT_DATA;
	if (!system_alpaca_is_active(device)) {
		return;
	}
	bool park = indigo_get_switch_target(MOUNT_PARK_PROPERTY, MOUNT_PARK_PARKED_ITEM_NAME);
	if (park && mount_postponed(device, mount_park_handler)) {
		return;
	}
	if (!system_alpaca_can(device, park ? "canpark" : "canunpark")) {
		// MOUNT_PARK exists if the telescope can do one of the two; nothing is sent for the other one
		mount_set_park(device);
		system_alpaca_update(device, MOUNT_PARK_PROPERTY, INDIGO_ALERT_STATE, "The telescope can not be %s", park ? "parked" : "unparked");
		return;
	}
	alpaca_result result = mount_started(device, system_alpaca_put(device, park ? "park" : "unpark", NULL, 0, ALPACA_WAIT_LONG | ALPACA_REPLAYABLE));
	data->park_alert = -1;
	if (result == ALPACA_OK) {
		data->park_requested = park;
		data->unpark_requested = !park;
		data->stop_tracking = false;
		if (park) {
			// from here on the telescope moves to its park position; what would move it elsewhere is refused until MOUNT_PARK is settled
			mount_set_parked(device, true);
		}
		mount_motion_start(device, park ? "Park" : "Unpark", false);
	} else {
		mount_set_park(device);
		system_alpaca_finish(device, MOUNT_PARK_PROPERTY, result, park ? "Park" : "Unpark");
	}
}

static void mount_park_set_handler(indigo_device *device) {
	alpaca_result result = ALPACA_OK;
	if (!system_alpaca_is_active(device)) {
		return;
	}
	if (indigo_get_switch_target(MOUNT_PARK_SET_PROPERTY, MOUNT_PARK_SET_CURRENT_ITEM_NAME)) {
		result = system_alpaca_put(device, "setpark", NULL, 0, ALPACA_REPLAYABLE);
	}
	MOUNT_PARK_SET_CURRENT_ITEM->sw.value = false;
	system_alpaca_finish(device, MOUNT_PARK_SET_PROPERTY, result, "Set park");
}

static void mount_home_handler(indigo_device *device) {
	mount_data *data = MOUNT_DATA;
	if (!system_alpaca_is_active(device)) {
		return;
	}
	bool home = indigo_get_switch_target(MOUNT_HOME_PROPERTY, MOUNT_HOME_ITEM_NAME);
	if (home && mount_postponed(device, mount_home_handler)) {
		return;
	}
	MOUNT_HOME_ITEM->sw.value = false;
	if (home) {
		alpaca_result result = mount_started(device, system_alpaca_put(device, "findhome", NULL, 0, ALPACA_WAIT_LONG | ALPACA_REPLAYABLE));
		data->home_alert = false;
		if (result == ALPACA_OK) {
			data->home_requested = true;
			data->stop_tracking = false;
			indigo_update_property(device, MOUNT_HOME_PROPERTY, NULL);
			mount_motion_start(device, "Find home", false);
		} else {
			mount_check_parked(device, result);
			system_alpaca_finish(device, MOUNT_HOME_PROPERTY, result, "Find home");
		}
	} else {
		system_alpaca_update(device, MOUNT_HOME_PROPERTY, INDIGO_OK_STATE, NULL);
	}
}

static void mount_side_of_pier_handler(indigo_device *device) {
	mount_data *data = MOUNT_DATA;
	if (!system_alpaca_is_active(device)) {
		return;
	}
	if (mount_postponed(device, mount_side_of_pier_handler)) {
		return;
	}
	alpaca_param params[] = { ALPACA_INT_PARAM("SideOfPier", indigo_get_switch_target(MOUNT_SIDE_OF_PIER_PROPERTY, MOUNT_SIDE_OF_PIER_WEST_ITEM_NAME) ? 1 : 0) };
	alpaca_result result = mount_started(device, system_alpaca_put(device, "sideofpier", params, 1, ALPACA_WAIT_LONG | ALPACA_REPLAYABLE));
	if (result == ALPACA_OK) {
		data->flip_requested = true;
		data->stop_tracking = false;
		mount_motion_start(device, "Pier flip", false);
	} else {
		mount_check_parked(device, result);
		mount_set_side_of_pier(device);
		system_alpaca_finish(device, MOUNT_SIDE_OF_PIER_PROPERTY, result, "Pier flip");
	}
}

// End a request for MOUNT_MOTION_DEC or MOUNT_MOTION_RA with the given state; after a failure no motion is on. The properties are
// accepted while they are BUSY, so a bus thread may be writing them: the items and the state are set under the lock of the device.
static void mount_end_motion(indigo_device *device, indigo_property *property, indigo_property_state state) {
	system_alpaca_lock(device);
	if (state != INDIGO_OK_STATE) {
		property->items[0].sw.value = property->items[1].sw.value = false;
	}
	property->state = state;
	system_alpaca_unlock(device);
}

// Side of the pier that decides the sense of the secondary axis, see MANUAL MOTION: read when a motion starts, so that a flip made by
// another client since the last poll tick counts; the value of the last poll tick if it can not be read now. 1 is pierWest; 0, -1
// (pierUnknown) and a telescope that does not implement SideOfPier leave the sense as it is.
static int mount_motion_side_of_pier(indigo_device *device) {
	int side = -1;
	alpaca_result result = system_alpaca_state_int(device, "SideOfPier", &side);
	if (result == ALPACA_UNSUPPORTED) {
		return -1;
	}
	return result == ALPACA_OK ? side : MOUNT_DATA->side_of_pier;
}

// MOUNT_MOTION_DEC and MOUNT_MOTION_RA: MoveAxis with the rate of the selected item of MOUNT_SLEW_RATE, a rate of zero when both items are off.
// The sign of a secondary rate is inverted on pierWest, so that NORTH always moves toward the north celestial pole.
static void mount_move_axis(indigo_device *device, int axis, indigo_property *property, const char *positive, const char *negative) {
	mount_data *data = MOUNT_DATA;
	double rate = 0;
	if (mount_is_parked(device)) {
		indigo_send_message(device, property, "Mount is parked!");
		mount_end_motion(device, property, INDIGO_ALERT_STATE);
		indigo_update_property(device, property, NULL);
		indigo_mount_commit_motion_client(device, property);
		return;
	}
	for (int i = 0; i < 4; i++) {
		if (MOUNT_SLEW_RATE_PROPERTY->items[i].sw.value) {
			rate = data->slew_rates[axis][i];
		}
	}
	if (indigo_get_switch_target(property, negative)) {
		rate = -rate;
	} else if (!indigo_get_switch_target(property, positive)) {
		rate = 0;
	}
	if (rate != 0 && mount_postponed(device, axis == 0 ? mount_motion_ra_handler : mount_motion_dec_handler)) {
		return;
	}
	system_alpaca_lock(device);
	bool sky = X_ALPACA_MOUNT_AXES_SKY_ITEM->sw.value;
	system_alpaca_unlock(device);
	if (sky) {
		rate = -rate;
	} else if (axis == 1 && rate != 0 && mount_motion_side_of_pier(device) == 1) {
		rate = -rate;
	}
	char reason[INDIGO_VALUE_SIZE];
	alpaca_result result = mount_put_axis_rate(device, axis, rate);
	system_alpaca_reason(device, result, reason, sizeof(reason));
	if (result != ALPACA_OK) {
		mount_check_parked(device, result);
	}
	mount_end_motion(device, property, system_alpaca_property_state(result));
	system_alpaca_report(device, property, result, rate != 0 ? "Move" : "Stop", reason);
	indigo_mount_commit_motion_client(device, property);
}

static void mount_motion_dec_handler(indigo_device *device) {
	if (!system_alpaca_is_active(device)) {
		return;
	}
	mount_move_axis(device, 1, MOUNT_MOTION_DEC_PROPERTY, MOUNT_MOTION_NORTH_ITEM_NAME, MOUNT_MOTION_SOUTH_ITEM_NAME);
}

static void mount_motion_ra_handler(indigo_device *device) {
	if (!system_alpaca_is_active(device)) {
		return;
	}
	mount_move_axis(device, 0, MOUNT_MOTION_RA_PROPERTY, MOUNT_MOTION_WEST_ITEM_NAME, MOUNT_MOTION_EAST_ITEM_NAME);
}

// AbortSlew stops a slew, a park, a search for home and MoveAxis. Requests that did not start yet are dropped, and every property that
// waited for the end of a motion ends in ALERT with what the telescope reports after the stop.
// MoveAxis(0) is sent for every axis that moves and AbortSlew always, so the failure to stop one axis neither keeps the other one moving
// nor keeps a slew from being aborted. AbortSlew stops MoveAxis as well (ITelescopeV3), so once it succeeded nothing moves any more.
// A telescope that does not implement AbortSlew has nothing to abort but the motion of its axes, unless this driver watches a slew.
static void mount_abort_motion_handler(indigo_device *device) {
	mount_data *data = MOUNT_DATA;
	alpaca_result result = ALPACA_OK, stop = ALPACA_OK;
	char reason[INDIGO_VALUE_SIZE] = { 0 };
	char stop_reason[INDIGO_VALUE_SIZE] = { 0 };
	if (!system_alpaca_is_active(device)) {
		return;
	}
	if (indigo_get_switch_target(MOUNT_ABORT_MOTION_PROPERTY, MOUNT_ABORT_MOTION_ITEM_NAME)) {
		for (int axis = 0; axis < 2; axis++) {
			if (data->axis_moving[axis]) {
				alpaca_result axis_result = mount_put_axis_rate(device, axis, 0);
				if (axis_result != ALPACA_OK && stop == ALPACA_OK) {
					stop = axis_result;
					system_alpaca_reason(device, stop, stop_reason, sizeof(stop_reason));
				}
			}
		}
		alpaca_result abort = system_alpaca_put(device, "abortslew", NULL, 0, ALPACA_REPLAYABLE);
		system_alpaca_reason(device, abort, reason, sizeof(reason));
		bool aborted = abort == ALPACA_OK;
		bool nothing_to_abort = system_alpaca_not_implemented(abort, 0) && !data->motion.active;
		if (aborted) {
			data->axis_moving[0] = data->axis_moving[1] = false;
			result = ALPACA_OK;
		} else if (nothing_to_abort) {
			result = stop;
			strcpy(reason, stop_reason);
		} else {
			result = abort;
		}
		if (aborted || nothing_to_abort) {
			indigo_cancel_pending_handler(device, mount_equatorial_coordinates_handler);
			indigo_cancel_pending_handler(device, mount_park_handler);
			indigo_cancel_pending_handler(device, mount_home_handler);
			indigo_cancel_pending_handler(device, mount_side_of_pier_handler);
			indigo_cancel_pending_handler(device, mount_motion_dec_handler);
			indigo_cancel_pending_handler(device, mount_motion_ra_handler);
			indigo_cancel_pending_handler(device, mount_motion_finalizer);
			system_alpaca_operation_end(device, &data->motion);
			data->park_requested = data->unpark_requested = data->home_requested = data->flip_requested = data->stop_tracking = data->external_slew = data->slew_requested = data->goto_waits = false;
		}
		if (aborted || stop == ALPACA_OK) {
			system_alpaca_lock(device);
			MOUNT_MOTION_NORTH_ITEM->sw.value = MOUNT_MOTION_SOUTH_ITEM->sw.value = MOUNT_MOTION_WEST_ITEM->sw.value = MOUNT_MOTION_EAST_ITEM->sw.value = false;
			MOUNT_MOTION_DEC_PROPERTY->state = MOUNT_MOTION_RA_PROPERTY->state = INDIGO_OK_STATE;
			system_alpaca_unlock(device);
			indigo_update_property(device, MOUNT_MOTION_DEC_PROPERTY, NULL);
			indigo_update_property(device, MOUNT_MOTION_RA_PROPERTY, NULL);
		}
		if (aborted || nothing_to_abort) {
			mount_read_state(device);
			if (data->slewing && aborted) {
				// AbortSlew returns at once and Slewing stays true until the telescope has stopped
				data->aborted = true;
				system_alpaca_operation_start(device, &data->motion, MOUNT_MOTION_TIMEOUT, mount_motion_finalizer);
				mount_apply_state(device);
				mount_update_state(device);
			} else {
				mount_settle_aborted(device);
			}
		} else {
			mount_check_parked(device, abort);
		}
		if (aborted && stop != ALPACA_OK) {
			indigo_send_message(device, MOUNT_ABORT_MOTION_PROPERTY, "MoveAxis(0) failed: %s%s%s%s, AbortSlew stopped the axis", alpaca_result_text(stop), *stop_reason ? " (" : "", stop_reason, *stop_reason ? ")" : "");
		}
	}
	MOUNT_ABORT_MOTION_ITEM->sw.value = false;
	if (result == ALPACA_OK) {
		system_alpaca_update(device, MOUNT_ABORT_MOTION_PROPERTY, INDIGO_OK_STATE, "Aborted");
		indigo_mount_commit_motion_client(device, MOUNT_ABORT_MOTION_PROPERTY);
	} else {
		system_alpaca_finish_with(device, MOUNT_ABORT_MOTION_PROPERTY, result, "Abort", reason);
	}
}

static void mount_tracking_handler(indigo_device *device) {
	if (!system_alpaca_is_active(device)) {
		return;
	}
	if (mount_is_parked(device)) {
		indigo_send_message(device, MOUNT_TRACKING_PROPERTY, "Mount is parked!");
		mount_set_tracking(device);
		system_alpaca_update(device, MOUNT_TRACKING_PROPERTY, INDIGO_ALERT_STATE, NULL);
		return;
	}
	alpaca_result result = mount_put_tracking(device, indigo_get_switch_target(MOUNT_TRACKING_PROPERTY, MOUNT_TRACKING_ON_ITEM_NAME));
	mount_check_parked(device, result);
	mount_set_tracking(device);
	MOUNT_STATE_TRACKING_ITEM->light.value = MOUNT_DATA->tracking ? INDIGO_OK_STATE : INDIGO_IDLE_STATE;
	indigo_update_property(device, MOUNT_STATE_PROPERTY, NULL);
	system_alpaca_finish(device, MOUNT_TRACKING_PROPERTY, result, "Tracking");
}

static void mount_track_rate_handler(indigo_device *device) {
	mount_data *data = MOUNT_DATA;
	int rate = data->tracking_rate;
	if (!system_alpaca_is_active(device)) {
		return;
	}
	for (int i = 0; i < data->track_rate_count; i++) {
		if (indigo_get_switch_target(MOUNT_TRACK_RATE_PROPERTY, MOUNT_TRACK_RATE_PROPERTY->items[i].name)) {
			rate = data->track_rates[i];
		}
	}
	alpaca_param params[] = { ALPACA_INT_PARAM("TrackingRate", rate) };
	alpaca_result result = system_alpaca_put(device, "trackingrate", params, 1, ALPACA_REPLAYABLE);
	if (result == ALPACA_OK) {
		data->tracking_rate = rate;
	}
	mount_set_tracking_rate(device);
	system_alpaca_finish(device, MOUNT_TRACK_RATE_PROPERTY, result, "Tracking rate");
	if (result == ALPACA_OK && mount_has_offset_rates(device)) {
		// the offset rates read zero unless the telescope tracks at the sidereal rate
		mount_read_offset_rates(device);
		system_alpaca_lock(device);
		bool idle = X_ALPACA_OFFSET_RATE_PROPERTY->state != INDIGO_BUSY_STATE;
		if (idle) {
			mount_set_offset_rates(device);
		}
		system_alpaca_unlock(device);
		if (idle) {
			indigo_update_property(device, X_ALPACA_OFFSET_RATE_PROPERTY, NULL);
		}
	}
}

static void mount_guide_rate_handler(indigo_device *device) {
	if (!system_alpaca_is_active(device)) {
		return;
	}
	mount_data *data = MOUNT_DATA;
	double ra_rate = MOUNT_GUIDE_RATE_RA_ITEM->number.target * MOUNT_SIDEREAL_RATE / 100;
	double dec_rate = MOUNT_GUIDE_RATE_DEC_ITEM->number.target * MOUNT_SIDEREAL_RATE / 100;
	alpaca_param ra[] = { ALPACA_DOUBLE_PARAM("GuideRateRightAscension", ra_rate) };
	alpaca_param dec[] = { ALPACA_DOUBLE_PARAM("GuideRateDeclination", dec_rate) };
	alpaca_result result = system_alpaca_put(device, "guideraterightascension", ra, 1, ALPACA_REPLAYABLE);
	if (result == ALPACA_OK) {
		data->guide_rate_ra = ra_rate;
		result = system_alpaca_put(device, "guideratedeclination", dec, 1, ALPACA_REPLAYABLE);
	}
	if (result == ALPACA_OK) {
		data->guide_rate_dec = dec_rate;
		// a telescope with one guide rate for both axes changes the other one, too; after a failure nothing is read, the message quotes the last answer
		mount_read_guide_rates(device);
	}
	mount_set_guide_rates(device);
	system_alpaca_finish(device, MOUNT_GUIDE_RATE_PROPERTY, result, "Guide rate");
}

