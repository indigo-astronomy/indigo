static void mount_geographic_coordinates_handler(indigo_device *device) {
	if (!system_alpaca_is_active(device)) {
		return;
	}
	mount_data *data = MOUNT_DATA;
	double longitude = MOUNT_GEOGRAPHIC_COORDINATES_LONGITUDE_ITEM->number.target > 180 ? MOUNT_GEOGRAPHIC_COORDINATES_LONGITUDE_ITEM->number.target - 360 : MOUNT_GEOGRAPHIC_COORDINATES_LONGITUDE_ITEM->number.target;
	alpaca_param latitude_params[] = { ALPACA_DOUBLE_PARAM("SiteLatitude", MOUNT_GEOGRAPHIC_COORDINATES_LATITUDE_ITEM->number.target) };
	alpaca_param longitude_params[] = { ALPACA_DOUBLE_PARAM("SiteLongitude", longitude) };
	alpaca_param elevation_params[] = { ALPACA_DOUBLE_PARAM("SiteElevation", MOUNT_GEOGRAPHIC_COORDINATES_ELEVATION_ITEM->number.target) };
	alpaca_result result = system_alpaca_put(device, "sitelatitude", latitude_params, 1, ALPACA_REPLAYABLE);
	if (result == ALPACA_OK) {
		data->latitude = MOUNT_GEOGRAPHIC_COORDINATES_LATITUDE_ITEM->number.target;
		result = system_alpaca_put(device, "sitelongitude", longitude_params, 1, ALPACA_REPLAYABLE);
	}
	if (result == ALPACA_OK) {
		data->longitude = longitude;
	}
	if (result == ALPACA_OK && system_alpaca_supported(device, "SiteElevation")) {
		result = system_alpaca_put(device, "siteelevation", elevation_params, 1, ALPACA_REPLAYABLE);
	}
	if (result == ALPACA_OK) {
		// after a failure nothing is read, the message quotes the last answer of the telescope; the property then shows what was accepted so far
		mount_read_site(device);
	}
	mount_set_site(device);
	system_alpaca_finish(device, MOUNT_GEOGRAPHIC_COORDINATES_PROPERTY, result, "Location");
}

static void mount_utc_time_handler(indigo_device *device) {
	if (!system_alpaca_is_active(device)) {
		return;
	}
	time_t utc = indigo_mount_get_utc_target(device, NULL);
	if (utc == -1) {
		// the request was no date: nothing is sent and the item shows the time of the telescope again
		mount_set_utc(device);
		system_alpaca_update(device, MOUNT_UTC_TIME_PROPERTY, INDIGO_ALERT_STATE, "The time has to be given as YYYY-MM-DDTHH:MM:SS");
		return;
	}
	alpaca_result result = mount_put_utc(device, utc);
	mount_set_utc(device);
	system_alpaca_finish(device, MOUNT_UTC_TIME_PROPERTY, result, "Time");
}

static void mount_set_host_time_handler(indigo_device *device) {
	alpaca_result result = ALPACA_OK;
	if (!system_alpaca_is_active(device)) {
		return;
	}
	if (indigo_get_switch_target(MOUNT_SET_HOST_TIME_PROPERTY, MOUNT_SET_HOST_TIME_ITEM_NAME)) {
		result = mount_put_utc(device, time(NULL));
		if (result == ALPACA_OK) {
			// the time is set: an ALERT left by an earlier request to set it is over
			system_alpaca_lock(device);
			bool idle = MOUNT_UTC_TIME_PROPERTY->state != INDIGO_BUSY_STATE;
			if (idle) {
				mount_set_utc(device);
				MOUNT_UTC_TIME_PROPERTY->state = INDIGO_OK_STATE;
			}
			system_alpaca_unlock(device);
			if (idle) {
				indigo_update_property(device, MOUNT_UTC_TIME_PROPERTY, NULL);
			}
		}
	}
	MOUNT_SET_HOST_TIME_ITEM->sw.value = false;
	system_alpaca_finish(device, MOUNT_SET_HOST_TIME_PROPERTY, result, "Time");
}

static bool mount_on_probe(indigo_device *device) {
	static const char *capabilities[] = { "canpulseguide", "canslewasync", "cansync", "canpark", "canunpark", "cansetpark", "canfindhome", "cansettracking", "cansetpierside", "cansetguiderates", "cansetrightascensionrate", "cansetdeclinationrate" };
	mount_data *data = MOUNT_DATA;
	for (int i = 0; i < (int)(sizeof(capabilities) / sizeof(capabilities[0])); i++) {
		if (system_alpaca_probe_bool(device, capabilities[i], NULL) != ALPACA_OK) {
			return false;
		}
	}
	if (!mount_probe_axis(device, 0) || !mount_probe_axis(device, 1) || !mount_probe_tracking_rates(device)) {
		return false;
	}
	data->equatorial_system = 0;
	if (!mount_usable(system_alpaca_state_int(device, "EquatorialSystem", &data->equatorial_system))) {
		return false;
	}
	data->name[0] = 0;
	if (!mount_usable(system_alpaca_get_string(device, "name", data->name, sizeof(data->name)))) {
		return false;
	}
	return mount_read_state(device) && mount_read_settings(device);
}

static bool mount_on_connect(indigo_device *device) {
	static const char *rate_names[] = { MOUNT_TRACK_RATE_SIDEREAL_ITEM_NAME, MOUNT_TRACK_RATE_LUNAR_ITEM_NAME, MOUNT_TRACK_RATE_SOLAR_ITEM_NAME, MOUNT_TRACK_RATE_KING_ITEM_NAME };
	static const char *rate_labels[] = { "Sidereal rate", "Lunar rate", "Solar rate", "King rate" };
	static const double epochs[] = { 0, 0, 2000, 2050, 1950 };
	mount_data *data = MOUNT_DATA;
	bool can_slew = system_alpaca_can(device, "canslewasync");
	bool can_sync = system_alpaca_can(device, "cansync");
	int count = 0;
	memset(&data->motion, 0, sizeof(data->motion));
	data->action = NULL;
	data->park_requested = data->unpark_requested = data->home_requested = data->flip_requested = data->stop_tracking = data->external_slew = data->coordinates_failed = data->aborted = false;
	data->slew_requested = data->goto_waits = data->home_alert = data->park_recovered = data->home_recovered = data->site_warned = false;
	data->park_alert = -1;
	data->stall_since = 0;
	data->axis_moving[0] = data->axis_moving[1] = false;
	data->utc_changed = false;
	mount_set_parked(device, false);
	mount_note_site(device);
	data->settings_ticks = 0;
	INDIGO_COPY_VALUE(MOUNT_INFO_VENDOR_ITEM->label, "Name");
	INDIGO_COPY_VALUE(MOUNT_INFO_VENDOR_ITEM->text.value, *data->name ? data->name : PRIVATE_DATA->device_name);
	INDIGO_COPY_VALUE(MOUNT_INFO_MODEL_ITEM->text.value, INFO_DEVICE_MODEL_ITEM->text.value);
	INDIGO_COPY_VALUE(MOUNT_INFO_FIRMWARE_ITEM->text.value, INFO_DEVICE_FW_REVISION_ITEM->text.value);
	data->motion_ended = 0;
	data->was_slewing = false;
	if (data->equatorial_system >= 1 && data->equatorial_system <= 4) {
		MOUNT_EPOCH_ITEM->number.value = MOUNT_EPOCH_ITEM->number.target = epochs[data->equatorial_system];
		MOUNT_EPOCH_PROPERTY->perm = INDIGO_RO_PERM;
	} else {
		MOUNT_EPOCH_PROPERTY->perm = INDIGO_RW_PERM;
	}
	if (can_slew) {
		indigo_init_switch_item(MOUNT_ON_COORDINATES_SET_PROPERTY->items + count++, MOUNT_ON_COORDINATES_SET_TRACK_ITEM_NAME, "Slew to target and track", true);
	}
	if (can_sync) {
		indigo_init_switch_item(MOUNT_ON_COORDINATES_SET_PROPERTY->items + count++, MOUNT_ON_COORDINATES_SET_SYNC_ITEM_NAME, "Sync to target", !can_slew);
	}
	if (can_slew && system_alpaca_can(device, "cansettracking")) {
		indigo_init_switch_item(MOUNT_ON_COORDINATES_SET_PROPERTY->items + count++, MOUNT_ON_COORDINATES_SET_SLEW_ITEM_NAME, "Slew to target and stop", false);
	}
	MOUNT_ON_COORDINATES_SET_PROPERTY->count = count > 0 ? count : 1;
	MOUNT_ON_COORDINATES_SET_PROPERTY->hidden = count == 0;
	MOUNT_EQUATORIAL_COORDINATES_PROPERTY->perm = count > 0 ? INDIGO_RW_PERM : INDIGO_RO_PERM;
	system_alpaca_set_state(device, MOUNT_EQUATORIAL_COORDINATES_PROPERTY, INDIGO_OK_STATE);
	MOUNT_PARK_PROPERTY->hidden = !system_alpaca_can(device, "canpark") && !system_alpaca_can(device, "canunpark");
	MOUNT_PARK_SET_PROPERTY->hidden = !system_alpaca_can(device, "cansetpark");
	MOUNT_PARK_SET_PROPERTY->count = 1;
	MOUNT_HOME_PROPERTY->hidden = !system_alpaca_can(device, "canfindhome");
	MOUNT_TRACKING_PROPERTY->perm = system_alpaca_can(device, "cansettracking") ? INDIGO_RW_PERM : INDIGO_RO_PERM;
	for (int i = 0; i < data->track_rate_count; i++) {
		indigo_init_switch_item(MOUNT_TRACK_RATE_PROPERTY->items + i, rate_names[data->track_rates[i]], rate_labels[data->track_rates[i]], false);
	}
	MOUNT_TRACK_RATE_PROPERTY->count = data->track_rate_count > 0 ? data->track_rate_count : 1;
	MOUNT_TRACK_RATE_PROPERTY->hidden = data->track_rate_count == 0 || !system_alpaca_supported(device, "TrackingRate");
	MOUNT_GUIDE_RATE_PROPERTY->hidden = !mount_has_guide_rates(device);
	MOUNT_GUIDE_RATE_PROPERTY->perm = system_alpaca_can(device, "cansetguiderates") ? INDIGO_RW_PERM : INDIGO_RO_PERM;
	MOUNT_GUIDE_RATE_RA_ITEM->number.max = MOUNT_GUIDE_RATE_DEC_ITEM->number.max = 1000;
	MOUNT_MOTION_RA_PROPERTY->hidden = !data->can_move_axis[0];
	MOUNT_MOTION_DEC_PROPERTY->hidden = !data->can_move_axis[1];
	MOUNT_SLEW_RATE_PROPERTY->hidden = !data->can_move_axis[0] && !data->can_move_axis[1];
	MOUNT_MOTION_NORTH_ITEM->sw.value = MOUNT_MOTION_SOUTH_ITEM->sw.value = MOUNT_MOTION_WEST_ITEM->sw.value = MOUNT_MOTION_EAST_ITEM->sw.value = false;
	MOUNT_SIDE_OF_PIER_PROPERTY->hidden = !system_alpaca_supported(device, "SideOfPier");
	MOUNT_SIDE_OF_PIER_PROPERTY->perm = system_alpaca_can(device, "cansetpierside") ? INDIGO_RW_PERM : INDIGO_RO_PERM;
	MOUNT_UTC_TIME_PROPERTY->hidden = MOUNT_SET_HOST_TIME_PROPERTY->hidden = !system_alpaca_supported(device, "UTCDate");
	MOUNT_UTC_TIME_PROPERTY->count = 1;
	MOUNT_STATE_PROPERTY->hidden = false;
	X_ALPACA_OFFSET_RATE_PROPERTY->hidden = !mount_has_offset_rates(device);
	mount_apply_settings(device);
	mount_apply_state(device);
	system_alpaca_lock(device);
	MOUNT_EQUATORIAL_COORDINATES_RA_ITEM->number.target = MOUNT_EQUATORIAL_COORDINATES_RA_ITEM->number.value;
	MOUNT_EQUATORIAL_COORDINATES_DEC_ITEM->number.target = MOUNT_EQUATORIAL_COORDINATES_DEC_ITEM->number.value;
	MOUNT_GUIDE_RATE_RA_ITEM->number.target = MOUNT_GUIDE_RATE_RA_ITEM->number.value;
	MOUNT_GUIDE_RATE_DEC_ITEM->number.target = MOUNT_GUIDE_RATE_DEC_ITEM->number.value;
	X_ALPACA_OFFSET_RATE_RA_ITEM->number.target = X_ALPACA_OFFSET_RATE_RA_ITEM->number.value;
	X_ALPACA_OFFSET_RATE_DEC_ITEM->number.target = X_ALPACA_OFFSET_RATE_DEC_ITEM->number.value;
	if (mount_has_site(device)) {
		MOUNT_GEOGRAPHIC_COORDINATES_LATITUDE_ITEM->number.target = MOUNT_GEOGRAPHIC_COORDINATES_LATITUDE_ITEM->number.value;
		MOUNT_GEOGRAPHIC_COORDINATES_LONGITUDE_ITEM->number.target = MOUNT_GEOGRAPHIC_COORDINATES_LONGITUDE_ITEM->number.value;
		MOUNT_GEOGRAPHIC_COORDINATES_ELEVATION_ITEM->number.target = MOUNT_GEOGRAPHIC_COORDINATES_ELEVATION_ITEM->number.value;
	}
	MOUNT_HORIZONTAL_COORDINATES_PROPERTY->state = MOUNT_EQUATORIAL_COORDINATES_PROPERTY->state;
	system_alpaca_unlock(device);
	if (system_alpaca_can(device, "canpulseguide")) {
		system_alpaca_attach_secondary(device, &system_alpaca_guider_class);
	}
	indigo_define_property(device, X_ALPACA_OFFSET_RATE_PROPERTY, NULL);
	indigo_define_property(device, X_ALPACA_MOUNT_AXES_PROPERTY, NULL);
	indigo_define_property(device, X_ALPACA_SETTLE_TIME_PROPERTY, NULL);
	return true;
}

static void mount_on_disconnect(indigo_device *device) {
	mount_data *data = MOUNT_DATA;
	// a manual motion runs until it is stopped, so it does not outlive the connection; a slew is left to finish
	for (int axis = 0; axis < 2; axis++) {
		if (data->axis_moving[axis]) {
			mount_put_axis_rate(device, axis, 0);
			data->axis_moving[axis] = false;
		}
	}
	system_alpaca_operation_end(device, &data->motion);
	data->park_requested = data->unpark_requested = data->home_requested = data->flip_requested = data->stop_tracking = data->external_slew = data->aborted = false;
	data->slew_requested = data->goto_waits = data->home_alert = false;
	data->park_alert = -1;
	// the properties are still defined, so a request may be accepted while they are reset; its handler finds the session closed
	system_alpaca_lock(device);
	data->site = false;
	MOUNT_MOTION_NORTH_ITEM->sw.value = MOUNT_MOTION_SOUTH_ITEM->sw.value = MOUNT_MOTION_WEST_ITEM->sw.value = MOUNT_MOTION_EAST_ITEM->sw.value = false;
	MOUNT_ABORT_MOTION_ITEM->sw.value = MOUNT_HOME_ITEM->sw.value = MOUNT_PARK_SET_CURRENT_ITEM->sw.value = MOUNT_SET_HOST_TIME_ITEM->sw.value = false;
	MOUNT_ABORT_MOTION_PROPERTY->state = MOUNT_PARK_SET_PROPERTY->state = MOUNT_TRACKING_PROPERTY->state = MOUNT_TRACK_RATE_PROPERTY->state = MOUNT_GUIDE_RATE_PROPERTY->state = INDIGO_OK_STATE;
	MOUNT_GEOGRAPHIC_COORDINATES_PROPERTY->state = MOUNT_UTC_TIME_PROPERTY->state = MOUNT_SET_HOST_TIME_PROPERTY->state = MOUNT_SIDE_OF_PIER_PROPERTY->state = X_ALPACA_OFFSET_RATE_PROPERTY->state = INDIGO_OK_STATE;
	system_alpaca_unlock(device);
	indigo_delete_property(device, X_ALPACA_OFFSET_RATE_PROPERTY, NULL);
	indigo_delete_property(device, X_ALPACA_MOUNT_AXES_PROPERTY, NULL);
	indigo_delete_property(device, X_ALPACA_SETTLE_TIME_PROPERTY, NULL);
}

// A site of exactly 0° / 0° reported by the telescope is not set, see SITE: warn once, and again after the site was something else.
static void mount_warn_site(indigo_device *device) {
	mount_data *data = MOUNT_DATA;
	bool unset = mount_has_site(device) && fabs(data->latitude) < 1e-6 && fabs(data->longitude) < 1e-6;
	if (unset && !data->site_warned) {
		indigo_send_message(device, MOUNT_GEOGRAPHIC_COORDINATES_PROPERTY, "Warning: the Alpaca server reports the site 0° N, 0° E, which is most likely not set; the telescope computes its sidereal time and coordinates for that site until GEOGRAPHIC_COORDINATES is set");
	}
	data->site_warned = unset;
}

static void mount_on_poll(indigo_device *device) {
	mount_data *data = MOUNT_DATA;
	mount_read_state(device);
	mount_apply_state(device);
	mount_update_state(device);
	if (++data->settings_ticks >= MOUNT_SETTINGS_TICKS && !data->motion.active) {
		data->settings_ticks = 0;
		mount_read_settings(device);
		mount_apply_settings(device);
		mount_update_settings(device);
	}
	mount_warn_site(device);
}

