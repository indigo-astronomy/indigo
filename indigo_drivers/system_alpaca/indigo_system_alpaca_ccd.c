// Find out how Gain or Offset is set: as a value between a minimum and a maximum, or as the index of a name of a list.
// A list with more names than a property of this driver holds is used by the index as a value.
static bool ccd_probe_level(indigo_device *device, const char *member, const char *min_member, const char *max_member, const char *list_member, ccd_level *level) {
	bool has_min = false, has_max = false, has_value = false;
	memset(level, 0, sizeof(ccd_level));
	if (!ccd_probe_int(device, min_member, &level->min, &has_min) || !ccd_probe_int(device, max_member, &level->max, &has_max)) {
		return false;
	}
	if (has_min && has_max && level->max >= level->min) {
		level->mode = CCD_LEVEL_VALUE;
	} else {
		alpaca_channel *channel = system_alpaca_channel(device);
		const alpaca_json_value *list = NULL;
		alpaca_result result = system_alpaca_check(device, alpaca_get_value(channel, list_member, NULL, 0, ALPACA_WAIT_STANDARD, &list));
		if (result == ALPACA_OK) {
			for (const alpaca_json_value *name = alpaca_json_first(list); name != NULL; name = alpaca_json_next(name)) {
				const char *text = "";
				alpaca_json_get_string(name, &text);
				if (level->count < CCD_MAX_LEVELS) {
					ccd_copy_text(level->names[level->count], INDIGO_NAME_SIZE, text, strlen(text));
				}
				level->count++;
			}
			alpaca_end(channel);
			if (level->count > 0) {
				level->mode = level->count <= CCD_MAX_LEVELS ? CCD_LEVEL_INDEX : CCD_LEVEL_VALUE;
				level->min = 0;
				level->max = level->count - 1;
			}
		} else if (!ccd_probed(device, list_member, result, NULL)) {
			return false;
		}
	}
	if (level->mode != CCD_LEVEL_NONE) {
		if (!ccd_probe_int(device, member, &level->value, &has_value)) {
			return false;
		}
		if (!has_value) {
			level->mode = CCD_LEVEL_NONE;
		}
	}
	return true;
}

// Remember the values of CCD_FRAME as the frame the client asked for.
static void ccd_remember_frame(indigo_device *device) {
	ccd_data *data = CCD_DATA;
	data->frame_left = (int)CCD_FRAME_LEFT_ITEM->number.value;
	data->frame_top = (int)CCD_FRAME_TOP_ITEM->number.value;
	data->frame_width = (int)CCD_FRAME_WIDTH_ITEM->number.value;
	data->frame_height = (int)CCD_FRAME_HEIGHT_ITEM->number.value;
}

// Bring CCD_FRAME in line with the binning and the sensor: the frame the client asked for is moved onto the binned pixels and cut to
// the sensor. It starts from the requested frame every time, so the frame does not shrink step by step when the binning changes
// and a saved configuration is restored whatever the order of CCD_FRAME and CCD_BIN is.
// Returns false if the requested frame had to be cut because it does not fit the sensor.
static bool ccd_normalize_frame(indigo_device *device) {
	ccd_data *data = CCD_DATA;
	int bin_x = (int)CCD_BIN_HORIZONTAL_ITEM->number.value, bin_y = (int)CCD_BIN_VERTICAL_ITEM->number.value;
	int max_x = data->width / bin_x > 0 ? data->width / bin_x : 1, max_y = data->height / bin_y > 0 ? data->height / bin_y : 1;
	int start_x = data->frame_left / bin_x, start_y = data->frame_top / bin_y;
	int num_x = data->frame_width / bin_x, num_y = data->frame_height / bin_y;
	bool fits = true;
	if (start_x < 0 || start_x >= max_x) {
		start_x = start_x < 0 ? 0 : max_x - 1;
		fits = false;
	}
	if (start_y < 0 || start_y >= max_y) {
		start_y = start_y < 0 ? 0 : max_y - 1;
		fits = false;
	}
	if (num_x < 1) {
		num_x = 1;
	}
	if (num_y < 1) {
		num_y = 1;
	}
	if (start_x + num_x > max_x) {
		num_x = max_x - start_x;
		fits = false;
	}
	if (start_y + num_y > max_y) {
		num_y = max_y - start_y;
		fits = false;
	}
	CCD_FRAME_LEFT_ITEM->number.value = CCD_FRAME_LEFT_ITEM->number.target = start_x * bin_x;
	CCD_FRAME_TOP_ITEM->number.value = CCD_FRAME_TOP_ITEM->number.target = start_y * bin_y;
	CCD_FRAME_WIDTH_ITEM->number.value = CCD_FRAME_WIDTH_ITEM->number.target = num_x * bin_x;
	CCD_FRAME_HEIGHT_ITEM->number.value = CCD_FRAME_HEIGHT_ITEM->number.target = num_y * bin_y;
	// the depth is what the camera delivers, it can not be chosen
	CCD_FRAME_BITS_PER_PIXEL_ITEM->number.value = CCD_FRAME_BITS_PER_PIXEL_ITEM->number.target = data->bits_per_pixel;
	return fits;
}

// PUT one member of the frame unless the camera has the value already.
static alpaca_result ccd_put_frame_member(indigo_device *device, const char *member, const char *name, int value, int *known, bool force) {
	if (!force && *known == value) {
		return ALPACA_OK;
	}
	alpaca_param params[] = { ALPACA_INT_PARAM(name, value) };
	alpaca_result result = system_alpaca_put(device, member, params, 1, ALPACA_REPLAYABLE);
	if (result == ALPACA_OK) {
		*known = value;
	}
	return result;
}

// Send the binning and the subframe of CCD_BIN and CCD_FRAME to the camera, as far as it does not have them.
static alpaca_result ccd_apply_frame(indigo_device *device) {
	ccd_data *data = CCD_DATA;
	int bin_x = (int)CCD_BIN_HORIZONTAL_ITEM->number.value, bin_y = (int)CCD_BIN_VERTICAL_ITEM->number.value;
	int start_x = (int)CCD_FRAME_LEFT_ITEM->number.value / bin_x, start_y = (int)CCD_FRAME_TOP_ITEM->number.value / bin_y;
	int num_x = (int)CCD_FRAME_WIDTH_ITEM->number.value / bin_x, num_y = (int)CCD_FRAME_HEIGHT_ITEM->number.value / bin_y;
	bool force = !data->frame_known;
	// a camera may reset its subframe when the binning changes, so the subframe is sent again after the binning
	bool rebinned = force || data->bin_x != bin_x || data->bin_y != bin_y;
	data->frame_known = false;
	alpaca_result result = ccd_put_frame_member(device, "binx", "BinX", bin_x, &data->bin_x, force);
	if (result == ALPACA_OK) {
		result = ccd_put_frame_member(device, "biny", "BinY", bin_y, &data->bin_y, force);
	}
	if (result == ALPACA_OK) {
		result = ccd_put_frame_member(device, "startx", "StartX", start_x, &data->start_x, rebinned);
	}
	if (result == ALPACA_OK) {
		result = ccd_put_frame_member(device, "starty", "StartY", start_y, &data->start_y, rebinned);
	}
	if (result == ALPACA_OK) {
		result = ccd_put_frame_member(device, "numx", "NumX", num_x, &data->num_x, rebinned);
	}
	if (result == ALPACA_OK) {
		result = ccd_put_frame_member(device, "numy", "NumY", num_y, &data->num_y, rebinned);
	}
	data->frame_known = result == ALPACA_OK;
	return result;
}

// Read CameraState and ImageReady: with one devicestate request from a Platform 7 camera, member by member otherwise.
// Like the poll of the core, a devicestate that gets an answer that is no snapshot (HTTP 500, a reply that can not be read, an error of
// the device) is no failure of the exposure: the members are read in the same call, and after CCD_STATE_FAILURE_LIMIT such answers in a
// row devicestate is not used for the exposures of this connection any more. Only a request without an answer (and NotConnected) is
// returned as it is; the core decides about the transport.
static alpaca_result ccd_read_progress(indigo_device *device, int *state, bool *ready) {
	ccd_data *data = CCD_DATA;
	if (PRIVATE_DATA->platform7 && !data->no_device_state) {
		alpaca_result result = system_alpaca_check(device, alpaca_get_device_state(system_alpaca_channel(device), &data->state));
		if (result == ALPACA_OK && alpaca_state_int(&data->state, "CameraState", state) && alpaca_state_bool(&data->state, "ImageReady", ready)) {
			data->state_failures = 0;
			return ALPACA_OK;
		}
		if (alpaca_is_transport_error(result) || result == ALPACA_NOT_CONNECTED) {
			return result;
		}
		if (result == ALPACA_OK || alpaca_is_unsupported(result)) {
			INDIGO_DRIVER_DEBUG(DRIVER_NAME, "'%s' does not report CameraState and ImageReady in devicestate, reading the members", device->name);
			data->no_device_state = true;
		} else if (++data->state_failures >= CCD_STATE_FAILURE_LIMIT) {
			INDIGO_DRIVER_DEBUG(DRIVER_NAME, "'%s' devicestate -> %s %d times in a row, reading the members from now on", device->name, alpaca_result_text(result), data->state_failures);
			data->no_device_state = true;
		} else {
			INDIGO_DRIVER_DEBUG(DRIVER_NAME, "'%s' devicestate -> %s, reading the members", device->name, alpaca_result_text(result));
		}
	}
	alpaca_result result = system_alpaca_get_int(device, "camerastate", state);
	if (result == ALPACA_OK) {
		result = system_alpaca_get_bool(device, "imageready", ready);
	}
	return result;
}

// BAYERPAT of the frame of the last exposure, NULL if the frame has no known colour filter pattern.
static const char *ccd_bayer_pattern(indigo_device *device) {
	ccd_data *data = CCD_DATA;
	if (data->sensor_type != CCD_SENSOR_RGGB || data->exposure_binned) {
		return NULL;
	}
	// the offsets of the Bayer matrix refer to the pixel 0, 0 of the sensor and do not follow the subframe
	return ccd_bayer_patterns[((data->bayer_offset_y + data->exposure_top) & 1) * 2 + ((data->bayer_offset_x + data->exposure_left) & 1)];
}

// Answer a request that failed because the camera does not implement the setter: the property stays, read only.
static void ccd_finish(indigo_device *device, indigo_property *property, alpaca_result result, const char *action) {
	if (result == ALPACA_UNSUPPORTED) {
		indigo_delete_property(device, property, NULL);
		property->perm = INDIGO_RO_PERM;
		system_alpaca_set_state(device, property, INDIGO_OK_STATE);
		indigo_define_property(device, property, "%s can not be changed on this camera", action);
	} else {
		system_alpaca_finish(device, property, result, action);
	}
}

