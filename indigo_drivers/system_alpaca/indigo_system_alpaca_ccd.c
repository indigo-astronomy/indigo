// Store the image that came in as width * height * planes elements of the given type. minimum and maximum are the limits of the
// elements if they are known already (scanned). The depth of the image follows MaxADU, so it does not change from frame to frame
// with the content, and the data only if they do not fit into what MaxADU promises.
static alpaca_result ccd_store_image(ccd_data *data, const unsigned char *source, int type, size_t width, size_t height, size_t planes, double minimum, double maximum, bool scanned) {
	size_t count = width * height * planes;
	size_t bytes = 1;
	int shift = 0;
	if (!scanned && (type == CCD_ELEMENT_BYTE || (type == CCD_ELEMENT_UINT16 && data->download.max_adu > 255))) {
		// the type itself keeps the elements within the range of the target
		minimum = maximum = 0;
	} else if (!scanned) {
		ccd_scan(source, type, count, &minimum, &maximum);
	}
	double range = fmax(data->download.max_adu, maximum);
	if (range > 255) {
		bytes = 2;
		while (range > 65535) {
			range = floor(range / 2);
			shift++;
		}
	}
	bool copy = shift == 0 && minimum >= 0 && ((type == CCD_ELEMENT_BYTE && bytes == 1) || ((type == CCD_ELEMENT_UINT16 || type == CCD_ELEMENT_INT16) && bytes == 2));
	size_t needed = FITS_HEADER_SIZE + count * bytes + FITS_LOGICAL_RECORD_LENGTH;
	if (needed > data->image_size) {
		data->image = indigo_safe_realloc(data->image, needed);
		data->image_size = needed;
	}
	ccd_transpose(source, type, width, height, planes, copy, shift, bytes, data->image + FITS_HEADER_SIZE);
	data->download.width = (int)width;
	data->download.height = (int)height;
	data->download.bpp = (int)(8 * bytes * planes);
	return ALPACA_OK;
}

// ImageBytes: 44 bytes of little endian int32 metadata, then the elements from DataStart on, or the UTF-8 text of the error.
static alpaca_result ccd_decode_imagebytes(ccd_data *data, alpaca_channel *channel, const alpaca_http_response *response) {
	const unsigned char *body = (const unsigned char *)response->body.data;
	size_t size = response->body.size;
	char text[CCD_MESSAGE_SIZE - 16];
	if (body == NULL || size < CCD_IMAGEBYTES_HEADER_SIZE) {
		return ccd_download_error(data, ALPACA_PROTOCOL_ERROR, "ImageBytes reply of %lu bytes is shorter than its metadata", (unsigned long)size);
	}
	int version = (int32_t)ccd_le32(body);
	int error_number = (int32_t)ccd_le32(body + 4);
	uint32_t echo = ccd_le32(body + 8);
	int data_start = (int32_t)ccd_le32(body + 16);
	int image_type = (int32_t)ccd_le32(body + 20);
	int transmission_type = (int32_t)ccd_le32(body + 24);
	int rank = (int32_t)ccd_le32(body + 28);
	int dimension1 = (int32_t)ccd_le32(body + 32);
	int dimension2 = (int32_t)ccd_le32(body + 36);
	int dimension3 = (int32_t)ccd_le32(body + 40);
	if (version != 1) {
		return ccd_download_error(data, ALPACA_PROTOCOL_ERROR, "Unsupported ImageBytes metadata version %d", version);
	}
	if (echo != 0 && !alpaca_accept_transaction_id(channel, echo)) {
		// the reply to another request: the connection is out of step
		alpaca_channel_close(channel);
		return ccd_download_error(data, ALPACA_PROTOCOL_ERROR, "ClientTransactionID %u of the image does not match the request", (unsigned)echo);
	}
	if (data_start < CCD_IMAGEBYTES_HEADER_SIZE || (size_t)data_start > size) {
		return ccd_download_error(data, ALPACA_PROTOCOL_ERROR, "ImageBytes DataStart %d is outside the reply of %lu bytes", data_start, (unsigned long)size);
	}
	if (error_number != 0) {
		ccd_copy_text(text, sizeof(text), (const char *)body + data_start, size - (size_t)data_start);
		return ccd_download_error(data, alpaca_error_result(error_number), "%s (0x%X)", *text ? text : "No error message", (unsigned)error_number);
	}
	if (rank != 2 && rank != 3) {
		return ccd_download_error(data, ALPACA_PROTOCOL_ERROR, "Unsupported ImageBytes rank %d", rank);
	}
	if (dimension1 <= 0 || dimension2 <= 0 || (rank == 3 && dimension3 != 3)) {
		return ccd_download_error(data, ALPACA_PROTOCOL_ERROR, "Unsupported ImageBytes dimensions %d x %d x %d", dimension1, dimension2, dimension3);
	}
	// the elements may be transmitted in a narrower type than the one of the array (the server narrows them when the values fit), never in a wider one
	bool known_types = image_type >= CCD_ELEMENT_INT16 && image_type <= CCD_ELEMENT_UINT32 && transmission_type >= CCD_ELEMENT_INT16 && transmission_type <= CCD_ELEMENT_UINT32;
	if (!known_types || ccd_element_size(transmission_type) > ccd_element_size(image_type)) {
		return ccd_download_error(data, ALPACA_PROTOCOL_ERROR, "Unsupported ImageBytes element types %d transmitted as %d", image_type, transmission_type);
	}
	size_t planes = rank == 3 ? 3 : 1;
	uint64_t expected = (uint64_t)dimension1 * (uint64_t)dimension2 * planes * (uint64_t)ccd_element_size(transmission_type);
	if (expected != size - (size_t)data_start) {
		return ccd_download_error(data, ALPACA_PROTOCOL_ERROR, "ImageBytes data of %lu bytes do not match %d x %d x %d elements of %d bytes", (unsigned long)(size - (size_t)data_start), dimension1, dimension2, (int)planes, ccd_element_size(transmission_type));
	}
	return ccd_store_image(data, body + data_start, transmission_type, (size_t)dimension1, (size_t)dimension2, planes, 0, 0, false);
}

// The server answered imagearray with the JSON envelope although ImageBytes was offered.
static alpaca_result ccd_decode_json(ccd_data *data, alpaca_channel *channel, const alpaca_http_response *response) {
	alpaca_json_image image = { 0 };
	char error[ALPACA_TEXT_SIZE] = { 0 };
	char text[CCD_MESSAGE_SIZE - 16];
	if (response->body.data == NULL || !alpaca_json_parse_image(response->body.data, response->body.size, ALPACA_JSON_IMAGE_INT32, &data->json_pixels, &data->json_capacity, true, &image, error, sizeof(error))) {
		return ccd_download_error(data, ALPACA_PROTOCOL_ERROR, "Malformed JSON image (%s)", error);
	}
	if (image.has_client_transaction_id && image.client_transaction_id != 0 && !alpaca_accept_transaction_id(channel, image.client_transaction_id)) {
		alpaca_channel_close(channel);
		return ccd_download_error(data, ALPACA_PROTOCOL_ERROR, "ClientTransactionID %u of the image does not match the request", (unsigned)image.client_transaction_id);
	}
	if (image.has_error_number && image.error_number != 0) {
		int error_number = image.error_number > INT32_MAX || image.error_number < INT32_MIN ? 0x4FF : (int)image.error_number;
		ccd_copy_text(text, sizeof(text), image.error_message, strlen(image.error_message));
		return ccd_download_error(data, alpaca_error_result(error_number), "%s (0x%X)", *text ? text : "No error message", (unsigned)error_number);
	}
	if (!image.has_value) {
		return ccd_download_error(data, ALPACA_PROTOCOL_ERROR, "Value is missing");
	}
	if ((image.rank != 2 && image.rank != 3) || image.dimensions[0] <= 0 || image.dimensions[1] <= 0 || (image.rank == 3 && image.dimensions[2] != 3)) {
		return ccd_download_error(data, ALPACA_PROTOCOL_ERROR, "Unsupported JSON image of rank %d, %d x %d x %d", image.rank, image.dimensions[0], image.dimensions[1], image.dimensions[2]);
	}
	return ccd_store_image(data, data->json_pixels, CCD_ELEMENT_NATIVE_INT32, (size_t)image.dimensions[0], (size_t)image.dimensions[1], image.rank == 3 ? 3 : 1, image.minimum, image.maximum, true);
}

