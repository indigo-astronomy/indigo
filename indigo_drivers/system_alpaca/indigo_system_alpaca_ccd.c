// Result of reading a member in ccd_on_probe: note whether the camera has it and return false if the camera did not answer at all.
static bool ccd_probed(indigo_device *device, const char *member, alpaca_result result, bool *supported) {
	if (supported != NULL) {
		*supported = result == ALPACA_OK;
	}
	if (alpaca_is_unsupported(result)) {
		system_alpaca_set_unsupported(device, member);
	}
	return !alpaca_is_transport_error(result);
}

