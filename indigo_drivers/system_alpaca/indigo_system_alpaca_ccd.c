// A new set point was requested and ccd_temperature_handler did not send it yet. Until then CCD_TEMPERATURE is BUSY because of the
// request and is left alone by everything else. Called with the lock of the device held: the count is written by the bus thread.
static bool ccd_set_point_pending(indigo_device *device) {
	return CCD_DATA->set_point_requests > 0;
}

// State of CCD_TEMPERATURE: BUSY while the cooler works towards the set point.
static indigo_property_state ccd_temperature_state(indigo_device *device) {
	ccd_data *data = CCD_DATA;
	return CCD_TEMPERATURE_PROPERTY->perm == INDIGO_RW_PERM && data->cooler_on && fabs(data->temperature - data->set_point) > CCD_TEMPERATURE_TOLERANCE ? INDIGO_BUSY_STATE : INDIGO_OK_STATE;
}

static void ccd_cooler_handler(indigo_device *device) {
	ccd_data *data = CCD_DATA;
	if (!system_alpaca_is_active(device)) {
		return;
	}
	alpaca_param params[] = { ALPACA_BOOL_PARAM("CoolerOn", CCD_COOLER_ON_ITEM->sw.value) };
	alpaca_result result = system_alpaca_put(device, "cooleron", params, 1, ALPACA_REPLAYABLE);
	if (result == ALPACA_OK) {
		data->cooler_on = CCD_COOLER_ON_ITEM->sw.value;
	}
	indigo_set_switch(CCD_COOLER_PROPERTY, data->cooler_on ? CCD_COOLER_ON_ITEM : CCD_COOLER_OFF_ITEM, true);
	ccd_finish(device, CCD_COOLER_PROPERTY, result, "Cooler");
	if (result == ALPACA_OK && !CCD_TEMPERATURE_PROPERTY->hidden) {
		system_alpaca_lock(device);
		bool changed = !ccd_set_point_pending(device) && CCD_TEMPERATURE_PROPERTY->state != ccd_temperature_state(device);
		if (changed) {
			CCD_TEMPERATURE_PROPERTY->state = ccd_temperature_state(device);
		}
		system_alpaca_unlock(device);
		if (changed) {
			indigo_update_property(device, CCD_TEMPERATURE_PROPERTY, NULL);
		}
	}
}

static void ccd_temperature_handler(indigo_device *device) {
	ccd_data *data = CCD_DATA;
	system_alpaca_lock(device);
	if (data->set_point_requests > 0) {
		data->set_point_requests--;
	}
	system_alpaca_unlock(device);
	if (!system_alpaca_is_active(device)) {
		return;
	}
	// the property is accepted while it is BUSY, so the bus thread may be writing the target
	system_alpaca_lock(device);
	double set_point = CCD_TEMPERATURE_ITEM->number.target;
	system_alpaca_unlock(device);
	alpaca_param params[] = { ALPACA_DOUBLE_PARAM("SetCCDTemperature", set_point) };
	alpaca_result result = system_alpaca_put(device, "setccdtemperature", params, 1, ALPACA_REPLAYABLE);
	if (result == ALPACA_OK) {
		data->set_point = set_point;
		// a newer set point that waits for its handler keeps the property BUSY
		system_alpaca_lock(device);
		if (!ccd_set_point_pending(device)) {
			CCD_TEMPERATURE_PROPERTY->state = ccd_temperature_state(device);
		}
		system_alpaca_unlock(device);
		indigo_update_property(device, CCD_TEMPERATURE_PROPERTY, NULL);
	} else {
		char reason[INDIGO_VALUE_SIZE];
		system_alpaca_reason(device, result, reason, sizeof(reason));
		system_alpaca_lock(device);
		bool superseded = ccd_set_point_pending(device);
		if (!superseded) {
			CCD_TEMPERATURE_ITEM->number.target = data->set_point;
		}
		system_alpaca_unlock(device);
		if (superseded) {
			// the newer set point owns the property; the failure of this one is told all the same
			system_alpaca_report(device, CCD_TEMPERATURE_PROPERTY, result, "Set point", reason);
		} else {
			ccd_finish(device, CCD_TEMPERATURE_PROPERTY, result, "Set point");
		}
	}
}

static bool ccd_on_probe(indigo_device *device) {
	ccd_data *data = CCD_DATA;
	alpaca_channel *channel = system_alpaca_channel(device);
	bool supported = false, has_offsets = false;
	bool known[6] = { false };
	int count = 0;
	if (system_alpaca_get_int(device, "cameraxsize", &data->width) != ALPACA_OK || system_alpaca_get_int(device, "cameraysize", &data->height) != ALPACA_OK) {
		return false;
	}
	if (data->width <= 0 || data->height <= 0) {
		INDIGO_DRIVER_ERROR(DRIVER_NAME, "'%s' reports a sensor of %d x %d pixels", device->name, data->width, data->height);
		return false;
	}
	for (size_t i = 0; i < sizeof(ccd_capabilities) / sizeof(ccd_capabilities[0]); i++) {
		if (alpaca_is_transport_error(system_alpaca_probe_bool(device, ccd_capabilities[i], NULL))) {
			return false;
		}
	}
	// the frame: what the camera does not tell is the whole sensor without binning
	data->max_bin_x = data->max_bin_y = data->bin_x = data->bin_y = 1;
	data->start_x = data->start_y = 0;
	data->num_x = data->width;
	data->num_y = data->height;
	if (!ccd_probe_int(device, "maxbinx", &data->max_bin_x, NULL) || !ccd_probe_int(device, "maxbiny", &data->max_bin_y, NULL)) {
		return false;
	}
	if (!ccd_probe_int(device, "binx", &data->bin_x, known + 0) || !ccd_probe_int(device, "biny", &data->bin_y, known + 1) || !ccd_probe_int(device, "startx", &data->start_x, known + 2)) {
		return false;
	}
	if (!ccd_probe_int(device, "starty", &data->start_y, known + 3) || !ccd_probe_int(device, "numx", &data->num_x, known + 4) || !ccd_probe_int(device, "numy", &data->num_y, known + 5)) {
		return false;
	}
	data->frame_known = known[0] && known[1] && known[2] && known[3] && known[4] && known[5];
	data->max_bin_x = data->max_bin_x < 1 ? 1 : data->max_bin_x;
	data->max_bin_y = data->max_bin_y < 1 ? 1 : data->max_bin_y;
	// the sensor
	data->pixel_size_x = data->pixel_size_y = 0;
	data->max_adu = 65535;
	data->sensor_type = CCD_SENSOR_MONOCHROME;
	data->bayer_offset_x = data->bayer_offset_y = 0;
	data->sensor_name[0] = 0;
	if (!ccd_probe_double(device, "pixelsizex", &data->pixel_size_x, NULL) || !ccd_probe_double(device, "pixelsizey", &data->pixel_size_y, NULL) || !ccd_probe_int(device, "maxadu", &data->max_adu, NULL)) {
		return false;
	}
	if (!ccd_probe_double(device, "electronsperadu", &data->electrons_per_adu, &data->has_electrons_per_adu) || !ccd_probe_double(device, "fullwellcapacity", &data->full_well_capacity, &data->has_full_well_capacity)) {
		return false;
	}
	if (!ccd_probe_int(device, "sensortype", &data->sensor_type, &data->has_sensor_type) || !ccd_probed(device, "sensorname", system_alpaca_get_string(device, "sensorname", data->sensor_name, sizeof(data->sensor_name)), NULL)) {
		return false;
	}
	if (data->sensor_type == CCD_SENSOR_RGGB) {
		if (!ccd_probe_int(device, "bayeroffsetx", &data->bayer_offset_x, &supported) || !ccd_probe_int(device, "bayeroffsety", &data->bayer_offset_y, &has_offsets)) {
			return false;
		}
		if (!supported || !has_offsets) {
			data->bayer_offset_x = data->bayer_offset_y = 0;
		}
	}
	data->max_adu = data->max_adu < 1 ? 65535 : data->max_adu;
	// the exposure
	if (!ccd_probe_double(device, "exposuremin", &data->exposure_min, &supported) || !ccd_probe_double(device, "exposuremax", &data->exposure_max, &data->has_exposure_limits)) {
		return false;
	}
	data->has_exposure_limits = data->has_exposure_limits && supported && data->exposure_max > data->exposure_min && data->exposure_min >= 0;
	data->exposure_resolution = 0;
	if (data->has_exposure_limits && !ccd_probe_double(device, "exposureresolution", &data->exposure_resolution, NULL)) {
		return false;
	}
	// readout modes
	data->readout_mode_count = data->readout_mode = 0;
	data->fast_readout = false;
	alpaca_result result = system_alpaca_check(device, alpaca_get_string_array(channel, "readoutmodes", NULL, 0, ALPACA_WAIT_STANDARD, data->readout_modes[0], INDIGO_NAME_SIZE, CCD_MAX_MODES, &count));
	if (!ccd_probed(device, "readoutmodes", result, &supported)) {
		return false;
	}
	if (supported && count >= 2) {
		if (!ccd_probe_int(device, "readoutmode", &data->readout_mode, &supported)) {
			return false;
		}
		data->readout_mode_count = supported && data->readout_mode >= 0 && data->readout_mode < count ? count : 0;
	}
	if (system_alpaca_can(device, "canfastreadout") && !ccd_probe_flag(device, "fastreadout", &data->fast_readout, NULL)) {
		return false;
	}
	// gain and offset
	if (!ccd_probe_level(device, "gain", "gainmin", "gainmax", "gains", &data->gain) || !ccd_probe_level(device, "offset", "offsetmin", "offsetmax", "offsets", &data->offset)) {
		return false;
	}
	// cooling
	data->cooler_on = false;
	data->temperature = data->set_point = data->cooler_power = 0;
	if (!ccd_probe_double(device, "ccdtemperature", &data->temperature, &data->has_temperature) || !ccd_probe_flag(device, "cooleron", &data->cooler_on, &data->has_cooler)) {
		return false;
	}
	data->set_point = data->temperature;
	if (system_alpaca_can(device, "cansetccdtemperature") && !ccd_probe_double(device, "setccdtemperature", &data->set_point, NULL)) {
		return false;
	}
	data->has_cooler_power = false;
	if (system_alpaca_can(device, "cangetcoolerpower") && !ccd_probe_double(device, "coolerpower", &data->cooler_power, &data->has_cooler_power)) {
		return false;
	}
	return true;
}

// Fill a switch property with the names of a list of the camera and select one of them.
static void ccd_fill_list(indigo_property *property, const char *prefix, const char names[][INDIGO_NAME_SIZE], int count, int selected) {
	char name[INDIGO_NAME_SIZE];
	char label[INDIGO_NAME_SIZE + 16];
	for (int i = 0; i < count; i++) {
		snprintf(name, sizeof(name), "%s_%d", prefix, i);
		snprintf(label, sizeof(label), "%s", names[i]);
		if (*label == 0) {
			snprintf(label, sizeof(label), "%s %d", prefix, i);
		}
		indigo_init_switch_item(property->items + i, name, label, i == selected);
	}
	property->count = count;
}

// Set up CCD_GAIN / CCD_OFFSET (a value) and X_ALPACA_GAIN / X_ALPACA_OFFSET (the index of a name) for the way the camera sets the level.
static void ccd_setup_level(const ccd_level *level, indigo_property *value_property, indigo_property *index_property, const char *prefix) {
	value_property->hidden = level->mode != CCD_LEVEL_VALUE;
	index_property->hidden = level->mode != CCD_LEVEL_INDEX;
	value_property->perm = index_property->perm = INDIGO_RW_PERM;
	value_property->state = index_property->state = INDIGO_OK_STATE;
	if (level->mode == CCD_LEVEL_VALUE) {
		value_property->items[0].number.min = level->min;
		value_property->items[0].number.max = level->max;
		value_property->items[0].number.step = 1;
		value_property->items[0].number.value = value_property->items[0].number.target = level->value;
	} else if (level->mode == CCD_LEVEL_INDEX) {
		ccd_fill_list(index_property, prefix, level->names, level->count, level->value);
	}
}

static bool ccd_on_connect(indigo_device *device) {
	ccd_data *data = CCD_DATA;
	char name[INDIGO_NAME_SIZE];
	char label[INDIGO_NAME_SIZE];
	bool symmetric = !system_alpaca_can(device, "canasymmetricbin");
	int max_bin_x = symmetric && data->max_bin_y < data->max_bin_x ? data->max_bin_y : data->max_bin_x;
	int max_bin_y = symmetric && data->max_bin_x < data->max_bin_y ? data->max_bin_x : data->max_bin_y;
	int bits = 0;
	for (unsigned adu = (unsigned)data->max_adu; adu > 0; adu >>= 1) {
		bits++;
	}
	data->phase = CCD_PHASE_IDLE;
	data->no_device_state = false;
	data->state_failures = 0;
	data->thermal_poll_time = 0;
	system_alpaca_lock(device);
	data->download.running = false;
	data->set_point_requests = 0;
	system_alpaca_unlock(device);
	data->transfer_queue = indigo_queue_create(device);
	if (data->transfer_queue == NULL) {
		return false;
	}
	// CCD_INFO
	CCD_INFO_WIDTH_ITEM->number.value = data->width;
	CCD_INFO_HEIGHT_ITEM->number.value = data->height;
	CCD_INFO_MAX_HORIZONAL_BIN_ITEM->number.value = max_bin_x;
	CCD_INFO_MAX_VERTICAL_BIN_ITEM->number.value = max_bin_y;
	CCD_INFO_PIXEL_WIDTH_ITEM->number.value = data->pixel_size_x;
	CCD_INFO_PIXEL_HEIGHT_ITEM->number.value = data->pixel_size_y;
	CCD_INFO_PIXEL_SIZE_ITEM->number.value = (data->pixel_size_x + data->pixel_size_y) / 2;
	CCD_INFO_BITS_PER_PIXEL_ITEM->number.value = bits;
	// CCD_BIN and CCD_FRAME start with what the camera is set to
	CCD_BIN_PROPERTY->perm = max_bin_x > 1 || max_bin_y > 1 ? INDIGO_RW_PERM : INDIGO_RO_PERM;
	CCD_BIN_HORIZONTAL_ITEM->number.min = CCD_BIN_VERTICAL_ITEM->number.min = 1;
	CCD_BIN_HORIZONTAL_ITEM->number.max = max_bin_x;
	CCD_BIN_VERTICAL_ITEM->number.max = max_bin_y;
	CCD_BIN_HORIZONTAL_ITEM->number.value = CCD_BIN_HORIZONTAL_ITEM->number.target = data->bin_x >= 1 && data->bin_x <= max_bin_x ? data->bin_x : 1;
	CCD_BIN_VERTICAL_ITEM->number.value = CCD_BIN_VERTICAL_ITEM->number.target = data->bin_y >= 1 && data->bin_y <= max_bin_y ? data->bin_y : 1;
	CCD_FRAME_LEFT_ITEM->number.max = CCD_FRAME_WIDTH_ITEM->number.max = data->width;
	CCD_FRAME_TOP_ITEM->number.max = CCD_FRAME_HEIGHT_ITEM->number.max = data->height;
	CCD_FRAME_LEFT_ITEM->number.value = (double)data->start_x * data->bin_x;
	CCD_FRAME_TOP_ITEM->number.value = (double)data->start_y * data->bin_y;
	CCD_FRAME_WIDTH_ITEM->number.value = data->num_x > 0 ? (double)data->num_x * data->bin_x : data->width;
	CCD_FRAME_HEIGHT_ITEM->number.value = data->num_y > 0 ? (double)data->num_y * data->bin_y : data->height;
	ccd_remember_frame(device);
	data->bits_per_pixel = (data->max_adu > 255 ? 16 : 8) * (data->sensor_type == CCD_SENSOR_COLOR ? 3 : 1);
	ccd_normalize_frame(device);
	CCD_FRAME_BITS_PER_PIXEL_ITEM->number.min = 8;
	CCD_FRAME_BITS_PER_PIXEL_ITEM->number.max = 48;
	CCD_FRAME_PROPERTY->state = CCD_BIN_PROPERTY->state = INDIGO_OK_STATE;
	// CCD_MODE: the readout modes of the camera, or the square binnings if it has no choice of readout modes
	CCD_MODE_PROPERTY->perm = INDIGO_RW_PERM;
	CCD_MODE_PROPERTY->state = INDIGO_OK_STATE;
	if (data->readout_mode_count >= 2) {
		ccd_fill_list(CCD_MODE_PROPERTY, "MODE", data->readout_modes, data->readout_mode_count, data->readout_mode);
	} else {
		int count = max_bin_x < max_bin_y ? max_bin_x : max_bin_y;
		for (int i = 0; i < count && i < CCD_MAX_MODES; i++) {
			snprintf(name, sizeof(name), "BIN_%dx%d", i + 1, i + 1);
			snprintf(label, sizeof(label), "RAW %dx%d", data->width / (i + 1), data->height / (i + 1));
			indigo_init_switch_item(CCD_MODE_PROPERTY->items + i, name, label, false);
		}
		CCD_MODE_PROPERTY->count = count < CCD_MAX_MODES ? count : CCD_MAX_MODES;
		ccd_sync_bin_mode(device);
	}
	CCD_READ_MODE_PROPERTY->hidden = !system_alpaca_can(device, "canfastreadout");
	CCD_READ_MODE_PROPERTY->perm = INDIGO_RW_PERM;
	CCD_READ_MODE_PROPERTY->state = INDIGO_OK_STATE;
	indigo_set_switch(CCD_READ_MODE_PROPERTY, data->fast_readout ? CCD_READ_MODE_HIGH_SPEED_ITEM : CCD_READ_MODE_LOW_NOISE_ITEM, true);
	// CCD_EXPOSURE
	if (data->has_exposure_limits) {
		CCD_EXPOSURE_ITEM->number.min = data->exposure_min;
		CCD_EXPOSURE_ITEM->number.max = data->exposure_max;
		if (data->exposure_resolution > 0) {
			CCD_EXPOSURE_ITEM->number.step = data->exposure_resolution;
		}
	}
	CCD_STREAMING_PROPERTY->hidden = true;
	// gain and offset
	ccd_setup_level(&data->gain, CCD_GAIN_PROPERTY, X_ALPACA_GAIN_PROPERTY, "GAIN");
	ccd_setup_level(&data->offset, CCD_OFFSET_PROPERTY, X_ALPACA_OFFSET_PROPERTY, "OFFSET");
	CCD_EGAIN_PROPERTY->hidden = !data->has_electrons_per_adu;
	CCD_EGAIN_ITEM->number.value = data->electrons_per_adu;
	// cooling
	CCD_COOLER_PROPERTY->hidden = !data->has_cooler;
	CCD_COOLER_PROPERTY->perm = INDIGO_RW_PERM;
	CCD_COOLER_PROPERTY->state = INDIGO_OK_STATE;
	indigo_set_switch(CCD_COOLER_PROPERTY, data->cooler_on ? CCD_COOLER_ON_ITEM : CCD_COOLER_OFF_ITEM, true);
	CCD_TEMPERATURE_PROPERTY->hidden = !data->has_temperature;
	CCD_TEMPERATURE_PROPERTY->perm = system_alpaca_can(device, "cansetccdtemperature") ? INDIGO_RW_PERM : INDIGO_RO_PERM;
	CCD_TEMPERATURE_ITEM->number.value = data->temperature;
	CCD_TEMPERATURE_ITEM->number.target = data->set_point;
	CCD_TEMPERATURE_PROPERTY->state = ccd_temperature_state(device);
	CCD_COOLER_POWER_PROPERTY->hidden = !data->has_cooler_power;
	CCD_COOLER_POWER_ITEM->number.value = data->cooler_power;
	CCD_COOLER_POWER_PROPERTY->state = INDIGO_OK_STATE;
	// X_ALPACA_SENSOR
	X_ALPACA_SENSOR_PROPERTY->hidden = !data->has_sensor_type && *data->sensor_name == 0 && !data->has_full_well_capacity;
	indigo_set_text_item_value(X_ALPACA_SENSOR_NAME_ITEM, data->sensor_name);
	if (!data->has_sensor_type || data->sensor_type < 0 || data->sensor_type >= CCD_SENSOR_TYPE_COUNT) {
		indigo_set_text_item_value(X_ALPACA_SENSOR_TYPE_ITEM, "");
	} else if (data->sensor_type == CCD_SENSOR_RGGB) {
		snprintf(label, sizeof(label), "Bayer %s", ccd_bayer_patterns[(data->bayer_offset_y & 1) * 2 + (data->bayer_offset_x & 1)]);
		indigo_set_text_item_value(X_ALPACA_SENSOR_TYPE_ITEM, label);
	} else {
		indigo_set_text_item_value(X_ALPACA_SENSOR_TYPE_ITEM, ccd_sensor_types[data->sensor_type]);
	}
	snprintf(label, sizeof(label), "%g", data->full_well_capacity);
	indigo_set_text_item_value(X_ALPACA_SENSOR_FULL_WELL_ITEM, data->has_full_well_capacity ? label : "");
	if (system_alpaca_can(device, "canpulseguide")) {
		system_alpaca_attach_secondary(device, &system_alpaca_guider_class);
	}
	indigo_define_property(device, X_ALPACA_SENSOR_PROPERTY, NULL);
	indigo_define_property(device, X_ALPACA_GAIN_PROPERTY, NULL);
	indigo_define_property(device, X_ALPACA_OFFSET_PROPERTY, NULL);
	return true;
}

static void ccd_on_disconnect(indigo_device *device) {
	ccd_data *data = CCD_DATA;
	if (data->exposure.active && data->phase == CCD_PHASE_EXPOSE) {
		ccd_cancel_on_camera(device);
	}
	// a transfer in progress uses the transfer channel, which is released after this hook: it is waited for
	system_alpaca_lock(device);
	data->download.cancelled = true;
	system_alpaca_unlock(device);
	indigo_queue_delete(&data->transfer_queue);
	system_alpaca_operation_end(device, &data->exposure);
	data->phase = CCD_PHASE_IDLE;
	data->download.channel = NULL;
	CCD_IMAGE_ITEM->blob.value = NULL;
	CCD_IMAGE_ITEM->blob.size = 0;
	indigo_safe_free(data->image);
	indigo_safe_free(data->json_pixels);
	data->image = NULL;
	data->image_size = 0;
	data->json_pixels = NULL;
	data->json_capacity = 0;
	// what a cancelled handler left BUSY; the properties are still defined, so a request may be accepted while they are reset
	system_alpaca_lock(device);
	data->download.running = false;
	CCD_ABORT_EXPOSURE_ITEM->sw.value = false;
	CCD_ABORT_EXPOSURE_PROPERTY->state = CCD_FRAME_PROPERTY->state = CCD_BIN_PROPERTY->state = CCD_MODE_PROPERTY->state = CCD_READ_MODE_PROPERTY->state = INDIGO_OK_STATE;
	CCD_GAIN_PROPERTY->state = CCD_OFFSET_PROPERTY->state = CCD_COOLER_PROPERTY->state = CCD_IMAGE_FILE_PROPERTY->state = INDIGO_OK_STATE;
	system_alpaca_unlock(device);
	indigo_delete_property(device, X_ALPACA_SENSOR_PROPERTY, NULL);
	indigo_delete_property(device, X_ALPACA_GAIN_PROPERTY, NULL);
	indigo_delete_property(device, X_ALPACA_OFFSET_PROPERTY, NULL);
}

// Cooling is read once per idle poll interval, also while an exposure makes the device tick faster: it changes slowly.
// Each of the three properties is read for itself, a camera may have any of them without the others.
static void ccd_on_poll(indigo_device *device) {
	ccd_data *data = CCD_DATA;
	double now = indigo_monotonic_time();
	double temperature = data->temperature, power = data->cooler_power;
	bool cooler_on = data->cooler_on;
	if (now < data->thermal_poll_time || (CCD_TEMPERATURE_PROPERTY->hidden && CCD_COOLER_PROPERTY->hidden && CCD_COOLER_POWER_PROPERTY->hidden)) {
		return;
	}
	data->thermal_poll_time = now + 0.9 * system_alpaca_poll_interval(false);
	// A change of the cooler that is on its way to the camera is not overwritten by what the camera says before it got it: the camera
	// is asked first and the property is touched afterwards, under the lock of the device and only if no request for it waits.
	system_alpaca_lock(device);
	bool cooler_idle = CCD_COOLER_PROPERTY->state != INDIGO_BUSY_STATE;
	system_alpaca_unlock(device);
	if (!CCD_COOLER_PROPERTY->hidden && cooler_idle && system_alpaca_get_bool(device, "cooleron", &cooler_on) == ALPACA_OK && cooler_on != data->cooler_on) {
		system_alpaca_lock(device);
		bool changed = CCD_COOLER_PROPERTY->state != INDIGO_BUSY_STATE;
		if (changed) {
			// the cooler was switched by somebody else
			data->cooler_on = cooler_on;
			indigo_set_switch(CCD_COOLER_PROPERTY, cooler_on ? CCD_COOLER_ON_ITEM : CCD_COOLER_OFF_ITEM, true);
		}
		system_alpaca_unlock(device);
		if (changed) {
			indigo_update_property(device, CCD_COOLER_PROPERTY, NULL);
		}
	}
	if (!CCD_TEMPERATURE_PROPERTY->hidden) {
		alpaca_result result = system_alpaca_state_double(device, "CCDTemperature", &temperature);
		if (result == ALPACA_OK) {
			data->temperature = temperature;
		}
		indigo_property_state state = result == ALPACA_OK ? ccd_temperature_state(device) : INDIGO_ALERT_STATE;
		// a new set point that is on its way to the camera keeps the property BUSY until ccd_temperature_handler has sent it
		system_alpaca_lock(device);
		bool changed = !ccd_set_point_pending(device) && (CCD_TEMPERATURE_ITEM->number.value != data->temperature || CCD_TEMPERATURE_PROPERTY->state != state);
		if (changed) {
			CCD_TEMPERATURE_ITEM->number.value = data->temperature;
			CCD_TEMPERATURE_PROPERTY->state = state;
		}
		system_alpaca_unlock(device);
		if (changed) {
			indigo_update_property(device, CCD_TEMPERATURE_PROPERTY, NULL);
		}
	}
	if (!CCD_COOLER_POWER_PROPERTY->hidden) {
		alpaca_result result = system_alpaca_state_double(device, "CoolerPower", &power);
		indigo_property_state state = result == ALPACA_OK ? INDIGO_OK_STATE : INDIGO_ALERT_STATE;
		if (result == ALPACA_OK) {
			data->cooler_power = power;
		}
		if (CCD_COOLER_POWER_ITEM->number.value != data->cooler_power || CCD_COOLER_POWER_PROPERTY->state != state) {
			CCD_COOLER_POWER_ITEM->number.value = data->cooler_power;
			system_alpaca_update(device, CCD_COOLER_POWER_PROPERTY, state, NULL);
		}
	}
}

// Refusal of a change of the settings of an exposure while one is in progress. Called by system_alpaca_accept() with the lock of the device held.
static const char *ccd_exposure_refusal(indigo_device *device) {
	return CCD_EXPOSURE_PROPERTY->state == INDIGO_BUSY_STATE ? "Exposure in progress" : NULL;
}

#pragma mark - Device API (ccd)

static indigo_result ccd_enumerate_properties(indigo_device *device, indigo_client *client, indigo_property *property);

static indigo_result ccd_attach(indigo_device *device) {
	assert(device != NULL);
	if (indigo_ccd_attach(device, DRIVER_NAME, DRIVER_VERSION) == INDIGO_OK) {
		X_ALPACA_SENSOR_PROPERTY = indigo_init_text_property(NULL, device->name, X_ALPACA_SENSOR_PROPERTY_NAME, CCD_MAIN_GROUP, "Sensor", INDIGO_OK_STATE, INDIGO_RO_PERM, 3);
		if (X_ALPACA_SENSOR_PROPERTY == NULL) {
			return INDIGO_FAILED;
		}
		indigo_init_text_item(X_ALPACA_SENSOR_NAME_ITEM, X_ALPACA_SENSOR_NAME_ITEM_NAME, "Name", "");
		indigo_init_text_item(X_ALPACA_SENSOR_TYPE_ITEM, X_ALPACA_SENSOR_TYPE_ITEM_NAME, "Type", "");
		indigo_init_text_item(X_ALPACA_SENSOR_FULL_WELL_ITEM, X_ALPACA_SENSOR_FULL_WELL_ITEM_NAME, "Full well capacity (e-)", "");
		X_ALPACA_GAIN_PROPERTY = indigo_init_switch_property(NULL, device->name, X_ALPACA_GAIN_PROPERTY_NAME, CCD_MAIN_GROUP, "Gain", INDIGO_OK_STATE, INDIGO_RW_PERM, INDIGO_ONE_OF_MANY_RULE, CCD_MAX_LEVELS);
		if (X_ALPACA_GAIN_PROPERTY == NULL) {
			return INDIGO_FAILED;
		}
		X_ALPACA_GAIN_PROPERTY->count = 0;
		X_ALPACA_GAIN_PROPERTY->hidden = true;
		X_ALPACA_OFFSET_PROPERTY = indigo_init_switch_property(NULL, device->name, X_ALPACA_OFFSET_PROPERTY_NAME, CCD_MAIN_GROUP, "Offset", INDIGO_OK_STATE, INDIGO_RW_PERM, INDIGO_ONE_OF_MANY_RULE, CCD_MAX_LEVELS);
		if (X_ALPACA_OFFSET_PROPERTY == NULL) {
			return INDIGO_FAILED;
		}
		X_ALPACA_OFFSET_PROPERTY->count = 0;
		X_ALPACA_OFFSET_PROPERTY->hidden = true;
		return system_alpaca_attach(device) == INDIGO_OK ? ccd_enumerate_properties(device, NULL, NULL) : INDIGO_FAILED;
	}
	return INDIGO_FAILED;
}

static indigo_result ccd_enumerate_properties(indigo_device *device, indigo_client *client, indigo_property *property) {
	if (system_alpaca_is_active(device)) {
		INDIGO_DEFINE_MATCHING_PROPERTY(X_ALPACA_SENSOR_PROPERTY);
		INDIGO_DEFINE_MATCHING_PROPERTY(X_ALPACA_GAIN_PROPERTY);
		INDIGO_DEFINE_MATCHING_PROPERTY(X_ALPACA_OFFSET_PROPERTY);
	}
	return indigo_ccd_enumerate_properties(device, client, property);
}

static indigo_result ccd_change_property(indigo_device *device, indigo_client *client, indigo_property *property) {
	if (system_alpaca_change_property(device, property)) {
		return INDIGO_OK;
	}
	if (indigo_property_match_changeable(CCD_EXPOSURE_PROPERTY, property)) {
		system_alpaca_accept(device, CCD_EXPOSURE_PROPERTY, property, ALPACA_ACCEPT_VALUES, NULL, ccd_exposure_handler);
		return INDIGO_OK;
	} else if (indigo_property_match_changeable(CCD_ABORT_EXPOSURE_PROPERTY, property)) {
		system_alpaca_accept(device, CCD_ABORT_EXPOSURE_PROPERTY, property, ALPACA_ACCEPT_VALUES | ALPACA_ACCEPT_URGENT, NULL, ccd_abort_exposure_handler);
		return INDIGO_OK;
	} else if (indigo_property_match_changeable(CCD_FRAME_PROPERTY, property)) {
		system_alpaca_accept(device, CCD_FRAME_PROPERTY, property, ALPACA_ACCEPT_VALUES, ccd_exposure_refusal, ccd_frame_handler);
		return INDIGO_OK;
	} else if (indigo_property_match_changeable(CCD_BIN_PROPERTY, property)) {
		system_alpaca_accept(device, CCD_BIN_PROPERTY, property, ALPACA_ACCEPT_TARGETS, ccd_exposure_refusal, ccd_bin_handler);
		return INDIGO_OK;
	} else if (indigo_property_match_changeable(CCD_MODE_PROPERTY, property)) {
		system_alpaca_accept(device, CCD_MODE_PROPERTY, property, ALPACA_ACCEPT_VALUES, ccd_exposure_refusal, ccd_mode_handler);
		return INDIGO_OK;
	} else if (indigo_property_match_changeable(CCD_READ_MODE_PROPERTY, property)) {
		system_alpaca_accept(device, CCD_READ_MODE_PROPERTY, property, ALPACA_ACCEPT_VALUES, ccd_exposure_refusal, ccd_read_mode_handler);
		return INDIGO_OK;
	} else if (indigo_property_match_changeable(CCD_GAIN_PROPERTY, property)) {
		system_alpaca_accept(device, CCD_GAIN_PROPERTY, property, ALPACA_ACCEPT_TARGETS, ccd_exposure_refusal, ccd_gain_handler);
		return INDIGO_OK;
	} else if (indigo_property_match_changeable(CCD_OFFSET_PROPERTY, property)) {
		system_alpaca_accept(device, CCD_OFFSET_PROPERTY, property, ALPACA_ACCEPT_TARGETS, ccd_exposure_refusal, ccd_offset_handler);
		return INDIGO_OK;
	} else if (indigo_property_match_changeable(X_ALPACA_GAIN_PROPERTY, property)) {
		system_alpaca_accept(device, X_ALPACA_GAIN_PROPERTY, property, ALPACA_ACCEPT_VALUES, ccd_exposure_refusal, ccd_x_alpaca_gain_handler);
		return INDIGO_OK;
	} else if (indigo_property_match_changeable(X_ALPACA_OFFSET_PROPERTY, property)) {
		system_alpaca_accept(device, X_ALPACA_OFFSET_PROPERTY, property, ALPACA_ACCEPT_VALUES, ccd_exposure_refusal, ccd_x_alpaca_offset_handler);
		return INDIGO_OK;
	} else if (indigo_property_match_changeable(CCD_COOLER_PROPERTY, property)) {
		system_alpaca_accept(device, CCD_COOLER_PROPERTY, property, ALPACA_ACCEPT_VALUES, NULL, ccd_cooler_handler);
		return INDIGO_OK;
	} else if (indigo_property_match_changeable(CCD_TEMPERATURE_PROPERTY, property)) {
		// CCD_TEMPERATURE is BUSY while the cooler works towards the set point; a new set point is accepted all the same.
		// The steps of system_alpaca_accept(), and the count of the set points that wait for their handler.
		system_alpaca_lock(device);
		CCD_DATA->set_point_requests++;
		indigo_property_copy_targets(CCD_TEMPERATURE_PROPERTY, property, false);
		CCD_TEMPERATURE_PROPERTY->state = INDIGO_BUSY_STATE;
		system_alpaca_unlock(device);
		indigo_update_property(device, CCD_TEMPERATURE_PROPERTY, NULL);
		indigo_execute_handler(device, ccd_temperature_handler);
		return INDIGO_OK;
	} else if (indigo_property_match(CONFIG_PROPERTY, property)) {
		if (indigo_switch_match(CONFIG_SAVE_ITEM, property)) {
			indigo_save_property(device, NULL, X_ALPACA_GAIN_PROPERTY);
			indigo_save_property(device, NULL, X_ALPACA_OFFSET_PROPERTY);
		}
	}
	return indigo_ccd_change_property(device, client, property);
}

static indigo_result ccd_detach(indigo_device *device) {
	assert(device != NULL);
	system_alpaca_detach(device);
	indigo_release_property(X_ALPACA_SENSOR_PROPERTY);
	indigo_release_property(X_ALPACA_GAIN_PROPERTY);
	indigo_release_property(X_ALPACA_OFFSET_PROPERTY);
	INDIGO_DEVICE_DETACH_LOG(DRIVER_NAME, device->name);
	return indigo_ccd_detach(device);
}

