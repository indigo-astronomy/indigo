// Set Gain or Offset and show what the camera accepted last, in the number property (a value) or in the switch property (an index).
static void ccd_set_level(indigo_device *device, const char *member, const char *name, ccd_level *level, indigo_property *property, const char *action) {
	int value = level->value;
	if (property->type == INDIGO_NUMBER_VECTOR) {
		value = (int)property->items[0].number.target;
	} else {
		for (int i = 0; i < property->count; i++) {
			if (property->items[i].sw.value) {
				value = i;
			}
		}
	}
	alpaca_param params[] = { ALPACA_INT_PARAM(name, value) };
	alpaca_result result = system_alpaca_put(device, member, params, 1, ALPACA_REPLAYABLE);
	if (result == ALPACA_OK) {
		level->value = value;
	}
	if (property->type == INDIGO_NUMBER_VECTOR) {
		property->items[0].number.value = property->items[0].number.target = level->value;
	} else if (level->value >= 0 && level->value < property->count) {
		indigo_set_switch(property, property->items + level->value, true);
	}
	ccd_finish(device, property, result, action);
}

