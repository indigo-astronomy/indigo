#pragma mark - text helpers

static char alpaca_http_lower(char c) {
	return c >= 'A' && c <= 'Z' ? (char)(c + ('a' - 'A')) : c;
}

// ASCII only and independent of the locale, unlike strcasecmp()
static bool alpaca_http_same(const char *text, size_t length, const char *token) {
	for (size_t i = 0; i < length; i++) {
		if (token[i] == 0 || alpaca_http_lower(text[i]) != alpaca_http_lower(token[i])) {
			return false;
		}
	}
	return token[length] == 0;
}

// true if the comma separated list contains the token; parameters after ';' are ignored
static bool alpaca_http_has_token(const char *list, const char *token) {
	while (*list) {
		while (*list == ' ' || *list == '\t' || *list == ',') {
			list++;
		}
		size_t length = strcspn(list, ",; \t");
		if (length > 0 && alpaca_http_same(list, length, token)) {
			return true;
		}
		list += strcspn(list, ",");
	}
	return false;
}

// True if a list of codings has a coding other than "chunked" (case insensitive, parameters after ';' ignored); empty elements are skipped.
static bool alpaca_http_has_other_coding(const char *list) {
	while (*list) {
		while (*list == ' ' || *list == '\t' || *list == ',') {
			list++;
		}
		size_t length = strcspn(list, ",; \t");
		if (length > 0 && !alpaca_http_same(list, length, "chunked")) {
			return true;
		}
		list += strcspn(list, ",");
	}
	return false;
}

static int alpaca_http_hex_digit(char c) {
	if (c >= '0' && c <= '9') {
		return c - '0';
	}
	if (c >= 'a' && c <= 'f') {
		return c - 'a' + 10;
	}
	if (c >= 'A' && c <= 'F') {
		return c - 'A' + 10;
	}
	return -1;
}

static bool alpaca_http_is_unreserved(unsigned char c) {
	return (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c == '-' || c == '.' || c == '_' || c == '~';
}

// printable ASCII without space: the only bytes allowed in a request target
static bool alpaca_http_is_valid_target(const char *text) {
	for (const unsigned char *c = (const unsigned char *)text; *c; c++) {
		if (*c <= ' ' || *c >= 0x7F) {
			return false;
		}
	}
	return true;
}

static bool alpaca_http_is_valid_headers(const char *headers) {
	if (headers == NULL || *headers == 0) {
		return true;
	}
	size_t length = strlen(headers);
	return length > 2 && strncmp(headers, "\r\n", 2) != 0 && strcmp(headers + length - 2, "\r\n") == 0 && strstr(headers, "\r\n\r\n") == NULL;
}

#pragma mark - buffer

void alpaca_http_buffer_init(alpaca_http_buffer *buffer, size_t max_size) {
	memset(buffer, 0, sizeof(alpaca_http_buffer));
	buffer->max_size = max_size < SIZE_MAX ? max_size : SIZE_MAX - 1;
}

void alpaca_http_buffer_free(alpaca_http_buffer *buffer) {
	indigo_safe_free(buffer->data);
	buffer->data = NULL;
	buffer->size = 0;
	buffer->capacity = 0;
}

void alpaca_http_buffer_clear(alpaca_http_buffer *buffer) {
	buffer->size = 0;
	if (buffer->data != NULL) {
		buffer->data[0] = 0;
	}
}

bool alpaca_http_buffer_reserve(alpaca_http_buffer *buffer, size_t size) {
	if (size > buffer->max_size) {
		return false;
	}
	if (size + 1 > buffer->capacity) {
		size_t capacity = buffer->capacity > SIZE_MAX / 2 ? SIZE_MAX : buffer->capacity * 2;
		if (capacity < ALPACA_HTTP_MIN_CAPACITY) {
			capacity = ALPACA_HTTP_MIN_CAPACITY;
		}
		if (capacity < size + 1) {
			capacity = size + 1;
		}
		if (capacity > buffer->max_size + 1) {
			capacity = buffer->max_size + 1;
		}
		buffer->data = indigo_safe_realloc(buffer->data, capacity);
		buffer->capacity = capacity;
		buffer->data[buffer->size] = 0;
	}
	return true;
}

bool alpaca_http_buffer_append(alpaca_http_buffer *buffer, const void *data, size_t size) {
	if (size > buffer->max_size - buffer->size || !alpaca_http_buffer_reserve(buffer, buffer->size + size)) {
		return false;
	}
	if (size > 0) {
		memcpy(buffer->data + buffer->size, data, size);
	}
	buffer->size += size;
	buffer->data[buffer->size] = 0;
	return true;
}

bool alpaca_http_buffer_append_encoded(alpaca_http_buffer *buffer, const char *text) {
	static const char hex[] = "0123456789ABCDEF";
	if (text == NULL) {
		return false;
	}
	size_t size = 0;
	for (const unsigned char *c = (const unsigned char *)text; *c; c++) {
		size += alpaca_http_is_unreserved(*c) ? 1 : 3;
	}
	if (size > buffer->max_size - buffer->size || !alpaca_http_buffer_reserve(buffer, buffer->size + size)) {
		return false;
	}
	char *out = buffer->data + buffer->size;
	for (const unsigned char *c = (const unsigned char *)text; *c; c++) {
		if (alpaca_http_is_unreserved(*c)) {
			*out++ = (char)*c;
		} else {
			*out++ = '%';
			*out++ = hex[*c >> 4];
			*out++ = hex[*c & 0x0F];
		}
	}
	*out = 0;
	buffer->size += size;
	return true;
}

static bool alpaca_http_buffer_append_text(alpaca_http_buffer *buffer, const char *text) {
	return alpaca_http_buffer_append(buffer, text, strlen(text));
}

#pragma mark - form and query builder

bool alpaca_http_format_double(char *text, size_t size, double value) {
	if (text == NULL || size < ALPACA_HTTP_DOUBLE_SIZE || !isfinite(value)) {
		return false;
	}
	for (int precision = 15; precision <= 17; precision++) {
		snprintf(text, size, "%.*g", precision, value);
		if (strtod(text, NULL) == value) {
			break;
		}
	}
	// printf() writes the decimal separator of LC_NUMERIC, which may be ',' or a multi-byte sequence; everything that is not part of a C number is that separator
	char *out = text;
	bool in_separator = false;
	for (const char *in = text; *in; in++) {
		if ((*in >= '0' && *in <= '9') || *in == '-' || *in == '+' || *in == 'e') {
			*out++ = *in;
			in_separator = false;
		} else if (!in_separator) {
			*out++ = '.';
			in_separator = true;
		}
	}
	*out = 0;
	return true;
}

static bool alpaca_http_form_add(alpaca_http_buffer *form, const char *name, const char *value) {
	size_t mark = form->size;
	if (name != NULL && *name && value != NULL && (mark == 0 || alpaca_http_buffer_append(form, "&", 1)) && alpaca_http_buffer_append_encoded(form, name) && alpaca_http_buffer_append(form, "=", 1) && alpaca_http_buffer_append_encoded(form, value)) {
		return true;
	}
	form->size = mark;
	if (form->data != NULL) {
		form->data[mark] = 0;
	}
	return false;
}

bool alpaca_http_form_add_string(alpaca_http_buffer *form, const char *name, const char *value) {
	return alpaca_http_form_add(form, name, value);
}

bool alpaca_http_form_add_int(alpaca_http_buffer *form, const char *name, long long value) {
	char text[32];
	snprintf(text, sizeof(text), "%lld", value);
	return alpaca_http_form_add(form, name, text);
}

bool alpaca_http_form_add_bool(alpaca_http_buffer *form, const char *name, bool value) {
	return alpaca_http_form_add(form, name, value ? "True" : "False");
}

bool alpaca_http_form_add_double(alpaca_http_buffer *form, const char *name, double value) {
	char text[ALPACA_HTTP_DOUBLE_SIZE];
	return alpaca_http_format_double(text, sizeof(text), value) && alpaca_http_form_add(form, name, text);
}

