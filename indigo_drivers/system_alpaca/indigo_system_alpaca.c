// Value of a number item of a setting of the bridge. A bus thread writes the settings under bridge_mutex when a client changes them.
static double bridge_setting(indigo_item *item) {
	pthread_mutex_lock(&bridge_mutex);
	double value = item->number.value;
	pthread_mutex_unlock(&bridge_mutex);
	return value;
}

// Driver queue: end a request for a property of the bridge. The state is set under bridge_mutex, because a bus thread accepts the
// next request and enumerates the properties under it; the property is published without it. reset is a switch item to clear, or NULL.
static void bridge_finish(indigo_device *device, indigo_property *property, indigo_item *reset) {
	pthread_mutex_lock(&bridge_mutex);
	if (reset != NULL) {
		reset->sw.value = false;
	}
	property->state = INDIGO_OK_STATE;
	pthread_mutex_unlock(&bridge_mutex);
	indigo_update_property(device, property, NULL);
}

// CONFIG of the bridge is written by the framework (the bus thread that starts a restore, the background handler of the restore that
// ends it) without any lock this driver could take as well, so the read can not be ordered against those writes from here. A stale
// value only defers the work by one CONFIG_WAIT_INTERVAL or lets one list update through before the restore has set BUSY.
static bool bridge_config_busy(void) {
	indigo_device *device = bridge;
	return CONFIG_PROPERTY->state == INDIGO_BUSY_STATE;
}

static server_record *server_find(const char *host, int port) {
	for (int i = 0; i < MAX_SERVERS; i++) {
		if (servers[i].used && servers[i].transport->port == port && same_text(servers[i].transport->host, host)) {
			return servers + i;
		}
	}
	return NULL;
}

static server_record *server_add(const char *host, int port) {
	int establish = 0, standard = 0, longest = 0;
	for (int i = 0; i < MAX_SERVERS; i++) {
		server_record *server = servers + i;
		if (!server->used) {
			memset(server, 0, sizeof(server_record));
			server->transport = alpaca_server_create(host, port);
			if (server->transport == NULL) {
				return NULL;
			}
			get_timeouts(&establish, &standard, &longest);
			alpaca_server_set_timeouts(server->transport, establish, standard, longest);
			server->channel = alpaca_channel_create(server->transport, NULL, 0, ALPACA_CONTROL_MAX_BODY);
			server->used = true;
			INDIGO_DRIVER_LOG(DRIVER_NAME, "Alpaca server %s:%d added", host, port);
			return server;
		}
	}
	INDIGO_DRIVER_ERROR(DRIVER_NAME, "Alpaca server %s:%d ignored, the limit of %d servers is reached", host, port, MAX_SERVERS);
	return NULL;
}

// Remove a server. No proxy device may use it any more: the devices of the server have to be detached before.
static void server_remove(server_record *server) {
	INDIGO_DRIVER_LOG(DRIVER_NAME, "Alpaca server %s:%d removed", server->transport->host, server->transport->port);
	for (int i = 0; i < MAX_RECORDS; i++) {
		if (records[i].used && records[i].server == server) {
			records[i].server = NULL;
			records[i].present = false;
		}
	}
	alpaca_channel_free(server->channel);
	alpaca_server_free(server->transport);
	memset(server, 0, sizeof(server_record));
}

static void server_set_absent(server_record *server) {
	for (int i = 0; i < MAX_RECORDS; i++) {
		if (records[i].used && records[i].server == server && records[i].present) {
			records[i].present = false;
			lost_record_count++;
		}
	}
	server->device_count = 0;
	server->duplicate_count = 0;
}

static device_record *record_find(const char *key) {
	for (int i = 0; i < MAX_RECORDS; i++) {
		if (records[i].used && !strcmp(records[i].key, key)) {
			return records + i;
		}
	}
	return NULL;
}

static device_record *record_add(const char *key) {
	for (int i = 0; i < MAX_RECORDS; i++) {
		device_record *record = records + i;
		if (!record->used) {
			memset(record, 0, sizeof(device_record));
			strcpy(record->key, key);
			record->used = true;
			return record;
		}
	}
	return NULL;
}

// Index of a key in switched_off, -1 if the device is not switched off. Called with bridge_mutex held.
static int switched_off_find(const char *key) {
	for (int i = 0; i < switched_off_count; i++) {
		if (!strcmp(switched_off[i], key)) {
			return i;
		}
	}
	return -1;
}

// Switch a device off or on by its key. Returns false if the set is full and the device could not be switched off. Called with bridge_mutex held.
static bool switched_off_set(const char *key, bool off) {
	int index = switched_off_find(key);
	if (off && index < 0) {
		if (switched_off_count == MAX_RECORDS) {
			return false;
		}
		strcpy(switched_off[switched_off_count++], key);
	} else if (!off && index >= 0) {
		// the last key takes the place of the one taken out; the last one itself only shortens the set
		if (index < --switched_off_count) {
			strcpy(switched_off[index], switched_off[switched_off_count]);
		}
	}
	return true;
}

// Driver queue: bring the records in line with switched_off. A device that is switched off and is not known yet gets a record of its own,
// listed as OFFLINE until a server lists it, so that its switch stays in X_ALPACA_DEVICES and is saved with the configuration.
static void records_apply_selection(void) {
	int lost = 0;
	pthread_mutex_lock(&bridge_mutex);
	for (int i = 0; i < MAX_RECORDS; i++) {
		if (records[i].used) {
			records[i].selected = switched_off_find(records[i].key) < 0;
		}
	}
	for (int i = 0; i < switched_off_count; i++) {
		if (record_find(switched_off[i]) == NULL) {
			device_record *record = record_add(switched_off[i]);
			if (record != NULL) {
				copy_text(record->unique_id, sizeof(record->unique_id), switched_off[i]);
			} else {
				lost++;
			}
		}
	}
	pthread_mutex_unlock(&bridge_mutex);
	if (lost > 0) {
		INDIGO_DRIVER_ERROR(DRIVER_NAME, "%d device(s) switched off are not listed, the limit of %d devices is reached", lost, MAX_RECORDS);
	}
}

static void proxy_free(indigo_device *device) {
	alpaca_private_data *private_data = PRIVATE_DATA;
	pthread_mutex_destroy(&private_data->mutex);
	alpaca_channel_free(private_data->channel);
	alpaca_channel_free(private_data->transfer);
	indigo_safe_free(private_data->class_data);
	indigo_safe_free(private_data->secondary_data);
	indigo_safe_free(private_data);
	indigo_safe_free(device);
}

// Remove every "alpaca" from a name, in any letter case and also inside a word ("MyAlpacaDome" becomes "MyDome"), and tidy what is
// left: a run of spaces becomes one space, and spaces and separators ("-", "_", ":") left dangling at either end are removed.
static void strip_alpaca(char *text) {
	static const char *word = "alpaca";
	size_t length = strlen(word);
	char *target = text;
	for (const char *source = text; *source; ) {
		size_t matched = 0;
		while (matched < length && source[matched] && lower_case(source[matched]) == word[matched]) {
			matched++;
		}
		if (matched == length) {
			source += length;
		} else if (*source == ' ' && (target == text || target[-1] == ' ')) {
			source++;
		} else {
			*target++ = *source++;
		}
	}
	*target = 0;
	while (target > text && strchr(" -_:", target[-1]) != NULL) {
		*--target = 0;
	}
	size_t skip = strspn(text, " -_:");
	memmove(text, text + skip, strlen(text + skip) + 1);
}

// Name of an Alpaca device without a number (decision D17): "ALPACA <DeviceName>", without any "alpaca" of the DeviceName (strip_alpaca())
// and with the characters a device name can not have replaced (copy_name_part(), "@" included, D14). If nothing is left of the
// DeviceName, the DeviceType is used. The prefix in upper case keeps every proxy apart from the bridge device "Alpaca".
// The DeviceName part is cut between UTF-8 characters to DEVICE_NAME_PART_SIZE, so that "ALPACA ", the number of a duplicate (" #" and
// up to 3 digits) and the suffix of a secondary device (" (guider)") still fit into INDIGO_NAME_SIZE with the terminating zero: 7 + 99 + 5 + 9 + 1 < 128.
static void proxy_base_name(const device_record *record, char *name) {
	char part[INDIGO_NAME_SIZE];
	char cut[DEVICE_NAME_PART_SIZE];
	copy_name_part(part, sizeof(part), record->name);
	strip_alpaca(part);
	if (*part == 0) {
		copy_name_part(part, sizeof(part), record->type);
		strip_alpaca(part);
	}
	copy_text(cut, sizeof(cut), *part ? part : "Device");
	strip_alpaca(cut);
	snprintf(name, INDIGO_NAME_SIZE, "ALPACA %s", cut);
}

// No device of the bus has the name. indigo_make_name_unique() is asked on a copy: it changes the copy only if the name is taken.
static bool proxy_name_free(const char *name) {
	char probe[INDIGO_NAME_SIZE + 16];
	snprintf(probe, sizeof(probe), "%s", name);
	indigo_make_name_unique(probe, NULL);
	return !strcmp(probe, name);
}

// Name of a proxy device (decision D17). Devices of the same name get a running number: "ALPACA Focuser Simulator", "ALPACA Focuser
// Simulator #2", ... The configuration of a device is saved under its name, so the numbers are given in a fixed order, not in the order
// of attaching: a device gets the place of its key among the keys of all devices of the same name the servers list now, switched on or
// off. A name that is taken on the bus (a device of that name that kept its name while it is attached, or any other device) is passed
// over for the next number. A proxy keeps its name while it is attached.
static void proxy_make_name(const device_record *record, char *name) {
	char base[INDIGO_NAME_SIZE];
	char other[INDIGO_NAME_SIZE];
	int number = 1;
	proxy_base_name(record, base);
	for (int i = 0; i < MAX_RECORDS; i++) {
		if (records[i].used && records + i != record && records[i].server != NULL && records[i].present) {
			proxy_base_name(records + i, other);
			if (!strcmp(base, other) && strcmp(records[i].key, record->key) < 0) {
				number++;
			}
		}
	}
	for (int attempt = 0; attempt < 1000; attempt++, number++) {
		if (number == 1) {
			strcpy(name, base);
		} else {
			snprintf(name, INDIGO_NAME_SIZE, "%s #%d", base, number);
		}
		if (proxy_name_free(name)) {
			return;
		}
	}
	indigo_make_name_unique(name, NULL);
}

// Create and attach the proxy device of an Alpaca device that is switched on. The device has to answer InterfaceVersion first: a device that is
// listed but does not work is not attached. On failure everything is released again and record->message says why.
static bool proxy_attach(device_record *record, const alpaca_class *device_class) {
	static const indigo_device proxy_template = INDIGO_DEVICE_INITIALIZER("", NULL, NULL, NULL, NULL, NULL);
	int slot = 0;
	int version = 0;
	while (slot < MAX_DEVICES && devices[slot] != NULL) {
		slot++;
	}
	if (slot == MAX_DEVICES) {
		snprintf(record->message, sizeof(record->message), "the limit of %d proxy devices is reached", MAX_DEVICES);
		return false;
	}
	alpaca_private_data *private_data = indigo_safe_malloc(sizeof(alpaca_private_data));
	indigo_device *device = indigo_safe_malloc_copy(sizeof(indigo_device), (void *)&proxy_template);
	pthread_mutexattr_t attributes;
	pthread_mutexattr_init(&attributes);
	pthread_mutexattr_settype(&attributes, PTHREAD_MUTEX_RECURSIVE);
	pthread_mutex_init(&private_data->mutex, &attributes);
	pthread_mutexattr_destroy(&attributes);
	private_data->server = record->server->transport;
	private_data->device_class = device_class;
	private_data->device_number = record->number;
	private_data->device = device;
	copy_text(private_data->device_type, sizeof(private_data->device_type), record->type);
	copy_text(private_data->device_name, sizeof(private_data->device_name), *record->name ? record->name : record->type);
	copy_text(private_data->unique_id, sizeof(private_data->unique_id), record->unique_id);
	private_data->channel = alpaca_channel_create(private_data->server, record->type, record->number, ALPACA_CONTROL_MAX_BODY);
	private_data->class_data = device_class->data_size > 0 ? indigo_safe_malloc(device_class->data_size) : NULL;
	device->private_data = private_data;
	device->master_device = device;
	device->attach = device_class->attach;
	device->enumerate_properties = device_class->enumerate_properties;
	device->change_property = device_class->change_property;
	device->detach = device_class->detach;
	alpaca_result result = alpaca_get_int(private_data->channel, "interfaceversion", NULL, 0, ALPACA_WAIT_ESTABLISH, &version);
	if (result != ALPACA_OK) {
		char reason[INDIGO_NAME_SIZE - 64];
		copy_text(reason, sizeof(reason), alpaca_last_error_message(private_data->channel));
		snprintf(record->message, sizeof(record->message), "the device does not answer (%s%s%s)", alpaca_result_text(result), *reason ? ", " : "", reason);
		proxy_free(device);
		return false;
	}
	alpaca_channel_close(private_data->channel);
	private_data->interface_version = version;
	private_data->platform7 = version >= device_class->platform7_version;
	proxy_make_name(record, device->name);
	devices[slot] = device;
	if (indigo_attach_device(device) != INDIGO_OK || device->last_result != INDIGO_OK) {
		snprintf(record->message, sizeof(record->message), "the proxy device could not be attached");
		devices[slot] = NULL;
		// a device whose base class was not attached has nothing its detach callback could release
		if (device->device_context == NULL) {
			device->detach = NULL;
		}
		indigo_detach_device(device);
		proxy_free(device);
		return false;
	}
	record->device = device;
	record->message[0] = 0;
	return true;
}

// Disconnect (decision D5) and detach the proxy device of a record. The handler queue of the device is emptied first and the lock of
// the device of the framework is taken, so no handler of the device runs while its session is closed; handlers that are queued
// afterwards see the detaching flag or a session that is closed and do nothing.
// Nothing may empty the queue (indigo_cancel_pending_handler(s)) while that lock is held: the worker of the queue marks a task as running
// before it takes the lock, and the cancel waits for a running task that matches, which waits for the lock. So the queue is emptied
// before the lock is taken, every handler and finalizer that runs after the detaching flag is set returns without queuing anything,
// and on_disconnect of a class does not cancel anything while the device is being detached.
static void proxy_detach(device_record *record) {
	indigo_device *device = record->device;
	indigo_device *secondary = NULL;
	indigo_cancel_pending_handlers(device);
	// The handlers of the device run with this lock held, so the flag is written while none of them runs and is read by them without
	// a race. From here on no handler attaches or detaches the secondary device, so its pointer stays valid without the lock.
	indigo_lock_master_device(device);
	PRIVATE_DATA->detaching = true;
	indigo_device *guider = PRIVATE_DATA->secondary;
	indigo_unlock_master_device(device);
	// the queue is not emptied with the lock held: it waits for a handler that is running, and that one may wait for the lock
	if (guider != NULL) {
		indigo_cancel_pending_handlers(guider);
	}
	indigo_lock_master_device(device);
	if (proxy_count(device) > 0 || system_alpaca_is_active(device)) {
		secondary = proxy_detach_secondary(device);
		proxy_close_session(device, false);
		proxy_set_connection(device, INDIGO_OK_STATE, true);
		PRIVATE_DATA->device_class->base_change_property(device, NULL, CONNECTION_PROPERTY);
	}
	indigo_unlock_master_device(device);
	proxy_free_secondary(secondary);
	for (int i = 0; i < MAX_DEVICES; i++) {
		if (devices[i] == device) {
			devices[i] = NULL;
		}
	}
	indigo_detach_device(device);
	proxy_free(device);
	record->device = NULL;
}

// A device that is attached was found at another address or with another device number: its channels follow it.
static void proxy_rebind(device_record *record) {
	indigo_device *device = record->device;
	indigo_lock_master_device(device);
	PRIVATE_DATA->server = record->server->transport;
	PRIVATE_DATA->device_number = record->number;
	alpaca_channel_bind(PRIVATE_DATA->channel, PRIVATE_DATA->server, record->type, record->number);
	if (PRIVATE_DATA->transfer != NULL) {
		alpaca_channel_bind(PRIVATE_DATA->transfer, PRIVATE_DATA->server, record->type, record->number);
	}
	indigo_unlock_master_device(device);
	INDIGO_DRIVER_LOG(DRIVER_NAME, "'%s' is now %s #%d at %s:%d", device->name, record->type, record->number, PRIVATE_DATA->server->host, PRIVATE_DATA->server->port);
}

static void server_missed(server_record *server, const char *error) {
	int retention = (int)bridge_setting(X_ALPACA_DISCOVERY_SETTINGS_RETENTION_ITEM);
	copy_text(server->error, sizeof(server->error), error);
	server->missed++;
	if (server->missed >= retention) {
		if (server->online) {
			INDIGO_DRIVER_LOG(DRIVER_NAME, "Alpaca server %s:%d does not answer (%s), its devices are removed", server->transport->host, server->transport->port, error);
		}
		server->online = false;
		server->described = false;
		server_set_absent(server);
	}
}

// Ask a server what it is and which devices it has, and merge the answer into the list of devices.
static void server_query(server_record *server) {
	int versions[8];
	int count = 0;
	alpaca_result result = ALPACA_OK;
	char key[KEY_SIZE];
	char generated_id[ALPACA_TEXT_SIZE];
	if (!server->described) {
		bool version1 = false;
		// An answer that is no Alpaca envelope is asked for again at once, twice: a server that echoes a wrong ClientTransactionID
		// is accepted by the transport layer at the third answer, and must not look like a silent server until then.
		for (int attempt = 0; attempt < 3; attempt++) {
			result = alpaca_get_api_versions(server->channel, versions, 8, &count);
			if (result != ALPACA_PROTOCOL_ERROR) {
				break;
			}
		}
		// a server without the apiversions request is taken as a version 1 server
		if (result != ALPACA_OK && !alpaca_is_unsupported(result)) {
			server_missed(server, alpaca_last_error_message(server->channel));
			return;
		}
		for (int i = 0; i < count; i++) {
			version1 = version1 || versions[i] == 1;
		}
		server->unsupported = result == ALPACA_OK && !version1;
		result = alpaca_get_description(server->channel, &server->description);
		if (result != ALPACA_OK && !alpaca_is_unsupported(result)) {
			server_missed(server, alpaca_last_error_message(server->channel));
			return;
		}
		single_line(server->description.server_name);
		single_line(server->description.manufacturer);
		single_line(server->description.manufacturer_version);
		copy_text(server->name, sizeof(server->name), server->description.server_name);
		copy_text(server->maker, sizeof(server->maker) - 40, server->description.manufacturer);
		if (*server->description.manufacturer_version) {
			size_t length = strlen(server->maker);
			server->maker[length++] = ' ';
			copy_text(server->maker + length, 39, server->description.manufacturer_version);
		}
		// proxy loop: the Alpaca server of INDIGO itself (agent_alpaca) exports INDIGO devices, importing them again would duplicate them endlessly
		server->bridge = same_text(server->description.server_name, INDIGO_BRIDGE_SERVER_NAME) || same_text(server->description.manufacturer, INDIGO_BRIDGE_MANUFACTURER);
		server->described = true;
		INDIGO_DRIVER_LOG(DRIVER_NAME, "Alpaca server %s:%d is '%s' (%s %s)%s", server->transport->host, server->transport->port, server->description.server_name, server->description.manufacturer, server->description.manufacturer_version, server->bridge ? ", an INDIGO bridge that is ignored" : server->unsupported ? ", without API version 1" : "");
	}
	if (server->bridge || server->unsupported) {
		server->online = true;
		server->missed = 0;
		server->error[0] = 0;
		server_set_absent(server);
		return;
	}
	result = alpaca_get_configured_devices(server->channel, listed_devices, MAX_LISTED_DEVICES, &count);
	if (result != ALPACA_OK) {
		server_missed(server, alpaca_last_error_message(server->channel));
		return;
	}
	if (count == MAX_LISTED_DEVICES && server->device_count != count) {
		INDIGO_DRIVER_ERROR(DRIVER_NAME, "Alpaca server %s:%d lists more than %d devices, the rest is ignored", server->transport->host, server->transport->port, MAX_LISTED_DEVICES);
	}
	server->online = true;
	server->missed = 0;
	server->error[0] = 0;
	server->device_count = count;
	server->duplicate_count = 0;
	for (int i = 0; i < MAX_RECORDS; i++) {
		records[i].listed = false;
	}
	for (int i = 0; i < count; i++) {
		alpaca_configured_device *listed = listed_devices + i;
		const char *unique_id = listed->unique_id;
		if (*unique_id == 0) {
			// a device without UniqueID gets one from its address; it loses its identity when the address changes
			snprintf(generated_id, sizeof(generated_id), "%s-%d-%s-%d", listed->device_type, listed->device_number, server->transport->host, server->transport->port);
			unique_id = generated_id;
		}
		make_key(unique_id, key);
		device_record *record = record_find(key);
		if (record == NULL) {
			record = record_add(key);
			if (record == NULL) {
				INDIGO_DRIVER_ERROR(DRIVER_NAME, "Alpaca device '%s' ignored, the limit of %d devices is reached", listed->device_name, MAX_RECORDS);
				continue;
			}
		} else if (record->listed || (record->server != NULL && record->server != server && record->server->online && record->present)) {
			// the same UniqueID twice: on another server that is alive (a server reachable at two addresses, or a cloned device) or in this listing; the first one stays
			server->duplicate_count++;
			continue;
		}
		bool moved = record->device != NULL && (record->server != server || record->number != listed->device_number);
		record->reattach = record->reattach || (record->device != NULL && !same_text(record->type, listed->device_type));
		record->server = server;
		record->number = listed->device_number;
		record->present = true;
		record->listed = true;
		copy_text(record->unique_id, sizeof(record->unique_id), unique_id);
		copy_text(record->name, sizeof(record->name), listed->device_name);
		copy_text(record->type, sizeof(record->type), listed->device_type);
		single_line(record->name);
		if (moved && !record->reattach) {
			proxy_rebind(record);
		}
	}
	for (int i = 0; i < MAX_RECORDS; i++) {
		if (records[i].used && records[i].server == server && !records[i].listed && records[i].present) {
			records[i].present = false;
			lost_record_count++;
		}
	}
}

// The management connection is not kept open between the cycles: small embedded servers have only a few sockets,
// and those are better used by the devices.
static void server_refresh(server_record *server) {
	server_query(server);
	alpaca_channel_close(server->channel);
}

static const char *record_state(const device_record *record) {
	if (record->device != NULL) {
		return "ATTACHED";
	}
	if (!record->present) {
		return "OFFLINE";
	}
	if (find_class(record->type) == NULL) {
		return "UNSUPPORTED";
	}
	return record->selected ? "FAILED" : "AVAILABLE";
}

// Replace the items of a property whose item list changes at run time with list_items[0..count). If only values changed, the
// property is updated; if the items themselves changed, it is deleted and defined again, as clients expect. The property was
// allocated for its largest item count, so it never moves. The items are edited under bridge_mutex, the bus is called without it.
static void bridge_sync_property(indigo_device *device, indigo_property *property, int count) {
	bool changed = false;
	pthread_mutex_lock(&bridge_mutex);
	bool same = property->count == count;
	for (int i = 0; same && i < count; i++) {
		indigo_item *item = property->items + i;
		same = !strcmp(item->name, list_items[i].name) && !strcmp(item->label, list_items[i].label);
		changed = changed || (property->type == INDIGO_SWITCH_VECTOR ? item->sw.value != list_items[i].value : strcmp(indigo_get_text_item_value(item), list_items[i].text) != 0);
	}
	for (int i = 0; same && changed && i < count; i++) {
		if (property->type == INDIGO_SWITCH_VECTOR) {
			property->items[i].sw.value = list_items[i].value;
		} else {
			indigo_set_text_item_value(property->items + i, list_items[i].text);
		}
	}
	pthread_mutex_unlock(&bridge_mutex);
	if (same) {
		if (changed) {
			indigo_update_property(device, property, NULL);
		}
		return;
	}
	indigo_delete_property(device, property, NULL);
	pthread_mutex_lock(&bridge_mutex);
	indigo_resize_property(property, count);
	for (int i = 0; i < count; i++) {
		if (property->type == INDIGO_SWITCH_VECTOR) {
			indigo_init_switch_item(property->items + i, list_items[i].name, list_items[i].label, list_items[i].value);
		} else {
			indigo_init_text_item(property->items + i, list_items[i].name, list_items[i].label, "%s", list_items[i].text);
		}
	}
	pthread_mutex_unlock(&bridge_mutex);
	indigo_define_property(device, property, NULL);
}

// Publish the lists of servers and devices. The item lists are not touched while the configuration is being restored, because the
// restore of a property fails when the property is deleted in the middle of it; the update is repeated when the restore is over.
// The switches are taken from switched_off, so a request accepted since the last reconcile is not published back to its old value.
static void bridge_update_lists(void) {
	indigo_device *device = bridge;
	int count = 0;
	if (bridge_config_busy()) {
		if (!lists_pending) {
			lists_pending = true;
			indigo_queue_add(driver_queue, device, INDIGO_TASK_PRIORITY_NORMAL, CONFIG_WAIT_INTERVAL, bridge_lists_handler, &driver_queue_mutex);
		}
		return;
	}
	records_apply_selection();
	for (int i = 0; i < MAX_SERVERS; i++) {
		server_record *server = servers + i;
		if (server->used) {
			list_item *item = list_items + count++;
			const char *origin = server->manual && server->discovered ? "manual and discovered" : server->manual ? "manual" : "discovered";
			snprintf(item->name, sizeof(item->name), "%s:%d", server->transport->host, server->transport->port);
			snprintf(item->label, sizeof(item->label), "%s", *server->name ? server->name : item->name);
			if (server->bridge) {
				snprintf(item->text, sizeof(item->text), "IGNORED: INDIGO Alpaca bridge, its devices are INDIGO devices already (%s)", origin);
			} else if (server->unsupported) {
				snprintf(item->text, sizeof(item->text), "UNSUPPORTED: the server has no Alpaca API version 1 (%s)", origin);
			} else if (server->online && server->missed == 0) {
				snprintf(item->text, sizeof(item->text), "ONLINE: %d device(s), %d duplicate(s), %s (%s)", server->device_count, server->duplicate_count, server->maker, origin);
			} else {
				snprintf(item->text, sizeof(item->text), "%s: no answer to %d request(s), %s (%s)", server->online ? "SILENT" : "OFFLINE", server->missed, server->error, origin);
			}
		}
	}
	bridge_sync_property(device, X_ALPACA_SERVER_STATUS_PROPERTY, count);
	count = 0;
	for (int i = 0; i < MAX_RECORDS; i++) {
		device_record *record = records + i;
		if (record->used) {
			list_item *item = list_items + count++;
			strcpy(item->name, record->key);
			item->value = record->selected;
			if (record->server != NULL) {
				snprintf(item->label, sizeof(item->label), "%s (%s) @ %s", record->name, record->type, *record->server->name ? record->server->name : record->server->transport->host);
				snprintf(item->text, sizeof(item->text), "%s: %s #%d at %s:%d, UniqueID %s", record_state(record), record->type, record->number, record->server->transport->host, record->server->transport->port, record->unique_id);
			} else {
				snprintf(item->label, sizeof(item->label), "%s%s%s%s", *record->name ? record->name : record->unique_id, *record->type ? " (" : "", record->type, *record->type ? ")" : "");
				snprintf(item->text, sizeof(item->text), "%s: not listed by any server, UniqueID %s", record_state(record), record->unique_id);
			}
			size_t length = strlen(item->text);
			if (record->device != NULL) {
				snprintf(item->text + length, sizeof(item->text) - length, ", device '%s'", record->device->name);
			} else if (*record->message) {
				snprintf(item->text + length, sizeof(item->text) - length, ", %s", record->message);
			}
		}
	}
	bridge_sync_property(device, X_ALPACA_DEVICES_PROPERTY, count);
	bridge_sync_property(device, X_ALPACA_DEVICE_STATUS_PROPERTY, count);
}

static bool proxy_room(void) {
	for (int slot = 0; slot < MAX_DEVICES; slot++) {
		if (devices[slot] == NULL) {
			return true;
		}
	}
	return false;
}

// Bring the proxy devices in line with the lists: attach what is switched on and present, detach what is not, forget what is on and
// listed by no server. Nothing is done while the configuration is being restored (see the top of this file): the work is repeated when
// the restore is over, so the switches restored from the configuration are known before the first proxy device is attached.
// The devices are detached first, so that the room a device switched off leaves is there for a device that waits for it.
static void bridge_reconcile(void) {
	int retention = (int)bridge_setting(X_ALPACA_DISCOVERY_SETTINGS_RETENTION_ITEM);
	bool stopping = is_shutting_down();
	int refused = 0;
	if (bridge_config_busy()) {
		if (!reconcile_pending) {
			reconcile_pending = true;
			indigo_queue_add(driver_queue, bridge, INDIGO_TASK_PRIORITY_NORMAL, CONFIG_WAIT_INTERVAL, bridge_reconcile_handler, &driver_queue_mutex);
		}
		return;
	}
	// this reconcile does what a deferred one would have done
	reconcile_pending = false;
	records_apply_selection();
	for (int i = 0; i < MAX_RECORDS; i++) {
		device_record *record = records + i;
		bool wanted = record->selected && record->present && find_class(record->type) != NULL && !stopping;
		if (record->used && record->device != NULL && (!wanted || record->reattach)) {
			INDIGO_DRIVER_LOG(DRIVER_NAME, "'%s' is detached (%s)", record->device->name, !record->selected ? "switched off" : !record->present ? "not available any more" : "changed");
			proxy_detach(record);
		}
	}
	for (int i = 0; i < MAX_RECORDS; i++) {
		device_record *record = records + i;
		if (!record->used) {
			continue;
		}
		const alpaca_class *device_class = find_class(record->type);
		bool wanted = record->selected && record->present && device_class != NULL && !stopping;
		record->reattach = false;
		if (wanted && record->device == NULL) {
			char previous[INDIGO_NAME_SIZE];
			strcpy(previous, record->message);
			bool attached = false;
			if (proxy_room()) {
				attached = proxy_attach(record, device_class);
			} else {
				snprintf(record->message, sizeof(record->message), "the limit of %d proxy devices is reached", MAX_DEVICES);
				refused++;
			}
			if (!attached && strcmp(previous, record->message)) {
				INDIGO_DRIVER_ERROR(DRIVER_NAME, "Alpaca device '%s' (%s #%d) is not attached: %s", record->name, record->type, record->number, record->message);
			}
		} else if (!wanted) {
			record->message[0] = 0;
		}
		if (!record->present && record->selected) {
			memset(record, 0, sizeof(device_record));
		}
	}
	for (int i = 0; i < MAX_SERVERS; i++) {
		server_record *server = servers + i;
		if (server->used && !server->manual && (!server->discovered || (!server->online && server->missed >= retention))) {
			server_remove(server);
		}
	}
	if (refused > 0 && refused != capacity_refused) {
		indigo_send_message(bridge, NULL, "%d Alpaca device(s) have no proxy device, the limit of %d proxy devices is reached; switch devices off in %s to make room", refused, MAX_DEVICES, X_ALPACA_DEVICES_PROPERTY_NAME);
	}
	capacity_refused = refused;
	bridge_update_lists();
}

// The reconcile deferred while the configuration was being restored, unless another one has run since.
static void bridge_reconcile_handler(indigo_device *device) {
	assert(device != NULL);
	if (reconcile_pending && !is_shutting_down()) {
		reconcile_pending = false;
		bridge_reconcile();
	}
}

static bool discovery_callback(const char *responder, int responder_port, const char *reply, long length, void *context) {
	discovery_result *result = context;
	int port = 0;
	if (!alpaca_parse_discovery_reply(reply, length, &port)) {
		INDIGO_DRIVER_DEBUG(DRIVER_NAME, "Discovery reply of %s:%d ignored: '%.*s'", responder, responder_port, (int)(length > 100 ? 100 : length), reply);
		return true;
	}
	for (int i = 0; i < result->count; i++) {
		if (result->endpoints[i].port == port && !strcmp(result->endpoints[i].host, responder)) {
			return true;
		}
	}
	if (result->count < MAX_SERVERS && strlen(responder) < ALPACA_HOST_SIZE) {
		strcpy(result->endpoints[result->count].host, responder);
		result->endpoints[result->count++].port = port;
	}
	return true;
}

// Send the discovery request: to the targets of X_ALPACA_DISCOVERY_TARGETS if there are any, otherwise as a broadcast on every
// interface and on the loopback network, and collect the endpoints (address of the responder and AlpacaPort) that answered.
static void bridge_discover(void) {
	// The UDP discovery waits for replies for polls * timeout, the handler queue task has no run time limit.
	indigo_set_handler_max_run_time(0);
	int port = (int)bridge_setting(X_ALPACA_DISCOVERY_SETTINGS_PORT_ITEM);
	int polls = (int)bridge_setting(X_ALPACA_DISCOVERY_SETTINGS_POLLS_ITEM);
	long timeout = (long)bridge_setting(X_ALPACA_DISCOVERY_SETTINGS_TIMEOUT_ITEM) * 1000;
	char targets[INDIGO_VALUE_SIZE];
	char host[ALPACA_HOST_SIZE];
	int target_count = 0;
	int target_port = 0;
	memset(&discovered, 0, sizeof(discovered));
	pthread_mutex_lock(&bridge_mutex);
	copy_text(targets, sizeof(targets), X_ALPACA_DISCOVERY_TARGETS_ITEM->text.value);
	pthread_mutex_unlock(&bridge_mutex);
	for (char *token = targets, *next = NULL; token != NULL && target_count < MAX_TARGETS; token = next) {
		next = strpbrk(token, ",; ");
		if (next != NULL) {
			*next++ = 0;
		}
		if (*token && alpaca_parse_endpoint(token, port, host, sizeof(host), &target_port)) {
			target_count++;
			indigo_uni_discover(host, target_port, ALPACA_DISCOVERY_MESSAGE, (long)strlen(ALPACA_DISCOVERY_MESSAGE), polls, timeout, false, discovery_callback, &discovered);
		}
	}
	if (target_count == 0) {
		indigo_uni_discover(NULL, port, ALPACA_DISCOVERY_MESSAGE, (long)strlen(ALPACA_DISCOVERY_MESSAGE), polls, timeout, true, discovery_callback, &discovered);
	}
	for (int i = 0; i < discovered.count; i++) {
		server_record *server = server_find(discovered.endpoints[i].host, discovered.endpoints[i].port);
		if (server == NULL) {
			server = server_add(discovered.endpoints[i].host, discovered.endpoints[i].port);
		}
		if (server != NULL) {
			server->discovered = true;
		}
	}
}

// One cycle: discovery (if asked for), then every known server is asked for its devices, then the proxy devices are brought in line.
static void bridge_cycle(bool discover) {
	if (discover) {
		bridge_discover();
	}
	lost_record_count = 0;
	for (int i = 0; i < MAX_SERVERS; i++) {
		if (servers[i].used) {
			server_refresh(servers + i);
		}
	}
	// A device that was refused as a duplicate while another server still listed it is taken over in the same cycle in which
	// that server lost it, whatever the order of the servers is, so the proxy device of a device that moved is kept.
	for (int i = 0; lost_record_count > 0 && i < MAX_SERVERS; i++) {
		if (servers[i].used && servers[i].online && servers[i].duplicate_count > 0) {
			server_refresh(servers + i);
		}
	}
	bridge_reconcile();
}

// The periodic cycle. It runs every INTERVAL seconds whether discovery is enabled or not: X_ALPACA_DISCOVERY only decides whether
// the cycle looks for new servers. The known servers (the manual ones above all) are always asked again, so a server that was down
// is found when it is back, a device that disappeared is detached and a failed attach is tried again.
// data is the generation the chain of calls belongs to: a change of the discovery properties starts a new generation, and a call
// of an older one ends its chain. Nothing runs while the configuration is being restored, so the first cycle after INIT already
// uses the saved settings.
static void bridge_discovery_handler(indigo_device *device, void *data) {
	unsigned generation = (unsigned)(uintptr_t)data;
	if (is_shutting_down() || generation != current_discovery_generation()) {
		return;
	}
	if (bridge_config_busy()) {
		indigo_queue_add_with_data(driver_queue, device, INDIGO_TASK_PRIORITY_NORMAL, CONFIG_WAIT_INTERVAL, bridge_discovery_handler, data, &driver_queue_mutex);
		return;
	}
	pthread_mutex_lock(&bridge_mutex);
	bool enabled = X_ALPACA_DISCOVERY_ENABLED_ITEM->sw.value;
	pthread_mutex_unlock(&bridge_mutex);
	bridge_cycle(enabled);
	if (!is_shutting_down() && generation == current_discovery_generation()) {
		indigo_queue_add_with_data(driver_queue, device, INDIGO_TASK_PRIORITY_NORMAL, bridge_setting(X_ALPACA_DISCOVERY_SETTINGS_INTERVAL_ITEM), bridge_discovery_handler, data, &driver_queue_mutex);
	}
}

// Start a new chain of periodic cycles, with the first cycle now or one interval from now.
static void bridge_restart_discovery(indigo_device *device, bool immediately) {
	pthread_mutex_lock(&settings_mutex);
	unsigned generation = ++discovery_generation;
	pthread_mutex_unlock(&settings_mutex);
	indigo_queue_add_with_data(driver_queue, device, INDIGO_TASK_PRIORITY_NORMAL, immediately ? 0 : X_ALPACA_DISCOVERY_SETTINGS_INTERVAL_ITEM->number.value, bridge_discovery_handler, (void *)(uintptr_t)generation, &driver_queue_mutex);
}

static void bridge_x_alpaca_discover_handler(indigo_device *device) {
	if (is_shutting_down()) {
		return;
	}
	if (bridge_config_busy()) {
		indigo_queue_add(driver_queue, device, INDIGO_TASK_PRIORITY_NORMAL, CONFIG_WAIT_INTERVAL, bridge_x_alpaca_discover_handler, &driver_queue_mutex);
		return;
	}
	bridge_cycle(true);
	bridge_finish(device, X_ALPACA_DISCOVER_PROPERTY, X_ALPACA_DISCOVER_ITEM);
}

// Apply X_ALPACA_SERVERS: servers that are new in the list are added and asked for their devices at once,
// servers that left the list and were not discovered are removed together with their devices.
// This handler and the one of X_ALPACA_DEVICES also run while the configuration is being restored: the restore waits for the
// property to leave the BUSY state. Only the lists are published later, see bridge_update_lists().
static void bridge_x_alpaca_servers_handler(indigo_device *device) {
	char list[INDIGO_VALUE_SIZE];
	char host[ALPACA_HOST_SIZE];
	int port = 0;
	if (is_shutting_down()) {
		return;
	}
	pthread_mutex_lock(&bridge_mutex);
	servers_pending = false;
	copy_text(list, sizeof(list), X_ALPACA_SERVERS_LIST_ITEM->text.value);
	pthread_mutex_unlock(&bridge_mutex);
	for (int i = 0; i < MAX_SERVERS; i++) {
		servers[i].manual = false;
	}
	for (char *token = list, *next = NULL; token != NULL; token = next) {
		next = strpbrk(token, ",; ");
		if (next != NULL) {
			*next++ = 0;
		}
		if (*token && alpaca_parse_endpoint(token, ALPACA_DEFAULT_PORT, host, sizeof(host), &port)) {
			server_record *server = server_find(host, port);
			if (server == NULL) {
				server = server_add(host, port);
			}
			if (server != NULL) {
				server->manual = true;
			}
		}
	}
	for (int i = 0; i < MAX_SERVERS; i++) {
		server_record *server = servers + i;
		if (server->used && !server->manual && !server->discovered) {
			server_set_absent(server);
		} else if (server->used && !server->described) {
			server_refresh(server);
		}
	}
	bridge_reconcile();
	bridge_finish(device, X_ALPACA_SERVERS_PROPERTY, NULL);
}

// Bring the proxy devices in line with the switches recorded by bridge_change_devices().
static void bridge_x_alpaca_devices_handler(indigo_device *device) {
	assert(device != NULL);
	if (is_shutting_down()) {
		return;
	}
	pthread_mutex_lock(&bridge_mutex);
	selection_pending = false;
	pthread_mutex_unlock(&bridge_mutex);
	bridge_reconcile();
}

static void bridge_x_alpaca_timeouts_handler(indigo_device *device) {
	if (is_shutting_down()) {
		return;
	}
	int establish = (int)round(bridge_setting(X_ALPACA_TIMEOUTS_ESTABLISH_ITEM) * 1000);
	int standard = (int)round(bridge_setting(X_ALPACA_TIMEOUTS_STANDARD_ITEM) * 1000);
	int longest = (int)round(bridge_setting(X_ALPACA_TIMEOUTS_LONG_ITEM) * 1000);
	pthread_mutex_lock(&settings_mutex);
	establish_timeout = establish;
	standard_timeout = standard;
	long_timeout = longest;
	pthread_mutex_unlock(&settings_mutex);
	for (int i = 0; i < MAX_SERVERS; i++) {
		if (servers[i].used) {
			alpaca_server_set_timeouts(servers[i].transport, establish, standard, longest);
		}
	}
	bridge_finish(device, X_ALPACA_TIMEOUTS_PROPERTY, NULL);
}

static void bridge_lists_handler(indigo_device *device) {
	assert(device != NULL);
	lists_pending = false;
	if (!is_shutting_down()) {
		bridge_update_lists();
	}
}

// Normalise a list of servers given by the user: every entry has to be host[:port], the result is "host:port, host:port" without
// duplicates. add and remove are single entries that are appended to or taken out of the list. Returns false if an entry is not valid
// or there are too many of them.
static bool bridge_edit_servers(const char *list, const char *add, const char *remove, char *result, size_t size) {
	char text[2 * INDIGO_VALUE_SIZE];
	char entries[MAX_SERVERS][ALPACA_HOST_SIZE + 16];
	char entry[ALPACA_HOST_SIZE + 16];
	char removed[ALPACA_HOST_SIZE + 16] = { 0 };
	char host[ALPACA_HOST_SIZE];
	int port = 0;
	int count = 0;
	size_t used = 0;
	if (*remove) {
		if (!alpaca_parse_endpoint(remove, ALPACA_DEFAULT_PORT, host, sizeof(host), &port)) {
			return false;
		}
		snprintf(removed, sizeof(removed), strchr(host, ':') != NULL ? "[%s]:%d" : "%s:%d", host, port);
	}
	snprintf(text, sizeof(text), "%s,%s", list, add);
	for (char *token = text, *next = NULL; token != NULL; token = next) {
		next = strpbrk(token, ",; ");
		if (next != NULL) {
			*next++ = 0;
		}
		if (*token == 0) {
			continue;
		}
		if (!alpaca_parse_endpoint(token, ALPACA_DEFAULT_PORT, host, sizeof(host), &port)) {
			return false;
		}
		snprintf(entry, sizeof(entry), strchr(host, ':') != NULL ? "[%s]:%d" : "%s:%d", host, port);
		bool skip = same_text(entry, removed);
		for (int i = 0; i < count && !skip; i++) {
			skip = same_text(entry, entries[i]);
		}
		if (skip) {
			continue;
		}
		if (count == MAX_SERVERS) {
			return false;
		}
		strcpy(entries[count++], entry);
	}
	*result = 0;
	for (int i = 0; i < count; i++) {
		if (used + strlen(entries[i]) + 3 > size) {
			return false;
		}
		used += (size_t)snprintf(result + used, size - used, "%s%s", i > 0 ? ", " : "", entries[i]);
	}
	return true;
}

// Discovery targets are numeric IPv4 addresses with an optional port, because that is what the discovery request can be sent to.
static bool bridge_targets_valid(const char *targets) {
	char text[INDIGO_VALUE_SIZE];
	char host[ALPACA_HOST_SIZE];
	int port = 0;
	int count = 0;
	if (strlen(targets) >= sizeof(text)) {
		return false;
	}
	strcpy(text, targets);
	for (char *token = text, *next = NULL; token != NULL; token = next) {
		next = strpbrk(token, ",; ");
		if (next != NULL) {
			*next++ = 0;
		}
		if (*token == 0) {
			continue;
		}
		if (++count > MAX_TARGETS || !alpaca_parse_endpoint(token, ALPACA_DISCOVERY_PORT, host, sizeof(host), &port) || strspn(host, "0123456789.") != strlen(host)) {
			return false;
		}
	}
	return true;
}

