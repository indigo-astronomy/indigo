alpaca_result system_alpaca_check(indigo_device *device, alpaca_result result) {
	if (alpaca_is_transport_error(result)) {
		if (++PRIVATE_DATA->transport_errors >= TRANSPORT_ERROR_LIMIT) {
			PRIVATE_DATA->offline = true;
		}
	} else if (result != ALPACA_FAILED) {
		// every reply of the server, also an error, proves that the transport works
		PRIVATE_DATA->transport_errors = 0;
		if (result == ALPACA_NOT_CONNECTED) {
			PRIVATE_DATA->not_connected = true;
		}
	}
	return result;
}

