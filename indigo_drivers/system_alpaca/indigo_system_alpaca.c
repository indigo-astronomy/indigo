static char lower_case(char c) {
	return c >= 'A' && c <= 'Z' ? (char)(c - 'A' + 'a') : c;
}

static bool same_text(const char *text, const char *other) {
	while (*text && lower_case(*text) == lower_case(*other)) {
		text++;
		other++;
	}
	return *text == 0 && *other == 0;
}

// Copy text into a buffer of size bytes, cut at a UTF-8 character boundary.
static void copy_text(char *target, size_t size, const char *source) {
	size_t length = strlen(source);
	if (length >= size) {
		length = size - 1;
		while (length > 0 && ((unsigned char)source[length] & 0xC0) == 0x80) {
			length--;
		}
	}
	memcpy(target, source, length);
	target[length] = 0;
}

// Copy text that becomes a part of a device name: characters that are not allowed in file names (the configuration of a device is
// saved in a file named after it), control characters and "@" are replaced, white space at both ends is removed. "@" is the separator
// of the remote service in the names of the bus: indigo_bus.c routes a request to a remote service "@ <service>" whose name is contained
// in the device name, indigo_xml.c cuts a name at its last "@" before it is sent to a server and indigo_filter.c takes a related device
// with "@" for a remote one, so a proxy name has none.
static void copy_name_part(char *target, size_t size, const char *source) {
	while (*source == ' ') {
		source++;
	}
	copy_text(target, size, source);
	for (char *c = target; *c; c++) {
		if ((unsigned char)*c < ' ' || strchr("/\\:*?\"<>|@", *c) != NULL) {
			*c = '-';
		}
	}
	size_t length = strlen(target);
	while (length > 0 && target[length - 1] == ' ') {
		target[--length] = 0;
	}
}

static void single_line(char *text) {
	for (char *c = text; *c; c++) {
		if ((unsigned char)*c < ' ') {
			*c = ' ';
		}
	}
}

// Key of a device: its UniqueID in lower case (UniqueIDs are compared without regard to case) with everything that is not safe in an
// item name replaced by '_'. A UniqueID that had a character replaced or is too long gets a hash of the whole text (after its beginning),
// so it stays unique: "cam:1" and "cam/1" are two devices.
static void make_key(const char *unique_id, char *key) {
	size_t length = strlen(unique_id);
	uint32_t hash = 2166136261u;
	bool replaced = false;
	for (size_t i = 0; i < length; i++) {
		char c = lower_case(unique_id[i]);
		bool safe = (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c == '-' || c == '.' || c == '_';
		hash = (hash ^ (unsigned char)c) * 16777619u;
		replaced = replaced || !safe;
		if (i < KEY_SIZE - 1) {
			key[i] = safe ? c : '_';
		}
	}
	if (length >= KEY_SIZE - 10 && (replaced || length >= KEY_SIZE)) {
		snprintf(key + KEY_SIZE - 10, 10, "_%08x", (unsigned)hash);
	} else if (replaced) {
		snprintf(key + length, 10, "_%08x", (unsigned)hash);
	} else {
		key[length] = 0;
	}
}

