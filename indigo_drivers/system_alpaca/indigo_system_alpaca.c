	snprintf(INFO_DEVICE_HW_REVISION_ITEM->text.value, INDIGO_VALUE_SIZE, "%d", PRIVATE_DATA->interface_version);
	if (is_secondary) {
		// the secondary device is attached while the primary one is connected, so INFO of the Alpaca device is known
		INDIGO_COPY_VALUE(INFO_DEVICE_MODEL_ITEM->text.value, proxy_info_model(PRIVATE_DATA->device));
		INDIGO_COPY_VALUE(INFO_DEVICE_FW_REVISION_ITEM->text.value, proxy_info_driver(PRIVATE_DATA->device));
	}
