static alpaca_capability *capability_find(indigo_device *device, const char *member) {
	for (int i = 0; i < PRIVATE_DATA->capability_count; i++) {
		if (same_text(PRIVATE_DATA->capabilities[i].member, member)) {
			return PRIVATE_DATA->capabilities + i;
		}
	}
	return NULL;
}

static void capability_set(indigo_device *device, const char *member, bool supported, bool value) {
	alpaca_capability *capability = capability_find(device, member);
	if (capability == NULL && PRIVATE_DATA->capability_count < ALPACA_MAX_CAPABILITIES && strlen(member) < ALPACA_MEMBER_SIZE) {
		capability = PRIVATE_DATA->capabilities + PRIVATE_DATA->capability_count++;
		strcpy(capability->member, member);
	}
	if (capability != NULL) {
		capability->supported = supported;
		capability->value = supported && value;
	}
}

