	bool is_secondary = device == PRIVATE_DATA->secondary;
	INFO_PROPERTY->count = 8;
	INDIGO_COPY_VALUE(INFO_DEVICE_MODEL_ITEM->text.value, PRIVATE_DATA->device_name);
