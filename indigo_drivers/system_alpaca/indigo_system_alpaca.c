// The switches of the devices (decision D15): every device is on unless it was switched off. The switch is recorded here, on the bus
// thread, in switched_off, so that the switches a configuration restore sends are all known when the restore ends; the handler then
// brings the proxy devices in line. An item is named by the key of its device; a name that is not a key yet (a UniqueID in upper case)
// is made one. A key that is not listed is taken as it is: switched off it is remembered and listed until its device appears, switched
// on it needs nothing, because on is the default.
static void bridge_change_devices(indigo_device *device, indigo_property *property) {
	int ignored = 0;
	for (int i = 0; i < property->count; i++) {
		indigo_item *request = property->items + i;
		char key[KEY_SIZE];
		if (*request->name == 0) {
			continue;
		}
		make_key(request->name, key);
		indigo_item *item = indigo_get_item(X_ALPACA_DEVICES_PROPERTY, key);
		if (item != NULL) {
			item->sw.value = request->sw.value;
			item->do_update = true;
		}
		if (!switched_off_set(key, !request->sw.value)) {
			ignored++;
		}
	}
	// every request is answered, also one that changes no item that exists yet: a client and the configuration restore wait for the answer
	X_ALPACA_DEVICES_PROPERTY->do_update = true;
	X_ALPACA_DEVICES_PROPERTY->state = ignored > 0 ? INDIGO_ALERT_STATE : INDIGO_OK_STATE;
	if (ignored > 0) {
		indigo_update_property(device, X_ALPACA_DEVICES_PROPERTY, "%d device(s) not switched off, at most %d devices can be switched off", ignored, MAX_RECORDS);
	} else {
		indigo_update_property(device, X_ALPACA_DEVICES_PROPERTY, NULL);
	}
	// one handler applies all the requests recorded until it runs, so a client that sends many requests does not fill the queue
	if (!selection_pending) {
		selection_pending = true;
		indigo_queue_add(driver_queue, device, INDIGO_TASK_PRIORITY_NORMAL, 0, bridge_x_alpaca_devices_handler, &driver_queue_mutex);
	}
}

static void bridge_change_servers(indigo_device *device, indigo_property *property) {
	char list[INDIGO_VALUE_SIZE];
	const char *requested = X_ALPACA_SERVERS_LIST_ITEM->text.value;
	const char *add = "";
	const char *remove = "";
	for (int i = 0; i < property->count; i++) {
		indigo_item *item = property->items + i;
		if (!strcmp(item->name, X_ALPACA_SERVERS_LIST_ITEM_NAME)) {
			requested = indigo_get_text_item_value(item);
		} else if (!strcmp(item->name, X_ALPACA_SERVERS_ADD_ITEM_NAME)) {
			add = indigo_get_text_item_value(item);
		} else if (!strcmp(item->name, X_ALPACA_SERVERS_REMOVE_ITEM_NAME)) {
			remove = indigo_get_text_item_value(item);
		}
	}
	if (strlen(requested) >= INDIGO_VALUE_SIZE || strlen(add) >= ALPACA_HOST_SIZE || strlen(remove) >= ALPACA_HOST_SIZE || !bridge_edit_servers(requested, add, remove, list, sizeof(list))) {
		indigo_reject_change(device, X_ALPACA_SERVERS_PROPERTY, "Servers have to be given as host:port, at most %d of them", MAX_SERVERS);
		return;
	}
	indigo_set_text_item_value(X_ALPACA_SERVERS_LIST_ITEM, list);
	indigo_set_text_item_value(X_ALPACA_SERVERS_ADD_ITEM, "");
	indigo_set_text_item_value(X_ALPACA_SERVERS_REMOVE_ITEM, "");
	X_ALPACA_SERVERS_PROPERTY->do_update = true;
	X_ALPACA_SERVERS_PROPERTY->state = INDIGO_BUSY_STATE;
	indigo_update_property(device, X_ALPACA_SERVERS_PROPERTY, NULL);
	if (!servers_pending) {
		servers_pending = true;
		indigo_queue_add(driver_queue, device, INDIGO_TASK_PRIORITY_NORMAL, 0, bridge_x_alpaca_servers_handler, &driver_queue_mutex);
	}
}

// Returns true if the request was for a property of the bridge and is handled. Called with bridge_mutex held.
static bool bridge_process_change(indigo_device *device, indigo_property *property) {
	if (indigo_property_match_changeable(X_ALPACA_DISCOVERY_PROPERTY, property)) {
		indigo_property_copy_values(X_ALPACA_DISCOVERY_PROPERTY, property, false);
		X_ALPACA_DISCOVERY_PROPERTY->state = INDIGO_OK_STATE;
		indigo_update_property(device, X_ALPACA_DISCOVERY_PROPERTY, NULL);
		bridge_restart_discovery(device, X_ALPACA_DISCOVERY_ENABLED_ITEM->sw.value);
		return true;
	} else if (indigo_property_match_changeable(X_ALPACA_DISCOVERY_SETTINGS_PROPERTY, property)) {
		indigo_property_copy_values(X_ALPACA_DISCOVERY_SETTINGS_PROPERTY, property, false);
		X_ALPACA_DISCOVERY_SETTINGS_PROPERTY->state = INDIGO_OK_STATE;
		indigo_update_property(device, X_ALPACA_DISCOVERY_SETTINGS_PROPERTY, NULL);
		bridge_restart_discovery(device, false);
		return true;
	} else if (indigo_property_match_changeable(X_ALPACA_DISCOVERY_TARGETS_PROPERTY, property)) {
		indigo_item *targets = indigo_get_item(property, X_ALPACA_DISCOVERY_TARGETS_ITEM_NAME);
		if (targets != NULL && !bridge_targets_valid(indigo_get_text_item_value(targets))) {
			indigo_reject_change(device, X_ALPACA_DISCOVERY_TARGETS_PROPERTY, "Discovery targets have to be IPv4 addresses, address[:port], at most %d of them", MAX_TARGETS);
			return true;
		}
		indigo_property_copy_values(X_ALPACA_DISCOVERY_TARGETS_PROPERTY, property, false);
		X_ALPACA_DISCOVERY_TARGETS_PROPERTY->state = INDIGO_OK_STATE;
		indigo_update_property(device, X_ALPACA_DISCOVERY_TARGETS_PROPERTY, NULL);
		bridge_restart_discovery(device, false);
		return true;
	} else if (indigo_property_match_changeable(X_ALPACA_DISCOVER_PROPERTY, property)) {
		if (X_ALPACA_DISCOVER_PROPERTY->state != INDIGO_BUSY_STATE) {
			indigo_property_copy_values(X_ALPACA_DISCOVER_PROPERTY, property, false);
			if (X_ALPACA_DISCOVER_ITEM->sw.value) {
				X_ALPACA_DISCOVER_PROPERTY->state = INDIGO_BUSY_STATE;
				indigo_queue_add(driver_queue, device, INDIGO_TASK_PRIORITY_NORMAL, 0, bridge_x_alpaca_discover_handler, &driver_queue_mutex);
			} else {
				X_ALPACA_DISCOVER_PROPERTY->state = INDIGO_OK_STATE;
			}
		}
		// a request that arrives while a cycle runs changes nothing, but it is answered with the current state all the same
		X_ALPACA_DISCOVER_PROPERTY->do_update = true;
		indigo_update_property(device, X_ALPACA_DISCOVER_PROPERTY, NULL);
		return true;
	} else if (indigo_property_match_changeable(X_ALPACA_SERVERS_PROPERTY, property)) {
		bridge_change_servers(device, property);
		return true;
	} else if (indigo_property_match_changeable(X_ALPACA_DEVICES_PROPERTY, property)) {
		bridge_change_devices(device, property);
		return true;
	} else if (indigo_property_match_changeable(X_ALPACA_TIMEOUTS_PROPERTY, property)) {
		bool pending = X_ALPACA_TIMEOUTS_PROPERTY->state == INDIGO_BUSY_STATE;
		indigo_property_copy_values(X_ALPACA_TIMEOUTS_PROPERTY, property, false);
		X_ALPACA_TIMEOUTS_PROPERTY->state = INDIGO_BUSY_STATE;
		indigo_update_property(device, X_ALPACA_TIMEOUTS_PROPERTY, NULL);
		if (!pending) {
			indigo_queue_add(driver_queue, device, INDIGO_TASK_PRIORITY_NORMAL, 0, bridge_x_alpaca_timeouts_handler, &driver_queue_mutex);
		}
		return true;
	} else if (indigo_property_match_changeable(X_ALPACA_POLLING_PROPERTY, property)) {
		indigo_property_copy_values(X_ALPACA_POLLING_PROPERTY, property, false);
		pthread_mutex_lock(&settings_mutex);
		poll_idle_interval = X_ALPACA_POLLING_IDLE_ITEM->number.value;
		poll_active_interval = X_ALPACA_POLLING_ACTIVE_ITEM->number.value;
		pthread_mutex_unlock(&settings_mutex);
		X_ALPACA_POLLING_PROPERTY->state = INDIGO_OK_STATE;
		indigo_update_property(device, X_ALPACA_POLLING_PROPERTY, NULL);
		return true;
	} else if (indigo_property_match(CONFIG_PROPERTY, property)) {
		if (indigo_switch_match(CONFIG_SAVE_ITEM, property) && CONFIG_PROPERTY->state != INDIGO_BUSY_STATE) {
			indigo_save_property(device, NULL, X_ALPACA_DISCOVERY_PROPERTY);
			indigo_save_property(device, NULL, X_ALPACA_DISCOVERY_SETTINGS_PROPERTY);
			indigo_save_property(device, NULL, X_ALPACA_DISCOVERY_TARGETS_PROPERTY);
			indigo_save_property(device, NULL, X_ALPACA_TIMEOUTS_PROPERTY);
			indigo_save_property(device, NULL, X_ALPACA_POLLING_PROPERTY);
			indigo_save_property(device, NULL, X_ALPACA_SERVERS_PROPERTY);
			indigo_save_property(device, NULL, X_ALPACA_DEVICES_PROPERTY);
		}
	}
	return false;
}

static indigo_result bridge_change_property(indigo_device *device, indigo_client *client, indigo_property *property) {
	assert(device != NULL);
	assert(property != NULL);
	pthread_mutex_lock(&bridge_mutex);
	bool handled = bridge_process_change(device, property);
	pthread_mutex_unlock(&bridge_mutex);
	if (handled) {
		return INDIGO_OK;
	}
	return indigo_aux_change_property(device, client, property);
}

static indigo_result bridge_detach(indigo_device *device) {
	indigo_release_property(X_ALPACA_DISCOVERY_PROPERTY);
	indigo_release_property(X_ALPACA_DISCOVERY_SETTINGS_PROPERTY);
	indigo_release_property(X_ALPACA_DISCOVERY_TARGETS_PROPERTY);
	indigo_release_property(X_ALPACA_DISCOVER_PROPERTY);
	indigo_release_property(X_ALPACA_SERVERS_PROPERTY);
	indigo_release_property(X_ALPACA_SERVER_STATUS_PROPERTY);
	indigo_release_property(X_ALPACA_DEVICES_PROPERTY);
	indigo_release_property(X_ALPACA_DEVICE_STATUS_PROPERTY);
	indigo_release_property(X_ALPACA_TIMEOUTS_PROPERTY);
	indigo_release_property(X_ALPACA_POLLING_PROPERTY);
	INDIGO_DEVICE_DETACH_LOG(DRIVER_NAME, device->name);
	return indigo_aux_detach(device);
}

#pragma mark - Device templates

static indigo_device bridge_template = INDIGO_DEVICE_INITIALIZER(BRIDGE_DEVICE_NAME, bridge_attach, bridge_enumerate_properties, bridge_change_property, NULL, bridge_detach);

#pragma mark - Hot-plug code

// A proxy device that is connected, or still connecting, keeps the driver loaded, as a connected device of a hot-plug driver does.
// It runs on the thread of SHUTDOWN with the driver queue locked, so devices[] does not change; CONNECTION and the count of the
// logical devices that hold the Alpaca device open are read under the lock of the device, which the bus thread and the handler queue
// write them under.
static indigo_result verify_devices_disconnected(void) {
	for (int i = 0; i < MAX_DEVICES; i++) {
		indigo_device *device = devices[i];
		if (device != NULL) {
			pthread_mutex_lock(&PRIVATE_DATA->mutex);
			bool busy = !IS_DISCONNECTED || PRIVATE_DATA->count > 0;
			pthread_mutex_unlock(&PRIVATE_DATA->mutex);
			if (busy) {
				return INDIGO_BUSY;
			}
		}
	}
	return INDIGO_OK;
}

// Take the lock the tasks of the driver queue run under, waiting at most the given number of seconds for a running task.
static bool lock_driver_queue(double timeout) {
	double deadline = indigo_monotonic_time() + timeout;
	while (pthread_mutex_trylock(&driver_queue_mutex) != 0) {
		if (indigo_monotonic_time() >= deadline) {
			return false;
		}
		indigo_usleep(10000);
	}
	return true;
}

static void remove_all_devices(void) {
	for (int i = MAX_RECORDS - 1; i >= 0; i--) {
		if (records[i].used && records[i].device != NULL) {
			proxy_detach(records + i);
		}
	}
	for (int i = 0; i < MAX_SERVERS; i++) {
		if (servers[i].used) {
			alpaca_channel_free(servers[i].channel);
			alpaca_server_free(servers[i].transport);
		}
	}
	memset(servers, 0, sizeof(servers));
	memset(records, 0, sizeof(records));
	switched_off_count = 0;
}

#pragma mark - Main code

indigo_result indigo_system_alpaca(indigo_driver_action action, indigo_driver_info *info) {
	static indigo_driver_action last_action = INDIGO_DRIVER_SHUTDOWN;
	SET_DRIVER_INFO(info, DRIVER_LABEL, __FUNCTION__, DRIVER_VERSION, true, last_action);
	if (action == last_action) {
		return INDIGO_OK;
	}
	switch (action) {
		case INDIGO_DRIVER_INIT: {
			last_action = action;
			pthread_mutexattr_t attributes;
			for (int i = 0; i < MAX_DEVICES; i++) {
				devices[i] = NULL;
			}
			memset(servers, 0, sizeof(servers));
			memset(records, 0, sizeof(records));
			switched_off_count = 0;
			selection_pending = false;
			reconcile_pending = false;
			capacity_refused = 0;
			servers_pending = false;
			lists_pending = false;
			pthread_mutex_lock(&settings_mutex);
			shutting_down = false;
			poll_idle_interval = 1.0;
			poll_active_interval = 0.2;
			establish_timeout = ALPACA_ESTABLISH_TIMEOUT;
			standard_timeout = ALPACA_STANDARD_TIMEOUT;
			long_timeout = ALPACA_LONG_TIMEOUT;
			pthread_mutex_unlock(&settings_mutex);
			pthread_mutexattr_init(&attributes);
			pthread_mutexattr_settype(&attributes, PTHREAD_MUTEX_RECURSIVE);
			pthread_mutex_init(&bridge_mutex, &attributes);
			pthread_mutexattr_destroy(&attributes);
			driver_queue = indigo_queue_create(NULL);
			if (driver_queue == NULL) {
				INDIGO_DRIVER_ERROR(DRIVER_NAME, "Failed to create driver queue");
				pthread_mutex_destroy(&bridge_mutex);
				last_action = INDIGO_DRIVER_SHUTDOWN;
				return INDIGO_FAILED;
			}
			indigo_queue_set_name(driver_queue, "Queue " DRIVER_LABEL);
			bridge = indigo_safe_malloc_copy(sizeof(indigo_device), &bridge_template);
			bridge->private_data = indigo_safe_malloc(sizeof(bridge_private_data));
			if (indigo_attach_device(bridge) != INDIGO_OK || bridge->last_result != INDIGO_OK) {
				INDIGO_DRIVER_ERROR(DRIVER_NAME, "Failed to attach '%s'", bridge->name);
				if (bridge->device_context == NULL) {
					bridge->detach = NULL;
				}
				indigo_detach_device(bridge);
				indigo_safe_free(bridge->private_data);
				indigo_safe_free(bridge);
				bridge = NULL;
				indigo_queue_delete(&driver_queue);
				pthread_mutex_destroy(&bridge_mutex);
				last_action = INDIGO_DRIVER_SHUTDOWN;
				return INDIGO_FAILED;
			}
			bridge_restart_discovery(bridge, true);
			break;
		}
		case INDIGO_DRIVER_SHUTDOWN: {
			// The driver queue may be in the middle of a cycle, which takes seconds and publishes properties. SHUTDOWN can be called
			// from a bus callback (a client unloads the driver), where the bus is locked and a cycle that needs the bus can not finish:
			// waiting for it without a limit would hang the bus. The wait is therefore bounded, and the shutdown is refused if the
			// queue does not become free in time; the caller can ask again.
			if (!lock_driver_queue(SHUTDOWN_WAIT)) {
				INDIGO_DRIVER_ERROR(DRIVER_NAME, "Shutdown refused, discovery is in progress");
				return INDIGO_BUSY;
			}
			indigo_result shutdown_result = verify_devices_disconnected();
			if (shutdown_result == INDIGO_OK) {
				// stop the producers of driver queue tasks: from now on every task of the queue returns at once
				pthread_mutex_lock(&settings_mutex);
				shutting_down = true;
				discovery_generation++;
				pthread_mutex_unlock(&settings_mutex);
			}
			pthread_mutex_unlock(&driver_queue_mutex);
			if (shutdown_result != INDIGO_OK) {
				return shutdown_result;
			}
			last_action = action;
			indigo_queue_remove(driver_queue, NULL, NULL);
			indigo_queue_drain(driver_queue);
			remove_all_devices();
			indigo_detach_device(bridge);
			indigo_safe_free(bridge->private_data);
			indigo_safe_free(bridge);
			bridge = NULL;
			indigo_queue_delete(&driver_queue);
			pthread_mutex_destroy(&bridge_mutex);
			break;
		}
		case INDIGO_DRIVER_INFO:
			break;
	}
	return INDIGO_OK;
}
