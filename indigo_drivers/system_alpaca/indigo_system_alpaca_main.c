/** INDIGO ASCOM Alpaca client driver main
 \file indigo_system_alpaca_main.c
 */

#include <signal.h>

#include <indigo/indigo_driver_xml.h>

#include "indigo_system_alpaca.h"

int main(int argc, const char * argv[]) {
	indigo_main_argc = argc;
	indigo_main_argv = argv;
	// The driver writes to TCP sockets. Where a write to a socket closed by the peer raises SIGPIPE (Linux), the default action would
	// end the process; indigo_server ignores the signal for the same reason. The driver itself never touches the signal dispositions
	// of the process it is loaded into, so this is done only by the stand-alone executable.
#ifdef SIGPIPE
	signal(SIGPIPE, SIG_IGN);
#endif
	indigo_client *protocol_adapter = indigo_xml_device_adapter(indigo_stdin_handle, indigo_stdout_handle);
	indigo_start();
	indigo_system_alpaca(INDIGO_DRIVER_INIT, NULL);
	indigo_attach_client(protocol_adapter);
	indigo_xml_parse(NULL, protocol_adapter);
	indigo_system_alpaca(INDIGO_DRIVER_SHUTDOWN, NULL);
	indigo_stop();
	return 0;
}
