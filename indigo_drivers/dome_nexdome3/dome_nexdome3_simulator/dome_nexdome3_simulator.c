static command_source serial_source = { -1, "", 0, false, false, "serial" }, tcp_source = { -1, "", 0, false, false, "tcp" };
static char version[64] = "3.2.0", shutter_version[64] = "";
static double speed_factor = 1, position_interval = 0.25, battery_interval = 1, xb_transition = 1, xb_interval = 10, shutter_latency = 0, noise_interval = 0;
static rotator_config rotator, rotator_eeprom;
static shutter_config shutter, shutter_eeprom;
