static void event(const char *kind, const char *format, ...) {
	if (!events) {
		return;
	}
	fprintf(events, "%.6f %s ", serial_motion_time(), kind);
	va_list args;
	va_start(args, format);
	vfprintf(events, format, args);
	va_end(args);
	fputc('\n', events);
	fflush(events);
}

static void stop_signal(int signal) {
	(void)signal;
	running = 0;
}

static void rotator_defaults(void) {
	rotator.acceleration = 1500;
	rotator.dead_zone = 300;
	rotator.home = 0;
	rotator.range = 55080;
	rotator.velocity = 600;
}

static void shutter_defaults(void) {
	shutter.acceleration = 1500;
	shutter.range = 46000;
	shutter.velocity = 800;
}

static bool supports_gsr(void) {
	int major = 0, minor = 0;
	return sscanf(version, "%d.%d", &major, &minor) == 2 && (major > 3 || (major == 3 && minor >= 2));
}

// ---------------------------------------------------------------------------- output

static void write_text(int fd, const char *text) {
	if (fd >= 0) {
		serial_simulator_write_all(fd, text, strlen(text));
	}
}

static void write_line(int fd, const char *text, bool terminated) {
	char line[REPLY_SIZE + 2];
	snprintf(line, sizeof(line), "%s%s", text, terminated ? "\n" : "");
	write_text(fd, line);
}

// a reply goes to the source of the command
static void reply(const char *text) {
	event("TX", "%s", text);
	serial_simulator_trace_line(trace, "<-", text);
	write_line(reply_fd, text, newline);
}

// an event goes to every connected client; position reports are always LF terminated
static void notify(const char *format, ...) __attribute__((format(printf, 1, 2)));

static void notify(const char *format, ...) {
	char text[REPLY_SIZE];
	va_list args;
	va_start(args, format);
	vsnprintf(text, sizeof(text), format, args);
	va_end(args);
	if (!events_enabled) {
		return;
	}
	// notifications caused by a command follow its reply
	if (defer_events) {
		int written = snprintf(deferred_events + deferred_length, sizeof(deferred_events) - deferred_length, "%s\n", text);
		if (written > 0 && deferred_length + written < sizeof(deferred_events)) {
			deferred_length += written;
		}
		return;
	}
	event("EV", "%s", text);
	serial_simulator_trace_line(trace, "<=", text);
	bool terminated = newline || *text != ':';
	write_line(serial_fd, text, terminated);
	write_line(tcp_source.fd, text, terminated);
}

static void flush_events(void) {
	defer_events = false;
	char *line = deferred_events;
	deferred_events[deferred_length] = 0;
	for (char *end; (end = strchr(line, '\n')) != NULL; line = end + 1) {
		*end = 0;
		notify("%s", line);
	}
	deferred_length = 0;
}

// ---------------------------------------------------------------------------- rotator

static long normalize_steps(double steps) {
	long range = rotator.range > 0 ? rotator.range : 1;
	long result = lround(steps) % range;
	return result < 0 ? result + range : result;
}

static long rotator_position(void) {
	return normalize_steps(serial_motion_update(&rotation));
}

static void send_rotator_status(bool as_reply) {
	char text[REPLY_SIZE];
	long position = rotator_position();
	snprintf(text, sizeof(text), ":SER,%ld,%d,%ld,%ld,%ld#", position, position == rotator.home ? 1 : 0, rotator.range, rotator.home, rotator.dead_zone);
	if (as_reply) {
		reply(text);
	} else {
		notify("%s", text);
	}
}

static void stop_rotator(const char *origin, bool report) {
	if (rotator_state == ROTATOR_STOPPED) {
		return;
	}
	serial_motion_stop(&rotation);
	serial_motion_sync(&rotation, rotator_position());
	rotator_state = ROTATOR_STOPPED;
	event("STATE", "%s rotator stopped at=%ld", origin, rotator_position());
	if (report) {
		send_rotator_status(false);
	}
}

// moves to a step position; direction 0 selects the shortest way like the firmware
static void move_rotator(long requested, int direction, bool dead_zone, const char *origin) {
	long position = rotator_position(), range = rotator.range;
	requested = normalize_steps(requested);
	long delta = position - requested;
	if (direction == 0) {
		if (dead_zone && labs(delta) <= rotator.dead_zone) {
			event("STATE", "%s within dead zone position=%ld requested=%ld", origin, position, requested);
			return;
		}
		if (delta < 0) {
			direction = labs(delta) > range / 2 ? ROTATOR_LEFT : ROTATOR_RIGHT;
		} else {
			direction = labs(delta) > range / 2 ? ROTATOR_RIGHT : ROTATOR_LEFT;
		}
	}
	double target = direction == ROTATOR_RIGHT ? position + ((requested - position) % range + range) % range : position - ((position - requested) % range + range) % range;
	serial_motion_sync(&rotation, position);
	serial_motion_start(&rotation, target, rotator.velocity * speed_factor);
	event("MOVE", "%s rotator from=%ld to=%ld direction=%s", origin, position, requested, direction == ROTATOR_RIGHT ? "right" : "left");
	if (rotator_state != direction) {
		rotator_state = direction;
		notify(direction == ROTATOR_RIGHT ? ":right#" : ":left#");
	}
	rotator_report_time = serial_motion_time() + position_interval;
	if (rotation.duration == 0) {
		stop_rotator(origin, true);
	}
}

static void update_rotator(void) {
	if (rotator_state == ROTATOR_STOPPED) {
		return;
	}
	serial_motion_update(&rotation);
	if (rotation.duration == 0) {
		stop_rotator("arrived", true);
	} else if (serial_motion_time() >= rotator_report_time) {
		rotator_report_time += position_interval;
		notify("P%ld", rotator_position());
	}
}

// ---------------------------------------------------------------------------- shutter

static long shutter_position(void) {
	return lround(serial_motion_update(&shutter_motion));
}

static void send_shutter_status(bool as_reply) {
	char text[REPLY_SIZE];
	long position = shutter_position();
	snprintf(text, sizeof(text), ":SES,%ld,%ld,%d,%d#", position, shutter.range, position == shutter.range ? 1 : 0, position == 0 ? 1 : 0);
	if (as_reply) {
		reply(text);
	} else {
		notify("%s", text);
	}
}

static void stop_shutter(const char *origin) {
	shutter_start_time = -1;
	if (shutter_state == SHUTTER_STOPPED) {
		return;
	}
	serial_motion_stop(&shutter_motion);
	shutter_state = SHUTTER_STOPPED;
	event("STATE", "%s shutter stopped at=%ld", origin, shutter_position());
	send_shutter_status(false);
}

static void start_shutter(long target) {
	int state = target > shutter_position() ? SHUTTER_OPENING : SHUTTER_CLOSING;
	shutter_start_time = -1;
	serial_motion_start(&shutter_motion, target, shutter.velocity * speed_factor);
	event("MOVE", "shutter from=%ld to=%ld", lround(shutter_motion.origin), target);
	if (shutter_state != state) {
		shutter_state = state;
		notify(state == SHUTTER_OPENING ? ":open#" : ":close#");
	}
	shutter_report_time = serial_motion_time() + position_interval;
}

// an open or close request ignores a shutter that is already at the requested end
static void request_shutter(bool open, const char *origin) {
	long target = open ? shutter.range : 0;
	if ((shutter_state == SHUTTER_STOPPED && shutter_start_time < 0 && shutter_position() == target) || (shutter_state == (open ? SHUTTER_OPENING : SHUTTER_CLOSING))) {
		event("STATE", "%s shutter already %s", origin, open ? "open" : "closed");
		return;
	}
	if (shutter_latency > 0) {
		shutter_start_time = serial_motion_time() + shutter_latency;
		shutter_start_target = target;
		event("MOVE", "%s shutter to=%ld after=%.3f", origin, target, shutter_latency);
	} else {
		start_shutter(target);
	}
}

static void update_shutter(void) {
	if (shutter_start_time >= 0 && serial_motion_time() >= shutter_start_time) {
		start_shutter(shutter_start_target);
	}
	if (shutter_state == SHUTTER_STOPPED) {
		return;
	}
	serial_motion_update(&shutter_motion);
	if (shutter_motion.duration == 0) {
		shutter_state = SHUTTER_STOPPED;
		event("STATE", "shutter arrived at=%ld", shutter_position());
		send_shutter_status(false);
	} else if (serial_motion_time() >= shutter_report_time) {
		shutter_report_time += position_interval;
		notify("S%ld", shutter_position());
	}
}

static void set_rain(bool rain) {
	if (rain && !raining) {
		raining = true;
		event("STATE", "rain closes shutter");
		request_shutter(false, "rain");
	} else if (!rain && raining) {
		raining = false;
	}
}

// ---------------------------------------------------------------------------- periodic reports

static void update_reports(void) {
	double now = serial_motion_time();
	if (battery_report && battery_interval > 0 && now >= battery_time) {
		battery_time = now + battery_interval;
		notify(":BV%d#", battery_adu);
	}
	if (xb_state < 4 && now >= xb_time) {
		xb_state++;
		xb_time = now + (xb_state < 4 ? xb_transition : xb_interval);
		notify("XB->%s", xb_states[xb_state]);
	} else if (xb_state == 4 && xb_interval > 0 && now >= xb_time) {
		xb_time = now + xb_interval;
		notify("XB->%s", xb_states[xb_state]);
	}
	if (noise_interval > 0 && now >= noise_time) {
		noise_time = now + noise_interval;
		notify("Diagnostic: motor current %d mA", 120 + (int)fmod(now * 1000, 50));
	}
}

// ---------------------------------------------------------------------------- commands

static bool has_parameter(const char *command) {
	return strlen(command) > 4 && command[3] == ',';
}

static long parameter(const char *command) {
	return strtol(command + 4, NULL, 10);
}

// executes one command and returns the reply or NULL when the reply was already sent
static const char *execute(const char *command) {
	static char result[REPLY_SIZE];
	size_t length = strlen(command);
	if (length < 3) {
		event("REJECT", "short %s", command);
		return ":Err#";
	}
	snprintf(result, sizeof(result), ":%.3s#", command);
	char verb[4];
	snprintf(verb, sizeof(verb), "%.3s", command);
	if (!strcmp(command, "ARR")) {
		snprintf(result, sizeof(result), ":ARR%ld#", rotator.acceleration);
	} else if (!strcmp(command, "ARS")) {
		snprintf(result, sizeof(result), ":ARS%ld#", shutter.acceleration);
	} else if (!strcmp(verb, "AWR") || !strcmp(verb, "AWS")) {
		if (!has_parameter(command) || parameter(command) < 100) {
			event("REJECT", "%s", command);
			return ":Err#";
		}
		*(verb[2] == 'R' ? &rotator.acceleration : &shutter.acceleration) = parameter(command);
	} else if (!strcmp(command, "CLS")) {
		request_shutter(false, "command");
	} else if (!strcmp(command, "DRR")) {
		snprintf(result, sizeof(result), ":DRR%ld#", rotator.dead_zone);
	} else if (!strcmp(verb, "DWR")) {
		if (!has_parameter(command) || parameter(command) < 0 || parameter(command) > 10000) {
			event("REJECT", "%s", command);
			return ":Err#";
		}
		rotator.dead_zone = parameter(command);
	} else if (!strcmp(command, "FRR")) {
		snprintf(result, sizeof(result), ":FR%s#", version);
	} else if (!strcmp(command, "FRS")) {
		snprintf(result, sizeof(result), ":FR%s#", *shutter_version ? shutter_version : version);
	} else if (!strcmp(verb, "GAR")) {
		if (!has_parameter(command)) {
			event("REJECT", "%s", command);
			return ":Err#";
		}
		move_rotator((rotator.range / 360) * parameter(command), 0, true, "goto");
	} else if (!strcmp(verb, "GSR") && supports_gsr()) {
		if (!has_parameter(command)) {
			event("REJECT", "%s", command);
			return ":Err#";
		}
		move_rotator(parameter(command), 0, true, "goto");
	} else if (!strcmp(command, "GHR")) {
		if (rotator_state == ROTATOR_STOPPED && rotator_position() == rotator.home) {
			rotator_state = ROTATOR_RIGHT;
			notify(":right#");
			stop_rotator("home", true);
		} else {
			move_rotator(rotator.home, ROTATOR_RIGHT, false, "home");
		}
	} else if (!strcmp(command, "HRR")) {
		snprintf(result, sizeof(result), ":HRR%ld#", rotator.home);
	} else if (!strcmp(verb, "HWR")) {
		if (!has_parameter(command) || parameter(command) < 0 || parameter(command) > rotator.range) {
			event("REJECT", "%s", command);
			return ":Err#";
		}
		rotator.home = parameter(command);
	} else if (!strcmp(command, "OPS")) {
		request_shutter(true, "command");
	} else if (!strcmp(command, "PRR")) {
		snprintf(result, sizeof(result), ":PRR%ld#", rotator_position());
	} else if (!strcmp(command, "PRS")) {
		snprintf(result, sizeof(result), ":PRS%ld#", shutter_position());
	} else if (!strcmp(verb, "PWR")) {
		if (!has_parameter(command)) {
			event("REJECT", "%s", command);
			return ":Err#";
		}
		double offset = parameter(command) - serial_motion_update(&rotation);
		rotation.position += offset;
		rotation.origin += offset;
		rotation.target += offset;
		event("STATE", "rotator position=%ld", rotator_position());
	} else if (!strcmp(verb, "PWS")) {
		if (!has_parameter(command)) {
			event("REJECT", "%s", command);
			return ":Err#";
		}
		serial_motion_sync(&shutter_motion, parameter(command));
	} else if (!strcmp(command, "RRR")) {
		snprintf(result, sizeof(result), ":RRR%ld#", rotator.range);
	} else if (!strcmp(command, "RRS")) {
		snprintf(result, sizeof(result), ":RRS%ld#", shutter.range);
	} else if (!strcmp(verb, "RWR") || !strcmp(verb, "RWS")) {
		if (!has_parameter(command)) {
			event("REJECT", "%s", command);
			return ":Err#";
		}
		*(verb[2] == 'R' ? &rotator.range : &shutter.range) = parameter(command);
	} else if (!strcmp(command, "SRR")) {
		send_rotator_status(true);
		return NULL;
	} else if (!strcmp(command, "SRS")) {
		send_shutter_status(true);
		return NULL;
	} else if (!strcmp(command, "SWR")) {
		stop_rotator("abort", true);
	} else if (!strcmp(command, "SWS")) {
		stop_shutter("abort");
	} else if (!strcmp(command, "VRR")) {
		snprintf(result, sizeof(result), ":VRR%ld#", rotator.velocity);
	} else if (!strcmp(command, "VRS")) {
		snprintf(result, sizeof(result), ":VRS%ld#", shutter.velocity);
	} else if (!strcmp(verb, "VWR") || !strcmp(verb, "VWS")) {
		if (!has_parameter(command) || parameter(command) < 32) {
			event("REJECT", "%s", command);
			return ":Err#";
		}
		*(verb[2] == 'R' ? &rotator.velocity : &shutter.velocity) = parameter(command);
	} else if (!strcmp(command, "ZDR")) {
		rotator_defaults();
	} else if (!strcmp(command, "ZDS")) {
		shutter_defaults();
	} else if (!strcmp(command, "ZRR")) {
		if (rotator_eeprom.valid) {
			rotator = rotator_eeprom;
		} else {
			rotator_defaults();
		}
	} else if (!strcmp(command, "ZRS")) {
		if (shutter_eeprom.valid) {
			shutter = shutter_eeprom;
		} else {
			shutter_defaults();
		}
	} else if (!strcmp(command, "ZWR")) {
		rotator_eeprom = rotator;
		rotator_eeprom.valid = true;
		event("STATE", "rotator settings saved");
	} else if (!strcmp(command, "ZWS")) {
		shutter_eeprom = shutter;
		shutter_eeprom.valid = true;
		event("STATE", "shutter settings saved");
	} else if (!strcmp(verb, "wbv")) {
		if (!has_parameter(command)) {
			return ":Err#";
		}
		battery_adu = (int)parameter(command);
	} else if (!strcmp(command, "StartRain")) {
		set_rain(true);
		return ":Rain#";
	} else if (!strcmp(command, "StopRain")) {
		set_rain(false);
		return ":RainStopped#";
	} else if (!strcmp(command, "EnaBatStatus")) {
		battery_report = true;
		return "BateryStatusEnabled";
	} else if (!strcmp(command, "DisBatStatus")) {
		battery_report = false;
		return "BateryStatusDisabled";
	} else if (!strcmp(command, "XBReset")) {
		xb_state = 0;
		xb_time = serial_motion_time() + xb_transition;
		return "XB->Start";
	} else if (!strcmp(command, "DeleteEEPROM")) {
		rotator_eeprom.valid = shutter_eeprom.valid = false;
		return "EEPROMisClear";
	} else {
		event("REJECT", "unknown %s", command);
		return ":Err#";
	}
	return result;
}

static bool fault(const char *command, char *action, char *argument) {
	if (!fault_file) {
		return false;
	}
	FILE *file = fopen(fault_file, "r");
	if (!file) {
		return false;
	}
	char line[256] = "", prefix[64] = "";
	int count = 1, consumed = 0;
	bool read = fgets(line, sizeof(line), file) != NULL;
	fclose(file);
	if (!read || sscanf(line, "%15s %d %127s %n", action, &count, argument, &consumed) < 3) {
		return false;
	}
	snprintf(prefix, sizeof(prefix), "%s", line + consumed);
	prefix[strcspn(prefix, "\n")] = 0;
	if (strcmp(prefix, "ANY") && strncmp(command, prefix, strlen(prefix))) {
		return false;
	}
	if (--count <= 0) {
		unlink(fault_file);
	} else {
		char temporary[PATH_MAX];
		snprintf(temporary, sizeof(temporary), "%s.sim", fault_file);
		file = fopen(temporary, "w");
		if (file) {
			fprintf(file, "%s %d %s %s\n", action, count, argument, prefix);
			fclose(file);
			rename(temporary, fault_file);
		}
	}
	for (char *c = argument; *c; c++) {
		*c = *c == '_' ? ' ' : *c;
	}
	event("FAULT", "%s %s", command, action);
	return true;
}

static void dispatch(const char *command) {
	char action[16], argument[128];
	event("RX", "%s", command);
	serial_simulator_trace_line(trace, "->", command);
	defer_events = true;
	if (fault(command, action, argument)) {
		if (!strcmp(action, "close")) {
			running = 0;
		} else if (!strcmp(action, "raw")) {
			event("TX", "%s", argument);
			write_text(reply_fd, argument);
		} else if (!strcmp(action, "error")) {
			event("REJECT", "injected %s", command);
			reply(":Err#");
		} else if (strcmp(action, "lost")) {
			if (!strcmp(action, "slow")) {
				usleep((useconds_t)(atoi(argument) > 0 ? atoi(argument) : 1000) * 1000);
			}
			const char *result = execute(command);
			if (!strcmp(action, "reply")) {
				reply(argument);
			} else if (result && strcmp(action, "mute")) {
				reply(result);
			}
		}
	} else {
		const char *result = execute(command);
		if (result) {
			reply(result);
		}
	}
	flush_events();
}

// ---------------------------------------------------------------------------- external control

static void apply_control(void) {
	if (!control_file) {
		return;
	}
	FILE *file = fopen(control_file, "r");
	if (!file) {
		return;
	}
	char key[32], value[256];
	while (fscanf(file, "%31s %255s", key, value) == 2) {
		for (char *c = value; *c; c++) {
			*c = *c == '_' ? ' ' : *c;
		}
		update_rotator();
		update_shutter();
		event("CONTROL", "%s %s", key, value);
		if (!strcmp(key, "azimuth")) {
			stop_rotator("control", false);
			serial_motion_sync(&rotation, normalize_steps((rotator.range / 360.0) * atof(value)));
		} else if (!strcmp(key, "position")) {
			stop_rotator("control", false);
			serial_motion_sync(&rotation, atol(value));
		} else if (!strcmp(key, "rotate")) {
			// a rotation not requested by the driver, for example by the toggle switch
			move_rotator((long)((rotator.range / 360.0) * atof(value)), 0, false, "control");
		} else if (!strcmp(key, "stall")) {
			stop_rotator("stall", true);
		} else if (!strcmp(key, "freeze")) {
			stop_rotator("freeze", false);
		} else if (!strcmp(key, "shutter")) {
			shutter_start_time = -1;
			shutter_state = SHUTTER_STOPPED;
			serial_motion_sync(&shutter_motion, !strcmp(value, "open") ? shutter.range : !strcmp(value, "closed") ? 0 : atol(value));
		} else if (!strcmp(key, "shuttermove")) {
			request_shutter(!strcmp(value, "open"), "control");
		} else if (!strcmp(key, "shutterstall")) {
			stop_shutter("stall");
		} else if (!strcmp(key, "rain")) {
			bool rain = atoi(value) != 0;
			if (rain && !raining) {
				notify(":Rain#");
			} else if (!rain && raining) {
				notify(":RainStopped#");
			}
			set_rain(rain);
		} else if (!strcmp(key, "battery")) {
			battery_adu = atoi(value);
		} else if (!strcmp(key, "batteryreport")) {
			battery_report = atoi(value) != 0;
		} else if (!strcmp(key, "xb")) {
			notify("XB->%s", value);
		} else if (!strcmp(key, "emit")) {
			bool enabled = events_enabled;
			events_enabled = true;
			notify("%s", value);
			events_enabled = enabled;
		} else if (!strcmp(key, "emitraw")) {
			event("EV", "%s", value);
			write_text(serial_fd, value);
			write_text(tcp_source.fd, value);
		} else if (!strcmp(key, "home")) {
			rotator.home = atol(value);
		} else if (!strcmp(key, "range")) {
			rotator.range = atol(value);
		} else if (!strcmp(key, "deadzone")) {
			rotator.dead_zone = atol(value);
		} else if (!strcmp(key, "version")) {
			snprintf(version, sizeof(version), "%s", value);
		} else if (!strcmp(key, "latency")) {
			shutter_latency = atof(value);
		} else if (!strcmp(key, "events")) {
			events_enabled = atoi(value) != 0;
		} else if (!strcmp(key, "noise")) {
			noise_interval = atof(value);
			noise_time = serial_motion_time();
		} else if (!strcmp(key, "drop") && tcp_source.fd >= 0) {
			close(tcp_source.fd);
			tcp_source.fd = -1;
			tcp_source.used = 0;
			event("STATE", "tcp client dropped");
		}
	}
	fclose(file);
	unlink(control_file);
}

