static bool parse_arguments(int argc, char **argv) {
	rotator_defaults();
	shutter_defaults();
	for (int i = 1; i < argc; i++) {
		if (!strcmp(argv[i], "--headless")) {
			headless = true;
		} else if (!strcmp(argv[i], "--trace")) {
			trace = true;
		} else if (!strcmp(argv[i], "--no-newline")) {
			newline = false;
		} else if (!strcmp(argv[i], "--rain")) {
			raining = true;
		} else if (!strcmp(argv[i], "--xb-online")) {
			xb_state = 4;
		} else if (!strcmp(argv[i], "--no-battery-report")) {
			battery_report = false;
		} else if (i + 1 < argc && !strcmp(argv[i], "--ready-file")) {
			ready_file = argv[++i];
		} else if (i + 1 < argc && !strcmp(argv[i], "--azimuth")) {
			serial_motion_sync(&rotation, lround((rotator.range / 360.0) * atof(argv[++i])));
		} else if (i + 1 < argc && !strcmp(argv[i], "--position")) {
			serial_motion_sync(&rotation, atol(argv[++i]));
		} else if (i + 1 < argc && !strcmp(argv[i], "--shutter")) {
			i++;
			serial_motion_sync(&shutter_motion, !strcmp(argv[i], "open") ? shutter.range : !strcmp(argv[i], "closed") ? 0 : atol(argv[i]));
		} else if (i + 1 < argc && !strcmp(argv[i], "--home")) {
			rotator.home = atol(argv[++i]);
		} else if (i + 1 < argc && !strcmp(argv[i], "--range")) {
			rotator.range = atol(argv[++i]);
		} else if (i + 1 < argc && !strcmp(argv[i], "--dead-zone")) {
			rotator.dead_zone = atol(argv[++i]);
		} else if (i + 1 < argc && !strcmp(argv[i], "--battery")) {
			battery_adu = atoi(argv[++i]);
		} else if (i + 1 < argc && !strcmp(argv[i], "--version")) {
			snprintf(version, sizeof(version), "%s", argv[++i]);
		} else if (i + 1 < argc && !strcmp(argv[i], "--shutter-version")) {
			snprintf(shutter_version, sizeof(shutter_version), "%s", argv[++i]);
		} else if (i + 1 < argc && !strcmp(argv[i], "--speed-factor")) {
			speed_factor = atof(argv[++i]);
		} else if (i + 1 < argc && !strcmp(argv[i], "--position-interval")) {
			position_interval = atof(argv[++i]);
		} else if (i + 1 < argc && !strcmp(argv[i], "--battery-interval")) {
			battery_interval = atof(argv[++i]);
		} else if (i + 1 < argc && !strcmp(argv[i], "--xb-transition")) {
			xb_transition = atof(argv[++i]);
		} else if (i + 1 < argc && !strcmp(argv[i], "--xb-interval")) {
			xb_interval = atof(argv[++i]);
		} else if (i + 1 < argc && !strcmp(argv[i], "--shutter-latency")) {
			shutter_latency = atof(argv[++i]);
		} else if (i + 1 < argc && !strcmp(argv[i], "--noise-interval")) {
			noise_interval = atof(argv[++i]);
		} else if (i + 1 < argc && !strcmp(argv[i], "--tcp-port")) {
			tcp_port = atoi(argv[++i]);
		} else if (!strcmp(argv[i], "--help") || !strcmp(argv[i], "-h")) {
			printf("Usage: %s [--headless] [--trace] [--ready-file PATH] [--version SEMVER] [--shutter-version SEMVER] [--azimuth DEG | --position STEPS] [--home STEPS] [--range STEPS] [--dead-zone STEPS] [--shutter open|closed|STEPS] [--battery ADU] [--no-battery-report] [--rain] [--xb-online] [--no-newline] [--speed-factor X] [--position-interval S] [--battery-interval S] [--xb-transition S] [--xb-interval S] [--shutter-latency S] [--noise-interval S] [--tcp-port PORT]\n", argv[0]);
			exit(0);
		} else {
			fprintf(stderr, "Unknown/incomplete option '%s'\n", argv[i]);
			return false;
		}
	}
	if (speed_factor <= 0 || position_interval <= 0 || battery_interval < 0 || xb_transition < 0 || xb_interval < 0 || shutter_latency < 0 || noise_interval < 0 || rotator.range <= 0) {
		fprintf(stderr, "Invalid rates or range\n");
		return false;
	}
	serial_motion_sync(&rotation, normalize_steps(rotation.position));
	return true;
}

static bool open_tcp_listener(void) {
	struct sockaddr_in address = { 0 };
	int reuse = 1;
	socklen_t length = sizeof(address);
	tcp_listen_fd = socket(AF_INET, SOCK_STREAM, 0);
	if (tcp_listen_fd < 0) {
		perror("socket");
		return false;
	}
	setsockopt(tcp_listen_fd, SOL_SOCKET, SO_REUSEADDR, &reuse, sizeof(reuse));
	address.sin_family = AF_INET;
	address.sin_addr.s_addr = htonl(INADDR_LOOPBACK);
	address.sin_port = htons(tcp_port);
	if (bind(tcp_listen_fd, (struct sockaddr *)&address, sizeof(address)) < 0 || listen(tcp_listen_fd, 1) < 0 || getsockname(tcp_listen_fd, (struct sockaddr *)&address, &length) < 0) {
		perror("tcp listener");
		close(tcp_listen_fd);
		tcp_listen_fd = -1;
		return false;
	}
	tcp_port = ntohs(address.sin_port);
	return true;
}

static bool write_ready_file(const char *port) {
	if (tcp_listen_fd < 0) {
		return serial_simulator_write_ready_file(ready_file, "dome_nexdome3_simulator", port);
	}
	char temporary[PATH_MAX];
	snprintf(temporary, sizeof(temporary), "%s.tmp.%ld", ready_file, (long)getpid());
	FILE *file = fopen(temporary, "w");
	if (file == NULL) {
		perror("fopen ready file");
		return false;
	}
	fprintf(file, "INDIGO_SIMULATOR=dome_nexdome3_simulator\n");
	fprintf(file, "INDIGO_SIMULATOR_PORT=%s\n", port);
	fprintf(file, "INDIGO_SIMULATOR_TCP_URL=tcp://127.0.0.1:%d\n", tcp_port);
	fprintf(file, "INDIGO_SIMULATOR_PID=%ld\n", (long)getpid());
	if (fclose(file) != 0 || rename(temporary, ready_file) != 0) {
		perror("ready file");
		unlink(temporary);
		return false;
	}
	return true;
}

// reads the available bytes of a source and dispatches complete commands; returns false when the source is closed
static bool read_source(command_source *source) {
	char buffer[256];
	ssize_t count = read(source->fd, buffer, sizeof(buffer));
	if (count == 0 || (count < 0 && errno != EAGAIN && errno != EINTR && errno != EIO)) {
		return source == &serial_source;
	}
	if (count < 0) {
		usleep(1000);
		return true;
	}
	for (ssize_t i = 0; i < count; i++) {
		char byte = buffer[i];
		if (byte == '@') {
			// the start character clears the receive buffer
			source->started = true;
			source->overflow = false;
			source->used = 0;
		} else if (!source->started) {
			continue;
		} else if (byte == '\n' || byte == '\r') {
			source->started = false;
			reply_fd = source->fd;
			if (source->overflow || source->used == 0) {
				event("RX", "%.*s", source->used, source->command);
				event("REJECT", "%s command %s", source->name, source->overflow ? "too long" : "empty");
				reply(":Err#");
			} else {
				source->command[source->used] = 0;
				dispatch(source->command);
			}
			source->used = 0;
		} else if (source->used < COMMAND_LENGTH) {
			source->command[source->used++] = byte;
		} else {
			source->overflow = true;
		}
	}
	return true;
}

int main(int argc, char **argv) {
	if (!parse_arguments(argc, argv)) {
		return 1;
	}
	fault_file = getenv("INDIGO_NEXDOME3_FAULT");
	control_file = getenv("INDIGO_NEXDOME3_CONTROL");
	const char *event_file = getenv("INDIGO_NEXDOME3_EVENTS");
	events = event_file ? fopen(event_file, "a") : NULL;
	signal(SIGTERM, stop_signal);
	signal(SIGINT, stop_signal);
	signal(SIGPIPE, SIG_IGN);
	char port[PATH_MAX];
	serial_fd = serial_simulator_open_pty(port, sizeof(port));
	if (serial_fd < 0 || (tcp_port >= 0 && !open_tcp_listener()) || (ready_file && !write_ready_file(port))) {
		return 1;
	}
	serial_source.fd = serial_fd;
	double now = serial_motion_time();
	battery_time = now + battery_interval;
	xb_time = now + (xb_state < 4 ? xb_transition : xb_interval);
	noise_time = now + noise_interval;
	event("OPEN", "version=%s position=%ld home=%ld range=%ld dead_zone=%ld shutter=%ld rain=%d tcp_port=%d", version, rotator_position(), rotator.home, rotator.range, rotator.dead_zone, shutter_position(), raining, tcp_port);
	if (!headless) {
		printf("NexDome 3 simulator is listening on %s\n", port);
		if (tcp_listen_fd >= 0) {
			printf("NexDome 3 simulator is listening on tcp://127.0.0.1:%d\n", tcp_port);
		}
		fflush(stdout);
	}
	while (running) {
		apply_control();
		update_rotator();
		update_shutter();
		update_reports();
		fd_set fds;
		FD_ZERO(&fds);
		FD_SET(serial_fd, &fds);
		int max_fd = serial_fd;
		if (tcp_source.fd >= 0) {
			FD_SET(tcp_source.fd, &fds);
			max_fd = tcp_source.fd > max_fd ? tcp_source.fd : max_fd;
		}
		if (tcp_listen_fd >= 0) {
			FD_SET(tcp_listen_fd, &fds);
			max_fd = tcp_listen_fd > max_fd ? tcp_listen_fd : max_fd;
		}
		struct timeval timeout = { 0, 10000 };
		if (select(max_fd + 1, &fds, NULL, NULL, &timeout) <= 0) {
			continue;
		}
		if (tcp_listen_fd >= 0 && FD_ISSET(tcp_listen_fd, &fds)) {
			int client = accept(tcp_listen_fd, NULL, NULL);
			if (client >= 0) {
				if (tcp_source.fd >= 0) {
					close(tcp_source.fd);
				}
				tcp_source.fd = client;
				tcp_source.used = 0;
				tcp_source.started = false;
				event("STATE", "tcp client connected");
			}
		}
		if (tcp_source.fd >= 0 && FD_ISSET(tcp_source.fd, &fds) && !read_source(&tcp_source)) {
			event("STATE", "tcp client closed");
			close(tcp_source.fd);
			tcp_source.fd = -1;
			tcp_source.used = 0;
		}
		if (FD_ISSET(serial_fd, &fds)) {
			read_source(&serial_source);
		}
	}
	event("STATE", "position=%ld shutter=%ld", rotator_position(), shutter_position());
	event("CLOSE", "simulator");
	if (tcp_source.fd >= 0) {
		close(tcp_source.fd);
	}
	if (tcp_listen_fd >= 0) {
		close(tcp_listen_fd);
	}
	close(serial_fd);
	if (events) {
		fclose(events);
	}
	return 0;
}
