static int rotator_state = ROTATOR_STOPPED, shutter_state = SHUTTER_STOPPED, xb_state;
static double rotator_report_time, shutter_report_time, battery_time, xb_time, noise_time, shutter_start_time = -1;
static long shutter_start_target;
static int battery_adu = 1000;
static bool battery_report = true, raining;

