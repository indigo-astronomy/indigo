// Code is generated by AI

// Protocol (Documents/Firmware-Protocol.md, Documents/email_communication.txt
// and dome_nexdome3_simulator.ino, NexDome firmware 3.x by Tim Long):
// a command is "@<verb><target>[,<parameter>]" terminated by CR or LF; "@"
// restarts the command, an empty, too short (< 3) or too long (> 30 characters)
// command and an unknown or invalid command are answered ":Err#". Replies are
// ":<verb><target>#" echoes or value replies (":ARR1500#", ":FR3.2.0#",
// ":SER,p,a,c,h,d#", ":SES,p,l,o,c#") followed by an undocumented LF.
// Events are sent at any time but never inside a reply: "P<steps>" and
// "S<steps>" (LF terminated) while a motor moves, ":left#", ":right#", ":open#",
// ":close#" before motion, ":SER"/":SES" when a motor stops, ":BV<adu>#",
// "XB-><state>" (Start, WaitAT, Config, Detect, Online; Online repeated),
// ":Rain#" and ":RainStopped#".
// Implemented commands: AR/AW (R, S), CLS, DRR/DWR, FRR/FRS, GAR, GSR (3.2 and
// later), GHR, HRR/HWR, OPS, PR/PW (R, S), RR/RW (R, S), SR/SW (R, S), VR/VW
// (R, S), ZD/ZR/ZW (R, S) and the simulator commands wbv, StartRain, StopRain,
// EnaBatStatus, DisBatStatus, XBReset and DeleteEEPROM.
// Simulator assumptions (undocumented or taken from the .ino): motors move
// linearly at velocity * --speed-factor steps per second without acceleration,
// GAR converts with (circumference / 360) * degrees in integers, a goto within
// the dead zone does not move, rotation takes the shortest way, GHR turns
// clockwise to the home position (":right#" and ":SER" at once when already at
// home), the home sensor is active exactly at the home position, the shutter
// switches are active exactly at the end positions, StartRain and a rain event
// close the shutter, and the shutter starts its motion after --shutter-latency.
//
// Test hooks (all optional, named by environment variables):
//   INDIGO_NEXDOME3_EVENTS   event log: "<time> RX|TX|EV|STATE|MOVE|FAULT|CONTROL|REJECT|OPEN|CLOSE <text>"
//                            (TX is a reply, EV an asynchronous notification)
//   INDIGO_NEXDOME3_FAULT    "<lost|error|reply|mute|raw|slow|close> <count> <argument|-> <command prefix|ANY>"
//                            lost: not executed, no reply; error: ":Err#" without executing;
//                            reply: executed, replaced reply; mute: executed, no reply;
//                            raw: argument written without terminator; '_' in an argument is a space
//   INDIGO_NEXDOME3_CONTROL  lines "<key> <value>": azimuth, position, rotate, stall, freeze, shutter,
//                            shuttermove, shutterstall, rain, battery, batteryreport, xb, emit, emitraw,
//                            home, range, deadzone, version, latency, events, noise, drop
// With --tcp-port the same protocol is also served to one TCP client on
// 127.0.0.1 (0 selects a free port); the ready file then contains
// INDIGO_SIMULATOR_TCP_URL. The "drop" control closes that client connection.

