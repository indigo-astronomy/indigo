// Code is generated by AI

// Protocol: fixed-length 9-byte ASCII frames without terminator in both
// directions. Behaviour follows dome_baader_simulator.ino (the Arduino
// simulator of the driver author): d#ser_num, d#getazim ("d#azi%04d" in
// tenths of degree, old firmware "d#azr%04d" when stopped), d#aziNNNN (shortest
// rotation, same direction rule as the sketch), d#stopdom (stops rotation and
// aborts a moving shutter and flap), d#getshut ("d#shutope", "d#shutclo",
// "d#shut_NN", old firmware "d#shutrun"), d#opeshut/d#closhut (a reverse
// request aborts a moving shutter), d#mvshtNN, d#getflap ("d#flapope",
// "d#flapclo", "d#flaprop", "d#flaprcl", "d#flaprim", old firmware
// "d#flaprun"), d#opeflap/d#cloflap ("d#err_sht" below 5 % shutter), d#opefull,
// d#get_eme ("d#emeRWTP"), d#chk_aon ("d#automod"), d#EMERWTP (sketch
// simulator command). Unknown commands answer "d#comerro".
// Simulator assumptions (undocumented): azimuth arguments must be four digits
// 0000..3600, a moving shutter reports 01..99, rotation, shutter and flap move
// linearly with configurable rates, and a newly raised emergency flag makes the
// controller perform an emergency close (rotation stops, flap and shutter close).
//
// Test hooks (all optional, named by environment variables):
//   INDIGO_BAADER_EVENTS   event log: "<time> RX|TX|STATE|MOVE|FAULT|CONTROL|REJECT|OPEN|CLOSE <text>"
//   INDIGO_BAADER_FAULT    "<command prefix without d#|ANY> <silent|error|domerro|partial|slow|close|reply> [count] [argument]"
//   INDIGO_BAADER_CONTROL  lines "<azimuth|rotate|shutter|flap|eme|serial|drop> <value>"
// With --tcp-port the same protocol is also served to one TCP client on
// 127.0.0.1 (0 selects a free port); the ready file then contains
// INDIGO_SIMULATOR_TCP_URL. The "drop" control closes that client connection.

#include <arpa/inet.h>
#include <errno.h>
#include <limits.h>
#include <math.h>
#include <signal.h>
#include <stdarg.h>
#include <stdbool.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <netinet/in.h>
#include <sys/select.h>
#include <sys/socket.h>
#include <unistd.h>

#include "../../../indigo_test/simulator_common/serial_motion.h"
#include "../../../indigo_test/simulator_common/serial_simulator_common.h"

#define FRAME 9

typedef struct {
	int fd;
	char request[FRAME + 1];
	size_t used;
	double last_byte;
	const char *name;
} frame_source;

static const char *ready_file, *fault_file, *control_file;
static FILE *events;
static bool trace, headless, old_firmware;
static volatile sig_atomic_t running = 1;
static int serial_fd = -1, reply_fd = -1, tcp_listen_fd = -1, tcp_port = -1;
static frame_source serial_source = { -1, "", 0, 0, "serial" }, tcp_source = { -1, "", 0, 0, "tcp" };
static char serial_number[FRAME] = "3141592";
static double rotation_speed = 5, shutter_time = 20, flap_time = 20;
static int emergency[4];
static serial_motion rotation, shutter, flap;

static void event(const char *kind, const char *format, ...) __attribute__((format(printf, 2, 3)));

static void event(const char *kind, const char *format, ...) {
	if (!events) {
		return;
	}
	fprintf(events, "%.6f %s ", serial_motion_time(), kind);
	va_list args;
	va_start(args, format);
	vfprintf(events, format, args);
	va_end(args);
	fputc('\n', events);
	fflush(events);
}

static void stop_signal(int signal) {
	(void)signal;
	running = 0;
}

static bool moving(serial_motion *motion) {
	serial_motion_update(motion);
	return motion->duration > 0;
}

static int azimuth(void) {
	long tenths = lround(serial_motion_update(&rotation));
	return (int)((tenths % 3600 + 3600) % 3600);
}

static int shutter_position(void) {
	return (int)floor(serial_motion_update(&shutter) + 1e-9);
}

static void write_frame(const char *text, size_t length) {
	char buffer[FRAME + 1];
	snprintf(buffer, sizeof(buffer), "%.*s", (int)length, text);
	event("TX", "%s", buffer);
	serial_simulator_trace_line(trace, "<-", buffer);
	serial_simulator_write_all(reply_fd, buffer, length);
}

static void rotate_to(int target, const char *origin) {
	int current = azimuth();
	int delta = target % 3600 - current;
	// direction rule of dome_baader_simulator.ino
	if (delta > 0 && delta > 1800) {
		delta -= 3600;
	} else if (delta < 0 && -delta > 1800) {
		delta += 3600;
	}
	serial_motion_sync(&rotation, current);
	serial_motion_start(&rotation, current + delta, rotation_speed * 10);
	event("MOVE", "%s rotation from=%d to=%d delta=%d", origin, current, target % 3600, delta);
}

static void shutter_to(double target) {
	serial_motion_start(&shutter, target, 100 / shutter_time);
	event("MOVE", "shutter from=%d to=%d", (int)shutter.origin, (int)target);
}

static void flap_to(double target) {
	serial_motion_start(&flap, target, 100 / flap_time);
	event("MOVE", "flap from=%d to=%d", (int)flap.origin, (int)target);
}

static void stop_motion(serial_motion *motion, const char *name) {
	if (moving(motion)) {
		serial_motion_stop(motion);
		event("STATE", "%s stopped at=%d", name, (int)lround(motion->position));
	}
}

static void open_shutter(void) {
	if (moving(&shutter) && shutter.target < shutter.origin) {
		stop_motion(&shutter, "shutter");
	} else {
		shutter_to(100);
	}
}

static void close_shutter(void) {
	if (moving(&shutter) && shutter.target > shutter.origin) {
		stop_motion(&shutter, "shutter");
	} else {
		shutter_to(0);
	}
}

static void open_flap(void) {
	if (moving(&flap) && flap.target < flap.origin) {
		stop_motion(&flap, "flap");
	} else {
		flap_to(100);
	}
}

static void close_flap(void) {
	if (moving(&flap) && flap.target > flap.origin) {
		stop_motion(&flap, "flap");
	} else {
		flap_to(0);
	}
}

static void set_emergency(const int flags[4], const char *origin) {
	bool raised = false;
	for (int i = 0; i < 4; i++) {
		raised |= flags[i] && !emergency[i];
		emergency[i] = flags[i];
	}
	event("STATE", "%s emergency=%d%d%d%d", origin, emergency[0], emergency[1], emergency[2], emergency[3]);
	if (raised) {
		stop_motion(&rotation, "rotation");
		flap_to(0);
		shutter_to(0);
		event("STATE", "emergency close");
	}
}

static bool parse_digits(const char *text, int length, int *value) {
	int result = 0;
	for (int i = 0; i < length; i++) {
		if (text[i] < '0' || text[i] > '9') {
			return false;
		}
		result = result * 10 + text[i] - '0';
	}
	*value = result;
	return true;
}

static void execute(const char *request, char *reply) {
	int value;
	strcpy(reply, "d#gotmess");
	if (!strcmp(request, "d#ser_num")) {
		snprintf(reply, FRAME + 1, "d#%s", serial_number);
	} else if (!strcmp(request, "d#getazim")) {
		snprintf(reply, FRAME + 1, "d#az%c%04d", old_firmware && !moving(&rotation) ? 'r' : 'i', azimuth());
	} else if (!strncmp(request, "d#azi", 5)) {
		if (!parse_digits(request + 5, 4, &value) || value > 3600) {
			event("REJECT", "azimuth %s", request);
			strcpy(reply, "d#comerro");
		} else {
			rotate_to(value, "command");
		}
	} else if (!strcmp(request, "d#stopdom")) {
		stop_motion(&rotation, "rotation");
		stop_motion(&shutter, "shutter");
		stop_motion(&flap, "flap");
	} else if (!strcmp(request, "d#getshut")) {
		int position = shutter_position();
		if (!moving(&shutter) && position >= 100) {
			strcpy(reply, "d#shutope");
		} else if (!moving(&shutter) && position <= 0) {
			strcpy(reply, "d#shutclo");
		} else if (old_firmware) {
			strcpy(reply, "d#shutrun");
		} else {
			snprintf(reply, FRAME + 1, "d#shut_%02d", position < 1 ? 1 : position > 99 ? 99 : position);
		}
	} else if (!strcmp(request, "d#opeshut")) {
		open_shutter();
	} else if (!strcmp(request, "d#closhut")) {
		close_shutter();
	} else if (!strncmp(request, "d#mvsht", 7) && parse_digits(request + 7, 2, &value)) {
		shutter_to(value);
	} else if (!strcmp(request, "d#getflap")) {
		double position = serial_motion_update(&flap);
		if (moving(&flap)) {
			strcpy(reply, old_firmware ? "d#flaprun" : flap.target > flap.origin ? "d#flaprop" : "d#flaprcl");
		} else if (position >= 100) {
			strcpy(reply, "d#flapope");
		} else if (position <= 0) {
			strcpy(reply, "d#flapclo");
		} else {
			strcpy(reply, old_firmware ? "d#flaprun" : "d#flaprim");
		}
	} else if (!strcmp(request, "d#opeflap") || !strcmp(request, "d#cloflap")) {
		if (shutter_position() < 5) {
			event("REJECT", "flap with shutter=%d", shutter_position());
			strcpy(reply, "d#err_sht");
		} else if (request[2] == 'o') {
			open_flap();
		} else {
			close_flap();
		}
	} else if (!strcmp(request, "d#opefull")) {
		open_shutter();
		open_flap();
	} else if (!strcmp(request, "d#get_eme")) {
		snprintf(reply, FRAME + 1, "d#eme%d%d%d%d", emergency[0], emergency[1], emergency[2], emergency[3]);
	} else if (!strcmp(request, "d#chk_aon")) {
		strcpy(reply, "d#automod");
	} else if (!strncmp(request, "d#EME", 5)) {
		int flags[4];
		for (int i = 0; i < 4; i++) {
			flags[i] = request[5 + i] > '0' && request[5 + i] <= '9';
		}
		set_emergency(flags, "command");
	} else {
		event("REJECT", "unsupported %s", request);
		strcpy(reply, "d#comerro");
	}
}

static bool fault(const char *request, char *action, int *argument, char *text) {
	if (!fault_file) {
		return false;
	}
	FILE *file = fopen(fault_file, "r");
	if (!file) {
		return false;
	}
	char command[16] = "";
	int count = 1;
	*text = 0;
	*argument = 0;
	int fields = fscanf(file, "%15s %15s %d %15s", command, action, &count, text);
	fclose(file);
	if (fields < 2 || (strcmp(command, "ANY") && strncmp(request + 2, command, strlen(command)))) {
		return false;
	}
	if (--count <= 0) {
		unlink(fault_file);
	} else {
		char temporary[PATH_MAX];
		snprintf(temporary, sizeof(temporary), "%s.sim", fault_file);
		file = fopen(temporary, "w");
		if (file) {
			fprintf(file, "%s %s %d %s\n", command, action, count, text);
			fclose(file);
			rename(temporary, fault_file);
		}
	}
	*argument = atoi(text);
	event("FAULT", "%s %s", request, action);
	return true;
}

static void dispatch(const char *request) {
	char reply[FRAME + 1], action[16], text[16];
	int argument;
	event("RX", "%s", request);
	serial_simulator_trace_line(trace, "->", request);
	if (fault(request, action, &argument, text)) {
		if (!strcmp(action, "silent")) {
			return;
		} else if (!strcmp(action, "error")) {
			write_frame("d#comerro", FRAME);
			return;
		} else if (!strcmp(action, "domerro")) {
			write_frame("d#domerro", FRAME);
			return;
		} else if (!strcmp(action, "reply")) {
			write_frame(text, strlen(text));
			return;
		} else if (!strcmp(action, "close")) {
			running = 0;
			return;
		}
		execute(request, reply);
		if (!strcmp(action, "partial")) {
			write_frame(reply, 5);
		} else {
			if (!strcmp(action, "slow")) {
				usleep((useconds_t)(argument > 0 ? argument : 1000) * 1000);
			}
			write_frame(reply, FRAME);
		}
		return;
	}
	execute(request, reply);
	write_frame(reply, FRAME);
}

static void apply_control(void) {
	if (!control_file) {
		return;
	}
	FILE *file = fopen(control_file, "r");
	if (!file) {
		return;
	}
	char key[32], value[64];
	while (fscanf(file, "%31s %63s", key, value) == 2) {
		if (!strcmp(key, "azimuth")) {
			serial_motion_sync(&rotation, atoi(value) % 3600);
		} else if (!strcmp(key, "rotate")) {
			rotate_to(atoi(value), "control");
		} else if (!strcmp(key, "shutter")) {
			serial_motion_sync(&shutter, atoi(value));
		} else if (!strcmp(key, "flap")) {
			serial_motion_sync(&flap, strcmp(value, "open") ? 0 : 100);
		} else if (!strcmp(key, "eme") && strlen(value) == 4) {
			int flags[4];
			for (int i = 0; i < 4; i++) {
				flags[i] = value[i] == '1';
			}
			set_emergency(flags, "control");
		} else if (!strcmp(key, "serial")) {
			snprintf(serial_number, sizeof(serial_number), "%s", value);
		} else if (!strcmp(key, "drop") && tcp_source.fd >= 0) {
			close(tcp_source.fd);
			tcp_source.fd = -1;
			tcp_source.used = 0;
		}
		event("CONTROL", "%s %s", key, value);
	}
	fclose(file);
	unlink(control_file);
}

static bool parse_arguments(int argc, char **argv) {
	for (int i = 1; i < argc; i++) {
		if (!strcmp(argv[i], "--headless")) {
			headless = true;
		} else if (!strcmp(argv[i], "--trace")) {
			trace = true;
		} else if (!strcmp(argv[i], "--old-firmware")) {
			old_firmware = true;
		} else if (i + 1 < argc && !strcmp(argv[i], "--ready-file")) {
			ready_file = argv[++i];
		} else if (i + 1 < argc && !strcmp(argv[i], "--azimuth")) {
			serial_motion_sync(&rotation, atoi(argv[++i]) % 3600);
		} else if (i + 1 < argc && !strcmp(argv[i], "--shutter")) {
			serial_motion_sync(&shutter, atoi(argv[++i]));
		} else if (i + 1 < argc && !strcmp(argv[i], "--flap")) {
			serial_motion_sync(&flap, strcmp(argv[++i], "open") ? 0 : 100);
		} else if (i + 1 < argc && !strcmp(argv[i], "--rotation-speed")) {
			rotation_speed = atof(argv[++i]);
		} else if (i + 1 < argc && !strcmp(argv[i], "--shutter-time")) {
			shutter_time = atof(argv[++i]);
		} else if (i + 1 < argc && !strcmp(argv[i], "--flap-time")) {
			flap_time = atof(argv[++i]);
		} else if (i + 1 < argc && !strcmp(argv[i], "--tcp-port")) {
			tcp_port = atoi(argv[++i]);
		} else if (!strcmp(argv[i], "--help") || !strcmp(argv[i], "-h")) {
			printf("Usage: %s [--headless] [--trace] [--ready-file PATH] [--old-firmware] [--azimuth TENTHS] [--shutter PERCENT] [--flap open|closed] [--rotation-speed DEG_PER_S] [--shutter-time S] [--flap-time S] [--tcp-port PORT]\n", argv[0]);
			exit(0);
		} else {
			fprintf(stderr, "Unknown/incomplete option '%s'\n", argv[i]);
			return false;
		}
	}
	if (rotation_speed <= 0 || shutter_time <= 0 || flap_time <= 0) {
		fprintf(stderr, "Rates must be positive\n");
		return false;
	}
	return true;
}

static bool open_tcp_listener(void) {
	struct sockaddr_in address = { 0 };
	int reuse = 1;
	socklen_t length = sizeof(address);
	tcp_listen_fd = socket(AF_INET, SOCK_STREAM, 0);
	if (tcp_listen_fd < 0) {
		perror("socket");
		return false;
	}
	setsockopt(tcp_listen_fd, SOL_SOCKET, SO_REUSEADDR, &reuse, sizeof(reuse));
	address.sin_family = AF_INET;
	address.sin_addr.s_addr = htonl(INADDR_LOOPBACK);
	address.sin_port = htons(tcp_port);
	if (bind(tcp_listen_fd, (struct sockaddr *)&address, sizeof(address)) < 0 || listen(tcp_listen_fd, 1) < 0 || getsockname(tcp_listen_fd, (struct sockaddr *)&address, &length) < 0) {
		perror("tcp listener");
		close(tcp_listen_fd);
		tcp_listen_fd = -1;
		return false;
	}
	tcp_port = ntohs(address.sin_port);
	return true;
}

static bool write_ready_file(const char *port) {
	if (tcp_listen_fd < 0) {
		return serial_simulator_write_ready_file(ready_file, "dome_baader_simulator", port);
	}
	char temporary[PATH_MAX];
	snprintf(temporary, sizeof(temporary), "%s.tmp.%ld", ready_file, (long)getpid());
	FILE *file = fopen(temporary, "w");
	if (file == NULL) {
		perror("fopen ready file");
		return false;
	}
	fprintf(file, "INDIGO_SIMULATOR=dome_baader_simulator\n");
	fprintf(file, "INDIGO_SIMULATOR_PORT=%s\n", port);
	fprintf(file, "INDIGO_SIMULATOR_TCP_URL=tcp://127.0.0.1:%d\n", tcp_port);
	fprintf(file, "INDIGO_SIMULATOR_PID=%ld\n", (long)getpid());
	if (fclose(file) != 0 || rename(temporary, ready_file) != 0) {
		perror("ready file");
		unlink(temporary);
		return false;
	}
	return true;
}

// reads available bytes of one source and dispatches complete frames; returns false when the source is closed
static bool read_source(frame_source *source) {
	char byte;
	ssize_t count = read(source->fd, &byte, 1);
	if (count == 0 || (count < 0 && errno != EAGAIN && errno != EINTR && errno != EIO)) {
		return source == &serial_source;
	}
	if (count < 0) {
		usleep(1000);
		return true;
	}
	source->last_byte = serial_motion_time();
	if (!source->used && byte != 'd') {
		event("REJECT", "%s out-of-frame 0x%02x", source->name, (unsigned char)byte);
		return true;
	}
	source->request[source->used++] = byte;
	if (source->used == FRAME) {
		source->request[source->used] = 0;
		reply_fd = source->fd;
		dispatch(source->request);
		source->used = 0;
	}
	return true;
}

static void reset_stale_frame(frame_source *source) {
	if (source->used && serial_motion_time() - source->last_byte > 0.5) {
		source->request[source->used] = 0;
		event("REJECT", "%s incomplete %s", source->name, source->request);
		source->used = 0;
	}
}

int main(int argc, char **argv) {
	if (!parse_arguments(argc, argv)) {
		return 1;
	}
	fault_file = getenv("INDIGO_BAADER_FAULT");
	control_file = getenv("INDIGO_BAADER_CONTROL");
	const char *event_file = getenv("INDIGO_BAADER_EVENTS");
	events = event_file ? fopen(event_file, "a") : NULL;
	signal(SIGTERM, stop_signal);
	signal(SIGINT, stop_signal);
	signal(SIGPIPE, SIG_IGN);
	char port[PATH_MAX];
	serial_fd = serial_simulator_open_pty(port, sizeof(port));
	if (serial_fd < 0 || (tcp_port >= 0 && !open_tcp_listener()) || (ready_file && !write_ready_file(port))) {
		return 1;
	}
	serial_source.fd = serial_fd;
	event("OPEN", "azimuth=%d shutter=%d flap=%d old_firmware=%d tcp_port=%d", azimuth(), shutter_position(), (int)flap.position, old_firmware, tcp_port);
	if (!headless) {
		printf("Baader Classic Dome simulator is listening on %s\n", port);
		if (tcp_listen_fd >= 0) {
			printf("Baader Classic Dome simulator is listening on tcp://127.0.0.1:%d\n", tcp_port);
		}
		fflush(stdout);
	}
	while (running) {
		apply_control();
		fd_set fds;
		FD_ZERO(&fds);
		FD_SET(serial_fd, &fds);
		int max_fd = serial_fd;
		if (tcp_listen_fd >= 0) {
			FD_SET(tcp_listen_fd, &fds);
			max_fd = tcp_listen_fd > max_fd ? tcp_listen_fd : max_fd;
		}
		if (tcp_source.fd >= 0) {
			FD_SET(tcp_source.fd, &fds);
			max_fd = tcp_source.fd > max_fd ? tcp_source.fd : max_fd;
		}
		struct timeval timeout = { 0, 20000 };
		if (select(max_fd + 1, &fds, NULL, NULL, &timeout) <= 0) {
			reset_stale_frame(&serial_source);
			reset_stale_frame(&tcp_source);
			continue;
		}
		if (tcp_listen_fd >= 0 && FD_ISSET(tcp_listen_fd, &fds)) {
			int client = accept(tcp_listen_fd, NULL, NULL);
			if (client >= 0) {
				if (tcp_source.fd >= 0) {
					close(tcp_source.fd);
				}
				tcp_source.fd = client;
				tcp_source.used = 0;
				event("STATE", "tcp client connected");
			}
		}
		if (tcp_source.fd >= 0 && FD_ISSET(tcp_source.fd, &fds) && !read_source(&tcp_source)) {
			event("STATE", "tcp client closed");
			close(tcp_source.fd);
			tcp_source.fd = -1;
			tcp_source.used = 0;
		}
		if (FD_ISSET(serial_fd, &fds)) {
			read_source(&serial_source);
		}
	}
	event("STATE", "azimuth=%d shutter=%d flap=%d", azimuth(), shutter_position(), (int)lround(serial_motion_update(&flap)));
	event("CLOSE", "simulator");
	if (tcp_source.fd >= 0) {
		close(tcp_source.fd);
	}
	if (tcp_listen_fd >= 0) {
		close(tcp_listen_fd);
	}
	close(serial_fd);
	if (events) {
		fclose(events);
	}
	return 0;
}
