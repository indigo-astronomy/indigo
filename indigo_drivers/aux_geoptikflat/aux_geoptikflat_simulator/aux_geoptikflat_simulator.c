// Code is generated by AI

// The Geoptik flat field generator speaks the Alnitak generic command set, documented in
// ../../aux_flipflat/Alnitak_GenericCommandsR4.pdf:
//
//   send ">POOO" CR -> receive "*Pii" "OOO" LF    ping, used to find the device
//   send ">VOOO" CR -> receive "*Vii" vvv  LF    firmware version, vvv is three digits
//   send ">LOOO" CR -> receive "*Lii" "OOO" LF    light on
//   send ">DOOO" CR -> receive "*Dii" "OOO" LF    light off
//   send ">Bxxx" CR -> receive "*Bii" xxx  LF    set brightness, xxx is 000-255
//
// ">" leads every request and "*" every reply, ii is the two digit product id and the reply is
// terminated by LF alone - there is no CR in front of it. indigo_aux_geoptikflat uses exactly
// these five commands; the documented ">JOOO" and ">SOOO" readbacks are not implemented here
// because the driver never sends them.

