#define MAX_CLIENTS 8
#define BUFFER_SIZE 4096
#define DEVICE_PATH "/dev/ttyACM0"

typedef enum {
	ALT_LEGACY,
	ALT_MODERN,
	ALT_BOTH
} alt_style;

typedef struct {
	int fd;
	bool watching;
	char buffer[BUFFER_SIZE];
	size_t length;
} client_state;

static struct {
	const char *ready_file;
	bool headless, trace;
	int port;
} options = { NULL, false, false, 0 };

static struct {
	int mode;
	bool time_valid, altitude_valid, dop_valid, sky_modern, refuse, banner;
	char time[64];
	double latitude, longitude, alt_hae, geoid_sep, pdop, hdop, vdop;
	int visible, used, period_ms;
	alt_style altitude_style;
	char split_rest[BUFFER_SIZE];
	double split_due;
} state;

static volatile sig_atomic_t running = 1;
static client_state clients[MAX_CLIENTS];
static int server_fd = -1;

static double monotonic_seconds(void) {
	struct timespec now;
	clock_gettime(CLOCK_MONOTONIC, &now);
	return now.tv_sec + now.tv_nsec / 1e9;
}

static void log_event(const char *format, ...) __attribute__((format(printf, 1, 2)));

static void log_event(const char *format, ...) {
	char line[BUFFER_SIZE];
	va_list args;
	va_start(args, format);
	vsnprintf(line, sizeof(line), format, args);
	va_end(args);
	if (options.trace) {
		fprintf(stderr, "gpsd-sim %s\n", line);
	}
	if (options.ready_file == NULL) {
		return;
	}
	char path[PATH_MAX];
	snprintf(path, sizeof(path), "%s.events", options.ready_file);
	FILE *file = fopen(path, "a");
	if (file != NULL) {
		fprintf(file, "%.6f\t%s\n", monotonic_seconds(), line);
		fclose(file);
	}
}

static void signal_handler(int signal) {
	(void)signal;
	running = 0;
}

static void usage(const char *name) {
	printf("Usage: %s [--headless] [--trace] [--ready-file <path>] [--port <port>]\n", name);
	printf("  --headless              Do not print the listening endpoint\n");
	printf("  --trace                 Log protocol events to stderr\n");
	printf("  --ready-file <path>     Write INDIGO_SIMULATOR_PORT after TCP setup\n");
	printf("  --port <port>           Listen on this loopback port instead of an ephemeral one\n");
}

static bool parse_options(int argc, char **argv) {
	for (int i = 1; i < argc; i++) {
		if (!strcmp(argv[i], "--headless")) {
			options.headless = true;
		} else if (!strcmp(argv[i], "--trace")) {
			options.trace = true;
		} else if (!strcmp(argv[i], "--ready-file") && i + 1 < argc) {
			options.ready_file = argv[++i];
		} else if (!strcmp(argv[i], "--port") && i + 1 < argc) {
			options.port = atoi(argv[++i]);
		} else if (!strcmp(argv[i], "--help")) {
			usage(argv[0]);
			exit(0);
		} else {
			fprintf(stderr, "Unknown or incomplete option %s\n", argv[i]);
			usage(argv[0]);
			return false;
		}
	}
	return true;
}

static int open_server_socket(int *port) {
	int fd = socket(AF_INET, SOCK_STREAM, 0);
	if (fd < 0) {
		perror("socket");
		return -1;
	}
	int reuse = 1;
	setsockopt(fd, SOL_SOCKET, SO_REUSEADDR, &reuse, sizeof(reuse));
	struct sockaddr_in address;
	memset(&address, 0, sizeof(address));
	address.sin_family = AF_INET;
	address.sin_addr.s_addr = htonl(INADDR_LOOPBACK);
	address.sin_port = htons((uint16_t)*port);
	if (bind(fd, (struct sockaddr *)&address, sizeof(address)) < 0 || listen(fd, MAX_CLIENTS) < 0) {
		perror("bind/listen");
		close(fd);
		return -1;
	}
	socklen_t length = sizeof(address);
	if (getsockname(fd, (struct sockaddr *)&address, &length) < 0) {
		perror("getsockname");
		close(fd);
		return -1;
	}
	*port = ntohs(address.sin_port);
	return fd;
}

static bool write_ready_file(const char *endpoint) {
	char tmp_file[PATH_MAX];
	snprintf(tmp_file, sizeof(tmp_file), "%s.tmp.%ld", options.ready_file, (long)getpid());
	FILE *file = fopen(tmp_file, "w");
	if (file == NULL) {
		perror("fopen ready file");
		return false;
	}
	fprintf(file, "INDIGO_SIMULATOR=gps_gpsd_simulator\n");
	fprintf(file, "INDIGO_SIMULATOR_PORT=%s\n", endpoint);
	fprintf(file, "INDIGO_SIMULATOR_TCP_URL=%s\n", endpoint);
	fprintf(file, "INDIGO_SIMULATOR_PID=%ld\n", (long)getpid());
	if (fclose(file) != 0 || rename(tmp_file, options.ready_file) != 0) {
		perror("ready file");
		unlink(tmp_file);
		return false;
	}
	return true;
}

static void close_client(client_state *client, const char *reason) {
	if (client->fd >= 0) {
		close(client->fd);
		log_event("CLOSE %s", reason);
	}
	client->fd = -1;
	client->watching = false;
	client->length = 0;
}

static void send_text(client_state *client, const char *text) {
	if (client->fd < 0) {
		return;
	}
	if (!serial_simulator_write_all(client->fd, text, strlen(text))) {
		close_client(client, "write-failed");
	}
}

static void send_line(client_state *client, const char *line) {
	char text[BUFFER_SIZE];
	snprintf(text, sizeof(text), "%s\n", line);
	send_text(client, text);
}

static void version_json(char *buffer, size_t size) {
	snprintf(buffer, size, "{\"class\":\"VERSION\",\"release\":\"3.20\",\"rev\":\"3.20\",\"proto_major\":3,\"proto_minor\":14}");
}

static void device_json(char *buffer, size_t size) {
	snprintf(buffer, size, "{\"class\":\"DEVICE\",\"path\":\"%s\",\"driver\":\"u-blox\",\"activated\":\"2026-01-01T00:00:00.000Z\",\"native\":1,\"bps\":9600,\"parity\":\"N\",\"stopbits\":1,\"cycle\":1.00,\"mincycle\":0.25}", DEVICE_PATH);
}

static void devices_json(char *buffer, size_t size) {
	char device[BUFFER_SIZE];
	device_json(device, sizeof(device));
	snprintf(buffer, size, "{\"class\":\"DEVICES\",\"devices\":[%s]}", device);
}

static void watch_json(bool enable, char *buffer, size_t size) {
	snprintf(buffer, size, "{\"class\":\"WATCH\",\"enable\":%s,\"json\":%s,\"nmea\":false,\"raw\":0,\"scaled\":false,\"timing\":false,\"split24\":false,\"pps\":false}", enable ? "true" : "false", enable ? "true" : "false");
}

static void tpv_json(char *buffer, size_t size) {
	int length = snprintf(buffer, size, "{\"class\":\"TPV\",\"device\":\"%s\",\"mode\":%d", DEVICE_PATH, state.mode);
	if (state.time_valid) {
		length += snprintf(buffer + length, size - length, ",\"time\":\"%s\",\"ept\":0.005", state.time);
	}
	if (state.mode >= 2) {
		length += snprintf(buffer + length, size - length, ",\"lat\":%.9f,\"lon\":%.9f", state.latitude, state.longitude);
	}
	if (state.mode == 3 && state.altitude_valid) {
		if (state.altitude_style != ALT_MODERN) {
			length += snprintf(buffer + length, size - length, ",\"alt\":%.3f", state.alt_hae);
		}
		if (state.altitude_style != ALT_LEGACY) {
			length += snprintf(buffer + length, size - length, ",\"altHAE\":%.3f,\"altMSL\":%.3f,\"geoidSep\":%.3f", state.alt_hae, state.alt_hae - state.geoid_sep, state.geoid_sep);
		}
	}
	snprintf(buffer + length, size - length, "}");
}

static void sky_json(char *buffer, size_t size) {
	int length = snprintf(buffer, size, "{\"class\":\"SKY\",\"device\":\"%s\"", DEVICE_PATH);
	if (state.dop_valid) {
		length += snprintf(buffer + length, size - length, ",\"vdop\":%.2f,\"hdop\":%.2f,\"pdop\":%.2f", state.vdop, state.hdop, state.pdop);
	}
	if (state.sky_modern) {
		length += snprintf(buffer + length, size - length, ",\"nSat\":%d,\"uSat\":%d", state.visible, state.used);
	}
	length += snprintf(buffer + length, size - length, ",\"satellites\":[");
	for (int i = 0; i < state.visible && length < (int)size - 128; i++) {
		length += snprintf(buffer + length, size - length, "%s{\"PRN\":%d,\"el\":%d,\"az\":%d,\"ss\":%d,\"used\":%s}", i ? "," : "", i + 1, 10 + (i * 7) % 80, (i * 37) % 360, 20 + i % 25, i < state.used ? "true" : "false");
	}
	snprintf(buffer + length, size - length, "]}");
}

static void emit(const char *what) {
	char line[BUFFER_SIZE];
	bool tpv = !strcmp(what, "tpv") || !strcmp(what, "all");
	bool sky = !strcmp(what, "sky") || !strcmp(what, "all");
	for (int i = 0; i < MAX_CLIENTS; i++) {
		if (clients[i].fd >= 0 && clients[i].watching) {
			if (tpv) {
				tpv_json(line, sizeof(line));
				send_line(clients + i, line);
			}
			if (sky) {
				sky_json(line, sizeof(line));
				send_line(clients + i, line);
			}
		}
	}
	if (tpv) {
		log_event("EMIT TPV mode=%d", state.mode);
	}
	if (sky) {
		log_event("EMIT SKY visible=%d used=%d", state.visible, state.used);
	}
}

static void send_to_watchers(const char *text) {
	for (int i = 0; i < MAX_CLIENTS; i++) {
		if (clients[i].fd >= 0 && clients[i].watching) {
			send_text(clients + i, text);
		}
	}
}

static void handle_request(client_state *client, const char *request) {
	char line[BUFFER_SIZE * 2];
	log_event("REQUEST %s", request);
	if (!strncmp(request, "?WATCH=", 7)) {
		if (strstr(request, "\"enable\":false")) {
			client->watching = false;
			watch_json(false, line, sizeof(line));
			send_line(client, line);
			log_event("WATCH DISABLE");
		} else {
			client->watching = true;
			devices_json(line, sizeof(line));
			send_line(client, line);
			watch_json(true, line, sizeof(line));
			send_line(client, line);
			log_event("WATCH ENABLE");
		}
	} else if (!strcmp(request, "?WATCH")) {
		watch_json(client->watching, line, sizeof(line));
		send_line(client, line);
	} else if (!strcmp(request, "?VERSION")) {
		version_json(line, sizeof(line));
		send_line(client, line);
	} else if (!strcmp(request, "?DEVICES")) {
		devices_json(line, sizeof(line));
		send_line(client, line);
	} else if (!strcmp(request, "?POLL")) {
		char tpv[BUFFER_SIZE], sky[BUFFER_SIZE];
		tpv_json(tpv, sizeof(tpv));
		sky_json(sky, sizeof(sky));
		snprintf(line, sizeof(line), "{\"class\":\"POLL\",\"time\":\"%s\",\"active\":1,\"tpv\":[%s],\"sky\":[%s]}", state.time_valid ? state.time : "1970-01-01T00:00:00.000Z", tpv, sky);
		send_line(client, line);
	} else {
		snprintf(line, sizeof(line), "{\"class\":\"ERROR\",\"message\":\"Unrecognized request '%.64s'\"}", request + (*request == '?'));
		send_line(client, line);
	}
}

static void process_client_input(client_state *client) {
	ssize_t count = read(client->fd, client->buffer + client->length, sizeof(client->buffer) - client->length - 1);
	if (count == 0 || (count < 0 && errno != EINTR && errno != EAGAIN && errno != EWOULDBLOCK)) {
		close_client(client, "peer");
		return;
	}
	if (count < 0) {
		return;
	}
	client->length += (size_t)count;
	client->buffer[client->length] = 0;
	char *start = client->buffer;
	char *end;
	while ((end = strpbrk(start, ";\n")) != NULL) {
		*end = 0;
		while (*start == ' ' || *start == '\r' || *start == '\t') {
			start++;
		}
		if (*start) {
			handle_request(client, start);
			if (client->fd < 0) {
				return;
			}
		}
		start = end + 1;
	}
	client->length = strlen(start);
	memmove(client->buffer, start, client->length + 1);
	if (client->length >= sizeof(client->buffer) - 1) {
		close_client(client, "overlong-request");
	}
}

static void accept_client(void) {
	int fd = accept(server_fd, NULL, NULL);
	if (fd < 0) {
		return;
	}
	if (state.refuse) {
		close(fd);
		log_event("REFUSE");
		return;
	}
	for (int i = 0; i < MAX_CLIENTS; i++) {
		if (clients[i].fd < 0) {
			clients[i].fd = fd;
			clients[i].watching = false;
			clients[i].length = 0;
			log_event("CONNECT");
			if (state.banner) {
				char line[BUFFER_SIZE];
				version_json(line, sizeof(line));
				send_line(clients + i, line);
			}
			return;
		}
	}
	close(fd);
	log_event("REFUSE capacity");
}

static void apply_control_line(char *line) {
	char *argument = strchr(line, ' ');
	if (argument != NULL) {
		*argument++ = 0;
	} else {
		argument = "";
	}
	if (!strcmp(line, "mode")) {
		state.mode = atoi(argument);
	} else if (!strcmp(line, "time")) {
		state.time_valid = strcmp(argument, "none") != 0;
		snprintf(state.time, sizeof(state.time), "%s", argument);
	} else if (!strcmp(line, "position")) {
		sscanf(argument, "%lf %lf", &state.latitude, &state.longitude);
	} else if (!strcmp(line, "altitude")) {
		state.altitude_valid = sscanf(argument, "%lf %lf", &state.alt_hae, &state.geoid_sep) == 2;
	} else if (!strcmp(line, "alt_style")) {
		state.altitude_style = !strcmp(argument, "legacy") ? ALT_LEGACY : (!strcmp(argument, "modern") ? ALT_MODERN : ALT_BOTH);
	} else if (!strcmp(line, "sky_style")) {
		state.sky_modern = !strcmp(argument, "modern");
	} else if (!strcmp(line, "satellites")) {
		sscanf(argument, "%d %d", &state.visible, &state.used);
	} else if (!strcmp(line, "dop")) {
		state.dop_valid = sscanf(argument, "%lf %lf %lf", &state.pdop, &state.hdop, &state.vdop) == 3;
	} else if (!strcmp(line, "period")) {
		state.period_ms = atoi(argument);
	} else if (!strcmp(line, "emit")) {
		emit(argument);
	} else if (!strcmp(line, "raw")) {
		char text[BUFFER_SIZE];
		snprintf(text, sizeof(text), "%s\n", argument);
		send_to_watchers(text);
		log_event("EMIT RAW");
	} else if (!strcmp(line, "split")) {
		char text[BUFFER_SIZE];
		size_t half = strlen(argument) / 2;
		snprintf(text, sizeof(text), "%.*s", (int)half, argument);
		send_to_watchers(text);
		snprintf(state.split_rest, sizeof(state.split_rest), "%s\n", argument + half);
		state.split_due = monotonic_seconds() + 0.1;
		log_event("EMIT SPLIT");
	} else if (!strcmp(line, "close")) {
		for (int i = 0; i < MAX_CLIENTS; i++) {
			close_client(clients + i, "control");
		}
	} else if (!strcmp(line, "refuse")) {
		state.refuse = atoi(argument) != 0;
	} else if (!strcmp(line, "banner")) {
		state.banner = atoi(argument) != 0;
	} else {
		log_event("CONTROL-UNKNOWN %s", line);
	}
}

static void read_control(void) {
	if (options.ready_file == NULL) {
		return;
	}
	char path[PATH_MAX];
	snprintf(path, sizeof(path), "%s.control", options.ready_file);
	FILE *file = fopen(path, "r");
	if (file == NULL) {
		return;
	}
	char line[BUFFER_SIZE];
	while (fgets(line, sizeof(line), file) != NULL) {
		line[strcspn(line, "\r\n")] = 0;
		if (*line) {
			apply_control_line(line);
		}
	}
	fclose(file);
	unlink(path);
}

int main(int argc, char **argv) {
	if (!parse_options(argc, argv)) {
		return 1;
	}
	signal(SIGTERM, signal_handler);
	signal(SIGINT, signal_handler);
	signal(SIGPIPE, SIG_IGN);
	for (int i = 0; i < MAX_CLIENTS; i++) {
		clients[i].fd = -1;
	}
	state.mode = 3;
	state.time_valid = true;
	snprintf(state.time, sizeof(state.time), "2026-01-02T03:04:05.000Z");
	state.latitude = 48.1486;
	state.longitude = 17.1077;
	state.altitude_valid = true;
	state.alt_hae = 180.5;
	state.geoid_sep = 44.25;
	state.altitude_style = ALT_BOTH;
	state.visible = 9;
	state.used = 7;
	state.dop_valid = true;
	state.pdop = 1.8;
	state.hdop = 0.9;
	state.vdop = 1.5;
	state.period_ms = 1000;
	state.banner = true;
	int port = options.port;
	server_fd = open_server_socket(&port);
	if (server_fd < 0) {
		return 1;
	}
	char endpoint[128];
	snprintf(endpoint, sizeof(endpoint), "gpsd://127.0.0.1:%d", port);
	if (options.ready_file != NULL && !write_ready_file(endpoint)) {
		close(server_fd);
		return 1;
	}
	if (!options.headless) {
		printf("gpsd simulator ready on %s\n", endpoint);
		fflush(stdout);
	}
	double next_emit = monotonic_seconds() + state.period_ms / 1000.0;
	while (running) {
		fd_set readers;
		FD_ZERO(&readers);
		FD_SET(server_fd, &readers);
		int max_fd = server_fd;
		for (int i = 0; i < MAX_CLIENTS; i++) {
			if (clients[i].fd >= 0) {
				FD_SET(clients[i].fd, &readers);
				if (clients[i].fd > max_fd) {
					max_fd = clients[i].fd;
				}
			}
		}
		struct timeval timeout = { 0, 10000 };
		int ready = select(max_fd + 1, &readers, NULL, NULL, &timeout);
		if (ready < 0 && errno != EINTR) {
			perror("select");
			break;
		}
		if (ready > 0) {
			if (FD_ISSET(server_fd, &readers)) {
				accept_client();
			}
			for (int i = 0; i < MAX_CLIENTS; i++) {
				if (clients[i].fd >= 0 && FD_ISSET(clients[i].fd, &readers)) {
					process_client_input(clients + i);
				}
			}
		}
		read_control();
		double now = monotonic_seconds();
		if (state.split_rest[0] && now >= state.split_due) {
			send_to_watchers(state.split_rest);
			state.split_rest[0] = 0;
		}
		if (state.period_ms <= 0) {
			next_emit = now;
		} else if (now >= next_emit) {
			emit("all");
			next_emit = now + state.period_ms / 1000.0;
		}
	}
	for (int i = 0; i < MAX_CLIENTS; i++) {
		close_client(clients + i, "shutdown");
	}
	close(server_fd);
	if (options.ready_file != NULL) {
		unlink(options.ready_file);
	}
	return 0;
}
