// Code is generated by AI

// Host-side GPS Service Daemon (gpsd) JSON protocol simulator.
//
// Listens on 127.0.0.1 (ephemeral port unless --port is given) and speaks the
// gpsd client protocol documented in gpsd_json(5) as consumed by the gpsd 3.20
// client library bundled with indigo_gps_gpsd:
//   - VERSION object on every accepted connection;
//   - requests are '?'-prefixed and terminated by ';' or newline;
//   - ?WATCH={"enable":true,...} replies DEVICES then WATCH and starts TPV/SKY;
//   - ?WATCH={"enable":false,...} replies WATCH and stops the stream;
//   - ?WATCH; replies the current WATCH policy, ?VERSION; ?DEVICES; ?POLL;
//   - any other request replies an ERROR object.
// TPV contains mode, time (when valid), lat/lon for modes 2 and 3 and altitude
// for mode 3. Altitude style "legacy" sends the pre-3.20 "alt" field, "modern"
// sends only "altHAE"/"altMSL", "both" sends all three. SKY style "legacy" sends
// DOP and the satellites array, "modern" additionally sends "nSat"/"uSat" as
// later gpsd releases do.
//
// Test control ("<ready-file>.control", written atomically, consumed and
// removed), one command per line:
//   mode <0..3>                        fix mode
//   time <ISO-8601 UTC>|none           TPV time
//   position <lat> <lon>               degrees
//   altitude <altHAE> <geoidSep>|none  metres
//   alt_style legacy|modern|both
//   sky_style legacy|modern
//   satellites <visible> <used>
//   dop <pdop> <hdop> <vdop>|none
//   period <milliseconds>              0 = emit only on request
//   emit tpv|sky|all                   emit to watching clients now
//   raw <text>                         send text and newline to watching clients
//   split <text>                       send first half now, rest 100 ms later
//   close                              close all client connections
//   refuse 0|1                         close new connections immediately
//   banner 0|1                         send VERSION on connect
// Events ("<ready-file>.events"): "<monotonic seconds>\t<event>" per line.

