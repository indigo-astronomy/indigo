static void event(const char *kind, const char *format, ...) {
	if (!events) {
		return;
	}
	fprintf(events, "%.6f %s ", serial_motion_time(), kind);
	va_list args;
	va_start(args, format);
	vfprintf(events, format, args);
	va_end(args);
	fputc('\n', events);
	fflush(events);
}

static void stop_signal(int signal) {
	(void)signal;
	running = 0;
}

static double normalize(double azimuth) {
	double result = fmod(azimuth, 360);
	return result < 0 ? result + 360 : result;
}

// azimuth in whole tenths of degree, the reported resolution
static int azimuth_tenths(void) {
	long tenths = lround(serial_motion_update(&rotation) * 10);
	return (int)((tenths % 3600 + 3600) % 3600);
}

static double azimuth(void) {
	return azimuth_tenths() / 10.0;
}

static double distance(double a, double b) {
	double delta = fabs(normalize(a) - normalize(b));
	return delta > 180 ? 360 - delta : delta;
}

static bool rotating(void) {
	serial_motion_update(&rotation);
	return rotation.duration > 0;
}

static bool shutter_moving(void) {
	serial_motion_update(&shutter);
	return shutter.duration > 0;
}

static void update_calibrations(void) {
	if (rotator_calibration_status == 1 && !rotating()) {
		serial_motion_sync(&rotation, home_azimuth);
		if (rotator_calibration_fail) {
			rotator_calibration_status = 3;
			rotator_error = true;
			rotator_failure_code = 21;
			snprintf(rotator_failure_message, sizeof(rotator_failure_message), "Rotator calibration failed");
			rotator_calibration_fail = false;
		} else {
			rotator_calibration_status = 2;
		}
		event("STATE", "rotator calibration status=%d", rotator_calibration_status);
	}
	if (shutter_calibration_status == 1 && serial_motion_time() >= shutter_calibration_end) {
		if (shutter_calibration_fail) {
			shutter_calibration_status = 3;
			shutter_calibration_fail = false;
		} else {
			shutter_calibration_status = 2;
		}
		event("STATE", "shutter calibration status=%d", shutter_calibration_status);
	}
}

static bool at_home(void) {
	return distance(azimuth(), home_azimuth) < 1;
}

static bool at_park(void) {
	return !rotating() && distance(azimuth(), park_azimuth) < 0.5;
}

static int shutter_status(void) {
	if (!shutter_up || shutter_error) {
		return 4;
	}
	if (shutter_moving()) {
		return shutter.target > shutter.origin ? 2 : 3;
	}
	if (shutter.position >= 100) {
		return 0;
	}
	if (shutter.position <= 0) {
		return 1;
	}
	return 4;
}

static int dome_status(void) {
	int status = 0, shutter_state = shutter_status();
	status |= rotating() ? 1 << 0 : 0;
	status |= shutter_state == 2 || shutter_state == 3 ? 1 << 1 : 0;
	status |= rotator_error ? 1 << 2 : 0;
	status |= shutter_error ? 1 << 3 : 0;
	status |= !shutter_up ? 1 << 4 : 0;
	status |= unsafe_cw ? 1 << 5 : 0;
	status |= unsafe_hydreon ? 1 << 6 : 0;
	status |= shutter_state == 0 ? 1 << 7 : 0;
	status |= shutter_state == 1 ? 1 << 8 : 0;
	status |= shutter_state == 2 ? 1 << 9 : 0;
	status |= shutter_state == 3 ? 1 << 10 : 0;
	status |= at_home() ? 1 << 11 : 0;
	status |= at_park() ? 1 << 12 : 0;
	return status;
}

static void rotate_to(double target, const char *origin) {
	double current = serial_motion_update(&rotation);
	double delta = normalize(target) - normalize(current);
	if (delta > 180) {
		delta -= 360;
	} else if (delta <= -180) {
		delta += 360;
	}
	serial_motion_start(&rotation, current + delta, rotation_speed);
	event("MOVE", "%s rotation from=%.1f to=%.1f delta=%.1f", origin, normalize(current), normalize(target), delta);
}

static void stop_rotation(const char *origin) {
	if (rotating()) {
		serial_motion_stop(&rotation);
		event("STATE", "%s rotation stopped at=%.1f", origin, azimuth());
	}
	if (rotator_calibration_status == 1) {
		rotator_calibration_status = 0;
		event("STATE", "%s rotator calibration stopped", origin);
	}
}

static void move_shutter(double target) {
	shutter_error = false;
	serial_motion_start(&shutter, target, 100 / shutter_time);
	event("MOVE", "shutter from=%d to=%d", (int)lround(shutter.origin), (int)target);
}

static void stop_shutter(const char *origin) {
	if (shutter_moving()) {
		serial_motion_stop(&shutter);
		event("STATE", "%s shutter stopped at=%d", origin, (int)lround(shutter.position));
	}
	if (shutter_calibration_status == 1) {
		shutter_calibration_status = 0;
		event("STATE", "%s shutter calibration stopped", origin);
	}
}

static bool parse_number(const char *text, double *value) {
	char *end;
	*value = strtod(text, &end);
	// an optional timeout argument may follow the number
	return end != text && (*end == 0 || *end == ' ');
}

// executes one request without the leading '!' and trailing '#'; writes the result part of the reply
static void execute(const char *command, char *result, size_t size) {
	double value;
	int a, r, s;
	update_calibrations();
	snprintf(result, size, "0");
	if (!strcmp(command, "seletek version")) {
		snprintf(result, size, "%d", version);
	} else if (!strncmp(command, "seletek echo", 12)) {
		snprintf(result, size, "%s", command[12] == ' ' ? command + 13 : "");
	} else if (!strcmp(command, "seletek savefs")) {
		// savefs stops a turning motor abruptly before writing the flash
		stop_rotation("savefs");
	} else if (!strcmp(command, "seletek getfailurecode")) {
		snprintf(result, size, "%d", rotator_failure_code);
	} else if (!strcmp(command, "seletek getfailuremsg")) {
		snprintf(result, size, "%s", rotator_failure_message);
	} else if (!strcmp(command, "seletek clearfailure")) {
		rotator_failure_code = 0;
		*rotator_failure_message = 0;
		rotator_error = false;
	} else if (!strncmp(command, "dome gotoaz ", 12) || !strncmp(command, "domerot goto ", 13)) {
		const char *argument = command + (command[4] == ' ' ? 12 : 13);
		if (!parse_number(argument, &value) || value < 0 || value > 360) {
			event("REJECT", "azimuth %s", command);
			snprintf(result, size, "-1");
		} else if (rotator_calibration_status == 1) {
			event("REJECT", "goto while calibrating");
			snprintf(result, size, "-5");
		} else {
			rotate_to(value, "goto");
		}
	} else if (!strcmp(command, "dome getaz") || !strcmp(command, "domerot getpos")) {
		snprintf(result, size, "%.1f", azimuth());
	} else if (!strncmp(command, "dome setaz ", 11) || !strncmp(command, "domerot setpos ", 15)) {
		if (!parse_number(command + (command[4] == ' ' ? 11 : 15), &value) || value < 0 || value > 360) {
			snprintf(result, size, "-1");
		} else {
			serial_motion_sync(&rotation, normalize(value));
			event("STATE", "synced azimuth=%.1f", azimuth());
		}
	} else if (!strcmp(command, "dome gohome")) {
		rotate_to(home_azimuth, "home");
	} else if (!strcmp(command, "dome gopark")) {
		rotate_to(park_azimuth, "park");
	} else if (!strcmp(command, "dome setpark")) {
		park_azimuth = azimuth();
		event("STATE", "park=%.1f", park_azimuth);
	} else if (!strncmp(command, "domerot setpark ", 16)) {
		if (!parse_number(command + 16, &value) || value < 0 || value > 360) {
			snprintf(result, size, "-1");
		} else {
			park_azimuth = normalize(value);
		}
	} else if (!strcmp(command, "domerot getpark")) {
		snprintf(result, size, "%.1f", park_azimuth);
	} else if (!strncmp(command, "domerot sethome ", 16)) {
		if (!parse_number(command + 16, &value) || value < 0 || value > 360) {
			snprintf(result, size, "-1");
		} else {
			home_azimuth = normalize(value);
		}
	} else if (!strcmp(command, "domerot gethome")) {
		snprintf(result, size, "%.1f", home_azimuth);
	} else if (!strcmp(command, "dome athome") || !strcmp(command, "domerot athome")) {
		snprintf(result, size, "%d", at_home());
	} else if (!strcmp(command, "dome atpark") || !strcmp(command, "domerot atpark")) {
		snprintf(result, size, "%d", at_park());
	} else if (!strcmp(command, "dome status")) {
		snprintf(result, size, "%d", dome_status());
	} else if (!strcmp(command, "dome shutterstatus")) {
		snprintf(result, size, "%d", shutter_status());
	} else if (!strcmp(command, "dome shutterisup")) {
		snprintf(result, size, "%d", shutter_up);
	} else if (!strcmp(command, "dome getshutterbatvoltage")) {
		snprintf(result, size, "%s", shutter_up ? "12.60" : "-1");
	} else if (!strcmp(command, "dome openshutter") || !strcmp(command, "dome closeshutter")) {
		bool open = command[5] == 'o';
		if (!shutter_up) {
			event("REJECT", "shutter not connected");
			snprintf(result, size, "-1");
		} else if (open ? (!shutter_moving() && shutter.position >= 100 && !shutter_error) : (!shutter_moving() && shutter.position <= 0 && !shutter_error)) {
			event("STATE", "shutter already %s", open ? "open" : "closed");
		} else {
			move_shutter(open ? 100 : 0);
		}
	} else if (!strncmp(command, "dome abort", 10)) {
		a = r = s = 0;
		// "dome abort", "dome abort 1" and the invalid "dome abort 0 0 0" abort all motion
		if (sscanf(command + 10, "%d %d %d", &a, &r, &s) < 3 || (!a && !r && !s)) {
			a = 1;
		}
		event("STATE", "abort all=%d rotation=%d shutter=%d", a, r, s);
		if (a || r) {
			stop_rotation("abort");
		}
		if (a || s) {
			stop_shutter("abort");
		}
	} else if (!strncmp(command, "dome autocalrot", 15)) {
		if (rotating() || rotator_calibration_status == 1) {
			snprintf(result, size, "-5");
		} else {
			double current = serial_motion_update(&rotation);
			serial_motion_start(&rotation, current + 360 + normalize(home_azimuth - current), (360 + normalize(home_azimuth - current)) / calibration_time);
			rotator_calibration_status = 1;
			rotator_error = false;
			event("MOVE", "rotator calibration from=%.1f", normalize(current));
		}
	} else if (!strcmp(command, "dome autocalshutter")) {
		if (!shutter_up) {
			snprintf(result, size, "-1");
		} else {
			shutter_calibration_status = 1;
			shutter_calibration_end = serial_motion_time() + shutter_calibration_time;
			event("MOVE", "shutter calibration");
		}
	} else if (!strcmp(command, "domerot getcalibrationstatus")) {
		snprintf(result, size, "%d", rotator_calibration_status);
	} else if (!strncmp(command, "dome sendtoshutter \"", 20) && command[strlen(command) - 1] == '"') {
		char inner[REQUEST_SIZE];
		snprintf(inner, sizeof(inner), "%.*s", (int)strlen(command) - 21, command + 20);
		if (!shutter_up) {
			snprintf(result, size, "-1");
		} else if (!strcmp(inner, "shutter getcalibrationstatus")) {
			snprintf(result, size, "%d", shutter_calibration_status);
		} else if (!strcmp(inner, "seletek getfailurecode")) {
			snprintf(result, size, "%d", shutter_failure_code);
		} else if (!strcmp(inner, "seletek getfailuremsg")) {
			snprintf(result, size, "%s", shutter_failure_message);
		} else if (!strcmp(inner, "seletek clearfailure")) {
			shutter_failure_code = 0;
			*shutter_failure_message = 0;
			shutter_error = false;
		} else {
			event("REJECT", "unsupported shutter command %s", inner);
			snprintf(result, size, "-1");
		}
	} else {
		event("REJECT", "unsupported %s", command);
		snprintf(result, size, "-1");
	}
}

static void write_reply(const char *reply) {
	event("TX", "%s", reply);
	serial_simulator_trace_line(trace, "<-", reply);
	serial_simulator_write_all(reply_fd, reply, strlen(reply));
}

static bool fault(const char *request, char *action, char *argument) {
	if (!fault_file) {
		return false;
	}
	FILE *file = fopen(fault_file, "r");
	if (!file) {
		return false;
	}
	char line[REQUEST_SIZE + 64] = "", prefix[REQUEST_SIZE] = "";
	int count = 1, consumed = 0;
	bool read = fgets(line, sizeof(line), file) != NULL;
	fclose(file);
	if (!read || sscanf(line, "%15s %d %63s %n", action, &count, argument, &consumed) < 3) {
		return false;
	}
	snprintf(prefix, sizeof(prefix), "%s", line + consumed);
	prefix[strcspn(prefix, "\n")] = 0;
	if (strcmp(prefix, "ANY") && strncmp(request + 1, prefix, strlen(prefix))) {
		return false;
	}
	if (--count <= 0) {
		unlink(fault_file);
	} else {
		char temporary[PATH_MAX];
		snprintf(temporary, sizeof(temporary), "%s.sim", fault_file);
		file = fopen(temporary, "w");
		if (file) {
			fprintf(file, "%s %d %s %s\n", action, count, argument, prefix);
			fclose(file);
			rename(temporary, fault_file);
		}
	}
	event("FAULT", "%s %s", request, action);
	return true;
}

static void dispatch(const char *request) {
	char command[REQUEST_SIZE], result[REPLY_SIZE / 2], reply[REPLY_SIZE], action[16], argument[64];
	event("RX", "%s", request);
	serial_simulator_trace_line(trace, "->", request);
	snprintf(command, sizeof(command), "%.*s", (int)strlen(request) - 2, request + 1);
	if (fault(request, action, argument)) {
		if (!strcmp(action, "silent")) {
			return;
		} else if (!strcmp(action, "close")) {
			running = 0;
			return;
		} else if (!strcmp(action, "raw")) {
			write_reply(argument);
			return;
		}
		// a rejected request is not executed, other faults alter the reply of an executed request
		if (!strcmp(action, "error")) {
			snprintf(result, sizeof(result), "-1");
		} else {
			execute(command, result, sizeof(result));
		}
		if (!strcmp(action, "reply")) {
			snprintf(result, sizeof(result), "%s", argument);
		} else if (!strcmp(action, "slow")) {
			usleep((useconds_t)(atoi(argument) > 0 ? atoi(argument) : 1000) * 1000);
		}
		snprintf(reply, sizeof(reply), "!%s:%s%s", command, result, strcmp(action, "partial") ? "#" : "");
		write_reply(reply);
		return;
	}
	execute(command, result, sizeof(result));
	snprintf(reply, sizeof(reply), "!%s:%s#", command, result);
	write_reply(reply);
}

static void apply_control(void) {
	if (!control_file) {
		return;
	}
	FILE *file = fopen(control_file, "r");
	if (!file) {
		return;
	}
	char key[32], value[64];
	while (fscanf(file, "%31s %63s", key, value) == 2) {
		if (!strcmp(key, "azimuth")) {
			serial_motion_sync(&rotation, normalize(atof(value)));
		} else if (!strcmp(key, "rotate")) {
			rotate_to(atof(value), "control");
		} else if (!strcmp(key, "shutter")) {
			shutter_error = false;
			serial_motion_sync(&shutter, !strcmp(value, "open") ? 100 : !strcmp(value, "closed") ? 0 : atof(value));
		} else if (!strcmp(key, "unsafe") && strlen(value) == 2) {
			unsafe_cw = value[0] == '1';
			unsafe_hydreon = value[1] == '1';
		} else if (!strcmp(key, "rotfault")) {
			stop_rotation("fault");
			rotator_error = true;
			rotator_failure_code = atoi(value);
			snprintf(rotator_failure_message, sizeof(rotator_failure_message), "Rotator motor stalled");
		} else if (!strcmp(key, "shutfault")) {
			stop_shutter("fault");
			shutter_error = true;
			shutter_failure_code = atoi(value);
			snprintf(shutter_failure_message, sizeof(shutter_failure_message), "Shutter motor stalled");
		} else if (!strcmp(key, "shutterup")) {
			shutter_up = atoi(value) != 0;
		} else if (!strcmp(key, "calfail")) {
			rotator_calibration_fail |= !strcmp(value, "rotator");
			shutter_calibration_fail |= !strcmp(value, "shutter");
		} else if (!strcmp(key, "park")) {
			park_azimuth = normalize(atof(value));
		} else if (!strcmp(key, "home")) {
			home_azimuth = normalize(atof(value));
		} else if (!strcmp(key, "version")) {
			version = atoi(value);
		} else if (!strcmp(key, "drop") && tcp_source.fd >= 0) {
			close(tcp_source.fd);
			tcp_source.fd = -1;
			tcp_source.used = 0;
		}
		event("CONTROL", "%s %s", key, value);
	}
	fclose(file);
	unlink(control_file);
}

static bool parse_arguments(int argc, char **argv) {
	for (int i = 1; i < argc; i++) {
		if (!strcmp(argv[i], "--headless")) {
			headless = true;
		} else if (!strcmp(argv[i], "--trace")) {
			trace = true;
		} else if (!strcmp(argv[i], "--no-shutter")) {
			shutter_up = false;
		} else if (i + 1 < argc && !strcmp(argv[i], "--ready-file")) {
			ready_file = argv[++i];
		} else if (i + 1 < argc && !strcmp(argv[i], "--azimuth")) {
			serial_motion_sync(&rotation, normalize(atof(argv[++i])));
		} else if (i + 1 < argc && !strcmp(argv[i], "--shutter")) {
			i++;
			serial_motion_sync(&shutter, !strcmp(argv[i], "open") ? 100 : !strcmp(argv[i], "closed") ? 0 : atof(argv[i]));
		} else if (i + 1 < argc && !strcmp(argv[i], "--park")) {
			park_azimuth = normalize(atof(argv[++i]));
		} else if (i + 1 < argc && !strcmp(argv[i], "--home")) {
			home_azimuth = normalize(atof(argv[++i]));
		} else if (i + 1 < argc && !strcmp(argv[i], "--unsafe")) {
			const char *flags = argv[++i];
			unsafe_cw = flags[0] == '1';
			unsafe_hydreon = flags[0] && flags[1] == '1';
		} else if (i + 1 < argc && !strcmp(argv[i], "--version")) {
			version = atoi(argv[++i]);
		} else if (i + 1 < argc && !strcmp(argv[i], "--rotation-speed")) {
			rotation_speed = atof(argv[++i]);
		} else if (i + 1 < argc && !strcmp(argv[i], "--shutter-time")) {
			shutter_time = atof(argv[++i]);
		} else if (i + 1 < argc && !strcmp(argv[i], "--calibration-time")) {
			calibration_time = atof(argv[++i]);
		} else if (i + 1 < argc && !strcmp(argv[i], "--shutter-calibration-time")) {
			shutter_calibration_time = atof(argv[++i]);
		} else if (i + 1 < argc && !strcmp(argv[i], "--tcp-port")) {
			tcp_port = atoi(argv[++i]);
		} else if (!strcmp(argv[i], "--help") || !strcmp(argv[i], "-h")) {
			printf("Usage: %s [--headless] [--trace] [--ready-file PATH] [--azimuth DEG] [--park DEG] [--home DEG] [--shutter open|closed|PERCENT] [--no-shutter] [--unsafe CH] [--version N] [--rotation-speed DEG_PER_S] [--shutter-time S] [--calibration-time S] [--shutter-calibration-time S] [--tcp-port PORT]\n", argv[0]);
			exit(0);
		} else {
			fprintf(stderr, "Unknown/incomplete option '%s'\n", argv[i]);
			return false;
		}
	}
	if (rotation_speed <= 0 || shutter_time <= 0 || calibration_time <= 0 || shutter_calibration_time < 0) {
		fprintf(stderr, "Rates must be positive\n");
		return false;
	}
	return true;
}

static bool open_tcp_listener(void) {
	struct sockaddr_in address = { 0 };
	int reuse = 1;
	socklen_t length = sizeof(address);
	tcp_listen_fd = socket(AF_INET, SOCK_STREAM, 0);
	if (tcp_listen_fd < 0) {
		perror("socket");
		return false;
	}
	setsockopt(tcp_listen_fd, SOL_SOCKET, SO_REUSEADDR, &reuse, sizeof(reuse));
	address.sin_family = AF_INET;
	address.sin_addr.s_addr = htonl(INADDR_LOOPBACK);
	address.sin_port = htons(tcp_port);
	if (bind(tcp_listen_fd, (struct sockaddr *)&address, sizeof(address)) < 0 || listen(tcp_listen_fd, 1) < 0 || getsockname(tcp_listen_fd, (struct sockaddr *)&address, &length) < 0) {
		perror("tcp listener");
		close(tcp_listen_fd);
		tcp_listen_fd = -1;
		return false;
	}
	tcp_port = ntohs(address.sin_port);
	return true;
}

static bool write_ready_file(const char *port) {
	if (tcp_listen_fd < 0) {
		return serial_simulator_write_ready_file(ready_file, "dome_beaver_simulator", port);
	}
	char temporary[PATH_MAX];
	snprintf(temporary, sizeof(temporary), "%s.tmp.%ld", ready_file, (long)getpid());
	FILE *file = fopen(temporary, "w");
	if (file == NULL) {
		perror("fopen ready file");
		return false;
	}
	fprintf(file, "INDIGO_SIMULATOR=dome_beaver_simulator\n");
	fprintf(file, "INDIGO_SIMULATOR_PORT=%s\n", port);
	fprintf(file, "INDIGO_SIMULATOR_TCP_URL=tcp://127.0.0.1:%d\n", tcp_port);
	fprintf(file, "INDIGO_SIMULATOR_PID=%ld\n", (long)getpid());
	if (fclose(file) != 0 || rename(temporary, ready_file) != 0) {
		perror("ready file");
		unlink(temporary);
		return false;
	}
	return true;
}

// reads one available byte of a source and dispatches complete requests; returns false when the source is closed
static bool read_source(request_source *source) {
	char byte;
	ssize_t count = read(source->fd, &byte, 1);
	if (count == 0 || (count < 0 && errno != EAGAIN && errno != EINTR && errno != EIO)) {
		return source == &serial_source;
	}
	if (count < 0) {
		usleep(1000);
		return true;
	}
	source->last_byte = serial_motion_time();
	if (byte == '!') {
		if (source->used) {
			source->request[source->used] = 0;
			event("REJECT", "%s unterminated %s", source->name, source->request);
		}
		source->used = 0;
	} else if (!source->used) {
		event("REJECT", "%s out-of-frame 0x%02x", source->name, (unsigned char)byte);
		return true;
	}
	if (source->used == REQUEST_SIZE - 1) {
		event("REJECT", "%s request too long", source->name);
		source->used = 0;
		return true;
	}
	source->request[source->used++] = byte;
	if (byte == '#') {
		source->request[source->used] = 0;
		reply_fd = source->fd;
		if (source->used > 2) {
			dispatch(source->request);
		}
		source->used = 0;
	}
	return true;
}

static void reset_stale_request(request_source *source) {
	if (source->used && serial_motion_time() - source->last_byte > 0.5) {
		source->request[source->used] = 0;
		event("REJECT", "%s incomplete %s", source->name, source->request);
		source->used = 0;
	}
}

int main(int argc, char **argv) {
	if (!parse_arguments(argc, argv)) {
		return 1;
	}
	fault_file = getenv("INDIGO_BEAVER_FAULT");
	control_file = getenv("INDIGO_BEAVER_CONTROL");
	const char *event_file = getenv("INDIGO_BEAVER_EVENTS");
	events = event_file ? fopen(event_file, "a") : NULL;
	signal(SIGTERM, stop_signal);
	signal(SIGINT, stop_signal);
	signal(SIGPIPE, SIG_IGN);
	char port[PATH_MAX];
	serial_fd = serial_simulator_open_pty(port, sizeof(port));
	if (serial_fd < 0 || (tcp_port >= 0 && !open_tcp_listener()) || (ready_file && !write_ready_file(port))) {
		return 1;
	}
	serial_source.fd = serial_fd;
	event("OPEN", "azimuth=%.1f park=%.1f home=%.1f shutter=%d shutter_up=%d version=%d tcp_port=%d", azimuth(), park_azimuth, home_azimuth, (int)lround(shutter.position), shutter_up, version, tcp_port);
	if (!headless) {
		printf("NexDome Beaver simulator is listening on %s\n", port);
		if (tcp_listen_fd >= 0) {
			printf("NexDome Beaver simulator is listening on tcp://127.0.0.1:%d\n", tcp_port);
		}
		fflush(stdout);
	}
	while (running) {
		apply_control();
		fd_set fds;
		FD_ZERO(&fds);
		FD_SET(serial_fd, &fds);
		int max_fd = serial_fd;
		if (tcp_listen_fd >= 0) {
			FD_SET(tcp_listen_fd, &fds);
			max_fd = tcp_listen_fd > max_fd ? tcp_listen_fd : max_fd;
		}
		if (tcp_source.fd >= 0) {
			FD_SET(tcp_source.fd, &fds);
			max_fd = tcp_source.fd > max_fd ? tcp_source.fd : max_fd;
		}
		struct timeval timeout = { 0, 20000 };
		if (select(max_fd + 1, &fds, NULL, NULL, &timeout) <= 0) {
			reset_stale_request(&serial_source);
			reset_stale_request(&tcp_source);
			continue;
		}
		if (tcp_listen_fd >= 0 && FD_ISSET(tcp_listen_fd, &fds)) {
			int client = accept(tcp_listen_fd, NULL, NULL);
			if (client >= 0) {
				if (tcp_source.fd >= 0) {
					close(tcp_source.fd);
				}
				tcp_source.fd = client;
				tcp_source.used = 0;
				event("STATE", "tcp client connected");
			}
		}
		if (tcp_source.fd >= 0 && FD_ISSET(tcp_source.fd, &fds) && !read_source(&tcp_source)) {
			event("STATE", "tcp client closed");
			close(tcp_source.fd);
			tcp_source.fd = -1;
			tcp_source.used = 0;
		}
		if (FD_ISSET(serial_fd, &fds)) {
			read_source(&serial_source);
		}
	}
	event("STATE", "azimuth=%.1f shutter=%d", azimuth(), (int)lround(serial_motion_update(&shutter)));
	event("CLOSE", "simulator");
	if (tcp_source.fd >= 0) {
		close(tcp_source.fd);
	}
	if (tcp_listen_fd >= 0) {
		close(tcp_listen_fd);
	}
	close(serial_fd);
	if (events) {
		fclose(events);
	}
	return 0;
}
