// Code is generated by AI

// Protocol (BeverAPI.txt): requests "!<group> <command> [arguments]#", replies
// "!<request without #>:<result>#"; result 0 means success, a negative result an
// error. Implemented commands: seletek version/echo/savefs (stops a turning
// rotator)/getfailurecode/getfailuremsg/clearfailure; dome gotoaz/getaz/setaz/
// gohome/gopark/setpark/athome/atpark/abort [all rotation shutter]/status (bit
// field 0..12)/shutterstatus/openshutter/closeshutter/shutterisup/autocalrot/
// autocalshutter/getshutterbatvoltage/sendtoshutter "<shutter or seletek
// command>"; domerot getpos/getpark/setpark/gethome/sethome/athome/atpark/
// getcalibrationstatus. Unknown or rejected requests answer -1.
// Simulator assumptions (undocumented): azimuths are reported with one decimal,
// rotation and shutter move linearly with configurable rates, rotation takes the
// shortest way, atpark requires a stopped rotator within 0.5 degree, athome is a
// 1 degree home sensor, a shutter stopped between its limits reports status 4,
// an open request while open (or close while closed) is accepted without motion,
// abort stops calibrations without an error, a rotator calibration turns one full
// revolution and stops at home, and without a connected shutter shutterstatus
// reports 4 and shutter commands answer -1.
//
// Test hooks (all optional, named by environment variables):
//   INDIGO_BEAVER_EVENTS   event log: "<time> RX|TX|STATE|MOVE|FAULT|CONTROL|REJECT|OPEN|CLOSE <text>"
//   INDIGO_BEAVER_FAULT    "<silent|error|reply|raw|partial|slow|close> <count> <argument|-> <request prefix without !|ANY>"
//                          (error rejects the request with -1 without executing it)
//   INDIGO_BEAVER_CONTROL  lines "<azimuth|rotate|shutter|unsafe|rotfault|shutfault|shutterup|calfail|park|home|version|drop> <value>"
// With --tcp-port the same protocol is also served to one TCP client on
// 127.0.0.1 (0 selects a free port); the ready file then contains
// INDIGO_SIMULATOR_TCP_URL. The "drop" control closes that client connection.

