"""Generate the portable, checked-in MCP help bundle; no runtime file access."""

import argparse
from pathlib import Path
import re
import tempfile

ROOT = Path(__file__).resolve().parents[2]
DOCS = ROOT / "indigo_docs/mcp"
OUTPUT = Path(__file__).with_name("indigo_agent_mcp_help.h")
TOPICS = (
	"README.md", "instructions.md", "server-and-devices.md", "agent-catalog.md",
	"acceptance-scenarios.md", "agents/imager.md", "agents/guider.md",
	"agents/mount.md", "agents/platesolver.md", "agents/astrometry.md",
	"agents/configuration.md", "agents/auxiliary.md", "agents/scripting.md",
	"agents/sequencer.md", "agents/alpaca.md", "agents/mcp.md", "agents/test.md",
	"reference/sequencer.md",
)
SOURCES = {
	topic: (ROOT / "indigo_drivers/agent_scripting/library/Sequencer.md"
			if topic == "reference/sequencer.md" else DOCS / topic)
	for topic in TOPICS
}


def generate():
	targets = {source.resolve(): topic for topic, source in SOURCES.items()}
	output = [
		"// Generated by generate_help.py. Do not edit; source manuals live in indigo_docs/mcp.\n",
		"// Copyright (c) 2026 CloudMakers, s. r. o.\n",
		"// Distributed under the INDIGO Astronomy open-source license (see LICENSE.md).\n\n",
		"typedef struct {\n\tconst char *topic;\n\tconst char *uri;\n\tconst char *title;\n\tconst char *text;\n} mcp_help_document;\n\n",
	]
	titles = []
	for index, (topic, source) in enumerate(SOURCES.items()):
		text = source.read_text(encoding="utf-8")
		title = next(line.lstrip("# ").strip() for line in text.splitlines() if line.startswith("# "))
		titles.append(title)

		def rewrite(match):
			link = match.group(1)
			if ":" in link or link.startswith(("#", "/")):
				return match.group(0)
			path, marker, anchor = link.partition("#")
			target = targets.get((source.parent / path).resolve())
			if target is None:
				return match.group(0)
			return "](indigo://help/" + target + (marker + anchor if marker else "") + ")"

		text = re.sub(r"\]\(([^)]+)\)", rewrite, text)
		if topic == "reference/sequencer.md":
			text = ("> Embedded reference: read the [Sequencer operating manual](indigo://help/agents/sequencer.md) "
					"for interpreter bootstrap and known limitations first. The table below describes the meridian-flip "
					"pause as seconds, but the current implementation forwards it to an Imager setting in hours. "
					"The nonzero offset contract is unresolved; follow the operating manual rather than this conflicting unit.\n\n" + text)
		data = text.encode("utf-8") + b"\0"
		output.append(f"static const unsigned char mcp_help_text_{index}[] = {{\n")
		for offset in range(0, len(data), 20):
			output.append("\t" + ", ".join(f"0x{value:02x}" for value in data[offset:offset + 20]) + ",\n")
		output.append("};\n\n")
	output.append("static const mcp_help_document mcp_help[] = {\n")
	for index, (topic, title) in enumerate(zip(TOPICS, titles)):
		# Metadata is ASCII escaped independently of the compiler source encoding.
		def literal(value):
			return '"' + ''.join(chr(c) if 32 <= c < 127 and c not in (34, 92) else f"\\{c:03o}" for c in value.encode("utf-8")) + '"'
		output.append(f"\t{{ {literal(topic)}, {literal('indigo://help/' + topic)}, {literal(title)}, (const char *)mcp_help_text_{index} }},\n")
	output.append("};\n")
	return "".join(output)


def main():
	parser = argparse.ArgumentParser(description=__doc__)
	parser.add_argument("--check", action="store_true", help="fail if the checked-in bundle is stale")
	args = parser.parse_args()
	content = generate()
	current = OUTPUT.read_text(encoding="ascii") if OUTPUT.exists() else None
	if args.check:
		if current != content:
			parser.exit(1, "MCP help bundle is stale; run python3 indigo_drivers/agent_mcp/generate_help.py\n")
		print(f"MCP help bundle is current ({len(TOPICS)} documents).")
	elif current != content:
		with tempfile.NamedTemporaryFile(mode="w", encoding="ascii", newline="\n", dir=OUTPUT.parent, delete=False) as temporary:
			temporary.write(content)
			name = Path(temporary.name)
		name.replace(OUTPUT)


if __name__ == "__main__":
	main()
