// Code is generated by AI

// Protocol: commands "&<payload>%#", replies "&<payload>#", 9600 8N1. Data
// bytes carry 7-bit values with bit 7 set, packed MSB first (3 bytes = 21 bits,
// 2 bytes = 14 bits); checksums are 0x80 | -(sum % 128) over the bytes after
// the command letter. Behaviour follows dome_talon6ror_simulator.ino (the
// Arduino simulator of the driver author) and the Talon6 RoR user manual:
//   V        "&V3.20N--#"
//   G        "&G" + 20 status bytes + checksum: state << 4 | last action,
//            position, voltage ADU (15/1024 V), timeout timer, power timer,
//            weather timer, switches (close button, COM, MGM), sensors (power
//            lost, weather, mount at park, open, closed, open button, stop
//            button), 5 unused bytes
//   O        open (refused without motion while an enabled power or weather
//            condition is active), last action 1
//   P        close with mount park: waits for the park sensor, or for the
//            configured park delay when it is not 0 (last action 15), then
//            closes with last action 2
//   C        close without park, last action 2
//   S        stop, last action 14 (emergency stop by the user)
//   p        "&p" + 54 configuration bytes + checksum
//   a…       54 configuration bytes + checksum, "&#"; invalid length, data or
//            checksum "&ERROR#"
//   other    "&ERROR#"
// Roof states: 0 open, 1 closed, 2 opening, 3 closing, 4 stopped between the
// end positions. Enabled power/weather conditions close the roof (with park)
// after their delay (last action 7/6), an enabled timeout condition closes it
// the configured time after an accepted open (last action 10).
// Simulator assumptions (undocumented): linear travel over the configured full
// encoder ticks in --travel-time seconds, "&#" acknowledgements, reply to
// unknown commands, keypad buttons latched for 1 s, timers in whole seconds.
//
// Test hooks (all optional, named by environment variables):
//   INDIGO_TALON6ROR_EVENTS   event log "<time> RX|TX|STATE|MOVE|FAULT|CONTROL|REJECT|OPEN|CLOSE <text>";
//                             frames are logged with printable characters as is and other bytes as " XX"
//   INDIGO_TALON6ROR_FAULT    "<command letter|ANY> <silent|error|reply|slow|checksum|short|garbage|long|ignore|close> [count] [argument]"
//   INDIGO_TALON6ROR_CONTROL  lines "<position|weather|power|parked|button|com|mgm|voltage|stall|travel-time|noise> <value>"

