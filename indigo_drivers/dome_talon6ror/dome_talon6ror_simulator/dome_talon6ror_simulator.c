#define CONFIGURATION_LENGTH 55
#define STATUS_LENGTH 21
#define REQUEST_LENGTH 128

#define STATE_OPEN 0
#define STATE_CLOSED 1
#define STATE_OPENING 2
#define STATE_CLOSING 3
#define STATE_ERROR 4

#define ACTION_OPEN 1
#define ACTION_CLOSE 2
#define ACTION_WEATHER 6
#define ACTION_POWER 7
#define ACTION_TIMEOUT 10
#define ACTION_STALL 13
#define ACTION_STOP 14
#define ACTION_PARK 15

static const char *ready_file, *fault_file, *control_file;
static FILE *events;
static bool trace, headless;
static volatile sig_atomic_t running = 1;
static int serial_fd = -1;
static serial_motion roof;
static double travel_time = 3;
static int last_action, voltage = 836;
static bool power_lost, weather, parked = true, com_input, mgm_input;
static double open_button, close_button, stop_button;
static double weather_deadline, power_deadline, timeout_deadline, park_deadline;
static bool close_pending;
static int close_pending_action;

// dome_talon6ror_simulator.ino defaults: KP 180, KI 140, KD 2, speeds 100/14, acceleration 20, park delay 120,
// weather 60, power 54, communication 60, maximum aperture 0, IP switch 120, full travel 50000, ramp 5,
// timeout 0, encoder factor 4, reverse 0, no close conditions, TW time 120
static uint8_t configuration[CONFIGURATION_LENGTH] = {
	0x80, 0x81, 0xB4, 0x80, 0x81, 0x8C, 0x80, 0x80, 0x82, 0x80, 0x80, 0xE4, 0x80, 0x80, 0x8E, 0x80, 0x80, 0x94, 0x80, 0x80, 0xF8, 0x80, 0x80, 0xBC, 0x80, 0x80, 0xB6, 0x80, 0x80, 0xBC, 0x80, 0x80, 0x80, 0x80, 0x80, 0xF8, 0x83, 0x86, 0xD0, 0x80, 0x80, 0x85, 0x80, 0x80, 0x80, 0x84, 0xA0, 0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0xF8, 0x9E
};

static void event(const char *kind, const char *format, ...) __attribute__((format(printf, 2, 3)));

static void event(const char *kind, const char *format, ...) {
	if (!events) {
		return;
	}
	fprintf(events, "%.6f %s ", serial_motion_time(), kind);
	va_list args;
	va_start(args, format);
	vfprintf(events, format, args);
	va_end(args);
	fputc('\n', events);
	fflush(events);
}

static void render(const uint8_t *data, size_t length, char *text, size_t size) {
	size_t used = 0;
	text[0] = 0;
	for (size_t i = 0; i < length && used + 4 < size; i++) {
		if (data[i] >= 32 && data[i] < 127) {
			text[used++] = (char)data[i];
		} else {
			used += (size_t)snprintf(text + used, size - used, " %02X", data[i]);
		}
		text[used] = 0;
	}
}

static void stop_signal(int signal) {
	(void)signal;
	running = 0;
}

static int unpack3(const uint8_t *data) {
	return ((data[0] & 0x7F) << 14) | ((data[1] & 0x7F) << 7) | (data[2] & 0x7F);
}

static void pack3(uint8_t *data, int value) {
	data[0] = 0x80 | ((value >> 14) & 0x7F);
	data[1] = 0x80 | ((value >> 7) & 0x7F);
	data[2] = 0x80 | (value & 0x7F);
}

static void pack2(uint8_t *data, int value) {
	data[0] = 0x80 | ((value >> 7) & 0x7F);
	data[1] = 0x80 | (value & 0x7F);
}

static uint8_t checksum(const uint8_t *data, size_t length) {
	int sum = 0;
	for (size_t i = 0; i < length; i++) {
		sum += data[i];
	}
	return (uint8_t)(0x80 | (-(sum % 128) & 0x7F));
}

// configuration indices (0-based, without the command letter)
static int full_travel(void) {
	int ticks = unpack3(configuration + 36);
	return ticks > 0 ? ticks : 1;
}

static int park_delay(void) {
	return unpack3(configuration + 18);
}

static int weather_delay(void) {
	return unpack3(configuration + 21);
}

static int power_delay(void) {
	return unpack3(configuration + 24);
}

static int timeout_delay(void) {
	return unpack3(configuration + 42);
}

static bool power_enabled(void) {
	return configuration[47] & 0x01;
}

static bool weather_enabled(void) {
	return configuration[47] & 0x02;
}

static bool timeout_enabled(void) {
	return configuration[47] & 0x04;
}

static int position(void) {
	return (int)lround(serial_motion_update(&roof));
}

static bool moving(void) {
	serial_motion_update(&roof);
	return roof.duration > 0;
}

static int roof_state(void) {
	int current = position();
	if (moving()) {
		return roof.target > roof.origin ? STATE_OPENING : STATE_CLOSING;
	}
	if (current >= full_travel()) {
		return STATE_OPEN;
	}
	if (current <= 0) {
		return STATE_CLOSED;
	}
	return STATE_ERROR;
}

static void move_roof(int target, int action, const char *origin) {
	int current = position();
	serial_motion_sync(&roof, current);
	if (current != target) {
		serial_motion_start(&roof, target, full_travel() / travel_time);
	}
	last_action = action;
	event("MOVE", "%s from=%d to=%d action=%d", origin, current, target, action);
}

static void stop_roof(int action, const char *origin) {
	serial_motion_stop(&roof);
	close_pending = false;
	last_action = action;
	event("STATE", "%s stopped at=%d action=%d", origin, position(), action);
}

static int timer_value(double deadline) {
	if (deadline <= 0) {
		return 0;
	}
	double remaining = deadline - serial_motion_time();
	return remaining > 0 ? (int)ceil(remaining) : 0;
}

static bool condition_blocks_open(void) {
	return (power_lost && power_enabled()) || (weather && weather_enabled());
}

static void close_roof(int action, bool with_park, const char *origin) {
	if (with_park && !parked) {
		close_pending = true;
		close_pending_action = action;
		park_deadline = park_delay() > 0 ? serial_motion_time() + park_delay() : 0;
		last_action = ACTION_PARK;
		event("STATE", "%s waits for mount park action=%d delay=%d", origin, action, park_delay());
		return;
	}
	close_pending = false;
	timeout_deadline = 0;
	move_roof(0, action, origin);
}

static bool open_roof(const char *origin) {
	if (condition_blocks_open()) {
		event("REJECT", "%s open blocked by safety condition power=%d weather=%d", origin, power_lost, weather);
		return false;
	}
	close_pending = false;
	move_roof(full_travel(), ACTION_OPEN, origin);
	timeout_deadline = timeout_enabled() ? serial_motion_time() + timeout_delay() : 0;
	return true;
}

static double condition_deadline(bool active, bool enabled, int delay, double deadline, int action, const char *name) {
	if (!active || !enabled || (roof_state() == STATE_CLOSED) || (moving() && roof.target <= 0) || close_pending) {
		return 0;
	}
	double now = serial_motion_time();
	if (deadline <= 0) {
		return now + delay;
	}
	if (now >= deadline) {
		close_roof(action, true, name);
		return 0;
	}
	return deadline;
}

static void update(void) {
	double now = serial_motion_time();
	static bool was_moving;
	bool is_moving = moving();
	if (was_moving && !is_moving) {
		event("STATE", "roof stopped at=%d state=%d", position(), roof_state());
	}
	was_moving = is_moving;
	weather_deadline = condition_deadline(weather, weather_enabled(), weather_delay(), weather_deadline, ACTION_WEATHER, "weather");
	power_deadline = condition_deadline(power_lost, power_enabled(), power_delay(), power_deadline, ACTION_POWER, "power");
	if (timeout_deadline > 0 && now >= timeout_deadline) {
		timeout_deadline = 0;
		close_roof(ACTION_TIMEOUT, true, "timeout");
	}
	if (close_pending && (parked || (park_deadline > 0 && now >= park_deadline))) {
		close_pending = false;
		timeout_deadline = 0;
		move_roof(0, close_pending_action, parked ? "parked" : "park delay");
	}
}

static size_t make_status(uint8_t *reply) {
	uint8_t *status = reply + 2;
	int current = position();
	memset(status, 0x80, STATUS_LENGTH);
	status[0] = 0x80 | ((roof_state() & 0x07) << 4) | (last_action & 0x0F);
	pack3(status + 1, current);
	pack2(status + 4, voltage);
	pack3(status + 6, timer_value(timeout_deadline));
	pack2(status + 9, timer_value(power_deadline));
	pack2(status + 11, timer_value(weather_deadline));
	double now = serial_motion_time();
	status[13] = 0x80 | (close_button > now ? 0x01 : 0) | (com_input ? 0x02 : 0) | (mgm_input ? 0x04 : 0);
	status[14] = 0x80 | (power_lost ? 0x01 : 0) | (weather ? 0x02 : 0) | (parked ? 0x04 : 0) | (current >= full_travel() ? 0x08 : 0) | (current <= 0 ? 0x10 : 0) | (open_button > now ? 0x20 : 0) | (stop_button > now ? 0x40 : 0);
	status[17] = 0x84;
	status[20] = checksum(status, 20);
	reply[0] = '&';
	reply[1] = 'G';
	reply[2 + STATUS_LENGTH] = '#';
	return STATUS_LENGTH + 3;
}

static size_t make_configuration(uint8_t *reply) {
	configuration[54] = checksum(configuration, 54);
	reply[0] = '&';
	reply[1] = 'p';
	memcpy(reply + 2, configuration, CONFIGURATION_LENGTH);
	reply[2 + CONFIGURATION_LENGTH] = '#';
	return CONFIGURATION_LENGTH + 3;
}

static size_t copy_text(uint8_t *reply, const char *text) {
	size_t length = strlen(text);
	memcpy(reply, text, length);
	return length;
}

static size_t write_configuration(const uint8_t *payload, size_t length, uint8_t *reply) {
	if (length != CONFIGURATION_LENGTH + 1) {
		event("REJECT", "configuration length=%zu", length - 1);
		return copy_text(reply, "&ERROR#");
	}
	for (size_t i = 1; i < length; i++) {
		if (!(payload[i] & 0x80)) {
			event("REJECT", "configuration byte %zu=0x%02X", i, payload[i]);
			return copy_text(reply, "&ERROR#");
		}
	}
	if (payload[55] != checksum(payload + 1, 54)) {
		event("REJECT", "configuration checksum 0x%02X expected 0x%02X", payload[55], checksum(payload + 1, 54));
		return copy_text(reply, "&ERROR#");
	}
	memcpy(configuration, payload + 1, CONFIGURATION_LENGTH);
	event("STATE", "configuration kp=%d park=%d weather=%d power=%d travel=%d timeout=%d encoder=%d reverse=%d conditions=%d", unpack3(configuration), park_delay(), weather_delay(), power_delay(), full_travel(), timeout_delay(), configuration[45] & 0x7F, configuration[46] & 0x0F, configuration[47] & 0x07);
	if (timeout_enabled() && roof_state() != STATE_CLOSED && timeout_deadline <= 0) {
		timeout_deadline = serial_motion_time() + timeout_delay();
	} else if (!timeout_enabled()) {
		timeout_deadline = 0;
	}
	return copy_text(reply, "&#");
}

static size_t execute(const uint8_t *payload, size_t length, uint8_t *reply) {
	if (length == 1) {
		switch (payload[0]) {
			case 'V':
				return copy_text(reply, "&V3.20N--#");
			case 'G':
				return make_status(reply);
			case 'p':
				return make_configuration(reply);
			case 'O':
				open_roof("command");
				return copy_text(reply, "&#");
			case 'P':
				close_roof(ACTION_CLOSE, true, "command");
				return copy_text(reply, "&#");
			case 'C':
				close_roof(ACTION_CLOSE, false, "command");
				return copy_text(reply, "&#");
			case 'S':
				stop_roof(ACTION_STOP, "command");
				return copy_text(reply, "&#");
			default:
				break;
		}
	} else if (length > 1 && payload[0] == 'a') {
		return write_configuration(payload, length, reply);
	}
	event("REJECT", "unsupported command");
	return copy_text(reply, "&ERROR#");
}

static bool fault(char letter, char *action, char *text) {
	if (!fault_file) {
		return false;
	}
	FILE *file = fopen(fault_file, "r");
	if (!file) {
		return false;
	}
	char command[16] = "";
	int count = 1;
	*text = 0;
	int fields = fscanf(file, "%15s %15s %d %127s", command, action, &count, text);
	fclose(file);
	if (fields < 2 || (strcmp(command, "ANY") && (strlen(command) != 1 || command[0] != letter))) {
		return false;
	}
	if (--count <= 0) {
		unlink(fault_file);
	} else {
		char temporary[PATH_MAX];
		snprintf(temporary, sizeof(temporary), "%s.sim", fault_file);
		file = fopen(temporary, "w");
		if (file) {
			fprintf(file, "%s %s %d %s\n", command, action, count, text);
			fclose(file);
			rename(temporary, fault_file);
		}
	}
	event("FAULT", "%c %s %s", letter, action, text);
	return true;
}

static void write_reply(const uint8_t *reply, size_t length) {
	char text[512];
	render(reply, length, text, sizeof(text));
	event("TX", "%s", text);
	serial_simulator_trace_line(trace, "<-", text);
	serial_simulator_write_all(serial_fd, (const char *)reply, length);
}

static void dispatch(const uint8_t *request, size_t length) {
	uint8_t reply[REQUEST_LENGTH * 2];
	char text[512], action[16], argument[128];
	render(request, length, text, sizeof(text));
	event("RX", "%s", text);
	serial_simulator_trace_line(trace, "->", text);
	// request is "&<payload>%#"
	if (length < 3 || request[length - 2] != '%') {
		event("REJECT", "missing %% terminator");
		write_reply((const uint8_t *)"&ERROR#", 7);
		return;
	}
	const uint8_t *payload = request + 1;
	size_t payload_length = length - 3;
	char letter = payload_length > 0 ? (char)payload[0] : 0;
	if (fault(letter, action, argument)) {
		if (!strcmp(action, "silent")) {
			return;
		} else if (!strcmp(action, "error")) {
			write_reply((const uint8_t *)"&ERROR#", 7);
			return;
		} else if (!strcmp(action, "reply")) {
			write_reply((const uint8_t *)argument, strlen(argument));
			return;
		} else if (!strcmp(action, "ignore")) {
			write_reply((const uint8_t *)"&#", 2);
			return;
		} else if (!strcmp(action, "long")) {
			uint8_t buffer[101];
			buffer[0] = '&';
			memset(buffer + 1, 0x80, 100);
			write_reply(buffer, sizeof(buffer));
			return;
		} else if (!strcmp(action, "close")) {
			running = 0;
			return;
		}
		size_t reply_length = execute(payload, payload_length, reply);
		if (!strcmp(action, "slow")) {
			int delay = atoi(argument);
			usleep((useconds_t)(delay > 0 ? delay : 1000) * 1000);
		} else if (!strcmp(action, "checksum") && reply_length > 3) {
			reply[reply_length - 2] ^= 0x01;
		} else if (!strcmp(action, "short") && reply_length > 4) {
			reply_length = reply_length / 2;
			reply[reply_length++] = '#';
		} else if (!strcmp(action, "garbage")) {
			static const uint8_t noise[] = "x#\r\nreset\r\n";
			write_reply(noise, sizeof(noise) - 1);
		}
		write_reply(reply, reply_length);
		return;
	}
	write_reply(reply, execute(payload, payload_length, reply));
}

static void apply_control(void) {
	if (!control_file) {
		return;
	}
	FILE *file = fopen(control_file, "r");
	if (!file) {
		return;
	}
	char key[32], value[128];
	double now = serial_motion_time();
	while (fscanf(file, "%31s %127s", key, value) == 2) {
		if (!strcmp(key, "position")) {
			serial_motion_sync(&roof, atoi(value));
		} else if (!strcmp(key, "weather")) {
			weather = atoi(value) != 0;
		} else if (!strcmp(key, "power")) {
			power_lost = atoi(value) != 0;
		} else if (!strcmp(key, "parked")) {
			parked = atoi(value) != 0;
		} else if (!strcmp(key, "com")) {
			com_input = atoi(value) != 0;
		} else if (!strcmp(key, "mgm")) {
			mgm_input = atoi(value) != 0;
		} else if (!strcmp(key, "voltage")) {
			voltage = atoi(value);
		} else if (!strcmp(key, "travel-time") && atof(value) > 0) {
			travel_time = atof(value);
		} else if (!strcmp(key, "stall")) {
			stop_roof(ACTION_STALL, "stall");
		} else if (!strcmp(key, "button") && !strcmp(value, "open")) {
			open_button = now + 1;
			open_roof("button");
		} else if (!strcmp(key, "button") && !strcmp(value, "close")) {
			close_button = now + 1;
			close_roof(ACTION_CLOSE, false, "button");
		} else if (!strcmp(key, "button") && !strcmp(value, "stop")) {
			stop_button = now + 1;
			stop_roof(last_action, "button");
		} else if (!strcmp(key, "noise")) {
			serial_simulator_write_all(serial_fd, value, strlen(value));
		}
		event("CONTROL", "%s %s", key, value);
	}
	fclose(file);
	unlink(control_file);
}

static bool parse_arguments(int argc, char **argv) {
	for (int i = 1; i < argc; i++) {
		if (!strcmp(argv[i], "--headless")) {
			headless = true;
		} else if (!strcmp(argv[i], "--trace")) {
			trace = true;
		} else if (i + 1 < argc && !strcmp(argv[i], "--ready-file")) {
			ready_file = argv[++i];
		} else if (i + 1 < argc && !strcmp(argv[i], "--position")) {
			serial_motion_sync(&roof, atoi(argv[++i]));
		} else if (i + 1 < argc && !strcmp(argv[i], "--travel-time")) {
			travel_time = atof(argv[++i]);
		} else if (i + 1 < argc && !strcmp(argv[i], "--parked")) {
			parked = atoi(argv[++i]) != 0;
		} else if (i + 1 < argc && !strcmp(argv[i], "--last-action")) {
			last_action = atoi(argv[++i]) & 0x0F;
		} else if (i + 1 < argc && !strcmp(argv[i], "--conditions")) {
			configuration[47] = 0x80 | (atoi(argv[++i]) & 0x07);
		} else if (!strcmp(argv[i], "--help") || !strcmp(argv[i], "-h")) {
			printf("Usage: %s [--headless] [--trace] [--ready-file PATH] [--position TICKS] [--travel-time S] [--parked 0|1] [--last-action N] [--conditions BITS]\n", argv[0]);
			exit(0);
		} else {
			fprintf(stderr, "Unknown/incomplete option '%s'\n", argv[i]);
			return false;
		}
	}
	if (travel_time <= 0) {
		fprintf(stderr, "Travel time must be positive\n");
		return false;
	}
	return true;
}

int main(int argc, char **argv) {
	if (!parse_arguments(argc, argv)) {
		return 1;
	}
	fault_file = getenv("INDIGO_TALON6ROR_FAULT");
	control_file = getenv("INDIGO_TALON6ROR_CONTROL");
	const char *event_file = getenv("INDIGO_TALON6ROR_EVENTS");
	events = event_file ? fopen(event_file, "a") : NULL;
	signal(SIGTERM, stop_signal);
	signal(SIGINT, stop_signal);
	signal(SIGPIPE, SIG_IGN);
	char port[PATH_MAX];
	serial_fd = serial_simulator_open_pty(port, sizeof(port));
	if (serial_fd < 0 || (ready_file && !serial_simulator_write_ready_file(ready_file, "dome_talon6ror_simulator", port))) {
		return 1;
	}
	event("OPEN", "position=%d travel=%d parked=%d action=%d", position(), full_travel(), parked, last_action);
	if (!headless) {
		printf("Talon6 ROR simulator is listening on %s\n", port);
		fflush(stdout);
	}
	uint8_t request[REQUEST_LENGTH];
	size_t used = 0;
	bool framing = false;
	while (running) {
		apply_control();
		update();
		fd_set fds;
		FD_ZERO(&fds);
		FD_SET(serial_fd, &fds);
		struct timeval timeout = { 0, 20000 };
		if (select(serial_fd + 1, &fds, NULL, NULL, &timeout) <= 0) {
			continue;
		}
		uint8_t byte;
		ssize_t count = read(serial_fd, &byte, 1);
		if (count <= 0) {
			if (count < 0 && errno != EAGAIN && errno != EINTR && errno != EIO) {
				break;
			}
			usleep(1000);
			continue;
		}
		if (byte == '&') {
			if (framing && used > 1) {
				event("REJECT", "incomplete frame of %zu bytes", used);
			}
			framing = true;
			used = 0;
		} else if (!framing) {
			event("REJECT", "out-of-frame 0x%02X", byte);
			continue;
		}
		if (used == sizeof(request)) {
			event("REJECT", "overlong frame");
			framing = false;
			used = 0;
			continue;
		}
		request[used++] = byte;
		if (byte == '#') {
			dispatch(request, used);
			framing = false;
			used = 0;
		}
	}
	event("STATE", "position=%d state=%d action=%d", position(), roof_state(), last_action);
	event("CLOSE", "simulator");
	close(serial_fd);
	if (events) {
		fclose(events);
	}
	return 0;
}
