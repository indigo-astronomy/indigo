#!/usr/bin/env python3
"""Generate a navigation index from canonical ADRs; never infer decisions from prose."""
import argparse
from datetime import date
from pathlib import Path
import re
import sys
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[2]
INDEX = 'indigo_docs/decisions/README.md'
LIMIT = 1024 * 1024
ADR = re.compile(r'indigo_docs/decisions/(ADR-[0-9]+)(?:-[A-Za-z0-9_-]+)?\.md')


def cell(value):
    return value.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;').replace('|', '&#124;').replace('[', '&#91;').replace(']', '&#93;')


def render(names, read):
    rows, ids = [], set()
    for name in sorted(names):
        match = ADR.fullmatch(name)
        if not match:
            if name.startswith('indigo_docs/decisions/ADR-') and name.endswith('.md') and name.count('/') == 2:
                raise ValueError('invalid ADR filename: ' + name)
            continue
        text = read(name)
        title = re.findall(r'^# (ADR-[0-9]+): (.+)$', text, re.M)
        metadata = {}
        for key in ('Status', 'Date', 'Decision owner', 'Related task'):
            values = re.findall(r'^- ' + key + r': (.+)$', text, re.M)
            if len(values) != 1 or values[0].strip() in ('TODO', ''):
                raise ValueError('ADR needs unique populated metadata: ' + name)
            metadata[key] = values[0].strip()
        if len(title) != 1 or title[0][0] != match[1] or int(match[1][4:]) in ids:
            raise ValueError('ADR title/ID is invalid or duplicated: ' + name)
        if metadata['Status'] not in ('proposed', 'accepted', 'superseded'):
            raise ValueError('invalid ADR status: ' + name)
        try:
            if not re.fullmatch(r'[0-9]{4}-[0-9]{2}-[0-9]{2}', metadata['Date']):
                raise ValueError('date format')
            date.fromisoformat(metadata['Date'])
        except ValueError:
            raise ValueError('invalid ADR date: ' + name) from None
        ids.add(int(match[1][4:]))
        rows.append((int(match[1][4:]), name, title[0][1], metadata))
    lines = ['# Decision index', '',
             'Generated by `python3 .factory/scripts/decision_index.py`. Edit the linked ADRs, then regenerate.',
             'This index is navigation; the original records contain the decisions and their authority.', '',
             '| Decision | Status | Date | Owner | Related task |',
             '| --- | --- | --- | --- | --- |']
    for _, name, title, meta in sorted(rows):
        label = cell(ADR.fullmatch(name)[1] + ': ' + title)
        values = [f'[{label}]({quote(Path(name).name)})']
        values.extend(cell(meta[k]) for k in ('Status', 'Date', 'Decision owner', 'Related task'))
        lines.append('| ' + ' | '.join(values) + ' |')
    if not rows:
        lines.append('| — | No ADRs recorded | — | — | — |')
    return '\n'.join(lines) + '\n'


def local_read(name):
    path = ROOT / name
    for part in (path, *path.parents):
        if part == ROOT:
            break
        if part.is_symlink():
            raise ValueError('decision inputs/output must not be symlinks')
    with path.open('rb') as stream:
        data = stream.read(LIMIT + 1)
    if len(data) > LIMIT:
        raise ValueError('decision input exceeds 1 MiB')
    return data.decode('utf-8')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail on missing/stale index, write nothing')
    args = parser.parse_args()
    try:
        directory = ROOT / 'indigo_docs/decisions'
        if directory.is_symlink() or not directory.is_dir() or (ROOT / 'indigo_docs').is_symlink():
            raise ValueError('indigo_docs/decisions must be a real directory')
        names = [p.relative_to(ROOT).as_posix() for p in directory.iterdir()]
        expected = render(names, local_read)
        output = ROOT / INDEX
        if output.is_symlink():
            raise ValueError('decision index must not be a symlink')
        if args.check:
            if not output.is_file() or local_read(INDEX) != expected:
                print('Decision index is stale; run python3 .factory/scripts/decision_index.py', file=sys.stderr)
                return 1
        else:
            output.write_text(expected, encoding='utf-8')
    except (OSError, ValueError) as exc:
        print('Decision index failed: ' + str(exc), file=sys.stderr)
        return 2
    print('Decision index current.' if args.check else 'Decision index generated.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
