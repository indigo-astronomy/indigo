static int connect_client(void) {
	int fd = socket(AF_INET, SOCK_STREAM, 0);
	if (fd < 0) {
		return -1;
	}
	struct sockaddr_in address = { 0 };
	address.sin_family = AF_INET;
	address.sin_port = htons(indigo_server_tcp_port);
	address.sin_addr.s_addr = htonl(INADDR_LOOPBACK);
	struct timeval timeout = { 3, 0 };
	setsockopt(fd, SOL_SOCKET, SO_RCVTIMEO, &timeout, sizeof(timeout));
	setsockopt(fd, SOL_SOCKET, SO_SNDTIMEO, &timeout, sizeof(timeout));
	int enabled = 1;
	setsockopt(fd, IPPROTO_TCP, TCP_NODELAY, &enabled, sizeof(enabled));
	if (connect(fd, (struct sockaddr *)&address, sizeof(address)) != 0) {
		close(fd);
		return -1;
	}
	return fd;
}

static bool send_bytes(int fd, const void *bytes, size_t size) {
	const char *cursor = bytes;
	while (size) {
		ssize_t count = write(fd, cursor, size);
		if (count <= 0) {
			return false;
		}
		cursor += count;
		size -= count;
	}
	return true;
}

static bool receive_closed(int fd, char *response, size_t capacity) {
	size_t size = 0;
	while (size + 1 < capacity) {
		ssize_t count = read(fd, response + size, capacity - size - 1);
		if (count == 0 || (count < 0 && errno == ECONNRESET)) {
			response[size] = 0;
			return true;
		}
		if (count < 0) {
			response[size] = 0;
			return false;
		}
		size += count;
	}
	response[size] = 0;
	return false;
}

static bool exchange(const void *request, size_t size, char *response, size_t capacity) {
	int fd = connect_client();
	if (fd < 0) {
		return false;
	}
	bool sent = send_bytes(fd, request, size);
	shutdown(fd, SHUT_WR);
	bool closed = receive_closed(fd, response, capacity);
	close(fd);
	return sent && closed;
}

static void capture_handler(indigo_uni_handle *handle, const indigo_http_request *request, void *context) {
	pthread_mutex_lock(&fixture_mutex);
	memset(&observed, 0, sizeof(observed));
	snprintf(observed.method, sizeof(observed.method), "%s", request->method);
	snprintf(observed.path, sizeof(observed.path), "%s", request->path);
	snprintf(observed.query, sizeof(observed.query), "%s", request->query ? request->query : "<absent>");
	const char *first = indigo_server_http_header(request, "x-test");
	snprintf(observed.first_header, sizeof(observed.first_header), "%s", first ? first : "<absent>");
	for (size_t i = 0; i < request->header_count; i++) {
		if (!strcasecmp(request->headers[i].name, "X-Test")) {
			if (++observed.duplicate_count == 2) {
				snprintf(observed.second_header, sizeof(observed.second_header), "%s", request->headers[i].value);
			}
		}
	}
	observed.context_matches = context == &context_marker;
	observed.body_length = request->body_length;
	for (size_t i = 0; i < request->body_length; i++) {
		observed.byte_sum += request->body[i];
	}
	observed.empty_body_is_null = request->body == NULL;
	if (request->body_length > 0 && request->body_length <= sizeof(observed.body)) {
		memcpy(observed.body, request->body, request->body_length);
	}
	atomic_fetch_add(&calls, 1);
	pthread_cond_broadcast(&fixture_condition);
	while (hold_callbacks) {
		pthread_cond_wait(&fixture_condition, &fixture_mutex);
	}
	pthread_mutex_unlock(&fixture_mutex);
	indigo_uni_printf(handle, "HTTP/1.1 200 OK\r\nContent-Length: 2\r\nConnection: close\r\n\r\nok");
}

