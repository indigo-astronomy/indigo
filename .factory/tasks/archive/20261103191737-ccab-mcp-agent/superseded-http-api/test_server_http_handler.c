static bool legacy_handler(indigo_uni_handle *handle, char *method, char *path, char *params) {
	atomic_fetch_add(&legacy_calls, 1);
	if (!strcmp(method, "PUT")) {
		char header[1024], body[4];
		bool length_seen = false;
		while (indigo_uni_read_line(handle, header, sizeof(header) - 1) > 0) {
			length_seen = length_seen || !strcmp(header, "Content-Length: 4");
		}
		if (!length_seen || indigo_uni_read(handle, body, sizeof(body)) != sizeof(body) || memcmp(body, "\0dat", 4)) {
			indigo_uni_printf(handle, "HTTP/1.1 500 Failed\r\nContent-Length: 0\r\nConnection: close\r\n\r\n");
			return false;
		}
	}
	indigo_uni_printf(handle, "HTTP/1.1 200 OK\r\nContent-Length: 0\r\nConnection: close\r\nX-Legacy: yes\r\n\r\n");
	return false;
}

static bool rejected(const void *request, size_t size, int expected_status) {
	int before = atomic_load(&calls);
	char response[1024];
	bool closed = exchange(request, size, response, sizeof(response));
	int status = 0;
	sscanf(response, "HTTP/1.1 %d", &status);
	return closed && atomic_load(&calls) == before && status == expected_status;
}

