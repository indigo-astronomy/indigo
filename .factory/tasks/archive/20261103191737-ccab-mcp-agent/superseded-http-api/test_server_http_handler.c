static void release_callbacks(void) {
	pthread_mutex_lock(&fixture_mutex);
	hold_callbacks = false;
	pthread_cond_broadcast(&fixture_condition);
	pthread_mutex_unlock(&fixture_mutex);
}

static void admission_limit_rejects_excess_without_callback(void) {
	pthread_mutex_lock(&fixture_mutex);
	hold_callbacks = true;
	pthread_mutex_unlock(&fixture_mutex);
	int fds[INDIGO_HTTP_MAX_REQUESTS];
	int before = atomic_load(&calls);
	bool accepted = true;
	const char request[] = "GET /http-test HTTP/1.1\r\n\r\n";
	for (size_t i = 0; i < INDIGO_HTTP_MAX_REQUESTS; i++) {
		fds[i] = connect_client();
		accepted = accepted && fds[i] >= 0;
		if (fds[i] >= 0) {
			accepted = send_bytes(fds[i], request, sizeof(request) - 1) && accepted;
		}
	}
	accepted = WAIT_UNTIL(atomic_load(&calls) == before + INDIGO_HTTP_MAX_REQUESTS, 2) && accepted;
	char response[1024];
	bool refused = exchange(request, sizeof(request) - 1, response, sizeof(response));
	int status = 0;
	sscanf(response, "HTTP/1.1 %d", &status);
	int reached = atomic_load(&calls);
	release_callbacks();
	bool drained = true;
	for (size_t i = 0; i < INDIGO_HTTP_MAX_REQUESTS; i++) {
		if (fds[i] >= 0) {
			drained = receive_closed(fds[i], response, sizeof(response)) && drained;
			close(fds[i]);
		}
	}
	ASSERT_TRUE(accepted && refused && status == 503 && drained);
	ASSERT_EQ_INT(before + INDIGO_HTTP_MAX_REQUESTS, reached);
}

static void removal_waits_for_active_callback_and_route_can_be_reused(void) {
	pthread_mutex_lock(&fixture_mutex);
	hold_callbacks = true;
	pthread_mutex_unlock(&fixture_mutex);
	int fd = connect_client();
	ASSERT_TRUE(fd >= 0);
	const char request[] = "GET /http-test HTTP/1.1\r\n\r\n";
	int before = atomic_load(&calls);
	bool sent = send_bytes(fd, request, sizeof(request) - 1);
	bool entered = WAIT_UNTIL(atomic_load(&calls) == before + 1, 1);
	atomic_store(&removal_started, false);
	atomic_store(&removal_finished, false);
	pthread_t remover;
	bool spawned = pthread_create(&remover, NULL, remove_handler, "/http-test") == 0;
	bool started = spawned && WAIT_UNTIL(atomic_load(&removal_started), 1);
	bool registered = started && WAIT_UNTIL(indigo_server_add_http_handler("/http-test", capture_handler, &context_marker), 1);
	bool waited = registered && !atomic_load(&removal_finished);
	release_callbacks();
	char response[1024];
	bool closed = receive_closed(fd, response, sizeof(response));
	close(fd);
	if (spawned) {
		pthread_join(remover, NULL);
	}
	ASSERT_TRUE(sent && entered && started && waited && closed && registered);
	ASSERT_TRUE(atomic_load(&removal_finished));
}

static void removal_during_incomplete_body_has_a_finite_deadline(void) {
	ASSERT_TRUE(indigo_server_add_http_handler("/body-drain", capture_handler, &context_marker));
	pthread_mutex_lock(&fixture_mutex);
	hold_callbacks = true;
	pthread_mutex_unlock(&fixture_mutex);
	int fds[INDIGO_HTTP_MAX_REQUESTS - 1];
	int before = atomic_load(&calls);
	bool accepted = true;
	const char held[] = "GET /http-test HTTP/1.1\r\n\r\n";
	for (size_t i = 0; i < INDIGO_HTTP_MAX_REQUESTS - 1; i++) {
		fds[i] = connect_client();
		accepted = accepted && fds[i] >= 0;
		if (fds[i] >= 0) {
			accepted = send_bytes(fds[i], held, sizeof(held) - 1) && accepted;
		}
	}
	accepted = WAIT_UNTIL(atomic_load(&calls) == before + INDIGO_HTTP_MAX_REQUESTS - 1, 2) && accepted;
	int fd = connect_client();
	const char request[] = "POST /body-drain HTTP/1.1\r\nContent-Length: 8\r\n\r\na";
	bool sent = fd >= 0 && send_bytes(fd, request, sizeof(request) - 1);
	// Fifteen barrier-held callbacks plus the partial body fill admission. A 503
	// response proves that the body read acquired the sixteenth request reference.
	char probe[1024];
	const char probe_request[] = "GET /probe HTTP/1.1\r\n\r\n";
	bool admitted = WAIT_UNTIL(exchange(probe_request, sizeof(probe_request) - 1, probe, sizeof(probe)) && strstr(probe, "HTTP/1.1 503 ") != NULL, 0.2);
	atomic_store(&removal_started, false);
	atomic_store(&removal_finished, false);
	pthread_t remover;
	bool spawned = pthread_create(&remover, NULL, remove_handler, "/body-drain") == 0;
	bool withdrawn = spawned && WAIT_UNTIL(indigo_server_add_http_handler("/body-drain", capture_handler, &context_marker), 1);
	bool waited = withdrawn && !atomic_load(&removal_finished);
	bool completed = spawned && WAIT_UNTIL(atomic_load(&removal_finished), 2);
	char response[1024];
	bool closed = fd >= 0 && receive_closed(fd, response, sizeof(response));
	if (fd >= 0) {
		close(fd);
	}
	if (spawned) {
		pthread_join(remover, NULL);
	}
	indigo_server_remove_resource("/body-drain");
	release_callbacks();
	bool drained = true;
	for (size_t i = 0; i < INDIGO_HTTP_MAX_REQUESTS - 1; i++) {
		if (fds[i] >= 0) {
			drained = receive_closed(fds[i], probe, sizeof(probe)) && drained;
			close(fds[i]);
		}
	}
	ASSERT_TRUE(sent && accepted && admitted && withdrawn && waited && completed && closed && drained);
	ASSERT_TRUE(strstr(response, "HTTP/1.1 408 ") != NULL);
	ASSERT_EQ_INT(before + INDIGO_HTTP_MAX_REQUESTS - 1, atomic_load(&calls));
}

