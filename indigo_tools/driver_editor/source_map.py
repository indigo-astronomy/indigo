# Code is generated by AI

"""Associate existing generated C with DSL nodes without changing the generator."""

import bisect
import re

from driver_format import DEVICES, PROPERTIES, attributes, walk

def compact(lines):
	ranges = []
	for line in sorted(lines):
		if ranges and line == ranges[-1]['endLine'] + 1:
			ranges[-1]['endLine'] = line
		else:
			ranges.append(dict(startLine=line, endLine=line))
	return ranges

def build_mapping(root, source):
	nodes = list(walk(root))
	by_id = {node['id']: node for node in nodes}
	mapped = {node['id']: set() for node in nodes}
	warnings = []
	lines = source.splitlines()
	starts = [0] + [m.end() for m in re.finditer('\n', source)]
	line_at = lambda offset: bisect.bisect_right(starts, offset)
	masked = list(source)
	lexical = re.compile(r'//(?:\\\r?\n|[^\n])*|/\*[\s\S]*?\*/|"(?:\\[\s\S]|[^"\\])*"|\'(?:\\[\s\S]|[^\'\\])*\'')
	for match in lexical.finditer(source):
		masked[match.start():match.end()] = ['\n' if c == '\n' else ' ' for c in match.group()]
	masked = ''.join(masked)
	brace_stack = []
	braces = {}
	for match in re.finditer('[{}]', masked):
		if match.group() == '{':
			brace_stack.append(match.start())
		elif brace_stack:
			braces[brace_stack.pop()] = match.start()
	functions = []
	for match in re.finditer(r'^[\w *]+\b(\w+)\([^;\n]*\)\s*\{', masked, re.M):
		opening = match.end() - 1
		if opening in braces:
			functions.append((line_at(match.start()), line_at(braces[opening]), match.group(1)))
	function_at = {}
	for first, last, name in functions:
		for line in range(first, last + 1):
			function_at[line] = name
	marker_nodes = {}
	for node in nodes:
		if not node['code']:
			continue
		parts = []
		parent = node['id'].rsplit('/', 1)[0]
		while parent in by_id:
			ancestor = by_id[parent]
			if ancestor['kind'] in DEVICES:
				parts.insert(0, ancestor['kind'])
			elif ancestor['kind'] in PROPERTIES:
				parts.insert(0, ancestor['name'].upper())
			elif ancestor['kind'] == 'sdk':
				parts.insert(0, 'sdk')
			parent = parent.rsplit('/', 1)[0]
		parts.append(node['kind'])
		marker_nodes.setdefault('.'.join(parts), []).append(node)
	opens = []
	handwritten = set()
	for number, text in enumerate(lines, 1):
		match = re.fullmatch(r'\s*//([+-])\s*(\S*)\s*', text)
		if not match:
			continue
		if match[1] == '+':
			opens.append((match[2], number))
		elif opens:
			name, first = opens.pop()
			if match[2] and match[2] != name:
				warnings.append(f'Unbalanced marker at C line {number}.')
			if name.endswith('.on_attach') and function_at.get(first, '').endswith('_detach'):
				name = name.removesuffix('.on_attach') + '.on_detach'
			owners = marker_nodes.get(name, [])
			if len(owners) > 1:
				warnings.append(f'Repeated {name} blocks share one generated range.')
			for owner in owners:
				mapped[owner['id']].update(range(first, number + 1))
			if name != 'definitions':
				handwritten.update(range(first, number + 1))
	if opens:
		warnings.append('Unclosed generated code marker.')
	tokens_by_line = {}
	for match in re.finditer(r'\b[A-Za-z_]\w*\b', masked):
		tokens_by_line.setdefault(line_at(match.start()), set()).add(match.group())
	devices = [node for node in root['children'] if node['kind'] in DEVICES]
	for device in devices:
		dtype = device['kind']
		for first, last, name in functions:
			if name in {dtype + suffix for suffix in ('_attach', '_detach', '_enumerate_properties', '_change_property', '_connection_handler', '_timer_callback')}:
				mapped[device['id']].update(range(first, last + 1))
		for number, tokens in tokens_by_line.items():
			if number not in handwritten and tokens & {dtype, dtype.upper() + '_DEVICE_NAME', dtype + '_template', 'indigo_' + dtype + '_driver'}:
				mapped[device['id']].add(number)
		for prop in device['children']:
			if prop['kind'] not in PROPERTIES:
				continue
			attrs = attributes(prop)
			base = prop['name'].upper()
			handle = attrs.get('handle', base + '_PROPERTY')
			pointer = attrs.get('pointer', base.lower() + '_property')
			handler = attrs.get('handler', ('' if base.lower().startswith(dtype) else dtype + '_') + base.lower() + '_handler')
			names = {handle, pointer, base + '_PROPERTY_NAME', handler}
			for item in prop['children']:
				if item['kind'] != 'item':
					continue
				item_attrs = attributes(item)
				item_names = {item_attrs.get('handle', item['name'].upper() + '_ITEM'), item['name'].upper() + '_ITEM_NAME'}
				names.update(item_names)
				for number, tokens in tokens_by_line.items():
					context = function_at.get(number, '')
					if number not in handwritten and (not context or context.startswith(dtype + '_') or context == handler) and tokens & item_names:
						mapped[item['id']].add(number)
			for first, last, name in functions:
				if name == handler:
					mapped[prop['id']].update(range(first, last + 1))
			for number, tokens in tokens_by_line.items():
				context = function_at.get(number, '')
				if number in handwritten or (context and not context.startswith(dtype + '_') and context != handler):
					continue
				if not tokens & names:
					continue
				mapped[prop['id']].add(number)
				text = lines[number - 1]
				if 'indigo_property_match_changeable(' in text and handle in tokens:
					indent = re.match(r'\s*', text)[0]
					last = number
					while last < len(lines) and not lines[last].startswith(indent + '}'):
						last += 1
					# An else-if closing line also opens the next property branch.
					# Include a standalone closing brace, but not that next header.
					if last < len(lines) and lines[last].strip() == '}':
						last += 1
					mapped[prop['id']].update(range(number, last + 1))
				elif re.search(r'if\s*\(\s*' + re.escape(handle) + r'\s*==\s*NULL\s*\)', text):
					opening = masked.find('{', starts[number - 1], starts[number] if number < len(starts) else len(source))
					if opening in braces:
						mapped[prop['id']].update(range(number, line_at(braces[opening]) + 1))
	for node in root['children']:
		if node['kind'] not in {'serial', 'sdk', 'libusb', 'hid'}:
			continue
		transport = node['kind']
		for number, tokens in tokens_by_line.items():
			if number in handwritten:
				continue
			if transport == 'serial' and tokens & {'DEVICE_PORT_PROPERTY', 'DEVICE_PORTS_PROPERTY', 'DEVICE_BAUDRATE_PROPERTY', 'indigo_enumerate_serial_ports', 'indigo_uni_handle', 'patterns', 'INDIGO_REGISER_MATCH_PATTERNS'}:
				mapped[node['id']].add(number)
			elif transport in {'sdk', 'libusb', 'hid'} and tokens & {'usbdev', 'MAX_DEVICES', 'driver_queue', 'driver_queue_mutex', 'callback_handle', 'sdk_discovery_stopping', 'libusb_hotplug_register_callback', 'libusb_hotplug_deregister_callback'}:
				mapped[node['id']].add(number)
		if transport == 'serial':
			patterns = [child for child in node['children'] if child['kind'] == 'pattern']
			for number, text in enumerate(lines, 1):
				match = re.search(r'\bpatterns\[(\d+)\]\.', text)
				if number not in handwritten and match and int(match[1]) < len(patterns):
					mapped[patterns[int(match[1])]['id']].add(number)
		else:
			in_hotplug = False
			for number, text in enumerate(lines, 1):
				if text.startswith('#pragma mark - '):
					in_hotplug = text == '#pragma mark - Hot-plug code'
				if in_hotplug:
					mapped[node['id']].add(number)
	for node in reversed(nodes):
		for child in node['children']:
			mapped[node['id']].update(mapped[child['id']])
	mapped[root['id']] = set(range(1, len(lines) + 1))
	return dict(ranges={identity: compact(numbers) for identity, numbers in mapped.items()}, warnings=sorted(set(warnings)), method='Existing markers and structural C association; shared scaffolding may not have unique ownership.')
