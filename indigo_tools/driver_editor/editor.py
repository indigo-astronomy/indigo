"""Local editing state, isolated generator invocation, and checked file writes."""

import copy
import hashlib
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import threading

from driver_format import DEVICES, edit, parse, schema, structure, walk
from source_map import build_mapping

ROOT = Path(__file__).resolve().parents[2]

class Conflict(ValueError):
	pass

class GenerationError(ValueError):
	pass

def fingerprint(path):
	return hashlib.sha256(path.read_bytes()).hexdigest() if path.exists() else None

def replace_file(path, content):
	"""Stage in the destination directory so os.replace stays on one filesystem."""
	if path.is_symlink():
		raise Conflict(f'Refusing to replace a symbolic link: {path.name}')
	fd, temporary = tempfile.mkstemp(prefix='.' + path.name + '.', dir=path.parent)
	try:
		with os.fdopen(fd, 'wb') as stream:
			stream.write(content)
			stream.flush()
			os.fsync(stream.fileno())
		if path.exists():
			os.chmod(temporary, path.stat().st_mode & 0o777)
		os.replace(temporary, path)
	finally:
		if os.path.exists(temporary):
			os.unlink(temporary)

def output_names(root):
	devices = [node for node in root['children'] if node['kind'] in DEVICES]
	if not devices:
		raise GenerationError('The definition must contain at least one supported device')
	stem = 'indigo_' + devices[0]['kind'] + '_' + root['name']
	return [stem + '.c', stem + '.h', stem + '_main.c']

def generate(source, filename, root, generator, repository, timeout):
	names = output_names(root)
	with tempfile.TemporaryDirectory(prefix='indigo-driver-editor-') as temporary:
		workspace = Path(temporary)
		working = workspace / 'indigo_drivers' / 'preview'
		working.mkdir(parents=True)
		base = workspace / 'indigo_libs'
		base.mkdir()
		for kind in {node['kind'] for node in root['children']} & DEVICES:
			original = repository / 'indigo_libs' / ('indigo_' + kind + '_driver.c')
			if not original.is_file():
				raise GenerationError(f'Missing base driver source: {original}. Set --repository to the INDIGO root.')
			shutil.copyfile(original, base / original.name)
		(working / filename).write_bytes(source.encode('utf-8'))
		try:
			result = subprocess.run([str(generator), filename], cwd=working, capture_output=True, timeout=timeout)
		except subprocess.TimeoutExpired as error:
			raise GenerationError(f'Generator exceeded {timeout:g} seconds and was terminated.') from error
		except OSError as error:
			raise GenerationError(f'Cannot start generator: {error}') from error
		diagnostic = (result.stderr + result.stdout).decode('utf-8', errors='replace').replace(str(workspace), '<preview>')
		if result.returncode != 0:
			raise GenerationError(f'Generator exited with status {result.returncode}.\n{diagnostic}')
		if not all((working / name).is_file() for name in names):
			raise GenerationError('Generator did not produce all expected output files.\n' + diagnostic)
		outputs = {name: (working / name).read_bytes() for name in names}
		return outputs, diagnostic

class Editor:
	def __init__(self, path, generator, repository=ROOT, timeout=30):
		self.path = Path(path).resolve(strict=True)
		if self.path.suffix != '.driver':
			raise ValueError('Open a .driver file')
		self.generator = Path(generator).resolve()
		self.repository = Path(repository).resolve()
		self.timeout = timeout
		self.source = self.path.read_bytes().decode('utf-8')
		self.root = parse(self.source)
		self.disk = fingerprint(self.path)
		self.revision = 1
		self.saved_source = self.source
		self.preview = None
		self.outputs = {}
		self.destinations = {}
		self.diagnostic = ''
		self.generation_failed = False
		self.lock = threading.RLock()
		self.generation_lock = threading.Lock()
		self.catalog = schema((ROOT / 'indigo_tools' / 'template.driver').read_text(encoding='utf-8'))
		self.remember_outputs()

	def remember_outputs(self):
		try:
			names = output_names(self.root)
		except GenerationError:
			return
		for name in names:
			if name not in self.destinations:
				self.destinations[name] = fingerprint(self.path.parent / name)

	def check_revision(self, revision):
		if type(revision) is not int or revision != self.revision:
			raise Conflict('This page has an outdated revision. Reload the working state before retrying.')

	def state(self):
		with self.lock:
			tree = copy.deepcopy(self.root)
			for node in walk(tree):
				node['source'] = self.source[node['start']:node['end']]
				if node['code']:
					node['body'] = self.source[node['bodyStart']:node['bodyEnd']]
			preview = copy.deepcopy(self.preview)
			if preview:
				preview['stale'] = preview['revision'] != self.revision or self.generation_failed
			return dict(filename=self.path.name, path=str(self.path), source=self.source, tree=tree, revision=self.revision, dirty=self.source != self.saved_source, preview=preview, diagnostic=self.diagnostic, schema=self.catalog)

	def apply(self, revision, node, changes):
		with self.lock:
			self.check_revision(revision)
			if not isinstance(changes, list) or not changes:
				raise ValueError('No edits supplied')
			old_nodes = list(walk(self.root))
			candidate, root = edit(self.source, self.root, node, changes)
			renamed = {old['id']: new['id'] for old, new in zip(old_nodes, walk(root)) if old['id'] != new['id']} if any(change['field'] == 'identifier' for change in changes) else {}
			if candidate != self.source:
				self.source, self.root = candidate, root
				self.revision += 1
				self.remember_outputs()
			return dict(self.state(), renamed=renamed)

	def change_structure(self, revision, node, action, kind='', name=''):
		with self.lock:
			self.check_revision(revision)
			candidate, root, selected = structure(self.source, self.root, node, action, kind, name)
			self.source, self.root = candidate, root
			self.revision += 1
			self.remember_outputs()
			return dict(self.state(), selected=selected)

	def save(self, revision):
		with self.lock:
			self.check_revision(revision)
			if self.path.is_symlink() or fingerprint(self.path) != self.disk:
				raise Conflict('The .driver file changed outside the editor. Your working changes are retained; reconcile the disk file before saving.')
			replace_file(self.path, self.source.encode('utf-8'))
			self.disk = hashlib.sha256(self.source.encode('utf-8')).hexdigest()
			self.saved_source = self.source
			return self.state()

	def refresh(self, revision):
		with self.generation_lock:
			with self.lock:
				self.check_revision(revision)
				source, root = self.source, copy.deepcopy(self.root)
			try:
				outputs, diagnostic = generate(source, self.path.name, root, self.generator, self.repository, self.timeout)
				c_name = output_names(root)[0]
				c_source = outputs[c_name].decode('utf-8')
				mapping = build_mapping(root, c_source)
			except (GenerationError, UnicodeError) as error:
				with self.lock:
					if revision == self.revision:
						self.diagnostic = str(error)
						self.generation_failed = True
				raise GenerationError(str(error)) from error
			with self.lock:
				self.check_revision(revision)
				self.outputs = outputs
				self.preview = dict(filename=c_name, source=c_source, revision=revision, mapping=mapping)
				self.diagnostic = diagnostic
				self.generation_failed = False
				return self.state()

	def publish(self, revision):
		with self.lock:
			self.check_revision(revision)
			if self.source != self.saved_source or self.path.is_symlink() or fingerprint(self.path) != self.disk:
				raise Conflict('Save the current definition and resolve any disk conflict before writing generated files.')
			if not self.preview or self.preview['revision'] != revision or self.generation_failed:
				raise Conflict('Generate a successful preview of the current revision first.')
			paths = {name: self.path.parent / name for name in self.outputs}
			for name, path in paths.items():
				if path.is_symlink() or fingerprint(path) != self.destinations[name]:
					raise Conflict(f'{name} changed outside the editor; no generated files were written.')
			originals = {name: path.read_bytes() if path.exists() else None for name, path in paths.items()}
			written = []
			try:
				with tempfile.TemporaryDirectory(prefix='.driver-editor-publish-', dir=self.path.parent) as temporary:
					for name, content in self.outputs.items():
						staged = Path(temporary) / name
						staged.write_bytes(content)
						if paths[name].exists():
							os.chmod(staged, paths[name].stat().st_mode & 0o777)
					for name, path in paths.items():
						if path.is_symlink() or fingerprint(path) != self.destinations[name]:
							raise Conflict(f'{name} changed while staging outputs.')
						os.replace(Path(temporary) / name, path)
						written.append(name)
			except (OSError, Conflict) as error:
				failures = []
				for name in reversed(written):
					try:
						if fingerprint(paths[name]) != hashlib.sha256(self.outputs[name]).hexdigest():
							raise Conflict('File changed during rollback')
						if originals[name] is None:
							paths[name].unlink()
						else:
							replace_file(paths[name], originals[name])
					except (OSError, Conflict) as rollback:
						failures.append(f'{name}: {rollback}')
				if failures:
					raise OSError(f'{error}; rollback incomplete: ' + '; '.join(failures)) from error
				raise
			for name, path in paths.items():
				self.destinations[name] = hashlib.sha256(self.outputs[name]).hexdigest()
			result = self.state()
			result['written'] = list(paths)
			return result
