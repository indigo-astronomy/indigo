				$('preview-state').textContent = 'Not generated';
				$('preview-state').className = 'badge idle-state';
				$('range-status').textContent = 'Generate a preview to inspect the C source';
				$('search-status').textContent = '';
				$('code-search').value = '';
				$('tree-filter').value = '';
				$('mapping-note').textContent = 'Preview generation uses the existing INDIGO generator.';
				$('mapping-note').title = '';
				update(next);
				$('driver-dialog').close();
