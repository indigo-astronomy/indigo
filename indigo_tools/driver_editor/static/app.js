function setDraft(node, change, original) {
	let values = drafts.get(node.id) || new Map();
	const key = draftKey(change);
	for (const [otherId, otherValues] of drafts) {
		if ((change.field === 'source' && otherId.startsWith(node.id + '/')) || (node.id.startsWith(otherId + '/') && otherValues.has('source:'))) {
			message('Apply or discard pending source edits before editing a node inside that source.', true);
			return false;
		}
	}
	if (change.value === original) {
		values.delete(key);
	} else {
		if ((change.field === 'source' && values.size && !values.has(key)) || (change.field !== 'source' && values.has('source:'))) {
			message('Apply or discard this node’s pending edits before switching between source and field editing.', true);
			return false;
		}
		values.set(key, change);
	}
	if (values.size) {
		drafts.set(node.id, values);
	} else {
		drafts.delete(node.id);
	}
	controls();
	return true;
}

function codeIndentation(original, reduceIndent = true) {
	const eol = original.includes('\r\n') ? '\r\n' : '\n';
	const lines = original.replace(/\r\n/g, '\n').split('\n');
	const content = lines.filter(line => /\S/.test(line));
	let indent = reduceIndent && content.length ? content[0].match(/^[\t ]*/)[0] : '';
	for (const line of content) {
		while (!line.startsWith(indent)) {
			indent = indent.slice(0, -1);
		}
	}
	const trimLines = rows => {
		let start = 0, end = rows.length;
		while (start < end && !/\S/.test(rows[start])) {
			start++;
		}
		while (end > start && !/\S/.test(rows[end - 1])) {
			end--;
		}
		return {start, end};
	};
	const bounds = trimLines(lines);
	const prefix = content.length ? lines.slice(0, bounds.start).map(line => line + eol).join('') : (lines.length > 1 ? eol : '');
	const suffix = content.length ? lines.slice(bounds.end).map(line => eol + line).join('') : (lines.length > 1 ? eol + lines[lines.length - 1] : '');
	const display = value => {
		const rows = value.replace(/\r\n/g, '\n').split('\n');
		const {start, end} = trimLines(rows);
		return rows.slice(start, end).map(line => /\S/.test(line) && line.startsWith(indent) ? line.slice(indent.length) : line).join('\n');
	};
	const initial = display(original);
	return {
		display,
		source: value => value === initial ? original : prefix + value.split('\n').map(line => /\S/.test(line) ? indent + line : line).join(eol) + suffix
	};
}

function textEditor(node, field, original) {
	const input = element('textarea');
	const format = codeIndentation(original);
	input.value = format.display(currentValue(node, {field}, original));
	input.spellcheck = false;
	input.setAttribute('aria-label', `${node.name} ${field}`);
	input.oninput = () => {
		if (!setDraft(node, {field, value: format.source(input.value)}, original)) {
			input.value = format.display(currentValue(node, {field}, original));
		}
	};
	input.onkeydown = event => {
		if (event.key === 'Tab') {
			event.preventDefault();
			input.setRangeText('\t', input.selectionStart, input.selectionEnd, 'end');
			input.dispatchEvent(new Event('input'));
		}
	};
	return input;
}

function attributeType(value) {
	if (/^"(?:[^"\\]|\\[\s\S])*"$/.test(value)) {
		return 'string';
	}
	if (['true', 'false'].includes(value)) {
		return 'boolean';
	}
	if (/^[+-]?(?:0[xX][\da-fA-F]+|\d+)[uUlL]*$/.test(value)) {
		return 'integer';
	}
	if (/^[+-]?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?[fFlL]?$/.test(value)) {
		return 'number';
	}
	return 'expression';
}

function attributeDisplay(value, type) {
	return type === 'string' ? value.slice(1, -1) : value;
}

function attributeSource(value, type) {
	// Keep C escape sequences intact; escape newly typed quotes and a trailing backslash.
	return type === 'string' ? '"' + value.replace(/\\[\s\S]|"|\\$/g, token => token === '"' || token === '\\' ? '\\' + token : token) + '"' : value;
}

