"""Run with: python3 driver_editor.py path/to/example.driver"""

import argparse
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
import json
from pathlib import Path
import secrets
import shutil
import sys
import threading
from urllib.parse import urlsplit
import webbrowser

from editor import Conflict, Editor, GenerationError, ROOT

ASSETS = Path(__file__).resolve().parent / 'static'
LIMIT = 4 * 1024 * 1024

class Server(ThreadingHTTPServer):
	daemon_threads = False
	block_on_close = True

	def __init__(self, editor=None, port=0, generator=None, repository=ROOT, timeout=30):
		self.editor = editor
		self.repository = editor.repository if editor else Path(repository).resolve()
		self.generator = editor.generator if editor else generator
		self.timeout = editor.timeout if editor else timeout
		self.lock = threading.RLock()
		self.document = secrets.token_urlsafe(16)
		self.token = secrets.token_urlsafe(32)
		super().__init__(('127.0.0.1', port), Handler)
		self.authority = f'127.0.0.1:{self.server_port}'
		self.origin = 'http://' + self.authority

	def driver_files(self):
		files = {}
		for directory in sorted(self.repository.iterdir()):
			if directory.name != 'indigo_drivers' and not directory.match('indigo_*_drivers'):
				continue
			if not directory.is_dir() or directory.is_symlink():
				continue
			for path in directory.rglob('*.driver'):
				resolved = path.resolve()
				if path.is_file() and resolved.is_relative_to(directory.resolve()):
					files[path.relative_to(self.repository).as_posix()] = resolved
		return dict(sorted(files.items()))

	def state(self):
		with self.lock:
			result = self.editor.state() if self.editor else dict(tree=None, revision=0, dirty=False, preview=None)
			return dict(result, document=self.document)

	def open_driver(self, data):
		if self.editor:
			self.editor.check_revision(data['revision'])
			if self.editor.source != self.editor.saved_source and data.get('discard') is not True:
				raise Conflict('Save or explicitly discard the current definition before opening another driver')
		files = self.driver_files()
		if data.get('file') not in files:
			raise ValueError('Select a driver from the repository list')
		candidate = Editor(files[data['file']], self.generator, self.repository, self.timeout)
		self.editor = candidate
		self.document = secrets.token_urlsafe(16)
		return self.state()

class Handler(BaseHTTPRequestHandler):
	def setup(self):
		super().setup()
		self.connection.settimeout(45)

	def log_message(self, format, *args):
		pass

	def reply(self, status, body, mime='application/json; charset=utf-8'):
		if not isinstance(body, bytes):
			body = json.dumps(body, ensure_ascii=False).encode('utf-8')
		self.send_response(status)
		self.send_header('Content-Type', mime)
		self.send_header('Content-Length', str(len(body)))
		self.send_header('Cache-Control', 'no-store')
		self.send_header('X-Content-Type-Options', 'nosniff')
		self.send_header('Referrer-Policy', 'no-referrer')
		self.send_header('Content-Security-Policy', "default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; connect-src 'self'; img-src 'self' data:; frame-ancestors 'none'; base-uri 'none'; form-action 'none'")
		self.end_headers()
		try:
			self.wfile.write(body)
		except (BrokenPipeError, ConnectionResetError):
			pass

	def allowed(self, mutation=False, api=False):
		if self.headers.get('Host') != self.server.authority:
			self.reply(403, dict(error='Unexpected Host'))
			return False
		if api and not secrets.compare_digest(self.headers.get('X-Editor-Token', ''), self.server.token):
			self.reply(403, dict(error='Missing or invalid editor session token. Open the URL printed by the server.'))
			return False
		if mutation and self.headers.get('Origin') != self.server.origin:
			self.reply(403, dict(error='Unexpected Origin'))
			return False
		return True

	def do_GET(self):
		path = urlsplit(self.path).path
		if not self.allowed(api=path.startswith('/api/')):
			return
		if path == '/api/state':
			self.reply(200, self.server.state())
			return
		if path == '/api/drivers':
			self.reply(200, dict(files=list(self.server.driver_files())))
			return
		assets = {'/': ('index.html', 'text/html'), '/app.js': ('app.js', 'text/javascript'), '/style.css': ('style.css', 'text/css')}
		if path in assets:
			name, mime = assets[path]
			self.reply(200, (ASSETS / name).read_bytes(), mime + '; charset=utf-8')
		elif path in {'/bootstrap.min.css', '/bootstrap.min.js', '/indigo.css', '/script.png'}:
			resource = ROOT / 'indigo_server' / 'resource' / path[1:]
			mime = {'.css': 'text/css; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.png': 'image/png'}[resource.suffix]
			self.reply(200, resource.read_bytes(), mime)
		else:
			self.reply(404, dict(error='Not found'))

	def do_POST(self):
		if not self.allowed(mutation=True, api=True):
			return
		try:
			if self.headers.get_content_type() != 'application/json' or self.headers.get('Transfer-Encoding'):
				raise ValueError('Expected JSON with Content-Length')
			length = int(self.headers.get('Content-Length', '0'))
			if not 0 < length <= LIMIT:
				self.reply(413, dict(error='Invalid request size'))
				return
			payload = self.rfile.read(length)
			if len(payload) != length:
				raise ValueError('Incomplete request body')
			data = json.loads(payload)
			if not isinstance(data, dict):
				raise ValueError('Expected JSON object')
			path = urlsplit(self.path).path
			with self.server.lock:
				if data.get('document', self.server.document) != self.server.document:
					raise Conflict('The open driver has changed; reload the editor')
				editor = self.server.editor
				if path == '/api/open':
					result = self.server.open_driver(data)
				elif editor is None:
					raise ValueError('Open a driver first')
				elif path == '/api/structure':
					result = editor.change_structure(data['revision'], data['node'], data['action'], data.get('kind', ''), data.get('name', ''))
				elif path == '/api/edit':
					result = editor.apply(data['revision'], data['node'], data['changes'])
				elif path in {'/api/save', '/api/generate', '/api/publish'}:
					operation = {'/api/save': editor.save, '/api/generate': editor.refresh, '/api/publish': editor.publish}[path]
					result = operation(data['revision'])
				else:
					self.reply(404, dict(error='Not found'))
					return
				result['document'] = self.server.document
			self.reply(200, result)
		except Conflict as error:
			self.reply(409, dict(error=str(error)))
		except GenerationError as error:
			self.reply(422, dict(error=str(error)))
		except (ValueError, KeyError, TypeError) as error:
			self.reply(400, dict(error=str(error)))
		except OSError as error:
			self.reply(500, dict(error=str(error)))

def main():
	parser = argparse.ArgumentParser(description='Local INDIGO .driver editor (Python standard library only).')
	parser.add_argument('file', nargs='?', type=Path, help='Existing .driver file')
	parser.add_argument('--generator', type=Path, help='Path to the existing indigo_generator executable')
	parser.add_argument('--repository', type=Path, default=ROOT, help='INDIGO root containing indigo_libs')
	parser.add_argument('--port', type=int, default=0, help='Local port; default: automatically assigned')
	parser.add_argument('--timeout', type=float, default=30, help='Generator timeout in seconds')
	parser.add_argument('--no-browser', action='store_true', help='Print the URL without launching a browser')
	args = parser.parse_args()
	if not 0 <= args.port <= 65535 or not 0 < args.timeout <= 300:
		parser.error('Port must be 0–65535 and timeout must be greater than 0 and at most 300 seconds')
	generator = args.generator
	if generator is None:
		candidates = [args.repository / 'build' / 'bin' / 'indigo_generator', args.repository / 'build' / 'bin' / 'indigo_generator.exe']
		generator = next((path for path in candidates if path.is_file()), None) or shutil.which('indigo_generator')
	if generator is None:
		parser.error('Generator not found; supply --generator /path/to/indigo_generator')
	try:
		editor = Editor(args.file, generator, args.repository, args.timeout) if args.file else None
		server = Server(editor, args.port, generator, args.repository, args.timeout)
	except (OSError, ValueError) as error:
		parser.error(str(error))
	url = server.origin + '/#token=' + server.token
	print(f'Driver editor: {url}\nFile: {editor.path if editor else "Select a driver with Open driver"}\nPress Ctrl+C to stop.', flush=True)
	if not args.no_browser:
		webbrowser.open(url)
	try:
		server.serve_forever()
	except KeyboardInterrupt:
		print('\nStopping driver editor.', flush=True)
	finally:
		server.server_close()
	return 0

if __name__ == '__main__':
	sys.exit(main())
