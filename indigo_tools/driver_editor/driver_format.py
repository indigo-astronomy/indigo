"""Lossless structural view of the driver DSL; the C generator validates semantics."""

import re
from dataclasses import dataclass

DEVICES = set('ccd wheel focuser mount guider rotator dome gps ao aux'.split())
PROPERTIES = set('inherited switch text number light'.split())
CODE = set('include define data code on_init on_shutdown on_timer on_attach on_detach on_connect on_disconnect on_change on_change_request plug unplug unplug_match'.split())

class FormatError(ValueError):
	def __init__(self, message, source, offset):
		self.line = source.count('\n', 0, offset) + 1
		self.column = offset - source.rfind('\n', 0, offset)
		super().__init__(f'{message} at {self.line}:{self.column}')

@dataclass
class Token:
	value: str
	start: int
	end: int
	kind: str

def tokenize(source):
	pattern = re.compile(r'(?P<space>\s+)|(?P<comment>//(?:\\\r?\n|[^\n])*|/\*[\s\S]*?\*/)|(?P<string>"(?:\\[\s\S]|[^"\\])*"|\'(?:\\[\s\S]|[^\'\\])*\')|(?P<identifier>[A-Za-z_][A-Za-z_0-9]*)|(?P<other>.)')
	result = []
	position = 0
	while position < len(source):
		match = pattern.match(source, position)
		if not match:
			raise FormatError('Unrecognized character', source, position)
		kind = match.lastgroup
		value = match.group()
		if kind == 'other' and (value in '\"\'' or source.startswith('/*', position)):
			raise FormatError('Unterminated string or comment', source, position)
		if kind not in ('space', 'comment'):
			result.append(Token(value, position, match.end(), kind))
		position = match.end()
	return result

def walk(node):
	yield node
	for child in node['children']:
		yield from walk(child)

def attributes(node):
	return {attribute['name']: attribute['value'] for attribute in node['attributes']}

class Parser:
	def __init__(self, source):
		self.source = source
		self.tokens = tokenize(source)
		self.index = 0

	def error(self, message):
		offset = self.tokens[self.index].start if self.index < len(self.tokens) else len(self.source)
		raise FormatError(message, self.source, offset)

	def peek(self, value=None):
		if self.index >= len(self.tokens):
			return False
		return value is None or self.tokens[self.index].value == value

	def take(self, value=None):
		if not self.peek(value):
			self.error(f'Expected {value or "token"}')
		token = self.tokens[self.index]
		self.index += 1
		return token

	def identifier(self):
		token = self.take()
		if token.kind != 'identifier':
			raise FormatError('Expected identifier', self.source, token.start)
		return token

	def block(self, parent='', siblings=None):
		first = self.identifier()
		kind = first.value
		name_token = self.identifier() if kind in PROPERTIES | {'driver', 'item'} else first
		name = name_token.value
		key = kind + (':' + name if kind != name else '')
		siblings = siblings if siblings is not None else {}
		siblings[key] = siblings.get(key, 0) + 1
		identity = parent + '/' + key + ':' + str(siblings[key])
		node = dict(id=identity, kind=kind, name=name, start=first.start, nameStart=name_token.start, nameEnd=name_token.end, attributes=[], children=[], code=kind in CODE)
		if self.peek(';'):
			node.update(end=self.take(';').end, bodyStart=None, bodyEnd=None)
			return node
		opening = self.take('{')
		node['bodyStart'] = opening.end
		if node['code']:
			depth = 1
			while depth:
				token = self.take()
				if token.kind != 'string':
					depth += (token.value == '{') - (token.value == '}')
			node.update(bodyEnd=token.start, end=token.end)
		else:
			counts = {}
			while not self.peek('}'):
				if not self.peek():
					self.error('Expected closing brace')
				if self.index + 1 < len(self.tokens) and self.tokens[self.index + 1].value == '=':
					name_token = self.identifier()
					self.take('=')
					value_start = self.index
					stack = []
					while not (self.peek(';') and not stack):
						token = self.take()
						if token.kind != 'string':
							if token.value in ('(', '[', '{'):
								stack.append(token.value)
							elif token.value in (')', ']', '}'):
								if not stack or stack.pop() != {')': '(', ']': '[', '}': '{'}[token.value]:
									raise FormatError('Unbalanced attribute expression or missing semicolon', self.source, token.start)
					if self.index == value_start:
						self.error('Expected attribute value')
					start = self.tokens[value_start].start
					end = self.tokens[self.index - 1].end
					terminator = self.take(';')
					node['attributes'].append(dict(name=name_token.value, value=self.source[start:end], start=start, end=end, statementStart=name_token.start, statementEnd=terminator.end))
				else:
					node['children'].append(self.block(identity, counts))
			closing = self.take('}')
			node.update(bodyEnd=closing.start, end=closing.end)
		return node

	def parse(self):
		root = self.block()
		if root['kind'] != 'driver':
			self.error('Expected driver definition')
		if self.peek():
			self.error('Unexpected content after driver definition')
		return root

def parse(source):
	return Parser(source).parse()

def find_node(root, identity):
	for node in walk(root):
		if node['id'] == identity:
			return node
	raise ValueError('The selected node no longer exists')

def validate_node_name(parent, kind, name, current=None):
	if not re.fullmatch(r'[A-Za-z_][A-Za-z_0-9]*', name):
		raise ValueError('Use a C identifier: letters, digits and underscores, not starting with a digit')
	if kind in PROPERTIES - {'inherited'} and not name.startswith('X_'):
		raise ValueError('Custom property identifiers must start with X_')
	for child in parent['children']:
		if child is not current and (child['kind'] in PROPERTIES if kind in PROPERTIES else child['kind'] == kind) and child['name'].upper() == name.upper():
			raise ValueError('An identifier with this name already exists here')

def structure(source, root, identity, action, kind='', name=''):
	node = find_node(root, identity)
	eol = '\r\n' if '\r\n' in source else '\n'
	outer = '\t' * (identity.count('/') - 1)
	if action == 'remove':
		if node['kind'] not in DEVICES | PROPERTIES | {'item'}:
			raise ValueError('This node cannot be removed')
		parent_id = identity.rsplit('/', 1)[0]
		start, end = node['start'], node['end']
		line_start = source.rfind('\n', 0, start) + 1
		line_end = source.find('\n', end)
		line_end = len(source) if line_end < 0 else line_end
		if not source[line_start:start].strip() and not source[end:line_end].strip():
			start, end = line_start, min(line_end + 1, len(source))
		updated = source[:start] + source[end:]
		return updated, parse(updated), parent_id
	if action != 'add':
		raise ValueError('Unknown structural action')
	allowed = DEVICES if node['kind'] == 'driver' else PROPERTIES if node['kind'] in DEVICES else {'item'} if node['kind'] in PROPERTIES - {'inherited'} else set()
	if kind not in allowed:
		raise ValueError('This child type is not supported here')
	if kind in DEVICES:
		name = kind
		if any(child['kind'] == kind for child in node['children']):
			raise ValueError('This device type already exists')
	else:
		validate_node_name(node, kind, name)
	indent = outer + '\t'
	header = kind if kind in DEVICES else kind + ' ' + name
	body = ''
	if kind in DEVICES:
		body = indent + '\tname = "' + name + '";' + eol
	elif kind != 'inherited':
		body = indent + '\tlabel = "' + name + '";' + eol
		if kind in {'switch', 'number', 'text'}:
			body += indent + '\ton_change { }' + eol
	block = indent + header + ' {' + eol + body + indent + '}' + eol
	if node['bodyStart'] is None:
		updated_node = source[node['start']:node['end'] - 1].rstrip() + ' {' + eol + block + outer + '}'
		updated = source[:node['start']] + updated_node + source[node['end']:]
	else:
		end = node['bodyEnd']
		line_start = source.rfind('\n', 0, end) + 1
		if not source[line_start:end].strip():
			updated = source[:line_start] + block + source[line_start:]
		else:
			updated = source[:end] + eol + block + outer + source[end:]
	new_root = parse(updated)
	parent = find_node(new_root, identity)
	return updated, new_root, parent['children'][-1]['id']

def edit(source, root, identity, changes):
	node = find_node(root, identity)
	replacements = []
	for change in changes:
		field = change['field']
		value = change['value']
		if not isinstance(value, str):
			raise ValueError('Edited values must be strings')
		if field == 'identifier':
			if node['kind'] not in PROPERTIES | {'item'}:
				raise ValueError('Only property and item identifiers can be renamed')
			parent = find_node(root, identity.rsplit('/', 1)[0])
			validate_node_name(parent, node['kind'], value, node)
			replacements.append((node['nameStart'], node['nameEnd'], value))
		elif field == 'source':
			if len(changes) != 1:
				raise ValueError('Source replacement cannot be combined with other edits')
			replacements.append((node['start'], node['end'], value))
		elif field == 'code' and node['code']:
			replacements.append((node['bodyStart'], node['bodyEnd'], value))
		elif field == 'attribute':
			name = change['name']
			matches = [a for a in node['attributes'] if a['name'] == name]
			if len(matches) > 1:
				raise ValueError('Repeated attributes must be edited in the node source')
			if matches:
				a = matches[0]
				if change.get('remove'):
					start, end = a['statementStart'], a['statementEnd']
					line_start = source.rfind('\n', 0, start) + 1
					line_end = source.find('\n', end)
					line_end = len(source) if line_end < 0 else line_end
					if not source[line_start:start].strip() and not source[end:line_end].strip():
						start, end = line_start, min(line_end + 1, len(source))
					replacements.append((start, end, ''))
				else:
					replacements.append((a['start'], a['end'], value))
			else:
				if change.get('remove'):
					raise ValueError('The attribute no longer exists')
				if node['code'] or node['bodyStart'] is None or not re.fullmatch(r'[A-Za-z_][A-Za-z_0-9]*', name):
					raise ValueError('Cannot add this attribute here; use the node source editor')
				indent = '\t' * identity.count('/')
				replacements.append((node['bodyStart'], node['bodyStart'], f'\n{indent}{name} = {value};'))
		else:
			raise ValueError('Unsupported edit')
	ordered = sorted(replacements, key=lambda r: (r[0], r[1]))
	for previous, current in zip(ordered, ordered[1:]):
		if previous[1] > current[0] or previous[:2] == current[:2]:
			raise ValueError('Overlapping edits; apply new attributes one at a time')
	for start, end, value in reversed(ordered):
		source = source[:start] + value + source[end:]
	return source, parse(source)

def schema(template):
	"""Use template.driver as the sole attribute and value-type catalog."""
	root = parse(template)
	catalog = {}
	for node in walk(root):
		context = 'device' if node['kind'] == 'XXXXX' else node['kind']
		if context == 'item':
			context = 'item:' + node['id'].split('/')[-2].split(':')[0]
		entries = catalog.setdefault(context, {})
		for attribute in node['attributes']:
			if attribute['name'] == 'XXXXX':
				continue
			line_end = template.find('\n', attribute['statementEnd'])
			help_text = template[attribute['statementEnd']:line_end if line_end >= 0 else len(template)].strip().removeprefix('//').strip()
			type_match = re.search(r' @type=(\w+)', help_text)
			value_type = type_match.group(1) if type_match else 'expression'
			help_text = re.sub(r' @type=\w+', '', help_text)
			entries[attribute['name']] = dict(example=attribute['value'], help=help_text, type=value_type)
	return catalog
