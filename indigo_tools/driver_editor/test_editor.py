	def test_edit_during_generation_discards_old_result(self):
		started, release = threading.Event(), threading.Event()
		errors = []
		def delayed(*args):
			started.set()
			if not release.wait(3):
				raise RuntimeError('Test synchronization timed out')
			return {'indigo_aux_sample.c': b'// old preview\n'}, ''
		def refresh():
			try:
				self.editor.refresh(1)
			except Exception as error:
				errors.append(error)
		with patch('editor.generate', side_effect=delayed):
			thread = threading.Thread(target=refresh)
			thread.start()
			try:
				self.assertTrue(started.wait(3))
				self.change_label()
			finally:
				release.set()
				thread.join(3)
		self.assertFalse(thread.is_alive())
		self.assertIsInstance(errors[0], Conflict)
		self.assertIsNone(self.editor.preview)

