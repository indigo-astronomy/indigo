	def test_delete_attribute_preserves_neighbors_and_can_be_added_again(self):
		for eol in ('\n', '\r\n'):
			source = eol.join(['driver a {', '\tversion = 1;', '\tlabel = "Camera"; // keep this comment', '\tauthor = "Author";', '}'])
			root = parse(source)
			updated, root = edit(source, root, root['id'], [dict(field='attribute', name='version', value='1', remove=True)])
			self.assertEqual(updated, source.replace('\tversion = 1;' + eol, ''))
			self.assertNotIn('version', attributes(root))
			updated, root = edit(updated, root, root['id'], [dict(field='attribute', name='label', value='', remove=True)])
			self.assertIn('// keep this comment', updated)
			self.assertEqual(attributes(root), {'author': '"Author"'})
			updated, root = edit(updated, root, root['id'], [dict(field='attribute', name='version', value='2')])
			self.assertEqual(attributes(root)['version'], '2')
			with self.assertRaises(ValueError):
				edit(updated, root, root['id'], [dict(field='attribute', name='missing', value='', remove=True)])
		source = 'driver a { version = 1; label = "Camera"; }'
		root = parse(source)
		updated, _ = edit(source, root, root['id'], [dict(field='attribute', name='version', value='', remove=True)])
		self.assertEqual(updated, 'driver a {  label = "Camera"; }')

	def test_structural_contexts_shorthand_and_preservation(self):
		for eol in ('\n', '\r\n'):
			source = eol.join(['// keep header', 'driver sample {', '\taux;', '}'])
			root = parse(source)
			updated, root, selected = structure(source, root, named(root, 'aux')['id'], 'add', 'number', 'X_VALUE')
			self.assertIn('aux {', updated)
			updated, root, item_id = structure(updated, root, selected, 'add', 'item', 'VALUE')
			self.assertIn('item VALUE {', updated)
			with self.assertRaises(ValueError):
				structure(updated, root, selected, 'add', 'item', 'value')
			with self.assertRaises(ValueError):
				structure(updated, root, item_id, 'add', 'item', 'NESTED')
			with self.assertRaises(ValueError):
				structure(updated, root, root['id'], 'remove')
			updated, root, parent_id = structure(updated, root, item_id, 'remove')
			self.assertEqual(parent_id, selected)
			self.assertNotIn('item VALUE', updated)
			self.assertTrue(updated.startswith('// keep header' + eol))
			inherited_source, inherited_root, inherited_id = structure(updated, root, named(root, 'aux')['id'], 'add', 'inherited', 'CONNECTION')
			with self.assertRaises(ValueError):
				structure(inherited_source, inherited_root, inherited_id, 'add', 'item', 'CONNECT')
			with self.assertRaises(ValueError):
				structure(updated, root, named(root, 'aux')['id'], 'add', 'number', 'BAD_CUSTOM')
			with self.assertRaises(ValueError):
				structure(updated, root, root['id'], 'add', 'aux')

