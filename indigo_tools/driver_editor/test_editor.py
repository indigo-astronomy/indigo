		self.assertEqual(self.request('/api/save', {'revision': 1})[0], 200)
		self.assertEqual(self.request('/api/edit', [1, 2])[0], 400)
		self.assertEqual(self.request('/api/edit', {'revision': 1, 'node': self.editor.root['id'], 'changes': []})[0], 400)

