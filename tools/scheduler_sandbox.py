class _Equatorial(ctypes.Structure):
	_fields_ = [("ra", ctypes.c_double), ("dec", ctypes.c_double)]


def _load_ephemeris():
	"""The Sun as the Scheduler Agent computes it, from the built INDIGO libraries; None if they cannot be loaded."""
	suffix = ".dylib" if sys.platform == "darwin" else ".so"
	try:
		indigo = ctypes.CDLL(str(REPOSITORY / "build/lib" / ("libindigo" + suffix)), mode=ctypes.RTLD_GLOBAL)
		catalog = ctypes.CDLL(str(REPOSITORY / "build/lib" / ("libindigocat" + suffix)), mode=ctypes.RTLD_GLOBAL)
	except OSError:
		return None
	catalog.indigocat_sun_equatorial_coords.argtypes = [ctypes.c_double, ctypes.POINTER(_Equatorial)]
	catalog.indigocat_sun_equatorial_coords.restype = None
	indigo.indigo_lst.argtypes = [ctypes.POINTER(ctypes.c_long), ctypes.c_double]
	indigo.indigo_lst.restype = ctypes.c_double
	return indigo, catalog


EPHEMERIS = _load_ephemeris()
# UT2JD() in indigo_align.h
DELTA_UT1_UTC = 0.0299836 / 86400.0


def sun_position(t):
	"""Right ascension, declination and Greenwich mean sidereal time in degrees, computed like the Scheduler Agent."""
	if EPHEMERIS:
		indigo, catalog = EPHEMERIS
		sun = _Equatorial()
		catalog.indigocat_sun_equatorial_coords(t / 86400.0 + 2440587.5 + DELTA_UT1_UTC, ctypes.byref(sun))
		utc = ctypes.c_long(int(t))
		return sun.ra, sun.dec, indigo.indigo_lst(ctypes.byref(utc), 0.0) * 15
	# a low precision formula of the Astronomical Almanac when the libraries are missing
	n = t / 86400.0 + 2440587.5 - 2451545.0
	mean_longitude = (280.460 + 0.9856474 * n) % 360
	anomaly = math.radians((357.528 + 0.9856003 * n) % 360)
	ecliptic = math.radians(mean_longitude + 1.915 * math.sin(anomaly) + 0.020 * math.sin(2 * anomaly))
	obliquity = math.radians(23.439 - 0.0000004 * n)
	ra = math.degrees(math.atan2(math.cos(obliquity) * math.sin(ecliptic), math.cos(ecliptic)))
	dec = math.degrees(math.asin(math.sin(obliquity) * math.sin(ecliptic)))
	gmst = (280.46061837 + 360.98564736629 * n) % 360
	return ra, dec, gmst


def sun_altitude(t, latitude, longitude):
	ra, dec, gmst = sun_position(t)
	hour_angle = math.radians(gmst + longitude - ra)
	lat, d = math.radians(latitude), math.radians(dec)
	return math.degrees(math.asin(math.sin(lat) * math.sin(d) + math.cos(lat) * math.cos(d) * math.cos(hour_angle)))


def crossing_longitude(t, altitude, rising):
	"""The equator longitude where the Sun is at the altitude at time t, setting or rising."""
	ra, dec, gmst = sun_position(t)
	d = math.radians(dec)
	hour_angle = math.degrees(math.acos(max(-1.0, min(1.0, math.sin(math.radians(altitude)) / math.cos(d)))))
	if rising:
		hour_angle = -hour_angle
	return round((hour_angle + ra - gmst) % 360, 5)


def lan_address():
	"""The address other computers reach this one at, the host name when it cannot be found."""
	try:
		with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as probe:
			# no packet is sent, connect() only selects the outgoing interface
			probe.connect(("192.0.2.1", 9))
			return probe.getsockname()[0]
	except OSError:
		return socket.gethostname()


def time_longitude(hour):
	hours = (time.time() % 86400) / 3600
	return round(((hour - hours) * 15) % 360, 5)


class Client:
	"""A small INDIGO JSON client that keeps the properties and messages of all devices."""

	def __init__(self, port):
		self.connection = socket.create_connection(("127.0.0.1", port), timeout=5)
		self.connection.settimeout(0.25)
		self.lock = threading.Lock()
		self.properties = {}
		self.messages = []
		self.shown = 0
		self.running = True
		self.buffer = ""
		self.decoder = json.JSONDecoder()
		self.reader = threading.Thread(target=self.read_loop, daemon=True)
		self.reader.start()

	def send(self, operation, value):
		with self.lock:
			self.connection.sendall((json.dumps({operation: value}, ensure_ascii=False) + "\n").encode())

	def change(self, kind, device, name, items):
		self.send("new" + kind + "Vector", {"device": device, "name": name, "items": [{"name": k, "value": v} for k, v in items.items()]})

	def read_loop(self):
		import codecs
		utf8 = codecs.getincrementaldecoder("utf-8")()
		heartbeat = time.monotonic()
		while self.running:
			# the server closes a JSON client that stays silent for a few seconds
			if time.monotonic() - heartbeat > 1:
				try:
					self.send("getProperties", {"version": 0x300, "device": AGENT, "name": "AGENT_SCHEDULER_STATE"})
				except OSError:
					return
				heartbeat = time.monotonic()
			try:
				data = self.connection.recv(1024 * 1024)
			except socket.timeout:
				continue
			except OSError:
				return
			if not data:
				return
			self.buffer += utf8.decode(data)
			while self.buffer.strip():
				self.buffer = self.buffer.lstrip()
				try:
					packet, end = self.decoder.raw_decode(self.buffer)
				except json.JSONDecodeError:
					break
				self.buffer = self.buffer[end:]
				self.handle(packet)

	def handle(self, packet):
		with self.lock:
			if isinstance(packet.get("message"), str):
				self.messages.append((packet.get("device") or "", packet["message"], time.time()))
				return
			for operation, value in packet.items():
				if not isinstance(value, dict):
					continue
				if value.get("message"):
					self.messages.append((value.get("device") or "", value["message"], time.time()))
				if operation.startswith(("def", "set")) and "name" in value:
					key = (value["device"], value["name"])
					previous = self.properties.get(key, {}) if operation.startswith("set") else {}
					items = {i["name"]: i for i in previous.get("items", [])}
					if operation.startswith("def"):
						items = {}
					for item in value.get("items", []):
						items[item["name"]] = dict(items.get(item["name"], {}), **item)
					merged = dict(previous, **value)
					merged["items"] = list(items.values())
					self.properties[key] = merged
				elif operation.startswith("delete"):
					for key in [k for k in self.properties if k[0] == value.get("device") and (not value.get("name") or k[1] == value["name"])]:
						del self.properties[key]

	def property(self, device, name):
		with self.lock:
			return self.properties.get((device, name))

	def value(self, device, name, item):
		p = self.property(device, name)
		for i in (p or {}).get("items", []):
			if i["name"] == item:
				return i.get("value")
		return None

	def new_messages(self):
		with self.lock:
			result = self.messages[self.shown:]
			self.shown = len(self.messages)
		return result

	def close(self):
		self.running = False
		try:
			self.connection.close()
		except OSError:
			pass


class Sandbox:

	def __init__(self, client, simulators, interactive):
		self.client = client
		self.simulators = simulators
		self.interactive = interactive
		self.failed = False
		# "until" looks at the messages that arrived since the previous command began
		self.until_mark = 0

	def say(self, text):
		print(text, flush=True)

	def flush_messages(self):
		for device, message, arrived in self.client.new_messages():
			if device == AGENT or self.simulators:
				self.say("  [%s] %s" % (time.strftime("%H:%M:%S", time.localtime(arrived)), message if device == AGENT else device + ": " + message))

	def wait_for(self, predicate, timeout):
		deadline = time.monotonic() + timeout
		while time.monotonic() < deadline:
			if predicate():
				return True
			time.sleep(0.05)
		return False

	def site(self, longitude):
		self.client.change("Number", "Mount Agent", "GEOGRAPHIC_COORDINATES", {"LATITUDE": 0, "LONGITUDE": longitude, "ELEVATION": 0})
		self.wait_for(lambda: self.client.value("Mount Agent", "GEOGRAPHIC_COORDINATES", "LONGITUDE") == longitude, 5)

	def night_limit(self):
		p = self.client.property(AGENT, "AGENT_SCHEDULER_NIGHT")
		for i in (p or {}).get("items", []):
			if i.get("value") is True:
				return i["name"], LIMITS.get(i["name"], -12.0)
		return "NAUTICAL", -12.0

	def setting(self, item):
		value = self.client.value(AGENT, "AGENT_SCHEDULER_SETTINGS", item)
		return value if isinstance(value, (int, float)) else 0

	def task_text(self, arguments):
		if len(arguments) < 2:
			raise ValueError("expected NAME SECONDS")
		name, seconds = arguments[0], float(arguments[1])
		lines = ["// @task " + name]
		fail = False
		for argument in arguments[2:]:
			if argument == "fail":
				fail = True
			elif "=" in argument:
				key, value = argument.split("=", 1)
				lines.append("// @" + key.strip() + " " + value.strip())
			else:
				raise ValueError("unexpected argument '%s'" % argument)
		body = "var sequence = new Sequence(scheduler_task.name);\nsequence.wait(%g);\nsequence.start();\n" % seconds
		if fail:
			body = "if (!scheduler_task.estimate) { throw new Error(\"failed on purpose\"); }\n" + body
		return "\n".join(lines) + "\n\n" + body

	def submit(self, property_name, text):
		key = (AGENT, property_name)
		before = self.client.property(*key)
		self.client.change("Text", AGENT, property_name, {"TASK": text})
		# the agent answers Busy, then Ok or Alert with a message
		self.wait_for(lambda: (self.client.property(*key) or {}).get("state") in ("Ok", "Alert") and self.client.property(*key) is not before, 5)
		time.sleep(0.2)

	def command(self, name, item):
		self.client.change("Text", AGENT, "AGENT_SCHEDULER_TASK_NAME", {"NAME": name})
		time.sleep(0.2)
		self.client.change("Switch", AGENT, "AGENT_SCHEDULER_TASK_COMMAND", {item: True})
		time.sleep(0.3)

	def show_list(self, name, title):
		p = self.client.property(AGENT, name)
		self.say(title + ":")
		items = (p or {}).get("items", [])
		if not items:
			self.say("  (empty)")
		for i in items:
			self.say("  %-5s %s" % (i.get("value", ""), i.get("label", "")))

	def status(self):
		state = (self.client.property(AGENT, "AGENT_SCHEDULER_STATE") or {})
		counters = {i["name"]: i.get("value") for i in state.get("items", [])}
		self.say("scheduler: %s, done %s, failed %s, urgent done %s, urgent failed %s, total %s" % (state.get("state"), counters.get("DONE"), counters.get("FAILED"), counters.get("URGENT_DONE"), counters.get("URGENT_FAILED"), counters.get("TOTAL")))
		for item in ("CURRENT", "NEXT", "NEXT_START", "REASON"):
			self.say("  %-10s %s" % (item, self.client.value(AGENT, "AGENT_SCHEDULER_CURRENT", item) or ""))
		hooks = {i["name"]: i.get("value") for i in (self.client.property(AGENT, "AGENT_SCHEDULER_HOOKS") or {}).get("items", []) if i.get("value")}
		self.say("  hooks      " + (", ".join("%s=%s" % h for h in hooks.items()) or "none"))
		self.show_list("AGENT_SCHEDULER_TASK_STATE", "tasks")

	def show_site(self):
		longitude = self.client.value("Mount Agent", "GEOGRAPHIC_COORDINATES", "LONGITUDE") or 0
		local = ((time.time() % 86400) / 3600 + longitude / 15) % 24
		altitude = sun_altitude(time.time(), 0, longitude)
		limit_name, limit = self.night_limit()
		self.say("site: latitude 0, longitude %.3f, local mean time %02d:%02d, Sun %.1f deg, %s limit %g deg: %s" % (longitude, int(local), int(local * 60) % 60, altitude, limit_name.lower(), limit, "night" if altitude < limit else "day"))

	def run(self, line):
		try:
			words = shlex.split(line, comments=True)
		except ValueError as error:
			self.say("error: %s" % error)
			return True
		if not words:
			return True
		verb, arguments = words[0].lower(), words[1:]
		if verb != "until":
			with self.client.lock:
				self.until_mark = len(self.client.messages)
		try:
			if verb in ("quit", "exit"):
				return False
			elif verb == "help":
				self.say(HELP)
			elif verb in ("night", "day", "time"):
				hour = 0 if verb == "night" else 12 if verb == "day" else float(arguments[0])
				self.site(time_longitude(hour))
				self.show_site()
			elif verb in ("dusk", "dawn"):
				seconds = float(arguments[0]) if arguments else 30
				limit_name, limit = self.night_limit()
				offset = self.setting("NIGHT_START_OFFSET" if verb == "dusk" else "NIGHT_END_OFFSET")
				# the scheduler's night starts or ends at the crossing plus the offset
				self.site(crossing_longitude(time.time() + seconds - offset * 60, limit, verb == "dawn"))
				self.say("the scheduler's night %s in %g s (%s limit, offset %g min)" % ("starts" if verb == "dusk" else "ends", seconds, limit_name.lower(), offset))
			elif verb == "site":
				self.show_site()
			elif verb == "task":
				self.submit("AGENT_SCHEDULER_ADD_TASK", self.task_text(arguments))
			elif verb == "hold":
				start = time.strftime("%Y-%m-%d %H:%M", time.gmtime(time.time() + 2 * 86400))
				self.submit("AGENT_SCHEDULER_ADD_TASK", self.task_text(["Hold", "1", "window=" + start + " .."]))
			elif verb == "urgent":
				self.submit("AGENT_SCHEDULER_URGENT_TASK", self.task_text(arguments))
			elif verb in ("upload", "urgent_file"):
				self.submit("AGENT_SCHEDULER_ADD_TASK" if verb == "upload" else "AGENT_SCHEDULER_URGENT_TASK", Path(arguments[0]).read_text())
			elif verb == "delete":
				self.client.change("Text", AGENT, "AGENT_SCHEDULER_DELETE_TASK", {"NAME": arguments[0]})
				time.sleep(0.3)
			elif verb in ("reset", "enable", "disable", "up", "down"):
				self.command(arguments[0], {"up": "MOVE_UP", "down": "MOVE_DOWN"}.get(verb, verb.upper()))
			elif verb in ("reset_all", "delete_all"):
				self.client.change("Switch", AGENT, "AGENT_SCHEDULER_TASK_COMMAND", {verb.upper(): True})
				time.sleep(0.3)
			elif verb in ("start", "stop", "abort"):
				self.client.change("Switch", AGENT, "AGENT_SCHEDULER_CONTROL", {verb.upper(): True})
				time.sleep(0.3)
			elif verb == "hooks":
				items = {}
				for argument in arguments:
					key, equals, value = argument.partition("=")
					if not equals:
						raise ValueError("expected ITEM=NAME or ITEM= for '%s'" % argument)
					if key.upper() not in HOOK_ITEMS:
						raise ValueError("unknown hook '%s'" % key)
					items[key.upper()] = value
				self.client.change("Text", AGENT, "AGENT_SCHEDULER_HOOKS", items)
				time.sleep(0.3)
			elif verb == "limit":
				item = arguments[0].upper()
				if item not in LIMITS:
					raise ValueError("expected civil, nautical or astronomical")
				self.client.change("Switch", AGENT, "AGENT_SCHEDULER_NIGHT", {item: True})
				time.sleep(0.3)
			elif verb == "set":
				items = {}
				for argument in arguments:
					key, _, value = argument.partition("=")
					items[key.upper()] = float(value)
				self.client.change("Number", AGENT, "AGENT_SCHEDULER_SETTINGS", items)
				time.sleep(0.3)
			elif verb == "status":
				self.status()
			elif verb == "plan":
				self.show_list("AGENT_SCHEDULER_PLAN", "night plan")
			elif verb == "history":
				count = int(arguments[0]) if arguments else 10
				p = self.client.property(AGENT, "AGENT_SCHEDULER_HISTORY")
				self.say("history:")
				for i in (p or {}).get("items", [])[:count]:
					self.say("  %-5s %s" % (i.get("value", ""), i.get("label", "")))
			elif verb == "wait":
				deadline = time.monotonic() + float(arguments[0])
				while time.monotonic() < deadline:
					self.flush_messages()
					time.sleep(0.1)
			elif verb == "until":
				text = arguments[0]
				timeout = float(arguments[1]) if len(arguments) > 1 else 60
				self.flush_messages()
				deadline = time.monotonic() + timeout
				found = False
				while time.monotonic() < deadline and not found:
					with self.client.lock:
						for index in range(self.until_mark, len(self.client.messages)):
							device, message, arrived = self.client.messages[index]
							if device == AGENT and text in message:
								found = True
								self.until_mark = index + 1
								break
					self.flush_messages()
					time.sleep(0.1)
				if not found:
					self.say("timeout: no message containing '%s' within %g s" % (text, timeout))
					self.failed = True
					# a script stops at the first miss
					if not self.interactive:
						return False
			else:
				self.say("unknown command '%s', type help" % verb)
		except (IndexError, ValueError, OSError) as error:
			self.say("error: %s" % (error or "missing argument"))
		self.flush_messages()
		return True


def main():
	parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
	parser.add_argument("--port", type=int, default=0, help="server port (default: a free one)")
	parser.add_argument("--simulators", action="store_true", help="also load the Imager and Guider agents with the CCD and mount simulators")
	parser.add_argument("--dir", type=Path, help="scratch directory to use and keep (default: a temporary one, removed at the end)")
	parser.add_argument("--script", type=Path, help="read the commands from this file")
	parser.add_argument("--name", default="Scheduler Sandbox", help="name announced by Bonjour, so that clients list the server (default: Scheduler Sandbox)")
	parser.add_argument("--no-bonjour", action="store_true", help="do not announce the server on the network")
	parser.add_argument("--fast", action=argparse.BooleanOptionalAction, default=True, help="IDLE_CHECK_INTERVAL 1 s and IDLE_PARK_AFTER 0 min at the start (default: on)")
	args = parser.parse_args()
	server = REPOSITORY / "build/bin/indigo_server"
	if not server.is_file():
		sys.exit("indigo_server is not built, run 'make all' in %s" % REPOSITORY)
	directory = args.dir.resolve() if args.dir else Path(tempfile.mkdtemp(prefix="indigo-scheduler-sandbox-"))
	(directory / "home").mkdir(parents=True, exist_ok=True)
	port = args.port
	# a busy port would connect the sandbox to the server that holds it, maybe your real one
	with socket.socket() as reservation:
		try:
			reservation.bind(("", port))
		except OSError:
			if not args.dir:
				shutil.rmtree(directory, ignore_errors=True)
			sys.exit("port %d is in use, choose another one or leave out --port" % port)
		port = reservation.getsockname()[1]
	drivers = ["indigo_agent_scripting", "indigo_agent_mount", "indigo_agent_scheduler"]
	if args.simulators:
		drivers += ["indigo_agent_imager", "indigo_agent_guider", "indigo_ccd_simulator", "indigo_mount_simulator"]
	environment = dict(os.environ, HOME=str(directory / "home"), INDIGO_CACHE_BASE=str(directory / "home/.indigo"))
	log = (directory / "server.log").open("w")
	process = None
	client = None
	failed = False
	try:
		bonjour = ["-b-"] if args.no_bonjour else ["-b", args.name]
		process = subprocess.Popen([str(server), "--", "-p", str(port)] + bonjour + drivers, cwd=str(directory), env=environment, stdout=log, stderr=subprocess.STDOUT)
		deadline = time.monotonic() + 20
		while True:
			if process.poll() is not None:
				sys.exit("indigo_server exited, see %s" % (directory / "server.log"))
			if "Can't bind" in (directory / "server.log").read_text(errors="replace"):
				sys.exit("indigo_server could not bind port %d, see %s" % (port, directory / "server.log"))
			try:
				client = Client(port)
				break
			except OSError:
				if time.monotonic() > deadline:
					sys.exit("indigo_server did not start")
				time.sleep(0.2)
		client.send("getProperties", {"version": 0x300})
		interactive = args.script is None and sys.stdin.isatty()
		sandbox = Sandbox(client, args.simulators, interactive)
		if not sandbox.wait_for(lambda: client.property(AGENT, "AGENT_SCHEDULER_SETTINGS") and client.property("Mount Agent", "GEOGRAPHIC_COORDINATES") and client.property("Scripting Agent", "AGENT_SCRIPTING_RUN_SCRIPT"), 20):
			sys.exit("the agents did not appear, see %s" % (directory / "server.log"))
		if args.simulators:
			client.change("Switch", "Mount Agent", "FILTER_MOUNT_LIST", {"Mount Simulator": True})
			client.change("Switch", "Imager Agent", "FILTER_CCD_LIST", {"CCD Imager Simulator": True})
			client.change("Switch", "Guider Agent", "FILTER_CCD_LIST", {"CCD Guider Simulator": True})
			client.change("Switch", "Guider Agent", "FILTER_GUIDER_LIST", {"CCD Guider Simulator (guider)": True})
			time.sleep(1)
		if args.fast:
			client.change("Number", AGENT, "AGENT_SCHEDULER_SETTINGS", {"IDLE_CHECK_INTERVAL": 1, "IDLE_PARK_AFTER": 0})
		sandbox.site(time_longitude(12))
		client.new_messages()
		print("Scheduler sandbox on port %d%s" % (port, "" if args.no_bonjour else ", announced as '%s'" % args.name))
		print("Web control panel: http://localhost:%d/ctrl.html, from another computer http://%s:%d/ctrl.html" % (port, lan_address(), port))
		print("Scratch directory %s; the site is at local noon. Type help for the commands." % directory, flush=True)
		source = args.script.open() if args.script else sys.stdin
		if interactive:
			try:
				import readline  # noqa: F401  line editing and history for input()
			except ImportError:
				pass
		while True:
			if process.poll() is not None:
				print("indigo_server exited, see %s" % (directory / "server.log"), flush=True)
				sandbox.failed = True
				break
			if interactive:
				try:
					line = input("scheduler> ")
				except EOFError:
					break
			else:
				line = source.readline()
				if not line:
					break
				print("scheduler> " + line.rstrip(), flush=True)
			if not sandbox.run(line):
				break
		failed = sandbox.failed
	except KeyboardInterrupt:
		failed = True
	except SystemExit:
		# keep the server log the message points to
		failed = True
		raise
	finally:
		if client:
			client.close()
		if process and process.poll() is None:
			process.terminate()
			try:
				process.wait(timeout=10)
			except subprocess.TimeoutExpired:
				process.kill()
		log.close()
		if not args.dir and not failed:
			shutil.rmtree(directory, ignore_errors=True)
		elif failed:
			print("the server log is kept in %s" % (directory / "server.log"), flush=True)
	return 1 if failed else 0


if __name__ == "__main__":
	sys.exit(main())
