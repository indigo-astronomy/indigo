"""Try the Scheduler Agent by hand in a private indigo_server.

The sandbox starts its own indigo_server with the Scripting, Mount and Scheduler agents (and with
--simulators also the Imager and Guider agents with the CCD and mount simulators), in a scratch
directory, so your own configuration is never touched. It puts the site on the equator and moves
its longitude to choose the time of day: "dusk 30" makes the scheduler's night start in 30 seconds.
Tasks made with "task" only wait, so they need no equipment.

Type "help" at the prompt for the commands. Commands can also come from a file (--script) or from
standard input; then an "until" that times out stops the run with exit code 1.
"""

