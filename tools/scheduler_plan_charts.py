"""Draw the night plan charts of the "Two nights compared" section of the scheduler guide.

The plans come from the real planner: the scheduler plan benchmark executes the example nights
with every strategy and writes the target altitudes and the executed runs as JSON. This script
draws one PNG per night, a panel per strategy, and prints the run tables of the guide.

Regenerate the charts from the repository root (after building the library and the scheduler
agent archive, see indigo_test/AGENTS.md):

    make -C indigo_test build/benchmark/bench_scheduler_plan
    indigo_test/build/benchmark/bench_scheduler_plan --examples /tmp/scheduler_examples.json
    python3 tools/scheduler_plan_charts.py /tmp/scheduler_examples.json indigo_docs/INDIGO_SCHEDULER_GUIDE

The example nights are defined in indigo_test/benchmark/bench_scheduler_plan.c. Needs matplotlib.
"""

import argparse
import json
import os
import sys
import time

import matplotlib

matplotlib.use("Agg")

import matplotlib.pyplot as plt  # noqa: E402
from matplotlib.lines import Line2D  # noqa: E402
from matplotlib.patches import Patch, Rectangle  # noqa: E402

# colourblind-safe categorical palette in a fixed order; a target that no strategy plans is grey
PALETTE = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4", "#008300", "#6250d6", "#e34948"]
LEFT_OUT = "#9a9993"
INK = "#0b0b0b"
INK_SECONDARY = "#52514e"
GRID = "#e4e3df"
# from dark to light: astronomical night, then astronomical, nautical and civil twilight, then day
TWILIGHT = [(-90, -18, "#ffffff"), (-18, -12, "#e9edf3"), (-12, -6, "#d9dfe8"), (-6, 0, "#c9d1dc"), (0, 90, "#b9c3d0")]
VIEW_FROM, VIEW_TO = 15.5, 5.0  # UTC hours
STRIP = (-4.5, -2.3)  # the altitudes of the timeline strip of the runs below the horizon line
DPI = 160


def hours(t, base):
	"""UTC hours of time t from midnight of the day of base, continuing past midnight."""
	return (t - base) / 3600.0


def hhmm(t):
	return time.strftime("%H:%M", time.gmtime(t))


def crossings(times, values, level):
	result = []
	for k in range(1, len(values)):
		a, b = values[k - 1] - level, values[k] - level
		if a == 0 or a * b < 0:
			result.append(times[k - 1] + (times[k] - times[k - 1]) * a / (a - b))
	return result


def interpolate(times, values, t):
	for k in range(1, len(times)):
		if times[k] >= t:
			f = (t - times[k - 1]) / (times[k] - times[k - 1])
			return values[k - 1] + f * (values[k] - values[k - 1])
	return values[-1]


def upper_culminations(times, hour_angle):
	"""Times where the hour angle passes 0 upwards (not the jump from +12 to -12)."""
	result = []
	for k in range(1, len(hour_angle)):
		a, b = hour_angle[k - 1], hour_angle[k]
		if a <= 0 < b and b - a < 1:
			result.append(times[k - 1] + (times[k] - times[k - 1]) * (-a) / (b - a))
	return result


def colours(night):
	planned = set()
	for plan in night["plans"]:
		for run in plan["runs"]:
			planned.add(run["task"])
	result = {}
	slot = 0
	for i in range(len(night["tasks"])):
		if i in planned:
			if slot >= len(PALETTE):
				sys.exit("more than %d planned targets in the %s night" % (len(PALETTE), night["name"]))
			result[i] = PALETTE[slot]
			slot += 1
		else:
			result[i] = LEFT_OUT
	return result


def draw_night(data, night, path):
	base = data["grid_start"] - data["grid_start"] % 86400
	times = [data["grid_start"] + k * data["grid_step"] for k in range(len(data["sun_altitude"]))]
	x = [hours(t, base) for t in times]
	sun = data["sun_altitude"]
	tasks = night["tasks"]
	colour = colours(night)
	dusk = [t for t in crossings(times, sun, -18)]
	plans = night["plans"]
	fig, axes = plt.subplots(len(plans), 1, figsize=(11, 4.1 * len(plans) + 0.9), sharex=True)
	fig.subplots_adjust(left=0.07, right=0.985, top=1 - 0.95 / fig.get_figheight(), bottom=0.55 / fig.get_figheight(), hspace=0.22)
	titles = {"COMPACT": "COMPACT", "VISIBILITY": "VISIBILITY, VISIBILITY_FLIP_PENALTY 0", "VISIBILITY F=10": "VISIBILITY, VISIBILITY_FLIP_PENALTY %d" % data["flip_penalty_minutes"]}
	for ax, plan in zip(axes, plans):
		# twilight bands
		for low, high, fill in TWILIGHT:
			inside = [low <= s < high for s in sun]
			k = 0
			while k < len(inside):
				if inside[k]:
					j = k
					while j + 1 < len(inside) and inside[j + 1]:
						j += 1
					ax.axvspan(x[max(k - 1, 0)] if k > 0 else x[0], x[j], color=fill, lw=0, zorder=0)
					k = j + 1
				else:
					k += 1
		for t in dusk:
			ax.axvline(hours(t, base), color=INK_SECONDARY, lw=0.8, ls=(0, (1, 2)), zorder=1)
		limits = sorted(set(task["min_altitude"] for task in tasks))
		for limit in limits:
			ax.axhline(limit, color=INK_SECONDARY, lw=1.0, ls=(0, (5, 3)), zorder=1)
		# every target over the night, thin
		for i, task in enumerate(tasks):
			line, = ax.plot(x, task["altitude"], color=colour[i], lw=1.3, alpha=0.55, zorder=2, solid_capstyle="round")
			line.set_clip_path(Rectangle((VIEW_FROM, 0), 24 + VIEW_TO - VIEW_FROM, 100, transform=ax.transData))
			for t in upper_culminations(times, task["hour_angle"]):
				h = hours(t, base)
				if VIEW_FROM <= h <= 24 + VIEW_TO:
					ax.plot([h], [interpolate(times, task["altitude"], t)], marker="^", ms=6, color=colour[i], markeredgecolor="white", markeredgewidth=0.8, zorder=3)
		# the runs, thick on their target's curve
		segments = []
		for run in plan["runs"]:
			i = run["task"]
			inside = [k for k, t in enumerate(times) if run["start"] <= t <= run["end"]]
			rx = [hours(run["start"], base)] + [x[k] for k in inside] + [hours(run["end"], base)]
			ry = [interpolate(times, tasks[i]["altitude"], run["start"])] + [tasks[i]["altitude"][k] for k in inside] + [interpolate(times, tasks[i]["altitude"], run["end"])]
			segments.append((run, rx, ry))
			ax.plot(rx, ry, color="white", lw=6.5, zorder=4, solid_capstyle="round")
			ax.plot(rx, ry, color=colour[i], lw=4.5, zorder=5, solid_capstyle="round")
			# the same run on the timeline strip above the time axis
			ax.add_patch(Rectangle((rx[0], STRIP[0]), rx[-1] - rx[0], STRIP[1] - STRIP[0], facecolor=colour[i], edgecolor="white", lw=1, zorder=5))
			if run["flip"]:
				flips = [t for t in crossings(times, tasks[i]["hour_angle"], data["flip_offset"]) if run["start"] <= t <= run["end"]]
				for t in flips:
					ax.plot([hours(t, base)], [interpolate(times, tasks[i]["altitude"], t)], marker="X", ms=10, color=INK, markeredgecolor="white", markeredgewidth=1.2, zorder=6)
					ax.plot([hours(t, base)], [(STRIP[0] + STRIP[1]) / 2], marker="X", ms=6, color=INK, markeredgewidth=0, zorder=6)
		# direct label above the middle of each run, else below it, else further away, clear of the other labels and runs
		occupied = [(px, py) for _, rx, ry in segments for px, py in zip(rx, ry)]
		placed = []
		for run, rx, ry in segments:
			text = "%s %s" % (tasks[run["task"]]["name"], hhmm(run["start"]))
			mx = (rx[0] + rx[-1]) / 2
			width = 0.095 * len(text)
			candidates = [y for k in range(12) for y in (max(ry) + 3 + 4.5 * k, min(ry) - 7 - 4.5 * k)]
			free = [y for y in candidates if 1 < y < 89 and all(abs(px - mx) >= (pw + width) / 2 + 0.1 or abs(py - y) >= 4.5 for px, py, pw in placed) and not any(abs(px - mx) < width / 2 + 0.1 and y - 2 < py < y + 6 for px, py in occupied)]
			my = free[0] if free else candidates[0]
			placed.append((mx, my, width))
			ax.text(mx, my, text, ha="center", va="bottom", fontsize=8.5, color=INK, zorder=7, bbox=dict(boxstyle="round,pad=0.15", fc="white", ec="none", alpha=0.85))
		ax.axhline(0, color=INK_SECONDARY, lw=0.6, zorder=1)
		ax.set_ylim(-5.5, 96)
		ax.set_xlim(VIEW_FROM, 24 + VIEW_TO)
		ax.set_yticks([(STRIP[0] + STRIP[1]) / 2] + list(range(0, 91, 15)))
		ax.set_yticklabels(["runs"] + [str(a) for a in range(0, 91, 15)])
		for a in range(15, 91, 15):
			ax.axhline(a, color=GRID, lw=0.6, zorder=0.5)
		ax.set_ylabel("altitude (°)", color=INK_SECONDARY, fontsize=9)
		ax.tick_params(colors=INK_SECONDARY, labelsize=9, length=3)
		for side in ("top", "right"):
			ax.spines[side].set_visible(False)
		for side in ("left", "bottom"):
			ax.spines[side].set_color(INK_SECONDARY)
		count = len(plan["runs"])
		flips = sum(1 for run in plan["runs"] if run["flip"])
		ax.set_title("%s: %d runs, quality %.0f %%, %d meridian flip%s" % (titles.get(plan["strategy"], plan["strategy"]), count, plan["weighted_quality"], flips, "" if flips == 1 else "s"), loc="left", fontsize=10.5, color=INK, pad=4)
	ticks = list(range(16, 24 + 5))
	axes[-1].set_xticks(ticks)
	axes[-1].set_xticklabels(["%02d:00" % (h % 24) for h in ticks])
	axes[-1].set_xlabel("UTC, night of %s, latitude %d°, longitude %d°" % (data["date"], data["latitude"], data["longitude"]), color=INK_SECONDARY, fontsize=9)
	handles = [Line2D([], [], color=colour[i], lw=5, label=task["name"] + ("" if colour[i] != LEFT_OUT else " (not planned)")) for i, task in enumerate(tasks)]
	handles += [
		Line2D([], [], color=INK_SECONDARY, marker="^", ls="none", ms=6, label="culmination"),
		Line2D([], [], color=INK, marker="X", ls="none", ms=9, markeredgecolor="white", label="meridian flip"),
		Line2D([], [], color=INK_SECONDARY, lw=1.0, ls=(0, (5, 3)), label="altitude limit"),
		Patch(facecolor=TWILIGHT[1][2], edgecolor=INK_SECONDARY, lw=0.5, label="twilight (darker: brighter sky)"),
	]
	fig.legend(handles=handles, loc="upper center", ncol=(len(handles) + 1) // 2, fontsize=8.5, frameon=False, bbox_to_anchor=(0.5, 1.0), handlelength=1.8, columnspacing=1.2, labelcolor=INK)
	fig.savefig(path, dpi=DPI, facecolor="white")
	plt.close(fig)


def print_tables(night):
	tasks = night["tasks"]
	print("%s night" % night["name"])
	for plan in night["plans"]:
		print("\n%s (weighted quality %.1f %%)\n" % (plan["strategy"], plan["weighted_quality"]))
		print("| Run (UTC) | Target | Quality | Flip |")
		print("|---|---|---|---|")
		for run in plan["runs"]:
			print("| %s–%s | %s | %.0f %% | %s |" % (hhmm(run["start"]), hhmm(run["end"]), tasks[run["task"]]["name"], run["quality"], "yes" if run["flip"] else ""))
	print()


def main():
	parser = argparse.ArgumentParser(description="Draw the scheduler guide night plan charts from the JSON of bench_scheduler_plan --examples.")
	parser.add_argument("json", help="output of bench_scheduler_plan --examples")
	parser.add_argument("directory", help="where the PNG files go, e.g. indigo_docs/INDIGO_SCHEDULER_GUIDE")
	args = parser.parse_args()
	with open(args.json) as file:
		data = json.load(file)
	os.makedirs(args.directory, exist_ok=True)
	for night in data["nights"]:
		for i, task in enumerate(night["tasks"]):
			culminations = [hhmm(t) for t in upper_culminations([data["grid_start"] + k * data["grid_step"] for k in range(len(task["hour_angle"]))], task["hour_angle"])]
			print("%-12s %4d min  culmination %s at %.0f°" % (task["name"], task["minutes"], ", ".join(culminations) or "outside the chart", task["transit_altitude"]))
		draw_night(data, night, os.path.join(args.directory, "%s_night.png" % night["name"]))
		print_tables(night)


if __name__ == "__main__":
	main()
